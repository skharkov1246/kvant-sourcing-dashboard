#!/usr/bin/env python3
"""Замена англицизмов на русские слова — в тексте, но не в цитатах.

ЗАЧЕМ. Владелец просил официальный технический русский без англицизмов. Пачки
разведки приходят от разных исполнителей, и слово «прайс» возвращается в набор
с каждой новой пачкой: одиночная чистка набора держится ровно до следующего
слияния. Поэтому замена стоит НА ВХОДЕ — в gt/tools/rv_merge.py, — а не
разовой правкой данных.

ЧЕГО ТРОГАТЬ НЕЛЬЗЯ. Дословная цитата со страницы продавца есть доказательство:
если на странице написано «прайс-лист», в цитате должно остаться «прайс-лист».
Поэтому участки в «ёлочках» и адреса из замены исключены. Это не придирка —
18.09.2026 механическая замена без такой защиты испортила одиннадцать составных
слов («прайс-файл» стал «прейскурант-файл»), и их пришлось править по смыслу
вручную.

ПОЧЕМУ СПИСОК ЗАКРЫТЫЙ. Замена по образцу вида «любое слово на -инг» портит
собственные имена и термины. Каждая пара внесена сюда разбором конкретного
вхождения, а не правилом словообразования.
"""
from __future__ import annotations

import re

# Порядок важен: длинные формы идут раньше коротких, иначе «прайс-лист»
# превратится в «прейскурант-лист».
PAIRS: tuple[tuple[str, str], ...] = (
    ("прайс-листов", "прейскурантов"),
    ("прайс-листами", "прейскурантами"),
    ("прайс-листах", "прейскурантах"),
    ("прайс-листом", "прейскурантом"),
    ("прайс-листа", "прейскуранта"),
    ("прайс-листу", "прейскуранту"),
    ("прайс-листе", "прейскуранте"),
    ("прайс-листы", "прейскуранты"),
    ("прайс-лист", "прейскурант"),
    ("прайс-файлом", "прейскурантным файлом"),
    ("прайс-файле", "прейскурантном файле"),
    ("прайс-файла", "прейскурантного файла"),
    ("прайс-файл", "прейскурантный файл"),
    ("прайс-бука", "сборника прейскурантов"),
    ("прайс-буке", "сборнике прейскурантов"),
    ("прайсбуке", "сборнике прейскурантов"),
    ("прайсбук", "сборник прейскурантов"),
    ("непрайсованные", "не внесённые в прейскурант"),
    ("прайсованные", "внесённые в прейскурант"),
    ("прайсовая", "прейскурантная"),
    ("прайсовую", "прейскурантную"),
    ("прайсовой", "прейскурантной"),
    ("прайсовый", "прейскурантный"),
    ("прайсовым", "прейскурантным"),
    ("прайсовых", "прейскурантных"),
    ("прайсовые", "прейскурантные"),
    ("прайсинга", "назначения цены"),
    ("прайсинг", "назначение цены"),
    ("прайсами", "прейскурантами"),
    ("прайсах", "прейскурантах"),
    ("прайсам", "прейскурантам"),
    ("прайсов", "прейскурантов"),
    ("прайсом", "прейскурантом"),
    ("прайса", "прейскуранта"),
    ("прайсу", "прейскуранту"),
    ("прайсе", "прейскуранте"),
    ("прайсы", "прейскуранты"),
    ("прайс", "прейскурант"),
)

_SAFE = re.compile(r"«[^»]*»|https?://\S+|www\.\S+")
_WORDS = re.compile("|".join(re.escape(a) for a, _ in PAIRS), re.I)
_MAP = {a.lower(): b for a, b in PAIRS}


def clean(text: str) -> str:
    """Возвращает текст с заменой англицизмов вне цитат и адресов."""
    if not isinstance(text, str) or "райс" not in text.lower():
        return text
    safe = [m.span() for m in _SAFE.finditer(text)]

    def repl(m: re.Match) -> str:
        if any(a <= m.start() < b for a, b in safe):
            return m.group(0)
        word = _MAP[m.group(0).lower()]
        return word[0].upper() + word[1:] if m.group(0)[0].isupper() else word

    return _WORDS.sub(repl, text)


def clean_row(row: dict) -> int:
    """Чистит все строковые поля записи. Возвращает число изменённых полей."""
    n = 0
    for f, v in list(row.items()):
        if isinstance(v, str):
            v2 = clean(v)
            if v2 != v:
                row[f] = v2
                n += 1
    return n
