#!/usr/bin/env python3
"""Закрытый список вердиктов перепроверки и ОДИН способ их считать.

Оплачено расхождением двух документов об одних данных 18.09.2026: справка
печатала «нечем проверить 30», а сама перепроверка — 21. Причин было две, и
обе типовые.

1. У справки классов было четыре, и «не подтверждена» вместе с «дублем»
   сваливались в «нечем проверить». Разные вещи: «нечем проверить» — цены не
   нашли вовсе; «не подтверждена» — вилка лишилась основания, но цены,
   которая её опровергает, никто не видел.
2. Вердикт опознавался ПОДСТРОКОЙ в любом месте текста. Но текст вердикта —
   проза с оговорками: «ВЕРНА (по верхней границе; нижняя половина вилки не
   подтверждена ничем)» содержит и «ВЕРНА», и «НЕ ПОДТВЕРЖДЕНА», и ответ
   зависел от порядка перебора.

Правило здесь одно: вердикт — это то, с чего текст НАЧИНАЕТСЯ. Оговорки идут
после и на класс не влияют.
"""
from __future__ import annotations

# Порядок — от частного к общему: «НЕ ПОДТВЕРЖДЕНА» проверяется раньше, чем
# «ВЕРНА», иначе строка «НЕ ПОДТВЕРЖДЕНА…» не совпала бы ни с чем полезным.
VERDICTS = ["НЕ ПОДТВЕРЖДЕНА", "НЕЧЕМ ПРОВЕРИТЬ", "ЗАНИЖЕНА", "ЗАВЫШЕНА",
            "ВЕРНА", "ДУБЛЬ"]
# Вердикты, которые выносятся ТОЛЬКО по найденной цене.
PRICED = {"ЗАНИЖЕНА", "ЗАВЫШЕНА", "ВЕРНА"}
UNKNOWN = "ВЕРДИКТ НЕ ОПОЗНАН"


def vkey(row_or_text) -> str:
    """Класс вердикта по началу текста. Ни в каком случае не по подстроке."""
    v = row_or_text
    if isinstance(row_or_text, dict):
        v = row_or_text.get("band_verdict")
    v = str(v or "").strip().upper()
    for k in VERDICTS:
        if v.startswith(k):
            return k
    return UNKNOWN
