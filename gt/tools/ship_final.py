def main() -> int:
    doc = build()
    if len(doc) < 20_000 or doc.count("<h2>") < 4:
        print(f"отчёт вышел пустым ({len(doc)} байт) — набор не прочитан", file=sys.stderr)
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    hp = OUT / "ОТЧЁТ-ЗАЯВКА-ЛУКОЙЛ.html"
    pp = OUT / "ОТЧЁТ-ЗАЯВКА-ЛУКОЙЛ.pdf"
    hp.write_text(doc, encoding="utf-8")
    exe = next((c for c in CHROME if Path(c).exists()), None)
    if not exe:
        print("Chromium не найден — документ не собран", file=sys.stderr)
        return 1
    subprocess.run(
        [exe, "--headless", "--disable-gpu", "--no-sandbox", "--no-pdf-header-footer",
         "--run-all-compositor-stages-before-draw", "--virtual-time-budget=180000",
         f"--print-to-pdf={pp}", hp.as_uri()],
        check=True, capture_output=True)
    print(f"{pp.name}: {pp.stat().st_size / 1e6:.1f} МБ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
