def E(x) -> str:
    return html.escape(str(x if x is not None else ""))


def pct(v: float) -> str:
    """Доля по-русски: разделитель — запятая, а не точка.

    Весь документ печатает числа с запятой, и одна «91.6» посреди русского
    текста читается как опечатка, а не как доля.
    """
    return f"{v:.1f}".replace(".", ",")


def ru(n) -> str:
    return f"{int(round(float(n or 0))):,}".replace(",", " ")


def money(n) -> str:
    return f"{float(n or 0):,.2f}".replace(",", " ")


def load(name: str):
    p = D / name
