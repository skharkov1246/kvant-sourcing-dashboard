        usd = sc.to_usd(r["price"], r["currency"])
        lo, hi = row.get("usd_lo"), row.get("usd_hi")
        band = "" if lo in (None, "") else f"{float(lo):g}–{float(hi):g} USD за штуку"
        quote = (f'«{r["pn"]} {r["desc"]} {r["qty_listed"]}pcs '
                 f'{r["price"]:,.2f}{r["currency"]} ea»').replace(",", ".")

