def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("page")
    ap.add_argument("--seller", required=True)
    ap.add_argument("--url", required=True)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    p = Path(a.page)
    if ROOT in p.resolve().parents:
        print("страница лежит внутри репозитория — это коммерческий документ контрагента, "
              "перенесите её в рабочую папку", file=sys.stderr)
        return 1
    r = build(p.read_text(encoding="utf-8", errors="replace"), a.seller, a.url)
    print(f"строк листа {r['listed']}, создано строк перепроверки {len(r['made'])}")
    for s in r["skipped"]:
        print("  пропуск:", s)
    if not a.dry_run and r["made"]:
        tmp = Path(sys.argv[0]).with_name("_fold_tmp.json")
        tmp.write_text(json.dumps({"rows": r["made"]}, ensure_ascii=False), encoding="utf-8")
        import rv_merge
        m = rv_merge.merge([tmp])
        tmp.unlink()
        print(f"принято набором: {len(m['took'])}, отказов {len(m['left'])}")
        for name, pn, why in m["left"]:
            print(f"  ОТКАЗ {pn}: {why}")
    else:
        for row in r["made"]:
            print(f"  {str(row['pn']):16} {row['band_verdict'][:70]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
