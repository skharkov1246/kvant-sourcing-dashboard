STOP = {"для", "и", "в", "с", "на", "по", "от", "до", "сборе", "шт", "мм", "модель"}


def stems(text: str) -> set[str]:
    return {w[:5] for w in re.findall(r"[а-яёa-z0-9]+", (text or "").lower())
            if len(w) > 3 and w not in STOP}


def head(desc: str) -> tuple[str, str]:
    """Первое слово описания после снятия ведущих номеров продавца."""
    d = desc.strip()
    while True:
        m = re.match(r"^(\S*\d[\w./-]*)\s+(.*)$", d)
        if not m:
            break
        d = m.group(2).strip()
    first = re.split(r"[,\s]+", d)[0].lower().strip(".")
    if first in ("solar", "solar turbines"):
        d2 = re.sub(r"^solar\s+turbines\s+", "", d, flags=re.I).strip()
        return re.split(r"[,\s]+", d2)[0].lower().strip("."), d
    return first, d


def key(pn) -> str:
    return re.sub(r"[^A-Z0-9]", "", str(pn or "").split("(")[0].upper())


