def файлы_письма(v) -> list[str]:
    """Номера файлов Диска из FILES письма.

    FILES у дела — тип diskfile, и его id — НАСТОЯЩИЙ идентификатор Диска
    (gt/tools/bitrix_tkp.py:from_activities). Форм значения три, как у
    bitrix_tkp.objs: список объектов, словарь «id → объект» и один объект.
    Ссылку url из FILES не берём: это страница портала, вебхуку она отдаёт
    страницу входа с кодом 200. Байты — только через disk.file.get.
    """
    if not v:
        return []
    if isinstance(v, list):
        объекты = v
    elif isinstance(v, dict):
        вложенные = [x for x in v.values() if isinstance(x, dict)]
        объекты = вложенные if вложенные and len(вложенные) == len(v) else [v]
    else:
        return []
    out: list[str] = []
    for o in объекты:
        if not isinstance(o, dict):
            continue
        n = str(o.get("id") or o.get("ID") or "").strip()
        if n.isdigit() and n not in out:
            out.append(n)
    return out


def ссылки_письма(письмо: dict, группа: str) -> list[dict]:
    """Ссылки на вложения одного письма в форме, которую понимает indexer.handle.

    fo несёт ТОЛЬКО номер Диска: indexer.download без ссылок в fo сразу идёт в
    disk.file.get и качает по DOWNLOAD_URL через очередь клиента. Номер
    спрашивается лениво — в handle, то есть уже после отсева разобранных по
    lib_files: за уже разобранный файл портал не платит ни запроса.
    """
    г = группа_или_отказ(группа)
    try:
        тип = int(письмо.get("OWNER_TYPE_ID") or 0)
        направление = int(письмо.get("DIRECTION") or 0)
    except (TypeError, ValueError):
        return []
    владелец = str(письмо.get("OWNER_ID") or "").strip()
    буква = БУКВА_ВЛАДЕЛЬЦА.get(тип)
    if буква is None or not владелец:
        return []
    заголовок = (_df.ЗАГОЛОВОК_ВХОДЯЩЕГО if направление == ВХОДЯЩЕЕ
                 else _df.ЗАГОЛОВОК_ИСХОДЯЩЕГО if направление == ИСХОДЯЩЕЕ else None)
    общее = {
        "deal": f"{буква}{владелец}",
        # Номер письма — в поле «field»: по нему файл находится в портале,
        # а колонки для номера дела в lib_files нет.
        "field": f"письмо {письмо.get('ID')}",
        "field_title": заголовок,
        "origin": г["origin"],
        "side": СТОРОНА.get((группа, направление), _ds.НЕИЗВЕСТНО),
        "our_company": None,
        # ПОСТАВЩИК ЦЕНЫ — ВЛАДЕЛЕЦ ПИСЬМА, ЕСЛИ ЭТО КОМПАНИЯ. Номер компании
        # портала — тот же ключ, что rfq_company у карточки запроса (ПОЛЕ_ПОСТАВЩИКА
        # СП-166 ведёт в компанию). У письма контакта компанию знает только сам
        # контакт, а лишний запрос crm.contact.get на письмо — нагрузка портала
        # ради догадки: поставщик тогда пуст, и сводки покажут «(не указан)», как
        # у карточки без поставщика. Используется только записью цен писем
        # (indexer.MAIL_PRICES); lib_files и lib_demand его не пишут.
        "company": владелец if тип == КОМПАНИЯ else None,
        # Дата письма — запасная дата квотации, как дата карточки у СП-166
        # (library/quote_date.py). Цены писем пишутся только со входом
        # MAIL_PRICES и только у стороны «поставщик» (indexer.цены_файла).
        "card_created": письмо.get("CREATED"),
    }
    refs = []
    for disk_id in (файлы_письма(письмо.get("FILES")) if файлы_включены() else []):
        refs.append({**общее, "fo": {"id": disk_id}, "file_id": ключ_файла(disk_id)})
    if тела_включены():
        # ТЕЛО ПИСЬМА — ТОЖЕ ДОКУМЕНТ. Заказчик часто пишет перечень прямо в
        # письме, без вложения; и оно уже пришло в списке дел — портал за него
        # не платит ни запроса, и прав на Диск ему не нужно (вложениям нужны:
        # зонд 25.09.2026, scripts/probe_mail_files.py).
        тело = тело_письма(письмо.get("DESCRIPTION"), письмо.get("DESCRIPTION_TYPE"))
        if тело:
            refs.append({**общее, "fo": {"тело": тело},
                         "file_id": f"{ПРИСТАВКА_ТЕЛА}{письмо.get('ID')}"})
    return refs


def читать_письма(группа: str, после_id: int, лимит_писем: int = 0,
                  до_id: int | None = None, поля: list[str] | None = None,
                  bx=None) -> tuple[list[dict], int]:
    """Письма группы с номером больше после_id по возрастанию. (письма, курсор).

    ПО КЛЮЧУ И БЕЗ ПОДСЧЁТА (start=-1): смещение заставляет портал на каждой
    странице считать total по всему фильтру, а это время метода — 24.09.2026 на
    нём пятьдесят частей получили HTTP 429 за две минуты (CLAUDE.md, «Битрикс
    не перегружать»). Своих пауз и повторов здесь нет: bx — общий клиент
    индексатора с бюджетом портала.

    Курсор — номер ПОСЛЕДНЕГО ВЗЯТОГО письма, а не последнего на странице:
    оборванная лимитом страница иначе сдвинула бы отметку за непрочитанные.
    """
    if bx is None:
        import indexer
        bx = indexer.bx
    базовый = фильтр_группы(группа)
    письма: list[dict] = []
    последний = int(после_id or 0)
    курсор = последний
    while not лимит_писем or len(письма) < лимит_писем:
        ф = dict(базовый)
        ф[">ID"] = последний
        if до_id is not None:
            ф["<=ID"] = int(до_id)
        j = bx(МЕТОД, {"filter": ф, "order": {"ID": "ASC"},
                       "select": list(поля or (ПОЛЯ + ПОЛЯ_ТЕЛА if тела_включены() else ПОЛЯ)),
                       "start": -1})
        страница = j.get("result") or []
        if isinstance(страница, dict):
            страница = страница.get("items") or []
        if not страница:
            break
        for x in страница:
            if лимит_писем and len(письма) >= лимит_писем:
                break
            письма.append(x)
            курсор = max(курсор, int(x["ID"]))
        последний = int(страница[-1]["ID"])
        if len(страница) < СТРАНИЦА:
            break
    return письма, курсор


def collect_refs_mail(группа: str, после_id: int, лимит_писем: int = 0,
                      до_id: int | None = None, bx=None) -> tuple[list[dict], int]:
    """Ссылки на вложения писем группы после отметки. (ссылки, курсор).

    лимит_писем — сколько писем взять (0 — до до_id или до конца). Счётчики —
    в журнал, только числа.
    """
    письма, курсор = читать_письма(группа, после_id, лимит_писем, до_id, bx=bx)
    refs: list[dict] = []
    с_файлами = 0
    тел = 0
    видели: set[str] = set()
    повторов = 0
    for п in письма:
        своих = ссылки_письма(п, группа)
        с_файлами += bool(файлы_письма(п.get("FILES")))
        тел += any(r["file_id"].startswith(ПРИСТАВКА_ТЕЛА) for r in своих)
        for r in своих:
            # Один файл Диска бывает в нескольких письмах (пересылка, ответ с
            # цитатой вложения): вставка конфликтует по file_id и роняет пакет.
            if r["file_id"] in видели:
                повторов += 1
                continue
            видели.add(r["file_id"])
            refs.append(r)
    print(f"писем прочитано: {len(письма)} · с вложениями: {с_файлами}"
          f" · файлов: {len(refs) - тел}{'' if файлы_включены() else ' (вложения выключены)'}"
          f" · тел писем к разбору: {тел}"
          f" · повторов одного файла отброшено: {повторов}"
          f" · группа {группа}, номера писем после {после_id}"
          + (f" до {до_id}" if до_id is not None else "")
          + f", отметка пачки {курсор}", flush=True)
    return refs, курсор


def границы_по_письмам(номера: list[int], от: int, до: int, shards: int) -> list[int]:
    """Границы частей пачки (от; до]: shards+1 номеров, часть k — (b[k]; b[k+1]].

    ДЕЛИТ ПОРОВНУ ПО ПИСЬМАМ, А НЕ ПО НОМЕРАМ. Прогон 36079859054 (25.09.2026,
    группа mail-lead, пачка 2 000 писем на 10 частей) резал номера пачки
    равными отрезками: в начале пачки номера писем лидов редки, и части 1–4
    (номера 0…17 320) не прочитали ни одного письма, а шесть остальных несли всё
    по три часа при 0,3 запроса в секунду. Тот же дефект у сделок снят в
    library/reparse.py:границы_по_файлам (PR #415) — граница по счёту, а не по
    значению.

    Граница — номер письма, взятый из самой пачки, поэтому части СМЕЖНЫ: первая
    начинается с отметки, последняя кончается концом пачки, и письмо с любым
    номером из (от; до] лежит ровно в одной части — даже если между планом и
    разбором письмо в пачке появилось или пропало. Писем в частях поровну с
    точностью до одного; при писем меньше, чем частей, лишние части пусты.
    Деление по-прежнему ОДНО (правило дробления): план считает границы, части
    их только берут.
    """
    от, до = int(от), int(до)
    if shards <= 1:
        return [от, до]
    н = sorted(int(x) for x in номера)
    if any(x <= от or x > до for x in н):
        raise ValueError("номера пачки вне (отметка; конец пачки] — план и пачка разошлись")

    def край(k: int) -> int:
        # Последнее письмо части k-1: у части поровну писем, остаток — по одному.
        i = k * len(н) // shards - 1
        return н[i] if i >= 0 else от

    return [от] + [край(k) for k in range(1, shards)] + [до]


def разобрать_границы(текст: str) -> list[int]:
    """Границы из вывода плана (JSON-список чисел). Мусор — отказ, а не догадка."""
    try:
        б = json.loads(текст)
    except ValueError as e:
        raise ValueError("границы частей не читаются как JSON") from e
    if not isinstance(б, list) or not б or not all(type(x) is int for x in б):
        raise ValueError("границы частей — не список целых номеров")
    return б


def границы_части(границы: list[int] | None, от: int, до: int,
                  shard: int, shards: int) -> tuple[int, int]:
    """Кусок своей части (после, включительно по) из границ плана.

    Часть не делит пачку сама: делить поровну по письмам может только тот, кто
    прочитал их номера, то есть план. Границы сверяются с пачкой и числом частей
    — расхождение значит, что план считал для другой пачки или другого деления,
    и часть отказывает громко: молча взятый чужой кусок терял бы письма.
    """
    if границы is None:
        if shards <= 1:
            return от, до
        raise ValueError(f"нет границ частей от плана (MAIL_BOUNDS) при {shards} частях")
    if len(границы) != shards + 1:
        raise ValueError(f"границ {len(границы)}, а частей {shards}: ждали {shards + 1}")
    if границы[0] != от or границы[-1] != до:
        raise ValueError("границы частей не совпадают с пачкой плана (MAIL_FROM / MAIL_TO)")
    if any(a > b for a, b in zip(границы, границы[1:])):
        raise ValueError("границы частей идут не по возрастанию")
    if not 0 <= shard < shards:
        raise ValueError(f"часть {shard} вне 0…{shards - 1}")
    return границы[shard], границы[shard + 1]


