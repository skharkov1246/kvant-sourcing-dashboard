def тела_включены() -> bool:
    """Вход прогона MAIL_BODIES — читается при каждом вызове, не при импорте."""
    return os.environ.get("MAIL_BODIES", "") not in ("", "0", "false")


def файлы_включены() -> bool:
    """Вход прогона MAIL_FILES: по умолчанию вложения берутся. Без них — прогон
    одних тел со своей отметкой (имя_отметки)."""
    return os.environ.get("MAIL_FILES", "1") not in ("0", "false")


def тело_письма(описание, тип=None) -> bytes:
    """Тело письма без цитаты прежней переписки — байтами для indexer.handle.

    HTML оставляется HTML (каскад читает таблицы письма, вставленные из
    Excel), с объявленной кодировкой; текст — текстом. Пусто — b"": такое тело
    ссылкой не становится вовсе.
    """
    т = str(описание or "")
    if not т.strip():
        return b""
    if str(тип or "") == "3" or _ПОХОЖЕ_НА_HTML.search(т[:4000]):
        m = _ЦИТАТА_HTML.search(т)
        if m:
            т = т[:m.start()]
        видимых = re.sub(r"<[^>]*>|&nbsp;|&#160;|\s+", "", т)
        if len(видимых) < ТЕЛО_МИН:
            return b""
        return ('<html><head><meta charset="utf-8"></head><body>'
                + т + "</body></html>").encode("utf-8")
    строки: list[str] = []
    for с in т.splitlines():
        if _ЦИТАТА_ТЕКСТ.match(с):
            break
        if с.lstrip().startswith(">"):
            continue
        строки.append(с)
    т = "\n".join(строки).strip()
    if len(re.sub(r"\s+", "", т)) < ТЕЛО_МИН:
        return b""
    return т.encode("utf-8")
