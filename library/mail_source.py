def имя_отметки(группа: str) -> str:
    """Имя отметки группы в lib_metric_runs.

    ПРОГОН ОДНИХ ТЕЛ ИДЁТ ПО СВОЕЙ ОТМЕТКЕ («почта:<группа>:тела»). Общая
    отметка сдвинулась бы за письма, чьи вложения не брали, и вложения этих
    писем пропали бы; а без сдвига прогон тел перечитывал бы одну пачку. Две
    отметки независимы: когда вложения станут доступны (вебхук файлов), прогон
    с вложениями пойдёт от своей, а уже записанные тела отсеются по lib_files.
    """
    return ЗАМЕР + группа + ("" if файлы_включены() else ":тела")


def прочитать_отметку(cur, группа: str) -> int:
    """Наибольший номер письма, разобранного целиком; 0 — отметки нет."""
    import psycopg2
    try:
        cur.execute("select nums from lib_metric_runs where metric = %s "
                    "order by measured_at desc limit 1", (имя_отметки(группа),))
    except psycopg2.Error as e:
        # Нет таблицы — не повод начинать с нуля молча: с нуля значит все
        # 789 тысяч писем лидов заново. Падаем громко.
        cur.connection.rollback()
        raise RuntimeError(f"отметка писем не прочитана ({type(e).__name__})") from e
    row = cur.fetchone()
    if not row:
        return 0
    nums = row[0] if not isinstance(row[0], str) else json.loads(row[0])
    return int((nums or {}).get("после_id") or 0)


def записать_отметку(cur, группа: str, от: int, до: int, писем: int, run_key: str) -> None:
    cur.execute(
        "insert into lib_metric_runs (metric, run_key, nums, note) values (%s, %s, %s::jsonb, %s) "
        "on conflict (metric, run_key) do update set nums = excluded.nums, "
        "measured_at = now(), note = excluded.note",
        (имя_отметки(группа), run_key,
         json.dumps({"от": int(от), "после_id": int(до), "писем": int(писем)}),
         "отметка писем: разобраны письма группы с номером до «после_id» включительно"))


def сдвинуть_отметку(cur, группа: str, от: int, до: int, писем: int, run_key: str) -> bool:
    """Сдвинуть отметку с «от» на «до». False — не сдвинута, и это не ошибка молча.

    Сдвиг только ВПЕРЁД и только с того места, с которого пачку планировали:
    если отметку за это время сдвинул другой прогон той же группы, наша пачка
    могла оказаться позади — запись откатила бы чужой прогресс назад.
    """
    сейчас = прочитать_отметку(cur, группа)
    if сейчас != от:
        print(f"::warning::отметка группы {группа} за время прогона сменилась "
              f"({от} → {сейчас}) — не трогаю", flush=True)
        return False
    if до <= от:
        print("пачка пуста — отметка остаётся", flush=True)
        return False
    записать_отметку(cur, группа, от, до, писем, run_key)
    return True


def _в_выход(строки: list[str]) -> None:
    print("\n".join(строки), flush=True)
    if os.getenv("GITHUB_OUTPUT"):
        with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as fh:
            fh.write("\n".join(строки) + "\n")


def main(argv: list[str]) -> int:
    команда = argv[1] if len(argv) > 1 else ""
    группа = os.environ.get("MAIL_GROUP", "").strip()
    try:
        группа_или_отказ(группа)
    except ValueError as e:
        print(f"::error::{e}", file=sys.stderr)
        return 2
    import indexer
    if команда == "план":
        # ПАЧКУ И ЕЁ ДЕЛЕНИЕ ОПРЕДЕЛЯЕТ ОДИН ПРОЦЕСС. Где пачка кончается и где
        # проходят границы частей, знает только тот, кто прочитал её номера:
        # лимит в письмах, а номера идут с пропусками. Здесь читаются одни
        # номера — страница на пятьдесят писем, лимит/50 запросов; границы
        # частей считаются по ним же, без единого лишнего запроса.
        try:
            лимит = int(os.environ.get("MAIL_LIMIT", "2000") or 2000)
        except ValueError:
            лимит = 2000
        try:
            частей = int(os.environ.get("SHARDS", "1") or 1)
        except ValueError:
            print("::error::SHARDS — не число частей", flush=True)
            return 2
        conn = indexer.connect()
        with conn.cursor() as cur:
            от = прочитать_отметку(cur, группа)
        conn.close()
        запросов = 0

        def bx_со_счётом(метод: str, параметры: dict) -> dict:
            nonlocal запросов
            запросов += 1
            return indexer.bx(метод, параметры)

        письма, до = читать_письма(группа, от, лимит, поля=["ID"], bx=bx_со_счётом)
        номера = [int(x["ID"]) for x in письма]
        границы = границы_по_письмам(номера, от, до, частей)
