def prose_marks(name):
    s = (name or "").lower().replace("ё", "е")
    f = set()
    if HARD_RE.search(s): f.add("лексика")
    for a, b in HARD_BIGRAMS:
        if a in s and b in s:
            f.add("оборот"); break
    if set(WORD.findall(s)) & PRED or PRED_TAIL.search(s): f.add("сказуемое")
    return f

CLOSED = frozenset(("лексика", "оборот"))

def row_marks(name, oem="", unit="", qty=None, dict_hit=False):
    sp = spec_marks(name, oem, unit, qty)
    if dict_hit: sp = sp | {"словарь"}
    pr = set() if sp else prose_marks(name)
    return sp, pr

def row_is_prose(sp, pr): return (not sp) and bool(pr & CLOSED)

def file_verdict(rows_all, spec_rows, prose_rows):
    if rows_all < MIN_ROWS: return "мало строк"
    if spec_rows / rows_all > MAX_SPEC_SHARE: return "есть признаки номенклатуры"
    if prose_rows < MIN_PROSE_ROWS: return "мало прозы"
    if prose_rows / rows_all < MIN_PROSE_SHARE: return "мало прозы"
    return "документация"
