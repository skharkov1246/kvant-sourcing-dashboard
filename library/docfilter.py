"""Спецификация или текст документа: признаки строки и вердикт по файлу.

ЗАЧЕМ. Разбор текстовых вложений (library/indexer.py, ветка разбора текста)
принимал за позицию спецификации ЛЮБУЮ строку длиннее восьми знаков. В lib_demand
из-за этого легла тендерная проза: извещения о закупке, проекты договоров, формы
КП — на 12.09.2026 это 369 171 строка из 1 451 732.

УСТРОЙСТВО. Признак может либо ЗАЩИЩАТЬ строку, либо ОБВИНЯТЬ её, и цена ошибки
у этих ролей разная. Ошибочная защита стоит полноты — мусор останется в базе и
будет виден числом. Ошибочное обвинение стоит спроса — настоящая позиция исчезнет
из аналитики. Поэтому:

  • защищают — щедро: стандарт (ГОСТ/DIN/ISO), типоразмер (45х65х10, Ду150, М12),
    количество с единицей в любом месте строки и в обоих порядках, марка
    (токен с буквами и цифрами или аббревиатура вида ВВГнг(А)-LS), заполненная
    структурная колонка (oem/unit/qty — в текстовой ветке они пусты всегда,
    поэтому непустая колонка доказывает, что строка пришла из таблицы);
  • обвиняет — только ЗАКРЫТЫЙ список: слова и обороты, невозможные в наименовании
    позиции («неустойка», «арбитражный», «ИНН», «настоящий договор», «календарных
    дней»). Признак «сказуемое» считается, но в обвинении НЕ участвует: русское
    описательное наименование по глагольным формам неотличимо от пункта договора.

Строка помечается, только если у неё нет НИ ОДНОГО защитного признака И есть
признак из закрытого списка И её файл получил вердикт «документация».

Смешанный файл (тендерный пакет с настоящей спецификацией внутри) не помечается
вообще — сознательная потеря полноты в пользу точности.

КАЛИБРОВКА. На корпусах из 97 строк настоящей номенклатуры непокрытых словарём
сегментов (крепёж, РТИ, кабель, спецодежда, химия) и 80 строк тендерной прозы:
ложных срабатываний 0, прозы поймано 22 из 40 характерных фраз. Скорость —
31 мкс на строку, то есть 1,45 млн строк за минуту на одном ядре.

Модуль намеренно без зависимостей: его импортируют тесты гейта (там нет ни
psycopg2, ни requests), разметка накопленного и сам индексатор. Одно правило на
два места вызова — иначе сухой прогон перестаёт быть измерением того, что
сделает разборщик.
"""
