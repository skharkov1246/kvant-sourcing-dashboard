"""Спецификация или текст документа: признаки строки и вердикт по файлу.

ЗАЧЕМ. Разбор текстовых вложений (library/indexer.py, ветка разбора текста)
принимал за позицию спецификации ЛЮБУЮ строку длиннее восьми знаков. В lib_demand
из-за этого легла тендерная проза: извещения о закупке, проекты договоров, формы
КП — на 12.09.2026 это 369 171 строка из 1 451 732.

УСТРОЙСТВО. Признак может либо ЗАЩИЩАТЬ строку, либо ОБВИНЯТЬ её, и цена ошибки
у этих ролей разная. Ошибочная защита стоит полноты — мусор останется в базе и
будет виден числом. Ошибочное обвинение стоит спроса — настоящая позиция исчезнет
из аналитики. Поэтому:

  • защищают — щедро: стандарт (ГОСТ/DIN/ISO), типоразмер (45х65х10, Ду150, М12),
    количество с единицей в любом месте строки и в обоих порядках, марка
    (токен с буквами и цифрами или аббревиатура вида ВВГнг(А)-LS), заполненная
    структурная колонка (oem/unit/qty — в текстовой ветке они пусты всегда,
    поэтому непустая колонка доказывает, что строка пришла из таблицы);
  • обвиняет — только ЗАКРЫТЫЙ список: слова и обороты, невозможные в наименовании
    позиции («неустойка», «арбитражный», «ИНН», «настоящий договор», «календарных
    дней»). Признак «сказуемое» считается, но в обвинении НЕ участвует: русское
    описательное наименование по глагольным формам неотличимо от пункта договора.

Строка помечается, только если у неё нет НИ ОДНОГО защитного признака И есть
признак из закрытого списка И её файл получил вердикт «документация».

Смешанный файл (тендерный пакет с настоящей спецификацией внутри) не помечается
вообще — сознательная потеря полноты в пользу точности.

КАЛИБРОВКА. На корпусах из 97 строк настоящей номенклатуры непокрытых словарём
сегментов (крепёж, РТИ, кабель, спецодежда, химия) и 80 строк тендерной прозы:
ложных срабатываний 0, прозы поймано 22 из 40 характерных фраз. Скорость —
31 мкс на строку, то есть 1,45 млн строк за минуту на одном ядре.

Модуль намеренно без зависимостей: его импортируют тесты гейта (там нет ни
psycopg2, ни requests), разметка накопленного и сам индексатор. Одно правило на
два места вызова — иначе сухой прогон перестаёт быть измерением того, что
сделает разборщик.
"""
from __future__ import annotations
import re

RULE_VERSION = "proza-v1"
MIN_ROWS = 25
MAX_SPEC_SHARE = 0.05
MIN_PROSE_ROWS = 15
MIN_PROSE_SHARE = 0.12

STD = re.compile(r"(?<![а-яёa-z])(гост|ост|ту|сто|стп|din|iso|en|astm|ansi|api|sae|jis|тр\s*тс)"
                 r"[\s.]*[рp]?[\s.]*\d", re.I)
SIZE = re.compile(r"\d\s*[хx×*]\s*\d")
DUPN = re.compile(r"(?<![а-яёa-z])(ду|ру|dn|pn|ф|м)\s*\d{1,4}(?![\d,.])", re.I)
UNIT = (r"шт|штук[аи]?|компл|комплект[аов]*|к-?т|набор[аов]*|пар[аыу]?|уп|упак|упаковк[аи]|"
        r"рулон[аов]*|бухт[аыу]|мешок|мешк[аов]+|ведро|вёдер|банк[аи]|бочк[аи]|канистр[аы]|"
        r"кг|гр|тн|тонн[аы]?|мм|см|дм|км|м2|м3|м²|м³|мл|литр[аов]*|барабан[аов]*|"
        r"пог\.?\s?м|п\.?\s?м|пм|секц[ияй]+|метр[аов]*|лист[аов]*|pcs|pc|ea|set|kg|pce")
QTY_UNIT = re.compile(r"(?<![а-яёa-z0-9])\d[\d\s.,]*\s*(?:" + UNIT + r")(?![а-яёa-z])", re.I)
UNIT_QTY = re.compile(r"(?<![а-яёa-z0-9])(?:" + UNIT + r")\.?\s+\d", re.I)
BARE_ML = re.compile(r"(?<![а-яёa-z0-9])\d[\d\s.,]*\s*[мл](?![а-яёa-z0-9])", re.I)
_DATE = re.compile(r"^\d{1,2}[.\-/]\d{1,2}[.\-/]\d{2,4}$|^\d{4}[.\-/]\d{1,2}[.\-/]\d{1,2}$")
_SECT = re.compile(r"^\d{1,2}\.\d{1,2}(\.\d{1,3})*$")
_LAW = re.compile(r"^\d{1,3}[-\s]?(фз|пп|рф|н)$", re.I)
_THOU = re.compile(r"^\d{1,3}([\s ]\d{3})+([.,]\d{1,2})?$")
TOKEN = re.compile(r"[0-9A-Za-zА-Яа-яЁё][0-9A-Za-zА-Яа-яЁё\-./()]*")
HASD = re.compile(r"\d")
HASL = re.compile(r"[A-Za-zА-Яа-яЁё]")
ABBR = re.compile(r"^[A-ZА-ЯЁ]{2,}(нг|мс)?(\([А-ЯЁA-Z]\))?([-/][0-9A-ZА-ЯЁ]+)+$")

def _clean(t): return t.strip(".,;:()")
def _rubbish(t):
    return bool(_DATE.match(t) or _SECT.match(t) or _LAW.match(t) or _THOU.match(t)
                or (t.isdigit() and len(t) == 4 and 1900 < int(t) < 2100))

def marks_pn(s):
    out = []
    for m in TOKEN.finditer(s or ""):
        t = _clean(m.group(0))
        if len(t) < 3 or _rubbish(t) or t.isdigit():
            continue
        if (HASD.search(t) and HASL.search(t) and len(t) >= 4) or ABBR.match(t):
            out.append(t)
    return out

def part_number_of(s):
    best = ""
    for m in TOKEN.finditer(s or ""):
        t = _clean(m.group(0))
        if len(t) < 4 or _rubbish(t):
            continue
        ok = (HASD.search(t) and HASL.search(t)) or (t.isdigit() and 6 <= len(t) <= 14) \
             or (re.fullmatch(r"\d{2,6}([-/]\d{2,6}){1,3}", t) is not None)
        if ok and len(t) > len(best):
            best = t
    return best[:120]

def spec_marks(name, oem="", unit="", qty=None):
    s = (name or "").strip()
    f = set()
    if (oem or "").strip() or (unit or "").strip() or qty is not None:
        f.add("колонка")
    if STD.search(s): f.add("стандарт")
    if SIZE.search(s) or DUPN.search(s): f.add("типоразмер")
    if QTY_UNIT.search(s) or UNIT_QTY.search(s) or BARE_ML.search(s): f.add("кол-во+ед")
    if marks_pn(s): f.add("марка")
    return f

HARD_PREFIX = ("форс-мажор", "форсмажор", "неустойк", "арбитражн", "оферт",
               "аукцион", "котировочн", "котировк", "извещени", "нижеподписавш",
               "грузополучател", "грузоотправител", "доверенност", "антимонопольн",
               "конфиденциальн", "расторжен", "претензи", "преддоговорн", "субподряд",
               "правопреемник", "аффилирован", "реквизит", "просрочк", "неисполнени",
               "третейск", "подсудност", "юрисдикц", "уведомлени", "разногласи")
HARD_EXACT = ("инн", "кпп", "огрн", "окпо", "бик", "пеня", "пени", "штраф", "штрафа",
              "акцепт", "акцепта", "акцепте")
HARD_RE = re.compile(r"(?<![а-яё])(?:" + "|".join(HARD_PREFIX) + r")"
                     r"|(?<![а-яё])(?:" + "|".join(HARD_EXACT) + r")(?![а-яё])")
HARD_BIGRAMS = (("участник", "закупк"), ("участник", "процедур"), ("предмет", "закупк"),
                ("закупочн", "документаци"), ("аукционн", "документаци"),
                ("конкурсн", "документаци"), ("настоящ", "договор"), ("настоящ", "контракт"),
                ("настоящ", "соглашени"), ("стороны", "обязу"), ("календарн", "дней"),
                ("рабочих", "дней"), ("банковск", "реквизит"), ("коммерческ", "предложени"),
                ("порядок", "расчет"), ("услови", "оплат"), ("гарантийн", "обязательств"),
                ("неотъемлем", "част"), ("одностороннем", "порядке"))
PRED = frozenset(("обязуется обязуются обязан обязана обязаны вправе является являются "
                  "допускается запрещается признается осуществляется осуществляются "
                  "производится оформляется подтверждает подтверждаем гарантирует несет "
                  "предоставляется устанавливается определяется считается направляем просим "
                  "согласны уплачивает возмещает освобождаются решаются размещено "
                  "принимаются указываются отказаться").split())
PRED_TAIL = re.compile(r"[а-яё]{4,}(ется|ются|лся|лась|лись|лось)(?![а-яё])")
WORD = re.compile(r"[а-яёa-z]+")

def prose_marks(name):
    s = (name or "").lower().replace("ё", "е")
    f = set()
    if HARD_RE.search(s): f.add("лексика")
    for a, b in HARD_BIGRAMS:
        if a in s and b in s:
            f.add("оборот"); break
    if set(WORD.findall(s)) & PRED or PRED_TAIL.search(s): f.add("сказуемое")
    return f

CLOSED = frozenset(("лексика", "оборот"))

def row_marks(name, oem="", unit="", qty=None, dict_hit=False):
    sp = spec_marks(name, oem, unit, qty)
    if dict_hit: sp = sp | {"словарь"}
    pr = set() if sp else prose_marks(name)
    return sp, pr

def row_is_prose(sp, pr): return (not sp) and bool(pr & CLOSED)

def file_verdict(rows_all, spec_rows, prose_rows):
    if rows_all < MIN_ROWS: return "мало строк"
    if spec_rows / rows_all > MAX_SPEC_SHARE: return "есть признаки номенклатуры"
    if prose_rows < MIN_PROSE_ROWS: return "мало прозы"
    if prose_rows / rows_all < MIN_PROSE_SHARE: return "мало прозы"
    return "документация"
