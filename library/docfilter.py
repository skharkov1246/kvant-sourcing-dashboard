_НЕ_КОД = tuple((класс, re.compile("(" + выр + ")")) for класс, выр in _КЛАССЫ_НЕ_КОДА)
# Одно выражение на все классы — ровно то, что стоит в lib_pn_plausible: ключ,
# целиком совпавший с ним, кодом не является. Классы нужны только замеру.
ВЫРАЖЕНИЕ_НЕ_КОДА = "^(" + "|".join(выр for _, выр in _КЛАССЫ_НЕ_КОДА) + ")$"
ВЫРАЖЕНИЕ_СТАНДАРТА = "^(" + _КЛАССЫ_НЕ_КОДА[0][1] + ")$"

# СТАНДАРТ С РАЗМЕРОМ — НОМЕР ДЕТАЛИ, А НЕ СТАНДАРТ. Кольцо «ГОСТ 9833-73
# 020-025-30», стопорное кольцо «DIN 471 25», подшипник «GB 276 6205»: ключ
# (гост98337302002530, din47125, gb2766205) целиком совпадает с классом
# «стандарт», потому что в ключе нет пробелов. По ключу голый стандарт от
# стандарта с размером не отличить: замер 25.09.2026 по живой базе (прогон
# 36114332994, scripts/code_rule_measure.py) — у каждой приставки длины цифр
# голых ключей накрывают длины ключей с размером, и лучший предел длины,
# подобранный по самим данным, отвергает все пять ключей с размером из пяти.
# Отличает НАПИСАНИЕ: второй числовой токен через пробел — размер. «ГОСТ
# 8752-79», «DIN 933», «ISO 9001:2015» — один числовой токен, это голый
# стандарт, и он обвиняется, как прежде.
#
# ЧИСЛОВОЙ ТОКЕН — С ДВУМЯ ЦИФРАМИ ПОДРЯД. Тот же замер: из 16 строк спроса, где
# у стандарта два токена с цифрой, 14 — голый стандарт, набранный вразрядку
# («G B / T 5 7 8 3 - 2 0 0 0», текст PDF). Одиночная цифра размером не
# считается; цена — размер из одной цифры («DIN 7 6») остаётся стандартом.
#
# Выражение одно на Python и SQL (lib_pn_plausible): цифры [0-9], пробел —
# явным списком (пробел, табуляция, перевод строки, неразрывный), без \s, \d и
# точки — их объём в Python и PostgreSQL разный. После пробела — что угодно без
# двух цифр подряд, потом две цифры: они уже в другом токене.
НАПИСАНИЕ_С_РАЗМЕРОМ = r"[0-9]{2}[^ \t\r\n\u00a0]*[ \t\r\n\u00a0]([^0-9]|[0-9][^0-9])*[0-9]{2}"
_С_РАЗМЕРОМ = re.compile(НАПИСАНИЕ_С_РАЗМЕРОМ)


def sql_правдоподобен(написание: str, ключ: str | None = None) -> str:
    """SQL-условие «ключ не марка, не размер, не стандарт» — тело lib_pn_plausible.

    Стандарт с размером в написании кодом остаётся (см. НАПИСАНИЕ_С_РАЗМЕРОМ).
    ключ — выражение ключа, если запрос его уже посчитал; иначе lib_pn_key от
    написания. Ключ без написания (x.code вместо d.part_number) пробелов не
    несёт, и стандарт с размером по нему обвиняется, как голый."""
    к = ключ or f"lib_pn_key({написание})"
    return (f"{к} !~ '{ВЫРАЖЕНИЕ_НЕ_КОДА}'"
            f" or ({написание} ~ '{НАПИСАНИЕ_С_РАЗМЕРОМ}' and {к} ~ '{ВЫРАЖЕНИЕ_СТАНДАРТА}')")


def sql_код_годен(выражение: str, ключ: str | None = None) -> str:
    """SQL-условие «код правдоподобен» для выражения запроса — тело
    lib_pn_plausible, вписанное прямо в запрос, плюс защита каталогом.

    выражение — НАПИСАНИЕ номера (part_number), а не его ключ: стандарт с
    размером отличается только по написанию. Если ключ уже посчитан, его
    выражение передаётся в ключ — чтобы не считать lib_pn_key второй раз.

    ПОЧЕМУ НЕ ВЫЗОВ ФУНКЦИИ. Миграции применяются вручную (zip-db.yml), а
    сборщики снимков идут по расписанию: вызов функции, которой в живой базе ещё
    нет, уронил бы публикацию страниц до применения схемы. Тело то же самое
    (сверяет tests/test_pn_plausible_sql.py), и планировщик всё равно
    встраивает однострочную SQL-функцию в запрос — по плану разницы нет.
    """
    # КАТАЛОГ ЗАЩИЩАЕТ (правило 7: защищай щедро, обвиняй закрытым списком).
    # Замер по живой базе 24.09.2026 (прогон 36059327675): закрытый список задел
    # 6 номеров курируемого каталога из 13 501 — размерные и «GB»-номера. Номер,
    # который есть в lib_parts, кодом считается всегда. Подзапрос не ссылается на
    # внешнюю строку и считается один раз (правило 8).
    к = ключ or f"lib_pn_key({выражение})"
    return (f"({sql_правдоподобен(выражение, к)}"
            f" or {к} in ({КАТАЛОГ_КЛЮЧЕЙ}))")


# Ключи курируемого каталога: и id, и ключ каталожного номера — у 82 деталей они
# расходятся (library/load_parts.py), защищать надо оба написания.
КАТАЛОГ_КЛЮЧЕЙ = ("select id from lib_parts union "
                  "select lib_pn_key(catalog_no) from lib_parts where catalog_no is not null")


def ключ_кода(t) -> str:
    """lib_pn_key на Python: регистр, потом «ё», потом только [0-9a-zа-я], 80 знаков."""
    return re.sub(r"[^0-9a-zа-я]", "", str(t or "").lower().replace("ё", "е"))[:80]


def класс_ключа(t) -> str | None:
    """Класс «не код» по одному КЛЮЧУ: «стандарт», «размер», «марка»; None — годен.

    Написание не смотрит: стандарт с размером здесь — «стандарт». Нужен там,
    где спрашивают «несёт ли ячейка число», а не «код ли это»: ячейка цены
    «DIN 471 25» цены не несёт (quotes.цена_строки)."""
    к = ключ_кода(t)
    if not к:
        return None
    for класс, rx in _НЕ_КОД:
        if rx.fullmatch(к):
            return класс
    return None


def стандарт_с_размером(t) -> bool:
    """Написание несёт второй числовой токен через пробел («DIN 471 25»);
    токен числовой, если в нём две цифры подряд (разрядка — не размер)."""
    return bool(_С_РАЗМЕРОМ.search(str(t or "")))


def класс_не_кода(t) -> str | None:
    """Почему написание — не код: «стандарт», «размер», «марка»; None — код годен.

    Судит ключ целиком (fullmatch), а стандарт — вместе с написанием: стандарт
    с размером («ГОСТ 9833-73 020-025-30») — номер детали, и кодом остаётся.
    Пустой ключ кодом не обвиняется: пустота — не марка, её отсеивают свои
    проверки."""
    кл = класс_ключа(t)
    if кл == "стандарт" and стандарт_с_размером(t):
        return None
    return кл


def код_правдоподобен(t) -> bool:
    """Код годен, если его ключ не марка, не размер и не голый стандарт
    (lib_pn_plausible)."""
    return класс_не_кода(t) is None


# Слова, рядом с которыми число — это сумма или цена, а не артикул.
MONEY = re.compile(r"(?<![а-яё])(рубл|руб\.|сумм|цена|цену|цены|стоимост|итого|ндс|тариф)", re.I)


def part_number_of(s):
    """Артикул из строки. Пусто — честный ответ: артикула в строке нет.

    Четыре отсева, каждый оплачен разбором ошибки:
      • мусор (_rubbish) — даты, номера пунктов, годы, разряды тысяч. Прежнее
        выражение на line.upper() принимало за артикул 01.09.2026 и 223-ФЗ;
      • типоразмер (45х65х10, 3х2,5) — это размер, а не артикул. Без отсева
        «Манжета 45х65х10 ГОСТ 8752-79» получала артикулом свой размер;
      • марка, размер с единицей и стандарт (код_правдоподобен): «SS316»,
        «19mm», «12Х18Н10Т» — свойства позиции, а не её номер;
      • голое число при денежных словах в строке — это сумма. Четырёхзначные
        числа принимаются, иначе теряются канонические номера подшипников
        (6205, 22315): в строке «Подшипник SKF 22315 EK» артикул — именно они."""
    text = s or ""
    money = bool(MONEY.search(text))
    best = ""
    for m in TOKEN.finditer(text):
        t = _clean(m.group(0))
        if len(t) < 4 or _rubbish(t) or SIZE.search(t):
            continue
        # Ду150, Ру16, М12 — условный проход и резьба, это параметр, а не артикул.
        if DUPN.match(t):
            continue
        # Марка стали, размер с единицей, стандарт — не артикул (код_правдоподобен).
        # Такой токен пропускается, и выбирается следующий по длине: в строке
        # «Клапан 12Х18Н10Т DN50 KV-4417-B» артикул — KV-4417-B, а не марка.
        if not код_правдоподобен(t):
            continue
        # Токен сразу после «№» — номер документа или позиции в списке.
        before = text[:m.start()].rstrip()
        if before.endswith("№") or before.endswith("No") or before.endswith("#"):
            continue
        ok = (HASD.search(t) and HASL.search(t)) \
             or (t.isdigit() and 4 <= len(t) <= 14 and not money) \
             or (re.fullmatch(r"\d{2,6}([-/]\d{2,6}){1,3}", t) is not None)
        if ok and len(t) > len(best):
            best = t
    return best[:120]

def spec_marks(name, oem="", unit="", qty=None):
    s = (name or "").strip()
    f = set()
    if (oem or "").strip() or (unit or "").strip() or qty is not None:
        f.add("колонка")
    if STD.search(s): f.add("стандарт")
    if SIZE.search(s) or DUPN.search(s): f.add("типоразмер")
    if QTY_UNIT.search(s) or UNIT_QTY.search(s) or BARE_ML.search(s): f.add("кол-во+ед")
    if marks_pn(s): f.add("марка")
    return f

