def _норм(текст: str) -> str:
    """Нижний регистр, «е» вместо «ё», неразрывные пробелы — обычными, без пустых строк.

    Пустые строки выбрасываются, чтобы «первые десять строк» значили десять строк
    текста, а не десять строк, из которых семь — пустые отбивки PDF."""
    т = (текст or "").lower().replace("ё", "е")
    т = т.replace(" ", " ").replace(" ", " ").replace("\t", " ")
    строки = (re.sub(r" {2,}", " ", s).strip() for s in т.split("\n"))
    return "\n".join(s for s in строки if s)


def _строки_таблицы(строки: list[list[str]] | None) -> list[list[str]]:
    """Ячейки строками: разборщик отдаёт и числа, и None."""
    return [["" if c is None else str(c) for c in r] for r in (строки or []) if r]


def _таблица(таблица: list[list[str]]) -> dict:
    """Шапка таблицы и сколько позиций в ней с ценой.

    Шапка — первая строка из двадцати, где нашлась ценовая колонка
    (quotes.колонки_цены) или пара «наименование + количество»."""
    итог = {"ценовая": False, "позиций": 0, "с_ценой": 0}
    шапка, цк = None, {}
    for i, r in enumerate(таблица[:20]):
        к = _q.колонки_цены(r)
        low = " | ".join(r).lower()
        if "price" in к or "total" in к or (_НАИМЕНОВАНИЕ.search(low) and _КОЛИЧЕСТВО.search(low)):
            шапка = i
            цк = {k: v for k, v in к.items() if k in ("price", "total")}
            break
    if шапка is None:
        return итог
    итог["ценовая"] = bool(цк)
    for r in таблица[шапка + 1:]:
        if sum(1 for c in r if c.strip()) < 2:
            continue
        итог["позиций"] += 1
        for j in цк.values():
            if j < len(r):
                v = _q.число_из(r[j])
                if v is not None and v > 0:
                    итог["с_ценой"] += 1
                    break
    return итог


# Куски текста для поиска цены по тройке «кол-во × цена = сумма». quotes бракует
# строку целиком, если в ней есть «Итого/НДС/всего», — а в сплошном тексте PDF
# строка одна на весь документ. Поэтому текст режется по строкам, по концам фраз
# и перед словами итога: позиции остаются отдельно от итоговой строки.
_РАЗРЕЗ = re.compile(r"\n|(?<=[!?;])\s+|(?<=[a-zа-я]{3}\.)\s+"
                     r"|\s+(?=итого|всего|в\s+т\.?\s*ч|в\s+том\s+числе|total)")


def _куски(текст: str) -> list[str]:
    return [к for к in _РАЗРЕЗ.split(текст) if к and к.strip()]


def _тройка(кусок: str) -> bool:
    """Цена по тройке в куске текста. Тройка с ценой ровно 1 отбрасывается: её
    складывает любой номер вида «CR-800-01, 1 pc» (800 × 1 = 800), а цены в одну
    денежную единицу в КП не бывает."""
    ц = _q.цена_из_текста(кусок)
    return bool(ц) and ц["price"] != 1.0


def _названо(образец: re.Pattern, текст: str) -> bool:
    """Совпадение, у которого рядом нет вопроса или требования.

    «Срок поставки 8 недель» — значение; «просим указать срок поставки» и «срок
    поставки не более 90 дней» — вопрос и требование, то есть признак запроса."""
    for m in образец.finditer(текст):
        окно = текст[max(0, m.start() - 40):m.end()]
        if not _ВОПРОС_ИЛИ_ТРЕБОВАНИЕ.search(окно):
            return True
    return False


def _граница(текст: str, m: re.Match) -> bool:
    """Настоящая ли это граница фразы, а не точка после сокращения."""
    if not m.group(0).startswith("."):
        return True
    слово = re.search(r"([a-zа-я\-]+)$", текст[max(0, m.start() - 8):m.start()])
    return not (слово and слово.group(1) in _СОКРАЩЕНИЯ)


def _начало_фразы(текст: str, поз: int) -> int:
    """Где начинается фраза с именем: после последней границы, не дальше ОКНО_МЕТКИ.

    Метка ищется только в своей фразе. Иначе в тексте одной строкой «перед
    именем» оказывается весь документ, и «Уважаемые коллеги!» из соседнего
    предложения делает наше «ООО «КВАНТ» предлагает» адресатом.

    Короткая предыдущая строка («Кому:», «Генеральному директору») к фразе
    присоединяется: это метка, стоящая над именем."""
    начало = max(0, поз - ОКНО_МЕТКИ)
    for m in _ГРАНИЦА.finditer(текст, начало, поз):
        if not _граница(текст, m):
            continue
        if m.group(0) == "\n":
            пред_начало = текст.rfind("\n", 0, m.start()) + 1
            if m.start() - пред_начало <= 25:
                continue
        начало = m.end()
    return начало


def _конец_фразы(текст: str, поз: int) -> int:
    """Где кончается фраза после имени — до первой настоящей границы, не дальше 250."""
    предел = min(len(текст), поз + 250)
    for m in _ГРАНИЦА.finditer(текст, поз, предел):
        if _граница(текст, m):
            return m.start()
    return предел


def _зона(текст: str, начало: int, конец: int) -> tuple[bool, bool]:
    """В шапке ли упоминание и в подписи ли — по строкам и по знакам сразу.

    В коротком документе зоны перекрываются; тогда упоминание относится к тому
    краю, к которому ближе, — иначе бланк в первой строке считался бы подписью, а
    подпись в конце однострочного текста — шапкой."""
    стр = текст.count("\n", 0, начало)
    всего_стр = текст.count("\n") + 1
    шапка = стр < ШАПКА_СТРОК and начало < ШАПКА_ЗНАКОВ
    подпись = стр >= всего_стр - ПОДПИСЬ_СТРОК and конец > len(текст) - ПОДПИСЬ_ЗНАКОВ
    if шапка and подпись:
        if начало <= len(текст) - конец:
            подпись = False
        else:
            шапка = False
    return шапка, подпись


def _реквизиты_рядом(текст: str, начало: int, конец: int) -> bool:
    """Реквизиты в окне вокруг имени (40 знаков до, 200 после) — признак бланка.

    Окно в знаках, а не в строках: в тексте одной строкой «та же строка» — это
    весь документ, и любое «Исх.» в нём делало бы бланком каждое упоминание."""
    return bool(_РЕКВИЗИТЫ.search(текст[max(0, начало - 40):конец + 200]))


def _адресный_блок_после(текст: str, конец: int) -> bool:
    """Сразу за именем «Генеральному директору» или «Иванову И.И.» — это адресат."""
    return bool(_АДРЕСНЫЙ_БЛОК.match(текст, конец))


def _последняя_метка(пред: str, адресат: re.Pattern) -> str | None:
    """Какая метка стоит ближе всего перед именем: адресата или отправителя.

    Ближайшая, а не первая: в «Поставщик: ООО «Х», Покупатель: ООО «КВАНТ»» перед
    КВАНТом есть обе, и решает «Покупатель»."""
    а = [m.end() for m in адресат.finditer(пред)]
    о = [m.end() for m in _ОТПРАВИТЕЛЬ.finditer(пред)]
    if not а and not о:
        return None
    return "адресат" if max(а, default=-1) > max(о, default=-1) else "отправитель"


def _конец_метки(пред: str, адресат: re.Pattern) -> int:
    """Где кончается ближайшая к имени метка (адресата или отправителя); -1 — нет."""
    концы = [m.end() for m in адресат.finditer(пред)] + [m.end() for m in _ОТПРАВИТЕЛЬ.finditer(пред)]
    return max(концы, default=-1)


# Что может стоять между формой собственности и её именем: кавычки, пробелы,
# запятая, скобки — «ООО «КВАНТ»», «KVANT LLC», «КВАНТ, ООО», «KVANT (LLC)».
_ЗАЗОР = re.compile(r"[\s«»\"'“”„‘’,()]*")
# Сколько знаков перед формой искать имя, которое она замыкает («Имя Из Трёх
# Слов LLC»). Имя длиннее этого в Битриксе не встречается.
ОКНО_ИМЕНИ = 120


def _своя_форма(текст: str, нач: int, кон: int, образец: re.Pattern) -> bool:
    """Форма собственности [нач, кон) — наша: наше имя вплотную за ней или перед ней.

    Прежде проверялось окно ±12 знаков, рассчитанное на короткое «КВАНТ»: имя
    длиннее десяти букв в окно не влезало, и своя форма становилась чужой
    организацией — одна компания была разом и нашей, и чужой (разведка
    23.09.2026). Теперь между формой и именем допускается только зазор из
    кавычек, пробелов, запятой и скобок, а длина имени не ограничена."""
    з = _ЗАЗОР.match(текст, кон)
    if образец.match(текст, з.end()):
        return True
    for н in образец.finditer(текст, max(0, нач - ОКНО_ИМЕНИ), нач):
        if _ЗАЗОР.fullmatch(текст, н.end(), нач):
            return True
    return False


def _автор(текст: str, образец: re.Pattern) -> set[str]:
    """Признаки автора по упоминаниям наших имён и чужих организаций.

    образец — наши имена (_образец_наших). Работает по позициям в тексте, а не по
    строкам: текст из PDF и распознавания часто приходит одной строкой, и ни одна
    проверка не должна от этого зависеть."""
    f: set[str] = set()
    for m in образец.finditer(текст):
        пред = текст[_начало_фразы(текст, m.start()):m.start()]
        хвост = текст[m.end():_конец_фразы(текст, m.end())]
        шапка, подпись = _зона(текст, m.start(), m.end())
        # Глагол, у которого наше имя — подлежащее: до него не должно стоять чужой
        # организации («ООО «КВАНТ» Иванову… ООО «Х» предлагает» — предлагает Х).
        # Своя форма собственности рядом с именем («KVANT LLC») чужой не считается.
        д = _ДЕЙСТВИЕ.search(хвост)
        if д and (any(not _своя_форма(текст, m.end() + o.start(), m.end() + o.end(), образец)
                      for o in _ОРГ.finditer(хвост, 0, д.start()))
                  or образец.search(хвост, 0, д.start())):
            д = None
        метка, где = _последняя_метка(пред, _АДРЕСАТ), _конец_метки(пред, _АДРЕСАТ)
        близкий_глагол = д is not None and д.start() <= БЛИЗКИЙ_ГЛАГОЛ
        if метка and not (близкий_глагол and len(пред) - где > БЛИЗКАЯ_МЕТКА):
            f.add("адресовано_нам" if метка == "адресат" else "отправитель_мы")
            continue
        # «ООО «КВАНТ», по Вашему запросу направляем…» — обращение к нам: «Вашему»
        # стоит раньше любого глагола с нашим именем-подлежащим. Адресный блок
        # («Иванову И.И.») сразу за именем — тоже адресат, что бы ни шло дальше.
        о = _ОБРАЩЕНИЕ.search(хвост[:60])
        if (о and (not д or о.start() < д.start())) or _адресный_блок_после(текст, m.end()):
            f.add("адресовано_нам")
        elif д:
            f.add("мы_действуем")
        elif _ПРИВЕТСТВИЕ.search(пред):
            f.add("адресовано_нам")
        elif подпись:
            f.add("подпись_наша")
        elif шапка:
            f.add("бланк_наш" if _реквизиты_рядом(текст, m.start(), m.end())
                  else "наше_имя_в_шапке")
    for m in _ОРГ.finditer(текст):
        # Организация наша, если наше имя стоит вплотную: «ООО «КВАНТ»», «KVANT LLC».
        if _своя_форма(текст, m.start(), m.end(), образец):
            continue
        шапка, подпись = _зона(текст, m.start(), m.end())
        if not (шапка or подпись):
            continue
        имя = _ИМЯ_В_КАВЫЧКАХ.match(текст, m.end())
        конец = имя.end() if имя else m.end()
        пред = текст[_начало_фразы(текст, m.start()):m.start()]
        if (_последняя_метка(пред, _АДРЕСАТ_СТРОГО) == "адресат"
                or _адресный_блок_после(текст, конец)):
            f.add("адресат_чужой")
        elif _последняя_метка(пред, _АДРЕСАТ_РОЛЬ) == "адресат":
            continue
        elif подпись:
            f.add("подпись_чужая")
        else:
            f.add("бланк_чужой" if _реквизиты_рядом(текст, m.start(), конец) else "имя_в_шапке")
    if not образец.search(текст):
        f.add("нет_имени")
    return f


def признаки(текст: str, строки: list[list[str]] | None = None, *,
             наши=None) -> dict[str, int]:
    """Сработавшие признаки содержимого: имя → сколько раз (или 1).

    наши — имена наших компаний (любые написания; см. с_транслитом). Без них
    признаки автора по имени (АВТОР_ПО_ИМЕНИ) не ставятся вовсе.

    Открыто для тестов и для разбора ошибок: по этому словарю видно, что увидел
    классификатор, до того как веса превратили это в папку."""
    образец = _образец(наши)
    таблица = _строки_таблицы(строки)
    строки_таблицы = [" | ".join(c for c in r if c.strip()) for r in таблица]
    основа = _норм(текст)
    # Зоны «шапка/подпись» считаются по тексту документа, а если его нет (xlsx без
    # текстового слоя) — по строкам таблицы. Склеивать оба нельзя: подпись текста
    # окажется в середине, а в конце — строки таблицы.
    текст_автора = основа or _норм("\n".join(строки_таблицы))
    весь = основа + "\n" + _норм("\n".join(строки_таблицы))

    f: dict[str, int] = {}
    if образец is not None:
        for имя in _автор(текст_автора, образец):
            f[имя] = 1

    т = _таблица(таблица)
    цены_текстом = sum(1 for кусок in _куски(весь) if _тройка(кусок))
    с_ценой = т["с_ценой"] + цены_текстом
    # Позиции — по числу совпадений «количество + единица», а не по строкам: в
    # сплошном тексте три позиции — это одна строка.
    строк_кол = max(sum(1 for s in весь.split("\n")
                        if _df.QTY_UNIT.search(s) or _df.UNIT_QTY.search(s)),
                    len(_df.QTY_UNIT.findall(весь)))
    позиций = max(т["позиций"], строк_кол)

    if с_ценой:
        f["цены_в_позициях"] = с_ценой
    if т["ценовая"] or _ЦЕНОВАЯ_ШАПКА_ТЕКСТ.search(весь):
        f["ценовая_шапка"] = 1
    if т["ценовая"] and т["позиций"] >= 2 and т["с_ценой"] == 0 and not цены_текстом:
        f["цены_не_заполнены"] = 1
    сумма = len(_СУММА_ДЕНЬГАМИ.findall(весь))
    if сумма:
        f["сумма_деньгами"] = сумма
    if позиций >= 3 and not с_ценой and not сумма:
        f["позиции_без_цен"] = позиций

    простые = (
        ("итог_ндс", _ИТОГ), ("оборот_предложения", _ОБОРОТ_ПРЕДЛОЖЕНИЯ),
        ("заголовок_предложения", _ЗАГОЛОВОК_ПРЕДЛОЖЕНИЯ), ("ответ_на_запрос", _ОТВЕТ),
        ("оборот_запроса", _ОБОРОТ_ЗАПРОСА), ("заголовок_запроса", _ЗАГОЛОВОК_ЗАПРОСА),
        ("заголовок_тз", _ЗАГОЛОВОК_ТЗ),
        ("цена_ориентир", _ЦЕНА_ОРИЕНТИР), ("договор", _ДОГОВОР), ("к_договору", _К_ДОГОВОРУ),
        ("счёт", _СЧЁТ), ("подписи_сторон", _ПОДПИСИ_СТОРОН),
        ("подтверждение_заказа", _ПОДТВЕРЖДЕНИЕ), ("отказ", _ОТКАЗ),
        ("обороты_письма", _ОБОРОТЫ_ПИСЬМА), ("форма_письма", _ФОРМА_ПИСЬМА),
        ("внутренний_расчёт", _ВНУТРЕННИЙ), ("вх_номер", _ВХ),
    )
    for имя, образец in простые:
        if образец.search(весь):
            f[имя] = 1
    for имя, образец in (("заголовок_предложения", _НОМЕР_ПРЕДЛОЖЕНИЯ),
                         ("заголовок_запроса", _НОМЕР_ЗАПРОСА)):
        if имя in f:
            continue
        for m in образец.finditer(весь):
            if not _ССЫЛКА.search(весь[max(0, m.start() - 15):m.start()]):
                f[имя] = 1
                break
    # Язык ТЗ — по числу оборотов: одно «не более» бывает и в КП.
    if len(_ЯЗЫК_ТЗ.findall(весь)) >= 3:
        f["язык_тз"] = 1
    for имя, образец in (("срок_назван", _СРОК_НАЗВАН), ("оплата_названа", _ОПЛАТА_НАЗВАНА),
                         ("срок_действия", _СРОК_ДЕЙСТВИЯ)):
        if _названо(образец, весь):
            f[имя] = 1
    # «Без предмета» — письмо, в котором нет ни цен, ни позиций, ни запроса, ни
    # предложения, ни договора. Без формы письма это не письмо, а просто текст.
    предмет = ("цены_в_позициях", "сумма_деньгами", "оборот_запроса", "заголовок_запроса",
               "заголовок_тз", "заголовок_предложения", "оборот_предложения", "договор",
               "к_договору", "счёт", "подтверждение_заказа")
    # Слова о цене и предложении — уже предмет, даже если оборот не опознан: такое
    # письмо лучше оставить «не определено», чем назвать письмом без предмета.
    if ("форма_письма" in f and позиций == 0 and not any(k in f for k in предмет)
            and not _ЦЕНОВАЯ_ЛЕКСИКА.search(весь)):
        f["без_предмета"] = 1
    return f


def _softmax(баллы: dict[str, float]) -> dict[str, float]:
    м = max(баллы.values())
    e = {k: math.exp(v - м) for k, v in баллы.items()}
    s = sum(e.values())
    return {k: v / s for k, v in e.items()}


# doc_kind_why обрезается записью до 300 знаков (indexer.py, reparse.py). Обрезка
# хвоста унесла бы ось автора целиком — а она и решает «наше или поставщика».
# Поэтому бюджет делится между осями заранее: у каждой — самые весомые признаки,
# остаток — числом.
ДЛИНА_ПОЧЕМУ = 300


def _список(пары: list[tuple[str, float]], предел: int | None = None) -> str:
    """«подпись +2.5; подпись −1.5» по убыванию модуля: главное — первым."""
    if not пары:
        return "признаков нет"
    пары = sorted(пары, key=lambda p: -abs(p[1]))
    показ = пары if предел is None else пары[:предел]
    текст = "; ".join(f"{подпись} {'+' if вес > 0 else '−'}{abs(вес):.1f}"
                      for подпись, вес in показ)
    if len(показ) < len(пары):
        текст += f"; ещё {len(пары) - len(показ)}"
    return текст


def вид_документа(текст: str, строки: list[list[str]] | None = None,
                  сторона_поля: str | None = None, *,
                  наши=None, длина_почему: int | None = None) -> tuple[str, float, str]:
    """Папка документа, уверенность 0..1 и почему — словами.

    текст         — текст документа (текстовый слой, распознанный скан, тело письма);
    строки        — строки таблицы, если разборщик её нашёл (xlsx, таблица PDF);
    сторона_поля  — сторона по названию поля карточки (doc_side.сторона): априорная
                    вероятность, а не ответ;
    наши          — имена наших компаний. Не передан или пуст — автор НЕ
                    ОПРЕДЕЛЁН: вероятность «мы» ровно 0,5, признаки автора не
                    считаются, и папки, которым нужен автор, уходят в «не
                    определено». Молча считать нашим одно имя нельзя: так
                    документ другой нашей компании читался чужим;
    длина_почему  — сколько знаков отдано «почему» (по умолчанию ДЛИНА_ПОЧЕМУ).
                    Меньше — когда вызывающий дописывает к нему своё, а запись
                    держит всего 300 знаков: списки признаков сокращаются по
                    обеим осям, а не срезается хвост с автором.

    У «не определено» уверенность — это уверенность лучшей отвергнутой догадки
    (она всегда ниже ПОРОГ), а «почему» называет эту догадку: разряд должен
    разбираться, а не копиться.
    """
    if not (текст or "").strip() and not _строки_таблицы(строки):
        return НЕ_ОПРЕДЕЛЕНО, 0.0, "текста нет"
    автор_известен = _образец(наши) is not None
    f = признаки(текст, строки, наши=наши)
    сторона = сторона_поля if сторона_поля in АПРИОРИ_ПОЛЯ else _ds.НЕИЗВЕСТНО
    априори_д, априори_а = АПРИОРИ_ПОЛЯ[сторона]
    if not автор_известен:
        априори_а = 0.0

    баллы = {д: 0.0 for д in ДЕЙСТВИЯ}
    автор = 0.0
    for имя in f:
        _, вклад, а = ВЕСА[имя]
        for д, w in вклад.items():
            баллы[д] += w
        if автор_известен:
            автор += а
    for д, w in априори_д.items():
        баллы[д] += w
    автор += априори_а

    p = _softmax(баллы)
    # Без списка наших компаний ось автора не решается ничем: ни имени, ни поля.
    # 0,5 ровно — и папки «мы / не мы» не дотягивают до порога сами, без
    # особого случая, так что инвариант «папка ⇔ уверенность ≥ ПОРОГ» держится.
    p_мы = 1.0 / (1.0 + math.exp(-автор)) if автор_известен else 0.5
    кандидаты = {
        ПРЕДЛОЖЕНИЕ_ПОСТАВЩИКА: p[ПРЕДЛОЖЕНИЕ] * (1 - p_мы),
        НАШЕ_ПРЕДЛОЖЕНИЕ: p[ПРЕДЛОЖЕНИЕ] * p_мы,
        ЗАПРОС_ЗАКАЗЧИКА: p[ЗАПРОС] * (1 - p_мы),
        НАШ_ЗАПРОС: p[ЗАПРОС] * p_мы,
        ДОГОВОР: p[ДОГОВОРНОЕ],
        ПИСЬМО: p[ИЗВЕЩЕНИЕ],
    }
    лучшая = max(кандидаты, key=lambda k: кандидаты[k])
    ув = кандидаты[лучшая]
    # ПОЛЕ СПОРИТ С КОНТРАГЕНТОМ. У папок «не мы» контрагент задан самой папкой:
    # предложение — от поставщика, запрос — от заказчика. Содержимое их почти не
    # различает (вопрос поставщика нам «просим сообщить срок» читается запросом),
    # а поле различает. Спор снижает уверенность и может увести только в «не
    # определено»: штраф ложится на уже выбранную папку и на другую её не меняет.
    конфликт = (лучшая, сторона) in КОНФЛИКТ_ПОЛЯ
    if конфликт:
        ув *= ШТРАФ_КОНФЛИКТА

    # Почему: сначала действие, потом автор — в этом порядке их и читают при разборе.
    действие = max(p, key=lambda k: p[k])
    за_действие = [(ВЕСА[k][0], ВЕСА[k][1][действие]) for k in f if действие in ВЕСА[k][1]]
    if действие in априори_д:
        за_действие.append((f"поле «{сторона}»", априори_д[действие]))
    второе = sorted(p, key=lambda k: -p[k])[1]
    # Соседнее действие называется, только если оно хоть сколько-то спорило.
    следом = f" (следом {второе} {p[второе]:.2f})" if p[второе] >= 0.05 else ""
    за_автора = [(ВЕСА[k][0], ВЕСА[k][2]) for k in f if ВЕСА[k][2]]
    if априори_а:
        за_автора.append((f"поле «{сторона}»", априори_а))
    кто = "мы" if p_мы >= 0.5 else "не мы"
    нужен_автор = лучшая in (ПРЕДЛОЖЕНИЕ_ПОСТАВЩИКА, НАШЕ_ПРЕДЛОЖЕНИЕ, ЗАПРОС_ЗАКАЗЧИКА,
                             НАШ_ЗАПРОС)
    # Без списка «лучшая догадка» между «мы» и «не мы» — ничья, и называть одну
    # из двух папок значило бы выдумать автора. Называется только действие.
    догадка = (f"{действие}, автор не определён" if нужен_автор and not автор_известен
               else лучшая)
    приставка = (f"ниже порога {ПОРОГ:.2f}: лучшая догадка «{догадка}» {ув:.2f} | "
                 if ув < ПОРОГ else "")
    хвост = f" | поле «{сторона}» спорит ×{ШТРАФ_КОНФЛИКТА}" if конфликт else ""

    def собрать(предел: int | None) -> str:
        т = f"{действие} {p[действие]:.2f}: {_список(за_действие, предел)}{следом}"
        if нужен_автор and not автор_известен:
            т += " | автор не определён: наши компании не заданы"
        elif нужен_автор:
            т += f" | автор {кто} {max(p_мы, 1 - p_мы):.2f}: {_список(за_автора, предел)}"
        return приставка + т + хвост

    бюджет = длина_почему or ДЛИНА_ПОЧЕМУ
    подробно = собрать(None)
    for предел in (5, 4, 3, 2, 1):
        if len(подробно) <= бюджет:
            break
        подробно = собрать(предел)

    if ув < ПОРОГ:
        return НЕ_ОПРЕДЕЛЕНО, round(ув, 3), подробно
    return лучшая, round(ув, 3), подробно
