def _чистое_имя(имя: str) -> str:
    """Имя без регистра, «ё», кавычек и формы собственности: «ООО «Квант»» → «квант»."""
    т = (имя or "").lower().replace("ё", "е")
    т = re.sub(r"[«»\"'“”„‘’`]", " ", т)
    т = _ФОРМА_В_ИМЕНИ.sub(" ", т)
    return re.sub(r"[\s,.;:()]+", " ", т).strip(" -")


def годное_имя(имя: str) -> bool:
    """Годится ли имя для поиска: не короче трёх букв и не одно родовое слово."""
    ч = _чистое_имя(имя)
    return len(re.findall(r"[а-яa-z]", ч)) >= 3 and ч not in _НЕ_ИМЯ


def с_транслитом(имена) -> tuple[str, ...]:
    """Имена плюс латинское написание кириллических: «КВАНТ» → («КВАНТ», «kvant»).

    Битрикс хранит название нашей компании одним написанием, а в английском
    документе оно стоит латиницей («KVANT LLC»). Без латинского написания такой
    документ читается чужим — и знак автора переворачивается (замер разведки
    23.09.2026: запрос заказчика «To: KVANT LLC» уходил в «наш запрос» 0,98).
    Транслит — догадка, но безвредная: не совпал — просто молчит."""
    out: list[str] = []
    for имя in имена or ():
        if not имя or not годное_имя(имя):
            continue
        ч = _чистое_имя(имя)
        for вариант in (ч, "".join(_ТРАНСЛИТ.get(б, б) for б in ч)):
            if вариант not in out and годное_имя(вариант):
                out.append(вариант)
    return tuple(out)


def _буквы(т: str) -> str:
    return "".join(_КЛАСС_БУКВЫ.get(б) or (r"\s+" if б == " " else r"[-\s]?" if б == "-"
                                           else re.escape(б)) for б in т)


def _образец_имени(имя: str) -> str:
    """Образец одного чистого имени: двойники классами, падежи у кириллицы."""
    if not re.search(r"[а-я]", имя):
        return _буквы(имя)          # латинское имя не склоняется
    последняя = имя[-1]
    if последняя in "ая":
        return _буквы(имя[:-1]) + "(?:" + "|".join(_буквы(о) for о in _ОКОНЧАНИЯ_А) + ")"
    if последняя in _ГЛАСНЫЕ_И_ЗНАКИ:
        return _буквы(имя)          # несклоняемое: «Энеротери»
    return _буквы(имя) + "(?:" + "|".join(_буквы(о) for о in _ОКОНЧАНИЯ_СОГЛАСНАЯ) + ")?"


@functools.lru_cache(maxsize=16)
def _образец_наших(наши: tuple[str, ...]) -> re.Pattern | None:
    """Один образец на все наши имена; кешируется по кортежу имён.

    Имя, негодное для поиска («ООО», две буквы), — ошибка вызывающего, и видна
    она сразу, а не молча на каждом файле. Само имя в сообщение не идёт
    (правило 17: сообщение доезжает до журнала).

    Граница справа запрещает дефис с продолжением: «Квант-Энерго» — чужая
    компания, а не мы (прежний образец её принимал: разведка 23.09.2026)."""
    имена: list[str] = []
    for имя in наши:
        if not годное_имя(имя):
            raise ValueError("имя нашей компании не годится для поиска: "
                             "короче трёх букв или только форма собственности")
        ч = _чистое_имя(имя)
        if ч not in имена:
            имена.append(ч)
    if not имена:
        return None
    имена.sort(key=len, reverse=True)          # длинное имя — раньше своего начала
    альтернативы = "|".join(_образец_имени(ч) for ч in имена)
    return re.compile(r"(?<![а-яa-z])(?:" + альтернативы + r")(?![а-яa-z])(?!-[а-яa-z])")


def _образец(наши) -> re.Pattern | None:
    return _образец_наших(tuple(наши)) if наши else None
