"""Запись цены из КП в lib_prices — одним местом для всех разборов.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Разборов у нас два: обычный (indexer.py) и распознавание
сканов (ocr.py). Оба кладут позиции в lib_demand, и оба обязаны класть цену.
CLAUDE.md, правило 14: две вставки в одну таблицу правятся вместе — колонка,
добавленная в одну, роняет вторую на каждой строке, ошибка молча уходит в
счётчик пропущенных, а файл уже отмечен разобранным. Здесь их не две: она одна,
и разойтись им негде.

СВЯЗЬ С ПОСТАВЩИКОМ НЕ ПРИДУМЫВАЕТСЯ. supplier_id не заполняется: там внешний
ключ на lib_suppliers, старый справочник, а ключ портала ведёт в sup_identifier
нового реестра. Пишется rfq_company, а соединяет их вид sup_quote_price.
"""

from __future__ import annotations

FEED = "разбор КП"
ИСТОЧНИК = "КП"

# ЦЕНА СО СКАНА — ТОТ ЖЕ ПОТОК, ДРУГОЙ ИСТОЧНИК. Поток (feed) остаётся «разбор
# КП»: по нему цену читают все виды (sup_quote_price, lib_work_queue, сводки
# покрытия), и цена со скана — такой же ответ поставщика. Источник (source)
# другой, и по нему каждый писатель снимает ТОЛЬКО свои строки: распознавание
# смешанного PDF добавляет цены страниц-сканов к ценам разбора текстовых страниц,
# и снятие по одному файлу стирало бы вклад соседа (перепроверка 23.09.2026).
ИСТОЧНИК_СКАНА = "распознавание скана"

# ВЫВЕДЕНА ИЗ ПОТОКА, НО НЕ УДАЛЕНА. Цены распознавания при повторе и откате не
# удаляются, а переходят в этот поток: виды читают только FEED и их не видят,
# а откат возвращает их одной командой (CLAUDE.md, правило 5). Кто и когда
# вывел — в журнале распознавания lib_ocr_writes.
FEED_ВЫВЕДЕНО = "разбор КП: выведено"

# ЦЕНА ИЗ ПИСЬМА ПОСТАВЩИКА — СВОЙ ПОТОК (indexer.MAIL_PRICES, вход prices
# прогона library-mail.yml). Не «разбор КП» намеренно: все виды и страницы
# читают цену по feed = 'разбор КП', и поток писем в них не попадает, пока
# владелец не решит по замеру, что ему там место. Снимается и откатывается
# одной командой по feed, как всякий поток (CLAUDE.md, правило 5).
#
# ПРИВЯЗКА К ПИСЬМУ — БЕЗ НОВЫХ КОЛОНОК. rfq_id хранит то же, что у карточки
# запроса: номер владельца файла ровно как в lib_files.deal_id и
# lib_demand.deal_id — у письма это номер с буквой сущности (C — компания,
# K — контакт, mail_source.БУКВА_ВЛАДЕЛЬЦА). Номер самого письма — по
# source_url: вложение «mail:<Диск>» → lib_files.field «письмо <номер>», тело
# «mail-body:<номер письма>» несёт его прямо в ключе. rfq_company — номер
# компании портала, если письмо висит на компании; у письма контакта пусто.
FEED_ПИСЬМА = "письмо поставщика"
ИСТОЧНИК_ПИСЬМА = "КП из письма"

КОЛОНКИ = ("segment_id", "item_name", "part_number", "oem", "price", "currency",
           "basis", "qty", "qty_unit", "source_url", "rfq_id", "rfq_company",
           "rfq_brands", "lead_days", "source", "feed", "confidence", "note",
           "price_date",
           # Коммерческие условия предложения — распоряжение владельца 22.09.2026.
           # Сумма хранится, а не только участвует в расчёте цены: «цена ×
           # количество = сумма» — единственная самопроверка ценовой строки.
           "total", "make_days", "pay_terms", "pay_advance_pct",
           # Откуда взято каждое условие. «нет» значит «искали в строке и в тексте
           # файла, не написано» — то есть верифицированное отсутствие, а не
           # пустота от того, что разбор не дошёл (library/offer_terms.py).
           "basis_src", "pay_src", "lead_src", "make_src",
           # Откуда дата квотации (price_date): документ, письмо, карточка или
           # «нет» — library/quote_date.py. Распоряжение владельца 24.09.2026.
           "price_date_src")

# НЕОБЯЗАТЕЛЬНЫЕ КОЛОНКИ — те, без которых запись цены не должна падать, если
# миграция до живой базы ещё не дошла. Риск записан в плане
# (docs/suppliers/IMPLEMENTATION_PLAN.md, «новые колонки lib_prices уронят ночной
# разбор КП»): ночной разбор идёт по расписанию, а схему применяет отдельный
# прогон. Без колонки источника дата квотации всё равно пишется в price_date,
# а источник появится после миграции и досчёта (library/quote_dates_backfill.py).
НЕОБЯЗАТЕЛЬНЫЕ = ("price_date_src",)


def вставка(колонки=КОЛОНКИ) -> str:
    return f"""
insert into lib_prices
  ({", ".join(колонки)})
values %s"""


ВСТАВКА = вставка()

# Колонки lib_prices, которые видит текущий путь поиска (search_path): тесты
# держат свою таблицу в отдельной схеме, прод — в public.
КОЛОНКИ_БАЗЫ = ("select column_name from information_schema.columns"
                " where table_name = 'lib_prices'"
                " and table_schema = any(current_schemas(false))")


def под_базу(cur, буфер: list[tuple]) -> tuple[str, list[tuple]]:
    """Запрос вставки и строки ровно под колонки, которые в базе есть.

    Снимаются только НЕОБЯЗАТЕЛЬНЫЕ: нет обязательной колонки — вставка падает, и
    это правильно (ПОДСКАЗКА называет, что применить). Пропуск печатается
    предупреждением: молчаливая потеря источника даты хуже упавшего прогона.
    """
    cur.execute(КОЛОНКИ_БАЗЫ)
    есть = {r[0] for r in cur.fetchall()}
    нет = [к for к in НЕОБЯЗАТЕЛЬНЫЕ if к not in есть]
    if not нет or not есть:
        return ВСТАВКА, буфер
    print(f"::warning::в lib_prices нет колонок {', '.join(нет)} — цены пишутся без "
          "них; примените library/supabase/schema.sql", flush=True)
    места = [i for i, к in enumerate(КОЛОНКИ) if к not in нет]
    return (вставка(tuple(КОЛОНКИ[i] for i in места)),
            [tuple(r[i] for i in места) for r in буфер])

# Идемпотентность по файлу: переразбор того же КП снимает свои прежние строки.
# Естественного ключа у цены нет (одна позиция законно имеет и цену, и сумму),
# поэтому ключ — файл, из которого она пришла.
#
# СВОИ — ЭТО ПОТОК И ИСТОЧНИК, А НЕ ТОЛЬКО ПОТОК. Разбор снимает всё своего
# потока, КРОМЕ цен со сканов: их пишет распознавание, и переразбор смешанного
# PDF иначе стирал бы цены страниц, которых сам не читает. «is distinct from», а
# не «=»: строки без источника, если такие есть, — разбора, и повтор их снимает.
СНЯТЬ = ("delete from lib_prices where feed = %s and source is distinct from %s"
         " and source_url = any(%s)")

# Свои прежние цены распознавания одного файла выводятся из потока (не
# удаляются); ключи выведенных возвращаются, чтобы откат знал, что возвращать.
ВЫВЕСТИ_СКАН = ("update lib_prices set feed = %s where feed = %s and source = %s"
                " and source_url = %s returning id")

_ФАЙЛ = КОЛОНКИ.index("source_url")
_ПОТОК = КОЛОНКИ.index("feed")


def строка(поз: dict, ц: dict, обрезать, источник: str = ИСТОЧНИК,
           поток: str = FEED) -> tuple:
    """Позиция плюс её ценовая часть → кортеж ровно под КОЛОНКИ.

    БАЗИС И СРОК БЕРУТСЯ ИЗ СВОДА, А НЕ ИЗ ЦЕНОВОЙ ЧАСТИ. Свод (offer_terms.свести)
    знает и колонку позиции, и общие условия КП, и то, что поле проверено дважды и
    отсутствует. Ценовая часть знает только свою строку, поэтому её базис и срок —
    лишь одно из слагаемых свода. Свода нет (старый вызов, разбор без условий) —
    работают значения ценовой части, и поведение остаётся прежним.
    """
    свод = поз.get("_условия") or {}
    базис = свод.get("basis", ц.get("basis")) if свод else ц.get("basis")
    срок = свод.get("lead_days", ц.get("lead_days")) if свод else ц.get("lead_days")
    return (поз.get("segment_id"), обрезать(поз.get("item_name"))[:500],
            обрезать(поз.get("part_number"))[:120],
            обрезать(поз.get("oem"))[:200] or None,
            ц["price"], ц["currency"], базис, поз.get("qty"),
            обрезать(поз.get("unit"))[:40], поз["source_file"], поз.get("deal_id"),
            поз.get("company"), обрезать(поз.get("brands"))[:200] or None,
            срок, источник, поток, ц["confidence"],
            обрезать(ц.get("note"))[:300] or None,
            # ДАТА КВОТАЦИИ, А НЕ ДАТА РАЗБОРА. Пусто, если её не нашли ни в КП,
            # ни на карточке (источник тогда «нет»); старый вызов без даты
            # оставляет и источник пустым — «не проверено», а не «нет».
            поз.get("price_date") or None,
            ц.get("total"), свод.get("make_days"),
            обрезать(свод.get("pay_terms"))[:120] or None,
            свод.get("pay_advance_pct"),
            свод.get("basis_src"), свод.get("pay_terms_src"),
            свод.get("lead_days_src"), свод.get("make_days_src"),
            поз.get("price_date_src"))


def записать(cur, буфер: list[tuple], execute_values) -> None:
    """Снять прежние строки этих файлов и вставить новые.

    Построчного досыла здесь НЕТ намеренно: пакет цен падает целиком только по
    одной причине — в базе нет колонок, которые добавляет миграция (их список —
    ДОБАВЛЕННЫЕ_МИГРАЦИЕЙ). Тогда не пройдёт и построчная вставка, а файлы уже
    были бы отмечены разобранными, и цены пропали бы молча. Вызывающий обязан
    откатить всё и упасть.
    """
    if not буфер:
        return
    запрос, строки = под_базу(cur, буфер)
    # Снимаются прежние строки КАЖДОГО потока буфера по его же файлам: поток
    # писем (FEED_ПИСЬМА) не трогает «разбор КП», и наоборот. У буфера одного
    # потока — ровно один прежний оператор с прежними параметрами.
    for поток in sorted({r[_ПОТОК] for r in буфер}):
        файлы = sorted({r[_ФАЙЛ] for r in буфер if r[_ПОТОК] == поток})
        cur.execute(СНЯТЬ, (поток, ИСТОЧНИК_СКАНА, файлы))
    execute_values(cur, запрос, строки, page_size=500)


_ИСТОЧНИК = КОЛОНКИ.index("source")


def записать_скан(cur, файл: str, буфер: list[tuple], execute_values,
                  ) -> tuple[list[int], list[int]]:
    """Цены распознавания одного файла: вывести свои прежние, вставить новые.

    Возвращает (ключи вставленных, ключи выведенных) — их хранит журнал
    распознавания, и по ним откат возвращает прежнее состояние. Цен разбора
    не касается: снимается только поток FEED с источником ИСТОЧНИК_СКАНА.
    """
    чужие = [r for r in буфер if r[_ФАЙЛ] != файл or r[_ИСТОЧНИК] != ИСТОЧНИК_СКАНА]
    if чужие:
        raise ValueError(f"в буфере распознавания файла {len(чужие)} цен чужого файла "
                         "или источника: вывод прежних их бы не снял")
    cur.execute(ВЫВЕСТИ_СКАН, (FEED_ВЫВЕДЕНО, FEED, ИСТОЧНИК_СКАНА, файл))
    выведены = [r[0] for r in cur.fetchall()]
    if not буфер:
        return [], выведены
    запрос, строки = под_базу(cur, буфер)
    новые = execute_values(cur, запрос + " returning id", строки, page_size=500,
                           fetch=True)
    return [r[0] for r in новые], выведены


# Колонки, которых в lib_prices не было изначально: их добавляет миграция, и
# именно их отсутствие роняет пакет. Список отдельной константой, потому что
# подсказку читают в момент падения ночного прогона, и устаревшая подсказка
# отправляет чинить не то: до 21.09.2026 она называла три колонки из пяти.
