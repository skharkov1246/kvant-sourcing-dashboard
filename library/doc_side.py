# РЕГУЛЯРКИ ДЛЯ НАЗВАНИЙ, КОТОРЫХ В СЛОВАРЕ НЕТ. Порядок значим и взят из
# gt/tools/bitrix_tkp.py: «наше исходящее» проверяется РАНЬШЕ «входящего», иначе
# «Processed file for supplier» (наш файл, отправленный поставщику) попадёт во
# входящие по слову supplier. Это не гипотетическая ошибка: именно её порядок и
# чинит.
ПО_ОБРАЗЦУ = (
    (re.compile(r"offer\s+from\s+us|наше?\s+кп|request\s+file|запрос\s+цен"
                r"|запрос\s+оферт|processed\s+file\s+for\s+supplier"
                r"|result\W*ткп|образец\s+ткп", re.I), МЫ),
    (re.compile(r"economics\s+of\s+the\s+project|экономика\s+проекта"
                r"|сравнени\w*\s+предложени|bank\s+details|perplexity", re.I), ВНУТРЕННИЙ),
    (re.compile(r"offer\s+from\s+supplier|кп\s+поставщика|supplier\s+offer"
                r"|offer\W*old|processed\s+offer|order\s+confirmation"
                r"|agreement\s+with\s+supplier", re.I), ПОСТАВЩИК),
    (re.compile(r"техническ\w*\s+специф|technical\s+data\s+from\s+customer"
                r"|customer\s+request|specification\s*\(file\)"
                r"|мануал|чертеж|шильд", re.I), ЗАКАЗЧИК),
)


def сторона(название: str | None) -> str:
    """Сторона документа по названию поля. При сомнении — «неизвестно».

    Точное совпадение сильнее образца: словарь собран по живым данным, а образец
    — обобщение, и обобщение не должно перебивать факт.
    """
    имя = (название or "").strip()
    if not имя:
        return НЕИЗВЕСТНО
    точно = ПО_НАЗВАНИЮ.get(имя)
    if точно:
        return точно
    for образец, сторона_ in ПО_ОБРАЗЦУ:
        if образец.search(имя):
            return сторона_
    return НЕИЗВЕСТНО


# СПРОС — ЭТО ТОЛЬКО ЗАЯВКА ЗАКАЗЧИКА. Ни наш исходящий документ, ни предложение
# поставщика, ни наша внутренняя экономика спросом не являются: позиция в них
# либо уже прокотирована, либо это вообще наша цена продажи.
#
# «Неизвестно» СПРОСОМ НЕ СЧИТАЕТСЯ — и это осознанный выбор в пользу точности
# против полноты. Неопознанное поле попадает в отдельный разряд, который видно
# числом; записав его в спрос, мы вернули бы ту же тавтологию через чёрный ход, и
# заметить это было бы нечем.
СПРОС = (ЗАКАЗЧИК,)


def это_спрос(название: str | None) -> bool:
    return сторона(название) in СПРОС
