def правка_файла(колонки: tuple[str, ...]) -> str:
    """UPDATE lib_files ровно по колонкам, которые есть в базе.

    Значения — indexer.строка_файла, та же, что у вставки разбора (правило 14).
    Колонки из indexer.НЕ_ЗАТИРАТЬ_ПУСТЫМ пустым значением не затираются, пока
    список наших компаний не прочитался (indexer.не_затирать_пустым): сбой чтения
    иначе стёр бы our_company у каждого файла прогона. Без сбоя пустое — факт.
    Колонки из indexer.ДОПОЛНЯТЬ_ПУСТОЕ записанное не переписывают вовсе —
    только пустое дополняют, как и вставка разбора при конфликте. first_seen_at
    UPDATE не называет никогда: её держит схема (file_dates_schema.sql)."""
    беречь = indexer.не_затирать_пустым()

    def сет_колонки(к: str) -> str:
        if к in indexer.ДОПОЛНЯТЬ_ПУСТОЕ:
            return f"{к} = coalesce({к}, %s)"
        if к in беречь:
            return f"{к} = coalesce(%s, {к})"
        return f"{к} = %s"
    сет = [сет_колонки(к) for к in колонки]
    return ("update lib_files set " + ", ".join(сет) + ", processed_at = now()\n"
            " where file_id = %s")


