#!/usr/bin/env python3
"""Переразбор вложений новым разборщиком: возврат потерянного спроса.

ЗАЧЕМ. Правки разборщика (#233) действуют только на новые файлы. Между тем
накопленные 9 920 файлов xlsx/docx разбирались кодом, в котором .docx склеивался
в ОДНУ строку: `text_from_docx` соединяет все <w:t> пробелом, `splitlines()` даёт
один элемент, и вся таблица спецификации превращалась в одну строку lib_demand.
Пока файлы не разобраны заново, возвращённые таблицы .docx не дают ничего.

ЧТО ДЕЛАЕТ. Разбирает файл заново текущим разборщиком и сравнивает с тем, что
лежит в базе. В холостом режиме только считает: сколько строк было, сколько
станет, у скольких файлов результат изменился. Запись — по файлу в одной
транзакции: старые строки помечаются в lib_row_junk как «переразбор», новые
вставляются. Пометка обратима, старые строки не удаляются.

ПОЧЕМУ ПОМЕТКА, А НЕ УДАЛЕНИЕ. Новый разбор может оказаться хуже старого —
например, ворота спецификации отсекут файл, который на самом деле был
спецификацией. Откат по run_id возвращает прежнее состояние целиком.

ПОРЯДОК. Сначала холостой прогон с LIMIT: он даёт измеренную оценку прироста на
выборке, а не догадку. Только потом полный прогон с записью.

    SUPABASE_DB_URL=... BITRIX_WEBHOOK_URL=... LIMIT=200 python library/reparse.py
    SUPABASE_DB_URL=... BITRIX_WEBHOOK_URL=... APPLY=1 python library/reparse.py

В журнал идут только агрегаты.
"""
from __future__ import annotations

import os
import sys
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import indexer  # noqa: E402
import price_store  # noqa: E402  (запись цены — одна на все разборы)

APPLY = os.environ.get("APPLY", "") not in ("", "0", "false")
# ПИСАТЬ ТОЛЬКО ТО, ЧТО НЕ ХУЖЕ ПО ЦЕНЕ. По умолчанию включено: сумма по выборке
# может расти, пока отдельные файлы теряют цену, и такую потерю сумма скрывает.
# Цена — ответ поставщика, другого источника у неё нет; позиции восстановимы
# переразбором, а цена, которой в файле больше не увидят, — нет.
НЕ_ХУЖЕ = os.environ.get("APPLY_ONLY_BETTER", "1") not in ("0", "false")
SHARDS = int(os.environ.get("SHARDS", "1"))
SHARD = int(os.environ.get("SHARD", "0"))
WORKERS = int(os.environ.get("WORKERS", "8"))
LIMIT = int(os.environ.get("LIMIT", "0"))
DAYS = int(os.environ.get("DAYS", "400"))
# Какие форматы переразбирать. Раньше по умолчанию стоял только «xlsx/docx»: правка
# 2026-09 касалась .docx, терявшего таблицы целиком. Теперь главная правка — PDF:
# он читается таблицей с восстановлением колонок (library/pdftable.py), и именно в
# нём лежит основная потеря — 2 498 немых файлов предложений с 258 363 позициями.
KINDS = tuple(k.strip() for k in
              os.environ.get("KINDS", "pdf,xlsx/docx,старый office").split(",")
              if k.strip())
RULE = "переразбор v2"
# Какой источник переразбираем. Определяется той же переменной SOURCE, что и у
# обычного разбора: иначе отбор кандидатов и обход портала разъехались бы, и
# переразбор молча не нашёл бы ни одного файла.
ORIGIN = "поле запроса" if indexer.SOURCE == "rfq" else "поле сделки"
ОПИСАНИЕ_ИСТОЧНИКА = ("предложения поставщиков (карточки запросов)"
                      if indexer.SOURCE == "rfq" else "спецификации сделок")

# ОТБОР ИДЁТ ПО ТОМУ ЖЕ ИСТОЧНИКУ, ЧТО И ОБХОД ПОРТАЛА. Прежде условия на origin
# не было вовсе, потому что переразбор умел только сделки. Теперь он умеет и
# карточки запросов, и без этого условия часть кандидатов гарантированно не
# нашлась бы среди собранных ссылок: обход отдаёт вложения одного вида.
CANDIDATES = """
select f.file_id, f.kind, coalesce(f.rows_found, 0)
  from lib_files f
 where f.status = 'разобран'
   and coalesce(f.parser_version, 1) < %s
   and f.kind = any(%s)
   and f.origin = %s"""

# Индекс по source_file обязателен: без него выборка старых строк файла — это
# последовательный проход по полутора миллионам строк на каждый из тысяч файлов
# (CLAUDE.md, правило 8). Скрипт отказывается работать без него.
INDEX_CHECK = """
select count(*) from pg_indexes
 where tablename = 'lib_demand' and indexdef like '%%source_file%%'"""

# КОЛОНКИ, КОТОРЫЕ ЗАПИСЬ НАЗЫВАЕТ ИМЕНЕМ. Схема живёт в файле, а применяется
# отдельным прогоном, и файл может уйти вперёд базы. 23.09.2026 так и вышло:
# колонка header_miss была добавлена в library/supabase/schema_junk.sql, миграцию
# никто не применил, и запись упала на первом же файле с причиной — УЖЕ ЗАПИСАВ
# часть файлов в каждой из пятидесяти частей. Проверка стоит ДО обхода портала:
# упавший прогон дешевле половины записанного.
КОЛОНКИ_ЗАПИСИ = ("status", "rows_found", "chars", "segment_id", "parse_path",
                  "header_found", "header_miss", "doc_class", "class_rule",
                  "text_lines", "item_lines", "parser_version", "reason",
                  "pdf_pages", "pdf_pages_text", "pdf_pages_lost", "pdf_mixed",
                  "subkind")
COLUMN_CHECK = """
select column_name from information_schema.columns
 where table_name = 'lib_files' and column_name = any(%s)"""

# ЦЕНЫ ДО ПЕРЕРАЗБОРА, ПО ФАЙЛАМ. Без них решение о записи принимать нечем.
#
# Прогон сравнивал только ПОЗИЦИИ и называл «хуже» всякий файл, где их стало
# меньше. Для правки сентября это годилось: .docx терял таблицу целиком, и больше
# строк значило лучше. Для табличного пути PDF — нет: он намеренно перестаёт
# делать позиции из прозы, и падение их числа бывает улучшением качества, а не
# потерей. Судить такую правку числом позиций — судить не по тому признаку.
#
# Смысл переразбора предложений — ЦЕНА. Её и надо сравнивать.
ЦЕНЫ_БЫЛО = """
select source_url, count(*)::bigint
  from lib_prices
 where feed = %s and source_url = any(%s)
 group by 1"""

OLD_ROWS = "select id from lib_demand where source_file = %s"
MARK = ("insert into lib_row_junk (demand_id, rule, run_id, marks) "
        "select unnest(%s::bigint[]), %s, %s, 'переразбор' "
        "on conflict (demand_id) do nothing")


def num(v, w=10):
    return f"{v:,}".replace(",", " ").rjust(w)


def main() -> int:
    for var in ("BITRIX_WEBHOOK_URL", "SUPABASE_DB_URL"):
        if not os.environ.get(var):
            print(f"нет переменной {var}", file=sys.stderr)
            return 2
    import psycopg2
    import psycopg2.extras

    run_id = "reparse-" + datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    if SHARDS > 1:
        print(f"часть {SHARD + 1} из {SHARDS}", flush=True)
    print(f"режим: {'ЗАПИСЬ В БАЗУ' if APPLY else 'холостой, без записи'} · прогон {run_id}")
    print(f"источник: {ОПИСАНИЕ_ИСТОЧНИКА} (origin = «{ORIGIN}»)")
    print(f"форматы к переразбору: {', '.join(KINDS)}", flush=True)

    conn = indexer.connect()
    with conn.cursor() as cur:
        cur.execute(INDEX_CHECK)
        if not cur.fetchone()[0]:
            print("нет индекса lib_demand(source_file): выборка старых строк файла превратится "
                  "в проход по всей таблице. Примените миграцию перед переразбором.",
                  file=sys.stderr)
            conn.close()
            return 2
        cur.execute(COLUMN_CHECK, (list(КОЛОНКИ_ЗАПИСИ),))
        нет = sorted(set(КОЛОНКИ_ЗАПИСИ) - {r[0] for r in cur.fetchall()})
        if нет:
            print(f"в lib_files нет колонок: {', '.join(нет)}. Схема в файле ушла вперёд "
                  "базы — примените миграции прогоном «ZIP base — apply DB migrations» "
                  "и повторите. Прогон остановлен ДО записи, чтобы не оставить "
                  "половину переразобранных файлов.", file=sys.stderr)
            conn.close()
            return 2
        cur.execute(CANDIDATES, (indexer.PARSER_VERSION, list(KINDS), ORIGIN))
        было = {r[0]: (r[1], r[2]) for r in cur.fetchall()}
        cur.execute(ЦЕНЫ_БЫЛО, (price_store.FEED, sorted(было)))
        цен_было_по_файлу = {r[0]: int(r[1]) for r in cur.fetchall()}
    conn.close()
    print(f"кандидатов на переразбор: {len(было)}", flush=True)
    if not было:
        print("нечего переразбирать")
        return 0

    корзины = Counter()
    for _kind, n in было.values():
        корзины["0–1 строка" if n <= 1 else "2–9" if n < 10 else "10–99" if n < 100 else "100+"] += 1
    print("сколько позиций эти файлы дали прежним разбором:")
    for k in ("0–1 строка", "2–9", "10–99", "100+"):
        if корзины[k]:
            print(f"    {k:12}{num(корзины[k])} файлов")

    # Часть перечисляет ТОЛЬКО свою долю сделок: иначе двенадцать частей делают
    # один и тот же обход портала одновременно и получают HTTP 429 (21.09.2026 —
    # все двенадцать частей умерли на этом). Разбиение уже сделано по сделкам,
    # поэтому отбор по хешу файла больше не нужен: файл принадлежит одной сделке.
    # ОБХОД ПОРТАЛА ДЕЛИТСЯ НА ЧАСТИ, И У ОБОИХ ИСТОЧНИКОВ ПО-СВОЕМУ.
    #
    # Распоряжение владельца, 22.09.2026: «никогда не бери сразу так много, всегда
    # дели минимум на 10, а если большие — то и на 50 частей». До этого переразбор
    # предложений шёл ОДНОЙ частью: обход карточек запросов читает страницы подряд
    # по возрастанию ключа, и поделить его было нечем — каждая часть прочитала бы
    # всё целиком, а двенадцать одинаковых обходов дают HTTP 429.
    #
    # Теперь делится и он: indexer.collect_refs_rfq берёт свой ДИАПАЗОН
    # идентификаторов карточек, и один полный обход раскладывается на части, а не
    # повторяется каждой. У сделок разбиение было и раньше — по списку ключей.
    refs = (indexer.collect_refs_rfq(DAYS, SHARD, SHARDS) if indexer.SOURCE == "rfq"
            else indexer.collect_refs(DAYS, SHARD, SHARDS))
    mine = [r for r in refs
            if str(r["fo"].get("id") or r["fo"].get("ID")) in было]
    if LIMIT:
        mine = mine[:LIMIT]
    print(f"\nк переразбору в этой части: {len(mine)}\n", flush=True)
    if not mine:
        print("нечего делать")
        return 0

    стат: Counter = Counter()
    # ЦЕНЫ ПИШУТСЯ ТОЛЬКО ДЛЯ КАРТОЧЕК ЗАПРОСОВ, И ЭТО НЕ ОСТОРОЖНОСТЬ, А СМЫСЛ.
    # Во вложении сделки цена бывает и предложением поставщика, и бюджетом
    # заказчика; писать их вперемешку значит испортить единственный источник цен.
    # Во вложении карточки запроса цена — это ответ поставщика, и другого смысла
    # у неё нет.
    #
    # ДО 22.09.2026 ПЕРЕРАЗБОР НЕ ПИСАЛ ЦЕН ВООБЩЕ, ни для какого источника: он
    # умел только сделки и только позиции. Из-за этого любая правка чтения цены
    # действовала лишь на новые файлы, а 5 640 уже разобранных предложений
    # оставались с прежним результатом — то есть работа над разборщиком не
    # доходила до данных. Это и был главный тормоз.
    цен_найдено = файлов_с_ценой = 0
    цен_было = цен_стало = 0
    цена_лучше = цена_хуже = цена_так_же = 0
    # КАКИМ ПУТЁМ ПОШЁЛ ФАЙЛ. Без этого разницу цен не истолковать: «цен не
    # прибавилось» значит разное, смотря добрался ли файл до табличного пути.
    # Ноль улучшенных файлов подозрителен сам по себе — либо путь не включается,
    # либо включается и даёт меньше. Различить можно только счётчиком.
    пути: Counter = Counter()
    цены_по_пути: Counter = Counter()
    почему_шапки: Counter = Counter()
    пропущено_хуже = 0
    слова_шапки: dict[str, set] = defaultdict(set)
    сетка: Counter = Counter()
    было_строк = стало_строк = 0
    лучше = хуже = так_же = 0
    записано_файлов = 0

    def запиши(rec, items):
        """Один файл — одна транзакция: пометить старое, вставить новое.

        Цены входят в ТУ ЖЕ транзакцию. Иначе при сбое между вставками файл
        остался бы с новыми позициями и старыми ценами — то есть с ценами,
        указывающими на строки, которые уже помечены как заменённые.
        """
        c = indexer.connect()
        try:
            with c.cursor() as cur:
                cur.execute(OLD_ROWS, (rec["file_id"],))
                старые = [r[0] for r in cur.fetchall()]
                if старые:
                    cur.execute(MARK, (старые, RULE, run_id))
                if items:
                    psycopg2.extras.execute_values(cur, """
                        insert into lib_demand
                          (segment_id, deal_id, item_name, oem, part_number, qty, unit, source,
                           source_file, segment_rule)
                        values %s""",
                        [(it["segment_id"], it["deal_id"], indexer.pg(it["item_name"])[:500],
                          indexer.pg(it.get("oem"))[:200], indexer.pg(it.get("part_number"))[:120],
                          it.get("qty"), indexer.pg(it.get("unit"))[:40],
                          indexer.ИСТОЧНИК_СТРОКИ, it["source_file"],
                          it.get("segment_rule"))
                         for it in items], page_size=500)
                if indexer.SOURCE == "rfq":
                    # Прежние цены этого файла снимает сам price_store.записать:
                    # ключ — файл, потому что естественного ключа у цены нет
                    # (одна позиция законно имеет и цену, и сумму). Переразбор
                    # того же КП поэтому идемпотентен.
                    цены = [price_store.строка(it, it["_цена"], indexer.pg)
                            for it in items if it.get("_цена")]
                    if цены:
                        price_store.записать(cur, цены,
                                             psycopg2.extras.execute_values)
                cur.execute("""
                    update lib_files set status = %s, rows_found = %s, chars = %s,
                           segment_id = %s, parse_path = %s, header_found = %s,
                           header_miss = %s, pdf_pages = %s, pdf_pages_text = %s,
                           pdf_pages_lost = %s, pdf_mixed = %s, subkind = %s,
                           doc_class = %s, class_rule = %s, text_lines = %s, item_lines = %s,
                           parser_version = %s, reason = %s, processed_at = now()
                     where file_id = %s""",
                    (rec["status"], rec["rows_found"], rec["chars"], rec["segment_id"],
                     rec["parse_path"], rec["header_found"], rec.get("header_miss"),
                     rec.get("pdf_pages"), rec.get("pdf_pages_text"),
                     rec.get("pdf_pages_lost"), rec.get("pdf_mixed"), rec.get("subkind"),
                     rec["doc_class"], rec["class_rule"],
                     rec["text_lines"], rec["item_lines"], indexer.PARSER_VERSION,
                     indexer.pg(rec["reason"]), rec["file_id"]))
            c.commit()
        finally:
            c.close()

    with ThreadPoolExecutor(max_workers=WORKERS) as pool:
        for n, (rec, items) in enumerate(pool.map(indexer.handle, mine), 1):
            fid = rec["file_id"]
            старое = было.get(fid, (None, 0))[1]
            новое = len(items)
            стат[rec["status"]] += 1
            с_ценой = sum(1 for it in items if it.get("_цена"))
            цен_найдено += с_ценой
            файлов_с_ценой += bool(с_ценой)
            клетка = (rec.get("parse_path") or "(не указан)",
                      "шапка есть" if rec.get("header_found") else "шапки нет")
            пути[клетка] += 1
            цены_по_пути[клетка] += с_ценой
            if rec.get("header_miss"):
                почему_шапки[rec["header_miss"]] += 1
                for слово in rec.get("header_words") or ():
                    слова_шапки[слово].add(fid)
                for вариант in rec.get("header_grid") or ():
                    сетка[вариант] += 1
            # Цена — тот признак, по которому эту правку и надо судить.
            б = цен_было_по_файлу.get(fid, 0)
            цен_было += б
            цен_стало += с_ценой
            if с_ценой > б:
                цена_лучше += 1
            elif с_ценой < б:
                цена_хуже += 1
            else:
                цена_так_же += 1
            было_строк += старое
            стало_строк += новое
            if новое > старое:
                лучше += 1
            elif новое < старое:
                хуже += 1
            else:
                так_же += 1
            if APPLY and НЕ_ХУЖЕ and с_ценой < б:
                # ФАЙЛ, У КОТОРОГО ЦЕН СТАЛО МЕНЬШЕ, НЕ ПЕРЕПИСЫВАЕТСЯ. Замер
                # ослабленного правила шапки 23.09.2026: строк цены 3 474 → 5 716
                # по всей выборке, но у 63 файлов из 832 их стало МЕНЬШЕ. В сумме
                # это прирост, а для каждого из тех 63 — потеря ответа поставщика,
                # которую сумма прячет. Пропущенный файл остаётся как был.
                пропущено_хуже += 1
            elif APPLY:
                запиши(rec, items)
                записано_файлов += 1
            if n % 100 == 0:
                print(f"  обработано {n} из {len(mine)} · было {было_строк} · стало {стало_строк}",
                      flush=True)

    print("\n=== ИТОГ ===")
    print(f"файлов переразобрано:{num(len(mine))}")
    print(f"позиций было:        {num(было_строк)}")
    print(f"позиций стало:       {num(стало_строк)}")
    дельта = стало_строк - было_строк
    print(f"разница:             {num(дельта)}   "
          f"{'прирост' if дельта > 0 else 'убыль' if дельта < 0 else 'без изменений'}")
    if почему_шапки:
        # РАЗБОР ПРИЧИН ИДЁТ ТЕМ ЖЕ ПРОХОДОМ, ЧТО И ПЕРЕРАЗБОР. Отдельная разведка
        # 23.09.2026 качала файлы по идентификатору из базы, и портал отказал на
        # 56 файлах из 60: работающий путь к файлу есть только у обхода карточек.
        print("\nПОЧЕМУ ШАПКА НЕ УЗНАНА (по файлам, где её не нашли):")
        всего_без_шапки = sum(почему_шапки.values())
        for причина, n in почему_шапки.most_common():
            print(f"    {n:>5d}  {100 * n / всего_без_шапки:5.1f} %  {причина}")

        # СЛОВА — ОТ ТРЁХ РАЗНЫХ ФАЙЛОВ И ОТ ШЕСТИ БУКВ (правило 17). Заголовок
        # таблицы — устройство документа, а не его содержимое, а слово, стоящее в
        # шапке у трёх разных поставщиков, названием компании быть не может.
        часто = sorted(((len(f), w) for w, f in слова_шапки.items() if len(f) >= 3),
                       reverse=True)
        # СЕТКА ОСЛАБЛЕНИЙ — ТАБЛИЦЕЙ ЗА ТОТ ЖЕ ПРОХОД (правило 4). Варианты
        # пересекаются, поэтому доли не складываются, и «всё сразу» считается
        # отдельной строкой, а не суммой.
        print("\nСКОЛЬКО ФАЙЛОВ ВЕРНУЛО БЫ КАЖДОЕ ОСЛАБЛЕНИЕ (ничего не изменено):")
        без_шапки = sum(почему_шапки.values())
        for вариант, n in сетка.most_common():
            print(f"    {n:>5d}  {100 * n / max(без_шапки, 1):5.1f} %  {вариант}")
        if not сетка:
            print("    ни одно — ослаблением правила эти файлы не берутся")

        print("\nСЛОВА ИЗ ШАПКИ, КОТОРЫХ ПРАВИЛО НЕ ЗНАЕТ (от 3 разных файлов):")
        if часто:
            for n, слово in часто[:40]:
                print(f"    {n:>4d} файлов  {слово}")
        else:
            print("    ни одного — значит наименование не написано словом вовсе")

    print("\nКАКИМ ПУТЁМ ПОШЛИ ФАЙЛЫ (ради табличного пути всё и делалось):")
    for (путь, шапка), n in пути.most_common():
        ц = цены_по_пути[(путь, шапка)]
        print(f"    {путь:10s} {шапка:12s} файлов {n:>5d} · строк цены {ц:>6d}"
              f" · на файл {ц / n:.1f}")

    print(f"\nПО ПОЗИЦИЯМ: лучше {лучше} · хуже {хуже} · без изменений {так_же}")
    print("    Осторожно: для табличного пути PDF число позиций — НЕ мерило.")
    print("    Он намеренно перестаёт делать позиции из прозы, и падение их")
    print("    числа бывает ростом качества. Судить надо по цене, ниже.")
    print(f"\nПО ЦЕНАМ — ВОТ ЧЕМ НАДО РЕШАТЬ:")
    print(f"    строк цены было:  {num(цен_было)}")
    print(f"    строк цены стало: {num(цен_стало)}")
    д = цен_стало - цен_было
    print(f"    разница:          {num(д)}   "
          f"{'прирост' if д > 0 else 'убыль' if д < 0 else 'без изменений'}")
    print(f"    файлов: цен больше {цена_лучше} · меньше {цена_хуже} · "
          f"столько же {цена_так_же}")
    if цена_хуже > цена_лучше:
        print("    ЗАПИСЫВАТЬ НЕЛЬЗЯ: файлов с потерей цены больше, чем с приростом.")
        print("    Снятие прежних цен по файлу необратимо, в отличие от пометок.")
    print(f"строк с ценой в этих файлах: {num(цен_найдено)} "
          f"у {файлов_с_ценой} файлов из {len(mine)}")
    if indexer.SOURCE == "rfq":
        print("цены " + ("ЗАПИСАНЫ" if APPLY else "будут записаны при APPLY=1")
              + ": это ответ поставщика, другого смысла у неё нет.")
    else:
        print("цены НЕ записаны: во вложении сделки цена бывает и предложением")
        print("поставщика, и бюджетом заказчика — писать их вперемешку значит")
        print("испортить единственный источник цен. Для предложений: SOURCE=rfq.")
    print(f"по состоянию: {dict(стат.most_common())}")
    if LIMIT and len(было) > len(mine):
        на_файл = дельта / len(mine) if mine else 0
        print(f"\nоценка на весь объём ({len(было)} файлов): "
              f"{int(на_файл * len(было)):+,} позиций".replace(",", " "))
        print("оценка линейная — выборка не случайна, а идёт в порядке обхода Битрикса")
    if not APPLY:
        print("\nхолостой прогон — в базе ничего не изменилось. Для записи: APPLY=1")
    else:
        print(f"\n✓ записано файлов: {записано_файлов} · откат: REVERT={run_id} у mark_prose.py")
        if пропущено_хуже:
            print(f"  пропущено как «стало хуже по цене»: {пропущено_хуже} файлов —"
                  f" остались как были (APPLY_ONLY_BETTER=0 снимает защиту)")
    return 0


