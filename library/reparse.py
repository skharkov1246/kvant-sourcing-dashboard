def профиль_цен(rec: dict, items: list[dict], цены: list[tuple]) -> dict:
    """Обезличенный профиль строк цены одного файла: доли и константы кода
    (правило 17) — ни наименований, ни кодов, ни номеров файла и сделки.

    По профилю судят, наше ли это КП: у предложения заказчику строка несёт код,
    количество и единицу, цены разные, а сумма сходится с «цена × количество»;
    у прайс-листа количества нет, у перечня с одной ценой цены повторяются."""
    n = len(цены)

    def доля(условие) -> float:
        return round(100 * sum(1 for r in цены if условие(r)) / n, 1) if n else 0.0

    def сходится(r) -> bool:
        ц, к, с = r[_К["price"]], r[_К["qty"]], r[_К["total"]]
        return bool(ц and к and с) and abs(ц * к - с) <= 0.01 * abs(с)

    валюты = Counter(r[_К["currency"]] or "(не названа)" for r in цены)
    п = {"строк": n, "позиций": len(items),
         "код": доля(lambda r: (r[_К["part_number"]] or "").strip()),
         "кол": доля(lambda r: r[_К["qty"]] is not None),
         "ед": доля(lambda r: (r[_К["qty_unit"]] or "").strip()),
         "сумма": доля(сходится),
         "разные": round(100 * len({r[_К["price"]] for r in цены}) / n, 1) if n else 0.0,
         "низкая": доля(lambda r: r[_К["confidence"]] == "low"),
         "валюты": " ".join(f"{в} {100 * k // n}%" for в, k in валюты.most_common(3)),
         "папка": rec.get("папка_содержимого") or "(не сверялась)",
         "вид": f"{rec.get('subkind') or rec.get('kind') or '?'} · {rec.get('parse_path') or '?'}"}
    признаки = []
    if п["кол"] < 50:
        признаки.append("мало кол-ва")
    if п["код"] < 30:
        признаки.append("мало кода")
    if п["разные"] < 30:
        признаки.append("повторы цен")
    if len(валюты) > 1:
        признаки.append("смесь валют")
    if п["низкая"] > 50:
        признаки.append("низкая ув.")
    п["признаки"] = ", ".join(признаки) or "без признаков"
    return п


def печать_крупных(крупные: list[dict], всего_строк: int) -> None:
    строк = sum(п["строк"] for п in крупные)
    print(f"\nКРУПНЫЕ ФАЙЛЫ НАШЕГО КП (от {КРУПНЫЙ_ФАЙЛ} строк цены): файлов {len(крупные)},"
          f" строк {строк}" + (f" ({100 * строк // всего_строк} % строк потока)"
                               if всего_строк else ""))
    if not крупные:
        return
    print("    доли строк цены, %: код · кол-во · единица · сумма = цена × кол-во ·"
          " различных цен · низкая уверенность")
    print(f"    {'№':>3} {'строк':>6} {'поз.':>6} {'код':>5} {'кол':>5} {'ед':>5} {'сумма':>5}"
          f" {'разн':>5} {'низк':>5}  {'валюты':22s} {'папка по содержимому':28s}"
          f" {'вид · путь':26s} признаки")
    for i, п in enumerate(sorted(крупные, key=lambda x: -x["строк"])[:40], 1):
        print(f"    {i:>3} {п['строк']:>6} {п['позиций']:>6} {п['код']:>5.0f} {п['кол']:>5.0f}"
              f" {п['ед']:>5.0f} {п['сумма']:>5.0f} {п['разные']:>5.0f} {п['низкая']:>5.0f}"
              f"  {п['валюты'][:22]:22s} {п['папка'][:28]:28s} {п['вид'][:26]:26s}"
              f" {п['признаки']}")
    по_признаку: Counter = Counter()
    строк_по_признаку: Counter = Counter()
    for п in крупные:
        for пр in п["признаки"].split(", "):
            по_признаку[пр] += 1
            строк_по_признаку[пр] += п["строк"]
    print("    по признакам (файлов · строк): " + " · ".join(
        f"{пр} {n}/{строк_по_признаку[пр]}" for пр, n in по_признаку.most_common()))


def стало_хуже(источник: str, цен_было: int, цен_стало: int,
               позиций_было: int, позиций_стало: int) -> bool:
    """Потерял ли файл то, ради чего его разбирают. Такой файл не переписывается.

    Предложения (rfq) судятся по цене: это ответ поставщика, другого источника у
    неё нет. Спецификации сделок — по ПОЗИЦИЯМ: цены из вложений сделки в базу не
    пишутся вовсе (там вперемешку предложение поставщика и бюджет заказчика),
    поэтому «цен было» у них всегда ноль и защита по цене не сработала бы ни разу.
    Холостой переразбор сделок 24.09.2026 (прогон 35989447789): по позициям
    лучше 6 860 файлов, ХУЖЕ 2 813 — а по цене «меньше» 0. Позиция сделки — это
    спрос заказчика, звено, из которого достаются машины, узлы и запчасти.
    """
    if источник == "rfq" or НАШЕ_КП_РЕЖИМ:
        return цен_стало < цен_было
    return позиций_стало < позиций_было


def цен_прежним_правилом(items: list[dict]) -> int:
    """Строк цены у файла по ПРЕЖНЕМУ правилу — на тех же байтах, тем же проходом.

    items_from_rows при включённой правке цены кладёт рядом с `_цена` поле
    `_цена_прежде`. У позиций, которых правка не касается (текстовый путь,
    распознавание), его нет — их цена одинакова при любом флаге."""
    return sum(1 for it in items
               if (it["_цена_прежде"] if "_цена_прежде" in it else it.get("_цена")))


def сменили_значение(items: list[dict]) -> int:
    """Строк, где цена есть и до, и после правки, но ЗНАЧЕНИЕ другое.

    Счёт строк этого не видит: при двух колонках «с НДС» и «без НДС» правка
    меняет не число цен, а саму цену. Корпус scripts/cascade_corpus.py: цен не
    из корпуса 60 → 0 при том же числе строк."""
    n = 0
    for it in items:
        до, после = it.get("_цена_прежде"), it.get("_цена")
        if до and после and до.get("price") != после.get("price"):
            n += 1
    return n


#: Ставки НДС, которые снимает выбор колонки «без НДС» (price_norm: РФ 18/20/22 %,
#: плюс 10 и 12 % — льготная и чужие ставки в КП иностранцев).
СТАВКИ_НДС = (0.22, 0.20, 0.18, 0.12, 0.10)
#: Допуск отношения цен: цена в КП округлена до копеек, отношение — нет.
ДОПУСК_СМЕНЫ = 0.003


def характер_смены(до: dict, после: dict, qty: float | None) -> str:
    """Во что правка превратила цену строки — одним из закрытого списка.

    Число «строк со сменённым значением» само не говорит, к лучшему ли смена:
    снятый НДС и цена за единицу вместо суммы — то, ради чего правка делалась,
    а цена, выросшая в количество раз, — её дефект. Журнал публичный, поэтому
    наружу идёт только название вида смены, без значений (CLAUDE.md, правило 17).
    """
    а, б = до.get("price"), после.get("price")
    ва, вб = (до.get("currency") or ""), (после.get("currency") or "")
    if ва != вб:
        # Валюта, впервые названная правкой (колонка «Price, USD» вместо суммы
        # без валюты), — улучшение; вид смены значения судится дальше как обычно.
        # Пропавшая или другая валюта — к проверке: цены несравнимы.
        if вб and not ва:
            return "валюта названа · " + характер_смены({**до, "currency": вб}, после, qty)
        if ва and not вб:
            return "валюта пропала (ПРОВЕРИТЬ)"
        return "валюта другая (ПРОВЕРИТЬ)"
    if not а or not б:
        return "нет значения"
    if round(а, 4) == round(б, 4):
        # Смена только в валюте (ветка выше): «упала меньше чем вдвое» при той
        # же цене вводило в заблуждение при чтении замера. Равенство — точное
        # (цена пишется с четырьмя знаками): 33,3333 делением суммы и 33,33
        # колонки — это смена «было делением суммы — стала колонкой цены».
        return "значение то же"
    r = б / а
    for с in СТАВКИ_НДС:
        if abs(r * (1 + с) - 1) < ДОПУСК_СМЕНЫ:
            return f"÷{1 + с:.2f} — снят НДС {round(с * 100)} %"
        if abs(r / (1 + с) - 1) < ДОПУСК_СМЕНЫ:
            return f"×{1 + с:.2f} — добавлен НДС {round(с * 100)} % (ПРОВЕРИТЬ)"
    if qty and qty > 1:
        if abs(а / qty / б - 1) < ДОПУСК_СМЕНЫ:
            return "была суммой строки — стала ценой за единицу"
        # Сумма строки бывает и другой природы НДС, чем прежняя цена: «Цена по
        # прайсу» без НДС и «Цена с НДС» партии. Такая смена прежде уходила в
        # «выросла …» и даже в желательную «было делением суммы — стала колонкой
        # цены»: дефект под видом смены, ради которой правка делалась (перебор
        # шапок, tests/test_price_sum_guard.py).
        for k, как in ((1.0, ""),
                       *((1 + с, f", НДС ×{1 + с:.2f}") for с in indexer.СТАВКИ_НДС_СУММЫ),
                       *((1 / (1 + с), f", НДС ÷{1 + с:.2f}")
                         for с in indexer.СТАВКИ_НДС_СУММЫ)):
            if abs(б / qty / а / k - 1) >= ДОПУСК_СМЕНЫ:
                continue
            # ВЫРОСЛА В КОЛИЧЕСТВО РАЗ — НЕ ВСЕГДА ДЕФЕКТ ПРАВКИ. Если новая цена
            # сверена арифметикой — выведена делением своей суммы или сходится
            # с ней тройкой, — суммой строки она быть не может (сумма тогда была бы
            # в количество раз больше суммы). Значит, это прежнее правило делило
            # на количество лишний раз: «Сумма за ед.» бралась им суммой строки и
            # делилась на кол-во (корпус tests/test_price_sum_guard.py).
            if (indexer.quotes.ОГОВОРКА_ИЗ_СУММЫ in (после.get("note") or "")
                    or indexer.quotes.тройка_сходится(qty, б, после.get("total"))):
                return "была ценой за единицу, делённой на кол-во, — стала ценой за единицу"
            return f"была ценой за единицу — стала суммой строки{как} (ДЕФЕКТ)"
    if "делением суммы" in (до.get("note") or "") and "делением суммы" not in (после.get("note") or ""):
        # Новая цена не сошлась со своей суммой — количество снято сверкой
        # (indexer.сверить_количество), и отношение к количеству выше проверить
        # было нечем. Так прячется сумма строки под словом цены: в переборе шапок
        # таких строк 560 против 72 верных (tests/test_price_sum_guard.py).
        if indexer.quotes.КОЛ_НЕ_СОШЛОСЬ in (после.get("note") or ""):
            return "было делением суммы — стала колонкой цены, с суммой не сошлась (ПРОВЕРИТЬ)"
        return "было делением суммы — стала колонкой цены"
    # ИСПРАВЛЕНИЕ ПРЕЖНЕГО ДЕФЕКТА — НЕ «ВЫРОСЛА В N РАЗ» (ревизия 29.09.2026).
    # Прежняя цена равна количеству строки или не сходилась со своей суммой, а
    # новая сверена тройкой «кол-во × цена = сумма»: это починка, а не повод к
    # проверке. Прежде такая смена шла в «выросла больше чем в 10 раз
    # (ПРОВЕРИТЬ)», и защита записи держала исправленный файл с мусором в базе.
    # Стоит после видов с названной причиной (снят НДС, была суммой строки):
    # они говорят больше.
    т = indexer.quotes.тройка_сходится
    if qty and т(qty, б, после.get("total")):
        if abs(а - qty) < 1e-9:
            return "была количеством — стала ценой (сверена тройкой)"
        if т(qty, а, до.get("total")) is False:
            return "прежняя не сходилась с суммой — новая сверена тройкой"
    раз = max(r, 1 / r)
    куда = "выросла" if r > 1 else "упала"
    if раз < 2:
        return f"{куда} меньше чем вдвое"
    if раз < 10:
        return f"{куда} в 2–10 раз (ПРОВЕРИТЬ)"
    return f"{куда} больше чем в 10 раз (ПРОВЕРИТЬ)"


def характеры_смены(items: list[dict]) -> Counter:
    """Виды смены значения по строкам файла — к тем же строкам, что считает
    сменили_значение."""
    к: Counter = Counter()
    for it in items:
        до, после = it.get("_цена_прежде"), it.get("_цена")
        if до and после and до.get("price") != после.get("price"):
            к[характер_смены(до, после, it.get("qty"))] += 1
    return к


def прибавленные(items: list[dict]) -> Counter:
    """Строки, которым цену дала ТОЛЬКО правка (прежнее правило на тех же байтах —
    ничего), по признакам правдоподобия. Только названия признаков, без значений.

    Классификатор смены (характер_смены) судит строки, у которых цена была и до
    правки; прибавленных он не видит, а их больше всего (холостые переразборы
    27.09.2026: +23 500 строк). Здесь для них — те же вопросы, что задаёт
    CLAUDE.md «больше цен — не значит лучше»: откуда цена (таблица без шапки,
    деление суммы, колонка), уверенность, названа ли валюта и сходится ли
    «кол-во × цена = сумма», когда проверять есть чем."""
    к: Counter = Counter()
    for it in items:
        ц = it.get("_цена")
        if not ц or "_цена_прежде" not in it or it["_цена_прежде"]:
            continue
        к["строк"] += 1
        note = str(ц.get("note") or "")
        к["путь: таблица без шапки" if indexer.quotes.ОГОВОРКА_БЕЗ_ШАПКИ in note else
          "путь: делением суммы" if indexer.quotes.ОГОВОРКА_ИЗ_СУММЫ in note else
          "путь: колонка цены"] += 1
        к["уверенность: " + str(ц.get("confidence") or "не указана")] += 1
        к["валюта: " + ("названа" if ц.get("currency") else "не названа")] += 1
        т = indexer.quotes.тройка_сходится(it.get("qty"), ц.get("price"), ц.get("total"))
        к["тройка: " + ("сходится" if т else "нечем проверить" if т is None else "НЕ сходится")] += 1
    return к


# ─────────────────────────────────────────────────────────────────────────────
# ЗАМЕР ПРАВОК КП НА ТЕХ ЖЕ БАЙТАХ (indexer.ПРАВКИ_КП, F1–F6)
#
# Ревизия 28.09.2026: переразбор с правками чтения КП сравнивал только ЧИСЛО
# строк цены с базой. Смена значения при том же числе строк (колонки съехали на
# одну, цена с НДС стала ценой без НДС) не видна вовсе, потеря количества — тоже,
# а база записана прогоном 36465256273 неизвестно какими флагами. Поэтому с
# правками каждый файл разбирается дважды на одних байтах (indexer.handle,
# СРАВНИТЬ_БЕЗ_ПРАВОК): рядом с итогом лежит rec["_без_правок"] = (rec, items)
# того же файла без F1–F6 — остальные флаги прогона одни в обеих сторонах.
def _ключ_позиции(it: dict) -> str:
    """Ключ сверки позиции двух разборов одного файла: наименование без регистра
    и лишних пробелов (номер строки у двух разрезов разный)."""
    return " ".join(str(it.get("item_name") or "").lower().split())[:160]


def цен_без_счёта(rec: dict, items: list[dict]) -> int:
    """Строк цены файла тем же отбором, что у записи (price_store.отобрать,
    против_поля у нашего КП), — без прибавки к счётчикам отказов: так
    считается сторона «без правок», которую не пишут."""
    if not (indexer.SOURCE == "rfq" or НАШЕ_КП_РЕЖИМ):
        return sum(1 for it in items if it.get("_цена"))
    if НАШЕ_КП_РЕЖИМ and (not indexer.цены_файла(rec) or indexer.против_поля(rec)):
        return 0
    return len(цены_к_записи(items, считать=False))


def с_количеством(items: list[dict]) -> int:
    """Строк цены, у которых есть количество (правило 0: у скольких хуже — и по нему)."""
    return sum(1 for it in items if it.get("_цена") and it.get("qty"))


def _код_позиции(it: dict) -> str:
    """Код позиции для сверки двух разборов: буквы и цифры без регистра."""
    return re.sub(r"[\W_]+", "", str(it.get("part_number") or "")).lower()


def _значение(it: dict) -> float:
    return round(float((it.get("_цена") or {}).get("price") or 0), 2)


def _деньгами_в_строке(строка: str, цена: float) -> bool:
    """Цена записана в строке деньгами — целая часть с разрядами или без и две
    цифры после запятой («1 173,21», «1173.21», «1,173.21»). Ищется по самой
    строке, а не по её числам: у строки таблицы ячейки склеены пробелом, и
    «3 | 100,00» читалось бы числом 3 100,00."""
    целая, дробь = f"{цена:.2f}".split(".")
    группы = []
    while len(целая) > 3:
        группы.insert(0, целая[-3:])
        целая = целая[:-3]
    группы.insert(0, целая)
    образец = (r"(?<![\d])" + r"[ \u00a0\u202f'’,.]?".join(группы) + r"[.,]" + дробь
               + r"(?![\d])")
    return re.search(образец, строка) is not None


#: Признаки строки цены, которую дали ТОЛЬКО правки КП или чьё значение они
#: сменили, — названия без значений (правило 17). «(ДЕФЕКТ)» — файл не пишется.
ПРИЗНАК_ЦЕНА_КОЛИЧЕСТВО = "цена = количество строки (ДЕФЕКТ)"
ПРИЗНАК_ЦЕНА_СУММА = "цена = сумма при количестве больше 1 (ДЕФЕКТ)"
ПРИЗНАК_НЕ_СХОДИТСЯ = "кол-во × цена ≠ сумма (ДЕФЕКТ)"
ПРИЗНАК_С_НДС = "цена к сумме — как ставка НДС: цена с НДС (ДЕФЕКТ)"
ПРИЗНАК_НЕ_ДЕНЬГИ = "цена не записана деньгами в строке с деньгами (ДЕФЕКТ)"
ПРИЗНАК_КОЛ_ВЕЛИКО = "количество больше 10 000 (ДЕФЕКТ)"


def признаки_строки(it: dict) -> list[str]:
    """Признаки дефекта новой строки цены — те вопросы, что задаёт CLAUDE.md
    «больше цен — не значит лучше» (ревизия 29.09.2026: защита переразбора не
    видела ни одной из 157 неверных строк, которые правки КП прибавили файлам
    без цен): цена = количество строки; цена = сумма при количестве больше
    одного; «кол-во × цена = сумма» не сходится при всех трёх; цена к сумме —
    как 1 + ставка НДС (цена с НДС при сумме без); цена не записана деньгами
    в строке, где деньги записаны (номер, диаметр, срок вместо цены);
    количество больше quotes.МАКС_ПРАВДОПОДОБНОЕ_КОЛИЧЕСТВО — так читается
    съехавшая колонка («57 711,86» или код «752.121» в количестве: замер F4
    отдельно на случайных КП, 29.09.2026)."""
    ц = it.get("_цена") or {}
    цена, кол, сумма = ц.get("price"), it.get("qty"), ц.get("total")
    if not цена:
        return []
    out = []
    if кол and кол > indexer.quotes.МАКС_ПРАВДОПОДОБНОЕ_КОЛИЧЕСТВО:
        out.append(ПРИЗНАК_КОЛ_ВЕЛИКО)
    if кол and abs(цена - кол) < 1e-9:
        out.append(ПРИЗНАК_ЦЕНА_КОЛИЧЕСТВО)
    if кол and кол > 1 and сумма and abs(цена - сумма) < 0.01:
        out.append(ПРИЗНАК_ЦЕНА_СУММА)
    if indexer.quotes.тройка_сходится(кол, цена, сумма) is False:
        out.append(ПРИЗНАК_НЕ_СХОДИТСЯ)
    if сумма and (not кол or кол == 1) and any(
            abs(цена / сумма - (1 + с)) < ДОПУСК_СМЕНЫ for с in indexer.СТАВКИ_НДС_СУММЫ):
        out.append(ПРИЗНАК_С_НДС)
    строка = str(it.get("_row") or "")
    if (indexer.quotes.ОГОВОРКА_ИЗ_СУММЫ not in str(ц.get("note") or "")
            and indexer.quotes.ДЕНЕЖНАЯ_ЗАПИСЬ.search(строка)
            and not _деньгами_в_строке(строка, цена)):
        out.append(ПРИЗНАК_НЕ_ДЕНЬГИ)
    return out


def _мусор_прежде(it: dict) -> bool:
    """Прежняя строка цены сама была дефектом (цена = количество, тройка не
    сходится): её пропажа — не потеря ответа поставщика."""
    return any(п in (ПРИЗНАК_ЦЕНА_КОЛИЧЕСТВО, ПРИЗНАК_НЕ_СХОДИТСЯ, ПРИЗНАК_ЦЕНА_СУММА)
               for п in признаки_строки(it))


def сверка_значений(до: list[dict], после: list[dict]) -> dict:
    """Сверка значений двух разборов одного файла (без правок КП → с ними).

    {совпало, цена, количество, виды, пропали, признаки}:
      • совпало, цена, количество, виды — по позициям, совпавшим наименованием:
        сколько сменили значение цены, количество и каким видом смены
        (характер_смены);
      • пропали — строки цены без правок, которых с правками нет ни под тем же
        наименованием, ни под тем же кодом, ни с тем же значением цены; прежняя
        строка-дефект (признаки_строки) потерей не считается. Путь чтения у
        двух разборов бывает разный (текст ↔ таблица), и наименования не
        совпадают вовсе — поэтому код и значение (ревизия 29.09.2026: «совпавших
        0», и 32 верные цены письма снимались ради таблицы других позиций);
      • признаки — Counter признаков дефекта (признаки_строки) у строк цены,
        которых без правок не было ни под каким ключом, и у сменивших цену или
        количество; ключ «строк» — сколько таких строк."""
    прежние: dict[str, list[dict]] = defaultdict(list)
    for it in до:
        if it.get("_цена"):
            прежние[_ключ_позиции(it)].append(it)
    итог = {"совпало": 0, "цена": 0, "количество": 0, "виды": Counter(),
            "пропали": 0, "признаки": Counter()}
    новые: list[dict] = []
    взяты: set[int] = set()
    for it in после:
        if not it.get("_цена"):
            continue
        пара = прежние.get(_ключ_позиции(it))
        if not пара:
            новые.append(it)
            continue
        it0 = пара.pop(0)
        взяты.add(id(it0))
        итог["совпало"] += 1
        а, б = it0["_цена"], it["_цена"]
        if а.get("price") != б.get("price") or (а.get("currency") or "") != (б.get("currency") or ""):
            итог["цена"] += 1
            итог["виды"][характер_смены(а, б, it.get("qty") or it0.get("qty"))] += 1
        if it0.get("qty") != it.get("qty"):
            итог["количество"] += 1
        if а.get("price") != б.get("price") or it0.get("qty") != it.get("qty"):
            # Сменили цену или количество — новая строка судится признаками:
            # количество тоже ложится в lib_prices (ревизия 29.09.2026).
            итог["признаки"]["строк"] += 1
            итог["признаки"].update(признаки_строки(it))
    остались = [it for it in до if it.get("_цена") and id(it) not in взяты]
    коды_до = {_код_позиции(it) for it in остались} - {""}
    значения_до = {_значение(it) for it in остались}
    коды_после = {_код_позиции(it) for it in после if it.get("_цена")} - {""}
    значения_после = {_значение(it) for it in после if it.get("_цена")}
    for it in новые:
        if _код_позиции(it) in коды_до or _значение(it) in значения_до:
            continue
        итог["признаки"]["строк"] += 1
        итог["признаки"].update(признаки_строки(it))
    итог["пропали"] = sum(1 for it in остались
                          if _код_позиции(it) not in коды_после
                          and _значение(it) not in значения_после
                          and not _мусор_прежде(it))
    return итог


def правки_хуже(было: dict, стало: dict, сверка: dict) -> str | None:
    """Почему файл с правками КП не пишется (APPLY_ONLY_BETTER) — или None.

    Сумма прячет потерю (правило 0), и число строк цены — не единственное мерило:
    меньше строк цены, меньше строк с количеством, у спецификаций сделок —
    меньше позиций, цена без правок, пропавшая с правками поимённо (ни под
    наименованием, ни под кодом, ни значением), новая или сменившая значение
    строка с признаком дефекта (признаки_строки), смена значения с пометкой
    «ДЕФЕКТ» или «ПРОВЕРИТЬ» (характер_смены), и решение «против поля» нашего
    КП, которое правки перевернули, — всё это потеря на тех же байтах.
    «Больше цен — не значит лучше»: число строк цены при этом может расти."""
    if стало["цен"] < было["цен"]:
        return "строк цены меньше"
    if стало["кол"] < было["кол"]:
        return "строк с количеством меньше"
    if not (indexer.SOURCE == "rfq" or НАШЕ_КП_РЕЖИМ) and стало["поз"] < было["поз"]:
        return "позиций меньше"
    if сверка.get("пропали"):
        return "цены пропали поимённо"
    if any("ДЕФЕКТ" in п for п in сверка.get("признаки") or ()):
        return "новые строки цены с дефектом"
    if any("ДЕФЕКТ" in вид or "ПРОВЕРИТЬ" in вид for вид in сверка["виды"]):
        return "смена значения к проверке"
    if было["против"] != стало["против"]:
        return "правки сменили решение «против поля»"
    return None


#: След правок в read_chain (indexer.записать_след) — не читатель: первый шаг
#: пути остаётся читателем и у прежнего читателя, где пути нет вовсе.
_ХВОСТ_СЛЕДА = re.compile(r"(?:^| → )правки: [^→]*$")


def цепь_без_следа(rec: dict) -> str:
    return _ХВОСТ_СЛЕДА.sub("", rec.get("read_chain") or "")


def цены_к_записи(items: list[dict], считать: bool = True) -> list[tuple]:
    """Строки цены файла ровно такими, какими их запишет запиши(): кортежи
    price_store.строка после отбора ложных строк (price_store.отобрать; отказы
    считаются в price_store.ОТКАЗАНО, и в холостом прогоне тоже).

    ОДИН СПИСОК НА ЗАМЕР И НА ЗАПИСЬ. До ревизии 27.09.2026 «стало хуже» и сводка
    считали цены ДО отбора, а запись шла после: строка, которую снимал отбор,
    в замере оставалась, APPLY_ONLY_BETTER её потерю не видел (правило 0), а
    файл, у которого отбор снял все цены, писался с новыми позициями при
    прежних строках цены. Теперь «с ценой» — длина этого списка, и в запись
    уходит он же."""
    return price_store.отобрать([price_store.строка(it, it["_цена"], indexer.pg)
                                 for it in items if it.get("_цена")], считать=считать)


def замер_было_стало(пары: list[tuple[int, int]]) -> dict[str, int]:
    """Замер по файлам: пары (строк цены было, стало) → агрегаты.

    Сумма прячет потерю (CLAUDE.md, правило 0), поэтому кроме итога считается,
    у скольких файлов стало хуже, и отдельно — сколько потеряли цену ЦЕЛИКОМ."""
    з = dict.fromkeys(("файлов", "с_ценой_было", "с_ценой_стало", "строк_было",
                       "строк_стало", "получили", "прибавили", "потеряли",
                       "потеряли_все", "так_же"), 0)
    for было, стало in пары:
        з["файлов"] += 1
        з["с_ценой_было"] += было > 0
        з["с_ценой_стало"] += стало > 0
        з["строк_было"] += было
        з["строк_стало"] += стало
        з["получили"] += было == 0 < стало
        з["прибавили"] += 0 < было < стало
        з["потеряли"] += стало < было
        з["потеряли_все"] += стало == 0 < было
        з["так_же"] += стало == было
    return з


def печать_замера(заголовок: str, з: dict[str, int]) -> None:
    """Только агрегаты (правило 17)."""
    print(заголовок)
    print(f"    файлов с ценой:   {num(з['с_ценой_было'])} → {num(з['с_ценой_стало'])}"
          f"   из {з['файлов']}")
    print(f"    строк цены:       {num(з['строк_было'])} → {num(з['строк_стало'])}")
    print(f"    получили цены (было 0): {з['получили']} · прибавили: {з['прибавили']}"
          f" · без изменений: {з['так_же']}")
    print(f"    ПОТЕРЯЛИ цены: {з['потеряли']} файлов, из них все цены — "
          f"{з['потеряли_все']}")


def печать_замера_кп(пары: list[tuple[int, int]], итог: Counter, виды: Counter,
                     хуже: Counter, по_читателю: dict, по_следу: dict,
                     признаки: Counter | None = None) -> None:
    """ЗАМЕР ПРАВОК КП НА ТЕХ ЖЕ БАЙТАХ — только агрегаты и константы кода (правило 17)."""
    признаки = признаки or Counter()
    печать_замера("\nЗАМЕР ПРАВОК КП НА ТЕХ ЖЕ БАЙТАХ: без правок → с правками (этим и"
                  " решать о правках КП; прочие флаги прогона — в обеих сторонах)",
                  замер_было_стало(пары))
    print(f"    строк цены с количеством: {num(итог['кол_было'])} → {num(итог['кол_стало'])}"
          f" · файлов, где их стало меньше: {итог['кол_хуже']}")
    print(f"    позиций: {num(итог['поз_было'])} → {num(итог['поз_стало'])}"
          f" · файлов, где их стало меньше: {итог['поз_хуже']}")
    print(f"    позиций с брендом (oem): {num(итог['oem_было'])} → {num(итог['oem_стало'])}"
          f" · файлов, где бренд появился у большего числа позиций: {итог['oem_больше']}"
          " (ПРОВЕРИТЬ: склейка шапки не должна заводить бренд)")
    print(f"    совпавших по наименованию строк с ценой: {итог['совпало']} · из них сменили"
          f" ЗНАЧЕНИЕ цены {итог['цена_сменена']} (в {итог['файлов_цена_сменена']} файлах),"
          f" количество {итог['кол_сменено']}")
    for вид, n in виды.most_common():
        print(f"        {n:>7}  {вид}")
    print(f"    строк цены без правок, пропавших с правками поимённо (ни наименованием,"
          f" ни кодом, ни значением): {итог['пропали']} в {итог['файлов_пропали']} файлах")
    print(f"    строк цены, которые правки прибавили или чьё значение сменили:"
          f" {признаки.get('строк', 0)} · по признакам дефекта (файл с «ДЕФЕКТ» не пишется):")
    for п, n in признаки.most_common():
        if п != "строк":
            print(f"        {n:>7}  {п}")
    if not any(п != "строк" for п in признаки):
        print("              —  ни одного признака")
    print(f"    файлов, где правки сменили решение «против поля» нашего КП:"
          f" {итог['против_сменилось']}")
    print("    ХУЖЕ НА ТЕХ ЖЕ БАЙТАХ (файлов, по первой причине): "
          + (" · ".join(f"{к} {n}" for к, n in хуже.most_common()) or "ни одного"))
    print("    по читателю (файлов · цен без → с · лучше · хуже):")
    for читатель, (ф, а, б, лучше, хуже_) in sorted(по_читателю.items(), key=lambda x: -x[1][0]):
        print(f"        {читатель[:28]:28s} {ф:>6d} {а:>7d} → {б:<7d} {лучше:>5d} {хуже_:>5d}")
