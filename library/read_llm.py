def _текст_из_ooxml(b: bytes) -> str:
    """Текст docx/pptx/odt грубо, снятием разметки. Сюда доходит только то, что
    родной читатель не открыл, — тонкий разбор тут уже ничего не спасёт. У книги
    берутся лишь общие строки: ячейки листа хранят номера строк, а не текст."""
    try:
        архив = zipfile.ZipFile(io.BytesIO(b))
    except Exception:                                                       # noqa: BLE001
        return ""
    части = []
    for имя in архив.namelist()[:500]:
        if not (имя.startswith(("word/document", "word/header", "word/footer", "ppt/slides/slide",
                                "xl/sharedStrings")) or имя == "content.xml") or not имя.endswith(".xml"):
            continue
        try:
            xml = архив.read(имя)[:5_000_000].decode("utf-8", "replace")
        except Exception:                                                   # noqa: BLE001, S112
            continue
        xml = re.sub(r"</(?:w:p|a:p|text:p|si)>", "\n", xml)
        xml = re.sub(r"</(?:w:tc|table:table-cell)>", "\t", xml)
        части.append(html.unescape(re.sub(r"<[^>]+>", "", xml)))
    return "\n".join(части)


def _текст_из_ole2(b: bytes) -> str:
    """Старый .doc/.xls/.msg без antiword и catdoc: текст там лежит отрезками
    UTF-16LE. Берутся отрезки от четырёх знаков — латиница, кириллица, №."""
    куски = re.findall(rb"(?:[\x20-\x7e\xa0-\xff]\x00|[\x01-\x5f]\x04|\x16\x21|[\t\r\n]\x00){4,}", b)
    строки = []
    for кусок in куски:
        s = кусок.decode("utf-16le", "ignore").strip()
        if sum(ch.isalpha() for ch in s) >= 3:
            строки.append(s)
    return "\n".join(строки)


def _текст_для_модели(b: bytes, п: str) -> str:
    r = _readers()
    if b[:2] == b"PK":
        текст = _текст_из_ooxml(b)
    elif b[:8] == b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1":
        текст = _текст_из_ole2(b)
    elif п == "rtf" or b.startswith(b"{\\rtf"):
        текст = r.text_from_rtf(b)
    elif п in ("html", "xml", "spreadsheetml"):
        текст = r.text_from_html(b)
    else:
        текст = r.декод(b)
    # Двоичный мусор, раскодированный с заменой, модели не отдаётся: за чтение
    # шума платят как за документ.
    знаков = len(текст) or 1
    годных = sum(ch.isprintable() or ch in "\n\t\r" for ch in текст) - текст.count("�")
    return текст if годных / знаков >= 0.8 else ""


def _b64(данные: bytes) -> str:
    return base64.standard_b64encode(данные).decode("ascii")


def собрать_запрос(b: bytes, подвид: str | None) -> tuple[dict, dict, str]:
    """(запрос к API, оценка токенов и долларов, заметка). Отказ — _Отказ.

    Запрос собирается отдельно от вызова: его же можно поставить в Batch API
    (вдвое дешевле) и положить ответы в тот же кэш по sha256 — синхронный проход
    тогда возьмёт их даром."""
    п = _уточнить(b, подвид)
    м = модель()
    предел_страниц = max(1, int(_число("LLM_READ_MAX_PAGES", 20)))
    заметка = ""
    if п == "pdf":
        данные, страниц, заметка = _pdf_в_пределах(b)
        блоки = [{"type": "document", "source": {"type": "base64", "media_type": "application/pdf",
                                                 "data": _b64(данные)}}]
        байт = len(данные)
        вход = страниц * (ТОКЕНОВ_ТЕКСТА_НА_СТРАНИЦУ + ТОКЕНОВ_КАРТИНКИ_НА_СТРАНИЦУ)
        выход = страниц * ТОКЕНОВ_ВЫХОДА_НА_СТРАНИЦУ
    elif п in КАРТИНКИ or п in ("tiff", "bmp"):
        if п in КАРТИНКИ and len(b) <= МАКС_БАЙТ_КАРТИНКИ:
            кадры, всего, вид = [b], 1, КАРТИНКИ[п]
        else:
            кадры, всего = _картинки_через_pillow(b, предел_страниц)
            вид = "image/jpeg" if кадры and кадры[0][:3] == b"\xff\xd8\xff" else "image/png"
        if всего > len(кадры):
            заметка = f"модель прочла {len(кадры)} кадров из {всего} (предел LLM_READ_MAX_PAGES={предел_страниц})"
        блоки = []
        for i, кадр in enumerate(кадры):
            if len(кадры) > 1:
                блоки.append({"type": "text", "text": f"Страница {i + 1}:"})
            вид_кадра = "image/jpeg" if кадр[:3] == b"\xff\xd8\xff" else вид
            блоки.append({"type": "image", "source": {"type": "base64", "media_type": вид_кадра, "data": _b64(кадр)}})
        страниц = len(кадры)
        байт = sum(len(к) for к in кадры)
        вход = страниц * ТОКЕНОВ_КАРТИНКИ_НА_СТРАНИЦУ
        выход = страниц * ТОКЕНОВ_ВЫХОДА_НА_СТРАНИЦУ
    elif п in АРХИВЫ:
        raise _Отказ("формат", f"{п}: архив модели не отдаётся — читаются его участники")
    else:
        текст = _текст_для_модели(b, п)
        if not текст.strip():
            raise _Отказ("формат", f"{п}: ни картинкой, ни текстом модели отдать нечего")
        предел_знаков = int(_число("LLM_READ_MAX_CHARS", 200_000))
        if len(текст) > предел_знаков:
            заметка = f"модель прочла {предел_знаков} знаков из {len(текст)} (предел LLM_READ_MAX_CHARS)"
            текст = текст[:предел_знаков]
        блоки = [{"type": "document", "source": {"type": "text", "media_type": "text/plain", "data": текст}}]
        страниц = 0
        байт = len(текст.encode("utf-8"))
        вход = int(len(текст) / ЗНАКОВ_НА_ТОКЕН)
        выход = int(вход * 1.1) + 500
    предел_мб = _число("LLM_READ_MAX_MB", 20.0)
    if байт > предел_мб * 1_000_000:
        # 32 МБ — предел всего запроса, а base64 раздувает байты на треть.
        raise _Отказ("предел", f"{п}: {байт / 1e6:.1f} МБ больше предела {предел_мб:g} МБ (LLM_READ_MAX_MB)")
    вход += ТОКЕНОВ_ПОДСКАЗКИ
    выход = min(МАКС_ВЫХОД, выход)
    # max_tokens — жёсткий потолок расхода на выход; с запасом вдвое к ожидаемому,
    # чтобы плотная спецификация не обрывалась на середине.
    макс_выход = min(МАКС_ВЫХОД, 4_000 + (страниц * 3_000 if страниц else выход * 2))
    вывод: dict = {"format": {"type": "json_schema", "schema": СХЕМА}}
    усилие = os.environ.get("LLM_READ_EFFORT", "low").strip()
    # Haiku 4.5 параметра effort не знает и отвечает 400.
    if усилие and "haiku" not in м:
        вывод["effort"] = усилие
    запрос = {
        "model": м,
        "max_tokens": макс_выход,
        "system": [{"type": "text", "text": СИСТЕМА, "cache_control": {"type": "ephemeral"}}],
        "messages": [{"role": "user", "content": блоки + [{"type": "text", "text": ПРОСЬБА}]}],
        "output_config": вывод,
    }
    оценка = {"страниц": страниц, "вход": вход, "выход": выход, "макс_выход": макс_выход,
              "долларов": _доллары(м, вход, выход), "потолок": _доллары(м, вход, макс_выход)}
    return запрос, оценка, заметка


