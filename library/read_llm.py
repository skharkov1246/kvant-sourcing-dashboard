def прочитать_моделью(b: bytes, подвид: str) -> tuple[list[list[str]], str, str]:
    """(строки таблицы, текст, причина). Никогда не бросает исключений.

    Причина при успехе пустая или называет неполноту («прочла 20 стр. из 57»);
    при неудаче начинается с «модель:» и называет, что чинить."""
    try:
        return _прочитать(b, подвид)
    except _Отказ as о:
        return _отказ(о.класс, о.причина)
    except Exception as e:                                                  # noqa: BLE001
        return _отказ("сбой", f"внутренний сбой ({type(e).__name__})")


def _прочитать(b: bytes, подвид: str) -> tuple[list[list[str]], str, str]:
    with _ЗАМОК:
        ИТОГ["файлов"] += 1
    if not _включено():
        raise _Отказ("выключено", "чтение моделью выключено (включается LLM_READ=1)")
    if not b:
        raise _Отказ("формат", "пустой файл")
    ключ = hashlib.sha256(b).hexdigest()
    with _замок_файла(ключ):
        готово = _из_кэша(ключ)
        if готово is not None:
            return готово
        клиент = _клиент()
        запрос, оценка, заметка = собрать_запрос(b, подвид)
        предел_файла = _число("LLM_READ_MAX_USD_FILE", 1.0)
        if оценка["потолок"] > предел_файла:
            raise _Отказ("предел", f"файлу нужно до ${оценка['потолок']:.2f}, предел файла "
                                   f"${предел_файла:.2f} (LLM_READ_MAX_USD_FILE)")
        _занять_бюджет(оценка["потолок"])
        try:
            with _ЗАМОК:
                ИТОГ["вызовов"] += 1
                ИТОГ["страниц"] += оценка["страниц"]
                ИТОГ["оценка_долларов"] += оценка["долларов"]
            ответ = _вызвать(клиент, запрос)
            _учесть(запрос["model"], getattr(ответ, "usage", None))
        finally:
            _вернуть_бюджет(оценка["потолок"])
        return _принять(ключ, ответ, запрос["max_tokens"], заметка)


def _учесть(м: str, исп) -> None:
    def n(поле: str) -> int:
        try:
            return int(getattr(исп, поле, 0) or 0)
        except (TypeError, ValueError):
            return 0
    вход, выход = n("input_tokens"), n("output_tokens")
    запись, чтение = n("cache_creation_input_tokens"), n("cache_read_input_tokens")
    with _ЗАМОК:
        ИТОГ["вход_токенов"] += вход
        ИТОГ["выход_токенов"] += выход
        ИТОГ["кэш_запись_токенов"] += запись
        ИТОГ["кэш_чтение_токенов"] += чтение
        ИТОГ["долларов"] += _доллары(м, вход, выход, запись, чтение)


def _принять(ключ: str, ответ, макс_выход: int, заметка: str) -> tuple[list[list[str]], str, str]:
    """Оплаченный ответ — в кэш в любом исходе, кроме сетевого: за отказ модели
    и обрезанный ответ уже заплачено, и второй раз платить за то же незачем."""
    def отказ(класс: str, причина: str):
        _в_кэш(ключ, {"ok": False, "class": класс, "reason": причина})
        return _отказ(класс, причина)

    стоп = getattr(ответ, "stop_reason", None)
    if стоп == "refusal":
        return отказ("модель", "модель отказалась читать файл (refusal)")
    сырой = "".join(getattr(бл, "text", "") or "" for бл in (getattr(ответ, "content", None) or [])
                    if getattr(бл, "type", "") == "text")
    строки, текст, сбой = разобрать_ответ(сырой)
    if сбой:
        if стоп == "max_tokens":
            сбой = f"ответ обрезан пределом {макс_выход} токенов, JSON не собран"
        return отказ("разбор", сбой)
    if not строки and not текст:
        return отказ("модель", "модель не нашла в файле ни текста, ни таблиц")
    # Считается по тексту: в нём уже стоят все таблицы (на месте меток или в хвосте),
    # и счёт ещё и по строкам удвоил бы каждое место.
    неразборчиво = текст.count(НЕРАЗБОРЧИВО)
    with _ЗАМОК:
        ИТОГ["прочитано"] += 1
        ИТОГ["неразборчиво"] += неразборчиво
    _в_кэш(ключ, {"ok": True, "rows": строки, "text": текст, "note": заметка})
    return строки, текст, заметка


