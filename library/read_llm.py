МЕТКА_ТАБЛИЦЫ = re.compile(r"\[\[\s*ТАБЛИЦА\s*(\d+)\s*\]\]")
НЕРАЗБОРЧИВО = "[неразборчиво]"


class _Отказ(Exception):
    """Названный отказ с классом для сводки. Наружу не выходит никогда."""

    def __init__(self, класс: str, причина: str):
        super().__init__(причина)
        self.класс, self.причина = класс, причина


# --------------------------------------------------------------------------- настройки
# Читаются при КАЖДОМ вызове, а не при импорте: прогон и проверки меняют окружение
# на лету, и значение, прибитое при импорте, врало бы журналу о том, на чём шли.

def _включено() -> bool:
    return os.environ.get("LLM_READ", "").strip() == "1"


def _число(имя: str, умолчание: float) -> float:
    try:
        return float(os.environ.get(имя, "").strip() or умолчание)
    except ValueError:
        return умолчание


def модель() -> str:
    return (os.environ.get("LLM_READ_MODEL") or МОДЕЛЬ_ПО_УМОЛЧАНИЮ).strip()


def каталог_кэша() -> str | None:
    """Кэш ЛЕЖИТ ВНЕ РЕПОЗИТОРИЯ: в нём содержимое документов, а репозиторий
    публичный (правило 5). «0» выключает кэш совсем."""
    свой = os.environ.get("LLM_READ_CACHE", "").strip()
    if свой in ("0", "-"):
        return None
    if свой:
        return свой
    база = os.environ.get("XDG_CACHE_HOME") or os.path.join(os.path.expanduser("~"), ".cache")
    return os.path.join(база, "kvant_read_llm")


def _цены(м: str) -> tuple[float, float, float]:
    for префикс, вход, выход, чтение in ЦЕНЫ:
        if м.startswith(префикс):
            return вход, выход, чтение
    return ЦЕНА_НЕИЗВЕСТНОЙ


def _доллары(м: str, вход: float, выход: float, запись: float = 0, чтение: float = 0) -> float:
    ц_вход, ц_выход, ц_чтение = _цены(м)
    return (вход * ц_вход + запись * ц_вход * 1.25 + чтение * ц_чтение + выход * ц_выход) / 1e6


# --------------------------------------------------------------------------- сводка
_ЗАМОК = threading.Lock()          # индексатор читает файлы пулом потоков
_ЗАМКИ_ФАЙЛОВ: dict[str, threading.Lock] = {}
_РЕЗЕРВ = {"долларов": 0.0}        # занятое под идущие вызовы: бюджет делят потоки
_КЛИЕНТ = None


def _пустой_итог() -> dict:
    return {"файлов": 0, "вызовов": 0, "повторов": 0, "из_кэша": 0, "прочитано": 0,
            "страниц": 0, "вход_токенов": 0, "выход_токенов": 0, "кэш_запись_токенов": 0,
            "кэш_чтение_токенов": 0, "долларов": 0.0, "оценка_долларов": 0.0,
            "неразборчиво": 0, "отказов": {}}


ИТОГ = _пустой_итог()


def сбросить() -> None:
    """Новый прогон: сводка, резерв бюджета и клиент с нуля."""
    global _КЛИЕНТ
    with _ЗАМОК:
        ИТОГ.clear()
        ИТОГ.update(_пустой_итог())
        _РЕЗЕРВ["долларов"] = 0.0
        _ЗАМКИ_ФАЙЛОВ.clear()
        _КЛИЕНТ = None


def итог() -> dict:
    with _ЗАМОК:
        копия = dict(ИТОГ)
        копия["отказов"] = dict(ИТОГ["отказов"])
        return копия


def строка_итога() -> str:
    """Сводка для журнала. ТОЛЬКО числа и собственные константы кода (правило 17)."""
    и = итог()
    отказы = ", ".join(f"{к} {н}" for к, н in sorted(и["отказов"].items()))
    return (f"чтение моделью ({модель()}): файлов {и['файлов']} · вызовов {и['вызовов']} "
            f"(повторов {и['повторов']}) · из кэша {и['из_кэша']} · прочитано {и['прочитано']} · "
            f"страниц {и['страниц']} · токенов вход {и['вход_токенов']} / выход {и['выход_токенов']} · "
            f"${и['долларов']:.2f} (оценка до вызова ${и['оценка_долларов']:.2f}) · "
            f"мест [неразборчиво] {и['неразборчиво']}" + (f" · отказы: {отказы}" if отказы else ""))


def _отказ(класс: str, причина: str) -> tuple[list[list[str]], str, str]:
    with _ЗАМОК:
        ИТОГ["отказов"][класс] = ИТОГ["отказов"].get(класс, 0) + 1
    return [], "", f"модель: {причина}"


def _замок_файла(ключ: str) -> threading.Lock:
    """Один файл в двух сделках, разобранных соседними потоками, оплачивается
    один раз: второй поток ждёт первого и берёт ответ из кэша."""
    with _ЗАМОК:
        return _ЗАМКИ_ФАЙЛОВ.setdefault(ключ, threading.Lock())


def _занять_бюджет(потолок: float) -> None:
    бюджет = _число("LLM_READ_BUDGET_USD", 10.0)
    with _ЗАМОК:
        if ИТОГ["долларов"] + _РЕЗЕРВ["долларов"] + потолок > бюджет:
            raise _Отказ("бюджет", f"бюджет прогона ${бюджет:.2f} исчерпан (LLM_READ_BUDGET_USD): "
                                   f"потрачено ${ИТОГ['долларов']:.2f}, файлу нужно до ${потолок:.2f}")
        _РЕЗЕРВ["долларов"] += потолок


def _вернуть_бюджет(потолок: float) -> None:
    with _ЗАМОК:
        _РЕЗЕРВ["долларов"] = max(0.0, _РЕЗЕРВ["долларов"] - потолок)


# --------------------------------------------------------------------------- кэш
def _путь_кэша(ключ: str) -> str | None:
    каталог = каталог_кэша()
    return os.path.join(каталог, ключ[:2], ключ + ".json") if каталог else None


def _из_кэша(ключ: str) -> tuple[list[list[str]], str, str] | None:
    путь = _путь_кэша(ключ)
    if not путь or not os.path.exists(путь):
        return None
    try:
        with open(путь, encoding="utf-8") as f:
            з = json.load(f)
    except (OSError, ValueError):
        return None                                     # битая запись — читаем заново
    if not isinstance(з, dict) or з.get("v") != ВЕРСИЯ:
        return None
    if з.get("ok"):
        with _ЗАМОК:
            ИТОГ["из_кэша"] += 1
            ИТОГ["прочитано"] += 1
        return [[str(c) for c in r] for r in з.get("rows") or []], str(з.get("text") or ""), str(з.get("note") or "")
    # Оплаченный отказ (модель отказалась, ответ обрезан) не повторяется даром:
    # повтор — только по явной просьбе, например после подъёма предела.
    if os.environ.get("LLM_READ_RETRY_FAILED", "").strip() == "1":
        return None
    with _ЗАМОК:
        ИТОГ["из_кэша"] += 1
    return _отказ(str(з.get("class") or "кэш"), f"из кэша: {з.get('reason') or 'прошлый отказ'}")


def _в_кэш(ключ: str, запись: dict) -> None:
    путь = _путь_кэша(ключ)
    if not путь:
        return
    try:
        os.makedirs(os.path.dirname(путь), exist_ok=True)
        # Через временный файл и переименование: оборванная запись не оставит
        # полфайла, который потом прочтётся как готовый ответ.
        fd, врем = tempfile.mkstemp(dir=os.path.dirname(путь), suffix=".tmp")
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump({"v": ВЕРСИЯ, "model": модель(), "when": time.strftime("%Y-%m-%dT%H:%M:%S"), **запись},
                      f, ensure_ascii=False)
        os.replace(врем, путь)
    except OSError:
        pass                                            # кэш — экономия, а не условие чтения


# --------------------------------------------------------------------------- клиент
def _создать_клиента():
    """Настоящий клиент Anthropic. В проверках подменяется.

    Свои повторы SDK выключены (max_retries=0): повтор делает _вызвать, иначе
    попытки перемножаются, а журнал не видит, сколько их было."""
    import anthropic
    return anthropic.Anthropic(api_key=os.environ["ANTHROPIC_API_KEY"].strip(), max_retries=0,
                               timeout=_число("LLM_READ_TIMEOUT", 600.0))


def _клиент():
    global _КЛИЕНТ
    if not os.environ.get("ANTHROPIC_API_KEY", "").strip():
        raise _Отказ("нет ключа", "нет ключа: секрет ANTHROPIC_API_KEY не передан в окружение прогона")
    with _ЗАМОК:
        if _КЛИЕНТ is None:
            try:
                _КЛИЕНТ = _создать_клиента()
            except ImportError:
                raise _Отказ("нет пакета", "нет пакета anthropic: добавить в pip install прогона") from None
            except Exception as e:                                          # noqa: BLE001
                raise _Отказ("api", f"клиент не создан ({type(e).__name__})") from None
        return _КЛИЕНТ


# --------------------------------------------------------------------------- подготовка
def _уточнить(b: bytes, подвид: str | None) -> str:
    """Сильная подпись важнее переданного подвида: PDF с чужим именем остаётся PDF."""
    if b.startswith(b"%PDF"):
        return "pdf"
    for подпись, имя in ((b"\x89PNG\r\n\x1a\n", "png"), (b"\xff\xd8\xff", "jpeg"), (b"GIF87a", "gif"),
                         (b"GIF89a", "gif"), (b"II*\x00", "tiff"), (b"MM\x00*", "tiff")):
        if b.startswith(подпись):
            return имя
    if b[:4] == b"RIFF" and b[8:12] == b"WEBP":
        return "webp"
    return (подвид or "неизвестно").strip() or "неизвестно"


def _страниц_по_подписи(b: bytes) -> int:
    return len(re.findall(rb"/Type\s*/Page(?![a-zA-Z])", b))


def _pdf_в_пределах(b: bytes) -> tuple[bytes, int, str]:
    """PDF, обрезанный до предела страниц, и число страниц в нём.

    ОБРЕЗАЕТСЯ, А НЕ ОТКЛОНЯЕТСЯ: у спецификации позиции стоят в начале, и первые
    двадцать страниц тома на двести — это почти всегда вся таблица. Обрезка
    называется в причине, чтобы статус не врал о полноте (правило 15).
    Запароленный пустым паролем PDF (частый запрет печати) расшифровывается:
    модель зашифрованный не берёт."""
    предел = max(1, int(_число("LLM_READ_MAX_PAGES", 20)))
    try:
        from pypdf import PdfReader, PdfWriter
    except ImportError:
        страниц = _страниц_по_подписи(b)
        if страниц > предел:
            raise _Отказ("предел", f"PDF на {страниц} стр. больше предела {предел}, а обрезать нечем: нет pypdf") from None
        return b, max(страниц, 1), ""
    try:
        чтец = PdfReader(io.BytesIO(b))
        зашифрован = bool(чтец.is_encrypted)
        if зашифрован:
            try:
                открыт = чтец.decrypt("")
            except Exception as e:                                          # noqa: BLE001
                raise _Отказ("формат", f"PDF зашифрован, расшифровать нечем ({type(e).__name__})") from None
            if not открыт:
                raise _Отказ("формат", "PDF закрыт паролем")
        всего = len(чтец.pages)
    except _Отказ:
        raise
    except Exception:                                                       # noqa: BLE001
        # pypdf не открыл, а модель бывает терпимее к битой разметке: шлём как
        # есть, если по подписи страниц не больше предела.
        страниц = _страниц_по_подписи(b)
        if страниц > предел:
            raise _Отказ("предел", f"PDF на {страниц} стр. больше предела {предел}, а pypdf его не открыл") from None
        return b, max(страниц, 1), ""
    if всего <= предел and not зашифрован:
        return b, max(всего, 1), ""
    взять = min(всего, предел)
    try:
        писатель = PdfWriter()
        for i in range(взять):
            писатель.add_page(чтец.pages[i])
        буфер = io.BytesIO()
        писатель.write(буфер)
    except Exception as e:                                                  # noqa: BLE001
        raise _Отказ("предел", f"PDF на {всего} стр. не обрезался до {взять} ({type(e).__name__})") from None
    заметка = (f"модель прочла {взять} стр. из {всего} (предел LLM_READ_MAX_PAGES={предел})"
               if всего > предел else "")
    return буфер.getvalue(), max(взять, 1), заметка


def _картинки_через_pillow(b: bytes, предел_кадров: int) -> tuple[list[bytes], int]:
    """TIFF, BMP и слишком тяжёлые картинки — в PNG не крупнее того, что модель
    всё равно увидит: длинную сторону больше 2 576 px API ужимает сам, так что
    ужатие здесь ничего не отнимает, а запрос становится легче. Многостраничный
    TIFF (обычный скан с МФУ) идёт всеми кадрами до предела страниц."""
    try:
        from PIL import Image
    except ImportError:
        raise _Отказ("формат", "картинку этого формата модель не берёт, а Pillow для перевода в PNG нет") from None
    try:
        with Image.open(io.BytesIO(b)) as изо:
            всего = int(getattr(изо, "n_frames", 1) or 1)
            взять = min(всего, предел_кадров)
            # Больше 20 картинок в запросе — предел 2 000 px на каждую.
            сторона = 2576 if взять <= 20 else 2000
            кадры = []
            for i in range(взять):
                изо.seek(i)
                кадр = изо.convert("RGB") if изо.mode not in ("RGB", "L") else изо.copy()
                кадр.thumbnail((сторона, сторона))
                буфер = io.BytesIO()
                кадр.save(буфер, "PNG", optimize=True)
                if буфер.tell() > МАКС_БАЙТ_КАРТИНКИ:
                    буфер = io.BytesIO()
                    кадр.save(буфер, "JPEG", quality=90)
                кадры.append(буфер.getvalue())
            return кадры, всего
    except _Отказ:
        raise
    except Exception as e:                                                  # noqa: BLE001
        raise _Отказ("формат", f"картинка не открылась ({type(e).__name__})") from None


