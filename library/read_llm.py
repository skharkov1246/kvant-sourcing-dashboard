СЕТЕВЫЕ = ("APIConnectionError", "APITimeoutError", "ConnectionError", "TimeoutError")
ПОВТОРЯЕМЫЕ_КОДЫ = (408, 409, 429, 500, 502, 503, 504, 529)


def _разобрать_ошибку(e: BaseException) -> tuple[bool, str, str]:
    """(повторять ли, класс для сводки, причина). По имени класса и коду, а не по
    isinstance: так же разбираются и ошибки SDK, и подставные в проверках."""
    имена = {c.__name__ for c in type(e).__mro__}
    код = getattr(e, "status_code", None)
    if isinstance(код, int):
        if код in ПОВТОРЯЕМЫЕ_КОДЫ or код >= 500:
            return True, "api", f"API не ответил ({код})"
        if код in (401, 403):
            return False, "нет ключа", f"ключ не принят ({код})"
        # У ошибки SDK суть лежит в body.error.message; message — это она же,
        # обёрнутая в «Error code: 400 - {...}».
        тело = getattr(e, "body", None)
        суть = тело.get("error", {}).get("message") if isinstance(тело, dict) and isinstance(тело.get("error"), dict) else None
        сообщение = " ".join(str(суть or getattr(e, "message", "") or "").split())[:160]
        return False, "api", f"API отказал ({код}){': ' + сообщение if сообщение else ''}"
    if имена & set(СЕТЕВЫЕ):
        return True, "сеть", f"сбой сети ({type(e).__name__})"
    return False, "api", f"сбой вызова ({type(e).__name__})"


def _выдержка(попытка: int, e: BaseException) -> float:
    заголовки = getattr(getattr(e, "response", None), "headers", None) or {}
    try:
        сказано = float(заголовки.get("retry-after"))
    except (TypeError, ValueError, AttributeError):
        сказано = 0.0
    return min(60.0, сказано or 2.0 * 4 ** попытка + random.uniform(0, 1))


def _вызвать(клиент, запрос: dict):
    """Потоковый вызов с повторами. Поток — потому что выход бывает в десятки
    тысяч токенов, и обычный запрос упёрся бы в таймаут HTTP."""
    попыток = max(1, int(_число("LLM_READ_RETRIES", 3)))
    for попытка in range(попыток):
        try:
            with клиент.messages.stream(**запрос) as поток:
                return поток.get_final_message()
        except Exception as e:                                              # noqa: BLE001
            повторять, класс, причина = _разобрать_ошибку(e)
            if not повторять or попытка == попыток - 1:
                if повторять:
                    причина += f", попыток {попыток}"
                raise _Отказ(класс, причина) from None
            with _ЗАМОК:
                ИТОГ["повторов"] += 1
            time.sleep(_выдержка(попытка, e))
    raise _Отказ("api", "попыток не было")                                  # недостижимо при попыток ≥ 1


