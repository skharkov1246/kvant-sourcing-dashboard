#!/usr/bin/env python3
"""ПОСЛЕДНИЙ РУБЕЖ ЧТЕНИЯ: файл, который не прочитала вся цепочка, читает модель.

Цепочка: родной читатель (indexer._читать) → конвертер → распознавание
(library/ocr.py) → модель. Сюда доходит то, на чём все дешёвые способы дали
пустоту: скан с таблицей, которую tesseract рассыпал, фото накладной, PDF с
печатями и рукописными пометками поверх текста. Модель читает такой файл так же,
как в обычном чате: документ целиком. PDF отдаётся нативно (каждая страница идёт
модели и текстовым слоем, и картинкой — поэтому таблица на скане понимается как
таблица), картинки — изображениями, прочее — текстом, если его можно достать.

ДЕНЬГИ. Это единственный читатель, который стоит денег за КАЖДЫЙ файл, поэтому:
  • выключен, пока его явно не включили: LLM_READ=1 (любое другое значение —
    выключено, чтобы опечатка в прогоне не открыла расход);
  • ответ кэшируется по sha256 файла: один и тот же файл, приложенный к десяти
    сделкам, оплачивается один раз, а не десять;
  • пределы страниц, размера, цены одного файла и бюджета прогона; цена
    оценивается ДО вызова и сверяется с пределами по потолку (выход по max_tokens);
  • итог — только агрегаты: число файлов, токенов, долларов. Журнал прогона
    публичный (правило 17 CLAUDE.md), ни строки документа в него не попадает.

ЦЕНА (посчитана 23.09.2026 по прайсу platform.claude.com/docs/en/about-claude/pricing
и страницам pdf-support и vision той же документации; перед решением владельца
перепроверить — цены меняются):
  claude-sonnet-5 (по умолчанию): $2 за млн входных токенов, $10 за млн выходных;
  Batch API — вдвое дешевле ($1 / $5), но ответ приходит асинхронно, до суток.
  Вход на страницу PDF: текстовый слой 1 500–3 000 токенов (у скана почти ноль)
  плюс картинка страницы — до 4 784 токенов (потолок высокого разрешения моделей
  Claude 4.7 и новее: 2 576 px по длинной стороне). Выход — переписанный текст:
  около 1 000–1 500 токенов на страницу (кириллица, новый токенизатор). Таблица в
  тексте НЕ повторяется (см. СИСТЕМА): иначе выход, самая дорогая часть, вдвое.
  Файл на 10 страниц:
      скан:       вход 10 × ~3 000 + 1 200 ≈ 31 000 ток. = $0,06;
                  выход 10 000–15 000 ток. = $0,10–0,15      → ≈ $0,16–0,21
      верхняя:    вход 10 × 7 784 + 1 200 ≈ 79 000 ток. = $0,16;
                  выход ~15 000 ток. = $0,15                  → ≈ $0,31
  1 000 таких файлов: ≈ $160–310 синхронно, ≈ $80–155 через Batch API.
  Рассуждения при effort=low — сверху до ~10 %. Для сравнения: claude-opus-5-5
  ($4 / $20) ровно вдвое дороже, claude-haiku-4-5 ($1 / $5) вдвое дешевле, но у
  него стандартное разрешение картинок (1 568 токенов), мелкий шрифт скана хуже.

Модуль ничего не печатает: он возвращает (строки, текст, причина) вызывающему,
а сводку отдаёт строка_итога() — её и пишут в журнал.
"""
