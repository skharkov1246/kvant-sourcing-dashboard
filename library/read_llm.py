def _json_из(сырой: str):
    сырой = (сырой or "").strip()
    без_ограды = re.sub(r"^```(?:json)?\s*|\s*```$", "", сырой)
    нач, кон = сырой.find("{"), сырой.rfind("}")
    for кандидат in (сырой, без_ограды, сырой[нач:кон + 1] if 0 <= нач < кон else ""):
        if not кандидат:
            continue
        try:
            return json.loads(кандидат)
        except ValueError:
            continue
    return None


def _ячейки(строка) -> list[str]:
    if isinstance(строка, str):
        строка = [строка]
    if not isinstance(строка, list):
        return []
    # Перевод строки внутри ячейки склеивается: иначе строка таблицы в тексте
    # рассыпалась бы на несколько «позиций».
    return ["" if c is None else " ".join(str(c).split()) for c in строка]


def разобрать_ответ(сырой: str) -> tuple[list[list[str]], str, str]:
    """JSON модели → (строки, текст, причина). Строки — шапка и тело каждой
    таблицы подряд, как у книги с несколькими листами. Текст — полный: на место
    меток [[ТАБЛИЦА k]] возвращаются строки таблицы через табуляцию, поэтому за
    таблицу платят один раз, а полный текст всё равно есть."""
    данные = _json_из(сырой)
    if not isinstance(данные, dict):
        return [], "", "ответ модели не разобран как JSON"
    таблицы = данные.get("tables")
    if not isinstance(таблицы, list):
        таблицы = []
    if not таблицы and isinstance(данные.get("rows"), list):          # запасная форма ответа
        таблицы = [{"header": [], "rows": данные["rows"]}]
    строки: list[list[str]] = []
    блоки: list[list[list[str]]] = []
    for т in таблицы:
        if not isinstance(т, dict):
            continue
        шапка = _ячейки(т.get("header"))
        тело = [_ячейки(r) for r in (т.get("rows") or []) if isinstance(r, (list, str))]
        блок = ([шапка] if any(шапка) else []) + [r for r in тело if any(r)]
        строки.extend(блок)
        блоки.append(блок)
    текст = данные.get("text")
    текст = текст if isinstance(текст, str) else ""
    вставлены: set[int] = set()

    def вставить(м: re.Match) -> str:
        k = int(м.group(1)) - 1
        if 0 <= k < len(блоки):
            вставлены.add(k)
            return "\n".join("\t".join(r) for r in блоки[k])
        return м.group(0)

    текст = МЕТКА_ТАБЛИЦЫ.sub(вставить, текст)
    хвост = ["\n".join("\t".join(r) for r in б) for k, б in enumerate(блоки) if k not in вставлены and б]
    текст = "\n".join(s for s in [текст.strip(), *хвост] if s)
    return строки, текст, ""


