"""Приведение цены предложения к сравнимой: без НДС, признак базиса, на сегодня.

ЗАЧЕМ. Решения владельца 26.09.2026: цены сравниваем без НДС; стандартный базис
— FCA или EXW; цена актуальна на дату выдачи и потом индексируется на инфляцию.
Три шага, каждый со своей оговоркой, потому что каждый может не сработать, и
сравнивать «приведённую» цену с неприведённой молча нельзя.

ШАГ 1 — НДС. Если в поле или примечании сказано, что цена с НДС, она делится на
(1 + ставка) страны на дату цены. Ставки известны только по России:

    18 % — до 31.12.2018;
    20 % — с 01.01.2019, Федеральный закон от 03.08.2018 № 303-ФЗ
           (http://publication.pravo.gov.ru/Document/View/0001201808030106);
    22 % — с 01.01.2026, Федеральный закон от 28.11.2025 № 425-ФЗ
           (http://publication.pravo.gov.ru/document/0001202511280017;
           порядок перехода — письмо ФНС от 11.12.2025 № АБ-4-20/11176@).

Ставка берётся по дате цены: цена, выданная в декабре 2025 «с НДС», содержит
20 %, а не 22 %. У прочих стран цена с НДС не пересчитывается — ставок и льгот
здесь нет, — а помечается. Страна не названа, а валюта рубль — ставка России, с
оговоркой. Ни «с», ни «без» не сказано — цена считается без НДС, с оговоркой:
угадывать нельзя, но и выбрасывать цену не за что.

ШАГ 2 — БАЗИС. Признак «стандартный»: EXW или FCA — да; любой другой код
Инкотермс — нет (в цене доставка, страховка или пошлина, её надо вычитать, а не
сравнивать); не указан — неизвестно. Сама цена базисом НЕ пересчитывается:
вычесть доставку не из чего. Базис распознаёт offer_terms.базис_из — одно
правило на портал.

ШАГ 3 — ИНФЛЯЦИЯ. library/inflation.индексировать на дату «на» (обычно — сегодня;
её передаёт вызывающий, чтобы функция была чистой).

Курса здесь нет: цена остаётся в своей валюте.
"""
from __future__ import annotations

import re
from datetime import date, datetime

try:                                             # pragma: no cover
    from . import inflation as _inf
    from . import offer_terms as _ot
except ImportError:                              # pragma: no cover
    import inflation as _inf
    import offer_terms as _ot

СТАНДАРТНЫЕ_БАЗИСЫ = ("EXW", "FCA")

#: Ставки НДС России: (действует с, ставка). Источники — в описании модуля.
НДС_РФ = (
    (date(1900, 1, 1), 0.18),
    (date(2019, 1, 1), 0.20),   # 303-ФЗ от 03.08.2018
    (date(2026, 1, 1), 0.22),   # 425-ФЗ от 28.11.2025
)
_РОССИЯ = {"RU", "RUS", "РФ", "РОССИЯ", "RUSSIA", "RUSSIAN FEDERATION"}

# «Без НДС» проверяется ПЕРВЫМ: «не включая НДС» содержит «включая НДС».
_БЕЗ_НДС = re.compile(
    r"без\s+(учёта\s+|учета\s+)?ндс|не\s+включая\s+ндс|ндс\s+не\s+(облагается|включ)"
    r"|не\s+облагается\s+ндс|ндс\s+сверху|\+\s*ндс|плюс\s+ндс|ндс\s+оплачивается\s+дополнительно"
    r"|excl\.?(uding)?\s+vat|vat\s+(excluded|not\s+included|exempt)|net\s+of\s+vat"
    r"|plus\s+vat|\+\s*vat|w/o\s+vat|without\s+vat", re.I)
_С_НДС = re.compile(
    r"(с|включая|в\s+т\.\s*ч\.?|в\s+том\s+числе|вкл\.?)\s+ндс|ндс\s+включ|с\s+учётом\s+ндс"
    r"|с\s+учетом\s+ндс|incl\.?(uding)?\s+vat|vat\s+included|with\s+vat|vat\s+incl", re.I)


def ндс_в_цене(текст: str | None) -> bool | None:
    """True — сказано, что цена с НДС; False — что без; None — не сказано."""
    t = текст or ""
    if _БЕЗ_НДС.search(t):
        return False
    if _С_НДС.search(t):
        return True
    return None


def _дата(д: date | datetime | str) -> date:
    if isinstance(д, datetime):
        return д.date()
    if isinstance(д, date):
        return д
    s = str(д).strip()
    if re.fullmatch(r"\d{4}-\d{2}", s):
        s += "-01"
    return date.fromisoformat(s[:10])


def ставка_ндс(страна: str | None, дата: date | datetime | str) -> float | None:
    """Ставка НДС страны на дату; None — ставка страны не известна."""
    if (страна or "").strip().upper() not in _РОССИЯ:
        return None
    д = _дата(дата)
    ставка = None
    for с, ст in НДС_РФ:
        if д >= с:
            ставка = ст
    return ставка


def базис(текст: str | None) -> tuple[str | None, bool | None]:
    """(код Инкотермс, стандартный ли): EXW/FCA — True, прочий — False, нет — None."""
    код = _ot.базис_из(текст or "")
    if код is None:
        return None, None
    return код, код in СТАНДАРТНЫЕ_БАЗИСЫ


def привести(цена: float | None, валюта: str | None, дата_цены: date | datetime | str,
             *, на_дату: date | datetime | str,
             ндс: bool | None = None, примечание: str | None = None,
             страна: str | None = None, базис_текст: str | None = None,
             ряды: _inf.Ряды | None = None) -> tuple[float | None, list[str]]:
    """(сравнимая цена, оговорки).

    цена        — цена за единицу в валюте предложения;
    ндс         — поле «цена с НДС» (True/False), если оно есть; иначе ищется
                  в примечании;
    примечание  — свободный текст: «цена с НДС 20 %», «EXW Шанхай» и т.п.;
    страна      — страна поставщика (RU/RUS/Россия…), для ставки НДС;
    базис_текст — поле базиса, если есть; иначе базис ищется в примечании;
    на_дату     — на какую дату индексировать (обычно сегодня).
    """
    п = привести_подробно(цена, валюта, дата_цены, на_дату=на_дату, ндс=ндс, примечание=примечание,
                          страна=страна, базис_текст=базис_текст, ряды=ряды)
    return п["цена"], п["оговорки"]


def привести_подробно(цена: float | None, валюта: str | None, дата_цены: date | datetime | str,
                      *, на_дату: date | datetime | str,
                      ндс: bool | None = None, примечание: str | None = None,
                      страна: str | None = None, базис_текст: str | None = None,
                      ряды: _inf.Ряды | None = None) -> dict:
    """То же, что привести(), плюс то, из чего цена получена — для проверки:
    {"цена", "оговорки", "ставка" (снятая ставка НДС или None), "k" (коэффициент
    индексации или None), "базис" (код Инкотермс или None), "стандартный"
    (True/False/None)}. Ревизия портала пересчитывает по ним цену и ловит
    неправдоподобный коэффициент (scripts/portal_audit.py, n.o_norm)."""
    оговорки: list[str] = []
    if цена is None:
        return {"цена": None, "оговорки": ["цены нет"], "ставка": None, "k": None,
                "базис": None, "стандартный": None}
    вал = (валюта or "").strip().upper()
    снята = None

    # 1. НДС
    с_ндс = ндс if ндс is not None else ндс_в_цене(примечание)
    if с_ндс is None:
        оговорки.append("не сказано, с НДС ли цена — считается без НДС")
    elif с_ндс:
        кто = страна
        if not (кто or "").strip() and вал == "RUB":
            кто = "RU"
            оговорки.append("страна не указана — НДС снят по ставке России (цена в рублях)")
        ст = ставка_ндс(кто, дата_цены)
        if ст is None:
            оговорки.append(f"цена с НДС, ставка страны {кто or '(не указана)'} не известна — "
                            "НДС не снят, сравнивать с ценами без НДС нельзя")
        else:
            цена = round(цена / (1 + ст), 2)
            снята = ст
            оговорки.append(f"НДС {round(ст * 100)} % снят (ставка России на {_дата(дата_цены).isoformat()})")

    # 2. Базис — только признак
    код, стандартный = базис(базис_текст if базис_текст else примечание)
    if стандартный is None:
        оговорки.append("базис не указан — стандартный ли (FCA/EXW), неизвестно")
    elif not стандартный:
        оговорки.append(f"базис {код} — не стандартный (FCA/EXW): в цене могут быть "
                        "доставка, страховка или пошлина")

    # 3. Инфляция
    новая, k, оговорка = _inf.индексировать(цена, вал, дата_цены, на_дату, ряды=ряды)
    if оговорка:
        оговорки.append(оговорка)
    return {"цена": новая, "оговорки": оговорки, "ставка": снята, "k": k,
            "базис": код, "стандартный": стандартный}
