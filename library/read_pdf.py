#!/usr/bin/env python3
"""Чтец PDF постранично: два извлекателя, лучший на каждой странице, сканы по номерам.

ЗАЧЕМ. Замер 23.09.2026 по всей базе (31 869 файлов): 9 527 файлов, то есть
29,9 %, не дали ни одной позиции, и PDF среди них — главное узкое место:

    PDF  11 217 файлов · 1 683 без позиций · 3 474 ушли «текстом без шапки»

Прежний путь (indexer.страницы_pdf) читает PDF одним pypdf и отвечает на вопрос
«есть ли текст» числом знаков на странице. Отсюда три потери, которые этот модуль
закрывает:

  1. pypdf НЕ ТЕРПИТ того, что терпит poppler. Битая таблица ссылок, мусор перед
     «%PDF», обрезанный хвост письма — poppler восстанавливает документ сам, а
     pypdf либо падает на открытии, либо теряет страницы. Поэтому каждая страница
     извлекается ДВАЖДЫ — pdftotext и pypdf, — и берётся лучшая по качеству.
  2. «Есть знаки» — не то же, что «есть текст». Шрифт без таблицы кодировки даёт
     на странице тысячи знаков вида «(cid:123)» или символов частной области
     Юникода, а старые генераторы 1С пишут кириллицу через WinAnsi, и выходит
     «Íàèìåíîâàíèå» вместо «Наименование». Такая страница проходила порог
     знаков, считалась текстовой и в распознавание не попадала НИКОГДА. Здесь
     мусор меряется по закрытому списку признаков, перекодировку чиним (она
     обратима), а неисправимые страницы называем номерами.
  3. Смешанный PDF (часть страниц текстовые, часть сканы) распознаванию нужен
     ПОСТРАНИЧНО: распознавать весь документ ради двух сканов из шестидесяти —
     это минута распознавания впустую на каждый такой файл. Поэтому наружу идут
     номера страниц: scan_pages и garbled_pages — ровно то, что берёт
     распознавание.

ОБЕЩАНИЕ: прочитать_pdf НИКОГДА НЕ БРОСАЕТ ИСКЛЮЧЕНИЙ и никогда не молчит.
Пустой текст всегда приходит с названной причиной: «зашифрован паролем», «нет ни
pdftotext, ни pypdf», «прочитано 200 стр. из 350». Невидимая потеря хуже видимой.

ПРАВИЛО 17 (журнал публичный) соблюдается тем, что модуль ничего не печатает
вовсе: он только возвращает текст вызывающему, а причины собраны из собственных
констант и чисел — ни слова из документа в них нет.

НУМЕРАЦИЯ СТРАНИЦ С ЕДИНИЦЫ — как у pdftoppm -f N -l N, которым распознавание
растрирует страницу: номер из scan_pages подставляется в него без пересчёта.
Текст страницы N лежит в text.split("\\f")[N - 1].
"""
from __future__ import annotations

import io
import os
import re
import shutil
import subprocess
import tempfile
import time
from pathlib import Path

#: Потолок страниц, если вход прогона PDF_PAGES не задан. Спецификация на сто
#: позиций бывает длиннее шестидесяти страниц (прежний потолок indexer), а
#: каталог производителя на тысячу страниц — не предложение, и читать его целиком
#: незачем. Обрыв на потолке всегда назван в reason.
ПРЕДЕЛ_ПО_УМОЛЧАНИЮ = 200

#: Сколько БУКВ И ЦИФР на странице считать текстовым слоем. Тот же порядок, что у
#: indexer.ЗНАКОВ_НА_СТРАНИЦЕ: скан даёт ноль или единицы знаков (номер листа,
#: штамп), страница с текстом — сотни. Считаются только буквы и цифры, а не все
#: знаки: строка подчёркиваний «____» в форме текстом не является.
ЗНАКОВ_НА_СТРАНИЦЕ = 40

#: Доля мусора, с которой страница объявляется мусорной и уходит в распознавание.
#: Один-два знака «№» или «±» из символьного шрифта без таблицы кодировки дают на
#: странице 1–3 % мусора — это текстовая страница. Шрифт без таблицы целиком —
#: 90–100 %. Четверть — середина между ними с запасом в обе стороны: страница, у
#: которой шапка набрана битым шрифтом, а таблица целым, в распознавание попадёт,
#: и уцелевшие цифры при этом останутся в тексте (см. _слот).
ПОРОГ_МУСОРА = 0.25

#: Меньше стольких мусорных знаков страницу мусорной не объявляем: три
#: «(cid:…)» в подписи — не повод распознавать лист.
МУСОРА_МИНИМУМ = 20

#: Ничья между извлекателями. Если балл предпочтённого не ниже 95 % лучшего, берём
#: предпочтённый: на обычной странице pdftotext и pypdf дают почти одно и то же
#: число знаков, и прыгать между ними постранично значит ломать выравнивание
#: колонок, по которому library/pdftable.py восстанавливает таблицу.
ПРЕИМУЩЕСТВО = 0.95

#: pdftotext зовётся кусками по 25 страниц, а не на каждую страницу отдельно и не
#: на весь документ разом. Вызов на страницу — это двести разборов одного файла
#: на двухсотстраничном документе; вызов на весь документ — это одна зависшая
#: страница, уносящая все остальные. Кусок, который упал или завис, повторяется
#: постранично, и потеря сжимается до одной страницы.
КУСОК = 25
ТАЙМАУТ_КУСКА = 120
ТАЙМАУТ_СТРАНИЦЫ = 30

#: Общий срок на файл для каждого извлекателя. Выход за срок не роняет файл:
#: недочитанные страницы остаются другому извлекателю, а если не взял и он —
#: они названы в reason числом.
СРОК_ИЗВЛЕКАТЕЛЯ = 300

#: Страница без текста, но с потоком содержимого длиннее этого, — не пустая:
#: так выглядит чертёж, где надписи переведены в кривые. Распознавание читает
#: такие надписи, текстовый слой — нет. Пустой лист и лист с одной картинкой
#: скана дают десятки байт, сетка пустой таблицы — сотни.
ВЕКТОР = 3000

#: Где искать подпись «%PDF». poppler сам ищет её в первом килобайте, pypdf — только
#: в начале; вложение из почты бывает с хвостом заголовков MIME перед подписью.
ГОЛОВА = 65536

#: Порядок предпочтения на ничьей: pdftotext точнее держит колонки и порядок
#: строк, pypdf — запасной.
ИЗВЛЕКАТЕЛИ = ("pdftotext", "pypdf")

# ── Мусор: закрытый список признаков ─────────────────────────────────────────
# Правило 7: признак либо защищает, либо обвиняет, и обвиняют только закрытым
# списком. Сюда входит лишь то, что в настоящем тексте не встречается никогда:
# ссылки на номер глифа, управляющие знаки, знак замены, частная область Юникода
# и следы перекодировки. «Мало букв» или «много согласных» не обвиняют: таблица с
# точками-отточиями и артикулами без гласных выглядит так же.

#: Номер глифа вместо буквы — так извлекатели пишут знак шрифта без ToUnicode.
_CID = re.compile(r"\(cid:\d+\)")

#: Управляющие C0 (кроме табуляции и переводов строки), C1, знак замены, частная
#: область Юникода — символьные шрифты без таблицы кодировки дают именно её.
_СОР = re.compile("[\x00-\x08\x0b\x0e-\x1f\x7f-\x9f\ufffd\ue000-\uf8ff]")

#: UTF-8, прочитанный как Latin-1 или cp1252: «Ð°» вместо «а», «Ñ\x81» вместо «с».
#: Второй знак пары — продолжение UTF-8 (0x80–0xBF) в любом из двух прочтений.
_UTF8_ПАРА = re.compile("[\xd0\xd1\xc3\xc2][\x80-\xbf\u0152\u0153\u0160\u0161\u0178\u017d\u017e\u0192\u02c6"
                        "\u02dc\u2013\u2014\u2018-\u201a\u201c-\u201e\u2020-\u2022\u2026\u2030"
                        "\u2039\u203a\u20ac\u2122]")

#: UTF-8, прочитанный как cp1251: «РќР°СЃРѕСЃ» вместо «Насос». Второй знак пары —
#: байт продолжения 0x80–0xBF в прочтении cp1251, но БЕЗ тех, что стоят после «Р»
#: и «С» в настоящем тексте: «ё» («Рёв»), украинские и белорусские «і», «ї», «є»,
#: «ў», «ґ», кавычки и тире («категория “С”», «класс С–D»), многоточие, «№»,
#: неразрывный пробел («ГОСТ Р 52857»), мягкий перенос и градус после «С» («80 С°»). Выпавшие
#: буквы (в, г, и, к, л, п, Б–Е, Ж, З…) мусор не прячут: в битом слове почти
#: всегда есть и а, е, о, н, с, т, чьи пары в списке.
_ПРОДОЛЖЕНИЯ_1251 = (
    "\u0402\u0403\u201a\u0453\u201e\u2020\u2021\u20ac\u2030\u0409\u2039\u040a"
    "\u040c\u040b\u040f\u0452\u2122\u0459\u203a\u045a\u045c\u045b\u045f\u0408"
    "\xa4\xa6\xa7\xa9\xac\xae\xb1\xb5\xb6\xb7\u0458"
    "\u0405\u0455")
_UTF8_В_1251 = re.compile(f"Р[\xb0{_ПРОДОЛЖЕНИЯ_1251}]|С[{_ПРОДОЛЖЕНИЯ_1251}]")

#: Слово cp1251, прочитанное как cp1252: «Íàèìåíîâàíèå». Кириллица cp1251
#: целиком ложится в À–ÿ (с × и ÷ — это «Ч» и «ч», с ¨ и ¸ — «Ё» и «ё»).
_СЛОВО_1252 = re.compile("[A-Za-z0-9\xc0-\xff\xa8\xb8-]{3,}")
_ВЕРХ_1252 = re.compile("[\xc0-\xff\xa8\xb8]")

#: Самые частые буквы русского текста: в правильно перекодированном тексте на них
#: приходится 70–80 % букв, в неправильном (KOI8 вместо cp1251) — заметно меньше.
_ЧАСТЫЕ = set("оеаинтсрвлкмдпу")


def _слово_1252(слово: str) -> bool:
    """Похоже ли слово на кириллицу cp1251, прочитанную как cp1252.

    Нужно не меньше трёх знаков верхней половины и 60 % от букв слова. Настоящее
    европейское слово несёт один-два знака с диакритикой на десяток латинских
    («Größe», «été»), а слово cp1251 состоит из верхней половины целиком.
    """
    верх = len(_ВЕРХ_1252.findall(слово))
    if верх < 3:
        return False
    букв = sum(1 for c in слово if c.isalpha())
    return верх >= 0.6 * max(букв, 1)


def _мусорный_токен(токен: str) -> bool:
    return bool(_CID.search(токен) or _СОР.search(токен) or _UTF8_ПАРА.search(токен)
                or _UTF8_В_1251.search(токен)
                or any(_слово_1252(m.group()) for m in _СЛОВО_1252.finditer(токен)))


def _очистить(текст: str, *, всё: bool) -> str:
    """Снять мусор.

    всё=False — только то, что ОДНИМ ЗНАКОМ текстом не бывает никогда: номера
    глифов, управляющие, знак замены, частная область. Так чистится текстовая
    страница: пары перекодировки на ней не трогаем, потому что «С–D» в «классе
    С–D» — редкий, но настоящий текст, и срезать из него букву нельзя.

    всё=True — ещё и пары перекодировки и слова cp1251, которые не удалось
    перекодировать. Это для замера и для остатка мусорной страницы, где они
    заведомо не текст.
    """
    т = _CID.sub("", текст)
    if всё:
        т = _UTF8_ПАРА.sub("", т)
        т = _UTF8_В_1251.sub("", т)
    т = _СОР.sub("", т)
    if всё:
        т = _СЛОВО_1252.sub(lambda m: "" if _слово_1252(m.group()) else m.group(), т)
    return т


def _непробельных(текст: str) -> int:
    return sum(1 for c in текст if not c.isspace())


def оценить(текст: str) -> dict:
    """Качество извлечённого текста страницы.

    Возвращает знаков (непробельных), мусор (сколько из них по закрытому списку),
    осмысленных (букв и цифр после снятия мусора), долю мусора и балл.

    БАЛЛ = осмысленные × (1 − доля мусора)² × штраф за разбивку. Квадрат — чтобы
    тысяча знаков пополам с мусором проигрывала шестистам чистым: при линейном
    множителе они шли бы вровень, а распознавать и чинить приходится именно
    первую. Штраф — за два вида порчи, которые мусором не являются, но текст
    портят: «Н а с о с» (буквы вразбивку, pypdf на части шрифтов) и
    «НасосЦНС38-176Задвижка» (слова слиплись без пробелов).
    """
    знаков = _непробельных(текст)
    чистый = _очистить(текст, всё=True)
    мусор = знаков - _непробельных(чистый)
    осмысленных = sum(1 for c in чистый if c.isalnum())
    доля = мусор / знаков if знаков else 0.0
    штраф = 1.0
    слова = re.findall(r"[^\W\d_]+", чистый)
    if len(слова) >= 20:
        # Однобуквенных слов в русском тексте 10–15 % («в», «с», «и»); больше
        # половины — это уже разбивка по буквам.
        if sum(1 for w in слова if len(w) == 1) / len(слова) > 0.6:
            штраф *= 0.5
        # Средняя длина русского слова — 6–7 букв; двадцать — склейка.
        if sum(len(w) for w in слова) / len(слова) > 20:
            штраф *= 0.7
    return {"знаков": знаков, "мусор": мусор, "осмысленных": осмысленных,
            "доля": доля, "балл": осмысленных * (1 - доля) ** 2 * штраф}


# ── Починка перекодировки ────────────────────────────────────────────────────
# Кириллица, записанная через WinAnsi, и UTF-8, прочитанный как Latin-1, —
# ОБРАТИМЫ: знаки возвращаются в байты и читаются нужной кодировкой. Это дешевле
# и точнее распознавания, которое пришлось бы звать на такую страницу.

#: Пути перекодировки: (чем знаки вернуть в байты, чем байты прочесть заново).
#: Порядок — это и приоритет на ничьей. UTF-8 первым: строгое чтение UTF-8 на
#: случайных байтах почти никогда не проходит, и если прошло — оно и верно.
#: «1252» — смешанный Latin-1/cp1252 (см. _в_байты); cp1251 — старый 1С и Word;
#: koi8_r — редкий, но живой.
_ПЕРЕКОДИРОВКИ = (("1252", "utf-8"), ("cp1251", "utf-8"), ("1252", "cp1251"), ("1252", "koi8_r"))


def _в_байты(токен: str, откуда: str = "1252") -> bytes | None:
    """Знаки обратно в байты. «1252» — Latin-1 для 0x00–0xFF и cp1252 для «“”€…»:
    смешанный вид нужен, потому что извлекатели читают однобайтовый шрифт
    по-разному — один отдаёт C1-знак 0x9D, другой на том же месте знак cp1252."""
    if откуда != "1252":
        try:
            return токен.encode(откуда)
        except UnicodeEncodeError:
            return None
    out = bytearray()
    for c in токен:
        o = ord(c)
        if o < 256:
            out.append(o)
            continue
        try:
            out += c.encode("cp1252")
        except UnicodeEncodeError:
            return None
    return bytes(out)


def _частотность(текст: str) -> float:
    буквы = [c for c in текст.lower() if "а" <= c <= "я" or c == "ё"]
    return sum(1 for c in буквы if c in _ЧАСТЫЕ) / len(буквы) if буквы else 0.0


def починить(текст: str) -> tuple[str, str]:
    """Перекодировать слова с признаками перекодировки. Возвращает (текст, чем).

    Кодировка выбирается ОДНА на страницу — по доле починенных слов и частотности
    букв результата, — а применяется пословно: на странице бывают вперемешку
    целые строки (артикулы, числа) и битые, и целые трогать нельзя. Если ни одна
    кодировка не чинит хотя бы половину битых слов, текст возвращается как был,
    с пустым «чем».
    """
    битые = [m for m in re.finditer(r"\S+", текст) if _мусорный_токен(m.group())]
    if not битые:
        return текст, ""
    лучший: tuple[float, str, dict[int, tuple[int, str]]] | None = None
    for откуда, кодировка in _ПЕРЕКОДИРОВКИ:
        замены: dict[int, tuple[int, str]] = {}
        for m in битые:
            сырые = _в_байты(m.group(), откуда)
            if сырые is None:
                continue
            try:
                новое = сырые.decode(кодировка)
            except UnicodeDecodeError:
                continue
            if новое != m.group() and not _мусорный_токен(новое):
                замены[m.start()] = (m.end(), новое)
        if len(замены) < 0.5 * len(битые):
            continue
        выход = " ".join(v for _, v in замены.values())
        кириллица = any("а" <= c <= "я" for c in выход.lower())
        частота = _частотность(выход) if кириллица else 1.0
        # Кириллица с частотностью ниже 45 % — это чужая кодировка (KOI8 поверх
        # cp1251 даёт «мЮХЛЕМНБЮМХЕ»): такую починку не берём вовсе.
        if кириллица and частота < 0.45:
            continue
        балл = len(замены) / len(битые) * частота
        if лучший is None or балл > лучший[0]:
            лучший = (балл, кодировка, замены)
    if лучший is None:
        return текст, ""
    _, кодировка, замены = лучший
    части, позиция = [], 0
    for начало in sorted(замены):
        конец, новое = замены[начало]
        части.append(текст[позиция:начало])
        части.append(новое)
        позиция = конец
    части.append(текст[позиция:])
    return "".join(части), кодировка


# ── Внешние программы ────────────────────────────────────────────────────────

def _запуск(команда: list[str], таймаут: float) -> tuple[int | None, bytes, bytes]:
    """Запуск внешней программы. Код None — таймаут; вывод при этом тот, что успел
    прийти. Отдельной функцией — чтобы проверка подставляла сбои, не ломая
    настоящий poppler."""
    try:
        готово = subprocess.run(команда, capture_output=True, timeout=max(таймаут, 1),
                                check=False)
        return готово.returncode, готово.stdout or b"", готово.stderr or b""
    except subprocess.TimeoutExpired as e:
        return None, e.stdout or b"", e.stderr or b""
    except Exception:                                                   # noqa: BLE001
        return -999, b"", b""


def _про_пароль(stderr: bytes) -> bool:
    # Сообщение poppler и qpdf о пароле — их собственная строка, не текст документа.
    return b"password" in stderr.lower()


def _pdfinfo_страниц(путь: str) -> tuple[int, bool]:
    """Число страниц по pdfinfo и признак «нужен пароль». pdfinfo восстанавливает
    таблицу ссылок, как и pdftotext, и без числа страниц нельзя сказать, оборван
    ли документ потолком, когда pypdf файл не открыл."""
    if not shutil.which("pdfinfo"):
        return 0, False
    код, вывод, ошибки = _запуск(["pdfinfo", путь], 60)
    if код != 0:
        return 0, _про_пароль(ошибки)
    m = re.search(rb"^Pages:\s+(\d+)", вывод, re.M)
    return (int(m.group(1)) if m else 0), False


def _pdftotext(путь: str, с: int, по: int, таймаут: float, layout: bool) -> tuple[int | None, list[str], bytes]:
    """Страницы с..по одним вызовом. Возвращает (код, ГОТОВЫЕ страницы, stderr).

    pdftotext ставит «\\f» после КАЖДОЙ страницы, пустой тоже, поэтому готовых
    страниц ровно столько, сколько знаков «\\f», а хвост после последнего —
    недописанная страница упавшего вызова, её не берём.
    """
    ключи = ["-layout"] if layout else []
    код, вывод, ошибки = _запуск(["pdftotext", *ключи, "-enc", "UTF-8", "-f", str(с), "-l", str(по),
                                  путь, "-"], таймаут)
    части = вывод.decode("utf-8", errors="replace").split("\f")
    return код, части[:-1], ошибки


def _poppler(путь: str, до: int, layout: bool) -> dict:
    """Страницы 1..до через pdftotext. Возвращает тексты по номеру, сбойные номера,
    признаки «не открылся» и «нужен пароль», и не кончился ли срок."""
    итог: dict = {"тексты": {}, "сбой": set(), "не_открылся": False, "пароль": False,
                  "запрет": False, "срок": False, "короче": 0}
    срок = time.monotonic() + СРОК_ИЗВЛЕКАТЕЛЯ
    начало = 1
    while начало <= до:
        конец = min(до, начало + КУСОК - 1)
        осталось = срок - time.monotonic()
        if осталось <= 1:
            итог["срок"] = True
            break
        код, страницы, ошибки = _pdftotext(путь, начало, конец, min(ТАЙМАУТ_КУСКА, осталось), layout)
        if код == 1 and not страницы:
            # Код 1 у poppler — «не открыл файл». Он одинаков для всех страниц,
            # и постраничный повтор был бы двумя сотнями одинаковых отказов.
            итог["не_открылся"] = True
            итог["пароль"] = _про_пароль(ошибки)
            break
        if код == 3 and not страницы:
            # Код 3 — запрет копирования, который poppler соблюдает в части
            # сборок. Он тоже одинаков для всех страниц; pypdf запрета не
            # соблюдает, а без pypdf его снимет qpdf.
            итог["не_открылся"] = итог["запрет"] = True
            break
        if код == 99 and not страницы and b"page range" in ошибки.lower():
            # poppler насчитал страниц меньше, чем pypdf: дальше читать нечего,
            # а постраничный повтор дал бы по отказу на каждую страницу куска.
            итог["короче"] = начало - 1
            break
        if код == 0:
            for i, т in enumerate(страницы[:конец - начало + 1]):
                итог["тексты"][начало + i] = т
            if len(страницы) < конец - начало + 1:
                # Документ короче, чем думали (число страниц не было известно).
                итог["короче"] = начало + len(страницы) - 1
                break
            начало = конец + 1
            continue
        # Кусок упал или завис: берём что успело прийти, остальное — по странице,
        # чтобы одна плохая страница не уносила двадцать четыре соседних.
        for i, т in enumerate(страницы[:конец - начало + 1]):
            итог["тексты"][начало + i] = т
        for н in range(начало + len(страницы), конец + 1):
            осталось = срок - time.monotonic()
            if осталось <= 1:
                итог["срок"] = True
                break
            код1, одна, _ = _pdftotext(путь, н, н, min(ТАЙМАУТ_СТРАНИЦЫ, осталось), layout)
            if код1 == 0 and одна:
                итог["тексты"][н] = одна[0]
            else:
                итог["сбой"].add(н)
        if итог["срок"]:
            break
        начало = конец + 1
    return итог


def _qpdf(путь: str, куда: str) -> tuple[bool, bool]:
    """qpdf --decrypt с пустым паролем: снимает шифрование и заодно переписывает
    файл с восстановленной таблицей ссылок. Возвращает (получилось, нужен пароль).
    Код 3 у qpdf — «сделал, но с предупреждениями»: файл годен."""
    код, _, ошибки = _запуск(["qpdf", "--decrypt", "--password=", путь, куда], ТАЙМАУТ_КУСКА)
    вышло = код in (0, 3) and Path(куда).exists() and Path(куда).stat().st_size > 0
    return вышло, (not вышло and _про_пароль(ошибки))


# ── pypdf ────────────────────────────────────────────────────────────────────

def _открыть_pypdf(данные: bytes) -> dict:
    """Открыть pypdf с пустым паролем. Возвращает читатель или названную причину."""
    итог: dict = {"читатель": None, "страниц": 0, "шифр": False, "пароль": False, "почему": ""}
    try:
        from pypdf import PdfReader
    except Exception:                                                   # noqa: BLE001
        итог["почему"] = "нет pypdf"
        return итог
    try:
        чт = PdfReader(io.BytesIO(данные), strict=False)
    except Exception as e:                                              # noqa: BLE001
        итог["почему"] = f"pypdf: не открыл ({type(e).__name__})"
        return итог
    try:
        if чт.is_encrypted:
            итог["шифр"] = True
            try:
                # 0 — PasswordType.NOT_DECRYPTED: пустой пароль не подошёл.
                if not чт.decrypt(""):
                    итог["пароль"] = True
                    итог["почему"] = "pypdf: пустой пароль не подошёл"
                    return итог
            except Exception as e:                                      # noqa: BLE001
                # Шифр AES требует пакета cryptography; без него pypdf бросает
                # DependencyError, и это причина окружения, а не файла.
                итог["почему"] = f"pypdf: не расшифровал ({type(e).__name__})"
                return итог
        итог["страниц"] = len(чт.pages)
        итог["читатель"] = чт
    except Exception as e:                                              # noqa: BLE001
        итог["почему"] = f"pypdf: не прочёл дерево страниц ({type(e).__name__})"
    return итог


#: Имя объекта, который поток рисует оператором Do: «/Im1 Do».
_DO = re.compile(rb"/([^\s/\[\]()<>{}%]+)\s*Do\b")


def _рисует_картинку(ресурсы, данные: bytes, глубина: int = 0) -> bool:
    """Рисует ли поток картинку — сам или через форму.

    Смотрим, ЧТО РИСУЕТСЯ (оператор Do), а не что лежит в ресурсах: часть
    генераторов кладёт все картинки документа в общий словарь ресурсов, и тогда
    каждый пустой лист выглядел бы сканом. Сканер часто кладёт лист в форму (Form
    XObject), поэтому идём вглубь, но не глубже четырёх уровней: у настоящих
    файлов вложенность — один-два.
    """
    if ресурсы is None or глубина > 4:
        return False
    имена = set(_DO.findall(данные[:2_000_000]))
    if not имена:
        return False
    объекты = ресурсы.get_object().get("/XObject")
    if not объекты:
        return False
    объекты = объекты.get_object()
    for имя in имена:
        ссылка = объекты.get("/" + имя.decode("latin-1"))
        if ссылка is None:
            continue
        о = ссылка.get_object()
        вид = о.get("/Subtype")
        if вид == "/Image":
            return True
        if вид == "/Form":
            # Форма без своих ресурсов пользуется ресурсами страницы.
            свои = о.get("/Resources")
            if _рисует_картинку(свои if свои is not None else ресурсы, о.get_data(), глубина + 1):
                return True
    return False


def _есть_что_распознавать(стр) -> bool | None:
    """Есть ли на странице без текста то, что увидит распознавание: картинка
    (скан), встроенная картинка или длинный векторный поток (надписи кривыми).
    None — не удалось понять; такую страницу считаем сканом: лишнее
    распознавание стоит секунды, пропущенная страница — позиций."""
    try:
        поток = стр.get_contents()
        данные = поток.get_data() if поток is not None else b""
        if _рисует_картинку(стр.get("/Resources"), данные):
            return True
        if re.search(rb"(?:^|\s)BI\s.*?\sID\s", данные[:2_000_000], re.S):
            return True
        return len(данные) > ВЕКТОР
    except Exception:                                                   # noqa: BLE001
        return None


def _pypdf_страницы(чт, до: int, layout: bool) -> dict:
    """Страницы 1..до через pypdf. Сбой страницы не уносит файл: прежде (до
    23.09.2026) одна битая страница в режиме layout обнуляла весь документ."""
    итог: dict = {"тексты": {}, "сбой": set(), "распознавать": {}, "срок": False}
    срок = time.monotonic() + СРОК_ИЗВЛЕКАТЕЛЯ
    for н in range(1, до + 1):
        if time.monotonic() > срок:
            итог["срок"] = True
            break
        try:
            стр = чт.pages[н - 1]
        except Exception:                                               # noqa: BLE001
            итог["сбой"].add(н)
            continue
        текст = None
        if layout:
            try:
                текст = стр.extract_text(extraction_mode="layout")
            except Exception:                                           # noqa: BLE001
                текст = None
        if текст is None or (layout and not текст.strip()):
            # Режим layout спотыкается на отдельных страницах и шрифтах, а обычный
            # на них же бывает цел: пустой layout — ещё не пустая страница.
            try:
                простой = стр.extract_text()
                текст = простой if простой and простой.strip() else (текст or простой)
            except Exception:                                           # noqa: BLE001
                pass
        if текст is None:
            итог["сбой"].add(н)
        else:
            итог["тексты"][н] = текст
        итог["распознавать"][н] = _есть_что_распознавать(стр)
    return итог


# ── Выбор и классификация ────────────────────────────────────────────────────

def _варианты(текст: str) -> tuple[str, dict, str]:
    """Лучший из двух вариантов текста одного извлекателя: как есть и починенный.
    Возвращает (текст, оценка, чем чинили)."""
    сам = оценить(текст)
    починенный, чем = починить(текст)
    if чем:
        оп = оценить(починенный)
        if оп["балл"] > сам["балл"]:
            return починенный, оп, чем
    return текст, сам, ""


def _слот(текст: str, класс: str) -> str:
    """Текст страницы для выхода. Мусорная страница отдаёт ОСТАТОК после снятия
    мусора — цифры и артикулы, набранные целым шрифтом, — а не пустоту: страницу
    обвиняем (в распознавание), но уцелевшее не выбрасываем (правило 7).
    Распознавание, если оно будет, заменит слот целиком."""
    т = _очистить(текст, всё=(класс == "garbled")).replace("\f", "\n")
    return "\n".join(s.rstrip() for s in т.splitlines()).strip("\n")


def предел_страниц() -> int:
    """Потолок страниц из входа прогона PDF_PAGES. Читается при каждом вызове, а
    не при импорте, чтобы прогон и проверка могли его менять без перезагрузки."""
    try:
        п = int(os.environ.get("PDF_PAGES", "") or ПРЕДЕЛ_ПО_УМОЛЧАНИЮ)
    except ValueError:
        return ПРЕДЕЛ_ПО_УМОЛЧАНИЮ
    return п if п > 0 else ПРЕДЕЛ_ПО_УМОЛЧАНИЮ


def _пусто(причина: str, **ещё) -> dict:
    итог = {"text": "", "pages": 0, "pages_read": 0, "text_pages": [], "scan_pages": [],
            "garbled_pages": [], "blank_pages": [], "failed_pages": [], "page_methods": [],
            "method": "", "reason": причина, "missing": []}
    итог.update(ещё)
    return итог


def _недостающие() -> list[str]:
    нет = [п for п in ("pdftotext", "pdfinfo", "qpdf") if not shutil.which(п)]
    try:
        import pypdf  # noqa: F401
    except Exception:                                                   # noqa: BLE001
        нет.append("pypdf")
    return нет


def _попытка(данные: bytes, путь: str, layout: bool, нет: list[str]) -> dict:
    """Один проход обоими извлекателями по одним байтам."""
    откр = _открыть_pypdf(данные) if "pypdf" not in нет else {
        "читатель": None, "страниц": 0, "шифр": False, "пароль": False, "почему": "нет pypdf"}
    # Число страниц — БОЛЬШЕЕ из двух мнений. pypdf на битом дереве страниц
    # (strict=False) находит часть листов и молчит об остальных; pdfinfo — тот же
    # poppler, которым потом растрирует распознавание, и его счёт с ним сходится.
    # Вызов стоит сотые доли секунды, а молча потерянные листы — позиций.
    всего_инфо, пароль_poppler = (_pdfinfo_страниц(путь) if "pdfinfo" not in нет else (0, False))
    всего = max(откр["страниц"], всего_инфо)
    предел = предел_страниц()
    до = min(всего, предел) if всего else предел
    поп = (_poppler(путь, до, layout) if "pdftotext" not in нет and not пароль_poppler
           else {"тексты": {}, "сбой": set(), "не_открылся": "pdftotext" not in нет,
                 "пароль": пароль_poppler, "запрет": False, "срок": False, "короче": 0})
    пай = (_pypdf_страницы(откр["читатель"], до, layout) if откр["читатель"] is not None
           else {"тексты": {}, "сбой": set(), "распознавать": {}, "срок": False})
    if not всего:
        # Число страниц не узнали ни pypdf, ни pdfinfo: судим по тому, что
        # pdftotext отдал. Оборван ли документ, тогда неизвестно — и это честно.
        всего = max(поп["тексты"], default=0)
    return {"откр": откр, "поп": поп, "пай": пай, "всего": всего,
            "до": min(всего, предел), "предел": предел,
            "пароль": откр["пароль"] or поп["пароль"],
            "открылся": откр["читатель"] is not None or bool(поп["тексты"])}


def _собрать(п: dict, нет: list[str]) -> dict:
    """Постраничный выбор извлекателя, классификация страниц и причина."""
    поп, пай, до = п["поп"], п["пай"], п["до"]
    источники = {"pdftotext": поп["тексты"], "pypdf": пай["тексты"]}
    варианты: dict[int, dict[str, tuple[str, dict, str]]] = {}
    сумма = dict.fromkeys(ИЗВЛЕКАТЕЛИ, 0.0)
    for н in range(1, до + 1):
        варианты[н] = {}
        for имя in ИЗВЛЕКАТЕЛИ:
            if н in источники[имя]:
                в = _варианты(источники[имя][н])
                варианты[н][имя] = в
                сумма[имя] += в[1]["балл"]
    # Предпочтённый извлекатель — ОДИН на документ, по сумме баллов: так таблица,
    # разрезанная на страницы, выровнена одним способом, а не вперемешку.
    предпочтённый = max(ИЗВЛЕКАТЕЛИ, key=lambda и: (сумма[и], -ИЗВЛЕКАТЕЛИ.index(и)))

    слоты: list[str] = []
    методы: list[str] = []
    классы: dict[str, list[int]] = {"text": [], "scan": [], "garbled": [], "blank": []}
    сбой: list[int] = []
    победы = dict.fromkeys(ИЗВЛЕКАТЕЛИ, 0)
    for н in range(1, до + 1):
        в = варианты[н]
        if not в:
            # Ни один извлекатель страницу не взял — её растрирует распознавание.
            сбой.append(н)
            классы["scan"].append(н)
            слоты.append("")
            методы.append("")
            continue
        лучший = max(в, key=lambda и: (в[и][1]["балл"], -ИЗВЛЕКАТЕЛИ.index(и)))
        if предпочтённый in в and в[предпочтённый][1]["балл"] >= ПРЕИМУЩЕСТВО * в[лучший][1]["балл"]:
            лучший = предпочтённый
        текст, оц, чем = в[лучший]
        if оц["мусор"] >= МУСОРА_МИНИМУМ and оц["доля"] >= ПОРОГ_МУСОРА:
            класс = "garbled"
        elif оц["осмысленных"] >= ЗНАКОВ_НА_СТРАНИЦЕ:
            класс = "text"
            победы[лучший] += 1
        else:
            класс = "blank" if пай["распознавать"].get(н) is False else "scan"
        классы[класс].append(н)
        слоты.append(_слот(текст, класс))
        методы.append(f"{лучший}+{чем}" if чем else лучший)

    выиграли = sorted((и for и in ИЗВЛЕКАТЕЛИ if победы[и]), key=lambda и: -победы[и])
    итог = _пусто("", text="\f".join(слоты), pages=п["всего"], pages_read=до,
                  text_pages=классы["text"], scan_pages=классы["scan"],
                  garbled_pages=классы["garbled"], blank_pages=классы["blank"],
                  failed_pages=сбой, page_methods=методы, method=",".join(выиграли),
                  missing=нет)

    причины: list[str] = []
    if п["всего"] > до:
        причины.append(f"прочитано {до} стр. из {п['всего']}: потолок PDF_PAGES={п['предел']}")
    без_текста = [н for н in классы["scan"] if н not in сбой]
    if без_текста and len(без_текста) == до:
        причины.append(f"без текстового слоя все {до} стр.: скан, читается распознаванием")
    elif без_текста:
        причины.append(f"смешанный: {len(без_текста)} из {до} стр. без текстового слоя — в распознавание")
    if классы["garbled"]:
        причины.append(f"мусор вместо текста на {len(классы['garbled'])} стр. (шрифт без таблицы "
                       f"кодировки) — в распознавание")
    if сбой:
        причины.append(f"не извлеклись ни одним способом: {len(сбой)} стр.")
    if поп["срок"] or пай["срок"]:
        причины.append(f"срок {СРОК_ИЗВЛЕКАТЕЛЯ} с на извлекатель исчерпан")
    if причины and нет:
        причины.append("нет " + ", ".join(нет))
    итог["reason"] = "; ".join(причины)
    return итог


def прочитать_pdf(b: bytes, *, layout: bool = True) -> dict:
    """PDF постранично. НИКОГДА НЕ БРОСАЕТ: любой сбой — названная причина.

    Ключи ответа:
      text          — страницы через «\\f», страница N в text.split("\\f")[N-1];
      pages         — страниц в документе (0, если не узнать);
      pages_read    — сколько прочитано (меньше pages при обрыве на потолке);
      text_pages    — номера страниц с годным текстом;
      scan_pages    — без текстового слоя, но с картинкой или чертежом: в распознавание;
      garbled_pages — текстовый слой есть, но мусор: тоже в распознавание;
      blank_pages   — пустые листы: распознавать нечего;
      failed_pages  — не извлеклись ни одним способом (входят и в scan_pages);
      page_methods  — какой извлекатель взят на каждой странице («pdftotext+cp1251»
                      — взят pdftotext, кириллица перекодирована);
      method        — какой извлекатель победил по документу: «pdftotext», «pypdf»,
                      «pdftotext,pypdf» (оба, первым тот, что взял больше страниц);
      reason        — пусто, если прочитано всё; иначе что и почему не прочитано;
      missing       — каких программ нет в системе (pdftotext, pdfinfo, qpdf, pypdf).

    layout=True сохраняет отступы колонок: по ним library/pdftable.py
    восстанавливает таблицу. Для прозы вызывающий сжимает пробелы сам.
    """
    try:
        return _прочитать(b, layout)
    except Exception as e:                                              # noqa: BLE001
        # Последний рубеж. Сюда попадать не должно, но обещание «не бросает» —
        # обещание, а не пожелание: одно исключение здесь роняет весь прогон
        # разбора вместе с буфером непрочитанных файлов.
        return _пусто(f"сбой чтения PDF ({type(e).__name__})")


def _прочитать(b: bytes, layout: bool) -> dict:
    if not isinstance(b, (bytes, bytearray, memoryview)) or not len(b):
        return _пусто("пустой файл")
    b = bytes(b)
    где = b.find(b"%PDF", 0, ГОЛОВА)
    if где < 0:
        return _пусто("не PDF: нет подписи %PDF в начале файла")
    if где:
        # Мусор перед подписью (хвост заголовков MIME, BOM) срезается: смещения в
        # таблице ссылок отсчитаны от «%PDF», и после среза они снова верны.
        b = b[где:]
    нет = _недостающие()
    if "pdftotext" in нет and "pypdf" in нет:
        return _пусто("нет ни pdftotext (poppler-utils), ни pypdf", missing=нет)
    with tempfile.TemporaryDirectory() as каталог:
        путь = str(Path(каталог) / "in.pdf")
        Path(путь).write_bytes(b)
        п = _попытка(b, путь, layout, нет)
        расшифрован = False
        # qpdf — ВТОРАЯ попытка, а не первая: он нужен двум случаям из тысячи
        # (шифр, который не снял pypdf, и файл, который не открыл никто), а
        # переписывать каждый файл ради них — лишний проход по всем.
        без_pypdf = п["откр"]["читатель"] is None
        нужен_qpdf = п["пароль"] or not п["открылся"] or (
            без_pypdf and (п["откр"]["шифр"] or п["поп"]["запрет"]))
        if нужен_qpdf and "qpdf" not in нет:
            куда = str(Path(каталог) / "out.pdf")
            вышло, пароль_qpdf = _qpdf(путь, куда)
            if вышло:
                повтор = _попытка(Path(куда).read_bytes(), куда, layout, нет)
                if повтор["открылся"]:
                    п, расшифрован = повтор, True
            elif пароль_qpdf:
                п["пароль"] = True
        if п["пароль"] and not расшифрован and not п["открылся"]:
            хвост = "; нет qpdf для второй попытки" if "qpdf" in нет else ", ни qpdf"
            return _пусто(f"PDF зашифрован паролем: пустой пароль не подошёл ни pypdf, ни pdftotext{хвост}",
                          missing=нет)
        if not п["открылся"]:
            части = []
            if п["откр"]["почему"]:
                части.append(п["откр"]["почему"])
            if "pdftotext" in нет:
                части.append("нет pdftotext")
            elif п["поп"]["не_открылся"]:
                части.append("pdftotext: не открыл")
            if "qpdf" in нет:
                части.append("нет qpdf")
            elif нужен_qpdf:
                части.append("qpdf: не восстановил")
            return _пусто("PDF не открылся: " + "; ".join(части), missing=нет)
        if not п["всего"]:
            return _пусто("PDF без страниц", missing=нет)
        return _собрать(п, нет)


def в_запись(р: dict, rec: dict | None) -> None:
    """Постраничный счёт в запись файла indexer — те же поля, что пишет
    indexer.записать_счёт, чтобы подключение не меняло схему базы.

    pdf_mixed ставится, когда есть что распознавать (сканы или мусор) И текст
    файла не пуст: пустой файл распознавание и так берёт по статусу «пусто», а
    непустой без этой пометки не возьмёт никогда (library/ocr.py отбирает
    смешанные по pdf_mixed).
    """
    if rec is None or not р.get("pages"):
        return
    rec["pdf_pages"] = р["pages"]
    rec["pdf_pages_text"] = len(р["text_pages"])
    rec["pdf_pages_lost"] = len(р["failed_pages"])
    if (р["scan_pages"] or р["garbled_pages"]) and р["text"].strip():
        rec["pdf_mixed"] = True
