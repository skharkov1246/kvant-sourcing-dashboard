def classify(text: str) -> str | None:
    """Сегмент по тексту: побеждает тот, чьих слов встретилось больше.

    Возвращает None, если не встретилось ни одного слова. None — это не ошибка,
    а честный ответ «не знаю»: позиция ляжет в базу с пустым сегментом, и её
    подберёт переклассификация, когда словарь пополнится."""
    t = text.lower().replace("ё", "е")
    best, score = None, 0
    for sid, (_n, words) in SEGMENTS.items():
        n = sum(t.count(w.replace("ё", "е")) for w in words)
        if n > score:
            best, score = sid, n
    return best


def name_of(sid: str | None) -> str:
    """Человеческое название сегмента для журналов и сводок."""
    if not sid:
        return "сегмент не определён"
    return SEGMENTS.get(sid, (sid, []))[0]
