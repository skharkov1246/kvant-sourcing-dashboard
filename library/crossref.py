# ключ нельзя. Тест сверяет, что числа в воркере те же.
#
# ЧАСТЕЙ СПИСКА ВОСЕМЬ, КОРЗИН ТРИДЦАТЬ ДВЕ. Замер на тяжёлом корпусе в три
# нынешних объёма (49 200 позиций): самая тяжёлая часть списка 2,69 МиБ (34 %
