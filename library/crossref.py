КОД_ГОДЕН = docfilter.sql_код_годен("part_number")

# КОЛИЧЕСТВО, КОТОРОЕ НЕ ЧИТАЕТСЯ, НЕ ПОКАЗЫВАЕТСЯ. До 24.09.2026 разбор склеивал
