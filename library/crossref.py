# ВЕС ПОЗИЦИИ: СКОЛЬКО ЕЁ СПРАШИВАЮТ. Восемь процентов позиций имеют выбор из
# двух поставщиков, у остальных девяноста двух предложение одно. Рассылать по ним
# запросы вторым поставщикам придётся по порядку, и порядок этот должны задавать
# деньги, а не алфавит.
#
# ИСТОЧНИК — СПРОС, А НЕ НАШИ ЗАПРОСЫ. Число карточек запроса говорит, сколько раз
# МЫ спрашивали рынок; число сделок в lib_demand — сколько раз спрашивали НАС.
# Второе и есть значимость: позиция, о которой спросил один заказчик один раз,
# и позиция из тридцати спецификаций — разная работа, хотя запрос мы посылали по
# одному разу.
#
# КОЛИЧЕСТВО СУММИРУЕТСЯ ТОЛЬКО В ОДНОЙ ЕДИНИЦЕ. «120 штук» и «40 килограммов» в
# сумме не дают «160» ничего. Поэтому сумма отдаётся ТОЛЬКО когда единица одна на
# все строки; иначе её нет, а число различных единиц печатается рядом. Это то же
# правило, по которому цены не складываются через валюты.
СПРОС_SQL = """
with ключи as (
  select distinct lib_pn_key(part_number) as ключ
    from lib_prices
   where feed = %s and coalesce(btrim(part_number), '') <> ''
     and lib_pn_key(part_number) <> '' and """ + КОД_ГОДЕН + """
)
select к.ключ,
       count(distinct d.deal_id)                                     as сделок,
       count(*)                                                      as строк,
       count(distinct coalesce(btrim(d.unit), ''))
         filter (where coalesce(btrim(d.unit), '') <> '')            as единиц,
       -- Количество спроса больше предела — склейка ячеек, а не спрос: в сумму
       -- не идёт (КОЛ_ЧИТАЕТСЯ, та же граница).
       sum(d.qty) filter (where d.qty > 0 and d.qty <= """ + str(int(quotes.МАКС_КОЛИЧЕСТВО)) + """)
                                                                     as количество,
       -- ИМЯ ЕДИНИЦЫ, А НЕ ТОЛЬКО ИХ ЧИСЛО. Количество без единицы — число без
       -- основания: «480» одинаково читается как штуки, метры и килограммы.
       -- min() здесь безопасен ровно потому, что число рядом печатается только
       -- при единиц = 1: тогда минимум и есть та единственная единица.
       min(nullif(btrim(d.unit), ''))                                as единица
  from ключи к
  -- ЖИВОЙ ВИД, А НЕ ТАБЛИЦА. lib_demand_live исключает строки, помеченные как
  -- текст тендерного документа (lib_row_junk). Считать пункт договора спросом
  -- значило бы завысить вес позиции тем, чего никто не спрашивал, — и порядок
  -- рассылки вторым поставщикам пошёл бы по мусору. Ошибка была здесь до
  -- 22.09.2026: запрос читал таблицу.
  join lib_demand_live d on lib_pn_key(d.part_number) = к.ключ
 group by к.ключ
"""

# БРЕНД, НАЗВАННЫЙ В СТРОКЕ СПЕЦИФИКАЦИИ, — ячейка изготовителя спроса по ключу
# кода (правило П2, источник «строка»; бренд_позиции ниже). Ячейки, а не бренды:
# узнаёт бренд сборка — реестром, тем же правилом, что у ячейки КП.
#
# СТОРОНА ФАЙЛА ОБЯЗАТЕЛЬНА. В lib_demand лежат строки всех файлов сделки и
# карточки: спецификации заказчика, КП поставщиков и НАШИ исходящие ТКП, где со
# второй строки идут аналоги (codes_sql.src_case, проверка определений
# 23.09.2026). Бренд позиции называет только спецификация заказчика; сторона
# едет колонкой, и сборка берёт «спецификацию», а остальное считает в журнал —
# сколько ячеек не пошло в дело, видно числом (правило 0). Сторона выводится
# тем же запасным путём, что у страницы /brands (codes_sql.FILES_CTE).
#
# Соединение — по выражению ключа, как у СПРОС_SQL (индекс lib_demand_pnkey),
# а ячейка обрезается до 200 знаков: длиннее — описание, а не имя.
СПРОС_БРЕНДЫ_SQL = """
with ключи as (
  select distinct lib_pn_key(part_number) as ключ
    from lib_prices
   where feed = %s and coalesce(btrim(part_number), '') <> ''
     and lib_pn_key(part_number) <> '' and """ + КОД_ГОДЕН + """
),
""" + codes_sql.FILES_CTE + """
select к.ключ,
       """ + codes_sql.src_case("coalesce(f.side, 'без файла')") + """ as сторона,
       left(btrim(d.oem), 200)                                     as ячейка,
       count(*)                                                    as строк
  from ключи к
  join lib_demand_live d on lib_pn_key(d.part_number) = к.ключ
  left join files f on f.file_id = d.source_file
 where coalesce(btrim(d.oem), '') <> ''
 group by 1, 2, 3
"""

# СЦЕПКА «КЛЮЧ КОТИРОВКИ → ДЕТАЛЬ КАТАЛОГА» — ОДНА НА ВСЕ ЧЕТЫРЕ ЗАПРОСА.
#
# Соединять по lib_parts.id недостаточно: id считается по catalog_norm, когда тот
# заполнен, и у 82 деталей из 13 501 он не равен lib_pn_key(catalog_no) (замер
# 22.09.2026). Такая деталь из соединения по id выпадает МОЛЧА — связи нет, и это
# неотличимо от «детали в каталоге нет». Тридцать артикулов котировок попали
# именно в этот хвост, и все тридцать ведут к машине.
#
# Ступеней две, и порядок важен. Совпадение по id точное, поэтому оно первое.
# Второй путь берётся ТОЛЬКО когда по id не нашлось ничего, и ТОЛЬКО когда он
# однозначен: два каталожных номера, дающих один ключ, привязали бы котировку к
# чужой детали, а на странице это было бы неотличимо от правды. Пустой раздел
# честнее неверного.
#
# Текст один на все четыре запроса намеренно: разойдись ступени между ними — и
# карточка показала бы аналоги одной детали, а машину другой.
СЦЕПКА = """
with ключи as (
  select distinct lib_pn_key(part_number) as ключ
    from lib_prices
   where feed = %s and coalesce(btrim(part_number), '') <> ''
     and lib_pn_key(part_number) <> '' and """ + КОД_ГОДЕН + """
), точно as (
  select к.ключ, p.id as part_id
    from ключи к join lib_parts p on p.id = к.ключ
), хвостом as (
  select ключ, min(part_id) as part_id
    from (select к.ключ, p.id as part_id
            from ключи к
            join lib_parts p on lib_pn_key(p.catalog_no) = к.ключ
           where not exists (select 1 from точно т where т.ключ = к.ключ)) x
   group by ключ having count(distinct part_id) = 1
), сцепка as (
  select ключ, part_id from точно
  union all
  select ключ, part_id from хвостом
)
"""

# Каталожная часть карточки. Позиция, не нашедшаяся в каталоге, покажет
# предложения и не покажет ни аналогов, ни машины — и скажет об этом словами, а
# не пустотой.
КАТАЛОГ_SQL = СЦЕПКА + """
select с.ключ, p.catalog_no, p.name, p.oem, p.category, p.target_equipment, p.kv_no
  from сцепка с join lib_parts p on p.id = с.part_id
"""

АНАЛОГИ_SQL = СЦЕПКА + """
select с.ключ, a.alt_pn, a.kind, a.alt_maker, a.confidence
  from сцепка с join lib_part_alt a on a.part_id = с.part_id
 order by с.ключ, a.kind, a.alt_pn
"""

МАШИНЫ_SQL = СЦЕПКА + """
select с.ключ, coalesce(mo.name, m.model_id) as машина
  from сцепка с
  join lib_part_models m on m.part_id = с.part_id
  left join lib_models mo on mo.id = m.model_id
 order by с.ключ, 2
"""

# КТО ЭТО ДЕЛАЕТ И В КАКОЙ РОЛИ. Ровно то, о чём ТЗ говорит «кто является ОЕМ,
# ОДМ». Роль — слово реестра исполнителей, а не наша оценка.
ИЗГОТОВИТЕЛИ_SQL = СЦЕПКА + """
select с.ключ, s.name, s.kind, s.country, ps.makes, ps.verdict, ps.confidence
  from сцепка с
  join lib_part_suppliers ps on ps.part_id = с.part_id
  join lib_suppliers s on s.id = ps.supplier_id
 order by с.ключ, s.name
"""


# БРЕНД С КАРТОЧКИ ЗАПРОСА — ИМЕНЕМ, А НЕ НОМЕРОМ. lib_prices.rfq_brands хранит
# номера элементов справочника марок портала (СП-176), и карточка номенклатуры
# печатала «1138, 340, 3448» (24.09.2026). Имя берётся из реестра брендов
# (library/supabase/brands_schema.sql): элемент → ключ бренда (вид
# lib_brand_sp176) → имя (lib_brands.name); элемент без однозначного бренда —
# написание самого справочника (lib_brand_alias, source «СП-176»). Реестра в базе
# нет — номера остаются как были: инструмент чтения сперва спрашивает базу, есть
# ли таблицы (РЕЕСТР_БРЕНДОВ_ЕСТЬ_SQL), и не падает на чистой.
РЕЕСТР_БРЕНДОВ_ЕСТЬ_SQL = """
select to_regclass('lib_brand_alias') is not null
   and to_regclass('lib_brand_sp176') is not null
   and to_regclass('lib_brands') is not null
"""

ИМЕНА_БРЕНДОВ_SQL = """
select a.sp176_id::text                                              as элемент,
       coalesce(min(b.name),
                min(btrim(a.spelling)) filter (where a.source = 'СП-176')) as имя
  from lib_brand_alias a
  left join lib_brand_sp176 s on s.sp176_id = a.sp176_id
  left join lib_brands b on b.brand_key = s.brand_key
 where a.sp176_id is not null
 group by a.sp176_id
"""


def имена_брендов(cur) -> dict[str, str]:
    """Номер элемента СП-176 → имя бренда; пусто, если реестра в базе нет."""
    cur.execute(РЕЕСТР_БРЕНДОВ_ЕСТЬ_SQL)
    if not cur.fetchone()[0]:
        return {}
    cur.execute(ИМЕНА_БРЕНДОВ_SQL)
    return {str(элемент): имя for элемент, имя in cur.fetchall() if имя and имя.strip()}


def _бренды(строка, имена=None) -> list[str]:
    """Список брендов из поля-сцепки. Пустые элементы — не бренды.

    «FAG,» с запятой в хвосте и значение из одного пробела дают элемент-пустышку;
    без отсева у компании без брендов бренд оказывается один.

    имена — номер элемента СП-176 → имя бренда (имена_брендов). Номер, которого
    в реестре нет, остаётся номером: пропажа бренда хуже непрочитанного имени.
    """
    if not строка:
        return []
    имена = имена or {}
    return sorted({имена.get(ч.strip(), ч.strip())
                   for ч in str(строка).split(",") if ч.strip()})


def _дата(v) -> str | None:
    return v.isoformat()[:10] if v is not None and hasattr(v, "isoformat") else None


def _число(v):
    """Numeric из psycopg2 — Decimal; в JSON он не сериализуется."""
    return float(v) if v is not None else None


