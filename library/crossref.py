# ТОЧНЫЙ ДУБЛЬ ПРЕДЛОЖЕНИЯ — ОДНО ПРАВИЛО НА СБОРКУ И РЕВИЗИЮ.
#
# Ревизия 25.09.2026 (прогон portal-audit.yml 36099589326, проверка n.o_dup)
# насчитала 9 589 предложений из 29 020 (33,0 %), у которых в той же позиции
# есть другое с теми же компанией, ценой, валютой, количеством и датой: сорсер
# видел одно предложение по два-три раза, «2 предложения» у позиции с одним
# и «сравнимы по цене» там, где сравнивать не с чем.
#
# ОТКУДА ОНИ. Не из соединений запроса: sup_identifier уникален по ключу портала
# (sup_identifier_bitrix_once), sup_name_shown — строка на сущность. Дубли лежат
# в самой lib_prices, и запрос отдавал каждую строку предложением. Идемпотентность
# записи цены — по ФАЙЛУ (price_store.СНЯТЬ, по source_url), а одинаковые строки
# приходят из разных файлов: разбор карточки берёт все пять полей КП (КП
# поставщика, Offer old, Processed offer, Processed offer / archive, Offer from
# supplier — indexer.ссылки_карточек), у копии одного КП в каждом поле свой id
# вложения, и без_повторов() их не узнаёт; тот же КП бывает приложен к
# нескольким карточкам; и сам файл может повторять строку. Какая из трёх причин
# главная, сборка теперь считает сама (снимок, поле dups) — по файлу и карточке.
#
# ЧТО С НИМИ ДЕЛАЕТСЯ. Точные дубли по этому ключу схлопываются в одно
# предложение; строки базы не трогаются. Предложение, отличающееся хоть одним
# полем ключа, остаётся отдельным. Сведения копий не теряются: число строк (x),
# другие карточки запроса (g), бренды карточек — объединением, а если копия
# несёт значение, которого оставшееся не показывает, — пометка w. Ревизия
# (scripts/portal_audit.py, n.o_dup) зовёт эту же функцию: разойдись правила —
# и она ругала бы то, что сборка считает разными предложениями.
ПОЛЯ_ДУБЛЯ = tuple(ПОЛЯ_ПРЕДЛОЖЕНИЯ[k] for k in ("co", "price", "cur", "qty", "date"))

# Поля, в которых копии одного предложения расходятся законно, и расхождением
# (w) это не считается: карточка запроса (копии с разных карточек и приходят) и
# её бренды — они объединяются; уверенность разбора и пометки источника —
# сведения о разборе, а не о предложении; и сами поля ключа и схлопывания.
_НЕ_СРАВНИВАТЬ = frozenset(ПОЛЯ_ДУБЛЯ) | frozenset(
    ПОЛЯ_ПРЕДЛОЖЕНИЯ[k] for k in ("rfq", "brands", "conf", "src", "dups", "rfq_more", "differ",
                                  "own"))


def ключ_дубля(o: dict) -> tuple:
    """Ключ точного дубля предложения в однобуквенных полях снимка."""
    return tuple(o.get(k) for k in ПОЛЯ_ДУБЛЯ)


# СРАВНИМОСТЬ — ЦЕНЫ ДВУХ РАЗНЫХ КОМПАНИЙ В ОДНОЙ ВАЛЮТЕ.
#
# Ревизия 25.09.2026 (прогон portal-audit.yml 36168124416, проверка n.cmp_co)
# нашла 3 654 позиции из 4 343 «сравнимых по цене» при ОДНОЙ компании: правило
# считало цены, а не поставщиков, и два КП одной компании (повторный запрос,
# две даты) попадали в отбор «Сравнимы по цене» — сорсер открывал позицию, а
# сравнивать было не с кем. Сравнение цен — это выбор между поставщиками,
# поэтому нужны две разные компании, у каждой цена, и все цены позиции в одной
# валюте (пересчёта по курсу нет намеренно, см. сборку). Предложение без
# компании второй компанией не считается: «Не назван» может быть той же.
# Одно правило на позицию и на код до разбиения (cmp_lost), иначе потеря от
# разбиения мерилась бы другим аршином.
def сравнима(предложения) -> bool:
    """Позиция сравнима по цене: цены от двух компаний и больше, валюта одна."""
    К = ПОЛЯ_ПРЕДЛОЖЕНИЯ
    с_ценой = [о for о in предложения if о.get(К["price"]) is not None and о.get(К["cur"])]
    return (len({о[К["cur"]] for о in с_ценой}) == 1
            and len({о[К["co"]] for о in с_ценой if о.get(К["co"])}) >= 2)


def _схлопнуть(копии: list[dict]) -> dict:
    """Копии одного предложения (одинаковый ключ_дубля) → одно предложение.

    Остаётся самая полная копия, при равенстве — первая, то есть самая свежая
    (ПРЕДЛОЖЕНИЯ_SQL упорядочен по created_at desc). Составлять предложение из
    полей разных копий нельзя: пометки источника r относятся к значениям своей
    строки, и сборная строка утверждала бы то, чего не писал ни один файл.
    """
    К = ПОЛЯ_ПРЕДЛОЖЕНИЯ
    о = dict(max(копии, key=len))
    о[К["dups"]] = len(копии)
    бренды = sorted({b for x in копии for b in x.get(К["brands"]) or []})
    if бренды:
        о[К["brands"]] = бренды
    другие = sorted({x[К["rfq"]] for x in копии if x.get(К["rfq"]) is not None}
                    - {о.get(К["rfq"])}, key=str)
    if другие:
        о[К["rfq_more"]] = другие
    if any(x[поле] != о.get(поле) for x in копии for поле in x if поле not in _НЕ_СРАВНИВАТЬ):
        о[К["differ"]] = 1
    return о


def _откуда_дубль(карточки: set, файлы: set) -> str:
    """Происхождение группы копий — для счёта в снимке (поле dups)."""
    if len(карточки) > 1:
        return "cards"          # один КП на нескольких карточках запроса
    if len(файлы) > 1:
        return "one_card"       # одна карточка, разные файлы: копии КП в полях
    if файлы and None not in файлы:
        return "one_file"       # строка повторена в самом файле
    return "no_file"            # файл неизвестен (строка без source_url)


# ПОМЕТКИ ИСТОЧНИКА УСЛОВИЙ ОДНОЙ СТРОКОЙ. Порядок закреплён: базис, оплата,
# срок поставки, срок изготовления. Значения — первая буква состояния разбора
# (library/offer_terms.py): с=строка, ф=файл, н=нет (ВЕРИФИЦИРОВАНО отсутствует),
# м=несколько (в КП разные значения, выбрать нельзя), ?=не проверено.
#
# «н» и «?» — РАЗНЫЕ вещи, и в этом весь смысл пометок: первое значит «поставщик
# условия не назвал, можно спросить», второе — «наш разбор до него не дошёл».
# Прочерк на экране без пометки путал их между собой.
ПОМЕТКА = {"строка": "с", "файл": "ф", "нет": "н", "несколько": "м",
           "не проверено": "?"}


def _пометки(*состояния) -> str | None:
    буквы = "".join(ПОМЕТКА.get(с or "не проверено", "?") for с in состояния)
    # Все четыре «не проверено» — это отсутствие сведений, а не сведения:
    # такой ключ в снимок не едет и на экране ничего не рисует.
    return None if set(буквы) <= {"?"} else буквы


def _коротко(d: dict) -> dict:
    """Пустые ключи выбрасывает, остальные переименовывает в однобуквенные.

    Две операции в одной функции нарочно: разделить их значило бы получить два
    места, где имя ключа может разойтись с таблицей.
    """
    готово = {}
    for имя, значение in d.items():
        if значение is None or значение == "" or значение == [] or значение == {}:
            continue
        готово[ПОЛЯ_ПРЕДЛОЖЕНИЯ[имя]] = значение
    return готово


def _без_пустых(d: dict) -> dict:
    """Ключи без значения выбрасываются; ноль и False — значения, они остаются.

    «Срок 0 дней» и «срок неизвестен» — разные вещи, и схлопнуть их в одно
    значило бы соврать о поставке. Поэтому проверка на None и пустоту, а не на
    ложность.
    """
    return {k: v for k, v in d.items()
            if v is not None and v != "" and v != []}


# ── БРЕНД ПОЗИЦИИ: ПАРА «БРЕНД + КОД» (правила номенклатуры П1 и П2) ─────────
#
# Владелец, 25.09.2026: «кодировка всегда привязана к бренду… код может стоять
# отдельно, но в соседнем столбце обязательно должен быть бренд». П1: позиция —
# пара «бренд + код», а не код; один код у двух брендов — две позиции; код без
# бренда записывается, но стоит в папке «Бренд не определён» с причиной. П2:
# бренд выбирается одним правилом по убыванию надёжности, у значения — источник.
# П9: правило сперва работает ПРИ ЧТЕНИИ — здесь, в сборке снимка; в базе не
# переписывается и не удаляется ничего.
#
# ИСТОЧНИКИ ПО УБЫВАНИЮ НАДЁЖНОСТИ (П2):
#   · каталог  — изготовитель детали каталога, сцепленной с кодом (lib_parts.oem,
#                СЦЕПКА). Наша ведомость: слово берётся и без реестра, кроме
#                закрытого списка «не бренд» (пометки незнания, страны, цифры);
#   · строка   — бренд, названный в строке спецификации заказчика
#                (СПРОС_БРЕНДЫ_SQL, сторона «заказчик») или в строке КП
#                (lib_prices.oem) и УЗНАННЫЙ реестром. Не узнанное реестром слово
#                бренда не даёт: оно остаётся «словом поставщика» в плитке карточки;
#   · карточка — марка на карточке запроса (rfq_brands → СП-176 → реестр), и
#                только когда марка у карточки ОДНА: карточка на двадцать строк с
#                марками «SKF, FAG, NSK» о бренде отдельного кода не говорит;
#   · маска    — форма кода изготовителя (МАСКИ ниже). ПРЕДПОЛОЖЕНИЕ, и только с
#                подтверждением (там же — почему).
#
# ЧЬЁ УТВЕРЖДЕНИЕ, О ЧЁМ ОНО. Каталог, спецификация и маска говорят о КОДЕ; строка
# КП и карточка запроса — о своём ПРЕДЛОЖЕНИИ (так же судит карточка кода /p,
# portal_code: слово поставщика делает строку другой позицией, а не позицию
# спорной). Отсюда правило разбиения, одно на сборку и ревизию:
#   1. Бренд предложения — его строка КП, если реестр узнал в ней ровно один
#      бренд; иначе марка его карточки, если она одна. Иначе своего бренда нет.
#   2. Бренд кода — бренд_позиции() по каталогу, спецификации и маске.
#   3. Предложение со своим брендом идёт в пару (свой бренд, код). Предложение без
#      своего бренда — в пару (бренд кода, код); бренда кода нет, а свои бренды у
#      предложений кода есть и он ОДИН — в пару этого бренда («присоединено»: у
#      предложения пометка, что его КП бренда не называет); иначе — в «Бренд не
#      определён» с причиной «спорно» (бренд кода спорен или своих брендов два и
#      больше) или «нет» (не назвал никто).
# Ни одно предложение не теряется и не удваивается: каждое идёт ровно в одну пару
# (тест test_предложения_не_теряются_при_разбиении).
#
# «СПОРНО» — только внутри одного уровня. Два разных бренда на ВЫСШЕМ уровне,
# где бренд вообще назван (ячейка каталога «SKF/FAG», спецификации заказчиков с
# SKF и с FAG), — бренд не определён, показываются оба. Разные уровни не спорят:
# для того порядок П2 и заведён. Каталог против спецификации — берётся каталог,
# а случай считается в журнал (cat_vs_row): чаще всего каталог называет
# изготовителя машины (Telsmith), а заказчик — изготовителя узла (SKF), и оба
# правы; объявить такие позиции спорными значило бы отправить в «не определён»
# самые описанные позиции (правило 0). Плитки карточки показывают все слова.
ИСТОЧНИКИ_БРЕНДА = ("каталог", "строка", "карточка", "маска")
ПРИЧИНЫ_БЕЗ_БРЕНДА = ("нет", "спорно")

# МАСКИ КОДОВ ИЗГОТОВИТЕЛЕЙ — ЗАКРЫТЫМ СПИСКОМ (правило 7: обвинять только им).
# Семь цифр подряд — это и Cummins, и внутренний номер завода, и номер чертежа, и
# новый номер Caterpillar без дефиса («123-4567»). Маска без подтверждения
# превратила бы в Cummins каждый такой номер, а неверный бренд хуже пустого: по
# нему сорсер пишет не тому изготовителю. Поэтому маска даёт бренд, только если
# СЛОВО бренда уже стоит у самой позиции — в наименовании, в не узнанном реестром
# слове изготовителя (строка КП, спецификация, каталог), в имени машины или в
# марке карточки. Типичный случай — «Фильтр масляный Cummins» в наименовании при
# пустой колонке изготовителя. Маска совпала, подтверждения нет — бренда нет, а
# число таких кодов идёт в журнал (mask_unconfirmed): правило сперва меряют.
# Поля: ключ бренда, имя, форма КЛЮЧА кода (fullmatch), слова-подтверждения,
# как читать.
МАСКИ = (
    ("cummins", "Cummins", r"\d{7}", r"cummins|к[ау]м+инс",
     "семь цифр подряд (4088833)"),
    ("caterpillar", "Caterpillar", r"\d[a-z]\d{4}",
     r"caterpillar|катерпил+[еа]р|(?<![a-zа-я])cat(?![a-zа-я])",
     "цифра, буква, четыре цифры (5P-9960)"),
)

# Деление ячейки изготовителя на части — то же, что у страницы /brands
# (codes_sql.SPLIT_RE; brands.ключи_ячейки): «SKF (Швеция)», «SKF/FAG».
_ДЕЛЕНИЕ = brands._ДЕЛЕНИЕ
# «Не бренд» для слова каталога — закрытым списком запроса страницы /brands:
# пометки незнания и стоп-слова, страны (codes_sql.JUNK_WORDS, COUNTRIES,
# UNKNOWN_RE) и значение без двух букв подряд.
_НЕ_БРЕНДЫ = frozenset(codes_sql.JUNK_WORDS) | frozenset(codes_sql.COUNTRIES)
_НЕЗНАНИЕ = re.compile(codes_sql.UNKNOWN_RE)


def реестр_брендов(словарь=None, *, разложение=None, карточка=None, откуда=None) -> dict:
    """Словарь брендов (форма dict/oem.json или brands.словарь_из_реестра) → то,
    чем сборка узнаёт бренд: карта «ключ написания → ключ бренда», разложение
    записей-не-брендов (brands.разложение_словаря), имена брендов и элементы
    СП-176 с ключом бренда (реестр базы, brands.читать_реестр).

    Карта считается тем же правилом, что у страницы /brands (brands.карта_словаря):
    бренд дают только записи вида «бренд», написание двух брендов в карту не идёт.
    """
    карта, записи, _ = brands.карта_словаря(словарь or {})
    return {"карта": карта,
            "разложение": {k: list(v) for k, v in (разложение or {}).items()},
            "имена": {k: (r.get("name") or k) for k, r in записи.items()},
            "карточка": {str(e): k for e, k in (карточка or {}).items() if k},
            "откуда": откуда}


def _имя_бренда(р, k, запасное=None) -> str:
    return (р or {}).get("имена", {}).get(k) or запасное or k


def узнать(ячейка, р, код=None) -> list[str]:
    """Ячейка изготовителя → ключи брендов, УЗНАННЫЕ реестром (без не узнанных).

    Сначала ячейка целиком; не нашлась — по частям. Ячейка, равная самому коду,
    — столкновение колонок шапки («Код/Артикул производителя»), а не бренд."""
    t = str(ячейка or "").strip()
    if not t or not р:
        return []
    if код and docfilter.ключ_кода(t) == код:
        return []
    k = codes_sql.ключ_написания(t)
    if k in р["карта"]:
        return [р["карта"][k]]
    if k in р["разложение"]:
        return list(р["разложение"][k])
    out = []
    for часть in _ДЕЛЕНИЕ.split(t):
        kч = codes_sql.ключ_написания(часть or "")
        if len(kч) < 2 or (код and docfilter.ключ_кода(часть) == код):
            continue
        for x in ([р["карта"][kч]] if kч in р["карта"] else р["разложение"].get(kч, [])):
            if x not in out:
                out.append(x)
    return out


def не_бренд(слово) -> bool:
    """Закрытый список «не бренд» для слова, которое реестр не узнал.

    Короткие имена белого списка страницы /brands («3M», «GE») защищены."""
    н = " ".join(str(слово or "").lower().replace("ё", "е").split()).strip(" .,;:-«»\"'")
    if codes_sql.ключ_написания(н) in codes_sql.WHITELIST:
        return False
    return (not re.search(r"[a-zа-я]{2}", н) or н in _НЕ_БРЕНДЫ
            or bool(_НЕЗНАНИЕ.match(н)))


def бренды_каталога(ячейка, р, код=None) -> list[tuple[str, str]]:
    """Ячейка изготовителя каталога → [(ключ, имя)]: узнанное реестром — его
    бренд; не узнанное — само слово (наша ведомость), кроме закрытого списка."""
    t = str(ячейка or "").strip()
    if not t or (код and docfilter.ключ_кода(t) == код):
        return []
    узнано = узнать(t, р, код)
    if узнано:
        return [(k, _имя_бренда(р, k)) for k in узнано]
    out = []
    for часть in [t] if not _ДЕЛЕНИЕ.search(t) else _ДЕЛЕНИЕ.split(t):
        часть = (часть or "").strip()
        k = codes_sql.ключ_написания(часть)
        if len(k) < 2 or не_бренд(часть) or (код and docfilter.ключ_кода(часть) == код):
            continue
        ключи = узнать(часть, р, код) or [k]
        for x in ключи:
            if x not in [o[0] for o in out]:
                out.append((x, _имя_бренда(р, x, часть)))
    return out


def бренды_карточки(строка, р=None, имена=None) -> list[tuple[str, str]]:
    """Поле rfq_brands → [(ключ, имя)] марок карточки запроса.

    Элемент СП-176 с ключом реестра — его бренд; без ключа — написание
    справочника, узнанное реестром или словом; номер без имени — не бренд
    (номер элемента наружу не идёт). Поле обрезано базой на 200 знаках:
    последний элемент такого поля может быть обрублен и не берётся (как у
    portal_code)."""
    t = str(строка or "")
    if not t.strip():
        return []
    элементы = t.split(",")
    if len(t) >= 200 and len(элементы) > 1:
        элементы = элементы[:-1]
    р = р or {}
    имена = имена or {}
    out = []
    for e in (x.strip() for x in элементы):
        if not e:
            continue
        k = р.get("карточка", {}).get(e)
        имя = имена.get(e)
        if k:
            имя = _имя_бренда(р, k, имя)
        else:
            if not имя and e.isdigit():
                continue
            имя = имя or e
            узнано = узнать(имя, р)
            if len(узнано) == 1:
                k = узнано[0]
                имя = _имя_бренда(р, k, имя)
            elif узнано or не_бренд(имя):
                continue
            else:
                k = codes_sql.ключ_написания(имя)
        if k and k not in [o[0] for o in out]:
            out.append((k, имя))
    return out


def маска_кода(ключ) -> list[tuple]:
    """Маски из закрытого списка, под которые подходит КЛЮЧ кода."""
    return [м for м in МАСКИ if re.fullmatch(м[2], str(ключ or ""))]


def подтверждена(маска, тексты) -> bool:
    """Слово бренда маски стоит в текстах самой позиции."""
    rx = re.compile(маска[3], re.I)
    return any(rx.search(str(t).lower().replace("ё", "е")) for t in тексты if t)


def бренд_позиции(претензии) -> dict:
    """Претензии на бренд → решение по П2. Одна функция на всё: бренд кода,
    источник бренда пары и причина «не определён» считаются ею.

    претензии — [(источник, ключ бренда, имя, строк)], источник из
    ИСТОЧНИКИ_БРЕНДА. Берётся ВЫСШИЙ уровень, где бренд назван:
      · один бренд — {"k", "n", "src"};
      · два и больше — {"why": "спорно", "cand": [[имя, источник], …]} (по
        убыванию строк, затем по имени);
      · претензий нет — {"why": "нет"}.
    """
    for источник in ИСТОЧНИКИ_БРЕНДА:
        уровень = [п for п in претензии if п[0] == источник and п[1]]
        if not уровень:
            continue
        строк, имя = collections.Counter(), {}
        for _, k, n, c in уровень:
            строк[k] += c or 1
            имя.setdefault(k, n or k)
        if len(строк) == 1:
            k = next(iter(строк))
            return {"k": k, "n": имя[k], "src": источник}
        return {"why": "спорно",
                "cand": [[имя[k], источник]
                         for k, _ in sorted(строк.items(), key=lambda x: (-x[1], имя[x[0]], x[0]))]}
    return {"why": "нет"}


def ид_позиции(p) -> str:
    """Ключ пары «бренд + код» в снимке: ключ кода, а при бренде — «код~бренд».

    Ключ кода k остаётся у позиции как был: на него ссылаются страницы брендов,
    поставщиков и поиска (/nomenclature#k=), и адрес кода, разбитого на пары,
    открывает все его пары. Корзина подробностей — по ключу кода, внутри неё
    пара лежит под этим ключом."""
    return str(p.get("k") or "") + ("~" + p["bk"] if p.get("bk") else "")


def собрать(предложения, каталог=(), аналоги=(), машины=(), изготовители=(),
            спрос=(), собран=None, имена_брендов=None, спрос_бренды=(), реестр=None):
    """Строки базы → снимок для страниц. Чистая функция: тестируется без базы.

    `собран` — метка времени сборки строкой. Передаётся снаружи, а не берётся
    здесь: функция чистая, и одинаковый вход обязан давать одинаковый выход,
    иначе тест на размер меряет разное при каждом прогоне.

    `имена_брендов` — номер элемента СП-176 → имя (имена_брендов(cur)); без него
    бренды карточки запроса остаются номерами, как до реестра.

    `спрос_бренды` — строки СПРОС_БРЕНДЫ_SQL (ключ, сторона, ячейка, строк);
    `реестр` — реестр_брендов(): чем узнаётся бренд строки. Без реестра бренд
    дают только каталог, карточка запроса и подтверждённая маска.

    ПОЗИЦИЯ — ПАРА «БРЕНД + КОД» (П1): у кода, разбитого на пары, позиций
    несколько, у каждой свой бренд (bk, bn) и его источник (bs), а у пары без
    бренда — причина (bw) и, если спорно, кандидаты (bc). Правило — над
    бренд_позиции.
    """
    по_позиции = collections.defaultdict(list)
    for r in предложения:
        по_позиции[r[0]].append(r)

    # ВСЕ ЧЕТЫРЕ НАБОРА РАСКЛАДЫВАЮТСЯ ПО КЛЮЧУ КОТИРОВКИ, А НЕ ПО id ДЕТАЛИ.
    # У 30 позиций они не совпадают: id считается по catalog_norm, когда тот
    # заполнен. Отдай один запрос id, а остальные ключ — и карточка получила бы
    # найденную деталь при пустых разделах «чем закрыть» и «где стоит», причём
    # ровно у тех позиций, ради которых вторая ступень сцепки и заведена.
    кат = {r[0]: r for r in каталог}
    альт = collections.defaultdict(list)
    for part_id, alt_pn, kind, maker, conf in аналоги:
        альт[part_id].append({"pn": alt_pn, "kind": kind, "maker": maker,
                              "conf": conf})
    маш = collections.defaultdict(list)
    for part_id, имя in машины:
        маш[part_id].append(имя)
    # Спрос по ключу позиции: сколько сделок спрашивали и в каком количестве.
    спр = {}
    for ключ, сделок, строк, единиц, количество, *хвост in спрос:
        единица = хвост[0] if хвост else None
        спр[ключ] = {
            "deals": сделок,
            "rows": строк,
            # Имя единицы едет рядом с количеством, иначе на экране остаётся
            # голое число. Когда единиц несколько, количества нет вовсе, и имя
            # тоже не нужно.
            **({"unit_name": единица} if единица and (единиц or 0) <= 1 else {}),
            # Сумма — только когда единица одна. Иначе складывали бы штуки с
            # килограммами, и число выглядело бы осмысленным.
            "qty": _число(количество) if (единиц or 0) <= 1 else None,
            "units": единиц or 0,
        }
    изг = collections.defaultdict(list)
    for part_id, имя, роль, страна, делает, вердикт, conf in изготовители:
        изг[part_id].append({"name": имя, "role": роль, "country": страна,
                             "makes": делает, "verdict": вердикт, "conf": conf})

    позиции = []
    по_компании = collections.defaultdict(lambda: {"позиции": {}, "бренды": set(),
                                                   "оем": collections.Counter(),
                                                   "строк": 0, "имя": None,
                                                   "сущность": None})
    с_выбором = сравнимых = в_каталоге = 0
    # Точные дубли по всему снимку: сколько групп, сколько строк ушло в них
    # лишними, откуда группы (_откуда_дубль) и у скольких копии расходились.
    дубли = collections.Counter()
    # БРЕНД ПОЗИЦИИ ПО ВСЕМУ СНИМКУ — только числа: публикатор печатает их в
    # журнал (правило 17), ревизия сверяет с пересчётом по частям.
    бр = collections.Counter()
    # Ячейки изготовителя спроса по ключу кода. Претензию «строка» даёт только
    # спецификация заказчика; ячейки прочих сторон считаются, в дело не идут.
    спец = collections.defaultdict(list)
    for ключ_спроса, сторона, ячейка, строк_ячейки in спрос_бренды:
        if сторона == "спецификация":
            спец[ключ_спроса].append((ячейка, строк_ячейки or 1))
        else:
            бр["spec_other_side"] += 1
    имена_брендов = имена_брендов or {}
    К = ПОЛЯ_ПРЕДЛОЖЕНИЯ

    for ключ, строки in по_позиции.items():
        к = кат.get(ключ)

        # 1. СТРОКИ → ПРЕДЛОЖЕНИЯ. Точный дубль — копия, а не ещё одно
        # предложение (ключ_дубля выше). Копии схлопываются ДО разбиения по
        # бренду: копии одного КП не разъедутся по разным парам.
        предл = []
        # Ключ дубля → номер предложения в предл, его копии, файлы, карточки и
        # строки базы (по строкам считается бренд предложения).
        группы: dict[tuple, dict] = {}
        записи = []                 # (номер предложения, строка базы, новое ли)
        for r in строки:
            (_, написание, _наим, комп, сущ, сущ_имя, оем, бренды, цена, вал,
             qty, ед, базис, срок, срок_изг, оплата, аванс, сумма,
             базис_ист, опл_ист, срок_ист, изг_ист,
             карточка, conf, дата, создано, *хвост) = r
            файл = хвост[0] if хвост else None
            # ПУСТЫЕ КЛЮЧИ В СНИМОК НЕ ЕДУТ, А ИМЯ КОМПАНИИ НЕ ПОВТОРЯЕТСЯ.
            # Предложений 18 388, ключей в каждом четырнадцать, а заполнены у
            # большинства четыре: остальное — вес без сведений. Имя компании
            # лежит один раз в companies и достаётся по ключу co; повторённое в
            # каждом предложении, оно стоило бы сотен килобайт и разошлось бы с
            # реестром при первом же переименовании.
            #
            # Страница обязана отличать «нет значения» от «поля нет»: и то и
            # другое она показывает как «Не знаем», поэтому отсутствие ключа
            # безопасно. А вот отсутствие ключа с НУЛЁМ было бы ошибкой —
            # «срок 0 дней» это не «срок неизвестен», поэтому ноль сохраняется.
            о = _коротко({
                "co": комп, "ent": сущ,
                "oem": оем, "brands": _бренды(бренды, имена_брендов),
                "price": _число(цена), "cur": вал,
                "qty": _число(qty), "unit": ед, "basis": базис,
                "lead": срок, "make": срок_изг, "total": _число(сумма),
                "pay": оплата, "adv": _число(аванс),
                # ЧЕТЫРЕ ПОМЕТКИ ИСТОЧНИКА — ОДНОЙ СТРОКОЙ «б|о|с|и». Четыре
                # отдельных ключа на каждое из двадцати пяти предложений дали бы
                # сто лишних ключей на позицию, а предел снимка 8 МиБ уже близко
                # (ПОТОЛОК_ПОЗИЦИЙ). Расшифровывает страница.
                "src": _пометки(базис_ист, опл_ист, срок_ист, изг_ист),
                "rfq": карточка, "conf": conf,
                "date": _дата(дата) or _дата(создано),
            })
            кд = ключ_дубля(о)
            г = группы.get(кд)
            новое = г is None
            if новое:
                г = группы[кд] = {"i": len(предл), "копии": [], "файлы": set(),
                                  "карточки": set(), "строки": []}
                предл.append(о)
            г["копии"].append(о)
            г["файлы"].add(файл)
            г["карточки"].add(карточка)
            г["строки"].append(r)
            записи.append((г["i"], r, новое))

        for г in группы.values():
            if len(г["копии"]) < 2:
                continue
            предл[г["i"]] = о = _схлопнуть(г["копии"])
            дубли["groups"] += 1
            дубли["rows"] += len(г["копии"]) - 1
            дубли[_откуда_дубль(г["карточки"], г["файлы"])] += 1
            дубли["differ"] += int(К["differ"] in о)

        # 2. СВОЙ БРЕНД ПРЕДЛОЖЕНИЯ (бренд_позиции, над ним — правило): строка
        # КП, где реестр узнал ровно один бренд, иначе одна марка карточки.
        # Бренды считаются по ВСЕМ копиям: копия не должна унести сказанное
        # только в ней. Заодно копятся претензии кода — по ним у пары источник.
        свой: list = [None] * len(предл)
        претензии = []
        for г in группы.values():
            из_строки, из_карточки = [], []
            for r in г["строки"]:
                for k in узнать(r[6], реестр, ключ):
                    претензии.append(("строка", k, _имя_бренда(реестр, k), 1))
                    if k not in из_строки:
                        из_строки.append(k)
                марки = бренды_карточки(r[7], реестр, имена_брендов)
                if len(марки) == 1:
                    претензии.append(("карточка", марки[0][0], марки[0][1], 1))
                    if марки[0][0] not in из_карточки:
                        из_карточки.append(марки[0][0])
            бр["row_multi"] += len(из_строки) > 1
            if len(из_строки) == 1:
                свой[г["i"]] = (из_строки[0], "с")
            elif len(из_карточки) == 1:
                свой[г["i"]] = (из_карточки[0], "к")

        # 3. БРЕНД КОДА: каталог → спецификация заказчика → маска (П2).
        код_пр = [("каталог", k, n, 1) for k, n in (бренды_каталога(к[3], реестр, ключ) if к else [])]
        for ячейка, n in спец.get(ключ, ()):
            for k in узнать(ячейка, реестр, ключ):
                код_пр.append(("строка", k, _имя_бренда(реестр, k), n))
        до_маски = бренд_позиции(код_пр)
        for м in маска_кода(ключ):
            тексты = ([r[2] for r in строки] + [r[6] for r in строки]
                      + [n for r in строки for _, n in бренды_карточки(r[7], реестр, имена_брендов)]
                      + [я for я, _ in спец.get(ключ, ())] + list(маш.get(ключ, []))
                      + ([к[1], к[2], к[3]] if к else []))
            if подтверждена(м, тексты):
                ключи = узнать(м[1], реестр)
                k = ключи[0] if len(ключи) == 1 else м[0]
                код_пр.append(("маска", k, _имя_бренда(реестр, k, м[1]), 1))
            elif до_маски.get("why") == "нет" and not any(свой):
                бр["mask_unconfirmed"] += 1
        код_бренд = бренд_позиции(код_пр)
        претензии += код_пр
        if код_бренд.get("src") == "каталог" and any(
                п[0] == "строка" and п[1] != код_бренд["k"] for п in код_пр):
            бр["cat_vs_row"] += 1

        # 4. РАЗБИЕНИЕ НА ПАРЫ. Своих брендов нет у предложения — оно идёт к
        # бренду кода; бренда кода нет, а свой бренд у предложений кода один —
        # к нему (присоединено); иначе — в «Бренд не определён».
        свои = sorted({с[0] for с in свой if с})
        if код_бренд.get("k"):
            без_своего = код_бренд["k"]
        elif код_бренд["why"] == "нет" and len(свои) == 1:
            без_своего = свои[0]
        else:
            без_своего = None
        пары: dict = {}
        for i, с in enumerate(свой):
            пары.setdefault(с[0] if с else без_своего, []).append(i)
            if с:
                предл[i][К["own"]] = с[1] + ":" + с[0]
            elif без_своего is not None:
                бр["joined"] += 1
        бр["offers_coded"] += len(предл)
        if len(пары) > 1:
            бр["split"] += 1
            бр["moved"] += len(предл) - max(len(v) for v in пары.values())

        # Выбор и сравнимость ДО разбиения — чтобы разбиение, отнявшее выбор у
        # кода, было видно числом (правило 0: сумма прячет потерю).
        был_выбор = len({r[3] for r in строки if r[3]}) >= 2
        была_сравнима = сравнима(предл)
        есть_выбор = есть_сравнимость = False

        спец_имена = sorted({п[2] for п in код_пр if п[0] == "строка"})
        for бк, номера in пары.items():
            набор = set(номера)
            строки_пары = [r for i, r, _ in записи if i in набор]
            предл_пары = [предл[i] for i in номера]
            # НОМЕР ДЛЯ ЧЕЛОВЕКА — КАТАЛОЖНЫЙ, ЕСЛИ ОН ЕСТЬ. Иначе самое частое
            # написание из котировок пары: выбирать первое попавшееся значит
            # показывать разный номер при каждой пересборке.
            написания = collections.Counter(r[1] for r in строки_пары if r[1])
            номер = (к[1] if к else None) or (написания.most_common(1)[0][0]
                                              if написания else ключ)
            наименования = collections.Counter(r[2] for r in строки_пары if r[2])
            имя = (к[2] if к else None) or (наименования.most_common(1)[0][0]
                                            if наименования else None)
            if бк is not None:
                решение = бренд_позиции([п for п in претензии if п[1] == бк])
                бренд = {"bk": бк, "bn": _имя_бренда(реестр, бк, решение.get("n")),
                         "bs": решение.get("src")}
                бр["pos_" + решение.get("src", "")] += 1
            elif код_бренд.get("why") == "спорно":
                бренд = {"bw": "спорно", "bc": код_бренд["cand"]}
            elif свои:
                решения = [бренд_позиции([п for п in претензии if п[1] == k]) for k in свои]
                бренд = {"bw": "спорно",
                         "bc": [[р.get("n", k), р.get("src")] for р, k in zip(решения, свои)]}
            else:
                бренд = {"bw": "нет"}
            if "bw" in бренд:
                бр["pos_" + бренд["bw"]] += 1

            ид = ид_позиции({"k": ключ, "bk": бк})
            компании = set()
            валюты = set()
            изг_из_файлов = collections.Counter()
            бренды_позиции = set()
            for i, r, новое in записи:
                if i not in набор:
                    continue
                комп, сущ, сущ_имя, оем, бренды, цена, вал, дата, создано = (
                    r[3], r[4], r[5], r[6], r[7], r[8], r[9], r[24], r[25])
                if комп:
                    компании.add(комп)
                if оем:
                    изг_из_файлов[оем] += 1
                бренды_позиции.update(_бренды(бренды, имена_брендов))
                if цена is not None and вал:
                    валюты.add(вал)
                if комп:
                    с = по_компании[комп]
                    с["строк"] += int(новое)
                    с["сущность"] = с["сущность"] or сущ
                    с["имя"] = с["имя"] or сущ_имя
                    с["бренды"].update(_бренды(бренды, имена_брендов))
                    if оем:
                        с["оем"][оем] += 1
                    п = с["позиции"].setdefault(ид, {"cnt": 0, "price": None,
                                                     "cur": None, "date": None})
                    п["cnt"] += int(новое)
                    if п["price"] is None and цена is not None:
                        п["price"], п["cur"] = _число(цена), вал
                    п["date"] = п["date"] or _дата(дата) or _дата(создано)
            с_ценой = sum(1 for о in предл_пары if о.get(К["price"]) is not None and о.get(К["cur"]))

            if len(компании) >= 2:
                с_выбором += 1
                есть_выбор = True
            # Сравнимость — только внутри одной валюты. Пересчёт по курсу здесь не
            # делается намеренно: курс на дату котировки мы не храним, а курс на
            # сегодня превратил бы прошлогоднее КП в сегодняшнее предложение.
            # Прежнее правило — две цены в одной валюте, сколько бы ни было
            # компаний; считается рядом, чтобы снятое было видно числом
            # (правило 0): у одной компании — дефект, снятый намеренно; при
            # двух компаниях, из которых цену дала одна, — сорсер теряет отбор.
            по_старому = с_ценой >= 2 and len(валюты) == 1
            сравнима_ = сравнима(предл_пары)
            if по_старому and not сравнима_:
                бр["cmp_one_co" if len(компании) < 2 else "cmp_one_priced"] += 1
            if сравнима_:
                сравнимых += 1
                есть_сравнимость = True
            if к:
                в_каталоге += 1

            позиции.append({
                "k": ключ,
                **бренд,
                "n": номер,
                "name": имя,
                "co": len(компании),
                # Предложений — после схлопывания точных дублей: три копии одного
                # КП на странице читались «3 предложения» при одном. Строк базы
                # за ними — в totals.offer_rows, у каждого схлопнутого — поле x.
                "offers": len(предл_пары),
                "shown": min(len(предл_пары), ПРЕДЛОЖЕНИЙ_НА_ПОЗИЦИЮ),
                "cmp": сравнима_,
                # Четыре утверждения об изготовителе — четырьмя полями. Слияние их
                # в одно потеряло бы, кто это сказал.
                "oem_file": [и for и, _ in изг_из_файлов.most_common(5)],
                "oem_cat": (к[3] if к else None),
                "brands": sorted(бренды_позиции),
                # Бренды, названные спецификациями заказчика и узнанные реестром,
                # — по коду целиком: спрос к предложениям не привязан.
                "spec": спец_имена,
                "makers": изг.get(ключ, []),
                "alts": альт.get(ключ, []),
                "models": маш.get(ключ, []),
                # Вес позиции: спрашивали ли её, и насколько. Ради него позиции без
                # выбора можно выстроить по деньгам, а не по алфавиту. Спрос — по
                # КОДУ: строки спроса к брендам пар не привязаны, и у кода,
                # разбитого на пары, он один на все его пары.
                "demand": спр.get(ключ),
                "cat": bool(к),
                "cat_name": (к[2] if к else None),
                "category": (к[4] if к else None),
                "unit": (к[5] if к else None),
                "kv": (к[6] if к else None),
                "list": предл_пары[:ПРЕДЛОЖЕНИЙ_НА_ПОЗИЦИЮ],
            })
        бр["choice_lost"] += был_выбор and not есть_выбор
        бр["cmp_lost"] += была_сравнима and not есть_сравнимость
        бр["codes"] += 1

    # ПОРЯДОК. Сверху то, где есть выбор, — карточка отвечает на «у кого брать»
    # только там. Внутри равного числа компаний — по спросу: позиция из тридцати
    # спецификаций важнее позиции из одной, а без этого порядка рассылка вторым
    # поставщикам пошла бы по алфавиту.
    #
    # Пары одного кода различаются брендом: он замыкает ключ, иначе порядок пар
    # с равным весом зависел бы от порядка строк базы.
    def вес(p):
        d = p.get("demand") or {}
        return (-p["co"], -(d.get("deals") or 0), -(d.get("rows") or 0),
                -p["offers"], p["n"] or "", p.get("bn") or "", p.get("bk") or "")

    позиции.sort(key=вес)

    компании = []
    for ключ, с in по_компании.items():
        компании.append({
            "co": ключ,
            "ent": с["сущность"],
            "name": с["имя"],
            "rows": с["строк"],
            # parts и rows считаются по всем строкам, а не по показанным: это
            # ответ на вопрос «сколько работы у нас с этой компанией», и усечение
            # списка предложений его искажать не должно. rows — предложений
            # после схлопывания точных дублей (ключ_дубля): копия одного КП не
            # работа, и сумма по рёбрам не больше offers позиции (n.e_cnt).
            "parts": len(с["позиции"]),
            "brands": sorted(с["бренды"]),
            # БРЕНДЫ ПО СЛОВУ ПОСТАВЩИКА — отдельно от брендов карточки запроса
            # (план, этап 8.1): «мы спросили SKF» и «он написал в КП FAG» —
            # разные утверждения. Не больше десяти самых частых: это подпись к
            # компании, а не перечень; полный разрез — на странице /brands.
            **({"oem": [и for и, _ in с["оем"].most_common(ОЕМ_НА_КОМПАНИЮ)]}
               if с["оем"] else {}),
        })
    компании.sort(key=lambda c: (-c["parts"], -c["rows"], c["co"]))

    # РЁБРА «ПОЗИЦИЯ ↔ КОМПАНИЯ» — ОДНОЙ КОПИЕЙ, У ПОЗИЦИИ. Компания в ребре —
    # номер в companies, а не повторённый ключ: так ребро стоит два-три десятка
    # байт. Строк, цена и дата — ровно то, что карточка поставщика печатает в
    # списке позиций; посчитаны по ВСЕМ строкам, а не по показанным, поэтому
    # список позиций у компании больше не короче её счётчика parts. «Строк» в
    # ребре — предложений без точных дублей, как и offers позиции.
    #
    # Хвостовые пустые места у ребра отрезаются: у большинства рёбер нет цены
    # или даты, и «null,null,null» на каждом стоило бы сотни килобайт.
    номер_компании = {c["co"]: i for i, c in enumerate(компании)}
    по_ключу = {ид_позиции(p): p for p in позиции}
    for ключ_компании, с in по_компании.items():
        ci = номер_компании[ключ_компании]
        for ключ_позиции, п in с["позиции"].items():
            ребро = [ci, п["cnt"], п["price"], п["cur"], п["date"]]
            while ребро[-1] is None:
                ребро.pop()
            по_ключу[ключ_позиции].setdefault("e", []).append(ребро)
    for p in позиции:
        if "e" in p:
            p["e"].sort()

    сведённых = sum(1 for c in компании if c["ent"])
    return {
        "version": 1,
        # ДАТА СБОРКИ. У страницы для неё с самого начала был пустой слот, а в
        # снимке даты не было вовсе: человек не видел, насколько данные свежие, и
        # вчерашний снимок выглядел как сегодняшний. Для номенклатуры это важнее,
        # чем для реестра: цена поставщика живёт неделями.
        **({"published_at": собран} if собран else {}),
        "positions": позиции,
        "companies": компании,
        "totals": {
            "positions": len(позиции),
            "with_choice": с_выбором,
            "comparable": сравнимых,
            "in_catalog": в_каталоге,
            "companies": len(компании),
            "companies_resolved": сведённых,
            # ПОЗИЦИЙ СО СПРОСОМ, НО БЕЗ СПРОСА ЗАВЕДЁННОГО — сколько позиций
            # вообще не встречается в lib_demand. Замер 22.09.2026: таких НОЛЬ,
            # спрос есть у всех 9 578 позиций. Это не совпадение: артикулы
            # котировок берутся из спецификаций сделок, то есть из того же
            # спроса, — и «спрашивали» для позиции котировки тавтология.
            #
            # Счётчик оставлен именно затем, чтобы тавтология была видна числом.
            # Первая его версия считала «без выбора и со спросом» и выдала 8 823,
            # то есть ровно все позиции без выбора: он выглядел сужением списка
            # работы, а не сужал ничего. Разойдись когда-нибудь эти множества —
            # придёт котировка на артикул, которого в спецификациях не было, —
            # число станет больше нуля и скажет об этом само.
            "no_demand": sum(1 for p in позиции if not (p.get("demand") or {}).get("deals")),
            "offers": sum(p["offers"] for p in позиции),
            # Строк котировок до схлопывания точных дублей: разница с offers —
            # сколько копий схлопнуто. Молчаливый отсев — та же ложь, что
            # молчаливое усечение, поэтому число едет рядом.
            "offer_rows": sum(len(строки) for строки in по_позиции.values()),
            # БРЕНД ПОЗИЦИИ (П1, П2) — счётом, а не догадкой. codes — кодов (до
            # разбиения на пары было столько позиций), determined — пар с
            # брендом, by — по источнику бренда, none и disputed — «Бренд не
            # определён» по причине. split — кодов, разбитых на две пары и
            # больше; moved — предложений, ушедших из самой большой пары кода в
            # другую; joined — предложений без своего бренда, отнесённых к
            # бренду кода или к единственному бренду его предложений;
            # offers_coded — предложений по кодам до разбиения (равно offers:
            # разбиение предложений не теряет). choice_lost и cmp_lost — кодов,
            # у которых был выбор из двух компаний (сравнимость цен), а ни у
            # одной пары его нет: что разбиение отняло (правило 0).
            # mask_unconfirmed — кодов без иного бренда, чей код подошёл под
            # маску, но слова бренда у позиции нет (бренд не дан); cat_vs_row —
            # каталог и спецификация назвали разное (взят каталог); row_multi —
            # предложений, чья строка КП назвала два бренда реестра и больше;
            # spec_other_side — ячеек изготовителя спроса не со стороны
            # заказчика (в дело не шли). cmp_one_co и cmp_one_priced — позиций,
            # у которых снята «сравнимость» (сравнима выше): две цены одной
            # компании (дефект n.cmp_co) и две компании, из которых цену в той
            # валюте дала одна. Только числа (правило 17).
            "brand": {
                "codes": бр["codes"],
                "determined": sum(бр["pos_" + и] for и in ИСТОЧНИКИ_БРЕНДА),
                "by": {и: бр["pos_" + и] for и in ИСТОЧНИКИ_БРЕНДА},
                "none": бр["pos_нет"], "disputed": бр["pos_спорно"],
                **{k: бр[k] for k in ("split", "moved", "joined", "offers_coded",
                                      "choice_lost", "cmp_lost", "mask_unconfirmed",
                                      "cat_vs_row", "row_multi", "spec_other_side",
                                      "cmp_one_co", "cmp_one_priced")},
            },
        },
        # ОТКУДА ДУБЛИ — СЧЁТОМ, А НЕ ДОГАДКОЙ. groups — групп копий, rows —
        # строк, ушедших в них лишними; дальше группы по происхождению
        # (_откуда_дубль): cards — одно предложение на нескольких карточках
        # запроса, one_card — одна карточка, разные файлы (копии КП в полях),
        # one_file — строка повторена в самом файле, no_file — файл неизвестен;
        # differ — у скольких групп копия несла значение, которого оставшееся
        # предложение не показывает (у предложения тогда пометка w). Только
        # числа: публикатор печатает их в журнал (правило 17).
        "dups": {k: дубли[k] for k in ("groups", "rows", "cards", "one_card",
                                         "one_file", "no_file", "differ")},
    }


# ПОДРОБНОСТИ ПОЗИЦИИ — ТО, ЧТО НУЖНО ТОЛЬКО ОТКРЫТОЙ КАРТОЧКЕ. Всё прочее
# (номер, наименование, спрос, изготовитель, аналоги, машины, рёбра) нужно списку:
# строке таблицы, отбору, поиску по номеру аналога или карточке поставщика.
ПОДРОБНОСТИ = ("list", "shown", "makers", "cat_name", "category", "unit", "spec")

# ПУСТОЕ ПОЛЕ В ПРОВОД НЕ ЕДЕТ. Страницы читают отсутствие ключа как «не знаем»
# и «нет», поэтому пустой список, null и ложный признак несут только вес: на
# шестнадцати тысячах позиций это сотни килобайт. Ноль остаётся — «0 компаний»
# и «компаний не знаем» различаются.
_ЛОЖЬ_НЕ_ВЕЗЁМ = {"cmp", "cat"}


def _без_пустого(d: dict) -> dict:
    return {k: v for k, v in d.items()
            if not (v is None or v == "" or v == [] or v == {}
                    or (k in _ЛОЖЬ_НЕ_ВЕЗЁМ and v is False))}


def разложить(снимок: dict) -> dict[str, dict]:
    """Снимок → {ключ KV: содержимое} по закрытому списку ВСЕ_КЛЮЧИ.

    crossref:v1 — заголовок (всё, кроме positions) плюс lists и parts: сколько
    частей списка и корзин читать. Части списка — подряд идущие куски
    отсортированных позиций, поэтому их склейка по номеру даёт исходный порядок.
    У строки списка нет ПОДРОБНОСТЕЙ, зато есть b — номер корзины, где они лежат.

    Пишутся ВСЕ ключи, в том числе пустые: ключ, не переписанный этим прогоном,
    остался бы от прошлого и показал бы вчерашние предложения при сегодняшнем
    заголовке.
    """
    собран = снимок.get("published_at")
    дата = {"published_at": собран} if собран else {}
    позиции = снимок["positions"]
    корзины = [{"version": 1, "part": i, **дата, "positions": {}} for i in range(КОРЗИН)]
    строки = []
    for p in позиции:
        # Корзина — по КЛЮЧУ КОДА: все пары кода лежат в одной корзине, и
        # карточка, открытая по адресу кода, тянет одну корзину. Внутри корзины
        # пара — под ключом пары (ид_позиции).
        b = корзина(p["k"])
        строки.append({**_без_пустого({k: v for k, v in p.items() if k not in ПОДРОБНОСТИ}),
                       "b": b})
        подробно = _без_пустого({k: p.get(k) for k in ПОДРОБНОСТИ})
        if подробно:
            корзины[b]["positions"][ид_позиции(p)] = подробно
    # Куски подряд и поровну: у первых частей на строку больше, если не делится.
    размер, остаток = divmod(len(строки), СПИСОК_ЧАСТЕЙ)
    части, начало = [], 0
    for i in range(СПИСОК_ЧАСТЕЙ):
        конец = начало + размер + (1 if i < остаток else 0)
        части.append({"version": 1, "part": i, **дата, "positions": строки[начало:конец]})
        начало = конец
    заголовок = {k: v for k, v in снимок.items() if k != "positions"}
    заголовок["lists"] = СПИСОК_ЧАСТЕЙ
    заголовок["parts"] = КОРЗИН
    return {КЛЮЧ: заголовок,
            **{КЛЮЧИ_СПИСКА[i]: ч for i, ч in enumerate(части)},
            **{КЛЮЧИ_КОРЗИН[i]: к for i, к in enumerate(корзины)}}
