КЛЮЧ = "crossref:v1"
СПИСОК_ЧАСТЕЙ = 8
КОРЗИН = 32
КЛЮЧИ_СПИСКА = tuple(f"crossref:list:{i:02d}" for i in range(СПИСОК_ЧАСТЕЙ))
КЛЮЧИ_КОРЗИН = tuple(f"crossref:offers:{i:02d}" for i in range(КОРЗИН))
ВСЕ_КЛЮЧИ = (КЛЮЧ,) + КЛЮЧИ_СПИСКА + КЛЮЧИ_КОРЗИН


def корзина(ключ: str) -> int:
    """Номер корзины позиции: CRC32 байтов UTF-8 ключа по модулю числа корзин.

    Тот же приём, что у brands.корзина: хеш стабилен между прогонами и языками,
    поэтому позиция не переезжает из корзины в корзину от пересборки к пересборке.
    """
    return zlib.crc32(str(ключ).encode("utf-8")) % КОРЗИН

# ПРАВДОПОДОБНЫЙ КОД — ПРИ ЧТЕНИИ. Марка стали, размер с единицей и стандарт
