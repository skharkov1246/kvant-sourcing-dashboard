def вставка_файлов(колонки: tuple[str, ...]) -> tuple[str, str]:
    """Пакетная вставка в lib_files по колонкам записи: (запрос, шаблон строки).

    Шаблон строки передаётся в execute_values явно: мест под значения ровно
    столько, сколько колонок, и кортеж другой длины падает на первой строке, а
    не пишет значения не в те колонки."""
    беречь = не_затирать_пустым()

    def обновление(к: str) -> str:
        if к in ДОПОЛНЯТЬ_ПУСТОЕ:
            return f"{к} = coalesce(lib_files.{к}, excluded.{к})"
        if к in беречь:
            return f"{к} = coalesce(excluded.{к}, lib_files.{к})"
        return f"{к} = excluded.{к}"
    обновить = [обновление(к) for к in колонки if к not in НЕ_ОБНОВЛЯТЬ]
    обновить.append("processed_at = now()")
    запрос = ("insert into lib_files\n  (" + ", ".join(колонки) + ")\nvalues %s\n"
              "on conflict (file_id) do update set\n  " + ",\n  ".join(обновить))
    return запрос, "(" + ", ".join(["%s"] * len(колонки)) + ")"


def отобрать_повторы(mine: list[dict], очередь: dict[str, int],
                     предел: int) -> tuple[list[dict], int, int]:
    """Новые файлы части — все и первыми, повторы «не скачался» — не больше предела.

    `очередь` — место файла в очереди повтора (0 — давняя попытка). Возвращает
    (список к разбору, взято повторов, отложено повторов). Предел 0 — без предела.
    """
    новые = [r for r in mine if ключ_ссылки(r) not in очередь]
    повторы = sorted((r for r in mine if ключ_ссылки(r) in очередь),
                     key=lambda r: очередь[ключ_ссылки(r)])
    взять = повторы if предел <= 0 else повторы[:предел]
    return новые + взять, len(взять), len(повторы) - len(взять)


