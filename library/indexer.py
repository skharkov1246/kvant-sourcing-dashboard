def поток_цены() -> tuple[str, str]:
    """(источник, поток) строки цены: у писем и у нашего КП свои, у карточек прежние.

    У сделок цену даёт только наше КП (цены_файла), поэтому поток сделки — всегда
    FEED_НАШЕ_КП: в «разбор КП» цена из поля сделки не попадает ни при каком входе."""
    if SOURCE == "mail":
        return price_store.ИСТОЧНИК_ПИСЬМА, price_store.FEED_ПИСЬМА
    if SOURCE == "deals":
        return price_store.ИСТОЧНИК_НАШЕ_КП, price_store.FEED_НАШЕ_КП
    return price_store.ИСТОЧНИК, price_store.FEED


#: СОДЕРЖИМОЕ, ПРОТИВОРЕЧАЩЕЕ ПОЛЮ «НАШЕ КП ЗАКАЗЧИКУ». Поле сделки говорит
#: «наше КП», а классификатор уверенно читает в файле КП поставщика нам, наш
#: запрос поставщику или заявку заказчика: цена такого файла — не наша цена
#: заказчику, и в поток нашего КП она не идёт. Холостой переразбор 27.09.2026
#: (2 512 файлов поля): КП поставщиков — 159 файлов и 751 строка цены.
#: Закрытый список обвиняет (правило 7), и в нём только папки С АВТОРОМ
#: (doc_kind: «мы / не мы» решает ось автора). «Договор, счёт» и «письмо» автора
#: не различают: наша спецификация к договору или наш счёт заказчику — та же
#: папка, и цена в них наша; их строки пишутся и видны числом по папке в
#: журнале. «Не определено» и сбой классификатора цену не теряют. Папка файла
#: не меняется — это отбор строк цены, а не переклассификация.
НЕ_НАШЕ_КП = (doc_kind.ПРЕДЛОЖЕНИЕ_ПОСТАВЩИКА, doc_kind.НАШ_ЗАПРОС, doc_kind.ЗАПРОС_ЗАКАЗЧИКА)

#: Отложено по содержимому за прогон: папка → [файлов с ценой, строк цены].
#: Пополняется из главного потока: строки_цен зовут из цикла, а не из пула.
ОТЛОЖЕНО_НАШЕ_КП: dict[str, list[int]] = {}


def против_поля(rec: dict) -> str | None:
    """Папка содержимого, противоречащая полю нашего КП (НЕ_НАШЕ_КП), иначе None.

    Только у сделок: у карточки запроса и у письма поле и содержимое судятся
    своими правилами (цены_файла), и этот отбор их не касается."""
    папка = rec.get("папка_содержимого")
    # Порог — и здесь: папку ниже него классификатор сегодня не называет, но
    # отбор не должен молча расшириться, если это когда-нибудь изменится.
    уверенно = (rec.get("ув_содержимого") or 0) >= doc_kind.ПОРОГ
    return папка if SOURCE == "deals" and уверенно and папка in НЕ_НАШЕ_КП else None


def строка_против_поля() -> str:
    """Строка журнала: цены нашего КП, отложенные по содержимому. Ключи — папки,
    собственные константы кода (правило 17)."""
    файлов = sum(ф for ф, _ in ОТЛОЖЕНО_НАШЕ_КП.values())
    строк = sum(с for _, с in ОТЛОЖЕНО_НАШЕ_КП.values())
    части = " · ".join(f"{п} {ф}/{с}" for п, (ф, с) in
                       sorted(ОТЛОЖЕНО_НАШЕ_КП.items(), key=lambda x: (-x[1][1], x[0])))
    return (f"цены нашего КП отложены по содержимому файла: файлов {файлов},"
            f" строк цены {строк}" + (f" ({части}; файлов/строк)" if части else "")
            + " · «не определено» и «наше предложение» пишутся")


def строки_цен(rec: dict, items: list[dict]) -> list[tuple]:
    """Строки lib_prices одного разобранного файла — одна дорога для всех источников.

    Отдельной функцией, чтобы её можно было проверить без базы и без портала:
    внутри цикла main() она проверялась бы только подменой сети.
    """
    if not цены_файла(rec):
        return []
    против = против_поля(rec)
    if против:
        # До отбора ложных: отложенный файл не должен пополнять счёт отказов
        # (price_store.ОТКАЗАНО) строками, которые и так не пишутся.
        найдено = sum(1 for it in items if it.get("_цена"))
        if найдено:
            счёт = ОТЛОЖЕНО_НАШЕ_КП.setdefault(против, [0, 0])
            счёт[0] += 1
            счёт[1] += найдено
        return []
    источник, поток = поток_цены()
    # Ложные строки цены (реквизит, итог, «x × 1 = x») снимаются на готовом
    # кортеже — тем же правилом, что помечает уже записанные
    # (price_store.отобрать, quotes.ложная_цена).
    return price_store.отобрать([price_store.строка(it, it["_цена"], pg, источник, поток)
                                 for it in items if it.get("_цена")])


def позиции_письма(items: list[dict]) -> list[dict]:
    """Строки тела письма, которые похожи на позицию, — остальное проза письма.

    Защита щедрая (правило 7): остаётся строка с любым признаком позиции
    (docfilter.spec_marks: колонка количества или единицы, стандарт, типоразмер,
    количество с единицей, марка) или со словом словаря сегментов («насос»,
    «подшипник»). Обвинение — закрытым списком контактов (_КОНТАКТ_ПИСЬМА).
    Построчный отбор здесь, а не отказ по файлу (правило 13), потому что письмо —
    не спецификация с переносами наименования, а проза, в которой перечень —
    исключение.
    """
    out = []
    for it in items:
        имя = str(it.get("item_name") or "")
        if _КОНТАКТ_ПИСЬМА.search(имя):
            continue
        sp, _ = docfilter.row_marks(имя, it.get("oem") or "", it.get("unit") or "",
                                    it.get("qty"), dict_hit=classify(имя) is not None)
        if sp:
            out.append(it)
    return out


