    if _КЛИЕНТ is None:
        from bitrix_client import BitrixClient
        # ЧАСТОТА — ИЗ ОБЩЕГО БЮДЖЕТА ПОРТАЛА, А НЕ СВОИМ ЧИСЛОМ. Прежде здесь
        # стояло 0,5 с «под лимит портала» — на процесс. Двенадцать частей по два
        # запроса в секунду давали двадцать четыре при утечке ведра два. Теперь
        # пауза = BITRIX_PARALLEL / BITRIX_RPS (bitrix_client.интервал_портала):
        # прогон частями передаёт, сколько частей читают портал разом.
