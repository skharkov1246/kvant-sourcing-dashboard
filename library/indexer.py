#: К какому крупному виду относится подвид. Крупный вид остаётся тем же, что был
#: до 23.09.2026: по нему отбирают файлы переразбор (`KINDS`) и распознавание,
#: и менять его значения — значит менять отбор во всех прогонах сразу.
ВИД_ПО_ПОДВИДУ = {
    "pdf": "pdf",
    "xlsx": "xlsx/docx", "docx": "xlsx/docx",
    "xls": "старый office", "doc": "старый office", "spreadsheetml": "старый office",
    "png": "изображение", "jpeg": "изображение", "tiff": "изображение",
    "gif": "изображение", "bmp": "изображение", "webp": "изображение",
    "zip": "архив", "rar": "архив", "7z": "архив", "gzip": "архив",
    "csv": "прочее", "txt": "прочее", "rtf": "прочее", "html": "прочее",
    "xml": "прочее", "неизвестно": "прочее",
}


def подвид(b: bytes) -> str:
    """ТОЧНЫЙ формат файла: от него зависит стратегия чтения.

    Крупный вид («xlsx/docx», «старый office», «прочее») для выбора читателя
    негоден: под одной вывеской лежат форматы, которые читаются по-разному и с
    разной ценой. Замер 23.09.2026 показал три подмены:

      • настоящий .zip-архив начинается с PK и опознавался как книга Excel —
        openpyxl на нём падал, и файл ложился как «пусто»;
      • .doc и .msg — такой же OLE2, как .xls, и уходили в xlrd, который на них
        падает: статус «формат не читаем», ноль позиций;
      • выгрузка 1С с расширением .xls — это XML Spreadsheet 2003, то есть текст,
        а не OLE2 вовсе.

    Различаются также TIFF, GIF, BMP (прежде опознавались только PNG и JPEG — а
    распознавание берёт файлы по виду «изображение»), 7z, RTF, HTML, XML и
    простой текст.
    """
    if b[:2] == b"PK":
        return внутри_zip(b)
    for подпись, имя in ПОДПИСИ:
        if b.startswith(подпись):
            return "ole2_разобрать" if имя == "ole2" else имя
    if b[:4] == b"RIFF" and b[8:12] == b"WEBP":
        return "webp"
    return по_тексту(b)


def внутри_zip(b: bytes) -> str:
    """Что за PK-контейнер: книга, документ Word или просто архив.

    Смотрим имена участников в голове файла, а не разжимаем: ZIP хранит каталог в
    хвосте, но локальный заголовок первого участника стоит в начале, и OOXML
    всегда кладёт туда `[Content_Types].xml` и папку `xl/` или `word/`.
    """
    голова = b[:8192]
    if b"xl/" in голова or b"workbook.xml" in голова:
        return "xlsx"
    if b"word/" in голова or b"document.xml" in голова:
        return "docx"
    return "zip"


def по_тексту(b: bytes) -> str:
    """Текстовые форматы: их подпись — не байты, а то, что читается словами."""
    голова = b[:4096]
    for кодировка in ("utf-8", "cp1251"):
        try:
            текст = голова.decode(кодировка)
        except UnicodeDecodeError:
            continue
        низ = текст.lstrip().lower()[:400]
        if низ.startswith("<?xml") or "<workbook" in низ:
            # XML Spreadsheet 2003: выгрузка 1С, расширение .xls, внутри текст.
            return "spreadsheetml" if "spreadsheet" in низ or "<workbook" in низ else "xml"
        if низ.startswith(("<!doctype html", "<html", "<head", "<body")):
            return "html"
        # CSV узнаётся по разделителю, повторяющемуся в первых строках одинаково.
        строки = [s for s in текст.splitlines()[:5] if s.strip()]
        for р in (";", "\t", ","):
            счёт = [s.count(р) for s in строки]
            if len(строки) >= 2 and счёт[0] >= 1 and len(set(счёт)) == 1:
                return "csv"
        return "txt"
    return "неизвестно"


def sniff(b: bytes) -> str:
    """Крупный вид файла. Значения те же, что были: по ним идёт отбор в прогонах.

    Подмены исправлены: PK-контейнер, который не книга и не документ Word, теперь
    «архив», а не «xlsx/docx»; TIFF, GIF, BMP и WEBP — «изображение», а не
    «прочее», и потому доходят до распознавания.
    """
    п = подвид(b)
    if п == "ole2_разобрать":
        return "старый office"
    return ВИД_ПО_ПОДВИДУ.get(п, "прочее")


def rows_from_xlsx(b: bytes) -> list[list[str]]:
    import openpyxl
    wb = openpyxl.load_workbook(io.BytesIO(b), read_only=True, data_only=True)
    out: list[list[str]] = []
    for ws in wb.worksheets:
        for row in ws.iter_rows(values_only=True):
            cells = ["" if c is None else str(c).strip() for c in row]
            if any(cells):
                out.append(cells)
            if len(out) > 20000:
                return out
    return out


def rows_from_xls(b: bytes) -> list[list[str]]:
    # ДВЕ ЗАЩИТЫ, найденные агентом книг 23.09.2026. Первая: xlrd зацикливается
    # на битой цепочке секторов OLE2 и выбирает память до гибели процесса — а с
    # ним всей части прогона (порча нескольких байт в .xls на 7 КБ — 1,8 ГБ за
    # 22 с). Вторая: xlrd печатает предупреждения в stdout вместе с именем листа
    # («КП поставщика»), то есть в публичный журнал прогона (правило 17).
    if not read_sheet.ole2_цепи_целы(b):
        raise ValueError("OLE2: цепочка секторов испорчена")
    import xlrd
    wb = xlrd.open_workbook(file_contents=b, logfile=io.StringIO(), verbosity=0)
    out: list[list[str]] = []
    for ws in wb.sheets():
        for i in range(ws.nrows):
            cells = [str(c.value).strip() for c in ws.row(i)]
            if any(cells):
                out.append(cells)
    return out


def docx_xml(b: bytes) -> str:
    try:
        z = zipfile.ZipFile(io.BytesIO(b))
        if "word/document.xml" in z.namelist():
            return z.read("word/document.xml").decode("utf-8", "ignore")
    except Exception:
        return ""
    return ""


def text_from_docx(b: bytes) -> str:
    """Весь текст документа. ВНИМАНИЕ: это одна строка без переводов.

    Спецификация в .docx почти всегда лежит таблицей, и её надо читать
    rows_from_docx. Эта функция годится только для определения сегмента по
    тексту файла целиком: склейка всего документа в одну строку означает, что
    text.splitlines() даст ровно один элемент, и построчный разбор потеряет всё.
    Именно так до 12.09.2026 терялись ячейки таблиц во всех .docx."""
    raw = docx_xml(b)
    return " ".join(re.findall(r"<w:t[^>]*>([^<]{1,400})</w:t>", raw)) if raw else ""


def rows_from_docx(b: bytes) -> list[list[str]]:
    """Таблицы документа построчно: <w:tr> — строка, <w:tc> — ячейка.

    Без этого спецификация в .docx не читается вовсе: текстовый путь склеивает
    документ в одну строку. Разметка Word разносит текст ячейки по нескольким
    <w:t> (правки, форматирование, автозамена), поэтому куски ячейки склеиваем."""
    raw = docx_xml(b)
    if not raw:
        return []
    out: list[list[str]] = []
    for tr in re.findall(r"<w:tr[\s>].*?</w:tr>", raw, re.S):
        cells = []
        for tc in re.findall(r"<w:tc[\s>].*?</w:tc>", tr, re.S):
            cells.append(" ".join(re.findall(r"<w:t[^>]*>([^<]{0,400})</w:t>", tc)).strip())
        if any(cells):
            out.append(cells)
        if len(out) >= 4000:
            break
    return out


#: Сколько страниц PDF читаем. Потолок стоял прибитым в двух местах сразу; теперь
#: он один и задаётся входом прогона: спецификация на сто позиций бывает длиннее
#: шестидесяти страниц, и обрыв на шестидесятой — это молчаливая потеря.
СТРАНИЦ_PDF = int(os.environ.get("PDF_PAGES", "60") or 60)

#: Сколько знаков на странице считать текстовым слоем. Страница скана даёт ноль
#: или единицы знаков (номер листа, штамп), страница с текстом — сотни.
ЗНАКОВ_НА_СТРАНИЦЕ = 40


def страницы_pdf(b: bytes, *, layout: bool = False) -> tuple[list[str], int, int]:
    """Текст постранично. Возвращает (страницы, всего страниц, сколько не прочлось).

    ОДНА СТРАНИЦА НЕ УНОСИТ ФАЙЛ. Прежде сбой режима layout на любой странице
    возвращал пустой список за ВЕСЬ файл, и уже прочитанные страницы
    выбрасывались: шестидесятистраничная спецификация теряла всё из-за одной
    битой страницы. Теперь непрочитанная страница даёт пустую строку и считается
    отдельно, а прочие остаются.

    ПОСТРАНИЧНЫЙ СЧЁТ НУЖЕН НЕ ТОЛЬКО ДЛЯ ЭТОГО. По нему виден СМЕШАННЫЙ PDF —
    часть страниц текстовые, часть сканы. Такой файл сейчас теряется молча: одна
    текстовая страница даёт chars > 0, файл получает «разобран», и отбор
    распознавания (library/ocr.py) его не берёт НИКОГДА, а сканы в нём — это
    позиции и цены, которых никто не увидит.
    """
    try:
        from pypdf import PdfReader
        rd = PdfReader(io.BytesIO(b))
    except Exception:                                                   # noqa: BLE001
        return [], 0, 0
    всего = len(rd.pages)
    страницы: list[str] = []
    потеряно = 0
    for pg in rd.pages[:СТРАНИЦ_PDF]:
        try:
            if layout:
                страницы.append(pg.extract_text(extraction_mode="layout") or "")
            else:
                страницы.append(pg.extract_text() or "")
        except Exception:                                               # noqa: BLE001
            # Режим layout есть не во всех версиях pypdf и спотыкается на отдельных
            # страницах. Страница без него — не причина терять файл.
            страницы.append("")
            потеряно += 1
    return страницы, всего, потеряно


def есть_текстовый_слой(страница: str) -> bool:
    """Страница с текстом, а не скан. Одно правило на разбор и распознавание."""
    return len(страница.strip()) >= ЗНАКОВ_НА_СТРАНИЦЕ


def счёт_страниц(страницы: list[str]) -> tuple[int, int]:
    """Сколько страниц с текстовым слоем и сколько без него."""
    с_текстом = sum(1 for s in страницы if есть_текстовый_слой(s))
    return с_текстом, len(страницы) - с_текстом


def страницы_сканов(страницы: list[str]) -> list[int]:
    """Номера (с единицы) страниц без текстового слоя — тех, что разбор не прочёл.

    Нужны распознаванию смешанного PDF (library/ocr.py): оно читает ТОЛЬКО эти
    страницы и добавляет их позиции к разбору, а не переписывает файл. Правило то
    же, по которому разбор ставит pdf_mixed, иначе распознавание прочло бы не те
    страницы, из-за которых файл попал в очередь.
    """
    return [i for i, s in enumerate(страницы, 1) if not есть_текстовый_слой(s)]


def записать_счёт(rec: dict | None, страницы: list[str], всего: int, потеряно: int) -> None:
    """Постраничный счёт в запись файла. Зовётся ОБОИМИ путями разбора PDF.

    Прежде счёт вёлся только в текстовом пути, и смешанный PDF, у которого
    таблица опозналась, оставался неотмеченным: его сканы так и не попадали в
    распознавание. Пометка нужна независимо от того, каким путём пошёл файл.
    """
    if rec is None or not всего:
        return
    с_текстом, без_текста = счёт_страниц(страницы)
    rec["pdf_pages"] = всего
    rec["pdf_pages_text"] = с_текстом
    rec["pdf_pages_lost"] = потеряно
    # СМЕШАННЫЙ PDF НАЗЫВАЕТСЯ ЗДЕСЬ, иначе его не отличить от текстового.
    if с_текстом and без_текста:
        rec["pdf_mixed"] = True


def плоский(страницы: list[str]) -> str:
    """Текст из страниц, прочитанных с сохранением выравнивания.

    Layout-режим добивает строки пробелами до колонок; для прозы эти пробелы —
    мусор, и их надо сжать. Иначе ворота спецификации (library/docfilter.py)
    считают одну строку длинной, а арифметика цены спотыкается о лишние
    промежутки между числами.
    """
    строки = []
    for страница in страницы:
        for s in страница.splitlines():
            s = re.sub(r"[ \t]{2,}", " ", s).strip()
            if s:
                строки.append(s)
    return "\n".join(строки)


#: Читать PDF ОДИН раз вместо двух. Прежде файл, у которого таблица не опозналась,
#: разбирался pypdf дважды: сначала с выравниванием ради таблицы, потом обычным
#: режимом ради текста — по шестьдесят страниц каждый раз. Это ровно двойная цена
#: самой дорогой части разбора.
#:
#: По умолчанию ВЫКЛЮЧЕНО: текст, полученный сжатием layout-страниц, — не тот же
#: самый текст, что даёт обычный режим, и судить об этом надо замером, а не
#: рассуждением (правило 3). Холостой переразбор сравнивает позиции и цены с
#: включённым входом и без него.
ОДИН_ПРОХОД = os.environ.get("PDF_ONE_PASS", "") not in ("", "0", "false")


def text_from_pdf(b: bytes, rec: dict | None = None) -> str:
    """Текст PDF. Попутно записывает постраничный счёт, если дана запись файла."""
    страницы, всего, потеряно = страницы_pdf(b)
    записать_счёт(rec, страницы, всего, потеряно)
    return "\n".join(страницы)


def троек_в_тексте(текст: str) -> int:
    """Сколько строк текста дают ПРАВДОПОДОБНУЮ цену по тройке «кол-во × цена =
    сумма» — тем же отбором строк, что текстовый путь handle (длиннее восьми
    знаков, не шум).

    Правдоподобную (quotes.цена_текста_правдоподобна): цена записана деньгами,
    количество — целое или с единицей. Ревизия 28.09.2026: простой счёт троек
    выбирал текст по техническим строкам «ДН-15 Мощность: 400 кВт, 6000 В»
    (15 × 400 = 6000) — пять «цен» мощности вместо двух настоящих."""
    строки = [ln.strip() for ln in текст.splitlines()
              if len(ln.strip()) > 8 and not NOISE_ROW.match(ln.strip())]
    n = 0
    for ln in строки[:2000]:
        ц = quotes.цена_из_текста(ln)
        n += bool(ц) and quotes.цена_текста_правдоподобна(ln, ц)
    return n


def текст_pdf(b: bytes, rec: dict | None, страницы: list[str]) -> tuple[str, str]:
    """Текст PDF для текстового пути и пометка, какой взят («» — прежний).

    Прежде: обычный режим pypdf, а при ОДИН_ПРОХОД — страницы с выравниванием,
    сжатые в строки (плоский). ПРАВКА F2 (PDF_BEST_TEXT): в PDF, где каждая
    ячейка — свой текстовый объект с переводом строки (печатная форма 1С),
    обычный режим ставит ячейки по одной на строку, и тройка «кол-во × цена =
    сумма» не собирается ни в одной строке. Страницы с выравниванием уже
    прочитаны (ради таблицы), и строка таблицы в них цела. Берётся тот текст,
    где сошлось больше правдоподобных троек (троек_в_тексте); при равенстве —
    прежний. Решение по файлу. След правки (F2) ставит тот, кто текст ВЗЯЛ:
    текст_pdf зовут и для пробы (таблица_уступает_тексту)."""
    if ОДИН_ПРОХОД:
        return плоский(страницы), ""
    обычный = text_from_pdf(b, rec)
    if not _действует(ЛУЧШИЙ_ТЕКСТ):
        return обычный, ""
    выровненный = плоский(страницы)
    т_обычный, т_выровненный = троек_в_тексте(обычный), троек_в_тексте(выровненный)
    if т_выровненный > т_обычный:
        return выровненный, f"текст с выравниванием: троек {т_выровненный} против {т_обычный}"
    return обычный, ""


