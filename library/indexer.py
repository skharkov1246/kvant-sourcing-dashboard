#: На смешанной выборке всех форматов тот же вход давал строк цены 3 474 → 5 716,
#: плюс 64,5 % (прогон 35844131867). Значит прирост шёл от офисных файлов, а
#: общий выключатель складывал прибыль одних с убытком других в одно число.
ШИРЕ_ПРИМЕНИМО = frozenset({"xlsx", "ods", "docx", "csv", "txt", "xml", "spreadsheetml"})


def header_map(rows: list[list[str]], *, шире: bool | None = None,
               глубина: int | None = None) -> tuple[int, dict[str, int]]:
    """Ищем строку заголовков: в ней должно найтись хотя бы два известных названия.

    ОСЛАБЛЕННОЕ ПРАВИЛО (`шире`) меняет ровно четыре вещи, каждая измерена
    отдельно сеткой: словарь пополняется словами замера; ценовые колонки идут в
    зачёт «двух» (их читает quotes.py, а COLS про них не знал — отсюда 19,6 %
    файлов с узнанным наименованием и «второй колонки нет»); одного наименования
    достаточно; просмотр идёт на ГЛУБОКО строк вместо ШАПКА_В_ПЕРВЫХ.

    Судить это надо ПО ЦЕНЕ, а не по числу найденных шапок: ослабление может
    принять за шапку строку тела, и тогда позиции поедут на одну вниз. Поэтому
    переразбор печатает «строк цены было / стало», и решение принимается там.

    глубина — сколько строк просматривать при строгом правиле (правка F5,
    глубина_шапки: у PDF шапка стоит под прозой письма); None — ШАПКА_В_ПЕРВЫХ.
    С правкой F4 (ШАПКА_БЛОКОМ) номер — ПОСЛЕДНЯЯ строка склеенного блока
    шапки: тело таблицы начинается за ней (найти_шапку).
    """
    hi, found, _шапка, _склеена = найти_шапку(rows, шире=шире, глубина=глубина)
    return hi, found


def _годится_шапкой(found: dict[str, int], row: list[str], шире: bool) -> bool:
    """Правило шапки (строгое или шире) для уже узнанных колонок строки."""
    if "item_name" not in found:
        return False
    # Первая редакция словаря — намеренно: флаг PRICE_DICT_V2 меняет только
    # чтение цены, а не то, где шапка. Иначе набор позиций поехал бы вместе
    # с ценой, и сравнение «без правки / с правкой» на одних байтах врало бы.
    сколько = len(found) + (len(quotes.колонки_цены(row, v2=False)) if шире else 0)
    return сколько >= (1 if шире else 2)


def _колонки_шапки(row: list[str], шире: bool) -> dict[str, int] | None:
    """Колонки строки, если она годится в шапку по правилу (строгому или шире)."""
    found = колонки_строки_шире(row) if шире else колонки_строки(row)
    return found if _годится_шапкой(found, row, шире) else None


def шапка_строгая(row: list[str], found: dict[str, int]) -> bool:
    """СТРОГИЕ ВОРОТА ШАПКИ — для строк, до которых прежнее правило не доходило:
    глубже сорока строк (правка F5) и в постраничном разрезе (правка F1).

    Прежние ворота засчитывают два слова словаря в ОДНОЙ ячейке за две колонки и
    не смотрят, заголовок ли это вообще. Ревизия 28.09.2026 на PDF репозитория:
    шапкой брались строка прозы «контроль материала, потом партия» (материал +
    парт, одна ячейка) и строка тела «5. | Steam-jet vacuum unit | … item 6»
    (unit + item) — файл уходил с текстового пути на табличный и терял цены и
    позиции. Строгая шапка: колонки узнаны в РАЗНЫХ ячейках (то же правило, что
    у почему_нет_шапки), ни одной числовой ячейки (номер позиции — признак
    строки тела), узнанные ячейки без цифр и не длиннее ЯЧЕЙКА_ШАПКИ_МАКС."""
    ячейки = set(found.values())
    if len(ячейки) < 2 or any(_числовая(c) for c in row if (c or "").strip()):
        return False
    return all(j < len(row) and not re.search(r"\d", row[j] or "")
               and len((row[j] or "").strip()) <= ЯЧЕЙКА_ШАПКИ_МАКС for j in ячейки)


def найти_шапку(rows: list[list[str]], *, шире: bool | None = None,
                глубина: int | None = None,
                строго: bool = False) -> tuple[int, dict[str, int], list[str], bool]:
    """(номер строки шапки, колонки, строка шапки, склеена ли блоком).

    Без правки F4 строка шапки — сама rows[номер]. С правкой: шапка, узнанная
    прежним правилом, склеивается с соседними строками своего блока
    (блок_шапки), если склейка что-то ДАЁТ (шапка_блоком); не узнанная ни одной
    строкой — ищется склейкой блоков. Порядок такой, чтобы шапка, которую
    прежнее правило нашло, осталась на своём месте: склейка строк над ней не
    может увести шапку выше.

    строго — только строгие шапки (шапка_строгая), для постраничного разреза
    (F1). Строки глубже ШАПКА_В_ПЕРВЫХ (досягаемы только правкой F5 — у
    ослабленного правила своя глубина и своё решение) — строгими всегда."""
    шире = ШАПКА_ШИРЕ if шире is None else шире
    предел = ГЛУБОКО if шире else ШАПКА_В_ПЕРВЫХ
    if глубина:
        предел = max(предел, глубина)
    блоком = _действует(ШАПКА_БЛОКОМ)

    def строже(i: int) -> bool:
        return строго or (i >= ШАПКА_В_ПЕРВЫХ and not шире)

    for i, row in enumerate(rows[:предел]):
        found = _колонки_шапки(row, шире)
        if found is None:
            continue
        if блоком:
            склейка = шапка_блоком(rows, i, шире)
            if склейка is not None and (not строже(i) or шапка_строгая(склейка[2], склейка[1])):
                return склейка
        if строже(i) and not шапка_строгая(row, found):
            continue
        return i, found, row, False
    if блоком:
        # Склейкой ищется шапка вокруг строки С НАИМЕНОВАНИЕМ, которой одной не
        # хватило второй колонки («№ | Наименование | Кол- | Цена,»): её колонки
        # склейка только дополняет. Строка над ней («Итого | Цена, EUR») опорой
        # быть не может — иначе «только добавляет» мерилось бы от чужой строки,
        # и цена уезжала бы в колонку суммы (ревизия 28.09.2026).
        for i, row in enumerate(rows[:предел]):
            if строка_шапки_верхняя(row) and "item_name" in (
                    колонки_строки_шире(row) if шире else колонки_строки(row)):
                склейка = шапка_блоком(rows, i, шире)
                if склейка is not None and (not строже(i)
                                            or шапка_строгая(склейка[2], склейка[1])):
                    return склейка
    return -1, {}, [], False


# ── ПРАВКА F4 (HEADER_BLOCK): ШАПКА В НЕСКОЛЬКО СТРОК ────────────────────────
# Узкая колонка печатной формы переносит заголовок: «Кол-» / «во», «Цена без» /
# «НДС, руб.», а «Цена за единицу» стоит строкой ВЫШЕ «Наименования». Прежнее
# правило видит одну строку: количество не узнаётся («кол-» не «кол-во»),
# валюта и НДС уходят в строку ниже, и из двух цен берётся не та. Блок шапки —
# соседние строки без чисел; склеиваются по колонкам, «Кол-» + «во» — без пробела.
#: Сколько строк держит блок шапки и сколько из них выше узнанной строки.
БЛОК_ШАПКИ_СТРОК = 4
БЛОК_ШАПКИ_ВЫШЕ = 2
#: Ячейка шапки длиннее этого — проза, а не заголовок колонки.
ЯЧЕЙКА_ШАПКИ_МАКС = 40


def _числовая(c: str) -> bool:
    """Ячейка — число («1», «4 243,42», «01.09.2026»), а не заголовок с числом
    («НДС 20 %»): число читается, а букв меньше двух."""
    s = (c or "").strip()
    return bool(s) and quotes.число_из(s) is not None and len(БУКВА.findall(s)) < 2


def строка_шапки_верхняя(row: list[str]) -> bool:
    """Строка над узнанной шапкой, годная в её блок: две и больше непустых
    ячеек, ни одной числовой, все короткие. Проза письма — одна ячейка (так
    её отдаёт pdftable) — в блок не попадает."""
    непустые = [c.strip() for c in row if (c or "").strip()]
    return (len(непустые) >= 2 and not any(_числовая(c) for c in непустые)
            and all(len(c) <= ЯЧЕЙКА_ШАПКИ_МАКС for c in непустые))


def строка_шапки_нижняя(row: list[str], j_имя: int | None = None,
                        заголовок_имени: str = "") -> bool:
    """Строка под шапкой, годная в её блок: ни одной числовой ячейки, все
    короткие; продолжение бывает в одной колонке («во» под «Кол-»), но не в
    нулевой одной — так pdftable отдаёт строку прозы.

    j_имя, заголовок_имени — колонка наименования шапки и её заголовок. Ячейка
    строки в этой колонке, похожая на ЗНАЧЕНИЕ, а не на продолжение заголовка
    (длиннее самого заголовка, с запятой или цифрой), делает строку позицией.
    Ревизия 28.09.2026: первая строка тела без количества («Кран шаровой, марка
    11с67п | по запросу | шт») вклеивалась в шапку — позиция пропадала, а слово
    «марка» заводило колонку бренда у всех позиций файла."""
    непустые = [(j, c.strip()) for j, c in enumerate(row) if (c or "").strip()]
    if not непустые or any(_числовая(c) or len(c) > ЯЧЕЙКА_ШАПКИ_МАКС for _, c in непустые):
        return False
    if j_имя is not None and j_имя < len(row):
        c = (row[j_имя] or "").strip()
        if c and (len(c) > len((заголовок_имени or "").strip()) or "," in c
                  or re.search(r"\d", c)):
            return False
    return not (len(непустые) == 1 and непустые[0][0] == 0)


def _колонка_имени(row: list[str]) -> tuple[int | None, str]:
    """Колонка наименования строки шапки и её заголовок (или None, «»)."""
    j = колонки_строки(row).get("item_name")
    return (j, row[j] or "") if j is not None and j < len(row) else (None, "")


def блок_шапки(rows: list[list[str]], i: int) -> tuple[int, int]:
    """(первая, последняя) строки блока шапки вокруг строки i."""
    lo = i
    while lo > 0 and i - lo < БЛОК_ШАПКИ_ВЫШЕ and строка_шапки_верхняя(rows[lo - 1]):
        lo -= 1
    j_имя, заголовок = next((_колонка_имени(rows[k]) for k in range(i, lo - 1, -1)
                            if _колонка_имени(rows[k])[0] is not None), (None, ""))
    hi = i
    while hi + 1 < len(rows) and hi + 1 - lo < БЛОК_ШАПКИ_СТРОК \
            and строка_шапки_нижняя(rows[hi + 1], j_имя, заголовок):
        hi += 1
        if j_имя is None:
            j_имя, заголовок = _колонка_имени(rows[hi])
    return lo, hi


def _склеить(верх: str, низ: str) -> str:
    """Две части заголовка колонки: «Кол-» + «во» — «Кол-во», иначе через пробел."""
    верх, низ = (верх or "").strip(), (низ or "").strip()
    if not верх or not низ:
        return верх or низ
    if верх.endswith("-") and not верх.endswith(" -"):
        return верх + низ
    return верх + " " + низ


def склеить_строки(строки: list[list[str]]) -> list[str]:
    """Строки блока шапки — в одну, по колонкам сверху вниз."""
    ширина = max(len(r) for r in строки)
    out = [""] * ширина
    for r in строки:
        out = [_склеить(out[j], r[j] if j < len(r) else "") for j in range(ширина)]
    return out


#: Сколько слов держит склеенная ячейка шапки, чтобы её колонка шла склейке в
#: зачёт: количество и наименование — до трёх («Кол-во, шт.», «Наименование
#: товара»), бренд, артикул и единица — до двух («Ед. изм.», «Код товара»).
#: Длиннее — текст, а не заголовок: «Поставщик: ООО «Завод Условный»» над колонкой
#: «№» заводил колонку бренда со значениями «1», «2», «3» (ревизия 28.09.2026).
СЛОВ_ЗАГОЛОВКА = {"qty": 3, "item_name": 3}
СЛОВ_ЗАГОЛОВКА_ПРОЧИХ = 2


def _заголовок_колонки(ключ: str, база: str, склейка: str) -> bool:
    """Склеенная ячейка — заголовок колонки ключа, которого в строке шапки не было:
    короткая, без цифр, и в строке шапки на её месте пусто или перенос («Кол-»)."""
    база, склейка = (база or "").strip(), (склейка or "").strip()
    if база and not база.endswith("-"):
        return False
    return (bool(склейка) and not re.search(r"\d", склейка)
            and len(склейка) <= ЯЧЕЙКА_ШАПКИ_МАКС
            and len(склейка.split()) <= СЛОВ_ЗАГОЛОВКА.get(ключ, СЛОВ_ЗАГОЛОВКА_ПРОЧИХ))


def шапка_блоком(rows: list[list[str]], i: int,
                 шире: bool) -> tuple[int, dict[str, int], list[str], bool] | None:
    """Склеенная шапка вокруг строки i или None — склеивать нечего или незачем.

    СКЛЕЙКА ОБЯЗАНА ЧТО-ТО ДАТЬ — И ТОЛЬКО ДОБАВИТЬ. В зачёт идёт (ревизия
    28.09.2026: прежде считались узнанные КЛЮЧИ, и подстрока «марка», «завод»,
    «код» в соседней строке сходила за прибыль):
      • колонка COLS, которой в строке i не было, в ячейке, которая в строке i
        пуста или оборвана переносом, — не колонка наименования и не занятая
        другой колонкой, и склеенная ячейка похожа на заголовок
        (_заголовок_колонки);
      • цена или сумма, которых в строке i не было (quotes.колонки_цены, первая
        редакция), и валюта шапки цены, которой не было.
    Колонки строки i склейка не меняет: итог — её колонки плюс новые, а ценовые
    колонки строки i обязаны остаться на местах. Строка тела под шапкой
    отсекается раньше, в блок_шапки. Из отрезков блока, содержащих строку i,
    берётся давший больше; при равенстве — самый короткий. Не дал ничего —
    None, и шапка та же, что без правки."""
    lo, hi = блок_шапки(rows, i)
    if hi == lo:
        return None
    строка = list(rows[i])
    база = колонки_строки_шире(строка) if шире else колонки_строки(строка)
    база_цк = quotes.колонки_цены(строка, v2=False)
    база_вал = quotes.валюта_заголовка(строка, база_цк)
    занято = set(база.values()) | set(база_цк.values())
    лучший = None
    for a in range(lo, i + 1):
        for b in range(i, hi + 1):
            if b == a:
                continue
            склейка = склеить_строки(rows[a:b + 1])
            цк = quotes.колонки_цены(склейка, v2=False)
            if any(цк.get(к) != j for к, j in база_цк.items()):
                continue                        # склейка сдвинула бы цену строки i
            узнано = колонки_строки_шире(склейка) if шире else колонки_строки(склейка)
            j_имя = база.get("item_name", узнано.get("item_name"))
            новые = {к: j for к, j in узнано.items()
                     if к not in база and j not in занято
                     and (j != j_имя or к == "item_name")
                     and j < len(склейка)
                     and _заголовок_колонки(к, строка[j] if j < len(строка) else "",
                                            склейка[j])}
            дало = (len(новые) + ("price" in цк and "price" not in база_цк)
                    + ("total" in цк and not база_цк)
                    + (not база_вал and bool(quotes.валюта_заголовка(склейка, цк))))
            found = {**база, **новые}
            if not дало or not _годится_шапкой(found, склейка, шире):
                continue
            мера = (дало, a - b)
            if лучший is None or мера > лучший[0]:
                лучший = (мера, b, found, склейка)
    if лучший is None:
        return None
    return лучший[1], лучший[2], лучший[3], True


#: Слово-кандидат из шапки: буквы одного алфавита, от шести знаков. Порог длины и
#: порог «от трёх разных файлов» в отчёте — условия правила 17 (публичный журнал).
СЛОВО_ШАПКИ = re.compile(r"[А-Яа-яЁё]{6,}|[A-Za-z]{6,}")


def слова_шапки_без_имени(rows: list[list[str]]) -> set[str]:
    """Слова из той строки шапки, где колонки узнались, А НАИМЕНОВАНИЕ — НЕТ.

    ЗАЧЕМ ИМЕННО ТАК. Разбор причин 23.09.2026 показал: 47 файлов из 53 без шапки
    спотыкаются на наименовании, а не на прочих колонках. Значит нужен не общий
    частотный список слов документа, а слова ИЗ ТОЙ САМОЙ строки, где количество
    или цена уже узнаны: это и есть пропущенные названия колонки наименования.

    Берётся лучшая строка — та, где узнано больше всего колонок. Возвращаются
    слова её НЕузнанных ячеек: узнанные и без того в COLS.
    """
    лучшая: list[str] = []
    лучших_колонок = 0
    for row in rows[:ШАПКА_В_ПЕРВЫХ]:
        found = колонки_строки(row)
        if "item_name" in found or len(found) < 1:
            continue
        if len(found) > лучших_колонок:
            лучшая, лучших_колонок = row, len(found)
    if not лучшая:
        return set()
    занятые = set(колонки_строки(лучшая).values())
    слова: set[str] = set()
    for j, c in enumerate(лучшая):
        if j in занятые or not c:
            continue
        слова.update(w.lower() for w in СЛОВО_ШАПКИ.findall(c))
    return слова


#: Слова колонок, встреченные ЗАМЕРОМ 23.09.2026 (прогон 35842239391, 290 файлов
#: без шапки) и правилу неизвестные. Держатся ОТДЕЛЬНО от COLS, пока сетка не
#: покажет, сколько файлов они возвращают и не ломают ли разбор: правило сначала
#: меряют, потом применяют (CLAUDE.md, правило 3).
СЛОВА_ЗАМЕРА = {
    "item_name": ("equipment", "product", "goods", "nomenclature", "товары"),
    "part_number": ("number", "article", "catalogue", "catalog", "designation"),
    "oem": ("origin", "make"),
}

#: Насколько глубже смотреть в варианте «шапка ниже сорока строк». Замер: семь
#: файлов из 290 держат шапку на 41-й и 64-й строках.
ГЛУБОКО = 200


def колонки_строки_шире(row: list[str]) -> dict[str, int]:
    """Колонки строки со словами замера. Только для сетки, не для разбора."""
    found = колонки_строки(row)
    low = [c.lower() for c in row]
    for key, words in СЛОВА_ЗАМЕРА.items():
        if key in found:
            continue
        for j, c in enumerate(low):
            if c and any(w in c for w in words):
                found[key] = j
                break
    return found


#: Сколько числовых колонок перебирать тройками. Перебор кубический, и на широкой
#: таблице без предела он съедает прогон: 20 числовых колонок дают 6 840 тройек на
#: каждый файл. Восемь самых числовых — 336, и этого хватает: тройка
#: «кол-во × цена = сумма» стоит в начале таблицы, а не в тридцатой колонке.
ЧИСЛОВЫХ_КОЛОНОК_МАКС = 8


def числовая_доля(колонка: list[str]) -> float:
    """Доля заполненных ячеек колонки, которые читаются как число."""
    заполнено = [c for c in колонка if c and c.strip()]
    if not заполнено:
        return 0.0
    return sum(1 for c in заполнено if quotes.число_из(c) is not None) / len(заполнено)


def кто_количество(таблица: list[list[str]], a: int, b: int) -> tuple[int, int]:
    """Которая из двух колонок-множителей — количество, а которая цена.

    АРИФМЕТИКА ИХ НЕ РАЗЛИЧАЕТ: x × y = z верно при любом порядке. Порядок
    перебора тоже не различает — он идёт по номерам колонок, а в файле цена
    попадается и левее количества. Первая редакция `тройка_колонок` обещала в
    комментарии порядок «кол-во, цена, сумма», а возвращала (1, 2, 3) и тогда,
    когда колонка 1 была ценой: взятие цены по такой тройке дало бы количество.

    Признак — целость: количества пишут целыми («2 шт.»), цену с копейками.
    При равенстве целых решает величина: цена единицы больше количества почти
    всегда, потому что количество — это штуки, а цена — деньги за штуку.
    """
    def свойства(j: int) -> tuple[int, float]:
        числа = [quotes.число_из(r[j]) for r in таблица if j < len(r)]
        числа = [x for x in числа if x is not None]
        if not числа:
            return 0, 0.0
        целых = sum(1 for x in числа if float(x) == int(x))
        return целых - len(числа), sum(abs(float(x)) for x in числа) / len(числа)

    целость_a, велич_a = свойства(a)
    целость_b, велич_b = свойства(b)
    if целость_a != целость_b:
        return (a, b) if целость_a > целость_b else (b, a)
    return (a, b) if велич_a <= велич_b else (b, a)


def тройка_колонок(таблица: list[list[str]]) -> tuple[int, int, int] | None:
    """Колонки «кол-во × цена = сумма», опознанные ПО ФОРМЕ ДАННЫХ, без заголовков.

    ЗАЧЕМ. Замер 23.09.2026 (прогон 35843048108): ослабление правила шапки
    возвращает 143 файла из 368, а 225 файлов — 61 % — не берутся никаким
    ослаблением словаря или порога. Для них заголовка попросту нет или он не
    слово. Единственный оставшийся признак — форма: колонка, где большинство
    ячеек правдоподобные числа, и тройка, сходящаяся по строкам арифметически.

    Допуск процентный: в предложениях округляют. Требуется не менее трёх строк и
    сходимость в 70 % из них — одна случайная тройка чисел совпадает сплошь и
    рядом, три подряд — уже нет.

    Возвращает номера колонок (кол-во, цена, сумма) или None. Номера, а не
    «да/нет»: по ним цену можно ВЗЯТЬ, а не только узнать, что она есть.
    """
    if not таблица:
        return None
    ширина = max(len(r) for r in таблица)
    колонки = [[r[j] if j < len(r) else "" for r in таблица] for j in range(ширина)]
    доли = sorted(((числовая_доля(k), j) for j, k in enumerate(колонки)), reverse=True)
    числовые = sorted(j for доля, j in доли[:ЧИСЛОВЫХ_КОЛОНОК_МАКС] if доля >= 0.6)
    for a in числовые:
        for b in числовые:
            if b == a:
                continue
            for c in числовые:
                if c in (a, b):
                    continue
                сошлось = всего = 0
                for r in таблица:
                    x, y, z = (quotes.число_из(r[j]) if j < len(r) else None for j in (a, b, c))
                    if None in (x, y, z) or 0 in (x, y):
                        continue
                    всего += 1
                    if abs(x * y - z) <= max(abs(z) * 0.01, 0.02):
                        сошлось += 1
                if всего >= ТРОЙКА_СТРОК_МИН and сошлось >= max(ТРОЙКА_СТРОК_МИН,
                                                                 int(всего * 0.7)):
                    кол, цена = кто_количество(таблица, a, b)
                    return кол, цена, c
    return None


def сетка_шапки(rows: list[list[str]]) -> set[str]:
    """КАКИЕ ОСЛАБЛЕНИЯ ПРАВИЛА НАШЛИ БЫ ШАПКУ В ЭТОМ ФАЙЛЕ.

    Ослабление порога меряется таблицей, а не одним прогоном (CLAUDE.md,
    правило 4): счётчики уже в памяти, и пересчёт четырёх вариантов за тот же
    проход стоит миллисекунды, а отдельный прогон на каждый — четверть часа
    портала.

    Ничего не меняет: возвращает названия вариантов, при которых шапка нашлась
    бы. Варианты складываются — «всё сразу» считается отдельной строкой, потому
    что пересечения между ними есть и сумма долей ответа не даёт.
    """
    нашли: set[str] = set()
    if not rows:
        return нашли

    def проходит(row, *, шире: bool, одной_хватит: bool, с_ценой: bool) -> bool:
        found = колонки_строки_шире(row) if шире else колонки_строки(row)
        if "item_name" not in found:
            return False
        n = len(found)
        if с_ценой:
            n += len(quotes.колонки_цены(row, v2=False))
        return n >= (1 if одной_хватит else 2)

    варианты = (
        ("цена считается колонкой", dict(шире=False, одной_хватит=False, с_ценой=True)),
        ("одного наименования хватает", dict(шире=False, одной_хватит=True, с_ценой=False)),
        ("слова замера в словаре", dict(шире=True, одной_хватит=False, с_ценой=False)),
    )
    for имя, как in варианты:
        if any(проходит(r, **как) for r in rows[:ШАПКА_В_ПЕРВЫХ]):
            нашли.add(имя)
    # «ВСЁ СРАЗУ» — ЭТО РОВНО ОСЛАБЛЕННЫЙ РАЗБОР, А НЕ ЕГО КОПИЯ. Свой перебор
    # здесь означал бы, что сетка обещает одно, а правка даёт другое: именно так
    # разведка шапки 23.09.2026 мерила не разборщика, и это стоило трёх прогонов.
    if header_map(rows, шире=True)[0] >= 0:
        нашли.add("всё сразу")
    # ПОСЛЕДНИЙ ПРИЗНАК — ФОРМА, а не слова: для файлов, которые ослаблением не
    # берутся вовсе, других зацепок нет. Считается здесь, чтобы объём этой работы
    # был известен ДО того, как её начинать.
    if тройка_колонок(rows) is not None:
        нашли.add("цена по форме: тройка кол-во × цена = сумма")
    # Глубина считается на исходном правиле: иначе не видно её собственного вклада.
    for row in rows[ШАПКА_В_ПЕРВЫХ:ГЛУБОКО]:
        found = колонки_строки(row)
        if "item_name" in found and len(found) >= 2:
            нашли.add(f"смотреть {ГЛУБОКО} строк вместо {ШАПКА_В_ПЕРВЫХ}")
            break
    return нашли


#: ВЕРСИЯ ПРИЧИН ОТКАЗА ШАПКИ (lib_files.header_miss) — печатается в строке
#: журнала (строка_правок_pdf), потому что колонка накапливается по всей базе и
#: ряды до и после смены смысла надо уметь разделить.
#:   1 — до 28.09.2026: все строки файла;
#:   2 — 28.09.2026: у PDF строка из одной непустой ячейки (так pdftable отдаёт
#:       прозу) в прежние причины не идёт: причина считается по строкам с
#:       колонками, а файл, где слова колонок есть только в прозе, получает СВОЮ
#:       — ПРОЗА_С_КОЛОНКАМИ. У прочих форматов — как в версии 1, байт в байт.
#:       Замер на 299 файлах репозитория (без флагов): причина сменилась у 34 PDF,
#:       и не только на новую — «шапка есть на строке 624 — глубже» от строки
#:       прозы стала «наименование узнали…» от строк с колонками. Поэтому ряды
#:       header_miss у PDF до и после версии 2 поштучно несравнимы.
#: ВЕРСИЯ 2 ДЕЙСТВУЕТ ТОЛЬКО ВМЕСТЕ С ПРАВКАМИ КП (ревизия 29.09.2026). Прежде
#: она действовала всегда, и ночной разбор без флагов писал в header_miss у PDF
#: другое значение, не помечая, какой редакцией причин оно получено: по строке
#: lib_files ряды различались бы только датой. Теперь редакция причин следует
#: за версией разборщика (PARSER_VERSION 6 — правки КП): без правок значение
#: байт в байт прежнее, а строка с версией 6 несёт причины версии 2.
ВЕРСИЯ_ПРИЧИН_ШАПКИ = 2
ПРОЗА_С_КОЛОНКАМИ = "слова колонок только в строке прозы PDF (одна ячейка)"


def версия_причин_шапки() -> int:
    """Редакция причин отказа шапки сейчас: 2 — действует хоть одна правка КП
    (версия разборщика 6), иначе 1, как до 28.09.2026."""
    return ВЕРСИЯ_ПРИЧИН_ШАПКИ if правки_действуют() else 1


def почему_нет_шапки(rows: list[list[str]], п: str = "", версия: int | None = None) -> str:
    """ПОЧЕМУ шапка не узнана — словами, годными для починки.

    «Шапки нет» само по себе чинить нельзя: за ним стоят четыре разные правки —
    расширить просмотр вглубь файла, добавить слово в COLS, ослабить требование
    двух колонок, починить читателя. Возвращаемая строка их различает и пишется
    в `lib_files.header_miss`, то есть накапливается по всей базе, а не живёт
    один прогон (правило 16: сохраняй, почему получилось значение).

    п — вид файла. У PDF при редакции причин 2 (версия; None — по правкам КП,
    версия_причин_шапки) строки прозы судятся отдельно.
    """
    версия = версия_причин_шапки() if версия is None else версия
    if not rows:
        return "читатель не дал строк"
    if max(len(r) for r in rows) <= 1:
        return "таблица в один столбец — колонок нет вообще"
    # СТРОКА ПРОЗЫ PDF — НЕ КАНДИДАТ В ШАПКУ. pdftable отдаёт прозу одной ячейкой,
    # и «Всего наименований 10, на сумму …» давало «наименование узнали, второй
    # колонки — нет» у файла, где шапки не было вовсе, а «Наименование и
    # количество товара» в письме — «шапка есть глубже» (разведка 28.09.2026).
    # Такие строки судятся после строк с колонками и получают свою причину. У
    # книги и документа строка шапки с одной заполненной ячейкой («Наименование»
    # и пустые соседние) — законный случай прежней причины, и там всё как было.
    if п == "pdf" and версия >= 2:
        строки = [(i, row) for i, row in enumerate(rows)
                  if sum(1 for c in row if (c or "").strip()) >= 2]
        проза = [row for row in rows if sum(1 for c in row if (c or "").strip()) < 2]
    else:
        строки, проза = list(enumerate(rows)), []
    # Та же проверка, но по ВСЕМУ файлу: отличает «шапки нет» от «шапка ниже».
    for i, row in строки:
        found = колонки_строки(row)
        if "item_name" in found and len(found) >= 2:
            return (f"шапка есть на строке {i + 1} — глубже, чем смотрим"
                    if i >= ШАПКА_В_ПЕРВЫХ else "шапка узнаётся — расходится с пометкой")
    # Шапки нет нигде. Что именно не сошлось в лучшей из строк?
    есть_наименование = ложь_колонок = 0
    for _i, row in строки:
        found = колонки_строки(row)
        if "item_name" in found:
            есть_наименование = max(есть_наименование, len(found))
        else:
            ложь_колонок = max(ложь_колонок, len(found))
    if есть_наименование:
        return "наименование узнали, второй колонки — нет"
    if ложь_колонок >= 2:
        return "колонки узнали, а наименования среди них нет"
    if ложь_колонок == 1:
        return "узнали одну колонку, и та не наименование"
    if any(колонки_строки(row) for row in проза):
        return ПРОЗА_С_КОЛОНКАМИ
    return "ни одного известного слова колонки"


def количество_ячейки(q: str) -> tuple[float | None, str | None]:
    """Количество из ячейки и причина отказа, если число не читается.

    Прежде бралось float(все цифры ячейки подряд): «3 163 518 182,316» склеивалось
    в 3163518182.316, и карточка номенклатуры показывала это количеством
    (24.09.2026). Теперь число читает quotes.число_из — тот же разбор разделителей
    тысяч, что у цены, — а число больше quotes.МАКС_КОЛИЧЕСТВО отвергается: такого
    количества в строке КП или спецификации не бывает, это склейка ячеек.
    """
    if not (q or "").strip():
        return None, None
    v = quotes.число_из(q)
    if v is None or v <= 0:
        return None, None
    if v > quotes.МАКС_КОЛИЧЕСТВО:
        return None, quotes.КОЛ_НЕ_ЧИТАЕТСЯ
    return v, None


def сверить_количество(rec: dict, ндс: bool = False) -> None:
    """Тройка «количество × цена = сумма»: не сошлась — количество не пишется.

    Угадывать нельзя: при цене, равной сумме, соблазнительно поставить 1, но
    неверной может быть любая из трёх ячеек. Поэтому количество снимается, а
    строка цены получает оговорку quotes.КОЛ_НЕ_СОШЛОСЬ — по ней её считает
    «строк_сумма_не_сошлась» страницы /brands (library/codes_sql.py). Цена,
    выведенная из суммы делением, сходится с ней по построению и не сверяется.
    Отказ по пределу (количество_ячейки) пишется в оговорку той же строкой.

    ндс — шапка склеена блоком (правка F4): склейка читает «Цена за единицу без
    НДС» над двумя ценами, и цена берётся без НДС, а сумма строки в печатной
    форме — «Сумма с НДС». Тройка тогда не сходится по построению, и прежде
    сверка снимала количество у всех строк файла (ревизия 28.09.2026: tallhead,
    8 → 0). Теперь «кол-во × цена × (1 + ставка) = сумма» по закрытому списку
    СТАВКИ_НДС_СУММЫ количество сохраняет, а сумма — с НДС, цене без НДС не
    пара — не записывается (как у второй редакции словаря: quotes._ценовые_v2),
    с оговоркой ОГОВОРКА_СУММА_С_НДС и следом «F4н».
    """
    ц = rec.get("_цена")
    причина = rec.pop("_кол_во_отказ", None)
    qty = rec.get("qty")
    if ц and qty and ц.get("price") and ц.get("total") \
            and quotes.ОГОВОРКА_ИЗ_СУММЫ not in (ц.get("note") or ""):
        допуск = max(quotes.ДОПУСК_МИН, qty * quotes.ДОПУСК_НА_ЕДИНИЦУ)
        if abs(qty * ц["price"] - ц["total"]) > допуск:
            ставки = [с for с in СТАВКИ_НДС_СУММЫ
                      if abs(qty * ц["price"] * (1 + с) - ц["total"]) <= допуск * (1 + с)] \
                if ндс and _действует(ШАПКА_БЛОКОМ) else []
            if ставки:
                ц["total"] = None
                причина = "; ".join(x for x in (причина, ОГОВОРКА_СУММА_С_НДС) if x)
                _след("F4н")
            else:
                rec["qty"] = None
                причина = quotes.КОЛ_НЕ_СОШЛОСЬ
    if ц and причина:
        ц["note"] = "; ".join(x for x in (ц.get("note"), причина) if x)


#: Сумма строки с НДС при цене без НДС (сверить_количество, правка F4).
ОГОВОРКА_СУММА_С_НДС = "сумма строки с НДС — к цене без НДС не пара, не записана"


БУКВА = re.compile(r"[A-Za-zА-Яа-яЁё]")
ОГОВОРКА_СТОИМОСТЬ_СВЕРЕНА = "цена из колонки «Стоимость», сверена с суммой"
ОГОВОРКА_СТОИМОСТЬ_КОЛ1 = "цена из колонки «Стоимость» при количестве 1"


def стоимость_как_цена(body: list[list[str]], j_кол: int, j_ст: int,
                       j_сум: int | None) -> str | None:
    """Голое «Стоимость» — цена за единицу? Решается по ФАЙЛУ (правило 13).

    Слово двусмысленно: у одних поставщиков это цена единицы, у других сумма
    строки. Угадать значит завысить цену в qty раз — ошибка выкладки по ЛУКОЙЛу.
    Поэтому только арифметика:
      • есть колонка суммы — «кол-во × стоимость = сумма» сходится не меньше чем
        в 70 % строк, где все три числа есть;
      • суммы нет — у всех строк количество 1: тогда цена и сумма совпадают, и
        спорить не о чем. Хоть одна строка с другим количеством — отказ.
    Возвращает оговорку для note или None, если колонку ценой считать нельзя.
    """
    def ячейка(r: list[str], j: int | None) -> str:
        return r[j] if j is not None and 0 <= j < len(r) else ""

    всего = сошлось = 0
    не_один = False
    for r in body:
        q = количество_ячейки(ячейка(r, j_кол))[0]
        c = quotes.число_из(ячейка(r, j_ст))
        if q is None or c is None or c <= 0:
            continue
        if j_сум is None:
            всего += 1
            не_один = не_один or q != 1
            continue
        ок = quotes.тройка_сходится(q, c, quotes.число_из(ячейка(r, j_сум)))
        if ок is None:
            continue
        всего += 1
        сошлось += ок
    if not всего:
        return None
    if j_сум is None:
        return None if не_один else ОГОВОРКА_СТОИМОСТЬ_КОЛ1
    return ОГОВОРКА_СТОИМОСТЬ_СВЕРЕНА if сошлось >= max(1, -(-всего * 7 // 10)) else None


def цена_сходится_с_суммой(body: list[list[str]], j_кол: int, j_цена: int,
                           j_сум: int) -> bool:
    """Колонка цены, при которой НДС лишь упомянут («Цена (НДС 20%)»), — цена
    той же природы, что сумма строки? Решается по ФАЙЛУ (правило 13).

    ЗАЧЕМ. Рядом с суммой без оговорки словарь v2 такую цену не берёт: она может
    быть с НДС при сумме без него, и тогда цена без НДС, выведенная из суммы,
    лучше (CLAUDE.md, «Цена и предложение»). Но в обычном КП «Цена, руб. (НДС
    20%) | Сумма, руб.» обе колонки одной природы, и цена, выведенная делением,
    уступает напечатанной: та же цифра идёт с низкой уверенностью и в сравнение
    не попадает. Арифметика различает эти случаи: «кол-во × цена = сумма».

    Сойтись должны ВСЕ строки, где есть три числа, и хоть одна. Не 70 %, как у
    «Стоимости»: взятая колонка сверяется и построчно (сверить_количество), и
    несошедшаяся строка потеряла бы количество, которое при цене делением суммы
    сохраняла.
    """
    def ячейка(r: list[str], j: int) -> str:
        return r[j] if 0 <= j < len(r) else ""

    всего = 0
    for r in body:
        ок = quotes.тройка_сходится(количество_ячейки(ячейка(r, j_кол))[0],
                                    quotes.число_из(ячейка(r, j_цена)),
                                    quotes.число_из(ячейка(r, j_сум)))
        if ок is None:
            continue
        if not ок:
            return False
        всего += 1
    return всего > 0


def скидка_в_файле(body: list[list[str]], j_ск: int) -> bool:
    """В колонке скидки хоть у одной строки не ноль. Колонка, где везде «0 %»,
    «—» или пусто, скидки не даёт, и прайсовая цена — цена предложения."""
    for r in body:
        v = quotes.число_из(r[j_ск]) if 0 <= j_ск < len(r) else None
        if v:
            return True
    return False


#: Колонку, которую словарь v2 взял ценой, арифметика признала суммой строки.
#: Цена тогда — из прежней колонки или, если её нет, делением суммы (своя оговорка).
ОГОВОРКА_ЦЕНА_БЫЛА_СУММОЙ = "колонка цены по словарю v2 — сумма строки, ценой не взята"
#: Ставки НДС, на которые сумма строки может расходиться с ценой другой колонки
#: («Цена за ед. с НДС» рядом с «Ценой партии без НДС»). 13 % — НДС Китая: КП в
#: юанях у нас больше всех.
СТАВКИ_НДС_СУММЫ = (0.22, 0.20, 0.18, 0.13, 0.12, 0.10)


def цена_это_сумма(body: list[list[str]], j_кол: int, j_цена: int,
                   j_прежде: int | None, j_сум: int | None) -> bool:
    """Колонка, которую вторая редакция словаря взяла ценой, — СУММА СТРОКИ?

    ЗАЧЕМ. Холостой переразбор 5 617 КП (прогон 36294056418) дал 34 строки «была
    ценой за единицу — стала суммой строки»: новая цена ровно в количество раз
    больше прежней. По коду путей к этому три, и все они — выбор колонки v2,
    отличный от прежнего (воспроизведены в tests/test_price_sum_guard.py):
      • прежняя колонка цены названа с НДС без «с»/«без» («Unit price (13%VAT)»,
        «Цена, руб. НДС 20%») — v2 берёт её последней (до 27.09.2026 считал
        налогом) и берёт соседнюю колонку со словом цены, а та — сумма («Price
        incl. VAT», «Общая цена»);
      • прежняя колонка — «чужая» для v2 («Цена по прайсу» рядом с другой
        ценой), дальше то же;
      • две цены, с НДС и без: v2 берёт «без», а это сумма партии.
    Словами шапки эти пути не закрыть — слова у всех законные. Закрывает их
    арифметика, как у «Стоимости» (стоимость_как_цена): решение по ФАЙЛУ
    (правило 13), по строкам с количеством от двух.

    Строка считает колонку суммой, если её число совпадает со своей суммой
    строки — ячейкой суммы v2 или «прежняя цена × количество» — с точностью до
    ставки НДС. Суммой колонка признаётся, если так в 70 % проверяемых строк.
    Количество от двух — не осторожность, а условие: сумма тогда не меньше двух
    цен, ставка НДС меньше 1,25, и верно прочитанная цена за единицу с суммой не
    совпадёт ни при какой ставке. При количестве 1,2 совпала бы: 1,2 м × цена
    ÷ 1,2 — снова цена.
    """
    def число(r: list[str], j: int | None) -> float | None:
        if j is None or not 0 <= j < len(r):
            return None
        v = quotes.число_из(r[j])
        return v if v is not None and v > 0 else None

    множители = (1.0,) + tuple(k for с in СТАВКИ_НДС_СУММЫ for k in (1 + с, 1 / (1 + с)))
    всего = суммой = 0
    for r in body:
        кол = количество_ячейки(r[j_кол] if 0 <= j_кол < len(r) else "")[0]
        ц = число(r, j_цена)
        if not кол or кол < 2 or ц is None:
            continue
        прежде = число(r, j_прежде) if j_прежде != j_цена else None
        образцы = [x for x in (число(r, j_сум), прежде and прежде * кол) if x]
        if not образцы:
            continue
        # Допуск тройки (quotes.тройка_сходится) с запасом на ставку: цена в КП
        # округлена до копеек, и «цена × кол-во × 1,2» расходится с суммой на
        # количество таких копеек.
        допуск = кол * quotes.ДОПУСК_НА_ЕДИНИЦУ * 1.25 + 0.01
        всего += 1
        суммой += any(abs(ц - о * k) <= допуск for о in образцы for k in множители)
    return всего > 0 and суммой >= max(1, -(-всего * 7 // 10))


def шапка_с_продолжением(rows: list[list[str]], hi: int) -> list[str]:
    """Строка шапки, склеенная со следующей, если та — её продолжение.

    В PDF и в узких колонках книги шапка переносится: «Цена без» / «НДС, руб.».
    По одной первой строке «Цена без» об НДС молчит, и из двух колонок цены
    бралась левая — с НДС (поймано корпусом scripts/cascade_corpus.py, вариант
    nds в PDF). Продолжение — строка без единой цифры, где есть текст хотя бы в
    одной ячейке под ценовой шапкой. Только для второй редакции словаря.
    """
    шапка = list(rows[hi])
    if hi + 1 >= len(rows):
        return шапка
    след = rows[hi + 1]
    if not any((c or "").strip() for c in след) or any(re.search(r"\d", c or "") for c in след):
        return шапка
    ширина = max(len(шапка), len(след))
    return [" ".join(x for x in ((шапка[j] if j < len(шапка) else "").strip(),
                                  (след[j] if j < len(след) else "").strip()) if x)
            for j in range(ширина)]


def колонки_без_шапки(rows: list[list[str]]) -> dict[str, int] | None:
    """Кол-во, цена и сумма таблицы без шапки — по тройке, или None."""
    т = тройка_колонок(rows)
    if т is None:
        return None
    кол, цена, сумма = т
    return {"qty": кол, "price": цена, "total": сумма}


def _след_шапки(hi: int, cols: dict[str, int], шапка: list[str], склеена: bool,
                шире: bool | None, глубина: int | None) -> None:
    """След правок шапки у таблицы, из которой берутся позиции (правило 16):
    F4 — склеена блоком, F5 — стоит глубже ШАПКА_В_ПЕРВЫХ (у строгого правила
    туда пускает только F5), F6 — наименование узнано только словом v3.

    F6 — ТОЛЬКО ЕСЛИ ПРАВКА ДЕЙСТВУЕТ И БЕЗ НЕЁ НАИМЕНОВАНИЯ НЕ БЫЛО тем правилом,
    которым шла шапка. Ревизия 29.09.2026: след ставился и при выключенной F6 —
    ослабленное правило (HEADER_RELAX, слово «товары» в СЛОВА_ЗАМЕРА) узнаёт
    «Товары (работы, услуги)» само, — и в lib_files.read_chain ночного разбора
    ложилось ложное «правки: F6» при прежних позициях и ценах (правило 16)."""
    if hi < 0:
        return
    шире = ШАПКА_ШИРЕ if шире is None else шире
    if склеена:
        _след("F4")
    if глубина and hi >= ШАПКА_В_ПЕРВЫХ and not шире:
        _след("F5")
    if _действует(СЛОВА_V3) and "item_name" in cols:
        with quotes.без_правок():
            прежде = (колонки_строки_шире if шире else колонки_строки)(шапка)
        if "item_name" not in прежде:
            _след("F6")


def items_from_rows(rows: list[list[str]], *, шире: bool | None = None,
                    словарь_v2: bool | None = None,
                    без_шапки: bool | None = None,
                    глубина: int | None = None) -> list[dict]:
    """Позиции из таблицы. Если заголовков нет — берём самую длинную текстовую
    ячейку строки как наименование: у большинства спецификаций это работает.

    шире — применять ли ослабленное правило шапки К ЭТОМУ ФАЙЛУ (ослаблять(вид)).
    Без него разбор брал общий выключатель, и решение «PDF — строго», принятое
    в воротах шапки, здесь не действовало: холостой прогон 23.09.2026 с
    ослаблением дал таблицам PDF 6 263 строки цены против 8 802 (хуже у 381
    файла), тогда как книгам Excel ослабление прибавило 3 200.

    словарь_v2 — вторая редакция словаря цены (quotes.СЛОВАРЬ_V2, PRICE_DICT_V2);
    без_шапки — цена по тройке в таблице без шапки (ЦЕНА_БЕЗ_ШАПКИ,
    HEADERLESS_PRICE). None — по флагу окружения.

    глубина — сколько строк смотреть в поисках шапки (header_map; правка F5
    для PDF — глубина_шапки). С правкой F4 шапка — склеенный блок строк, и
    ценовые колонки обеих редакций словаря читаются по склейке.

    СРАВНЕНИЕ НА ОДНИХ БАЙТАХ. Когда включена хоть одна правка цены, у каждой
    позиции рядом с `_цена` лежит `_цена_прежде` — что дало бы прежнее правило на
    той же строке. Набор позиций правки не меняют (шапка ищется как прежде),
    поэтому переразбор сравнивает «без правки / с правкой» в одном проходе, а не
    с базой, записанной неизвестно какими флагами (CLAUDE.md, «Стиль работы»).
    """
    v2 = quotes.СЛОВАРЬ_V2 if словарь_v2 is None else словарь_v2
    без_шапки = ЦЕНА_БЕЗ_ШАПКИ if без_шапки is None else без_шапки
    сравнивать = v2 or без_шапки
    hi, cols, шапка_блока, склеена = найти_шапку(rows, шире=шире, глубина=глубина)
    _след_шапки(hi, cols, шапка_блока, склеена, шире, глубина)
    # Ценовые колонки ищутся в той же строке заголовков. У спецификаций заказчика
    # их там нет, и разбор не меняется; у КП поставщика в них весь смысл файла
    # (library/quotes.py).
    # Вторая редакция читает шапку вместе с её переносом на следующую строку.
    # Шапка, склеенная блоком (правка F4), перенос уже несёт — и для обеих
    # редакций словаря. Прежнее правило в сравнении на одних байтах читает ту
    # же склейку первой редакцией: иначе сравнение мерило бы блок, а не словарь.
    шапка_прежде = шапка_блока if склеена else (rows[hi] if hi >= 0 else [])
    if склеена:
        шапка = шапка_блока
    else:
        шапка = (шапка_с_продолжением(rows, hi) if v2 else rows[hi]) if hi >= 0 else []
    цк = quotes.колонки_цены(шапка, v2=v2) if hi >= 0 else {}
    # Валюта почти всегда написана только в шапке («Цена за ед., EUR»), а в
    # ячейках стоят голые числа.
    вк = quotes.валюта_заголовка(шапка, цк) if цк else None
    оговорка_файла = quotes.оговорка_колонок(шапка, v2=v2) if hi >= 0 else None
    низкая = False
    body = rows[hi + 1:] if hi >= 0 else rows
    # «СТОИМОСТЬ» БЕЗ «ЦЕНЫ» — только второй редакцией и только при колонке
    # количества: без количества проверить, цена это или сумма, нечем.
    if v2 and hi >= 0 and "price" not in цк and "qty" in cols:
        j_ст = quotes.колонка_стоимости(шапка, цк)
        if j_ст is not None:
            о = стоимость_как_цена(body, cols["qty"], j_ст, цк.get("total"))
            if о:
                цк = dict(цк, price=j_ст)
                вк = quotes.валюта_заголовка(шапка, цк)
                # Оговорка v2 об НДС говорила о сумме (цены не было) — теперь
                # цена из «Стоимости», и об НДС говорит её шапка.
                оговорка_файла = "; ".join(x for x in (quotes.оговорка_ндс(шапка[j_ст]), о)
                                           if x)
    # ЦЕНА ПО ПРАЙСУ — единственная цена шапки — рядом с суммой: только если
    # сходится с ней по файлу. Иначе сумма посчитана не по прайсу (скидка), и
    # цена предложения — её частное, как прежде. Прайсовую, при которой НДС лишь
    # упомянут, проверяет следующий шаг.
    if v2 and hi >= 0 and "price" not in цк and "total" in цк and "qty" in cols:
        j_пр = quotes.цена_по_прайсу(шапка, цк)
        if j_пр is not None and цена_сходится_с_суммой(body, cols["qty"], j_пр, цк["total"]):
            цк = dict(цк, price=j_пр)
            вк = quotes.валюта_заголовка(шапка, цк)
            # Об НДС говорит шапка цены, а если она молчит — шапка суммы: цена с
            # ней сошлась, значит той же природы («Сумма без НДС» — и цена без).
            оговорка_файла = (quotes.оговорка_ндс(шапка[j_пр])
                              or quotes.оговорка_ндс(шапка[цк["total"]]))
    # ЦЕНА, ПРИ КОТОРОЙ НДС ЛИШЬ УПОМЯНУТ («Цена, руб. (НДС 20%)»), рядом с
    # суммой без оговорки — только если сходится с ней по файлу. Иначе цена
    # выводится из суммы, как прежде.
    if v2 and hi >= 0 and "price" not in цк and "total" in цк and "qty" in cols:
        j_уп = quotes.цена_при_ндс(шапка, цк)
        if j_уп is not None and цена_сходится_с_суммой(body, cols["qty"], j_уп, цк["total"]):
            цк = dict(цк, price=j_уп)
            вк = quotes.валюта_заголовка(шапка, цк)
            оговорка_файла = quotes.оговорка_ндс(шапка[j_уп])
    # Листовая цена («List price»), которую v2 до 27.09.2026 брал ценой, а теперь
    # отдал цене предложения («Net price»): прежняя цена для проверки ниже и
    # последний довод о валюте (quotes.лист_был_ценой).
    j_лист = quotes.лист_был_ценой(шапка) if v2 and hi >= 0 else None
    # ЦЕНА НЕ СУММА СТРОКИ. Вторая редакция выбрала ценой не ту колонку, что
    # прежнее правило, — выбор проверяется арифметикой по файлу (цена_это_сумма).
    # Колонка, чьё число совпадает с суммой строки, ценой не становится: цена
    # остаётся в прежней колонке, а без прежней — выводится из суммы, как прежде.
    if v2 and hi >= 0 and "price" in цк and "qty" in cols:
        j_прежде = quotes.колонки_цены(шапка_прежде, v2=False).get("price")
        if j_прежде == цк.get("total"):
            j_прежде = None                   # суммой её назвала сама вторая редакция
        if j_прежде is None:
            # Прежнее правило английской шапки не читает — прежней ценой служит
            # листовая, которую v2 брал до 27.09.2026.
            j_прежде = j_лист
        # Опора — сумма строки v2, а без неё — сумма, которую суммой не взяли
        # (quotes.опорная_сумма): «Rate | Amount (13%VAT) | Line price» иначе
        # сверить не с чем.
        j_опора = цк.get("total")
        if j_опора is None:
            j_опора = quotes.опорная_сумма(шапка, цк)
        if j_прежде != цк["price"] and цена_это_сумма(body, cols["qty"], цк["price"],
                                                      j_прежде, j_опора):
            цк = {к: j for к, j in цк.items() if к != "price"}
            if j_прежде is not None:
                цк["price"] = j_прежде
            elif j_опора is not None:
                # Прежней цены нет — цена выводится делением опорной суммы, как
                # у прежнего правила.
                цк["total"] = j_опора
            вк = quotes.валюта_заголовка(шапка, цк) if цк else None
            # Оговорка v2 об НДС говорила об отвергнутой колонке — пишется своя:
            # о прежней колонке цены или, без неё, о сумме, из которой цена
            # выводится делением.
            j_ндс = цк.get("price", цк.get("total"))
            оговорка_файла = "; ".join(x for x in (
                quotes.оговорка_ндс(шапка[j_ндс]) if j_ндс is not None and j_ндс < len(шапка)
                else None,
                ОГОВОРКА_ЦЕНА_БЫЛА_СУММОЙ) if x)
    # НОВАЯ ПАРА «ЦЕНА — СУММА» ДОКАЗЫВАЕТСЯ ПО ФАЙЛУ. Два выбора 27.09.2026
    # меняют пару цены и суммы строки:
    #   • колонка скидки («Сумма скидки») больше не сумма строки
    #     (quotes.скидка_была_суммой) — сумма теперь другая колонка;
    #   • листовая цена («List price») уступила цене предложения
    #     (quotes.лист_был_ценой) — цена теперь другая колонка, а сумма могла
    #     быть парой листовой («Total list price», «Amount incl. VAT» при «List
    #     price incl. VAT»).
    # При колонке цены сумма берётся, только если сходится с ценой по файлу
    # (правило 13); иначе — первая другая сумма шапки, которая сходится; нет
    # такой — суммы у файла нет, и количество остаётся. Взятая без сверки, она
    # сняла бы количество у строк, где прежде оно оставалось (перебор части C:
    # 5 092 строки при простом исключении скидки; части D: 6 240 при листовой).
    # Без колонки цены новая сумма берётся всегда: цена выводится её делением,
    # а прежде — делением скидки.
    j_скидка = quotes.скидка_была_суммой(шапка) if v2 and hi >= 0 else None
    if (j_скидка is not None or j_лист is not None) and "price" in цк and "total" in цк \
            and "qty" in cols \
            and not цена_сходится_с_суммой(body, cols["qty"], цк["price"], цк["total"]):
        цк = {к: j for к, j in цк.items() if к != "total"}
        сошлась = next((j for j in quotes.суммы_шапки(шапка, цк)
                        if цена_сходится_с_суммой(body, cols["qty"], цк["price"], j)), None)
        if сошлась is not None:
            цк["total"] = сошлась
    # Валюту шапки прежде называли и листовая цена, и колонка скидки, взятая
    # суммой, — последним доводом они остаются: деньги в них те же, что в цене.
    for j_запас in (j_лист, j_скидка):
        if вк is None and j_запас is not None:
            вк = quotes.валюта_из(шапка[j_запас])
    # ЦЕНА ПО ПРАЙСУ ПРИ СКИДКЕ ОТДЕЛЬНОЙ КОЛОНКОЙ. Ценой взята прайсовая (другой
    # цены в шапке нет) или выведена из суммы по прайсу, а скидка названа рядом
    # и не нулевая: поставщик продаёт дешевле. Цена — всё равно его ответ, и она
    # пишется; но сравнивать её с ценами других как равную нельзя (CLAUDE.md,
    # «Цена и предложение»: «лучшая цена» — только среди строго сравнимых).
    # Отсюда оговорка и уверенность «low». Скидку в цену не пересчитываем: в
    # процентах она или в деньгах, на строку или на единицу — по шапке не сказано.
    j_ц = цк.get("price", цк.get("total"))
    if v2 and hi >= 0 and j_ц is not None and j_ц < len(шапка) \
            and quotes.цена_до_скидки(шапка[j_ц]):
        j_ск = quotes.колонка_скидки(шапка)
        if j_ск is not None and скидка_в_файле(body, j_ск):
            оговорка_файла = "; ".join(x for x in (оговорка_файла,
                                                   quotes.ОГОВОРКА_ПРАЙС_СКИДКА) if x)
            низкая = True
    # ТАБЛИЦА БЕЗ ШАПКИ: колонки по тройке «кол-во × цена = сумма».
    тройка = колонки_без_шапки(body) if без_шапки and hi < 0 else None
    if тройка:
        цк = {"price": тройка["price"], "total": тройка["total"]}
        оговорка_файла = quotes.ОГОВОРКА_БЕЗ_ШАПКИ
        низкая = True
    # Прежнее правило — для сравнения на одних байтах.
    цк_прежде = (quotes.колонки_цены(шапка_прежде, v2=False) if hi >= 0 else {}) \
        if сравнивать else {}
    вк_прежде = quotes.валюта_заголовка(шапка_прежде, цк_прежде) if цк_прежде else None
    out: list[dict] = []
    for row in body:
        if not row:
            continue
        joined = " ".join(row).strip()
        if len(joined) < 6 or NOISE_ROW.match(joined):
            continue
        rec: dict = {}
        if cols:
            def get(key: str) -> str:
                j = cols.get(key, -1)
                return row[j].strip() if 0 <= j < len(row) else ""
            rec["item_name"] = get("item_name")
            rec["part_number"] = get("part_number")
            # Ячейка артикула, в которой стоит только марка, размер или стандарт
            # («SS316», «19mm», «ГОСТ 8752-79»), артикула не несёт. Код тогда
            # ищется в НАИМЕНОВАНИИ, а не во всей строке: в строке стоят
            # количество, цена и сумма, и голое «25600» стало бы артикулом.
            if not docfilter.код_правдоподобен(rec["part_number"]):
                rec["part_number"] = docfilter.part_number_of(get("item_name"))
                rec["_код_искали"] = True
            rec["oem"] = get("oem")
            rec["unit"] = get("unit")
            rec["qty"], rec["_кол_во_отказ"] = количество_ячейки(get("qty"))
        elif тройка:
            # Наименование — самая длинная ячейка ВНЕ тройки и с буквами: иначе
            # «1 250 000,00» длиннее «Болт М12» и стало бы наименованием. Мерило —
            # буквы, а не число_из: «Насос ЦНС 38-176» число в себе несёт.
            занятые = set(тройка.values())
            текстовые = [c for j, c in enumerate(row)
                         if j not in занятые and c and БУКВА.search(c)]
            rec["item_name"] = max(текстовые, key=len) if текстовые else ""
            rec["part_number"] = ""
            rec["oem"] = ""
            rec["unit"] = ""
            j = тройка["qty"]
            rec["qty"], rec["_кол_во_отказ"] = количество_ячейки(
                row[j] if j < len(row) else "")
        else:
            cand = max(row, key=lambda c: len(c)) if row else ""
            rec["item_name"] = cand
            rec["part_number"] = ""
            rec["oem"] = ""
            rec["unit"] = ""
            rec["qty"] = None
        name = (rec.get("item_name") or "").strip()
        if len(name) < 4 or name.isdigit():
            continue
        if not rec.pop("_код_искали", False) and not rec.get("part_number"):
            # Прежнее выражение искало по joined.upper() и принимало за артикул
            # дату 01.09.2026, номер закона 223-ФЗ и любое пятизначное число.
            # docfilter.part_number_of отбрасывает даты, номера пунктов, годы и
            # разряды тысяч. Замена действует только на новые разборы: пересчёт
            # накопленных 113 769 парт-номеров — это UPDATE на полтора миллиона
            # строк с пересчётом fts, отдельная задача.
            rec["part_number"] = docfilter.part_number_of(joined)
        rec["_row"] = joined[:600]
        # Цена берётся только из названной колонки. Сумма строки ценой не
        # становится: из неё цена выводится делением на количество, и такая
        # строка помечена как выведенная (library/quotes.py).
        rec["_цена"] = quotes.цена_строки(row, цк, rec.get("qty"), вк,
                                          оговорка_файла=оговорка_файла,
                                          низкая=низкая) if цк else None
        if сравнивать:
            # Количество прежнего правила — из колонки шапки; у таблицы без
            # шапки его не было вовсе, но и цены тогда не было.
            rec["_цена_прежде"] = (quotes.цена_строки(row, цк_прежде, rec.get("qty"),
                                                     вк_прежде)
                                   if цк_прежде else None)
        сверить_количество(rec, ндс=склеена)
        # Условия из СВОИХ колонок этой позиции: базис, оплата, срок изготовления,
        # срок поставки. Они главнее общих условий файла — они про эту позицию.
        rec["_из_строки"] = offer_terms.из_строки(row, цк) if цк else None
        out.append(rec)
        if len(out) >= 3000:
            break
    return out


def collect_refs(days: int, shard: int = 0, shards: int = 1,
                 границы: tuple[int, int | None] | None = None) -> list[dict]:
    """Ссылки на все вложения сделок за период.

    Берём их через crm.item.list (entityTypeId=2), а НЕ через crm.deal.list.
    Разница решающая: crm.deal.list отдаёт у файловых полей только ссылки на
    страницы портала (`crm.deal.show/show_file.php`, `crm_show_file.php`), а те
    требуют сессии пользователя и вебхуку возвращают страницу входа с кодом 200 —
    отсюда прежние «не скачался» на всей выборке. Универсальный item-метод отдаёт
    у тех же полей `urlMachine`: REST-ссылку с одноразовым токеном, по которой
    файл приходит как есть. Проверено на портале 08.09.2026: 22 181 вложение
    у 2 928 сделок года, скачивание отдаёт PDF, XLSX и DOCX.
    """
    if ИНКРЕМЕНТ and shard == 0:
        return collect_refs_increment()
    if ИНКРЕМЕНТ:
        print(f"ежедневный проход идёт одной частью — часть {shard + 1} не нужна", flush=True)
        return []
    since = (datetime.now(timezone.utc) - timedelta(days=days)).strftime("%Y-%m-%dT00:00:00+03:00")
    ffields, названия = файловые_поля_сделки()
    # ЧАСТЬ ЧИТАЕТ СВОЙ ДИАПАЗОН НОМЕРОВ СДЕЛОК, А НЕ ВЕСЬ СПИСОК. Двенадцать
    # частей, каждая из которых перечисляет ВСЕ сделки, — двенадцатикратная
    # нагрузка на портал одним залпом. Прежде список делился по остатку уже
    # ПОСЛЕ полного перечисления, и это спасало только чтение файловых полей:
    # 24.09.2026 холостой переразбор сделок за 3 650 дней умер в 44 частях из 50
    # с HTTP 429 на самом crm.deal.list. Теперь, как у карточек запросов
    # (collect_refs_rfq), часть узнаёт наибольший номер и читает только смежный
    # кусок [низ+1; верх]: сделка лежит ровно в одном диапазоне, значит ни один
    # файл не теряется и не читается дважды.
    фильтр = {">=DATE_CREATE": since}
    if shards > 1 and границы is not None:
        # ГРАНИЦЫ ПРИШЛИ ИЗВНЕ — от переразбора, который знает, у каких сделок
        # его файлы, и делит их поровну по ЧИСЛУ ФАЙЛОВ (reparse.границы_по_файлам).
        # Разбиение по-прежнему одно и смежное: сделка лежит ровно в одной части.
        низ, верх = границы
        фильтр[">ID"] = низ
        if верх is not None:
            фильтр["<=ID"] = верх
        print(f"часть {shard + 1} из {shards}: сделки с номером от {низ + 1} "
              f"до {верх if верх is not None else 'конца'} (границы по файлам)", flush=True)
    elif shards > 1:
        # crm.deal.list — старый метод: поле «ID» заглавными, и bx_max_id (он
        # для crm.item.list, «id») здесь молча вернул бы 0, а с нулём каждая
        # часть читала бы весь список — ровно то, от чего уходим.
        j = bx("crm.deal.list", {"select": ["ID"], "order": {"ID": "DESC"}, "start": -1})
        макс = int(((j.get("result") or [{}])[0] or {}).get("ID") or 0)
        if not макс:
            raise RuntimeError("не удалось узнать наибольший номер сделки: "
                               "без него часть прочитала бы весь портал")
        низ, верх = диапазон_части(макс, shard, shards)
        фильтр[">ID"] = низ
        if верх is not None:
            фильтр["<=ID"] = верх
        print(f"часть {shard + 1} из {shards}: сделки с номером от {низ + 1} "
              f"до {верх if верх is not None else 'конца'} (всего до {макс})", flush=True)
    # ПО КЛЮЧУ И БЕЗ ПОДСЧЁТА (start=-1), А НЕ СМЕЩЕНИЕМ. Смещение заставляет
    # портал на КАЖДОЙ странице считать total по всему фильтру, а это время
    # метода: у него свой предел 420 с за 10 минут на вебхук, общий для всех
    # частей. 24.09.2026 пятьдесят частей исчерпали его за две минуты — HTTP 429
    # на crm.deal.list и есть OPERATION_TIME_LIMIT (apidocs.bitrix24.ru/limits.html).
    # НАЗВАНИЕ, КОМПАНИЯ И СТАДИЯ СДЕЛКИ — В ТОМ ЖЕ SELECT (deal_links.ПОЛЯ_СДЕЛКИ):
    # заказчик сделки нужен недельному своду, а страницы те же — ни одного
    # лишнего запроса. Пишутся в lib_deals после обхода (записать_связи).
    deals = bx_all_by_id("crm.deal.list", {"filter": фильтр,
                                           "select": list(deal_links.ПОЛЯ_СДЕЛКИ)},
                         ключ="ID")
    запомнить_сделки(deals)
    ids = [int(d["ID"]) for d in deals]
    print(f"сделок за {days} дн.: {len(ids)}"
          + (f" (часть {shard + 1} из {shards})" if shards > 1 else "")
          + f" · файловых полей: {len(ffields)}", flush=True)
    return ссылки_сделок(ids, ffields, названия)


def файловые_поля_сделки() -> tuple[list[str], dict[str, str]]:
    """Коды файловых полей сделки и их названия. Один запрос."""
    fields = ((bx("crm.item.fields", {"entityTypeId": 2}).get("result") or {}).get("fields") or {})
    ffields = [k for k, v in fields.items() if v.get("type") == "file"]
    # НАЗВАНИЕ ПОЛЯ — РЯДОМ С КОДОМ. По названию определяется СТОРОНА документа
    # (library/doc_side.py), а в базе названия нет: там только код. Без стороны
    # «поле сделки» остаётся одной кучей, в которой заявка заказчика лежит вместе с
    # нашим же исходящим ТКП и с предложениями поставщиков — замер 22.09.2026:
    # настоящий спрос 41,7 % строк, остальное спросом не является.
    названия = {k: (fields[k].get("title") or "") for k in ffields}
    return ffields, названия


def collect_refs_increment() -> list[dict]:
    """Ежедневный проход по сделкам: изменённые после отметки плюс новые по номеру.

    crm.deal.list по ключу без подсчёта (start=-1): страница — пятьдесят
    сделок, день — обычно одна-две страницы.
    """
    import increment
    с, после_id = increment.окно_из_базы("deals")
    поля = list(deal_links.ПОЛЯ_СДЕЛКИ)
    изменённые = bx_all_by_id("crm.deal.list",
                              {"filter": {">=DATE_MODIFY": increment.для_фильтра(с)},
                               "select": поля}, ключ="ID")
    новые = (bx_all_by_id("crm.deal.list", {"filter": {}, "select": поля},
                          с_id=после_id, ключ="ID") if после_id else [])
    сделки = increment.объединить(изменённые, новые, ключ="ID")
    запомнить_сделки(сделки)
    ids = [int(d["ID"]) for d in сделки]
    print(f"сделок изменено: {len(изменённые)} · новых по номеру: {len(новые)}"
          f" · к чтению вложений: {len(ids)}", flush=True)
    if not ids:
        return []
    ffields, названия = файловые_поля_сделки()
    return ссылки_сделок(ids, ffields, названия)


def ссылки_сделок(ids: list[int], ffields: list[str], названия: dict[str, str]) -> list[dict]:
    """Вложения файловых полей данных сделок — пачками по пятьдесят."""
    refs: list[dict] = []
    # НАША КОМПАНИЯ СДЕЛКИ — тем же запросом, что и файлы (mycompanyId в select):
    # ни одного лишнего обращения к порталу.
    сделок = с_нашей = чужих_id = 0
    for i in range(0, len(ids), 50):
        # createdTime — в том же select: по нему судится заголовок даты закачки
        # (дата_заголовка), ни одного лишнего запроса.
        j = bx("crm.item.list", {"entityTypeId": 2, "filter": {"@id": ids[i:i + 50]},
                                 "select": ["id", "mycompanyId", "createdTime"] + ffields,
                                 "start": 0})
        for x in (j.get("result") or {}).get("items") or []:
            сделок += 1
            наша = наша_компания(x.get("mycompanyId"))
            с_нашей += bool(наша)
            чужих_id += bool(crm_id(x.get("mycompanyId")) and not наша)
            for f in ffields:
                v = x.get(f)
                if not v:
                    continue
                for fo in (v if isinstance(v, list) else [v]):
                    if isinstance(fo, dict) and fo.get("urlMachine"):
                        refs.append({"deal": str(x["id"]), "field": f,
                                     "field_title": названия.get(f) or None,
                                     "origin": "поле сделки", "fo": fo,
                                     "our_company": наша,
                                     "owner_created": x.get("createdTime")})
    print(f"вложений в полях сделок: {len(refs)}", flush=True)
    print(f"сделок с нашей компанией (mycompanyId): {с_нашей} из {сделок}"
          f" · mycompanyId вне списка наших: {чужих_id}", flush=True)
    return refs


def ключи_брендов(v) -> str:
    """Ключи брендов карточки списком через запятую.

    Поле многозначное, и первый бренд в нём — не «главный», а просто первый:
    берём все. Имена здесь НЕ разрешаем, как и у поставщика: сопоставление
    ключа со справочником — отдельный проход, а догадка вместо связи хуже
    пустоты.
    """
    значения = v if isinstance(v, list) else ([v] if v else [])
    ключи: list[str] = []
    for z in значения:
        k = crm_id(z)
        if k and str(k) not in ключи:
            ключи.append(str(k))
    return ",".join(ключи)


def ключ_ссылки(ref: dict) -> str:
    """lib_files.file_id ссылки. Письма несут его явно («mail:<номер Диска>»):
    номер файла Диска и номер вложения поля CRM — разные ряды чисел, и голый
    номер Диска совпал бы с чужим file_id. У полей — id объекта вложения."""
    if ref.get("file_id"):
        return str(ref["file_id"])
    fo = ref.get("fo") or {}
    return str(fo.get("id") or fo.get("ID") or "")


def без_повторов(refs: list[dict]) -> tuple[list[dict], int]:
    """Ссылки на вложения без повторов по id файла плюс число отброшенных.

    Ключ — id объекта вложения, тот же, что уходит в lib_files.file_id. Именно
    по нему таблица конфликтует, и именно повтор внутри одного пакета роняет
    вставку целиком.
    """
    видели: set[str] = set()
    out: list[dict] = []
    дублей = 0
    for r in refs:
        fid = ключ_ссылки(r)
        if not fid:
            out.append(r)          # без id отсеять нельзя, пусть идёт как есть
            continue
        if fid in видели:
            дублей += 1
            continue
        видели.add(fid)
        out.append(r)
    return out, дублей


def диапазон_части(макс: int, shard: int, shards: int) -> tuple[int, int | None]:
    """Границы идентификаторов для своей части: (после, включительно по).

    Диапазоны СМЕЖНЫЕ, а не по остатку от деления: обход идёт по возрастанию
    ключа, и только смежный кусок можно прочитать, не трогая чужие страницы.

    Плотность идентификаторов неравномерна — где-то пропуски, где-то густо, —
    поэтому части выходят разного размера. Это допустимо: делится нагрузка на
    портал, а она пропорциональна прочитанным страницам, а не ровности долей.
    Сколько досталось каждой части, прогон печатает — ровность видно числом.
    """
    if shards <= 1 or макс <= 0:
        return 0, None
    шаг = макс // shards + 1
    низ = shard * шаг
    верх = макс if shard == shards - 1 else низ + шаг
    return низ, верх


def collect_refs_rfq(days: int, shard: int = 0, shards: int = 1) -> list[dict]:
    """Ссылки на вложения карточек запросов поставщикам (СП-166).

    БЕРЁМ ТОЛЬКО ФАЙЛЫ СО СТОРОНЫ ПОСТАВЩИКА. «Request file» — то, что отправили
    мы; разобрать его как котировку значит объявить прокотированным собственный
    запрос. Список полей — общий с замерами (scripts/quote_coverage.py).

    Механика та же, что у сделок: crm.item.list отдаёт у файловых полей
    urlMachine — REST-ссылку с одноразовым токеном. Разница только в том, какую
    сущность спрашиваем и какие поля берём.
    """
    # ФИЛЬТР ПО ДАТЕ НА СТОРОНЕ ПОРТАЛА СЪЕДАЛ ДВЕ ТРЕТИ КАРТОЧЕК. Замер
    # 21.09.2026: с «>=createdTime» за 7 300 дней (двадцать лет) приходило 7 150
    # карточек, а замеры котировок, читающие ту же сущность БЕЗ фильтра, видят
    # 21 865. Двадцатилетнее окно отсечь ничего не может — значит отсекал сам
    # фильтр: у карточки либо нет createdTime, либо сравнение по нему у СП-166
    # работает не так, как ожидается. Цена ошибки — две трети котировок молча
    # мимо разбора.
    #
    # Поэтому читаем ВСЁ, как это делают scripts/quote_coverage.py и
    # scripts/supplier_responsiveness.py, а окно применяем у себя. Карточку без
    # даты окно НЕ отбрасывает: недоказанное «старая» дешевле потерянной цены.
    if ИНКРЕМЕНТ and shard == 0:
        return collect_refs_rfq_increment()
    if ИНКРЕМЕНТ:
        print(f"ежедневный проход идёт одной частью — часть {shard + 1} не нужна", flush=True)
        return []
    поля = list(ПОЛЯ_КП)
    # Обход по ключу, а не по смещению: на смещении приходило 7 750 карточек
    # вместо 21 865, и без единой ошибки (замер 21.09.2026).
    низ, верх = (0, None)
    if shards > 1:
        макс = bx_max_id("crm.item.list", {"entityTypeId": SPA_RFQ})
        низ, верх = диапазон_части(макс, shard, shards)
        print(f"часть {shard + 1} из {shards}: карточки с id от {низ + 1} "
              f"до {верх if верх is not None else 'конца'} (всего до {макс})",
              flush=True)
    # ПОЛЕ НАШЕГО ЗАПРОСА И НАША КОМПАНИЯ — В ТОМ ЖЕ SELECT. Битрикс отдаёт только
    # то, что попросили: до 23.09.2026 «Request file» в select не было, и счётчик
    # «карточек с нашим «Request file»» печатал ноль на живом портале всегда.
    # Файлы этого поля по-прежнему НЕ разбираются (разбор нашего запроса меняет
    # замеры спроса и требует отдельного замера) — только считаются.
    карточки = bx_all_by_id("crm.item.list",
                            {"entityTypeId": SPA_RFQ, "select": ПОЛЯ_КАРТОЧКИ + поля},
                            с_id=низ, до_id=верх)
    # СВЯЗЬ КАРТОЧКИ СО СДЕЛКОЙ — ДО ОКНА ДАТ: карточки уже прочитаны, и старая
    # карточка связана со сделкой не хуже свежей.
    запомнить_карточки(карточки)
    всего = len(карточки)
    без_даты = 0
    if days and days > 0:
        порог = (datetime.now(timezone.utc) - timedelta(days=days)).strftime("%Y-%m-%d")
        в_окне = []
        for x in карточки:
            д = str(x.get("createdTime") or "")[:10]
            if not д:
                без_даты += 1
                в_окне.append(x)
            elif д >= порог:
                в_окне.append(x)
        карточки = в_окне
    print(f"карточек запросов: всего {всего}, в окне {days} дн. — {len(карточки)}"
          f" (без даты {без_даты}, взяты) · полей КП: {len(поля)}", flush=True)
    return ссылки_карточек(карточки, поля)


#: Поля карточки запроса, кроме файловых полей КП: дата, наша компания,
#: поставщик, бренды и наш «Request file» (только для счёта). Сделка карточки
#: (parentId2) и её название (title) — для связи lib_rfq_cards
#: (library/deal_links.py): в том же select, ни одного лишнего запроса.
ПОЛЯ_КАРТОЧКИ = ["id", "createdTime", "mycompanyId", ПОЛЕ_ПОСТАВЩИКА, ПОЛЕ_БРЕНДОВ, ПОЛЕ_ЗАПРОСА,
                 deal_links.ПОЛЕ_СДЕЛКИ_КАРТОЧКИ, "title"]


# ── СВЯЗИ КАРТОЧКА → СДЕЛКА → ЗАКАЗЧИК ИЗ ТОГО ЖЕ ОБХОДА ─────────────────────
# Обход кладёт сюда строки lib_rfq_cards и lib_deals (deal_links.строка_*),
# разбор пишет их одним пакетом после обхода (записать_связи). Ключ — номер:
# карточка, прочитанная дважды (изменённая и новая по номеру), даёт одну строку.
_СВЯЗИ: dict[str, dict[str, tuple]] = {"карточки": {}, "сделки": {}}


def запомнить_карточки(карточки: list[dict]) -> None:
    for x in карточки:
        r = deal_links.строка_карточки(x)
        if r:
            _СВЯЗИ["карточки"][r[0]] = r


def запомнить_сделки(сделки: list[dict]) -> None:
    for x in сделки:
        r = deal_links.строка_сделки(x)
        if r:
            _СВЯЗИ["сделки"][r[0]] = r


def ключ_прогона_связей() -> str:
    """run_id строк связи из разбора: номер прогона Actions, источник и часть."""
    return (f"ix-{os.environ.get('GITHUB_RUN_ID') or int(time.time())}"
            f"-{SOURCE}-p{SHARD}")


def записать_связи() -> None:
    """Связи из обхода — в базу, одним пакетом. В журнал только агрегаты.

    ВСПОМОГАТЕЛЬНАЯ ЗАПИСЬ РАЗБОР НЕ РОНЯЕТ: нет таблиц (схему ещё не
    применили) или сбой записи — предупреждение, и разбор файлов идёт дальше.
    Связь досчитает library/backfill_deal_links.py, а файлы — только разбор.
    """
    карточки = list(_СВЯЗИ["карточки"].values())
    сделки = list(_СВЯЗИ["сделки"].values())
    if not карточки and not сделки:
        return
    к_всего, к_связь = deal_links.счёт_python(карточки, 1)
    с_всего, с_связь = deal_links.счёт_python(сделки, 2)
    try:
        conn = connect()
        try:
            with conn.cursor() as cur:
                итог = deal_links.записать_свежие(cur, карточки, сделки, ключ_прогона_связей(),
                                                  psycopg2.extras.execute_values)
            conn.commit()
        finally:
            conn.close()
    except psycopg2.Error as e:
        print(f"::warning::связи карточка → сделка не записаны ({type(e).__name__}) — "
              "разбор идёт дальше; историю досчитает library/backfill_deal_links.py",
              flush=True)
        return
    if итог is None:
        print("::warning::нет таблиц lib_rfq_cards и lib_deals — примените "
              "library/supabase/deal_links_schema.sql прогоном «ZIP base — apply DB "
              "migrations»; разбор идёт без записи связей", flush=True)
        return
    print(f"связи: карточек {к_всего} (со сделкой {к_связь}) · сделок {с_всего} "
          f"(с компанией {с_связь}) · вставлено или изменено: карточек {итог[0]}, "
          f"сделок {итог[1]}", flush=True)


def collect_refs_rfq_increment() -> list[dict]:
    """Ежедневный проход по карточкам запросов: изменённые после отметки
    (updatedTime — карточка меняется, когда поставщик прислал КП и файл лёг в
    поле) плюс новые по номеру выше прошлого наибольшего."""
    import increment
    поля = list(ПОЛЯ_КП)
    с, после_id = increment.окно_из_базы("rfq")
    параметры = {"entityTypeId": SPA_RFQ, "select": ПОЛЯ_КАРТОЧКИ + поля}
    изменённые = bx_all_by_id("crm.item.list",
                              {**параметры, "filter": {">=updatedTime": increment.для_фильтра(с)}})
    новые = (bx_all_by_id("crm.item.list", параметры, с_id=после_id) if после_id else [])
    карточки = increment.объединить(изменённые, новые)
    запомнить_карточки(карточки)
    print(f"карточек запросов изменено: {len(изменённые)} · новых по номеру: {len(новые)}"
          f" · к чтению вложений: {len(карточки)}", flush=True)
    return ссылки_карточек(карточки, поля)


def ссылки_карточек(карточки: list[dict], поля: list[str]) -> list[dict]:
    """Вложения КП от поставщиков с данных карточек, с поставщиком и брендами."""
    refs: list[dict] = []
    свои = 0
    свои_и_кп = 0
    без_поставщика = 0
    без_брендов = 0
    с_нашей = чужих_id = 0
    for x in карточки:
        # Компания-поставщик известна ПРЯМО ЗДЕСЬ, и связать цену с ней надо
        # сейчас: отдельный проход позже означал бы второе сплошное чтение
        # портала ради того, что уже держим в руках.
        компания = crm_id(x.get(ПОЛЕ_ПОСТАВЩИКА))
        if not компания:
            без_поставщика += 1
        бренды = ключи_брендов(x.get(ПОЛЕ_БРЕНДОВ))
        if not бренды:
            без_брендов += 1
        # От какой НАШЕЙ компании заведена карточка — из системы, не из текста.
        наша = наша_компания(x.get("mycompanyId"))
        с_нашей += bool(наша)
        чужих_id += bool(crm_id(x.get("mycompanyId")) and not наша)
        запрос = x.get(ПОЛЕ_ЗАПРОСА) or []
        ид_запроса = {str(fo.get("id")) for fo in (запрос if isinstance(запрос, list) else [запрос])
                      if isinstance(fo, dict) and fo.get("id")}
        for f in поля:
            v = x.get(f)
            if not v:
                continue
            for fo in (v if isinstance(v, list) else [v]):
                if isinstance(fo, dict) and fo.get("urlMachine"):
                    refs.append({"deal": str(x["id"]), "field": f,
                                 # Название поля КП известно из константы: ПОЛЯ_КП
                                 # держит код и название рядом. Отдельного вызова
                                 # crm.item.fields здесь не нужно.
                                 "field_title": ПОЛЯ_КП.get(f) or None,
                                 "origin": "поле запроса", "fo": fo,
                                 "company": str(компания) if компания else None,
                                 "brands": бренды or None,
                                 "our_company": наша,
                                 # ДАТА СОЗДАНИЯ КАРТОЧКИ — запасная дата
                                 # квотации, когда в самом КП её нет
                                 # (library/quote_date.py). Уже в select:
                                 # ни одного лишнего запроса к порталу.
                                 "card_created": x.get("createdTime")})
                    # Один файл и в поле КП, и в нашем «Request file» — чья это
                    # цена, система не говорит. Пока только считаем.
                    свои_и_кп += str(fo.get("id")) in ид_запроса
        if x.get(ПОЛЕ_ЗАПРОСА):
            свои += 1
    # ОДИН ФАЙЛ — ОДНА ССЫЛКА. Вложение висит на карточке, но одно и то же
    # вложение встречается у нескольких карточек и в нескольких полях сразу.
    # Прогон 22.09.2026 упал на этом: «ON CONFLICT DO UPDATE cannot affect row a
    # second time» — PostgreSQL не даёт обновить одну строку дважды в одном
    # операторе, а lib_files конфликтует по file_id. На 46 файлах дубль не
    # попадался, на 7 523 попался. Помимо падения дубль стоил бы второй закачки
    # того же файла и удвоенных строк цены.
    #
    # Оставляем первую ссылку: поля карточки перебираются в постоянном порядке,
    # поэтому выбор воспроизводим. Число отброшенных печатается — молчаливый
    # отсев скрыл бы, что портал отдаёт файл по нескольку раз.
    refs, дублей = без_повторов(refs)
    print(f"вложений КП от поставщиков: {len(refs)}"
          f" · повторов одного файла отброшено: {дублей}"
          f" · карточек с нашим «Request file» (не берём): {свои}"
          f" · файлов и в поле КП, и в «Request file»: {свои_и_кп}", flush=True)
    print(f"карточек с нашей компанией (mycompanyId): {с_нашей} из {len(карточки)}"
          f" · mycompanyId вне списка наших: {чужих_id}", flush=True)
    print(f"карточек без указанного поставщика: {без_поставщика} из {len(карточки)}"
          " — их цены лягут без привязки к компании", flush=True)
    print(f"карточек без указанного бренда: {без_брендов} из {len(карточки)}"
          " — по ним разрез «чей это» даст только то, что написано в файле",
          flush=True)
    return refs


def is_login_page(b: bytes) -> bool:
    """Портал отдаёт страницу входа с кодом 200 — по коду ответа её не отличить.
    Отличаем по содержимому, иначе HTML формы логина уходит в разбор как файл."""
    head = b.lstrip()[:512].lower()
    return head.startswith(b"<!doctype htm") or head.startswith(b"<html")


#: Сколько раз повторять закачку одного адреса. Прежде попытка была ОДНА, и любая
#: сетевая осечка давала «не скачался» навсегда: замер 23.09.2026 — 999 файлов с
#: этим статусом и НИ ОДНОЙ причины, потому что ошибка глоталась целиком.
ПОПЫТОК_ЗАКАЧКИ = int(os.environ.get("DOWNLOAD_RETRIES", "3") or 3)

#: Коды ответа, которые лечатся повтором. Остальные повторять бессмысленно: 404
#: не станет двухсотым, сколько его ни проси.
ПОВТОРИМЫЕ_КОДЫ = frozenset({408, 425, 429, 500, 502, 503, 504})


def скачать_адрес(u: str, заголовки: dict | None = None) -> tuple[bytes | None, str]:
    """Одна ссылка с повторами. Возвращает (байты, причина неудачи).

    С `заголовки` удачная закачка кладёт туда заголовки ответа, по которым
    судится дата файла у источника (ЗАГОЛОВКИ_ДАТЫ, дата_заголовка): ни одного
    лишнего запроса — это тот же ответ, что принёс файл.

    ПРИЧИНА ВОЗВРАЩАЕТСЯ, А НЕ ГЛОТАЕТСЯ. По «не скачался» без причины чинить
    нечего: не видно, протух ли токен, отказал портал, пришла ли вместо файла
    страница входа. В журнал и в базу идут код ответа и имя класса исключения —
    ни адресов, ни имён файлов (правило 17).

    ЗАКАЧКА — ТОЖЕ ЗАПРОС К ПОРТАЛУ. urlMachine ведёт на REST-метод
    crm.controller.item.getFile того же вебхука, поэтому каждая закачка идёт
    через очередь клиента (общий бюджет частоты) и считается в сводке
    нагрузки. Прежде двенадцать потоков каждой части качали мимо очереди.
    Отказ по лимиту (429 — время метода, 503 — частота) пережидается бюджетом
    ожидания клиента, а не тремя попытками по 1–2 с: метод, заблокированный по
    времени, освобождается до десяти минут.
    """
    последняя = "не пробовали"
    к = клиент()
    попытка = лимит = 0
    ждали = 0.0
    while попытка < ПОПЫТОК_ЗАКАЧКИ:
        к.before_request("файл")
        try:
            r = requests.get(str(u), timeout=90)
        except Exception as e:                                          # noqa: BLE001
            последняя = f"сеть: {type(e).__name__}"
        else:
            if r.status_code == 200 and len(r.content) > 200 and not is_login_page(r.content):
                if заголовки is not None:
                    заголовки.update(заголовки_даты(r))
                return r.content, ""
            if r.status_code == 200 and is_login_page(r.content):
                # Токен протух: повтор по тому же адресу даст ту же страницу входа.
                return None, "вместо файла страница входа"
            if r.status_code == 200:
                return None, f"тело {len(r.content)} байт — меньше порога"
            последняя = f"код {r.status_code}"
            if r.status_code in (429, 503):
                прождано = к.wait_limit(лимит, ждали, "закачка файла", r)
                if прождано is None:
                    return None, последняя + " (лимит портала дольше бюджета ожидания)"
                ждали += прождано
                лимит += 1
                continue
            if r.status_code not in ПОВТОРИМЫЕ_КОДЫ:
                return None, последняя
        попытка += 1
        if попытка < ПОПЫТОК_ЗАКАЧКИ:
            time.sleep(2 ** (попытка - 1))
    return None, последняя


def заголовки_адреса(u: str) -> tuple[dict | None, str]:
    """Заголовки ответа закачки БЕЗ тела файла: (заголовки, причина неудачи).

    Нужна досчёту даты загрузки (library/backfill_file_dates.py): файл уже
    разобран, качать его целиком ради заголовка — зря гонять мегабайты. Запрос
    тот же, что у скачать_адрес, и стоит в той же очереди портала: ответ
    читается потоком, берутся первые байты — отличить страницу входа, чьи
    заголовки о файле не говорят ничего, — и соединение закрывается.

    Повторы и ожидание лимита — ровно как у скачать_адрес (две закачки одного
    адреса правятся вместе, правило 14); своих пауз против лимита здесь нет."""
    последняя = "не пробовали"
    к = клиент()
    попытка = лимит = 0
    ждали = 0.0
    while попытка < ПОПЫТОК_ЗАКАЧКИ:
        к.before_request("файл")
        try:
            r = requests.get(str(u), timeout=90, stream=True)
        except Exception as e:                                          # noqa: BLE001
            последняя = f"сеть: {type(e).__name__}"
        else:
            try:
                if r.status_code == 200:
                    try:
                        начало = next(r.iter_content(512), b"")
                    except Exception as e:                              # noqa: BLE001
                        return None, f"сеть: {type(e).__name__}"
                    if is_login_page(начало):
                        return None, "вместо файла страница входа"
                    return заголовки_даты(r), ""
                последняя = f"код {r.status_code}"
            finally:
                r.close()
            if r.status_code in (429, 503):
                прождано = к.wait_limit(лимит, ждали, "заголовки файла", r)
                if прождано is None:
                    return None, последняя + " (лимит портала дольше бюджета ожидания)"
                ждали += прождано
                лимит += 1
                continue
            if r.status_code not in ПОВТОРИМЫЕ_КОДЫ:
                return None, последняя
        попытка += 1
        if попытка < ПОПЫТОК_ЗАКАЧКИ:
            time.sleep(2 ** (попытка - 1))
    return None, последняя


def download(fo: dict, rec: dict | None = None) -> bytes | None:
    """Файл по любой из ссылок вложения. Причина неудачи кладётся в `rec`.

    Порядок ссылок прежний: urlMachine с одноразовым токеном первой, disk.file.get
    последним — он стоит запроса к порталу.
    """
    if "тело" in fo:
        # Тело письма уже пришло в списке дел (library/mail_source.тело_письма):
        # скачивать нечего, и портал за него не платит.
        if fo["тело"]:
            return fo["тело"]
        if rec is not None:
            rec["reason"] = "пустое тело письма"
        return None
    причины: list[str] = []
    # Заголовки удачного ответа — в rec: по ним дата_у_источника судит дату
    # загрузки файла, не тратя на неё запроса.
    заголовки: dict = {}
    for key in ("urlMachine", "downloadUrl", "url", "URL_MACHINE", "DOWNLOAD_URL"):
        u = fo.get(key)
        if not u:
            continue
        тело, почему = скачать_адрес(str(u), заголовки)
        if тело:
            if rec is not None:
                rec["заголовки_закачки"] = заголовки
            return тело
        причины.append(f"{key}: {почему}")
    fid = fo.get("id") or fo.get("ID")
    if fid:
        try:
            u = (bx_файлов("disk.file.get", {"id": fid}).get("result") or {}).get("DOWNLOAD_URL")
        except Exception as e:                                          # noqa: BLE001
            причины.append(f"disk.file.get: {код_ошибки_портала(e)}")
            u = None
        if u:
            тело, почему = скачать_адрес(u, заголовки)
            if тело:
                if rec is not None:
                    rec["заголовки_закачки"] = заголовки
                return тело
            причины.append(f"disk.file.get: {почему}")
        elif not причины or not причины[-1].startswith("disk.file.get"):
            # Ответ без ссылки — не «ссылок нет вовсе»: номер файла был.
            причины.append("disk.file.get: ответил без ссылки")
    if rec is not None:
        rec["reason"] = "; ".join(причины)[:400] or "ссылок на файл нет вовсе"
    return None


#: Код отказа портала: заглавные буквы и подчёркивания, и только они. Описание
#: рядом с кодом может нести идентификатор файла — в журнал идёт код (правило 17).
КОД_ПОРТАЛА = re.compile(r"[A-Z][A-Z0-9_]{2,59}")


def код_ошибки_портала(e: Exception) -> str:
    найдено = КОД_ПОРТАЛА.search(str(e))
    return найдено.group(0) if найдено else type(e).__name__


def применить_условия(items: list[dict], весь_текст: str) -> None:
    """Свод коммерческих условий по каждой позиции КП: значение и ОТКУДА оно.

    ОТДЕЛЬНОЙ ФУНКЦИЕЙ, ЧТОБЫ ЕЁ МОЖНО БЫЛО ПРОВЕРИТЬ. Внутри handle() этот шаг
    стоит за скачиванием файла, и тест на него пришлось бы писать через подмену
    сети — то есть проверять копию логики вместо самой логики.

    ОБЩИЕ УСЛОВИЯ РАЗБИРАЮТСЯ ОДИН РАЗ НА ФАЙЛ. Блок условий под таблицей один, а
    позиций в КП бывают сотни.

    Пустое поле без источника означало разом «в КП не указано» (факт о
    предложении — можно спросить поставщика) и «разбор не дошёл» (наш недочёт —
    спрашивать надо разборщик). Это разные выводы и разные действия, поэтому
    источник пишется явно (library/offer_terms.py).
    """
    общие = offer_terms.условия_файла(весь_текст or "")
    был_текст = bool((весь_текст or "").strip())
    for it in items:
        it["_условия"] = offer_terms.свести(it.get("_из_строки") or {},
                                            общие, был_текст)


def ослаблять(п: str) -> bool:
    """Применять ли ослабленное правило шапки к этому виду файла.

    Замер по видам обязателен: общий выключатель складывал прибыль офисных файлов
    с убытком PDF, и сумма выглядела прибылью.
    """
    return ШАПКА_ШИРЕ and п in ШИРЕ_ПРИМЕНИМО


def глубина_шапки(п: str) -> int | None:
    """Глубина поиска шапки для вида файла: у PDF — по правке F5
    (ГЛУБИНА_ШАПКИ_PDF), у прочих и без правки — None, то есть прежняя.

    Только у PDF: в первых сорока строках PDF стоят бланк и проза письма, и
    шапка КП уходит на строки 45–123 (разведка 28.09.2026). У книги Excel
    глубже смотрит ослабленное правило (ГЛУБОКО), и второе правило глубины
    там не нужно."""
    return ГЛУБИНА_ШАПКИ_PDF if п == "pdf" and _действует(ГЛУБИНА_ШАПКИ_PDF) else None


def таблица_или_текст(rows: list[list[str]], текст_иначе, rec: dict | None,
                      п: str = "") -> tuple:
    """ВОРОТА ТАБЛИЦЫ: берём её только при опознанной шапке.

    Без шапки ветка «самая длинная ячейка строки» превращает таблицу реквизитов,
    колонтитулы и подписи в строки номенклатуры. Не прошло — разбираем текстом,
    то есть хуже, чем было, не становится.

    ПРИЧИНА ОТКАЗА ЗАПИСЫВАЕТСЯ ЗДЕСЬ, а не в ветке `if rows`: файл уходит в
    текстовый путь, и там строк таблицы уже нет. Воронка 23.09.2026: 3 474 файла
    стоят в клетке «текст, шапки нет» — 334 535 позиций почти без цены, и это в
    основном ОТВЕРГНУТЫЕ таблицы.
    """
    if rows and header_map(rows, шире=ослаблять(п) if п else None,
                           глубина=глубина_шапки(п))[0] >= 0:
        return rows, ""
    if rows and rec is not None:
        rec["header_miss"] = почему_нет_шапки(rows, п)
        rec["header_words"] = слова_шапки_без_имени(rows)
        rec["header_grid"] = сетка_шапки(rows)
    return [], текст_иначе()


def таблица_уступает_тексту(строки: list[list[str]], страницы: list[str], b: bytes) -> bool:
    """РЕШЕНИЕ ПО ФАЙЛУ: таблица, которую открыли ПРАВКИ, беднее текстового пути.

    Правки F1, F4, F5 и F6 открывают табличный путь файлу, который прежде шёл
    текстом, и тогда он теряет цены, сошедшиеся тройкой в строках текста.
    Ревизия 28.09.2026: письмо с двенадцатью верными ценами тройкой и таблицей
    характеристик «Наименование параметра | Ед. изм. | Значение» ниже сорокой
    строки — F5 брала таблицу характеристик, и цен становилось ноль; то же на
    PDF репозитория (ПИЛОТ-ЗАКАЗ-1: 9 → 0). Поэтому, если без правок таблица
    воротами не бралась, а с правками берётся, считаются её строки цены и
    правдоподобные тройки текста (троек_в_тексте), и при цен в таблице меньше
    файл идёт текстом (след «Fт»). Прежний путь от решения не меняется: где
    таблица бралась и без правок, решения нет вовсе."""
    if not правки_действуют():
        return False
    with quotes.без_правок():
        прежняя = таблица_из_страниц(страницы)
        if прежняя and header_map(прежняя, шире=ослаблять("pdf"),
                                  глубина=глубина_шапки("pdf"))[0] >= 0:
            return False
    with _без_следа():
        цен = sum(1 for it in позиции_по_листам(строки, ослаблять("pdf"), глубина_шапки("pdf"))
                  if it.get("_цена"))
        троек = троек_в_тексте(текст_pdf(b, None, страницы)[0])
    if цен < троек:
        _снять_след("F1", "F1о")
        _след("Fт")
        return True
    return False


#: Почему читатель вернул пустоту — по подвидам. Пустота БЕЗ причины это и есть
#: потерянный файл: по «нет текстового слоя» не видно, скан это, битый файл или
#: пустая книга. Замер 23.09.2026: у 770 файлов PDF стоит ровно такая причина, и
#: чинить по ней нечего.
ПУСТО_ПОЧЕМУ = {
    "pdf": "PDF без текстового слоя: скан, читается распознаванием",
    "xlsx": "книга без непустых строк",
    "docx": "документ без текста и таблиц",
    "csv": "файл без строк",
    "txt": "файл без строк",
    "rtf": "RTF без текста",
    "html": "HTML без текста",
    "xml": "XML без строк и текста",
}


def читать(b: bytes, п: str, rec: dict | None = None) -> tuple[list[list[str]], str, str]:
    """Стратегия чтения плюс ЗАПРЕТ МОЛЧАТЬ.

    Ни один вид не имеет права вернуть пустоту без названной причины: такой файл
    получает «пусто» и выпадает из работы навсегда, потому что ни переразбор, ни
    распознавание его не отбирают. Проверка на это есть, и первая же её редакция
    нашла дефект: PDF без текстового слоя молчал.
    """
    if КАСКАД:
        строки, текст, отказ = читать_каскадом(b, п, rec)
    else:
        строки, текст, отказ = _читать(b, п, rec)
    if not строки and not текст and not отказ:
        отказ = ПУСТО_ПОЧЕМУ.get(п, f"{п}: читатель не дал ни строк, ни текста")
    return строки, текст, отказ


def _читать(b: bytes, п: str, rec: dict | None = None) -> tuple[list[list[str]], str, str]:
    """СТРАТЕГИЯ ЧТЕНИЯ ПО ВИДУ ФАЙЛА. Возвращает (строки таблицы, текст, отказ).

    ЗАЧЕМ ОДНА ФУНКЦИЯ НА ВСЁ. До 23.09.2026 ветвление в handle покрывало три вида
    из шести: «изображение», «архив» и «прочее» не попадали ни в одну ветку, у них
    оставались пустые строки и пустой текст, и файл получал «пусто» с причиной
    «нет текстового слоя». Замер по всей базе: «прочее» 410 файлов и «архив» 169 —
    все до единого без позиций, 100 %.

    ПОРЯДОК ВНУТРИ ВИДА ВЫБРАН ПО ЦЕНЕ: сначала самый дешёвый и самый вероятный
    читатель, запасной — только если первый не дал ничего. Лишних попыток нет:
    книга не читается как документ Word, .doc не пробуется как книга дважды.

    ОТКАЗ — ТРЕТЬИМ ЗНАЧЕНИЕМ, А НЕ ИСКЛЮЧЕНИЕМ. «Формат не читаем» с именем
    класса исключения не говорит, что чинить; названный отказ («нет ни antiword,
    ни catdoc», «rar: нет распаковщика») говорит.
    """
    if п == "xlsx":
        try:
            return rows_from_xlsx(b), "", ""
        except Exception as e:                                          # noqa: BLE001
            # PK-контейнер, который не открылся книгой: чаще всего это архив,
            # которому подписи xl/ достались от вложенной внутрь книги.
            строки, текст, _ = читать_архив(b, rec)
            if строки or текст:
                return строки, текст, ""
            return [], "", f"книга не открылась ({type(e).__name__})"
    if п == "docx":
        строки, текст = таблица_или_текст(rows_from_docx(b), lambda: text_from_docx(b),
                                          rec, "docx")
        return строки, текст, ""
    if п == "pdf":
        # СТРАНИЦЫ ЧИТАЮТСЯ ЗДЕСЬ, ОДИН РАЗ, и счёт пишется независимо от того,
        # каким путём пойдёт файл: смешанный PDF с опознанной таблицей тоже
        # обязан попасть в распознавание своими сканами.
        страницы, всего, потеряно = страницы_pdf(b, layout=True)
        записать_счёт(rec, страницы, всего, потеряно)
        if потеряно and потеряно < len(страницы):
            print(f"::warning::PDF: {потеряно} страниц из {len(страницы)} не дали "
                  f"выравнивания, таблица собрана по остальным", flush=True)
        строки = таблица_из_страниц(страницы)
        строки, текст = таблица_или_текст(строки, lambda: текст_pdf_взят(b, rec, страницы),
                                          rec, "pdf")
        if строки and таблица_уступает_тексту(строки, страницы, b):
            строки, текст = [], текст_pdf_взят(b, rec, страницы)
        return строки, текст, ""
    if п == "ole2_разобрать":
        # OLE2 — это и .xls, и .doc, и .msg. Книга пробуется первой: она дешевле
        # и встречается чаще. Падение xlrd НЕ означает «формат не читаем» — до
        # 23.09.2026 означало, и так терялись 375 файлов (XLRDError 362,
        # AssertionError 11, CompDocError 2).
        try:
            строки = rows_from_xls(b)
            if строки:
                return строки, "", ""
        except Exception:                                               # noqa: BLE001, S110
            pass
        текст, почему = readers.text_from_doc(b)
        return [], текст, почему
    if п == "spreadsheetml":
        строки = readers.rows_from_spreadsheetml(b)
        return строки, "", "" if строки else "XML Spreadsheet без строк"
    if п in ("csv", "txt"):
        строки, текст = таблица_или_текст(readers.rows_from_text(b),
                                          lambda: readers.декод(b[:400000]), rec, п)
        return строки, текст, ""
    if п == "rtf":
        return [], readers.text_from_rtf(b), ""
    if п == "html":
        return [], readers.text_from_html(b), ""
    if п == "xml":
        строки = readers.rows_from_spreadsheetml(b)
        if строки:
            return строки, "", ""
        return [], readers.text_from_html(b), ""
    if п == "zip":
        return читать_архив(b, rec)
    if п in ("png", "jpeg", "tiff", "gif", "bmp", "webp"):
        # Картинку читает распознавание отдельным проходом (library/ocr.py). Здесь
        # важно НАЗВАТЬ это, а не оставить «нет текстового слоя»: по такой причине
        # не видно, ждёт файл распознавания или потерян.
        return [], "", "скан: читается распознаванием"
    if п in ("rar", "7z", "gzip"):
        return [], "", f"{п}: нужен внешний распаковщик, в прогоне его нет"
    return [], "", "формат не опознан"


def читать_архив(b: bytes, rec: dict | None = None) -> tuple[list[list[str]], str, str]:
    """Архив: читается КАЖДЫЙ участник, берётся лучший.

    Лучший — тот, что дал больше строк таблицы; если таблицы не дал никто, тексты
    участников склеиваются. Брать первого попавшегося нельзя: в архиве «КП и
    приложения» первым обычно лежит письмо, а спецификация вторым.

    Архив в архиве не берётся (library/readers.py): настоящие случаи закрываются
    одним уровнем.
    """
    участники = readers.участники_архива(b)
    if not участники:
        return [], "", "архив не открылся или пуст"
    лучшие: list[list[str]] = []
    тексты: list[str] = []
    for имя, содержимое in участники:
        п = подвид(содержимое)
        if п == "zip":
            continue
        try:
            строки, текст, _ = читать(содержимое, п, None)
        except Exception:                                               # noqa: BLE001, S112
            continue                                    # битый участник — не весь архив
        if len(строки) > len(лучшие):
            лучшие = строки
        if текст:
            тексты.append(текст)
    if лучшие:
        return лучшие, "", ""
    склейка = "\n".join(тексты)[:400000]
    return [], склейка, "" if склейка else f"в архиве {len(участники)} файлов без текста"


#: Сколько уровней вложенности читает каскад: письмо → архив → книга — это три.
ГЛУБИНА_КАСКАДА = 3

#: Подвиды, которым LibreOffice — последний рубеж, когда свой читатель не дал
#: ничего. Архив сюда не входит: конвертер отказывает ему сразу, но только после
#: того, как свой распаковщик уже сказал, что внутри.
ДЛЯ_КОНВЕРТЕРА = frozenset({"ole2_разобрать", "xlsx", "docx", "ods", "odt", "rtf",
                            "xml", "spreadsheetml", "html", "неизвестно"})

КАРТИНКИ = frozenset({"png", "jpeg", "tiff", "gif", "bmp", "webp"})
АРХИВЫ = frozenset({"zip", "rar", "7z", "gzip"})

#: Отказы, после которых каскад не пробует ничего дальше: книга опознана, но без
#: пароля не читается никем, а битый OLE2 — то, на чём зацикливаются чужие разборы.
ОКОНЧАТЕЛЬНО = ("книга зашифрована", "OLE2 испорчен")

#: Начало причины у файла, который не PDF и не картинка, но несёт сканы внутри:
#: документ Word из фотографий страниц, архив сканов, письмо со снимком КП.
#: Отбор распознавания (library/ocr.py) берёт файлы по этому началу строки —
#: иначе такой файл лёг бы «пустым» навсегда: по виду он не скан.
КАРТИНКИ_ВНУТРИ = "картинки внутри:"
МАКС_СКАНОВ_ФАЙЛА = 40


def картинки_файла(b: bytes, глубина: int = 0) -> list[tuple[str, bytes]]:
    """Что внутри файла читает распознавание: [(«картинка» | «pdf», байты)].

    PDF берётся только из архива и письма: собственный PDF файла распознавание
    и так читает целиком, а PDF-вложение, не давшее текста каскаду, — это скан.
    """
    п = уточнить_подвид(b, подвид(b))
    if п in КАРТИНКИ:
        return [("картинка", b)]
    if глубина and п == "pdf":
        return [("pdf", b)]
    if глубина >= ГЛУБИНА_КАСКАДА:
        return []
    if п in ("docx", "odt", "rtf", "html", "ole2_разобрать"):
        return [("картинка", к) for _, к in read_word.прочитать_документ(b).get("images") or []
                ][:МАКС_СКАНОВ_ФАЙЛА]
    if п in АРХИВЫ:
        части = read_archive.распаковать(b, глубина=2)[0]
    elif п in ("msg", "eml"):
        части = read_mail.прочитать_письмо(b)["attachments"]
    else:
        return []
    сканы: list[tuple[str, bytes]] = []
    for _, содержимое in части:
        if содержимое:
            сканы += картинки_файла(содержимое, глубина + 1)
        if len(сканы) >= МАКС_СКАНОВ_ФАЙЛА:
            break
    return сканы[:МАКС_СКАНОВ_ФАЙЛА]


def уточнить_подвид(b: bytes, п: str) -> str:
    """Подвиды, которые различает только каскад.

    В подвид() их нет намеренно: прежняя таблица стратегий не знает, что делать
    с «msg» и «eml», и при выключенном каскаде письмо ушло бы в «формат не
    опознан» вместо нынешнего чтения текстом. Письмо Outlook — такой же OLE2,
    как .xls; OpenDocument — такой же PK-контейнер, как архив.
    """
    if п == "ole2_разобрать" and read_mail.это_письмо_outlook(b):
        return "msg"
    if п in ("txt", "неизвестно") and read_mail.это_письмо_eml(b):
        return "eml"
    if п == "zip" and b"mimetype" in b[:120]:
        голова = b[:400]
        if b"opendocument.spreadsheet" in голова:
            return "ods"
        if b"opendocument.text" in голова:
            return "odt"
    return п


def _лучше(строки: list[list[str]]) -> tuple[bool, int]:
    """Ключ выбора таблицы среди участников архива или вложений письма.

    Опознанная шапка важнее числа строк: справочник на тысячу строк без шапки
    уступает спецификации на двадцать строк с ней.
    """
    return (bool(строки) and header_map(строки)[0] >= 0, len(строки))


def _из_многих(части: list[tuple[str, bytes]], глубина: int,
               путь: list[str]) -> tuple[list[list[str]], list[str], int]:
    """Прочитать участников архива или вложения письма: лучшая таблица и все тексты."""
    лучшие: list[list[str]] = []
    тексты: list[str] = []
    прочитано = 0
    for _имя, содержимое in части:
        if not содержимое:
            continue
        try:
            с, т, _ = читать_каскадом(содержимое, подвид(содержимое), None, глубина + 1)
        except Exception:                                               # noqa: BLE001, S112
            continue                                    # битый участник — не весь архив
        прочитано += bool(с or т)
        if _лучше(с) > _лучше(лучшие):
            лучшие = с
        if т:
            тексты.append(т)
    путь.append(f"частей {len(части)}, прочитано {прочитано}")
    return лучшие, тексты, прочитано


def _слово(р: dict, rec: dict | None, п: str, путь: list[str]) -> tuple:
    """Итог read_word: таблица через ворота шапки, иначе текст."""
    путь.append(f"read_word:{р.get('format') or '?'}")
    строки, текст = таблица_или_текст(р["rows"], lambda: р["text"], rec, п)
    if р.get("images") and not (строки or текст.strip()):
        путь.append(f"картинок {len(р['images'])}")
    return строки, текст, "" if (строки or текст.strip()) else р["reason"]


def _родной(b: bytes, п: str, rec: dict | None, глубина: int,
            путь: list[str]) -> tuple[list[list[str]], str, str]:
    """Свой читатель по точному формату. Ни один не бросает — каждый называет отказ."""
    if п == "pdf":
        # ТАБЛИЦА — ПРЕЖНИМ ПУТЁМ (pypdf с выравниванием), ПРОЗА — read_pdf.
        # Сборка таблицы (library/pdftable.py) настроена на раскладку pypdf.
        # pdftotext -layout ставит между колонками одиночные пробелы там, где
        # pypdf ставит несколько: на придуманном КП шапка слиплась в одну ячейку,
        # цена взялась из колонки «№», а количество склеилось в семизначное
        # число (замер 23.09.2026, прогон каскада по корпусу). Ворота шапки такую
        # таблицу пропустили — значит решать её судьбу им нельзя.
        страницы, всего, потеряно = страницы_pdf(b, layout=True)
        записать_счёт(rec, страницы, всего, потеряно)
        строки = таблица_из_страниц(страницы)
        if строки and header_map(строки, шире=ослаблять("pdf"),
                                 глубина=глубина_шапки("pdf"))[0] >= 0:
            if not таблица_уступает_тексту(строки, страницы, b):
                путь.append("pypdf:таблица")
                return строки, "", ""
        else:
            таблица_или_текст(строки, str, rec, "pdf")  # причина отказа шапки — в запись
        # ПРОЗА — ТОЖЕ ПРЕЖНИМ ПУТЁМ (pypdf без выравнивания). Холостой переразбор
        # 23.09.2026 показал: pdftotext без выравнивания разносит ячейки строки
        # таблицы по разным строкам, тройка «кол-во × цена = сумма» на одной строке
        # не собирается, и 50 PDF дали 3 цены — у первой части прогона строк цены
        # стало 427 вместо 1 079. pypdf строку держит.
        # С правкой F2 — лучший из двух текстов pypdf (текст_pdf); какой взят,
        # пишется в путь чтения ПОСЛЕ читателя: первый шаг пути — это читатель.
        текст, какой = текст_pdf(b, rec, страницы)
        if текст.strip() and text_quality.качество(текст)[0] >= text_quality.ПОРОГ_OCR:
            путь.append("pypdf:текст")
            if какой:
                путь.append(какой)
                _след("F2")
            return [], текст, ""
        # pypdf не дал текста или дал мусор (шифр, битая таблица ссылок, символьный
        # шрифт): тогда read_pdf — pdftotext, снятие пустого пароля qpdf, починка
        # кодировки по страницам. Берётся, только если его текст не хуже.
        р = read_pdf.прочитать_pdf(b, layout=False)
        свой = "\n".join(р["text"].split("\f"))
        if свой.strip() and (not текст.strip() or text_quality.качество(свой)[0]
                             > text_quality.качество(текст)[0]):
            read_pdf.в_запись(р, rec)
            путь.append(f"read_pdf:{р.get('method') or '—'}")
            if р["reason"]:
                путь.append(f"неполно: {р['reason'][:80]}")
            return [], свой, ""
        if текст.strip():
            путь.append("pypdf:текст")
            if какой:
                путь.append(какой)
                _след("F2")
            return [], текст, ""
        read_pdf.в_запись(р, rec)
        путь.append(f"read_pdf:{р.get('method') or '—'}")
        return [], "", р["reason"]
    if п in ("xlsx", "ods"):
        строки, текст, причина = read_sheet.прочитать_книгу(b)
        путь.append("read_sheet")
        if строки or текст:
            return строки, текст, ""
        if п == "xlsx":
            # PK-контейнер, который не открылся книгой: чаще всего это архив,
            # которому подписи xl/ достались от вложенной внутрь книги.
            с, т, о = _родной(b, "zip", None, глубина, путь)
            if с or т:
                return с, т, ""
        return [], "", причина
    if п == "ole2_разобрать":
        # Книга первой: она дешевле и встречается чаще. Отказ read_sheet на .doc
        # ничего не значит — дальше документ.
        строки, текст, причина = read_sheet.прочитать_книгу(b)
        if строки:
            путь.append("read_sheet")
            return строки, текст, ""
        if причина.startswith(ОКОНЧАТЕЛЬНО):
            # Книга опознана, но не читается ничем: документом Word её пробовать
            # незачем, а битый OLE2 — ровно то, на чём зацикливаются чужие разборы.
            путь.append("read_sheet")
            return [], "", причина
        с, т, о = _слово(read_word.прочитать_документ(b), rec, "docx", путь)
        if с or т:
            return с, т, ""
        т, почему = readers.text_from_doc(b)
        if т:
            путь.append("antiword")
            return [], т, ""
        return [], "", "; ".join(x for x in (о, почему) if x) or причина
    if п in ("msg", "eml"):
        р = read_mail.прочитать_письмо(b)
        путь.append(f"read_mail:{р.get('формат') or п}")
        тело = р["text"]
        лучшие: list[list[str]] = []
        тексты: list[str] = []
        if р["attachments"] and глубина < ГЛУБИНА_КАСКАДА:
            лучшие, тексты, _ = _из_многих(р["attachments"], глубина, путь)
        # Тело письма идёт вместе с таблицей вложения: в нём условия поставки и
        # то, кто кому пишет, — по нему определяется папка документа.
        текст = "\n\n".join(x for x in [тело, *тексты] if x.strip())[:400000]
        if лучшие or текст:
            return лучшие, текст, ""
        return [], "", р["reason"] or "письмо без текста и вложений"
    if п in АРХИВЫ:
        if глубина >= ГЛУБИНА_КАСКАДА:
            return [], "", "архив глубже предела вложенности"
        части, причина = read_archive.распаковать(b, глубина=2)
        путь.append(f"read_archive:{п}")
        if причина:
            путь.append(причина[:80])
        if not части:
            return [], "", причина or "архив пуст"
        лучшие, тексты, _ = _из_многих(части, глубина, путь)
        if лучшие:
            return лучшие, "", ""
        склейка = "\n".join(тексты)[:400000]
        return [], склейка, "" if склейка else (причина or f"в архиве {len(части)} файлов без текста")
    if п == "rtf":
        # Свой разбор, а не read_word: тот отдаёт RTF только текстом, а таблица
        # КП в RTF — это строки \cell…\row, и ячейки режутся табуляцией.
        путь.append("readers:rtf")
        строки, текст = таблица_или_текст(readers.rows_from_rtf(b),
                                          lambda: readers.text_from_rtf(b), rec, п)
        return строки, текст, "" if (строки or текст) else "RTF без текста"
    if п in ("docx", "odt", "html"):
        с, т, о = _слово(read_word.прочитать_документ(b), rec, п, путь)
        if с or т:
            return с, т, ""
        if п == "html":
            т = readers.text_from_html(b)
        return [], т, "" if т else о
    if п in ("xml", "spreadsheetml"):
        строки, текст, причина = read_sheet.прочитать_книгу(b)
        if строки:
            путь.append("read_sheet")
            return строки, текст, ""
        строки = readers.rows_from_spreadsheetml(b)
        if строки:
            return строки, "", ""
        с, т, о = _слово(read_word.прочитать_документ(b), rec, "docx", путь)
        if с or т:
            return с, т, ""
        т = readers.text_from_html(b)
        return [], т, "" if т else (о or причина)
    if п in ("csv", "txt"):
        путь.append(f"readers:{п}")
        строки, текст = таблица_или_текст(readers.rows_from_text(b),
                                          lambda: readers.декод(b[:400000]), rec, п)
        return строки, текст, ""
    if п in КАРТИНКИ:
        путь.append("скан")
        return [], "", "скан: читается распознаванием"
    путь.append("не опознан")
    return [], "", "формат не опознан"


def читать_каскадом(b: bytes, п: str, rec: dict | None = None,
                    глубина: int = 0) -> tuple[list[list[str]], str, str]:
    """КАСКАД ЧТЕНИЯ: свой читатель → починка текста → LibreOffice → модель.

    ЗАЧЕМ. Прежняя таблица стратегий (_читать) давала каждому формату ОДНОГО
    читателя, и его отказ был отказом файла. Замер 23.09.2026: 9 527 файлов из
    31 869 (29,9 %) без единой позиции. Каскад идёт от дешёвого к дорогому и
    останавливается на первом, кто дал строки или текст:

      1. свой читатель по точному формату (read_pdf, read_sheet, read_word,
         read_mail, read_archive, readers) — без внешних программ, кроме
         poppler и распаковщиков;
      2. починка извлечённого текста (text_quality): кракозябры cp1251/koi8,
         разрядка, символьные шрифты PDF — только если оценка строго выросла;
      3. LibreOffice (convert_office) — только офисным файлам и только если
         своё не дало ничего: это секунды на файл против миллисекунд;
      4. модель (read_llm) — только при LLM_READ=1: деньги и секрет решает
         владелец.

    Сканы читает распознавание отдельным проходом (library/ocr.py); здесь их
    важно НАЗВАТЬ, чтобы файл не лёг «пустым» навсегда.

    ПУТЬ ЧТЕНИЯ ЗАПИСЫВАЕТСЯ (rec["read_chain"], правило 16): без него следующая
    ошибка снова неизмерима — не видно, какой читатель взял файл.
    """
    п = уточнить_подвид(b, п)
    if rec is not None:
        rec["subkind"] = п
    путь: list[str] = []
    строки, текст, отказ = _родной(b, п, rec, глубина, путь)
    if отказ.startswith(ОКОНЧАТЕЛЬНО):
        if rec is not None:
            rec["read_chain"] = " → ".join(путь)[:200] or None
        return [], "", отказ
    if not строки and not текст.strip() and п in ДЛЯ_КОНВЕРТЕРА \
            and convert_office.найти_soffice():
        с, почему = convert_office.в_csv(b)
        т = "" if с else convert_office.в_текст(b)[0]
        if с or т:
            путь.append("libreoffice")
            строки, текст = таблица_или_текст(с, lambda: т, rec, п) if с else ([], т)
            отказ = ""
        elif почему:
            отказ = f"{отказ}; {почему}" if отказ else почему
    if текст.strip():
        починенный, что = text_quality.починить(текст)
        if что:
            текст = починенный
            путь.append(f"починка: {что}"[:60])
    if not строки and not текст.strip() and read_llm.включено():
        с, т, почему = read_llm.прочитать_моделью(b, п)
        if с or т:
            путь.append("модель")
            строки, текст, отказ = с, т, ""
        elif почему:
            отказ = f"{отказ}; {почему}" if отказ else почему
    if (глубина == 0 and not строки and not текст.strip()
            and п not in КАРТИНКИ and п != "pdf"):
        сканы = картинки_файла(b)
        if сканы:
            # Причина меняется на ту, по которой файл заберёт распознавание:
            # прежняя («документ без текста») верна, но ничего не чинит.
            путь.append(f"сканов {len(сканы)}")
            отказ = f"{КАРТИНКИ_ВНУТРИ} {len(сканы)} — читаются распознаванием"
    if rec is not None:
        rec["read_chain"] = " → ".join(путь)[:200] or None
    return строки, текст, отказ


def листы_книги(rows: list[list[str]]) -> list[list[list[str]]]:
    """Строки по листам, если их разметил read_sheet (и каскад включён); иначе одним куском."""
    if КАСКАД and rows and read_sheet.это_метка(rows[0]):
        return [тело for _, тело in read_sheet.по_листам(rows) if тело]
    return [rows]


def позиции_по_листам(rows: list[list[str]], шире: bool | None = None,
                      глубина: int | None = None) -> list[dict]:
    """Позиции книги — КАЖДЫЙ ЛИСТ СО СВОЕЙ ШАПКОЙ.

    items_from_rows ищет шапку в первых сорока строках всего списка и применяет
    её ко всему ниже. Книга «сопроводительное письмо на первом листе, прайс на
    втором» шапки не находит вовсе, а книга из двух прайсов с разными колонками
    разбирает второй колонками первого (нашёл агент книг 23.09.2026). Предел в
    три тысячи позиций — на книгу, как и прежде.
    """
    листы = листы_книги(rows)
    if len(листы) == 1:
        return items_from_rows(листы[0], шире=шире, глубина=глубина)
    items: list[dict] = []
    for тело in листы:
        items += items_from_rows(тело, шире=шире, глубина=глубина)
        if len(items) >= 3000:
            break
    return items[:3000]


#: Сколько текста видит сверка с содержимым: голова и хвост. Автора решают бланк,
#: адресат и подпись — они в начале и в конце; середина длинной спецификации
#: ничего не добавляет, а стоит почти секунду на 400 тысячах знаков.
ПАПКА_ГОЛОВА, ПАПКА_ХВОСТ = 60000, 20000
#: Столько знаков держит lib_files.doc_kind_why (обе записи обрезают до него).
ДЛИНА_ПОЧЕМУ = 300


def папка_системы(rec: dict) -> None:
    """Папка по данным системы (library/doc_folder.py): сущность и код поля.

    Требование владельца 23.09.2026: папку документа решает система запросов,
    где «вся избыточная информация» уже есть, а не имя компании в тексте.
    Уверенность говорит, откуда папка: 1.0 — код поля, 0.8/0.6 — название
    поля, 0.0 — папки нет, в том числе у поля, опознанного кодом.
    Ставится ДО закачки: файл, который не скачался или не прочитался, тоже
    получает папку — ей содержимое не нужно."""
    п, ув, почему = doc_folder.определить(rec.get("origin"), rec.get("field"),
                                          rec.get("field_title"))
    rec["doc_kind"], rec["doc_kind_conf"], rec["doc_kind_why"] = п, ув, f"поле: {почему}"


def определить_папку(rec: dict, текст: str, строки: list[list[str]]) -> None:
    """Папку ставит система; содержимое (library/doc_kind.py) — только сверка.

    Классификатор содержимого получает имена ВСЕХ наших компаний (наши_имена) и
    НЕ получает сторону поля: сверка, в которую подмешан ответ системы, свою
    независимость теряет (правило 1: эталон не может быть производным от
    правила). Уверенная папка по содержимому, отличная от папки системы, —
    РАСХОЖДЕНИЕ: папка остаётся системной, а в doc_kind_why пишется
    «расхождение: поле → X, содержимое → Y 0.83» и признаки (только их подписи,
    ни слова из документа — правило 17). Если система папки не знает («не
    определено»), содержимое её не назначает: его вердикт остаётся подсказкой.

    Сбой классификатора файл не теряет и папку системы не трогает.
    В запись уходят и счётчики для журнала прогона: папка_содержимого,
    ув_содержимого, расхождение — в базу они не пишутся."""
    if rec.get("doc_kind") is None:
        папка_системы(rec)
    система, почему_системы = rec["doc_kind"], rec.get("doc_kind_why") or ""
    rec["расхождение"] = False
    т = текст or ""
    if len(т) > ПАПКА_ГОЛОВА + ПАПКА_ХВОСТ:
        т = т[:ПАПКА_ГОЛОВА] + "\n" + т[-ПАПКА_ХВОСТ:]
    # Сколько знаков остаётся «почему» содержимого при самой длинной приставке
    # (расхождение с самой длинной папкой): классификатор сам сократит списки
    # признаков, и ось автора не срежется хвостом записи.
    приставка = (f"расхождение: поле → {система}, содержимое → "
                 f"{'#' * max(map(len, doc_kind.ПАПКИ))} 0.00 | {почему_системы} | ")
    try:
        папка, ув, почему = doc_kind.вид_документа(
            т, (строки or [])[:3000], None, наши=наши_имена(),
            длина_почему=max(60, ДЛИНА_ПОЧЕМУ - len(приставка)))
    except Exception as e:                                              # noqa: BLE001
        rec["doc_kind_why"] = (f"{почему_системы} | сверка с содержимым: "
                               f"сбой классификатора ({type(e).__name__})")[:ДЛИНА_ПОЧЕМУ]
        return
    rec["папка_содержимого"], rec["ув_содержимого"] = папка, round(ув, 3)
    уверенно = папка != doc_kind.НЕ_ОПРЕДЕЛЕНО and ув >= doc_kind.ПОРОГ
    if уверенно and папка == система:
        итог = f"{почему_системы} | содержимое согласно {ув:.2f}"
    elif уверенно and система == doc_folder.НЕ_ОПРЕДЕЛЕНО:
        итог = f"{почему_системы} | подсказка содержимого → {папка} {ув:.2f}: {почему}"
    elif уверенно:
        rec["расхождение"] = True
        итог = (f"расхождение: поле → {система}, содержимое → {папка} {ув:.2f}"
                f" | {почему_системы} | {почему}")
    else:
        итог = f"{почему_системы} | содержимое: {почему}"
    rec["doc_kind_why"] = итог[:ДЛИНА_ПОЧЕМУ]


#: Строка контактов письма: почта, адрес сайта, телефон, факс. Закрытый список —
#: обвиняет (правило 7): в наименовании позиции этих слов не бывает.
_КОНТАКТ_ПИСЬМА = re.compile(
    r"@|https?://|www\.|(?<![а-яёa-z])(?:тел|телефон|моб|мобильный|факс|e-?mail|почта)"
    r"(?![а-яёa-z])", re.I)


#: Количество в строке тела письма. Счётные единицы — где угодно в строке;
#: мера (м, кг, л, т) — только после тире или двоеточия: «Труба 57х3,5 мм» —
#: размер, а «Кабель 3х2,5 — 100 м» — количество. Число с пробелами — только
#: тройками («1 500 шт»), иначе «6205 10 шт» склеилось бы в 620 510.
_ЧИСЛО_КОЛ = r"(\d{1,3}(?:[ \u00a0]\d{3})+|\d+)(?:[.,]\d+)?"
_КОЛ_ШТ = re.compile(
    r"(?<![\w.,])(" + _ЧИСЛО_КОЛ + r")\s*(шт|штук[аи]?|компл(?:ект[аов]*)?|к-?т|набор[аов]*"
    r"|пар[аыу]?|уп(?:ак(?:овк[аи])?)?|pcs|pce|pc|ea|sets?)\.?(?![а-яёa-z])", re.I)
_КОЛ_МЕРА = re.compile(
    r"(?:[—–-]|:)\s*(" + _ЧИСЛО_КОЛ + r")\s*(метр[аов]*|литр[аов]*|тонн[аы]?|кг|м|л|тн|т)"
    r"\.?(?![а-яёa-z0-9])", re.I)
_ЕДИНИЦА_КОЛ = {"pcs": "шт", "pce": "шт", "pc": "шт", "ea": "шт", "set": "компл",
                "sets": "компл", "кт": "компл", "к-т": "компл"}


def количество_в_строке(строка: str) -> tuple[float | None, str | None]:
    """(количество, единица) из строки перечня в тексте письма; (None, None) —
    не прочитано. Берётся последнее упоминание: номер и размер стоят раньше."""
    for выражение in (_КОЛ_ШТ, _КОЛ_МЕРА):
        найдено = list(выражение.finditer(строка or ""))
        if not найдено:
            continue
        m = найдено[-1]
        v = quotes.число_из(m.group(1))
        if v is None or not (0 < v < 1_000_000):
            return None, None
        ед = m.group(3).lower().rstrip(".")
        ед = _ЕДИНИЦА_КОЛ.get(ед, ед)
        for полное, короткое in (("штук", "шт"), ("компл", "компл"), ("набор", "набор"),
                                 ("пар", "пар"), ("уп", "уп"), ("метр", "м"),
                                 ("литр", "л"), ("тонн", "т")):
            if ед.startswith(полное):
                ед = короткое
                break
        return v, ед
    return None, None


