# КОГДА ФАЙЛ ПОЯВИЛСЯ У ИСТОЧНИКА — lib_files.source_created_at
# (library/supabase/file_dates_schema.sql). processed_at переписывает каждая
# обработка, first_seen_at говорит, когда файл увидели МЫ, а недельному своду
# (scripts/weekly_offers.py) нужно, когда он пришёл В КОМПАНИЮ. Берётся только
# то, что не стоит ни одного лишнего запроса к порталу:
#
#   письмо — CREATED дела-письма: пришло в списке писем вместе с файлами
#     (mail_source.ссылки_письма кладёт его в ref["card_created"]). Одна дата у
#     тела и всех вложений письма. Пишется всегда.
#   поле карточки или сделки — файловое поле CRM даты загрузки не отдаёт
#     (crm.item.list несёт только id, url и urlMachine). Остаётся ответ самой
#     закачки: заголовок Last-Modified. Что он значит у портала — время загрузки
#     файла, время копии в облачном хранилище или что-то третье, — на живых
#     данных не проверено. Поэтому (CLAUDE.md, правило 3) заголовок МЕРЯЕТСЯ
#     всегда — строка «дата загрузки из заголовка закачки» в итоге части, — а
#     ПИШЕТСЯ только со входом FILE_DATE_HEADER=1. Полный замер с перекрёстными
#     проверками — холостой досчёт library/backfill_file_dates.py.
#
# ГРАНИЦЫ ПРАВДОПОДОБИЯ ЗАГОЛОВКА — каждая со своей причиной для журнала (ключи
# счёта — константы кода, правило 17):
#   нет заголовка или он не читается;
#   равен времени ответа (± ДОПУСК_ОТВЕТА): так выглядит заголовок, который
#     сервер ставит «сейчас» любому ответу, — это не дата файла;
#   раньше 2000 года или позже времени ответа;
#   раньше создания карточки или сделки больше чем на ДОПУСК_ВЛАДЕЛЬЦА: файл
#     кладут в поле уже заведённой карточки, и такой заголовок — дата другой
#     копии того же содержимого, а не этой загрузки.
ИСТ_ДАТЫ_ПИСЬМО = "письмо: создано в CRM"
ИСТ_ДАТЫ_ЗАКАЧКА = "закачка: Last-Modified"
#: Колонки даты у источника: пишутся парой (ограничение в схеме) и только в
#: пустое (ДОПОЛНЯТЬ_ПУСТОЕ) — записанная дата не переписывается ничем.
КОЛОНКИ_ДАТ = ("source_created_at", "source_date_src")
ДАТА_ЗАГОЛОВКА = os.environ.get("FILE_DATE_HEADER", "").strip().lower() in ("1", "true", "yes")
#: Заголовки ответа, которые нужны суду о дате, — и только они: имя файла из
#: Content-Disposition не нужно и в журнал не должно попасть никак.
ЗАГОЛОВКИ_ДАТЫ = ("Last-Modified", "Date", "Content-Length")
ДАТА_НЕ_РАНЬШЕ = datetime(2000, 1, 1, tzinfo=timezone.utc)
ДОПУСК_ОТВЕТА = timedelta(seconds=2)
ДОПУСК_ВЛАДЕЛЬЦА = timedelta(hours=1)
ЗАГ_ПРИНЯТ = "принят"
ЗАГ_НЕТ = "заголовка нет"
ЗАГ_НЕ_ЧИТАЕТСЯ = "не читается"
ЗАГ_ОТВЕТ = "равен времени ответа"
ЗАГ_ДО_2000 = "раньше 2000 года"
ЗАГ_БУДУЩЕЕ = "позже времени ответа"
ЗАГ_ДО_ВЛАДЕЛЬЦА = "раньше создания карточки или сделки"
ЗАГ_НЕ_КАЧАЛИ = "файл не скачался"


def заголовки_даты(ответ) -> dict:
    """Заголовки ответа закачки, нужные суду о дате (ЗАГОЛОВКИ_ДАТЫ)."""
    з = getattr(ответ, "headers", None) or {}
    return {к: str(з.get(к)) for к in ЗАГОЛОВКИ_ДАТЫ if з.get(к)}


def момент(значение) -> datetime | None:
    """Время портала («2026-09-20T10:15:00+03:00») или HTTP-дата → datetime с поясом.

    Время без пояса — None, а не догадка: пояс портала и пояс сервера разные, и
    угаданный сдвиг на три часа переносит файл через полночь, то есть в другой день."""
    if isinstance(значение, datetime):
        return значение if значение.tzinfo else None
    с = str(значение or "").strip()
    if not с:
        return None
    try:
        м = datetime.fromisoformat(с.replace("Z", "+00:00"))
    except ValueError:
        try:
            м = email.utils.parsedate_to_datetime(с)
        except (TypeError, ValueError, IndexError):
            return None
    return м if м is not None and м.tzinfo is not None else None


def дата_заголовка(заголовки: dict | None, создан_владелец=None) -> tuple[datetime | None, str]:
    """(момент загрузки файла, почему принят или нет) по заголовкам ответа закачки.

    создан_владелец — createdTime карточки или сделки, в поле которой лежит файл."""
    з = {str(к).lower(): v for к, v in (заголовки or {}).items()}
    if not з.get("last-modified"):
        return None, ЗАГ_НЕТ
    м = момент(з["last-modified"])
    if м is None:
        return None, ЗАГ_НЕ_ЧИТАЕТСЯ
    ответ = момент(з.get("date")) or datetime.now(timezone.utc)
    if abs(ответ - м) <= ДОПУСК_ОТВЕТА:
        return None, ЗАГ_ОТВЕТ
    if м < ДАТА_НЕ_РАНЬШЕ:
        return None, ЗАГ_ДО_2000
    if м > ответ:
        return None, ЗАГ_БУДУЩЕЕ
    владелец = момент(создан_владелец)
    if владелец is not None and м < владелец - ДОПУСК_ВЛАДЕЛЬЦА:
        return None, ЗАГ_ДО_ВЛАДЕЛЬЦА
    return м, ЗАГ_ПРИНЯТ


def дата_письма(создано) -> datetime | None:
    """CREATED дела-письма → момент; вне [2000 год; сутки вперёд] — None."""
    м = момент(создано)
    if м is None or м < ДАТА_НЕ_РАНЬШЕ or м > datetime.now(timezone.utc) + timedelta(days=1):
        return None
    return м


def дата_у_источника(ref: dict, rec: dict) -> None:
    """source_created_at и source_date_src файла — в rec; исход суда о заголовке
    закачки — в rec["дата_заголовка"] (для счёта в журнале; у письма — None).

    Одна на все записи файла: вставку разбора и UPDATE переразбора (правило 14)."""
    rec["source_created_at"] = rec["source_date_src"] = None
    rec["дата_заголовка"] = None
    if ref.get("origin") in doc_folder.ПРОИСХОЖДЕНИЯ_ПИСЕМ:
        м = дата_письма(ref.get("card_created"))
        if м is not None:
            rec["source_created_at"], rec["source_date_src"] = м, ИСТ_ДАТЫ_ПИСЬМО
        return
    if rec.get("заголовки_закачки") is None:
        rec["дата_заголовка"] = ЗАГ_НЕ_КАЧАЛИ
        return
    м, почему = дата_заголовка(rec["заголовки_закачки"],
                               ref.get("owner_created") or ref.get("card_created"))
    rec["дата_заголовка"] = почему
    if м is not None and ДАТА_ЗАГОЛОВКА:
        rec["source_created_at"], rec["source_date_src"] = м, ИСТ_ДАТЫ_ЗАКАЧКА


def handle(ref: dict) -> tuple[dict, list[dict]]:
    fo = ref["fo"]
    fid = ключ_ссылки(ref)
    название = ref.get("field_title")
    rec = {"file_id": fid, "deal_id": ref["deal"], "origin": ref["origin"], "field": ref["field"],
           # НАША КОМПАНИЯ — из карточки (mycompanyId), не из текста документа.
           "our_company": ref.get("our_company"),
           # СТОРОНА СЧИТАЕТСЯ ПРИ ЗАПИСИ, А НЕ ПРИ ЧТЕНИИ. Запросы к базе идут без
           # доступа к порталу, а названия полей живут только там; посчитанная
           # сторона — единственный способ отобрать заявки заказчика запросом.
           # У письма поля нет, и сторону говорит источник (группа и направление
           # письма, mail_source.СТОРОНА), а не название.
           "field_title": название, "side": ref.get("side") or doc_side.сторона(название),
           "kind": None, "size_bytes": None, "status": "не скачался", "reason": None,
           "chars": 0, "rows_found": 0, "segment_id": None, "sha256": None,
           "parse_path": None, "header_found": None, "header_miss": None,
           "header_words": None, "header_grid": None, "subkind": None,
           "pdf_pages": None, "pdf_pages_text": None, "pdf_pages_lost": None,
           "pdf_mixed": None, "doc_kind": None, "doc_kind_conf": None, "doc_kind_why": None,
           "read_chain": None, "doc_class": None,
           "class_rule": None, "text_lines": None, "item_lines": None}
    папка_системы(rec)
    цены = цены_файла(rec)
    b = download(fo, rec)
    # Дата у источника — и у не скачавшегося файла: письмо пришло в свой день,
    # скачали мы его или нет.
    дата_у_источника(ref, rec)
    if not b:
        return rec, []
    rec["size_bytes"] = len(b)
    rec["sha256"] = hashlib.sha256(b).hexdigest()
    основа = dict(rec)
    rec, items = разобрать_байты(b, ref, rec, цены)
    # ЗАМЕР ПРАВОК КП НА ТЕХ ЖЕ БАЙТАХ (переразбор, СРАВНИТЬ_БЕЗ_ПРАВОК): тот же
    # файл ещё раз, с выключенными правками, — без второй закачки. Сравнение с
    # базой смешало бы эффект правок с флагами прогона, писавшего базу (CLAUDE.md,
    # «Сравнивай с эталоном, записанным в тех же условиях»).
    if СРАВНИТЬ_БЕЗ_ПРАВОК and правки_действуют():
        with quotes.без_правок():
            rec["_без_правок"] = разобрать_байты(b, ref, dict(основа), цены)
    return rec, items


#: Переразбор с правками КП разбирает каждый файл дважды — с правками и без
#: (library/reparse.py ставит флаг; разбор новых файлов его не ставит).
СРАВНИТЬ_БЕЗ_ПРАВОК = False


def разобрать_байты(b: bytes, ref: dict, rec: dict, цены: bool) -> tuple[dict, list[dict]]:
    """Разбор скачанного файла со следом сработавших правок КП (записать_след)."""
    след: list[str] = []
    метка = _СЛЕД.set(след)
    try:
        rec, items = _разобрать(b, ref, rec, цены)
    finally:
        _СЛЕД.reset(метка)
    if any(quotes.ОГОВОРКА_ПАРА_НДС in str((it.get("_цена") or {}).get("note") or "")
           for it in items):
        след.append("F3")
    записать_след(rec, след)
    return rec, items


def записать_след(rec: dict, след: list[str]) -> None:
    """След правок — в rec["правки_кп"] и в конец read_chain: «… → правки: F1,F4».

    Коды — закрытый список СЛЕДЫ, в порядке списка; хвост read_chain держит
    место под след (колонка — 200 знаков), обрезается путь, а не след."""
    коды = [к for к in СЛЕДЫ if к in след]
    rec["правки_кп"] = коды
    if not коды:
        return
    хвост = "правки: " + ",".join(коды)
    путь = rec.get("read_chain") or ""
    if путь:
        путь = путь[:200 - len(хвост) - 3] + " → "
    rec["read_chain"] = путь + хвост


def _разобрать(b: bytes, ref: dict, rec: dict, цены: bool) -> tuple[dict, list[dict]]:
    """Разбор скачанного файла: чтение, позиции, цены (тело handle)."""
    fo = ref["fo"]
    fid = rec["file_id"]
    п = подвид(b)
    kind = "старый office" if п == "ole2_разобрать" else ВИД_ПО_ПОДВИДУ.get(п, "прочее")
    rec["kind"] = kind
    # ПОДВИД СОХРАНЯЕТСЯ РЯДОМ С ВИДОМ. Крупный вид говорит «прочее» у csv, txt,
    # rtf, html и мусора разом — по нему нельзя понять, какая стратегия сработала
    # и какую чинить (правило 16: сохраняй, почему получилось значение).
    rec["subkind"] = п
    rows: list[list[str]] = []
    text = ""
    try:
        rows, text, отказ = читать(b, rec.get("subkind") or подвид(b), rec)
        if отказ:
            rec["reason"] = отказ
    except Exception as e:
        rec["status"] = "формат не читаем"
        rec["reason"] = type(e).__name__
        return rec, []
    определить_папку(rec, text, rows)

    items: list[dict] = []
    # ПОЛНЫЙ ТЕКСТ ФАЙЛА — ОТДЕЛЬНО ОТ text. text у табличного пути склеен из
    # строк-позиций, а блок условий («Условия поставки: DAP Москва. Оплата 30/70»)
    # стоит ПОД таблицей и в позиции не попадает. Искать в text общие условия
    # значит не находить их никогда — при том, что в файле они написаны, и это
    # обычная форма КП (владелец: «бывает, что в конце предложения вообще цифра»).
    весь_текст = ""
    текст_читателя = text if rows else ""
    if rows:
        шире_файла = ослаблять(rec.get("subkind") or п)
        глубина_файла = глубина_шапки(rec.get("subkind") or п)
        items = позиции_по_листам(rows, шире_файла, глубина_файла)
        text = " ".join(r.get("_row", "") for r in items)[:200000]
        весь_текст = "\n".join(" ".join(c for c in r if c) for r in rows)[:400000]
        if текст_читателя:
            # Каскад отдаёт текст ВМЕСТЕ с таблицей там, где он несёт условия:
            # тело письма к спецификации, надписи в фигурах книги.
            весь_текст = (весь_текст + "\n" + текст_читателя)[:400000]
        rec["parse_path"] = "таблица"
        rec["header_found"] = any(header_map(тело, шире=шире_файла,
                                             глубина=глубина_файла)[0] >= 0
                                  for тело in листы_книги(rows))
        # ПОЧЕМУ шапки нет — рядом с тем, что её нет. Иначе «шапки нет» стоит в
        # базе у сотен файлов и не говорит, какую из четырёх правок делать.
        if not rec["header_found"]:
            rec["header_miss"] = почему_нет_шапки(rows, rec.get("subkind") or п)
            rec["header_words"] = слова_шапки_без_имени(rows)
            rec["header_grid"] = сетка_шапки(rows)
    elif text:
        # ВОРОТА СПЕЦИФИКАЦИИ. До 12.09.2026 здесь любая строка длиннее восьми
        # знаков становилась позицией номенклатуры, и в спрос лёг текст извещений
        # о закупке, проектов договоров и форм КП — 369 171 строка, четверть базы.
        #
        # Отказ выносится ЦЕЛИКОМ ПО ФАЙЛУ, а не по строке. Построчный отказ стоил
        # бы до сорока процентов позиций даже в заведомо хорошей спецификации:
        # продолжение наименования, перенесённое на вторую строку, никаких
        # признаков позиции не несёт. Внутри принятого файла пишутся все строки.
        lines = [ln.strip() for ln in text.splitlines()
                 if len(ln.strip()) > 8 and not NOISE_ROW.match(ln.strip())]
        spec_n = prose_n = 0
        for ln in lines:
            sp, pr = docfilter.row_marks(ln[:300])
            spec_n += bool(sp)
            prose_n += bool(pr and not sp)
        rec["parse_path"], rec["header_found"] = "текст", False
        rec["text_lines"], rec["item_lines"] = len(lines), spec_n
        весь_текст = text[:400000]
        verdict = docfilter.file_verdict(len(lines), spec_n, prose_n)
        if verdict == "документация" and SPECGATE:
            rec["chars"] = len(text)
            rec["status"] = "текст без спецификации"
            rec["reason"] = (f"строк {len(lines)} · с признаками позиции {spec_n} · "
                             f"с признаками текста {prose_n}")      # только агрегаты
            rec["doc_class"], rec["class_rule"] = "документация", docfilter.RULE_VERSION
            return rec, []
        for ln in lines[:2000]:
            # КП приходят PDF-ами, и таблицы в них нет: разбор по заголовкам
            # мимо. Цена здесь опознаётся арифметикой — кол-во × цена = сумма,
            # тройка чисел в самой строке (library/quotes.py). Замер 21.09.2026:
            # без этого пробный разбор дал 139 позиций и НОЛЬ цен.
            ц = quotes.цена_из_текста(ln) if цены else None
            items.append({"item_name": ln[:300], "part_number": docfilter.part_number_of(ln),
                          "oem": "", "unit": "", "qty": ц["qty"] if ц else None,
                          "_row": ln[:600], "_цена": ц})

    if "тело" in fo and items:
        # ТЕЛО ПИСЬМА — ПРОЗА С ВКРАПЛЕНИЯМИ ПЕРЕЧНЯ, отбор ПО СТРОКЕ (позиции_письма).
        # Ворота файла (docfilter.file_verdict) рассчитаны на длинный документ: у
        # письма в десять строк они говорят «мало строк», и позицией становилось
        # всё — приветствие, подпись, телефон. Холостой замер 25.09.2026 (прогон
        # 36102189853): 1 819 тел писем лидов дали 33 231 позицию, по 18 на письмо.
        до = len(items)
        items = позиции_письма(items)
        rec["item_lines"] = len(items)
        for it in items:
            # Количество из самой строки: у разбора текста его нет вовсе, а в
            # письме оно почти всегда рядом — «… — 10 шт.». Замер 25.09.2026
            # (прогон 36103645077): у 2 457 позиций тел количества ноль.
            if it.get("qty") is None:
                it["qty"], ед = количество_в_строке(it.get("item_name") or "")
                if ед and not it.get("unit"):
                    it["unit"] = ед
        if not items:
            rec["reason"] = f"в тексте письма нет строк с признаками позиции (строк {до})"
    rec["chars"] = len(text)
    rec["rows_found"] = len(items)
    rec["segment_id"] = classify(text) if text else None
    if not items:
        # «Пусто» перестало врать: тендерный PDF с текстовым слоем, но без позиций,
        # раньше ложился как «нет текстового слоя», и оценка объёма распознавания
        # сканов по этому статусу была завышена.
        rec["status"] = "пусто" if not rec["chars"] else "текст без спецификации"
        # КОНКРЕТНАЯ ПРИЧИНА ЧИТАТЕЛЯ НЕ ЗАТИРАЕТСЯ ДЕЖУРНОЙ. Прежде здесь всегда
        # писалось «нет текстового слоя» — поверх того, что назвал читатель. Замер
        # 23.09.2026: из 229 файлов, оставшихся пустыми, 150 docx и 57 xlsx
        # значились «без текстового слоя», что для офисного документа бессмыслица:
        # настоящая причина («книга не открылась (BadZipFile)», «документ без
        # текста и таблиц») стиралась, и чинить было нечего.
        if not rec.get("reason"):
            rec["reason"] = ("нет текстового слоя" if not rec["chars"]
                             else "позиции не распознаны")
        return rec, []
    rec["status"] = "разобран"
    # Валюта всего файла — последний довод, когда ни заголовок колонки, ни
    # ячейка её не назвали. Берётся, только если в тексте ровно одна валюта:
    # две («цена в евро, НДС в рублях») угадывать нельзя.
    вф = quotes.валюта_файла(text)
    for it in items:
        # Сегмент СТРОКИ — по самой строке. Наследование от файла помечается
        # отдельно: пока оно молчаливо, segment_id нельзя использовать как эталон
        # (текст строки — подмножество текста файла, поэтому файл либо весь
        # классифицирован, либо весь нет, и любое измерение по нему тавтологично).
        own = classify(it.get("_row", ""))
        it["segment_id"] = own or rec["segment_id"]
        it["segment_rule"] = "строка" if own else ("файл" if rec["segment_id"] else None)
        it["deal_id"] = ref["deal"]
        it["source_file"] = fid
        it["company"] = ref.get("company")
        it["brands"] = ref.get("brands")
        # Валюта файла вместо ненайденной; оговорка и уверенность правятся там же,
        # чтобы в строке не стояли разом «не названа» и «взята по файлу».
        quotes.подставить_валюту(it.get("_цена"), вф)
    if цены:
        применить_условия(items, весь_текст)
        # ДАТА КВОТАЦИИ — С ИСТОЧНИКОМ. Распоряжение владельца 24.09.2026: месяц
        # и год квотации нужны для индексации на инфляцию. Дата самого КП или
        # письма, иначе дата создания карточки запроса; дата разбора — никогда.
        quote_date.проставить(items, весь_текст or text, ref)
    return rec, items


NULLS = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f]")


def pg(s) -> str:
    """Строка, пригодная для PostgreSQL.

    В тексте, извлечённом из PDF и старых .xls, попадаются нулевые байты и другие
    управляющие символы. PostgreSQL их в text не принимает — psycopg2 падает с
    «A string literal cannot contain NUL (0x00) characters», и вместе с одной
    строкой теряется весь пакет разобранных файлов."""
    return NULLS.sub(" ", str(s or ""))


def ensure_segments(cur) -> None:
    """Справочник сегментов в базе должен существовать ДО записи номенклатуры.

    lib_demand.segment_id ссылается на lib_segments(id); при пустом справочнике
    вся запись падает с ForeignKeyViolation, а разобранные файлы теряются —
    именно так оборвались все двенадцать частей прогона 08.09.2026.
    Источник истины — словарь SEGMENTS в library/segments.py, поэтому справочник
    наполняем из него, а не поддерживаем вручную в двух местах."""
    psycopg2.extras.execute_values(
        cur,
        "insert into lib_segments (id, name) values %s on conflict (id) do nothing",
        [(sid, name) for sid, (name, _words) in SEGMENTS.items()],
    )


