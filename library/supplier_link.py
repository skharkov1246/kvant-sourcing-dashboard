def _домен_годен(h: str) -> bool:
    """Узел с буквенной зоной: «2.5» из строки каталога доменом не считается."""
    return bool(h) and bool(_ЗОНА.search(h))


def домены_сайта(текст) -> tuple[set[str], int]:
    """Домены из поля сайта (там бывает несколько адресов) и число общих."""
    свои, общих = set(), 0
    for кусок in _РАЗДЕЛ.split(str(текст or "").lower()):
        if "@" in кусок:
            continue                  # почта в поле сайта — не сайт
        h = хост(кусок)
        if not _домен_годен(h):
            continue
        if общий_домен(h):
            общих += 1
        else:
            свои.add(h)
    return свои, общих


def домены_почты(текст) -> tuple[set[str], int]:
    """Домены адресов почты и число общих (gmail, mail.ru, площадки)."""
    свои, общих = set(), 0
    for m in _ПОЧТА.finditer(str(текст or "").lower()):
        h = хост(m.group(1))
        if not _домен_годен(h):
            continue
        if общий_домен(h):
            общих += 1
        else:
            свои.add(h)
    return свои, общих


def инн(v) -> str:
    """ИНН цифрами, если контрольная сумма верна; иначе пусто."""
    s = re.sub(r"\D", "", str(v or ""))
    return s if инн_верен(s) else ""


def vat(v) -> str:
    s = re.sub(r"[^0-9A-Z]", "", str(v or "").upper())
    return s if len(s) >= 8 else ""


def инн_из_текста(*тексты) -> set[str]:
    """«ИНН 7701234567» в тексте разведки — только с верной контрольной суммой."""
    out = set()
    for t in тексты:
        for m in _ИНН.finditer(str(t or "")):
            if инн_верен(m.group(1)):
                out.add(m.group(1))
    return out


def страна(v) -> str:
    return re.sub(r"[^a-zа-я]", "", str(v or "").lower().replace("ё", "е"))


# ── Стороны ─────────────────────────────────────────────────────────────────

class Разведка(NamedTuple):
    id: int
    ключ: str | None            # lib_suppliers.name_key — страховка от чужого id
    имя: str                    # norm_name
    формы: frozenset
    страна: str
    налоги: frozenset           # {('inn', '7701…'), ('vat', 'DE…')}
    сайты: frozenset
    почты: frozenset
    общих: int                  # адресов на общих доменах (не сводят)
    телефон: bool


def разведка_из(r: dict) -> Разведка:
    """Строка lib_suppliers (словарь колонок) → ключи сопоставления."""
    сайты, общ1 = домены_сайта(r.get("site"))
    почты, общ2 = домены_почты(r.get("contact_email"))
    налоги = {("inn", x) for x in инн_из_текста(*(r.get(п) for п in ПОЛЯ_ТЕКСТА))}
    if инн(r.get("inn")):
        налоги.add(("inn", инн(r.get("inn"))))
    if vat(r.get("vat")):
        налоги.add(("vat", vat(r.get("vat"))))
    return Разведка(
        id=int(r["id"]), ключ=r.get("name_key"), имя=norm_name(r.get("name")),
        формы=форма(r.get("name")), страна=страна(r.get("country")),
        налоги=frozenset(налоги), сайты=frozenset(сайты), почты=frozenset(почты - сайты),
        общих=общ1 + общ2, телефон=bool(str(r.get("contact_phone") or "").strip()))


def корни(слито: dict[str, str | None]) -> dict[str, str]:
    """Сущность → корень цепочки слияний, как portal_companies и вид связи:
    A → B → C даёт C, не больше двадцати шагов; круг или цепочка длиннее —
    сущность остаётся собой."""
    out = {}
    for старт in слито:
        cur, шаг = старт, 0
        while слито.get(cur) and шаг < 20:
            cur = слито[cur]
            шаг += 1
        out[старт] = старт if слито.get(cur) else cur
    return out


class Реестр:
    """Признаки реестра компаний, разложенные по ключам сопоставления."""

    def __init__(self):
        self.корень: dict[str, str] = {}
        self.по_налогу: dict[tuple[str, str], set[str]] = collections.defaultdict(set)
        self.по_домену: dict[str, set[str]] = collections.defaultdict(set)
        self.по_имени: dict[str, set[str]] = collections.defaultdict(set)
        # По КОРНЮ: что знает о компании реестр целиком, со слитыми в неё.
        self.формы: dict[str, set[str]] = collections.defaultdict(set)
        self.домены: dict[str, set[str]] = collections.defaultdict(set)
        self.налоги: dict[str, set[tuple[str, str]]] = collections.defaultdict(set)
        self.страна: dict[str, str] = {}
        self.общих_доменов = 0


def собрать_реестр(сущности, признаки, имена_показа=()) -> Реестр:
    """сущности — [(id, merged_into, country, display_name)];
    признаки — [(sup_id, kind, value)] без отклонённых;
    имена_показа — [(sup_id, name, full_name, inn)] действующих строк
    sup_display_name (карточка и реквизиты Битрикса)."""
    р = Реестр()
    слито = {}
    for sid, merged, country, display in сущности:
        слито[sid] = merged
    р.корень = корни(слито)
    for sid, merged, country, display in сущности:
        к = р.корень[sid]
        if страна(country) and к not in р.страна:
            р.страна[к] = страна(country)
        _имя(р, sid, display)

    for sid, kind, value in признаки:
        к = р.корень.get(sid)
        if к is None:
            continue
        if kind == "inn" and инн(value):
            р.по_налогу[("inn", инн(value))].add(sid)
            р.налоги[к].add(("inn", инн(value)))
        elif kind == "vat" and vat(value):
            р.по_налогу[("vat", vat(value))].add(sid)
            р.налоги[к].add(("vat", vat(value)))
        elif kind == "domain":
            h = хост(value)
            if not _домен_годен(h):
                continue
            if общий_домен(h):
                р.общих_доменов += 1
                continue
            р.по_домену[h].add(sid)
            р.домены[к].add(h)
        elif kind in ("alias", "trading"):
            _имя(р, sid, value)
        elif kind == "legal":
            р.формы[к] |= форма(value)

    for sid, name, full_name, inn_ in имена_показа:
        к = р.корень.get(sid)
        if к is None:
            continue
        for n in (name, full_name):
            _имя(р, sid, n)
        if инн(inn_):
            р.по_налогу[("inn", инн(inn_))].add(sid)
            р.налоги[к].add(("inn", инн(inn_)))
    return р


def _имя(р: Реестр, sid: str, сырое) -> None:
    n = norm_name(сырое)
    if n:
        р.по_имени[n].add(sid)
    ф = форма(сырое)
    if ф:
        р.формы[р.корень[sid]] |= ф


