class Итог:
    """Что вышло. строки — к записи: (research_id, research_key, sup_id, rule,
    status, confidence, evidence, note); остальное — для счёта."""

    def __init__(self):
        self.строки: dict[tuple[int, str, str], tuple] = {}
        self.связь: dict[int, str] = {}                 # разведка → корень
        self.правила: dict[int, set[str]] = collections.defaultdict(set)
        self.спор_две: set[int] = set()                 # разведка → ≥2 корня
        self.спор_налог: set[int] = set()               # домен против налогового номера
        self.придержано: set[int] = set()               # только домены «площадок»
        self.доменов_придержано: set[str] = set()
        self.кандидаты: dict[int, dict[str, str]] = {}  # разведка → {корень: правило}
        self.отвергнуто: collections.Counter = collections.Counter()
        self.согласие: collections.Counter = collections.Counter()

    def строка(self, x: Разведка, sid: str, rule: str, status: str, conf: float,
               evidence: str, note: str | None = None) -> None:
        ключ = (x.id, sid, rule)
        прежняя = self.строки.get(ключ)
        # На одну пару одно правило пишется один раз: связь сильнее спора,
        # спор сильнее кандидата.
        порядок = {"link": 0, "conflict": 1, "candidate": 2}
        if прежняя and порядок[прежняя[4]] <= порядок[status]:
            return
        self.строки[ключ] = (x.id, x.ключ, sid, rule, status, conf, evidence, note)


def имён_на_домене(разведка: list[Разведка]) -> dict[str, int]:
    """Сколько РАЗНЫХ имён разведки носят домен. Без имени — сама строка."""
    имена: dict[str, set[str]] = collections.defaultdict(set)
    for x in разведка:
        for d in x.сайты | x.почты:
            имена[d].add(x.имя or f"#{x.id}")
    return {d: len(v) for d, v in имена.items()}


def имя_кандидата(x: Разведка, р: Реестр) -> tuple[dict[str, str], list[str]]:
    """Корни, на которые указывает имя, и почему отвергнуты остальные.
    Длина ключа здесь не судится — её порог ставит вызывающий."""
    годные: dict[str, str] = {}
    причины: list[str] = []
    свои_домены = x.сайты | x.почты
    for к in sorted({р.корень[s] for s in р.по_имени.get(x.имя, ())}):
        if налог_мешает(x.налоги, р.налоги.get(к, set())):
            причины.append("налоговые номера разные")
        elif x.формы and р.формы.get(к) and not (x.формы & р.формы[к]):
            причины.append("правовые формы разные")
        elif свои_домены and р.домены.get(к) and not (свои_домены & р.домены[к]):
            причины.append("домены разные")
        else:
            годные[к] = "имя+страна" if x.страна and р.страна.get(к) == x.страна else "имя"
    return годные, причины


def сопоставить(разведка: list[Разведка], р: Реестр, *,
                мин_длина: int = МИН_ДЛИНА_ИМЕНИ,
                макс_имён: int | None = МАКС_ИМЁН_НА_ДОМЕН) -> Итог:
    итог = Итог()
    на_домене = имён_на_домене(разведка)
    for x in разведка:
        совпало: list[tuple[str, str, str]] = []      # (правило, sup_id, значение)
        придержано: list[tuple[str, str, str]] = []
        for пара in sorted(x.налоги):
            for sid in sorted(р.по_налогу.get(пара, ())):
                совпало.append((ПРАВИЛО_НАЛОГА[пара[0]], sid, пара[1]))
        for правило, домены in (("домен сайта", x.сайты), ("домен почты", x.почты)):
            for d in sorted(домены):
                for sid in sorted(р.по_домену.get(d, ())):
                    много = макс_имён is not None and на_домене.get(d, 0) > макс_имён
                    (придержано if много else совпало).append((правило, sid, d))
                    if много:
                        итог.доменов_придержано.add(d)
        # Домен против налогового номера: у обеих сторон номер одного вида, и
        # он разный — один сайт у группы из разных юрлиц. Такой домен не сводит.
        против = [(п, sid, v) for п, sid, v in совпало
                  if п.startswith("домен") and налог_мешает(x.налоги, р.налоги.get(р.корень[sid], set()))]
        for п, sid, v in против:
            совпало.remove((п, sid, v))
            итог.строка(x, sid, п, "conflict", СИЛЬНЫЕ[п], v, "налоговые номера разные")
            итог.спор_налог.add(x.id)
        корни_x = {р.корень[sid] for _, sid, _ in совпало}
        if len(корни_x) == 1:
            итог.связь[x.id] = next(iter(корни_x))
            for п, sid, v in совпало:
                итог.строка(x, sid, п, "link", СИЛЬНЫЕ[п], v)
                итог.правила[x.id].add(п)
        elif len(корни_x) > 1:
            итог.спор_две.add(x.id)
            for п, sid, v in совпало:
                итог.строка(x, sid, п, "conflict", СИЛЬНЫЕ[п], v, "ключи ведут в разные сущности")
        for п, sid, v in придержано:
            итог.строка(x, sid, п, "conflict", СИЛЬНЫЕ[п], v, "домен носят много разных имён разведки")
        if придержано and not корни_x:
            итог.придержано.add(x.id)

        имя_годно = len(x.имя) >= мин_длина
        if x.id in итог.связь:
            # Мера точности имени: там, где есть сильная связь, куда указывает имя.
            if имя_годно and р.по_имени.get(x.имя):
                в_имени = {р.корень[s] for s in р.по_имени[x.имя]}
                связь = итог.связь[x.id]
                итог.согласие["совпало" if в_имени == {связь}
                              else "среди нескольких" if связь in в_имени else "мимо"] += 1
            continue
        if совпало or придержано or против or not имя_годно:
            continue
        годные, причины = имя_кандидата(x, р)
        for причина in причины:
            итог.отвергнуто[причина] += 1
        if годные:
            итог.кандидаты[x.id] = годные
            for к, правило in годные.items():
                итог.строка(x, к, правило, "candidate", КАНДИДАТ[правило], x.имя,
                            "совпало только имя — ждёт человека")
    return итог


# ── Счёт и печать (только агрегаты) ─────────────────────────────────────────

def доля(a: int, b: int) -> str:
    return f"{a} из {b} ({100 * a / b:.1f} %)" if b else f"{a} из 0"


def на_сущность(итог: Итог) -> collections.Counter:
    """Корень → сколько поставщиков разведки на нём держится."""
    return collections.Counter(итог.связь.values())


def сетка_имени(разведка: list[Разведка], р: Реестр, итог: Итог) -> list[tuple]:
    """(порог длины, кандидатов, из них однозначных, с совпавшей страной,
    проверяемых сильной связью, из них мимо) — для каждого порога сетки.
    Кандидатом считается только тот, у кого сильного совпадения нет вовсе."""
    сильные = set(итог.связь) | итог.спор_две | итог.спор_налог | итог.придержано
    строки = []
    for порог in СЕТКА_ДЛИНЫ:
        канд = одн = стр = пров = мимо = 0
        for x in разведка:
            if len(x.имя) < порог:
                continue
            if x.id in итог.связь:
                if р.по_имени.get(x.имя):
                    пров += 1
                    в_имени = {р.корень[s] for s in р.по_имени[x.имя]}
                    мимо += итог.связь[x.id] not in в_имени
                continue
            if x.id in сильные:
                continue
            годные, _ = имя_кандидата(x, р)
            if годные:
                канд += 1
                одн += len(годные) == 1
                стр += any(v == "имя+страна" for v in годные.values())
        строки.append((порог, канд, одн, стр, пров, мимо))
    return строки


def сетка_домена(разведка: list[Разведка], р: Реестр, рёбра: dict[int, tuple[int, int]]) -> list[tuple]:
    """(предел имён на домен, сведено, строк «кто делает» со ссылкой, споров
    «две сущности», придержано, наибольшее число разведки на одну сущность)."""
    out = []
    for предел in СЕТКА_ДОМЕНА:
        и = сопоставить(разведка, р, макс_имён=предел)
        св_рёбер = sum(рёбра.get(i, (0, 0))[0] for i in и.связь)
        наиб = max(на_сущность(и).values(), default=0)
        out.append((предел, len(и.связь), св_рёбер, len(и.спор_две), len(и.придержано), наиб))
    return out


def гейты(итог: Итог, разведка: list[Разведка], прежние: dict[int, str] | None) -> list[str]:
    провалы = []
    if len(итог.связь) < ГЕЙТЫ["мин_связей"]:
        провалы.append(f"связей {len(итог.связь)}, нужно не меньше {ГЕЙТЫ['мин_связей']} — "
                       "не прочиталась одна из сторон?")
    с_ключом = len(итог.связь) + len(итог.спор_две)
    if с_ключом and len(итог.спор_две) / с_ключом > ГЕЙТЫ["макс_доля_споров"]:
        провалы.append(f"споров «две сущности» {доля(len(итог.спор_две), с_ключом)}, "
                       f"порог {100 * ГЕЙТЫ['макс_доля_споров']:.0f} %")
    наиб = max(на_сущность(итог).values(), default=0)
    if наиб > ГЕЙТЫ["макс_разведки_на_сущность"]:
        провалы.append(f"на одну сущность сведено {наиб} поставщиков разведки, порог "
                       f"{ГЕЙТЫ['макс_разведки_на_сущность']} — просочилась площадка?")
    пров = sum(итог.согласие.values())
    if пров >= ГЕЙТЫ["мин_проверяемых"] and итог.согласие["мимо"] / пров > ГЕЙТЫ["макс_доля_мимо"]:
        провалы.append(f"имя указывает мимо сильной связи у {доля(итог.согласие['мимо'], пров)}, "
                       f"порог {100 * ГЕЙТЫ['макс_доля_мимо']:.0f} %")
    if прежние:
        хуже = sum(1 for i, к in прежние.items() if итог.связь.get(i) != к)
        предел = max(ГЕЙТЫ["мин_потерь"], ГЕЙТЫ["макс_доля_потерь"] * len(прежние))
        if хуже > предел:
            провалы.append(f"хуже стало у {хуже} из {len(прежние)} прежних связей "
                           f"(потеряна или сменила сущность), предел {предел:.0f}")
    return провалы


