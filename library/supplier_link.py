def есть(cur, имя: str) -> bool:
    cur.execute("select to_regclass(%s) is not null", (имя,))
    return bool(cur.fetchone()[0])


def колонки(cur, таблица: str) -> set[str]:
    """Инструмент чтения спрашивает у базы, какие колонки есть, прежде чем их
    запрашивать (CLAUDE.md, стиль работы)."""
    cur.execute("select column_name from information_schema.columns "
                "where table_schema = current_schema() and table_name = %s", (таблица,))
    return {r[0] for r in cur.fetchall()}


def читать(cur):
    """→ (разведка, реестр, рёбра {research_id: (строк, с проверкой)}, прежние
    связи {research_id: корень} или None, число сущностей)."""
    есть_колонки = колонки(cur, "lib_suppliers")
    поля = ["id", "name_key", "name", "country", "site", "contact_email", "contact_phone",
            "strengths", "certificates", "sanctions", "inn", "vat"]
    выбор = ", ".join(п if п in есть_колонки else f"null as {п}" for п in поля)
    cur.execute(f"select {выбор} from lib_suppliers order by id")
    имена = [d[0] for d in cur.description]
    разведка = [разведка_из(dict(zip(имена, r))) for r in cur.fetchall()]

    рёбра: dict[int, tuple[int, int]] = {}
    if есть(cur, "lib_part_suppliers"):
        проверка = ("count(*) filter (where verdict is not null)"
                    if "verdict" in колонки(cur, "lib_part_suppliers") else "0")
        cur.execute(f"select supplier_id, count(*), {проверка} from lib_part_suppliers group by 1")
        рёбра = {int(i): (int(a), int(b)) for i, a, b in cur.fetchall()}

    cur.execute("select id, merged_into, country, display_name from sup_entity")
    сущности = cur.fetchall()
    cur.execute("select sup_id, kind, value from sup_identifier where status <> 'rejected' "
                "and kind in ('inn', 'vat', 'domain', 'alias', 'trading', 'legal')")
    признаки = cur.fetchall()
    имена_показа = []
    if есть(cur, "sup_display_name"):
        cur.execute("select distinct on (sup_id, source) sup_id, name, full_name, inn "
                    "from sup_display_name where rolled_back_at is null "
                    "order by sup_id, source, id desc")
        имена_показа = cur.fetchall()
    р = собрать_реестр(сущности, признаки, имена_показа)

    прежние = None
    if есть(cur, "sup_research_link_live"):
        cur.execute("select research_id, sup_id from sup_research_link_live")
        прежние = {int(i): s for i, s in cur.fetchall()} or None
    return разведка, р, рёбра, прежние, len(сущности)


def записать(cur, итог: Итог, run_id: str) -> int:
    import psycopg2.extras
    строки = [(*s, run_id) for s in итог.строки.values()]
    psycopg2.extras.execute_values(cur, """
        insert into sup_research_link
          (research_id, research_key, sup_id, rule, status, confidence, evidence, note, run_id)
        values %s""", строки, page_size=1000)
    return len(строки)


def откатить(cur, run_id: str) -> int:
    cur.execute("update sup_research_link set rolled_back_at = now() "
                "where run_id = %s and rolled_back_at is null", (run_id,))
    return cur.rowcount


def прогон(conn, *, apply: bool, run_id: str, rollback: str = "") -> int:
    """Весь прогон на готовом соединении: откат, замер или замер с записью."""
    with conn.cursor() as cur:
        if rollback:
            if not есть(cur, "sup_research_link"):
                print("таблицы sup_research_link нет — откатывать нечего", file=sys.stderr)
                return 3
            n = откатить(cur, rollback)
            conn.commit()
            print(f"откат прогона: помечено строк {n}")
            if not n:
                print("ни одной действующей строки с таким ключом — ключ набран неверно?",
                      file=sys.stderr)
                return 3
            print("действующим снова стал прежний прогон (если он был)")
            return 0
        for опора in ("lib_suppliers", "sup_entity", "sup_identifier"):
            if not есть(cur, опора):
                print(f"нет таблицы {опора} — сопоставлять не с чем", file=sys.stderr)
                return 2
        if apply and not есть(cur, "sup_research_link"):
            print("запись запрошена, но таблицы sup_research_link нет — примените "
                  "library/supabase/supplier_link_schema.sql", file=sys.stderr)
            return 2
        разведка, р, рёбра, прежние, сущностей = читать(cur)
        итог = сопоставить(разведка, р)
        печать(разведка, р, итог, рёбра, прежние, сущностей)

        провалы = гейты(итог, разведка, прежние)
        print()
        if провалы:
            print("ГЕЙТЫ НЕ СОШЛИСЬ:")
            for p in провалы:
                print(f"  ✗ {p}")
            print("Запись отменена — так и задумано: правило меряют до применения.")
            conn.rollback()
            return 1
        print("гейты: сошлись все")
        if not apply:
            conn.rollback()
            print("Прогон ВХОЛОСТУЮ: в базу ничего не записано.")
            return 0
        n = записать(cur, итог, run_id)
        conn.commit()
    по_статусу = collections.Counter(s[4] for s in итог.строки.values())
    print(f"\nЗАПИСАНО, ключ прогона {run_id}: строк {n} — связей {по_статусу['link']}, "
          f"споров {по_статусу['conflict']}, кандидатов {по_статусу['candidate']}")
    print(f"Откат: ROLLBACK_RUN_ID={run_id} (строки помечаются, не удаляются).")
    return 0


def main() -> int:
    url = os.environ.get("SUPABASE_DB_URL", "")
    if not url:
        print("нет переменной SUPABASE_DB_URL", file=sys.stderr)
        return 2
    apply = os.environ.get("APPLY", "") not in ("", "0", "false")
    rollback = os.environ.get("ROLLBACK_RUN_ID", "").strip()
    run_id = os.environ.get("RUN_ID", "").strip() or f"link-{int(time.time())}"

    import psycopg2
    # statement_timeout — в строке подключения, а не через SET (правило 9).
    conn = psycopg2.connect(url, connect_timeout=20,
                            options="-c statement_timeout=300000 -c lock_timeout=30000")
    try:
        if not apply and not rollback:
            conn.set_session(readonly=True)
        return прогон(conn, apply=apply, run_id=run_id, rollback=rollback)
    finally:
        conn.close()


if __name__ == "__main__":
    raise SystemExit(main())
