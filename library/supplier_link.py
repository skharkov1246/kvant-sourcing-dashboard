#!/usr/bin/env python3
"""Связь двух реестров поставщиков: разведка → реестр компаний. Вхолостую по умолчанию.

ЗАЧЕМ. Шаг 4 плана «одна стартовая страница». Поставщики живут в двух реестрах
без связи: реестр компаний портала (sup_entity с вечным номером KV-S и
признаками sup_identifier) и реестр разведки (lib_suppliers — кто делает, и
lib_part_suppliers — «деталь → исполнитель» с проверкой наличия). Карточка кода
показывает «кто делает» именами разведки без ссылки, а поставщик разведки,
которого давно знает Битрикс, выглядит чужим. Мерило шага — доля поставщиков
разведки, сведённых с реестром компаний. Рядом — то, ради чего связь делается
(правило 0а): доля строк «кто делает», получивших ссылку на карточку компании.

ЧТО СВОДИТ — только сильные ключи, закрытым списком (правило 7: обвинять только
закрытым списком, защищать щедро):
  инн, vat     — налоговый номер точно. ИНН — с верной контрольной суммой
                 (company_names.инн_верен). У разведки колонки ИНН нет; он
                 берётся из колонки, если её заведут, и из текста «ИНН …»;
  домен сайта  — точно, тем же разбором адреса, каким сведение пишет признак
                 domain (supplier_registry_overlap.хост / norm_domain);
  домен почты  — то же по адресу почты: сведение берёт домен почты, когда
                 сайта нет, поэтому и признак реестра бывает им.
НЕ СВОДИТ НИКОГДА:
  · общий домен — почтовый хостинг, площадка, соцсеть, конструктор сайтов,
    справочник компаний (закрытый список supplier_registry_overlap.общий_домен);
  · домен, который в разведке носят больше МАКС_ИМЁН_НА_ДОМЕН разных имён: так
    выглядит площадка, которой в списке нет. Пара пишется спором, а не связью;
  · ключи, ведущие в две разные сущности (по корню цепочки слияний), — спор;
  · домен, против которого говорит налоговый номер (он есть у обеих сторон и
    разный): один сайт у группы из разных юрлиц — спор.
ТОЛЬКО КАНДИДАТ — имя. Ключ имени — norm_name, ТО ЖЕ правило, каким сведение
пишет написания реестра (alias): ключ написания бренда (codes_sql.LEGAL_FORMS_KEY)
режет другой набор форм, и с написаниями реестра он бы не сошёлся. Кандидат не
пишется, если против говорят правовая форма («ООО Ромашка» и «АО Ромашка» —
разные юрлица), домен или налоговый номер, и если ключ короче МИН_ДЛИНА_ИМЕНИ.
Совпала ещё и страна — правило «имя+страна», иначе «имя». Страна кандидата
только повышает, но не отвергает: «Германия» и «Germany» без словаря стран
неотличимы от разных стран.

ЧТО ПЕЧАТАЕТ — только агрегаты (правило 17): ни имени, ни домена, ни ИНН.
  · какие ключи есть у каждой стороны;
  · сколько поставщиков разведки сведено каждым ключом и всего — мерило шага;
  · доля строк «кто делает» (lib_part_suppliers), чей исполнитель сведён, и
    отдельно — строк с проверкой наличия;
  · споры: разведка → две сущности; сущность ← много поставщиков разведки;
    придержано доменом, который носит слишком много имён;
  · кандидаты по имени и почему отвергнуты; согласие имени с сильной связью —
    там, где есть оба, это единственная мера точности имени, какая у нас есть;
  · сетки порогов (правило 4): длина ключа имени и предел имён на домен;
  · сравнение с действующим прогоном: сколько связей потеряно и сколько
    сменило сущность — у скольких стало хуже (правило 0).

ЗАПИСЬ — APPLY=1: строки в sup_research_link с ключом прогона, одной
транзакцией; непройденный гейт отменяет запись целиком. Откат —
ROLLBACK_RUN_ID: строки прогона помечаются rolled_back_at, и действующим снова
становится прежний прогон (правило 5 — пометка, а не удаление).

ОДНОЙ ЧАСТЬЮ, И ЭТО РЕШЕНИЕ. Правило дробления требует частей там, где упавшая
часть уносит свою долю работы. Здесь чтения два — около пяти тысяч строк
разведки и десятков тысяч признаков реестра, секунды, — а спор «одна сущность
← много поставщиков разведки» и «домен носят много имён» считаются только по
всему реестру сразу: деление по частям их бы не увидело. Запись — одна
транзакция на несколько тысяч строк. Битрикс не читается вовсе.

    python library/supplier_link.py                          # вхолостую
    APPLY=1 RUN_ID=link-1 python library/supplier_link.py    # запись
    ROLLBACK_RUN_ID=link-1 python library/supplier_link.py   # откат
"""
