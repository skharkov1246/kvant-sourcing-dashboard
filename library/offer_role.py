def нет_бренда(написание) -> bool:
    """Пусто, пометка незнания или указание к закупке — бренда нет."""
    s = str(написание or "").strip()
    return (not s or len(codes_sql.ключ_написания(s)) < 2 or brand_registry.пометка_незнания(s)
            or oem_kind.указание(s) is not None)


def бренды_позиции(написания, р: Реестр) -> set[str]:
    """Написания бренда позиции → ключи брендов. Неразрешённое написание остаётся
    своим ключом с префиксом «~»: бренд вне реестра — всё равно бренд."""
    out = set()
    for н in написания:
        if нет_бренда(н):
            continue
        сост, ключи = brand_registry.разрешить(н, р.карта)
        if сост == brand_registry.ОЧЕРЕДЬ:
            kk = codes_sql.ключ_написания(н)
            ключи = р.канон.get(транслит(kk)) or (р.остовы.get(остов(kk)) if len(остов(kk)) >= ОСТОВ_ОТ else None)
            ключи = set(ключи or {"~" + kk})
        out |= ключи
    return out


def варианты_имени(имя) -> list[str]:
    """Ключи имени компании целиком: как есть, без страны через разделитель, без
    хвоста-страны. Части «A / B» сюда не входят — их судит бренды_имени."""
    out = []
    for н in (имя, codes_sql.без_страны(имя), без_хвоста(имя), без_хвоста(codes_sql.без_страны(имя))):
        kk = codes_sql.ключ_написания(н or "")
        if len(kk) >= 2 and kk not in out:
            out.append(kk)
    return out


def _свести_ключ(kk: str, р: "Реестр") -> tuple[set, str]:
    if kk in р.карта_компании:
        return set(р.карта_компании[kk]), "имя"
    if _кириллица(kk) and транслит(kk) in р.канон:
        return set(р.канон[транслит(kk)]), "транслит"
    if len(остов(kk)) >= ОСТОВ_ОТ and остов(kk) in р.остовы:
        return set(р.остовы[остов(kk)]), "транслит"
    return set(), ""


def бренды_имени(имя, р: Реестр) -> tuple[set, str]:
    """Имя компании → (ключи брендов, путь «имя» | «транслит»); не свелось — (∅, "").

    Сначала имя целиком (с хвостом и без). Не свелось — части «A / B», «A (B)»,
    и только если свелась КАЖДАЯ часть: «Siemens / Сименс» — Siemens, а
    «Ромашка (SKF)» — не SKF: часть «Ромашка» бренда не называет."""
    for kk in варианты_имени(имя):
        ключи, путь = _свести_ключ(kk, р)
        if ключи:
            return ключи, путь
    части = [ч for ч in brands._ЧАСТИ_ИМЕНИ.split(str(имя or "")) if len(codes_sql.ключ_написания(ч)) >= 2]
    if len(части) < 2:
        return set(), ""
    ключи, пути = set(), set()
    for ч in части:
        кч, пч = set(), ""
        for kk in варианты_имени(ч):
            кч, пч = _свести_ключ(kk, р)
            if кч:
                break
        if not кч:
            return set(), ""
        ключи |= кч
        пути.add(пч)
    return ключи, ("транслит" if "транслит" in пути else "имя")


# Метки второго уровня, после которых имя компании стоит третьей меткой:
# skf.co.uk, siemens.com.cn.
_ВТОРЫЕ = frozenset({"co", "com", "net", "org", "ac", "gov", "edu", "ltd", "plc", "or", "ne", "spb", "msk"})


def метка_домена(домен) -> str:
    """Домен → метка имени: www.siemens.ru → siemens, skf.co.uk → skf; общий — «»."""
    if str(ROOT / "scripts") not in sys.path:
        sys.path.insert(0, str(ROOT / "scripts"))
    import supplier_registry_overlap as sro
    h = sro.хост(str(домен or ""))
    if not h or sro.общий_домен(h):
        return ""
    м = h.split(".")
    if len(м) >= 3 and м[-2] in _ВТОРЫЕ:
        return м[-3]
    return м[-2] if len(м) >= 2 else ""


def связь(c: str, b: str, р: Реестр) -> str | None:
    """Ключ бренда компании c против ключа бренда позиции b → связь или None."""
    if c == b:
        return ТОТ_ЖЕ
    if c.startswith("~") or b.startswith("~") or not р.владение:
        return None
    вверх_b = [x["key"] for x in brand_owner.цепочка_владельцев(b, р.владение) if x.get("key")]
    if c in вверх_b:
        return ВЛАДЕЛЕЦ
    вверх_c = [x["key"] for x in brand_owner.цепочка_владельцев(c, р.владение) if x.get("key")]
    if b in вверх_c:
        return ДОЧЕРНЯЯ
    if set(вверх_b) & set(вверх_c):
        return ГРУППА
    return None


def _лучшая(компании: set, позиции: set, р: Реестр) -> tuple[str | None, str | None, str | None]:
    """(связь, ключ компании, ключ позиции) — сильнейшая из прямых связей."""
    лучшая = (None, None, None)
    for c in sorted(компании):
        for b in sorted(позиции):
            с = связь(c, b, р)
            if с in (ТОТ_ЖЕ, ВЛАДЕЛЕЦ, ДОЧЕРНЯЯ):
                if лучшая[0] is None or (ТОТ_ЖЕ, ВЛАДЕЛЕЦ, ДОЧЕРНЯЯ).index(с) < (
                        ТОТ_ЖЕ, ВЛАДЕЛЕЦ, ДОЧЕРНЯЯ).index(лучшая[0]):
                    лучшая = (с, c, b)
    return лучшая


def узел(адрес) -> str:
    """Адрес сайта или почты → узел тем же разбором, каким сведение реестров
    пишет признак domain (supplier_registry_overlap.хост); общий — «»."""
    if str(ROOT / "scripts") not in sys.path:
        sys.path.insert(0, str(ROOT / "scripts"))
    import supplier_registry_overlap as sro
    h = sro.хост(str(адрес or "").rsplit("@", 1)[-1])
    return "" if not h or sro.общий_домен(h) else h


def дилер_по_ключу(домены, инн, р: Реестр) -> set[tuple[str, str, str]]:
    """Записи dealers разведки, чей домен или ИНН — домен или ИНН компании:
    {(ключ бренда, вид записи, «домен» | «инн»)}. Домен сравнивается точно,
    узлом, как в сведении реестров: поддомен чужого сайта — не он."""
    out = set()
    for d in домены:
        for k, вид in р.дилеры_ключ.get(("домен", узел(d)), ()):
            out.add((k, вид, "домен"))
    for x in инн:
        for k, вид in р.дилеры_ключ.get(("инн", re.sub(r"\D", "", str(x))), ()):
            out.add((k, вид, "инн"))
    return out


def _ответ(роль, почему, **доказательство) -> dict:
    assert почему in ПРИЧИНЫ[роль], почему
    return {"role": роль, "why": почему, "evidence": {k: v for k, v in доказательство.items()
                                                      if v not in (None, "", [], ())}}


def роль_предложения(компания, бренд_позиции, *, домены=(), инн=(), карта_инн=None,
                     реестр: Реестр | None = None) -> dict:
    """Роль предложения: {"role": «прямое» | «трейдер» | «не определено», "why", "evidence"}.

    компания      — имя компании КП (как в реестре компаний);
    бренд_позиции — написание бренда позиции или несколько написаний;
    домены        — домены сайта и почты компании; общие (почтовые хостинги,
                    площадки) не опознают;
    инн, карта_инн — ИНН компании и карта «ИНН → ключ бренда» (пока у нас её нет:
                    ИНН сведётся, когда карту заведут);
    реестр        — Реестр; по умолчанию — из файлов репозитория.

    evidence — без имени компании: via (путь), company (ключи бренда компании),
    position (ключи бренда позиции), relation, marker (признаки трейдера), key
    (сильный ключ записи разведки: «домен», «инн»)."""
    р = реестр or реестр_файлов()
    написания = [бренд_позиции] if isinstance(бренд_позиции, str) or бренд_позиции is None else list(бренд_позиции)
    позиции = бренды_позиции(написания, р)
    if not позиции:
        return _ответ(НЕ_ОПРЕДЕЛЕНО, "нет бренда позиции")
    pos = sorted(позиции)
    имя = str(компания or "").strip()
    домены = [домены] if isinstance(домены, str) else list(домены or ())
    инн = [инн] if isinstance(инн, str) else list(инн or ())
    if not имя and not домены and not инн:
        return _ответ(НЕ_ОПРЕДЕЛЕНО, "нет компании", position=pos)

    # 1. Сильные ключи: ИНН, домен. Против них имя не спорит. Порядок: ИНН по
    # карте брендов; затем запись dealers разведки, сведённая доменом или ИНН
    # (тем же ключом, каким library/dealer_link.py сводит дилера с реестром
    # компаний); затем метка домена. Запись разведки — раньше метки: сайт
    # дилера бывает назван именем бренда (jichai.ru у дистрибьютора), и метка
    # сочла бы дилера самим брендом.
    с, c, b = _лучшая({(карта_инн or {}).get(re.sub(r"\D", "", str(x))) for x in инн} - {None}, позиции, р)
    if с:
        return _ответ(ПРЯМОЕ, f"инн: {с}", via="инн", company=[c], position=[b], relation=с)
    найдено = дилер_по_ключу(домены, инн, р)
    for вид in (СВОЯ, ОФИЦИАЛЬНЫЙ, ДИЛЕР):
        с, c, b = _лучшая({k for k, в, _ in найдено if в == вид}, позиции, р)
        if not с:
            continue
        ключ = sorted({кл for k, в, кл in найдено if в == вид and k == c})
        if вид == СВОЯ:
            return _ответ(ПРЯМОЕ, f"разведка: {с}", via="разведка", key=ключ, company=[c], position=[b],
                          relation=с)
        return _ответ(ТРЕЙДЕР, "официальный дилер" if вид == ОФИЦИАЛЬНЫЙ else "дилер бренда по разведке",
                      via="разведка", key=ключ, company=[c], position=pos)
    по_домену = set().union(*[р.карта_компании.get(codes_sql.ключ_написания(метка_домена(d)), set())
                              for d in домены if метка_домена(d)] or [set()])
    с, c, b = _лучшая(по_домену, позиции, р)
    if с:
        return _ответ(ПРЯМОЕ, f"домен: {с}", via="домен", company=[c], position=[b], relation=с)

    варианты = варианты_имени(имя) if имя else []
    # 2. Разведка брендов: своя площадка бренда — прямое; дилер — трейдер.
    свои = set().union(*[р.свои.get(kk, set()) for kk in варианты] or [set()])
    с, c, b = _лучшая(свои, позиции, р)
    if с:
        return _ответ(ПРЯМОЕ, f"разведка: {с}", via="разведка", company=[c], position=[b], relation=с)
    дилер = set().union(*[р.дилеры.get(kk, set()) for kk in варианты] or [set()])
    if any(связь(x, b_, р) in (ТОТ_ЖЕ, ВЛАДЕЛЕЦ, ДОЧЕРНЯЯ) for x in дилер for b_ in позиции):
        return _ответ(ТРЕЙДЕР, "дилер бренда по разведке", via="разведка", position=pos)

    # 3. Имя. Признак трейдера, которого нет в собственном имени бренда, обвиняет.
    ключи, путь = бренды_имени(имя, р) if имя else (set(), "")
    признаки = признаки_трейдера(имя)
    чужие = [x for x in признаки if not any(x in р.признаки_бренда.get(k, ()) for k in ключи)]
    if чужие:
        return _ответ(ТРЕЙДЕР, "признак трейдера в имени", via=путь or None, company=sorted(ключи),
                      position=pos, marker=чужие)
    if not ключи:
        # Вне реестра: имя и бренд позиции сравниваются ключом — бренд, которого
        # реестр не знает, всё равно может сам прислать КП («Ромашкамаш»).
        свои_ключи = {"~" + kk for kk in варианты}
        с, c, b = _лучшая(свои_ключи, позиции, р)
        if с:
            return _ответ(ПРЯМОЕ, f"имя: {с}", via="имя", company=[c], position=[b], relation=с)
    else:
        с, c, b = _лучшая(ключи, позиции, р)
        if с:
            if len(ключи) > 1:
                return _ответ(НЕ_ОПРЕДЕЛЕНО, "имя спорно между брендами", via=путь,
                              company=sorted(ключи), position=pos)
            return _ответ(ПРЯМОЕ, f"{путь}: {с}", via=путь, company=[c], position=[b], relation=с)

    # 4. Трейдер — с причиной.
    суб = set().union(*[р.субпоставщики.get(kk, set()) for kk in варианты] or [set()])
    if any(связь(x, b_, р) in (ТОТ_ЖЕ, ВЛАДЕЛЕЦ, ДОЧЕРНЯЯ) for x in суб for b_ in позиции):
        return _ответ(ТРЕЙДЕР, "субпоставщик бренда по разведке", via="разведка", position=pos)
    if ключи and any(связь(c, b_, р) == ГРУППА for c in ключи for b_ in позиции):
        return _ответ(ТРЕЙДЕР, "другой бренд той же группы", via=путь, company=sorted(ключи), position=pos)
    if ключи:
        return _ответ(ТРЕЙДЕР, "компания — другой бренд", via=путь, company=sorted(ключи), position=pos)
    return _ответ(ТРЕЙДЕР, "имя не бренд", position=pos)
