"""Дата квотации: когда поставщик назвал цену — и откуда мы это знаем.

Распоряжение владельца 24.09.2026: «Важно иметь в виду месяц и год получения
квотации, чтобы индексировать их на инфляцию в конкретно выбранной стране».
До этой правки lib_prices.price_date у цен из КП не заполнялся вовсе, и
карточка номенклатуры показывала вместо даты предложения дату РАЗБОРА — день,
когда наш прогон дошёл до файла. Для индексации это худшая из ошибок: цена
двухлетней давности выглядела вчерашней.

ИСТОЧНИКИ — ПО УБЫВАНИЮ НАДЁЖНОСТИ, каждый пишется в price_date_src (правило 16):

  документ           — дата, названная в самом КП: «КП № 15 от 12.03.2025»,
                       «Дата: 12.03.2025», «Quotation date: 12 March 2025»,
                       «Исх. № 77 от …». Точность — день;
  письмо             — дата письма (.eml/.msg): читатель писем выводит её строкой
                       «Дата: ГГГГ-ММ-ДД ЧЧ:ММ» (library/read_mail.py). Это день,
                       когда предложение пришло;
  карточка: создана  — createdTime карточки запроса СП-166. Это НИЖНЯЯ граница:
                       предложение не может прийти раньше, чем мы запросили,
                       и обычно приходит в пределах недель. Для индексации по
                       месяцу — приемлемое приближение, но не дата документа;
  нет                — искали в тексте и на карточке, не нашли.

ДАТЫ ЗАГРУЗКИ ФАЙЛА НЕТ, И ЭТО ИЗМЕРЕНО, А НЕ ПРОПУЩЕНО. Файловое поле карточки
CRM отдаёт ровно три значения: id (идентификатор файла CRM — «на Диске такого
объекта нет, методам Диска это число передавать нельзя»), url и urlMachine
(документация REST Битрикс24, раздел о скачивании файла из поля элемента CRM).
Ни даты, ни автора. Дата изменения карточки (updatedTime) меняется от любой
правки, а не только от вложения, поэтому датой файла её не называем.

ДАТА РАЗБОРА НЕ ПИШЕТСЯ НИКОГДА. Пустая дата с источником «нет» честнее
правдоподобной неправды.

ЧЕГО ИЗВЛЕЧЕНИЕ НЕ ДЕЛАЕТ (правило 7: обвинять только закрытым списком, здесь —
«принимать»): не берёт дату, у которой слева стоит «действительно до», «срок
поставки», «договор», «ГОСТ», «ваш запрос» и подобное из ЧУЖИЕ; не угадывает
порядок дня и месяца в «03/04/2025» — такая дата неоднозначна, и её не берём;
не принимает дату из будущего и дату, которая старше карточки больше чем на два
года (почти наверняка ссылка на старый договор или стандарт).
"""

from __future__ import annotations

import re
from datetime import date, datetime, timedelta, timezone
from email.utils import parsedate_to_datetime

ДОКУМЕНТ = "документ"
ПИСЬМО = "письмо"
КАРТОЧКА = "карточка: создана"
НЕТ = "нет"
#: Значения price_date_src — тот же список стоит в проверке схемы
#: (lib_prices_price_date_src_chk, library/supabase/schema.sql).
ИСТОЧНИКИ = (ДОКУМЕНТ, ПИСЬМО, КАРТОЧКА, НЕТ)

#: Раньше этого КП у нас не бывает: всё, что старше, — год стандарта или договора.
НИЖНЯЯ = date(2000, 1, 1)
#: Документ, датированный будущим, — это срок действия или поставки, а не дата КП.
#: Сутки запаса — на часовые пояса.
ВПЕРЁД_ДНЕЙ = 1
#: Насколько дата документа может быть старше карточки запроса.
НАЗАД_ОТ_КАРТОЧКИ_ДНЕЙ = 730
#: Дата без подписи, но после «от», принимается только в шапке документа.
ГОЛОВА = 3000
#: Сколько знаков слева от даты смотрим на подпись и на чужой смысл.
ОКНО = 60

МЕСЯЦЫ = {
    # русский: родительный и именительный падеж, сокращения
    "январ": 1, "феврал": 2, "март": 3, "апрел": 4, "ма": 5, "июн": 6,
    "июл": 7, "август": 8, "сентябр": 9, "октябр": 10, "ноябр": 11, "декабр": 12,
    "янв": 1, "фев": 2, "мар": 3, "апр": 4, "авг": 8, "сен": 9, "сент": 9,
    "окт": 10, "ноя": 11, "дек": 12,
    # английский
    "january": 1, "february": 2, "march": 3, "april": 4, "may": 5, "june": 6,
    "july": 7, "august": 8, "september": 9, "october": 10, "november": 11,
    "december": 12, "jan": 1, "feb": 2, "apr": 4, "jun": 6, "jul": 7, "aug": 8,
    "sep": 9, "sept": 9, "oct": 10, "nov": 11, "dec": 12,
}
_РУ_МЕСЯЦ = (r"январ[яь]|феврал[яь]|марта?|апрел[яь]|ма[яй]|июн[яь]|июл[яь]|августа?"
             r"|сентябр[яь]|октябр[яь]|ноябр[яь]|декабр[яь]")
_EN_МЕСЯЦ = (r"january|february|march|april|may|june|july|august|september|october"
             r"|november|december|jan|feb|mar|apr|jun|jul|aug|sept|sep|oct|nov|dec")

# Числовая дата: 12.03.2025, 12-03-2025, 12/03/2025, 12.03.25.
_ЧИСЛО = re.compile(r"(?<![\d.,/-])(\d{1,2})([./-])(\d{1,2})\2(\d{4}|\d{2})(?!\d|[.,/-]\d)")
_ISO = re.compile(r"(?<![\d.])(\d{4})-(\d{2})-(\d{2})(?![\d])")
_РУ_ТЕКСТ = re.compile(r"(?<!\d)[«\"]?(\d{1,2})[»\"]?\s+(" + _РУ_МЕСЯЦ + r")\s+(\d{4})",
                       re.IGNORECASE)
_EN_ДМГ = re.compile(r"(?<!\d)(\d{1,2})(?:st|nd|rd|th)?[\s-]+(" + _EN_МЕСЯЦ
                     + r")\.?[\s,-]+(\d{4})(?!\d)", re.IGNORECASE)
_EN_МДГ = re.compile(r"\b(" + _EN_МЕСЯЦ + r")\.?\s+(\d{1,2})(?:st|nd|rd|th)?,?\s+(\d{4})(?!\d)",
                     re.IGNORECASE)

#: Строка шапки письма, как её пишет library/read_mail.py (_Сбор.письмо).
_ПИСЬМО = re.compile(r"^Дата: (\d{4}-\d{2}-\d{2}) \d{2}:\d{2}\s*$", re.MULTILINE)
#: СЫРОЙ ЗАГОЛОВОК ПИСЬМА. Без каскада (CASCADE пуст — так идут ночной и
#: ежедневный разбор) .eml читается простым текстом, и заголовок «Date: Wed, 12
#: Mar 2025 10:00:00 +0300» стоит в тексте как есть. Письмом считается только
#: строка, которую разбирает email.utils — формат RFC 5322, а не любое «Date:».
_ПИСЬМО_СЫРОЕ = re.compile(r"^Date:[ \t]*([^\r\n]+?)[ \t]*\r?$", re.MULTILINE)

#: Подпись, прямо называющая дату документа. Проверяется по хвосту строки слева.
_ПОДПИСЬ = re.compile(
    r"(дата\s+(коммерческого\s+)?(кп|предложения|документа|письма|составления)"
    r"|дата\s*[:：]?|date\s+of\s+(the\s+)?(offer|quotation|quote|proposal|issue)"
    r"|(quotation|quote|offer|proposal|issue)\s+date|\bdate\s*[:：]?|\bdated|datum\s*[:：]?"
    r"|(кп|к\.п\.|коммерческое\s+предложение|предложение|ткп|quotation|offer|quote|proposal)"
    r"\b[^\n]{0,40}?(\bот|\bdated|\bof)"
    r"|исх(одящий|\.)?[^\n]{0,30}?\bот)\s*[:：]?\s*$",
    re.IGNORECASE)
#: «от» без подписи — дата в шапке («№ 15 от 12.03.2025»).
_ОТ = re.compile(r"(\bот|\bdated)\s*$", re.IGNORECASE)
#: Граница оборота слева от даты: точка с запятой, табуляция, черта, два пробела
#: или точка перед пробелом и заглавной (конец фразы, но не «Исх.» и не «К.П.»).
_ОБОРОТ = re.compile(r"[;|\t]|\s{2,}|[.!?]\s+(?=[A-ZА-ЯЁ])")
#: Сколько знаков оборота смотрим на чужой смысл.
ОКНО_ЧУЖОГО = 35
#: ЧУЖОЙ СМЫСЛ: такая дата — не дата предложения. Закрытый список.
_ЧУЖИЕ = re.compile(
    r"действ|valid|until|expir|истека|\bдо\b|\bпо\b\s*$|срок|поставк|отгруз|deliver|ship"
    r"|договор|контракт|contract|agreement|гост|\bту\b|\bost\b|din\b|iso\b|рожд|birth"
    r"|запрос|request|rfq|inquiry|enquiry|заявк|тендер|tender|закупк|счет|счёт|invoice"
    r"|оплат|payment|изготовл|производств|manufactur|выпуск|сертифик|certific|паспорт"
    r"|лиценз|licen|регистрац|приказ|постановлен",
    re.IGNORECASE)


def _дата(год: int, месяц: int, день: int) -> date | None:
    if год < 100:
        год += 2000
    try:
        return date(год, месяц, день)
    except ValueError:
        return None


def _месяц(слово: str) -> int | None:
    с = слово.lower().rstrip(".")
    if с in МЕСЯЦЫ:
        return МЕСЯЦЫ[с]
    for длина in (7, 6, 5, 4, 3):
        if с[:длина] in МЕСЯЦЫ:
            return МЕСЯЦЫ[с[:длина]]
    return МЕСЯЦЫ.get(с[:2]) if с.startswith("ма") else None


def даты_в_тексте(текст: str) -> list[tuple[int, date | None, str]]:
    """Все даты текста: (позиция, дата или None у неоднозначной, вид записи)."""
    out: list[tuple[int, date | None, str]] = []
    for m in _ЧИСЛО.finditer(текст):
        а, разд, б, г = int(m.group(1)), m.group(2), int(m.group(3)), m.group(4)
        if разд == "/" and а <= 12 and б <= 12 and а != б:
            # 03/04/2025 — третье апреля или четвёртое марта: не угадываем.
            out.append((m.start(), None, "число"))
            continue
        if разд == "/" and а <= 12 < б:
            а, б = б, а                               # американская запись
        out.append((m.start(), _дата(int(г), б, а), "число" if len(г) == 4 else "число2"))
    for m in _ISO.finditer(текст):
        out.append((m.start(), _дата(int(m.group(1)), int(m.group(2)), int(m.group(3))), "iso"))
    for m in _РУ_ТЕКСТ.finditer(текст):
        мес = _месяц(m.group(2))
        out.append((m.start(), _дата(int(m.group(3)), мес, int(m.group(1))) if мес else None,
                    "слово"))
    for m in _EN_ДМГ.finditer(текст):
        мес = _месяц(m.group(2))
        out.append((m.start(), _дата(int(m.group(3)), мес, int(m.group(1))) if мес else None,
                    "слово"))
    for m in _EN_МДГ.finditer(текст):
        мес = _месяц(m.group(1))
        out.append((m.start(), _дата(int(m.group(3)), мес, int(m.group(2))) if мес else None,
                    "слово"))
    out.sort(key=lambda x: x[0])
    return out


def _в_пределах(д: date | None, сегодня: date, карточка: date | None) -> bool:
    if д is None or д < НИЖНЯЯ or д > сегодня + timedelta(days=ВПЕРЁД_ДНЕЙ):
        return False
    if карточка and д < карточка - timedelta(days=НАЗАД_ОТ_КАРТОЧКИ_ДНЕЙ):
        return False
    return True


def дата_документа(текст: str, сегодня: date, карточка: date | None = None) -> date | None:
    """Дата, которую КП называет своей. Строки шапки письма не в счёт.

    Приоритет: подпись («Дата:», «КП … от», «Quotation date») → «от» в шапке
    документа. Внутри одного приоритета — первая по тексту. Двузначный год
    принимается только при подписи: «6.3.25» без неё слишком похоже на номер.
    """
    if not текст:
        return None
    без_писем = текст
    for поз, конец, _д in _строки_писем(текст):
        без_писем = без_писем[:поз] + " " * (конец - поз) + без_писем[конец:]
    лучшая: tuple[int, int, date] | None = None
    for поз, д, вид in даты_в_тексте(без_писем):
        if not _в_пределах(д, сегодня, карточка):
            continue
        начало_строки = без_писем.rfind("\n", 0, поз) + 1
        слева = без_писем[max(начало_строки, поз - ОКНО):поз]
        # Чужой смысл ищется только в своём обороте: «Цены с доставкой до склада.
        # Дата: 12.03.2025» — «до» относится к соседней фразе, а не к дате.
        if _ЧУЖИЕ.search(_ОБОРОТ.split(слева)[-1][-ОКНО_ЧУЖОГО:]):
            continue
        if _ПОДПИСЬ.search(слева):
            ранг = 0
        elif поз < ГОЛОВА and _ОТ.search(слева) and вид != "число2":
            ранг = 1
        else:
            continue
        if лучшая is None or (ранг, поз) < лучшая[:2]:
            лучшая = (ранг, поз, д)
    return лучшая[2] if лучшая else None


def _строки_писем(текст: str) -> list[tuple[int, int, date]]:
    """Строки шапок писем: (начало, конец, дата) — от читателя и сырые, по порядку."""
    out = []
    for m in _ПИСЬМО.finditer(текст or ""):
        try:
            out.append((m.start(), m.end(), date.fromisoformat(m.group(1))))
        except ValueError:
            continue
    for m in _ПИСЬМО_СЫРОЕ.finditer(текст or ""):
        try:
            out.append((m.start(), m.end(), parsedate_to_datetime(m.group(1)).date()))
        except (TypeError, ValueError, IndexError):
            continue
    return sorted(out)


def дата_письма(текст: str, сегодня: date, карточка: date | None = None) -> date | None:
    """Дата верхнего письма: первая шапка письма в тексте (вложенные — ниже)."""
    for _поз, _конец, д in _строки_писем(текст):
        if _в_пределах(д, сегодня, карточка):
            return д
    return None


def дата_карточки(значение) -> date | None:
    """createdTime карточки («2024-07-22T18:00:08+03:00») → дата. Пусто — None."""
    с = str(значение or "").strip()
    if len(с) < 10:
        return None
    try:
        return date.fromisoformat(с[:10])
    except ValueError:
        return None


def дата_квотации(текст: str, создана=None, сегодня: date | None = None
                  ) -> tuple[date | None, str]:
    """(дата, источник) по убыванию надёжности: документ → письмо → карточка."""
    сегодня = сегодня or datetime.now(timezone.utc).date()
    карточка = дата_карточки(создана)
    if карточка and not _в_пределах(карточка, сегодня, None):
        карточка = None
    д = дата_документа(текст, сегодня, карточка)
    if д:
        return д, ДОКУМЕНТ
    д = дата_письма(текст, сегодня, карточка)
    if д:
        return д, ПИСЬМО
    if карточка:
        return карточка, КАРТОЧКА
    return None, НЕТ


def проставить(items: list[dict], текст: str, ref: dict,
               сегодня: date | None = None) -> tuple[date | None, str]:
    """Дата квотации — всем позициям файла разом: у одного КП дата одна."""
    д, источник = дата_квотации(текст, ref.get("card_created"), сегодня)
    for it in items:
        it["price_date"] = д.isoformat() if д else None
        it["price_date_src"] = источник
    return д, источник
