#!/usr/bin/env python3
"""Правило извлечения дефекта из текста технического задания.

Отдельный модуль без зависимостей — чтобы правило проверялось тестом на гейте,
где нет ни сети, ни базы (как segments.py и equipment.py).

ЗАЧЕМ. Знание о дефектах у нас есть, но лежит не в таблицах, а в текстах: в ТЗ
на ремонт написано, что именно течёт, трескается, прогорает и какой ресурс
вырабатывает узел. Разборщик такие файлы относит к «текст без спецификации» и
выбрасывает целиком — вместе с этим знанием.

ПРАВИЛО ДВУХ УСЛОВИЙ. Предложение считается дефектным, если в нём есть И слово
дефекта, И указание на узел или машину. Одного слова мало: «трещины в
асфальтовом покрытии площадки» и «износ трудовых ресурсов» — не дефекты
оборудования. Пересечение двух условий и есть вся точность правила.

ЧЕГО ПРАВИЛО НЕ ДЕЛАЕТ. Оно не понимает причинно-следственной связи и не
отличает «обнаружен прогар» от «прогар не допускается». Поэтому извлечённое
кладётся с собственным источником и со счётчиком встречаемости: то, что
встретилось в сотне ТЗ, — типовое требование, а не единичная находка.
"""
from __future__ import annotations

import re

RULE_VERSION = "defect-v1"

# Слова дефекта. Только существительные и корни, по которым инженер ищет: вид
# повреждения либо вид отказа. Глаголы («требуется», «заменить») сюда не идут —
# они есть в любом ТЗ и ничего не различают.
TERMS: dict[str, tuple[str, ...]] = {
    "прогар": ("прогар", "прожог"),
    "трещина": ("трещин", "растрескив"),
    "износ": ("износ", "выработка металла", "истирани"),
    # «~» впереди значит регулярное выражение. Нужно ровно здесь:
    # «электроэрозионная обработка» — это способ ремонта, а не дефект, и по
    # подстроке «эрози» он попадал в находки.
    "эрозия": ("~(?<!электро)(?<!электро-)эрози",),
    "коррозия": ("коррози", "ржавчин", "окалин"),
    "вибрация": ("вибрац", "биение", "дисбаланс", "разбаланс"),
    "помпаж": ("помпаж",),
    "задир": ("задир", "наволакивани"),
    "коробление": ("коробл", "деформац"),
    "обрыв": ("обрыв", "разрушени", "излом", "поломк"),
    "течь": ("течь", "утечк", "негерметичн", "пропуск среды"),
    "люфт": ("люфт", "зазор сверх", "просадк"),
    "перегрев": ("перегрев", "превышение температуры"),
    "нагар": ("нагар", "закоксов", "отложени"),
    "кавитация": ("кавитац",),
    "усталость": ("усталостн", "малоцикловая"),
    "выработка ресурса": ("выработ ресурс", "исчерпан ресурс", "наработк"),
}

# Указание на узел или машину. Без него слово дефекта ничего не значит.
EQUIP: tuple[str, ...] = (
    "турбин", "компрессор", "камер сгоран", "жаров", "горелк", "лопат", "ротор",
    "статор", "подшипник", "вкладыш", "баббит", "уплотнени", "вал", "диск",
    "рабочее колесо", "насос", "редуктор", "маслосистем", "маслонасос",
    "теплообмен", "фильтр", "клапан", "форсунк", "запальник", "генератор",
    "возбудител", "муфт", "гтд", "гту", "гпа", "двигател", "агрегат", "цилиндр",
    "поршн", "шестерн", "шейк",
    "sgt", "solar", "taurus", "centaur", "titan", "mars", "saturn", "frame",
)
# Короткий корень ищется со словоизменением, но не дальше двух букв: «вал»,
# «вала», «валом» — оборудование, «валюта» — уже нет. Длинный корень ищется
# вхождением: «подшипник» внутри другого слова не окажется.
_EQUIP_RX = tuple(
    (w, re.compile(rf"(?<![0-9a-zа-я]){re.escape(w)}[а-я]{{0,2}}(?![0-9a-zа-я])"))
    for w in EQUIP)

# Слова профилактики и осмотра. Дефект в таком окружении НЕ произошёл: его
# предотвращают, ищут или не допускают. Проверено на текстах разведки: из
# восемнадцати находок четыре были именно такими — «улучшенные уплотнения против
# износа», «поиск следов истирания», «зубья с биением в единицы микрон» (это
# допуск, а не дефект). Без этого условия в справочник дефектов пошла бы реклама
# улучшений и объём инспекции.
NEG_CONTEXT = (
    "против износ", "против коррози", "против эрози", "защита от", "защиту от",
    "стойкость к", "стойкости к", "устойчив", "не допускается", "не допускаются",
    "не допускать", "поиск следов", "поиску следов", "во избежание", "для предотвращ",
    "предотвраща", "исключает", "исключающ", "улучшенн", "усиленн", "продление ресурс",
    "продлени ресурс", "снижает", "снижена", "уменьшает", "профилактик",
    "с биением в", "допуск по биению", "мониторинг",
    # Наработка парком — статистика изготовителя, а не выработка ресурса машины:
    # «>312 млн часов наработки» это реклама надёжности, а не повод на ремонт.
    "млн часов", "млн. часов", "миллионов часов", "млрд часов",
)

_SENT = re.compile(r"(?<=[.!?;])\s+|\n+")
_WS = re.compile(r"\s+")
# Мусор распознавания и вёрстки: строки из одних знаков, номера пунктов, точки.
_JUNK = re.compile(r"^[\W\d_]+$")


def norm(s: str) -> str:
    return _WS.sub(" ", (s or "").replace("ё", "е")).strip()


def sentences(text: str) -> list[str]:
    """Текст → предложения. Точка с запятой делит наравне с точкой: в ТЗ
    перечисления дефектов пишут через неё, и без деления одно «предложение»
    вбирает всю страницу."""
    out = []
    for s in _SENT.split(text or ""):
        t = norm(s)
        if 20 <= len(t) <= 600 and not _JUNK.match(t):
            out.append(t)
    return out


_TERM_RX = {вид: tuple(re.compile(w[1:]) for w in слова if w.startswith("~"))
            for вид, слова in TERMS.items()}
_TERM_SUB = {вид: tuple(w for w in слова if not w.startswith("~"))
             for вид, слова in TERMS.items()}


def terms_in(s: str) -> list[str]:
    low = norm(s).lower()
    out = set()
    for вид in TERMS:
        if any(w in low for w in _TERM_SUB[вид]) or any(
                rx.search(low) for rx in _TERM_RX[вид]):
            out.add(вид)
    return sorted(out)


def equip_in(s: str) -> bool:
    low = norm(s).lower()
    return any(rx.search(low) if len(w) <= 4 else w in low for w, rx in _EQUIP_RX)


def defect_of(s: str) -> tuple[list[str], bool]:
    """Предложение → (виды дефектов, названо ли оборудование)."""
    return terms_in(s), equip_in(s)


def prevention(s: str) -> bool:
    """Предложение про предотвращение, а не про случившееся."""
    low = norm(s).lower()
    return any(w in low for w in NEG_CONTEXT)


def is_defect(s: str) -> bool:
    виды, есть_узел = defect_of(s)
    return bool(виды) and есть_узел and not prevention(s)


def key_of(s: str) -> str:
    """Ключ для склейки повторов: без регистра, цифр и пунктуации.

    Одно и то же типовое требование ходит по десяткам ТЗ с разными номерами
    пунктов и разными размерами. Цифры из ключа выброшены именно поэтому."""
    low = re.sub(r"[^a-zа-я ]+", " ", norm(s).lower())
    return _WS.sub(" ", low).strip()[:300]
