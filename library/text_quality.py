# ════════════════════════════ образец ════════════════════════════


def _образец(т: str, предел: int) -> str:
    """Не больше `предел` знаков, взятых кусками по ВСЕЙ длине.

    Одна голова обманывает: письмо сверху чистое, а спецификация ниже —
    кракозябры (или наоборот). Куски режутся по переводам строк, чтобы не
    рассечь пару байтов перекодировки или строку вразрядку.
    """
    if len(т) <= предел:
        return т
    кусков = 20
    длина = предел // кусков
    шаг = len(т) // кусков
    части = []
    for i in range(кусков):
        нач = i * шаг
        if нач:
            п = т.find("\n", нач, нач + длина // 2)
            нач = п + 1 if п >= 0 else нач
        кон = нач + длина
        п = т.rfind("\n", кон - длина // 2, кон)
        кон = п if п > нач else кон
        части.append(т[нач:кон])
    return "\n".join(части)


# ════════════════════════════ замер ════════════════════════════


def _доля(часть: float, всего: float) -> float:
    return часть / всего if всего > 0 else 0.0


def _фактор(доля: float, провал: float) -> float:
    return max(0.0, 1.0 - доля / провал)


def _процент(доля: float) -> str:
    return f"{round(доля * 100)} %"


def _странных(слово: str) -> int:
    return sum(1 for ch in слово if ch in _СТРАННЫЕ)


#: Однобуквенное слово кракозябрами: «РІ» (в), «Рё» (и), «1-Р№» (1-й) — ровно
#: одна пара, обрамлённая цифрами и знаками. В законном тексте такого слова нет.
#: Не в счёт пары с неразрывным пробелом («ГОСТ Р 52857») и с «°» («20 С°»
#: с кириллической «С» пишут и в законном тексте).
_ОДНОБУКВЕННОЕ = {
    "utf-8→cp1251": re.compile("[РС][" + _Х1251.replace("\xa0", "").replace("°", "") + "]"),
    "utf-8→latin-1": re.compile("[ÐÑ][" + _ХЛАТ.replace("\xa0", "").replace("°", "") + "]"),
    "utf-8→cp866": re.compile("[╨╤][" + _Х866 + "]"),
}
_КРАЯ = "0123456789!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~«»"


_РАМКА = frozenset(chr(c) for c in range(0x2500, 0x25A0))


def _вид_слова(слово: str) -> str:
    """Какая порча в слове, или пусто. Слово — отрезок без пробелов ASCII."""
    for вид, подпись in _ПОДПИСИ.items():
        if подпись.search(слово):
            return вид
    ядро = слово.strip(_КРАЯ)
    if len(ядро) == 2:
        for вид, пара in _ОДНОБУКВЕННОЕ.items():
            if пара.fullmatch(ядро):
                return вид
    лат = sum(1 for ch in слово if ch in _ЛАТ_УЛИКИ)
    содержательных = sum(1 for ch in слово if not (ch.isascii() and not ch.isalpha()))
    if лат >= 3 and лат >= 0.5 * содержательных:
        # Ð и Ñ на каждом втором месте — utf-8, у которого срезаны невидимые
        # байты C1: «ÐÐ°ÑÐ¾Ñ». Иначе — однобайтовая кириллица под latin-1.
        дн = слово.count("Ð") + слово.count("Ñ")
        return "utf-8→latin-1" if дн >= 0.4 * лат else "однобайтовая кириллица→latin-1"
    # Странные знаки считаются без псевдографики: рамки и разделители
    # («────», «│Насос│») — законная вёрстка текстов DOS и писем.
    странных = sum(1 for ch in слово if ch in _СТРАННЫЕ and ch not in _РАМКА)
    if странных >= 2 and any(0x400 <= ord(ch) <= 0x4FF for ch in слово):
        return "кракозябры"
    # Каша из псевдографики — буквы, прочитанные как cp866: «╨╥┼─╠╧╓┼╬╔┼».
    # Рамка обходится четырьмя разными знаками («╔══╦══╗», «├──┼──┤»),
    # каша — нет.
    if len(set(слово) & _РАМКА) >= 5:
        return "кракозябры"
    return ""


def _покрытие(слова: list[str]) -> tuple[int, int]:
    всего = попало = 0
    for с in слова:
        for i in range(len(с) - 1):
            всего += 1
            if с[i:i + 2] in _БИГРАММЫ:
                попало += 1
    return попало, всего


def _шкала_биграмм(доля: float) -> float:
    return min(1.0, max(0.0, (доля - БИГРАММЫ_НИЗ) / (БИГРАММЫ_ВЕРХ - БИГРАММЫ_НИЗ)))


def _строка_вразрядку(строка: str) -> bool:
    """Разрядка занимает строку почти целиком. «кириллические С и А в номере»
    — это однобуквенные слова в прозе: одиночных знаков там десятая часть, и
    склеить их в «СиАв» значило бы испортить хороший текст."""
    токены = строка.split()
    всего = sum(map(len, токены))
    return всего > 0 and sum(1 for т in токены if len(т) == 1) >= 0.5 * всего


def _разрядка(отрезок: str) -> str | None:
    """Склеенный отрезок «Н а с о с   Ц Н С» → «Насос ЦНС», или None, если это
    не разрядка.

    Не разрядка: меньше трёх букв (номера колонок «1 2 3 4»); меньше трёх
    четвертей букв и цифр — это формула «t = i / n»; перечень подряд по
    алфавиту («А Б В Г»); отрезок без единого одиночного пробела — это
    однобуквенные слова или колонки, склеивать там нечего.
    """
    знаки = отрезок.split()
    буквы = [ch for ch in знаки if ch.isalpha()]
    if len(знаки) < 4 or len(буквы) < 3 or sum(ch.isalnum() for ch in знаки) < 0.75 * len(знаки):
        return None
    коды = [ord(ch.lower()) for ch in буквы]
    if all(b - a == 1 for a, b in zip(коды, коды[1:])):
        return None
    слова = re.split(" {2,}", отрезок)
    if all(len(с) == 1 for с in слова):
        return None
    return " ".join(с.replace(" ", "") for с in слова)


def _замер(т: str) -> list[tuple[float, str]]:
    """Все признаки разом: список (оценка признака, причина словами)."""
    с = _образец(т, ОБРАЗЕЦ)
    непроб = len(с) - sum(map(с.count, _ПРОБЕЛЫ))
    if непроб <= 0:
        return [(0.0, "пусто")]
    итог: list[tuple[float, str]] = []

    # Шрифт без таблицы Юникода. cid — это один глиф, записанный 9–11 знаками,
    # поэтому долю считаем в глифах, а не в знаках.
    cid = _CID.findall(с)
    if cid:
        знаков_cid = sum(map(len, cid))
        д = _доля(len(cid), непроб - знаков_cid + len(cid))
        итог.append((_фактор(д, ПРОВАЛ["cid"]), f"глифы без Юникода (cid) {_процент(д)}"))
    частные = [ch for ch in _ЧАСТНАЯ.findall(с) if ch not in _МАРКЕРЫ]
    if частные:
        д = _доля(len(частные), непроб)
        итог.append((_фактор(д, ПРОВАЛ["частная"]),
                     f"глифы без Юникода (частная область) {_процент(д)}"))
    замен = с.count(ЗНАК_ЗАМЕНЫ)
    if замен:
        д = _доля(замен, непроб)
        итог.append((_фактор(д, ПРОВАЛ["замена"]), f"знаки замены {_процент(д)}"))
    вопросы = sum(map(len, _ВОПРОСЫ.findall(с)))
    if вопросы:
        д = _доля(вопросы, непроб)
        итог.append((_фактор(д, ПРОВАЛ["вопросы"]), f"знаки вопроса вместо букв {_процент(д)}"))
    упр = _УПРАВЛЯЮЩИЕ.findall(с)
    if упр:
        д = _доля(len(упр), непроб)
        причина = ("UTF-16, прочитанный побайтно" if упр.count("\x00") >= 0.2 * непроб
                   else f"управляющие знаки {_процент(д)}")
        итог.append((_фактор(д, ПРОВАЛ["управляющие"]), причина))

    # Кракозябры: каждое подозрительное слово относится к одному виду порчи.
    по_видам: dict[str, int] = {}
    for m in _ПОДОЗРИТЕЛЬНОЕ.finditer(с):
        слово = m.group()
        вид = _вид_слова(слово)
        if вид:
            по_видам[вид] = по_видам.get(вид, 0) + len(слово)
    if по_видам:
        вид = max(по_видам, key=по_видам.get)
        д = _доля(sum(по_видам.values()), непроб)
        название = {"кракозябры": "кракозябры",
                    "однобайтовая кириллица→latin-1": "кириллица cp1251/cp866, прочитанная как latin-1",
                    }.get(вид, f"двойная перекодировка {вид}")
        итог.append((_фактор(д, ПРОВАЛ["кракозябры"]), f"{название} {_процент(д)}"))

    # Буквы вразрядку.
    вразрядку = 0
    строки_вразрядку: dict[int, bool] = {}
    for m in _РАЗРЯДКА.finditer(с):
        нач = с.rfind("\n", 0, m.start()) + 1
        if нач not in строки_вразрядку:
            кон = с.find("\n", m.end())
            строки_вразрядку[нач] = _строка_вразрядку(с[нач:кон if кон >= 0 else len(с)])
        if строки_вразрядку[нач] and _разрядка(m.group()) is not None:
            вразрядку += sum(1 for ch in m.group() if ch.isalpha())
    if вразрядку:
        д = _доля(вразрядку, sum(1 for ch in с if ch.isalpha()))
        итог.append((_фактор(д, ПРОВАЛ["разрядка"]), f"буквы вразрядку {_процент(д)}"))

    # Русские слова: перестановка букв кодировкой, регистр, обратный порядок.
    слова = _РУ_СЛОВО.findall(с)
    if len(слова) > 20000:
        слова = слова[::len(слова) // 20000 + 1]
    # koi8-r ↔ cp1251 меняет регистр: «Насос» → «мЮЯНЯ» — слово со строчной
    # в начале и заглавными дальше. «кВт», «кВА» короче пяти букв и под счёт
    # не попадают; «ТехноСервис», «ЭнергоМаш» начинаются с заглавной — тоже.
    длинные = [w for w in слова if len(w) >= 5]
    вперемешку = sum(1 for w in длинные if w[0].islower() and not w.islower())
    if вперемешку:
        д = _доля(вперемешку, len(длинные))
        итог.append((_фактор(д, ПРОВАЛ["регистр"]), f"регистр вперемешку {_процент(д)}"))
    # Аббревиатуры («ЗИП», «ГТУ», «ГПА») — не слова, их биграммы случайны.
    # Перестановка koi8-r делает заглавными и длинные слова, так что без
    # коротких заглавных она всё равно видна.
    низ = [w.lower().replace("ё", "е") for w in слова if len(w) > 4 or not w.isupper()]
    попало, всего = _покрытие(низ)
    if всего >= МИН_БИГРАММ:
        прямо = попало / всего
        обр_попало, обр_всего = _покрытие([w[::-1] for w in низ])
        обратно = обр_попало / обр_всего
        # Перевёрнутое слово начинается с «й», «ь», «ъ», «ы» — окончаний
        # «-ый», «-ть», «-ы». Считаем ТОЛЬКО если обратное прочтение лучше
        # прямого: одно «йод» в коротком письме не повод для тревоги.
        if обратно > прямо + 0.05:
            начал = sum(1 for w in низ if w[0] in "йьъы")
            д = _доля(начал, len(низ))
            итог.append((_фактор(д, ПРОВАЛ["перевёрнутые"]) * _шкала_биграмм(прямо),
                         "перевёрнутый порядок букв"))
        else:
            итог.append((_шкала_биграмм(прямо),
                         f"буквы не складываются в русские слова (биграммы {_процент(прямо)})"))
    return итог


def _оценка(т: str) -> tuple[float, str]:
    признаки = _замер(т)
    if not признаки:
        return 1.0, "годится"
    балл = 1.0
    for ф, _ in признаки:
        балл *= ф
    худший = min(признаки, key=lambda п: п[0])
    if балл >= ПОРОГ_ГОДИТСЯ and худший[0] >= ПОРОГ_ГОДИТСЯ:
        return round(балл, 4), "годится"
    return round(балл, 4), худший[1]


