def качество(текст: str) -> tuple[float, str]:
    """Оценка 0..1 и причина словами: «годится» или худший признак с долей."""
    try:
        if not isinstance(текст, str) or not текст.strip():
            return 0.0, "пусто"
        return _оценка(текст)
    except Exception as e:                                          # noqa: BLE001
        return 0.0, f"не оценено: сбой {type(e).__name__}"


def починить(текст: str) -> tuple[str, str]:
    """Вернуть (текст, что сделано). Пустое «что сделано» — ничего не менялось.

    Меняется только то, что возвращается без потерь, и только если оценка
    после починки СТРОГО выше исходной: иначе возвращается исходный текст.
    """
    try:
        if not isinstance(текст, str):
            return "", ""
        return _починить(текст)
    except Exception:                                               # noqa: BLE001
        return (текст if isinstance(текст, str) else ""), ""


def _починить(т: str) -> tuple[str, str]:
    if not т.strip():
        return т, ""
    балл = _оценка(т)[0]
    if балл >= 0.9999:
        return т, ""
    сделано: list[str] = []
    for _ in range(МАКС_ШАГОВ):
        шаг = _шаг(т, балл)
        if шаг is None:
            break
        т, балл, имя = шаг
        сделано.append(имя)
        if балл >= 0.9999:
            break
    return т, "; ".join(сделано)


def нужно_распознавание(текст: str) -> bool:
    """Текст безнадёжен даже после починки — страницу надо отдать OCR.

    Решает оценка ПОСЛЕ починки: перекодировка или разрядка чинятся даром, и
    гнать такую страницу в распознавание — платить за то, что уже есть.
    """
    try:
        if not isinstance(текст, str):
            текст = ""
        # Внутренние функции, а не качество()/починить(): те прячут сбой за
        # оценкой 0, и сбой оценщика уводил бы в распознавание весь поток.
        if текст.strip() and _оценка(текст)[0] >= ПОРОГ_OCR:
            починенный = текст
        else:
            починенный, _ = _починить(текст)
            if not починенный.strip() or _оценка(починенный)[0] < ПОРОГ_OCR:
                return True
        # Буквы считаются в ПОЧИНЕННОМ тексте: у символьного шрифта PDF их
        # нет вовсе (всё в частной области), а после починки — целая страница.
        return sum(1 for ch in починенный if ch.isalnum()) < МИН_ЗНАКОВ
    except Exception:                                               # noqa: BLE001
        # Сбой оценщика — не повод платить за распознавание: он виден тестами,
        # а ложная тревога на всём потоке стоила бы дороже.
        return False
