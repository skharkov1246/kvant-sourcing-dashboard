def _перекодировать(т: str, откуда: str, куда: str) -> str | None:
    b = _закодировать(т, откуда)
    return None if b is None else _раскодировать(b, куда)


#: Байт 0x98 в cp1251 не определён, а в utf-8 он хвост у «И» (D0 98), «Ø»
#: (C3 98), «‘» (E2 80 98). После прочтения он лежит в тексте знаком замены,
#: у «И» — ещё и «?» или вовсе пропадает, оставляя «Р» без пары. Другого байта,
#: который cp1251 не показывает, нет — поэтому восстановление точное, а
#: ошибочное (знак замены был в тексте и раньше) отсеет строгий разбор utf-8.
#: Применяется только когда строгая обратная перекодировка уже не удалась.
_ПОТЕРЯННЫЙ_98 = re.compile(ЗНАК_ЗАМЕНЫ + "|(?<=Р)\\?|(?<=Р)(?=[^" + _Х1251 + "]|$)")


def _перекодировать_с_и(т: str, откуда: str, куда: str) -> str | None:
    р = _перекодировать(т, откуда, куда)
    if р is None and откуда == "cp1251" and куда == "utf-8":
        р = _перекодировать(_ПОТЕРЯННЫЙ_98.sub("\x98", т), откуда, куда)
    return р


def _странность(слово: str, однобайтовая: bool) -> int:
    """Сколько в слове улик порчи: пары перекодировки и странные знаки. Для
    однобайтового назначения латиница верхней половины — тоже улика («Íàñîñ»),
    и весит втрое: в законном тексте её в русском слове нет."""
    н = len(_ПАРА.findall(слово)) + _странных(слово)
    if однобайтовая:
        н += 3 * sum(1 for ch in слово if ch in _ЛАТ_УЛИКИ)
    return н


def _улик(т: str) -> int:
    """Сколько в тексте знаков, которых не бывает в нормальном тексте:
    странные, латиница-улики, частная область, пары перекодировки.

    Предохранитель всех починок: настоящая починка улики УБАВЛЯЕТ (из
    кракозябр выходят буквы), перестановка koi8-r оставляет на нуле, а
    ошибочная — прибавляет. Оценка одиночный странный знак в слове не
    штрафует (так бывает и в законном тексте), поэтому починка, которая
    убрала «?», но рассыпала по словам «Ђ» и «ў», без этой проверки прошла
    бы. Для перекодировки в utf-8 и прочих починок, где правило русских букв
    неприменимо, держит только она.
    """
    # Псевдографика не в счёт: законные рамки возвращаются в текст верной
    # починкой koi8-r и cp866, и считать их уликами значило бы отвергать
    # верную починку. Кашу из псевдографики ловит оценка (см. _вид_слова).
    return (sum(1 for ch in т if (ch in _СТРАННЫЕ and ch not in _РАМКА) or ch in _ЛАТ_УЛИКИ
                or 0xE000 <= ord(ch) <= 0xF8FF)
            + len(_ПАРА.findall(т)))


_БУКВЫ = re.compile(r"[^\W\d_]+")


def _письменности_вперемешку(слово: str) -> bool:
    """Кириллица и латиница в одном буквенном отрезке — след ошибочной
    починки, а не слово: «Größe» через cp1251 дало бы «Grцяe», «SKF®» через
    cp866 — «SKFо». Кириллица под latin-1 даёт буквы À–ÿ сплошь, без ASCII,
    и её починка в такой итог не приходит."""
    return any(any(ch.isascii() for ch in о) and any(ch in _РУ_МНОЖ for ch in о)
               for о in _БУКВЫ.findall(слово))


#: Сколько биграмм нужно предохранителю «слова складываются». Меньше, чем
#: оценке (МИН_БИГРАММ): здесь сравниваются два прочтения одного текста, а не
#: выносится приговор, и ошибка стоит только отказа от починки.
МИН_БИГРАММ_СРАВНЕНИЯ = 10


def _биграммы_текста(т: str) -> tuple[int, int]:
    слова = _РУ_СЛОВО.findall(_образец(т, ПРОБА))
    return _покрытие([w.lower().replace("ё", "е") for w in слова if len(w) > 4 or not w.isupper()])


def _русских(т: str) -> int:
    return sum(1 for ch in т if ch in _РУ_МНОЖ)


def _допустимо(было: str, стало: str, однобайтовая: bool = False) -> bool:
    """Предохранители всякой починки, кроме оценки.

    1. Однобайтовая перекодировка не убавила русских букв. Верная починка их
       прибавляет (кракозябры latin-1 и cp866 → кириллица) или сохраняет
       (перестановка koi8-r), а порча хорошей кириллицы через cp866 делает из
       заглавных псевдографику: «К?о?л?-в?о?» → «╩?ю?ы?-т?ю?», «Подшипник SKF®
       и <кракозябры> в наличии» → «╧юф°шяэшъ … эрышўшш». Там, где слова
       разбиты «?» на буквы, ни биграмм, ни целых слов нет, и держит только
       это. Для починки в utf-8 правило не годится: «и» в кракозябрах — две
       русские буквы «Рё», — но там есть строгий разбор utf-8.
    2. Улик порчи не прибавилось (см. _улик).
    3. Русские слова складываются не хуже прежнего: на короткой строке оценка
       по биграммам не выносится вовсе, а сравнить два прочтения можно.
    """
    if однобайтовая and _русских(стало) < _русских(было):
        return False
    if _улик(стало) > _улик(было):
        return False
    п_стало, в_стало = _биграммы_текста(стало)
    if в_стало < МИН_БИГРАММ_СРАВНЕНИЯ:
        return True
    доля_стало = п_стало / в_стало
    п_было, в_было = _биграммы_текста(было)
    if в_было >= МИН_БИГРАММ_СРАВНЕНИЯ and доля_стало < п_было / в_было - 0.05:
        return False
    return доля_стало >= БИГРАММЫ_НИЗ


def _слово_починить(слово: str, откуда: str, куда: str) -> tuple[str, bool]:
    """Одно слово, до трёх обратных перекодировок подряд (двойная порча).
    Возвращает (слово, сильная ли правка).

    Сильная правка — две улики и больше, а для однобайтового назначения ещё и
    две русские буквы в итоге: она делается всегда. Слабая — одна улика или
    одна буква («РІ» → «в», «1-é» → «1-й»): её делает _по_словам, только если
    в той же строке есть сильная, иначе «à» во французской фразе стала бы «а».
    Никогда не чинится пара «Р + неразрывный пробел» («ГОСТ Р 52857») и не
    принимается итог, где кириллица и латиница в одном слове («Größe» →
    «Grцяe», «SKF®» → «SKFо») или остались странные знаки.
    """
    однобайтовая = куда != "utf-8"
    улики = _странность(слово, однобайтовая)
    if улики < 1:
        return слово, False
    if not однобайтовая and улики == 1 and re.search("[РС]\xa0", слово):
        return слово, False
    лучшее, лучшая, русских = слово, улики, 0
    тек = слово
    for _ in range(3):
        след = _перекодировать_с_и(тек, откуда, куда)
        if not след or след == тек:
            break
        с = _странность(след, однобайтовая)
        р = sum(ch in _РУ_МНОЖ for ch in след)
        чисто = all(ch.isascii() or ch in _ОБЫЧНЫЕ for ch in след)
        if однобайтовая:
            # Знаки C1 в законном тексте не встречаются вовсе, и слово из
            # одних них («2\x965» → «2–5») чинится и без русских букв.
            с_c1 = any(0x80 <= ord(ch) <= 0x9F for ch in слово)
            чисто = (чисто and с == 0 and (р >= 1 or с_c1)
                     and not _письменности_вперемешку(след))
        if чисто and с < лучшая:
            лучшее, лучшая, русских = след, с, р
        тек = след
    if лучшее == слово:
        return слово, False
    # Сила — по ЧИСЛУ знаков-улик, без веса: одна «é» в кавычках весит в
    # странности втрое, но это одна улика, и ««é»» не должно становиться «оВп».
    знаков_улик = len(_ПАРА.findall(слово)) + _странных(слово) + (
        sum(1 for ch in слово if ch in _ЛАТ_УЛИКИ) if однобайтовая else 0)
    return лучшее, знаков_улик >= 2 and (not однобайтовая or русских >= 2)


def _по_словам(откуда: str, куда: str):
    """Починка по словам — для текста, где порча не сплошная: письмо целое,
    а в строке одна ячейка из другого источника кракозябрами. Целиком такая
    строка обратно не перекодируется — целые русские слова в utf-8 не
    складываются. Слабые правки — только в строке, где есть сильная."""
    def строка_починить(строка: str) -> str:
        замены = []
        for m in _ПОДОЗРИТЕЛЬНОЕ.finditer(строка):
            новое, сильная = _слово_починить(m.group(), откуда, куда)
            if новое != m.group():
                замены.append((m.start(), m.end(), новое, сильная))
        if not any(сильная for *_, сильная in замены):
            return строка
        части, поз = [], 0
        for нач, кон, новое, _ in замены:
            части += [строка[поз:нач], новое]
            поз = кон
        части.append(строка[поз:])
        return "".join(части)

    def f(т: str) -> str:
        return "\n".join(строка if строка.isascii() else строка_починить(строка)
                         for строка in т.split("\n"))
    return f


def _по_строкам(откуда: str, куда: str):
    """Починка по строкам — для склейки разных источников (участники архива,
    письмо и таблица): строка перекодируется целиком и меняется, только если
    её СОБСТВЕННАЯ оценка строго выросла. Ловит то, чего не видно в слове:
    однобуквенные «РІ» и «Рё» (одна улика) и cp866, где половина букв
    остаётся кириллицей. Короткая строка без улик остаётся как есть: при
    равной оценке ничего не меняется."""
    def f(т: str) -> str:
        out = []
        for строка in т.split("\n"):
            if строка.isascii():
                out.append(строка)
                continue
            лучшее, лучший = строка, None
            тек = строка
            for _ in range(2):
                тек = _перекодировать_с_и(тек, откуда, куда)
                if not тек:
                    break
                if лучший is None:
                    лучший = _оценка(строка)[0]
                б = _оценка(тек)[0]
                if б > лучший + 1e-6 and _допустимо(строка, тек, куда != "utf-8"):
                    лучшее, лучший = тек, б
            out.append(лучшее)
        return "\n".join(out)
    return f


def _целиком(откуда: str, куда: str, раз: int):
    def f(т: str) -> str | None:
        for _ in range(раз):
            т = _перекодировать_с_и(т, откуда, куда)
            if т is None:
                return None
        return т
    return f


def _utf16(т: str) -> str | None:
    b = _закодировать(т, "западная")
    if b is None:
        return None
    b = b[: len(b) // 2 * 2]
    лучшее = None
    for к in ("utf-16-le", "utf-16-be"):
        try:
            р = b.decode(к)
        except UnicodeDecodeError:
            continue
        if лучшее is None or р.count("\x00") < лучшее.count("\x00"):
            лучшее = р
    # Двоичный мусор с нулями тоже раскодируется — в случайные иероглифы,
    # которых оценка не судит. Берём только текст из кириллицы и ASCII.
    if лучшее is None:
        return None
    знаки = [ch for ch in лучшее if not ch.isspace()]
    своих = sum(1 for ch in знаки if ch.isascii() or 0x400 <= ord(ch) <= 0x4FF)
    return лучшее if знаки and своих >= 0.8 * len(знаки) else None


def _склеить_разрядку(т: str) -> str:
    def f(m: re.Match) -> str:
        склеено = _разрядка(m.group())
        return m.group() if склеено is None else склеено
    return "\n".join(_РАЗРЯДКА.sub(f, строка) if _строка_вразрядку(строка) else строка
                     for строка in т.split("\n"))


_БЕЗ_УПРАВЛЯЮЩИХ: dict[int, str | None] = {
    c: None for c in range(0x20) if chr(c) not in "\t\n\r\f\v"}
# \x07 — конец ячейки таблицы старого Word: он разделяет колонки, поэтому
# становится табуляцией; \x1e — неразрывный дефис Word. Прочие знаки C0
# текста не несут.
_БЕЗ_УПРАВЛЯЮЩИХ.update({0x7F: None, 0x07: "\t", 0x1E: "-"})


def _убрать_управляющие(т: str) -> str:
    return т.translate(_БЕЗ_УПРАВЛЯЮЩИХ)


def _строка_перевёрнута(строка: str) -> bool:
    """Строка читается лучше задом наперёд: частые биграммы прибавились, а
    слова перестали начинаться с «й», «ь», «ы». Одиночное слово не решает —
    нужны две улики."""
    слова = [w.lower().replace("ё", "е") for w in _РУ_СЛОВО.findall(строка)]
    if not слова:
        return False
    прямо, всего = _покрытие(слова)
    обратно, _ = _покрытие([w[::-1] for w in слова])
    плохо_прямо = sum(1 for w in слова if w[0] in "йьъы")
    плохо_обратно = sum(1 for w in слова if w[-1] in "йьъы")
    return (всего > 0 and (обратно - прямо) / всего > 0.1
            and плохо_прямо >= плохо_обратно and плохо_прямо + (обратно - прямо) >= 2)


def _развернуть(т: str, выборочно: bool) -> str:
    out = []
    for строка in т.split("\n"):
        хвост = "\r" if строка.endswith("\r") else ""
        тело = строка[:-1] if хвост else строка
        if not выборочно or _строка_перевёрнута(тело):
            тело = тело[::-1]
        out.append(тело + хвост)
    return "\n".join(out)


#: Символьный шрифт PDF: код знака c попадает в U+F000 + c. У русских
#: документов за c обычно стоит байт cp1251 — тогда «U+F0CD» это «Н».
#: Догадка проверяется оценкой: если за кодами не cp1251, текст не улучшится
#: и починка отвергнется.
_ИЗ_СИМВОЛЬНОГО = {0xF000 + b: _ЗНАКИ["cp1251"][b] for b in range(0x20, 0x100)}


def _в_основном_кириллица(знаки: list[str]) -> bool:
    """Предохранитель догадок «код → байт cp1251». Оценка не отличает кашу
    из латиницы и знаков препинания от текста — в ней нет русских слов, и
    биграммам нечего проверить. Поэтому догадка принимается, только если из
    кодов вышла в основном кириллица: у русского документа так и есть, а
    индексы глифов дают любые знаки подряд."""
    букв = [ch for ch in знаки if ch.isalpha()]
    return len(букв) >= 0.5 * len(знаки) and sum(ch in _РУ_МНОЖ for ch in букв) >= 0.6 * len(букв)


def _из_символьного_шрифта(т: str) -> str:
    знаки = [_ИЗ_СИМВОЛЬНОГО[ord(ch)] for ch in т if ord(ch) in _ИЗ_СИМВОЛЬНОГО]
    return т.translate(_ИЗ_СИМВОЛЬНОГО) if _в_основном_кириллица(знаки) else т


def _cid_как_cp1251(т: str) -> str:
    """(cid:N) у простого (не CID) шрифта — это код знака в кодировке шрифта,
    и у русских PDF она часто cp1251 под другим именем. У шрифтов CID номер —
    индекс глифа: догадка даст кашу, и предохранитель её не пропустит."""
    def знак(m: re.Match) -> str:
        н = int(m.group()[5:-1])
        return _ЗНАКИ["cp1251"][н] if 0x20 <= н < 0x100 else m.group()
    знаки = [знак(m) for m in _CID.finditer(т)]
    return _CID.sub(знак, т) if _в_основном_кириллица(знаки) else т


def _кандидаты(признаки: list[tuple[float, str]]):
    """Что пробовать: только то, на что указывают признаки. Хороший текст не
    доходит сюда вовсе, а плохой не гоняется через все пары зря.

    Каждый кандидат — (имя, преобразование, вид). Вид решает, какие
    предохранители _допустимо к нему применимы: «однобайтовая» — перекодировка
    в однобайтовую кириллицу (и догадки «код → байт cp1251»), «utf-8» —
    перекодировка в utf-8, «прочее» — разворот, разрядка, UTF-16, управляющие.
    """
    причины = " ".join(п for ф, п in признаки if ф < 1.0)
    if "UTF-16" in причины:
        yield "текст UTF-16 раскодирован", _utf16, "прочее"
    if "частная область" in причины:
        yield "символьный шрифт прочитан как cp1251", _из_символьного_шрифта, "однобайтовая"
    if "(cid)" in причины:
        yield "коды cid прочитаны как cp1251", _cid_как_cp1251, "однобайтовая"
    if "управляющие" in причины:
        yield "убраны управляющие знаки", _убрать_управляющие, "прочее"
    if "вразрядку" in причины:
        yield "склеены буквы вразрядку", _склеить_разрядку, "прочее"
    if "перевёрнут" in причины or "биграммы" in причины:
        yield "развёрнуты перевёрнутые строки", lambda т: _развернуть(т, выборочно=False), "прочее"
        yield ("развёрнуты перевёрнутые строки (выборочно)", lambda т: _развернуть(т, выборочно=True),
               "прочее")
    if any(с in причины for с in ("перекодировка", "кракозябры", "latin-1", "биграммы",
                                   "регистр", "замены", "вопроса", "управляющие")):
        for имя, откуда, куда in ПАРЫ:
            вид = "utf-8" if куда == "utf-8" else "однобайтовая"
            yield f"исправлена перекодировка {имя}", _целиком(откуда, куда, 1), вид
            yield f"исправлена двойная перекодировка {имя}", _целиком(откуда, куда, 2), вид
            # По строкам — раньше, чем по словам: при равной оценке выигрывает
            # первый, а строка целиком чинит и то, чего не видно в слове.
            yield f"исправлена перекодировка {имя} по строкам", _по_строкам(откуда, куда), вид
            yield f"исправлена перекодировка {имя} по словам", _по_словам(откуда, куда), вид


def _шаг(т: str, балл: float) -> tuple[str, float, str] | None:
    """Одна починка: лучший кандидат на пробе, затем проверка на всём тексте.

    Берутся три лучших на пробе: проба может не содержать знака, из-за
    которого преобразование целиком на полном тексте не проходит, — тогда
    выручает следующий (обычно тот же, но по словам).
    """
    проба = _образец(т, ПРОБА)
    балл_пробы = балл if проба is т else _оценка(проба)[0]
    оценённые = []
    for имя, f, вид in _кандидаты(_замер(т)):
        try:
            р = f(проба)
        except Exception:                                           # noqa: BLE001
            continue
        if not р or р == проба:
            continue
        б = _оценка(р)[0]
        if б > балл_пробы + 1e-6 and _допустимо(проба, р, вид == "однобайтовая"):
            оценённые.append((б, имя, f, вид))
    оценённые.sort(key=lambda x: -x[0])
    for _, имя, f, вид in оценённые[:3]:
        try:
            р = f(т)
        except Exception:                                           # noqa: BLE001
            continue
        if not р or р == т:
            continue
        б = _оценка(р)[0]
        if б > балл + 1e-6 and _допустимо(_образец(т, ОБРАЗЕЦ), _образец(р, ОБРАЗЕЦ),
                                           вид == "однобайтовая"):
            return р, б, имя
    return None


