"""Вид записи словаря брендов dict/oem.json: бренд, указание, несколько, описание, номер, материал.

ЗАЧЕМ. Словарь собирается из полей изготовителя семи баз (scripts/build_dict.py),
и в эти поля люди писали не только марку: «Заказ по спецификации», «ABB/Siemens/
OMRON (по типу)», «Epiroc, Normet», «Bently Nevada (по профилю)», «330180/330105
(speed probe)». Сборщик заводил каждую такую строку брендом, читатели словаря
(library/brands.py, library/brand_registry.py) принимали её за марку, и страница
показывала «странный бренд» (жалоба владельца 25.09.2026). Удалять такие записи
нельзя (CLAUDE.md, правило 5): это ответ сорсеру, а не мусор. Поэтому запись
получает вид, и читатель берёт бренд только у вида «бренд».

ОДНО ПРАВИЛО В ОДНОМ МЕСТЕ. Признаки ниже судят и сборщик (вид записи), и ревизия
словаря scripts/portal_audit.py (проверки d.*): ревизия считает запись вида
«бренд», у которой признак есть, — то есть то, что читатель примет за бренд, хотя
текст говорит иное. Указание к закупке — то же выражение, что отсеивает часть
ячейки на странице /brands (codes_sql.NOT_A_COMPANY, порт в Python — здесь же).

ОБВИНЯЕТ ТОЛЬКО ЗАКРЫТЫЙ СПИСОК ИЛИ ДОКАЗАТЕЛЬСТВО ИЗ САМОГО СЛОВАРЯ (правило 7):
  · указание — фраза из закрытого списка (как у страницы /brands) или «типовые»;
  · номер    — пять и больше цифр в ключе, а до скобок нет трёх букв подряд;
  · несколько — разделитель брендов («/», «,», «или») и не меньше ДВУХ разных
                брендов словаря среди частей: «Epiroc, Normet» — два бренда; либо
                разделитель в голове имени вместе с пояснением: «Henkel / Dow
                (расходка)». «MTU / Rolls-Royce Power Systems» — марка и
                владелец, и доказать обратное нечем;
  · материал — имя целиком материал из справочника dict/material.json
               (library/materials.py): марка стали «SS316», торговое название
               материала «Viton», «Kalrez», «Teflon». Имя, которое носит и
               компания («Stellite»), не обвиняется;
  · описание — пояснение (скобки, тире, двоеточие, «по/для», шесть слов) или
               страна в части имени, и голова записи — бренд словаря («Bently
               Nevada (по профилю)» — это Bently Nevada с заметкой) либо
               пояснение называет два бренда словаря и больше.
Признак без доказательства запись не обвиняет: она остаётся брендом, а признак
виден числом в ревизии (ошибочная защита стоит полноты, а не спроса).

Доказательство «бренд словаря» — запись без единого признака (чистая), ключ части
— правило запроса страницы /brands (codes_sql.ключ_написания). Модуль стоит
только на стандартной библиотеке; codes_sql подгружается лениво, потому что
codes_sql сам загружает scripts/build_dict.py, а тот — этот модуль.
"""
from __future__ import annotations

import collections
import functools
import re

ВИДЫ = ("бренд", "указание", "несколько", "описание", "номер", "материал")
БРЕНД, УКАЗАНИЕ, НЕСКОЛЬКО, ОПИСАНИЕ, НОМЕР, МАТЕРИАЛ = ВИДЫ
# Виды, у которых читатель берёт бренды из поля brands записи (разложение), и
# виды, у которых бренда нет вовсе.
С_РАЗЛОЖЕНИЕМ = frozenset((НЕСКОЛЬКО, ОПИСАНИЕ))
БЕЗ_БРЕНДА = frozenset((УКАЗАНИЕ, НОМЕР, МАТЕРИАЛ))

# Длина ключа nkey (scripts/build_dict.py) и ключа написания (codes_sql,
# lib_brand_key в SQL): ключ длиннее обрезается, и ключ ровно этой длины — след
# обрезки.
ДЛИНА_КЛЮЧА = 40


# ── Правовая форма и описание ────────────────────────────────────────────────

_ФОРМА_ВПЕРЕДИ = re.compile(r"^\s*(ооо|оао|зао|пао|ао|ип|нпо|нпп|тоо|llc|ooo)\b\.?\s*", re.I)
_ФОРМА_В_ХВОСТЕ = re.compile(
    r"(?:,?\s*\b(?:l\.?l\.?c|inc|ltd|limited|corp(?:oration)?|co\.?,?\s*ltd|gmbh(?:\s*&\s*co\.?\s*kg)?"
    r"|s\.?a\.?s|a/s|ag|plc|s\.?p\.?a|s\.?a|b\.?v|n\.?v|oyj?|ab|kg|pte\.?\s*ltd|sarl|s\.?r\.?l"
    r"|ооо|оао|зао|пао|ао)\b\.?)+\s*$", re.I)


def без_формы(s) -> str:
    """Имя без правовой формы (впереди «ООО», в хвосте «, Inc», «GmbH», «Co., Ltd.»)
    и без кавычек — чтобы судить само имя, а не то, как оформлено юрлицо."""
    t = str(s or "").strip()
    for _ in range(3):
        прежде = t
        t = _ФОРМА_ВПЕРЕДИ.sub("", t)
        t = _ФОРМА_В_ХВОСТЕ.sub("", t).strip(" ,.;")
        t = t.strip(" «»\"'“”„")
        if t == прежде:
            break
    return t


def похоже_на_описание(s) -> bool:
    """Имя бренда — описание, а не имя: тире, двоеточие, точка с запятой,
    стрелка, «по/для/или/типа», пояснение в скобках (слово со строчной буквы или
    цифра: «(по профилю)», «(speed probe)», «(тип.)»), шесть слов и больше.

    Судится имя БЕЗ правовой формы: «Parker Hannifin Manufacturing France S.A.S.»
    и «Ленинградский металлический завод» — имена, как бы длинно ни звались.
    Расшифровка в скобках — «CCS (Custom Control Sensors)», «Druck (Baker
    Hughes)» — тоже имя; «Clifford and Snell», «KESSLER - ELLIS» — имена."""
    t = без_формы(s)
    if re.search(r"\s[—–]\s|[:;→]|\s(по|для|или|типа|for|or)\s", t, re.I):
        return True
    if any(re.search(r"(?<![A-Za-zА-Яа-яЁё])[a-zа-яё]{3,}|\d", x) for x in re.findall(r"\(([^)]*)\)", t)):
        return True
    return len(t.split()) >= 6


# ── Указание к закупке ───────────────────────────────────────────────────────

# «Типовые: EAO/ABB/Schneider — по формату», «… — типовой для пакетов Solar»:
# марки названы примером, бренд позиции не назван. Страница /brands такую часть
# не отсеивает (она делит ячейку по «/» раньше), поэтому слово — здесь, а не в
# выражении запроса.
_ТИПОВЫЕ = r"(?<!\w)типов(ые|ой|ая|ое|ых)(?!\w)"


@functools.lru_cache(maxsize=1)
def не_компания() -> re.Pattern:
    """Указание к закупке — выражение запроса страницы /brands
    (codes_sql.NOT_A_COMPANY), где слово привязано к началу: Python-оригинал из
    build_dict ищет подстроку, и «Восток» у него — «сток». Границы \\m и \\M
    PostgreSQL переведены в Python."""
    from library import codes_sql

    return re.compile(codes_sql.NOT_A_COMPANY.replace("\\m", r"(?<!\w)").replace("\\M", r"(?!\w)"), re.I)


def указание(имя) -> str | None:
    """Фраза указания к закупке в имени (закрытый список) или None."""
    t = str(имя or "").replace("ё", "е").replace("Ё", "Е")
    m = не_компания().search(t) or re.search(_ТИПОВЫЕ, t, re.I)
    return m.group(0).strip() if m else None


# ── Материал ─────────────────────────────────────────────────────────────────

def материал(имя) -> dict | None:
    """Имя без правовой формы целиком — материал из справочника
    (library/materials.ячейка_материал): {key, spelling, kind} или None."""
    try:
        from library import materials
    except ImportError:  # модуль загружен из каталога library/
        import materials
    return materials.ячейка_материал(без_формы(имя), короткие=False)


# ── Номер, несколько брендов, ключ ───────────────────────────────────────────

def цифр_в_ключе(ключ) -> int:
    return len(re.findall(r"\d", str(ключ or "")))


def номер(имя, ключ) -> bool:
    """Номер детали вместо имени: в ключе пять цифр и больше, а в имени до скобок
    нет трёх букв подряд («330180/330105 (speed probe)», «330180-X0-05»).
    «ABB (силовой модуль FS450R17KE3)» — имя с пояснением, а не номер."""
    голова = re.sub(r"\([^)]*\)", " ", str(имя or ""))
    return цифр_в_ключе(ключ) >= 5 and not re.search(r"[A-Za-zА-Яа-яЁё]{3}", голова)


def разделитель_брендов(имя) -> bool:
    """«/», «,» или «или» в имени без правовой формы и без скобок: запятая в скобках —
    расшифровка («Jichai (Jinan Diesel, CNPC)»), а «, Inc» и «Co., Ltd.» —
    правовая форма; ни то ни другое не второй бренд."""
    return bool(re.search(r"/|,|\sили\s", re.sub(r"\([^)]*\)", "", без_формы(имя))))


def голова_имени(имя) -> str:
    """Имя до пояснения: без правовой формы и скобок, до первого тире, двоеточия,
    точки с запятой или стрелки. «Bently Nevada / Wilcoxon (тип.)» → «Bently
    Nevada / Wilcoxon»; «Versa Products (…) — серия V/VSG» → «Versa Products»."""
    t = re.sub(r"\([^)]*\)", " ", без_формы(имя))
    return re.split(r"\s[—–]\s|[:;→]", t, maxsplit=1)[0].strip()


def кириллица_при_латинице(ключ, имя) -> bool:
    """Русское слово в ключе при латинском имени: «bentlynevadaпопрофилю». Это
    след пояснения по-русски, а не транслитерация: «Сименс» даёт ключ «сименс»
    без латиницы в имени и сюда не попадает."""
    return bool(re.search(r"[а-я]{4,}", str(ключ or ""))) and bool(re.search(r"[A-Za-z]", str(имя or "")))


def ключ_обрезан(ключ) -> bool:
    return len(str(ключ or "")) == ДЛИНА_КЛЮЧА


# Деление имени на части — как у читателей (codes_sql.SPLIT_RE,
# brand_registry.части_имени): запятая, точка с запятой, косая, скобки, «и/или/or»;
# плюс пояснительные тире, двоеточие и стрелка — у записи словаря это границы
# пояснения, а не части имени.
ДЕЛЕНИЕ = re.compile(r"\s*[,;/()\[\]:→]\s*|\s+[—–]\s+|\s+(?:и|или|or)\s+", re.I)


def части(имя) -> list[str]:
    out = []
    for ч in ДЕЛЕНИЕ.split(без_формы(имя)):
        ч = (ч or "").strip(" .-–—")
        if ч and ч not in out:
            out.append(ч)
    return out


@functools.lru_cache(maxsize=1)
def _страны() -> frozenset:
    from library import codes_sql

    return frozenset(codes_sql.COUNTRIES)


def страна(часть) -> bool:
    """Часть имени — страна (закрытый список страницы /brands, codes_sql.COUNTRIES)."""
    t = " ".join(str(часть or "").lower().replace("ё", "е").split()).strip(" .,;:")
    return t in _страны()


def страна_в_имени(имя) -> bool:
    чч = части(имя)
    return len(чч) >= 2 and any(страна(ч) for ч in чч[1:])


def ключ_написания(s) -> str:
    from library import codes_sql

    return codes_sql.ключ_написания(s)


# ── Признаки записи и её вид ─────────────────────────────────────────────────

def признаки(имя, ключ) -> dict[str, bool]:
    """Признаки не-бренда по имени и ключу записи. Их же считает ревизия (d.*)."""
    return {
        "описание": похоже_на_описание(имя),
        "указание": указание(имя) is not None,
        "несколько": разделитель_брендов(имя),
        "номер": цифр_в_ключе(ключ) >= 5,
        "кириллица": кириллица_при_латинице(ключ, имя),
        "ключ_40": ключ_обрезан(ключ),
        "страна": страна_в_имени(имя),
    }


# Признаки, которые делают запись «не чистой»: такая запись не служит
# доказательством чужого вида. Кириллица и длина ключа — следы пояснения и
# обрезки, у чистого имени их не бывает, но сами по себе они не обвиняют.
ГРЯЗНЫЕ = ("описание", "указание", "несколько", "номер", "страна")


def чистая(имя, ключ) -> bool:
    п = признаки(имя, ключ)
    return not any(п[x] for x in ГРЯЗНЫЕ)


def карта_чистых(записи) -> dict[str, set]:
    """Ключ написания → ключи ЧИСТЫХ записей: доказательство «бренд словаря».
    Записи — dict/oem.json records (oem_key, name, spellings)."""
    карта: dict[str, set] = collections.defaultdict(set)
    for r in записи:
        k, имя = r.get("oem_key"), r.get("name")
        if not k or not чистая(имя, k) or материал(имя):
            continue
        for н in {имя, k} | {s.get("spelling") for s in r.get("spellings") or []}:
            kн = ключ_написания(н or "")
            if len(kн) >= 2:
                карта[kн].add(k)
    return карта


def вид_записи(имя, ключ, карта: dict[str, set]) -> dict:
    """Вид записи: {"kind", "kind_why"?, "brands"?, "unresolved"?}.

    карта — карта_чистых(): по ней части имени ищутся среди брендов словаря.
    Часть, сведённая к двум записям, доказательством не служит."""
    п = признаки(имя, ключ)
    найдено = []                      # (часть, ключ бренда или None)
    for ч in части(имя):
        кк = карта.get(ключ_написания(ч), set())
        найдено.append((ч, next(iter(кк)) if len(кк) == 1 else None))
    бренды = []
    for _, k in найдено:
        if k and k != ключ and k not in бренды:
            бренды.append(k)

    мат = материал(имя)
    if мат:
        return _вид(МАТЕРИАЛ, f"материал, а не бренд: «{мат['spelling']}» ({мат['key']})", [])
    фраза = указание(имя)
    if фраза:
        return _вид(УКАЗАНИЕ, f"указание к закупке: «{фраза}»", бренды)
    if номер(имя, ключ):
        return _вид(НОМЕР, "номер детали вместо имени", [])
    без_бренда = [ч for ч, k in найдено if not k and имя_части(ч)]
    if п["несколько"] and len(бренды) >= 2:
        return _вид(НЕСКОЛЬКО, f"несколько брендов словаря в одной записи: {len(бренды)}",
                    бренды, без_бренда)
    # Разделитель брендов в голове имени вместе с пояснением — два признака
    # согласны: «Henkel / Dow (расходка)», «Bently Nevada / Wilcoxon (тип.)».
    # Без пояснения «/» один не обвиняет: «MTU / Rolls-Royce Power Systems» —
    # марка и владелец. Разделитель в самом пояснении («Versa Products (…) —
    # серия V/VSG») — часть пояснения, а не второй бренд.
    if п["описание"] and re.search(r"/|,|\sили\s", голова_имени(имя)):
        return _вид(НЕСКОЛЬКО, "несколько брендов с пояснением", бренды, без_бренда)
    # Описание: голова записи — бренд словаря («Bently Nevada (по профилю)»,
    # «Caterpillar, США»). Один бренд где-то в пояснении — не доказательство:
    # «X (картридж альтернативы — Mann & Hummel)» не Mann & Hummel.
    голова = найдено[0][1] if найдено else None
    if (п["описание"] or п["страна"]) and голова:
        почему = "страна в имени" if п["страна"] and not п["описание"] else "пояснение при бренде словаря"
        return _вид(ОПИСАНИЕ, почему, [голова])
    # Пояснение, называющее два бренда словаря и больше: «Тяжёлые ГТУ (GE /
    # Siemens / Alstom) — энергетика».
    if п["описание"] and len(бренды) >= 2:
        return _вид(ОПИСАНИЕ, "пояснение называет несколько брендов словаря", бренды)
    обвинения = [x for x in ("описание", "несколько", "номер", "страна") if п[x]]
    if обвинения:
        # Признак есть, доказательства нет: запись защищена и остаётся брендом.
        return {"kind": БРЕНД, "kind_why": "признак без доказательства, защищена: " + ", ".join(обвинения)}
    return {"kind": БРЕНД}


def имя_части(ч) -> bool:
    """Часть похожа на имя, а не на пояснение: с заглавной буквы или цифры, не
    страна и не пояснение («по диапазону из ТЗ», «тип.»)."""
    t = str(ч or "").strip()
    return bool(re.match(r"[A-ZА-ЯЁ0-9]", t)) and not страна(t) and not похоже_на_описание(t)


def _вид(вид, почему, бренды, без_бренда=None) -> dict:
    out = {"kind": вид, "kind_why": почему}
    if бренды:
        out["brands"] = list(бренды)
    if без_бренда:
        out["unresolved"] = list(без_бренда)
    return out


def вид(запись) -> str:
    """Вид записи для читателя. Записи без поля kind (словарь прежней сборки) —
    бренд: так читатель ведёт себя, как вёл до пометок."""
    return (запись or {}).get("kind") or БРЕНД


def бренд_ли(запись) -> bool:
    return вид(запись) == БРЕНД
