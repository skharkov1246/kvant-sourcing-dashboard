#!/usr/bin/env python3
"""Дилеры разведки брендов → реестр компаний. Только замер (вхолостую).

ЗАЧЕМ. Разведка брендов (data/brand_research/*.json, раздел dealers) называет
371 дилера, дистрибьютора и площадку бренда, а реестр компаний портала
(sup_entity с признаками sup_identifier) — тех, кто присылает нам КП. Пока
они не сведены, роль предложения (library/offer_role.py) узнаёт дилера только
по имени, а имя — только кандидат: «ООО Ромашка» и «АО Ромашка» — разные
юрлица. Сведённый сильным ключом дилер даёт предложению причину «трейдер:
официальный дилер» (решение владельца 26.09.2026: дилеры — трейдеры, в том
числе официальные), а сорсеру — ответ, у кого из наших компаний есть статус
у бренда.

ЧТО СВОДИТ — правило одно с library/supplier_link.py (тот же сопоставитель,
те же ключи и отказы):
  домен сайта  — поле domain записи дилера (ставится только с доказательством:
                 domain_source — ссылка из sources, чей узел — этот домен;
                 проверщик scripts/brand_research_check.py) против признака
                 domain реестра, точно;
  ИНН          — из текста записи («ИНН 7729634343») с верной контрольной
                 суммой, и из поля inn, если его заведут;
  имя          — ТОЛЬКО кандидат, связью не идёт (norm_name, без пояснений в
                 скобках: «Atlas Copco China (дочернее общество)» → «Atlas
                 Copco China»).
Общий домен (почта, площадка, соцсеть) не сводит; домен, ведущий в две
сущности, и домен против налогового номера — спор, а не связь.

ВИД ЗАПИСИ — offer_role.вид_дилера, закрытыми списками: своя площадка бренда
(дочерняя, филиал, изготовитель), официальный дилер (подтверждён ролью или
локатором бренда, без «независимый», «не подтверждён», самозаявления),
дилер (всё прочее — независимые, перепродавцы, самозаявленные).

ЧТО ПЕЧАТАЕТ — только агрегаты (CLAUDE.md, правило 17): числа записей,
компаний, ключей бренда (константы справочника). Ни имени дилера, ни домена,
ни ИНН, ни имени компании реестра.

ОДНОЙ ЧАСТЬЮ, И ЭТО РЕШЕНИЕ. Дилеров — сотни записей из файлов репозитория,
реестр читается тремя выборками за секунды; спор «одна сущность ← много
дилеров» и «домен носят много имён» видны только по всему набору. Запись в
базу не делается вовсе, Битрикс не читается.

    SUPABASE_DB_URL=… python library/dealer_link.py
"""
from __future__ import annotations

import collections
import json
import os
import re
import sys
from pathlib import Path
from typing import NamedTuple

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT))

from supplier_registry_overlap import norm_name, общий_домен, форма, хост  # noqa: E402

from library import offer_role  # noqa: E402
from library import supplier_link as sl  # noqa: E402

ПАПКА = ROOT / "data" / "brand_research"
ВИДЫ = (offer_role.СВОЯ, offer_role.ОФИЦИАЛЬНЫЙ, offer_role.ДИЛЕР)


# ── Ключи записи дилера ─────────────────────────────────────────────────────

def ключи_дилера(x: dict) -> tuple[frozenset, frozenset]:
    """Запись dealers разведки → (домены, ИНН). Домен — только поле domain
    (проверщик разведки требует доказательства), узлом, без общих; ИНН — из
    текста записи и поля inn, с верной контрольной суммой. Этот же разбор
    читает offer_role (Реестр.дилеры_ключ): роль предложения и замер сведения
    видят одни ключи."""
    домены = set()
    h = хост(str(x.get("domain") or ""))
    if sl._домен_годен(h) and not общий_домен(h):
        домены.add(h)
    инн = set(sl.инн_из_текста(x.get("company"), x.get("role")))
    if sl.инн(x.get("inn")):
        инн.add(sl.инн(x.get("inn")))
    return frozenset(домены), frozenset(инн)


def без_пояснений(имя) -> str:
    """«Atlas Copco China (дочернее общество, Дубай)» → «Atlas Copco China»."""
    return " ".join(re.sub(r"\([^)]*\)", " ", str(имя or "")).split())


class Дилер(NamedTuple):
    oem_key: str
    номер: int              # место записи в разделе dealers файла бренда
    вид: str                # offer_role.вид_дилера
    разведка: sl.Разведка   # ключи сопоставления в форме supplier_link


def дилеры(разведка: list[dict]) -> list[Дилер]:
    """Файлы разведки брендов (словари) → записи дилеров с ключами. id записи
    для сопоставителя — порядковый номер во всём наборе."""
    out = []
    for d in разведка:
        k = d.get("oem_key")
        if not k:
            continue
        for i, x in enumerate(d.get("dealers") or []):
            if not isinstance(x, dict):
                continue
            домены, инн = ключи_дилера(x)
            имя = без_пояснений(x.get("company"))
            р = sl.Разведка(
                id=len(out), ключ=f"{k}#{i}", имя=norm_name(имя), формы=форма(имя),
                страна=sl.страна(x.get("country")), налоги=frozenset(("inn", n) for n in инн),
                сайты=домены, почты=frozenset(), общих=int(bool(x.get("domain")) and not домены),
                телефон=False)
            out.append(Дилер(k, i, offer_role.вид_дилера(x.get("role")), р))
    return out


def читать_файлы(папка: Path = ПАПКА) -> list[dict]:
    out = []
    for f in sorted(папка.glob("*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        if isinstance(d, dict) and d.get("oem_key"):
            out.append(d)
    return out


def сопоставить(список: list[Дилер], р: sl.Реестр) -> sl.Итог:
    """То же правило, что сведение поставщиков разведки (supplier_link)."""
    return sl.сопоставить([x.разведка for x in список], р)


# ── Счёт (только агрегаты) ──────────────────────────────────────────────────

def счёт(список: list[Дилер], итог: sl.Итог) -> dict:
    """Все числа замера словарём — печать и тесты читают одно."""
    по_id = {x.разведка.id: x for x in список}
    компании = {x.разведка.имя or f"#{x.разведка.id}" for x in список}
    сведено = [по_id[i] for i in итог.связь]
    правила = collections.Counter(п for правила_ in итог.правила.values() for п in правила_)
    бренды_офиц = {x.oem_key for x in сведено if x.вид == offer_role.ОФИЦИАЛЬНЫЙ}
    return {
        "записей": len(список),
        "брендов": len({x.oem_key for x in список}),
        "компаний": len(компании),
        "по_виду": collections.Counter(x.вид for x in список),
        "с_доменом": sum(1 for x in список if x.разведка.сайты),
        "с_инн": sum(1 for x in список if x.разведка.налоги),
        "с_ключом": sum(1 for x in список if x.разведка.сайты or x.разведка.налоги),
        "домен_отсеян": sum(1 for x in список if x.разведка.общих),
        "сведено": len(итог.связь),
        "сведено_по": {"домен сайта": правила.get("домен сайта", 0),
                       "инн": правила.get("инн", 0)},
        "сведено_по_виду": collections.Counter(x.вид for x in сведено),
        "сущностей": len(set(итог.связь.values())),
        "брендов_с_офиц": len(бренды_офиц),
        "спор_две": len(итог.спор_две),
        "спор_налог": len(итог.спор_налог),
        "придержано": len(итог.придержано),
        "с_ключом_не_сведено": sum(1 for x in список if (x.разведка.сайты or x.разведка.налоги)
                                   and x.разведка.id not in итог.связь
                                   and x.разведка.id not in итог.спор_две | итог.спор_налог | итог.придержано),
        "кандидатов": len(итог.кандидаты),
        "кандидатов_одн": sum(1 for v in итог.кандидаты.values() if len(v) == 1),
        "кандидатов_стр": sum(1 for v in итог.кандидаты.values() if "имя+страна" in v.values()),
        "кандидатов_по_виду": collections.Counter(по_id[i].вид for i in итог.кандидаты),
        "отвергнуто": dict(итог.отвергнуто),
        "согласие": dict(итог.согласие),
    }


def печать(с: dict, сущностей: int, р: sl.Реестр) -> None:
    доля = sl.доля
    print("ДИЛЕРЫ РАЗВЕДКИ БРЕНДОВ (data/brand_research/*.json, dealers)")
    print(f"  записей:                               {с['записей']}  (брендов {с['брендов']}, "
          f"различных имён {с['компаний']})")
    for вид in ВИДЫ:
        print(f"    {вид:36} {с['по_виду'].get(вид, 0)}")
    print(f"  с доменом сайта (с доказательством):   {доля(с['с_доменом'], с['записей'])}")
    print(f"  с ИНН (контрольная сумма верна):       {с['с_инн']}")
    print(f"  с сильным ключом (домен или ИНН):      {доля(с['с_ключом'], с['записей'])}")
    print(f"  домен отсеян как общий:                {с['домен_отсеян']}")
    print(f"РЕЕСТР КОМПАНИЙ: сущностей {сущностей}; корней с доменом "
          f"{sum(1 for v in р.домены.values() if v)}, с налоговым номером "
          f"{sum(1 for v in р.налоги.values() if v)}")
    print()
    print("СВЕДЕНО СИЛЬНЫМ КЛЮЧОМ — связь")
    for п, n in с["сведено_по"].items():
        print(f"  {п:14} {n}")
    print(f"  ВСЕГО записей дилеров сведено:         {доля(с['сведено'], с['записей'])}")
    print(f"    из тех, у кого сильный ключ есть:    {доля(с['сведено'], с['с_ключом'])}")
    for вид in ВИДЫ:
        print(f"    {вид:36} {с['сведено_по_виду'].get(вид, 0)}")
    print(f"  сущностей реестра, получивших дилера:  {с['сущностей']}")
    print(f"  брендов, у которых сведён официальный дилер: {с['брендов_с_офиц']}")
    print(f"  с ключом, но в реестре его нет:        {с['с_ключом_не_сведено']}  ← компании нет в реестре "
          "или у неё нет этого признака")
    print()
    print("СПОРЫ — связью не идут")
    print(f"  ключи ведут в разные сущности:         {с['спор_две']}")
    print(f"  домен против налогового номера:        {с['спор_налог']}")
    print(f"  придержано (домен носят много имён):   {с['придержано']}")
    print()
    print("КАНДИДАТЫ ПО ИМЕНИ — только кандидат, связью не идут и роль предложения не меняют")
    print(f"  записей с кандидатом:                  {с['кандидатов']}  (однозначных {с['кандидатов_одн']}, "
          f"совпала страна {с['кандидатов_стр']})")
    for вид in ВИДЫ:
        print(f"    {вид:36} {с['кандидатов_по_виду'].get(вид, 0)}")
    print("  отвергнуто кандидатов:")
    for причина in ("правовые формы разные", "домены разные", "налоговые номера разные"):
        print(f"    {причина:26} {с['отвергнуто'].get(причина, 0)}")
    пров = sum(с["согласие"].values())
    print(f"  согласие имени с сильной связью (проверяемых {пров}):")
    for k in ("совпало", "среди нескольких", "мимо"):
        print(f"    {k:18} {с['согласие'].get(k, 0)}")


def прогон(conn, разведка: list[dict]) -> int:
    """Замер на готовом соединении (только выборки): реестр → сведение → печать."""
    список = дилеры(разведка)
    with conn.cursor() as cur:
        for опора in ("sup_entity", "sup_identifier"):
            if not sl.есть(cur, опора):
                print(f"нет таблицы {опора} — сводить не с чем", file=sys.stderr)
                return 2
        р, сущностей = sl.читать_реестр(cur)
    conn.rollback()
    итог = сопоставить(список, р)
    печать(счёт(список, итог), сущностей, р)
    print("\nПрогон ВХОЛОСТУЮ: в базу ничего не записано.")
    return 0


def main() -> int:
    dsn = os.environ.get("SUPABASE_DB_URL", "").strip()
    if not dsn:
        print("нет переменной SUPABASE_DB_URL", file=sys.stderr)
        return 2
    import psycopg2

    # statement_timeout — в строке подключения, а не через SET (правило 9).
    conn = psycopg2.connect(dsn, connect_timeout=20, options="-c statement_timeout=300000")
    try:
        conn.set_session(readonly=True)
        return прогон(conn, читать_файлы())
    finally:
        conn.close()


if __name__ == "__main__":
    raise SystemExit(main())
