# ОДНО ПРАВИЛО НА ЗАПИСЬ И НА ПОМЕТКУ. ложная_цена судит строку цены по тем
# полям, что лежат в lib_prices: наименование, код, единица, количество, цена,
# сумма, оговорка. Её зовут цена_из_текста (текстовый путь, до записи позиции),
