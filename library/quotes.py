# СРОК ПОСТАВКИ — ТОЛЬКО КАК ЕДИНСТВЕННОЕ СОДЕРЖАНИЕ СТРОКИ. «Delivery 4 weeks»
# в наименовании позиции — законная оговорка к ней, а строка, в которой, кроме
# срока, ничего нет («Items 1 & 2: Approx. 3–4 months»), ценой не бывает.
# Голое «Delivery» без срока (строка стоимости доставки) не обвиняется: это
# настоящие деньги предложения, хоть и не деталь.
