_ЧИСЛО = re.compile(r"-?\d[\d   '’.,]*")

# ПРЕДЕЛ ПРАВДОПОДОБИЯ — НЕ ВЫДУМАННЫЙ ПОРОГ, А ОБЪЯВЛЕННЫЙ КОНТРАКТ КОЛОНКИ.
# lib_prices.total объявлена numeric(18,4): она держит меньше 10^14. Значит число
# крупнее в неё просто не влезает, и записать его нельзя физически — полный
# переразбор 35769505964 упал на этом с «numeric field overflow».
#
# Но починка не в том, чтобы обрезать число до предела. Сто триллионов за позицию —
# это не дорогая деталь, это ПРОМАХ РАЗБОРА: склеенные колонки, номер телефона,
# принятый за сумму, длинный артикул, прочитанный числом. Строка с таким числом не
# заслуживает доверия целиком, и по собственному правилу этого модуля «цифра без
# основания хуже пустоты» она не пишется вовсе.
#
# Тот же предел применяется и к цене за единицу. Колонка price объявлена без
# точности и приняла бы сто триллионов МОЛЧА — а это хуже отказа: такое число
# утянет любое среднее и любой разброс, и заметить его будет нечем.
ПРЕДЕЛ_ЦЕНЫ = 10 ** 14


def правдоподобна(*числа) -> bool:
    """Число влезает в объявленную колонку. Иначе это не цена, а промах разбора."""
    return all(x is None or abs(x) < ПРЕДЕЛ_ЦЕНЫ for x in числа)



def валюта_из(текст: str) -> str | None:
    """Код валюты из произвольного текста: заголовка колонки или самой ячейки."""
    low = (текст or "").lower()
    for код, метки in ВАЛЮТЫ:
        if any(m in low for m in метки):
            return код
    return None


def базис_из(текст: str) -> str | None:
    """Базис поставки по Инкотермс. Только полное слово: «CIF» внутри «pacific»
    базисом не является."""
    up = (текст or "").upper()
    for b in БАЗИСЫ:
        if re.search(rf"(?<![A-Z]){b}(?![A-Z])", up):
            return b
    return None


def число_из(текст: str) -> float | None:
    """Число из ячейки. Терпит пробелы-разделители тысяч, запятую как дробную
    часть и валютные знаки рядом; «—», «по запросу», «-» дают None."""
    if not текст:
        return None
    m = _ЧИСЛО.search(текст.replace(" ", " ").replace(" ", " "))
    if not m:
        return None
    s = m.group(0).strip().rstrip(".,")
    s = s.replace(" ", "").replace("'", "").replace("’", "")
    # Какой знак дробный: последний из встреченных, если за ним не три цифры.
    точка, запятая = s.rfind("."), s.rfind(",")
    if точка >= 0 and запятая >= 0:
        дробный = max(точка, запятая)
        s = s[:дробный].replace(".", "").replace(",", "") + "." + s[дробный + 1:]
    elif запятая >= 0:
        s = s.replace(",", "." if len(s) - запятая - 1 != 3 else "")
    elif точка >= 0 and len(s) - точка - 1 == 3 and s.count(".") == 1:
        # «1.200» без второго разделителя — это тысяча двести, а не 1,2.
        # Оговорка: «1.200» как одна целая двести тысячных в КП не встречается.
        s = s.replace(".", "")
    try:
        v = float(s)
    except ValueError:
        return None
    return v if v == v and abs(v) != float("inf") else None


def срок_из(текст: str) -> int | None:
    """Срок поставки в днях. «4-6 недель» → 42: берём верхнюю границу, потому
    что обещанный минимум продавца — не срок, а надежда."""
    low = (текст or "").lower()
    if not low.strip():
        return None
    if any(w in low for w in _СКЛАД) and not re.search(r"\d", low):
        return 0
    числа = [float(x) for x in re.findall(r"\d+(?:[.,]\d+)?", low.replace(",", "."))]
    if not числа:
        return 0 if any(w in low for w in _СКЛАД) else None
    множитель = 1
    for метки, м in _СРОК_ЕД:
        if any(t in low for t in метки):
            множитель = м
            break
    д = int(round(max(числа) * множитель))
    return д if 0 <= д <= 3650 else None


def колонки_цены(заголовки: list[str], *, v2: bool | None = None) -> dict[str, int]:
    """Номера ценовых колонок в строке заголовков.

    Возвращает ключи price, total, currency, lead, basis — те, что нашлись.
    «Сумма» и «цена за единицу» ищутся раздельно и никогда не подменяют друг
    друга.

    v2 — выбирать price и total второй редакцией словаря (СЛОВАРЬ_V2); None —
    по флагу окружения PRICE_DICT_V2."""
    low = [(c or "").lower() for c in заголовки]
    найдено: dict[str, int] = {}
    v2 = СЛОВАРЬ_V2 if v2 is None else v2
    пары = (("price", ЦЕНА_ЗА_ЕД), ("total", СУММА_СТРОКИ),
            ("currency", ВАЛЮТА_КОЛОНКА), ("basis", БАЗИС_КОЛОНКА),
            ("pay", ОПЛАТА_КОЛОНКА), ("make", ПРОИЗВОДСТВО_КОЛОНКА))
    if v2:
        # Цену и сумму выбирает вторая редакция, и первая их не перебивает:
        # иначе «Сумма НДС», стоящая левее «Суммы с НДС», снова стала бы суммой.
        найдено.update(_ценовые_v2(заголовки)[0])
        пары = tuple(п for п in пары if п[0] not in ("price", "total"))
    for ключ, слова in пары:
        for j, c in enumerate(low):
            if c and any(w in c for w in слова):
                найдено.setdefault(ключ, j)
                break
    # Срок ПОСТАВКИ — отдельно и последним: сначала отсев чужих сроков, потом
    # совпадение. Иначе «Срок оплаты» становится сроком поставки (СРОК_ЧУЖОЙ), а
    # «Срок изготовления» — тоже: слово «срок» есть и там. Колонку изготовления
    # уже нашёл ключ make, и занимать ею же поставку нельзя.
    for j, c in enumerate(low):
        if not c or any(w in c for w in СРОК_ЧУЖОЙ):
            continue
        if j == найдено.get("make") or any(w in c for w in ПРОИЗВОДСТВО_КОЛОНКА):
            continue
        if any(w in c for w in СРОК_САМО) or any(w in c for w in СРОК_КОЛОНКА):
            найдено["lead"] = j
            break
    # Голое «цена» без указания «за единицу» встречается чаще всего и обычно
    # означает именно цену за единицу: рядом с ней в тех же КП стоит «сумма».
    if "price" not in найдено and not v2:
        for j, c in enumerate(low):
            if c and "цена" in c and j != найдено.get("total"):
                найдено["price"] = j
                break
    return найдено


