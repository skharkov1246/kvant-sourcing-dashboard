# Строки служебной записки: «Вывод: КП … дороже …». Начало «Вывод:» или
# сравнение цен предложений словами «дороже» и «дешевле» рядом с «КП».
_ВЫВОД = re.compile(r"^\W*(?:вывод|выводы|заключение)\s*[:—–-]", re.I)
_ДОРОЖЕ = re.compile(_Н + r"(?:дороже|дешевле)" + _К, re.I)
_КП = re.compile(_Н + r"(?:кп|предложени\w*)" + _К, re.I)

ПРИЧИНЫ_ЛОЖНОЙ = (tuple(вид for вид, _ in РЕКВИЗИТЫ)
                  + (ПРИЧИНА_СРОК, ПРИЧИНА_ЗАПИСКА, ПРИЧИНА_ВЫРОЖДЕНА))

# Код валюты, прилепленный к числу («USD100.00»), — деньги, а не марка: без
# разрезки docfilter.marks_pn засчитал бы такую сумму признаком позиции.
_ВАЛЮТА_У_ЧИСЛА = re.compile(
    r"(?:usd|eur|rmb|cny|rub|rur|gbp|kzt|inr|руб)\.?(?=\d)"
    r"|(?<=\d)(?:usd|eur|rmb|cny|rub|rur|gbp|kzt|inr|руб)" + _К, re.I)


def _число(v) -> float | None:
    """Число поля строки: float, Decimal из базы или None."""
    if v is None:
        return None
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    return f if f == f and abs(f) != float("inf") else None


def вырождена(кол, цена, сумма) -> bool:
    """«x × 1 = x»: цена не больше ПОРОГ_ВЫРОЖДЕНИЯ, а сумма равна количеству.

    Такая тройка сходится у любого x и потому ничего не доказывает: число в
    строке повторено дважды, а между ними стоит единица."""
    кол, цена, сумма = _число(кол), _число(цена), _число(сумма)
    if кол is None or цена is None or сумма is None or кол <= 0 or цена < 0:
        return False
    if цена > ПОРОГ_ВЫРОЖДЕНИЯ:
        return False
    return abs(сумма - кол) <= max(ДОПУСК_МИН, кол * ДОПУСК_НА_ЕДИНИЦУ)


def _без_чисел(текст: str, числа: tuple) -> str:
    """Строка без чисел самой тройки: сумма «143880» — не артикул."""
    значения = [x for x in числа if x is not None]
    out = []
    for t in текст.split():
        чистый = t.strip("()[]{}:;,¥$€£₽*#")
        if чистый and re.fullmatch(r"[\d.,'’]+", чистый):
            v = число_из(чистый)
            if v is not None and any(abs(v - x) < 0.005 for x in значения):
                continue
        out.append(t)
    return " ".join(out)


def признаки_позиции(имя, код=None, единица=None, кол=None, числа: tuple = ()) -> set[str]:
    """Признаки позиции в строке цены — то, что защищает её от обвинения.

    Ищутся в наименовании без фрагментов реквизитов (РЕКВИЗИТЫ) и без чисел
    тройки; код и единица из своих колонок считаются отдельно. Пустое множество —
    защиты нет. Имена признаков — собственные константы кода (для замера)."""
    текст = str(имя or "")
    фрагменты = []
    for _вид, rx in РЕКВИЗИТЫ:
        фрагменты.extend(m.group(0) for m in rx.finditer(текст))
        текст = rx.sub(" ", текст)
    текст = _без_чисел(_ВАЛЮТА_У_ЧИСЛА.sub(" ", текст), числа)
    out = set(docfilter.spec_marks(текст))
    if docfilter.part_number_of(текст):
        out.add("код")
    if segments.classify(текст):
        out.add("словарь")
    if str(единица or "").strip() and _число(кол) is not None:
        out.add("единица")
    к = str(код or "").strip()
    if к and docfilter.код_правдоподобен(к):
        ключ = docfilter.ключ_кода(к)
        число = число_из(к) if re.fullmatch(r"[\d.,'’ ]+", к) else None
        в_реквизите = bool(ключ) and any(ключ in docfilter.ключ_кода(ф) for ф in фрагменты)
        из_тройки = число is not None and any(
            x is not None and abs(число - x) < 0.005 for x in числа)
        if ключ and not в_реквизите and not из_тройки:
            out.add("код колонки")
    return out


def только_срок(имя) -> bool:
    """В строке, кроме срока поставки и пустых слов (СРОК_ПУСТЫЕ), ничего нет."""
    текст = str(имя or "")
    if not (СРОК_ПЕРИОД.search(текст) or СРОК_ФРАЗА.search(текст)):
        return False
    остаток = СРОК_ФРАЗА.sub(" ", СРОК_ПЕРИОД.sub(" ", текст)).lower().replace("ё", "е")
    слова = [w for w in re.findall(r"[a-zа-я]+", остаток)
             if len(w) >= 3 and w not in СРОК_ПУСТЫЕ]
    return not слова


def причина_без_защиты(имя, кол=None, цена=None, сумма=None) -> str | None:
    """Что обвинило бы строку, не будь у неё защиты: первая причина закрытого
    списка или None. Отдельно от защиты — чтобы замер видел, сколько строк
    спасла защита и какими признаками (правило 7: ошибка защиты видна числом)."""
    текст = str(имя or "")
    for вид, rx in РЕКВИЗИТЫ:
        if rx.search(текст):
            return вид
    if только_срок(текст):
        return ПРИЧИНА_СРОК
    if _ВЫВОД.search(текст) or (_ДОРОЖЕ.search(текст) and _КП.search(текст)):
        return ПРИЧИНА_ЗАПИСКА
    if вырождена(кол, цена, сумма):
        return ПРИЧИНА_ВЫРОЖДЕНА
    return None


def сумма_строки(кол, цена, сумма, оговорка) -> float | None:
    """Сумма строки цены. У текстового пути в базе её нет, но она сошлась с
    количеством и ценой по построению (ОГОВОРКА_ТЕКСТА) — выводится обратно."""
    сумма = _число(сумма)
    if сумма is not None:
        return сумма
    кол, цена = _число(кол), _число(цена)
    if кол is not None and цена is not None and ОГОВОРКА_ТЕКСТА in str(оговорка or ""):
        return кол * цена
    return None


def ложная_цена(имя, код=None, единица=None, кол=None, цена=None, сумма=None,
                оговорка=None) -> str | None:
    """Почему строка цены — не цена: причина из ПРИЧИНЫ_ЛОЖНОЙ или None.

    Поля — ровно колонки lib_prices: item_name, part_number, qty_unit, qty,
    price, total, note. Строку с признаком позиции (признаки_позиции) не
    обвиняет ничто; остальное обвиняет только закрытый список."""
    сумма = сумма_строки(кол, цена, сумма, оговорка)
    причина = причина_без_защиты(имя, кол, цена, сумма)
    if причина is None:
        return None
    if признаки_позиции(имя, код, единица, кол, (_число(кол), _число(цена), сумма)):
        return None
    return причина
