"""Цена из коммерческого предложения поставщика.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Разборщик вложений писался под спецификации заказчика:
что просят, сколько штук, в каких единицах. Цены там нет и быть не должно.
Файлы КП — обратное: номенклатура в них вторична, а весь смысл в цене, валюте и
сроке. Замер 21.09.2026: в lib_demand нет колонки цены вообще, и разбор 5 231
файла КП собрал бы номенклатуру, выбросив ровно то, ради чего затевался.

ЧТО ЗДЕСЬ ГЛАВНОЕ — РАЗНИЦА МЕЖДУ ЦЕНОЙ И СУММОЙ. В КП рядом стоят «Цена за
ед.» и «Сумма»; перепутать их значит завысить в qty раз. Это та же ошибка, что
стоила доверия к выкладке по ЛУКОЙЛу (CLAUDE.md, «Числа в выгрузках владельцу»),
только на пять тысяч файлов. Поэтому:

* цена за единицу берётся только из колонки, названной ценой за единицу;
* сумма строки ценой не считается никогда — из неё цена ВЫВОДИТСЯ делением на
  количество, и такая строка помечена уверенностью «low» и оговоркой;
* если количества нет, а есть только сумма — строка не пишется совсем.
  Неизвестное лучше отсутствующего: цифра без основания хуже пустоты.

ВАЛЮТА НЕ УГАДЫВАЕТСЯ. Не нашли — пишем NULL, а не «EUR по умолчанию».
Умолчание в схеме сработало бы молча и превратило бы юани в евро.
"""

from __future__ import annotations

import re

# Правило правдоподобного кода живёт в docfilter (без зависимостей). Модуль
# грузят и пакетом (library.quotes), и из каталога library/ (индексатор, ocr).
try:
    from . import docfilter
except ImportError:
    import docfilter

# Заголовки колонок. Разделены намеренно: «цена» и «сумма» — разные величины,
# и общий список склеил бы их обратно.
ЦЕНА_ЗА_ЕД = [
    "цена за ед", "цена ед", "цена, ", "цена(", "цена руб", "цена usd", "цена eur",
    "цена за единиц", "стоимость ед", "стоимость за ед", "unit price", "price per",
    "цена/ед", "цена за шт", "price, ", "unit cost",
]
СУММА_СТРОКИ = [
    "сумма", "итого по", "стоимость поз", "стоимость строки", "total", "amount",
    "общая стоимость", "line total",
]
ВАЛЮТА_КОЛОНКА = ["валюта", "currency", "вал."]
# Основы слов, а не именительный падеж: в русском КП «поставка» почти всегда в
# косвенном падеже («срок поставки», «условия поставки»), и якорь «поставка» не
# ловил ничего.
СРОК_КОЛОНКА = [
    "срок поставк", "срок изготовл", "срок,", "срок ", "поставк, ", "lead time",
    "delivery time", "delivery, ", "отгрузк",
]
# ЧУЖИЕ СРОКИ. Колонка срока ищется по подстроке «срок», и до 22.09.2026 образец
# «срок » (с пробелом) уже ловил «Срок оплаты» и «Срок действия предложения» —
# то есть срок поставки читался из условий платежа. Тридцать дней отсрочки
# становились тридцатью днями поставки, и ни оговорки, ни признака не было.
#
# Поэтому колонка срока ищется отдельно от остальных: сначала отсев по этому
# списку, потом совпадение. Голое «Срок» при этом стало законным — самая частая
# запись в шапке, и ни один прежний образец её не ловил, потому что все требовали
# что-нибудь после слова.
СРОК_ЧУЖОЙ = ("оплат", "действ", "гарант", "рассмотр", "хранен", "отсрочк",
              "payment", "validity", "warranty", "terms", "basis", "address",
              "условия", "базис", "адрес", "incoterm")
# Слова, означающие колонку срока сами по себе, без уточнения. Русское «срок» и
# английские «delivery» и «lead» — самые частые записи в шапке, и ни один образец
# из СРОК_КОЛОНКА их не ловит: у всех требуется что-нибудь после слова. На
# придуманном КП со столбцом «Delivery» срок поставки не читался вовсе, при том
# что он там написан, — а КП с английской шапкой у нас больше всех.
СРОК_САМО = ("срок", "delivery", "lead time", "lead-time", "leadtime")
БАЗИС_КОЛОНКА = ["базис", "условия поставки", "incoterms", "инкотермс", "basis"]
# Колонка условий оплаты и колонка срока ИЗГОТОВЛЕНИЯ. Разбирает их значения
# library/offer_terms.py — здесь только место в шапке: цена и коммерческие условия
# живут в разных модулях, и импорт идёт одним направлением (offer_terms → quotes).
ОПЛАТА_КОЛОНКА = ["условия оплаты", "оплата", "payment", "terms of payment",
                  "платеж", "платёж"]
ПРОИЗВОДСТВО_КОЛОНКА = ["срок изготовл", "срок производств", "время изготовл",
                        "production time", "production lead", "manufacturing",
                        "изготовлен"]

# Валюты: знак, код, слово. Порядок важен — «руб» найдётся и внутри «рублей».
ВАЛЮТЫ: list[tuple[str, tuple[str, ...]]] = [
    ("RUB", ("₽", "руб", "rub", "rur", "рубл")),
    ("USD", ("$", "usd", "долл", "dollar")),
    ("EUR", ("€", "eur", "евро", "euro")),
    ("CNY", ("¥", "cny", "rmb", "юан", "yuan")),
    ("KZT", ("₸", "kzt", "тенге")),
    ("GBP", ("£", "gbp", "фунт")),
]

БАЗИСЫ = ("EXW", "FCA", "FOB", "CIF", "CIP", "CPT", "DAP", "DDP", "DAT")

# Одна формулировка на весь модуль: её же снимает подстановка валюты файла.
НЕТ_ВАЛЮТЫ = "валюта в файле не названа"

# Единицы срока. Склад и наличие — ноль дней, и это не догадка: так написано.
_СРОК_ЕД = [
    (("недел", "week", "нед."), 7),
    (("месяц", "мес.", "мес ", "month"), 30),
    (("рабоч", "раб.дн", "раб. дн", "working day", "business day"), 1),
    (("дн", "day", "сут"), 1),
]
_СКЛАД = ("склад", "наличи", "in stock", "ex stock", "сток")

_ЧИСЛО = re.compile(r"-?\d[\d   '’.,]*")

# ПРЕДЕЛ ПРАВДОПОДОБИЯ — НЕ ВЫДУМАННЫЙ ПОРОГ, А ОБЪЯВЛЕННЫЙ КОНТРАКТ КОЛОНКИ.
# lib_prices.total объявлена numeric(18,4): она держит меньше 10^14. Значит число
# крупнее в неё просто не влезает, и записать его нельзя физически — полный
# переразбор 35769505964 упал на этом с «numeric field overflow».
#
# Но починка не в том, чтобы обрезать число до предела. Сто триллионов за позицию —
# это не дорогая деталь, это ПРОМАХ РАЗБОРА: склеенные колонки, номер телефона,
# принятый за сумму, длинный артикул, прочитанный числом. Строка с таким числом не
# заслуживает доверия целиком, и по собственному правилу этого модуля «цифра без
# основания хуже пустоты» она не пишется вовсе.
#
# Тот же предел применяется и к цене за единицу. Колонка price объявлена без
# точности и приняла бы сто триллионов МОЛЧА — а это хуже отказа: такое число
# утянет любое среднее и любой разброс, и заметить его будет нечем.
ПРЕДЕЛ_ЦЕНЫ = 10 ** 14


def правдоподобна(*числа) -> bool:
    """Число влезает в объявленную колонку. Иначе это не цена, а промах разбора."""
    return all(x is None or abs(x) < ПРЕДЕЛ_ЦЕНЫ for x in числа)



def валюта_из(текст: str) -> str | None:
    """Код валюты из произвольного текста: заголовка колонки или самой ячейки."""
    low = (текст or "").lower()
    for код, метки in ВАЛЮТЫ:
        if any(m in low for m in метки):
            return код
    return None


def базис_из(текст: str) -> str | None:
    """Базис поставки по Инкотермс. Только полное слово: «CIF» внутри «pacific»
    базисом не является."""
    up = (текст or "").upper()
    for b in БАЗИСЫ:
        if re.search(rf"(?<![A-Z]){b}(?![A-Z])", up):
            return b
    return None


def число_из(текст: str) -> float | None:
    """Число из ячейки. Терпит пробелы-разделители тысяч, запятую как дробную
    часть и валютные знаки рядом; «—», «по запросу», «-» дают None."""
    if not текст:
        return None
    m = _ЧИСЛО.search(текст.replace(" ", " ").replace(" ", " "))
    if not m:
        return None
    s = m.group(0).strip().rstrip(".,")
    s = s.replace(" ", "").replace("'", "").replace("’", "")
    # Какой знак дробный: последний из встреченных, если за ним не три цифры.
    точка, запятая = s.rfind("."), s.rfind(",")
    if точка >= 0 and запятая >= 0:
        дробный = max(точка, запятая)
        s = s[:дробный].replace(".", "").replace(",", "") + "." + s[дробный + 1:]
    elif запятая >= 0:
        s = s.replace(",", "." if len(s) - запятая - 1 != 3 else "")
    elif точка >= 0 and len(s) - точка - 1 == 3 and s.count(".") == 1:
        # «1.200» без второго разделителя — это тысяча двести, а не 1,2.
        # Оговорка: «1.200» как одна целая двести тысячных в КП не встречается.
        s = s.replace(".", "")
    try:
        v = float(s)
    except ValueError:
        return None
    return v if v == v and abs(v) != float("inf") else None


def срок_из(текст: str) -> int | None:
    """Срок поставки в днях. «4-6 недель» → 42: берём верхнюю границу, потому
    что обещанный минимум продавца — не срок, а надежда."""
    low = (текст or "").lower()
    if not low.strip():
        return None
    if any(w in low for w in _СКЛАД) and not re.search(r"\d", low):
        return 0
    числа = [float(x) for x in re.findall(r"\d+(?:[.,]\d+)?", low.replace(",", "."))]
    if not числа:
        return 0 if any(w in low for w in _СКЛАД) else None
    множитель = 1
    for метки, м in _СРОК_ЕД:
        if any(t in low for t in метки):
            множитель = м
            break
    д = int(round(max(числа) * множитель))
    return д if 0 <= д <= 3650 else None


def колонки_цены(заголовки: list[str]) -> dict[str, int]:
    """Номера ценовых колонок в строке заголовков.

    Возвращает ключи price, total, currency, lead, basis — те, что нашлись.
    «Сумма» и «цена за единицу» ищутся раздельно и никогда не подменяют друг
    друга."""
    low = [(c or "").lower() for c in заголовки]
    найдено: dict[str, int] = {}
    пары = (("price", ЦЕНА_ЗА_ЕД), ("total", СУММА_СТРОКИ),
            ("currency", ВАЛЮТА_КОЛОНКА), ("basis", БАЗИС_КОЛОНКА),
            ("pay", ОПЛАТА_КОЛОНКА), ("make", ПРОИЗВОДСТВО_КОЛОНКА))
    for ключ, слова in пары:
        for j, c in enumerate(low):
            if c and any(w in c for w in слова):
                найдено.setdefault(ключ, j)
                break
    # Срок ПОСТАВКИ — отдельно и последним: сначала отсев чужих сроков, потом
    # совпадение. Иначе «Срок оплаты» становится сроком поставки (СРОК_ЧУЖОЙ), а
    # «Срок изготовления» — тоже: слово «срок» есть и там. Колонку изготовления
    # уже нашёл ключ make, и занимать ею же поставку нельзя.
    for j, c in enumerate(low):
        if not c or any(w in c for w in СРОК_ЧУЖОЙ):
            continue
        if j == найдено.get("make") or any(w in c for w in ПРОИЗВОДСТВО_КОЛОНКА):
            continue
        if any(w in c for w in СРОК_САМО) or any(w in c for w in СРОК_КОЛОНКА):
            найдено["lead"] = j
            break
    # Голое «цена» без указания «за единицу» встречается чаще всего и обычно
    # означает именно цену за единицу: рядом с ней в тех же КП стоит «сумма».
    if "price" not in найдено:
        for j, c in enumerate(low):
            if c and "цена" in c and j != найдено.get("total"):
                найдено["price"] = j
                break
    return найдено


def валюта_заголовка(заголовки: list[str], цк: dict[str, int]) -> str | None:
    """Валюта, названная в шапке таблицы: «Цена за ед., EUR».

    Это самое частое место, где валюта вообще написана: в ячейках стоят голые
    числа. Спрашиваются только ценовые колонки — «Кол-во, руб-метров» валютой
    колонку не делает."""
    for ключ in ("price", "currency", "total"):
        j = цк.get(ключ, -1)
        if 0 <= j < len(заголовки):
            в = валюта_из(заголовки[j])
            if в:
                return в
    return None


def цена_строки(row: list[str], цк: dict[str, int], qty: float | None,
                валюта_колонки: str | None = None,
                валюта_файла: str | None = None) -> dict | None:
    """Ценовая часть строки КП или None, если цены в строке нет.

    qty — количество из той же строки: без него сумма в цену не превращается.
    валюта_файла — валюта, найденная в тексте файла целиком; берётся, только
    если ни заголовок колонки, ни ячейка своей валюты не назвали.
    """
    def ячейка(ключ: str) -> str:
        j = цк.get(ключ, -1)
        return row[j].strip() if 0 <= j < len(row) else ""

    сырая_цена = ячейка("price")
    сырая_сумма = ячейка("total")
    # Ячейка, в которой стоит марка или размер («SS316», «19mm»), числа не
    # несёт: число_из вынуло бы из «SS316» цену 316 (карточка номенклатуры,
    # 24.09.2026). Судит то же правило, что отказывает таким токенам в коде, —
    # по одному ключу: стандарт с размером («DIN 471 25») для кода годен, но
    # цены в ячейке тоже не несёт.
    цена = число_из(сырая_цена) if docfilter.класс_ключа(сырая_цена) is None else None
    сумма = число_из(сырая_сумма) if docfilter.класс_ключа(сырая_сумма) is None else None

    уверенность, оговорка = "med", None
    if цена is not None and цена > 0:
        pass
    elif сумма is not None and сумма > 0:
        if not qty or qty <= 0:
            return None                      # сумма без количества цены не даёт
        цена = сумма / qty
        уверенность = "low"
        оговорка = "цена выведена делением суммы строки на количество"
    else:
        return None

    # От частного к общему: своя ячейка → шапка ценовой колонки → ячейка колонки
    # валюты → ячейка суммы → валюта файла целиком.
    валюта = (валюта_из(сырая_цена) or валюта_колонки or валюта_из(ячейка("currency"))
              or валюта_из(сырая_сумма) or валюта_файла)
    if валюта is None:
        уверенность = "low"
        оговорка = "; ".join(x for x in (оговорка, НЕТ_ВАЛЮТЫ) if x)

    срок = срок_из(ячейка("lead"))
    базис = базис_из(ячейка("basis")) or базис_из(ячейка("price"))
    # СУММА ВОЗВРАЩАЕТСЯ, А НЕ ТОЛЬКО УЧАСТВУЕТ В РАСЧЁТЕ. Прежде она читалась,
    # из неё выводилась цена делением на количество, и след терялся. Проверить
    # «цена × количество = сумма» задним числом было нечем, а это единственная
    # самопроверка ценовой строки, какая у нас есть.
    сумма_к_записи = сумма if сумма is not None and сумма > 0 else None
    if not правдоподобна(цена, сумма_к_записи):
        return None            # промах разбора: см. ПРЕДЕЛ_ЦЕНЫ
    return {"price": round(цена, 4), "currency": валюта, "basis": базис,
            "lead_days": срок, "confidence": уверенность, "note": оговорка,
            "total": round(сумма_к_записи, 4) if сумма_к_записи else None}


def валюта_файла(текст: str) -> str | None:
    """Валюта всего КП: берётся, если в тексте встречается ровно одна.

    Две валюты в одном файле — обычное дело (цена в евро, НДС в рублях), и
    тогда угадывать нельзя: колонка решит сама."""
    low = (текст or "").lower()
    нашлись = {код for код, метки in ВАЛЮТЫ if any(m in low for m in метки)}
    return нашлись.pop() if len(нашлись) == 1 else None


# ─────────────────────────────────────────────────────────────────────────────
# Цена из ТЕКСТОВОЙ строки (PDF без таблицы)
#
# ЗАЧЕМ ОТДЕЛЬНОЕ ПРАВИЛО. Замер 21.09.2026: пробный разбор четырёх файлов КП дал
# 139 позиций и НОЛЬ цен. Причина не в колонках — КП приходят PDF-ами, а PDF
# разбирается построчно, таблицы там нет вовсе, и весь разбор по заголовкам мимо.
#
# КАК ОТЛИЧИТЬ ЦЕНУ ОТ СУММЫ БЕЗ ЗАГОЛОВКОВ. Никак — если гадать. Но строка
# позиции обычно несёт все три числа сразу, и между ними есть проверяемое
# отношение: количество × цена = сумма. Оно самопроверяемо: тройка, которая
# сошлась, почти не может быть случайной, а не сошедшаяся не берётся вовсе.
# Поэтому здесь нет порогов «похожести» — есть арифметика.
#
# ЧЕГО ЭТО ПРАВИЛО НЕ ДЕЛАЕТ. Оно не берёт цену из строки, где сумма не указана:
# одинокое число в строке — это и цена, и вес, и год, и номер позиции. Пропустить
# такую строку дешевле, чем объявить ценой чужое число.
ШУМ_СТРОКИ = re.compile(
    r"(?i)(ндс|итого|всего|подытог|скидк|предоплат|отсрочк|курс|\bстр\.|страница)")
# Число с необязательной дробной частью. Пробел допускается ТОЛЬКО как разделитель
# тысяч, то есть перед ровно тремя цифрами. Свободный пробел внутри числа склеивал
# соседние: «50   4 » читалось как 504, и тройка не сходилась (поймано на разборе
# строки «…M74N-50   4 шт   850,00   3 400,00»).
_ТОКЕН = re.compile(
    r"(?<![\d.,])\d{1,3}(?:[ \u00a0\u202f'’]\d{3})+(?:[.,]\d{1,4})?(?![\d])"
    r"|(?<![\d.,])\d+(?:[.,]\d{1,4})?(?![\d])")
# Ниже этой суммы строка не считается позицией: «2 3 6» арифметике удовлетворяет,
# но ценой не является.
МИН_СУММА = 10.0
МАКС_КОЛИЧЕСТВО = 1_000_000.0
# ОГОВОРКИ О КОЛИЧЕСТВЕ (library/indexer.сверить_количество). Количество не
# угадывается: не читается или не сошлось с ценой и суммой — оно не пишется, а
# строка цены несёт одну из этих фраз. По второй её считает «строк_сумма_не_
# сошлась» страницы /brands (library/codes_sql.py): без неё строка со снятым
# количеством выпала бы из сверки молча.
КОЛ_НЕ_ЧИТАЕТСЯ = "количество не читается (больше предела) — не записано"
КОЛ_НЕ_СОШЛОСЬ = "количество не сошлось с ценой и суммой — не записано"
# Метка цены, выведенной из суммы делением: такая цена сходится с суммой по
# построению, и сверка тройки её не проверяет.
ОГОВОРКА_ИЗ_СУММЫ = "делением суммы"
# ДОПУСК ПРИВЯЗАН К КОЛИЧЕСТВУ, А НЕ К СУММЕ. Расхождение берётся из того, что
# в КП напечатана округлённая цена за единицу: 1000 × 12,345 показано как 12,35,
# и сумма расходится на qty × полкопейки. От суммы допуск не зависит вовсе —
# доля от суммы дала бы на девятистах тысячах четыре с половиной тысячи слака,
# и «10 × 100 = 999» прошло бы как сошедшееся.
ДОПУСК_НА_ЕДИНИЦУ = 0.005
ДОПУСК_МИН = 0.5


def _числа_строки(строка: str) -> list[float]:
    значения = []
    for m in _ТОКЕН.finditer(строка):
        v = число_из(m.group(0))
        if v is not None:
            значения.append(v)
    return значения


def цена_из_текста(строка: str, валюта_файла: str | None = None) -> dict | None:
    """Цена из строки PDF без таблицы — только если арифметика сошлась.

    Ищется тройка подряд идущих чисел (кол-во, цена, сумма), для которой
    кол-во × цена = сумма с допуском на округление. Берётся самая правая такая
    тройка: слева в строке стоят номер позиции и характеристики, справа — деньги.
    """
    if not строка or ШУМ_СТРОКИ.search(строка):
        return None
    # В строке позиции обязан быть текст: «1 2 2» — не позиция.
    if len(re.sub(r"[^A-Za-zА-Яа-яЁё]", "", строка)) < 4:
        return None
    числа = _числа_строки(строка)
    if len(числа) < 3:
        return None
    for i in range(len(числа) - 3, -1, -1):
        кол, цена, сумма = числа[i], числа[i + 1], числа[i + 2]
        if not (0 < кол <= МАКС_КОЛИЧЕСТВО) or цена <= 0 or сумма < МИН_СУММА:
            continue
        ожидание = кол * цена
        if abs(ожидание - сумма) > max(ДОПУСК_МИН, кол * ДОПУСК_НА_ЕДИНИЦУ):
            continue
        if not правдоподобна(цена, сумма):
            continue           # промах разбора: см. ПРЕДЕЛ_ЦЕНЫ
        валюта = валюта_из(строка) or валюта_файла
        уверенность = "med" if валюта else "low"
        оговорка = "цена опознана в тексте по равенству кол-во × цена = сумма"
        if валюта is None:
            оговорка += "; " + НЕТ_ВАЛЮТЫ
        return {"price": round(цена, 4), "currency": валюта, "basis": базис_из(строка),
                "lead_days": None, "confidence": уверенность, "note": оговорка,
                "qty": кол}
    return None


def подставить_валюту(ц: dict, валюта: str | None) -> dict:
    """Валюта файла вместо ненайденной — с исправлением оговорки и уверенности.

    Без этого в строке оставались бы две несовместимые фразы разом: «валюта не
    названа» и «валюта взята по файлу». Оговорка должна описывать итог, а не
    историю его получения.
    """
    if not ц or валюта is None or ц.get("currency") is not None:
        return ц
    ц["currency"] = валюта
    части = [ч for ч in (ц.get("note") or "").split("; ") if ч and ч != НЕТ_ВАЛЮТЫ]
    части.append("валюта взята по файлу целиком")
    ц["note"] = "; ".join(части)
    # Отсутствие валюты было единственной причиной низкой уверенности — снимаем.
    if ц.get("confidence") == "low" and not any("делением" in ч for ч in части):
        ц["confidence"] = "med"
    return ц
