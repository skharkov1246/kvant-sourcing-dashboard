# скидкой». Любая другая цена её не отменяет, и правило суммы #479 («при сумме —
# только сошедшаяся») на неё не распространяется. Перебор 27.09.2026 с правилом
# #479 целиком дал хуже у 2 416 строк части A и у 40 000 строк части D: «List
# price | Line price» — другая «цена» оказалась суммой строки под словом цены
# (у английской шапки нет прежней колонки цены, которая спасает русскую);
# «Catalogue price | Amount incl. VAT» — сумма с НДС не сходится с ценой без
# него, и цена выводилась из суммы уже с НДС; «Catalogue price | Цена с НДС |
# Amount» — цена с НДС при сумме без него, и количество снималось.
# Скидка, названная рядом с листовой ценой, — та же оговорка, что у прайсовой.
ЦЕНА_V2_ЛИСТ = ("list price", "list-price", "listprice", "catalogue price",
                "catalog price", "listenpreis", "прейскурант", "каталожн", "по каталогу")
ЦЕНА_V2_НЕТТО = re.compile(
    r"\bnett?\s+(?:unit\s+)?price|\bunit\s+net\s+price|\byour\s+price"
    r"|\bdiscount(?:ed)?\s+price|\bspecial\s+price|\boffer(?:ed)?\s+price"
    r"|\bprice\s+(?:after|with)\s+discount|nettopreis"
    r"|со\s+скидк|с\s+уч[её]том\s+скидк|после\s+скидк|специальн\w*\s+цен|ваша\s+цена"
    r"|цена\s+предложени")
# КОЛОНКА СКИДКИ — то, о чём колонка, как у налога (ндс_колонки): «Скидка, %»,
# «Discount», «Сумма скидки», «Discount amount», «Скидка, сумма». «Цена со
# скидкой», «Сумма с учётом скидки», «Discount price», «Price after discount»,
# «Discounted amount» — цена и сумма, при которых скидка лишь названа.
#
# СУММОЙ СТРОКИ КОЛОНКА СКИДКИ НЕ БЫВАЕТ (27.09.2026). До того v2 брал «Сумму
# скидки» и «Discount amount» суммой строки: слово суммы в них есть. Отсюда
# цена «скидка ÷ количество» в КП без колонки цены и снятое количество в КП с
# ней (тройка «кол-во × цена = скидка» не сходится). Теперь колонка скидки не
# кандидат ни суммы, ни цены (_кандидаты_v2). Сумма, ставшая суммой строки
# ВМЕСТО неё, — новый выбор, и при колонке цены он доказывается арифметикой по
# файлу (indexer.items_from_rows, скидка_была_суммой): перебор части C показал
# 5 092 строки, где простое исключение снимало количество, — скидка нулевая, а
# следующая сумма другой природы НДС («Сумма с НДС» при цене без оговорки).
СКИДКА_СЛОВА = re.compile(r"скидк|discount|rabatt|折扣")
СКИДКА_ПРЕДМЕТ = re.compile(
    r"(?:сумм\w*|размер\w*|величин\w*|стоимост\w*|итого|всего)\s+скидк"
    r"|(?:amount|sum|total|value)\s+of\s+discount|total\s+discount"
    r"|discount\s+(?:amount|sum|value|total)")
# Скидка названа первой, а цены в шапке нет: «Скидка, сумма», «Скидка (сумма,
# руб.)», «Discount, amount». Существительное целиком: «Discounted amount» —
# сумма со скидкой, а «Discount price» — цена (при ней слово цены).
СКИДКА_ПЕРВОЙ = re.compile(r"^\W*(?:скидк[аи]|discount|rabatt)\b")
# Сумма строки. «Total price» и «Gesamtpreis» — сумма, хотя в них есть «price»:
# проверка суммы идёт РАНЬШЕ проверки цены.
СУММА_V2 = tuple(СУММА_СТРОКИ) + (
    "total price", "gesamtpreis", "gesamt", "总价", "金额", "extended price",
    "ext. price", "всего", "итого",
)
# НДС. Колонка «Сумма НДС» — это налог, а не сумма строки: взятая суммой, она
# вывела бы цену делением налога на количество.
#
# НАЛОГ — ТО, О ЧЁМ КОЛОНКА, А НЕ ТО, ЧТО В НЕЙ УПОМЯНУТО. До 27.09.2026 налогом
# считалась всякая шапка с НДС без «с» и «без» — и «Unit price (13%VAT)», «Цена,
# руб. НДС 20%», «Amount (13%VAT)» тоже. Вторая редакция словаря такую цену не
# брала вовсе, хотя прежнее правило её читало (перебор выдуманных шапок: 902
# шапки «прежнее дало цену за единицу — v2 ничего»), а сумму не брала опорой, и
# колонку суммы под словом цены сверить было не с чем. Теперь колонка — налог,
# если налог и есть её предмет (ндс_колонки):
#   • в шапке нет слова цены или суммы: «НДС», «НДС, руб.», «НДС 20%», «Tax»;
#   • налог назван раньше слова суммы: «VAT amount», «Tax total», «НДС, сумма»;
#   • налог — дополнение при слове суммы: «Сумма НДС», «Итого НДС», «Сумма
#     налога», «Amount of VAT», «Total VAT» (НАЛОГ_ПРЕДМЕТ).
# Иначе налог только упомянут в шапке цены или суммы — «упомянут»: колонка
# остаётся ценой или суммой, а включён ли НДС, не сказано, и строка несёт об
# этом оговорку. Ценой «с НДС» она не объявляется и на ставку не делится: так
# сказано только при «с НДС», «incl.», «в т.ч.» (С_НДС).
НДС_СЛОВА = ("ндс", "vat", "mwst", "增值税")
# Налог, названный не «НДС»: «Сумма налога», «Tax amount», «税额». Английское
# «tax» — только целым словом: «Taxable amount» — облагаемая сумма, не налог.
НАЛОГ_СЛОВА = re.compile(r"ндс|vat|mwst|增值税|налог|\btax(?:es)?\b|税")
БЕЗ_НДС = ("без ндс", "без учета ндс", "без учёта ндс", "ндс не облага",
           "не облагается", "ндс не предусм", "excl", "w/o vat", "without vat",
           "net of vat", "ohne mwst", "netto", "不含税",
           "ex vat", "ex. vat", "ex-vat", "exc vat", "exc. vat",
           "без налог", "w/o tax", "without tax", "net of tax", "before tax",
           "tax free", "tax-free")
С_НДС = ("с ндс", "с учетом ндс", "с учётом ндс", "вкл", "в т.ч", "в т. ч",
         "в том числе", "incl", "with vat", "inkl", "brutto", "含税",
         "inc vat", "inc. vat",
         "с налог", "с учетом налог", "с учётом налог", "with tax")
# Налог — дополнение при слове суммы: «Сумма НДС», «Итого НДС», «Сумма налога»,
# «Стоимость НДС», «Amount of VAT», «Total VAT». Между словами только пробел:
# «Сумма, руб. НДС 20%» и «Сумма (НДС 20%)» — сумма, при которой НДС упомянут.
# «Цены» здесь нет: у налога цены не бывает, «Цена НДС» — цена.
НАЛОГ_ПРЕДМЕТ = re.compile(
    r"(?:сумм\w*|стоимост\w*|размер\w*|величин\w*|ставк\w*|итого|всего)\s+(?:ндс|налог)"
    r"|(?:amount|sum|total|value)\s+of\s+(?:vat|tax\b)"
    r"|total\s+(?:vat|tax\b)")
# Голое «Стоимость» — цена или сумма, по самому слову не понять. Решает файл
# целиком (indexer.стоимость_как_цена), здесь только место колонки.
СТОИМОСТЬ_ГОЛАЯ = "стоимость"

ОГОВОРКА_БЕЗ_НДС = "взята цена без НДС (в файле есть и с НДС)"
ОГОВОРКА_С_НДС = "цена указана с НДС"
ОГОВОРКА_БЕЗ_НДС_ОДНА = "цена указана без НДС"
ОГОВОРКА_НДС_НЕ_СКАЗАНО = "НДС упомянут в шапке, включён ли в цену — не сказано"


def _слово_цены_или_суммы(low: str) -> int | None:
    """Где в шапке первое слово цены или суммы (словарь v2), или None."""
    места = [low.find(w) for w in (*ЦЕНА_V2_ЕД, *ЦЕНА_V2_СЛОВО, *СУММА_V2, СТОИМОСТЬ_ГОЛАЯ)
             if w in low]
    return min(места) if места else None


def ндс_колонки(c: str) -> str | None:
    """Что шапка говорит об НДС: «без», «с», «налог» (колонка самого налога),
    «упомянут» (цена или сумма, при которой НДС назван, но не сказано, включён
    ли), или None — если об НДС молчит."""
    low = (c or "").lower()
    if any(w in low for w in БЕЗ_НДС):
        return "без"
    if any(w in low for w in С_НДС):
        return "с"
    налог = НАЛОГ_СЛОВА.search(low)
    if not налог:
        return None
    слово = _слово_цены_или_суммы(low)
    if слово is None or налог.start() < слово or НАЛОГ_ПРЕДМЕТ.search(low):
        return "налог"
    # Упомянут именно НДС. Цена при слове «tax» или «налог» — «Unit price (tax
    # 13%)» — как и прежде, считается ценой без оговорки: налог при ней может
    # быть и не НДС, а переводить её в последние кандидаты — значит отнять цену у
    # файлов, которые её давали.
    return "упомянут" if any(w in low for w in НДС_СЛОВА) else None


def оговорка_ндс(c: str) -> str | None:
    """Оговорка строки о НДС колонки, из которой взята (или выведена) цена."""
    return {"с": ОГОВОРКА_С_НДС, "без": ОГОВОРКА_БЕЗ_НДС_ОДНА,
            "упомянут": ОГОВОРКА_НДС_НЕ_СКАЗАНО}.get(ндс_колонки(c))


def колонка_скидки_ли(c: str) -> bool:
    """Колонка самой скидки («Скидка, %», «Сумма скидки», «Discount amount»), а
    не цена или сумма, при которой скидка названа («Цена со скидкой»)."""
    low = (c or "").lower()
    if not СКИДКА_СЛОВА.search(low):
        return False
    if СКИДКА_ПРЕДМЕТ.search(low) or _слово_цены_или_суммы(low) is None:
        return True
    return bool(СКИДКА_ПЕРВОЙ.search(low)) and not any(
        w in low for w in (*ЦЕНА_V2_ЕД, *ЦЕНА_V2_СЛОВО))


def колонка_скидки(заголовки: list[str]) -> int | None:
    """Номер первой колонки скидки в шапке или None."""
    return next((j for j, c in enumerate(заголовки) if колонка_скидки_ли(c)), None)


def прайсовая(c: str) -> bool:
    """Цена по прайсу — цена до скидки («Цена по прайсу», «Price list price»)."""
    low = (c or "").lower()
    return any(w in low for w in ЦЕНА_V2_ПРАЙС)


def листовая(c: str) -> bool:
    """Листовая цена — английская и каталожная прайсовая («List price»,
    «Catalogue price», «Цена по каталогу»): чужая только при цене предложения."""
    low = (c or "").lower()
    return any(w in low for w in ЦЕНА_V2_ЛИСТ)


def цена_до_скидки(c: str) -> bool:
    """Прайсовая или листовая — цена, от которой скидка считается."""
    return прайсовая(c) or листовая(c)


def _есть_цена_предложения(low: list[str]) -> bool:
    """Есть ли в шапке цена предложения из закрытого списка («Net price», «Your
    price», «Цена со скидкой»; занятые колонки — тоже)."""
    return any(c and ЦЕНА_V2_НЕТТО.search(c) and ндс_колонки(c) != "налог" and _цена_v2(c)
               and not цена_до_скидки(c) for c in low)


def _сумма_v2(c: str) -> bool:
    return any(w in c for w in СУММА_V2)


def _цена_v2(c: str) -> bool:
    if _сумма_v2(c) or any(w in c for w in ЦЕНА_V2_ЧУЖАЯ) or ПРАЙС_ССЫЛКА.search(c):
        return False
    return any(w in c for w in ЦЕНА_V2_ЕД) or any(w in c for w in ЦЕНА_V2_СЛОВО)


def _кандидаты_v2(low: list[str], занято: set[int], *,
                 как_прежде: bool = False) -> tuple[list[int], list[int],
                                                    list[int], list[int], bool]:
    """Кандидаты цены и суммы: без оговорки об НДС (или с «с»/«без») и те, при
    которых НДС лишь упомянут. Колонки налога и колонки скидки не кандидаты ни
    того, ни другого.

    Прайсовая цена — кандидат, только если другой цены в шапке нет (занятые
    колонки считаются тоже: «другая цена в той же шапке»). Пятое значение — что
    кандидаты цены прайсовые.

    Листовая цена («List price») — кандидат, если в шапке нет цены предложения
    («Net price», «Цена со скидкой»): тогда она обычная цена, как до 27.09.2026.

    как_прежде — выбор, каким он был до 27.09.2026: колонка скидки со словом
    суммы («Сумма скидки») — кандидат суммы, листовая — обычная цена. Только
    чтобы узнать, что стояло ценой и суммой прежде (скидка_была_суммой,
    лист_был_ценой)."""
    цены, цены_упом, суммы, суммы_упом = [], [], [], []
    прайс, прайс_упом = [], []
    лист_чужая = not как_прежде and _есть_цена_предложения(low)
    for j, c in enumerate(low):
        if not c or j in занято:
            continue
        ндс = ндс_колонки(c)
        if ндс == "налог":
            continue
        if not как_прежде and колонка_скидки_ли(c):
            continue
        if _цена_v2(c):
            if лист_чужая and листовая(c) and not прайсовая(c):
                continue
            if прайсовая(c):
                (прайс_упом if ндс == "упомянут" else прайс).append(j)
            else:
                (цены_упом if ндс == "упомянут" else цены).append(j)
        elif _сумма_v2(c):
            (суммы_упом if ндс == "упомянут" else суммы).append(j)
    if _есть_другая_цена(low):
        return цены, цены_упом, суммы, суммы_упом, False
    return прайс, прайс_упом, суммы, суммы_упом, bool(прайс or прайс_упом)


def _есть_другая_цена(заголовки: list[str]) -> bool:
    """Есть ли в шапке цена, кроме прайсовой (занятые колонки — тоже)."""
    for c in заголовки:
        low = (c or "").lower().strip()
        if low and ндс_колонки(low) != "налог" and _цена_v2(low) and not прайсовая(low):
            return True
    return False


def _первая_цена(low: list[str], цены: list[int]) -> int:
    прямые = [j for j in цены if any(w in low[j] for w in ЦЕНА_V2_ЕД)]
    return (прямые or цены)[0]


def _ценовые_v2(заголовки: list[str], *,
                как_прежде: bool = False) -> tuple[dict[str, int], str | None]:
    """Колонки price и total по второй редакции и оговорка об НДС.

    Колонки, при которых НДС лишь упомянут («Unit price (13%VAT)», «Amount (13%
    VAT)»), берутся ТОЛЬКО там, где без них у файла не было бы ни цены, ни суммы:
    рядом с ценой без оговорки такая колонка скорее с НДС, а цену без НДС
    владелец велел предпочитать (CLAUDE.md, «Цена и предложение»). Цену такой
    колонки при сумме без оговорки проверяет арифметика по файлу
    (indexer.цена_сходится_с_суммой), здесь она не выбирается.

    как_прежде — выбор, каким он был до 27.09.2026 (_кандидаты_v2)."""
    low = [(c or "").lower().strip() for c in заголовки]
    найдено: dict[str, int] = {}
    оговорка = None
    цены, цены_упом, суммы, суммы_упом, прайс = _кандидаты_v2(low, set(),
                                                              как_прежде=как_прежде)
    if прайс and (суммы or суммы_упом):
        # Прайсовая цена — единственная, а сумма есть: сумма могла быть
        # посчитана со скидкой. Ценой прайсовая станет, только если сойдётся с
        # суммой по файлу (indexer.items_from_rows); иначе цена выводится из
        # суммы, как до 27.09.2026.
        цены, цены_упом = [], []
    две_цены = False
    if цены:
        j = _первая_цена(low, цены)
        без = [k for k in цены if ндс_колонки(low[k]) == "без"]
        с = [k for k in цены if ндс_колонки(low[k]) == "с"]
        две_цены = bool(без and с)
        if две_цены:
            # ДВЕ ЦЕНЫ — С НДС И БЕЗ. Берётся без: её можно сравнить с любым
            # другим предложением, а ставка налога у поставщиков разная (ноль у
            # упрощёнки и у иностранца). Какую взяли — в оговорку строки.
            j = без[0]
            оговорка = ОГОВОРКА_БЕЗ_НДС
        else:
            оговорка = оговорка_ндс(low[j])
        найдено["price"] = j
    elif цены_упом and not суммы:
        # Цены и суммы без оговорки нет — прежде файл оставался без цены вовсе,
        # хотя прежнее правило её читало. Включён ли НДС, не сказано: оговорка.
        найдено["price"] = _первая_цена(low, цены_упом)
        оговорка = ОГОВОРКА_НДС_НЕ_СКАЗАНО
    суммы = [j for j in суммы if j != найдено.get("price")]
    if суммы:
        # Сумма — той же природы, что цена: цена без НДС сверяется с суммой без
        # НДС. Иначе тройка «кол-во × цена = сумма» не сходится по построению.
        ндс_цены = ндс_колонки(low[найдено["price"]]) if "price" in найдено else None
        хочу = ндс_цены if ндс_цены in ("с", "без") else "без"
        свои = [j for j in суммы if ндс_колонки(low[j]) == хочу]
        if свои or not (две_цены and all(ндс_колонки(low[j]) == "с" for j in суммы)):
            найдено["total"] = (свои or суммы)[0]
        # Иначе цен две, взята без НДС, а все суммы — с НДС: они пара цене с НДС.
        # Суммой строки к цене без НДС такая не ставится — тройка не сошлась бы
        # по построению, и строка потеряла бы количество.
    elif суммы_упом and ("price" not in найдено
                         or ндс_колонки(low[найдено["price"]]) == "упомянут"):
        # Сумма, при которой НДС упомянут, — сумма строки только цене той же
        # природы или файлу без цены (цена выведется делением). Цене без
        # оговорки она не пара: тройка не сошлась бы, и строка потеряла бы
        # количество, которое прежде сохраняла.
        найдено["total"] = суммы_упом[0]
    if "price" not in найдено and "total" in найдено:
        # Цены нет — её выведут делением суммы: оговорка о НДС суммы.
        оговорка = оговорка_ндс(low[найдено["total"]])
    return найдено, оговорка


def скидка_была_суммой(заголовки: list[str]) -> int | None:
    """Колонка скидки, которую v2 до 27.09.2026 брал суммой строки («Сумма
    скидки», «Discount amount»), или None.

    Сумма строки у такой шапки теперь — другая колонка (или никакой), и это
    новый выбор: при колонке цены он доказывается арифметикой по файлу
    (indexer.items_from_rows). Иначе нулевая «Сумма скидки», прежде молча
    дававшая пустую сумму, уступила бы место «Сумме с НДС» при цене без НДС —
    тройка не сошлась бы, и строка потеряла бы количество."""
    j = _ценовые_v2(заголовки, как_прежде=True)[0].get("total")
    return j if j is not None and колонка_скидки_ли(заголовки[j]) else None


def суммы_шапки(заголовки: list[str], цк: dict[str, int]) -> list[int]:
    """Кандидаты суммы строки, кроме занятых колонок: сначала без оговорки об
    НДС, потом те, при которых он упомянут. Для замены суммы, не сошедшейся с
    ценой (indexer.items_from_rows)."""
    low = [(c or "").lower().strip() for c in заголовки]
    _, _, суммы, суммы_упом, _ = _кандидаты_v2(low, set(цк.values()))
    return суммы + суммы_упом


def лист_был_ценой(заголовки: list[str]) -> int | None:
    """Листовая колонка, которую v2 до 27.09.2026 брал ценой, а теперь не берёт
    (в шапке цена предложения), или None. Её шапка — последний довод о валюте,
    и она — прежняя цена для проверки «новая цена не сумма строки»
    (indexer.цена_это_сумма)."""
    j = _ценовые_v2(заголовки, как_прежде=True)[0].get("price")
    if j is None or not листовая(заголовки[j]) or прайсовая(заголовки[j]):
        return None
    return j if _ценовые_v2(заголовки)[0].get("price") != j else None


def цена_при_ндс(заголовки: list[str], цк: dict[str, int]) -> int | None:
    """Колонка цены, при которой НДС упомянут, если ценой её не взяли, — для
    проверки арифметикой по файлу (indexer.цена_сходится_с_суммой)."""
    low = [(c or "").lower().strip() for c in заголовки]
    цены_упом = _кандидаты_v2(low, set(цк.values()))[1]
    return _первая_цена(low, цены_упом) if цены_упом else None


def цена_по_прайсу(заголовки: list[str], цк: dict[str, int]) -> int | None:
    """Прайсовая цена — единственная цена шапки, — которую ценой не взяли из-за
    колонки суммы: для проверки арифметикой по файлу. Из двух — без НДС.
    Прайсовую, при которой НДС лишь упомянут, проверяет цена_при_ндс."""
    low = [(c or "").lower().strip() for c in заголовки]
    цены, _, _, _, прайс = _кандидаты_v2(low, set(цк.values()))
    if not (прайс and цены):
        return None
    без = [k for k in цены if ндс_колонки(low[k]) == "без"]
    return без[0] if без else _первая_цена(low, цены)


def опорная_сумма(заголовки: list[str], цк: dict[str, int]) -> int | None:
    """Сумма строки, которую суммой не взяли (при ней НДС упомянут или она с НДС
    при цене без НДС), — опора проверки «цена v2 не сумма строки»
    (indexer.цена_это_сумма): «Rate | Amount (13%VAT) | Line price» — без неё
    сумму под словом «price» сверить не с чем. Проверка терпит расхождение на
    ставку НДС, поэтому природа суммы ей не важна."""
    low = [(c or "").lower().strip() for c in заголовки]
    _, _, суммы, суммы_упом, _ = _кандидаты_v2(low, set(цк.values()))
    return (суммы + суммы_упом)[0] if суммы or суммы_упом else None


def оговорка_колонок(заголовки: list[str], *, v2: bool | None = None) -> str | None:
    """Что сказать в note о выбранной колонке цены (НДС) — или о сумме, если цена
    будет выведена её делением. Только при второй редакции."""
    if not (СЛОВАРЬ_V2 if v2 is None else v2):
        return None
    return _ценовые_v2(заголовки)[1]


def колонка_стоимости(заголовки: list[str], цк: dict[str, int]) -> int | None:
    """Колонка с голым «Стоимость», если она не сумма, не налог, не скидка
    («Стоимость скидки») и не занята. «Стоимость», при которой НДС лишь
    упомянут, — только если другой нет."""
    занято = set(цк.values())
    годные = []
    for j, c in enumerate(заголовки):
        low = (c or "").lower()
        if (j not in занято and СТОИМОСТЬ_ГОЛАЯ in low and not _сумма_v2(low)
                and ндс_колонки(low) != "налог" and not колонка_скидки_ли(low)
                and not any(w in low for w in ЦЕНА_V2_ЧУЖАЯ)
                and not ПРАЙС_ССЫЛКА.search(low)):
            годные.append((прайсовая(low), ндс_колонки(low) == "упомянут", j))
    # «Стоимость по прайсу» — как прайсовая цена: только если другой цены и
    # другой «Стоимости» в шапке нет.
    if any(not п for п, _, _ in годные) or _есть_другая_цена(заголовки):
        годные = [г for г in годные if not г[0]]
    return min(годные)[2] if годные else None


def тройка_сходится(кол: float | None, цена: float | None,
                    сумма: float | None) -> bool | None:
    """Сходится ли «кол-во × цена = сумма» с допуском на округление цены.

    None — если проверять нечем (нет одного из трёх чисел)."""
    if not кол or not цена or not сумма or кол <= 0 or цена <= 0 or сумма <= 0:
        return None
    return abs(кол * цена - сумма) <= max(ДОПУСК_МИН, кол * ДОПУСК_НА_ЕДИНИЦУ)


def валюта_заголовка(заголовки: list[str], цк: dict[str, int]) -> str | None:
    """Валюта, названная в шапке таблицы: «Цена за ед., EUR».

    Это самое частое место, где валюта вообще написана: в ячейках стоят голые
    числа. Спрашиваются только ценовые колонки — «Кол-во, руб-метров» валютой
    колонку не делает."""
    for ключ in ("price", "currency", "total"):
        j = цк.get(ключ, -1)
        if 0 <= j < len(заголовки):
            в = валюта_из(заголовки[j])
            if в:
                return в
    return None


def цена_строки(row: list[str], цк: dict[str, int], qty: float | None,
                валюта_колонки: str | None = None,
                валюта_файла: str | None = None, *,
                оговорка_файла: str | None = None,
                низкая: bool = False) -> dict | None:
    """Ценовая часть строки КП или None, если цены в строке нет.

    qty — количество из той же строки: без него сумма в цену не превращается.
    валюта_файла — валюта, найденная в тексте файла целиком; берётся, только
    если ни заголовок колонки, ни ячейка своей валюты не назвали.
    оговорка_файла — что сказано о колонках файла целиком («взята цена без НДС»,
    «шапка не найдена, колонки по тройке»); идёт первой в note.
    низкая — уверенность не выше «low»: колонки узнаны не по шапке.
    """
    def ячейка(ключ: str) -> str:
        j = цк.get(ключ, -1)
        return row[j].strip() if 0 <= j < len(row) else ""

    сырая_цена = ячейка("price")
    сырая_сумма = ячейка("total")
    # Ячейка, в которой стоит марка или размер («SS316», «19mm»), числа не
    # несёт: число_из вынуло бы из «SS316» цену 316 (карточка номенклатуры,
    # 24.09.2026). Судит то же правило, что отказывает таким токенам в коде, —
    # по одному ключу: стандарт с размером («DIN 471 25») для кода годен, но
    # цены в ячейке тоже не несёт.
    цена = число_из(сырая_цена) if docfilter.класс_ключа(сырая_цена) is None else None
    сумма = число_из(сырая_сумма) if docfilter.класс_ключа(сырая_сумма) is None else None

    уверенность, оговорка = "med", None
    if цена is not None and цена > 0:
        pass
    elif сумма is not None and сумма > 0:
        if not qty or qty <= 0:
            return None                      # сумма без количества цены не даёт
        цена = сумма / qty
        уверенность = "low"
        оговорка = "цена выведена делением суммы строки на количество"
    else:
        return None

    # От частного к общему: своя ячейка → шапка ценовой колонки → ячейка колонки
    # валюты → ячейка суммы → валюта файла целиком.
    валюта = (валюта_из(сырая_цена) or валюта_колонки or валюта_из(ячейка("currency"))
              or валюта_из(сырая_сумма) or валюта_файла)
    if валюта is None:
        уверенность = "low"
        оговорка = "; ".join(x for x in (оговорка, НЕТ_ВАЛЮТЫ) if x)

    if низкая:
        уверенность = "low"
    if оговорка_файла:
        оговорка = "; ".join(x for x in (оговорка_файла, оговорка) if x)

    срок = срок_из(ячейка("lead"))
    базис = базис_из(ячейка("basis")) or базис_из(ячейка("price"))
    # СУММА ВОЗВРАЩАЕТСЯ, А НЕ ТОЛЬКО УЧАСТВУЕТ В РАСЧЁТЕ. Прежде она читалась,
    # из неё выводилась цена делением на количество, и след терялся. Проверить
    # «цена × количество = сумма» задним числом было нечем, а это единственная
    # самопроверка ценовой строки, какая у нас есть.
    сумма_к_записи = сумма if сумма is not None and сумма > 0 else None
    if not правдоподобна(цена, сумма_к_записи):
        return None            # промах разбора: см. ПРЕДЕЛ_ЦЕНЫ
    return {"price": round(цена, 4), "currency": валюта, "basis": базис,
            "lead_days": срок, "confidence": уверенность, "note": оговорка,
            "total": round(сумма_к_записи, 4) if сумма_к_записи else None}


def валюта_файла(текст: str) -> str | None:
    """Валюта всего КП: берётся, если в тексте встречается ровно одна.

    Две валюты в одном файле — обычное дело (цена в евро, НДС в рублях), и
    тогда угадывать нельзя: колонка решит сама."""
    low = (текст or "").lower()
    нашлись = {код for код, метки in ВАЛЮТЫ if any(m in low for m in метки)}
    return нашлись.pop() if len(нашлись) == 1 else None


# ─────────────────────────────────────────────────────────────────────────────
# Цена из ТЕКСТОВОЙ строки (PDF без таблицы)
#
# ЗАЧЕМ ОТДЕЛЬНОЕ ПРАВИЛО. Замер 21.09.2026: пробный разбор четырёх файлов КП дал
# 139 позиций и НОЛЬ цен. Причина не в колонках — КП приходят PDF-ами, а PDF
# разбирается построчно, таблицы там нет вовсе, и весь разбор по заголовкам мимо.
#
# КАК ОТЛИЧИТЬ ЦЕНУ ОТ СУММЫ БЕЗ ЗАГОЛОВКОВ. Никак — если гадать. Но строка
# позиции обычно несёт все три числа сразу, и между ними есть проверяемое
# отношение: количество × цена = сумма. Оно самопроверяемо: тройка, которая
# сошлась, почти не может быть случайной, а не сошедшаяся не берётся вовсе.
# Поэтому здесь нет порогов «похожести» — есть арифметика.
#
# ЧЕГО ЭТО ПРАВИЛО НЕ ДЕЛАЕТ. Оно не берёт цену из строки, где сумма не указана:
# одинокое число в строке — это и цена, и вес, и год, и номер позиции. Пропустить
# такую строку дешевле, чем объявить ценой чужое число.
ШУМ_СТРОКИ = re.compile(
    r"(?i)(ндс|итого|всего|подытог|скидк|предоплат|отсрочк|курс|\bстр\.|страница)")
# Число с необязательной дробной частью. Пробел допускается ТОЛЬКО как разделитель
# тысяч, то есть перед ровно тремя цифрами. Свободный пробел внутри числа склеивал
# соседние: «50   4 » читалось как 504, и тройка не сходилась (поймано на разборе
# строки «…M74N-50   4 шт   850,00   3 400,00»).
_ТОКЕН = re.compile(
    r"(?<![\d.,])\d{1,3}(?:[ \u00a0\u202f'’]\d{3})+(?:[.,]\d{1,4})?(?![\d])"
    r"|(?<![\d.,])\d+(?:[.,]\d{1,4})?(?![\d])")
# Ниже этой суммы строка не считается позицией: «2 3 6» арифметике удовлетворяет,
# но ценой не является.
МИН_СУММА = 10.0
МАКС_КОЛИЧЕСТВО = 1_000_000.0
# ОГОВОРКИ О КОЛИЧЕСТВЕ (library/indexer.сверить_количество). Количество не
# угадывается: не читается или не сошлось с ценой и суммой — оно не пишется, а
# строка цены несёт одну из этих фраз. По второй её считает «строк_сумма_не_
# сошлась» страницы /brands (library/codes_sql.py): без неё строка со снятым
# количеством выпала бы из сверки молча.
КОЛ_НЕ_ЧИТАЕТСЯ = "количество не читается (больше предела) — не записано"
КОЛ_НЕ_СОШЛОСЬ = "количество не сошлось с ценой и суммой — не записано"
# Метка цены, выведенной из суммы делением: такая цена сходится с суммой по
# построению, и сверка тройки её не проверяет.
ОГОВОРКА_ИЗ_СУММЫ = "делением суммы"
# Метка цены из таблицы, у которой шапка не найдена, а колонки опознаны тройкой
# «кол-во × цена = сумма» (indexer.ЦЕНА_БЕЗ_ШАПКИ). Уверенность у такой строки
# всегда низкая, и валюта файла её не поднимает (подставить_валюту).
ОГОВОРКА_БЕЗ_ШАПКИ = "шапка не найдена, колонки по тройке"
# ДОПУСК ПРИВЯЗАН К КОЛИЧЕСТВУ, А НЕ К СУММЕ. Расхождение берётся из того, что
# в КП напечатана округлённая цена за единицу: 1000 × 12,345 показано как 12,35,
# и сумма расходится на qty × полкопейки. От суммы допуск не зависит вовсе —
# доля от суммы дала бы на девятистах тысячах четыре с половиной тысячи слака,
# и «10 × 100 = 999» прошло бы как сошедшееся.
ДОПУСК_НА_ЕДИНИЦУ = 0.005
ДОПУСК_МИН = 0.5


def _числа_строки(строка: str) -> list[float]:
    значения = []
    for m in _ТОКЕН.finditer(строка):
        v = число_из(m.group(0))
        if v is not None:
            значения.append(v)
    return значения


def _токены_строки(строка: str) -> list[tuple[float, re.Match]]:
    """Числа строки вместе с местом, где они стоят: прочтению тройки нужно знать,
    что идёт за числом (единица) и как оно записано (целым или с дробной частью)."""
    out = []
    for m in _ТОКЕН.finditer(строка):
        v = число_из(m.group(0))
        if v is not None:
            out.append((v, m))
    return out


def _прочтение_годно(кол: float, цена: float, сумма: float) -> bool:
    """«кол-во × цена = сумма» в этом прочтении: те же ворота, что были у тройки."""
    if not (0 < кол <= МАКС_КОЛИЧЕСТВО) or цена <= 0 or сумма < МИН_СУММА:
        return False
    if abs(кол * цена - сумма) > max(ДОПУСК_МИН, кол * ДОПУСК_НА_ЕДИНИЦУ):
        return False
    return правдоподобна(цена, сумма)      # промах разбора: см. ПРЕДЕЛ_ЦЕНЫ


def _единица_после(строка: str, m: re.Match) -> bool:
    return _ЕД_ПОСЛЕ.match(строка, m.end()) is not None


def _целое_написано(m: re.Match) -> bool:
    """Число записано без дробной части: «1», «12», «1 200». «1,00» — нет."""
    return re.fullmatch(r"[\d   '’]+", m.group(0)) is not None


def количество_правдоподобно(v: float) -> bool:
    """Целое и не больше МАКС_ПРАВДОПОДОБНОЕ_КОЛИЧЕСТВО: так пишут штуки."""
    return 0 < v <= МАКС_ПРАВДОПОДОБНОЕ_КОЛИЧЕСТВО and v == int(v)


def прочтение_тройки(строка: str, а: tuple[float, re.Match], б: tuple[float, re.Match],
                     сумма: float, отбор: bool | None = None) -> tuple[float, float] | None:
    """(кол-во, цена) из двух соседних чисел перед суммой — или None.

    ПРОЧТЕНИЙ ДВА, И АРИФМЕТИКА ИХ НЕ РАЗЛИЧАЕТ: а × б = б × а. Прежнее правило
    всегда брало первое число количеством, и строка «1 compressor crosshead
    ¥32890.00 1 ¥32890.00» (цена стоит перед количеством) легла ценой 1,0 за
    32 890 штук. Выбор — по правдоподобию количества (целое, не больше
    МАКС_ПРАВДОПОДОБНОЕ_КОЛИЧЕСТВО), и порядок решений такой:
      • единица сразу за числом («150,5 м», «2 шт») — это и есть количество;
      • первое число — правдоподобное количество: прежнее прочтение, как было;
      • первое неправдоподобно, а второе правдоподобно и записано целым
        («32890.00 1») — второе количество, первое цена;
      • иначе прежнее прочтение.
    Каждый шаг только сужает перестановку: при сомнении остаётся прежний ответ.

    ТОЛЬКО ПЕРЕСТАНОВКА, НИКОГДА НОВОЕ ПРОЧТЕНИЕ. Второе прочтение берётся лишь
    там, где первое тоже сошлось: строка, которую прежнее правило ценой не
    считало («Contract 2500000 1 2500000» — количество больше предела), ценой
    не становится и теперь.

    отбор=None — по переключателю ОТБОР_ЛОЖНЫХ; False — прежнее прочтение.
    """
    (ва, ма), (вб, мб) = а, б
    первое = (ва, вб) if _прочтение_годно(ва, вб, сумма) else None
    if not (ОТБОР_ЛОЖНЫХ if отбор is None else отбор) or первое is None:
        return первое
    второе = (вб, ва) if _прочтение_годно(вб, ва, сумма) else None
    if второе is None or _единица_после(строка, ма):
        return первое
    if _единица_после(строка, мб):
        return второе
    if количество_правдоподобно(ва):
        return первое
    if количество_правдоподобно(вб) and _целое_написано(мб):
        return второе
    return первое


def цена_из_текста(строка: str, валюта_файла: str | None = None,
                   отбор: bool | None = None, пара: bool | None = None) -> dict | None:
    """Цена из строки PDF без таблицы — только если арифметика сошлась.

    Ищется тройка подряд идущих чисел (кол-во, цена, сумма), для которой
    кол-во × цена = сумма с допуском на округление. Берётся самая правая такая
    тройка: слева в строке стоят номер позиции и характеристики, справа — деньги.

    С отбором ложных порядок количества и цены в тройке решает прочтение_тройки,
    а строку, которую правило ложной цены обвиняет, правило не берёт:
    вырожденная тройка «x × 1 = x» пропускается (левее может стоять настоящая),
    строка-реквизит отвергается целиком. Судит ложная_цена — по тем же полям,
    что лягут в lib_prices, и так же, как пометка уже записанного.

    отбор=None — по переключателю ОТБОР_ЛОЖНЫХ (так зовут писатели цены);
    True или False — явно, мимо переключателя: замер пометки меряет само
    правило, а соседний классификатор (doc_kind) держит прежнее чтение, пока его
    сдвиг не измерен.

    пара=None — по флагу ПАРА_НДС (PRICE_VAT_PAIR); False — прежнее чтение:
    тройка не нашлась — строка цены не даёт (см. цена_пары_ндс).
    """
    отбор = ОТБОР_ЛОЖНЫХ if отбор is None else отбор
    if not строка or ШУМ_СТРОКИ.search(строка):
        return None
    # В строке позиции обязан быть текст: «1 2 2» — не позиция.
    if len(re.sub(r"[^A-Za-zА-Яа-яЁё]", "", строка)) < 4:
        return None
    токены = _токены_строки(строка)
    if len(токены) < 3:
        return None
    for i in range(len(токены) - 3, -1, -1):
        сумма = токены[i + 2][0]
        прочтение = прочтение_тройки(строка, токены[i], токены[i + 1], сумма, отбор)
        if прочтение is None:
            continue
        кол, цена = прочтение
        валюта = валюта_из(строка) or валюта_файла
        уверенность = "med" if валюта else "low"
        оговорка = ОГОВОРКА_ТЕКСТА
        if прочтение != (токены[i][0], токены[i + 1][0]):
            оговорка += "; " + ОГОВОРКА_ПЕРЕСТАВЛЕНО
        if валюта is None:
            оговорка += "; " + НЕТ_ВАЛЮТЫ
        if отбор:
            # Поля — ровно те, что лягут в lib_prices: наименование и код у
            # текстовой позиции берутся из этой же строки (indexer, ocr), суммы
            # текстовый путь не пишет — её выводит из оговорки само правило.
            причина = ложная_цена(строка[:300], docfilter.part_number_of(строка), "",
                                  кол, round(цена, 4), None, оговорка)
            if причина == ПРИЧИНА_ВЫРОЖДЕНА:
                continue
            if причина:
                return None
        return {"price": round(цена, 4), "currency": валюта, "basis": базис_из(строка),
                "lead_days": None, "confidence": уверенность, "note": оговорка,
                "qty": кол}
    if пара is None:
        пара = ПАРА_НДС and not правки_выключены()
    if not пара:
        return None
    return цена_пары_ндс(строка, токены, валюта_файла, отбор)


def ставка_пары(ц1: float, ц2: float, валюта: str | None = None) -> float | None:
    """Ставка НДС, на которую ц2 больше ц1, — ровно одна из закрытого списка.

    Список — СТАВКИ_НДС_ПАРЫ и ставка страны валюты (СТАВКИ_НДС_ПАРЫ_ПО_ВАЛЮТЕ).
    Две подходящие ставки (копеечная цена: 0,05 × 1,2 и × 1,22 равны с точностью
    до копейки) — не ответ: угадывать ставку нельзя, и строка пары не даёт."""
    if not (0 < ц1 < ц2):
        return None
    ставки = СТАВКИ_НДС_ПАРЫ + СТАВКИ_НДС_ПАРЫ_ПО_ВАЛЮТЕ.get(валюта or "", ())
    годные = [с for с in ставки if abs(ц1 * (1 + с) - ц2) <= ДОПУСК_ПАРЫ]
    return годные[0] if len(годные) == 1 else None


def _денежная(m: re.Match) -> bool:
    """Число записано деньгами: две цифры после запятой (ДЕНЕЖНАЯ_ЗАПИСЬ)."""
    return ДЕНЕЖНАЯ_ЗАПИСЬ.fullmatch(m.group(0)) is not None


def _пара_сходится(кол: float, цена: float, сумма: float) -> bool:
    """«кол-во × цена = сумма» с допуском округления цены до копейки — без
    полуединицы ДОПУСК_МИН тройки: у пары обе цены в копейках, и слабее допуск
    здесь не нужен, а полуединица на малых числах сходится случайно."""
    if сумма < МИН_СУММА or not правдоподобна(цена, сумма):
        return False
    return abs(кол * цена - сумма) <= кол * ДОПУСК_НА_ЕДИНИЦУ + 0.01


def количество_пары(строка: str, m: re.Match, кол: float) -> bool:
    """Количество пары правдоподобно: единица сразу за числом («1,2 м», «2 шт»)
    или целое, записанное целым, не больше МАКС_ПРАВДОПОДОБНОЕ_КОЛИЧЕСТВО.
    Ревизия 28.09.2026: без этого парой шли «4,13 т/ч» и год «2026»."""
    if not (0 < кол <= МАКС_КОЛИЧЕСТВО):
        return False
    return _единица_после(строка, m) or (количество_правдоподобно(кол)
                                          and _целое_написано(m))


def цена_текста_правдоподобна(строка: str, ц: dict) -> bool:
    """Цена, опознанная в строке текста (цена_из_текста), похожа на цену КП: сама
    записана деньгами (две цифры после запятой), а количество — целое, записанное
    целым, или с единицей сразу за числом (количество_пары).

    Нужна выбору текста PDF (indexer.троек_в_тексте, правка F2) и решению «таблица
    или текст» по файлу: там сравнивается число цен, и технические строки
    («ДН-15 Мощность: 400 кВт, 6000 В» — 15 × 400 = 6000) голосовать не должны.
    Разбор строки она не меняет — только счёт."""
    токены = _токены_строки(строка)
    цена, кол = round(ц.get("price") or 0, 2), ц.get("qty")
    if not кол or not any(_денежная(м) and round(v, 2) == цена for v, м in токены):
        return False
    return any(v == кол and количество_пары(строка, м, v) for v, м in токены)


def цена_пары_ндс(строка: str, токены: list[tuple[float, re.Match]],
                  валюта_файла: str | None, отбор: bool) -> dict | None:
    """Цена без НДС из четвёрки (кол-во, ц1, ц2, сумма), где ц2 = ц1 × (1 + ставка).

    Сумма строки — с НДС или без: сходиться с количеством обязана одна из цен
    (кол-во × ц2 = сумма или кол-во × ц1 = сумма). Берётся самая правая такая
    четвёрка, как и тройка. Порядок в четвёрке — прямой: количество первым;
    перестановки, как у тройки, здесь нет. Отбор ложных — тот же, что у тройки,
    по тем же полям, что лягут в lib_prices.

    ПРАВДОПОДОБИЕ — ДО АРИФМЕТИКИ (ревизия 28.09.2026). Два шанса сойтись (с ц1 и
    с ц2) и шесть ставок делали правило рыхлым: «Пар КУ, т/ч 4,13 4,55 5,00 19,2»
    шло парой. Теперь: количество правдоподобно (количество_пары), все три
    денежных числа — в денежной записи (ДЕНЕЖНАЯ_ЗАПИСЬ), цена не меньше
    МИН_ЦЕНА_ПАРЫ, ставка — из закрытого списка при своей валюте (ставка_пары),
    сумма сходится без полуединицы тройки (_пара_сходится)."""
    for i in range(len(токены) - 4, -1, -1):
        (кол, мк), (ц1, м1), (ц2, м2), (сумма, мс) = (токены[i + k] for k in range(4))
        if ц1 < МИН_ЦЕНА_ПАРЫ or not (_денежная(м1) and _денежная(м2) and _денежная(мс)):
            continue
        if not количество_пары(строка, мк, кол):
            continue
        валюта = валюта_из(строка) or валюта_файла
        ставка = ставка_пары(ц1, ц2, валюта)
        if ставка is None:
            continue
        if not (_пара_сходится(кол, ц2, сумма) or _пара_сходится(кол, ц1, сумма)):
            continue
        оговорка = (f"{ОГОВОРКА_ТЕКСТА}; {ОГОВОРКА_ПАРА_НДС}"
                    f" (ставка {round(ставка * 100):d} %)")
        if валюта is None:
            оговорка += "; " + НЕТ_ВАЛЮТЫ
        if отбор:
            причина = ложная_цена(строка[:300], docfilter.part_number_of(строка), "",
                                  кол, round(ц1, 4), None, оговорка)
            if причина == ПРИЧИНА_ВЫРОЖДЕНА:
                continue
            if причина:
                return None
        return {"price": round(ц1, 4), "currency": валюта, "basis": базис_из(строка),
                "lead_days": None, "confidence": "med" if валюта else "low",
                "note": оговорка, "qty": кол}
    return None


def подставить_валюту(ц: dict, валюта: str | None) -> dict:
    """Валюта файла вместо ненайденной — с исправлением оговорки и уверенности.

    Без этого в строке оставались бы две несовместимые фразы разом: «валюта не
    названа» и «валюта взята по файлу». Оговорка должна описывать итог, а не
    историю его получения.
    """
    if not ц or валюта is None or ц.get("currency") is not None:
        return ц
    ц["currency"] = валюта
    части = [ч for ч in (ц.get("note") or "").split("; ") if ч and ч != НЕТ_ВАЛЮТЫ]
    части.append("валюта взята по файлу целиком")
    ц["note"] = "; ".join(части)
    # Отсутствие валюты было единственной причиной низкой уверенности — снимаем.
    # Кроме цены, чьи колонки узнаны не по шапке: там низкая уверенность — про
    # колонки, а не про валюту, и валюта файла её не поднимает.
    if ц.get("confidence") == "low" and not any(
            "делением" in ч or ОГОВОРКА_БЕЗ_ШАПКИ in ч for ч in части):
        ц["confidence"] = "med"
    return ц


