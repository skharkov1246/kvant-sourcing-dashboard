def ндс_колонки(c: str) -> str | None:
    """«без», «с», «налог» — что шапка говорит об НДС, или None, если молчит."""
    low = (c or "").lower()
    if any(w in low for w in БЕЗ_НДС):
        return "без"
    if any(w in low for w in С_НДС):
        return "с"
    if any(w in low for w in НДС_СЛОВА):
        return "налог"
    return None


def _сумма_v2(c: str) -> bool:
    return any(w in c for w in СУММА_V2)


def _цена_v2(c: str) -> bool:
    if _сумма_v2(c) or any(w in c for w in ЦЕНА_V2_ЧУЖАЯ):
        return False
    return any(w in c for w in ЦЕНА_V2_ЕД) or any(w in c for w in ЦЕНА_V2_СЛОВО)


def _ценовые_v2(заголовки: list[str]) -> tuple[dict[str, int], str | None]:
    """Колонки price и total по второй редакции и оговорка об НДС."""
    low = [(c or "").lower().strip() for c in заголовки]
    найдено: dict[str, int] = {}
    оговорка = None
    цены = [j for j, c in enumerate(low)
            if c and ндс_колонки(c) != "налог" and _цена_v2(c)]
    if цены:
        прямые = [j for j in цены if any(w in low[j] for w in ЦЕНА_V2_ЕД)]
        j = (прямые or цены)[0]
        без = [k for k in цены if ндс_колонки(low[k]) == "без"]
        с = [k for k in цены if ндс_колонки(low[k]) == "с"]
        if без and с:
            # ДВЕ ЦЕНЫ — С НДС И БЕЗ. Берётся без: её можно сравнить с любым
            # другим предложением, а ставка налога у поставщиков разная (ноль у
            # упрощёнки и у иностранца). Какую взяли — в оговорку строки.
            j = без[0]
            оговорка = ОГОВОРКА_БЕЗ_НДС
        elif ндс_колонки(low[j]) == "с":
            оговорка = ОГОВОРКА_С_НДС
        elif ндс_колонки(low[j]) == "без":
            оговорка = ОГОВОРКА_БЕЗ_НДС_ОДНА
        найдено["price"] = j
    суммы = [j for j, c in enumerate(low)
             if c and j != найдено.get("price") and ндс_колонки(c) != "налог"
             and _сумма_v2(c)]
    if суммы:
        # Сумма — той же природы, что цена: цена без НДС сверяется с суммой без
        # НДС. Иначе тройка «кол-во × цена = сумма» не сходится по построению.
        ндс_цены = ндс_колонки(low[найдено["price"]]) if "price" in найдено else None
        хочу = ндс_цены if ндс_цены in ("с", "без") else "без"
        свои = [j for j in суммы if ндс_колонки(low[j]) == хочу]
        найдено["total"] = (свои or суммы)[0]
    return найдено, оговорка


def оговорка_колонок(заголовки: list[str], *, v2: bool | None = None) -> str | None:
    """Что сказать в note о выбранной колонке цены (НДС). Только при второй редакции."""
    if not (СЛОВАРЬ_V2 if v2 is None else v2):
        return None
    return _ценовые_v2(заголовки)[1]


def колонка_стоимости(заголовки: list[str], цк: dict[str, int]) -> int | None:
    """Колонка с голым «Стоимость», если она не сумма, не налог и не занята."""
    занято = set(цк.values())
    for j, c in enumerate(заголовки):
        low = (c or "").lower()
        if (j not in занято and СТОИМОСТЬ_ГОЛАЯ in low and not _сумма_v2(low)
                and ндс_колонки(low) != "налог"
                and not any(w in low for w in ЦЕНА_V2_ЧУЖАЯ)):
            return j
    return None


def тройка_сходится(кол: float | None, цена: float | None,
                    сумма: float | None) -> bool | None:
    """Сходится ли «кол-во × цена = сумма» с допуском на округление цены.

    None — если проверять нечем (нет одного из трёх чисел)."""
    if not кол or not цена or not сумма or кол <= 0 or цена <= 0 or сумма <= 0:
        return None
    return abs(кол * цена - сумма) <= max(ДОПУСК_МИН, кол * ДОПУСК_НА_ЕДИНИЦУ)


def валюта_заголовка(заголовки: list[str], цк: dict[str, int]) -> str | None:
    """Валюта, названная в шапке таблицы: «Цена за ед., EUR».

    Это самое частое место, где валюта вообще написана: в ячейках стоят голые
    числа. Спрашиваются только ценовые колонки — «Кол-во, руб-метров» валютой
    колонку не делает."""
    for ключ in ("price", "currency", "total"):
        j = цк.get(ключ, -1)
        if 0 <= j < len(заголовки):
            в = валюта_из(заголовки[j])
            if в:
                return в
    return None


def цена_строки(row: list[str], цк: dict[str, int], qty: float | None,
                валюта_колонки: str | None = None,
                валюта_файла: str | None = None, *,
                оговорка_файла: str | None = None,
                низкая: bool = False) -> dict | None:
    """Ценовая часть строки КП или None, если цены в строке нет.

    qty — количество из той же строки: без него сумма в цену не превращается.
    валюта_файла — валюта, найденная в тексте файла целиком; берётся, только
    если ни заголовок колонки, ни ячейка своей валюты не назвали.
    оговорка_файла — что сказано о колонках файла целиком («взята цена без НДС»,
    «шапка не найдена, колонки по тройке»); идёт первой в note.
    низкая — уверенность не выше «low»: колонки узнаны не по шапке.
    """
    def ячейка(ключ: str) -> str:
        j = цк.get(ключ, -1)
        return row[j].strip() if 0 <= j < len(row) else ""

    сырая_цена = ячейка("price")
    сырая_сумма = ячейка("total")
    # Ячейка, в которой стоит марка или размер («SS316», «19mm»), числа не
    # несёт: число_из вынуло бы из «SS316» цену 316 (карточка номенклатуры,
    # 24.09.2026). Судит то же правило, что отказывает таким токенам в коде, —
    # по одному ключу: стандарт с размером («DIN 471 25») для кода годен, но
    # цены в ячейке тоже не несёт.
    цена = число_из(сырая_цена) if docfilter.класс_ключа(сырая_цена) is None else None
    сумма = число_из(сырая_сумма) if docfilter.класс_ключа(сырая_сумма) is None else None

    уверенность, оговорка = "med", None
    if цена is not None and цена > 0:
        pass
    elif сумма is not None and сумма > 0:
        if not qty or qty <= 0:
            return None                      # сумма без количества цены не даёт
        цена = сумма / qty
        уверенность = "low"
        оговорка = "цена выведена делением суммы строки на количество"
    else:
        return None

    # От частного к общему: своя ячейка → шапка ценовой колонки → ячейка колонки
    # валюты → ячейка суммы → валюта файла целиком.
    валюта = (валюта_из(сырая_цена) or валюта_колонки or валюта_из(ячейка("currency"))
              or валюта_из(сырая_сумма) or валюта_файла)
    if валюта is None:
        уверенность = "low"
        оговорка = "; ".join(x for x in (оговорка, НЕТ_ВАЛЮТЫ) if x)

    if низкая:
        уверенность = "low"
    if оговорка_файла:
        оговорка = "; ".join(x for x in (оговорка_файла, оговорка) if x)

    срок = срок_из(ячейка("lead"))
    базис = базис_из(ячейка("basis")) or базис_из(ячейка("price"))
    # СУММА ВОЗВРАЩАЕТСЯ, А НЕ ТОЛЬКО УЧАСТВУЕТ В РАСЧЁТЕ. Прежде она читалась,
    # из неё выводилась цена делением на количество, и след терялся. Проверить
    # «цена × количество = сумма» задним числом было нечем, а это единственная
    # самопроверка ценовой строки, какая у нас есть.
    сумма_к_записи = сумма if сумма is not None and сумма > 0 else None
    if not правдоподобна(цена, сумма_к_записи):
        return None            # промах разбора: см. ПРЕДЕЛ_ЦЕНЫ
    return {"price": round(цена, 4), "currency": валюта, "basis": базис,
            "lead_days": срок, "confidence": уверенность, "note": оговорка,
            "total": round(сумма_к_записи, 4) if сумма_к_записи else None}


def валюта_файла(текст: str) -> str | None:
    """Валюта всего КП: берётся, если в тексте встречается ровно одна.

    Две валюты в одном файле — обычное дело (цена в евро, НДС в рублях), и
    тогда угадывать нельзя: колонка решит сама."""
    low = (текст or "").lower()
    нашлись = {код for код, метки in ВАЛЮТЫ if any(m in low for m in метки)}
    return нашлись.pop() if len(нашлись) == 1 else None


# ─────────────────────────────────────────────────────────────────────────────
# Цена из ТЕКСТОВОЙ строки (PDF без таблицы)
#
# ЗАЧЕМ ОТДЕЛЬНОЕ ПРАВИЛО. Замер 21.09.2026: пробный разбор четырёх файлов КП дал
# 139 позиций и НОЛЬ цен. Причина не в колонках — КП приходят PDF-ами, а PDF
# разбирается построчно, таблицы там нет вовсе, и весь разбор по заголовкам мимо.
#
# КАК ОТЛИЧИТЬ ЦЕНУ ОТ СУММЫ БЕЗ ЗАГОЛОВКОВ. Никак — если гадать. Но строка
# позиции обычно несёт все три числа сразу, и между ними есть проверяемое
# отношение: количество × цена = сумма. Оно самопроверяемо: тройка, которая
# сошлась, почти не может быть случайной, а не сошедшаяся не берётся вовсе.
# Поэтому здесь нет порогов «похожести» — есть арифметика.
#
# ЧЕГО ЭТО ПРАВИЛО НЕ ДЕЛАЕТ. Оно не берёт цену из строки, где сумма не указана:
# одинокое число в строке — это и цена, и вес, и год, и номер позиции. Пропустить
# такую строку дешевле, чем объявить ценой чужое число.
ШУМ_СТРОКИ = re.compile(
    r"(?i)(ндс|итого|всего|подытог|скидк|предоплат|отсрочк|курс|\bстр\.|страница)")
# Число с необязательной дробной частью. Пробел допускается ТОЛЬКО как разделитель
# тысяч, то есть перед ровно тремя цифрами. Свободный пробел внутри числа склеивал
# соседние: «50   4 » читалось как 504, и тройка не сходилась (поймано на разборе
# строки «…M74N-50   4 шт   850,00   3 400,00»).
_ТОКЕН = re.compile(
    r"(?<![\d.,])\d{1,3}(?:[ \u00a0\u202f'’]\d{3})+(?:[.,]\d{1,4})?(?![\d])"
    r"|(?<![\d.,])\d+(?:[.,]\d{1,4})?(?![\d])")
# Ниже этой суммы строка не считается позицией: «2 3 6» арифметике удовлетворяет,
# но ценой не является.
МИН_СУММА = 10.0
МАКС_КОЛИЧЕСТВО = 1_000_000.0
# ОГОВОРКИ О КОЛИЧЕСТВЕ (library/indexer.сверить_количество). Количество не
# угадывается: не читается или не сошлось с ценой и суммой — оно не пишется, а
# строка цены несёт одну из этих фраз. По второй её считает «строк_сумма_не_
# сошлась» страницы /brands (library/codes_sql.py): без неё строка со снятым
# количеством выпала бы из сверки молча.
КОЛ_НЕ_ЧИТАЕТСЯ = "количество не читается (больше предела) — не записано"
КОЛ_НЕ_СОШЛОСЬ = "количество не сошлось с ценой и суммой — не записано"
# Метка цены, выведенной из суммы делением: такая цена сходится с суммой по
# построению, и сверка тройки её не проверяет.
ОГОВОРКА_ИЗ_СУММЫ = "делением суммы"
# Метка цены из таблицы, у которой шапка не найдена, а колонки опознаны тройкой
# «кол-во × цена = сумма» (indexer.ЦЕНА_БЕЗ_ШАПКИ). Уверенность у такой строки
# всегда низкая, и валюта файла её не поднимает (подставить_валюту).
ОГОВОРКА_БЕЗ_ШАПКИ = "шапка не найдена, колонки по тройке"
# ДОПУСК ПРИВЯЗАН К КОЛИЧЕСТВУ, А НЕ К СУММЕ. Расхождение берётся из того, что
# в КП напечатана округлённая цена за единицу: 1000 × 12,345 показано как 12,35,
# и сумма расходится на qty × полкопейки. От суммы допуск не зависит вовсе —
# доля от суммы дала бы на девятистах тысячах четыре с половиной тысячи слака,
# и «10 × 100 = 999» прошло бы как сошедшееся.
ДОПУСК_НА_ЕДИНИЦУ = 0.005
ДОПУСК_МИН = 0.5


def _числа_строки(строка: str) -> list[float]:
    значения = []
    for m in _ТОКЕН.finditer(строка):
        v = число_из(m.group(0))
        if v is not None:
            значения.append(v)
    return значения


def _токены_строки(строка: str) -> list[tuple[float, re.Match]]:
    """Числа строки вместе с местом, где они стоят: прочтению тройки нужно знать,
    что идёт за числом (единица) и как оно записано (целым или с дробной частью)."""
    out = []
    for m in _ТОКЕН.finditer(строка):
        v = число_из(m.group(0))
        if v is not None:
            out.append((v, m))
    return out


def _прочтение_годно(кол: float, цена: float, сумма: float) -> bool:
    """«кол-во × цена = сумма» в этом прочтении: те же ворота, что были у тройки."""
    if not (0 < кол <= МАКС_КОЛИЧЕСТВО) or цена <= 0 or сумма < МИН_СУММА:
        return False
    if abs(кол * цена - сумма) > max(ДОПУСК_МИН, кол * ДОПУСК_НА_ЕДИНИЦУ):
        return False
    return правдоподобна(цена, сумма)      # промах разбора: см. ПРЕДЕЛ_ЦЕНЫ


def _единица_после(строка: str, m: re.Match) -> bool:
    return _ЕД_ПОСЛЕ.match(строка, m.end()) is not None


def _целое_написано(m: re.Match) -> bool:
    """Число записано без дробной части: «1», «12», «1 200». «1,00» — нет."""
    return re.fullmatch(r"[\d   '’]+", m.group(0)) is not None


def количество_правдоподобно(v: float) -> bool:
    """Целое и не больше МАКС_ПРАВДОПОДОБНОЕ_КОЛИЧЕСТВО: так пишут штуки."""
    return 0 < v <= МАКС_ПРАВДОПОДОБНОЕ_КОЛИЧЕСТВО and v == int(v)


def прочтение_тройки(строка: str, а: tuple[float, re.Match], б: tuple[float, re.Match],
                     сумма: float) -> tuple[float, float] | None:
    """(кол-во, цена) из двух соседних чисел перед суммой — или None.

    ПРОЧТЕНИЙ ДВА, И АРИФМЕТИКА ИХ НЕ РАЗЛИЧАЕТ: а × б = б × а. Прежнее правило
    всегда брало первое число количеством, и строка «1 compressor crosshead
    ¥32890.00 1 ¥32890.00» (цена стоит перед количеством) легла ценой 1,0 за
    32 890 штук. Выбор — по правдоподобию количества (целое, не больше
    МАКС_ПРАВДОПОДОБНОЕ_КОЛИЧЕСТВО), и порядок решений такой:
      • единица сразу за числом («150,5 м», «2 шт») — это и есть количество;
      • первое число — правдоподобное количество: прежнее прочтение, как было;
      • первое неправдоподобно, а второе правдоподобно и записано целым
        («32890.00 1») — второе количество, первое цена;
      • иначе прежнее прочтение.
    Каждый шаг только сужает перестановку: при сомнении остаётся прежний ответ.

    ТОЛЬКО ПЕРЕСТАНОВКА, НИКОГДА НОВОЕ ПРОЧТЕНИЕ. Второе прочтение берётся лишь
    там, где первое тоже сошлось: строка, которую прежнее правило ценой не
    считало («Contract 2500000 1 2500000» — количество больше предела), ценой
    не становится и теперь.
    """
    (ва, ма), (вб, мб) = а, б
    первое = (ва, вб) if _прочтение_годно(ва, вб, сумма) else None
    if not ОТБОР_ЛОЖНЫХ or первое is None:
        return первое
    второе = (вб, ва) if _прочтение_годно(вб, ва, сумма) else None
    if второе is None or _единица_после(строка, ма):
        return первое
    if _единица_после(строка, мб):
        return второе
    if количество_правдоподобно(ва):
        return первое
    if количество_правдоподобно(вб) and _целое_написано(мб):
        return второе
    return первое


def цена_из_текста(строка: str, валюта_файла: str | None = None) -> dict | None:
    """Цена из строки PDF без таблицы — только если арифметика сошлась.

    Ищется тройка подряд идущих чисел (кол-во, цена, сумма), для которой
    кол-во × цена = сумма с допуском на округление. Берётся самая правая такая
    тройка: слева в строке стоят номер позиции и характеристики, справа — деньги.

    С ОТБОР_ЛОЖНЫХ (по умолчанию) порядок количества и цены в тройке решает
    прочтение_тройки, а строку, которую правило ложной цены обвиняет, правило не
    берёт: вырожденная тройка «x × 1 = x» пропускается (левее может стоять
    настоящая), строка-реквизит отвергается целиком. Судит ложная_цена — по тем
    же полям, что лягут в lib_prices, и так же, как пометка уже записанного.
    """
    if not строка or ШУМ_СТРОКИ.search(строка):
        return None
    # В строке позиции обязан быть текст: «1 2 2» — не позиция.
    if len(re.sub(r"[^A-Za-zА-Яа-яЁё]", "", строка)) < 4:
        return None
    токены = _токены_строки(строка)
    if len(токены) < 3:
        return None
    for i in range(len(токены) - 3, -1, -1):
        сумма = токены[i + 2][0]
        прочтение = прочтение_тройки(строка, токены[i], токены[i + 1], сумма)
        if прочтение is None:
            continue
        кол, цена = прочтение
        валюта = валюта_из(строка) or валюта_файла
        уверенность = "med" if валюта else "low"
        оговорка = ОГОВОРКА_ТЕКСТА
        if прочтение != (токены[i][0], токены[i + 1][0]):
            оговорка += "; " + ОГОВОРКА_ПЕРЕСТАВЛЕНО
        if валюта is None:
            оговорка += "; " + НЕТ_ВАЛЮТЫ
        if ОТБОР_ЛОЖНЫХ:
            # Поля — ровно те, что лягут в lib_prices: наименование и код у
            # текстовой позиции берутся из этой же строки (indexer, ocr), суммы
            # текстовый путь не пишет — её выводит из оговорки само правило.
            причина = ложная_цена(строка[:300], docfilter.part_number_of(строка), "",
                                  кол, round(цена, 4), None, оговорка)
            if причина == ПРИЧИНА_ВЫРОЖДЕНА:
                continue
            if причина:
                return None
        return {"price": round(цена, 4), "currency": валюта, "basis": базис_из(строка),
                "lead_days": None, "confidence": уверенность, "note": оговорка,
                "qty": кол}
    return None


def подставить_валюту(ц: dict, валюта: str | None) -> dict:
    """Валюта файла вместо ненайденной — с исправлением оговорки и уверенности.

    Без этого в строке оставались бы две несовместимые фразы разом: «валюта не
    названа» и «валюта взята по файлу». Оговорка должна описывать итог, а не
    историю его получения.
    """
    if not ц or валюта is None or ц.get("currency") is not None:
        return ц
    ц["currency"] = валюта
    части = [ч for ч in (ц.get("note") or "").split("; ") if ч and ч != НЕТ_ВАЛЮТЫ]
    части.append("валюта взята по файлу целиком")
    ц["note"] = "; ".join(части)
    # Отсутствие валюты было единственной причиной низкой уверенности — снимаем.
    # Кроме цены, чьи колонки узнаны не по шапке: там низкая уверенность — про
    # колонки, а не про валюту, и валюта файла её не поднимает.
    if ц.get("confidence") == "low" and not any(
            "делением" in ч or ОГОВОРКА_БЕЗ_ШАПКИ in ч for ч in части):
        ц["confidence"] = "med"
    return ц


