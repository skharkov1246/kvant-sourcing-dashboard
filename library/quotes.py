# ЗАЩИТА РАНЬШЕ ОБВИНЕНИЯ (правило 7 CLAUDE.md). Ошибочная защита стоит
# полноты — остаток мусора виден числом в замере; ошибочное обвинение стоит
# настоящей цены. Поэтому строку с признаком позиции не обвиняет ничто: код
# детали (docfilter), единица рядом с количеством или в своей колонке,
# стандарт, типоразмер, марка, слово словаря сегментов. Признак ищется в строке
# БЕЗ фрагментов реквизитов и без чисел самой тройки (кроме количества с
# единицей — оно и есть число тройки): номер CIN «L70109MH…» и
# телефон «2345 6789» docfilter принял бы за код, сумму «143880» — за артикул,
# и строка-реквизит защищала бы сама себя.
#
# ОБВИНЯЕТ ТОЛЬКО ЗАКРЫТЫЙ СПИСОК — ПРИЧИНЫ_ЛОЖНОЙ, каждая покрыта тестом
# (tests/test_false_prices.py); добавлять — вместе с тестом. Обвиняет РЕКВИЗИТ,
# А НЕ СЛОВО: у телефона и регистрационного номера обязано быть значение (или
# пометка «Tel:»), у итога — «Total:», «Total amount», число сразу за словом.
# Ревизия 27.09.2026 нашла, во что обходится голое слово: «Mob/Demob of service
# engineers», «Mobile compressor», «Swift coupling», «КПП» (коробка передач),
# масла TOTAL, «Amount of work: …» — настоящие строки КП, которые правило
# снимало как реквизит. «total» внутри наименования («total height 150») не
# обвиняет и подавно.
#
# ПЕРЕКЛЮЧАТЕЛЬ ЗАПИСИ — ВЫКЛЮЧЕН ПО УМОЛЧАНИЮ (правило 3: сначала мерят, потом
# применяют). FALSE_PRICE_RULE=1 включает отбор при записи всем трём писателям
# (разбор, переразбор, распознавание) — и прочтение тройки, и отказ; без него
# запись идёт прежним путём целиком, что и нужно для замера A/B на тех же
# байтах. Включать по умолчанию — после просмотренного холостого замера
# (scripts/mark_false_prices.py, задание false-prices). Пометка уже записанного
# переключателя не видит: она меряет само правило.
# 27.09.2026 замер просмотрен и пометка записана (701 строка из 64 915, четыре
# гейта, сверка Python ↔ SQL): в прогонах разбора переключатель включает общая
# точка окружения .github/actions/parse-env. В коде умолчание прежнее — выключен:
# тесты и разовые вызовы без окружения пишут прежним путём.
def _включено(значение: str | None) -> bool:
    """Значение переключателя: включает только явное «1», «true», «yes», «on»."""
    return str(значение or "").strip().lower() in ("1", "true", "yes", "on")


ОТБОР_ЛОЖНЫХ = _включено(os.environ.get("FALSE_PRICE_RULE"))
ЛОЖНАЯ_ЦЕНА_ВЕРСИЯ = "ложная-цена-v2"

# ПАРА ЦЕН «БЕЗ НДС / С НДС» В СТРОКЕ ТЕКСТА (правка F3 чтения КП в PDF,
# indexer.ПРАВКИ_КП) — за флагом, по умолчанию выключена (правило 3).
#
# Печатная форма КП часто несёт между количеством и суммой ДВЕ цены: «2 шт
# 4 243,42 5 092,10 10 184,21». Тройка подряд идущих чисел здесь не сходится
# ни в одном окне (кол-во × цена без НДС ≠ цена с НДС), и строка цены не давала
# вовсе. Четвёрка (кол-во, ц1, ц2, сумма) берётся, когда ц2 = ц1 × (1 + ставка)
# по закрытому списку ставок и кол-во × ц2 или кол-во × ц1 = сумма. Цена — ц1,
# без НДС (CLAUDE.md, «Цена и предложение»: сравниваем без НДС), с оговоркой.
#
# ТОЛЬКО ДОБАВЛЯЕТ. Четвёрка ищется, лишь когда тройка не нашлась: строка,
# которую прежнее правило читало, читается как прежде.
#
# ОДИН ВХОД НА ШЕСТЬ ПРАВОК, НО КАЖДАЯ ИЗМЕРИМА ОТДЕЛЬНО. PDF_OFFER_FIXES — не
# булев переключатель, а перечень: пусто — ни одной, «все» (или «1») — все шесть,
# «F1,F4» — названные. Так прогон переразбора меряет «у скольких хуже» по одной
# правке, не заводя шесть входов (у workflow_dispatch их не больше 25). Неверное
# значение — отказ с названной причиной, а не молчаливое «выключено»: журнал
# обязан говорить, на чём шёл прогон (CLAUDE.md, «Читай ВЫЗОВ»).
ПРАВКИ_ВСЕ = ("F1", "F2", "F3", "F4", "F5", "F6")
_ПРАВКИ_ВСЕ_СЛОВА = frozenset({"1", "true", "yes", "on", "все", "all"})
_ПРАВКИ_НИ_ОДНОЙ = frozenset({"", "0", "false", "no", "off", "нет"})


def правки_из(значение: str | None) -> frozenset[str]:
    """Перечень правок из значения PDF_OFFER_FIXES; неверное — ValueError с причиной."""
    сырое = str(значение or "").strip()
    if сырое.lower() in _ПРАВКИ_НИ_ОДНОЙ:
        return frozenset()
    if сырое.lower() in _ПРАВКИ_ВСЕ_СЛОВА:
        return frozenset(ПРАВКИ_ВСЕ)
    куски = [к.upper() for к in re.split(r"[\s,;+]+", сырое) if к]
    чужие = [к for к in куски if к not in ПРАВКИ_ВСЕ]
    if чужие or not куски:
        raise ValueError(f"PDF_OFFER_FIXES={сырое!r}: ждём пусто, «все» или перечень "
                         f"{', '.join(ПРАВКИ_ВСЕ)} через запятую; не понято: "
                         f"{', '.join(чужие) or сырое}")
    return frozenset(куски)


