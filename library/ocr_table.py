def вид_и_размер(путь: str) -> tuple[str | None, tuple[int, int] | None]:
    """Формат картинки по сигнатуре и её размер по заголовку, без библиотек.

    ФОРМАТ ПРОВЕРЯЕТСЯ ДО tesseract НЕ ИЗ ОСТОРОЖНОСТИ. Файл, который не
    опознан как картинка, tesseract читает как СПИСОК ПУТЕЙ к картинкам — по
    строке на путь — и пытается распознать то, на что эти строки указывают
    (проверено: 300 случайных байт дают «image file not found: <мусор>»). Чужой
    файл в распознавание попадать не должен вовсе.

    Размер None — заголовок не прочитан; формат при этом может быть известен."""
    try:
        with open(путь, "rb") as f:
            г = f.read(32)
            if г.startswith(b"\x89PNG\r\n\x1a\n"):
                return "png", _пара(">II", г[16:24])
            if г[:3] == b"GIF":
                return "gif", _пара("<HH", г[6:10])
            if г[:2] == b"BM":
                п = _пара("<ii", г[18:26])
                return "bmp", (abs(п[0]), abs(п[1])) if п else None
            if г[:4] == b"RIFF" and г[8:12] == b"WEBP":
                return "webp", _размер_webp(г)
            if г[:4] in (b"II*\x00", b"MM\x00*"):
                return "tiff", _размер_tiff(f, "<" if г[:2] == b"II" else ">")
            if г[:2] == b"\xff\xd8":
                return "jpeg", _размер_jpeg(f)
            if г[:1] == b"P" and г[1:2] in (b"1", b"2", b"3", b"4", b"5", b"6"):
                f.seek(0)
                return "pnm", _размер_pnm(f.read(512))
            if г[4:8] == b"jP  " or г[:4] == b"\xff\x4f\xff\x51":
                return "jp2", None
    except OSError:
        return None, None
    return None, None


def _пара(формат: str, байты: bytes) -> tuple[int, int] | None:
    try:
        w, h = struct.unpack(формат, байты)
    except struct.error:
        return None
    return (int(w), int(h)) if w and h else None


def _размер_webp(г: bytes) -> tuple[int, int] | None:
    try:
        вид = г[12:16]
        if вид == b"VP8X":
            w = int.from_bytes(г[24:27], "little") + 1
            h = int.from_bytes(г[27:30], "little") + 1
            return w, h
        if вид == b"VP8 ":
            w, h = struct.unpack("<HH", г[26:30])
            return w & 0x3FFF, h & 0x3FFF
        if вид == b"VP8L":
            v = int.from_bytes(г[21:25], "little")
            return (v & 0x3FFF) + 1, ((v >> 14) & 0x3FFF) + 1
    except (struct.error, IndexError):
        return None
    return None


def _размер_tiff(f, е: str) -> tuple[int, int] | None:
    try:
        f.seek(4)
        (смещение,) = struct.unpack(е + "I", f.read(4))
        f.seek(смещение)
        (n,) = struct.unpack(е + "H", f.read(2))
        размер: dict[int, int] = {}
        for _ in range(min(n, 512)):
            тег, тип, _кол = struct.unpack(е + "HHI", f.read(8))
            значение = f.read(4)
            if тег in (256, 257):
                размер[тег] = (struct.unpack(е + "H", значение[:2])[0] if тип == 3
                               else struct.unpack(е + "I", значение)[0])
        if размер.get(256) and размер.get(257):
            return размер[256], размер[257]
    except (struct.error, OSError, ValueError):
        return None
    return None


def _sof_jpeg(f) -> tuple[int, int, int] | None:
    """(ширина, высота, число каналов) из заголовка кадра JPEG."""
    try:
        f.seek(2)
        for _ in range(512):
            м = f.read(2)
            if len(м) < 2 or м[0] != 0xFF:
                return None
            if 0xC0 <= м[1] <= 0xCF and м[1] not in (0xC4, 0xC8, 0xCC):
                f.read(3)
                h, w, n = struct.unpack(">HHB", f.read(5))
                return (w, h, n) if w and h else None
            (длина,) = struct.unpack(">H", f.read(2))
            f.seek(длина - 2, 1)
    except (struct.error, OSError, ValueError):
        return None
    return None


def _размер_jpeg(f) -> tuple[int, int] | None:
    sof = _sof_jpeg(f)
    return sof[:2] if sof else None


def _размер_pnm(г: bytes) -> tuple[int, int] | None:
    без_пояснений = re.sub(rb"#[^\n]*", b" ", г[2:])
    числа = re.findall(rb"\d+", без_пояснений)
    if len(числа) >= 2:
        return int(числа[0]), int(числа[1])
    return None


def _множитель(размер: tuple[int, int]) -> int:
    w, h = размер
    сторона = min(w, h)
    if сторона <= 0 or сторона >= МЕЛКАЯ:
        return 1
    k = min(МАКС_УВЕЛИЧЕНИЕ, math.ceil(МЕЛКАЯ / сторона))
    while k > 1 and w * h * k * k > МАКС_ПИКСЕЛЕЙ:
        k -= 1
    return k


def _pillow():
    """Модуль Image из Pillow или None. Отдельной функцией — чтобы тест мог
    изобразить машину без Pillow, не ломая импорт у всех."""
    try:
        from PIL import Image
        return Image
    except Exception:                                                    # noqa: BLE001
        return None


def _куски_png(данные: bytes) -> dict | None:
    """IHDR, палитра и сжатые данные PNG — без распаковки."""
    if not данные.startswith(b"\x89PNG\r\n\x1a\n"):
        return None
    i, idat, out = 8, [], {}
    try:
        while i + 8 <= len(данные):
            (длина,) = struct.unpack(">I", данные[i:i + 4])
            тип, тело = данные[i + 4:i + 8], данные[i + 8:i + 8 + длина]
            if тип == b"IHDR":
                (out["w"], out["h"], out["глубина"], out["цвет"], _сж, _фильтр,
                 out["черезстрочный"]) = struct.unpack(">IIBBBBB", тело)
            elif тип == b"PLTE":
                out["палитра"] = тело
            elif тип == b"IDAT":
                idat.append(тело)
            elif тип == b"IEND":
                break
            i += 12 + длина
    except struct.error:
        return None
    if "w" not in out or not idat:
        return None
    out["данные"] = b"".join(idat)
    return out


def pdf_из_картинки(путь: str, поворот: int = 0) -> tuple[bytes | None, str]:
    """Картинка → одностраничный PDF с /Rotate, БЕЗ распаковки пикселей.

    ЗАЧЕМ. Повернуть и увеличить картинку можно Pillow или ImageMagick, но в
    прогоне распознавания (library-index.yml) их нет, а poppler есть — pdftoppm
    уже разворачивает сканы PDF в ocr.py. PDF умеет принять JPEG как есть
    (/DCTDecode) и PNG как есть (/FlateDecode с предиктором PNG: сжатые строки
    PNG и есть такой поток). Остаётся поставить странице /Rotate и отрисовать её
    pdftoppm с нужным разрешением — поворот и увеличение за один проход.

    Не берутся: PNG с прозрачностью (альфа-канал в PDF идёт отдельным потоком, и
    его пришлось бы распаковывать), черезстрочный PNG и прочие форматы. Для них
    (None, почему)."""
    try:
        with open(путь, "rb") as f:
            данные = f.read()
    except OSError:
        return None, "файл не читается"
    if данные[:2] == b"\xff\xd8":
        import io
        sof = _sof_jpeg(io.BytesIO(данные))
        if not sof:
            return None, "JPEG без заголовка кадра"
        w, h, n = sof
        пространство = {1: "/DeviceGray", 3: "/DeviceRGB", 4: "/DeviceCMYK"}.get(n)
        if not пространство:
            return None, f"JPEG с {n} каналами"
        # CMYK из Photoshop (метка Adobe) хранится инвертированным.
        инверсия = " /Decode [1 0 1 0 1 0 1 0]" if n == 4 and b"Adobe" in данные[:65536] else ""
        словарь = f"/Filter /DCTDecode /ColorSpace {пространство} /BitsPerComponent 8{инверсия}"
        поток = данные
    else:
        png = _куски_png(данные)
        if png is None:
            return None, "не PNG и не JPEG"
        if png["черезстрочный"]:
            return None, "черезстрочный PNG"
        цвет, глубина, w, h = png["цвет"], png["глубина"], png["w"], png["h"]
        if цвет == 0:
            пространство, каналов = "/DeviceGray", 1
        elif цвет == 2:
            пространство, каналов = "/DeviceRGB", 3
        elif цвет == 3 and png.get("палитра"):
            палитра = png["палитра"]
            пространство = (f"[/Indexed /DeviceRGB {len(палитра) // 3 - 1} "
                            f"<{палитра.hex()}>]")
            каналов = 1
        else:
            return None, "PNG с прозрачностью"
        словарь = (f"/Filter /FlateDecode /DecodeParms << /Predictor 15 /Colors {каналов}"
                   f" /BitsPerComponent {глубина} /Columns {w} >> /ColorSpace {пространство}"
                   f" /BitsPerComponent {глубина}")
        поток = png["данные"]
    # Страница в пунктах равна картинке в пикселях: при -r 72 пиксель в пиксель,
    # при -r 72·k — увеличение в k раз. /Interpolate — сглаживание при увеличении,
    # иначе poppler растит пиксели квадратами.
    содержимое = f"q {w} 0 0 {h} 0 0 cm /Im0 Do Q".encode()
    объекты = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        (f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {w} {h}] /Rotate {поворот % 360}"
         f" /Resources << /XObject << /Im0 5 0 R >> >> /Contents 4 0 R >>").encode(),
        b"<< /Length %d >>\nstream\n" % len(содержимое) + содержимое + b"\nendstream",
        (f"<< /Type /XObject /Subtype /Image /Width {w} /Height {h} /Interpolate true "
         f"{словарь} /Length {len(поток)} >>\nstream\n").encode() + поток + b"\nendstream",
    ]
    out = bytearray(b"%PDF-1.5\n")
    смещения = []
    for i, о in enumerate(объекты, 1):
        смещения.append(len(out))
        out += b"%d 0 obj\n" % i + о + b"\nendobj\n"
    начало = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(объекты) + 1)
    for смещение in смещения:
        out += b"%010d 00000 n \n" % смещение
    out += (b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n"
            % (len(объекты) + 1, начало))
    return bytes(out), ""


def _подготовить(путь: str, tmp: str, k: int, поворот: int, env: dict,
                 timeout: int) -> tuple[str | None, str]:
    """Копия картинки: увеличена в k раз и повёрнута на «поворот» по часовой.

    (путь к копии или None, чем сделано или почему не вышло). Инструменты по
    очереди: Pillow, ImageMagick, poppler — первый, который справился."""
    выход = os.path.join(tmp, f"prep_{k}_{поворот}.png")
    почему: list[str] = []
    Image = _pillow()
    if Image is not None:
        try:
            with Image.open(путь) as im:
                if getattr(im, "n_frames", 1) > 1:
                    # Pillow отдаёт только первый кадр, а tesseract читает все
                    # страницы TIFF: подготовка потеряла бы остальные листы.
                    return None, "многостраничная картинка, подготовка пропущена"
                кадр = im if im.mode in ("1", "L", "RGB", "P") else im.convert("RGB")
                if k > 1:
                    фильтр = getattr(getattr(Image, "Resampling", Image), "LANCZOS")
                    кадр = кадр.resize((im.width * k, im.height * k), фильтр)
                if поворот:
                    т = getattr(Image, "Transpose", Image)
                    # Pillow крутит против часовой, OSD говорит по часовой.
                    кадр = кадр.transpose({90: т.ROTATE_270, 180: т.ROTATE_180,
                                           270: т.ROTATE_90}[поворот])
                кадр.save(выход)
            return выход, "Pillow"
        except Exception as e:                                           # noqa: BLE001
            почему.append(f"Pillow: {type(e).__name__}")
    exe = shutil.which("magick") or shutil.which("convert")
    if exe:
        команда = [exe, путь] + (["-rotate", str(поворот)] if поворот else []) \
            + (["-resize", f"{k * 100}%"] if k > 1 else []) + [выход]
        сделано, отчёт = _запустить(команда, выход, timeout,
                                    {**env, "MAGICK_THREAD_LIMIT": env.get("OMP_THREAD_LIMIT", OMP)})
        if сделано:
            return выход, "ImageMagick"
        почему.append(f"ImageMagick: {отчёт}")
    if shutil.which("pdftoppm"):
        pdf, отказ = pdf_из_картинки(путь, поворот)
        if pdf is None:
            почему.append(f"poppler: {отказ}")
        else:
            вход = os.path.join(tmp, f"prep_{k}_{поворот}.pdf")
            with open(вход, "wb") as f:
                f.write(pdf)
            # -gray: tesseract всё равно переводит лист в серый перед бинаризацией,
            # а серый файл втрое меньше цветного.
            сделано, отчёт = _запустить(
                ["pdftoppm", "-r", str(72 * k), "-gray", "-png", "-singlefile", вход,
                 выход[:-4]], выход, timeout, env)
            if сделано:
                return выход, "poppler"
            почему.append(f"poppler: {отчёт}")
    if not почему:
        return None, "нет Pillow, ImageMagick и pdftoppm"
    return None, "; ".join(почему)


def _запустить(команда: list[str], выход: str, timeout: int,
               env: dict) -> tuple[bool, str]:
    """Вспомогательная программа: (вышел ли файл, что не так). Слов «таймаут»
    и «код» здесь нет намеренно: ocr.почему_пусто ищет их в причине и принял
    бы сбой подготовки за сбой распознавания."""
    try:
        r = subprocess.run(команда, capture_output=True, timeout=timeout, env=env)
    except subprocess.TimeoutExpired:
        return False, "не уложился во время"
    except Exception as e:                                               # noqa: BLE001
        return False, f"не запустился: {type(e).__name__}"
    if r.returncode == 0 and os.path.exists(выход):
        return True, ""
    return False, f"не справился (выход {r.returncode})"


def _tesseract(аргументы: list[str], env: dict,
               timeout: int) -> tuple[subprocess.CompletedProcess | None, str]:
    """Запуск tesseract. Причины отказа — те же строки, что в ocr.ocr_image."""
    try:
        r = subprocess.run(["tesseract", *аргументы], capture_output=True,
                           timeout=timeout, env=env)
    except subprocess.TimeoutExpired:
        return None, "таймаут распознавания"
    except FileNotFoundError:
        return None, "tesseract не установлен"
    except Exception as e:                                               # noqa: BLE001
        return None, f"сбой запуска: {type(e).__name__}"
    return r, ""


def ориентация(путь: str, env: dict | None = None,
               timeout: int | None = None) -> tuple[int, float, str]:
    """OSD: (поворот по часовой из строки «Rotate:», уверенность, почему не вышло).

    Отказ OSD — не отказ распознавания: лист читается как прямой, а причина идёт
    в пояснение. Исключение — отказы окружения, их вызывающий обязан вернуть."""
    r, отказ = _tesseract([путь, "stdout", "--psm", "0"],
                          СРЕДА if env is None else env, timeout or TIMEOUT)
    if r is None:
        return 0, 0.0, отказ
    вывод = r.stdout.decode("utf-8", "ignore")
    м = re.search(r"Rotate:\s*(\d+)", вывод)
    у = re.search(r"Orientation confidence:\s*([\d.]+)", вывод)
    if м:
        try:
            return int(м.group(1)) % 360, float(у.group(1)) if у else 0.0, ""
        except ValueError:
            pass
    ошибка = r.stderr.decode("utf-8", "ignore")
    if "Too few characters" in ошибка:
        return 0, 0.0, "мало знаков для OSD"
    if "osd" in ошибка.lower():
        return 0, 0.0, "нет данных OSD (пакет tesseract-ocr-osd)"
    return 0, 0.0, "OSD не ответил"


def распознать_таблицу_подробно(путь_к_картинке: str, *, env: dict | None = None,
                                lang: str | None = None, psm: str | None = None,
                                timeout: int | None = None,
                                годится=None) -> tuple[Таблица, str]:
    """(Таблица, причина). Причина при успехе — служебная сводка: средняя
    уверенность, слабые слова, поворот, увеличение. Никогда не бросает."""
    try:
        return _распознать(путь_к_картинке, СРЕДА if env is None else env,
                           lang or LANG, psm or PSM_MAIN, timeout or TIMEOUT, годится)
    except Exception as e:                                               # noqa: BLE001
        return Таблица(), f"сбой разбора таблицы: {type(e).__name__}"


def распознать_таблицу(путь_к_картинке: str, **kw) -> tuple[list[list[str]], str, str]:
    """(rows, text, reason) по картинке. rows пуст — таблицы нет, text остаётся.

    rows обязаны пройти ворота шапки у вызывающего (indexer.header_map), как и
    таблица из PDF: без опознанной шапки разрез отвергается целиком."""
    таблица, причина = распознать_таблицу_подробно(путь_к_картинке, **kw)
    return таблица.rows, таблица.text, причина


def _распознать(путь: str, env: dict, lang: str, psm: str, timeout: int,
                годится) -> tuple[Таблица, str]:
    if not os.path.isfile(путь):
        return Таблица(), "файл не найден"
    вид, размер = вид_и_размер(путь)
    if вид is None:
        return Таблица(), "не картинка: формат не опознан"
    пояснения: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        рабочий = путь
        if размер is None:
            пояснения.append("размер не прочитан, увеличение не решалось")
        elif min(размер) < МЕЛКАЯ:
            k = _множитель(размер)
            мелкая = f"мелкая {размер[0]}×{размер[1]}"
            if k < 2:
                пояснения.append(f"{мелкая}: увеличение упёрлось в предел пикселей")
            else:
                новый, чем = _подготовить(путь, tmp, k, 0, env, timeout)
                if новый:
                    рабочий = новый
                    пояснения.append(f"{мелкая}: увеличено ×{k} ({чем})")
                else:
                    пояснения.append(f"{мелкая}: увеличить нечем ({чем})")

        # Ориентация — по уже увеличенной копии: на мелкой OSD молчит («Too few
        # characters» при 100 dpi в калибровке).
        угол, увер, почему = ориентация(рабочий, env, timeout)
        if почему.startswith(("таймаут", "tesseract не установлен", "сбой запуска")):
            отказ = почему if почему != "таймаут распознавания" \
                else "таймаут распознавания (определение ориентации)"
            return Таблица(), "; ".join([отказ] + пояснения)
        повёрнут = угол != 0 and увер >= ПОРОГ_ОСД
        if почему:
            пояснения.append(f"ориентация не определена: {почему}")
        elif угол and not повёрнут:
            пояснения.append(f"OSD предлагал поворот {угол}°, уверенность {увер:.2f}"
                             f" ниже {ПОРОГ_ОСД}: читано как прямой")

        # ЛИСТ НА БОКУ ПОВОРАЧИВАЕТСЯ КАРТИНКОЙ, А НЕ РЕЖИМОМ. Режим --psm 1
        # поворачивает лист сам, но на придуманном КП (200 dpi) терял одиночные
        # цифры количества при любом повороте, а на 270° принял столбец номеров
        # «1 2 3 4» за вертикальную строку и прочитал «MO ST AN». Выключение
        # поиска вертикального текста чинило 270° и ломало 90° и 180° в мусор.
        # Повёрнутая картинка в основном режиме читается как прямой лист. Режим
        # --psm 1 остаётся последним запасом, когда повернуть нечем.
        сам = False
        if повёрнут:
            новый, чем = _подготовить(рабочий, tmp, 1, угол, env, timeout)
            if новый:
                рабочий, сам = новый, True
                пояснения.append(f"лист на боку: повёрнут на {угол}° ({чем}),"
                                 f" OSD {увер:.1f}")
            else:
                пояснения.append(f"лист на боку: OSD {угол}° ({увер:.1f}), повернуть"
                                 f" нечем ({чем}), читано режимом --psm {PSM_ПОВОРОТ}")

        # Порядок попыток. Прямой (или повёрнутый) лист — основной режим, затем
        # запасной, как в ocr.recognise: на фотографии блочный режим иногда
        # молчит. Лист на боку без поворота — режим с ориентацией, затем основной
        # на случай, если OSD ошибся.
        режимы = [PSM_ПОВОРОТ, psm] if повёрнут and not сам else [psm, PSM_RETRY]
        таблица, отказ = Таблица(), "текста не найдено"
        for режим in dict.fromkeys(режимы):
            r, отказ_запуска = _tesseract(
                [рабочий, "stdout", "-l", lang, "--psm", режим,
                 # Ключом, а не именем конфига «tsv»: конфиг лежит в
                 # tessdata/configs, и в урезанной установке его может не быть.
                 "-c", "tessedit_create_tsv=1"], env, timeout)
            if r is None:
                # После таймаута не повторяем: вторая попытка тоже не уложится.
                return Таблица(), "; ".join([отказ_запуска] + пояснения)
            таблица = разобрать_tsv(r.stdout.decode("utf-8", "ignore"), годится)
            if таблица.слов:
                отказ = ""
                if режим != режимы[0]:
                    пояснения.append(f"прочитано запасным режимом --psm {режим}")
                break
            отказ = (f"tesseract вернул код {r.returncode}" if r.returncode
                     else "текста не найдено")
    if отказ:
        return таблица, "; ".join([отказ] + пояснения)
    if таблица.поворот:
        пояснения.append(f"кадр слов повёрнут на {таблица.поворот}°")
    return таблица, "; ".join([таблица.сводка()] + пояснения)
