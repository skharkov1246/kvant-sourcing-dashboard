@dataclass
class Слово:
    x: float
    y: float
    w: float
    h: float
    conf: float
    text: str
    ключ: tuple = ()        # (страница, блок, абзац, строка) — строка tesseract
    номер: int = 0          # порядок слова в строке tesseract: по нему виден поворот
    линейка: bool = False   # глиф вертикальной линейки: граница поля, не текст

    @property
    def r(self) -> float:
        return self.x + self.w

    @property
    def b(self) -> float:
        return self.y + self.h

    @property
    def cx(self) -> float:
        return self.x + self.w / 2

    @property
    def cy(self) -> float:
        return self.y + self.h / 2


@dataclass
class Таблица:
    """Итог разбора. rows пуст — таблицы нет, и вызывающий идёт текстовым путём."""
    rows: list[list[str]] = field(default_factory=list)
    text: str = ""
    # Наименьшая уверенность слов в ячейке; None — ячейка пуста. Наименьшая, а не
    # средняя: одна неверно прочитанная цифра портит всю цену.
    уверенность: list[list[float | None]] = field(default_factory=list)
    слов: int = 0
    слабых: int = 0
    средняя: float | None = None
    поворот: int = 0        # на сколько градусов по часовой повёрнут кадр слов
    допуск: int = -1        # ступень ДОПУСКИ, давшая таблицу; -1 — таблицы нет

    def слабые(self, порог: float = ПОРОГ_ДОВЕРИЯ) -> list[tuple[int, int]]:
        """Ячейки (строка, колонка), где хоть одно слово ниже порога доверия."""
        return [(i, j) for i, ряд in enumerate(self.уверенность)
                for j, c in enumerate(ряд) if c is not None and c < порог]

    def сводка(self) -> str:
        if not self.слов:
            return "слов не распознано"
        части = []
        if self.средняя is not None:
            части.append(f"уверенность {self.средняя:.0f}")
        части.append(f"слабых слов {self.слабых} из {self.слов} (conf < {ПОРОГ_ДОВЕРИЯ:.0f})")
        if not self.rows:
            части.append("таблицы нет: колонки не нашлись")
        return "; ".join(части)


ИМЕНА = ("level", "page_num", "block_num", "par_num", "line_num", "word_num",
         "left", "top", "width", "height", "conf", "text")
# Без номера страницы — так формат описан в постановке задачи; tesseract 5 номер
# пишет. Принимаются оба, чтобы не зависеть от того, кто и как собрал вывод.
БЕЗ_СТРАНИЦЫ = tuple(n for n in ИМЕНА if n != "page_num")


def _страницы(tsv: str) -> dict[int, tuple[list[Слово], tuple[float, float] | None]]:
    """TSV → {страница: (слова, (ширина, высота) страницы или None)}.

    Строка, которая не разбирается, пропускается молча: один обрывок вывода не
    должен стоить всего листа."""
    строки = [s for s in (tsv or "").splitlines() if s.strip()]
    имена = None
    данные = []
    for s in строки:
        части = s.split("\t")
        if части[0].strip().lower() == "level":
            имена = tuple(ч.strip().lower() for ч in части)
        else:
            данные.append(части)
    if имена is None:
        # Шапки нет — формат узнаётся по строкам слов: у них текст не пуст, и хвост
        # строки никто не срезал. У строк уровней 1–4 текст пуст, и срезанный
        # хвостовой таб делает из двенадцати полей одиннадцать.
        длины = [len(ч) for ч in данные if len(ч) >= 11 and ч[-1].strip()]
        имена = ИМЕНА if длины and max(длины) >= 12 else БЕЗ_СТРАНИЦЫ
    if "text" not in имена:
        return {}
    страницы: dict[int, tuple[list[Слово], tuple[float, float] | None]] = {}
    for части in данные:
        if len(части) < len(имена):
            части = части + [""] * (len(имена) - len(части))
        rec = dict(zip(имена, части))
        if len(части) > len(имена) and имена[-1] == "text":
            rec["text"] = "\t".join(части[len(имена) - 1:])
        try:
            уровень = int(rec["level"])
            стр = int(rec.get("page_num") or 1)
            x, y = float(rec["left"]), float(rec["top"])
            w, h = float(rec["width"]), float(rec["height"])
        except (ValueError, KeyError):
            continue
        if w < 0 or h < 0 or not all(map(math.isfinite, (x, y, w, h))):
            continue
        слова, размер = страницы.get(стр, ([], None))
        if уровень == 1:
            страницы[стр] = (слова, (x + w, y + h) if w and h else размер)
            continue
        текст = (rec.get("text") or "").strip()
        if уровень != 5 or not текст:
            continue
        try:
            conf = float(rec.get("conf") or -1)
            ключ = (стр, int(rec.get("block_num") or 0), int(rec.get("par_num") or 0),
                    int(rec.get("line_num") or 0))
            номер = int(rec.get("word_num") or 0)
        except ValueError:
            continue
        if not math.isfinite(conf):
            conf = -1.0
        слова.extend(_с_линейками(Слово(x, y, w, h, conf, текст, ключ, номер)))
        страницы[стр] = (слова, размер)
    return страницы


def _с_линейками(с: Слово) -> list[Слово]:
    """Слово без глифов линейки по краям; сами глифы — отдельными границами.

    tesseract читает вертикальную линейку как «|» — отдельным словом или
    прилипшим к соседу («шт|»). В узкой таблице с линейками промежуток между
    ячейками бывает уже порога поля, и граница видна только по линейке."""
    чистый = с.text.strip(ЛИНЕЙКИ + " ")
    if not чистый:
        return [replace(с, линейка=True)]
    if чистый == с.text:
        return [с]
    # Рамка прилипшего глифа входит в рамку слова. Её доля неизвестна и берётся
    # по числу знаков: «кг|» в 33 px → «кг» в 22 px. Без этого рамка слова
    # заходит на промежуток до соседней колонки и съедает жёлоб.
    слева = len(с.text) - len(с.text.lstrip(ЛИНЕЙКИ + " "))
    справа = len(с.text) - len(с.text.rstrip(ЛИНЕЙКИ + " "))
    знак = с.w / len(с.text)
    слово = replace(с, x=с.x + слева * знак, w=len(чистый) * знак, text=чистый)
    out = []
    if слева:
        out.append(replace(с, w=0.0, text="|", линейка=True))
    out.append(слово)
    if справа:
        out.append(replace(с, x=слово.r, w=0.0, text="|", линейка=True))
    return out


def _угол(слова: list[Слово]) -> int:
    """На сколько градусов по часовой повернуть кадр, чтобы строки легли слева направо.

    Порядок слов в строке tesseract — порядок чтения. Если слова идут слева
    направо, лист прямой; сверху вниз — лист повёрнут по часовой, и кадр надо
    повернуть на 270; снизу вверх — на 90; справа налево — на 180. Числа те же,
    что пишет OSD в строке «Rotate:», — проверено на повёрнутых листах."""
    по_строкам: dict[tuple, list[Слово]] = {}
    for с in слова:
        if not с.линейка:
            по_строкам.setdefault(с.ключ, []).append(с)
    sx = sy = 0.0
    n = 0
    for ряд in по_строкам.values():
        if len(ряд) < 2:
            continue
        ряд.sort(key=lambda с: с.номер)
        dx, dy = ряд[-1].cx - ряд[0].cx, ряд[-1].cy - ряд[0].cy
        d = math.hypot(dx, dy)
        if d:
            sx, sy, n = sx + dx / d, sy + dy / d, n + 1
    if not n or (sx > 0 and sx >= abs(sy)):
        return 0
    # Поворот объявляется только при ясном перевесе: три строки из пяти должны
    # течь в одну сторону. Иначе кадр не трогается — повернуть прямой лист хуже,
    # чем оставить кривой.
    if max(abs(sx), abs(sy)) < 0.6 * n:
        return 0
    if abs(sx) >= abs(sy):
        return 180
    return 270 if sy > 0 else 90


def _в_прямой_кадр(с: Слово, угол: int, W: float, H: float) -> Слово:
    """Рамка слова из кадра картинки W×H в кадр, повёрнутый на угол по часовой."""
    if угол == 90:
        return replace(с, x=H - с.b, y=с.x, w=с.h, h=с.w)
    if угол == 180:
        return replace(с, x=W - с.r, y=H - с.b)
    if угол == 270:
        return replace(с, x=с.y, y=W - с.r, w=с.h, h=с.w)
    return с


def _наложение(a0: float, a1: float, b0: float, b1: float) -> float:
    return max(0.0, min(a1, b1) - max(a0, b0))


def _ряды(слова: list[Слово], h: float) -> list[list[Слово]]:
    """Слова → видимые строки листа, по вертикали, а не по строкам tesseract.

    В блочном режиме строка tesseract и есть строка таблицы. Но в автоматическом
    (--psm 1 и 3, а повёрнутый лист читается только так) каждая колонка — свой
    блок, и вывод идёт колонка за колонкой: «наименования… количества… цены…».
    Поэтому строки tesseract здесь — только куски, а строка листа собирается из
    них по вертикальному перекрытию. Кусок сравнивается с БЛИЖАЙШИМ по горизонтали
    соседом в строке, а не со строкой целиком: при перекосе листа в 1° строка
    шириной 2000 px уходит вниз на 35 px, больше высоты слова, и сравнение с
    началом строки её бы разорвало, а соседние ячейки отличаются на пиксели."""
    по_ключу: dict[tuple, list[Слово]] = {}
    for с in слова:
        по_ключу.setdefault(с.ключ, []).append(с)
    куски = [(min(с.x for с in к), min(с.y for с in к), max(с.r for с in к),
              max(с.b for с in к), к) for к in по_ключу.values()]
    куски.sort(key=lambda к: ((к[1] + к[3]) / 2, к[0]))
    ряды: list[list[tuple]] = []
    центры: list[float] = []
    for к in куски:
        цк = (к[1] + к[3]) / 2
        лучший, лучшее = None, 0.0
        for i in range(len(ряды) - 1, -1, -1):
            # Строки заводятся сверху вниз; строка, начатая на десять высот выше,
            # с этим куском уже не сойдётся ни при каком перекосе.
            if цк - центры[i] > 10 * h:
                break
            ряд = ряды[i]
            if any(_наложение(к[0], к[2], g[0], g[2]) > НАЛОЖЕНИЕ * h for g in ряд):
                continue
            g = min(ряд, key=lambda g: max(g[0] - к[2], к[0] - g[2], 0.0))
            доля = _наложение(к[1], к[3], g[1], g[3]) / max(1.0, min(к[3] - к[1], g[3] - g[1]))
            # «>=» при обходе снизу вверх: при равенстве выигрывает верхняя строка.
            if доля >= ПЕРЕКРЫТИЕ and доля >= лучшее:
                лучший, лучшее = i, доля
        if лучший is None:
            ряды.append([к])
            центры.append(цк)
        else:
            ряды[лучший].append(к)
    out = []
    for ряд in ряды:
        out.append(sorted((с for к in ряд for с in к[4]), key=lambda с: (с.x, с.y)))
    out.sort(key=lambda р: statistics.median(с.cy for с in р))
    return out


def _поля(ряд: list[Слово], h: float) -> list[list[Слово]]:
    """Строка → поля: слова, разделённые промежутком от ПОЛЕ_ОТ·h или линейкой."""
    поля: list[list[Слово]] = []
    текущее: list[Слово] = []
    for с in ряд:
        if с.линейка:
            if текущее:
                поля.append(текущее)
                текущее = []
            continue
        if текущее and с.x - текущее[-1].r >= ПОЛЕ_ОТ * h:
            поля.append(текущее)
            текущее = []
        текущее.append(с)
    if текущее:
        поля.append(текущее)
    return поля


def _границы(блок: list[list[list[Слово]]], допуск: int, h: float) -> list[float]:
    """Позиции разреза: середины жёлобов, занятых не более чем в «допуск» строках.

    Считается заметанием по краям полей, а не по пикселям: лист в 5000 px и сотня
    строк дали бы полмиллиона шагов на ступень."""
    события = []
    for поля in блок:
        for п in поля:
            события.append((п[0].x, 1))
            события.append((max(с.r for с in п), -1))
    if not события:
        return []
    события.sort()                        # при равном x конец (−1) раньше начала
    первый = события[0][0]
    жёлобы: list[tuple[float, float]] = []
    счёт, пред, начало = 0, None, None
    for x, d in события:
        if пред is not None and x > пред:
            if счёт <= допуск:
                if начало is None:
                    начало = пред
            elif начало is not None:
                # Жёлоб от самого левого края — отступ перед таблицей, а не граница
                # (то же правило, что «a == 0» в pdftable._границы).
                if начало > первый and пред - начало >= МИН_ЖЁЛОБ * h:
                    жёлобы.append((начало, пред))
                начало = None
        счёт += d
        пред = x
    # Незакрытый жёлоб у правого края — поле справа от таблицы, тоже не граница.
    return [(a + b) / 2 for a, b in жёлобы]


def _режет(п: list[Слово], границы: list[float]) -> bool:
    """Поле пересекает границу колонки — значит это проза поперёк таблицы."""
    x0, x1 = п[0].x, max(с.r for с in п)
    return any(x0 < g < x1 for g in границы)


def _мин(слова: list[Слово]) -> float | None:
    значения = [с.conf for с in слова if с.conf >= 0]
    return min(значения) if значения else None


def _разложить(ряды: list[list[list[Слово]]], границы: list[float],
               в_блоке: list[bool]) -> tuple[list[list[str]], list[list[float | None]]]:
    колонок = len(границы) + 1
    rows, conf = [], []
    for поля, табличная in zip(ряды, в_блоке):
        if not табличная and any(_режет(п, границы) for п in поля):
            # ПРОЗУ ПО КОЛОНКАМ НЕ РЕЖЕМ — та же ловушка 3, что в pdftable:
            # «Условия поставки: DAP Москва. Оплата 100%» под границы не ложится,
            # и разрез дал бы обрывки, из которых разбор сделает выдуманную позицию.
            # Строка идёт одной ячейкой.
            слова = [с for п in поля for с in п]
            rows.append([" ".join(с.text for с in слова)] + [""] * (колонок - 1))
            conf.append([_мин(слова)] + [None] * (колонок - 1))
            continue
        # Строка таблицы или продолжение (перенос наименования, строка «Итого» под
        # колонкой суммы): каждое слово — в колонку своего центра. По центру, а не
        # по краю: цифры выровнены вправо, текст влево, и край слова на границе
        # колонки при свисающей шапке отрезал бы слово не туда.
        ячейки: list[list[Слово]] = [[] for _ in range(колонок)]
        for п in поля:
            for с in п:
                ячейки[bisect_left(границы, с.cx)].append(с)
        rows.append([" ".join(с.text for с in я) for я in ячейки])
        conf.append([_мин(я) if я else None for я in ячейки])
    return rows, conf


def _годится(проверка, rows) -> bool:
    try:
        return bool(проверка(rows))
    except Exception:                                                    # noqa: BLE001
        return False


def разобрать_tsv(tsv: str, годится=None) -> Таблица:
    """Вывод `tesseract … tsv` → Таблица. Никогда не бросает.

    годится — проверка вызывающего: rows → bool, та же, что в
    pdftable.строки_в_таблицу. Перебираются ступени ДОПУСКИ, и возвращается
    первый разрез, который проверку прошёл; без проверки — строгая ступень.
    Правильность разреза знает только тот, кто умеет опознать шапку."""
    try:
        return _разобрать(tsv, годится)
    except Exception:                                                    # noqa: BLE001
        return Таблица()


def строки_по_координатам(tsv: str, годится=None) -> list[list[str]]:
    """Вывод `tesseract … tsv` → строки таблицы. Пустой список — таблицы нет."""
    return разобрать_tsv(tsv, годится).rows


def _разобрать(tsv: str, годится) -> Таблица:
    итог = Таблица()
    страницы = []
    все: list[Слово] = []
    for _номер, (слова, размер) in sorted(_страницы(tsv).items()):
        текстовые = [с for с in слова if not с.линейка]
        if not текстовые:
            continue
        угол = _угол(слова)
        if угол:
            W, H = размер or (max(с.r for с in слова), max(с.b for с in слова))
            слова = [_в_прямой_кадр(с, угол, W, H) for с in слова]
            текстовые = [с for с in слова if not с.линейка]
            итог.поворот = итог.поворот or угол
        h = max(1.0, statistics.median(с.h for с in текстовые))
        ряды = [п for п in (_поля(р, h) for р in _ряды(слова, h)) if п]
        страницы.append((ряды, h))
        все.extend(текстовые)
    if not все:
        return итог
    итог.слов = len(все)
    уверенные = [с.conf for с in все if с.conf >= 0]
    итог.средняя = sum(уверенные) / len(уверенные) if уверенные else None
    итог.слабых = sum(1 for c in уверенные if c < ПОРОГ_ДОВЕРИЯ)
    # ТЕКСТ — ПО ВИДИМЫМ СТРОКАМ, поля через два пробела. Две выгоды: в
    # автоматическом режиме колонки больше не идут друг за другом, а количество
    # и цена не склеиваются в одно число — quotes._ТОКЕН берёт пробел в число
    # только одиночный, перед тремя цифрами (разделитель тысяч).
    итог.text = "\n".join("  ".join(" ".join(с.text for с in п) for п in поля)
                          for ряды, _ in страницы for поля in ряды)

    первый = None
    прежние = None
    for допуск in ДОПУСКИ:
        rows: list[list[str]] = []
        conf: list[list[float | None]] = []
        нашлась = False
        for ряды, h in страницы:
            в_блоке = [len(п) >= МИН_КОЛОНОК for п in ряды]
            n = sum(в_блоке)
            границы: list[float] = []
            # Допуск меньше половины блока: жёлоб, занятый половиной строк, — не
            # жёлоб. На двух строках допустим только строгий разрез.
            if n >= МИН_СТРОК_БЛОКА and допуск * 2 < n:
                границы = _границы([п for п, т in zip(ряды, в_блоке) if т], допуск, h)
            if len(границы) + 1 >= МИН_КОЛОНОК:
                нашлась = True
                r, c = _разложить(ряды, границы, в_блоке)
            else:
                r, c = _разложить(ряды, [], [False] * len(ряды))
            rows.extend(r)
            conf.extend(c)
        if not нашлась or rows == прежние:
            continue
        прежние = rows
        ширина = max(len(r) for r in rows)
        rows = [r + [""] * (ширина - len(r)) for r in rows]
        conf = [c + [None] * (ширина - len(c)) for c in conf]
        кандидат = (rows, conf, допуск)
        if годится is None or _годится(годится, rows):
            первый = кандидат
            break
        первый = первый or кандидат
    if первый:
        итог.rows, итог.уверенность, итог.допуск = первый
    return итог


