#!/usr/bin/env python3
"""Что названо в обозначении машины: вид, направление, список моделей.

ЗАЧЕМ. Реестр машин `dict/machine.json` собирается из строкового поля `mach`
баз запчастей. Поле заполняли люди, и в нём лежит вперемешку четыре разных
вещи: модель машины («Taurus 70MD»), узел или деталь этой машины («Фильтр
масляный турбокомпрессора»), несколько машин одной строкой («Taurus 60S,
Taurus 70, Taurus 70MD») и признание, что модель неизвестна («не указана
(вероятно Mars)»). Пока они не разведены, счётчик цепочки
(`data/chain_coverage.json`) считает машинами шкафы и блоки, а настоящие
насосы и электродвигатели не видит вовсе: до 09.10.2026 клетка «Машина» у
направлений «Насосы», «Электротехника и приводы» и «КИПиА» стояла в нуле,
хотя обозначения этих машин в базе есть.

ЧТО РЕШАЕТ ПРАВИЛО. Три вопроса по тексту обозначения, и ничего больше:

    вид          машина      названа модель: обозначение годится в реестр
                 черновик    машина названа, а модели в обозначении нет
                             («Электродвигатель», «Solar Centaur»)
                 не машина   узел, деталь, арматура, расходник или оснастка
                 не опознать ни машины, ни модели («не указана», «Solar (сток)»)
    направление  одно из семи направлений портала, либо «вне» — машина, которую
                 ни одно из них не покрывает (буровое, судовое, котельное)
    модели       составное обозначение разложено на настоящие модели

ЧЕМ МЕРЯЕТСЯ. Ручной эталон `data/machine_truth.json`: все 296 обозначений поля
`mach` размечены руками по тексту, правилом разметка не пользовалась (CLAUDE.md,
правило 1 — эталон не производен от правила). Точность и охват считает
`scripts/machine_segment_check.py`; порог стоит в гейте.

ПОРЯДОК ПРОВЕРОК ЗАКРЫТЫМИ СПИСКАМИ, А НЕ ОБЩИМ ПРАВИЛОМ. Слово машины и слово
детали в одном названии — обычное дело («Фильтр масляный турбокомпрессора»,
«Бумажная вставка центробежного насоса»). Общее правило «есть слово насос —
значит насос» давало 4 ложные машины из 52. Решает ГЛАВНОЕ СЛОВО: в русском
техническом названии оно стоит первым, поэтому из двух совпадений выигрывает
то, которое РАНЬШЕ в строке.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

#: Направления портала (SEGMENTS в scripts/build_chain_coverage.py) плюс «вне».
НАПРАВЛЕНИЯ = ("gtu", "gpu", "gsho", "recip", "pumps", "instrum", "electro")
ВНЕ = "вне"

#: Пометка источника в скобках: она говорит о записи, а не о машине.
ПОМЕТКА = re.compile(r"\s*\((сток|общая|sepoc|по документу|унифиц\w*|разные|все|эпоха|серия|"
                     r"также|генераторный|c-серия|typhoon|tornado|cyclone)[^)]*\)\s*", re.I)

# ─────────────────────────────────────────────────────────────────────────────
# НЕ МАШИНА. Главные слова узлов, деталей, арматуры, расходников и оснастки.
# Список закрытый и мерится эталоном: добавлять в него можно только то, что
# эталон подтверждает. Проверяется по МЕСТУ В СТРОКЕ против списка машин ниже.
НЕ_МАШИНА = re.compile(
    r"кольц|шкаф|клапан|фильтр|прокладк|болт|гайк|труб(?!н\w*\s+ключ)|подшипник|"
    r"уплотн|шланг|кабель|реле|модул|плат|блок|комплект|к-кт|набор|втулк|диск|лопат|"
    r"форсунк|свеч|щуп|масл|смазк|выкл\.|автомат|вставк|запчаст|элемент|картридж|"
    r"наконечник|колпачек|колпачок|патрубок|задвижк|заслонк|кран пробков|дроссель|"
    r"предохранител|варистор|тиристор|транзистор|миниконтактор|переключател|"
    r"контакт|скоба|соединител|разделк|полоск|присадк|нагревател|обогревател|"
    r"подогревател|доводчик|пускорегулирующ|блокиратор|инструмент|подвеск|"
    r"площадк|воронк|элеватор|голока|igbt|фго|катушка|тэн",
    re.I)

# ─────────────────────────────────────────────────────────────────────────────
# МАШИНЫ ПО НАПРАВЛЕНИЯМ. Главное слово → направление. Порядок внутри набора
# значения не имеет: выигрывает то совпадение, которое раньше в строке.
МАШИНЫ: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("pumps", re.compile(r"насос|multitec", re.I)),
    # Электрическая машина и привод. «Привод» без уточнения — буровой верхний
    # привод, поэтому слово само по себе направления не даёт: нужен признак
    # электрической машины или электрического привода арматуры.
    ("electro", re.compile(r"электродвигател|эл\.\s*двигател|вибродвигател|вибромотор|"
                           r"электромотор|мотор установочн|электропривод(?!ом)|"
                           r"электрическ\w*\s+привод|привод\s+электрогидравлическ|"
                           r"\bskc\d", re.I)),
    # КИПиА: прибор — это и есть обслуживаемая единица направления.
    ("instrum", re.compile(r"датчик|преобразователь\s+давлен|контроллер|вольтметр|"
                           r"генератор\s+импульсов", re.I)),
    ("gpu", re.compile(r"\bгпу\b|jenbacher|waukesha|\bmwm\b|газопоршнев", re.I)),
    # ГТУ: семейства турбин.
    # ЗАМЫКАЮЩЕГО \b У СЕМЕЙСТВ НЕТ НАМЕРЕННО: в LM2500 граница после «LM2» не
    # наступает, и с ней правило молча теряет самые массовые машины базы — 09.10.2026
    # я вернул эту границу и потерял LM2500 с LM6000, 5 425 строк. Слова, которым
    # граница нужна (tay, t56, solar), стоят отдельной частью, со своей \b.
    ("gtu", re.compile(r"\b(lms[\s-]*\d|lm[\s-]*\d|sgt|taurus|centaur|mars|titan|saturn|avon|olympus|"
                       r"spey|proteus|tyne|coberra|rb[\s-]*\d|frame[\s-]*\d|ms\d{4}|ta\d{4}|tb\d{4}|"
                       r"gt\d{1,2}|v\d{2}\.|трент|trent|garrett|kg2|газотурбин)"
                       r"|\b(solar|tay|t\d{2})\b", re.I)),
)

# МАШИНА БЕЗ НАПРАВЛЕНИЯ: буровое, портовое, котельное, судовое. Клетку цепочки
# она не заполняет, но машиной быть не перестаёт. Проверяется ПОСЛЕДНИМ и только
# если ни одно направление не нашлось: 09.10.2026 это стоило двух ошибок —
# «центробежный компрессор Solar» уходил в «вне», потому что слово «компрессор»
# стоит раньше бренда, хотя бренд и называет направление. Направление важнее
# места в строке; «вне» — это признание, что направления нет.
МАШИНА_ВНЕ = (
    (ВНЕ, re.compile(r"превентор|вентилятор|лебедк|лебёдк|станци|опреснит|агрегат|"
                     r"верхний\s+привод|силовая\s+установк|перемешиват|центрифуг|"
                     r"вибросито|ситогидроциклон|дивертер|котел|котёл|компрессор|"
                     r"трубн\w*\s+ключ|ключ\s+трубн|кран\s+мостов|система\s+перемещен|"
                     r"liebherr|liebher|rollgriss|teminox|compressor|blower|winch", re.I)),
)

# ─────────────────────────────────────────────────────────────────────────────
# ЧТО НЕ НАЗЫВАЕТ НИЧЕГО. Закрытый список: обозначение, в котором нет ни машины,
# ни модели. Это не «правило не сработало», а записанное признание, что модель
# неизвестна, либо складская корзина бренда.
НЕ_ОПОЗНАТЬ = re.compile(r"^(не указана|пакетн|solar\s*(\(|пакет)|vision$|питающ|"
                         r"\d[A-Z]{2},)", re.I)

#: Оговорка в записи: «вероятно Mars» — догадка, а не знание, и направления она
#: не даёт. Две разные семьи в скобках («Centaur/Taurus», «каталог Saturn–Mars»)
#: — тоже не знание: пока не выбрано одно, опознания нет.
ДОГАДКА = re.compile(r"вероятн|предположительн|возможн|\bили\b", re.I)

#: ОДИН БРЕНД И НИЧЕГО БОЛЬШЕ — складская корзина, а не машина. «Solar (сток)»
#: после снятия пометки остаётся словом «Solar»: это ярлык партии, модели в нём
#: нет. Бренд рядом с семейством или видом машины — другое дело («Solar Centaur»,
#: «Solar COMPRESSOR»): там машина названа, не названа только модель.
БРЕНД_ОДИН = re.compile(r"^(solar|ge|siemens|rolls-?royce|abb|пакет\w*)$", re.I)
СЕМЕЙСТВО = re.compile(r"\b(taurus|centaur|mars|titan|saturn|avon|olympus|spey|sgt|"
                       r"frame|lm\d|lms\d|tb\d{4}|ta\d{4})", re.I)
#: То же семейство вместе с номером исполнения, если он назван рядом: из
#: «не указана (Centaur 50 по серии 196xxx)» в реестр идёт «Centaur 50».
СЕМЕЙСТВО_С_НОМЕРОМ = re.compile(СЕМЕЙСТВО.pattern + r"(\s*-?\s*\d+[A-Za-z]*)?", re.I)

# СЕМЕЙСТВО ИЛИ МОДЕЛЬ. «Saturn» — семейство, у него есть Saturn 20; «Spey» —
# одна машина, и номера у неё нет. Без этого различения «Rolls-Royce Spey»
# считался черновиком, а он полноценная модель (замер 09.10.2026: 3 ошибки).
ОДНОМОДЕЛЬНЫЕ = re.compile(r"\b(olympus|spey|proteus|tyne|tay|t\d{2}|trent|трент|"
                           r"coberra|kg2)\b", re.I)

#: Модель названа: код с цифрой при буквах, либо семейство с номером. РАЗМЕР
#: моделью не считается: «8Х6Х14» и «5x6» — это дюймы рабочего колеса, а
#: «1,2 KW; 705r/min» — мощность и обороты, и ни то ни другое не обозначение.
МОДЕЛЬ = re.compile(r"[A-Za-zА-Яа-я][-\s]?\d|\d{2,}[A-Za-z]|\b\d{2,}\b")
# Число снимается ВМЕСТЕ с единицей: «705r/min» — это обороты, а не обозначение.
# Латинская одиночная «a» (ампер) в список НЕ входит: она съела бы хвост
# обозначения — «V94.3A» превратилось бы в «V». Вольты и герцы безопасны.
ЕДИНИЦЫ = re.compile(r"\d+(?:[.,]\d+)?\s*(?:kw|квт|r/?min|об/мин|psi|hp|л\.с\.|"
                     r"кгс|бар|bar|мм|mm|шт|в|гц|hz|ква|kva|va|v)\b", re.I)
РАЗМЕР_В_СТРОКЕ = re.compile(r"\b\d{1,2}\s*[xXхХ]\s*\d{1,2}(\s*[xXхХ]\s*\d{1,3})?\b")

#: Разделители составного обозначения: «A, B», «A / B» (с пробелами), «A и B».
#: Косая БЕЗ ПРОБЕЛОВ сама по себе разделителем НЕ считается: она чаще входит в
#: код, чем делит его — «Pompetravaini TCH TRSA 200-2500/C/SX» разваливалось на
#: три машины, «AC/DC 24V» обрезалось до «AC», «Multitec V50/8A-4.1 20.181» — до
#: «Multitec V50». Условия, при которых она всё же делит, — в _по_косой.
# Запятая МЕЖДУ ЦИФРАМИ — десятичная, а не разделитель: «1,2 KW» не две части.
# 09.10.2026 из-за этого «Эл. двигатель … 1,2 KW; 705r/min» дробился так, что
# «1» оставалась в первой части и выглядела обозначением модели.
РАЗДЕЛИТЕЛЬ = re.compile(r"(?<!\d)\s*,\s*|\s*,\s*(?!\d)|\s+/\s+|\s+и\s+")
РУССКОЕ_СЛОВО = re.compile(r"[а-яё]{3,}")


@dataclass(frozen=True)
class Разбор:
    """Что правило вычитало из обозначения."""
    вид: str                 # машина · черновик · не машина · не опознать
    направление: str = ""    # одно из НАПРАВЛЕНИЯ, либо ВНЕ, либо пусто
    модели: tuple[str, ...] = field(default_factory=tuple)


def основа(обозначение) -> str:
    """Обозначение без пометки источника и без хвостовой пунктуации."""
    т = ПОМЕТКА.sub(" ", str(обозначение or ""))
    return re.sub(r"\s{2,}", " ", т).strip(" ,.;")


def _направление(т: str) -> tuple[str, int]:
    """Направление по ГЛАВНОМУ слову: побеждает совпадение раньше в строке.

    Сначала — семь направлений портала; «вне» берётся только если ни одно из
    них не нашлось (см. МАШИНА_ВНЕ).
    """
    лучшее, где = "", 10**6
    for напр, rx in МАШИНЫ:
        м = rx.search(т)
        if м and м.start() < где:
            лучшее, где = напр, м.start()
    if лучшее:
        return лучшее, где
    for напр, rx in МАШИНА_ВНЕ:
        м = rx.search(т)
        if м:
            return напр, м.start()
    return "", 10**6


def _модель_названа(т: str) -> bool:
    """Есть ли в обозначении обозначение модели, а не только вид машины.

    Считается по ЦЕЛОЙ строке, а не по отдельным словам: в «GE Frame 6B» номер
    стоит отдельным словом от семейства, и построчная проверка его теряла
    (замер 09.10.2026 — 3 ошибки). Размеры и величины с единицами снимаются
    заранее: дюймы колеса и обороты обозначением модели не являются.
    """
    хвост = РАЗМЕР_В_СТРОКЕ.sub(" ", ЕДИНИЦЫ.sub(" ", т))
    if ОДНОМОДЕЛЬНЫЕ.search(хвост):
        return True
    return bool(МОДЕЛЬ.search(хвост))


#: Приставка обозначения — всё до его последней числовой части. Нужна, чтобы
#: дописать сокращённую вторую половину: «Taurus 70/70MD» — это Taurus 70 и
#: Taurus 70MD, а не Taurus 70 и машина с именем «70MD».
ПРИСТАВКА = re.compile(r"^(.*?[A-Za-zА-Яа-я][\s-]*)\d[\dA-Za-zА-Яа-я./-]*$")


#: СОКРАЩЁННАЯ ПОЛОВИНА составного обозначения: голое число с буквенным хвостом
#: и ничего больше — «70MD», «800», «1534», «6». Знаки внутри (точка, дефис)
#: означают, что это продолжение КОДА, а не братская модель: 09.10.2026 без
#: этого «Multitec V50/8A-4.1» делилось на «Multitec V50» и выдуманный
#: «Multitec V8A-4.1», которого не существует (V50/8 — число ступеней насоса KSB).
СОКРАЩЕНИЕ = re.compile(r"^\d{1,5}[A-Za-zА-Яа-я]{0,3}$")


def _по_косой(ч: str) -> list[str]:
    """Косая без пробелов делит только БРАТСКИЕ обозначения.

    Братское — либо короткое сокращение из одного слова, начинающееся с цифры
    («Taurus 70/70MD», «SGT-400/800», «GE Frame 5/6»), либо самостоятельное
    обозначение машины («Saturn/Centaur»). Всё прочее — часть кода, и делить её
    нельзя. Вдобавок правило вообще не применяется там, где есть русское слово:
    в русском названии косая почти всегда внутри кода изготовителя.
    """
    if "/" not in ч:
        return [ч]
    куски = [к.strip() for к in ч.split("/") if к.strip()]
    if len(куски) < 2:
        return [ч]
    for к in куски[1:]:
        if not (СОКРАЩЕНИЕ.match(к) or _направление(к)[0]):
            return [ч]
    return куски


def _модели(т: str) -> tuple[str, ...]:
    """Составное обозначение — списком моделей; одиночное — самим собой.

    Части, которые сами машины не называют (шкаф, блок), выбрасываются: строка
    «Taurus 70, Шкаф управления PMS МЛСПК» — это одна машина, а не две.
    Сокращённая часть дополняется приставкой первой: «SGT-400/800» — это
    SGT-400 и SGT-800.
    """
    части = [ч.strip(" ,.;") for ч in РАЗДЕЛИТЕЛЬ.split(т) if ч.strip(" ,.;")]
    if not РУССКОЕ_СЛОВО.search(т):
        части = [к for ч in части for к in _по_косой(ч)]
    if len(части) < 2:
        return (т,) if т else ()
    годные: list[str] = []
    приставка = ""
    for ч in части:
        н, где_м = _направление(ч)
        м_нет = НЕ_МАШИНА.search(ч)
        if м_нет is not None and не_машина_раньше(м_нет, где_м, ч):
            continue
        # Сокращение — короткая часть из одного слова, начинающаяся с цифры
        # («70MD», «800», «1534»). «2800 N» сокращением не является: с пробелом
        # внутри приставка дописывалась к величине и рождала «SIEMENS SKC2800 N».
        if not н and приставка and ч[:1].isdigit() and len(ч) <= 8 and " " not in ч:
            ч, н = приставка + ч, _направление(приставка + ч)[0]
        if н and ч not in годные:
            годные.append(ч)
            if not приставка and (м := ПРИСТАВКА.match(ч)):
                приставка = м.group(1)
    # ЧАСТЬ БЕЗ МОДЕЛИ ОТБРАСЫВАЕТСЯ, ЕСЛИ МОДЕЛЬ ЕСТЬ В ДРУГОЙ ЧАСТИ. Строка
    # «Вакуумный насос Pompetravaini TCH TRSA 200-2500/C/SX, Насос подпитки
    # деаэратора» называет ОДНУ машину двумя ролями, а не две машины: вторая
    # часть — это назначение, модели в ней нет. Но если модели нет НИ У ОДНОЙ
    # части («Saturn/Centaur»), остаются обе: это два семейства.
    с_моделью = [ч for ч in годные if _модель_названа(ч)]
    if с_моделью and len(с_моделью) < len(годные):
        # ...но часть, называющая СВОЁ семейство, остаётся: «Saturn/Centaur 40» —
        # это Saturn и Centaur 40, а не один Centaur 40. Выбрасывается только
        # голый вид машины («…, Насос подпитки деаэратора» — это назначение).
        годные = [ч for ч in годные if _модель_названа(ч) or СЕМЕЙСТВО.search(ч)]
    return tuple(годные) if годные else (т,)


#: Окончания русского прилагательного. «Масляный насос» — насос, а не масло:
#: слово детали здесь ОПРЕДЕЛЕНИЕ, а главное слово всё равно второе. Без этой
#: проверки 09.10.2026 «Масляный насос MPC 320-100» и «Кабельный насос» уходили
#: в «не машина» — посылка «главное слово первое» на прилагательном не работает.
ПРИЛАГАТЕЛЬНОЕ = re.compile(r"(ый|ий|ой|ая|яя|ое|ее|ые|ие|ого|его|ому|ему|ым|им|"
                            r"ую|юю|ой|ей|ых|их|ым|им)$", re.I)


def _слово_в(т: str, где: int) -> str:
    """Слово строки, внутрь которого попало совпадение на позиции `где`."""
    левее = т.rfind(" ", 0, где) + 1
    правее = т.find(" ", где)
    return т[левее:правее if правее != -1 else len(т)].strip(" ,.;()\"'»«")


def не_машина_раньше(м_нет: re.Match[str], где_машины: int, т: str = "") -> bool:
    """Слово детали стоит раньше слова машины — значит названа деталь.

    Кроме случая, когда это слово — прилагательное при слове машины: тогда оно
    определение, а не главное слово («Масляный насос», «Кабельный насос»).
    """
    if м_нет.start() >= где_машины:
        return False
    if т and где_машины < 10**6:
        слово = _слово_в(т, м_нет.start())
        if ПРИЛАГАТЕЛЬНОЕ.search(слово):
            # прилагательное машину не отменяет; решает следующее слово детали
            далее = НЕ_МАШИНА.search(т, м_нет.end())
            return далее is not None and далее.start() < где_машины
    return True


def разобрать(обозначение) -> Разбор:
    """Вид, направление и модели одного обозначения поля `mach`."""
    т = основа(обозначение)
    if not т:
        return Разбор("не опознать")
    if БРЕНД_ОДИН.match(т):
        return Разбор("не опознать")
    # ДОГАДКА СПРАШИВАЕТСЯ ДО ВСЕГО ОСТАЛЬНОГО. 09.10.2026 она проверялась только
    # внутри ветки «не указана», и «Centaur 40 или Centaur 50» становилось
    # МАШИНОЙ с таким именем: пока не выбрано одно, опознания нет.
    if ДОГАДКА.search(т):
        return Разбор("не опознать")
    if НЕ_ОПОЗНАТЬ.match(т):
        # «не указана (Centaur 50 по серии …)» — модель всё же выведена по
        # серии, но не названа в поле: это черновик направления, не машина.
        # «вероятно Mars» и «Centaur/Taurus» опознанием не считаются.
        # Внутри «не указана (…)» требуется РОВНО ОДНО семейство: две семьи в
        # скобках («Centaur/Taurus», «каталог Saturn–Mars») опознанием не
        # считаются. Снаружи это требование неверно — «TA1750 / TB5000» честно
        # называет две машины, — поэтому оно и стоит только здесь.
        семей = {м.group(0).lower() for м in СЕМЕЙСТВО.finditer(т)}
        if len(семей) != 1:
            return Разбор("не опознать")
        напр, _ = _направление(т)
        if not напр:
            return Разбор("не опознать")
        м = СЕМЕЙСТВО_С_НОМЕРОМ.search(т)
        return Разбор("черновик", напр, (м.group(0).strip(),) if м else ())
    напр, где_машины = _направление(т)
    м_нет = НЕ_МАШИНА.search(т)
    if м_нет is not None and не_машина_раньше(м_нет, где_машины, т):
        return Разбор("не машина")
    if not напр:
        return Разбор("не машина") if м_нет else Разбор("не опознать")
    # ВИД СЧИТАЕТСЯ ПО ТЕМ ЖЕ ЧАСТЯМ, ЧТО ПОПАЛИ В «МОДЕЛИ», а не по целой
    # строке. 09.10.2026: «Электродвигатель, Шкаф управления PMS МЛСК Ф-1»
    # считался МАШИНОЙ — модель нашлась в шкафу, который сам в список моделей
    # не попал. Список считается и для черновика: «Saturn/Centaur» — это два
    # семейства, и реестру нужны оба, пусть и без номера исполнения.
    модели = _модели(т)
    вид = "машина" if any(_модель_названа(м) for м in модели) else "черновик"
    return Разбор(вид, напр, модели)
