"""Справочник промышленных материалов dict/material.json: поиск в тексте и суждение о ячейке.

ЗАЧЕМ. 24.09.2026 марка нержавеющей стали «SS316» показывалась кодом детали и
брендом: система не знала, что это материал. То же ждёт PTFE, Viton, 12Х18Н10Т,
БрАЖ9-4, ВК8 — всё, из чего делают запчасти. Справочник — закрытый список
написаний материалов (рус/лат, марки ГОСТ/AISI/EN/UNS, торговые названия
материалов), и этот модуль — единственный его читатель:

  · материал_в_тексте(строка) — какие материалы упомянуты и где;
  · ячейка_материал(ячейка) — ячейка целиком говорит о материале («Viton»,
    «AISI 316L», «Сталь 40Х»), а значит, это не код и не бренд;
  · марка_ли(токен) — токен кода целиком совпал с обозначением материала
    (library/docfilter.part_number_of: «ВТ1-0» — марка титана, а не артикул);
  · выражение_не_кода() — фрагменты класса «марка» правила правдоподобия кода
    (docfilter.ВЫРАЖЕНИЕ_НЕ_КОДА, двойник lib_pn_plausible в schema.sql).

ОБВИНЯЕТ ТОЛЬКО ЗАКРЫТЫЙ СПИСОК, ЗАЩИЩАЕТ ЩЕДРО (CLAUDE.md, правило 7):
  · написание ищется с границами токена: до и после не буква и не цифра, а
    дефис, точка и косая допустимы только перед пробелом или знаком, — так
    «PA» в «PA-100» и «СЧ» внутри «ПСЧ20» не находятся;
  · короткие аббревиатуры (PA, PP, PE, CR, ПП, СЧ), голые числа (316, 6061,
    625) и номера EN (1.4301) помечены context: такое написание — материал,
    только если ячейка — оно целиком (кроме числа: голое число материалом не
    бывает никогда) или рядом стоит слово материала: «сталь», «материал»,
    «из», «Shore», другой найденный материал через «/» или «+»;
  · название материала по-русски склоняется: «фторопласта», «латунный».

СВЁРТКА. Регистр, «ё» → «е» и латиница, похожая на кириллицу, → кириллица:
«12X18H10T», набранный латиницей, — тот же 12Х18Н10Т. Свёртка знак в знак,
поэтому позиции в свёрнутой строке — позиции в исходной.

Модуль на одной стандартной библиотеке: его импортирует docfilter, а тот —
тесты гейта без psycopg2 и requests.
"""
from __future__ import annotations

import functools
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ФАЙЛ = "dict/material.json"

# Латиница, похожая на кириллицу (строчные после lower()).
_ЛАТ_В_КИР = str.maketrans("abcehkmoptxy", "авсенкмортху")
_БУКВА = "0-9a-zа-я"


def свернуть(s) -> str:
    """Свёртка знак в знак: длина та же, позиции совпадают."""
    out = []
    for ч in str(s or ""):
        н = ч.lower()
        out.append(н if len(н) == 1 else ч)
    return "".join(out).replace("ё", "е").translate(_ЛАТ_В_КИР)


def ключ(s) -> str:
    """Ключ написания для сравнения токена целиком: свёртка и только буквы и цифры."""
    return re.sub(rf"[^{_БУКВА}]", "", свернуть(s))


@functools.lru_cache(maxsize=1)
def справочник() -> dict:
    return json.loads((ROOT / ФАЙЛ).read_text(encoding="utf-8"))


@functools.lru_cache(maxsize=1)
def записи() -> dict[str, dict]:
    return {r["key"]: r for r in справочник()["records"]}


# ── Выражение написания ──────────────────────────────────────────────────────

_РАЗД = r"[\s\-.]?"
# До написания: не буква/цифра, и не «буква-дефис» (хвост кода «KV-PTFE»).
# Косая после буквы допустима: «NBR/CR» — перечисление материалов.
_ДО = rf"(?<![{_БУКВА}])(?<![{_БУКВА}][\-.])(?<![0-9]/)"
# После: не буква/цифра, и не дефис/точка/косая перед буквой или цифрой
# («PA-100», «SS316-4417»); косая перед буквой — перечисление материалов
# («NBR/PTFE»), она допустима.
_ПОСЛЕ = rf"(?![{_БУКВА}])(?![\-.][{_БУКВА}])(?!/[0-9])"
_ОКОНЧАНИЕ = re.compile(r"[аяоеыийьую]{1,2}$")


def _слово(w: str, склонять: bool) -> str:
    """Выражение одного слова написания: разделитель между буквой и цифрой
    необязателен («SS 316», «SS-316»), русское слово от пяти букв склоняется."""
    if склонять and re.fullmatch(r"[а-я]{5,}", w):
        основа = _ОКОНЧАНИЕ.sub("", w)
        if len(основа) >= 4:
            return re.escape(основа) + "[а-я]{0,4}"
    out = []
    пред = ""
    for ч in w:
        if ч in " -.":
            if out and out[-1] != _РАЗД:
                out.append(_РАЗД)
            пред = ""
            continue
        if пред and ((пред.isdigit() and ч.isalpha()) or (пред.isalpha() and ч.isdigit())):
            out.append(_РАЗД)
        out.append(re.escape(ч))
        пред = ч
    return "".join(out)


def выражение_написания(text: str, вид: str) -> str:
    t = свернуть(text).strip()
    склонять = вид == "название"
    слова = t.split()
    тело = r"\s+".join(_слово(w, склонять) for w in слова)
    return _ДО + "(" + тело + ")" + _ПОСЛЕ


@functools.lru_cache(maxsize=1)
def _написания() -> list[tuple]:
    """(ключ записи, написание, вид, контекст, компания, число, выражение)."""
    out = []
    for r in справочник()["records"]:
        for s in r["spellings"]:
            t = s["text"]
            число = bool(re.fullmatch(r"[0-9.,\-]+", t))
            out.append((r["key"], t, s["kind"], bool(s.get("context")), bool(s.get("also_company")),
                        число, re.compile(выражение_написания(t, s["kind"]))))
    # Длинное — вперёд: при перекрытии побеждает более полное написание.
    out.sort(key=lambda x: -len(x[1]))
    return out


@functools.lru_cache(maxsize=1)
def _якоря() -> list[str]:
    """Подстрока, без которой написание не найдётся: первый однородный отрезок
    (только буквы или только цифры) свёрнутого написания, не длиннее трёх знаков.
    Разделители выражение вставляет лишь между отрезками, склонение меняет
    окончание, а не начало, — поэтому проверка подстроки ничего не теряет, а
    отсекает почти все выражения до поиска."""
    out = []
    for _k, t, *_ in _написания():
        m = re.search(r"[0-9]+|[a-zа-я]+", свернуть(t))
        out.append(m.group(0)[:3] if m else "")
    return out


# ── Контекст для коротких написаний ──────────────────────────────────────────

_СЛОВА_КОНТЕКСТА = (
    "материал", "мат.", "mat.", "material", "марка", "марки", "grade", "gr.", "сталь", "стали", "стальн",
    "steel", "нерж", "stainless", "inox", "сплав", "alloy", "полимер", "пластик", "plastic", "резин", "rubber",
    "эластомер", "elastomer", "каучук", "чугун", "iron", "бронз", "латун", "алюмин", "титан", "titan",
    "масло", "oil", "смазк", "из", "werkstoff", "w.-nr", "w.nr", "wnr", "din", "en", "aisi", "astm", "гост",
    "класс", "class", "shore", "шор",
)
# Короткое слово (до трёх знаков) — только целым словом: «из», но не «изделие».
_КОНТЕКСТ_ДО = re.compile(
    rf"(?<![{_БУКВА}])(" + "|".join(
        re.escape(свернуть(w)) + (rf"(?![{_БУКВА}])" if len(w.rstrip(".")) <= 3 else "")
        for w in _СЛОВА_КОНТЕКСТА) + r")")
_ТВЁРДОСТЬ_ПОСЛЕ = re.compile(r"^[\s\-]*\d{2}\s*(шор|shore|sh|ед|°)", re.I)
_ОКНО = 24


def _контекст(св: str, нач: int, кон: int, найденные: list[tuple[int, int]]) -> bool:
    окно = св[max(0, нач - _ОКНО):нач]
    if _КОНТЕКСТ_ДО.search(окно):
        return True
    if _ТВЁРДОСТЬ_ПОСЛЕ.match(свернуть(св[кон:кон + 16])):
        return True
    # Рядом другой материал через «/», «+», «,»: «NBR/CR», «PTFE+PP».
    for a, b in найденные:
        if 0 <= нач - b <= 3 and re.fullmatch(r"\s*[/+,]\s*", св[b:нач]):
            return True
        if 0 <= a - кон <= 3 and re.fullmatch(r"\s*[/+,]\s*", св[кон:a]):
            return True
    return False


def материал_в_тексте(строка) -> list[dict]:
    """Материалы, упомянутые в строке: [{key, spelling, text, kind, start, end, context}].

    spelling — написание справочника, text — как написано в строке, start/end —
    позиция в исходной строке. Перекрытия не бывает: побеждает более длинное."""
    исходная = str(строка or "")
    if not исходная.strip():
        return []
    св = свернуть(исходная)
    кандидаты = []
    for (k, t, вид, ctx, _комп, число, rx), якорь in zip(_написания(), _якоря()):
        if якорь not in св:
            continue
        for m in rx.finditer(св):
            кандидаты.append((m.start(1), m.end(1), k, t, вид, ctx, число))
    # Сначала без контекста — они сами служат контекстом соседям.
    занято: list[tuple[int, int]] = []
    итог = []

    def свободно(a, b):
        return all(b <= x or a >= y for x, y in занято)

    for нач, кон, k, t, вид, ctx, число in sorted(кандидаты, key=lambda x: (x[5], -(x[1] - x[0]), x[0])):
        if not свободно(нач, кон):
            continue
        if ctx and not _контекст(св, нач, кон, занято):
            continue
        занято.append((нач, кон))
        итог.append({"key": k, "spelling": t, "text": исходная[нач:кон], "kind": вид,
                     "start": нач, "end": кон, "context": ctx})
    итог.sort(key=lambda x: x["start"])
    return итог


# ── Ячейка целиком и токен кода ──────────────────────────────────────────────

# Слова, которые в ячейке материала допустимы вокруг самой марки: «Сталь 40Х»,
# «Материал: PTFE», «нерж. AISI 316L», «резина NBR», «ГОСТ 5632».
# Выражение строится из свёрнутых слов: ячейка судится после свёртки, и
# латинское «steel» в ней уже «sтееl».
_СЛОВА_ОБВЯЗКИ = ("материал[а-я]*", "мат", "mat", "material", "марк[а-я]*", "сталь", "стали", "steel",
                  "нерж[а-я]*", "stainless", "сплав", "alloy", "резин[а-я]*", "rubber", "пластик", "plastic",
                  "из", "of", "type", "тип", "grade", "gr")
_СТАНДАРТЫ_ОБВЯЗКИ = ("гост", "ост", "ту", "din", "en", "iso", "astm", "asme", "aisi", "jis", "uns")
_ОБВЯЗКА = re.compile(
    rf"(?<![{_БУКВА}])(" + "|".join(свернуть(w) for w in _СЛОВА_ОБВЯЗКИ)
    + "|(" + "|".join(свернуть(w) for w in _СТАНДАРТЫ_ОБВЯЗКИ) + rf")\s*[{_БУКВА}.\-/:]*"
    + rf")(?![{_БУКВА}])")


@functools.lru_cache(maxsize=1)
def _ключи_ячейки() -> dict[str, list[tuple]]:
    """Ключ написания → [(ключ записи, вид, компания, контекст)] для ячейки целиком.

    Голое число (316, 6061, 1.4301) ячейкой-материалом не бывает никогда."""
    out: dict[str, list[tuple]] = {}
    for k, t, вид, ctx, комп, число, _rx in _написания():
        if число:
            continue
        кл = ключ(t)
        if len(кл) >= 2:
            out.setdefault(кл, []).append((k, вид, комп, ctx))
    return out


def ячейка_материал(ячейка, *, компании_тоже: bool = False, короткие: bool = True) -> dict | None:
    """Ячейка целиком говорит о материале → {key, spelling, kind}; иначе None.

    Ячейка — материал, если после снятия слов обвязки («сталь», «материал:»,
    «ГОСТ 5632») в ней не остаётся ничего, кроме найденных материалов и
    разделителей. «Stellite» — и материал, и имя компании: по умолчанию такое
    написание ячейку не обвиняет (компании_тоже=False).

    короткие=False — для суда над брендом: написание с пометкой context («TC»,
    «PC», «CR», «SS») ячейку не обвиняет, потому что так же пишут сокращённое
    имя компании. Защищай щедро (правило 7): бренд, принятый за материал,
    пропадает со страницы, а материал, принятый за бренд, виден числом."""
    t = str(ячейка or "").strip()
    if not t:
        return None
    кк = _ключи_ячейки().get(ключ(t))
    if кк:
        годные = [x for x in кк if (компании_тоже or not x[2]) and (короткие or not x[3])]
        if not годные:
            return None
        k, вид, _, _ = годные[0]
        return {"key": k, "spelling": t, "kind": вид}
    найдено = материал_в_тексте(t)
    if not найдено:
        return None
    if not компании_тоже and any(_компания(x) for x in найдено):
        return None
    if not короткие and any(x["context"] for x in найдено):
        return None
    св = list(свернуть(t))
    for x in найдено:
        for i in range(x["start"], x["end"]):
            св[i] = " "
    остаток = _ОБВЯЗКА.sub(" ", "".join(св))
    if re.search(rf"[{_БУКВА}]", остаток):
        return None
    x = найдено[0]
    return {"key": x["key"], "spelling": x["text"], "kind": x["kind"]}


def _компания(найденное: dict) -> bool:
    for k, t, _вид, _ctx, комп, _ч, _rx in _написания():
        if комп and k == найденное["key"] and ключ(t) == ключ(найденное["text"]):
            return True
    return False


@functools.lru_cache(maxsize=1)
def _ключи_марок() -> frozenset:
    """Ключи обозначений, по которым токен кода целиком — марка материала.

    Только написания без пометки context и с цифрой: токен кода без цифры кодом
    и так не выбирается (docfilter.part_number_of), а короткое или числовое
    написание обвинять код не может."""
    out = set()
    for _k, t, _вид, ctx, комп, число, _rx in _написания():
        if ctx or комп or число or not re.search(r"\d", t):
            continue
        кл = ключ(t)
        if len(кл) >= 3:
            out.add(кл)
    return frozenset(out)


def марка_ли(токен) -> bool:
    """Токен целиком — обозначение материала из справочника: «ВТ1-0», «БрАЖ9-4»,
    «PA6», «42CrMo4», «316L». «PA-100», «KV-4417-SS316» — нет."""
    return ключ(токен) in _ключи_марок()


# ── Ключи ячейки изготовителя для запроса /brands ────────────────────────────

_ФОРМЫ_В_НАПИСАНИИ = frozenset(("co", "ао", "ag", "ab", "sa", "kg", "ltd", "inc", "llc", "oy", "nv", "bv",
                                "as", "spa", "srl", "sas", "plc", "gmbh", "ооо", "оао", "зао", "пао", "ип"))


def _ключ_бренда(s: str) -> str:
    """codes_sql.ключ_написания для написаний справочника: у них нет ни
    диакритики, ни правовой формы, поэтому хватает регистра, «ё», отсева знаков и
    кириллических двойников в смешанном ключе. Равенство с настоящим правилом
    сверяет tests/test_materials.py (codes_sql грузит этот модуль раньше, чем
    объявляет ключ_написания)."""
    k = re.sub(r"[^0-9a-zа-я]", "", str(s or "").lower().replace("ё", "е"))[:40]
    if re.search(r"[a-z]", k) and re.search(r"[а-я]", k):
        k = k.translate(str.maketrans("аевкмнорстху", "aebkmhopctxy"))
    return k


@functools.lru_cache(maxsize=1)
def ключи_не_бренда() -> tuple[str, ...]:
    """Ключи написаний, которые ячейкой изготовителя целиком — материал, а не
    бренд: «Viton», «PTFE», «фторопласт», «Inconel». Написания с цифрой не
    нужны — запрос /brands отсевает часть с цифрой и так («есть цифры»); имя,
    которое носит и компания («Stellite»), не обвиняется."""
    out = set()
    for r in справочник()["records"]:
        for s in r["spellings"]:
            t = s["text"]
            if s.get("also_company") or re.search(r"[0-9]", t) or ячейка_материал(t, короткие=False) is None:
                continue
            # Токен правовой формы («WC-Co») ключ_написания снимает — такое
            # написание своим ключом не совпадёт, обвинять им нельзя.
            if set(re.split(r"[^0-9a-zа-яё]+", t.lower())) & _ФОРМЫ_В_НАПИСАНИИ:
                continue
            k = _ключ_бренда(t)
            if len(k) >= 2:
                out.add(k)
    return tuple(sorted(out))


# ── Класс «марка» правила правдоподобия кода ─────────────────────────────────

def фрагменты_не_кода() -> list[str]:
    return [x["pattern"] for x in справочник()["not_a_code"]]


def выражение_не_кода() -> str:
    """Тело класса «марка» docfilter._КЛАССЫ_НЕ_КОДА: фрагменты справочника через «|».
    Выражение вписано в lib_pn_plausible буква в букву — менять фрагменты значит
    менять и schema.sql (сверяет tests/test_code_plausible.py)."""
    return "|".join(фрагменты_не_кода())


# ── Сводка ───────────────────────────────────────────────────────────────────

def сводка() -> dict:
    """Счётчики справочника, как их пишет сам файл: записи и написания по группам и видам."""
    сп = справочник()
    группы = []
    for g in сп["groups"]:
        rr = [r for r in сп["records"] if r["group"] == g["key"]]
        группы.append({"key": g["key"], "title": g["title"], "records": len(rr),
                       "spellings": sum(len(r["spellings"]) for r in rr)})
    виды: dict[str, int] = {}
    for r in сп["records"]:
        for s in r["spellings"]:
            виды[s["kind"]] = виды.get(s["kind"], 0) + 1
    return {"count": len(сп["records"]), "spellings_count": sum(len(r["spellings"]) for r in сп["records"]),
            "by_kind": виды, "groups": группы}
