#: Номера свойств MAPI (MS-OXPROPS), которые нужны читателю.
ТЕМА, ТЕМА_НОРМ = 0x0037, 0x0E1D
ТЕЛО, ТЕЛО_HTML, ТЕЛО_RTF = 0x1000, 0x1013, 0x1009
ОТПРАВЛЕНО, ДОСТАВЛЕНО = 0x0039, 0x0E06
КОДСТРАНИЦА, КОДСТРАНИЦА_ИНТЕРНЕТ = 0x3FFD, 0x3FDE
ОТПРАВИТЕЛЬ = (0x0C1A, 0x0C1F, 0x0042, 0x0065, 0x5D01, 0x5D02)
КОМУ, КОПИЯ = 0x0E04, 0x0E03
ВЛОЖЕНИЕ_ДАННЫЕ, ВЛОЖЕНИЕ_СПОСОБ = 0x3701, 0x3705
