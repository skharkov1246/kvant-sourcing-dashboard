class _Хранилище(int):
    """Номер записи-хранилища в значении свойства типа 000D (объект)."""


def _msg_файл(b: bytes, сбор: _Сбор, глубина: int) -> None:
    try:
        ole = _Ole(b)
    except Exception as e:                                  # noqa: BLE001
        сбор.заметка(f"контейнер OLE не разобран ({type(e).__name__})")
        return
    if not _хранилище_письма(ole, 0):
        сбор.заметка("OLE без потоков Outlook: это книга или документ, а не письмо")
        return
    _msg_письмо(ole, 0, сбор, глубина, шапка=32)


def _msg_фикс(ole: _Ole, дети: dict[str, int], шапка: int) -> dict[int, tuple[int, bytes]]:
    """Свойства фиксированной длины (числа, даты) из потока `__properties_version1.0`.

    У каждого 16 байт: тег (тип в младших двух байтах, номер в старших), флаги,
    значение. Шапка потока: 32 байта у письма верхнего уровня, 24 — у письма во
    вложении, 8 — у вложения и получателя. Ошибись с шапкой — и все свойства
    съедут на полстроки.
    """
    фикс: dict[int, tuple[int, bytes]] = {}
    поток = ole.поток(дети.get("__PROPERTIES_VERSION1.0", -1))
    for п in range(шапка, len(поток) - 15, 16):
        тег = struct.unpack_from("<I", поток, п)[0]
        фикс[тег >> 16] = (тег & 0xFFFF, поток[п + 8:п + 16])
    return фикс


def _msg_перем(ole: _Ole, дети: dict[str, int], кодировка: str) -> dict[int, object]:
    """Свойства переменной длины: каждое — свой поток `__substg1.0_ИИИИТТТТ`.

    Строка 001E (не Юникод) читается в кодовой странице письма, поэтому её надо
    знать ДО этого разбора: она лежит среди фиксированных свойств.
    """
    перем: dict[int, object] = {}
    for имя, номер in дети.items():
        m = re.fullmatch(r"__SUBSTG1\.0_([0-9A-F]{4})([0-9A-F]{4})", имя)
        if not m:
            continue
        ид, тип = int(m.group(1), 16), int(m.group(2), 16)
        if тип == 0x000D:
            if ole.хранилище(номер):
                перем[ид] = _Хранилище(номер)
            continue
        данные = ole.поток(номер)
        if тип == 0x001F:
            перем[ид] = данные.decode("utf-16-le", errors="replace").rstrip("\x00")
        elif тип == 0x001E:
            перем[ид] = данные.rstrip(b"\x00").decode(кодировка, errors="replace")
        elif тип == 0x0102:
            перем[ид] = данные
    return перем


def _фикс_число(фикс: dict[int, tuple[int, bytes]], ид: int) -> int | None:
    if ид not in фикс:
        return None
    тип, значение = фикс[ид]
    if тип in (0x0003, 0x000A):
        return struct.unpack_from("<i", значение)[0]
    if тип in (0x0002, 0x000B):
        return struct.unpack_from("<h", значение)[0]
    if тип in (0x0014, 0x0040):
        return struct.unpack_from("<q", значение)[0]
    return None


def _дата_filetime(ft: int | None) -> str:
    """FILETIME — сотни наносекунд от 1601 года, всемирное время."""
    if not ft or ft <= 0:
        return ""
    try:
        return (dt.datetime(1601, 1, 1) + dt.timedelta(microseconds=ft // 10)).strftime(
            "%Y-%m-%d %H:%M")
    except (OverflowError, ValueError):
        return ""


def _msg_письмо(ole: _Ole, i: int, сбор: _Сбор, глубина: int, шапка: int) -> None:
    дети = ole.дети(i)
    фикс = _msg_фикс(ole, дети, шапка)
    кодировка = _кодек(_фикс_число(фикс, КОДСТРАНИЦА) or _фикс_число(фикс, КОДСТРАНИЦА_ИНТЕРНЕТ))
    перем = _msg_перем(ole, дети, кодировка)
    тема = перем.get(ТЕМА) or перем.get(ТЕМА_НОРМ) or ""
    дата = _дата_filetime(_фикс_число(фикс, ОТПРАВЛЕНО) or _фикс_число(фикс, ДОСТАВЛЕНО))
    получатели = [н for к, н in дети.items() if к.startswith("__RECIP_VERSION1.0_")]
    кому = bool(получатели) or bool(перем.get(КОМУ))
    копия = bool(перем.get(КОПИЯ))
    тело = _msg_тело(перем, фикс, кодировка)
    место = сбор.письмо(глубина, _заголовок(тема) if isinstance(тема, str) else "", дата,
                        any(перем.get(н) for н in ОТПРАВИТЕЛЬ), кому, копия, тело)
    имена = []
    for имя in sorted(к for к in дети if к.startswith("__ATTACH_VERSION1.0_")):
        учтено = _msg_вложение(ole, дети[имя], сбор, глубина, кодировка, bool(тело.strip()))
        if учтено:
            имена.append(учтено)
    if имена:
        сбор.дописать(место, "Вложения: " + "; ".join(dict.fromkeys(имена)))


def _msg_тело(перем: dict[int, object], фикс: dict, кодировка: str) -> str:
    """Тело письма Outlook: простой текст, иначе HTML, иначе сжатый RTF.

    У письма, сохранённого из Outlook, обычно есть все три, но письмо в формате
    RTF (так пишут старые Exchange) несёт тело только в сжатом RTF — без его
    распаковки такое письмо оставалось бы одной темой.
    """
    простой = перем.get(ТЕЛО)
    if isinstance(простой, str) and простой.strip():
        return _норм_текст(простой)
    богатый = перем.get(ТЕЛО_HTML)
    if isinstance(богатый, bytes) and богатый.strip(b"\x00 \r\n"):
        cpid = _фикс_число(фикс, КОДСТРАНИЦА_ИНТЕРНЕТ)
        заявлено = _кодек(cpid) if cpid else _кодировка_html(богатый)
        return _html_в_текст(_декод_байты(богатый.rstrip(b"\x00"), заявлено))
    if isinstance(богатый, str) and богатый.strip():
        return _html_в_текст(богатый)
    сжатый = перем.get(ТЕЛО_RTF)
    if isinstance(сжатый, bytes) and сжатый:
        return _rtf_в_текст(_rtf_распаковать(сжатый), кодировка)
    return ""


def _msg_вложение(ole: _Ole, i: int, сбор: _Сбор, глубина: int, кодировка: str,
                  тело_есть: bool) -> str:
    дети = ole.дети(i)
    фикс = _msg_фикс(ole, дети, 8)
    перем = _msg_перем(ole, дети, кодировка)
    имя = next((перем[н] for н in ВЛОЖЕНИЕ_ИМЕНА if isinstance(перем.get(н), str)
                and перем[н].strip()), "")
    данные = перем.get(ВЛОЖЕНИЕ_ДАННЫЕ)
    способ = _фикс_число(фикс, ВЛОЖЕНИЕ_СПОСОБ)
    if isinstance(данные, _Хранилище):
        if _хранилище_письма(ole, данные):
            # Способ 5: письмо во вложении. Его поток свойств с шапкой 24 байта.
            if сбор.глубже(глубина):
                _msg_письмо(ole, данные, сбор, глубина + 1, шапка=24)
            return ""
        return _ole_объект(ole, данные, имя, сбор, глубина)
    if isinstance(данные, bytes) and данные:
        return сбор.вложение(имя, данные, глубина, тело_есть)
    if способ in (2, 3, 4, 7):
        # Вложение ссылкой: на диск отправителя или в облако. Байтов в письме нет,
        # и это надо видеть числом, а не потерять молча.
        сбор.заметка("вложение ссылкой, самого файла в письме нет")
    return ""


def _ole_объект(ole: _Ole, i: int, имя: str, сбор: _Сбор, глубина: int) -> str:
    """Способ 6: объект OLE, вставленный в тело RTF-письма (книга, PDF, пакет).

    Сам объект — ещё одно хранилище. Готовый файл лежит в одном из трёх потоков:
    `Package` (книга или документ OOXML целиком), `CONTENTS` (так вставляется
    PDF) или `\\x01Ole10Native` (упакованный файл: имя, путь, затем байты).
    """
    дети = ole.дети(i)
    for поток_имя in ("PACKAGE", "CONTENTS"):
        if поток_имя in дети:
            данные = ole.поток(дети[поток_имя])
            if данные:
                return сбор.вложение(имя, данные, глубина)
    if "\x01OLE10NATIVE" in дети:
        имя_внутри, данные = _ole10native(ole.поток(дети["\x01OLE10NATIVE"]))
        if данные:
            return сбор.вложение(имя_внутри or имя, данные, глубина)
    сбор.заметка("вставленный объект OLE без извлекаемого файла")
    return ""


def _ole10native(d: bytes) -> tuple[str, bytes]:
    """Упаковщик объектов Windows: размер, флаги, подпись, путь, ещё путь, байты."""
    try:
        п = 6
        подпись_конец = d.index(b"\x00", п)
        имя = d[п:подпись_конец].decode("cp1251", errors="replace")
        п = d.index(b"\x00", подпись_конец + 1) + 1         # исходный путь
        п += 4                                              # 0x00030000
        длина_пути = struct.unpack_from("<I", d, п)[0]
        п += 4 + длина_пути
        размер = struct.unpack_from("<I", d, п)[0]
        return имя, d[п + 4:п + 4 + размер]
    except (ValueError, struct.error):
        return "", b""


# ───────────────────────────── сжатый RTF (LZFu) ────────────────────────────

#: Начальный словарь сжатого RTF (MS-OXRTFCP 2.1.3.1.1) — 207 байт, одинаковых
#: для всех писем: сжатие ссылается на них с первого байта.
_RTF_СЛОВАРЬ = (
    b"{\\rtf1\\ansi\\mac\\deff0\\deftab720{\\fonttbl;}{\\f0\\fnil \\froman \\fswiss "
    b"\\fmodern \\fscript \\fdecor MS Sans SerifSymbolArialTimes New RomanCourier"
    b"{\\colortbl\\red0\\green0\\blue0\r\n\\par \\pard\\plain\\f0\\fs20\\b\\i\\u\\tab\\tx")


def _rtf_распаковать(b: bytes) -> bytes:
    """Сжатый RTF Outlook в обычный RTF.

    Шапка 16 байт: размер сжатого (от поля «размер» и дальше), размер несжатого,
    вид («LZFu» — сжат, «MELA» — нет), контрольная сумма. Далее управляющий байт на
    восемь элементов: бит 0 — буква как есть, бит 1 — ссылка в кольцевой словарь
    на 4096 байт (12 бит смещения, 4 бита длины минус два). Ссылка на текущую
    позицию записи — конец данных. Контрольная сумма не проверяется: битое письмо
    лучше прочитать частично, чем не прочитать.
    """
    if len(b) < 16:
        return b""
    размер_сж, размер, вид = struct.unpack_from("<III", b, 0)
    данные = b[16:4 + размер_сж] if размер_сж >= 12 else b[16:]
    if вид == 0x414C454D:                                   # «MELA»
        return данные[:размер]
    if вид != 0x75465A4C:                                   # «LZFu»
        return b""
    словарь = bytearray(4096)
    словарь[:len(_RTF_СЛОВАРЬ)] = _RTF_СЛОВАРЬ
    пиш = len(_RTF_СЛОВАРЬ)
    out = bytearray()
    предел = max(размер, 1) * 4 + 1_000_000
    п = 0
    while п < len(данные) and len(out) < предел:
        упр = данные[п]
        п += 1
        for бит in range(8):
            if п >= len(данные):
                return bytes(out)
            if упр & (1 << бит):
                if п + 1 >= len(данные):
                    return bytes(out)
                ссылка = (данные[п] << 8) | данные[п + 1]
                п += 2
                смещ, длина = ссылка >> 4, (ссылка & 0xF) + 2
                if смещ == пиш:
                    return bytes(out)
                for _ in range(длина):
                    c = словарь[смещ]
                    out.append(c)
                    словарь[пиш] = c
                    пиш, смещ = (пиш + 1) & 0xFFF, (смещ + 1) & 0xFFF
            else:
                c = данные[п]
                п += 1
                out.append(c)
                словарь[пиш] = c
                пиш = (пиш + 1) & 0xFFF
    return bytes(out)


#: Группы RTF, в которых нет текста письма: шрифты, цвета, стили, картинки.
_RTF_ПРОПУСК = frozenset((
    "fonttbl", "colortbl", "stylesheet", "info", "pict", "object", "header",
    "footer", "xmlnstbl", "listtable", "listoverridetable", "rsidtbl",
    "generator", "themedata", "colorschememapping", "latentstyles", "datastore",
    "mmathpr", "filetbl", "revtbl", "fldinst", "objdata", "bkmkstart", "bkmkend",
))
_RTF_ЗНАКИ = {"par": "\n", "line": "\n", "row": "\n", "sect": "\n", "page": "\n",
              "tab": "\t", "cell": "\t", "emdash": "—", "endash": "–", "bullet": "•",
              "lquote": "‘", "rquote": "’", "ldblquote": "«", "rdblquote": "»",
              "emspace": " ", "enspace": " "}
_RTF_ЛЕКСЕМА = re.compile(
    r"\\([a-zA-Z]+)(-?\d+)? ?|\\'([0-9a-fA-F]{2})|\\([^a-zA-Z'])|([{}])|([^\\{}\r\n]+)|[\r\n]+")


def _rtf_в_текст(rtf: bytes, кодировка: str = "cp1251") -> str:
    """RTF тела письма в текст, включая HTML, упакованный в RTF.

    Outlook хранит HTML-письмо внутри RTF (MS-OXRTFEX, признак \\fromhtml1):
    исходный HTML лежит в группах {\\*\\htmltag …}, а то, что между \\htmlrtf и
    \\htmlrtf0, — оформление только для RTF, в HTML его не было. Разбор лексемами
    с учётом групп: readers.text_from_rtf для этого не годится — он не знает ни
    \\htmlrtf, ни \\ucN (сколько знаков пропустить после \\uNNNN) и берёт
    кодировку cp1251 всегда, а не из \\ansicpg.
    """
    if not rtf:
        return ""
    s = rtf.decode("latin-1")
    m = re.search(r"\\ansicpg(\d+)", s[:4096])
    if m:
        кодировка = _кодек(int(m.group(1)))
    как_html = "\\fromhtml" in s[:4096]
    out: list[str] = []
    байты = bytearray()
    стек: list[tuple[bool, bool, int]] = []
    пропуск, htmlrtf, uc, сбросить, звезда = False, False, 1, 0, False

    def слить() -> None:
        if байты:
            out.append(bytes(байты).decode(кодировка, errors="replace"))
            байты.clear()

    for л in _RTF_ЛЕКСЕМА.finditer(s):
        слово, число, hexbyte, знак, скобка, текст = л.groups()
        видно = not пропуск and not htmlrtf
        if hexbyte is not None:
            if сбросить:
                сбросить -= 1
            elif видно:
                байты.append(int(hexbyte, 16))
            continue
        слить()
        if скобка == "{":
            стек.append((пропуск, htmlrtf, uc))
            звезда = False
        elif скобка == "}":
            if стек:
                пропуск, htmlrtf, uc = стек.pop()
            звезда = False
        elif слово is not None:
            слово = слово.lower()
            if звезда:
                звезда = False
                if not слово.startswith("htmltag"):
                    пропуск = True
                    continue
            if слово in _RTF_ПРОПУСК:
                пропуск = True
            elif слово == "htmlrtf":
                htmlrtf = число != "0"
            elif слово == "uc" and число:
                uc = max(0, int(число))
            elif слово == "u" and число:
                if видно:
                    out.append(chr(int(число) % 65536))
                сбросить = uc
            elif слово in _RTF_ЗНАКИ and видно:
                out.append(_RTF_ЗНАКИ[слово])
        elif знак is not None:
            if знак == "*":
                звезда = True
            elif видно and знак in "\\{}":
                out.append(знак)
            elif видно and знак == "~":
                out.append(" ")
            elif видно and знак in "\r\n":
                out.append("\n")
        elif текст is not None:
            if сбросить:
                отброс = min(сбросить, len(текст))
                текст, сбросить = текст[отброс:], сбросить - отброс
            if видно and текст:
                # RTF по правилам семибитный, но иные программы пишут кириллицу
                # байтами кодовой страницы прямо в текст, без \'hh.
                out.append(текст.encode("latin-1").decode(кодировка, errors="replace")
                           if not текст.isascii() else текст)
    слить()
    итог = "".join(out)
    return _html_в_текст(итог) if как_html else _норм_текст(итог)


# ────────────────────────────── winmail.dat (TNEF) ──────────────────────────

#: Атрибуты TNEF (MS-OXTNEF 2.1.3.3): полный номер — тип в старших битах.
_TNEF_ТЕМА = 0x00018004
_TNEF_ТЕЛО = 0x0001800C
_TNEF_СВОЙСТВА = 0x00069003
_TNEF_НОВОЕ_ВЛОЖЕНИЕ = 0x00069002
_TNEF_ИМЯ_ВЛОЖЕНИЯ = 0x00018010
_TNEF_ДАННЫЕ_ВЛОЖЕНИЯ = 0x0006800F
_TNEF_СВОЙСТВА_ВЛОЖЕНИЯ = 0x00069005
_TNEF_КОДСТРАНИЦА = 0x00069007

#: Размеры значений фиксированной длины в свойствах MAPI внутри TNEF.
_TNEF_ФИКС = {0x0002: 4, 0x0003: 4, 0x0004: 4, 0x0005: 8, 0x0006: 8, 0x0007: 8,
              0x000A: 4, 0x000B: 4, 0x0014: 8, 0x0040: 8, 0x0048: 16}
_TNEF_ПЕРЕМ = (0x001E, 0x001F, 0x0102, 0x000D)


def _tnef(b: bytes, сбор: _Сбор, глубина: int, тело_есть: bool) -> list[str]:
    """winmail.dat: упаковка Outlook, в которой лежат настоящие вложения.

    Outlook, отправляя письмо в формате RTF, кладёт вложения не частями MIME, а
    внутрь одного файла winmail.dat. Без его раскрытия КП в PDF, приложенное к
    такому письму, не видно вовсе: снаружи есть только непонятный «.dat».

    Тело из TNEF берётся, только если у письма снаружи тела нет (`тело_есть`):
    обычно там тот же текст, что и в простой части MIME, и взятый дважды он
    задвоил бы позиции. Возвращает имена вложений, если своего блока текста
    TNEF не завёл, — тогда они идут в строку «Вложения:» внешнего письма.
    """
    if len(b) < 6 or not b.startswith(TNEF_ПОДПИСЬ):
        сбор.заметка("winmail.dat без подписи TNEF")
        return []
    кодировка = "cp1251"
    тема, тело_атрибут = "", ""
    свойства: dict[int, tuple[int, object]] = {}
    вложения: list[dict] = []
    п = 6
    while п + 9 <= len(b):
        уровень = b[п]
        атрибут, длина = struct.unpack_from("<II", b, п + 1)
        п += 9
        данные = b[п:п + длина]
        п += длина + 2
        if len(данные) < длина:
            сбор.заметка("winmail.dat обрезан")
            break
        if атрибут == _TNEF_КОДСТРАНИЦА and len(данные) >= 4:
            кодировка = _кодек(struct.unpack_from("<I", данные)[0])
        elif атрибут == _TNEF_ТЕМА:
            тема = данные.rstrip(b"\x00").decode(кодировка, errors="replace")
        elif атрибут == _TNEF_ТЕЛО:
            тело_атрибут = данные.rstrip(b"\x00").decode(кодировка, errors="replace")
        elif атрибут == _TNEF_СВОЙСТВА:
            свойства = _mapi_свойства(данные, кодировка)
        elif уровень == 2:
            if атрибут == _TNEF_НОВОЕ_ВЛОЖЕНИЕ or not вложения:
                вложения.append({"имя": "", "данные": None, "свойства": {}})
            if атрибут == _TNEF_ИМЯ_ВЛОЖЕНИЯ:
                вложения[-1]["имя"] = данные.rstrip(b"\x00").decode(кодировка, errors="replace")
            elif атрибут == _TNEF_ДАННЫЕ_ВЛОЖЕНИЯ:
                вложения[-1]["данные"] = данные
            elif атрибут == _TNEF_СВОЙСТВА_ВЛОЖЕНИЯ:
                вложения[-1]["свойства"] = _mapi_свойства(данные, кодировка)
    место = -1
    if not тело_есть:
        место = сбор.письмо(глубина, _заголовок(тема), "", False, False, False,
                            _tnef_тело(свойства, тело_атрибут, кодировка))
    имена: list[str] = []
    for вл in вложения:
        свойства_вл = вл["свойства"]
        имя = next((str(свойства_вл[н][1]) for н in ВЛОЖЕНИЕ_ИМЕНА
                    if н in свойства_вл and isinstance(свойства_вл[н][1], str)), вл["имя"])
        объект = свойства_вл.get(ВЛОЖЕНИЕ_ДАННЫЕ)
        if объект and объект[0] == 0x000D and isinstance(объект[1], bytes):
            # Письмо во вложении: 16 байт идентификатора интерфейса, затем TNEF.
            if сбор.глубже(глубина):
                _tnef(объект[1][16:], сбор, глубина + 1, тело_есть=False)
            continue
        данные = вл["данные"]
        if not данные and объект and isinstance(объект[1], bytes):
            данные = объект[1]
        if данные:
            учтено = сбор.вложение(имя, данные, глубина)
            if учтено:
                имена.append(учтено)
    if место >= 0:
        if имена:
            сбор.дописать(место, "Вложения: " + "; ".join(dict.fromkeys(имена)))
        return []
    return имена


def _tnef_тело(свойства: dict[int, tuple[int, object]], тело_атрибут: str,
               кодировка: str) -> str:
    простой = свойства.get(ТЕЛО)
    if простой and isinstance(простой[1], str) and простой[1].strip():
        return _норм_текст(простой[1])
    if тело_атрибут.strip():
        return _норм_текст(тело_атрибут)
    богатый = свойства.get(ТЕЛО_HTML)
    if богатый and isinstance(богатый[1], bytes):
        return _html_в_текст(_декод_байты(богатый[1], _кодировка_html(богатый[1])))
    if богатый and isinstance(богатый[1], str):
        return _html_в_текст(богатый[1])
    сжатый = свойства.get(ТЕЛО_RTF)
    if сжатый and isinstance(сжатый[1], bytes):
        return _rtf_в_текст(_rtf_распаковать(сжатый[1]), кодировка)
    return ""


def _mapi_свойства(d: bytes, кодировка: str) -> dict[int, tuple[int, object]]:
    """Список свойств MAPI внутри TNEF: номер → (тип, значение).

    Именованные свойства (номер от 0x8000) пропускаются: читателю из них ничего
    не нужно, но их длину надо пройти правильно, иначе съедет всё следующее. На
    неизвестном типе разбор останавливается с тем, что успел собрать, — угадывать
    длину значит читать мусор.
    """
    out: dict[int, tuple[int, object]] = {}
    try:
        число = struct.unpack_from("<I", d, 0)[0]
        п = 4
        for _ in range(min(число, 20000)):
            тип, ид = struct.unpack_from("<HH", d, п)
            п += 4
            if ид >= 0x8000:
                п += 16
                вид = struct.unpack_from("<I", d, п)[0]
                п += 4
                if вид == 0:
                    п += 4
                else:
                    длина = struct.unpack_from("<I", d, п)[0]
                    п += 4 + ((длина + 3) & ~3)
            много = bool(тип & 0x1000)
            основной = тип & 0x0FFF
            перем = основной in _TNEF_ПЕРЕМ
            if много or перем:
                сколько = struct.unpack_from("<I", d, п)[0]
                п += 4
            else:
                сколько = 1
            значения: list[object] = []
            for _ in range(min(сколько, 100000)):
                if перем:
                    длина = struct.unpack_from("<I", d, п)[0]
                    сырое = d[п + 4:п + 4 + длина]
                    п += 4 + ((длина + 3) & ~3)
                    if основной == 0x001F:
                        значения.append(сырое.decode("utf-16-le", errors="replace").rstrip("\x00"))
                    elif основной == 0x001E:
                        значения.append(сырое.rstrip(b"\x00").decode(кодировка, errors="replace"))
                    else:
                        значения.append(сырое)
                else:
                    размер = _TNEF_ФИКС.get(основной)
                    if размер is None:
                        return out
                    значения.append(d[п:п + размер])
                    п += размер
            if not много and значения and ид < 0x8000:
                out[ид] = (основной, значения[0])
    except struct.error:
        pass
    return out
