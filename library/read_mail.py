def _eml_файл(b: bytes, сбор: _Сбор, глубина: int, верхний: bool) -> None:
    b = b.lstrip(b"\xef\xbb\xbf \t\r\n")
    try:
        сообщение = BytesParser(policy=policy.default).parsebytes(b)
    except Exception as e:                                  # noqa: BLE001
        сбор.заметка(f"MIME не разобран ({type(e).__name__})")
        return
    if верхний and not _есть_заголовки(сообщение):
        сбор.заметка("не письмо: заголовков письма нет")
        return
    _eml_письмо(сообщение, сбор, глубина)


def _есть_заголовки(m: Message) -> bool:
    try:
        return any(k.lower() in ЗАГОЛОВКИ_ПИСЬМА for k, _ in m.raw_items())
    except Exception:                                       # noqa: BLE001
        return False


def _сырые_заголовки(m: Message) -> dict[str, str]:
    """Первое вхождение каждого заголовка в сыром виде (с байтами-суррогатами)."""
    out: dict[str, str] = {}
    try:
        for имя, значение in m.raw_items():
            out.setdefault(str(имя).lower(), str(значение))
    except Exception:                                       # noqa: BLE001, S110
        pass
    return out


def _дата_eml(сырое: str | None) -> str:
    if not сырое:
        return ""
    try:
        return parsedate_to_datetime(re.sub(r"\s+", " ", сырое)).strftime("%Y-%m-%d %H:%M")
    except Exception:                                       # noqa: BLE001
        return ""


class _Разбор:
    """Что нашлось в дереве частей одного письма: тела, вложения, вложенные письма."""

    def __init__(self) -> None:
        self.тела: list[tuple[str, str]] = []           # (plain | html, текст)
        self.вложения: list[tuple[str, bytes]] = []
        self.письма: list[Message | bytes] = []

    def влить(self, другой: _Разбор, с_телами: bool = True) -> None:
        if с_телами:
            self.тела.extend(другой.тела)
        self.вложения.extend(другой.вложения)
        self.письма.extend(другой.письма)


def _eml_письмо(m: Message, сбор: _Сбор, глубина: int) -> None:
    заг = _сырые_заголовки(m)
    разбор = _Разбор()
    _часть(m, разбор, сбор, 0)
    тело = "\n\n".join(т for _, т in разбор.тела if т.strip())
    место = сбор.письмо(глубина, _заголовок(заг.get("subject")), _дата_eml(заг.get("date")),
                        "from" in заг or "sender" in заг, "to" in заг, "cc" in заг, тело)
    имена = []
    for имя, данные in разбор.вложения:
        учтено = сбор.вложение(имя, данные, глубина, bool(тело.strip()))
        if учтено:
            имена.append(учтено)
    for вложенное in разбор.письма:
        if not сбор.глубже(глубина):
            continue
        if isinstance(вложенное, bytes):
            _eml_файл(вложенное, сбор, глубина + 1, верхний=False)
        else:
            _eml_письмо(вложенное, сбор, глубина + 1)
    if имена:
        сбор.дописать(место, "Вложения: " + "; ".join(dict.fromkeys(имена)))


def _часть(p: Message, разбор: _Разбор, сбор: _Сбор, вглубь: int) -> None:
    """Одна часть MIME. Ошибка в части не роняет письмо: она называется, и
    соседние части читаются дальше."""
    if вглубь > МАКС_ЧАСТЕЙ_ВГЛУБЬ:
        сбор.заметка(f"части MIME вложены глубже {МАКС_ЧАСТЕЙ_ВГЛУБЬ}: остаток не читан")
        return
    try:
        _часть_без_защиты(p, разбор, сбор, вглубь)
    except Exception as e:                                  # noqa: BLE001
        сбор.заметка(f"часть письма не разобрана ({type(e).__name__})")


def _часть_без_защиты(p: Message, разбор: _Разбор, сбор: _Сбор, вглубь: int) -> None:
    вид = p.get_content_type()
    if вид in ("message/rfc822", "message/global"):
        вложенное = p.get_payload()
        внутри = вложенное[0] if isinstance(вложенное, list) and вложенное else None
        байты = _письмо_в_base64(p, внутри)
        if байты:
            разбор.письма.append(байты)
        elif isinstance(внутри, Message):
            разбор.письма.append(внутри)
        else:
            байты = p.get_payload(decode=True)
            if isinstance(байты, bytes) and байты:
                разбор.письма.append(байты)
        return
    if p.is_multipart():
        дети = [д for д in (p.get_payload() or []) if isinstance(д, Message)]
        if вид == "multipart/alternative":
            _альтернативы(дети, разбор, сбор, вглубь)
        else:
            for д in дети:
                _часть(д, разбор, сбор, вглубь + 1)
        return
    if вид in ПОДПИСИ_ЭЦП or вид in ТЕХНИЧЕСКИЕ:
        return
    if вид in ("application/pkcs7-mime", "application/x-pkcs7-mime"):
        сбор.заметка("часть S/MIME (smime.p7m): зашифрована или подписана целиком, не раскрыта")
        return
    имя = _имя_части(p)
    расположение = (p.get_content_disposition() or "").lower()
    if вид in ("text/plain", "text/html") and not имя and расположение != "attachment":
        байты = p.get_payload(decode=True) or b""
        try:
            кодировка = p.get_content_charset()
        except Exception:                                   # noqa: BLE001
            кодировка = None
        if вид == "text/html":
            разбор.тела.append(("html", _html_в_текст(
                _декод_байты(байты, кодировка or _кодировка_html(байты)))))
        else:
            разбор.тела.append(("plain", _норм_текст(_декод_байты(байты, кодировка))))
        return
    байты = p.get_payload(decode=True)
    if not isinstance(байты, bytes) or not байты:
        return
    if not имя and вид != "application/octet-stream":
        расширение = mimetypes.guess_extension(вид) or ""
        имя = f"вложение{расширение}" if расширение else ""
    разбор.вложения.append((имя, байты))


def _письмо_в_base64(p: Message, внутри) -> bytes:
    """Пересланное письмо, закодированное base64 целиком.

    Против правил (RFC 2046 запрещает base64 у message/rfc822), но так делают
    иные почтовые шлюзы. Пакет email тогда строит «письмо без заголовков», телом
    которого служит сам base64, — и в текст шла простыня букв вместо письма.
    Признак: объявлено base64, а у разобранного письма нет ни одного заголовка.
    """
    кодирование = dict(_сырые_заголовки_все(p)).get("content-transfer-encoding", "")
    if кодирование.strip().lower() != "base64":
        return b""
    if isinstance(внутри, Message) and not _есть_заголовки(внутри):
        текст = внутри.get_payload()
        if isinstance(текст, str):
            try:
                чистый = re.sub(r"[^A-Za-z0-9+/]", "", текст)
                return base64.b64decode(чистый + "=" * (-len(чистый) % 4))
            except (binascii.Error, ValueError):
                return b""
    return b""


def _альтернативы(дети: list[Message], разбор: _Разбор, сбор: _Сбор, вглубь: int) -> None:
    """Одно и то же тело в нескольких видах: берётся ОДНО, иначе цены задвоятся.

    По заданию берётся text/plain, а HTML — только если простого нет. Исключение —
    заглушка: иная почтовая программа кладёт в простую часть «включите HTML для
    просмотра», и таблица цен остаётся только в HTML. Простой вид признаётся
    заглушкой, когда он короче трети HTML. Вложения и вложенные письма берутся из
    всех видов: картинка, вставленная в HTML (снимок таблицы цен), существует
    только там.
    """
    виды = []
    for д in дети:
        под = _Разбор()
        _часть(д, под, сбор, вглубь + 1)
        виды.append(под)
        разбор.влить(под, с_телами=False)
    простой = next((в for в in виды if в.тела and в.тела[0][0] == "plain"), None)
    богатый = next((в for в in reversed(виды) if any(к == "html" for к, _ in в.тела)), None)

    def длина(в: _Разбор) -> int:
        return sum(len(т.strip()) for _, т in в.тела)

    if простой and (богатый is None or длина(простой) >= 0.3 * длина(богатый)):
        разбор.тела.extend(простой.тела)
    elif богатый:
        разбор.тела.extend(богатый.тела)
    elif простой:
        разбор.тела.extend(простой.тела)


def _имя_части(p: Message) -> str:
    """Имя файла вложения.

    get_filename() справляется с RFC 2231 (filename*=utf-8''…), но сырые байты
    cp1251 в имени заменяет на «�», а слово RFC 2047 в кавычках («=?UTF-8?B?…?=»
    — так пишет Outlook, против правил) иногда оставляет как есть. Для этих
    случаев имя достаётся из сырого заголовка своим разбором.
    """
    try:
        имя = p.get_filename()
    except Exception:                                       # noqa: BLE001
        имя = None
    if имя and "\ufffd" not in имя and "=?" not in имя and not _есть_суррогаты(имя):
        return _чистое_имя(имя)
    for заголовок, значение in _сырые_заголовки_все(p):
        if заголовок not in ("content-disposition", "content-type"):
            continue
        m = re.search(r'(?i)(?:^|;)\s*(?:file)?name\s*=\s*(?:"([^"]*)"|([^;\s]+))', значение)
        if m:
            return _чистое_имя(_заголовок(m.group(1) if m.group(1) is not None else m.group(2)))
    return _чистое_имя(_заголовок(имя)) if имя else ""


def _сырые_заголовки_все(p: Message) -> list[tuple[str, str]]:
    try:
        return [(str(к).lower(), re.sub(r"\r?\n[ \t]+", " ", str(з))) for к, з in p.raw_items()]
    except Exception:                                       # noqa: BLE001
        return []


def _есть_суррогаты(s: str) -> bool:
    return any("\udc80" <= c <= "\udcff" for c in s)


# ──────────────────────────── контейнер OLE (CFB) ───────────────────────────

_МАКС_СЕКТОР = 0xFFFFFFFA
_НЕТ = 0xFFFFFFFF


class _Запись:
    __slots__ = ("имя", "тип", "лев", "прав", "ребёнок", "начало", "размер")

    def __init__(self, e: bytes, старый: bool) -> None:
        длина = struct.unpack_from("<H", e, 64)[0]
        self.имя = e[:max(0, min(64, длина) - 2)].decode("utf-16-le", errors="replace")
        self.тип = e[66]
        self.лев, self.прав, self.ребёнок = struct.unpack_from("<III", e, 68)
        self.начало = struct.unpack_from("<I", e, 116)[0]
        self.размер = struct.unpack_from("<Q", e, 120)[0]
        if старый:
            # В версии 3 старшие 4 байта размера не определены и бывают мусором.
            self.размер &= 0xFFFFFFFF


class _Ole:
    """Составной файл OLE (MS-CFB) только на чтение.

    Устройство: шапка 512 байт; секторы по 512 (версия 3) или 4096 байт (версия
    4); таблица размещения (FAT) связывает секторы в цепочки; её собственные
    секторы перечислены в шапке и, если их больше 109, в цепочке DIFAT. Каталог —
    записи по 128 байт, дерево через левого и правого соседа и первого ребёнка.
    Потоки меньше 4096 байт лежат в мини-потоке кусками по 64 байта со своей
    таблицей (mini FAT).

    Битый файл не должен ни зациклить разбор, ни раздуть память: каждая цепочка
    обходится с учётом пройденных секторов, а размеры обрезаются по данным.
    """

    def __init__(self, b: bytes) -> None:
        if len(b) < 512 or not b.startswith(OLE_ПОДПИСЬ):
            raise ValueError("не OLE")
        версия, порядок, сдвиг, мини_сдвиг = struct.unpack_from("<HHHH", b, 26)
        if порядок != 0xFFFE or сдвиг not in (9, 12) or not 0 < мини_сдвиг < сдвиг:
            raise ValueError("шапка OLE испорчена")
        self.b = b
        self.сектор = 1 << сдвиг
        self.мини = 1 << мини_сдвиг
        число_fat, первый_каталог = struct.unpack_from("<II", b, 44)
        self.отсечка = struct.unpack_from("<I", b, 56)[0] or 4096
        первый_minifat, _число_minifat, первый_difat, _число_difat = struct.unpack_from(
            "<IIII", b, 60)
        список_fat = list(struct.unpack_from("<109I", b, 76))
        на_сектор = self.сектор // 4
        s, видено = первый_difat, set()
        while s <= _МАКС_СЕКТОР and s not in видено:
            видено.add(s)
            d = self._сектор(s)
            if len(d) < self.сектор:
                break
            значения = struct.unpack(f"<{на_сектор}I", d)
            список_fat.extend(значения[:-1])
            s = значения[-1]
        секторы_fat = [x for x in список_fat if x <= _МАКС_СЕКТОР]
        if число_fat:
            секторы_fat = секторы_fat[:число_fat]
        self.fat = self._таблица(b"".join(self._сектор(x) for x in секторы_fat))
        каталог = self._цепь(первый_каталог, self.fat, self._сектор)
        self.записи = [_Запись(каталог[i:i + 128], версия == 3)
                       for i in range(0, len(каталог) - 127, 128)]
        if not self.записи or self.записи[0].тип != 5:
            raise ValueError("нет корневой записи OLE")
        корень = self.записи[0]
        self.мини_поток = self._цепь(корень.начало, self.fat, self._сектор)[:корень.размер]
        self.minifat = self._таблица(self._цепь(первый_minifat, self.fat, self._сектор))

    @staticmethod
    def _таблица(d: bytes) -> tuple[int, ...]:
        return struct.unpack(f"<{len(d) // 4}I", d[:len(d) // 4 * 4])

    def _сектор(self, n: int) -> bytes:
        начало = (n + 1) * self.сектор
        return self.b[начало:начало + self.сектор]

    def _мини_сектор(self, n: int) -> bytes:
        return self.мини_поток[n * self.мини:(n + 1) * self.мини]

    @staticmethod
    def _цепь(начало: int, таблица: tuple[int, ...], читать) -> bytes:
        куски, s, видено = [], начало, set()
        while s <= _МАКС_СЕКТОР and s not in видено:
            видено.add(s)
            кусок = читать(s)
            if not кусок:
                break
            куски.append(кусок)
            if s >= len(таблица):
                break
            s = таблица[s]
        return b"".join(куски)

    def дети(self, i: int) -> dict[str, int]:
        """Непосредственные дети хранилища: ИМЯ В ВЕРХНЕМ РЕГИСТРЕ → номер записи.
        Регистр снимается, потому что имена в CFB сравниваются без регистра, а
        программы пишут шестнадцатеричные цифры в именах потоков по-разному."""
        out: dict[str, int] = {}
        if not 0 <= i < len(self.записи):
            return out
        стек, видено = [self.записи[i].ребёнок], set()
        while стек:
            j = стек.pop()
            if j == _НЕТ or j >= len(self.записи) or j in видено:
                continue
            видено.add(j)
            з = self.записи[j]
            if з.тип in (1, 2):
                out.setdefault(з.имя.upper(), j)
            стек.extend((з.лев, з.прав))
        return out

    def поток(self, i: int) -> bytes:
        if not 0 < i < len(self.записи) or self.записи[i].тип != 2:
            return b""
        з = self.записи[i]
        if з.размер < self.отсечка:
            данные = self._цепь(з.начало, self.minifat, self._мини_сектор)
        else:
            данные = self._цепь(з.начало, self.fat, self._сектор)
        return данные[:з.размер]

    def хранилище(self, i: int) -> bool:
        return 0 <= i < len(self.записи) and self.записи[i].тип in (1, 5)


def _хранилище_письма(ole: _Ole, i: int) -> bool:
    дети = ole.дети(i)
    return ("__PROPERTIES_VERSION1.0" in дети
            and any(к.startswith("__SUBSTG1.0_") for к in дети))


