#: Сколько уровней вложенных писем раскрывать: письмо → пересланное → пересланное
#: в пересланном → ещё одно. Глубже — это либо ошибка пересылки, либо бомба, и
#: потеря называется в reason, а не проходит молча.
МАКС_ГЛУБИНА = 3

#: Предел вложений на всё письмо с вложенными. Архив ограничен сорока участниками
#: (readers.МАКС_УЧАСТНИКОВ); письмо с чертежами бывает больше, но шестьдесят
#: файлов в одном письме — уже рассылка каталога, а не предложение.
МАКС_ВЛОЖЕНИЙ = 60

#: Предел текста. Переписка с цитатами бывает длинной, но мегабайт текста — это
#: уже выгрузка, а не письмо; обрезка называется в reason.
МАКС_ТЕКСТ = 1_000_000

#: Предел вложенности частей MIME. Настоящее письмо укладывается в пять-шесть
#: уровней; сотни уровней — это бомба, которая иначе исчерпала бы стек.
МАКС_ЧАСТЕЙ_ВГЛУБЬ = 40

OLE_ПОДПИСЬ = b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1"
TNEF_ПОДПИСЬ = b"\x78\x9f\x3e\x22"

#: Заголовки, по которым текст узнаётся письмом. Нужны два из них: одно совпадение
#: даёт и CSV с колонкой «Date», а пара «From + Subject» в простом тексте не
#: встречается.
ЗАГОЛОВКИ_ПИСЬМА = frozenset((
    "from", "to", "cc", "subject", "date", "message-id", "mime-version",
    "received", "return-path", "reply-to", "sender", "delivered-to",
    "content-type", "x-mailer", "user-agent", "thread-topic", "thread-index",
    "in-reply-to", "references", "x-originating-ip", "importance",
))

#: Подписи S/MIME и PGP: читать в них нечего, и в attachments они только занимают
#: место и время распознавания.
ПОДПИСИ_ЭЦП = frozenset((
    "application/pkcs7-signature", "application/x-pkcs7-signature",
    "application/pgp-signature", "application/pgp-keys",
))

#: Технические части отчётов о доставке: там только адреса и коды сервера.
ТЕХНИЧЕСКИЕ = frozenset((
    "message/delivery-status", "message/disposition-notification",
    "text/rfc822-headers", "message/feedback-report",
))

#: Адрес почты. Повторы ограничены длинами из RFC 5321 (64 знака имени, 63 —
#: части домена): без пределов строка из миллиона букв без «@» — вставленный в
#: письмо base64 — перебиралась бы квадратично и вешала прогон.
_АДРЕС = re.compile(r"[\w.+'-]{1,64}@(?:[\w-]{1,63}\.){1,8}[^\W\d_]{2,24}")
_СЛОВО_2047 = re.compile(r"=\?([^?\s]+)\?([bBqQ])\?([^?\s]*)\?=")


# ─────────────────────────────── общий вход ────────────────────────────────

def прочитать_письмо(b: bytes) -> dict:
    """Письмо в текст и список вложений. Исключений не бросает никогда."""
    try:
        return _прочитать(b)
    except Exception as e:                                  # noqa: BLE001
        return _пусто(f"сбой разбора письма ({type(e).__name__})")


def это_письмо_outlook(b: bytes) -> bool:
    """Отличает .msg от .xls, .doc и .ppt — все четыре один и тот же OLE2.

    Смотрится корень контейнера: у письма там лежат поток свойств
    `__properties_version1.0` и потоки `__substg1.0_…`, у книги — `Workbook`
    или `Book`, у документа — `WordDocument`. Поиск по байтам без разбора
    ошибся бы на документе Word со вложенным письмом: его потоки лежат глубже,
    а не в корне. Байтовый поиск берётся только запасным путём — когда
    контейнер битый и каталог не читается.
    """
    try:
        b = bytes(b)
        if not b.startswith(OLE_ПОДПИСЬ):
            return False
        try:
            return _хранилище_письма(_Ole(b), 0)
        except Exception:                                   # noqa: BLE001
            return ("__substg1.0_".encode("utf-16-le") in b
                    and "__properties_version1.0".encode("utf-16-le") in b)
    except Exception:                                       # noqa: BLE001
        return False


def это_письмо_eml(b: bytes) -> bool:
    """Текст с заголовками письма: .eml, а заодно и .mht (тоже MIME).

    Письмо начинается с блока «Имя: значение» до первой пустой строки; нужны два
    известных заголовка, и первая строка обязана быть заголовком (или строкой
    «From » почтового ящика mbox). Заголовки считаются до пустой строки или до
    первой строки, заголовком не являющейся. Кириллическое «Кому:» в простом тексте
    заголовком не считается: имя заголовка — только латиница.
    """
    try:
        b = bytes(b)
        голова = b[:16384].lstrip(b"\xef\xbb\xbf \t\r\n")
        строки = голова.decode("latin-1").splitlines()
        if строки and строки[0].startswith("From "):
            строки = строки[1:]
        известных, первая = 0, True
        for s in строки[:200]:
            if not s.strip():
                break
            if s[:1] in " \t":                  # продолжение сложенного заголовка
                if первая:
                    return False
                continue
            m = re.match(r"([!-9;-~]+):", s)
            if not m:
                # Тело без пустой строки после заголовков — против RFC 5322, но
                # встречается; после двух узнанных заголовков это уже письмо.
                break
            первая = False
            if m.group(1).lower() in ЗАГОЛОВКИ_ПИСЬМА:
                известных += 1
        return известных >= 2
    except Exception:                                       # noqa: BLE001
        return False


def _пусто(почему: str) -> dict:
    return {"text": "", "attachments": [], "reason": почему, "формат": "", "писем": 0}


def _прочитать(b) -> dict:
    if not isinstance(b, (bytes, bytearray, memoryview)):
        return _пусто("на вход пришли не байты")
    b = bytes(b)
    if not b.strip():
        return _пусто("пустой файл")
    сбор = _Сбор()
    if b.startswith(OLE_ПОДПИСЬ):
        формат = "msg"
        _msg_файл(b, сбор, 0)
    elif b.startswith(TNEF_ПОДПИСЬ):
        формат = "tnef"
        _tnef(b, сбор, 0, тело_есть=False)
    else:
        формат = "eml"
        _eml_файл(b, сбор, 0, верхний=True)
    return сбор.итог(формат)


# ─────────────────────────────── сбор итога ────────────────────────────────

class _Сбор:
    """Копит текст писем цепочки, вложения и названные потери.

    Одно на весь вызов: вложения всех уровней идут в один список, повторы по
    содержимому отбрасываются. Повтор — обычное дело: ответ с КП пересылают с
    исходным письмом внутри, и тот же PDF лежит на двух уровнях; прочитанный
    дважды, он дал бы вдвое больше строк спроса.
    """

    def __init__(self) -> None:
        self.части: list[str] = []
        self.вложения: list[tuple[str, bytes]] = []
        self.хеши: set[bytes] = set()
        self.заметки: dict[str, int] = {}
        self.писем = 0

    def заметка(self, текст: str) -> None:
        self.заметки[текст] = self.заметки.get(текст, 0) + 1

    def письмо(self, глубина: int, тема: str, дата: str, от: bool, кому: bool,
               копия: bool, тело: str) -> int:
        """Шапка и тело одного письма. Возвращает место, чтобы дописать строку
        вложений ПОСЛЕ разбора вложений: вложенные письма встают своими блоками
        следом, а перечень файлов должен остаться у своего письма."""
        self.писем += 1
        строки = []
        if глубина:
            строки.append(f"----- вложенное письмо, уровень {глубина} -----")
        if тема:
            строки.append(f"Тема: {тема}")
        if дата:
            строки.append(f"Дата: {дата}")
        if от:
            строки.append("От: отправитель")
        if кому:
            строки.append("Кому: получатель")
        if копия:
            строки.append("Копия: получатель")
        блок = "\n".join(строки)
        if тело.strip():
            блок = f"{блок}\n\n{тело.strip()}" if блок else тело.strip()
        self.части.append(блок)
        return len(self.части) - 1

    def дописать(self, место: int, строка: str) -> None:
        if 0 <= место < len(self.части) and строка:
            self.части[место] = f"{self.части[место]}\n\n{строка}".strip()

    def вложение(self, имя: str, данные: bytes, глубина: int, тело_есть: bool = True) -> str:
        """Одно вложение. Возвращает имя, под которым оно учтено (для строки
        «Вложения:» в тексте), или пусто, если оно раскрыто здесь же.

        winmail.dat раскрывается сразу: это не файл, а упаковка Outlook, внутри
        которой лежат настоящие вложения. Письмо во вложении — тоже здесь, чтобы
        глубина считалась одной на всю цепочку: отдай его наружу, вызывающий
        начал бы счёт заново, и предел глубины ничего бы не ограничивал.
        """
        имя = _чистое_имя(имя)
        if not данные:
            return ""
        if данные.startswith(TNEF_ПОДПИСЬ):
            return "; ".join(_tnef(данные, self, глубина, тело_есть))
        if данные.startswith(OLE_ПОДПИСЬ) and это_письмо_outlook(данные):
            if self.глубже(глубина):
                _msg_файл(данные, self, глубина + 1)
            return ""
        if имя.lower().endswith(".eml") and это_письмо_eml(данные):
            if self.глубже(глубина):
                _eml_файл(данные, self, глубина + 1, верхний=False)
            return ""
        хеш = hashlib.sha1(данные).digest()             # noqa: S324 — не защита, а ключ повтора
        if хеш in self.хеши:
            return имя or "вложение"
        if len(self.вложения) >= МАКС_ВЛОЖЕНИЙ:
            self.заметка(f"вложений больше {МАКС_ВЛОЖЕНИЙ}: лишние не взяты")
            return ""
        self.хеши.add(хеш)
        if not имя:
            имя = f"вложение-{len(self.вложения) + 1}"
        занятые = {и for и, _ in self.вложения}
        if имя in занятые:
            # Два безымянных PDF или два «image001.png» из разных писем цепочки:
            # имя должно различать вложения, иначе вызывающий спутает их.
            основа, точка, расш = имя.rpartition(".")
            основа, расш = (основа, "." + расш) if точка and основа else (имя, "")
            номер = 2
            while f"{основа}-{номер}{расш}" in занятые:
                номер += 1
            имя = f"{основа}-{номер}{расш}"
        self.вложения.append((имя, данные))
        return имя

    def глубже(self, глубина: int) -> bool:
        """Можно ли раскрыть письмо уровнем ниже. Нельзя — потеря называется."""
        if глубина + 1 > МАКС_ГЛУБИНА:
            self.заметка(f"вложенность писем глубже {МАКС_ГЛУБИНА}: письмо не раскрыто")
            return False
        return True

    def итог(self, формат: str) -> dict:
        текст = "\n\n".join(ч for ч in self.части if ч.strip())
        текст = _АДРЕС.sub("[почта]", текст)
        if len(текст) > МАКС_ТЕКСТ:
            текст = текст[:МАКС_ТЕКСТ]
            self.заметка(f"текст обрезан на {МАКС_ТЕКСТ} знаках")
        заметки = [т if н == 1 else f"{т} (×{н})" for т, н in self.заметки.items()]
        if not текст.strip() and not self.вложения and not заметки:
            заметки.append("письмо без текста и вложений")
        return {"text": текст, "attachments": self.вложения, "reason": "; ".join(заметки),
                "формат": формат, "писем": self.писем}


def _чистое_имя(имя: str) -> str:
    """Имя файла без пути: Outlook иногда кладёт полный путь с диска отправителя."""
    имя = (имя or "").replace("\x00", "").strip()
    return re.split(r"[\\/]", имя)[-1].strip()


# ───────────────────────────── кодировки и текст ────────────────────────────

_КОДЕКИ = {65001: "utf-8", 1200: "utf-16-le", 1201: "utf-16-be", 20866: "koi8_r",
           21866: "koi8_u", 28595: "iso8859_5", 10007: "mac_cyrillic",
           20127: "ascii", 28591: "latin-1"}


def _кодек(номер: int | None) -> str:
    """Кодовая страница Windows (число из свойств письма) в имя кодека Python."""
    if not номер:
        return "cp1251"
    имя = _КОДЕКИ.get(номер, f"cp{номер}")
    try:
        codecs.lookup(имя)
        return имя
    except LookupError:
        return "cp1251"


def _кодек_по_имени(имя: str | None) -> str | None:
    """Объявленная кодировка письма в кодек Python, или None, если не узнана.

    Почтовые программы пишут её как придётся: «windows-1251», «x-cp1251»,
    «cp-1251», в кавычках. «unknown-8bit» — честное «не знаю».
    """
    if not имя:
        return None
    имя = str(имя).strip().strip("\"'").lower()
    for вариант in (имя, имя.removeprefix("x-"), имя.replace("-", ""),
                    имя.removeprefix("x-").replace("-", "")):
        try:
            return codecs.lookup(вариант).name
        except LookupError:
            continue
    return None


def _угадать_кириллицу(b: bytes) -> str:
    """cp1251, koi8-r или cp866 — по тому, какая даёт осмысленный текст.

    В русском тексте строчных букв много больше, чем заглавных. KOI8-R, прочитанный
    как cp1251, даёт почти одни заглавные (строчные и заглавные там переставлены), а
    cp866 — псевдографику. Поэтому счёт «строчные минус заглавные минус прочий
    не-ASCII» выбирает кодировку без словаря. Считается по первым 64 КБ: на теле в
    мегабайт полный счёт — девять проходов Python по каждому знаку, а кодировка
    письма посреди текста не меняется.
    """
    образец = b[:65536]
    лучший, лучший_счёт = "cp1251", None
    for кодек in ("cp1251", "koi8_r", "cp866"):
        s = образец.decode(кодек, errors="replace")
        строчных = sum(1 for c in s if "а" <= c <= "я" or c == "ё")
        заглавных = sum(1 for c in s if "А" <= c <= "Я" or c == "Ё")
        прочих = sum(1 for c in s if ord(c) > 127 and not ("А" <= c <= "я" or c in "Ёё"))
        счёт = строчных - заглавных - прочих
        if лучший_счёт is None or счёт > лучший_счёт:
            лучший, лучший_счёт = кодек, счёт
    return b.decode(лучший, errors="replace")


def _декод_байты(b: bytes, заявлено: str | None = None) -> str:
    """Байты текста письма в строку.

    Порядок выбран по цене ошибки. UTF-8 проверяется первым: кириллица в cp1251 и
    KOI8-R почти никогда не бывает правильной последовательностью UTF-8, поэтому
    успех строгого разбора — надёжный признак. Объявленная кодировка идёт второй:
    ей верить можно не всегда — «us-ascii» на письме с 8-битным телом обычное
    дело. Последней — догадка по буквам. Исключение одно: UTF-16 без метки порядка
    байт выглядит правильным UTF-8 (нулевые байты допустимы), и объявленный UTF-16
    пробуется раньше.
    """
    if not b:
        return ""
    if b.startswith(codecs.BOM_UTF8):
        return b[3:].decode("utf-8", errors="replace")
    if b.startswith((codecs.BOM_UTF16_LE, codecs.BOM_UTF16_BE)):
        return b.decode("utf-16", errors="replace")
    кодек = _кодек_по_имени(заявлено)
    порядок = []
    if кодек and кодек.startswith(("utf-16", "utf-32", "utf_16", "utf_32")):
        порядок.append(кодек)
    порядок.append("utf-8")
    if кодек and кодек not in порядок and кодек != "ascii":
        порядок.append(кодек)
    for к in порядок:
        try:
            return b.decode(к)
        except (UnicodeDecodeError, LookupError):
            continue
    return _угадать_кириллицу(b)


def _заголовок(сырое) -> str:
    """Заголовок письма в текст: слова RFC 2047 и сырые 8-битные байты.

    Стандартный разбор (policy.default) сырые байты cp1251 в теме заменяет на
    «�», а старые почтовые программы пишут тему именно так. Поэтому разбор свой.
    Соседние закодированные слова одной кодировки склеиваются ДО декодирования:
    длинную тему в UTF-8 программы режут посреди буквы, и по отдельности каждая
    половина даёт «�».
    """
    if сырое is None:
        return ""
    s = re.sub(r"\r?\n[ \t]+", " ", str(сырое))
    куски: list[list] = []          # ["сырое", str] | ["слово", кодировка, bytes]
    поз = 0
    for m in _СЛОВО_2047.finditer(s):
        между = s[поз:m.start()]
        прежнее_слово = bool(куски) and куски[-1][0] == "слово"
        # Пробел между двумя словами RFC 2047 не значим (RFC 2047, п. 6.2).
        if между and not (прежнее_слово and not между.strip()):
            куски.append(["сырое", между])
        кодировка, вид, данные = m.group(1).split("*")[0], m.group(2), m.group(3)
        try:
            if вид in "bB":
                байты = base64.b64decode(данные + "=" * (-len(данные) % 4))
            else:
                байты = quopri.decodestring(данные.encode("ascii", "surrogateescape"),
                                            header=True)
        except (binascii.Error, ValueError, UnicodeEncodeError):
            куски.append(["сырое", m.group(0)])
            поз = m.end()
            continue
        if куски and куски[-1][0] == "слово" and куски[-1][1].lower() == кодировка.lower():
            куски[-1][2] += байты
        else:
            куски.append(["слово", кодировка, байты])
        поз = m.end()
    if s[поз:]:
        куски.append(["сырое", s[поз:]])
    текст = "".join(_сырой_кусок(к[1]) if к[0] == "сырое" else _декод_байты(к[2], к[1])
                    for к in куски)
    return re.sub(r"\s+", " ", текст.replace("\x00", "")).strip()


def _сырой_кусок(s: str) -> str:
    """Незакодированная часть заголовка: 8-битные байты хранятся в строке как
    «суррогаты» (surrogateescape), и их надо вернуть в байты и прочитать."""
    try:
        b = s.encode("ascii", "surrogateescape")
    except UnicodeEncodeError:
        return s                        # уже настоящий Юникод
    return _декод_байты(b) if any(c > 127 for c in b) else s


def _норм_текст(s: str) -> str:
    """Простой текст письма: единые переводы строк, без хвостовых пробелов и без
    простыней пустых строк (цитаты Outlook ими богаты)."""
    s = s.replace("\x00", "").replace("\r\n", "\n").replace("\r", "\n")
    s = "\n".join(строка.rstrip() for строка in s.split("\n"))
    return re.sub(r"\n{3,}", "\n\n", s).strip()


def _html_в_текст(s: str) -> str:
    """HTML тела письма в текст.

    Свой, а не readers.text_from_html, по двум причинам, обе про цены. Первая:
    Outlook разбивает строки тегом <br> без закрывающей пары, и «Позиция 1 —
    100 руб<br>Позиция 2 — 200 руб» у прежнего читателя сливались в одну строку.
    Вторая: сущности вида &#1062; и &laquo; там не раскрываются, и кириллица в
    письмах из веб-почты оставалась цифрами. Ячейки таблиц разделяются табуляцией,
    чтобы разбор колонок дальше видел таблицу, а не прозу.
    """
    s = _без_служебных_блоков(s)
    s = re.sub(r"\s+", " ", s)
    s = re.sub(r"(?i)<br\s*/?\s*>", "\n", s)
    s = re.sub(r"(?i)</?(?:p|div|tr|li|ul|ol|table|h[1-6]|blockquote|pre|hr)\b[^>]*>", "\n", s)
    s = re.sub(r"(?i)</t[dh]\s*>", "\t", s)
    s = re.sub(r"(?s)<[^>]*>", "", s)
    s = html.unescape(s).replace("\xa0", " ").replace("\x00", "")
    строки = []
    for строка in s.split("\n"):
        строка = re.sub(r" *\t *", "\t", re.sub(r" {2,}", " ", строка)).strip(" ").rstrip("\t")
        if строка.strip():
            строки.append(строка)
    return "\n".join(строки)


#: Открытие комментария или служебного блока — вместе с атрибутами тега, но не
#: дальше следующей «<»: иначе незакрытый тег проглотил бы соседние.
_HTML_ОТКРЫТИЕ = re.compile(r"<!--|<(script|style|head|title|xml)\b[^<>]*>?", re.I)


def _без_служебных_блоков(s: str) -> str:
    """Вырезает комментарии и блоки script, style, head, title, xml.

    Не регуляркой «<!--.*?-->»: на незакрытом комментарии она от каждого
    открытия просматривает строку до конца, и двадцать тысяч «<!--» в письме
    на полмегабайта читались девять секунд. Здесь проход один: если закрытия
    не нашлось после позиции p, его нет и после любой более поздней, и это
    запоминается. Незакрытый блок не съедает остаток письма: вырезается только
    его открытие, текст после него остаётся.
    """
    куски: list[str] = []
    поз = 0
    нет_закрытия: set[str] = set()
    for m in _HTML_ОТКРЫТИЕ.finditer(s):
        if m.start() < поз:
            continue
        куски.append(s[поз:m.start()])     # без пробела: «Це<!-- -->на» — это «Цена»
        тег = (m.group(1) or "").lower()
        ключ = тег or "--"
        конец = -1
        if ключ not in нет_закрытия:
            if тег:
                найдено = re.compile(rf"</{тег}\s*>", re.I).search(s, m.end())
                конец = найдено.end() if найдено else -1
            else:
                конец = s.find("-->", m.end())
                конец = конец + 3 if конец >= 0 else -1
            if конец < 0:
                нет_закрытия.add(ключ)
        поз = конец if конец >= 0 else m.end()
    куски.append(s[поз:])
    return "".join(куски)


def _кодировка_html(b: bytes) -> str | None:
    m = re.search(rb"""charset\s*=\s*["']?([\w.:-]+)""", b[:4096], re.I)
    return m.group(1).decode("ascii", "replace") if m else None


