#!/usr/bin/env python3
"""Читатель писем: .eml (MIME), .msg (Outlook) и winmail.dat (TNEF) внутри них.

ЗАЧЕМ. Поставщики и менеджеры прикладывают к карточкам письма целиком. Внутри
письма — текст с ценами и вложения: КП в PDF, книги Excel, пересланные письма
с ещё одним слоем вложений. До этого модуля в репозитории не было ни одного
читателя писем:

    .msg  — контейнер OLE2, как .xls и .doc; опознавался «старым office», падал
            в xlrd, затем в antiword — ноль позиций;
    .eml  — текст с заголовками; опознавался «txt/прочее» и читался как проза,
            то есть base64 вложений шёл в базу вместо КП.

ЧТО ВОЗВРАЩАЕТСЯ. `прочитать_письмо(b)` отдаёт словарь:

    text         тема, дата, роли участников и тело каждого письма цепочки;
    attachments  список (имя, байты) — вложения для рекурсивного чтения другими
                 читателями (PDF, книги, архивы); письма внутри письма сюда НЕ
                 попадают, они раскрываются здесь же, до глубины МАКС_ГЛУБИНА;
    reason       пусто, если прочитано всё; иначе названные потери через «; ».
                 При непустом text это заметки о частичной потере, при пустом —
                 причина, почему не прочитано ничего;
    формат       «eml», «msg», «tnef» или пусто;
    писем        сколько писем раскрыто вместе с вложенными.

ПУТЬ ДЛЯ .msg — СВОЙ РАЗБОР СОСТАВНОГО ФАЙЛА OLE (MS-CFB), БЕЗ ЗАВИСИМОСТЕЙ.
Взвешено три пути:
  • olefile / extract_msg — в окружении прогона их нет, а новая pip-зависимость
    ради одного формата — это ещё одна причина, по которой прогон может не
    собраться; extract_msg к тому же тянет за собой десяток пакетов;
  • 7z — внешняя программа, в прогоне её тоже нет (проверено 23.09.2026), а
    вызов через временный каталог и разбор листинга ломается на именах потоков;
  • свой разбор — формат открыт и мал: шапка, таблица размещения секторов,
    каталог записей, мини-поток. Около ста строк стандартного struct, работает
    везде, где есть Python, и не пишет на диск.
Выбран третий. Сам формат .msg (MS-OXMSG) поверх контейнера — это потоки
`__substg1.0_ИИИИТТТТ`, где ИИИИ — номер свойства MAPI, ТТТТ — его тип:
001F — строка UTF-16, 001E — строка в кодовой странице письма, 0102 — байты,
000D — вложенное хранилище (письмо во вложении).

ПРАВИЛО 17 (журнал публичный): модуль ничего не печатает. Адреса почты в text не
попадают вовсе: участники заменены ролями «отправитель» и «получатель», а адреса
внутри тела и подписи — меткой «[почта]». Имена людей из заголовков тоже не
берутся: роль достаточна, чтобы понять устройство письма.

НИКОГДА НЕ БРОСАЕТ ИСКЛЮЧЕНИЙ: письмо читается внутри общего прохода по тысячам
файлов, и одно битое письмо не должно останавливать прогон.
"""
