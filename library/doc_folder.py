def _по_названию(сущность: str | None, название: str) -> tuple[str, float, str]:
    if сущность == СП166 and название in НАЗВАНИЯ_СП166:
        return НАЗВАНИЯ_СП166[название], УВ_НАЗВАНИЕ, "название поля СП-166"
    if название in ПАПКА_ПО_НАЗВАНИЮ:
        п = ПАПКА_ПО_НАЗВАНИЮ[название]
        if п == НЕ_ОПРЕДЕЛЕНО:
            return НЕ_ОПРЕДЕЛЕНО, 0.0, f"название поля: {НАПРАВЛЕНИЕ_НЕ_УСТАНОВЛЕНО}"
        return п, УВ_НАЗВАНИЕ, "название поля"
    if название in ПАПКА_ПО_НАЗВАНИЮ_ОСЛАБЛЕННО:
        return (ПАПКА_ПО_НАЗВАНИЮ_ОСЛАБЛЕННО[название], УВ_ОБРАЗЕЦ,
                "название поля вне СП-166: сторона словаря неверна")
    if название in _ds.ПО_НАЗВАНИЮ:
        return ПАПКА_ПО_СТОРОНЕ[_ds.ПО_НАЗВАНИЮ[название]], УВ_НАЗВАНИЕ, "название поля"
    for образец, п in ПАПКА_ПО_ОБРАЗЦУ:
        if образец.search(название):
            return п, УВ_ОБРАЗЕЦ, "образец названия поля"
    сторона = _ds.сторона(название)
    п = ПАПКА_ПО_СТОРОНЕ.get(сторона, НЕ_ОПРЕДЕЛЕНО)
    if п == НЕ_ОПРЕДЕЛЕНО:
        return НЕ_ОПРЕДЕЛЕНО, 0.0, "поле не опознано"
    return п, УВ_ОБРАЗЕЦ, "образец названия поля"


def определить(origin: str | None, field_code: str | None,
               field_title: str | None) -> tuple[str, float, str]:
    """Папка, уверенность 0..1 и почему — по сущности и полю.

    origin      — lib_files.origin («поле запроса» у СП-166, «поле сделки»);
    field_code  — код поля портала (любое из двух написаний);
    field_title — название поля; спрашивается, только если код неизвестен.
    """
    сущность = СУЩНОСТЬ_ПО_ПРОИСХОЖДЕНИЮ.get((origin or "").strip())
    точно = _ПО_КЛЮЧУ.get(сущность, {}).get(_ключ(field_code)) if сущность else None
    if точно:
        п = точно[0]
        if п == НЕ_ОПРЕДЕЛЕНО:
            почему = _ПОЧЕМУ_БЕЗ_ПАПКИ_ПО_КЛЮЧУ.get((сущность, _ключ(field_code)), РАЗНОРОДНОЕ)
            return НЕ_ОПРЕДЕЛЕНО, 0.0, f"код поля ({сущность}): {почему}"
        return п, УВ_КОД, f"код поля ({сущность})"
    название = (field_title or "").strip()
    if not название:
        return НЕ_ОПРЕДЕЛЕНО, 0.0, "поле не опознано"
    return _по_названию(сущность, название)


def папка(origin: str | None, field_code: str | None,
          field_title: str | None) -> tuple[str, str]:
    """Папка и почему. Уверенность — в определить()."""
    п, _, почему = определить(origin, field_code, field_title)
    return п, почему
