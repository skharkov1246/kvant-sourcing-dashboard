def _текст_odf(эл) -> str:
    части = [эл.text or ""]
    for ч in эл:
        и = _имя(ч.tag)
        if и == "s":
            части.append(" " * max(1, _целое(_атр(ч, "c"), 1)))
        elif и == "tab":
            части.append("\t")
        elif и == "line-break":
            части.append("\n")
        elif и != "annotation":              # примечание — не значение ячейки
            части.append(_текст_odf(ч))
        части.append(ч.tail or "")
    return "".join(части)


def _значение_ods(яч):
    """(значение, формула). Число берётся из office:value, а не из показа: показ
    «1 234,50 руб.» пришлось бы разбирать обратно, а office:value — уже 1234.5."""
    тип = _атр(яч, "value-type")
    ф = _атр(яч, "formula")
    if тип in ("float", "percentage", "currency"):
        try:
            return float(_атр(яч, "value")), ф
        except (TypeError, ValueError):
            pass
    elif тип == "date" and _атр(яч, "date-value"):
        return _дата_iso(_атр(яч, "date-value")), ф
    elif тип == "time" and _атр(яч, "time-value"):
        return _время_iso(_атр(яч, "time-value")), ф
    elif тип == "boolean" and _атр(яч, "boolean-value"):
        return _атр(яч, "boolean-value").strip().lower() == "true", ф
    текст = "\n".join(_текст_odf(p) for p in яч if _имя(p.tag) in ("p", "h")).strip()
    if not текст and тип == "string":
        текст = (_атр(яч, "string-value") or "").strip()
    return (текст or None), ф


def _формула_odf(ф: str) -> str:
    """Формула ODF в запись Excel: «of:=[.A1]*[$Лист2.B3]» -> «A1*'Лист2'!B3».
    Разделитель аргументов «;» разбор формул понимает и так."""
    ф = re.sub(r"^[a-z]+:", "", (ф or "").strip()).lstrip("=")

    def ссылка(m: re.Match) -> str:
        части = []
        for часть in m.group(1).split(":"):
            лист, _, адрес = часть.rpartition(".")
            лист = лист.lstrip("$").strip("'").replace("''", "'")
            части.append(f"'{лист}'!{адрес}" if лист else адрес)
        if len(части) == 2 and "!" in части[1]:
            части[1] = части[1].rpartition("!")[2]
        return ":".join(части)

    return re.sub(r"\[([^\]]+)\]", ссылка, ф)


def _ряд_ods(эл, лист: _Лист, строка: int, предел: int) -> int:
    """Строка table:table-row. Возвращает номер последней строки после неё.

    Повторы: «пустая строка × 1 048 000» в конце листа — обычное дело, и
    разворачивать её нельзя; непустая строка повторяется не больше МАКС_ПОВТОРА."""
    повтор = max(1, _целое(_атр(эл, "number-rows-repeated"), 1))
    ячейки = []
    кол = 0
    for яч in эл:
        и = _имя(яч.tag)
        if и not in ("table-cell", "covered-table-cell"):
            continue
        повтор_к = max(1, _целое(_атр(яч, "number-columns-repeated"), 1))
        if и == "table-cell":
            знач, ф = _значение_ods(яч)
            if знач is not None or ф:
                ячейки.append((кол + 1, знач, ф, min(повтор_к, МАКС_ПОВТОРА),
                               max(1, _целое(_атр(яч, "number-columns-spanned"), 1)),
                               max(1, _целое(_атр(яч, "number-rows-spanned"), 1))))
        кол += повтор_к
    if not ячейки:
        return строка + повтор
    for k in range(min(повтор, МАКС_ПОВТОРА)):
        r = строка + 1 + k
        for c0, знач, ф, повтор_к, шир, выс in ячейки:
            for j in range(повтор_к):
                c = c0 + j
                if c > МАКС_КОЛОНОК:
                    break
                if знач is not None:
                    лист.яч[(r, c)] = знач
                else:
                    try:
                        текст = _сдвиг(_формула_odf(ф), k, j)
                    except _НеСчитается:
                        текст = None
                    лист.формулы[(r, c)] = (текст, None)
                if (шир > 1 or выс > 1) and not k and not j:
                    лист.объединения.append((r, c, r + выс - 1, c + шир - 1))
        лист.строк += 1
        лист.макс_строка = r
        if _полон(лист, предел):
            break
    return строка + повтор


def _листы_ods(поток) -> list[_Лист]:
    """content.xml из .ods или весь .fods — разбор один и тот же. Скрытый лист в
    ODS задан не атрибутом листа, а его стилем: table:display="false"."""
    листы: list[_Лист] = []
    скрытые: set[str] = set()
    стиль = None
    лист = None
    глубина = 0
    строка = 0
    предел = МАКС_СТРОК_ЛИСТА
    бюджет = _Бюджет()
    try:
        for событие, эл in ET.iterparse(поток, events=("start", "end")):
            и = _имя(эл.tag)
            if событие == "start":
                if и == "style":
                    стиль = _атр(эл, "name") if _атр(эл, "family") == "table" else None
                elif и == "table-properties" and стиль and _атр(эл, "display") == "false":
                    скрытые.add(стиль)
                elif и == "table":
                    глубина += 1
                    if глубина == 1:
                        лист = _Лист(_атр(эл, "name") or f"Лист{len(листы) + 1}", len(листы) + 1,
                                     _атр(эл, "style-name") in скрытые)
                        листы.append(лист)
                        строка = 0
                        предел = бюджет.выдать(лист)
                continue
            if и == "table-row" and лист is not None and глубина == 1:
                if not (лист.обрезан or лист.пропущен):
                    строка = _ряд_ods(эл, лист, строка, предел)
                эл.clear()
            elif и == "table":
                глубина -= 1
                if глубина == 0 and лист is not None:
                    бюджет.списать(лист)
                    лист = None
                    эл.clear()
            elif и == "style":
                стиль = None
    except Exception:                                               # noqa: BLE001
        if лист is not None:
            лист.испорчен = True
    return листы


