@dataclass
class _Лист:
    имя: str
    номер: int                      # место в книге, с единицы; им подписана метка
    скрытый: bool = False
    яч: dict = field(default_factory=dict)            # (r, c) -> float | str | bool
    даты: dict = field(default_factory=dict)          # (r, c) -> «д» | «дв» | «в»
    формулы: dict = field(default_factory=dict)       # (r, c) -> (текст | ("общая", si) | None, запасное)
    общие_формулы: dict = field(default_factory=dict)  # si -> (текст, r, c)
    объединения: list = field(default_factory=list)   # (r1, c1, r2, c2)
    строк: int = 0                  # строк со значениями
    макс_строка: int = 0            # последняя прочитанная строка
    предел_яч: int = МАКС_ЯЧЕЕК     # сколько ячеек этому листу осталось от книги
    обрезан: bool = False
    испорчен: bool = False
    пропущен: bool = False


def _ячеек(лист: _Лист) -> int:
    return len(лист.яч) + len(лист.формулы)


def _полон(лист: _Лист, предел_строк: int) -> bool:
    """Предел листа исчерпан — по строкам или по ячейкам. Ставит «обрезан»."""
    if лист.строк >= предел_строк or _ячеек(лист) >= лист.предел_яч:
        лист.обрезан = True
    return лист.обрезан


class _Бюджет:
    """Что осталось книге: строки и ячейки. Лист берёт из остатка, а не из
    полного предела, иначе предел книги был бы пределом листа × число листов."""

    def __init__(self):
        self.строк, self.ячеек = МАКС_СТРОК, МАКС_ЯЧЕЕК

    def выдать(self, лист: _Лист) -> int:
        """Предел строк листу; ноль — лист не читается (пропущен)."""
        лист.предел_яч = max(0, self.ячеек)
        предел = min(МАКС_СТРОК_ЛИСТА, self.строк) if self.ячеек > 0 else 0
        лист.пропущен = предел <= 0
        return предел

    def списать(self, лист: _Лист) -> None:
        self.строк -= лист.строк
        self.ячеек -= _ячеек(лист)


def _собрать(листы: list[_Лист], режим: str, путь: str, счёт, текст: str,
             потери: list[str], d1904: bool) -> Книга:
    """Формулы, объединения, метки и причина — общие для всех видов книги."""
    _Вычислитель(листы).всё(счёт)
    строки: list[list[str]] = []
    данных = 0
    # Видимые листы — первыми. Скрытый лист чаще всего справочник для выпадающих
    # списков (валюты, единицы); он читается, но в предел строк идёт последним.
    for лист in sorted(листы, key=lambda л: (л.скрытый, л.номер)):
        счёт["листов"] += 1
        счёт["скрытых"] += лист.скрытый
        счёт["листов_обрезано"] += лист.обрезан
        счёт["листов_испорчено"] += лист.испорчен
        счёт["листов_пропущено"] += лист.пропущен
        счёт["объединений"] += len(лист.объединения)
        ряды = _строки_листа(лист, режим, d1904, счёт)
        if not ряды:
            continue
        if данных + len(ряды) > МАКС_СТРОК:
            ряды = ряды[:МАКС_СТРОК - данных]
            счёт["листов_обрезано"] += not лист.обрезан
            if not ряды:
                continue
        метка = f"{МЕТКА_ЛИСТА} {лист.номер} «{лист.имя.strip()}»" + (" (скрытый)" if лист.скрытый else "")
        строки.append([метка])
        строки.extend(ряды)
        данных += len(ряды)
    счёт["строк"] = данных
    п = list(потери)
    if счёт["формул_без_значения"]:
        п.append(f"формул без значения {счёт['формул_без_значения']}")
    if счёт["листов_обрезано"]:
        п.append(f"листов обрезано по пределу: {счёт['листов_обрезано']}")
    if счёт["листов_пропущено"]:
        п.append(f"листов не прочитано сверх предела книги: {счёт['листов_пропущено']}")
    if счёт["листов_испорчено"]:
        п.append(f"листов с испорченной разметкой: {счёт['листов_испорчено']}")
    if not строки and not текст:
        if счёт["картинок"]:
            # Скан, вклеенный в лист картинкой: читать его — дело распознавания.
            п.append(f"ячеек нет, картинок {счёт['картинок']}: нужен распознаватель")
        elif not п:
            п.append(f"книга без заполненных ячеек (листов {len(листы)})")
    return Книга(строки, текст, " · ".join(п), путь)


_ЧИСЛО_ТЕКСТОМ = re.compile(r"^-?\d[\d \u00a0]*(?:[.,]\d+)?$")


def _строки_листа(лист: _Лист, режим: str, d1904: bool, счёт) -> list[list[str]]:
    сетка: dict[tuple[int, int], str] = {}
    числа: set[tuple[int, int]] = set()
    for место, v in лист.яч.items():
        вид = лист.даты.get(место)
        if isinstance(v, bool):
            т = "TRUE" if v else "FALSE"
        elif isinstance(v, (int, float)):
            т = _дата(float(v), вид, d1904) if вид else _число(v)
            if not вид:
                числа.add(место)
        else:
            т = str(v).strip()
            if _ЧИСЛО_ТЕКСТОМ.match(т):
                числа.add(место)
        if т:
            сетка[место] = т
    if сетка and лист.объединения and режим != "нет":
        _размножить(сетка, числа, лист.объединения, режим, счёт)
    ряды: dict[int, dict[int, str]] = defaultdict(dict)
    for (r, c), т in сетка.items():
        ряды[r][c] = т
    out = []
    for r in sorted(ряды):
        ряд = ряды[r]
        строка = [""] * max(ряд)
        for c, т in ряд.items():
            строка[c - 1] = т
        out.append(строка)
    return out


def _размножить(сетка: dict, числа: set, объединения: list, режим: str, счёт) -> None:
    """Значение объединённой ячейки — в ячейки области.

    «вся» — буквально на всю область. Это даёт три вреда, каждый на обычной форме:
      1) позиция высотой в две строки, где слиты ВСЕ ячейки (просто высокая
         строка), становится двумя одинаковыми позициями — спрос удваивается;
      2) заголовок раздела «Насосы», растянутый на всю ширину, попадает в колонку
         наименования и становится позицией;
      3) шапка в две строки («Наименование» слито по вертикали, «Цена» разбита на
         «руб.» и «USD» под ней) даёт строку «Наименование руб. USD» в теле.

    «по_смыслу» (по умолчанию) отличает позицию от шапки ЧИСЛОМ: у строки позиции
    есть номер, количество или цена, у шапки и подписи — только слова.
      • подпись (в строке больше ничего нет) — не размножается вовсе;
      • строка без чисел (шапка) — только вширь: «Цена» над «руб.» и «USD»
        достаётся обеим колонкам;
      • строка с числом (позиция) — только вниз, только текст и только в те
        строки области, где есть своё число. Так наименование доходит до каждого
        варианта цены, а цена комплекта, слитая на три строки комплектующих,
        не утраивается.
    «нет» — оставить как в файле.
    """
    макс_r = max(r for r, _ in сетка)
    макс_c = max(c for _, c in сетка)
    по_рядам: dict[int, set[int]] = defaultdict(set)
    числа_по_рядам: dict[int, set[int]] = defaultdict(set)
    for r, c in сетка:
        по_рядам[r].add(c)
    for r, c in числа:
        числа_по_рядам[r].add(c)
    for r1, c1, r2, c2 in объединения:
        v = сетка.get((r1, c1))
        if not v:
            continue
        r2, c2 = min(r2, макс_r), min(c2, макс_c)
        if r2 < r1 or c2 < c1 or (r2 - r1 + 1) * (c2 - c1 + 1) > МАКС_ОБЛАСТИ:
            continue

        def вне(r: int, где: dict = по_рядам) -> bool:
            return any(c < c1 or c > c2 for c in где.get(r, ()))

        if режим == "вся":
            цели = [(r, c) for r in range(r1, r2 + 1) for c in range(c1, c2 + 1) if (r, c) != (r1, c1)]
        elif not вне(r1):
            цели = []
        elif вне(r1, числа_по_рядам):
            цели = ([] if (r1, c1) in числа else
                    [(r, c1) for r in range(r1 + 1, r2 + 1) if вне(r, числа_по_рядам)])
        else:
            цели = [(r1, c) for c in range(c1 + 1, c2 + 1)]
        for место in цели:
            сетка[место] = v
        счёт["размножено"] += len(цели)


