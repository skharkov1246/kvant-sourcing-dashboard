@dataclass
class Книга:
    """Результат разбора. строки/текст/причина — договор indexer.читать;
    путь и счёт — служебное: чем прочитана и что по дороге насчитано."""
    строки: list[list[str]] = field(default_factory=list)
    текст: str = ""
    причина: str = ""
    путь: str = ""
    счёт: dict[str, int] = field(default_factory=dict)


def прочитать_книгу(b: bytes, объединения: str = "по_смыслу") -> tuple[list[list[str]], str, str]:
    """(строки, текст, причина). Замена rows_from_xlsx/rows_from_xls. Не бросает."""
    к = разобрать_книгу(b, объединения=объединения)
    return к.строки, к.текст, к.причина


def разобрать_книгу(b: bytes, *, объединения: str = "по_смыслу") -> Книга:
    """То же, что прочитать_книгу, плюс служебные счётчики (Книга.счёт)."""
    счёт: defaultdict[str, int] = defaultdict(int)
    try:
        if объединения not in ВИДЫ_ОБЪЕДИНЕНИЙ:
            объединения = "по_смыслу"
        к = _разобрать(bytes(b or b""), объединения, счёт)
    except Exception as e:                                          # noqa: BLE001
        к = Книга(причина=f"книга: сбой разбора ({type(e).__name__})")
    к.счёт = {k: int(v) for k, v in счёт.items() if v}
    if not к.строки and not к.текст and not к.причина:
        к.причина = "книга без заполненных ячеек"
    return к


def это_метка(ряд: list[str]) -> bool:
    """Строка-метка листа, которую ставит этот модуль."""
    return (len(ряд) == 1 and isinstance(ряд[0], str)
            and ряд[0].startswith(МЕТКА_ЛИСТА + " "))


def по_листам(строки: list[list[str]]) -> list[tuple[str, list[list[str]]]]:
    """Строки книги обратно по листам: [(метка, строки листа)].

    ЗАЧЕМ. items_from_rows ищет шапку в первых 40 строках ВСЕГО списка и
    применяет её ко всем строкам ниже. На книге из двух листов с разной шапкой
    второй лист разбирается колонками первого. Отдельный разбор каждого листа
    даёт каждому свою шапку."""
    out: list[tuple[str, list[list[str]]]] = []
    метка, тело = "", []
    for ряд in строки:
        if это_метка(ряд):
            if тело or метка:
                out.append((метка, тело))
            метка, тело = ряд[0], []
        else:
            тело.append(ряд)
    if тело or метка:
        out.append((метка, тело))
    return out


def _разобрать(b: bytes, режим: str, счёт) -> Книга:
    if not b:
        return Книга(причина="пустой файл")
    if b[:2] == b"PK":
        return _из_архива(b, режим, счёт)
    if b[:8] == _OLE2:
        if _ЗАШИФРОВАН in b:
            return Книга(путь="ole2", причина="книга зашифрована паролем: без пароля не читается")
        if not _ole2_цепи_целы(b):
            return Книга(путь="ole2", причина="OLE2 испорчен: цепочка секторов книги зациклена")
        листы, почему, d1904 = _листы_xls(b)
        if not листы:
            return Книга(путь="xls", причина=почему)
        return _собрать(листы, режим, "xls", счёт, "", [], d1904)
    голова = b[:16384].decode("utf-8", "ignore").lstrip("\ufeff \t\r\n").lower()
    if голова.startswith("<"):
        if "urn:schemas-microsoft-com:office:spreadsheet" in голова:
            return _собрать(_листы_ssml(io.BytesIO(b)), режим, "spreadsheetml", счёт, "", [], False)
        if "opendocument.spreadsheet" in голова:
            return _собрать(_листы_ods(io.BytesIO(b)), режим, "fods", счёт, "", [], False)
    return Книга(причина="не книга: ни zip, ни OLE2, ни XML таблицы")


