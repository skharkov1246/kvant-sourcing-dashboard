МАКС_ПОВТОРА = 1000

#: Сколько формул пересчитывать на книгу и насколько глубоко идти по ссылкам.
МАКС_ФОРМУЛ = 200000
МАКС_ГЛУБИНЫ = 64

#: Объединение, растянутое на всю область, не должно порождать миллионы ячеек:
