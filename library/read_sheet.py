МАКС_СТРОК = 40000
МАКС_СТРОК_ЛИСТА = 20000

#: Колонок в строке. Настоящая широкая таблица (сводка по датам) — сотни колонок;
#: 16 384 (XFD) бывает только у стиля, растянутого на весь ряд.
