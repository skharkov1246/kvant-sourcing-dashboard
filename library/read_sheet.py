#: Номера сектора от этого и выше — служебные метки OLE2: конец цепочки,
#: свободный сектор, сектор FAT, сектор DIFAT.
_КОНЕЦ_ЦЕПИ = 0xFFFFFFFA


class _Цикл(Exception):
    pass


def _цепь(начало: int, таблица, предел: int) -> list[int]:
    out, видено, s = [], set(), начало
    while s < _КОНЕЦ_ЦЕПИ:
        if s in видено or len(out) > предел:
            raise _Цикл
        if s >= len(таблица):
            break
        видено.add(s)
        out.append(s)
        s = таблица[s]
    return out


def ole2_цепи_целы(b: bytes) -> bool:
    """Открытая проверка для прежнего пути indexer.rows_from_xls (см. ниже)."""
    return _ole2_цепи_целы(b)


def _ole2_цепи_целы(b: bytes) -> bool:
    """Не зациклена ли цепочка секторов потока книги в контейнере OLE2.

    ЗАЧЕМ. xlrd читает «малый» поток (меньше 4 096 байт) по мини-таблице
    размещения без учёта пройденных секторов, а исчерпав длину, продолжает класть
    пустые куски до конца цепочки. Зацикленная цепочка не кончается никогда:
    порча нескольких байт в .xls на 7 КБ выбрала 1,8 ГБ за 22 секунды (замер
    23.09.2026), а без предела памяти процесс убивается целиком — и с ним вся
    часть прогона. Здесь цепочка проходится заранее, с учётом пройденного.

    Прочая порча здесь не судится — её назовёт xlrd. Поэтому любой сбой этого
    разбора означает «целы», и решение остаётся за xlrd."""
    try:
        сдвиг, мини_сдвиг = struct.unpack_from("<HH", b, 30)
        if not 7 <= сдвиг <= 16 or мини_сдвиг >= сдвиг:
            return True
        размер = 1 << сдвиг
        слов = размер // 4
        n_fat, первый_каталог = struct.unpack_from("<II", b, 44)
        отсечка, первый_мини, _, первый_difat, _ = struct.unpack_from("<IIIII", b, 56)

        def сектор(s: int):
            нач = (s + 1) * размер
            return struct.unpack_from(f"<{слов}I", b, нач) if нач + размер <= len(b) else None

        difat = list(struct.unpack_from("<109I", b, 76))
        s, видено = первый_difat, set()
        while s < _КОНЕЦ_ЦЕПИ and s not in видено and len(difat) < n_fat + слов:
            видено.add(s)
            знач = сектор(s)
            if знач is None:
                break
            difat.extend(знач[:-1])
            s = знач[-1]
        fat: list[int] = []
        for s in difat[:n_fat]:
            знач = сектор(s) if s < _КОНЕЦ_ЦЕПИ else None
            if знач is not None:
                fat.extend(знач)
        каталог = b"".join(b[(s + 1) * размер:(s + 2) * размер] for s in _цепь(первый_каталог, fat, len(fat)))
        for k in range(0, len(каталог) - 127, 128):
            запись = каталог[k:k + 128]
            длина = min(struct.unpack_from("<H", запись, 64)[0], 64)
            имя = запись[:max(0, длина - 2)].decode("utf-16-le", "ignore").lower()
            if запись[66] == 2 and имя in ("workbook", "book"):
                начало, размер_потока = struct.unpack_from("<II", запись, 116)
                if размер_потока < отсечка:     # большой поток xlrd проходит с учётом сам
                    мини = [v for s in _цепь(первый_мини, fat, len(fat)) for v in (сектор(s) or ())]
                    _цепь(начало, мини, len(мини))
        return True
    except _Цикл:
        return False
    except Exception:                                               # noqa: BLE001
        return True



def _листы_xls(b: bytes) -> tuple[list[_Лист], str, bool]:
    """Старый .xls через xlrd. formatting_info=True нужен ради объединений: без
    него xlrd их не читает. На части файлов он падает — тогда второй заход без."""
    try:
        import xlrd
    except ImportError:
        return [], "xls: нет пакета xlrd", False
    книга, ошибка = None, None
    for формат in (True, False):
        try:
            # logfile — ОБЯЗАТЕЛЬНО. По умолчанию xlrd пишет предупреждения в
            # stdout, и в них имя листа («MERGEDCELLS bad range» на листе «КП
            # поставщика»): в публичный журнал прогона это не должно попасть
            # (CLAUDE.md, правило 17). Поймано 23.09.2026 порчей .xls.
            книга = xlrd.open_workbook(file_contents=b, formatting_info=формат,
                                       logfile=io.StringIO(), verbosity=0)
            break
        except Exception as e:                                      # noqa: BLE001
            ошибка = e
    if книга is None:
        if "encrypt" in str(ошибка).lower():
            return [], "xls зашифрована паролем: без пароля не читается", False
        return [], f"OLE2 не открылся книгой ({type(ошибка).__name__}): возможно, это .doc или .msg", False
    листы: list[_Лист] = []
    бюджет = _Бюджет()
    for н, sh in enumerate(книга.sheets(), 1):
        лист = _Лист(str(sh.name), н, getattr(sh, "visibility", 0) != 0)
        листы.append(лист)
        предел = бюджет.выдать(лист)
        if not предел:
            continue
        for r in range(sh.nrows):
            есть = False
            for c, яч in enumerate(sh.row(r)[:МАКС_КОЛОНОК], 1):
                т = яч.ctype
                if т == 1:
                    знач = яч.value
                elif т in (2, 3):
                    знач = float(яч.value)
                elif т == 4:
                    знач = bool(яч.value)
                elif т == 5:
                    знач = _Ошибка(xlrd.error_text_from_code.get(яч.value, "#ERR"))
                else:
                    continue
                if знач == "":
                    continue
                лист.яч[(r + 1, c)] = знач
                if т == 3:
                    лист.даты[(r + 1, c)] = "в" if знач < 1 else "дв"
                есть = True
            if есть:
                лист.строк += 1
                лист.макс_строка = r + 1
            if лист.строк >= предел or _ячеек(лист) >= лист.предел_яч:
                лист.обрезан = r + 1 < sh.nrows          # последняя строка — не обрезка
                break
        for rlo, rhi, clo, chi in getattr(sh, "merged_cells", None) or []:
            if rhi > rlo and chi > clo:
                лист.объединения.append((rlo + 1, clo + 1, rhi, chi))
        бюджет.списать(лист)
    return листы, "", getattr(книга, "datemode", 0) == 1


