#: Местные имена тегов. Различных тегов в книге десятки, а элементов — миллион
#: (лист 20 000 × 12 даёт 1,24 млн вызовов): разбор имени каждый раз заново
#: занимал седьмую часть всего чтения.
_МЕСТНОЕ: dict = {}


def _имя(тег) -> str:
    и = _МЕСТНОЕ.get(тег)
    if и is None:
        и = тег.rpartition("}")[2] if isinstance(тег, str) else ""
        if len(_МЕСТНОЕ) < 4096:
            _МЕСТНОЕ[тег] = и
    return и


def _атр(эл, имя: str):
    """Атрибут по местному имени: в ODS и SpreadsheetML все атрибуты с
    пространством имён, а префиксы у разных писателей разные."""
    v = эл.get(имя)
    if v is not None:
        return v
    хвост = "}" + имя
    for k, v in эл.attrib.items():
        if k.endswith(хвост):
            return v
    return None


def _целое(s, иначе: int) -> int:
    try:
        return int(s)
    except (TypeError, ValueError):
        return иначе


def _естественно(s: str):
    """sheet2 раньше sheet10: при сортировке строкой было бы наоборот."""
    return [int(ч) if ч.isdigit() else ч for ч in re.split(r"(\d+)", s)]


_X_ESC = re.compile(r"_x([0-9A-Fa-f]{4})_")


def _снять_x(s: str) -> str:
    """OOXML пишет управляющие знаки как _x000D_. Без разворота в наименовании
    остаётся «Насос_x000D_ЦНС»."""
    return _X_ESC.sub(lambda m: chr(int(m.group(1), 16)), s) if "_x" in s else s


_АДРЕС = re.compile(r"\$?([A-Za-z]{1,3})\$?(\d+)$")
_КОЛОНКИ: dict[str, int] = {}


def _кол(буквы: str) -> int:
    n = _КОЛОНКИ.get(буквы)
    if n is None:
        n = 0
        for ч in буквы.upper():
            n = n * 26 + (ord(ч) - 64)
        if len(_КОЛОНКИ) < 20000:
            _КОЛОНКИ[буквы] = n
    return n


def _буквы(n: int) -> str:
    s = ""
    while n > 0:
        n, ост = divmod(n - 1, 26)
        s = chr(65 + ост) + s
    return s


def _адрес(ссылка: str) -> tuple[int, int] | None:
    m = _АДРЕС.match(ссылка) or _АДРЕС.match(ссылка.strip())
    if not m:
        return None
    return int(m.group(2)), _кол(m.group(1))


def _область(ссылка: str) -> tuple[int, int, int, int] | None:
    части = ссылка.split(":")
    a, b = _адрес(части[0]), _адрес(части[-1])
    if not a or not b:
        return None
    return min(a[0], b[0]), min(a[1], b[1]), max(a[0], b[0]), max(a[1], b[1])


def _число(x) -> str:
    """Число как текст. Целое — без «.0»; дробное — 15 значащих знаков, как
    показывает Excel: 12.300000000000001 из разметки становится «12.3»."""
    if isinstance(x, bool):
        return "TRUE" if x else "FALSE"
    if isinstance(x, int):
        return str(x)
    if math.isnan(x) or math.isinf(x):
        return ""
    if x == int(x) and abs(x) < 1e15:
        return str(int(x))
    return f"{x:.15g}"


_ЭПОХА_1900 = dt.datetime(1899, 12, 30)
_ЭПОХА_1904 = dt.datetime(1904, 1, 1)


def _дата(x: float, вид: str, d1904: bool) -> str:
    """Порядковый номер дня Excel — в дату. Вид: «д» дата, «дв» дата и время,
    «в» только время."""
    if not 0 <= x < 2958466:                     # за 31.12.9999 — это не дата
        return _число(x)
    if вид == "в":
        сек = round((x % 1) * 86400) % 86400
        ч, ост = divmod(сек, 3600)
        м, с = divmod(ост, 60)
        return f"{ч:02d}:{м:02d}" + (f":{с:02d}" if с else "")
    if x < 1:
        return _число(x)
    if d1904:
        момент = _ЭПОХА_1904 + dt.timedelta(seconds=round(x * 86400))
    else:
        # Excel считает 1900 год високосным: номера до 60 сдвинуты на день.
        момент = _ЭПОХА_1900 + dt.timedelta(seconds=round((x + (1 if x < 60 else 0)) * 86400))
    текст = момент.strftime("%d.%m.%Y")
    if вид == "дв" and (момент.hour or момент.minute or момент.second):
        текст += момент.strftime(" %H:%M")
    return текст


def _показ_момента(м) -> str:
    if isinstance(м, dt.datetime):
        т = м.strftime("%d.%m.%Y")
        return т + м.strftime(" %H:%M") if (м.hour or м.minute or м.second) else т
    if isinstance(м, dt.date):
        return м.strftime("%d.%m.%Y")
    if isinstance(м, dt.time):
        return м.strftime("%H:%M")
    return str(м)


def _дата_iso(v: str) -> str:
    s = (v or "").strip()
    try:
        return _показ_момента(dt.datetime.fromisoformat(s.replace("Z", "+00:00")))
    except ValueError:
        return s


def _время_iso(v: str) -> str:
    m = re.match(r"-?PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)(?:\.\d+)?S)?", (v or "").strip())
    if not m:
        return (v or "").strip()
    ч, мин, с = (_целое(g, 0) for g in m.groups())
    return f"{ч:02d}:{мин:02d}" + (f":{с:02d}" if с else "")


#: Встроенные номера форматов, которые означают дату или время. 27–36 и 50–58 —
#: китайские и японские даты: в наших данных китайских КП больше всего (CNY —
#: 11 247 строк цены из 22 084, indexer.py), а openpyxl эти номера датой не считает.
_ДАТЫ_ВСТРОЕННЫЕ = {**{n: "д" for n in (14, 15, 16, 17, 27, 28, 29, 30, 31, 36,
                                        50, 51, 52, 53, 54, 55, 56, 57, 58)},
                    22: "дв",
                    **{n: "в" for n in (18, 19, 20, 21, 32, 33, 34, 35, 45, 46, 47)}}


def _вид_формата(код: str) -> str | None:
    """Дата ли это по строке формата. Снимаются литералы в кавычках, экранированные
    знаки, заполнители и скобки ([Red], [$₽-419]); остаются коды d, m, y, h, s."""
    if not код:
        return None
    c = код.split(";")[0]
    c = re.sub(r'"[^"]*"', "", c)
    c = re.sub(r"\\.", "", c)
    c = re.sub(r"[_*].", "", c)
    c = re.sub(r"\[[hHmMsS]+\]", "h", c)            # [h]:mm — прошедшее время
    c = re.sub(r"\[[^\]]*\]", "", c)
    low = c.lower().strip()
    if low in ("general", "@", ""):
        return None
    # Заполнители числа: у даты их не бывает, кроме долей секунды «mm:ss.0».
    if "#" in c or "?" in c or ("0" in c and ":" not in c):
        return None
    дата = bool(re.search(r"[dy]", low))
    время = bool(re.search(r"[hs]", low)) or "am/pm" in low
    if дата and время:
        return "дв"
    if дата:
        return "д"
    if время:
        return "в"
    return "д" if "m" in low else None               # «mmmm» — месяц словом


def _вид_номера(n: int, форматы: dict[int, str]) -> str | None:
    if n in форматы:
        return _вид_формата(форматы[n])
    return _ДАТЫ_ВСТРОЕННЫЕ.get(n)


