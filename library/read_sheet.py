def _значение_ssml(данные):
    тип = _атр(данные, "Type") or "String"
    текст = "".join(данные.itertext())
    s = текст.strip()
    if тип == "Number":
        try:
            return float(s)
        except ValueError:
            return s or None
    if тип == "DateTime":
        return _дата_iso(s) if s else None
    if тип == "Boolean":
        return s in ("1", "true")
    if тип == "Error":
        return _Ошибка(s) if s else None
    return текст if s else None


def _листы_ssml(поток) -> list[_Лист]:
    """Выгрузка 1С «.xls», которая внутри XML. У readers.rows_from_spreadsheetml
    нет объединений (ss:MergeAcross, ss:MergeDown), а 1С сливает ячейки охотно."""
    листы: list[_Лист] = []
    лист = None
    строка = кол = 0
    есть = False
    предел = МАКС_СТРОК_ЛИСТА
    бюджет = _Бюджет()
    try:
        for событие, эл in ET.iterparse(поток, events=("start", "end")):
            и = _имя(эл.tag)
            if событие == "start":
                if и == "Worksheet":
                    лист = _Лист(_атр(эл, "Name") or f"Лист{len(листы) + 1}", len(листы) + 1)
                    листы.append(лист)
                    строка = 0
                    предел = бюджет.выдать(лист)
                elif и == "Row" and лист is not None:
                    строка = _целое(_атр(эл, "Index"), строка + 1)
                    кол, есть = 0, False
                continue
            if лист is None:
                continue
            if и == "Cell" and not (лист.обрезан or лист.пропущен):
                кол = _целое(_атр(эл, "Index"), кол + 1)
                данные = next((ч for ч in эл if _имя(ч.tag) == "Data"), None)
                знач = _значение_ssml(данные) if данные is not None else None
                if кол <= МАКС_КОЛОНОК and знач is not None and знач != "":
                    лист.яч[(max(строка, 1), кол)] = знач
                    есть = True
                elif данные is None and _атр(эл, "Formula") and кол <= МАКС_КОЛОНОК:
                    # Формула в записи R1C1 без значения: пересчёта нет, но счёт есть.
                    лист.формулы[(max(строка, 1), кол)] = (None, None)
                вширь = max(0, _целое(_атр(эл, "MergeAcross"), 0))
                вниз = max(0, _целое(_атр(эл, "MergeDown"), 0))
                if вширь or вниз:
                    лист.объединения.append((max(строка, 1), кол, max(строка, 1) + вниз, кол + вширь))
                кол += вширь
            elif и == "Row":
                if есть:
                    лист.строк += 1
                    лист.макс_строка = строка
                if not лист.пропущен:
                    _полон(лист, предел)
                эл.clear()
            elif и == "Visible" and (эл.text or "").strip() in ("SheetHidden", "SheetVeryHidden"):
                лист.скрытый = True
            elif и == "Worksheet":
                бюджет.списать(лист)
                лист = None
    except Exception:                                               # noqa: BLE001
        if лист is not None:
            лист.испорчен = True
    return листы


