def _листы_openpyxl(b: bytes) -> list[_Лист] | None:
    """Запасной путь: книга, на разметке которой свой разбор ничего не нашёл.
    Без объединений — read_only их не отдаёт; даты openpyxl распознаёт сам."""
    try:
        import openpyxl
    except ImportError:
        return None
    try:
        книга = openpyxl.load_workbook(io.BytesIO(b), read_only=True, data_only=True)
    except Exception:                                               # noqa: BLE001
        return None
    листы: list[_Лист] = []
    бюджет = _Бюджет()
    try:
        for н, ws in enumerate(книга.worksheets, 1):
            лист = _Лист(str(ws.title), н, getattr(ws, "sheet_state", "visible") != "visible")
            листы.append(лист)
            предел = бюджет.выдать(лист)
            if not предел:
                continue
            for r, ряд in enumerate(ws.iter_rows(values_only=True), 1):
                есть = False
                for c, v in enumerate(ряд[:МАКС_КОЛОНОК], 1):
                    if v is None or v == "":
                        continue
                    if isinstance(v, (dt.datetime, dt.date, dt.time)):
                        v = _показ_момента(v)
                    elif not isinstance(v, (bool, int, float, str)):
                        v = str(v)
                    лист.яч[(r, c)] = v
                    есть = True
                if есть:
                    лист.строк += 1
                    лист.макс_строка = r
                if _полон(лист, предел):
                    break
            бюджет.списать(лист)
    except Exception:                                               # noqa: BLE001
        if листы:
            листы[-1].испорчен = True
    finally:
        try:
            книга.close()
        except Exception:                                           # noqa: BLE001, S110
            pass
    return листы


