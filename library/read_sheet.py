def _из_архива(b: bytes, режим: str, счёт) -> Книга:
    архив = _Архив(b)
    имена = архив.имена
    if not имена:
        return Книга(путь="zip", причина="архив не читается: ни одного участника")
    потери = ["архив книги повреждён: прочитаны уцелевшие части"] if архив.починен else []
    if any(re.search(r"(^|/)(workbook\.bin|worksheets/[^/]+\.bin)$", и) for и in имена):
        return _книга_xlsb(архив, режим, счёт, потери)
    if "content.xml" in имена:
        вид = ""
        if архив.есть("mimetype"):
            try:
                вид = архив.прочитать("mimetype", 200).decode("ascii", "ignore")
            except Exception:                                       # noqa: BLE001
                вид = ""
        if вид and "spreadsheet" not in вид:
            return Книга(путь="odf", причина=f"документ ODF, но не таблица ({вид.rsplit('.', 1)[-1][:20]})")
        try:
            листы = _листы_ods(архив.открыть("content.xml"))
        except Exception:                                           # noqa: BLE001
            листы = []
        return _собрать(листы, режим, "ods", счёт, "", потери, False)
    if any(и.startswith("xl/") or и.startswith("worksheets/") or "/worksheets/" in и for и in имена):
        return _книга_xlsx(архив, режим, счёт, потери)
    return Книга(путь="zip", причина="архив без листов книги: не xlsx, не xlsb, не ods")


