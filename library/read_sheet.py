class _ОшибкаExcel(Exception):
    """Excel сам дал бы ошибку (#DIV/0!, #VALUE!). Это значение: его ловит IFERROR."""


class _НеСчитается(Exception):
    """Посчитать нельзя: незнакомая функция, внешняя ссылка, цикл. Значение
    неизвестно, и выдумывать его нельзя — ячейка остаётся пустой."""


#: Лексемы формулы. Функция проверяется раньше ссылки: «LOG10(» похоже на адрес.
_ФТОКЕН = re.compile(r"""
 (?P<стр>"(?:[^"]|"")*")
|(?P<функция>[A-Za-z_][A-Za-z0-9_.]*)\s*\(
|(?P<ссылка>(?:(?:'(?:[^']|'')+'|[^\W\d][\w.]*)!)?\$?[A-Za-z]{1,3}\$?\d+(?::\$?[A-Za-z]{1,3}\$?\d+)?)(?![\w(])
|(?P<число>(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)
|(?P<имя>[A-Za-z_][A-Za-z0-9_.]*)
|(?P<оп><>|<=|>=|[-+*/^&=<>%(),;])
""", re.X)

_ЧАСТЬ_АДРЕСА = re.compile(r"(\$?)([A-Za-z]{1,3})(\$?)(\d+)")
_ССЫЛКА_ЦЕЛИКОМ = re.compile(r"(?:(?P<лист>'(?:[^']|'')+'|[^!]+)!)?(?P<a>\$?[A-Za-z]{1,3}\$?\d+)"
                             r"(?::(?P<b>\$?[A-Za-z]{1,3}\$?\d+))?$")


def _лексемы(текст: str) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    i, n = 0, len(текст)
    while i < n:
        if текст[i].isspace():
            i += 1
            continue
        m = _ФТОКЕН.match(текст, i)
        if not m:
            raise _НеСчитается
        out.append((m.lastgroup, m.group(m.lastgroup)))
        i = m.end()
    return out


def _сдвинуть_адрес(m: re.Match, dr: int, dc: int) -> str:
    кол = _кол(m.group(2)) + (0 if m.group(1) else dc)
    ряд = int(m.group(4)) + (0 if m.group(3) else dr)
    if кол < 1 or ряд < 1:
        raise _НеСчитается
    return f"{m.group(1)}{_буквы(кол)}{m.group(3)}{ряд}"


def _сдвиг(текст: str, dr: int, dc: int) -> str:
    """Общая формула: текст записан один раз у первой ячейки области, остальные
    ссылаются на него номером. Относительные адреса сдвигаются, $-адреса — нет."""
    if not dr and not dc:
        return текст
    out, i, n = [], 0, len(текст)
    while i < n:
        if текст[i].isspace():
            out.append(текст[i])
            i += 1
            continue
        m = _ФТОКЕН.match(текст, i)
        if not m:
            raise _НеСчитается
        if m.lastgroup == "ссылка":
            лист, воскл, адрес = m.group(0).rpartition("!")
            out.append(лист + воскл + _ЧАСТЬ_АДРЕСА.sub(lambda a: _сдвинуть_адрес(a, dr, dc), адрес))
        else:
            out.append(m.group(0))
        i = m.end()
    return "".join(out)


class _Разбор:
    """Разбор формулы в дерево. Порядок операций — как в Excel: сравнение, «&»,
    «+ -», «* /», «^», унарный минус, «%». Унарный минус сильнее степени:
    -2^2 = 4, как в Excel."""

    def __init__(self, лексемы: list[tuple[str, str]]):
        self.л, self.i = лексемы, 0

    def смотреть(self) -> tuple[str, str]:
        return self.л[self.i] if self.i < len(self.л) else ("конец", "")

    def взять(self) -> tuple[str, str]:
        т = self.смотреть()
        self.i += 1
        return т

    def _двоичный(self, дальше, знаки: tuple[str, ...]):
        лев = дальше()
        while self.смотреть()[0] == "оп" and self.смотреть()[1] in знаки:
            лев = ("оп", self.взять()[1], лев, дальше())
        return лев

    def выражение(self):
        return self._двоичный(self.сцепка, ("=", "<>", "<", ">", "<=", ">="))

    def сцепка(self):
        return self._двоичный(self.сложение, ("&",))

    def сложение(self):
        return self._двоичный(self.умножение, ("+", "-"))

    def умножение(self):
        return self._двоичный(self.степень, ("*", "/"))

    def степень(self):
        return self._двоичный(self.унарный, ("^",))

    def унарный(self):
        if self.смотреть()[0] == "оп" and self.смотреть()[1] in ("+", "-"):
            return ("знак", self.взять()[1], self.унарный())
        у = self.первичное()
        while self.смотреть() == ("оп", "%"):
            self.взять()
            у = ("%", у)
        return у

    def первичное(self):
        вид, т = self.взять()
        if вид == "число":
            return ("зн", float(т))
        if вид == "стр":
            return ("зн", т[1:-1].replace('""', '"'))
        if вид == "ссылка":
            return ("ссылка", т)
        if вид == "имя" and т.upper() in ("TRUE", "FALSE"):
            return ("зн", т.upper() == "TRUE")
        if вид == "функция":
            имя = re.sub(r"^_(?:XLFN|XLWS)\.", "", т.upper())
            арг = []
            if self.смотреть() == ("оп", ")"):
                self.взять()
                return ("ф", имя, арг)
            while True:
                if self.смотреть()[0] == "оп" and self.смотреть()[1] in (",", ";", ")"):
                    арг.append(("зн", None))                 # пропущенный аргумент
                else:
                    арг.append(self.выражение())
                вид2, т2 = self.взять()
                if (вид2, т2) == ("оп", ")"):
                    return ("ф", имя, арг)
                if not (вид2 == "оп" and т2 in (",", ";")):
                    raise _НеСчитается
        if (вид, т) == ("оп", "("):
            в = self.выражение()
            if self.взять() != ("оп", ")"):
                raise _НеСчитается
            return в
        raise _НеСчитается                       # имена диапазонов, массивы, «A:A»


def _разбор_формулы(текст: str):
    т = текст.strip()
    if т.startswith("="):
        т = т[1:]
    if not т or т.startswith("{") or len(т) > 8192:
        raise _НеСчитается
    р = _Разбор(_лексемы(т))
    дерево = р.выражение()
    if р.i != len(р.л):
        raise _НеСчитается
    return дерево


def _ч(v) -> float:
    """Число из значения, как в арифметике Excel. Текст «12,5» — число только
    если прочтение однозначно; иначе значение неизвестно (_НеСчитается), а не 0:
    Excel в русской и английской настройке прочтёт его по-разному."""
    if v is None:
        return 0.0
    if isinstance(v, bool):
        return 1.0 if v else 0.0
    if isinstance(v, (int, float)):
        return float(v)
    if isinstance(v, _Ошибка):
        raise _ОшибкаExcel(str(v))
    if isinstance(v, str):
        s = v.strip().replace("\u00a0", "").replace(" ", "")
        if not s:
            raise _ОшибкаExcel("#VALUE!")
        try:
            return float(s)
        except ValueError:
            pass
        if re.fullmatch(r"-?\d+,\d+", s):
            return float(s.replace(",", "."))
        raise _НеСчитается
    raise _НеСчитается


def _т(v) -> str:
    if v is None:
        return ""
    if isinstance(v, (bool, int, float)):
        return _число(v)
    return str(v)


def _истина(v) -> bool:
    if isinstance(v, bool):
        return v
    if v is None:
        return False
    if isinstance(v, (int, float)):
        return v != 0
    if isinstance(v, str) and v.strip().upper() in ("TRUE", "FALSE"):
        return v.strip().upper() == "TRUE"
    raise _ОшибкаExcel("#VALUE!")


def _сравнить(a, b, оп: str) -> bool:
    if a is None and isinstance(b, str):
        a = ""
    if b is None and isinstance(a, str):
        b = ""

    def ключ(v):
        if isinstance(v, bool):
            return (2, v)
        if v is None or isinstance(v, (int, float)):
            return (0, float(v or 0))
        return (1, str(v).lower())

    ka, kb = ключ(a), ключ(b)
    return {"=": ka == kb, "<>": ka != kb, "<": ka < kb, ">": ka > kb,
            "<=": ka <= kb, ">=": ka >= kb}[оп]


def _округлить(x: float, n: int, как: str) -> float:
    """ROUND Excel — половина от нуля, по десятичной записи числа (2,675 -> 2,68),
    а не по двоичной, как round() Питона (2,675 -> 2,67)."""
    if abs(n) > 15:
        raise _НеСчитается
    режим = {"ROUND": ROUND_HALF_UP, "ROUNDUP": ROUND_UP, "ROUNDDOWN": ROUND_DOWN}[как]
    try:
        return float(Decimal(repr(x)).quantize(Decimal(1).scaleb(-n), rounding=режим))
    except (InvalidOperation, ValueError):
        raise _НеСчитается from None


_ПРОВАЛ = object()


class _Вычислитель:
    """Пересчёт формул без сохранённого значения. Только арифметика, сцепка,
    сравнения и десяток функций, которыми считают цену: SUM, PRODUCT, MIN, MAX,
    AVERAGE, ROUND*, ABS, INT, IF, IFERROR, CONCAT*, VALUE. Всё прочее
    (VLOOKUP, имена диапазонов, внешние книги) — «не считается», и ячейка
    остаётся пустой: выдуманная цена хуже пропавшей."""

    def __init__(self, листы: list[_Лист]):
        self.листы = листы
        self.по_имени = {л.имя.strip().lower(): л for л in листы}
        self.готово: dict[tuple, object] = {}
        self.в_работе: set[tuple] = set()
        self.шагов = 0

    def всё(self, счёт) -> None:
        for лист in self.листы:
            # По строкам сверху вниз: нарастающий итог «=C2+B3» на тысячу строк
            # тогда считается по одной ссылке за раз, а не рекурсией в тысячу.
            for r, c in sorted(лист.формулы):
                try:
                    знач = self.формула(лист, r, c, 0)
                except _НеСчитается:
                    запасное = лист.формулы[(r, c)][1]
                    if запасное is not None:
                        лист.яч[(r, c)] = запасное
                    else:
                        счёт["формул_без_значения"] += 1
                    continue
                счёт["формул_пересчитано"] += 1
                if знач is not None and знач != "":
                    лист.яч[(r, c)] = знач

    def формула(self, лист: _Лист, r: int, c: int, гл: int):
        ключ = (лист.номер, r, c)
        if ключ in self.готово:
            знач = self.готово[ключ]
            if знач is _ПРОВАЛ:
                raise _НеСчитается
            return знач
        if ключ in self.в_работе or гл > МАКС_ГЛУБИНЫ or self.шагов >= МАКС_ФОРМУЛ:
            raise _НеСчитается
        self.шагов += 1
        текст = лист.формулы[(r, c)][0]
        self.в_работе.add(ключ)
        try:
            if isinstance(текст, tuple):
                мастер = лист.общие_формулы.get(текст[1])
                if мастер is None:
                    raise _НеСчитается
                текст = _сдвиг(мастер[0], r - мастер[1], c - мастер[2])
            if not текст:
                raise _НеСчитается
            try:
                знач = self.скаляр(_разбор_формулы(текст), лист, гл)
            except _ОшибкаExcel as e:
                знач = _Ошибка(e.args[0] if e.args else "#VALUE!")
            except (ZeroDivisionError, OverflowError, ValueError):
                знач = _Ошибка("#NUM!")
        except (_НеСчитается, RecursionError):
            self.готово[ключ] = _ПРОВАЛ
            raise _НеСчитается from None
        finally:
            self.в_работе.discard(ключ)
        self.готово[ключ] = знач
        return знач

    def ячейка(self, лист: _Лист, r: int, c: int, гл: int):
        if (r, c) in лист.формулы:
            return self.формула(лист, r, c, гл + 1)
        # За пределом прочитанного значение неизвестно, а не пусто: сумма по
        # столбцу обрезанного листа иначе вышла бы правдоподобной и неверной.
        if лист.пропущен or ((лист.обрезан or лист.испорчен) and r > лист.макс_строка):
            raise _НеСчитается
        return лист.яч.get((r, c))

    def ссылка(self, текст: str, лист: _Лист, гл: int):
        m = _ССЫЛКА_ЦЕЛИКОМ.match(текст)
        if not m:
            raise _НеСчитается
        цель = лист
        if m.group("лист"):
            имя = m.group("лист")
            if имя.startswith("'"):
                имя = имя[1:-1].replace("''", "'")
            цель = self.по_имени.get(имя.strip().lower())
            if цель is None:
                raise _НеСчитается
        r1, c1 = _адрес(m.group("a"))
        if not m.group("b"):
            return self.ячейка(цель, r1, c1, гл)
        r2, c2 = _адрес(m.group("b"))
        r1, r2 = min(r1, r2), max(r1, r2)
        c1, c2 = min(c1, c2), max(c1, c2)
        if (r2 - r1 + 1) * (c2 - c1 + 1) <= 20000:
            места = [(r, c) for r in range(r1, r2 + 1) for c in range(c1, c2 + 1)]
        else:
            if цель.пропущен or ((цель.обрезан or цель.испорчен) and r2 > цель.макс_строка):
                raise _НеСчитается
            места = sorted(к for к in {*цель.яч, *цель.формулы} if r1 <= к[0] <= r2 and c1 <= к[1] <= c2)
        return [self.ячейка(цель, r, c, гл) for r, c in места]

    def скаляр(self, у, лист: _Лист, гл: int):
        v = self.вычислить(у, лист, гл)
        if isinstance(v, list):
            if len(v) != 1:
                raise _НеСчитается
            v = v[0]
        if isinstance(v, _Ошибка):
            raise _ОшибкаExcel(str(v))
        return v

    def вычислить(self, у, лист: _Лист, гл: int):
        вид = у[0]
        if вид == "зн":
            return у[1]
        if вид == "ссылка":
            return self.ссылка(у[1], лист, гл)
        if вид == "знак":
            x = _ч(self.скаляр(у[2], лист, гл))
            return -x if у[1] == "-" else x
        if вид == "%":
            return _ч(self.скаляр(у[1], лист, гл)) / 100
        if вид == "ф":
            return self.функция(у[1], у[2], лист, гл)
        оп = у[1]
        a, b = self.скаляр(у[2], лист, гл), self.скаляр(у[3], лист, гл)
        if оп == "&":
            return _т(a) + _т(b)
        if оп in ("=", "<>", "<", ">", "<=", ">="):
            return _сравнить(a, b, оп)
        x, y = _ч(a), _ч(b)
        if оп == "+":
            return x + y
        if оп == "-":
            return x - y
        if оп == "*":
            return x * y
        if оп == "/":
            if y == 0:
                raise _ОшибкаExcel("#DIV/0!")
            return x / y
        р = x ** y
        if isinstance(р, complex):
            raise _ОшибкаExcel("#NUM!")
        return р

    def функция(self, имя: str, арг: list, лист: _Лист, гл: int):
        if имя == "IF":
            if not 1 <= len(арг) <= 3:
                raise _НеСчитается
            if _истина(self.скаляр(арг[0], лист, гл)):
                return self.скаляр(арг[1], лист, гл) if len(арг) > 1 else True
            return self.скаляр(арг[2], лист, гл) if len(арг) > 2 else False
        if имя == "IFERROR":
            if len(арг) != 2:
                raise _НеСчитается
            try:
                return self.скаляр(арг[0], лист, гл)
            except _ОшибкаExcel:
                return self.скаляр(арг[1], лист, гл)
        знач = [self.вычислить(a, лист, гл) for a in арг]
        if имя in ("SUM", "PRODUCT", "MIN", "MAX", "AVERAGE"):
            числа: list[float] = []
            for v in знач:
                for x in (v if isinstance(v, list) else [v]):
                    if isinstance(x, _Ошибка):
                        raise _ОшибкаExcel(str(x))
                    if isinstance(v, list):
                        # В диапазоне Excel берёт только числа: текст и пустоту пропускает.
                        if isinstance(x, (int, float)) and not isinstance(x, bool):
                            числа.append(float(x))
                    elif x is not None:
                        числа.append(_ч(x))
            if имя == "SUM":
                return math.fsum(числа)
            if имя == "PRODUCT":
                return math.prod(числа) if числа else 0.0
            if имя == "AVERAGE":
                if not числа:
                    raise _ОшибкаExcel("#DIV/0!")
                return math.fsum(числа) / len(числа)
            if not числа:
                return 0.0
            return min(числа) if имя == "MIN" else max(числа)
        if имя in ("ROUND", "ROUNDUP", "ROUNDDOWN"):
            if not 1 <= len(знач) <= 2:
                raise _НеСчитается
            n = int(_ч(self._один(знач[1]))) if len(знач) == 2 else 0
            return _округлить(_ч(self._один(знач[0])), n, имя)
        if имя in ("ABS", "INT", "VALUE") and len(знач) == 1:
            x = _ч(self._один(знач[0]))
            return abs(x) if имя == "ABS" else float(math.floor(x)) if имя == "INT" else x
        if имя in ("CONCATENATE", "CONCAT"):
            части = []
            for v in знач:
                for x in (v if isinstance(v, list) else [v]):
                    if isinstance(x, _Ошибка):
                        raise _ОшибкаExcel(str(x))
                    части.append(_т(x))
            return "".join(части)
        raise _НеСчитается

    @staticmethod
    def _один(v):
        if isinstance(v, list):
            if len(v) != 1:
                raise _НеСчитается
            v = v[0]
        if isinstance(v, _Ошибка):
            raise _ОшибкаExcel(str(v))
        return v
