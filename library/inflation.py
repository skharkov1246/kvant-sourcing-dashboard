"""Индексация цены на инфляцию валюты: цена месяца выдачи → цена на нужную дату.

ЗАЧЕМ. Решение владельца 26.09.2026: «Цена считается актуальной на дату выдачи,
потом индексируется на инфляцию». Цена 2021 года и цена 2026 года сравнимы
только приведёнными к одному месяцу; множитель — отношение индекса цен в стране
валюты на месяц «на» к индексу на месяц выдачи цены.

ДАННЫЕ — data/inflation/cpi_monthly.json (собирает scripts/fetch_inflation.py):
помесячный ИПЦ для RUB, USD, EUR, CNY, GBP с 2018-01. Почему ИПЦ, а не ИЦП, и
откуда каждое число — написано в самом файле и в сборщике.

ПРАВИЛА (каждое — оговорка в ответе, а не молчаливое допущение):
  · валюты нет в наборе — цена не индексируется: «индекса для … нет»;
  · месяц цены раньше начала ряда — цена не индексируется: догонять цену 2015
    года по ряду с 2018 нельзя, а подставить первый месяц — выдумать инфляцию
    за три года;
  · индекса за месяц нет (не опубликован ещё или пропущен источником — у США
    нет октября 2025) — берётся последний известный месяц до него, и это
    сказано: «индекс за 2026-09 не опубликован, взят 2026-08»;
  · индексируется уровень цен ВНУТРИ валюты. Курса здесь нет: пересчёт валют —
    отдельный шаг, и делать его надо после индексации, по курсу даты «на».

ЧИСТЫЕ ФУНКЦИИ. Единственное чтение с диска — файл индексов, один раз, и его
можно передать явно аргументом «ряды» (так делают тесты).

    >>> индексировать(100.0, "USD", "2024-01-15", "2025-01-15", ряды={"USD": {"2024-01": 200.0, "2025-01": 206.0}})
    (103.0, 1.03, None)
"""
from __future__ import annotations

import json
import re
from datetime import date, datetime
from functools import lru_cache
from pathlib import Path

PATH = Path(__file__).resolve().parent.parent / "data" / "inflation" / "cpi_monthly.json"

Ряды = dict[str, dict[str, float]]   # валюта → {"ГГГГ-ММ": значение индекса}

_МЕСЯЦ = re.compile(r"^(\d{4})-(\d{2})")


def загрузить(path: Path | str | None = None) -> Ряды:
    """Ряды из файла набора: {валюта: {месяц: значение}}."""
    doc = json.loads(Path(path or PATH).read_text(encoding="utf-8"))
    return {вал: {т["месяц"]: float(т["значение"]) for т in р["точки"]}
            for вал, р in doc["ряды"].items()}


@lru_cache(maxsize=1)
def _ряды_по_умолчанию() -> Ряды:
    return загрузить()


def месяц(д: date | datetime | str) -> str:
    """Дата в любом из видов → «ГГГГ-ММ». Строка — ISO: «2025-03», «2025-03-17…»."""
    if isinstance(д, (date, datetime)):
        return f"{д.year:04d}-{д.month:02d}"
    m = _МЕСЯЦ.match(str(д).strip())
    if not m or not 1 <= int(m[2]) <= 12:
        raise ValueError(f"не дата: {д!r}")
    return f"{m[1]}-{m[2]}"


def _точка(ряд: dict[str, float], мес: str) -> tuple[str | None, str | None]:
    """Месяц, чей индекс берётся для «мес», и оговорка, если это не он сам."""
    if мес in ряд:
        return мес, None
    раньше = [k for k in ряд if k < мес]
    if not раньше:
        return None, None
    взят = max(раньше)
    return взят, f"индекс за {мес} не опубликован, взят {взят}"


def индексировать(цена: float | None, валюта: str | None,
                  дата_цены: date | datetime | str, дата_на: date | datetime | str,
                  ряды: Ряды | None = None) -> tuple[float | None, float | None, str | None]:
    """(цена на дату «на», коэффициент, оговорка или None).

    Коэффициент = индекс(месяц «на») / индекс(месяц цены) одного ряда. Цена
    округляется до сотых, коэффициент — до шести знаков. Когда индексировать
    нельзя, коэффициент None, а цена возвращается как была — с оговоркой почему.
    """
    ряды = _ряды_по_умолчанию() if ряды is None else ряды
    вал = (валюта or "").strip().upper()
    ряд = ряды.get(вал)
    if not ряд:
        return цена, None, f"индекса цен для валюты {вал or '(не указана)'} нет — без индексации"
    м_цены, м_на = месяц(дата_цены), месяц(дата_на)
    первый = min(ряд)
    if м_цены < первый:
        return цена, None, (f"цена {м_цены} старше ряда индекса {вал} (с {первый}) — "
                            "без индексации")
    if м_на < первый:
        return цена, None, f"дата {м_на} раньше ряда индекса {вал} (с {первый}) — без индексации"
    к_цены, о_цены = _точка(ряд, м_цены)
    к_на, о_на = _точка(ряд, м_на)
    оговорки = [о for о in (о_цены, о_на) if о]
    if о_цены and о_на and к_цены == к_на:
        # Оба месяца за краем ряда — индексировать не на что.
        оговорки = [f"индексы {вал} за {м_цены} и {м_на} не опубликованы — без индексации"]
    k = ряд[к_на] / ряд[к_цены]
    if м_на < м_цены:
        оговорки.append(f"дата «на» ({м_на}) раньше даты цены ({м_цены}) — цена приведена назад")
    k = round(k, 6)
    новая = None if цена is None else round(цена * k, 2)
    return новая, k, "; ".join(оговорки) or None
