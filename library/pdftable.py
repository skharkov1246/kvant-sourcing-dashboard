"""Таблица из PDF: колонки восстанавливаются по выравниванию текста.

ЗАЧЕМ. Коммерческие предложения приходят PDF-ами, и до сих пор PDF разбирался
единственным способом — построчно, как проза. Из-за этого цена в нём опознавалась
арифметикой: тройка чисел, у которой кол-во × цена = сумма (quotes.цена_из_текста).
Правило честное, но узкое — оно молчит, если суммы в строке нет, если числа стоят
не подряд, если строка перенесена. А главное: оно не различает цену и сумму иначе
как через арифметику, тогда как в самом файле НАПИСАНО, где что — в шапке таблицы.

ЧТО ЗДЕСЬ. pypdf умеет extract_text(extraction_mode="layout"): горизонтальные
отступы сохраняются, и таблица в тексте остаётся таблицей — колонки стоят на
своих местах, разделённые пробелами. Значит колонки можно вернуть: найти
вертикальные «жёлобы» — позиции, пустые почти во всех строках, — и разрезать по
ним. На выходе rows: list[list[str]] — ровно то, что уже умеет читать
indexer.items_from_rows со всей машинерией шапки: цена за единицу против суммы,
валюта из заголовка, срок, базис.

ПОЧЕМУ ЭТО НЕ ОПАСНО. Неверный разрез даёт мусорные ячейки — но на выходе стоят
те же ворота, что и у xlsx: header_map требует найти в одной строке название
колонки наименования и ещё хотя бы одно известное название. Случайный разрез эти
ворота не проходит, и разбор откатывается на прежний текстовый путь. То есть
худший исход нового кода равен прежнему поведению, а не хуже его.

ЖЁЛОБЫ СЧИТАЮТСЯ НЕ ПО ВСЕМУ ФАЙЛУ, А ПО ТАБЛИЧНОМУ БЛОКУ. Первая версия брала
все строки разом, и заголовок «КОММЕРЧЕСКОЕ ПРЕДЛОЖЕНИЕ № 114 от 18.09.2026»
вместе со строкой условий поставки съел все жёлобы левой половины: пять колонок
(№, наименование, артикул, кол-во, единица) склеились в одну. Это не мелочь —
именно в них лежат номенклатура и количество, без которых цена бесполезна.

Табличной считается строка, которая сама по себе распадается на три и более поля
по промежуткам от двух пробелов. Признак местный: ни выравнивания, ни соседей он
не спрашивает, поэтому проза («Условия поставки: DAP Москва») в блок не попадает
и разметку колонок не портит. Жёлобы ищутся только внутри блока, а разрезаются
потом ВСЕ строки — иначе перенос наименования на вторую строку потерялся бы.
"""

from __future__ import annotations

# ЛЕСТНИЦА ДОПУСКОВ. Жёлоб строго — позиция, пустая в КАЖДОЙ строке блока: тогда
# ни одна граница не может попасть внутрь слова, потому что там, где есть буква,
# жёлоба нет по определению. Это и есть первая ступень, и в большинстве файлов
# другой не нужно.
#
# Но шапка бывает ШИРЕ своей колонки: «Цена за ед., EUR» выровнена влево, а числа
# под ней — вправо, и заголовок свисает в соседний жёлоб. Одна такая строка
# закрывает жёлоб для всего блока, и «Ед.» склеивается с «Цена за ед., EUR» —
# колонка цены не опознаётся, и цена начинает выводиться делением суммы на
# количество вместо того, чтобы просто читаться. Число выходит то же, но с ложной
# оговоркой и низкой уверенностью, а на строке без суммы теряется совсем.
#
# Поэтому ступени: 0, 1, 2 занятых строки. На ступени выше нуля граница МОЖЕТ
# разрезать слово — но только в тех одной-двух строках, которые жёлоб и занимают,
# то есть как раз в свисающей шапке. Данные, которых большинство, остаются целы.
# Выбирает ступень не этот код, а вызывающий: он проверяет результат воротами
# header_map, и разрез, не давший опознаваемой шапки, отвергается целиком.
ДОПУСКИ = (0, 1, 2)
# Промежуток, по которому строка сама распадается на поля. Два пробела — потому
# что один встречается внутри наименования, а колонки в layout-режиме всегда
# разделены шире.
import re  # noqa: E402  (нужен ниже в разборе полей)
ПРОМЕЖУТОК = re.compile(r"\s{2,}")
# Жёлоб уже двух пробелов — это пробел внутри наименования, а не граница колонки.
МИН_ШИРИНА_ЖЁЛОБА = 2
# Меньше трёх колонок — не таблица: номер и наименование бывают и в прозе.
МИН_КОЛОНОК = 3
# Строки короче этого в расчёте жёлобов не участвуют: обрывок в две буквы делает
# пустым весь остаток ширины и тем объявляет его жёлобом.
МИН_ДЛИНА_СТРОКИ = 12
# Блок из двух строк даёт жёлобы, которых нет: нужен объём, чтобы выравнивание
# проявилось.
МИН_СТРОК_БЛОКА = 4


def _табличные(строки: list[str]) -> list[str]:
    """Строки, похожие на строки таблицы: три и более поля по промежуткам.

    Признак местный и потому надёжный: он не зависит ни от выравнивания, ни от
    того, что стоит выше и ниже. Проза в блок не попадает, а значит не портит
    разметку колонок.
    """
    блок = []
    for s in строки:
        if len(s.strip()) < МИН_ДЛИНА_СТРОКИ:
            continue
        поля = [ч for ч in ПРОМЕЖУТОК.split(s.strip()) if ч]
        if len(поля) >= МИН_КОЛОНОК:
            блок.append(s)
    return блок


def _жёлобы(строки: list[str], допуск: int = 0) -> list[tuple[int, int]]:
    """Вертикальные промежутки: (начало, конец) позиций, пустых почти везде."""
    if len(строки) < МИН_СТРОК_БЛОКА:
        return []
    ширина = max(len(s) for s in строки)
    предел = допуск
    занято = [0] * ширина
    for s in строки:
        for i, ch in enumerate(s):
            if ch != " ":
                занято[i] += 1
    жёлобы: list[tuple[int, int]] = []
    начало = None
    for i in range(ширина):
        пусто = занято[i] <= предел
        if пусто and начало is None:
            начало = i
        elif not пусто and начало is not None:
            if i - начало >= МИН_ШИРИНА_ЖЁЛОБА:
                жёлобы.append((начало, i))
            начало = None
    if начало is not None and ширина - начало >= МИН_ШИРИНА_ЖЁЛОБА:
        жёлобы.append((начало, ширина))
    return жёлобы


def _границы(жёлобы: list[tuple[int, int]], ширина: int) -> list[int]:
    """Позиции разреза: по середине каждого жёлоба.

    По середине, а не по краю: текст в колонке бывает выровнен и влево, и вправо
    (числа — вправо), и край жёлоба тогда отрезал бы последнюю цифру.
    """
    точки = [0]
    for a, b in жёлобы:
        # Жёлоб, начинающийся с нулевой позиции, — это отступ слева, а не граница.
        if a == 0:
            точки[0] = b
            continue
        if b >= ширина:
            break
        точки.append((a + b) // 2)
    точки.append(ширина)
    return точки


def строки_в_таблицу(текст: str, годится=None) -> list[list[str]]:
    """Текст из extract_text(extraction_mode="layout") → строки таблицы.

    годится — проверка вызывающего: rows → bool. Перебираются ступени допуска
    (ДОПУСКИ), и возвращается первый разрез, который проверку прошёл. Без
    проверки берётся строгая ступень. Проверка нужна потому, что «правильность»
    разреза определяется не здесь: её знает только тот, кто умеет опознать шапку.

    Пустой список — честный ответ: выравнивания не нашлось, таблицы здесь нет.
    Вызывающий обязан в этом случае идти прежним текстовым путём.
    """
    сырые = [s.rstrip() for s in (текст or "").splitlines()]
    блок = _табличные(сырые)
    if len(блок) < МИН_СТРОК_БЛОКА:
        return []
    первый: list[list[str]] = []
    for допуск in ДОПУСКИ:
        таблица = _разрез(сырые, блок, допуск)
        if not таблица:
            continue
        if годится is None:
            return таблица
        if годится(таблица):
            return таблица
        первый = первый or таблица
    # Ни одна ступень шапки не дала. Возвращается строгая: вызывающий всё равно
    # её отвергнет, но пустой список и отвергнутая таблица для него — одно и то
    # же, а отдать строгую честнее, чем сделать вид, что выравнивания не было.
    return первый


def разрезы_страницы(текст: str) -> list[tuple[list[int], list[list[str]]]]:
    """Все разрезы ОДНОЙ страницы по лестнице допусков: [(точки, таблица), …].

    Для постраничной сборки (indexer.таблица_постранично, PDF_PAGEWISE): pypdf
    считает ширину знака у каждой страницы свою (средняя по тексту страницы),
    и колонки второй страницы стоят не на тех позициях, что первой. Жёлобы по
    склейке страниц тогда закрываются, и колонки слипаются по всему файлу.
    Ступень здесь не выбирается — выбирает вызывающий: у страницы с шапкой её
    решают ворота шапки, у страницы без шапки — совпадение числа колонок.
    Пустой список — у страницы меньше МИН_СТРОК_БЛОКА табличных строк."""
    сырые = [s.rstrip() for s in (текст or "").splitlines()]
    блок = _табличные(сырые)
    if len(блок) < МИН_СТРОК_БЛОКА:
        return []
    out = []
    for допуск in ДОПУСКИ:
        точки = _точки(блок, допуск)
        if точки is not None:
            out.append((точки, _нарезать(сырые, set(блок), точки)))
    return out


#: Насколько границе образца, пересчитанной на масштаб страницы, можно сдвинуться
#: к пустой позиции страницы (знаков). Больше — и она уйдёт в соседнюю колонку.
СДВИГ_ГРАНИЦЫ = 2
#: Пределы масштаба страницы против образца: ширина знака у pypdf — средняя по
#: странице, и крупный заголовок или колонка цифр меняют её на проценты, а не в
#: разы. Шире предел — больше случайных совпадений.
МАСШТАБ_МИН, МАСШТАБ_МАКС = 0.75, 1.33


def _пустые(блок: list[str]) -> list[bool]:
    """Позиция пуста во ВСЕХ строках блока (за концом строки — тоже пусто)."""
    ширина = max(len(s) for s in блок)
    return [all(i >= len(s) or s[i] == " " for s in блок) for i in range(ширина)]


#: Число с разрядами через пробел («8 966,30», «1 200 000»): пробел внутри него —
#: разделитель тысяч, а не промежуток между колонками.
_ЧИСЛО_С_РАЗРЯДАМИ = re.compile(
    r"(?<![\d.,])\d{1,3}(?:[ \u00a0\u202f]\d{3})+(?:[.,]\d{1,4})?(?!\d)")


def _годные_границы(блок: list[str], пусто: list[bool]) -> list[bool]:
    """Позиции, где разрез границей образца законен.

    ЖЁЛОБ ОТ ДВУХ ЗНАКОВ — всегда (МИН_ШИРИНА_ЖЁЛОБА, как у своего разреза).
    Одиночный пробел — только если он ни в одной строке не стоит ВНУТРИ числа с
    разрядами и не разделяет две буквы. Ревизия 28.09.2026: граница образца,
    прижатая к любому одиночному пробелу, резала «8 966,30» на «8» и «966,30»
    — у правых чисел с одинаковым числом знаков пробел-разделитель стоит на
    одном месте во всех строках хвоста, и позиция «пуста». А одиночный пробел
    нужен законно: «12 шт» (количество вплотную к единице) и «8 966,30 26 898,90»
    (цена вплотную к сумме) — это границы колонок узкой страницы."""
    годные = list(пусто)
    i = 0
    while i < len(пусто):
        if not пусто[i]:
            i += 1
            continue
        j = i
        while j < len(пусто) and пусто[j]:
            j += 1
        if j - i < МИН_ШИРИНА_ЖЁЛОБА:
            for p in range(i, j):
                годные[p] = not any(_внутри_числа(s, p) or _между_букв(s, p) for s in блок)
        i = j
    return годные


def _внутри_числа(s: str, p: int) -> bool:
    return any(m.start() < p < m.end() for m in _ЧИСЛО_С_РАЗРЯДАМИ.finditer(s))


def _между_букв(s: str, p: int) -> bool:
    return 0 < p < len(s) - 1 and s[p - 1].isalpha() and s[p + 1].isalpha()


def _пустая_рядом(пусто: list[bool], цель: int, после: int) -> int | None:
    """Ближайшая к цели годная позиция правее «после», не дальше СДВИГ_ГРАНИЦЫ.
    пусто — годные позиции (_годные_границы), за концом строк — годно."""
    for d in range(СДВИГ_ГРАНИЦЫ + 1):
        for p in (цель - d, цель + d):
            if p > после and (p >= len(пусто) or пусто[p]):
                return p
    return None


def _границы_по_масштабу(пусто: list[bool], образец: list[int],
                         масштаб: float) -> tuple[list[int], float] | None:
    """Внутренние границы образца, пересчитанные и прижатые к пустым позициям, и
    сумма сдвигов прижатия (мера того, насколько масштаб подходит)."""
    out: list[int] = []
    после = 0
    сдвиг = 0.0
    for r in образец[1:-1]:
        цель = r * масштаб
        p = _пустая_рядом(пусто, round(цель), после)
        if p is None:
            return None
        out.append(p)
        сдвиг += abs(p - цель)
        после = p
    return out, сдвиг


def по_образцу(текст: str, образец: list[int], годится=None) -> list[list[str]] | None:
    """Страница, разрезанная границами ОБРАЗЦА — страницы с шапкой той же таблицы.

    ЗАЧЕМ. Своих жёлобов у страницы может не хватить: табличных строк меньше
    МИН_СТРОК_БЛОКА (хвост таблицы), или промежуток между колонками у неё уже
    двух знаков («6 шт» — количество, выровненное вправо, вплотную к единице),
    и две колонки слиплись. Границы образца годятся — но не как есть: pypdf
    ставит знак на позицию x ÷ (средняя ширина знака страницы), и у этой
    страницы масштаб свой. Поэтому масштаб подбирается: из тех, при которых ВСЕ
    внутренние границы образца попадают в пустые (во всех табличных строках
    страницы) позиции не дальше СДВИГ_ГРАНИЦЫ, берётся тот, где сумма сдвигов
    прижатия меньше (при равенстве — ближайший к 1). Первый подошедший брать
    нельзя: при чужом масштабе граница прыгает в соседний жёлоб, и колонки
    съезжают на одну. Граница прижимается к годной позиции (_годные_границы):
    разрез не режет ни знак, ни число с разрядами, ни слово наименования.

    СМЫСЛ КОЛОНОК ЗДЕСЬ НЕ ПРОВЕРЯЕТСЯ — это делает вызывающий проверкой
    годится (indexer.страница_сходится): масштаб, при котором все границы
    «легли», ещё не значит, что колонки те же. Ревизия 28.09.2026: на хвосте из
    двух строк ложились и масштаб 1,1, и 1,3, у второго сумма сдвигов меньше, а
    колонки у него съехали на одну («шт 8 966,30» в колонке количества). Поэтому
    масштабы перебираются по возрастанию меры, и берётся первый разрез, который
    годится; без проверки — первый по мере, как прежде.

    None — масштаба, при котором легли все границы, нет: страница с образцом
    не сопоставляется. Страница без табличных строк — проза, одной ячейкой."""
    сырые = [s.rstrip() for s in (текст or "").splitlines()]
    блок = _табличные(сырые)
    колонок = len(образец) - 1
    if not блок:
        return [[s.strip()] + [""] * (колонок - 1) for s in сырые if s.strip()]
    пусто = _годные_границы(блок, _пустые(блок))
    # Кандидаты масштаба: середины годных промежутков страницы против границ образца.
    середины = []
    начало = None
    for i, п in enumerate(пусто + [False]):
        if п and начало is None:
            начало = i
        elif not п and начало is not None:
            if начало > 0:
                середины.append((начало + i - 1) / 2)
            начало = None
    кандидаты = {1.0} | {round(с / r, 4) for с in середины for r in образец[1:-1]
                         if r > 0 and МАСШТАБ_МИН <= с / r <= МАСШТАБ_МАКС}
    легли_все: list[tuple[tuple[float, float], list[int]]] = []
    for масштаб in кандидаты:
        легли = _границы_по_масштабу(пусто, образец, масштаб)
        if легли is not None:
            легли_все.append(((round(легли[1], 6), abs(масштаб - 1)), легли[0]))
    виденные: set[tuple[int, ...]] = set()
    for _мера, внутренние in sorted(легли_все):
        if tuple(внутренние) in виденные:
            continue
        виденные.add(tuple(внутренние))
        хвост = max(max(len(s) for s in сырые) + 1, (внутренние[-1] + 1) if внутренние else 0)
        таблица = _нарезать(сырые, set(блок), [0] + внутренние + [хвост])
        if годится is None or годится(таблица):
            return таблица
    return None


def _точки(блок: list[str], допуск: int) -> list[int] | None:
    """Границы колонок блока на ступени допуска; None — колонок меньше трёх."""
    жёлобы = _жёлобы(блок, допуск)
    ширина = max(len(s) for s in блок)
    точки = _границы(жёлобы, ширина)
    return точки if len(точки) - 1 >= МИН_КОЛОНОК else None


def _нарезать(сырые: list[str], в_блоке: set[str], точки: list[int]) -> list[list[str]]:
    """Строки по границам; табличные режутся, проза — одной ячейкой (как в _разрез)."""
    таблица: list[list[str]] = []
    for s in сырые:
        if not s.strip():
            continue
        if s in в_блоке:
            ячейки = [s[точки[i]:точки[i + 1]].strip() for i in range(len(точки) - 1)]
        else:
            ячейки = [s.strip()] + [""] * (len(точки) - 2)
        if any(ячейки):
            таблица.append(ячейки)
    return таблица


def _разрез(сырые: list[str], блок: list[str], допуск: int) -> list[list[str]]:
    # ПРОЗУ ПО КОЛОНКАМ НЕ РЕЖЕМ (_нарезать). «Условия поставки: DAP Москва.
    # Оплата 100% предоплата» под границы таблицы не ложится, и разрез даёт
    # «Усл» | «овия поставки: DAP М» | «лата 100% предоплата» — три обрывка, из
    # которых разбор сделает выдуманную позицию с выдуманным количеством. Такая
    # строка идёт одной ячейкой: дальше её судьбу решают те же ворота, что и на
    # прежнем текстовом пути, то есть поведение не меняется, а мусор не появляется.
    точки = _точки(блок, допуск)
    if точки is None:
        return []
    return _нарезать(сырые, set(блок), точки)
