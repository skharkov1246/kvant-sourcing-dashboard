"""Прайс-бук КП (разбор моделью) — ключ артикула и правило строгой сравнимости.

ЧТО ЭТО. Владелец 01.10.2026 передал прайс-бук: 3 423 КП из поля «Offer from
supplier», разобранные языковой моделью, — тот же корпус, что читает наш
разборщик (`indexer.py`), под тем же ключом `request_id`. Сам прайс-бук —
коммерческие данные и в репозиторий не кладётся (CLAUDE.md, правило 5): здесь
только правила, по которым его строки читаются, а загрузчик
(`load_pricebook.py`) пишет их в закрытую базу.

ЗАЧЕМ ОН НАМ. Два применения, и правила у них разные.
1. Эталон для нашего разборщика: эталон не производен от нашего правила
   (LESSONS, правило 1), поэтому по нему меряется «у скольких файлов хуже»
   при включении флагов разбора F1–F6.
2. Второй источник цены. Здесь действуют решения владельца 26.09.2026: цена
   сравнивается без НДС и на базисе FCA/EXW; прайс-лист — справочная цена без
   объёма; низкая уверенность показывается, но в сравнение не идёт. Замер
   01.10.2026: из 49 752 строк с ценой строго сравнимы 8 638 (17,4 %); сверено
   построчно с независимым счётом на pandas — расходятся 4 строки «6m³», и это
   правило право: объём не артикул.

ПОЧЕМУ КЛЮЧ ПЕРЕСЧИТЫВАЕТСЯ. Ключ прайс-бука — верхний регистр без пробелов,
дефисов, точек, запятых, слешей, двоеточий и «#»; знаки «+», «()» и прочие он
сохраняет. Наш `lib_pn_key` оставляет только латиницу, кириллицу и цифры. На
59 121 ключе прайс-бука ключи расходятся у 736 — без пересчёта эти строки не
встретились бы с нашими.
"""
from __future__ import annotations

import re

NOT_KEY = re.compile(r"[^0-9a-zа-я]+")

# Базисы, на которых цена сравнима (решение владельца 26.09.2026).
БАЗИС_СТАНДАРТ = frozenset({"EXW", "FCA"})
# Валюты, у которых есть курс в прайс-буке; прочие (динары, рупии…) — не сравнимы.
ВАЛЮТЫ = frozenset({"RUB", "USD", "EUR", "CNY", "AED", "GBP"})
# Ниже — сканы и обрывки переписки: показываются, в сравнение не идут.
УВЕРЕННОСТЬ_МИН = 0.55
# Короче — номер позиции, а не код: замер 01.10.2026 нашёл 31 сравнимую по
# остальным условиям строку с «артикулом» вида «3.1», «22», «4.5». Порог тот же,
# что у самого прайс-бука, — сверка с ним сходится построчно.
АРТИКУЛ_МИН = 3

# Причины несравнимости в порядке проверки: первая сработавшая и записывается.
# Порядок тот же, что у воронки в отчёте владельцу 01.10.2026, — чтобы счёт по
# причинам сходился с ней построчно.
ПРИЧИНЫ = (
    "нет цены",
    "нет валюты",
    "прайс-лист",
    "низкая уверенность",
    "цена не найдена в исходнике",
    "нет артикула",
    "базис не FCA/EXW",
    "НДС не известен",
)


def part_key(pn: str | None) -> str:
    """Ключ артикула ровно как `lib_pn_key` в SQL: сначала регистр, потом «ё»."""
    return NOT_KEY.sub("", (pn or "").lower().replace("ё", "е"))[:80]


def _да(v) -> bool:
    return str(v).strip().lower() in ("1", "1.0", "true", "t", "да")


def _нет_значения(v) -> bool:
    return v is None or str(v).strip() in ("", "nan", "None")


def причина_несравнимости(строка: dict, шапка: dict) -> str | None:
    """None — строка строго сравнима; иначе первая причина из ПРИЧИНЫ.

    НДС. Решение владельца — сравнивать без НДС. Явная пометка в КП есть у трети
    документов; у иностранной валюты экспортная цена идёт без российского НДС,
    поэтому иностранная валюта засчитывается как «НДС известен». Рублёвая цена
    без пометки — нет: у российского поставщика она бывает и с НДС, и без.
    """
    цена = строка.get("unit_price")
    if _нет_значения(цена):
        return "нет цены"
    валюта = (строка.get("currency_eff") or "").strip().upper()
    if валюта not in ВАЛЮТЫ:
        return "нет валюты"
    if (шапка.get("doc_type") or "") == "pricelist":
        return "прайс-лист"
    try:
        уверенность = float(строка.get("confidence"))
    except (TypeError, ValueError):
        уверенность = 0.0
    if уверенность < УВЕРЕННОСТЬ_МИН:
        return "низкая уверенность"
    if not _да(строка.get("price_in_source")):
        return "цена не найдена в исходнике"
    if len(part_key(строка.get("part_number"))) < АРТИКУЛ_МИН:
        return "нет артикула"
    if (шапка.get("incoterm") or "").strip().upper() not in БАЗИС_СТАНДАРТ:
        return "базис не FCA/EXW"
    if _нет_значения(шапка.get("vat_included")) and валюта == "RUB":
        return "НДС не известен"
    return None
