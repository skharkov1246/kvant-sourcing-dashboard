"""Коммерческие условия предложения: базис, оплата, срок производства и поставки.

ЗАЧЕМ. Распоряжение владельца, 22.09.2026: «Очень важно всегда искать в каждом
входящем офере сопоставление кодов, цены, цены за штуку, суммы, базис поставки
(DDP, EXW), условия оплаты (LC, 30/70, 50/50 и подобное), срок производства, срок
поставки. Это всё критически важные данные, которые нужно извлекать из каждого КП.
Если их нет, то нужно перепроверять дважды и писать, что это не отсутствует, а
верифицировано отсутствует».

Отсюда три требования, каждое меняет устройство кода.

ТРЕБОВАНИЕ ПЕРВОЕ: ИСКАТЬ И В СТРОКЕ, И В ФАЙЛЕ. Владелец: «бывает, что по
строкам это бывает, что в конце предложения вообще цифра». То есть базис, оплата
и срок живут в двух местах: колонкой в таблице позиций либо одной записью в блоке
условий под таблицей. Прежний код смотрел только в строку, поэтому у КП с общими
условиями — а это обычная форма — все четыре поля оставались пустыми при том, что
в файле они написаны.

ТРЕБОВАНИЕ ВТОРОЕ: РАЗЛИЧАТЬ «НЕТ» И «НЕ СМОТРЕЛИ». Пустое поле сегодня означает
разом и «в КП не указано», и «разбор не дошёл». Это разные вещи: первое — факт о
предложении, по нему можно спрашивать поставщика; второе — наш недочёт, и спрашивать
надо не поставщика, а разборщик. Поэтому у каждого поля есть источник:

    строка         — взято из колонки этой позиции
    файл           — взято из общих условий КП (оговорка: относится ко всем строкам)
    нет            — ПРОВЕРЕНО ДВАЖДЫ: искали и в строке, и в тексте файла, не написано
    несколько      — в файле найдено несколько разных значений, угадывать нельзя
    не проверено   — смотреть было нечего: текста файла нет (скан без слоя)

«Нет» здесь — это и есть «верифицировано отсутствует»: состояние достигается
только после двух проверок, а не по факту пустой ячейки.

ТРЕБОВАНИЕ ТРЕТЬЕ: СРОК ПРОИЗВОДСТВА И СРОК ПОСТАВКИ — РАЗНЫЕ ПОЛЯ. Прежде был
один lead_days, и «срок изготовления 8 недель» с «поставка со склада» складывались
в одно поле в зависимости от того, что встретилось раньше. Для закупки это разные
величины: первая говорит, когда деталь появится, вторая — когда доедет.

НЕОДНОЗНАЧНОСТЬ НЕ РАЗРЕШАЕТСЯ УГАДЫВАНИЕМ. Если в тексте файла нашлись два
разных базиса или две разные схемы оплаты, поле получает «несколько», а не первое
встреченное. Тот же принцип, что у quotes.валюта_файла: молчание честнее догадки.
"""

from __future__ import annotations

import re

# Импорт в ОДНУ сторону: offer_terms знает про quotes, quotes про offer_terms — нет.
# Цена и коммерческие условия — разные вещи, и цикл между ними означал бы, что
# граница проведена не там. Две формы импорта потому, что indexer.py берёт модули
# библиотеки плоско (sys.path на library/), а тесты — пакетом.
try:                                             # pragma: no cover
    from . import quotes as _q
except ImportError:                              # pragma: no cover
    import quotes as _q

СТРОКА = "строка"
ФАЙЛ = "файл"
НЕТ = "нет"
НЕСКОЛЬКО = "несколько"
НЕ_ПРОВЕРЕНО = "не проверено"

ПОЛЯ = ("basis", "pay_terms", "lead_days", "make_days")

# ─────────────────────────────────────────────────────────────────────────────
# БАЗИС ПОСТАВКИ
#
# Инкотермс плюс русские формулировки, которые означают базис однозначно.
# «До склада покупателя» СЮДА НЕ ВХОДИТ: это и DAP, и DDP, и CPT — разница в том,
# кто платит пошлину, а она из фразы не видна. Угадывать базис нельзя: он решает,
# кто везёт и кто таможит.
БАЗИСЫ = ("EXW", "FCA", "FAS", "FOB", "CFR", "CIF", "CPT", "CIP",
          "DAP", "DPU", "DDP", "DAT", "DDU", "DES", "DEQ")
БАЗИС_СЛОВАМИ = (
    ("EXW", ("самовывоз", "со склада поставщика", "ex works", "франко-склад поставщика")),
    ("DDP", ("с учётом пошлин", "пошлины оплачены", "duty paid")),
)

# ─────────────────────────────────────────────────────────────────────────────
# УСЛОВИЯ ОПЛАТЫ
#
# Порядок важен: сначала схемы с числами (30/70), потом полная предоплата, потом
# инструменты (LC, T/T), потом отсрочка. Иначе «30/70 через аккредитив» опознается
# как просто аккредитив и потеряет разбивку платежа.
#
# ДОЛЯ АВАНСА ХРАНИТСЯ ЧИСЛОМ ОТДЕЛЬНО. «30/70» и «50/50» — самое частое условие в
# наших КП, и доля аванса решает, сколько денег уходит до поставки. Из текста её
# видно, из строки «30/70» — нет, пока её не разобрали.
_ДРОБЬ = re.compile(r"(?<!\d)(\d{1,3})\s*%?\s*[/\\]\s*(\d{1,3})\s*%?(?!\d)")
_ПРЕДОПЛАТА = ("предоплат", "аванс", "in advance", "advance payment", "prepay",
               "prepaid", "before shipment", "до отгрузки", "до поставки")
_ПОЛНАЯ = ("100%", "100 %", "full", "полная", "полностью")
_АККРЕДИТИВ = ("аккредитив", "letter of credit", "l/c", "lc at sight", "irrevocable lc")
_ПЕРЕВОД = ("t/t", "telegraphic transfer", "банковск", "wire transfer", "bank transfer")
_ДОКУМЕНТЫ = ("cash against documents", "against documents", "d/p", "d/a",
              "против документов")
_ОТСРОЧКА = ("отсрочк", "постоплат", "net 30", "net 60", "net 90",
             "после поставки", "after delivery", "по факту", "upon delivery")
# «CAD» — и Cash Against Documents, и канадский доллар. Само по себе не считается:
# нужен либо развёрнутый текст, либо денежное слово рядом. Иначе валюта КП
# превратится в условие платежа.
_ОПЛАТА_РЯДОМ = ("оплат", "платеж", "платёж", "payment", "terms", "условия")
# ЗАПИСЫВАЕТСЯ НЕ «CAD», А «против документов». Сокращение верное, но в
# коммерческом поле его прочтут как канадский доллар: «30/70 CAD» выглядит ценой
# в валюте, а не схемой платежа. Однозначность здесь важнее краткости — поле
# уходит людям, которые по нему принимают решение о деньгах.
ИНСТРУМЕНТЫ = {"LC": "LC", "T/T": "T/T", "CAD": "против документов"}

# ─────────────────────────────────────────────────────────────────────────────
# СРОКИ. Изготовление и поставка — РАЗНЫЕ поля, и путаница между ними стоит
# дорого: первое говорит, когда деталь появится, второе — когда доедет.
#
# ЯКОРЬ РЕШАЕТ ВИД СРОКА, И ПОРЯДОК ЯКОРЕЙ ВАЖЕН. Общие слова («срок», «lead
# time», «delivery») стоят последними: иначе «Срок изготовления 8 недель» попадёт
# в поле поставки, потому что «срок» там встречается раньше любого слова о
# поставке. Так и вышло в первой версии — 56 дней изготовления записались разом и
# сроком поставки.
#
# ОБЩИЙ ЯКОРЬ ПЕРЕСПРАШИВАЕТ ХВОСТ. «Срок изготовления» — это make, даже если
# поймано словом «срок»: уточнение стоит сразу за якорем, и его надо прочитать.
_ЯКОРЯ = (
    ("срок изготовл", "make_days"), ("срок производств", "make_days"),
    ("время изготовл", "make_days"), ("production time", "make_days"),
    ("production lead", "make_days"), ("manufacturing", "make_days"),
    ("изготовлен", "make_days"),
    # ЯКОРЯ — ОСНОВЫ СЛОВ, А НЕ ИМЕНИТЕЛЬНЫЙ ПАДЕЖ. «Условия поставки: 6 недель»
    # не находилось вовсе: якорь стоял «поставка», а в тексте «поставки». В русском
    # КП это слово почти всегда в косвенном падеже — «срок поставки», «до
    # поставки», «условия поставки», — так что именительный падеж не ловил ничего.
    ("срок поставк", "lead_days"), ("срок доставк", "lead_days"),
    ("срок отгрузк", "lead_days"), ("delivery time", "lead_days"),
    ("delivery period", "lead_days"), ("shipment", "lead_days"),
    ("отгрузк", "lead_days"), ("доставк", "lead_days"), ("поставк", "lead_days"),
    # Общие — последними.
    ("lead time", "lead_days"), ("delivery", "lead_days"), ("срок", "lead_days"),
)
_ОБЩИЕ_ЯКОРЯ = ("lead time", "delivery", "срок")
_ПРОИЗВОДСТВО_СЛОВА = ("изготовл", "производств", "production", "manufactur")
# Чужие сроки: их нельзя принимать ни за производство, ни за поставку.
#
# «TERMS» И «УСЛОВИЯ» ЗДЕСЬ НАМЕРЕННО НЕТ. Сначала были: «Terms of delivery: DAP
# Moscow» давало семьдесят дней поставки, потому что якорь «delivery» там есть, а
# срока нет, и правило хватало первое число из следующей строки («Payment terms:
# 30/70»). Но лечило это не то: настоящая причина — голое число, принятое за дни,
# и она закрыта требованием слова единицы (_срок_дней, нужна_мера). Мутация это и
# показала: с требованием единицы отсев по «terms» уже ничего не держит — ни один
# тест от его снятия не краснеет.
#
# А вреда он приносит: «Terms of delivery: 4 weeks» — законный срок поставки, и
# отсев по слову «terms» потерял бы его молча. Широкое правило, которое ничего не
# защищает, но теряет данные, убрано. Остались слова, за которыми срока не бывает
# вовсе: базис и адрес.
_ЧУЖОЙ_СРОК = ("оплат", "payment", "действ", "validity", "гарант", "warranty",
               "рассмотр", "хранен", "отсрочк", "basis", "базис", "incoterm",
               "address", "адрес")
# Слова единицы срока: по ним обрезается хвост якоря.
_ЕДИНИЦЫ_СРОКА = ("недел", "week", "дн", "day", "сут", "мес", "month", "нед.")
ХВОСТ = 60
ОКНО_БЕЗ_ЕДИНИЦЫ = 40


# Конец предложения: точка НЕ между цифрами (чтобы «1.5 недели» осталось целым),
# точка с запятой, перевод строки.
_КОНЕЦ_ФРАЗЫ = re.compile(r"(?<!\d)\.(?!\d)|[;\n]")


# Насколько далеко от якоря слово ещё считается его уточнением. «Срок ОПЛАТЫ»,
# «ГАРАНТИЙНЫЙ срок», «Срок ДЕЙСТВИЯ предложения» — уточнение стоит вплотную.
РАДИУС_ДО = 20
РАДИУС_ПОСЛЕ = 22


def _уточнение(t: str, начало: int, конец: int) -> str:
    """Слова вплотную к якорю — и ТОЛЬКО внутри его же фразы.

    ДВЕ ГРАНИЦЫ, И ОДНОЙ НЕ ХВАТАЕТ. Обе найдены на живых формулировках.

    Рамка фразы. Отсев чужого срока смотрел ±20 знаков и перескакивал через
    точку: «30% предоплата. Срок изготовления 8 недель» терял срок ИЗГОТОВЛЕНИЯ,
    потому что слева нашлось «оплат» из предыдущей фразы. Строка об оплате перед
    строкой о сроке — обычная форма КП, так что терялось бы у многих файлов.

    Тесное окно. Одной рамки фразы мало: «Срок поставки: 2-3 недели с момента
    100% оплаты» — здесь «оплаты» в ТОЙ ЖЕ фразе, но оно уточняет не срок, а
    момент отсчёта, и глушить по нему значит терять законный срок поставки.
    Уточнение стоит вплотную к якорю, дальше идёт уже другое.
    """
    л = 0
    for m in _КОНЕЦ_ФРАЗЫ.finditer(t[:начало]):
        л = m.end()
    пр = _КОНЕЦ_ФРАЗЫ.search(t, конец)
    п = пр.start() if пр else len(t)
    return t[max(л, начало - РАДИУС_ДО):min(п, конец + РАДИУС_ПОСЛЕ)]


def _окно(хвост: str) -> str:
    """Часть хвоста, в которой считаются числа срока.

    ОБРЕЗАТЬ ОБЯЗАТЕЛЬНО, И ПО ДВУМ ГРАНИЦАМ СРАЗУ.

    Первая — конец фразы. Срок, названный после якоря, стоит в ТОМ ЖЕ предложении.
    Без этой границы «Условия оплаты: 30/70 — 70% по факту поставки. Срок
    изготовления 8 недель» давало пятьдесят шесть дней ПОСТАВКИ: якорь «поставк»
    стоит в конце одной фразы, а восемь недель изготовления — в начале следующей.

    Вторая — слово единицы. quotes.срок_из берёт МАКСИМУМ чисел, и это задумано:
    «4–6 недель» обязано дать верхнюю границу, потому что обещанный минимум
    продавца — не срок, а надежда. Но на длинном хвосте максимумом оказывается
    чужое число: «Срок поставки: 2-3 недели с момента 100% оплаты» дало бы
    100 × 7 = 700 дней вместо 21.
    """
    фраза = _КОНЕЦ_ФРАЗЫ.search(хвост)
    if фраза:
        хвост = хвост[:фраза.start()]
    low = хвост.lower()
    лучшее = -1
    for e in _ЕДИНИЦЫ_СРОКА:
        i = low.find(e)
        if i >= 0 and (лучшее < 0 or i < лучшее):
            лучшее = i + len(e)
    if лучшее >= 0:
        return хвост[:лучшее]
    # Единицы нет — значит либо «со склада», либо срока здесь вообще нет.
    # Короткое окно: чем дальше от якоря, тем меньше число к нему относится.
    return хвост[:ОКНО_БЕЗ_ЕДИНИЦЫ]


def базис_из(текст: str) -> str | None:
    """Базис поставки. Только полное слово: «CIF» внутри «pacific» — не базис."""
    t = текст or ""
    up = t.upper()
    for b in БАЗИСЫ:
        if re.search(rf"(?<![A-Z]){b}(?![A-Z])", up):
            return b
    low = t.lower()
    for код, слова in БАЗИС_СЛОВАМИ:
        if any(w in low for w in слова):
            return код
    return None


def оплата_из(текст: str) -> dict | None:
    """Условия оплаты: нормализованная запись и доля аванса, если она видна.

    Возвращает {"terms": str, "advance_pct": int|None} или None.
    """
    t = (текст or "").lower()
    if not t.strip():
        return None
    рядом = any(w in t for w in _ОПЛАТА_РЯДОМ)
    аванс = any(w in t for w in _ПРЕДОПЛАТА)
    инструмент = None
    if any(w in t for w in _АККРЕДИТИВ):
        инструмент = "LC"
    elif any(w in t for w in _ДОКУМЕНТЫ) or ("cad" in t and рядом):
        инструмент = ИНСТРУМЕНТЫ["CAD"]
    elif any(w in t for w in _ПЕРЕВОД):
        инструмент = "T/T"

    # Схема с разбивкой: «30/70», «50 / 50», «30%/70%». Сумма долей обязана быть
    # сотней — иначе это не схема платежа, а размер, дата или дробь из текста.
    for m in _ДРОБЬ.finditer(t):
        a, b = int(m.group(1)), int(m.group(2))
        if a + b == 100 and 0 < a < 100:
            запись = f"{a}/{b}"
            if инструмент:
                запись += f" {инструмент}"
            return {"terms": запись, "advance_pct": a}

    if аванс and any(w in t for w in _ПОЛНАЯ):
        запись = "предоплата 100%"
        return {"terms": запись + (f" {инструмент}" if инструмент else ""),
                "advance_pct": 100}
    if any(w in t for w in _ОТСРОЧКА):
        дн = _дней(t)
        запись = f"отсрочка {дн} дн" if дн else "оплата после поставки"
        return {"terms": запись + (f" {инструмент}" if инструмент else ""),
                "advance_pct": 0}
    if аванс:
        # Предоплата есть, а доля не названа: записываем факт, долю не выдумываем.
        return {"terms": "предоплата" + (f" {инструмент}" if инструмент else ""),
                "advance_pct": None}
    if инструмент:
        return {"terms": инструмент, "advance_pct": None}
    return None


def _дней(текст: str) -> int | None:
    """Число дней из формулировки отсрочки. «net 30», «отсрочка 30 дней»."""
    m = re.search(r"(\d{1,3})\s*(?:календарн\w*|банковск\w*|рабоч\w*)?\s*"
                  r"(?:дн|дней|days?|сут)", текст)
    if m:
        д = int(m.group(1))
        return д if 0 < д <= 365 else None
    m = re.search(r"net\s*(\d{1,3})", текст)
    return int(m.group(1)) if m else None


# Слова, без которых число в СВОБОДНОМ ТЕКСТЕ сроком не является.
_МЕРА_СРОКА = _ЕДИНИЦЫ_СРОКА + ("склад", "наличи", "in stock", "ex stock", "сток")


def _срок_дней(текст: str, нужна_мера: bool = False) -> int | None:
    """Срок в днях из формулировки. Переиспользует правило quotes.срок_из.

    нужна_мера — требовать слово единицы («недель», «дней») или наличия («склад»).
    В СВОБОДНОМ ТЕКСТЕ это обязательно: quotes.срок_из считает голое число днями,
    и это верно для ЯЧЕЙКИ колонки «Срок, дн» — там единицу называет заголовок, —
    но в тексте голое «70» днями не является. Без этого требования «Terms of
    delivery: DAP Moscow. Payment terms: 30/70» давало семьдесят дней поставки.
    """
    if нужна_мера and not any(w in (текст or "").lower() for w in _МЕРА_СРОКА):
        return None
    return _q.срок_из(текст)


def сроки_из(текст: str) -> dict:
    """Срок производства и срок поставки из текста — раздельно.

    Каждый берётся от своего якоря: слово-указатель плюс окно за ним. Брать срок
    из всего текста разом нельзя — тогда «срок изготовления 8 недель, поставка со
    склада» даст обоим полям одно значение, а это разные вещи.
    """
    t = текст or ""
    out: dict[str, int | None] = {"make_days": None, "lead_days": None}
    for слово, вид in _ЯКОРЯ:
        if out["make_days"] is not None and out["lead_days"] is not None:
            break
        for m in re.finditer(re.escape(слово), t, re.I):
            # Отсев чужого срока: «срок оплаты 30 дней» — не срок поставки.
            # Смотрим ТОЛЬКО свою фразу: соседняя про оплату к этому сроку
            # отношения не имеет (см. _фраза).
            вокруг = _уточнение(t, m.start(), m.end()).lower()
            if any(x in вокруг for x in _ЧУЖОЙ_СРОК):
                continue
            хвост = t[m.end():m.end() + ХВОСТ]
            поле = вид
            # Общий якорь переспрашивает хвост: «Срок изготовления» — это make,
            # даже если поймано словом «срок».
            if слово in _ОБЩИЕ_ЯКОРЯ and any(
                    w in хвост[:20].lower() for w in _ПРОИЗВОДСТВО_СЛОВА):
                поле = "make_days"
            if out[поле] is not None:
                continue
            д = _срок_дней(_окно(хвост), нужна_мера=True)
            if д is not None:
                out[поле] = д
                break
    return out


def из_строки(row: list[str], цк: dict) -> dict:
    """Коммерческие условия ИЗ КОЛОНОК самой позиции.

    цк — номера колонок из quotes.колонки_цены: basis, pay, make, lead. Читается
    только то, что стоит в своей колонке; догадок по соседним ячейкам здесь нет —
    их место в условиях файла, и они помечаются другим источником.
    """
    def ячейка(ключ: str) -> str:
        j = (цк or {}).get(ключ, -1)
        return row[j].strip() if 0 <= j < len(row) else ""

    out: dict[str, object] = {}
    out["basis"] = базис_из(ячейка("basis")) or None
    о = оплата_из(ячейка("pay"))
    out["pay_terms"] = о["terms"] if о else None
    out["pay_advance_pct"] = о["advance_pct"] if о else None
    out["make_days"] = _срок_дней(_окно(ячейка("make"))) if ячейка("make") else None
    out["lead_days"] = _срок_дней(_окно(ячейка("lead"))) if ячейка("lead") else None
    return out


def условия_файла(текст: str) -> dict:
    """Общие условия из текста всего КП. Неоднозначность не разрешается.

    Значение берётся, только если в тексте оно ОДНО. Два разных базиса или две
    разные схемы оплаты — это НЕСКОЛЬКО, а не первое встреченное: угадывать здесь
    значит соврать в коммерческом поле (тот же принцип, что quotes.валюта_файла).
    """
    t = текст or ""
    out: dict[str, object] = {}

    базисы = {b for b in БАЗИСЫ
              if re.search(rf"(?<![A-Z]){b}(?![A-Z])", t.upper())}
    low = t.lower()
    for код, слова in БАЗИС_СЛОВАМИ:
        if any(w in low for w in слова):
            базисы.add(код)
    out["basis"] = (базисы.pop() if len(базисы) == 1
                    else (НЕСКОЛЬКО if базисы else None))

    # Оплата ищется по предложениям: разные схемы в разных абзацах надо увидеть
    # как разные, а не склеить в одну строку и разобрать первую подходящую.
    схемы, доли = set(), {}
    for кусок in re.split(r"[.;\n]", t):
        о = оплата_из(кусок)
        if о:
            схемы.add(о["terms"])
            доли[о["terms"]] = о["advance_pct"]
    if len(схемы) == 1:
        единственная = схемы.pop()
        out["pay_terms"] = единственная
        out["pay_advance_pct"] = доли[единственная]
    else:
        out["pay_terms"] = НЕСКОЛЬКО if схемы else None
        out["pay_advance_pct"] = None

    ср = сроки_из(t)
    out["make_days"] = ср["make_days"]
    out["lead_days"] = ср["lead_days"]
    return out


def свести(из_строки: dict, из_файла: dict, был_текст: bool) -> dict:
    """Значение каждого поля и ОТКУДА оно, включая «проверено, нет».

    из_строки — что дала колонка этой позиции (None там, где колонки нет).
    из_файла  — что дали общие условия КП (условия_файла).
    был_текст — был ли у файла текст, в котором можно было искать. Если нет, поле
                не «отсутствует», а «не проверено»: это наш недочёт, а не факт о
                предложении, и спрашивать надо разборщик, а не поставщика.

    Возвращает {поле: значение, поле + "_src": источник}.
    """
    итог: dict[str, object] = {}
    for поле in ПОЛЯ:
        своё = (из_строки or {}).get(поле)
        общее = (из_файла or {}).get(поле)
        if своё is not None:
            итог[поле], итог[поле + "_src"] = своё, СТРОКА
        elif общее == НЕСКОЛЬКО:
            итог[поле], итог[поле + "_src"] = None, НЕСКОЛЬКО
        elif общее is not None:
            итог[поле], итог[поле + "_src"] = общее, ФАЙЛ
        else:
            # Искали дважды — в строке и в тексте файла. Вот это и есть
            # «верифицировано отсутствует». Без текста — «не проверено».
            итог[поле] = None
            итог[поле + "_src"] = НЕТ if был_текст else НЕ_ПРОВЕРЕНО
    доля = (из_строки or {}).get("pay_advance_pct")
    if доля is None and итог.get("pay_terms_src") == ФАЙЛ:
        доля = (из_файла or {}).get("pay_advance_pct")
    итог["pay_advance_pct"] = доля
    return итог


def полнота(своды: list[dict]) -> dict[str, dict[str, int]]:
    """Сколько позиций по каждому полю имеют значение и откуда.

    Нужна, чтобы на КП можно было смотреть числом: «базис — из файла у всех
    строк, оплата — проверено, нет». Только счётчики, никаких значений.
    """
    итог: dict[str, dict[str, int]] = {п: {} for п in ПОЛЯ}
    for с in своды:
        for п in ПОЛЯ:
            и = с.get(п + "_src") or НЕ_ПРОВЕРЕНО
            итог[п][и] = итог[п].get(и, 0) + 1
    return итог
