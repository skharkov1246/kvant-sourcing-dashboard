"""Модельные ряды брендов: какая машина названа в строке спроса или предложения.

ЗАЧЕМ. Распоряжение владельца 25.09.2026: наполнять бренды — западные и
китайские — модельными рядами, прежде всего те, что попадались в наших запросах
и предложениях. Справочник рядов — dict/model_series.json (ряд, тип машины,
шаблон, примеры, источник); здесь — одно правило его применения, которым
пользуются и замер по базе (scripts/brand_models.py), и тесты.

ПРАВИЛО.
  · Шаблон ряда пишется без границ: границу слова ставит модуль — слева и справа
    не должно быть буквы (латиница или кириллица) или цифры. «J620» в «J6200»
    и «SGT-400» в «XSGT-4001» не узнаются.
  · Кириллические двойники латиницы («С32», «КТА50», «ТН-545») переводятся в
    латиницу — но только внутри слов, где есть цифра: обычный русский текст так
    не портится, а обозначение, набранное русской раскладкой, узнаётся.
  · У шаблона context «сам» — обозначение различимо само; «бренд» — засчитывается
    лишь тогда, когда бренд назван в той же строке (aliases, context_aliases)
    либо передан явно (поле изготовителя строки, сведённое к ключу). Голые
    числа (3516, 4012, 75131) и короткие коды (GA, ZR, CR, SD, HP) без бренда
    неоднозначны — их обвинение машиной стоило бы ложных связей.
  · Совпадения не перекрываются: из пересекающихся берётся самое длинное
    («TCG 2020 V12», а не «TCG 2020»), при равной длине — первое по справочнику.

Каноническое обозначение модели: верхний регистр, без пробелов; дефис снимается,
кроме как между двумя цифрами («SGT-400» → «SGT400», «CG170-12» остаётся).
"""
from __future__ import annotations

import functools
import json
import re
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ФАЙЛ = ROOT / "dict" / "model_series.json"

САМ, БРЕНД = "сам", "бренд"

_БУКВА = "0-9A-Za-zА-Яа-яЁё"
Л = rf"(?<![{_БУКВА}])"
П = rf"(?![{_БУКВА}])"

# Кириллица, неотличимая от латиницы на письме. Заглавные и строчные.
_ДВОЙНИКИ = str.maketrans("АВЕКМНОРСТУХаеокрсух", "ABEKMHOPCTYXaeokpcyx")
_СЛОВО_С_ЦИФРОЙ = re.compile(rf"[{_БУКВА}\-.+/]*\d[{_БУКВА}\-.+/]*")


@dataclass(frozen=True)
class Шаблон:
    бренд: str
    ряд: str
    контекст: str
    rx: re.Pattern


@dataclass(frozen=True)
class Справочник:
    шаблоны: tuple
    бренды: dict                 # ключ → запись бренда
    имена: re.Pattern | None     # все aliases, группа на бренд
    контекст: re.Pattern | None  # aliases ∪ context_aliases, группа на бренд
    группы: dict                 # имя группы → ключ бренда
    предфильтр: re.Pattern | None


def _фраза(имя: str) -> str:
    """Имя бренда → выражение: пробел и дефис взаимозаменяемы, регистр любой."""
    части = [re.escape(ч) for ч in re.split(r"[\s\-]+", имя.strip()) if ч]
    return r"[\s\-]*".join(части)


def _сборка(данные: dict) -> Справочник:
    шаблоны, бренды = [], {}
    имена_г, контекст_г, группы = [], [], {}
    for i, б in enumerate(данные.get("brands", [])):
        ключ = б["brand_key"]
        бренды[ключ] = б
        г = f"b{i}"
        группы[г] = ключ
        if б.get("aliases"):
            имена_г.append(f"(?P<{г}>" + "|".join(_фраза(a) for a in б["aliases"]) + ")")
        все = list(б.get("aliases", [])) + list(б.get("context_aliases", []))
        if все:
            контекст_г.append(f"(?P<{г}>" + "|".join(_фраза(a) for a in все) + ")")
        for р in б.get("series", []):
            for ш in р.get("patterns", []):
                rx = re.compile(Л + "(?:" + ш["rx"] + ")" + П, re.I)
                шаблоны.append(Шаблон(ключ, р["id"], ш.get("context", САМ), rx))
    имена = re.compile(Л + "(?:" + "|".join(имена_г) + ")" + П, re.I) if имена_г else None
    контекст = re.compile(Л + "(?:" + "|".join(контекст_г) + ")" + П, re.I) if контекст_г else None
    # Предфильтр: одно выражение на все шаблоны без групп. Строка, где ни один
    # шаблон не нашёлся, отсекается одним проходом — таких в спросе большинство.
    пред = None
    if шаблоны:
        пред = re.compile(Л + "(?:" + "|".join("(?:" + ш.rx.pattern[len(Л):-len(П)] + ")"
                                                for ш in шаблоны) + ")" + П, re.I)
    return Справочник(tuple(шаблоны), бренды, имена, контекст, группы, пред)


@functools.lru_cache(maxsize=4)
def справочник(путь: str | None = None) -> Справочник:
    with open(путь or ФАЙЛ, encoding="utf-8") as f:
        return _сборка(json.load(f))


def из_данных(данные: dict) -> Справочник:
    """Справочник из уже прочитанного словаря — для тестов на придуманных рядах."""
    return _сборка(данные)


def нормализовать(строка) -> str:
    """Кириллические двойники → латиница внутри слов с цифрой."""
    t = str(строка or "")
    return _СЛОВО_С_ЦИФРОЙ.sub(lambda m: m.group(0).translate(_ДВОЙНИКИ), t)


# Русские написания имён рядов → латинское имя изготовителя: «Таурус 60» и
# «Taurus 60» — одна машина, и считаться она должна одной строкой.
_РУССКИЕ_ИМЕНА = {"ТАУРУС": "TAURUS", "ЦЕНТАВР": "CENTAUR", "КЕНТАВР": "CENTAUR",
                  "САТУРН": "SATURN", "МАРС": "MARS", "ТИТАН": "TITAN"}


def канон(обозначение: str) -> str:
    t = re.sub(r"\s+", "", str(обозначение or "").upper())
    t = re.sub(r"(?<!\d)-|-(?!\d)", "", t)
    for рус, лат in _РУССКИЕ_ИМЕНА.items():
        if t.startswith(рус):
            t = лат + t[len(рус):]
    return t


def _ключи(rx: re.Pattern | None, группы: dict, t: str) -> set:
    if rx is None or not t:
        return set()
    return {группы[m.lastgroup] for m in rx.finditer(t) if m.lastgroup}


def бренды_в_тексте(строка, спр: Справочник | None = None) -> set:
    """Ключи брендов, названных в строке своими именами (aliases)."""
    спр = спр or справочник()
    return _ключи(спр.имена, спр.группы, str(строка or ""))


def модель_в_тексте(строка, бренды=(), спр: Справочник | None = None) -> list[tuple[str, str, str]]:
    """Строка → [(бренд, ряд, модель)] в порядке появления.

    бренды — ключи брендов, известные о строке помимо текста (поле изготовителя):
    они разрешают шаблоны с context «бренд» так же, как имя в самой строке.
    """
    спр = спр or справочник()
    t = нормализовать(строка)
    if not t or спр.предфильтр is None or not спр.предфильтр.search(t):
        return []
    рядом = set(бренды or ()) | _ключи(спр.контекст, спр.группы, str(строка or ""))
    кандидаты = []
    for порядок, ш in enumerate(спр.шаблоны):
        if ш.контекст == БРЕНД and ш.бренд not in рядом:
            continue
        for m in ш.rx.finditer(t):
            if m.end() > m.start():
                кандидаты.append((m.start(), m.end(), порядок, ш, m.group(0)))
    кандидаты.sort(key=lambda к: (-(к[1] - к[0]), к[2], к[0]))
    занято, итог = [], []
    for нач, кон, _, ш, текст in кандидаты:
        if any(нач < к2 and н2 < кон for н2, к2 in занято):
            continue
        занято.append((нач, кон))
        итог.append((нач, (ш.бренд, ш.ряд, канон(текст))))
    итог.sort(key=lambda x: x[0])
    return [x[1] for x in итог]
