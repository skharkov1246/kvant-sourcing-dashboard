#!/usr/bin/env python3
"""Сведение реестров поставщиков в канонический sup_entity. Вхолостую по умолчанию.

ЗАЧЕМ. Поставщики живут в шести реестрах с шестью ключами, и одна компания в трёх
написаниях считается тремя. Этот модуль сводит их в одну сущность с вечным
номером KV-S-NNNNNN-C, не перезаписывая ни одного имени: каждое совпадение
становится строкой sup_identifier со своим доказательством и статусом.

ПРАВИЛО СВЕДЕНИЯ ВЫВЕДЕНО ИЗ ЗАМЕРА, а не придумано — см.
scripts/supplier_registry_overlap.py, scripts/supplier_merge_stats.py и
docs/suppliers/IMPLEMENTATION_PLAN.md. Замер 20.09.2026: по пяти файловым
реестрам 61 домен несёт по два и больше разных написания при 4 спорных именах
из 2 394 (0,17 %); портал же даёт 8 298 компаний против 2 890 имён во всех пяти
файловых, пересекаясь с ними лишь на 4,2 %. Отсюда порядок признаков — от
сильного к слабому:

  0. совпал идентификатор портала (bitrix:NNN) → одна сущность, всегда: это
     ключ чужой системы, а не совпадение строк;
  1. совпал домен                              → слияние, status = verified;
  2. совпало имя, и ничто не мешает            → слияние, status = candidate;
  3. имя указывает на разные домены            → НЕ слияние, sup_review
                                                 (kind = ambiguous_match);
  4. имя совпало, правовые формы РАЗНЫЕ        → НЕ слияние, sup_review
                                                 (kind = different_legal_form).

Пункт 4 — про юрлица. norm_name правовую форму вырезает, и «ООО Ромашка» с
«АО Ромашка» после неё неотличимы; слить их значит приписать одному чужие
сделки (ТЗ §1.12). При этом Ltd и Limited — одно и то же слово, и блокировать
по ним нельзя: см. СИНОНИМЫ_ФОРМ в supplier_registry_overlap.py.

СТАТУСА inferred НЕТ. Он был в первой версии и оказался недостижим: если домен
есть у обеих сторон и совпал — слияние произошло раньше, по пункту 1; если
разошёлся — имя спорное и не слило ничего. Недоказанное слияние — candidate,
и автоматически оно не повышается никогда (ТЗ §5.3).

ЗАДВОЕНИЯ ПОРТАЛА СХЛОПЫВАЮТСЯ. 141 название в Bitrix носят по две и больше
карточек. Не свести их значит оставить статистику одного поставщика
расщеплённой; свести молча — выдать догадку за факт. Поэтому сводим, но
статусом candidate и с причиной в тексте.

ВХОЛОСТУЮ ПО УМОЛЧАНИЮ. Без --apply не открывается даже соединение: считает по
файлам и печатает, что получилось бы. Запись включается явно и отменяется сама,
если не сошёлся хоть один гейт приёмки (CLAUDE.md, правило 3).

НОМЕРА НЕ ПЕРЕИЗДАЮТСЯ. Опознание идёт через sup_identifier, где у сущности
сколько угодно признаков, а sup_number_registry хранит только «сущность → номер».
Появился у компании сайт во втором прогоне — добавится признак, номер прежний.

    python library/load_supplier_master.py              # вхолостую
    python library/load_supplier_master.py --apply      # с записью, нужен SUPABASE_DB_URL
"""
