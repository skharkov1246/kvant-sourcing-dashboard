#!/usr/bin/env python3
"""Сведение реестров поставщиков в канонический sup_entity. Вхолостую по умолчанию.

ЗАЧЕМ. Поставщики живут в шести реестрах с шестью ключами, и одна компания в трёх
написаниях считается тремя. Этот модуль сводит их в одну сущность с вечным
номером KV-S-NNNNNN-C, не перезаписывая ни одного имени: каждое совпадение
становится строкой sup_identifier со своим доказательством и статусом.

ПРАВИЛО СВЕДЕНИЯ ВЫВЕДЕНО ИЗ ЗАМЕРА, а не придумано — см.
scripts/supplier_registry_overlap.py и docs/suppliers/IMPLEMENTATION_PLAN.md.
Замер 20.09.2026 по пяти файловым реестрам: 61 домен несёт по два и больше разных
написания (144 строки), а спорных имён, указывающих на разные домены, всего 4 из
2 394 — 0,17 %. Отсюда:

  1. совпал домен            → слияние, status = verified;
  2. совпало имя, домены не противоречат → слияние, status = inferred;
  3. совпало имя, домены РАЗНЫЕ          → НЕ слияние, строка в sup_review
                                           (kind = ambiguous_match);
  4. совпало только имя, домена нет ни у одной стороны → status = candidate,
     ждёт подтверждения человеком. Сюда попадают досье ГТУ целиком: у них 878
     совпадений по имени и ни одного сайта на 1 359 записей.

ВХОЛОСТУЮ ПО УМОЛЧАНИЮ. Без --apply не открывается даже соединение: считает по
файлам и печатает, что получилось бы. Запись включается явно и отменяется сама,
если не сошёлся хоть один гейт приёмки (CLAUDE.md, правило 3).

НОМЕРА НЕ ПЕРЕИЗДАЮТСЯ. Опознание идёт через sup_identifier, где у сущности
сколько угодно признаков, а sup_number_registry хранит только «сущность → номер».
Появился у компании сайт во втором прогоне — добавится признак, номер прежний.

    python library/load_supplier_master.py              # вхолостую
    python library/load_supplier_master.py --apply      # с записью, нужен SUPABASE_DB_URL
"""
from __future__ import annotations

import argparse
import collections
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "pnw" / "tools"))

from supplier_registry_overlap import (  # noqa: E402
    РЕЕСТРЫ, читать,
)

# Контрольная цифра — та же функция, что у номеров деталей: два алгоритма Луна в
# одном репозитории разошлись бы, и номер стал бы непроверяемым.
from kv_number import luhn  # noqa: E402

ГЕЙТЫ = {
    # Доля сущностей, опознанных доменом, не должна обвалиться: домен — основной
    # признак, замер дал 61 домен с несколькими написаниями против 4 спорных имён.
    "мин_доля_с_доменом": 0.50,
    # Спорных имён было 0,17 %. Порог с запасом: рост вдесятеро означает, что
    # нормализация стала склеивать разное, и писать такое в базу нельзя.
    "макс_доля_спорных": 0.02,
    # Сведение обязано что-то сводить: если сущностей столько же, сколько строк,
    # правило не сработало вовсе.
    "мин_схлопнуто": 100,
}


def номер(seq: int, род: str = "S") -> str:
    """KV-S-NNNNNN-C. Контрольная цифра считается по шести цифрам, как у деталей."""
    тело = str(seq).zfill(6)
    return f"KV-{род}-{тело}-{luhn(тело)}"


class Сущность:
    __slots__ = ("имена", "домены", "источники", "статус", "причина")

    def __init__(self):
        self.имена: set[str] = set()
        self.домены: set[str] = set()
        self.источники: list[tuple[str, str, str]] = []   # реестр, имя, домен
        self.статус = "single"
        self.причина = "один источник, сливать не с чем"


def классифицировать(e: "Сущность") -> None:
    """Статус зависит от того, чем слияние МОЖНО ПРОВЕРИТЬ, а не от того,
    нашёлся ли домен хоть у кого-то.

    Первая версия этого не различала и ставила inferred всему, у чего домен
    был хотя бы с одной стороны. Замер показал цену ошибки: из 977 слияний
    доменом проверяемы 77, а 900 — нет, потому что у досье ГТУ сайта нет ни у
    одной из 1 359 записей. Девятьсот слияний уехали бы в базу вторым по силе
    статусом, хотя их никто не проверял. ТЗ §5.3: candidate и inferred НИКОГДА
    не повышаются автоматически.
    """
    if len(e.источники) < 2:
        e.статус = "single"
        e.причина = "один источник, сливать не с чем"
        return
    с_доменом = sum(1 for _, _, d in e.источники if d)
    if len(e.домены) == 1 and с_доменом >= 2:
        e.статус = "verified"
        e.причина = "домен совпал у двух и более источников"
    elif с_доменом > 0:
        e.статус = "candidate"
        e.причина = "имя совпало, но домен есть не у всех — проверить нечем"
    else:
        e.статус = "candidate"
        e.причина = "имя совпало, домена нет ни у одного источника"

    # Разряда «имя совпало, домен есть у ВСЕХ и не противоречит» здесь нет, и это
    # не упущение: он недостижим. Если у обеих сторон есть домен и он тот же —
    # слияние произошло раньше, по домену, и статус уже verified. Если домены
    # разные — имя попало в спорные и не слило ничего. Первая версия такую ветку
    # содержала, она вечно показывала ноль и обещала доказательство, которого в
    # этой модели не бывает.


def свести(наборы: dict[str, list[tuple[str, str]]]) -> tuple[list[Сущность], list[dict]]:
    """Реестры → сущности плюс строки в очередь проверки.

    Порядок важен: сначала домен (сильный признак), потом имя. Иначе имя успеет
    слить то, что домен развёл бы.
    """
    # Спорные имена вычисляются ДО сведения: имя, указывающее на разные домены,
    # не имеет права ничего сливать.
    домены_имени: dict[str, set[str]] = collections.defaultdict(set)
    for строки in наборы.values():
        for имя, дом in строки:
            if имя and дом:
                домены_имени[имя].add(дом)
    спорные = {n for n, v in домены_имени.items() if len(v) > 1}

    по_домену: dict[str, Сущность] = {}
    по_имени: dict[str, Сущность] = {}
    сущности: list[Сущность] = []
    очередь: list[dict] = []

    for реестр, строки in наборы.items():
        for имя, дом in строки:
            if not имя and not дом:
                continue
            e = None
            if дом and дом in по_домену:                      # 1. домен
                e = по_домену[дом]
            elif имя and имя in спорные:                      # 3. спорное имя
                if имя in по_имени:
                    очередь.append({
                        "kind": "ambiguous_match",
                        "reason": "одно имя указывает на разные домены",
                        "domains": sorted(домены_имени[имя]),
                        "registry": реестр,
                    })
            elif имя and имя in по_имени:                     # 2. имя
                кандидат = по_имени[имя]
                if not дом or not кандидат.домены or дом in кандидат.домены:
                    e = кандидат
            if e is None:
                e = Сущность()
                сущности.append(e)
            if имя:
                e.имена.add(имя)
                по_имени.setdefault(имя, e)
            if дом:
                e.домены.add(дом)
                по_домену.setdefault(дом, e)
            e.источники.append((реестр, имя, дом))

    for e in сущности:
        классифицировать(e)
    return сущности, очередь


def гейты(сущности: list[Сущность], строк: int) -> list[str]:
    """Непройденный гейт отменяет запись. Возвращает список провалов."""
    провалы = []
    с_доменом = sum(1 for e in сущности if e.домены)
    доля = с_доменом / max(len(сущности), 1)
    if доля < ГЕЙТЫ["мин_доля_с_доменом"]:
        провалы.append(f"сущностей с доменом {100 * доля:.1f} %, "
                       f"порог {100 * ГЕЙТЫ['мин_доля_с_доменом']:.0f} %")
    схлопнуто = строк - len(сущности)
    if схлопнуто < ГЕЙТЫ["мин_схлопнуто"]:
        провалы.append(f"схлопнулось всего {схлопнуто} строк, "
                       f"порог {ГЕЙТЫ['мин_схлопнуто']}")
    return провалы


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true",
                    help="записать в базу (нужен SUPABASE_DB_URL); без него — вхолостую")
    ap.add_argument("--run-id", default="", help="ключ прогона; по умолчанию из времени")
    args = ap.parse_args()

    наборы = читать()
    строк = sum(len(v) for v in наборы.values())
    сущности, очередь = свести(наборы)

    по_статусу = collections.Counter(e.статус for e in сущности)
    с_доменом = sum(1 for e in сущности if e.домены)
    многоимённых = sum(1 for e in сущности if len(e.имена) > 1)

    print(f"РЕЕСТРОВ прочитано: {len(наборы)} из {len(РЕЕСТРЫ)}")
    print(f"строк на входе:     {строк}")
    print(f"сущностей вышло:    {len(сущности)}")
    print(f"схлопнулось строк:  {строк - len(сущности)}")
    print()
    одиночки = [e for e in сущности if e.статус == "single"]
    слияния = [e for e in сущности if e.статус != "single"]
    print("ЧТО ПОЛУЧИЛОСЬ")
    print(f"  одиночек (один источник, сливать не с чем): {len(одиночки)}")
    print(f"  слияний  (два и больше источников):         {len(слияния)}")
    print()
    print("СЛИЯНИЯ ПО ТОМУ, ЧЕМ ИХ МОЖНО ПРОВЕРИТЬ")
    for статус, пояснение in (
            ("verified", "домен совпал у двух и более источников"),
            ("candidate", "домен проверить нечем — нужен человек")):
        print(f"  {статус:10} {по_статусу.get(статус, 0):5}   {пояснение}")
    print()
    print(f"сущностей с доменом:             {с_доменом} "
          f"({100 * с_доменом / max(len(сущности), 1):.1f} %)")
    print(f"сущностей с несколькими именами: {многоимённых}")
    print(f"строк в очередь проверки:        {len(очередь)}")

    провалы = гейты(сущности, строк)
    print()
    if провалы:
        print("ГЕЙТЫ ПРИЁМКИ НЕ СОШЛИСЬ:")
        for p in провалы:
            print(f"  ✗ {p}")
        print("Запись отменена — так и задумано: правило меряют до применения.")
        return 1
    print("гейты приёмки: сошлись все")

    if not args.apply:
        print()
        print("Прогон ВХОЛОСТУЮ: в базу ничего не записано.")
        print("Номера будут выданы при --apply из sup_number_registry, а не здесь:")
        print(f"  первые три выглядели бы так — {номер(1)}, {номер(2)}, {номер(3)}")
        return 0

    url = os.environ.get("SUPABASE_DB_URL", "")
    if not url:
        print("нет переменной SUPABASE_DB_URL", file=sys.stderr)
        return 2
    print("\nЗАПИСЬ пока не реализована: сначала нужен шестой реестр (Bitrix).")
    print("Его даёт Actions → «Поставщики — замер сведения»; без него сведение")
    print("неполно, а номера выдаются навсегда — выдавать их до полного набора")
    print("признаков значит раздваивать сущности при следующем прогоне.")
    return 3


if __name__ == "__main__":
    raise SystemExit(main())
