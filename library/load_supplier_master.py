class Источник(NamedTuple):
    """Одна строка любого реестра, приведённая к общему виду.

    ключ — твёрдый идентификатор чужой системы («bitrix:12345») или пусто;
    формы — правовые формы из СЫРОГО названия, до нормализации;
    налоги — пары (вид, значение): ('inn', '7701234567'), ('vat', 'DE123…').
    Налоговый номер сильнее домена: домен тождество юрлица ПРЕДПОЛАГАЕТ, ИНН его
    ДОКАЗЫВАЕТ. Поэтому он и сливает, и запрещает слияние.
    """
    реестр: str
    имя: str
    домен: str
    ключ: str = ""
    формы: frozenset[str] = frozenset()
    налоги: frozenset[tuple[str, str]] = frozenset()


def номер(seq: int, род: str = "S") -> str:
    """KV-S-NNNNNN-C. Контрольная цифра считается по шести цифрам, как у деталей."""
    тело = str(seq).zfill(6)
    return f"KV-{род}-{тело}-{luhn(тело)}"


class Сущность:
    __slots__ = ("имена", "домены", "ключи", "формы", "налоги", "источники", "статус",
                 "причина", "чем_слито")

    def статус_схемы(self) -> str:
        """Статус сведения в словах схемы: sup_entity.resolution.

        verified → resolved, всё прочее → candidate. Одиночка тоже candidate:
        её никто не подтверждал, просто не с чем было сливать (ТЗ §5.3 —
        автоматически статус не повышается).
        """
        return "resolved" if self.статус == "verified" else "candidate"

    def __init__(self):
        self.имена: set[str] = set()
        self.домены: set[str] = set()
        # Твёрдые ключи: «bitrix:12345». Это не строковое совпадение, а настоящий
        # идентификатор чужой системы — по нему сущность опознаётся и в неё можно
        # записать обратно. Строкового ключа у файловых реестров нет.
        self.ключи: set[str] = set()
        # Правовые формы всех источников сущности. Не сливают, а запрещают слияние.
        self.формы: set[str] = set()
        # Налоговые номера: пары (вид, значение). В отличие от формы — и сливают,
        # и запрещают. Разный ИНН означает разные юрлица без всяких допущений.
        self.налоги: set[tuple[str, str]] = set()
        self.источники: list[Источник] = []
        # Чем присоединялись источники: «домен», «имя», «ключ». Нужно, чтобы
        # ответить, ПОЧЕМУ схлопнулись задвоения портала: по имени (дубль
        # карточки) или по домену (а это может быть и группа из разных юрлиц).
        self.чем_слито: set[str] = set()
        self.статус = "single"
        self.причина = "один источник, сливать не с чем"


def классифицировать(e: "Сущность") -> None:
    """Статус зависит от того, чем слияние МОЖНО ПРОВЕРИТЬ, а не от того,
    нашёлся ли домен хоть у кого-то.

    Первая версия этого не различала и ставила inferred всему, у чего домен
    был хотя бы с одной стороны. Замер показал цену ошибки: из 977 слияний
    доменом проверяемы 77, а 900 — нет, потому что у досье ГТУ сайта нет ни у
    одной из 1 359 записей. Девятьсот слияний уехали бы в базу вторым по силе
    статусом, хотя их никто не проверял. ТЗ §5.3: candidate и inferred НИКОГДА
    не повышаются автоматически.
    """
    if len(e.источники) < 2:
        e.статус = "single"
        e.причина = "один источник, сливать не с чем"
        return
    с_доменом = sum(1 for r in e.источники if r.домен)
    ключей = len(e.ключи)
    if ключей > 1:
        e.статус = "candidate"
        e.причина = (f"схлопнуты {ключей} карточки портала под одним именем — "
                     "задвоение Bitrix, подтвердить человеком")
        return
    if len(e.домены) == 1 and с_доменом >= 2:
        e.статус = "verified"
        e.причина = "домен совпал у двух и более источников"
    elif с_доменом > 0:
        e.статус = "candidate"
        e.причина = "имя совпало, но домен есть не у всех — проверить нечем"
    else:
        e.статус = "candidate"
        e.причина = "имя совпало, домена нет ни у одного источника"

    # Разряда «имя совпало, домен есть у ВСЕХ и не противоречит» здесь нет, и это
    # не упущение: он недостижим. Если у обеих сторон есть домен и он тот же —
    # слияние произошло раньше, по домену, и статус уже verified. Если домены
    # разные — имя попало в спорные и не слило ничего. Первая версия такую ветку
    # содержала, она вечно показывала ноль и обещала доказательство, которого в
    # этой модели не бывает.


def налог_мешает(мои: frozenset[tuple[str, str]] | set, чужие: set) -> bool:
    """Налоговые номера одного вида, но разные — это разные юрлица, и точка.

    Сравниваются только виды, которые есть у обеих сторон: у нас ИНН, у кандидата
    только VAT — это не противоречие, это разная полнота данных.
    """
    мои_виды = {k for k, _ in мои}
    чужие_виды = {k for k, _ in чужие}
    for вид in мои_виды & чужие_виды:
        a = {норма(v) for k, v in мои if k == вид}
        b = {норма(v) for k, v in чужие if k == вид}
        if a and b and not (a & b):
            return True
    return False


def свести(наборы: dict[str, list[Источник]]) -> tuple[list[Сущность], list[dict]]:
    """Реестры → сущности плюс строки в очередь проверки.

    ПОРЯДОК ПРИЗНАКОВ ОТ СИЛЬНОГО К СЛАБОМУ, и он важен: слабый признак, пущенный
    первым, успеет слить то, что сильный развёл бы.

      0. твёрдый ключ (bitrix:NNN) — настоящий идентификатор чужой системы;
      1. налоговый номер (ИНН, VAT) — доказывает тождество юрлица;
      2. домен — совпал у двух источников, значит это одна компания;
      3. имя — и только если ему ничто не противоречит.

    НАЛОГОВЫЙ НОМЕР ВЫШЕ ДОМЕНА, потому что домен тождество предполагает, а номер
    доказывает: у группы компаний один сайт на все юрлица. Он же единственный
    признак, который запрещает слияние по домену, — форма и имя этого не могут.

    ИМЕНИ ЗАПРЕЩЕНО СЛИВАТЬ В ТРЁХ СЛУЧАЯХ:
      • имя указывает на разные домены (спорное) — очередь, ambiguous_match;
      • домен строки противоречит домену сущности;
      • налоговые номера одного вида разные — очередь, different_tax_number;
      • правовые формы РАЗНЫЕ — очередь, different_legal_form. «ООО Ромашка» и
        «АО Ромашка» после norm_name неотличимы, а это разные юридические лица;
        слить их — приписать одному чужие сделки (ТЗ §1.12).

    А вот две карточки ПОРТАЛА под одним именем и с непротиворечивой формой имя
    слить обязано: это задвоение самого Bitrix (замер 20.09.2026 — 141 название
    на две и больше карточек), и без схлопывания статистика одного поставщика
    останется расщеплённой. Такое слияние получает статус candidate: оно ждёт
    человека, а не выдаётся за доказанное.
    """
    # Спорные имена вычисляются ДО сведения: имя, указывающее на разные домены,
    # не имеет права ничего сливать.
    домены_имени: dict[str, set[str]] = collections.defaultdict(set)
    for строки in наборы.values():
        for r in строки:
            if r.имя and r.домен:
                домены_имени[r.имя].add(r.домен)
    спорные = {n for n, v in домены_имени.items() if len(v) > 1}

    по_ключу: dict[str, Сущность] = {}
    по_налогу: dict[tuple[str, str], Сущность] = {}
    по_домену: dict[str, Сущность] = {}
    по_имени: dict[str, Сущность] = {}
    сущности: list[Сущность] = []
    очередь: list[dict] = []

    for реестр, строки in наборы.items():
        for r in строки:
            if not r.имя and not r.домен and not r.ключ:
                continue
            e = None
            чем = ""
            налог_ключи = [(k, норма(v)) for k, v in r.налоги if норма(v)]
            найден_налог = next((по_налогу[k] for k in налог_ключи if k in по_налогу), None)
            if r.ключ and r.ключ in по_ключу:                 # 0. твёрдый ключ
                e = по_ключу[r.ключ]
                чем = "ключ"
            elif найден_налог is not None:                    # 1. налоговый номер
                e = найден_налог
                чем = "инн"
            elif r.домен and r.домен in по_домену:            # 2. домен
                кандидат = по_домену[r.домен]
                if налог_мешает(r.налоги, кандидат.налоги):
                    # Один сайт, разные ИНН — это группа компаний, а не одна.
                    очередь.append({
                        "kind": "different_tax_number",
                        "reason": "домен совпал, налоговые номера разные — разные юрлица",
                        "registry": реестр,
                    })
                else:
                    e = кандидат
                    чем = "домен"
            elif r.имя and r.имя in спорные:                  # 4. спорное имя
                if r.имя in по_имени:
                    очередь.append({
                        "kind": "ambiguous_match",
                        "reason": "одно имя указывает на разные домены",
                        "domains": sorted(домены_имени[r.имя]),
                        "registry": реестр,
                    })
            elif r.имя and r.имя in по_имени:                 # 3. имя
                кандидат = по_имени[r.имя]
                домен_мешает = bool(r.домен and кандидат.домены
                                    and r.домен not in кандидат.домены)
                форма_мешает = bool(r.формы and кандидат.формы
                                    and not (r.формы & кандидат.формы))
                if налог_мешает(r.налоги, кандидат.налоги):
                    очередь.append({
                        "kind": "different_tax_number",
                        "reason": "имя совпало, налоговые номера разные — разные юрлица",
                        "registry": реестр,
                    })
                elif форма_мешает:
                    очередь.append({
                        "kind": "different_legal_form",
                        "reason": "имя совпало, правовые формы разные — разные юрлица",
                        "forms": sorted(r.формы | кандидат.формы),
                        "registry": реестр,
                    })
                elif not домен_мешает:
                    e = кандидат
                    чем = "имя"
            if e is None:
                e = Сущность()
                сущности.append(e)
            elif чем:
                e.чем_слито.add(чем)
            if r.имя:
                e.имена.add(r.имя)
                по_имени.setdefault(r.имя, e)
            if r.домен:
                e.домены.add(r.домен)
                по_домену.setdefault(r.домен, e)
            if r.ключ:
                e.ключи.add(r.ключ)
                по_ключу.setdefault(r.ключ, e)
            for пара in r.налоги:
                e.налоги.add(пара)
                if норма(пара[1]):
                    по_налогу.setdefault((пара[0], норма(пара[1])), e)
            e.формы |= r.формы
            e.источники.append(r)

    for e in сущности:
        классифицировать(e)
    return сущности, очередь


def читать_файлы() -> dict[str, list[Источник]]:
    """Пять файловых реестров в общем виде. Твёрдого ключа у них нет.

    Сырое название нужно для правовой формы, а читать() отдаёт уже
    нормализованное, поэтому форма берётся из второго прохода по тем же файлам —
    дублировать разбор JSON дешевле, чем менять сигнатуру читать(), на которую
    завязан замер scripts/supplier_registry_overlap.py.
    """
    import json

    сырые: dict[str, list[str]] = {}
    for имя, путь, ключ, поле_имени, _ in РЕЕСТРЫ:
        файл = ROOT / путь
        if not файл.exists():
            continue
        узел = json.loads(файл.read_text(encoding="utf-8"))[ключ]
        items = узел.items() if isinstance(узел, dict) else enumerate(узел)
        сырые[имя] = [str((з.get(поле_имени) if поле_имени else к) or "")
                      for к, з in items if isinstance(з, dict)]

    out: dict[str, list[Источник]] = {}
    for реестр, строки in читать().items():
        формы = сырые.get(реестр, [])
        out[реестр] = [Источник(реестр, n, d, "", форма(формы[i] if i < len(формы) else ""))
                       for i, (n, d) in enumerate(строки)]
    return out


def читать_битрикс(client, *, spa: int = 166,
                   поле: str = "ufCrm18Supplier") -> list[Источник]:
    """Шестой реестр: компании портала, которым писали запросы (СП-166).

    БЕРЁМ НЕ ВСЕ КОМПАНИИ ПОРТАЛА, а только те, на которые ссылается карточка
    запроса. Остальные — клиенты, перевозчики, наши же юрлица; в реестре
    поставщиков им делать нечего, а вечный номер выдаётся навсегда.

    Домен берётся из сайта карточки, а если его нет — из домена почты. Почтовые
    хостинги отсеивает norm_domain: адрес на gmail компанию не опознаёт.
    """
    карточки = client.list_items(spa, select=["id", поле])
    ids = set()
    for k in карточки:
        сырой = str(k.get(поле) or "")
        цифры = сырой.rsplit("_", 1)[-1] if "_" in сырой else сырой
        if цифры.isdigit():
            ids.add(int(цифры))

    целиком = sorted(ids)
    налоги = _реквизиты(client, целиком)

    строки: list[Источник] = []
    for i in range(0, len(целиком), 50):
        res = client.call("crm.company.list", {
            "filter": {"@ID": целиком[i:i + 50]},
            "select": ["ID", "TITLE", "WEB", "EMAIL"]}) or []
        for c in res:
            сырое = (c.get("TITLE") or "").strip()
            строки.append(Источник(
                реестр="bitrix/companies",
                имя=norm_name(сырое),
                домен=_домен_карточки(c),
                ключ=f"bitrix:{c['ID']}",
                формы=форма(сырое),
                налоги=налоги.get(int(c["ID"]), frozenset()),
            ))
    return строки


# Поля реквизитов, где лежит налоговый номер. RQ_INN — российский ИНН,
# RQ_VAT_ID — зарубежный VAT. ENTITY_TYPE_ID=4 — реквизиты компании.
ПОЛЯ_НОМЕРА = (("RQ_INN", "inn"), ("RQ_VAT_ID", "vat"))
ТИП_КОМПАНИЯ = 4


def _реквизиты(client, ids: list[int]) -> dict[int, frozenset[tuple[str, str]]]:
    """Налоговые номера компаний портала из crm.requisite.list.

    ЗАЧЕМ ОТДЕЛЬНЫЙ ЗАПРОС. Номер лежит НЕ на карточке компании, а в её
    реквизитах, и crm.company.list его не отдаёт ни в каком select. Замер
    20.09.2026 это показал (scripts/supplier_inn_coverage.py), но само сведение
    реквизиты не читало — и холостой прогон публикации 22:55 нашёл результат:
    32 ИНН в портале, НОЛЬ в реестре. Тот ИНН, который у нас уже есть, до
    реестра не доезжал.

    Пустая карточка реквизитов — основной случай: строк реквизитов много больше,
    чем непустых номеров. Пустое значение не пишется: признак «ИНН пустой» не
    признак, а отсутствие признака.
    """
    out: dict[int, set[tuple[str, str]]] = collections.defaultdict(set)
    for i in range(0, len(ids), 50):
        строки = client.list_paged("crm.requisite.list", {
            "filter": {"ENTITY_TYPE_ID": ТИП_КОМПАНИЯ, "ENTITY_ID": ids[i:i + 50]},
            "select": ["ID", "ENTITY_ID", *[поле for поле, _ in ПОЛЯ_НОМЕРА]]}) or []
        for r in строки:
            сырой = str(r.get("ENTITY_ID") or "")
            if not сырой.isdigit():
                continue
            for поле, вид in ПОЛЯ_НОМЕРА:
                v = (r.get(поле) or "").strip()
                if v:
                    out[int(сырой)].add((вид, v))
    return {cid: frozenset(v) for cid, v in out.items()}


def _домен_карточки(c: dict) -> str:
    """Сайт карточки, иначе домен первой почты. Пусто, если ни то ни другое."""
    for поле in ("WEB", "EMAIL"):
        for запись in (c.get(поле) or []):
            v = (запись.get("VALUE") if isinstance(запись, dict) else "") or ""
            d = norm_domain(v.rsplit("@", 1)[-1] if "@" in v else v)
            if d:
                return d
    return ""


def разбор(сущности: list[Сущность]) -> None:
    """Почему схлопнулись задвоения портала — и не склеил ли домен разные юрлица.

    ЗАЧЕМ. Прогон 20.09.2026 дал 456 схлопнутых задвоений против 141 у дневного
    замера, и разница объяснялась догадкой: «лишние сошлись по домену, а не по
    имени». Догадку надо мерить, а не принимать.

    ГЛАВНОЕ ЗДЕСЬ НЕ СЧЁТ, А РИСК. Совпадение имени сторожит правовая форма:
    «ООО Ромашка» и «АО Ромашка» не сливаются. Совпадение домена её НЕ спрашивает
    — домен считается сильным сам по себе. Значит две карточки одной группы с
    общим сайтом, но разными юрлицами, домен сольёт молча, и запрет смешивать
    юрлица (ТЗ §1.12) обойдётся стороной.

    Поэтому разложение идёт не по «имени или домену», а по тому, СОВПАДАЮТ ЛИ
    ИМЕНА у схлопнутого: одно имя — дубль карточки, разные — случай под вопросом.
    """
    задвоенные = [e for e in сущности if len(e.ключи) > 1]
    одно_имя = [e for e in задвоенные if len(e.имена) <= 1]
    разные = [e for e in задвоенные if len(e.имена) > 1]
    по_домену = [e for e in разные if "домен" in e.чем_слито]
    формы = [e for e in по_домену if len(e.формы) > 1]
    print("    из них по совпадению имени (дубль карточки):     "
          f"{len(одно_имя)}")
    print(f"    имена РАЗНЫЕ, схлопнул домен:                    {len(разные)}")
    print("      из них с несколькими правовыми формами:        "
          f"{len(формы)}  ← проверить человеком")
    print("    Разные имена под одним доменом — это и дубль с опечаткой, и группа")
    print("    из разных юрлиц. Форму домен не спрашивает, поэтому последняя")
    print("    строка и есть мера риска смешать юрлица (ТЗ §1.12).")


def гейты(сущности: list[Сущность], строк: int) -> list[str]:
    """Непройденный гейт отменяет запись. Возвращает список провалов."""
    провалы = []
    опознано = sum(1 for e in сущности if e.домены or e.ключи)
    доля = опознано / max(len(сущности), 1)
    if доля < ГЕЙТЫ["мин_доля_опознанных"]:
        провалы.append(f"сущностей с твёрдым признаком {100 * доля:.1f} %, "
                       f"порог {100 * ГЕЙТЫ['мин_доля_опознанных']:.0f} %")
    схлопнуто = строк - len(сущности)
    if схлопнуто < ГЕЙТЫ["мин_схлопнуто"]:
        провалы.append(f"схлопнулось всего {схлопнуто} строк, "
                       f"порог {ГЕЙТЫ['мин_схлопнуто']}")
    return провалы


