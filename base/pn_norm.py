#!/usr/bin/env python3
"""Ключ сведения артикула для базы знаний. Один на все модули base/.

ПОЧЕМУ НЕ pnkey. Имя pnkey уже занято модулем gt/tools/pnkey.py. Два файла с одним
именем в разных каталогах подменяют друг друга в зависимости от порядка sys.path,
и подмена молчаливая: ключ посчитается другим правилом, а ошибку никто не увидит.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Правило было выписано четырьмя копиями — kb_catalog.py:54,
quote.py:29 и дважды в JS страницы kb_page.py:106,108 — и ни одна не сводила
кириллические буквы-двойники к латинице. Ошибка здесь другая, чем была в
инструментах заявки: там правило кириллицу ВЫБРАСЫВАЛО, а здесь класс символов
`[^0-9A-ZА-Я]` её СОХРАНЯЕТ. Итог один и тот же — один номер под двумя ключами:

    «917427С1» с кириллической С  →  917427С1
    «917427C1» с латинской  C     →  917427C1

Это разные строки, и каталог считает их разными изделиями. Сведение двойников
исправляет ровно этот случай, и его давно применяют scripts/build_index.py,
scripts/lookup.py и gt/tools/pnkey.py — а base/ остался в стороне (замер аудита
20.09.2026). Таблица двойников взята оттуда же, из gt/tools/homoglyphs.py, чтобы
номер жил в репозитории под ОДНИМ ключом, а не под двумя в зависимости от модуля.

ЧЕГО ЗДЕСЬ НЕТ. Само поле артикула не правится: в нём записано то, что прислал
заказчик или поставщик, и менять это не наше дело. Сведение живёт только в ключе.

Прочую кириллицу правило не трогает: «БП-123» остаётся «БП123». Двойников ровно
девятнадцать — те буквы, что в латинице и кириллице пишутся одинаково.

ПОСЛЕ ИЗМЕНЕНИЯ КЛЮЧА нужен пересчёт: catalog_items и supplier_prices собираются
kb_catalog.py и match_prices.py, обе таблицы пересоздаются целиком на каждом
прогоне, поэтому половинчатого состояния не бывает — но до пересчёта старые ключи
в базе и новые в коде не совпадут. Порядок в base/RUNBOOK.md.
"""
from __future__ import annotations

import re

# Буквы, которые в латинице и кириллице выглядят одинаково. Источник тот же, что
# у gt/tools/homoglyphs.py: две таблицы обязаны совпадать, иначе номер снова
# получит два ключа — по одному на подсистему. Совпадение закреплено тестом.
HOMOGLYPHS = {
    "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M", "Н": "H", "О": "O",
    "Р": "P", "С": "C", "Т": "T", "У": "Y", "Х": "X",
    "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x",
}

# Что выбрасывается из ключа. Кириллица сохраняется намеренно: у российских
# изделий обозначение бывает кириллическим целиком, и выбрасывать его нельзя.
NORM = re.compile(r"[^0-9A-ZА-Я]")


def fold(s: str) -> str:
    """Сводит кириллические двойники к латинице. Прочую кириллицу не трогает."""
    return "".join(HOMOGLYPHS.get(c, c) for c in str(s or ""))


def key_of(pn: str) -> str:
    """Сравнимый вид артикула: двойники сведены, регистр верхний, разделители убраны.

    Сведение идёт ДО отсева символов и ДО перевода регистра — иначе строчная
    кириллическая «с» успела бы стать заглавной «С» и осталась бы кириллической.
    """
    return NORM.sub("", fold(pn or "").upper())


# Тот же алгоритм для JS страницы справочника: ключ, посчитанный в браузере,
# обязан совпадать с ключом в базе, иначе поиск по кириллическому написанию не
# найдёт запись, сохранённую под латинским.
JS_FOLD = (
    "const PN_HOMOGLYPHS={"
    + ",".join(f"'{k}':'{v}'" for k, v in HOMOGLYPHS.items())
    + "};\n"
    "const pnKey=(s)=>String(s||'').split('').map(c=>PN_HOMOGLYPHS[c]||c).join('')"
    ".toUpperCase().replace(/[^0-9A-ZА-Я]/g,'');\n"
)
