# СЛУЖЕБНЫЕ УЧЁТНЫЕ ЗАПИСИ. От их имени карточки запросов заводит робот. Их
# нельзя считать исполнителями — иначе работа сорсера, запустившего робота,
# исчезает из его статистики и оседает на служебной записи.
#
# Как устроен робот (замер 23.09.2026, зонд v46): карточку создаёт №234
# «Служебный Аккаунт №2» (446 карточек за отчётное окно), ответственным ставится
# №542 «Служебный Аккаунт №3 (Сорсинг)» (450). Ни одна не числится в отделе 172,
# поэтому вся работа робота уходила в столбец «вне отдела». №1718 — запись,
# подтверждённая владельцем как робот: 145 карточек, создаёт и ведёт сама.
#
# ОШИБКА, КОТОРУЮ НЕЛЬЗЯ ПОВТОРИТЬ. «Аккаунт №2» — это ИМЯ записи, а не её
# номер в портале. Номер 2 в умолчании стоял ошибочно: у пользователя с таким
# идентификатором за всю историю смарт-процесса нет ни одной карточки.
#
# СОСТАВ МЕНЯЕТСЯ, поэтому источников два и оба живые:
#   * номера — SERVICE_ACCOUNT_IDS из окружения, иначе умолчание ниже;
#   * имя — запись, чьё имя само называет её служебной (закрытый список слов
#     SERVICE_NAME_RE). Нового робота, заведённого с таким именем, разбор
#     подхватит сам, без правки кода и без деплоя.
# Отключается всё словом «off», а не пустым значением: GitHub Actions
# подставляет пустую строку для каждой НЕзаданной переменной, и «пусто =
# выключено» тихо обнуляло бы список на каждом прогоне.
SERVICE_ACCOUNT_DEFAULT = "234,542,1718"
SERVICE_ACCOUNT_OFF = "off"
# Закрытый список: признак ИМЕНИ, а не должности. Живого человека по нему не
# спутать — «Аккаунт», «Служебный» и «Бот» фамилиями не бывают.
SERVICE_NAME_RE = re.compile(
    r"служебн|аккаунт|\bбот\b|\bbot\b|robot|webhook|service\s+account", re.I)
_service_env = (os.getenv("SERVICE_ACCOUNT_IDS") or "").strip()
SERVICE_ACCOUNTS_OFF = _service_env.lower() == SERVICE_ACCOUNT_OFF
_service_raw = "" if SERVICE_ACCOUNTS_OFF else (_service_env or SERVICE_ACCOUNT_DEFAULT)
SERVICE_ACCOUNT_IDS = {u.strip() for u in _service_raw.split(",") if u.strip()}


def service_accounts(names: dict[str, str]) -> set[str]:
    """Служебные записи: заданные номерами плюс названные служебными по имени."""
    if SERVICE_ACCOUNTS_OFF:
        return set()
    return set(SERVICE_ACCOUNT_IDS) | {u for u, n in names.items() if SERVICE_NAME_RE.search(n or "")}


