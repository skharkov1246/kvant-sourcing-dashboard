"""Правка чтения цены не берёт сумму строки за цену за единицу.

ЗАЧЕМ. Холостой переразбор 5 617 КП (прогон 36294056418, PRICE_DICT_V2 и
HEADERLESS_PRICE включены) разложил 2 545 строк со сменённой ценой, и 34 из них
легли в вид «была ценой за единицу — стала суммой строки (ДЕФЕКТ)»: новая цена
ровно в количество раз больше прежней. Путей у словаря v2 к этому три — каждый
ниже выдуманной шапкой (CLAUDE.md, правило 18): прежнее правило берёт цену за
единицу, словарь v2 — колонку суммы партии. Закрывает их одна проверка
арифметикой по файлу (indexer.цена_это_сумма).

И ошибки самого классификатора reparse.характер_смены, найденные перебором
выдуманных шапок (61 176 строк со сменённой ценой на прочтении до проверки):
  • ложный дефект — прежнее правило делило на количество цену за единицу («Сумма
    за ед.» бралась суммой строки), правка читает верно, а смена выглядела
    дефектом (68 строк перебора);
  • спрятанный дефект — сумма строки другой природы НДС, чем прежняя цена, шла в
    «выросла …» и даже в желательную «было делением суммы — стала колонкой цены»;
  • новая цена, не сошедшаяся со своей суммой (сверка сняла количество), тоже
    шла в желательную смену.

Здесь же — что желательные виды смены (сумма → цена за единицу, деление суммы →
колонка цены, снят НДС) проверкой не задеты.
"""
from __future__ import annotations

import pytest

from library import indexer
from library import quotes as q
from library import reparse

# Позиции: наименование, количество, цена за единицу. Количество больше единицы
# у всех — иначе цена и сумма строки совпадают и спорить не о чем.
ПОЗИЦИИ = [("Насос ЦНС 38-176 с рамой", 2, 150000.0), ("Задвижка 30с41нж Ду100", 4, 25000.0),
           ("Подшипник 6208-2RS", 10, 350.0), ("Уплотнение торцевое", 3, 12000.0)]
ДЕФЕКТ = "была ценой за единицу — стала суммой строки (ДЕФЕКТ)"


def _деньги(x: float) -> str:
    return f"{x:,.2f}".replace(",", " ").replace(".", ",")


def _таблица(шапка: list[str], ячейки) -> list[list[str]]:
    """ячейки(кол, цена) → числа денежных колонок строки."""
    return [["Наименование", "Кол-во"] + шапка] + [
        [имя, str(кол)] + [_деньги(x) for x in ячейки(кол, цена)] for имя, кол, цена in ПОЗИЦИИ]


# Три пути словаря v2 к сумме строки. Номер колонки суммы в полной строке шапки
# (с «Наименованием» и «Кол-вом»): её v2 берёт ценой, прежнее правило — нет.
# Прежняя колонка цены везде первая из денежных — её число и есть цена за единицу.
ПУТИ = {
    # Прежняя колонка цены названа с НДС без «с» и «без»: для v2 это налог, и
    # ценой становится соседняя колонка со словом цены — сумма партии.
    "налог": (["Цена за ед., руб. (НДС 20%)", "Общая цена, руб."],
              lambda к, ц: [ц, ц * к], 3),
    "налог, английская шапка": (["Unit price (13%VAT)", "Price incl. VAT"],
                                lambda к, ц: [ц, ц * к], 3),
    # Сумма без НДС Китая при цене с ним: сходится только с учётом ставки 13 %.
    "налог 13 %, сумма без НДС": (["Unit price (13%VAT)", "Price excl. VAT"],
                                  lambda к, ц: [ц * 1.13, ц * к], 3),
    # Прежняя колонка «чужая» для v2 («прайс»).
    "чужая": (["Цена по прайсу, руб.", "Цена партии, руб."], lambda к, ц: [ц, ц * к], 3),
    "чужая, сумма с НДС": (["Цена по прайсу, руб.", "Цена партии с НДС, руб."],
                           lambda к, ц: [ц, ц * к * 1.2], 3),
    # Две цены, с НДС и без: v2 берёт «без», а это сумма партии.
    "пара с/без НДС": (["Цена за ед., руб.", "Цена за ед. с НДС, руб.",
                        "Цена партии без НДС, руб."],
                       lambda к, ц: [ц, ц * 1.2, ц * к], 4),
}


@pytest.mark.parametrize("путь", list(ПУТИ))
def test_путь_v2_к_сумме_воспроизведён_словарём(путь):
    """Сам словарь берёт колонку суммы ценой — это и есть дефект, который ловит
    проверка. Если словарь поправят, тест скажет, что путь закрыт иначе."""
    шапка, _, j_суммы = ПУТИ[путь]
    полная = ["Наименование", "Кол-во"] + шапка
    assert q.колонки_цены(полная, v2=True).get("price") == j_суммы
    assert q.колонки_цены(полная, v2=False).get("price") == 2


@pytest.mark.parametrize("путь", list(ПУТИ))
def test_правка_не_берёт_сумму_строки_за_цену(путь):
    шапка, ячейки, _ = ПУТИ[путь]
    items = indexer.items_from_rows(_таблица(шапка, ячейки), словарь_v2=True, без_шапки=True)
    assert len(items) == len(ПОЗИЦИИ)
    for it, (_, кол, цена) in zip(items, ПОЗИЦИИ):
        ц, прежде = it["_цена"], it["_цена_прежде"]
        за_единицу = round(ячейки(кол, цена)[0], 2)
        assert прежде["price"] == за_единицу, "прежнее правило брало цену за единицу"
        assert ц["price"] == за_единицу, (путь, ц["price"], "сумма строки?")
        assert indexer.ОГОВОРКА_ЦЕНА_БЫЛА_СУММОЙ in ц["note"]
        assert it["qty"] == кол
    # И переразбор больше не видит здесь дефекта: значение не сменилось.
    assert not reparse.характеры_смены(items)


def test_решение_по_файлу_строка_без_количества_тоже_получает_цену_за_единицу():
    """Правило 13: колонка — сумма для всего файла, а не для строк, где это
    видно. Строка без количества иначе осталась бы с суммой партии за цену."""
    шапка, ячейки, _ = ПУТИ["чужая"]
    rows = _таблица(шапка, ячейки)
    rows.append(["Кольцо уплотнительное 100х4", "", _деньги(80.0), _деньги(400.0)])
    it = indexer.items_from_rows(rows, словарь_v2=True, без_шапки=False)[-1]
    assert it["qty"] is None
    assert it["_цена"]["price"] == 80.0


def test_строки_с_количеством_один_колонку_суммой_не_делают():
    """При количестве 1 цена и сумма строки равны — по такой строке колонку
    суммой не признать. Файл, где почти все строки штучные, а цена v2 верна
    (прежнее правило брало голым «цена» колонку «Цена партии»), остаётся с ценой
    v2: у штучных строк прежняя цена × 1 совпала бы с новой, и по ним одним
    проверка вернула бы сумму партии пятиштучной строке."""
    позиции = [("Насос ЦНС 38-176 с рамой", 1, 150000.0), ("Задвижка 30с41нж Ду100", 1, 25000.0),
               ("Подшипник 6208-2RS", 1, 350.0), ("Уплотнение торцевое", 5, 12000.0)]
    rows = [["Наименование", "Кол-во", "Price", "Цена партии"]] + [
        [имя, str(кол), _деньги(ц), _деньги(ц * кол)] for имя, кол, ц in позиции]
    items = indexer.items_from_rows(rows, словарь_v2=True, без_шапки=False)
    assert [it["_цена"]["price"] for it in items] == [ц for _, _, ц in позиции]
    assert items[-1]["_цена_прежде"]["price"] == 60000.0, "прежнее брало сумму"


def test_количество_равное_ставке_ндс_колонку_суммой_не_делает():
    """1,2 м × цена = сумма, и сумма ÷ 1,2 (снятый НДС) — снова цена: по такой
    строке верная цена за единицу выглядела бы суммой. Поэтому судят строки с
    количеством от двух."""
    rows = [["Наименование", "Кол-во", "Price", "Сумма"]] + [
        [имя, "1,2", _деньги(ц), _деньги(ц * 1.2)] for имя, _, ц in ПОЗИЦИИ]
    for it, (_, _, цена) in zip(indexer.items_from_rows(rows, словарь_v2=True,
                                                        без_шапки=False), ПОЗИЦИИ):
        assert it["qty"] == 1.2
        assert it["_цена"]["price"] == цена
        assert indexer.ОГОВОРКА_ЦЕНА_БЫЛА_СУММОЙ not in (it["_цена"]["note"] or "")
        assert q.ОГОВОРКА_ИЗ_СУММЫ not in (it["_цена"]["note"] or "")


def test_прежняя_колонка_сумма_по_v2_ценой_не_возвращается():
    """«Total price, EUR» прежнее правило брало ценой (образец «price, »), а v2 —
    суммой. Если и колонка цены v2 оказалась суммой, вернуть «прежнюю колонку»
    значит снова взять сумму: цена тогда выводится делением суммы."""
    шапка = ["Цена партии, EUR", "Total price, EUR"]
    полная = ["Наименование", "Кол-во"] + шапка
    assert q.колонки_цены(полная, v2=False)["price"] == 3
    assert q.колонки_цены(полная, v2=True) == {"price": 2, "total": 3}
    for it, (_, кол, цена) in zip(indexer.items_from_rows(
            _таблица(шапка, lambda к, ц: [ц * к, ц * к]), словарь_v2=True, без_шапки=False),
            ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert q.ОГОВОРКА_ИЗ_СУММЫ in it["_цена"]["note"]
        assert it["qty"] == кол


def test_без_флага_проверка_не_работает_и_оговорки_нет():
    шапка, ячейки, _ = ПУТИ["налог"]
    for it in indexer.items_from_rows(_таблица(шапка, ячейки), словарь_v2=False,
                                      без_шапки=False):
        assert "_цена_прежде" not in it
        assert indexer.ОГОВОРКА_ЦЕНА_БЫЛА_СУММОЙ not in (it["_цена"]["note"] or "")


def test_оговорка_ндс_прежней_колонки_пишется_вместо_оговорки_отвергнутой():
    """Оговорка «взята цена без НДС» говорила о колонке суммы — её больше нет."""
    шапка, ячейки, _ = ПУТИ["пара с/без НДС"]
    ц = indexer.items_from_rows(_таблица(шапка, ячейки), словарь_v2=True,
                                без_шапки=False)[0]["_цена"]
    assert q.ОГОВОРКА_БЕЗ_НДС not in ц["note"]
    # Прежняя колонка названа «с НДС» — это и пишется.
    шапка_с = ["Цена по прайсу с НДС, руб.", "Цена партии с НДС, руб."]
    ц = indexer.items_from_rows(_таблица(шапка_с, lambda к, x: [x * 1.2, x * к * 1.2]),
                                словарь_v2=True, без_шапки=False)[0]["_цена"]
    assert ц["price"] == 180000.0
    assert ц["note"].startswith(q.ОГОВОРКА_С_НДС)
    assert indexer.ОГОВОРКА_ЦЕНА_БЫЛА_СУММОЙ in ц["note"]


# ── желательные смены проверкой не задеты ───────────────────────────────────
def _виды(шапка, ячейки, *, позиции=ПОЗИЦИИ):
    rows = [["Наименование", "Кол-во"] + шапка] + [
        [имя, str(кол)] + [_деньги(x) for x in ячейки(кол, цена)] for имя, кол, цена in позиции]
    items = indexer.items_from_rows(rows, словарь_v2=True, без_шапки=True)
    assert all(indexer.ОГОВОРКА_ЦЕНА_БЫЛА_СУММОЙ not in (it["_цена"]["note"] or "")
               for it in items), "проверка сработала на верно прочитанной цене"
    return items, reparse.характеры_смены(items)


def test_сумма_строки_стала_ценой_за_единицу_сохраняется():
    """Прежнее правило брало голое «цена» из «Цена итого» — сумму строки; v2
    знает «итого» суммой и берёт «Price»."""
    items, виды = _виды(["Price", "Цена итого"], lambda к, ц: [ц, ц * к])
    assert [it["_цена"]["price"] for it in items] == [ц for _, _, ц in ПОЗИЦИИ]
    assert виды == {"была суммой строки — стала ценой за единицу": len(ПОЗИЦИИ)}


def test_деление_суммы_стало_колонкой_цены_сохраняется():
    """Прежнее правило «Price (EUR)» не знало и делило сумму; округлённая цена
    колонки отличается от частного — это смена, и она желательная."""
    # Цена за единицу в КП округлена, сумма посчитана от неокруглённой: 100/3.
    позиции = [("Насос ЦНС 38-176 с рамой", 3, 33.33), ("Задвижка 30с41нж Ду100", 7, 14.29),
               ("Подшипник 6208-2RS", 6, 16.67)]
    суммы = {33.33: 100.0, 14.29: 100.0, 16.67: 100.0}
    items, виды = _виды(["Price (EUR)", "Total"], lambda к, ц: [ц, суммы[ц]],
                        позиции=позиции)
    assert [it["_цена"]["price"] for it in items] == [ц for _, _, ц in позиции]
    assert set(виды) <= {"было делением суммы — стала колонкой цены",
                         "валюта названа · было делением суммы — стала колонкой цены"}
    assert sum(виды.values()) == len(позиции)


def test_снятый_ндс_сохраняется():
    items, виды = _виды(["Цена с НДС", "Цена без НДС", "Сумма без НДС"],
                        lambda к, ц: [ц * 1.2, ц, ц * к])
    assert [it["_цена"]["price"] for it in items] == [ц for _, _, ц in ПОЗИЦИИ]
    assert виды == {"÷1.20 — снят НДС 20 %": len(ПОЗИЦИИ)}


# ── классификатор: дефект только там, где новая цена не сверена ─────────────
def test_классификатор_не_зовёт_дефектом_исправленное_деление_цены():
    """«Сумма за ед.» прежнее правило брало суммой строки и делило на кол-во;
    v2 берёт суммой «Сумма без НДС», и цена верна. Рост в количество раз здесь —
    исправление, а не дефект: новая цена выведена из своей суммы."""
    rows = _таблица(["Сумма за ед., руб.", "Сумма без НДС, руб."], lambda к, ц: [ц, ц * к])
    items = indexer.items_from_rows(rows, словарь_v2=True, без_шапки=False)
    for it, (_, кол, цена) in zip(items, ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert it["_цена_прежде"]["price"] == pytest.approx(цена / кол, abs=1e-4)
    виды = reparse.характеры_смены(items)
    assert ДЕФЕКТ not in виды
    assert виды == {"была ценой за единицу, делённой на кол-во, — стала ценой за единицу":
                    len(ПОЗИЦИИ)}


def test_классификатор_дефект_только_у_несверенной_цены():
    х = reparse.характер_смены
    исправлено = "была ценой за единицу, делённой на кол-во, — стала ценой за единицу"
    # Новая цена без суммы — проверить нечем: дефект, как и был.
    assert х({"price": 300.0}, {"price": 900.0}, 3) == ДЕФЕКТ
    # Новая цена сходится со своей суммой тройкой — суммой строки она быть не может.
    assert х({"price": 300.0}, {"price": 900.0, "total": 2700.0}, 3) == исправлено
    # Сумма есть, но не сходится (сумма = цена): это и есть сумма под словом цены.
    assert х({"price": 300.0}, {"price": 900.0, "total": 900.0}, 3) == ДЕФЕКТ
    # Новая цена выведена делением своей суммы.
    assert х({"price": 300.0, "note": "цена выведена делением суммы строки на количество"},
             {"price": 900.0, "note": "цена выведена делением суммы строки на количество"},
             3) == исправлено


def test_классификатор_видит_сумму_строки_другой_природы_ндс():
    """Прежняя цена без НДС выведена делением суммы, новая — сумма партии с НДС:
    рост в «кол-во × 1,2» раз. Прежде такая смена шла в «выросла …» или даже
    желательной «было делением суммы — стала колонкой цены», и дефект прятался:
    в переборе шапок на прочтении до проверки — 3 296 и 48 строк."""
    х = reparse.характер_смены
    делением = "цена выведена делением суммы строки на количество"
    assert х({"price": 100.0, "note": делением}, {"price": 360.0}, 3) == \
        "была ценой за единицу — стала суммой строки, НДС ×1.20 (ДЕФЕКТ)"
    assert х({"price": 120.0}, {"price": 300.0}, 3) == \
        "была ценой за единицу — стала суммой строки, НДС ÷1.20 (ДЕФЕКТ)"
    # НДС Китая: 13 %.
    assert х({"price": 100.0}, {"price": 339.0}, 3) == \
        "была ценой за единицу — стала суммой строки, НДС ×1.13 (ДЕФЕКТ)"
    # Желательная смена «делением → колонка» (округление цены) не задета.
    assert х({"price": 33.3333, "note": делением}, {"price": 33.33}, 3) == \
        "было делением суммы — стала колонкой цены"


def test_деление_суммы_и_не_сошедшаяся_колонка_цены_к_проверке():
    """Новая цена не сошлась со своей суммой, и сверка сняла количество: отношение
    к количеству проверить нечем, и желательной такую смену назвать нельзя. Здесь
    прежнее правило делило «Сумму за ед.», v2 взял ценой «Price» с суммой партии —
    неверны оба, и смена идёт к проверке, а не в «было делением — стала колонкой»."""
    rows = _таблица(["Сумма за ед., руб.", "Price"], lambda к, ц: [ц, ц * к])
    items = indexer.items_from_rows(rows, словарь_v2=True, без_шапки=False)
    assert all(q.КОЛ_НЕ_СОШЛОСЬ in it["_цена"]["note"] for it in items)
    assert reparse.характеры_смены(items) == {
        "было делением суммы — стала колонкой цены, с суммой не сошлась (ПРОВЕРИТЬ)":
            len(ПОЗИЦИИ)}
