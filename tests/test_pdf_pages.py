def test_счёт_страниц_пишется_и_когда_таблица_опозналась(подставить):
    """Смешанный PDF с опознанной таблицей тоже обязан попасть в распознавание.

    Прежде счёт вёлся только в текстовом пути: файл, у которого таблица нашлась,
    оставался неотмеченным, и его сканы не видел никто.
    """
    # ТАБЛИЦА ДОЛЖНА ДЕЙСТВИТЕЛЬНО ОПОЗНАТЬСЯ, иначе файл уйдёт текстовым путём,
    # счёт запишется там, и мутация «убрать счёт из ветки PDF» проверку переживёт.
    страница = "\n".join([
        "Наименование            Кол-во      Цена",
        "Насос ЦНС-38                  2      1500",
        "Задвижка 30с41нж              4       250",
        "Подшипник 6208               10        35",
        "Прокладка паронит             6        12",
    ])
    подставить([страница, "", "  "])
    rec: dict = {}
    строки, текст, отказ = indexer.читать(b"%PDF", "pdf", rec)
    assert строки, "таблица не опозналась — проверка стережёт не тот путь"
    assert текст == "", "файл ушёл текстом, а должен был таблицей"
    assert rec["pdf_pages"] == 3, rec
    assert rec["pdf_mixed"] is True, "смешанный документ с таблицей не отмечен"


def test_один_проход_читает_страницы_единожды(подставить, monkeypatch):
    """Прежде файл, ушедший текстом, читался pypdf ДВАЖДЫ: с выравниванием ради
    таблицы и обычным режимом ради текста — по шестьдесят страниц каждый раз."""
    подставить(["Договор поставки без таблицы. " * 20])
    вызовы = {"n": 0}
    настоящая = indexer.страницы_pdf

    def считать(b, *, layout=False):
        вызовы["n"] += 1
        return настоящая(b, layout=layout)

    monkeypatch.setattr(indexer, "страницы_pdf", считать)
    monkeypatch.setattr(indexer, "ОДИН_ПРОХОД", True)
    строки, текст, отказ = indexer.читать(b"%PDF", "pdf", {})
    assert вызовы["n"] == 1, f"страницы прочитаны {вызовы['n']} раза вместо одного"
    assert "Договор поставки" in текст


