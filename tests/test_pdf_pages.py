def test_страница_с_единственным_номером_листа_за_текст_не_считается(подставить):
    """Скан даёт «12» или штамп — это не текстовый слой."""
    подставить(["12", "Насос ЦНС-38 две штуки по тысяче пятьсот рублей за штуку"])
    rec: dict = {}
    indexer.text_from_pdf(b"%PDF", rec)
    assert rec["pdf_pages_text"] == 1, "номер листа принят за текстовый слой"
    assert rec["pdf_mixed"] is True
