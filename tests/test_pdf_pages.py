"""Постраничное чтение PDF: одна страница не уносит файл, смешанный виден.

PDF — главное узкое место системы: 11 217 файлов, из них 1 683 без позиций, и
ещё 3 474 стоят в клетке «текст, шапки нет» с 334 535 позициями почти без цены.

Два дефекта, найденные разбором кода 23.09.2026:

  • сбой режима layout на ОДНОЙ странице возвращал пустой список за ВЕСЬ файл,
    и уже прочитанные страницы выбрасывались;
  • смешанный PDF (часть страниц текстовые, часть сканы) теряется молча: одна
    текстовая страница даёт chars > 0, файл получает «разобран», и отбор
    распознавания его не берёт никогда — а сканы в нём это позиции и цены.

Страницы здесь придуманные (подставной читатель), а не снятые с базы: правило 18.
"""
from __future__ import annotations

import pytest

from library import indexer


class Страница:
    """Подставная страница pypdf: либо отдаёт текст, либо падает."""

    def __init__(self, текст: str | None):
        self.текст = текст

    def extract_text(self, extraction_mode: str = "plain") -> str:
        if self.текст is None:
            raise ValueError("страница не читается")
        return self.текст


class Читатель:
    def __init__(self, страницы):
        self.pages = страницы


@pytest.fixture
def подставить(monkeypatch):
    def внутри(тексты):
        страницы = [Страница(t) for t in тексты]
        import sys
        import types
        модуль = types.SimpleNamespace(PdfReader=lambda _поток: Читатель(страницы))
        monkeypatch.setitem(sys.modules, "pypdf", модуль)
    return внутри


def test_одна_битая_страница_не_уносит_весь_файл(подставить):
    """Прежде сбой на любой странице возвращал ноль строк за весь документ."""
    подставить(["Наименование  Кол-во  Цена", None, "Насос ЦНС-38  2  1500"])
    страницы, всего, потеряно = indexer.страницы_pdf(b"%PDF", layout=True)
    assert всего == 3 and потеряно == 1
    assert "Наименование" in страницы[0] and "Насос" in страницы[2]
    assert страницы[1] == "", "непрочитанная страница должна быть пустой, а не отсутствовать"


def test_смешанный_pdf_назван_смешанным(подставить):
    """Одна текстовая страница из трёх — и файл уже не берут в распознавание.

    Без этой пометки два скана внутри документа теряются вместе со своими
    позициями и ценами.
    """
    подставить(["Договор поставки. " * 20, "", "   \n  "])
    rec: dict = {}
    indexer.text_from_pdf(b"%PDF", rec)
    assert rec["pdf_pages"] == 3
    assert rec["pdf_pages_text"] == 1
    assert rec["pdf_mixed"] is True, "смешанный документ не назван"


def test_полностью_текстовый_pdf_смешанным_не_считается(подставить):
    подставить(["Договор поставки. " * 20, "Спецификация. " * 20])
    rec: dict = {}
    indexer.text_from_pdf(b"%PDF", rec)
    assert rec["pdf_pages_text"] == 2 and rec.get("pdf_mixed") is None


def test_полный_скан_смешанным_не_считается_и_это_важно(подставить):
    """Скан целиком уже берётся распознаванием; смешанный — нет, и разница в этом."""
    подставить(["", "  ", "\n"])
    rec: dict = {}
    indexer.text_from_pdf(b"%PDF", rec)
    assert rec["pdf_pages_text"] == 0 and rec.get("pdf_mixed") is None


