"""Цена по прайсу в словаре v2 — чужая, только если в шапке есть другая цена.

ЗАЧЕМ. До 27.09.2026 словарь v2 (quotes.СЛОВАРЬ_V2) отбрасывал колонку со
словом «прайс» или «price list» всегда — ради КП «Цена по прайсу | Скидка |
Цена со скидкой», где ценой предложения должна быть цена со скидкой. Но в КП,
где другой цены нет, прайсовая и есть ответ поставщика, а v2 не брал ничего,
хотя прежнее правило её читало: перебор выдуманных шапок дал 62 и 222 шапки
«прежнее — цена за единицу, v2 — ничего», все с «Ценой по прайсу». Ещё сотни
шапок выводили цену делением суммы, хотя колонка цены в них стоит.

Теперь прайсовая цена:
  • отбрасывается, если в шапке есть другая цена — со скидкой, «Net price»,
    даже та, при которой НДС лишь упомянут;
  • берётся, если другой цены нет и суммы нет;
  • при колонке суммы — только если сходится с ней по файлу: иначе сумма
    посчитана со скидкой, и цена предложения — её частное, как прежде;
  • при ненулевой скидке отдельной колонкой — с оговоркой и уверенностью low.
Ссылка на прайс-лист («Price list No.») ценой не бывает никогда. Колонку самой
скидки («Скидка, %», «Сумма скидки») от цены со скидкой отличает
quotes.колонка_скидки_ли.

Корпуса придуманы (CLAUDE.md, правило 18).
"""
from __future__ import annotations

import pytest

from library import indexer
from library import quotes as q

# Наименование, количество, цена предложения за единицу (со скидкой, без НДС).
ПОЗИЦИИ = [("Насос ЦНС 38-176 с рамой", 2, 150000.0), ("Задвижка 30с41нж Ду100", 4, 25000.0),
           ("Подшипник 6208-2RS", 10, 350.0), ("Уплотнение торцевое", 3, 12000.0)]
# Прайсовая цена при скидке 20 %: цена предложения — 0,8 прайсовой.
ПРАЙС = 1 / 0.8


def _деньги(x: float) -> str:
    return f"{x:,.2f}".replace(",", " ").replace(".", ",")


def _таблица(шапка: list[str], ячейки) -> list[list[str]]:
    """ячейки(кол, цена) → ячейки денежных колонок строки (строки или числа)."""
    return [["Наименование", "Кол-во"] + шапка] + [
        [имя, str(кол)] + [x if isinstance(x, str) else _деньги(x) for x in ячейки(кол, цена)]
        for имя, кол, цена in ПОЗИЦИИ]


def _v2(шапка, ячейки) -> list[dict]:
    items = indexer.items_from_rows(_таблица(шапка, ячейки), словарь_v2=True, без_шапки=True)
    assert len(items) == len(ПОЗИЦИИ)
    return items


def _note(it) -> str:
    return it["_цена"]["note"] or ""


# ── потеря цены: прайсовая — единственная цена шапки ─────────────────────────
ОДНА_ПРАЙСОВАЯ = {
    "одна": (["Цена по прайсу, руб."], lambda к, ц: [ц]),
    "при налоге": (["Цена по прайсу, руб.", "НДС, руб."], lambda к, ц: [ц, ц * к * 0.2]),
    # «Стоимость» здесь — сумма строки; ценой её v2 без сверки не берёт.
    "при стоимости": (["Цена по прайсу, руб.", "Стоимость, руб."], lambda к, ц: [ц, ц * к]),
    "прайсовая цена": (["Прайсовая цена, руб.", "Value"], lambda к, ц: [ц, ц * к]),
    "английская": (["Price list price, EUR", "VAT"], lambda к, ц: [ц, ц * к * 0.2]),
    "прайс-лист": (["Цена по прайс-листу, EUR"], lambda к, ц: [ц]),
}


@pytest.mark.parametrize("вариант", list(ОДНА_ПРАЙСОВАЯ))
def test_прайсовая_единственная_цена_берётся(вариант):
    шапка, ячейки = ОДНА_ПРАЙСОВАЯ[вариант]
    assert q.колонки_цены(["Наименование", "Кол-во"] + шапка, v2=True).get("price") == 2
    for it, (_, кол, цена) in zip(_v2(шапка, ячейки), ПОЗИЦИИ):
        assert it["_цена_прежде"]["price"] == цена, "прежнее правило брало прайсовую"
        assert it["_цена"]["price"] == цена
        assert it["_цена"]["confidence"] == "med"
        assert q.ОГОВОРКА_ПРАЙС_СКИДКА not in _note(it)
        assert it["qty"] == кол


# ── сохранение: прайс + скидка + цена со скидкой — цена со скидкой ───────────
СО_СКИДКОЙ = {
    "русская": (["Цена по прайсу, руб.", "Скидка, %", "Цена со скидкой, руб.", "Сумма, руб."],
                lambda к, ц: [ц * ПРАЙС, "20%", ц, ц * к], 4, 1.0),
    "прайсовая цена": (["Прайсовая цена, руб.", "Цена со скидкой, руб."],
                       lambda к, ц: [ц * ПРАЙС, ц], 3, 1.0),
    "английская": (["Price list price, EUR", "Discount, %", "Net price, EUR", "Amount"],
                   lambda к, ц: [ц * ПРАЙС, "20", ц, ц * к], 4, 1.0),
    # Другая цена — та, при которой НДС лишь упомянут: прайсовая всё равно чужая.
    "другая при НДС": (["Цена по прайсу, руб.", "Цена со скидкой, руб. (НДС 20%)"],
                       lambda к, ц: [ц * ПРАЙС, ц * 1.2], 3, 1.2),
}


@pytest.mark.parametrize("вариант", list(СО_СКИДКОЙ))
def test_прайсовая_при_другой_цене_отбрасывается(вариант):
    шапка, ячейки, j_цены, множитель = СО_СКИДКОЙ[вариант]
    assert q.колонки_цены(["Наименование", "Кол-во"] + шапка, v2=True)["price"] == j_цены
    for it, (_, кол, цена) in zip(_v2(шапка, ячейки), ПОЗИЦИИ):
        assert it["_цена"]["price"] == round(цена * множитель, 2)
        assert q.ОГОВОРКА_ПРАЙС_СКИДКА not in _note(it)
        assert it["qty"] == кол
        if "Сумма, руб." in шапка or "Amount" in шапка:
            assert it["_цена"]["total"] == цена * кол


# ── при колонке суммы — только со сверкой по файлу ───────────────────────────
def test_прайсовая_сошедшаяся_с_суммой_берётся_колонкой():
    """Прежде цена выводилась делением суммы (уверенность low) — теперь та же
    цифра из колонки цены."""
    шапка = ["Цена по прайсу, руб.", "Сумма, руб."]
    assert "price" not in q.колонки_цены(["Наименование", "Кол-во"] + шапка, v2=True)
    for it, (_, кол, цена) in zip(_v2(шапка, lambda к, ц: [ц, ц * к]), ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert q.ОГОВОРКА_ИЗ_СУММЫ not in _note(it)
        assert it["_цена"]["confidence"] == "med"
        assert it["qty"] == кол


def test_сумма_со_скидкой_цена_её_частное_а_не_прайсовая():
    """Сумма посчитана со скидкой: цена предложения — сумма ÷ количество, как
    до правки. Прайсовая ценой не берётся, количество не теряется."""
    шапка = ["Цена по прайсу, руб.", "Скидка, %", "Сумма, руб."]
    for it, (_, кол, цена) in zip(_v2(шапка, lambda к, ц: [ц * ПРАЙС, "20%", ц * к]),
                                  ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert q.ОГОВОРКА_ИЗ_СУММЫ in _note(it)
        assert it["qty"] == кол


def test_сумма_при_упомянутом_ндс_тоже_сверяется():
    """Сумма, при которой НДС лишь упомянут, — тоже сумма: прайсовая рядом с ней
    без сверки ценой не берётся, и сумма со скидкой даёт цену делением."""
    шапка = ["Цена по прайсу, руб.", "Скидка, %", "Сумма, руб. (НДС 20%)"]
    for it, (_, кол, цена) in zip(_v2(шапка, lambda к, ц: [ц * ПРАЙС, "20%", ц * к]),
                                  ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert q.ОГОВОРКА_ИЗ_СУММЫ in _note(it)
        assert it["qty"] == кол


def test_цена_по_прайсу_только_прайсовая():
    """Кандидат сверки — прайсовая цена, и только когда другой цены нет."""
    assert q.цена_по_прайсу(["Наименование", "Кол-во", "Цена по прайсу", "Сумма"],
                            {"total": 3}) == 2
    assert q.цена_по_прайсу(["Наименование", "Кол-во", "Цена, руб.", "Сумма"],
                            {"total": 3}) is None
    assert q.цена_по_прайсу(["Наименование", "Кол-во", "Цена по прайсу", "Цена, руб.",
                             "Сумма"], {"total": 4}) is None


def test_сверка_по_файлу_одна_несошедшаяся_строка_решает_за_всех():
    """Правило 13: колонка — цена для всего файла или ни для кого."""
    шапка = ["Цена по прайсу, руб.", "Сумма, руб."]
    rows = _таблица(шапка, lambda к, ц: [ц, ц * к])
    rows[-1][-1] = _деньги(12000.0 * 3 * 0.9)   # последняя строка — со скидкой
    items = indexer.items_from_rows(rows, словарь_v2=True, без_шапки=False)
    assert all(q.ОГОВОРКА_ИЗ_СУММЫ in _note(it) for it in items)


def test_ндс_суммы_переходит_к_сошедшейся_прайсовой():
    """Прайсовая молчит об НДС, сумма — «без НДС», и они сошлись: цена без НДС.
    Прежде это говорила оговорка цены, выведенной из суммы."""
    шапка = ["Цена по прайсу, руб.", "Сумма без НДС, руб."]
    for it in _v2(шапка, lambda к, ц: [ц, ц * к]):
        assert _note(it).startswith(q.ОГОВОРКА_БЕЗ_НДС_ОДНА)
        assert q.ОГОВОРКА_ИЗ_СУММЫ not in _note(it)


def test_из_двух_прайсовых_сверяется_без_ндс():
    шапка = ["Цена по прайсу с НДС, руб.", "Цена по прайсу без НДС, руб.",
             "Сумма без НДС, руб."]
    for it, (_, кол, цена) in zip(_v2(шапка, lambda к, ц: [ц * 1.2, ц, ц * к]), ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert q.ОГОВОРКА_ИЗ_СУММЫ not in _note(it)
        assert it["qty"] == кол


# ── скидка отдельной колонкой при прайсовой цене ─────────────────────────────
def test_прайсовая_при_скидке_с_оговоркой_и_низкой_уверенностью():
    """Ответ поставщика — прайсовая цена: она пишется. Но продаёт он дешевле, и
    сравнивать её с ценами других как равную нельзя."""
    шапка = ["Цена по прайсу, руб.", "Скидка, %"]
    for it, (_, кол, цена) in zip(_v2(шапка, lambda к, ц: [ц * ПРАЙС, "20%"]), ПОЗИЦИИ):
        assert it["_цена"]["price"] == round(цена * ПРАЙС, 2)
        assert q.ОГОВОРКА_ПРАЙС_СКИДКА in _note(it)
        assert it["_цена"]["confidence"] == "low"
        assert it["qty"] == кол


