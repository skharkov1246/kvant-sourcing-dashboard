"""Потоков распознавания не больше, чем ядер, сколько бы ни попросили.

ЗАЧЕМ. Прогон разбора и прогон распознавания берут число потоков из одного входа
`workers`. Для СКАЧИВАНИЯ двенадцать потоков разумны — там ждут сеть. Для tesseract
губительны: распознавание упирается в процессор.

ПОПРАВКА 23.09.2026. Прежняя редакция этого пояснения утверждала, что 69 %
таймаутов прогона 35790672035 вызваны двенадцатью потоками. Это неверно: шаг
прогона вызывал распознавание строкой `WORKERS=4 python library/ocr.py`, и вход
`workers` до него не доходил ни тогда, ни раньше. Повторный прогон 35833770032
подтвердил — те же таймауты при четырёх потоках. Предел остаётся страховкой от
второго вызывающего, который прибитой четвёрки не унаследует; починкой таймаутов
он не был и не является.

Предел стоит в модуле, а не в прогоне: про то, что распознавание процессорное,
знает модуль, а вызывающий — нет. Проверка закрепляет именно это: вызывающий может
попросить больше и не получит. Последняя проверка держит вторую половину урока:
шаг прогона не имеет права молча подменять число потоков.
"""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def модуль(потоков: str):
    for p in (ROOT, ROOT / "library", ROOT / "scripts"):
        if str(p) not in sys.path:
            sys.path.insert(0, str(p))
    старое = os.environ.get("WORKERS")
    os.environ["WORKERS"] = потоков
    try:
        spec = importlib.util.spec_from_file_location(
            f"kvant_ocr_{потоков}", ROOT / "library" / "ocr.py")
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        return m
    finally:
        if старое is None:
            os.environ.pop("WORKERS", None)
        else:
            os.environ["WORKERS"] = старое


def test_запрос_больше_числа_ядер_обрезается():
    ядер = os.cpu_count() or 2
    m = модуль("100")
    assert m.WORKERS == ядер, f"попросили 100, дали {m.WORKERS}, ядер {ядер}"
    assert m.ЗАПРОШЕНО == 100, "запрошенное значение потерялось — нечего печатать в журнал"


def test_запрос_меньше_числа_ядер_уважается():
    """Обрезка сверху, а не подмена: попросили один поток — значит один."""
    m = модуль("1")
    assert m.WORKERS == 1


def test_ноль_и_мусор_не_обнуляют_потоки():
    """Поток должен остаться хотя бы один, иначе прогон не сделает ничего молча."""
    m = модуль("0")
    assert m.WORKERS >= 1


def test_предел_в_модуле_а_не_в_прогоне():
    """Вызывающий не обязан знать, что распознавание процессорное.

    Если предел переехал бы в workflow, второй вызывающий его не унаследовал бы.
    """
    код = (ROOT / "library" / "ocr.py").read_text(encoding="utf-8")
    без_пояснений = "\n".join(s.split("#")[0] for s in код.splitlines())
    assert "os.cpu_count()" in без_пояснений
    assert "min(ЗАПРОШЕНО" in без_пояснений


def test_прогон_не_подменяет_число_потоков():
    """Шаг прогона обязан передавать вход, а не прибивать своё число.

    Прибитое `WORKERS=4` в шаге распознавания перекрывало вход `workers` и делало
    журнал прогона недостоверным: в окружении задания стояло 12, работало 4, а
    разобрать это можно было только чтением yml. На этом 23.09.2026 построен и
    опубликован ложный диагноз таймаутов. Обрезка — дело модуля, подмена — ничьё.
    """
    yml = (ROOT / ".github" / "workflows" / "library-index.yml").read_text(encoding="utf-8")
    без_пояснений = "\n".join(s.split("#")[0] for s in yml.splitlines())
    виноватые = [s.strip() for s in без_пояснений.splitlines()
                 if "WORKERS=" in s and "ocr.py" in s]
    assert not виноватые, f"шаг подменяет число потоков: {виноватые}"
