"""Потоков распознавания не больше, чем ядер, сколько бы ни попросили.

ЗАЧЕМ. Прогон разбора и прогон распознавания берут число потоков из одного входа
`workers`. Для СКАЧИВАНИЯ двенадцать потоков разумны — там ждут сеть. Для tesseract
губительны: распознавание упирается в процессор, а у раннера GitHub два ядра.

Холостой прогон 22.09.2026 показал цену: при WORKERS=12 из 132 файлов части 91
(69 %) вернули «таймаут распознавания». Не потому что файлы тяжёлые, а потому что
каждый процесс получил шестую часть ядра. Полезный выход — 253 позиции и 4 строки
цены на 132 файла, то есть прогон почти целиком ушёл в таймауты.

Предел стоит в модуле, а не в прогоне: про то, что распознавание процессорное,
знает модуль, а вызывающий — нет. Проверка закрепляет именно это: вызывающий может
попросить больше и не получит.
"""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def модуль(потоков: str):
    for p in (ROOT, ROOT / "library", ROOT / "scripts"):
        if str(p) not in sys.path:
            sys.path.insert(0, str(p))
    старое = os.environ.get("WORKERS")
    os.environ["WORKERS"] = потоков
    try:
        spec = importlib.util.spec_from_file_location(
            f"kvant_ocr_{потоков}", ROOT / "library" / "ocr.py")
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        return m
    finally:
        if старое is None:
            os.environ.pop("WORKERS", None)
        else:
            os.environ["WORKERS"] = старое


def test_запрос_больше_числа_ядер_обрезается():
    ядер = os.cpu_count() or 2
    m = модуль("100")
    assert m.WORKERS == ядер, f"попросили 100, дали {m.WORKERS}, ядер {ядер}"
    assert m.ЗАПРОШЕНО == 100, "запрошенное значение потерялось — нечего печатать в журнал"


def test_запрос_меньше_числа_ядер_уважается():
    """Обрезка сверху, а не подмена: попросили один поток — значит один."""
    m = модуль("1")
    assert m.WORKERS == 1


def test_ноль_и_мусор_не_обнуляют_потоки():
    """Поток должен остаться хотя бы один, иначе прогон не сделает ничего молча."""
    m = модуль("0")
    assert m.WORKERS >= 1


def test_предел_в_модуле_а_не_в_прогоне():
    """Вызывающий не обязан знать, что распознавание процессорное.

    Если предел переехал бы в workflow, второй вызывающий его не унаследовал бы —
    и наступил бы на те же 69 % таймаутов.
    """
    код = (ROOT / "library" / "ocr.py").read_text(encoding="utf-8")
    без_пояснений = "\n".join(s.split("#")[0] for s in код.splitlines())
    assert "os.cpu_count()" in без_пояснений
    assert "min(ЗАПРОШЕНО" in без_пояснений
