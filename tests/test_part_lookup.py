"""Поиск по артикулу обязан находить то, что записано иначе.

ЗАЧЕМ. Владелец, 22.09.2026: «Только код подшипника 6265ZZ. Давай, перебирай все».
Один артикул записывают десятком способов, и точное совпадение находит меньшую
часть. Прибор проверяется на двух свойствах, каждое из которых молча теряет данные.

1. НОРМАЛИЗАЦИЯ ДОЛЖНА СОВПАДАТЬ С БАЗОЙ. Ключ считает и Python (для печати и
   разбора), и SQL (lib_pn_key). Разойдутся — прибор напечатает один ключ, а
   искать будет по другому, и «ничего не найдено» станет неотличимо от «ничего
   нет». На расхождении этих двух реализаций замеры уже разъезжались.
2. ОСНОВА НЕ ДОЛЖНА ОТКУСЫВАТЬ ЗНАЧАЩЕЕ. «62652rs» ведущими цифрами даёт «62652»:
   двойка от уплотнения 2RS приклеивается к номеру, и поиск семьи вырождается в
   поиск несуществующего номера. А «NU 2216» и «2216» — РАЗНЫЕ подшипники, и
   отбросить буквенный префикс типа хуже, чем не расширить поиск.

Корпус придуман (CLAUDE.md, правило 18): обозначения подшипников — открытые
обозначения производителя, не данные заказчиков.
"""
from __future__ import annotations

import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def прибор():
    spec = importlib.util.spec_from_file_location(
        "kvant_part_lookup", ROOT / "scripts" / "part_lookup.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def test_разные_написания_дают_один_ключ():
    """Регистр, дефис, пробел и точка — не различия, а оформление."""
    м = прибор()
    формы = ["6265ZZ", "6265-ZZ", "6265 ZZ", "6265.zz", "6265zz", " 6265 - ZZ "]
    ключи = {м.ключ(ф) for ф in формы}
    assert ключи == {"6265zz"}, ключи


def test_ключ_совпадает_с_определением_в_базе():
    """Python и SQL считают ключ одинаково, иначе прибор ищет не то, что печатает.

    Определение читается ИЗ СХЕМЫ кодом, а не сверяется с копией в голове: копия
    устаревает молча. Проверяются те же три действия — нижний регистр, «ё» → «е»,
    отсев всего, кроме цифр и букв, обрезка до восьмидесяти знаков.
    """
    м = прибор()
    схема = (ROOT / "library" / "supabase" / "schema.sql").read_text()
    тело = схема[схема.index("create or replace function lib_pn_key"):][:900]
    код = "\n".join(ln for ln in тело.splitlines() if not ln.lstrip().startswith("--"))
    assert "lower(" in код and "'ё', 'е'" in код
    assert "[^0-9a-zа-я]" in код
    assert re.search(r"left\(.*,\s*80\)", код, re.S)
    # И поведение совпадает на придуманных строках, включая ловушку с «Ё».
    assert м.ключ("Шайба12Ё") == "шайба12е"
    assert м.ключ("6265-ZZ/C3") == "6265zzc3"
    assert м.ключ("x" * 100) == "x" * 80
    assert м.ключ("") == ""


def test_основа_снимает_уплотнение_и_зазор():
    """«62652rs» — это 6265, а не 62652: двойка принадлежит уплотнению."""
    м = прибор()
    for форма, ждём in (("6265ZZ", "6265"), ("6265-2RS", "6265"),
                        ("6265ZZ/C3", "6265"), ("6265 DDU", "6265"),
                        ("6205-2Z", "6205"), ("6265", "6265")):
        assert м.основа(м.ключ(форма)) == ждём, форма


def test_основа_сохраняет_буквенный_префикс_типа():
    """«NU 2216» и «2216» — разные подшипники, смешивать их нельзя.

    Первый роликовый с бортами на внутреннем кольце, второй шариковый
    сферический. Узкий поиск лучше, чем поиск не того изделия.
    """
    м = прибор()
    assert м.основа(м.ключ("NU 2216 ECP")) == "nu2216"
    assert м.основа(м.ключ("22315 EK")) == "22315"
    assert м.основа(м.ключ("7208 BECBP")) == "7208"


def test_запросы_ищут_и_в_колонке_артикула_и_в_тексте():
    """У предложений артикул сплошь и рядом сидит в тексте, а колонка пуста.

    Искать только по колонке значит не находить большую часть — это и показал
    замер: из 300 000 строк предложений артикул распознан у 31 %.
    """
    м = прибор()
    for имя in ("СПРОС", "ЦЕНЫ", "УСЛОВИЯ", "ПОДРОБНОСТИ"):
        sql = getattr(м, имя)
        assert "part_number" in sql, имя
        assert "item_name ~*" in sql, имя


def test_в_журнал_по_умолчанию_не_идут_коммерческие_сведения():
    """Репозиторий публичный, журнал прогона виден всем (правило 17).

    Названия компаний и цены построчно выводятся только по явному ПОДРОБНО=1.
    """
    м = прибор()
    исходник = (ROOT / "scripts" / "part_lookup.py").read_text()
    # Выборка с названием компании существует, но вызывается под условием.
    assert "rfq_company" in м.ПОДРОБНОСТИ
    строки = исходник.splitlines()
    вызов = [i for i, ln in enumerate(строки) if "cur.execute(ПОДРОБНОСТИ" in ln]
    assert len(вызов) == 1
    выше = "\n".join(строки[max(0, вызов[0] - 3):вызов[0]])
    assert "if ПОДРОБНО" in выше, "подробности обязаны быть под условием"
    # А сводные запросы названий компаний не отдают — только их число.
    assert "rfq_company" not in м.УСЛОВИЯ
    assert "count(distinct p.rfq_company)" in м.ЦЕНЫ


def test_недостающая_колонка_не_теряет_ответ():
    """Прибор для интерактивного вопроса не должен падать из-за колонки.

    Прогон 35761985937 прошёл весь поиск, напечатал результат и упал на последнем
    запросе с «column p.pay_terms does not exist»: колонки коммерческих условий
    добавляет миграция, а между мержем кода и её применением есть промежуток. Код
    возврата 1 при полностью полученном ответе — негодное поведение: недостающая
    колонка это повод сказать о ней, а не потерять ответ.
    """
    м = прибор()
    # Проверка наличия колонок существует и спрашивает именно те четыре.
    assert "information_schema.columns" in м.ЕСТЬ_УСЛОВИЯ
    for колонка in ("pay_terms", "make_days", "basis_src", "total"):
        assert колонка in м.ЕСТЬ_УСЛОВИЯ, колонка
    # И запрос условий стоит под этой проверкой, а не выполняется безусловно.
    исходник = (ROOT / "scripts" / "part_lookup.py").read_text()
    строки = исходник.splitlines()
    вызов = [i for i, ln in enumerate(строки) if "cur.execute(УСЛОВИЯ" in ln]
    assert len(вызов) == 1
    выше = "\n".join(строки[max(0, вызов[0] - 8):вызов[0]])
    assert "колонок < 4" in выше or "колонок >= 4" in выше


