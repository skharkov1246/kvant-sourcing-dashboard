def test_шапка_с_переносом_на_вторую_строку():
    """PDF переносит шапку: «Цена без» / «НДС, руб.». По первой строке об НДС не
    сказано ничего, и бралась левая цена — с НДС (корпус cascade_corpus, nds/pdf)."""
    rows = [["№", "Наименование", "Кол-во", "Цена с НДС,", "Цена без", "Сумма без", "Сумма",
             "Сумма с"],
            ["", "", "", "руб.", "НДС, руб.", "НДС", "НДС", "НДС"],
            ["1", "Насос ЦНС 38-176 с рамой", "2", "180 000,00", "150 000,00", "300 000,00",
             "60 000,00", "360 000,00"]]
    it = indexer.items_from_rows(rows, словарь_v2=True, без_шапки=False)[0]
    assert it["_цена"]["price"] == 150000.0
    assert it["_цена"]["total"] == 300000.0
    assert q.ОГОВОРКА_БЕЗ_НДС in it["_цена"]["note"]
    # Строка с цифрами продолжением шапки не считается.
    assert indexer.шапка_с_продолжением(rows[1:], 0) == rows[1]


