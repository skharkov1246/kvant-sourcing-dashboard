"""Правка чтения цены 26.09.2026: словарь v2 и таблица без шапки — за флагами.

ЗАЧЕМ. Замер базы 26.09.2026 (прогон 36265649414): из 5 690 разобранных файлов
КП карточек запросов цену дали 2 556. Первая редакция словаря не узнаёт голое
«Price», «Net price», «Preis», «单价»; таблица без найденной шапки (404 файла) цен
не даёт вовсе — цена ищется только в строке шапки.

Здесь закрытый список слов v2 (каждое — тестом), выбор цены без НДС при двух
колонках, отказ считать «Сумму НДС» суммой строки, «Стоимость» со сверкой
суммой, цена по тройке в таблице без шапки и то, что без флагов не меняется
НИЧЕГО. Корпуса придуманы (CLAUDE.md, правило 18).
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

from library import indexer
from library import quotes as q
from library import reparse

КОРЕНЬ = Path(__file__).resolve().parent.parent


# ── закрытый список: каждое слово v2 узнаётся ценой ──────────────────────────
@pytest.mark.parametrize("шапка_цены", [
    "Price", "Unit price", "Price (EUR)", "Цена, руб.", "Стоимость за ед.",
    "Net price", "Preis", "Einzelpreis", "单价", "Цена", "Price per piece",
    "Цена на условиях DAP, EUR", "Unit cost",
])
def test_слово_v2_узнаётся_ценой(шапка_цены):
    шапка = ["№", "Description", "Qty", шапка_цены, "Total"]
    цк = q.колонки_цены(шапка, v2=True)
    assert цк.get("price") == 3, (шапка_цены, цк)
    assert цк.get("total") == 4, (шапка_цены, цк)


@pytest.mark.parametrize("шапка_цены", ["Price", "Price (EUR)", "Net price", "Preis", "单价"])
def test_первая_редакция_этих_слов_не_знала(шапка_цены):
    """Иначе правка ничего не прибавляет и мерить нечего."""
    assert "price" not in q.колонки_цены(["Description", "Qty", шапка_цены], v2=False)


@pytest.mark.parametrize("шапка_суммы", [
    "Total price", "Gesamtpreis", "总价", "Amount", "Сумма, руб.", "Итого", "Extended price",
])
def test_сумма_с_словом_цены_остаётся_суммой(шапка_суммы):
    """«Total price» содержит «price», но это сумма строки: цена завысилась бы в qty раз."""
    цк = q.колонки_цены(["Description", "Qty", шапка_суммы], v2=True)
    assert "price" not in цк, цк
    assert цк.get("total") == 2, цк


