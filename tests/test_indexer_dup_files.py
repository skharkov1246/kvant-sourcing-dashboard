"""Один файл — одна строка: повтор в пакете роняет вставку целиком.

Прогон 22.09.2026 упал на полном объёме:

    psycopg2.errors.CardinalityViolation: ON CONFLICT DO UPDATE command cannot
    affect row a second time

lib_files конфликтует по file_id, а PostgreSQL не даёт обновить одну строку
дважды в ОДНОМ операторе. Вложение висит на карточке запроса, и одно и то же
вложение встречается у нескольких карточек и в нескольких полях сразу — на 46
файлах дубль не попался, на 7 523 попался и уронил прогон после 422 файлов.

Помимо падения повтор стоил бы второй закачки того же файла и удвоенных строк
цены: снятие прежних цен идёт по source_url, и второй разбор того же файла
вставил бы их заново.

Корпус придуман (CLAUDE.md, правило 18).
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def модуль():
    """Индексатор грузится по пути: он тянет тяжёлые зависимости при импорте."""
    spec = importlib.util.spec_from_file_location(
        "kvant_indexer", ROOT / "library" / "indexer.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def ссылка(fid, deal, field="ufCrm18_1700698211875"):
    return {"deal": deal, "field": field, "origin": "поле запроса",
            "fo": {"id": fid, "urlMachine": f"https://x/{fid}"},
            "company": "4242", "brands": None}


def test_один_файл_на_двух_карточках_даёт_одну_ссылку():
    без_повторов = модуль().без_повторов
    refs = [ссылка("101", "1"), ссылка("102", "1"),
            ссылка("101", "2"),                      # тот же файл, другая карточка
            ссылка("103", "3")]
    out, дублей = без_повторов(refs)
    assert [r["fo"]["id"] for r in out] == ["101", "102", "103"]
    assert дублей == 1
    # Оставлена ПЕРВАЯ ссылка: выбор обязан быть воспроизводимым.
    assert out[0]["deal"] == "1"


def test_один_файл_в_двух_полях_одной_карточки():
    без_повторов = модуль().без_повторов
    refs = [ссылка("201", "7", "ufCrm18_1700698211875"),
            ссылка("201", "7", "ufCrm18_1731179998")]
    out, дублей = без_повторов(refs)
    assert len(out) == 1 and дублей == 1


def test_ссылка_без_id_не_отсеивается():
    """Отсеять по отсутствующему ключу нельзя: молча потерять файл хуже дубля."""
    без_повторов = модуль().без_повторов
    refs = [{"deal": "1", "fo": {"urlMachine": "https://x/a"}},
            {"deal": "2", "fo": {"urlMachine": "https://x/b"}}]
    out, дублей = без_повторов(refs)
    assert len(out) == 2 and дублей == 0


def test_пустой_список_не_роняет():
    out, дублей = модуль().без_повторов([])
    assert out == [] and дублей == 0


def test_инвариант_пакета_записан_в_коде_вставки():
    """Отсев у источника — не гарантия: буфер наполняет не только этот путь.

    Требование «ключ в пакете уникален» принадлежит самой вставке, поэтому оно
    обязано стоять рядом с ней, а не только выше по течению.
    """
    код = (ROOT / "library" / "indexer.py").read_text(encoding="utf-8")
    место = код.index("insert into lib_files")
    окно = код[max(0, место - 600):место]
    assert "buf_files = list({r[0]: r for r in buf_files}.values())" in окно, (
        "перед вставкой в lib_files нет отсева повторов по ключу пакета")


def test_отсев_подключён_к_сбору_ссылок():
    """Функция без вызова не чинит ничего.

    Первые проверки этого файла зовут без_повторов() напрямую и проходят даже
    тогда, когда её вызов из collect_refs_rfq убран: тест, который зелен и на
    исправленном, и на сломанном коде, не проверяет ничего. Поэтому отдельно
    сверяется, что отсев стоит в самом сборе ссылок.
    """
    код = (ROOT / "library" / "indexer.py").read_text(encoding="utf-8")
    начало = код.index("def collect_refs_rfq(")
    конец = код.index("\ndef ", начало + 1)
    тело = код[начало:конец]
    assert "без_повторов(refs)" in тело, (
        "collect_refs_rfq не вызывает без_повторов: повторы дойдут до вставки")
