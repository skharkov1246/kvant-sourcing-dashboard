"""Набор перепроверки не должен противоречить сам себе.

Написано после трёх собственных ошибок за одну ночь 17–18.09.2026, каждую из
которых поймала проверка, а не внимательность: справка утверждала про поля
«Result, ТКП» то, что замер опроверг; измеритель покрытия не считал КП
поставщиков и печатал «сошлось 0»; вывод по LF16031 был построен на цене
ПОХОЖЕГО номера и указывал в противоположную сторону.

Здесь проверяется внутренняя связность того, что уходит владельцу: вердикт по
вилке обязан согласовываться с наличием цены, а «нечем проверить» не может
соседствовать с рекомендованной цифрой.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "gt/data/ship_reverify.json"
VERDICTS = {"ЗАНИЖЕНА", "ЗАВЫШЕНА", "ВЕРНА", "НЕ ПОДТВЕРЖДЕНА", "ДУБЛЬ",
            "НЕЧЕМ ПРОВЕРИТЬ"}
PRICED = {"ЗАНИЖЕНА", "ЗАВЫШЕНА", "ВЕРНА"}

sys.path.insert(0, str(ROOT / "gt/tools"))
from verdicts import UNKNOWN, vkey            # noqa: E402  единый классификатор


def rows() -> list[dict]:
    if not SRC.exists():
        pytest.skip("набора перепроверки нет")
    d = json.loads(SRC.read_text(encoding="utf-8"))
    return d["rows"] if isinstance(d, dict) else d


def verdict(r: dict) -> str:
    """Класс вердикта — ТОЛЬКО через общий классификатор.

    Свой поиск подстрокой здесь стоял до 18.09.2026 и делал два теста
    случайными: перебор шёл по МНОЖЕСТВУ, а строка «ВЕРНА (середина вилки
    завышена на 35 %)» содержит и «ВЕРНА», и «ЗАВЫШЕНА». Класс зависел от
    порядка обхода множества, то есть от PYTHONHASHSEED: на двух сидах из
    четырёх проверка падала на строке, которой никто не касался. Гейт при
    этом проходил по удаче.
    """
    v = vkey(r)
    return "" if v == UNKNOWN else v


def has_number(*vals) -> bool:
    """Есть ли в тексте хоть одно число, похожее на цену."""
    for v in vals:
        if re.search(r"\d[\d\s .,]*\d", str(v or "")):
            return True
    return False


def test_вердикт_из_закрытого_списка():
    bad = [r["pn"] for r in rows() if not verdict(r)]
    assert not bad, f"вердикт не опознан у строк: {bad}"


def test_у_каждой_строки_есть_чем_подтверждено():
    """Без этого поля строка — утверждение без основания."""
    bad = [r["pn"] for r in rows() if not (r.get("note") or "").strip()]
    assert not bad, f"нет поля «чем подтверждено»: {bad}"


def test_вердикт_с_ценой_опирается_на_источник():
    """ЗАНИЖЕНА, ЗАВЫШЕНА и ВЕРНА выносятся ТОЛЬКО по найденной цене.

    Иначе вердикт — догадка, а выглядит как замер.
    """
    bad = []
    for r in rows():
        if verdict(r) not in PRICED:
            continue
        if not has_number(r.get("price_low"), r.get("price_high"),
                          r.get("price_authorized"), r.get("recommended")):
            bad.append(r["pn"])
        elif not (r.get("price_source") or "").strip():
            bad.append(f'{r["pn"]} (нет price_source)')
    assert not bad, f"вердикт по цене без цены или без источника: {bad}"


def test_нечем_проверить_не_даёт_рекомендованной_цифры():
    """Самая опасная связка: «проверить нечем» рядом с конкретной ценой.

    Такая строка читается как подтверждённая, хотя подтверждения нет.
    Рекомендация при этом остаётся полезной, если она говорит, что закладывать
    нечего или чего не хватает, — поэтому запрещено именно ЧИСЛО.
    """
    # Цена — это число С ЕДИНИЦЕЙ: валюта или «за штуку». Просто «число в тексте»
    # ценой не является, и требовать оговорку у него нельзя. Оплачено четырьмя
    # ложными срабатываниями 18.09.2026: проверка считала ценой сами артикулы —
    # CT97200/01, 64/04012024/3, 525743000, 595872000, — то есть ровно те номера,
    # о которых строка и говорит «цены по ним нет».
    price = re.compile(
        r"\d[\d\s .,]*\s*(?:USD|EUR|GBP|RUB|доллар|евро|руб|фунт)"
        r"|\d[\d\s .,]*\s*за\s+штуку", re.I)
    bad = []
    for r in rows():
        if verdict(r) != "НЕЧЕМ ПРОВЕРИТЬ":
            continue
        rec = str(r.get("recommended") or "")
        # разрешаем числа, которые описывают НАШУ вилку или объём, а не
        # рекомендованный уровень: их вводят словами «наша вилка», «по строке»
        if price.search(rec) and not re.search(
                r"наша вилка|нечем|не опроверг|не подтвержд|по строке|закладывать нечего"
                r"|проверить нечего|для порядка величин", rec, re.I):
            bad.append(r["pn"])
    assert not bad, ("«нечем проверить» с конкретной рекомендованной ценой "
                     f"без оговорки: {bad}")


def test_скептики_списком_и_с_полем_holds():
    bad = []
    for r in rows():
        sk = r.get("skeptics")
        if sk is None or not isinstance(sk, list):
            bad.append(r["pn"])
            continue
        for s in sk:
            if not isinstance(s, dict) or "holds" not in s:
                bad.append(f'{r["pn"]} (скептик без holds)')
    assert not bad, f"поле проверки на опровержение испорчено: {bad}"


def test_артикулы_не_дублируются():
    """Дубликат удваивает строку в документе и в любой сумме по нему."""
    seen, dup = set(), []
    for r in rows():
        k = re.sub(r"[^A-Z0-9]", "", str(r.get("pn") or "").split("(")[0].upper())
        if k in seen:
            dup.append(r["pn"])
        seen.add(k)
    assert not dup, f"дубликаты артикулов: {dup}"

def test_строка_говорит_о_том_же_предмете_что_заявка():
    """Разбор обязан быть про ТОТ предмет, который назван в заявке.

    Оплачено ошибкой на VS-4-57 и VS-6-82: предмет строки был выведен из
    префикса артикула («VS» → бренд Vibrostop → виброизолятор), хотя в заявке
    прямо стоят изготовитель Victory Energy, модель Vision, наименование
    «Электрод розжига» и категория «зажигание и свечи». Строки «виброизолятор»
    в заявке нет ни одной, а вердикт «ЗАВЫШЕНА» с уровнем 30–60 USD/шт был
    вынесен именно по классу виброопор. Вердикт не о том предмете опаснее
    отсутствия вердикта.
    """
    src = ROOT / "gt/data/ship_lukoil.json"
    if not src.exists():
        pytest.skip("сводки заявки нет")
    ask = {re.sub(r"[^A-Z0-9]", "", str(r.get("pn") or "").upper()): r
           for r in json.loads(src.read_text(encoding="utf-8"))["rows"]}
    stop = {"для", "и", "в", "с", "на", "по", "от", "до", "сборе", "шт", "мм", "модель"}

    def words(text: str) -> set[str]:
        """Корни, а не словоформы.

        Сравнение целых слов спотыкалось на русских падежах: «расцепителя» в
        заявке против «расцепитель» в разборе — разные строки, и проверка
        ругалась на строку, где предмет опознан верно. Берём первые пять букв:
        падеж это снимает, а грубое расхождение остаётся видимым —
        «виброизолятор» и «электрод» не сходятся и по корню.
        """
        return {w[:5] for w in re.findall(r"[а-яёa-z0-9]+", (text or "").lower())
                if len(w) > 3 and w not in stop}

    bad = []
    for r in rows():
        key = re.sub(r"[^A-Z0-9]", "", str(r.get("pn") or "").split("(")[0].upper())
        row = ask.get(key)
        if row is None:          # номер записан с пояснением — сверять нечего
            continue
        want = words(row.get("name"))
        have = words(" ".join(str(r.get(k) or "") for k in
                              ("what_it_is", "note", "volume_head", "recommended")))
        if want and not (want & have):
            bad.append(f'{r["pn"]}: в заявке «{(row.get("name") or "")[:40]}», '
                       f"а в разборе это слово не встречается")
    assert not bad, f"разбор не о том предмете, что заявка: {bad}"


# Домены зон, откуда на самом деле приходят наши свидетели. Список расширяется по
# факту: 18.09.2026 к нему добавлены fr, it, ch, se, dk, be, ca, au, hk, sg, co.za,
# jp — французские дилеры фильтров HIFI дали по патрону Jenbacher ДВЕ независимые
# цены, и проверка отвергла их только потому, что зоны .fr в списке не было. Это
# ошибка списка, а не источника: белый список TLD не должен решать, чья страница
# считается названной.
DOMAIN = re.compile(
    r"[a-z0-9][a-z0-9-]*\.(com|net|org|ru|de|co\.uk|cz|pl|in|cn|eu|at|io|uk|store|parts"
    r"|nl|es|kz|tr|fr|it|ch|se|dk|be|ca|au|hk|sg|co\.za|jp)\b",
    re.I)
NO_LINK = "ССЫЛКА НЕ СОХРАНЕНА"


def test_вердикт_по_цене_называет_страницу():
    """У найденной цены должна быть названа страница, а не только проза.

    Оплачено разбором семи строк Allen-Bradley и Pepperl+Fuchs: шесть выводов из
    семи не устояли, и восстанавливать, какую страницу открывали, приходилось из
    другого набора. Три цифры оказались не с карточек, а возвращёнными из уже
    опровергнутых значений — при названной ссылке это было бы видно сразу.

    Где ссылка честно утеряна, в источнике стоит явная пометка: она хуже ссылки,
    но лучше умолчания — её видно в документе.
    """
    bad = []
    for r in rows():
        if verdict(r) not in PRICED:
            continue
        src = r.get("price_source") or ""
        if not DOMAIN.search(src) and NO_LINK not in src:
            bad.append(r["pn"])
    assert not bad, f"вердикт по цене без названной страницы и без пометки об утере: {bad}"


OWN_NUMBERS = ("qty", "lo", "hi", "expo", "band_lo", "band_hi", "exposure")


def test_строка_не_хранит_своих_количеств_и_вилок():
    """Количество, вилка и экспозиция живут в сводке заявки, и только там.

    Оплачено разбором трёх строк: они несли выдуманные числа — «экспозиция
    33 600 USD» при настоящих 4 410, «21 250» при 892, «56 250» при 788, — и
    вердикт «завышена» выносился против вилки, которой в данных нет. Пока
    источник этих чисел один, такое в документ попасть не может; поле в строке
    перепроверки снова откроет эту дверь.
    """
    bad = [f'{r["pn"]}.{f}' for r in rows() for f in OWN_NUMBERS if f in r]
    assert not bad, ("количество, вилка и экспозиция берутся из gt/data/ship_lukoil.json, "
                     f"а не из строки перепроверки: {bad}")


def test_вердикт_опознаётся_началом_текста_а_не_подстрокой():
    """Два документа об одних данных не должны расходиться в счёте.

    Оплачено расхождением 18.09.2026: справка печатала «нечем проверить 30»,
    а перепроверка — 21. Причин было две: у справки классов было четыре, и
    «не подтверждена» с «дублем» сваливались в «нечем проверить»; плюс вердикт
    искался подстрокой в любом месте прозы, а «ВЕРНА (… нижняя половина вилки
    не подтверждена ничем)» содержит оба слова, и ответ зависел от порядка
    перебора. Здесь закреплено правило: вердикт — это начало текста.
    """
    from verdicts import VERDICTS as CLOSED

    assert set(CLOSED) == VERDICTS, "закрытый список разошёлся с тем, что проверяет тест"
    bad = [r["pn"] for r in rows() if vkey(r) == UNKNOWN]
    assert not bad, f"вердикт не опознан по началу текста: {bad}"

    # проза с оговоркой не должна менять класс
    assert vkey("ВЕРНА (по верхней границе; нижняя половина вилки не подтверждена ничем)") == "ВЕРНА"
    assert vkey("НЕ ПОДТВЕРЖДЕНА, риск в сторону занижения") == "НЕ ПОДТВЕРЖДЕНА"
    assert vkey("НЕЧЕМ ПРОВЕРИТЬ (цены нет; наименование опознано)") == "НЕЧЕМ ПРОВЕРИТЬ"

    # и счёт по классам обязан совпадать с числом строк
    import collections
    by = collections.Counter(vkey(r) for r in rows())
    assert sum(by.values()) == len(rows())


def test_цена_в_строке_это_число_а_не_проза():
    """price_low и price_high — числа в долларах за штуку, либо null.

    Оплачено разбором 44 строк, где в этих полях лежала проза: «319,31 GBP за
    штуку (£1 277,25 за коробку из 4) — аналог ERS/Hatraco…», «805 EUR за к-кт
    из 4 шт», «356,32 USD за ведро 18,9 л». Проверка «есть ли в поле число»
    такую строку принимала, то есть вердикт по цене считался обоснованным, а
    сравнить цифру с вилкой было нельзя: единица другая, валюта другая, а
    иногда в одной строке стояли две цифры сразу.

    Проза сохраняется в price_note — там она и должна быть.
    """
    bad = []
    for r in rows():
        for f in ("price_low", "price_high"):
            v = r.get(f)
            if v is None:
                continue
            if not isinstance(v, (int, float)):
                bad.append(f'{r["pn"]}.{f} = {type(v).__name__} «{str(v)[:40]}»')
            elif isinstance(v, bool) or v <= 0:
                bad.append(f'{r["pn"]}.{f} = {v!r}')
    assert not bad, ("цена в строке перепроверки должна быть положительным числом в долларах "
                     f"за штуку или null; проза живёт в price_note: {bad}")


def test_пол_цены_не_выше_потолка():
    bad = [r["pn"] for r in rows()
           if isinstance(r.get("price_low"), (int, float))
           and isinstance(r.get("price_high"), (int, float))
           and r["price_low"] > r["price_high"]]
    assert not bad, f"найденный пол выше найденного потолка: {bad}"


def test_цена_внутри_вилки_не_даёт_вердикта_занижена_или_завышена():
    """Если найденная цена ЦЕЛИКОМ внутри вилки, вилка верна — и точка.

    Оплачено тремя строками. У двух из них вердикт стоял «ЗАНИЖЕНА» при цене
    внутри вилки: 4 101,36 против вилки 1 200–4 150 и 463,96–558,00 против
    280–560. Занижала не вилка, а её СЕРЕДИНА — а это другое утверждение, и в
    сводке «занижена» читается как «вилку надо поднимать». У третьей в числовом
    поле цены лежала ОТВЕРГНУТАЯ цифра (106 200 USD, ask одного перепродавца на
    половину объёма), и любой счёт по строке выносил «занижена в сорок раз» —
    ровно то, чего текст той же строки велел не делать.

    Правило: вердикт по вилке отвечает на вопрос «вилка верна или нет». Про
    середину есть оговорка в тексте вердикта.
    """
    src = ROOT / "gt/data/ship_lukoil.json"
    if not src.exists():
        pytest.skip("сводки заявки нет")
    band = {re.sub(r"[^A-Z0-9]", "", str(r.get("pn") or "").upper()): r
            for r in json.loads(src.read_text(encoding="utf-8"))["rows"]}
    bad = []
    for r in rows():
        k = re.sub(r"[^A-Z0-9]", "", str(r.get("pn") or "").split("(")[0].upper())
        b = band.get(k)
        if b is None or b.get("usd_lo") in (None, "") or b.get("usd_hi") in (None, ""):
            continue
        lo, hi = float(b["usd_lo"]), float(b["usd_hi"])
        plo, phi = r.get("price_low"), r.get("price_high")
        if not isinstance(plo, (int, float)) or not isinstance(phi, (int, float)):
            continue
        if plo < lo or phi > hi:          # вилку задевают — вердикт может быть любым
            continue
        v = verdict(r)
        if v in ("ЗАНИЖЕНА", "ЗАВЫШЕНА"):
            bad.append(f'{r["pn"]}: цена {plo}–{phi} внутри вилки {lo}–{hi}, а вердикт «{v}»')
    assert not bad, ("вердикт по вилке отвечает на «вилка верна или нет», а не на «верна ли её "
                     f"середина»: {bad}")
