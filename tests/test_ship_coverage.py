"""Лестница понимания накопительна, признаки — нет, и путать их нельзя.

Написано вместе с замером 18.09.2026. Первая же его редакция печатала
«признаки» как лестницу, и в ней «канал назван» (423 строки) выходило больше,
чем «цена найдена» (277): канал у нас записан и там, где цены нет вовсе. Такая
таблица читается как лестница, не будучи ею, и завышает готовность.

Здесь закреплено: каждая ступень лестницы не больше предыдущей; ступень
требует всех предыдущих; доли считаются от строк с оценкой, а строки без
оценки названы отдельным числом.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "gt/data/ship_coverage.json"
sys.path.insert(0, str(ROOT / "gt/tools"))
ORDER = ["опознана", "есть кому написать", "есть цена и адрес", "отгружаема"]


def doc() -> dict:
    if not SRC.exists():
        pytest.skip("замера нет")
    return json.loads(SRC.read_text(encoding="utf-8"))


def test_лестница_не_растёт_вверх():
    lad = doc()["ladder"]
    assert list(lad) == ORDER, "порядок ступеней в наборе не тот, что в правиле"
    for a, b in zip(ORDER, ORDER[1:]):
        assert lad[b]["rows"] <= lad[a]["rows"], (
            f"ступень «{b}» шире предыдущей «{a}» — значит она не требует её")
        assert lad[b]["usd"] <= lad[a]["usd"] + 1.0


def test_ни_одна_ступень_не_больше_всей_заявки():
    d = doc()
    for k, v in d["ladder"].items():
        assert v["rows"] <= d["rows_total"], f"{k}: строк больше, чем в заявке"
        assert v["usd"] <= d["usd_total"] + 1.0, f"{k}: денег больше, чем во всей оценке"


def test_строки_без_оценки_названы_отдельно():
    d = doc()
    assert d["rows_without_band"] > 0
    assert d["rows_without_band_identified"] <= d["rows_without_band"]
    assert "оценк" in (d.get("caveat") or "").lower(), (
        "набор обязан сказать, что доли считаются от строк с оценкой")


def test_признаки_и_лестница_названы_разными_вещами():
    t = (doc().get("why_steps") or "").lower()
    assert "накопительн" in t and "независим" in t, (
        "набор обязан различать накопительную лестницу и независимые признаки: иначе "
        "«канал» окажется больше «цены» и таблицу прочитают как лестницу")


def test_признак_не_меньше_соответствующей_ступени():
    """Ступень — это признак ПЛЮС все предыдущие, значит она не может быть шире."""
    d = doc()
    assert d["ladder"]["есть цена и адрес"]["rows"] <= d["steps"]["цена найдена"]["rows"]
    assert d["ladder"]["есть кому написать"]["rows"] <= d["steps"]["канал назван"]["rows"]
    assert d["ladder"]["отгружаема"]["rows"] <= d["steps"]["остаток числом"]["rows"]


def test_квотируемых_не_больше_чем_строк_без_цены():
    """Счёт квотируемых каналов — подмножество разрыва, и он намеренно занижен."""
    g = doc()["channel_without_price"]
    assert g["of_them_quote_only"] <= g["rows"]
    assert g["usd_quote_only"] <= g["usd"] + 1.0
    assert "не значит" in g["what_it_means"].lower(), (
        "набор обязан сказать, что отсутствие цены при наличии канала — не всегда наша "
        "недоработка")


def test_признак_квотируемого_канала_не_срабатывает_на_пустоте():
    import ship_coverage as sc

    assert not sc.quote_only({})
    assert not sc.quote_only({"channel": "склад, цена на карточке", "price_kind": "розница"})
    assert sc.quote_only({"channel": "продавец есть, но цена только по запросу"})
    assert sc.quote_only({"price_kind": "прайса нет, Request a Quote"})



def test_разрыв_лестницы_раскладывается_без_потерь_и_без_двойного_счёта():
    """Три части разрыва обязаны складываться ровно в целое.

    Разрыв между «есть кому написать» и «есть цена» — 195 строк на 5 047 437
    USD, и читать его одним числом нельзя: это три разные вещи с тремя разными
    действиями. Квотируемый канал закрывается письмом, ожидание заказчика —
    вопросом, остальное — поиском. Если части перестанут складываться в целое,
    значит признак начал срабатывать дважды либо строка выпала, и любое
    прикладное предложение по этому разделу станет неверным.
    """
    g = doc().get("channel_without_price") or {}
    if "of_them_open_to_search" not in g:
        pytest.skip("замер старой сборки")
    parts_rows = (g["of_them_quote_only"] + g["of_them_waiting_customer"]
                  + g["of_them_open_to_search"])
    assert parts_rows == g["rows"], (parts_rows, g["rows"])
    parts_usd = (g["usd_quote_only"] + g["usd_waiting_customer"] + g["usd_open_to_search"])
    assert abs(parts_usd - g["usd"]) < 1.0, (parts_usd, g["usd"])


def test_ждущие_ответа_заказчика_это_не_наша_недоработка():
    """Строка с вопросом заказчику не должна попадать в «нашу работу».

    Иначе самый дорогой такой случай — VS-4-57 на 138 000 USD, где обозначение
    оказалось моделью котла, а не номером детали, — уйдёт в разведку, и её труд
    спишется в ноль: продавец вернёт вопрос, а не цену.
    """
    import ship_coverage as sc

    asked = sc.asked_keys()
    assert asked, "список вопросов заказчику пуст — разложение работать не будет"
    g = doc().get("channel_without_price") or {}
    if "of_them_waiting_customer" not in g:
        pytest.skip("замер старой сборки")
    assert g["of_them_waiting_customer"] > 0


def test_квотируемый_канал_не_значит_что_цены_нет():
    """Продавец не публикует прейскурант — но мог ответить нам письмом.

    Замер 18.09.2026: из 65 строк с квотируемым каналом у 48 на 2 750 988 USD
    предложение поставщика УЖЕ лежит во вложении сделки — это 85 % денег
    разряда, включая две самые дорогие строки всей заявки. Без этого разбиения
    отчёт утверждал, что по ним «цену даёт письмо», и отправлял исполнителя
    писать туда, откуда ответ давно получен.
    """
    g = doc().get("channel_without_price") or {}
    if "of_them_quote_only_already_answered" not in g:
        pytest.skip("замер старой сборки")
    assert g["of_them_quote_only_already_answered"] <= g["of_them_quote_only"]
    assert g["usd_quote_only_already_answered"] <= g["usd_quote_only"] + 1.0
    assert g["of_them_quote_only_already_answered"] > 0, (
        "ни одна квотируемая строка не отмечена как уже отвеченная — "
        "проверь, что gt/data/ship_inside_quotes.json собран")


def test_ступень_цены_учитывает_письменные_предложения_контрагентов():
    """Цену, названную контрагентом письменно, ступень обязана видеть.

    До 18.09.2026 ступень «цена найдена» считалась только по набору
    перепроверки, то есть по разведке витрин. Письменная цифра контрагента по
    этой самой заявке — доказательство сильнее любой карточки, и её в счёте не
    было вовсе: 195 позиций с подтверждённой ценой в лестницу не попадали, и
    ступень «есть цена и адрес» показывала 43,7 % денег вместо 67,9 %.
    """
    import ship_coverage as sc
    offered = sc.priced_by_offer()
    if not offered:
        pytest.skip("набор gt/data/ship_inside_priced.json не собран")
    m = sc.measure()
    po = m["price_from_offer"]
    assert po["rows"] > 0, "предложения контрагентов не добавили ни одной строки"
    # Прибавка не может превышать саму ступень: иначе счёт двойной.
    assert po["rows"] <= m["steps"]["цена найдена"]["rows"]
    assert po["usd"] <= m["steps"]["цена найдена"]["usd"] + 1.0


def test_набор_подтверждённых_цен_не_содержит_чисел():
    """Он уходит в публичный репозиторий, а цены — данные контрагента."""
    src = ROOT / "gt/data/ship_inside_priced.json"
    if not src.exists():
        pytest.skip("набора нет")
    doc = json.loads(src.read_text(encoding="utf-8"))
    for part in doc["parts"]:
        assert not any(isinstance(v, (int, float)) and not isinstance(v, bool)
                       for v in part.values()), f"число в записи {part.get('pn')}"
        assert "price" not in part and "usd" not in part


