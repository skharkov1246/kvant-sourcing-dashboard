def test_первая_фраза_решает_как_у_вердикта():
    """Вывод стоит в начале, оговорки идут после — то же правило, что у вердиктов.

    Поле «Подтверждённого остатка по нашему номеру нет. IER FZCO — 2 комплекта
    новых горелок…» называет остаток отсутствующим, а «2 комплекта» — это чужое
    изделие в оговорке. Без этого правила такая строка числилась спорной, хотя
    разбор её уже закрыл: 197 спорных против 107 после правки.
    """
    import ship_coverage as sc
    assert sc.stock_state(
        "Числа остатка нет ни на одной карточке; против номера стоят «150pcs», "
        "но остатком это не является") == "нет"
    assert sc.stock_state(
        "Подтверждённого остатка по нашему номеру нет. Продавец — 2 комплекта, "
        "состояние «New», но номера на странице нет") == "нет"


def test_и_отказ_и_число_в_одном_поле_дают_спорно():
    """Ни считать отгружаемой, ни молча выбросить — это работа на один проход.

    Спор настоящий, когда число названо ПЕРВЫМ, а отказ идёт оговоркой по
    остальным продавцам: тогда поле само не решает.
    """
    import ship_coverage as sc
