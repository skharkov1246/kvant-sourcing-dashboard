from __future__ import annotations

import datetime as dt
import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.modules.setdefault("dotenv", types.SimpleNamespace(load_dotenv=lambda *a, **k: None))

from scripts import probe_realization as зонд  # noqa: E402

З = зонд.З
СЕГОДНЯ = dt.date(2026, 10, 19)


def test_открытые_заказы_контрольные_точки():
    заказы = [
        {"stageId": "D1:PAY", З["срок"]: "2026-10-01T03:00:00+03:00", З["отгр_план"]: "2026-09-20",
         З["оплачено_пост"]: "50"},
        {"stageId": "D1:SHIP", З["срок"]: "2026-10-30", З["дост_план"]: "2026-11-05"},
        {"stageId": "D1:NEW"},
        {"stageId": "D1:SUCCESS", З["срок"]: "2026-01-01"},
    ]
    c = зонд.разбор_открытых(заказы, {"D1:SUCCESS"}, СЕГОДНЯ, {"D1:SHIP"})
    assert c["открыто"] == 3 and c["есть срок"] == 2 and c["нет срока клиента"] == 1
    assert c["срок клиента прошёл, не доставлен"] == 1 and c["просрочка 8–30 дн."] == 1
    assert c["плановая отгрузка поставщика прошла без факта"] == 1
    assert c["до срока ≤ 14 дн., поставщик не отгрузил"] == 1
    assert c["план доставки позже срока клиента"] == 1
    assert c["после стадии оплаты, оплачено поставщику < 100 %"] == 1, "оплата < 100 % считается только после стадии оплаты"


def test_доставленные_сроки_и_закрывающие():
    заказы = [
        {"createdTime": "2026-06-01T10:00:00+03:00", З["срок"]: "2026-08-01", З["дост_факт"]: "2026-08-11",
         З["отгр_план"]: "2026-07-01", З["отгр_факт"]: "2026-07-05", З["склад_факт"]: "2026-07-25",
         З["схема"]: "11", З["упд_дата"]: "2026-08-12", З["пп_клиента"]: [{"id": 1}]},
        {"createdTime": "2026-07-01", З["срок"]: "2026-09-30", З["дост_факт"]: "2026-09-01", З["схема"]: "11",
         З["оплата_план"]: "2026-10-01"},
        {"createdTime": "2024-01-01", З["дост_факт"]: "2024-02-01"},
    ]
    д = зонд.разбор_доставленных(заказы, СЕГОДНЯ, dt.date(2025, 10, 19))
    assert д["n"] == 2 and д["со сроком"] == 2 and д["в срок"] == 1 and д["задержка"] == [10]
    assert д["сквозной"] == [71, 62] and д["заказ→отгрузка"] == [34] and д["отгрузка→склад"] == [20]
    assert д["склад→клиент"] == [17] and д["сдвиг отгрузки"] == [4]
    assert д["без УПД"] == 1 and д["без УПД > 14 дн."] == 1
    assert д["без п/п клиента > 30 дн."] == 1 and д["срок оплаты прошёл, п/п нет"] == 1
    assert д["по схеме"]["11"] == [2, 1]
    assert зонд.корзина(200) == "больше 180 дн." and зонд.медиана([]) == "—"
