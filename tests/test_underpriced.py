"""Разряды заниженных строк: складывать их нельзя, и это должно быть машинным.

ОПЛАЧЕНО В ТОТ ЖЕ ДЕНЬ. Первый подсчёт разрыва по заниженным строкам дал
2 782 352 USD, и половину суммы принесли две строки: брокерский запрос на
половину объёма и витрина одного перекупщика, у которого два домена и один
телефон. Правило владельца («цена действует на подтверждённый остаток; если
covers_qty не full — строка в сумму закупки не идёт») запрещает такой счёт, но
запрещало его только словами, а считал я кодом.

Здесь закрыт порядок разбора: качество цены важнее покрытия. Брокерский запрос
остаётся брокерским и при полном покрытии — иначе полное покрытие «отмывает»
негодную цену, и самая дорогая строка набора уходит в разряд, который идёт в
сумму.

Корпус придуман, а не взят из набора, как велят правила репозитория.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "gt/tools"))


def up():
    import ship_underpriced
    return ship_underpriced


def test_полное_покрытие_и_честная_цена_идут_в_сумму():
    t, why = up().tier({"covers_qty": "full"}, {"price_kind": "розница, карточка магазина"}, False)
    assert t == "в сумму идёт", why


def test_брокерский_запрос_не_идёт_в_сумму_даже_при_полном_покрытии():
    t, why = up().tier({"covers_qty": "full"}, {"price_kind": "Прайс брокера, за штуку («ea»)"}, False)
    assert t == "цена не закупочная"
    assert "брокер" in why


def test_единственный_оператор_под_двумя_доменами_не_идёт_в_сумму():
    t, why = up().tier({"covers_qty": "full"}, {"price_kind": "розница"}, True)
    assert t == "цена не закупочная"
    assert "оператор" in why


def test_неподтверждённое_покрытие_это_оговорка_а_не_негодная_цена():
    """Разряды различаются по смыслу: «не спросили объём» и «цена не та» —
    разные вещи, и валить их в одну кучу значит потерять управление."""
    u = up()
    for covers in ("partial", "unknown", "no", None, ""):
        t, why = u.tier({"covers_qty": covers}, {"price_kind": "дистрибьютор"}, False)
        assert t == "покрытие не подтверждено", (covers, t)
        assert "покрытие" in why


def test_вторичный_рынок_и_маркетплейс_тоже_не_закупочная_цена():
    u = up()
    for kind in ("цена вторичного рынка", "лот на eBay", "торговая площадка Made-in-China",
                 "ask брокера"):
        t, _ = u.tier({"covers_qty": "full"}, {"price_kind": kind}, False)
        assert t == "цена не закупочная", kind


def test_глагольная_форма_обвинением_не_является():
    """«Продавец перекупает» в описании канала не делает цену брокерской:
    обвинять можно только закрытым списком существительных (правило 7)."""
    u = up()
    assert not u.BROKER.search("цена изготовителя, дистрибьютор торговой марки")
    assert u.BROKER.search("прайс брокера")
