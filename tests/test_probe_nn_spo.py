def test_журнал_чатов_без_текста(capsys):
    чаты = {"1": [("2025-05-12", "Учебная гарантия по НН-901 Caterpillar")]}
    зонд.отчёт_чатов(чаты, КОРПУС, зонд.кварталы("2025-01", "2025-06"), "сделок 5")
