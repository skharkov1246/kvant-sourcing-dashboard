def test_ряд_по_кварталам():
    кв = зонд.кварталы("2024-10", "2026-09")
    р = зонд.ряд(КОРПУС, ЗАКАЗЫ, кв, "СПО (тема или контакт)")
    assert р["2025-Q2"]["заявки"] == 1 and р["2025-Q2"]["контракты"] == 1 and р["2025-Q2"]["живые заказы СП-172"] == 1
    assert р["2025-Q2"]["вид: приглашение к процедуре"] == 1
    assert р["2025-Q3"]["проиграно"] == 1 and р["2025-Q3"]["проиграно после ТКП"] == 1
    assert р["2025-Q3"]["живые заказы СП-172"] == 0                                       # проваленный заказ
    assert р["2026-Q2"]["заявки"] == 1 and р["2026-Q2"]["открыто сейчас"] == 1
    assert р["2024-Q4"]["карточки реализации"] == 1 and р["2024-Q4"]["заявки"] == 0
    п = зонд.ряд(КОРПУС, ЗАКАЗЫ, кв, "прочий Норникель")
    assert п["2026-Q3"]["контракты"] == 1 and п["2026-Q3"]["живые заказы СП-172"] == 1
    assert зонд.ряд(КОРПУС, ЗАКАЗЫ, кв, "СПО по контакту")["2025-Q3"]["заявки"] == 1


