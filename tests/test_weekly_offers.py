def test_дата_поступления_по_убыванию_точности():
    qd = wo.quote_date
    п = _предложение(wo.ИСТ_ПИСЬМА, даты={qd.КАРТОЧКА: date(2026, 9, 16)})
    wo.выбрать_дату(п, None)
    assert (п.дата_поступления, п.откуда_дата) == (date(2026, 9, 16), wo.ДАТА_CRM)
    п = _предложение(wo.ИСТ_КАРТОЧКИ, даты={qd.КАРТОЧКА: date(2026, 9, 14)})
    wo.выбрать_дату(п, None)
    assert п.откуда_дата == wo.ДАТА_КАРТОЧКИ and not п.дата_по_другому_файлу
    п = _предложение(wo.ИСТ_КАРТОЧКИ, даты={qd.ДОКУМЕНТ: date(2026, 9, 1), qd.ПИСЬМО: date(2026, 9, 3)})
    wo.выбрать_дату(п, date(2026, 8, 1))
    assert (п.дата_поступления, п.откуда_дата) == (date(2026, 9, 3), wo.ДАТА_ПИСЬМА)
    # Своих строк нет — дата карточки по другому её файлу, с пометкой.
    п = _предложение(wo.ИСТ_КАРТОЧКИ)
    wo.выбрать_дату(п, date(2026, 9, 14))
    assert (п.откуда_дата, п.дата_по_другому_файлу) == (wo.ДАТА_КАРТОЧКИ, True)
    # У письма и сделки дата чужой карточки не берётся.
    п = _предложение(wo.ИСТ_СДЕЛКИ)
    wo.выбрать_дату(п, date(2026, 9, 14))
    assert (п.дата_поступления, п.откуда_дата) == (None, wo.НЕТ_ДАТЫ)
    # Письмо с датированным КП: дата в CRM вытеснена датой документа
    # (quote_date пишет одну), но записана другим файлом того же письма — она и
    # берётся: день прихода письма один на все его файлы.
    п = _предложение(wo.ИСТ_ПИСЬМА, поле="письмо 1", даты={qd.ДОКУМЕНТ: date(2026, 9, 1)})
    wo.выбрать_дату(п, None, date(2026, 9, 17))
    assert (п.дата_поступления, п.откуда_дата, п.дата_по_другому_файлу) == \
        (date(2026, 9, 17), wo.ДАТА_CRM, True)
    # Без неё — дата документа, и это нижняя граница, а не день прихода.
    п = _предложение(wo.ИСТ_ПИСЬМА, поле="письмо 1", даты={qd.ДОКУМЕНТ: date(2026, 9, 1)})
    wo.выбрать_дату(п, None, None)
    assert п.откуда_дата == wo.ДАТА_КП and wo.ДАТА_КП not in wo.ТОЧНЫЕ_ДАТЫ


def test_приход_по_двум_границам():
    """Нижняя граница (КП, карточка) в окне — ещё не приход в окне: верхняя —
    первая обработка файла. Точная дата (письмо в CRM) — как есть."""
    утс = timezone.utc
    о = wo.Окно(date(2026, 9, 14), date(2026, 9, 20))

    def где(откуда, д, первые=None, обработан=None, распознан=None):
        п = _предложение(wo.ИСТ_КАРТОЧКИ)
        п.дата_поступления, п.откуда_дата = д, откуда
        п.первые_строки, п.обработан, п.распознан = первые, обработан, распознан
        return п.где_поступило(о)
    м = lambda д, ч=10: datetime(2026, 9, д, ч, tzinfo=утс)          # noqa: E731
    # Карточка создана в окне, КП без даты обработан после окна — не установлен.
    assert где(wo.ДАТА_КАРТОЧКИ, date(2026, 9, 15), первые=м(22), обработан=м(22)) == wo.НЕ_УСТАНОВЛЕН
    assert где(wo.ДАТА_КАРТОЧКИ, date(2026, 9, 15), первые=м(16), обработан=м(22)) == wo.В_ОКНЕ
    # КП составлен до окна, обработан в окне — пришёл мог и в окне.
    assert где(wo.ДАТА_КП, date(2026, 9, 1), первые=м(16), обработан=м(16)) == wo.НЕ_УСТАНОВЛЕН
    # КП составлен до окна и обработан до окна — пришёл до окна наверняка.
    assert где(wo.ДАТА_КП, date(2026, 9, 1), первые=datetime(2026, 9, 2, tzinfo=утс),
               обработан=м(16)) == wo.ДО_ОКНА
    assert где(wo.ДАТА_КП, date(2026, 9, 21), обработан=м(22, 0)) == wo.ПОСЛЕ_ОКНА
    # «Нижняя» позже первой обработки — не граница: судит только верхняя.
    assert где(wo.ДАТА_КП, date(2026, 9, 17), первые=datetime(2026, 8, 1, tzinfo=утс)) == wo.ДО_ОКНА
    # Верхняя граница — по календарю портала: 20.09 23:30 UTC — это уже 21.09 МСК.
    assert где(wo.ДАТА_КП, date(2026, 9, 15), обработан=datetime(2026, 9, 20, 23, 30, tzinfo=утс)) == \
        wo.НЕ_УСТАНОВЛЕН
    # Точная дата — как есть, обработка ей не указ.
    assert где(wo.ДАТА_CRM, date(2026, 9, 15), обработан=м(25)) == wo.В_ОКНЕ
    assert где(wo.ДАТА_CRM, date(2026, 9, 13), обработан=м(15)) == wo.ДО_ОКНА
    assert где(None, None) == wo.НЕ_ЗАПИСАНА


def test_дата_файла_у_источника_и_впервые_увидели():
    """Дата файла (file_dates_schema.sql): у источника — точная, если не позже
    первой обработки; «впервые увидели» — верхняя граница, судится одна, после
    прежних точных и перед нижними границами."""
    qd = wo.quote_date
    утс = timezone.utc
    о = wo.Окно(date(2026, 9, 14), date(2026, 9, 20))
    # Письмо: CREATED у источника — та же «письмо в CRM», и по календарю портала:
    # 19.09 21:30 UTC — это уже 20.09 МСК.
    п = _предложение(wo.ИСТ_ПИСЬМА, у_источника=datetime(2026, 9, 19, 21, 30, tzinfo=утс),
                     откуда_у_источника=wo.ИСТ_ДАТЫ_ПИСЬМО, даты={qd.ДОКУМЕНТ: date(2026, 9, 1)})
    wo.выбрать_дату(п, None)
    assert (п.дата_поступления, п.откуда_дата) == (date(2026, 9, 20), wo.ДАТА_CRM)
    assert п.где_поступило(о) == wo.В_ОКНЕ
    # Поле карточки: загрузка в Битрикс — точная, прежние даты ей не указ.
    п = _предложение(wo.ИСТ_КАРТОЧКИ, у_источника=datetime(2026, 9, 10, 8, tzinfo=утс),
                     откуда_у_источника=wo.ИСТ_ДАТЫ_ЗАКАЧКА, впервые=datetime(2026, 9, 16, tzinfo=утс),
                     даты={qd.КАРТОЧКА: date(2026, 9, 15)})
    wo.выбрать_дату(п, None)
    assert (п.откуда_дата, п.где_поступило(о)) == (wo.ДАТА_ЗАГРУЗКИ, wo.ДО_ОКНА)
    # Дата у источника позже первой обработки — не берётся; дальше «впервые».
    п = _предложение(wo.ИСТ_КАРТОЧКИ, у_источника=datetime(2026, 9, 18, tzinfo=утс),
                     откуда_у_источника=wo.ИСТ_ДАТЫ_ЗАКАЧКА, впервые=datetime(2026, 9, 12, tzinfo=утс))
    wo.выбрать_дату(п, None)
    assert п.у_источника_отвергнута and (п.откуда_дата, п.где_поступило(о)) == (wo.ДАТА_ВПЕРВЫЕ, wo.ДО_ОКНА)
    # «Впервые увидели» — перед нижними границами: КП до окна, увидели в окне — в окне.
    п = _предложение(wo.ИСТ_КАРТОЧКИ, впервые=datetime(2026, 9, 16, 10, tzinfo=утс),
                     даты={qd.ДОКУМЕНТ: date(2026, 9, 1)})
    wo.выбрать_дату(п, date(2026, 9, 2))
    assert (п.дата_поступления, п.откуда_дата, п.где_поступило(о)) == \
        (date(2026, 9, 16), wo.ДАТА_ВПЕРВЫЕ, wo.В_ОКНЕ)
    assert wo.ДАТА_ВПЕРВЫЕ not in wo.ТОЧНЫЕ_ДАТЫ and wo.ДАТА_ВПЕРВЫЕ in wo.САМОСТОЯТЕЛЬНЫЕ
    # …но после прежней точной: заголовок письма .eml точнее, чем день, когда увидели.
    п = _предложение(wo.ИСТ_КАРТОЧКИ, впервые=datetime(2026, 9, 16, tzinfo=утс),
                     даты={qd.ПИСЬМО: date(2026, 9, 12)})
    wo.выбрать_дату(п, None)
    assert (п.откуда_дата, п.где_поступило(о)) == (wo.ДАТА_ПИСЬМА, wo.ДО_ОКНА)
    # Верхняя граница нижних оценок учитывает «впервые»: она раньше любой обработки.
    п = _предложение(wo.ИСТ_КАРТОЧКИ, впервые=datetime(2026, 9, 13, tzinfo=утс))
    п.обработан = datetime(2026, 9, 16, tzinfo=утс)
    assert п.верхняя_граница() == date(2026, 9, 13)


