def test_причины_несравнимости_счётом():
    """«Сравнимых пар 0» без причины не говорит, что чинить: валюту, единицу или
    уверенность. Счёт по причине и по паре валют — только константы и коды."""
    def ряд(i, код, **п):
        return {"id": i, "код": код, "цена": 10, "валюта": "EUR", "единица": "pcs", "уверенность": "med", **п}

    наше = wo.НашеКП("f-наше", "1", None, None, 0,
                     цены=[{"код": "CD 5678", "цена": 900, "валюта": "RUB", "единица": "шт", "уверенность": "med"},
                           {"код": "QX-1001", "цена": 12, "валюта": "EUR", "единица": "шт", "уверенность": "med"}],
                     строки=[{"код": "ZC-2002"}])
    ряды = {"1": [ряд(1, "cd-5678"), ряд(2, "QX1001"), ряд(3, "QX-1001", единица=None),
                  ряд(4, "QX-1001", валюта="USD"), ряд(5, "ZC-2002")]}
    с = wo.сопоставить(ряды, {"1": [наше]})
    assert с["итог"]["пар_сравнимых"] == 1
    assert с["причины"] == {wo.СРАВНИМО: 1, "валюты разные": 2, "единица не названа": 1,
                            f"{wo.СТРОКА_БЕЗ_ПАРЫ}: {wo.НЕТ_ЦЕНЫ_КОДА}": 1}
    assert с["валюты_пар"] == {"EUR→RUB": 1, "USD→EUR": 1}
    строка = wo.строка_причин(с)
    assert "пары по причине: валюты разные 2 · единица не названа 1 · сравнимо 1" in строка
    assert "(валюты: EUR→RUB 1 · USD→EUR 1)" in строка
    assert f"совпали по коду без нашей цены (строк поставщика): {wo.НЕТ_ЦЕНЫ_КОДА} 1" in строка
    for кусок in ("CD", "QX", "ZC", "f-наше", "900"):
        assert кусок not in строка
    assert wo.строка_причин({"причины": {}}) is None
