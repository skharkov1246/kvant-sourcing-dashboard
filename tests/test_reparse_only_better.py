"""Файл, у которого цен стало МЕНЬШЕ, переразбором не переписывается.

Замер ослабленного правила шапки 23.09.2026 (прогон 35844131867, 832 файла):
строк цены 3 474 → 5 716, то есть плюс 64,5 %. При этом у 63 файлов цен стало
МЕНЬШЕ, а у 129 больше. В сумме прирост, а для каждого из тех 63 — потеря ответа
поставщика, которую сумма прячет.

Цена — ответ поставщика, другого источника у неё нет. Позиции восстановимы
повторным переразбором, цена — нет.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "library"))
КОД = (Path(__file__).resolve().parent.parent / "library/reparse.py").read_text(encoding="utf-8")


def код_без_пояснений() -> str:
    """Разбор исходника читает КОД, а не комментарии (CLAUDE.md, стиль работы)."""
    return re.sub(r"(?<!\w)#[^\n]*", "", КОД)


def test_запись_защищена_условием_хуже():
    код = код_без_пояснений()
    m = re.search(r"if APPLY and НЕ_ХУЖЕ and стало_хуже\(indexer\.SOURCE, б, с_ценой, старое, новое\):", код)
    assert m, "нет условия «стало хуже — не писать»"
    # Ветка записи должна быть ИНАЧЕ, а не рядом: иначе файл запишется и так.
    # Между ними — только другие ветки той же цепочки (elif), и каждая лишь
    # пропускает файл (правка цены и правки КП на тех же байтах).
    хвост = код[m.end():код.index("if n % 100 == 0", m.end())]
    запись = re.search(r"\n(\s*)elif APPLY:\s*\n\s*запиши\(", хвост)
    assert запись, "запись не в ветке elif — защита обходится"
    отступ = запись.group(1)
    ветки = re.findall(r"\n" + отступ + r"(\S+)", хвост[:запись.start() + 1])
    assert set(ветки) <= {"elif"}, f"между защитой и записью не только elif: {ветки}"


def test_предложения_судятся_по_цене():
    import reparse
    assert reparse.стало_хуже("rfq", 5, 4, 10, 20)       # цена ушла — хуже
    assert not reparse.стало_хуже("rfq", 5, 5, 20, 10)   # позиций меньше, цена та же — не хуже


def test_сделки_судятся_по_позициям():
    """Цены вложений сделки в базу не пишутся, «было» у них ноль всегда.

    Холостой переразбор сделок 24.09.2026: 2 813 файлов с потерей позиций и
    ноль «хуже по цене» — защита по цене пропустила бы все.
    """
    import reparse
    assert reparse.стало_хуже("deals", 0, 0, 30, 12)
    assert reparse.стало_хуже("deals", 0, 7, 30, 29)      # цены нашлись, но спрос потерян
    assert not reparse.стало_хуже("deals", 0, 0, 30, 30)
    assert not reparse.стало_хуже("deals", 0, 0, 30, 45)


def test_защита_включена_по_умолчанию():
    код = код_без_пояснений()
    m = re.search(r'НЕ_ХУЖЕ = os\.environ\.get\("APPLY_ONLY_BETTER", "(\d)"\)', код)
    assert m and m.group(1) == "1", "защита выключена по умолчанию"
    assert 'not in ("0", "false")' in m.string[m.end():m.end() + 40], \
        "снимается не только явным нулём"


def test_пропущенные_файлы_считаются_и_печатаются():
    """Молча пропущенный файл — невидимая потеря, а она хуже видимой."""
    код = код_без_пояснений()
    assert "пропущено_хуже += 1" in код, "пропуск не считается"
    assert re.search(r'print\(f?"?\s*пропущено как', код) or "пропущено как" in код, \
        "число пропущенных не печатается"
