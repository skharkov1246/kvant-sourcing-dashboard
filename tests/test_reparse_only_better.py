"""Файл, у которого цен стало МЕНЬШЕ, переразбором не переписывается.

Замер ослабленного правила шапки 23.09.2026 (прогон 35844131867, 832 файла):
строк цены 3 474 → 5 716, то есть плюс 64,5 %. При этом у 63 файлов цен стало
МЕНЬШЕ, а у 129 больше. В сумме прирост, а для каждого из тех 63 — потеря ответа
поставщика, которую сумма прячет.

Цена — ответ поставщика, другого источника у неё нет. Позиции восстановимы
повторным переразбором, цена — нет.
"""
from __future__ import annotations

import re
from pathlib import Path

КОД = (Path(__file__).resolve().parent.parent / "library/reparse.py").read_text(encoding="utf-8")


def код_без_пояснений() -> str:
    """Разбор исходника читает КОД, а не комментарии (CLAUDE.md, стиль работы)."""
    return re.sub(r"(?<!\w)#[^\n]*", "", КОД)


def test_запись_защищена_условием_по_цене():
    код = код_без_пояснений()
    m = re.search(r"if APPLY and НЕ_ХУЖЕ and с_ценой < б:", код)
    assert m, "нет условия «цен стало меньше — не писать»"
    # Ветка записи должна быть ИНАЧЕ, а не рядом: иначе файл запишется и так.
    хвост = код[m.end():m.end() + 400]
    assert re.search(r"elif APPLY:\s*\n\s*запиши\(", хвост), \
        "запись не в ветке elif — защита обходится"


def test_защита_включена_по_умолчанию():
    код = код_без_пояснений()
    m = re.search(r'НЕ_ХУЖЕ = os\.environ\.get\("APPLY_ONLY_BETTER", "(\d)"\)', код)
    assert m and m.group(1) == "1", "защита выключена по умолчанию"
    assert 'not in ("0", "false")' in m.string[m.end():m.end() + 40], \
        "снимается не только явным нулём"


def test_пропущенные_файлы_считаются_и_печатаются():
    """Молча пропущенный файл — невидимая потеря, а она хуже видимой."""
    код = код_без_пояснений()
    assert "пропущено_хуже += 1" in код, "пропуск не считается"
    assert re.search(r'print\(f?"?\s*пропущено как', код) or "пропущено как" in код, \
        "число пропущенных не печатается"
