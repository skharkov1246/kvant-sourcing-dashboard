def _обе_записи(rec: dict):
    """Обе записи lib_files — вставка разбора и UPDATE переразбора — как их
    строит код: (имя, запрос, значения по колонкам). Поведение, а не написание."""
    from library import indexer
    import library.reparse as r
    колонки = indexer.КОЛОНКИ_ВСТАВКИ
    запрос, _ = indexer.вставка_файлов(колонки)
    yield "вставка разбора", запрос, dict(zip(колонки, indexer.кортеж_файла(rec, колонки)))
    колонки = r.КОЛОНКИ_ЗАПИСИ
    yield ("UPDATE переразбора", r.правка_файла(колонки),
           dict(zip(колонки, r.значения_правки(rec, колонки))))


def _запись(**значения) -> dict:
    rec = {к: None for к in ("kind", "size_bytes", "reason", "segment_id", "sha256",
                             "parse_path", "header_found", "doc_class", "class_rule",
                             "text_lines", "item_lines")}
    rec.update(file_id="5", deal_id="11", origin="поле сделки", field="ufCrm_1633502831",
               status="разобран", chars=10, rows_found=0, **значения)
    return rec


def test_подвид_доезжает_до_базы_обеими_записями():
    """Правило 14: колонка, добавленная в одну запись, роняет вторую."""
    for имя, запрос, значения in _обе_записи(_запись(subkind="csv")):
        assert re.search(r"(?<!\w)subkind(?!\w)", запрос), f"{имя}: подвид не пишется"
        assert значения["subkind"] == "csv", f"{имя}: подвид без значения"


def test_замер_переживает_отсутствие_новой_колонки():
    """Схема в файле уходит вперёд базы на всё время между правкой и миграцией.

    23.09.2026 замер — инструмент ЧТЕНИЯ — упал на «column subkind does not
    exist», потому что миграцию нельзя применить: база в режиме только чтения.
    Сломанный замер хуже пропущенного раздела: он закрывает единственный
    оставшийся способ смотреть на данные.
    """
    assert "ЕСТЬ_КОЛОНКИ" in КОД, "замер не спрашивает у базы, какие колонки есть"
    q = запрос("ЕСТЬ_КОЛОНКИ")
    assert "information_schema.columns" in q
    # Разрез по подвиду обязан быть под условием наличия колонки.
    место = КОД.index("ПОТЕРИ_ПО_ПОДВИДУ)")
    рядом = КОД[место - 400:место]
    assert 'if "subkind" not in колонки' in рядом or '"subkind" in колонки' in рядом, \
        "запрос по подвиду идёт без проверки наличия колонки"


def test_папки_документов_печатаются_рядом_со_стороной_поля():
    """Расхождение «поле: поставщик, содержимое: наше ТКП» — то, ради чего
    классификатор смотрит в содержимое. Без стороны рядом его не увидеть."""
    q = запрос("ПО_ПАПКАМ")
    assert "doc_kind" in q and "side" in q
    assert "coalesce(doc_kind, '(ещё не разложен)')" in q
    место = КОД.index("ПО_ПАПКАМ)")
    assert '{"doc_kind", "side"} <= колонки' in КОД[место - 300:место], \
        "запрос по папкам без проверки наличия колонки — замер упадёт до миграции"


def test_папка_доезжает_до_базы_обеими_записями():
    rec = _запись(doc_kind="запрос заказчика нам", doc_kind_conf=1.0,
                  doc_kind_why="поле: код поля (сделка)")
    for имя, запрос, значения in _обе_записи(rec):
        for колонка in ("doc_kind", "doc_kind_conf", "doc_kind_why"):
            assert re.search(rf"(?<!\w){колонка}(?!\w)", запрос), f"{имя}: {колонка} не пишется"
            assert значения[колонка] == rec[колонка], f"{имя}: {колонка} без значения"


def test_читатели_каскада_печатаются_под_проверкой_колонки():
    """Путь чтения показывает, у какого читателя собрались потери, — но колонку
    добавляет миграция, и до неё замер не имеет права падать."""
    q = запрос("ПО_ЧИТАТЕЛЯМ")
    assert "split_part(read_chain" in q and "rows_found" in q
    # Без параметров запрос уходит как есть: удвоенный «%%» остался бы в тексте.
    assert "%%" not in q
    место = КОД.index("ПО_ЧИТАТЕЛЯМ)")
    assert '"read_chain" in колонки' in КОД[место - 300:место], \
        "запрос по читателям без проверки наличия колонки"
