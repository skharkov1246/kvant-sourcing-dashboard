"""Ведомость потерь по виду файла: цель владельца — читать 99,9 % файлов.

Каждый непрочитанный файл это потерянные деньги, поэтому отказ считается по
самому строгому признаку: файл не дал НИ ОДНОЙ позиции. Файл с позициями без
цены недочитан, но не потерян.

Проверка читает запросы как текст: живой базы у гейта нет. Разбор исходника
читает КОД, а не комментарии (CLAUDE.md, стиль работы).
"""
from __future__ import annotations

import re
from pathlib import Path

ПУТЬ = Path(__file__).resolve().parent.parent / "scripts/quote_parse_funnel.py"
КОД = re.sub(r"(?<!\w)#[^\n]*", "", ПУТЬ.read_text(encoding="utf-8"))


def запрос(имя: str) -> str:
    m = re.search(имя + r' = """(.*?)"""', КОД, re.S)
    assert m, f"нет запроса {имя}"
    return m.group(1)


def test_потери_считаются_по_всей_базе_а_не_по_предложениям():
    """В сделках файлов втрое больше, и вид у них другой.

    Если считать цель по одним предложениям, 24 306 файлов сделок в знаменатель
    не попадут, и «99,9 %» будет посчитано не от того числа.
    """
    q = запрос("ПОТЕРИ_ПО_ВИДУ")
    assert "from lib_files" in q
    assert "origin" not in q, "ведомость потерь ограничена происхождением файла"


def test_отказ_это_ноль_позиций_а_не_перечень_статусов():
    """Список статусов устареет с первым новым статусом, а ноль позиций — нет."""
    q = запрос("ПОТЕРИ_ПО_ВИДУ")
    assert re.search(r"filter \(where coalesce\(rows_found, 0\) = 0\)", q), \
        "«без позиций» считается не по нулю позиций"


def test_вид_не_определён_идёт_отдельной_строкой():
    """У нескачанного файла вида нет: sniff до байтов не дошёл.

    Без coalesce такие файлы собираются в строку NULL и легко теряются глазом, а
    это как раз самый крупный разряд потерь.
    """
    q = запрос("ПОТЕРИ_ПО_ВИДУ")
    assert "coalesce(kind, '(вид не определён)')" in q


def test_причина_отказа_печатается_и_это_тип_исключения_а_не_данные():
    """Правило 17: журнал публичный. У «формат не читаем» reason — имя класса."""
    q = запрос("ПРИЧИНЫ_ОТКАЗА")
    assert "reason" in q and "count(*)" in q
    assert "item_name" not in q and "source_file" not in q, "в отчёт попали данные строк"
    assert "limit" in q.lower(), "без предела частотный список может быть огромным"


def test_замер_первым_делом_говорит_пишется_ли_база():
    """Если база не пишется, все прочие цифры объясняются этим.

    23.09.2026 запись переразбора упала на «cannot execute INSERT in a read-only
    transaction» — 11 частей из 50, после того как 39 отработали. Причину пришлось
    выяснять по журналу упавшего задания. Замер обязан говорить это сам.
    """
    q = запрос("СОСТОЯНИЕ_БАЗЫ")
    assert "transaction_read_only" in q, "нет проверки режима только чтения"
    assert "pg_is_in_recovery" in q, "реплику от кончившегося диска не отличить"
    assert "pg_database_size" in q, "нет размера базы — не видно, в диске ли дело"
    # И печататься это должно РАНЬШЕ прочих разделов.
    assert КОД.index("СОСТОЯНИЕ_БАЗЫ)") < КОД.index("ПОТЕРИ_ПО_ВИДУ)"), \
        "состояние базы печатается после ведомости потерь"


def test_размеры_таблиц_считают_данные_и_индексы_раздельно():
    """«База не пишется» без «вот что занимает место» решения не даёт.

    У lib_demand столбец fts объявлен generated + GIN, и индекс там бывает крупнее
    данных: без раздельного счёта владелец не увидит, чистить строки или
    перестраивать индекс.
    """
    q = запрос("РАЗМЕРЫ_ТАБЛИЦ")
    assert "pg_total_relation_size" in q and "pg_relation_size" in q, \
        "данные и индексы не разделены"
    assert "n_live_tup" in q, "нет числа строк — не с чем сопоставить размер"
    assert "limit" in q.lower()


def test_индексы_печатаются_с_числом_обращений():
    """Крупный индекс, которым ни разу не пользовались, — первый кандидат на снятие.

    Без числа обращений список индексов не решение, а перечень: по размеру одному
    нельзя отличить рабочий полнотекстовый индекс от забытого дубля.
    """
    q = запрос("РАЗМЕРЫ_ИНДЕКСОВ")
    assert "idx_scan" in q, "нет числа обращений"
    assert "indisunique" in q, "уникальный индекс снимать нельзя, а его не видно"
    assert "pg_relation_size" in q and "limit" in q.lower()


def test_потери_разложены_и_по_точному_формату():
    """«Прочее» — это csv, txt, rtf, html, xml и мусор разом: 410 файлов.

    По крупному виду не видно, какая стратегия чтения окупилась, а какую чинить.
    """
    q = запрос("ПОТЕРИ_ПО_ПОДВИДУ")
    assert "subkind" in q, "нет разреза по точному формату"
    assert "coalesce(subkind, '(ещё не перечитан)')" in q, \
        "старые записи без подвида растворятся в прочих"
    assert "filter (where coalesce(rows_found, 0) = 0)" in q


def test_подвид_доезжает_до_базы_обеими_записями():
    """Правило 14: колонка, добавленная в одну запись, роняет вторую."""
    for путь, начало, конец in (
        ("library/indexer.py", "insert into lib_files", "processed_at = now()"),
        ("library/reparse.py", "update lib_files set", "where file_id = %s"),
    ):
        часть = запрос_из(путь, начало, конец)
        assert "subkind" in часть, f"{путь}: подвид не пишется"


def запрос_из(путь: str, начало: str, конец: str) -> str:
    текст = re.sub(r"(?<!\w)#[^\n]*", "",
                   (ПУТЬ.parent.parent / путь).read_text(encoding="utf-8"))
    i = текст.index(начало)
    return текст[i:текст.index(конец, i) + len(конец)]
