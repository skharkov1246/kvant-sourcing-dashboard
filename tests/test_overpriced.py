"""Завышенная цена — риск сделки, а не убыток, и порог обвинения назван числом.

Замер-зеркало к заниженным строкам. Написан потому, что односторонний счёт
выглядит как подбор: если считать только там, где мы дешевле рынка, вывод «нас
надо перецени́ть вверх» получается сам собой. Проверка наоборот обязательна, и
она обязана иметь ЯВНЫЙ порог: наценка на логистику и растаможку нормальна и
измеряется разами, поэтому «дороже найденной» само по себе ничего не значит.

Корпус придуман, а не взят из набора, как велят правила репозитория.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "gt/tools"))


def op():
    import ship_overpriced
    return ship_overpriced


def test_порог_назван_числом_и_лежит_в_наборе():
    o = op()
    assert o.TIMES >= 2, "порог ниже двух превратил бы обычную наценку в обвинение"


def test_разряды_те_же_что_у_заниженных():
    """Одна цена одного брокера не рынок — ни в ту сторону, ни в другую."""
    o = op()
    t, _ = o.tier({"covers_qty": "full"}, {"price_kind": "прайс брокера"}, False)
    assert t == "цена не закупочная"
    t2, _ = o.tier({"covers_qty": "full"}, {"price_kind": "дистрибьютор"}, False)
    assert t2 == "в сумму идёт"


def test_итог_набора_не_складывает_разряды():
    """Сумма по разрядам обязана сходиться с итогом, иначе одно из чисел лишнее."""
    o = op()
    doc = o.build()
    by_tier = sum(v["our_exposure_usd"] for v in doc["tiers"].values())
    assert abs(by_tier - doc["our_exposure_usd"]) < 1.0, (by_tier, doc["our_exposure_usd"])
    assert sum(v["rows"] for v in doc["tiers"].values()) == doc["rows_total"]


def test_отсев_печатается_а_не_молчит():
    """Строка, не дошедшая до порога, обязана быть посчитанной: иначе набор
    выглядит так, будто завышенных почти нет, а их просто не показали."""
    o = op()
    doc = o.build()
    assert "превышение меньше порога" in doc["skipped"]
    assert doc["skipped"]["превышение меньше порога"] >= 0
