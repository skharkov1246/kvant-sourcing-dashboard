def test_схема_платежа_с_разбивкой():
    """«30/70» и «50/50» — самое частое условие, и доля аванса решает деньги."""
    о = t.оплата_из("Условия оплаты: 30/70")
    assert о == {"terms": "30/70", "advance_pct": 30}
    assert t.оплата_из("Payment terms: 50/50, LC at sight") == {
        "terms": "50/50 LC", "advance_pct": 50}
    assert t.оплата_из("Terms: DDP Moscow, payment 20/80")["advance_pct"] == 20


def test_дробь_не_из_платежа_схемой_не_считается():
    """Сумма долей обязана быть сотней: иначе это размер, дата или дробь текста."""
    assert t.оплата_из("Манжета 45/65, цена 1 250,00") is None
    assert t.оплата_из("Чертёж 12/34 от 05.09.2026") is None
    # А 40/60 — законная схема.
    assert t.оплата_из("оплата 40/60")["advance_pct"] == 40


def test_полная_предоплата_и_отсрочка():
    assert t.оплата_из("Оплата 100% предоплата") == {
        "terms": "предоплата 100%", "advance_pct": 100}
    assert t.оплата_из("Payment: 100% in advance by T/T") == {
        "terms": "предоплата 100% T/T", "advance_pct": 100}
    assert t.оплата_из("Условия оплаты: отсрочка 30 дней после поставки") == {
        "terms": "отсрочка 30 дн", "advance_pct": 0}
    assert t.оплата_из("Payment: net 60") == {
        "terms": "отсрочка 60 дн", "advance_pct": 0}


def test_доля_аванса_не_выдумывается():
    """Предоплата есть, доля не названа — пишем факт, долю оставляем пустой."""
    о = t.оплата_из("Оплата: предоплата")
    assert о["terms"] == "предоплата"
    assert о["advance_pct"] is None


def test_инструмент_платежа_записан_однозначно():
    """«CAD» в коммерческом поле прочтут канадским доллáром, а не платежом.

    «30/70 CAD» выглядит ценой в валюте. Однозначность важнее краткости: поле
    уходит людям, принимающим по нему решение о деньгах.
    """
    о = t.оплата_из("Оплата: 30/70 — 30% предоплата, 70% против документов")
    assert о == {"terms": "30/70 против документов", "advance_pct": 30}
    assert "CAD" not in о["terms"]
    assert t.оплата_из("Оплата по аккредитиву (LC)")["terms"] == "LC"
    assert t.оплата_из("Оплата банковским переводом")["terms"] == "T/T"


def test_валюта_не_становится_условием_платежа():
    """«CAD» без денежных слов рядом — валюта, а не Cash Against Documents."""
    assert t.оплата_из("Стоимость доставки CAD 500") is None
    assert t.оплата_из("Цена 1 250,00 руб") is None
    assert t.оплата_из("") is None


