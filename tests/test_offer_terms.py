# СРОКИ

СРОКИ = [
    # (текст, срок производства, срок поставки)
    ("Срок изготовления 8 недель, поставка со склада в Москве", 56, 0),
    ("Срок поставки 6 недель", None, 42),
    ("Production time 12 weeks, delivery 2 weeks after production", 84, 14),
    ("Lead time: 45 days", None, 45),
    ("Срок изготовления 90 дней", 90, None),
    ("Срок 4-6 недель", None, 42),
    ("Поставка со склада", None, 0),
]


def test_срок_производства_и_срок_поставки_разные_поля():
    """Первое говорит, когда деталь появится, второе — когда доедет."""
    for текст, make, lead in СРОКИ:
        r = t.сроки_из(текст)
        assert r["make_days"] == make, текст
        assert r["lead_days"] == lead, текст


def test_срок_изготовления_не_попадает_в_срок_поставки():
    """Общее слово «срок» встречается раньше любого слова о поставке.

    В первой версии 56 дней изготовления записывались разом и сроком поставки.
    Якорь обязан переспросить хвост: «Срок изготовления» — это производство, даже
    если поймано словом «срок».
    """
    r = t.сроки_из("Срок изготовления 8 недель")
    assert r == {"make_days": 56, "lead_days": None}


def test_чужое_число_из_хвоста_не_становится_сроком():
    """«2-3 недели с момента 100% оплаты» — это 21 день, а не 700.

    Правило берёт МАКСИМУМ чисел, и это нужно для «4–6 недель»: обещанный
    минимум продавца — не срок, а надежда. Но на длинном хвосте максимумом
    оказывается чужое число, поэтому окно кончается на слове единицы.
    """
    assert t.сроки_из("Срок поставки: 2-3 недели с момента 100% оплаты") == {
        "make_days": None, "lead_days": 21}
    # И числа дальше слова единицы в срок не идут.
    assert t.сроки_из("Срок поставки 6 недель. Цена 1 250,00 за штуку.")[
        "lead_days"] == 42


def test_голое_число_в_тексте_сроком_не_является():
    """«Terms of delivery: DAP Moscow. Payment terms: 30/70» — не 70 дней поставки.

    Две ошибки разом, обе поймал сквозной тест цепочки:
      · «Terms of delivery» — это БАЗИС. Якорь «delivery» там есть, а срока нет,
        и правило брало первое число из следующей строки;
      · quotes.срок_из считает голое число днями. Для ЯЧЕЙКИ колонки «Срок, дн»
        это верно — единицу называет заголовок, — но в свободном тексте голое
        «70» днями не является.
    """
    r = t.сроки_из("Terms of delivery: DAP Moscow.\n"
                   "Payment terms: 30/70 - 30% in advance.\nProduction time 8 weeks.")
    assert r["make_days"] == 56
    assert r["lead_days"] is None
    # Голое число без единицы — не срок.
    assert t.сроки_из("Срок поставки 30")["lead_days"] is None
    # А с единицей — срок.
    assert t.сроки_из("Срок поставки 30 дней")["lead_days"] == 30
    # И «со склада» — ноль дней, это не догадка: так написано.
    assert t.сроки_из("Срок поставки: со склада")["lead_days"] == 0


def test_в_ячейке_колонки_голое_число_сроком_является():
    """Единицу называет заголовок колонки, поэтому «30» в ней — тридцать дней.

    Ровно обратное предыдущему тесту, и оба обязаны быть верны: свободный текст и
    ячейка колонки — разные источники с разной опорой.
    """
    цк = {"lead": 0, "make": 1}
    assert t.из_строки(["30", ""], цк)["lead_days"] == 30
    assert t.из_строки(["", "45"], цк)["make_days"] == 45
    assert t.из_строки(["6 недель", ""], цк)["lead_days"] == 42


def test_якорь_ловит_косвенный_падеж():
    """«Условия поставки: 6 недель» не находилось вовсе.

    Якорь стоял «поставка», а в русском КП это слово почти всегда в косвенном
    падеже: «срок поставки», «до поставки», «условия поставки». Именительный
    падеж не ловил ничего.
    """
    assert t.сроки_из("Условия поставки: 6 недель")["lead_days"] == 42
    assert t.сроки_из("До поставки 30 дней")["lead_days"] == 30
    assert t.сроки_из("Срок поставок 8 недель")["lead_days"] == 56
    assert t.сроки_из("Отгрузка через 3 недели")["lead_days"] == 21


def test_окно_срока_не_переходит_в_следующую_фразу():
    """Срок, названный после якоря, стоит в ТОМ ЖЕ предложении.

    «Условия оплаты: 30/70 — 70% по факту поставки. Срок изготовления 8 недель»
    давало 56 дней ПОСТАВКИ: якорь «поставк» стоит в конце одной фразы, а восемь
    недель изготовления — в начале следующей.
    """
    текст = ("Условия поставки: DAP Москва.\n"
             "Условия оплаты: 30/70 — 30% предоплата, 70% по факту поставки.\n"
             "Срок изготовления 8 недель.")
    r = t.сроки_из(текст)
    assert r["make_days"] == 56
    assert r["lead_days"] is None
    # Но внутри одной фразы срок берётся, даже если дальше идёт чужое число.
    assert t.сроки_из("Срок поставки 6 недель. Цена 1 250,00")["lead_days"] == 42
    # И дробное число не считается концом фразы: полторы недели — это десять с
    # половиной дней, а round() в Python округляет половину к чётному.
    assert t.сроки_из("Срок поставки 1.5 недели")["lead_days"] == 10


def test_оплата_в_соседней_фразе_не_глушит_срок():
    """«30% предоплата. Срок изготовления 8 недель» — это 56 дней изготовления.

    Отсев чужого срока смотрел ±20 знаков вокруг якоря и перескакивал через точку:
    слева находилось «оплат» из предыдущей фразы, и срок ИЗГОТОВЛЕНИЯ терялся.
    Строка об оплате перед строкой о сроке — обычная форма КП, так что терялось бы
    у большой доли файлов. Поймано сквозной проверкой записи: в базу легло «срок
    изготовления проверено, не написано» при том, что он написан.
    """
    assert t.сроки_из("30% предоплата. Срок изготовления 8 недель.") == {
        "make_days": 56, "lead_days": None}
    assert t.сроки_из("Оплата 100% предоплата. Срок поставки 6 недель.") == {
        "make_days": None, "lead_days": 42}
    # И через перевод строки — блок условий в КП обычно построчный.
    текст = ("Условия поставки: DAP Москва.\n"
             "Условия оплаты: 30/70 — 30% предоплата.\n"
             "Срок изготовления 8 недель.")
    assert t.сроки_из(текст)["make_days"] == 56


def test_но_уточнение_вплотную_к_якорю_глушит():
    """Рамки фразы одной недостаточно, и обратного случая тоже.

    «Срок поставки: 2-3 недели с момента 100% оплаты» — «оплаты» в ТОЙ ЖЕ фразе,
    но уточняет не срок, а момент отсчёта: глушить по нему значит терять законный
    срок поставки. А «Срок оплаты 30 дней» — уточнение стоит вплотную, и это
    действительно не срок поставки.
    """
    assert t.сроки_из("Срок поставки: 2-3 недели с момента 100% оплаты")[
        "lead_days"] == 21
    assert t.сроки_из("Срок оплаты 30 дней")["lead_days"] is None
    assert t.сроки_из("Гарантийный срок 12 месяцев")["lead_days"] is None


def test_чужие_сроки_не_становятся_сроком_поставки():
    """Отсрочка платежа — не срок поставки, и срок действия КП — тоже."""
    for текст in ("Срок оплаты 30 дней",
                  "Срок действия предложения 30 дней",
                  "Гарантийный срок 12 месяцев",
                  "Срок рассмотрения 5 дней"):
        r = t.сроки_из(текст)
        assert r == {"make_days": None, "lead_days": None}, текст


