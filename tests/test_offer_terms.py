# ОБЩИЕ УСЛОВИЯ ФАЙЛА И СВОД

КП = """КОММЕРЧЕСКОЕ ПРЕДЛОЖЕНИЕ № 114 от 18.09.2026
 №  Наименование        Артикул     Кол-во  Цена, EUR  Сумма, EUR
 1  Подшипник           22315 EK        4     312,50    1 250,00
 2  Уплотнение          TRZ-4471/2     10      85,00      850,00
Условия поставки: DAP Москва.
Условия оплаты: 30/70 — 30% предоплата, 70% по факту поставки.
Срок изготовления 8 недель.
"""


def test_условия_берутся_из_блока_под_таблицей():
    """Владелец: «бывает, что в конце предложения вообще цифра»."""
    у = t.условия_файла(КП)
    assert у["basis"] == "DAP"
    assert у["pay_terms"] == "30/70"
    assert у["pay_advance_pct"] == 30
    assert у["make_days"] == 56
    # Срока поставки в этом КП нет, и это факт о предложении, а не наш недочёт.
    assert у["lead_days"] is None


def test_свод_ставит_источник_каждому_полю():
    у = t.условия_файла(КП)
    св = t.свести({}, у, был_текст=True)
    assert (св["basis"], св["basis_src"]) == ("DAP", t.ФАЙЛ)
    assert (св["pay_terms"], св["pay_terms_src"]) == ("30/70", t.ФАЙЛ)
    assert (св["make_days"], св["make_days_src"]) == (56, t.ФАЙЛ)
    # Срок поставки: искали в строке и в файле — не написано. Это и есть
    # «верифицировано отсутствует».
    assert (св["lead_days"], св["lead_days_src"]) == (None, t.НЕТ)
    assert св["pay_advance_pct"] == 30


def test_строка_главнее_файла():
    """Своя колонка позиции важнее общих условий: она про эту позицию."""
    св = t.свести({"lead_days": 14}, t.условия_файла(КП), был_текст=True)
    assert (св["lead_days"], св["lead_days_src"]) == (14, t.СТРОКА)
    # Остальные поля при этом остаются файловыми.
    assert св["basis_src"] == t.ФАЙЛ


def test_отсутствие_проверено_дважды_а_не_просто_пусто():
    """Главное требование владельца: «не отсутствует, а верифицировано отсутствует»."""
    пусто = t.условия_файла("Направляем предложение на поставку подшипников.")
    св = t.свести({}, пусто, был_текст=True)
    for поле in t.ПОЛЯ:
        assert св[поле] is None
        assert св[поле + "_src"] == t.НЕТ, поле


def test_без_текста_это_не_проверено_а_не_нет():
    """Скан без текстового слоя — наш недочёт, а не факт о предложении.

    Разница в том, кому задавать вопрос: «нет» — поставщику, «не проверено» —
    разборщику. Свалить их в одно значит постоянно спрашивать не того.
    """
    св = t.свести({}, t.условия_файла(""), был_текст=False)
    for поле in t.ПОЛЯ:
        assert св[поле + "_src"] == t.НЕ_ПРОВЕРЕНО, поле


def test_несколько_разных_значений_не_разрешается_угадыванием():
    """Два базиса в файле — «несколько», а не первый встреченный."""
    дв = t.условия_файла("Позиции 1-3: EXW Shanghai. Позиции 4-6: DDP Москва.")
    assert дв["basis"] == t.НЕСКОЛЬКО
    св = t.свести({}, дв, был_текст=True)
    assert св["basis"] is None
    assert св["basis_src"] == t.НЕСКОЛЬКО
    # То же для оплаты.
    дв2 = t.условия_файла("Позиции 1-3: оплата 30/70. Позиции 4-6: оплата 50/50.")
    assert дв2["pay_terms"] == t.НЕСКОЛЬКО
    assert дв2["pay_advance_pct"] is None


def test_полнота_считает_источники_а_не_значения():
    """Чтобы на КП можно было смотреть числом, а не глазами."""
    у = t.условия_файла(КП)
    своды = [t.свести({}, у, был_текст=True) for _ in range(3)]
    своды.append(t.свести({"lead_days": 14}, у, был_текст=True))
    п = t.полнота(своды)
    assert п["basis"] == {t.ФАЙЛ: 4}
    assert п["make_days"] == {t.ФАЙЛ: 4}
    assert п["lead_days"] == {t.НЕТ: 3, t.СТРОКА: 1}
