def test_базис_только_однозначный():
    assert t.базис_из("DDP Москва") == "DDP"
    assert t.базис_из("EXW Shanghai") == "EXW"
    assert t.базис_из("Terms of delivery: FCA Hamburg") == "FCA"
    assert t.базис_из("самовывоз со склада поставщика") == "EXW"
    # «До склада покупателя» — это и DAP, и DDP, и CPT: разница в том, кто платит
    # пошлину, и из фразы она не видна. Угадывать базис нельзя — он решает, кто
    # везёт и кто таможит.
    assert t.базис_из("доставка до склада покупателя") is None
    # «CIF» внутри слова базисом не является.
    assert t.базис_из("pacific ocean freight") is None
    assert t.базис_из("") is None


