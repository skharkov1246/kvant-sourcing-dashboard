"""Коммерческие условия КП: базис, оплата, срок производства, срок поставки.

ЗАЧЕМ. Распоряжение владельца, 22.09.2026: «Очень важно всегда искать в каждом
входящем офере сопоставление кодов, цены, цены за штуку, суммы, базис поставки
(DDP, EXW), условия оплаты (LC, 30/70, 50/50 и подобное), срок производства, срок
поставки. Если их нет, нужно перепроверять дважды и писать, что это не
отсутствует, а верифицировано отсутствует».

Отсюда три свойства, каждое проверяется отдельно, потому что каждое можно сломать
незаметно.

1. ИСКАТЬ И В СТРОКЕ, И В ФАЙЛЕ. Владелец: «бывает, что по строкам, бывает, что в
   конце предложения вообще цифра». Условия живут либо колонкой в таблице, либо
   одной записью в блоке под таблицей. Смотреть только в строку — терять обычную
   форму КП целиком.
2. РАЗЛИЧАТЬ «НЕТ» И «НЕ СМОТРЕЛИ». Пустое поле означает разом «в КП не указано»
   (факт о предложении — можно спросить поставщика) и «разбор не дошёл» (наш
   недочёт — спрашивать надо разборщик). Это разные выводы и разные действия.
3. НЕ УГАДЫВАТЬ. Два разных базиса в файле — это «несколько», а не первый
   встреченный. Тот же принцип, что у quotes.валюта_файла.

Пять ошибок, найденных при разработке, — каждая ниже закреплена тестом:

  · «Срок изготовления 8 недель» попадало разом и в срок поставки: общее слово
    «срок» встречается раньше любого слова о поставке;
  · «Срок поставки 2-3 недели с момента 100% оплаты» давало 700 дней: правило
    берёт максимум чисел (это нужно для «4–6 недель»), а на длинном хвосте
    максимумом оказывалось 100 из «100% оплаты»;
  · «против документов» записывалось как «CAD» — в коммерческом поле это читается
    канадским доллáром, то есть «30/70 CAD» выглядит ценой, а не схемой платежа;
  · «Срок оплаты 30 дней» становилось сроком поставки;
  · «доставка до склада покупателя» бралось за базис, хотя это и DAP, и DDP, и
    CPT — разница в том, кто платит пошлину, и из фразы она не видна.

Корпус придуман (CLAUDE.md, правило 18).
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
