def test_прогон_разведки_ставит_читатели_таблиц():
    """Разведка перечитывает файлы теми же indexer.rows_from_*, что и разбор.

    Те подтягивают openpyxl и xlrd ВНУТРИ функции, поэтому нехватка библиотеки
    не видна ни при импорте, ни при компиляции: прогон 35837112523 дошёл до
    середины, напечатал главный ответ и упал на ModuleNotFoundError. Проверка
    сверяет список с тем прогоном, где он заведомо полный.
    """
    import re
    разведка = (ROOT / ".github" / "workflows" / "demand-sides.yml").read_text(encoding="utf-8")
    разбор = (ROOT / ".github" / "workflows" / "library-index.yml").read_text(encoding="utf-8")

    def ставит(текст: str) -> set[str]:
        без_пояснений = "\n".join(s.split("#")[0] for s in текст.splitlines())
        слова: set[str] = set()
        for строка in re.findall(r"pip install[^\n]*(?:\n\s{2,}[^\n-][^\n]*)*", без_пояснений):
            слова |= {w.split("==")[0] for w in строка.replace("\n", " ").split()}
        return слова

    нужны = {"openpyxl", "xlrd"} & ставит(разбор)
    assert нужны == {"openpyxl", "xlrd"}, "образец сам их не ставит — сверять не с чем"
    не_хватает = нужны - ставит(разведка)
    assert not не_хватает, f"разведка не поставит {sorted(не_хватает)} и упадёт на середине"


def test_читатель_не_роняет_разведку_на_чужом_файле():
    """openpyxl на .docx БРОСАЕТ, а не возвращает пусто.

    Выражение «rows_from_xlsx(b) or rows_from_docx(b)» до второго читателя не
    доходит вовсе: прогон 35837557194 умер на первом же .docx с OSError «File
    contains no valid workbook part», уже напечатав разбивку и не перечитав ни
    одного файла. Корпус выдуман (правило 18): zip-архив с одним посторонним
    файлом внутри — по сигнатуре PK это «xlsx/docx», книгой не является.

    Какое именно исключение бросит читатель, зависит от машины: там, где openpyxl
    не поставлен (гейт его не ставит), это ModuleNotFoundError, а не OSError.
    Проверка держит не имя исключения, а правило: НИКАКОЕ исключение читателя не
    имеет права унести выборку. Второй случай ниже это и закрепляет прямо.
    """
    import collections
    import io as _io
    import zipfile

    recon = модуль()
    буфер = _io.BytesIO()
    with zipfile.ZipFile(буфер, "w") as z:
        z.writestr("word/document.xml", "<w:document/>")
    архив = буфер.getvalue()
    assert архив[:2] == b"PK", "корпус должен выглядеть как xlsx/docx"

    итог = collections.Counter()
    таблица = recon.по_виду(архив, "xlsx/docx", итог)   # не должно бросить
    assert таблица == []
    assert итог["читатель не дал таблицы"] == 1, "потеря не сосчитана — она станет невидимой"


def test_любое_исключение_читателя_остаётся_внутри():
    """Правило шире одного openpyxl: падает читатель — теряется файл, не прогон."""
    recon = модуль()

    def злой(_b):
        raise RuntimeError("читатель развалился")

    assert recon.прочитать(злой, b"anything") == []
    assert recon.прочитать_текст(злой, b"anything") == ""
    # И пустой ответ читателя — это пусто, а не None: вызывающий перебирает строки.
    assert recon.прочитать(lambda _b: None, b"") == []
    assert recon.прочитать_текст(lambda _b: None, b"") == ""


def test_доля_причины_считается_от_выборки():
    """Знаменатель — выборка, а не число прочитанных файлов.

    Прогон 35838052594 напечатал «282  1566.7 %  файл не скачался»: в числителе
    стояли все файлы выборки, в знаменателе — только прочитанные (18). Доля
    больше ста процентов обесценивает и остальные строки таблицы: читатель
    перестаёт верить числам, которые верны.
    """
    import collections
    recon = модуль()
    итог = collections.Counter({"файл не скачался: код 403": 282,
                                "шапка ЕСТЬ, но слова правилу неизвестны": 12})
    строки = recon.таблица_причин(итог, 300)
    первая = next(s for s in строки if "не скачался" in s)
    assert "94.0 %" in первая, первая
    вторая = next(s for s in строки if "слова правилу" in s)
    assert "4.0 %" in вторая, вторая
    assert not any("%" in s and float(s.split("%")[0].split()[-1]) > 100 for s in строки[1:])


def test_нескачанный_файл_называет_причину(monkeypatch):
    """Одна строка «файл не скачался» на 282 файла не говорит, что чинить."""
    recon = модуль()

    class Ответ:
        def __init__(self, код, тело=b"x" * 300):
            self.status_code, self.content = код, тело

    monkeypatch.setattr(recon.indexer, "bx", lambda *a, **k: {"error": "ACCESS_DENIED"})
    b, почему = recon.скачать("1")
    assert b is None and "ACCESS_DENIED" in почему

    monkeypatch.setattr(recon.indexer, "bx", lambda *a, **k: {"result": {}})
    b, почему = recon.скачать("2")
    assert b is None and почему == "у файла нет адреса загрузки"

    monkeypatch.setattr(recon.indexer, "bx",
                        lambda *a, **k: {"result": {"DOWNLOAD_URL": "https://пример/1"}})
    monkeypatch.setattr(recon.requests, "get", lambda *a, **k: Ответ(403))
    b, почему = recon.скачать("3")
    assert b is None and "403" in почему

    monkeypatch.setattr(recon.requests, "get", lambda *a, **k: Ответ(200))
    monkeypatch.setattr(recon.indexer, "is_login_page", lambda _b: False)
    b, почему = recon.скачать("4")
    assert b and почему == ""


def test_код_отказа_портала_доезжает_до_журнала_без_описания():
    """«портал не ответил (BitrixError)» не говорит, что чинить.

    Прогон 35838739209: 56 файлов из 60 свелись к имени класса исключения, а
    настоящий ответ портала — код внутри строки. Описание рядом с кодом может
    нести идентификатор файла, поэтому в журнал идёт только код (правило 17).
    """
    recon = модуль()
    e = RuntimeError("disk.file.get: ERROR_NOT_FOUND Файл 123456 не найден")
    assert recon.код_ошибки(e) == "ERROR_NOT_FOUND"
    # Описание не просачивается: ни цифр идентификатора, ни слов из него.
    assert "123456" not in recon.код_ошибки(e)
    # Кода нет вовсе — остаётся имя исключения, а не пустая строка.
    assert recon.код_ошибки(ValueError("сеть отвалилась")) == "ValueError"
