"""Разведка причин непрочитанной шапки: проверяются сами её признаки.

ЗАЧЕМ. Разведка решает, ЧТО править в разборщике: список слов заголовков, правило
склейки строк или переход к опознанию колонки по форме данных. Ошибись она — и
править будут не то. Поэтому её признаки проверяются как правило, а не как утилита.

Корпус придуман (CLAUDE.md, правило 18).
"""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def модуль():
    for p in (ROOT, ROOT / "library", ROOT / "scripts"):
        if str(p) not in sys.path:
            sys.path.insert(0, str(p))
    os.environ.setdefault("BITRIX_WEBHOOK_URL", "нет-сети-в-тесте")
    spec = importlib.util.spec_from_file_location(
        "kvant_header_recon", ROOT / "scripts" / "header_recon.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def test_строка_заголовков_отличается_от_строки_данных():
    m = модуль()
    assert m.похоже_на_шапку(["№", "Наименование", "Кол-во", "Цена, EUR", "Сумма"])
    assert m.похоже_на_шапку(["Unit price", "Amount", "Qty", "Delivery time"])
    # Строка данных шапкой считаться не должна: иначе разведка объявит, что шапка
    # есть у всех, и причина «шапки нет вовсе» станет невидимой.
    assert not m.похоже_на_шапку(["1", "Подшипник 6205", "10", "12.50", "125.00"])
    assert not m.похоже_на_шапку(["1", "2", "3"])
    assert not m.похоже_на_шапку([])


def test_длинный_абзац_не_шапка():
    """Проза в ячейке — признак того, что это не таблица, а текст."""
    m = модуль()
    долгая = "Оплата производится в течение тридцати банковских дней с даты счёта"
    assert not m.похоже_на_шапку([долгая, долгая, долгая])


