"""Разведка причин непрочитанной шапки: проверяются сами её признаки.

ЗАЧЕМ. Разведка решает, ЧТО править в разборщике: список слов заголовков, правило
склейки строк или переход к опознанию колонки по форме данных. Ошибись она — и
править будут не то. Поэтому её признаки проверяются как правило, а не как утилита.

Корпус придуман (CLAUDE.md, правило 18).
"""
from __future__ import annotations

import importlib.util
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def модуль():
    for p in (ROOT, ROOT / "library", ROOT / "scripts"):
        if str(p) not in sys.path:
            sys.path.insert(0, str(p))
    os.environ.setdefault("BITRIX_WEBHOOK_URL", "нет-сети-в-тесте")
    spec = importlib.util.spec_from_file_location(
        "kvant_header_recon", ROOT / "scripts" / "header_recon.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def test_строка_заголовков_отличается_от_строки_данных():
    m = модуль()
    assert m.похоже_на_шапку(["№", "Наименование", "Кол-во", "Цена, EUR", "Сумма"])
    assert m.похоже_на_шапку(["Unit price", "Amount", "Qty", "Delivery time"])
    # Строка данных шапкой считаться не должна: иначе разведка объявит, что шапка
    # есть у всех, и причина «шапки нет вовсе» станет невидимой.
    assert not m.похоже_на_шапку(["1", "Подшипник 6205", "10", "12.50", "125.00"])
    assert not m.похоже_на_шапку(["1", "2", "3"])
    assert not m.похоже_на_шапку([])


def test_длинный_абзац_не_шапка():
    """Проза в ячейке — признак того, что это не таблица, а текст."""
    m = модуль()
    долгая = "Оплата производится в течение тридцати банковских дней с даты счёта"
    assert not m.похоже_на_шапку([долгая, долгая, долгая])


def test_тройка_сходится_только_когда_арифметика_верна():
    """Это проверка причины «шапки нет вовсе»: цену можно взять по форме данных."""
    m = модуль()
    сходится = [["1", "вал", "10", "12.5", "125"],
                ["2", "втулка", "4", "3", "12"],
                ["3", "болт", "2", "5", "10"]]
    assert m.тройка_сходится(сходится)
    # Те же колонки, но суммы не произведения: опираться на форму нельзя.
    assert not m.тройка_сходится([["1", "вал", "10", "12.5", "999"],
                                  ["2", "втулка", "4", "3", "777"],
                                  ["3", "болт", "2", "5", "555"]])


def test_тройка_не_сходится_на_двух_строках():
    """Три строки — минимум: на двух совпадение бывает случайным."""
    m = модуль()
    assert not m.тройка_сходится([["1", "вал", "10", "12.5", "125"],
                                  ["2", "втулка", "4", "3", "12"]])


def test_округление_в_кп_не_ломает_тройку():
    """В предложениях округляют: допуск процент, иначе тройка не сойдётся нигде."""
    m = модуль()
    assert m.тройка_сходится([["1", "a", "3", "33.33", "100.00"],
                              ["2", "b", "7", "14.29", "100.03"],
                              ["3", "c", "6", "16.67", "100.02"]])


def test_числовая_доля_различает_колонки():
    m = модуль()
    assert m.числовая_доля(["12.5", "3", "5"]) == 1.0
    assert m.числовая_доля(["вал", "втулка", "болт"]) == 0.0
    # Пустая колонка — ноль, а не деление на ноль.
    assert m.числовая_доля(["", "  ", None]) == 0.0


def test_выборка_не_угадывает_вид_файла():
    """Первая версия отбирала kind = 'pdf' по догадке и дала бы пусто.

    rows_from_pdf отвергает разрез, если шапка не узнана, значит для PDF «таблица
    без шапки» невозможна по устройству кода. Разведка обязана СПРОСИТЬ базу, а не
    предполагать: догадка о виде файла стоила бы холостого перечита портала.
    """
    текст = (ROOT / "scripts" / "header_recon.py").read_text(encoding="utf-8")
    код = "\n".join(s.split("#")[0] for s in текст.splitlines())
    assert "РАЗБОРКА" in код, "нет запроса о виде файлов"
    assert "f.kind = 'pdf'" not in код, "вернулась догадка о виде файла"
    assert "group by 1, 2" in код, "раскладка не по виду и версии разборщика"


def test_порог_частотного_списка_по_разным_файлам():
    """Слово, сто раз повторённое в одном документе, о рынке не говорит ничего.

    И это же условие правила 17: частотный список допустим при жёстком фильтре.
    """
    m = модуль()
    assert m.ПОРОГ_ФАЙЛОВ >= 3
    # Шесть букв — та же граница, что в правиле 17.
    assert m.СЛОВО.pattern.endswith("{6,}")
    assert m.СЛОВО.findall("цена") == []
    assert m.СЛОВО.findall("стоимость") == ["стоимость"]
