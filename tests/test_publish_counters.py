"""Снимок точек замеров для страницы счётчиков: что попадёт на сайт.

ЗАЧЕМ. Снимок уезжает в KV и оттуда на страницу, которую смотрит владелец.
Проверяется не «собралось», а то, что даёт НЕВЕРНУЮ или ОПАСНУЮ страницу:

1. НЕЧИСЛОВОЕ ЗНАЧЕНИЕ. Колонка nums объявлена jsonb, положить в неё строку
   ничто не мешает. Таблица lib_metric_runs публичная по назначению, и снимок
   публичным быть не обязан — нечисловое значение отбрасывается, а не публикуется
   (CLAUDE.md, правило 17). Отброшенное считается вслух: молчаливая потеря
   значения хуже самой потери.
2. ПУСТАЯ ИСТОРИЯ — НЕ ПОВОД ПИСАТЬ ПУСТОЙ КЛЮЧ. Страница тогда скажет «пока
   пусто» вместо вчерашних точек, и разобраться, потерялись они или их не было,
   будет уже нечем.
3. ПОРЯДОК ТОЧЕК. Перепутанный порядок рисует пилу на графике.
4. РАЗМЕР. У истории замеров свой предел, куда меньше снимка номенклатуры: это
   сотни точек по десятку чисел.

Корпус придуман (правило 18).
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]


def модуль():
    spec = importlib.util.spec_from_file_location(
        "kvant_publish_counters", ROOT / "scripts" / "publish_counters.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def строка(metric, run, at, nums, note=None):
    return (metric, run, at, nums, note)


def test_числа_переносятся_как_есть():
    m = модуль()
    снимок = m.собрать([
        строка("коды_и_цены", "111", "2026-09-21T01:00:00Z", {"asked": 100, "with_kp": 10}),
        строка("коды_и_цены", "222", "2026-09-22T01:00:00Z", {"asked": 120, "with_kp": 18}),
    ])
    точки = снимок["metrics"]["коды_и_цены"]
    assert [т["run"] for т in точки] == ["111", "222"]
    assert точки[1]["nums"] == {"asked": 120, "with_kp": 18}
    assert снимок["version"] == 1
    assert снимок["dropped"] == 0


def test_нечисловое_значение_не_уезжает_на_сайт():
    """Строка в nums — это уже утечка, чем бы она ни была."""
    m = модуль()
    снимок = m.собрать([
        строка("коды_и_цены", "111", "2026-09-21T01:00:00Z",
               {"asked": 100, "поставщик": "Учебный завод", "флаг": True}),
    ])
    числа = снимок["metrics"]["коды_и_цены"][0]["nums"]
    assert числа == {"asked": 100}, "нечисловое значение попало в снимок"
    # True — это int в Python, и без отдельной проверки он проехал бы числом.
    assert снимок["dropped"] == 2, "отброшенное не посчитано вслух"
    assert "Учебный завод" not in json.dumps(снимок, ensure_ascii=False)


def test_оговорка_единственное_текстовое_поле_и_она_доезжает():
    """Оговорку пишет рукой автор замера — без неё «цифра упала» читается как провал."""
    m = модуль()
    снимок = m.собрать([
        строка("коды_и_цены", "111", "2026-09-21T01:00:00Z", {"asked": 1},
               "замер во время переразбора"),
        строка("коды_и_цены", "222", "2026-09-22T01:00:00Z", {"asked": 2}),
    ])
    точки = снимок["metrics"]["коды_и_цены"]
    assert точки[0]["note"] == "замер во время переразбора"
    # Пустая оговорка не кладётся вовсе, а не кладётся как null: страница тогда
    # показывает плашку на каждой точке.
    assert "note" not in точки[1]


def test_замеры_не_смешиваются():
    """Страница отбирает свой замер по имени: смешать их — нарисовать чужую линию."""
    m = модуль()
    снимок = m.собрать([
        строка("коды_и_цены", "111", "2026-09-21T01:00:00Z", {"asked": 100}),
        строка("воронка_разбора", "111", "2026-09-21T01:00:00Z", {"files": 7}),
    ])
    assert set(снимок["metrics"]) == {"коды_и_цены", "воронка_разбора"}
    assert len(снимок["metrics"]["коды_и_цены"]) == 1


def test_запрос_берёт_последние_точки_каждого_замера():
    """Предел точек применяется ПО ЗАМЕРУ, а не ко всей таблице.

    Общий предел означал бы, что частый замер вытесняет редкий целиком — и
    страница редкого замера однажды покажет «пока пусто» без всякой поломки.
    """
    m = модуль()
    assert "partition by metric" in m.ИСТОРИЯ
    assert "order by measured_at desc" in m.ИСТОРИЯ
    # Выдача упорядочена по времени возрастанию: график читается слева направо.
    assert m.ИСТОРИЯ.rstrip().endswith("order by metric, at")


def test_время_отдаётся_в_utc_с_явной_меткой():
    """Без «Z» страница прочитает время как местное и сдвинет точки на часы."""
    m = модуль()
    assert "at time zone 'UTC'" in m.ИСТОРИЯ
    assert '"Z"' in m.ИСТОРИЯ


def test_предел_размера_скромный_и_свой():
    """Мегабайты здесь означали бы ошибку публикатора, а не рост истории."""
    m = модуль()
    assert m.ПРЕДЕЛ == 1 << 20
    # Не позаимствован у снимка номенклатуры: тот 8 МиБ, и общий предел скрыл бы
    # разбухание истории до самого конца.
    assert m.ПРЕДЕЛ < 8 * 1024 * 1024


def test_ключ_закрытый_и_не_переписывает_чужие():
    """Публикатор не должен уметь затереть реестр поставщиков или права."""
    m = модуль()
    assert m.KEY == "counters:v1"
    # РАЗБОР ЧИТАЕТ КОД, А НЕ ПОЯСНЕНИЯ (CLAUDE.md, «Стиль работы»). Строка
    # документации модуля объясняет, ПОЧЕМУ он не может переписать suppliers:v1 и
    # crossref:v1, — и первая версия этой проверки поймала именно её, отчитавшись
    # о том, чего в коде нет. Поэтому берётся AST: строковые значения кода без
    # строк документации.
    import ast

    дерево = ast.parse((ROOT / "scripts" / "publish_counters.py").read_text(encoding="utf-8"))
    документация = {id(ast.get_docstring(узел, clean=False)) for узел in ast.walk(дерево)
                    if isinstance(узел, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef,
                                         ast.ClassDef))}
    значения = set()
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Constant) and isinstance(узел.value, str):
            значения.add(узел.value)
    for узел in ast.walk(дерево):
        if isinstance(узел, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            текст_док = ast.get_docstring(узел, clean=False)
            значения.discard(текст_док)
    assert документация  # проверка сама себя: строки документации найдены
    for чужой in ("suppliers:v1", "acl:v1", "crossref:v1", "library:v1"):
        assert not any(чужой in v for v in значения), \
            f"публикатор счётчиков знает про {чужой}"
    # Свой ключ при этом в строках кода есть — иначе проверка выше проходила бы
    # на пустом множестве.
    assert m.KEY in значения


@pytest.mark.parametrize("точки", [[], [("коды_и_цены", "1", "t", {}, None)]])
def test_пустая_история_не_публикуется_пустым_ключом(точки, monkeypatch):
    """Пустой ключ поверх вчерашних точек — потеря, которую нечем отличить от «их не было»."""
    m = модуль()
    снимок = m.собрать(точки)
    if not точки:
        assert снимок["metrics"] == {}
    else:
        # Точка без единого числа всё же точка: она говорит, что замер состоялся.
        assert снимок["metrics"]["коды_и_цены"][0]["nums"] == {}
