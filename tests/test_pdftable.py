"""Таблица из PDF: колонки по выравниванию, и ни одной выдуманной позиции.

ЗАЧЕМ. Коммерческие предложения приходят PDF-ами, и до 22.09.2026 PDF разбирался
как проза: цена в нём опознавалась арифметикой «кол-во × цена = сумма». Правило
честное, но узкое — без суммы в строке оно молчит, а различить цену и сумму иначе
как счётом не может, тогда как в файле НАПИСАНО, где что: в шапке таблицы.

pypdf умеет extract_text(extraction_mode="layout") — отступы сохраняются, и
таблица остаётся таблицей. library/pdftable.py возвращает колонки, дальше работает
та же машинерия шапки, что у xlsx.

Четыре ловушки, каждая уже сработала при разработке:

1. ЗАГОЛОВОК ДОКУМЕНТА СЪЕДАЕТ ЖЁЛОБЫ. «КОММЕРЧЕСКОЕ ПРЕДЛОЖЕНИЕ № 114», строка
   условий поставки и подписи тянутся во всю ширину. Считая жёлобы по всем
   строкам, пять левых колонок склеиваются в одну — а в них номенклатура и
   количество, без которых цена бесполезна.
2. ШАПКА ШИРЕ СВОЕЙ КОЛОНКИ. «Цена за ед., EUR» выровнена влево, числа под ней —
   вправо; заголовок свисает в соседний жёлоб и закрывает его для всего блока.
   Колонка цены не опознаётся, и цена начинает выводиться делением суммы на
   количество: число то же, но с ложной оговоркой, а на строке без суммы теряется
   совсем.
3. ПРОЗА, РАЗРЕЗАННАЯ ПО КОЛОНКАМ. «Условия поставки: DAP Москва. Оплата 100%
   предоплата» под границы таблицы не ложится, и разрез даёт три обрывка, из
   которых разбор делает выдуманную позицию с выдуманным количеством.
4. «UNIT PRICE», ПРИНЯТОЕ ЗА КОЛОНКУ ЕДИНИЦЫ. Слово «unit» опознаёт единицу
   измерения и заодно ловит «Unit price». Тогда в qty_unit уезжает цена. В наших
   данных КП больше всего китайских, то есть шапки чаще английские, и промах
   типовой, а не редкий.

Корпус придуман (CLAUDE.md, правило 18). PDF собирается здесь же, руками: он
нужен, чтобы проверить цепочку целиком, от байтов до цены.
"""
from __future__ import annotations

import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "library"))

import indexer  # noqa: E402
import pdftable  # noqa: E402
import quotes  # noqa: E402


def мини_pdf(строки: list[str], кегль: int = 9) -> bytes:
    """Одностраничный PDF моноширинным шрифтом: строка на своей координате.

    Собирается руками, а не библиотекой: писать PDF в зависимостях гейта нет, а
    проверить цепочку до байтов включительно надо — именно на стыке «extract_text
    вернул не то, что ожидалось» ломается разбор в проде.
    """
    части = ["BT", f"/F1 {кегль} Tf"]
    for i, s in enumerate(строки):
        t = s.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")
        части.append(f"1 0 0 1 40 {560 - i * 14} Tm ({t}) Tj")
    части.append("ET")
    поток = "\n".join(части).encode("latin-1", "replace")
    объекты = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 842 595] "
        b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length %d >>\nstream\n" % len(поток) + поток + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>",
    ]
    out = bytearray(b"%PDF-1.4\n")
    смещения = []
    for i, o in enumerate(объекты, 1):
        смещения.append(len(out))
        out += b"%d 0 obj\n" % i + o + b"\nendobj\n"
    начало = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(объекты) + 1)
    for off in смещения:
        out += b"%010d 00000 n \n" % off
    out += (b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n"
            % (len(объекты) + 1, начало))
    return bytes(out)


# КОРПУС. Английская шапка — в наших данных КП больше всего китайских, и шапки у
# них английские. Заголовок «Unit Price, USD» шире своей колонки: числа под ним
# выровнены вправо. Это ловушка 2 в чистом виде.
КП = [
    "                    QUOTATION No. 114 dated 18.09.2026",
    "",
    " No  Description               Part No      Qty  Unit  Unit Price, USD   Amount, USD   Delivery",
    " 1   Roller bearing            22315 EK       4  pcs           312,50      1 250,00   6 weeks",
    " 2   Mechanical seal           TRZ-4471/2    10  pcs            85,00        850,00   in stock",
    " 3   Spacer ring               6205-2RS       2  pcs            47,25         94,50   4 weeks",
    " 4   Rotor shaft assembly      NM-125/07      1  pcs        12 400,00     12 400,00   12 weeks",
    "",
    " Terms of delivery: DAP Moscow. Payment 100% in advance. Validity 30 days.",
]

# Ожидания посчитаны руками по КП выше.
ОЖИДАЕМЫЕ = [("22315 EK", 4.0, 312.50, 1250.00, 42),
             ("TRZ-4471/2", 10.0, 85.00, 850.00, 0),
             ("6205-2RS", 2.0, 47.25, 94.50, 28),
             ("NM-125/07", 1.0, 12400.00, 12400.00, 84)]


def _разобрать():
    rows = indexer.rows_from_pdf(мини_pdf(КП))
    hi, cols = indexer.header_map(rows)
    return rows, hi, cols


def test_шапка_опознана_и_колонки_цены_найдены():
    """Ловушки 1 и 2: шапка должна найтись, и цена — своей колонкой."""
    rows, hi, cols = _разобрать()
    assert hi >= 0, "шапка не опознана — вся цепочка дальше не работает"
    assert set(cols) >= {"item_name", "part_number", "qty"}
    цк = quotes.колонки_цены(rows[hi])
    # Цена и сумма — РАЗНЫЕ колонки. Если price не нашёлся, цена будет выводиться
    # делением, и на строке без суммы потеряется совсем.
    assert "price" in цк and "total" in цк
    assert цк["price"] != цк["total"]
    assert quotes.валюта_заголовка(rows[hi], цк) == "USD"
    # Ловушка 4: «Unit Price, USD» — не колонка единицы измерения.
    assert cols.get("unit") == 4, "колонкой единицы должна быть Unit, а не Unit Price"


def test_цена_читается_из_колонки_а_не_выводится_делением():
    """Главное, ради чего табличный путь и заведён."""
    rows, hi, cols = _разобрать()
    цк = quotes.колонки_цены(rows[hi])
    вк = quotes.валюта_заголовка(rows[hi], цк)
    прочитано = []
    for r in rows[hi + 1:]:
        q = quotes.число_из(r[cols["qty"]])
        ц = quotes.цена_строки(r, цк, q, вк)
        if ц is None:
            continue
        прочитано.append((r[cols["part_number"]], q, ц))
    assert len(прочитано) == len(ОЖИДАЕМЫЕ)
    for (арт, кол, ожид_цена, _сумма, срок), (факт_арт, факт_кол, ц) in zip(
            ОЖИДАЕМЫЕ, прочитано):
        assert факт_арт == арт
        assert факт_кол == кол
        assert ц["price"] == ожид_цена
        assert ц["currency"] == "USD"
        # Цена взята из своей колонки: оговорки о делении быть не должно.
        assert "делением" not in (ц["note"] or "")
        assert ц["confidence"] == "med"
        assert ц["lead_days"] == срок


def test_проза_не_становится_позицией_из_обрывков():
    """Ловушка 3: строка условий идёт одной ячейкой, а не тремя обрывками."""
    rows, _hi, _cols = _разобрать()
    условия = [r for r in rows if "Terms of delivery" in r[0]]
    assert len(условия) == 1, "строка условий должна остаться целой в первой ячейке"
    # Остальные ячейки пусты: количества и цены у прозы нет и быть не может.
    assert all(not c for c in условия[0][1:])
    # И заголовок документа — тоже целиком в одной ячейке.
    шапки_документа = [r for r in rows if r[0].startswith("QUOTATION")]
    assert len(шапки_документа) == 1
    assert all(not c for c in шапки_документа[0][1:])


def test_строгий_разрез_не_режет_слова():
    """Ступень допуска 0: граница не может попасть внутрь слова.

    Проверяется прямо, а не через шапку: там, где стоит буква, жёлоба нет по
    определению, значит ни одна ячейка не начинается и не кончается обрывком.
    """
    текст = "\n".join(КП)
    блок = pdftable._табличные([s.rstrip() for s in текст.splitlines()])
    жёлобы = pdftable._жёлобы(блок, допуск=0)
    точки = pdftable._границы(жёлобы, max(len(s) for s in блок))
    for s in блок:
        for т in точки[1:-1]:
            если_внутри = (0 < т < len(s) and s[т - 1] != " " and s[т] != " ")
            assert not если_внутри, (т, s)


def test_без_выравнивания_таблицы_нет():
    """Проза без колонок обязана дать пустой список, а не случайный разрез."""
    проза = ("Уважаемые коллеги! Направляем вам наше предложение на поставку "
             "запасных частей. Цены указаны с учётом доставки до склада "
             "покупателя. Просим подтвердить готовность к заключению договора.")
    assert pdftable.строки_в_таблицу(проза) == []
    assert pdftable.строки_в_таблицу("") == []
    assert pdftable.строки_в_таблицу("одна строка и всё") == []


def test_битый_pdf_не_роняет_разбор():
    """Не PDF, обрезанный PDF, пустые байты — пустой список, а не исключение."""
    assert indexer.rows_from_pdf(b"") == []
    assert indexer.rows_from_pdf(b"not a pdf at all") == []
    целый = мини_pdf(КП)
    assert indexer.rows_from_pdf(целый[:len(целый) // 3]) == []


def test_чужой_срок_не_становится_сроком_поставки():
    """«Срок оплаты» — не срок поставки.

    Образец «срок » (с пробелом) ловил «Срок оплаты», и отсрочка платежа
    записывалась сроком поставки. Тридцать дней отсрочки — не тридцать дней
    поставки, и ни оговорки, ни признака при этом не было.
    """
    assert quotes.колонки_цены(["№", "Наименование", "Цена", "Сумма",
                                "Срок оплаты"]).get("lead") is None
    assert quotes.колонки_цены(["№", "Наименование", "Цена", "Сумма",
                                "Срок действия предложения"]).get("lead") is None
    # А голое «Срок» — самая частая запись в шапке — сроком поставки быть обязано.
    assert quotes.колонки_цены(["№", "Наименование", "Цена", "Сумма",
                                "Срок"]).get("lead") == 4
    # И если в шапке оба, берётся именно срок поставки.
    assert quotes.колонки_цены(["№", "Цена", "Сумма", "Срок оплаты",
                                "Срок поставки"]).get("lead") == 4
