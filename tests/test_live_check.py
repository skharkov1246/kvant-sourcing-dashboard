"""Живая сверка обязана ловить ровно те ошибки, которые 23.09.2026 ушли в прод.

Каждый тест воспроизводит реальный случай на придуманных числах той же формы:
#396 — пустой ряд на живых данных, #397 — служебная запись с неверным номером,
#400 — перенос сотен запросов на одного человека. Если сверка пропустит хоть
один из них, она не нужна. И обратное: законная правка вроде #401, которая
раскладывает запросы по десятку людей, проходить обязана, иначе сверку начнут
обходить.

Корпус придуман, а не взят из портала, как велят правила репозитория.
"""
from __future__ import annotations

import copy
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))


def lc():
    import live_check
    return live_check


def сборка(люди: dict[str, int], вне: int, *, kp: int = 40, неопр: int = 10,
           служебные: tuple[str, ...] = ("234", "542")) -> dict:
    отдел = sum(люди.values())
    return {
        "kpi": {"total": отдел + вне, "deptA": отдел, "outside": вне},
        "sourcersA": [{"id": u, "c": c} for u, c in люди.items()],
        "weekly": [{"w": "W1", "d": "1–7", "A": отдел // 2, "B": вне // 2, "kp": kp // 2},
                   {"w": "W2", "d": "8–14", "A": отдел - отдел // 2, "B": вне - вне // 2, "kp": kp - kp // 2}],
        "origin": {"service": [{"uid": u, "n": 100} for u in служебные],
                   "resolvedHow": [{"how": "не определён", "n": неопр}]},
    }


ПРОД = сборка({"76": 25, "77": 400, "78": 380, "79": 350, "80": 300}, вне=900)


def провалы(до, после, текст="", служебные=frozenset({"234", "542"})):
    p = lc()
    return [t for u, t in p.сверить(до, после, p.ожидания(текст), set(служебные)) if u == p.ПРОВАЛ]


def test_без_правки_сверка_чиста():
    assert провалы(ПРОД, copy.deepcopy(ПРОД)) == []


def test_шум_живого_портала_не_провал():
    """Два прогона читают портал с разницей в минуты: пара карточек успевает
    переехать. Это не сдвиг от правки."""
    после = сборка({"76": 25, "77": 402, "78": 379, "79": 350, "80": 299}, вне=900)
    assert провалы(ПРОД, после) == []


def test_ошибка_400_перенос_сотен_на_одного_ловится():
    """Заявлено «сорсерам +517», получено «руководителю +517»."""
    после = сборка({"76": 542, "77": 400, "78": 380, "79": 350, "80": 300}, вне=383)
    f = провалы(ПРОД, после, "ожидается: сорсеры +517\nожидается: вне отдела -517\nожидается: отдел +517")
    assert any("#76" in t and "одного человека" in t for t in f), f


def test_ошибка_400_ловится_и_без_заявки():
    после = сборка({"76": 542, "77": 400, "78": 380, "79": 350, "80": 300}, вне=383)
    f = провалы(ПРОД, после)
    assert any("#76" in t and "не заявлен" in t for t in f), f


def test_законная_раскладка_по_людям_проходит():
    """#401: 517 запросов ушли от руководителя к сорсерам, по сотне с небольшим."""
    до = сборка({"76": 542, "77": 400, "78": 380, "79": 350, "80": 300}, вне=383)
    после = сборка({"76": 25, "77": 530, "78": 510, "79": 480, "80": 427}, вне=383)
    assert провалы(до, после, "ожидается: #76 -517\nожидается: сорсеры +517") == []


def test_заявленный_сдвиг_которого_нет_провал():
    f = провалы(ПРОД, copy.deepcopy(ПРОД), "ожидается: вне отдела -540")
    assert any("заявлено -540, получено +0" in t for t in f), f


def test_ошибка_396_пустой_новый_ряд_ловится():
    после = copy.deepcopy(ПРОД)
    for w in после["weekly"]:
        w["kpa"] = 0                      # новый ряд, на живых данных пустой
    f = провалы(ПРОД, после)
    assert any("«kpa»" in t and "пуст" in t for t in f), f


def test_ряд_опустевший_после_правки_ловится():
    после = copy.deepcopy(ПРОД)
    for w in после["weekly"]:
        w["kp"] = 0                       # был 40, стал 0
    f = провалы(ПРОД, после)
    assert any("«kp»" in t and "в проде был 40" in t for t in f), f


def test_ошибка_397_служебная_запись_без_карточек_ловится():
    f = провалы(ПРОД, copy.deepcopy(ПРОД), служебные={"234", "542", "2"})
    assert any("#2 задана номером" in t for t in f), f


def test_правка_не_может_менять_итог():
    после = сборка({"76": 25, "77": 400, "78": 380, "79": 350, "80": 300}, вне=700)
    f = провалы(ПРОД, после, "ожидается: вне отдела -200")
    assert any("всего запросов" in t for t in f), f


def test_рост_нераспознанных_ловится():
    после = copy.deepcopy(ПРОД)
    после["origin"]["resolvedHow"] = [{"how": "не определён", "n": 60}]
    f = провалы(ПРОД, после)
    assert any("не определён" in t for t in f), f


def test_целостность_сборки_проверяется():
    после = copy.deepcopy(ПРОД)
    после["kpi"]["deptA"] += 5            # отдел разошёлся с суммой по людям и с итогом
    f = провалы(ПРОД, после, "ожидается: отдел +5")
    assert any("≠" in t for t in f), f


def test_разбор_заявки():
    p = lc()
    got = p.ожидания("текст\nожидается: #76 −517\nОжидается: вне отдела -540\n"
                     "ожидается: отдел +540\nожидается: сорсеры +517")
    assert got == {"#76": -517, "вне отдела": -540, "отдел": 540, "сорсеры": 517}
    assert p.ожидания("ожидается: без изменений") == {"__заявлено__": 0}
    assert p.ожидания("") == {}
