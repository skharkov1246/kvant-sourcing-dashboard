def сборка(люди: dict[str, int], вне: int, *, звенья: dict[str, int] | None = None, без_исп: int = 20,
           служебные: tuple[str, ...] = ("234", "542"), kp: int = 40) -> dict:
    """Самосогласованная сборка метрик: все инварианты сходятся."""
    отдел = sum(люди.values())
    сорсеры = [{"id": u, "n": f"Сорсер {u}", "c": c, "wk": [c // 2, c - c // 2],
                "closed": c // 4, "kp": c // 4, "refusedCol": 0, "noAnswer": 0, "quotes": c // 5 + 1}
               for u, c in люди.items()]
    return {
        "kpi": {"total": отдел + вне, "deptA": отдел, "outside": вне, "tkpPct": 35,
                "respCount": len(люди) + 7},
        "sourcersA": сорсеры,
        "weekly": [{"w": "W1", "d": "1–7", "A": sum(s["wk"][0] for s in сорсеры), "B": вне // 2,
                    "kp": kp // 2, "kpa": 3, "inb": 0},
                   {"w": "W2", "d": "8–14", "A": sum(s["wk"][1] for s in сорсеры), "B": вне - вне // 2,
                    "kp": kp - kp // 2, "kpa": 4, "inb": 0}],
        "origin": {"service": [{"uid": u, "n": 100, "looksHuman": False} for u in служебные],
                   "resolvedHow": [{"how": k, "n": v} for k, v in (звенья or ЗВЕНЬЯ).items()],
                   "byOwnerDept": [{"dept": "Отдел поиска", "n": отдел},
                                   {"dept": "Прочие", "n": вне - без_исп},
                                   {"dept": "исполнитель не определён", "n": без_исп}],
                   "summary": {"total": отдел + вне}},
        "chain": {"early": 100, "tkp": 50, "lost": 20},
    }


def вкладки(**правки) -> dict:
    d = {"company": {"pulse": {"deals": 310, "won": 41}},
         "kam": {"rows": [{"id": "5", "open": 7}, {"id": "6", "open": 3}]},
         "eng": {"rows": [{"id": "5", "open": 2}]},
         "prod": {"rows": [{"id": "6", "open": 4}]},
         "contracts": {"rows": [{"id": "91", "sum": 1200}]},
         "reps": {"reps": [{"id": "8", "deals": 20}, {"id": "9", "deals": 11}]},
         "advisor": {"brief": [{"lbl": "прогноз", "v": 12}]},
         "people": {"staff": {"active": 12, "fired": 3}},
         "_portal": {"mode": "replay", "saved": 0, "hits": 40, "misses": 0}}
    d.update(правки)
    return d


ПРОД = сборка({"10": 25, "11": 400, "12": 380, "13": 350, "14": 300}, вне=900)


def итог(до, после, текст="", *, точно=True, служебные=frozenset({"234", "542"}), служебные_прод=None,
         модули_до=..., модули_после=...):
    """Обе сборки по умолчанию выгрузили одинаковые вкладки — как в настоящем
    прогоне, где правка выгружает их всегда."""
    p = lc()
    return p.сверить(до, после, p.ожидания(текст), служебные=set(служебные), служебные_прод=служебные_прод,
                     модули_до=вкладки() if модули_до is ... else модули_до,
                     модули_после=вкладки() if модули_после is ... else модули_после, точно=точно)


def провалы(*a, **k):
    return [t for u, t in итог(*a, **k) if u == lc().ПРОВАЛ]


def внимание(*a, **k):
    return [t for u, t in итог(*a, **k) if u == lc().ВНИМАНИЕ]


