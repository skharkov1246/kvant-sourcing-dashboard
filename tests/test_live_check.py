def test_разбор_заявки_в_разметке():
    """Форматы, которые первая версия молча теряла или читала неверно."""
    p = lc()
    assert p.ожидания("**ожидается:** #10 -300").сдвиги == {"#10": -300}
    assert p.ожидания("ожидается: **#10 -300**").сдвиги == {"#10": -300}
    assert p.ожидания("| ожидается: | #10 −300 |").сдвиги == {"#10": -300}
    assert p.ожидания("### Ожидается:\n- #10 −300\n- сорсеры +300\n\nпрочий текст").сдвиги == \
        {"#10": -300, "сорсеры": 300}
    assert p.ожидания("ожидается: вне отдела −1 540").сдвиги == {"вне отдела": -1540}
    assert p.ожидания("ожидается: #10 —300").сдвиги == {"#10": -300}
    assert p.ожидания("ожидается: #10 −300; сорсеры +300, отдел +0").сдвиги == \
        {"#10": -300, "сорсеры": 300, "отдел": 0}
    z = p.ожидания("ожидается: звено «сорсер сделки» +300\nожидается: меняется people, reps\n"
                   "ожидается: пустой weekly.inb\nожидается: не определён −40")
    assert z.сдвиги == {"звено сорсер сделки": 300, "не определен": -40}
    assert z.разделы == {"people", "reps"} and z.пустые == {"weekly.inb"} and not z.ошибки


