"""Рядом с итоговой суммой заявки обязана стоять доля, не подтверждённая ценой.

Замер написан 18.09.2026 по простому наблюдению: у записей разведки цен есть
поле основания, и оно написано честно — где-то «retail: <продавец> $326.50», а
где-то прямо «экспертная вилка». Пока доля вторых не названа, итоговая сумма
читается как замер, хотя замер она только на части строк. По деньгам оказалось
64,1 процента.

Здесь закреплено три правила. Первое: класс основания определяется по НАЧАЛУ
перебора и «экспертная вилка» бьёт всё остальное — запись, назвавшая себя
мнением, не перестаёт им быть от слова «дистрибьютор» в том же предложении.
Второе: счёт по классам сходится с итогом. Третье: то, что перепроверка уже
закрыла найденной ценой, считается отдельно — иначе доля будет описывать
вчерашнее состояние и обесценит проделанную работу.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "gt/data/ship_band_basis.json"
sys.path.insert(0, str(ROOT / "gt/tools"))


def doc() -> dict:
    if not SRC.exists():
        pytest.skip("замера нет")
    return json.loads(SRC.read_text(encoding="utf-8"))


def test_мнение_бьёт_прочие_слова_в_том_же_основании():
    import band_basis as bb

    name, _ = bb.classify("экспертная вилка; сверено с дистрибьютором и с ebay")
    assert name == "мнение: экспертная вилка", (
        "запись, назвавшая себя мнением, не перестаёт им быть от слова «дистрибьютор» рядом")
    assert bb.classify("retail: продавец $326.50")[0] == "цена продавца: розница или дистрибьютор"
    assert bb.classify("")[0] == "основание не записано"


def test_счёт_по_классам_сходится_с_итогом():
    d = doc()
    s = sum(v["usd_exposure"] for v in d["by_basis"].values())
    assert abs(s - d["usd_exposure"]) < 1.0, "деньги по классам основания не сходятся с итогом"
    n = sum(v["records"] for v in d["by_basis"].values())
    assert n == d["records"]


def test_доля_не_найденной_цены_считается_из_тех_же_чисел():
    d = doc()
    want = d["usd_on_opinion"] + d["usd_on_transfer"]
    assert abs(100 * want / d["usd_exposure"] - d["share_not_a_found_price"]) < 0.11, (
        "доля напечатана словами, а не посчитана из тех же слагаемых")
    assert 0 <= d["share_not_a_found_price"] <= 100


def test_закрытое_перепроверкой_названо_и_не_больше_самого_мнения():
    d = doc()
    cl = d["closed_by_reverify"]
    assert cl["usd_exposure"] <= d["usd_on_opinion"] + d["usd_on_transfer"] + 1.0, (
        "перепроверка не может закрыть больше денег, чем стояло на мнении и переносе")
    assert cl["records"] >= 0


def test_набор_говорит_что_он_не_упрёк_разведке():
    t = (doc().get("what_it_is_not") or "").lower()
    assert "не" in t and ("эксперт" in t or "упрёк" in t), (
        "набор обязан сказать, что экспертная вилка нормальна как рабочая оценка: иначе "
        "замер прочитают как обвинение, а он про другое")
