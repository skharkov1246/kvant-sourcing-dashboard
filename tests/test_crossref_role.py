# ── Роль ─────────────────────────────────────────────────────────────────────

def test_коды_роли_закрытый_список_из_причин():
    assert len(crossref.КОДЫ_РОЛИ) == sum(len(v) for v in offer_role.ПРИЧИНЫ.values())
    for код, (роль, почему) in crossref.КОДЫ_РОЛИ.items():
        assert почему in offer_role.ПРИЧИНЫ[роль]
        assert crossref.код_роли({"role": роль, "why": почему}) == код


def test_роль_против_бренда_пары(снимок):
    п = пары(снимок)
    o = по_компании(п["zx100~zentrix"])
    роль = {c: crossref.КОДЫ_РОЛИ[x["h"]] for c, x in o.items()}
    assert роль["101"] == (offer_role.ПРЯМОЕ, "имя: тот же бренд")
    assert роль["102"] == (offer_role.ТРЕЙДЕР, "признак трейдера в имени")
    # Домен компании — из идентификаторов реестра по сущности.
    assert роль["103"] == (offer_role.ПРЯМОЕ, "домен: тот же бренд")
    assert роль["104"] == (offer_role.НЕ_ОПРЕДЕЛЕНО, "нет компании")
    assert п["zx100~zentrix"]["dr"] == 2
    # Пара без бренда: «не определено», прямых нет — поля dr нет вовсе.
    без = п["qq1"]
    assert без.get("bw") == "нет" and "dr" not in без
    assert crossref.КОДЫ_РОЛИ[без["list"][0]["h"]] == (offer_role.НЕ_ОПРЕДЕЛЕНО, "нет бренда позиции")


