# ── Корзина: оговорки номерами ───────────────────────────────────────────────

def test_оговорки_в_корзине_номерами(снимок):
    до = copy.deepcopy(снимок)
    ключи = crossref.разложить(снимок)
    assert снимок == до, "разложить не меняет снимок"
    пары_ = пары(снимок)
    проверено = 0
    for k in crossref.КЛЮЧИ_КОРЗИН:
        корзина = ключи[k]
        for ид, подробно in корзина["positions"].items():
            for o, исходное in zip(подробно["list"], пары_[ид]["list"]):
                if "j" in исходное:
                    assert all(isinstance(x, int) for x in o["j"])
                    assert [корзина["notes"][x] for x in o["j"]] == исходное["j"]
                    проверено += 1
        if "notes" in корзина:
            assert len(set(корзина["notes"])) == len(корзина["notes"])
    assert проверено == 4
