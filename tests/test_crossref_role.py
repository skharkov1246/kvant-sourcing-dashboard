def строка(ключ, компания, *, дата_откуда=None, примечание=None, страна=None, файл=None, **kw):
    """Строка ПРЕДЛОЖЕНИЯ_SQL с хвостом: файл, откуда дата, примечание, страна."""
    kw.setdefault("дата", Д)
    return _строка(ключ, ключ.upper(), компания, **kw) + (файл, дата_откуда, примечание, страна)


