"""Роль предложения и приведённая цена в снимке номенклатуры (library/crossref.py).

Корпус придуман (CLAUDE.md, правило 18): Zentrix и Kvarcton — выдуманные бренды,
компании и коды тоже; ряды индексов сочинены круглыми, чтобы ответ считался
руками.

Что защищается:
  · роль судится против бренда ПАРЫ (П2), а у пары без бренда — «не определено:
    нет бренда позиции»; домен компании доезжает из идентификаторов реестра;
  · dr — прямых у пары по ВСЕМ предложениям, а не по показанным 25;
  · приведённая цена — ровно price_norm, без домножений сверх него: НДС по дате
    цены, индекс валюты, базис только признаком; без даты цена не приводится;
  · правило 0: новые поля ничего не отнимают — снимок без них тот же, что прежде;
  · оговорки в корзине — номерами в её notes, и номер разворачивается в ту же фразу.
"""
