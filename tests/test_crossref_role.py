def test_рубли_с_ндс_делятся_на_ставку_даты_и_индексируются(снимок):
    o = по_компании(пары(снимок)["zx100~zentrix"])["101"]
    # 122 / 1,22 = 100 (ставка 2026 года) × 105/100 = 105; FCA — стандартный.
    assert o["i"] == [105.0, 1.05, 1, 0.22]
    assert o["p"] == 122.0, "исходная цена остаётся как была"
    assert any(x.startswith("НДС 22 % снят") for x in o["j"])


def test_нестандартный_базис_и_валюта_без_ряда_с_оговорками(снимок):
    o = по_компании(пары(снимок)["zx100~zentrix"])
    # EUR, DAP: НДС не назван — без НДС с оговоркой; индекс 204/200 = 1,02.
    assert o["102"]["i"] == [208.08, 1.02, 0, None]
    assert any("DAP — не стандартный" in x for x in o["102"]["j"])
    assert any(x.startswith("не сказано, с НДС") for x in o["102"]["j"])
    # Валюты нет в рядах — цена не индексируется, и это сказано.
    assert o["103"]["i"] == [10.0, None, None, None]
    assert any("индекса цен для валюты XYZ нет" in x for x in o["103"]["j"])
    # Без цены — приведения нет.
    assert "i" not in o["104"] and "j" not in o["104"]


def test_без_даты_цена_не_приводится_а_от_дня_разбора_с_оговоркой():
    s = собрать([строка("qq1", "103", цена=5, валюта="RUB", дата=None)])
    o = s["positions"][0]["list"][0]
