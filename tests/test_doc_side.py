"""Сторона документа по названию поля: кто автор файла.

ЗАЧЕМ ЭТО ВООБЩЕ ПРОВЕРЯТЬ. Пока сторона не различается, позиции НАШЕГО
исходящего ТКП считаются нашим спросом и попадают в знаменатель «по скольким
позициям мы не получили цену». Это та же тавтология, что и с предложениями
поставщиков (CLAUDE.md, правило 1), только слоем глубже, и цена её — искажённое
число в отчёте владельцу.

Проверяется то, что даёт НЕВЕРНУЮ сторону:

1. ПОРЯДОК ОБРАЗЦОВ. «Processed file for supplier» — НАШ файл, отправленный
   поставщику. По слову supplier он уезжает во входящие, если «наше исходящее» не
   проверено раньше. Ровно эту ошибку чинит порядок в gt/tools/bitrix_tkp.py, и
   она обязана остаться починенной.
2. ТОЧНОЕ СОВПАДЕНИЕ СИЛЬНЕЕ ОБРАЗЦА. Словарь собран по живым названиям, образец
   — обобщение; обобщение не должно перебивать факт.
3. «НЕИЗВЕСТНО» НЕ СПРОС. Записав неопознанное поле в спрос, мы вернули бы
   тавтологию через чёрный ход, и заметить это было бы нечем.
4. ТРИ КОНТУРА ОДНОГО ЗНАНИЯ НЕ ДОЛЖНЫ РАСХОДИТЬСЯ. Словарь здесь — перенос из
   base/file_cards.py; расхождение проверяется сверкой с тем файлом.

Названия полей — настройки нашего же Битрикса, не данные заказчиков.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

from library import doc_side as ds

ROOT = Path(__file__).resolve().parents[1]


def test_наш_файл_для_поставщика_не_входящее():
    """Главная ловушка порядка: по слову supplier файл уехал бы к поставщику."""
    assert ds.сторона("Processed file for supplier") == ds.МЫ
    assert not ds.это_спрос("Processed file for supplier")
    # А настоящее входящее — к поставщику.
    assert ds.сторона("Offer from supplier(s)") == ds.ПОСТАВЩИК


def test_наше_исходящее_предложение_не_спрос():
    """Позиции нашего ТКП — это то, что мы уже прокотировали, а не заявка."""
    for имя in ("Result, ТКП", "Offer from us", "Образец ТКП", "Result file"):
        assert ds.сторона(имя) == ds.МЫ, имя
        assert not ds.это_спрос(имя), имя


def test_наша_экономика_не_спрос_и_не_наше_предложение():
    """Экономика проекта — внутренний документ: там наша себестоимость."""
    assert ds.сторона("Economics of the project") == ds.ВНУТРЕННИЙ
    assert not ds.это_спрос("Economics of the project")


def test_заявка_заказчика_и_есть_спрос():
    for имя in ("Техническая спецификация", "Technical data from customer",
                "Customer request for automatic processing", "Specification (file)"):
        assert ds.сторона(имя) == ds.ЗАКАЗЧИК, имя
        assert ds.это_спрос(имя), имя


def test_неопознанное_поле_не_становится_спросом():
    """Точность против полноты: неопознанное видно числом, а не растворено в спросе."""
    for имя in ("Какое-то новое поле", "Tender platform", "", None, "   "):
        assert ds.сторона(имя) == ds.НЕИЗВЕСТНО, имя
        assert not ds.это_спрос(имя), имя


def test_точное_совпадение_сильнее_образца():
    """«Documents, Bot» — заказчик по словарю, хотя ни один образец его не ловит."""
    assert "Documents, Bot" in ds.ПО_НАЗВАНИЮ
    assert ds.сторона("Documents, Bot") == ds.ЗАКАЗЧИК
    # Проверка, что это не случайное срабатывание образца: без словаря было бы
    # «неизвестно».
    assert not any(о.search("Documents, Bot") for о, _ in ds.ПО_ОБРАЗЦУ)


def test_образец_ловит_названия_вне_словаря():
    """Новое написание известного документа не должно становиться «неизвестно»."""
    assert ds.ПО_НАЗВАНИЮ.get("Result, ТКП (копия)") is None
    assert ds.сторона("Result, ТКП (копия)") == ds.МЫ
    assert ds.сторона("Экономика проекта, файл") == ds.ВНУТРЕННИЙ


def test_словарь_не_разошёлся_с_офлайн_контуром():
    """Словарь — перенос из base/file_cards.py. Расхождение стоило бы перевода.

    Сверяется не побуквенно: в офлайн-контуре есть названия, которых у нас нет, и
    это нормально. Проверяется, что ни одно ОБЩЕЕ название не получило другую
    сторону — именно такое расхождение и есть молчаливая ошибка.
    """
    текст = (ROOT / "base" / "file_cards.py").read_text(encoding="utf-8")
    m = re.search(r"SIDE_BY_FIELD = \{(.*?)\n\}", текст, re.S)
    assert m, "в base/file_cards.py больше нет SIDE_BY_FIELD"
    их = dict(re.findall(r'"([^"]+)":\s*"([^"]+)"', m.group(1)))
    assert len(их) >= 29, f"разобрано мало строк: {len(их)}"
    расхождения = {имя: (наша, их[имя]) for имя, наша in ds.ПО_НАЗВАНИЮ.items()
                   if имя in их and их[имя] != наша}
    assert not расхождения, f"одно название — две стороны: {расхождения}"


def test_сторона_всегда_из_закрытого_списка():
    """Иначе колонка в базе примет что угодно, а проверка схемы промолчит."""
    for имя in list(ds.ПО_НАЗВАНИЮ) + ["чужое", "", None, "Result, ТКП (копия)"]:
        assert ds.сторона(имя) in ds.СТОРОНЫ, имя


@pytest.mark.parametrize("сторона_", ds.СТОРОНЫ)
def test_каждая_сторона_достижима(сторона_):
    """Сторона, которую нельзя получить, — мёртвая ветка правила."""
    if сторона_ == ds.НЕИЗВЕСТНО:
        assert ds.сторона("заведомо чужое название") == сторона_
        return
    assert сторона_ in set(ds.ПО_НАЗВАНИЮ.values()), сторона_
