def test_все_поля_сделки_из_описи_в_карте():
    """Каждое файловое поле сделки, встреченное в описи, получает папку по коду."""
    опись = json.loads((ROOT / "gt" / "data" / "bitrix_tkp_index.json").read_text(encoding="utf-8"))
    коды = {r["field"] for охват in опись["scopes"].values() for r in охват.get("inventory", [])
            if str(r.get("origin", "")).startswith("сделка")}
    assert len(коды) >= 16
    assert коды <= set(dfo.ПО_КОДУ[dfo.СДЕЛКА]), коды - set(dfo.ПО_КОДУ[dfo.СДЕЛКА])


@pytest.mark.parametrize("сущность,происхождение", [(dfo.СП166, СП), (dfo.СДЕЛКА, СД)])
def test_путь_по_названию_согласован_с_кодом(сущность, происхождение):
    """Если код поля когда-нибудь сменится, запасной путь по его названию обязан
    дать ту же папку — только с меньшей уверенностью."""
    for код, (папка, название) in dfo.ПО_КОДУ[сущность].items():
        if папка == dfo.НЕ_ОПРЕДЕЛЕНО:
            continue
        п, ув, почему = dfo.определить(происхождение, "ufCrm_неизвестный", название)
        assert п == папка, (код, название, п)
        assert ув < 1.0 and "назван" in почему, (код, ув, почему)


