def test_все_восемь_полей_сп166_по_коду():
    ждём = {
        "ufCrm18_1700698211875": dfo.ПРЕДЛОЖЕНИЕ_ПОСТАВЩИКА,
        "ufCrm18_1703711961310": dfo.ПРЕДЛОЖЕНИЕ_ПОСТАВЩИКА,
        "ufCrm18_1703712059311": dfo.ПРЕДЛОЖЕНИЕ_ПОСТАВЩИКА,
        "ufCrm18_1703712074559": dfo.ПРЕДЛОЖЕНИЕ_ПОСТАВЩИКА,
        "ufCrm18_1731179998": dfo.ПРЕДЛОЖЕНИЕ_ПОСТАВЩИКА,
        ЗАПРОС_ФАЙЛ: dfo.НАШ_ЗАПРОС,
        "ufCrm18_1730999038678": dfo.ТЕХДОК,
        "ufCrm18_1730999106096": dfo.РЕКВИЗИТЫ,
    }
    for код, папка in ждём.items():
        # Название нарочно ложное: по коду оно не спрашивается вовсе.
        assert dfo.определить(СП, код, "заведомо чужое название") == (
            папка, 1.0, "код поля (СП-166)"), код
    assert set(dfo.ПО_КОДУ[dfo.СП166]) == set(ждём)


def test_request_file_на_карточке_это_наш_запрос():
    """Главная коллизия: словари сторон по названию ставят «заказчик», а на
    карточке СП-166 в этом поле лежит наш исходящий запрос."""
    assert ds.сторона("Request file") == ds.ЗАКАЗЧИК          # словарь сторон — как был
    assert dfo.папка(СП, ЗАПРОС_ФАЙЛ, "Request file")[0] == dfo.НАШ_ЗАПРОС
    # И запасным путём по названию на карточке — тоже наш запрос.
    п, ув, _ = dfo.определить(СП, "ufCrm18_0000000000", "Request file")
    assert (п, ув) == (dfo.НАШ_ЗАПРОС, dfo.УВ_НАЗВАНИЕ)


def test_сторона_сделки_не_меняется():
    """doc_side питает замеры спроса (lib_files.side): ни одно название не
    получило другую сторону."""
    for название, сторона in ds.ПО_НАЗВАНИЮ.items():
        assert ds.сторона(название) == сторона, название


@pytest.mark.parametrize("происхождение,код", [
    (СД, "ufCrm_0000000000"), (СД, None), (None, None), ("задача", "ufCrm18_0000000000")])
def test_request_file_вне_карточки_не_наследует_ошибку_словаря(происхождение, код):
    """Словарь сторон ставит «Request file» заказчику — это признанная ошибка
    (base/suppliers.py, tests/test_supplier_evidence_side.py): поле держит наш
    исходящий файл. Вне карточки СП-166 папка — наш запрос, но с уверенностью
    образца, а не точного названия: направление известно по заметкам, а не по
    работе с полем. Прежде папка шла за стороной словаря — запрос заказчика."""
    assert ds.сторона("Request file") == ds.ЗАКАЗЧИК          # словарь сторон — как был
    п, ув, почему = dfo.определить(происхождение, код, "Request file")
    assert (п, ув) == (dfo.НАШ_ЗАПРОС, dfo.УВ_ОБРАЗЕЦ), (п, ув, почему)
    assert п != dfo.ПАПКА_ПО_СТОРОНЕ[ds.сторона("Request file")]
    assert "Request file" not in почему and len(почему) <= 60
    # Точное название весит больше образца, а ослабленное — не больше образца:
    # «Request file (old)» и «Request file» теперь одного веса и одной папки.
    assert dfo.определить(происхождение, код, "Request file (old)")[:2] == (п, ув)


def test_result_file_сделки_без_папки_пока_направление_не_установлено():
    """«Result file» — наше ТКП или нет, в репозитории не установлено: вопрос
    владельцу не отвечен (gt/tools/ship_brief.py), gt/tools/ship_offer.py гадать
    запрещает. Папка «наше предложение» с уверенностью 1.0 выдавала догадку по
    названию за факт системы — и сверка с содержимым её уже не поправила бы."""
    assert ds.сторона("Result file") == ds.МЫ                 # словарь сторон — как был
    п, ув, почему = dfo.определить(СД, "ufCrm_1780061070", "Result file")
    assert (п, ув) == (dfo.НЕ_ОПРЕДЕЛЕНО, 0.0)
    assert почему == "код поля (сделка): направление не установлено", почему
    # Оба написания кода и запасной путь по названию — тоже без папки.
    assert dfo.определить(СД, "UF_CRM_1780061070", None)[:2] == (dfo.НЕ_ОПРЕДЕЛЕНО, 0.0)
    п, ув, почему = dfo.определить(СД, "ufCrm_неизвестный", "Result file")
    assert (п, ув) == (dfo.НЕ_ОПРЕДЕЛЕНО, 0.0) and "направление не установлено" in почему


def test_у_каждого_поля_без_папки_своя_причина():
    """Разнородное поле папки не получит никогда, поле с неустановленным
    направлением — как только владелец ответит: причины разные, и в базе их
    надо различать."""
    без_папки = {(с, к) for с, поля in dfo.ПО_КОДУ.items()
                 for к, (п, _) in поля.items() if п == dfo.НЕ_ОПРЕДЕЛЕНО}
    assert без_папки == set(dfo.ПОЧЕМУ_БЕЗ_ПАПКИ)
    for (с, к), причина in dfo.ПОЧЕМУ_БЕЗ_ПАПКИ.items():
        происхождение = {dfo.СП166: СП, dfo.СДЕЛКА: СД}[с]
        assert dfo.определить(происхождение, к, None) == (
            dfo.НЕ_ОПРЕДЕЛЕНО, 0.0, f"код поля ({с}): {причина}")


