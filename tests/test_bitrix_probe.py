"""Зонд обязан отвечать на свой вопрос, а не подтверждать гипотезу.

Зонд разовый: каждый выпуск отвечает на вопрос своего дня, и вместе с ним
переписываются его проверки. v44 выбирал между двумя причинами непрочитанных
вложений; v45 отвечает на другой вопрос — какой след в Битриксе указывает на
живого сорсера, когда карточку запроса завёл робот, а сделку ведёт КАМ.

Мерить тут нечего, кроме двух чистых функций, и обе несущие. `след` решает,
какой признак мы объявим надёжным: если он зачтёт пустое значение за
заполненное или спутает «указывает на сотрудника отдела» с «просто заполнено»,
зонд назовёт надёжным негодный след — и восстановление исполнителя будет
построено на нём. `доля` печатает результат, и её ошибка на нулевом знаменателе
уронила бы прогон ровно там, где ответ «ни одной такой карточки нет» сам по себе
и есть результат.

Корпус придуман, а не взят из портала, как велят правила репозитория.
"""
from __future__ import annotations

import sys
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT))
# зонд берёт константы портала из config.py, а тот тянет python-dotenv
sys.modules.setdefault("dotenv", types.SimpleNamespace(load_dotenv=lambda *a, **k: None))


def probe():
    import bitrix_probe
    return bitrix_probe


ОТДЕЛ = {"11", "12", "13"}           # придуманный отдел поиска поставщиков
КАРТОЧКИ = [
    # ответственный в отделе, двигал он же
    {"assignedById": 11, "createdBy": 99, "movedBy": 11, "updatedBy": ""},
    # ответственный КАМ, а двигал сорсер — такую карточку и надо вернуть отделу
    {"assignedById": 50, "createdBy": 99, "movedBy": 12, "updatedBy": 12},
    # ответственный КАМ, следов отдела нет вовсе
    {"assignedById": 51, "createdBy": 99, "movedBy": 51, "updatedBy": None},
    # пустые значения во всех видах, какие отдаёт портал
    {"assignedById": 13, "createdBy": 0, "movedBy": "0", "updatedBy": "None"},
]


def test_пустое_значение_не_считается_заполненным():
    """Портал отдаёт пустоту четырьмя видами: '', None, 0 и строкой 'None'.
    Зачесть любой из них за заполненный след значит завысить его надёжность."""
    p = probe()
    есть, _, _ = p.след(КАРТОЧКИ, "updatedBy", ОТДЕЛ)
    assert есть == 1, "заполнен updatedBy ровно у одной карточки"
    есть, _, _ = p.след(КАРТОЧКИ, "createdBy", ОТДЕЛ)
    assert есть == 3, "ноль — это не автор"
    есть, _, _ = p.след(КАРТОЧКИ, "movedBy", ОТДЕЛ)
    assert есть == 3, "строка «0» — тоже пустота"


def test_заполненность_и_попадание_в_отдел_считаются_отдельно():
    """Поле, заполненное у всех карточек, бесполезно, если показывает КАМа."""
    p = probe()
    есть, в_отделе, _ = p.след(КАРТОЧКИ, "createdBy", ОТДЕЛ)
    assert (есть, в_отделе) == (3, 0), "createdBy заполнен, но в отдел не ведёт"
    есть, в_отделе, _ = p.след(КАРТОЧКИ, "movedBy", ОТДЕЛ)
    assert (есть, в_отделе) == (3, 2)


def test_отличие_от_ответственного_считается_по_значению_а_не_по_наличию():
    p = probe()
    _, _, иначе = p.след(КАРТОЧКИ, "movedBy", ОТДЕЛ)
    assert иначе == 1, "movedBy отличается от ответственного ровно у одной карточки"
    _, _, иначе = p.след(КАРТОЧКИ, "assignedById", ОТДЕЛ)
    assert иначе == 0, "поле не может отличаться само от себя"


def test_число_приводится_к_строке_перед_сравнением():
    """Портал отдаёт идентификатор то числом, то строкой; состав отдела —
    строками. Без приведения след «в отдел» оказался бы нулевым всегда."""
    p = probe()
    _, в_отделе, _ = p.след([{"assignedById": 11, "movedBy": 11}], "movedBy", ОТДЕЛ)
    assert в_отделе == 1
    _, в_отделе, _ = p.след([{"assignedById": "11", "movedBy": "11"}], "movedBy", ОТДЕЛ)
    assert в_отделе == 1


def test_доля_не_падает_на_пустой_выборке():
    """«Ни одной такой карточки» — это результат замера, а не повод уронить прогон."""
    p = probe()
    assert p.доля(0, 0) == "0/0"
    assert p.доля(1, 2) == "1/2 (50 %)"
    assert p.доля(2, 3).startswith("2/3 (67 %)")
