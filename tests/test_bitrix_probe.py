"""Зонд обязан отвечать на свой вопрос, а не подтверждать гипотезу.

Зонд разовый: каждый выпуск отвечает на вопрос своего дня, и вместе с ним
переписываются его проверки. v47 выясняет, откуда у руководителя отдела поиска
поставщиков сотни запросов: записан ли он ответственным в самом Битриксе или
получил их через цепочку восстановления исполнителя.

Несущие здесь две классификации. `роль` решает, кем приходится запись, и если
она спутает руководителя с рядовым сотрудником отдела (он ведь тоже числится в
отделе), ответ «кто создал его карточки» потеряет смысл. `сорсер_сделки`
решает, выступает ли руководитель раздатчиком: ошибка в пустом значении или в
множественном поле выдала бы «сорсер не заполнен» там, где он есть.

Корпус придуман, а не взят из портала, как велят правила репозитория.
"""
from __future__ import annotations

import sys
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT))
# зонд берёт константы портала из config.py, а тот тянет python-dotenv
sys.modules.setdefault("dotenv", types.SimpleNamespace(load_dotenv=lambda *a, **k: None))


def probe():
    import bitrix_probe
    return bitrix_probe


РУКОВОДИТЕЛЬ = "76"
ОТДЕЛ = {"76", "77", "78"}                  # руководитель тоже числится в отделе
РОБОТЫ = {"234", "542"}
ПОЛЕ = "UF_CRM_1779187335"


def test_руководитель_не_смешивается_с_сотрудниками_отдела():
    p = probe()
    assert p.роль(76, РУКОВОДИТЕЛЬ, ОТДЕЛ, РОБОТЫ) == "сам руководитель"
    assert p.роль("77", РУКОВОДИТЕЛЬ, ОТДЕЛ, РОБОТЫ) == "сотрудник отдела"


def test_роль_различает_робота_постороннего_и_пустоту():
    p = probe()
    assert p.роль("234", РУКОВОДИТЕЛЬ, ОТДЕЛ, РОБОТЫ) == "служебная запись"
    assert p.роль("90", РУКОВОДИТЕЛЬ, ОТДЕЛ, РОБОТЫ) == "вне отдела"
    for пусто in ("", None, 0, "0", "None"):
        assert p.роль(пусто, РУКОВОДИТЕЛЬ, ОТДЕЛ, РОБОТЫ) == "без автора", пусто


def test_сорсер_сделки_отличает_раздатчика_от_исполнителя():
    p = probe()
    assert p.сорсер_сделки(None, ПОЛЕ, РУКОВОДИТЕЛЬ, ОТДЕЛ) == "сделки нет"
    assert p.сорсер_сделки({ПОЛЕ: ""}, ПОЛЕ, РУКОВОДИТЕЛЬ, ОТДЕЛ) == "«Сорсер» не заполнен"
    assert p.сорсер_сделки({ПОЛЕ: 76}, ПОЛЕ, РУКОВОДИТЕЛЬ, ОТДЕЛ) == "«Сорсер» — сам руководитель"
    assert p.сорсер_сделки({ПОЛЕ: "78"}, ПОЛЕ, РУКОВОДИТЕЛЬ, ОТДЕЛ) == "«Сорсер» — другой сотрудник отдела"
    assert p.сорсер_сделки({ПОЛЕ: "90"}, ПОЛЕ, РУКОВОДИТЕЛЬ, ОТДЕЛ) == "«Сорсер» — вне отдела"


def test_множественное_поле_сорсера_берёт_первого_непустого():
    p = probe()
    assert p.сорсер_сделки({ПОЛЕ: ["0", "", "78"]}, ПОЛЕ, РУКОВОДИТЕЛЬ, ОТДЕЛ) == \
        "«Сорсер» — другой сотрудник отдела"
    assert p.сорсер_сделки({ПОЛЕ: []}, ПОЛЕ, РУКОВОДИТЕЛЬ, ОТДЕЛ) == "«Сорсер» не заполнен"


def test_доля_не_падает_на_пустой_выборке():
    """«Ни одной такой карточки» — это результат замера, а не повод уронить прогон."""
    p = probe()
    assert p.доля(0, 0) == "0/0"
    assert p.доля(1, 2) == "1/2 (50 %)"
