"""Обход портала делится на части без пропусков и без нахлёста.

ЗАЧЕМ. Распоряжение владельца, 22.09.2026: «никогда не бери сразу так много,
всегда дели минимум на 10, а если большие — то и на 50 частей». Сказано после
того, как полный переразбор 5 640 предложений пошёл ОДНОЙ частью и упал через
сорок минут, потеряв всё несделанное время.

ПОЧЕМУ ДИАПАЗОНЫ, А НЕ ОСТАТОК ОТ ДЕЛЕНИЯ. Обход идёт по возрастанию ключа
(bx_all_by_id: filter[>id] = последний прочитанный), поэтому прочитать «каждую
двенадцатую карточку» нельзя — можно только смежный кусок. С остатком от деления
каждая часть всё равно листала бы все страницы, и двенадцать частей дали бы
двенадцать полных обходов портала: HTTP 429, на котором 21.09.2026 умерли все
двенадцать частей.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, И ПОЧЕМУ ИМЕННО ЭТО. Ошибка в границах не падает, а МОЛЧА
теряет данные: пропуск между частями — это карточки, которых не увидел никто, а
нахлёст — это двойная работа и двойная запись. Ни то, ни другое не заметно по
журналу прогона, который у каждой части свой.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "library"))

import indexer  # noqa: E402


def покрытие(макс: int, частей: int) -> list[int]:
    """Сколько частей видят каждый идентификатор от 1 до макс."""
    счёт = [0] * (макс + 1)
    for i in range(частей):
        низ, верх = indexer.диапазон_части(макс, i, частей)
        верх = макс if верх is None else верх
        for x in range(низ + 1, верх + 1):
            if x <= макс:
                счёт[x] += 1
    return счёт[1:]


@pytest.mark.parametrize("частей", [2, 10, 12, 25, 50])
@pytest.mark.parametrize("макс", [21865, 1000, 97, 50, 7])
def test_каждый_ключ_достаётся_ровно_одной_части(макс, частей):
    """Пропуск — потерянные данные, нахлёст — двойная запись."""
    счёт = покрытие(макс, частей)
    пропуски = [i + 1 for i, c in enumerate(счёт) if c == 0]
    нахлёсты = [i + 1 for i, c in enumerate(счёт) if c > 1]
    assert not пропуски, f"не увидел никто: {пропуски[:10]} (всего {len(пропуски)})"
    assert not нахлёсты, f"увидели дважды: {нахлёсты[:10]} (всего {len(нахлёсты)})"


def test_одна_часть_читает_всё_без_границ():
    """Без разбиения границы не ставятся вовсе — обход остаётся прежним."""
    assert indexer.диапазон_части(21865, 0, 1) == (0, None)
    # И при неизвестном максимуме тоже: нечего делить.
    assert indexer.диапазон_части(0, 3, 12) == (0, None)


def test_последняя_часть_забирает_хвост():
    """Иначе карточки, добавленные между замером максимума и обходом, пропадут."""
    низ, верх = indexer.диапазон_части(21865, 11, 12)
    assert верх == 21865
    # А в середине граница конечна — иначе части перекрылись бы.
    assert indexer.диапазон_части(21865, 5, 12)[1] is not None


def test_обход_принимает_границы_диапазона(monkeypatch):
    """Границы обязаны доезжать до самого запроса, а не оставаться в расчёте.

    Проверяется то, что уходит в портал, а не написание строки в исходнике:
    перестановка кода при том же поведении проверку не роняет."""
    import inspect
    подпись = inspect.signature(indexer.bx_all_by_id).parameters
    assert "с_id" in подпись and "до_id" in подпись
    фильтры = []

    def bx(method, params):
        фильтры.append(dict(params["filter"]))
        return {"result": {"items": []}}

    monkeypatch.setattr(indexer, "bx", bx)
    indexer.bx_all_by_id("crm.item.list", {"entityTypeId": 166}, с_id=40, до_id=80)
    assert фильтры == [{">id": 40, "<=id": 80}], "границы не ушли в фильтр портала"
    # старый метод: ключ заглавными, нижняя граница может прийти и в фильтре
    фильтры.clear()
    monkeypatch.setattr(indexer, "bx", lambda m, p: (фильтры.append(dict(p["filter"])),
                                                     {"result": []})[1])
    indexer.bx_all_by_id("crm.deal.list", {"filter": {">ID": 7, "<=ID": 9}}, ключ="ID")
    assert фильтры == [{">ID": 7, "<=ID": 9}]
