"""Объём закупки нельзя назвать, пока он не измерен — и оговорка обязана стоять рядом.

Владелец спросил прямо: какой объём продаж и какой объём закупки. Соблазн —
сложить все найденные цены и назвать сумму. Это дало бы «объём закупки», который
на три четверти состоит из цен, за которые никто не продаст: запрос брокера,
одна витрина под двумя доменами, цена без подтверждённого покрытия объёма.

Здесь закрыты два свойства замера. Первое: строка, чью цену перепроверка не
смотрела, в сумму закупки не идёт НИКОГДА — именно в таких ценах жили заглушки
(0.00 при «нет в наличии», одно значение на 132 разнородных изделиях). Второе:
сальдо счётной доли обязано ехать вместе с оговоркой о смещении выборки, потому
что тринадцать строк из восьмисот пятидесяти семи — перечень, а не выборка, и
всё сальдо там делает одна строка.

Корпус придуман, а не взят из набора.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "gt/tools"))


def mg():
    import ship_margin
    return ship_margin


def test_разряды_покрывают_все_строки_с_нашей_ценой():
    m = mg()
    doc = m.build()
    assert sum(v["rows"] for v in doc["by_grade"].values()) == doc["sales_rows"]
    assert abs(sum(v["sales_usd"] for v in doc["by_grade"].values()) - doc["sales_usd"]) < 1.0


def test_в_сумму_закупки_идёт_только_счётный_разряд():
    m = mg()
    doc = m.build()
    good = doc["by_grade"]["в сумму идёт"]
    assert doc["countable"]["purchase_usd"] == good["purchase_usd"]
    assert doc["countable"]["rows"] == good["rows"]


def test_у_каждого_разряда_сказано_что_он_значит():
    m = mg()
    doc = m.build()
    for name, v in doc["by_grade"].items():
        assert v["what_it_means"], f"разряд {name} без объяснения"


def test_оговорка_о_смещении_выборки_стоит_рядом_с_сальдо():
    m = mg()
    doc = m.build()
    b = doc["bias_warning"]
    assert "не является маржой сделки" in b["why"] or "НЕ является маржой" in b["why"]
    assert b["rows_sales_above_purchase"] + b["rows_sales_below_purchase"] == \
        doc["countable"]["rows"], "строки счётного разряда должны делиться на две стороны нацело"
    assert b["largest_single_row"], "самая крупная строка сальдо обязана быть названа"


def test_объём_закупки_по_заявке_в_целом_не_назван():
    """Набор не должен содержать поля, которое читалось бы как «закупка по всей
    заявке»: такого числа нет, и появись оно — его сложат."""
    m = mg()
    doc = m.build()
    assert "purchase_usd" not in doc, "итоговая закупка по заявке названа быть не может"
    assert "назван быть не может" in doc["what_it_is_not"]
