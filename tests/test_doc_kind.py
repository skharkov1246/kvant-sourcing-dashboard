def _прогон(корпус):
    return [(ид, ждали, разложить(т, с, поле)) for ид, ждали, поле, т, с in корпус]


def _матрица(корпус) -> Counter:
    return Counter((ждали, получили) for _, ждали, (получили, _, _) in _прогон(корпус))


