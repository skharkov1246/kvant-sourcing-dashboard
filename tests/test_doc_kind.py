def _по_ид(ид):
    for строка in НАСТРОЙКА:
        if строка[0] == ид:
            return строка
    raise KeyError(ид)


def test_наше_ткп_в_поле_поставщика_остаётся_нашим():
    """Поле «КП поставщика» заполнено нашим ТКП: бланк и подпись перевешивают поле."""
    _, _, поле, т, с = _по_ид("н2 наше ТКП в поле поставщика")
    папка, ув, почему = разложить(т, с, поле)
    assert папка == dk.НАШЕ_ПРЕДЛОЖЕНИЕ, почему
    # Поле при этом учтено и названо — иначе разбор ошибки не увидит спора.
    assert "поле «поставщик»" in почему
    # Без подсказки поля уверенность выше: поле спорило с содержимым.
    _, ув_без_поля, _ = разложить(т, с, None)
    assert ув_без_поля > ув


