def test_порог_в_безошибочном_окне():
    """Порог меряется таблицей (CLAUDE.md, правило 4): на всём корпусе при ПОРОГ
    нет неверных папок, а чуть ниже — уже есть. Значит, порог не завышен зря и не
    занижен до ошибок."""
    весь = НАСТРОЙКА + ПРОВЕРКА

    def неверных(порог):
        прежний = dk.ПОРОГ
        dk.ПОРОГ = порог
        try:
            return sum(1 for _, ждали, (п, _, _) in _прогон(весь)
                       if п not in (ждали, dk.НЕ_ОПРЕДЕЛЕНО))
        finally:
            dk.ПОРОГ = прежний

    assert неверных(dk.ПОРОГ) == 0
    assert неверных(0.5) > 0          # окно узкое: 0,55–0,60 — это и надо знать
    # По устройству: «внутренний расчёт» побеждает с долей ≥ любой другой, то есть
    # у остальных тогда ≤ 0,5, и порог ниже 0,5 выпустил бы их в папку.
    assert dk.ПОРОГ >= 0.5


