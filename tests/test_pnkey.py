"""Ключ номера: двойники сводятся, а не выбрасываются.

Написано 18.09.2026. Правило «оставить A–Z и 0–9» лежало в тридцати пяти
файлах и в каждом ВЫБРАСЫВАЛО кириллические буквы-двойники: «917427С1»
превращалось в «9174271» вместо «917427C1». Замер по заявке: 26 строк с таким
ключом. Корпуса придуманы, но каждая форма взята с живой строки.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "gt/tools"))

from pnkey import key  # noqa: E402


def test_двойник_сводится_к_латинице():
    """«В» кириллическая и «B» латинская дают один ключ, а не разные."""
    assert key("180В4158") == key("180B4158") == "180B4158"
    assert key("917427С1") == "917427C1"
    assert key("У808750D9J") == "Y808750D9J"


def test_порядок_важен_сведение_раньше_отсева():
    """Если отсев идёт первым, буква исчезает — это и была ошибка.

    Проверка на длине: правильный ключ на один знак длиннее испорченного.
    """
    assert len(key("1794-IВ10XOB6XT")) == len("1794IB10XOB6XT")
    assert key("1794-IВ10XOB6XT") == "1794IB10XOB6XT"


def test_латинский_номер_не_меняется():
    """Исправление не должно шевелить те 1 616 строк, где кириллицы нет."""
    for pn in ("1042018-3400", "6ES7960-1AA04-0XA0", "CT1185/8", "036505/000", "4650N-465"):
        assert key(pn) == "".join(c for c in pn.upper() if c.isalnum())


def test_пояснение_в_скобках_снимается():
    assert key("1042018-3400 (клапан)") == key("1042018-3400")


def test_разные_изделия_не_склеиваются_в_один_ключ():
    """Проза в поле номера теперь даёт разные ключи — ложный дубль распался.

    «Комплект поршня» и «К-т колец стопорных» — разные изделия одного насоса;
    прежний ключ выбрасывал из обоих всю кириллицу и оставлял «DANFOSSAPP5182».
    """
    a = key("Комплект поршня нас. Danfoss APP 5.1-8.2")
    b = key("К-т колец стопорных Danfoss APP 5.1-8.2")
    assert a != b, "разные изделия не должны иметь один ключ"


def test_пустое_значение_даёт_пустой_ключ():
    for x in (None, "", "   ", "—"):
        assert key(x) == ""
