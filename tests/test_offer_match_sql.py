def test_подзапрос_не_выполняется_заново_на_каждую_строку(cur):
    """CLAUDE.md, правило 8: коррелированную форму проверяют ПЛАНОМ.

    ПРОВЕРЯЕТСЯ СВОЙСТВО, А НЕ СПОСОБ ЕГО ДОСТИЖЕНИЯ. Первая версия теста искала
    в плане слово «Index» и падала — а план был правильный: PostgreSQL выбрал
    «hashed SubPlan», то есть выполнил подзапрос ОДИН РАЗ и сложил результат в
    хеш. Это ровно то, чего требует правило 8; индекс — лишь один из способов
    получить то же. Требовать именно индекс значит красить тест на верном коде.

    Запрещено правилом другое: повторный проход по таблице на каждую строку. В
    плане он выглядел бы как SubPlan без «hashed» — подзапрос, выполняемый заново.
    """
    м = скрипт()
    подготовь(cur, м)
    # Корпус мал, и на трёх строках планировщик выберет что угодно. Наполним
    # временные таблицы придуманными строками до объёма, где выбор осмыслен.
    cur.execute("""
        insert into ключи_заявок (deal_id, ключ)
          select 'S' || (i % 500), 'k' || i from generate_series(1, 20000) i;
        insert into строки_кп (id, deal_id, ключ, текст_ключ)
          select 1000 + i, 'S' || (i % 500), 'k' || i, '' from generate_series(1, 20000) i;
        analyze ключи_заявок; analyze строки_кп;""")
    cur.execute("explain " + м.СО_СТОРОНЫ_КП)
    план = "\n".join(r[0] for r in cur.fetchall())
    # Подзапрос либо захеширован, либо взят индексом — оба означают «один раз».
    хорошо = "hashed SubPlan" in план or "Index" in план
    assert хорошо, план
    # А повторного подзапроса на строку быть не должно: SubPlan без «hashed».
    голых = [ln for ln in план.splitlines()
             if "SubPlan" in ln and "hashed" not in ln and "->" in ln]
    assert not голых, план
