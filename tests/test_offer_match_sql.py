def подготовь(cur, м, поток=None):
    поток = поток or м.FEED
    cur.execute(м.ПОДГОТОВКА, (поток, поток))


def test_объём_считает_сделки_и_позиции_заявок(cur):
    """Ловушки 2 и 5: помеченный мусор и сделка без прочитанной заявки."""
    м = скрипт()
    подготовь(cur, м)
    cur.execute(м.ОБЪЁМ)
    строк, сделок, ключей, с_заявкой = [int(x) for x in cur.fetchone()]
    assert строк == 7
    assert сделок == 3                    # D1, D2, D3
    # Пять, а не шесть: позиция aaa444 помечена мусором и в счёт не идёт.
    assert ключей == 5
    # Две, а не три: у D3 заявка не прочитана, сопоставлять там не с чем.
    assert с_заявкой == 2


def test_разряды_со_стороны_предложения(cur):
    """Ловушка 3: совпадение в чужой сделке — отдельный разряд, не «совпало»."""
    м = скрипт()
    подготовь(cur, м)
    cur.execute(м.СО_СТОРОНЫ_КП)
    по = {r[0]: int(r[1]) for r in cur.fetchall()}
    assert по["ключ совпал в своей сделке"] == 3          # цены 1, 5, 6
    assert по["ключ совпал, но в другой сделке"] == 1     # цена 4
    assert по["артикула в строке нет"] == 1               # цена 2
    assert по["артикул есть, совпадения нет"] == 2        # цены 3, 7
    assert sum(по.values()) == 7


