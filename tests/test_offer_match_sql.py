"""Сопоставление предложения с заявкой считается двумя встречными долями.

ЗАЧЕМ. Владелец, 22.09.2026: предложения приходят «с отсылками к нашему запросу»,
и «очень важно всегда искать в каждом входящем офере сопоставление кодов».

СЧИТАТЬ НАДО ОБЕ СТОРОНЫ, И ПУТАТЬ ИХ НЕЛЬЗЯ. Со стороны предложения — какая доля
строк цены отвечает нашей позиции. Со стороны заявки — какая доля наших позиций
получила цену. Вторая важнее: это закупочная величина. Только первая даёт лестную
или, наоборот, пугающую картину без смысла — поставщик присылает прайс на тысячу
позиций, из них десять наши, доля со стороны предложения ничтожна, а заявка
закрыта полностью.

Пять ловушек, каждая даёт правдоподобное, но неверное число:

1. ЧУЖОЙ ПОТОК ЦЕН. lib_prices держит и прайсы, и таможню. Строка чужого потока,
   совпавшая с позицией заявки, объявит её прокотированной, хотя предложения по
   ней не было.
2. ПОМЕЧЕННЫЙ МУСОР В ЗАЯВКЕ. Считать надо lib_demand_live, а не lib_demand:
   пункт договора, попавший в спрос и уже помеченный мусором, иначе станет
   позицией, по которой «не получили цену», и раздует знаменатель.
3. СОВПАДЕНИЕ В ЧУЖОЙ СДЕЛКЕ. Тот же артикул спрашивали в другой заявке — это не
   ответ на нашу. Разряд отдельный, и в «совпало» он идти не должен.
4. КОД В ТЕКСТЕ, А НЕ В КОЛОНКЕ. У предложений артикул часто пуст, а код стоит
   внутри наименования. Считать только по колонке значит занизить сопоставление.
5. СДЕЛКА, У КОТОРОЙ ЗАЯВКА НЕ ПРОЧИТАНА. Сопоставлять там не с чем, и это наш
   недочёт разбора, а не свойство предложений. В долю со стороны заявки такие
   сделки не входят вовсе, и это надо видеть отдельной строкой.

Корпус придуман (CLAUDE.md, правило 18), ответы посчитаны руками.
"""
