def test_чужой_поток_не_котирует_нашу_позицию(cur):
    """Ловушка 1: строка потока «прайс» на aaa333 в счёт идти не должна.

    Проверяется сменой потока: в потоке «прайс» лежит ровно одна строка, и
    картина обязана перевернуться. Если фильтр не работает, числа не изменятся.
    """
    м = скрипт()
    подготовь(cur, м, поток="прайс")
    cur.execute(м.ОБЪЁМ)
    строк, сделок, ключей, с_заявкой = [int(x) for x in cur.fetchone()]
    assert строк == 1 and сделок == 1     # только строка прайса, только D1
    assert ключей == 3                    # заявка D1 без помеченной позиции
