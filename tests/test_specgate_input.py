"""Ворота спецификации выключаются входом прогона — как и обещает код.

В library/indexer.py стоит комментарий: «Ворота спецификации можно выключить без
выката кода». До 23.09.2026 это было невыполнимо: переменная читалась, но прогон
её не передавал, и входа не существовало. Обещание в комментарии, которого нет в
прогоне, хуже отсутствия обещания — на него рассчитывают.

Замер по всей базе: 867 файлов xlsx/docx с причиной «позиции не распознаны» плюс
118 отброшенных воротами. Сколько из них ворота держат напрасно, без выключателя
узнать нельзя.
"""
from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent


def без_комментариев(путь: str, знак: str = "#") -> str:
    текст = (КОРЕНЬ / путь).read_text(encoding="utf-8")
    return re.sub(rf"(?m)^\s*{re.escape(знак)}[^\n]*$", "", текст)


def test_ворота_передаются_прогоном():
    yml = без_комментариев(".github/workflows/library-index.yml")
    assert "specgate:" in yml, "входа нет — выключить ворота прогоном нельзя"
    assert re.search(r"SPECGATE:\s*\$\{\{\s*inputs\.specgate", yml), \
        "SPECGATE не привязан к входу"


def test_ворота_включены_по_умолчанию():
    """Выключенные ворота пускают документацию в спрос строками прозы."""
    yml = без_комментариев(".github/workflows/library-index.yml")
    шаг = yml[yml.index("specgate:"):]
    шаг = шаг[:шаг.index("pdf_one_pass:")]
    assert "default: true" in шаг, "ворота выключены по умолчанию"
    ind = без_комментариев("library/indexer.py")
    assert 'os.environ.get("SPECGATE", "1")' in ind, "в коде умолчание не «включено»"


def test_выключение_видно_в_журнале():
    """Иначе прогон молча положит в спрос прозу, и это обнаружится замером позже."""
    ind = без_комментариев("library/indexer.py")
    assert "ВОРОТА СПЕЦИФИКАЦИИ ВЫКЛЮЧЕНЫ" in ind, "выключение не называется в журнале"
    assert "не для записи в базу" in ind, "не сказано, что это только для замера"


def test_пустое_значение_входа_не_включает_ворота_молча():
    """`inputs.specgate && '1' || '0'` — ноль, а не пустая строка.

    Пустая строка в SPECGATE означала бы «включено» (код считает пустое значение
    выключенным... проверим прямо): важно, чтобы выключение доезжало однозначно.
    """
    yml = без_комментариев(".github/workflows/library-index.yml")
    assert re.search(r"SPECGATE:[^\n]*\|\|\s*'0'", yml), \
        "при выключенном входе передаётся пустая строка, а не ноль"


def test_пустое_значение_переменной_не_выключает_защиту():
    """Пустая строка получается сама: шаг, забывший подставить значение.

    У признаков-возможностей (повтор, ослабление, один проход) пустое значение
    «выключено» безопасно — возможность просто не включится. У ЗАЩИТЫ наоборот:
    пустая строка выключала ворота молча, и в спрос шла проза.
    """
    import importlib
    import os
    import sys
    sys.path.insert(0, str(КОРЕНЬ))
    import library.indexer as ix

    def при(значение):
        if значение is None:
            os.environ.pop("SPECGATE", None)
        else:
            os.environ["SPECGATE"] = значение
        importlib.reload(ix)
        return ix.SPECGATE

    try:
        assert при("") is True, "пустая строка выключила ворота"
        assert при("   ") is True, "пробелы выключили ворота"
        assert при(None) is True, "без переменной ворота должны быть включены"
        assert при("1") is True
        assert при("0") is False, "явный ноль должен выключать"
        assert при("false") is False
        assert при("FALSE") is False, "регистр не должен мешать выключению"
    finally:
        os.environ.pop("SPECGATE", None)
        importlib.reload(ix)
