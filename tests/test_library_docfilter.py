def code_of(path: Path) -> str:
    """Текст модуля без его docstring: в шапке mark_prose.py приведена команда
    отката наследования сегментов, и она не должна путаться с исполняемым кодом."""
    import ast
    src = path.read_text(encoding="utf-8")
    doc = ast.get_docstring(ast.parse(src))
    return src.replace(doc, "") if doc else src


