def test_словарь_и_структурная_колонка_защищают():
    """Инвариант кода: непустые oem/unit/qty заполняются только в табличной ветке
    разбора, значит строка пришла из таблицы и прозой быть не может."""
    d = load()
    проза = ПРОЗА[0]
    assert d.row_is_prose(*d.row_marks(проза)), "корпус прозы подобран неверно"
    assert not d.row_is_prose(*d.row_marks(проза, oem="Bosch")), "колонка oem не защищает"
    assert not d.row_is_prose(*d.row_marks(проза, unit="шт")), "колонка unit не защищает"
    assert not d.row_is_prose(*d.row_marks(проза, qty=5)), "колонка qty не защищает"
    assert not d.row_is_prose(*d.row_marks(проза, dict_hit=True)), "словарь не защищает"


def test_обвиняет_только_закрытый_список():
    """Признак «сказуемое» считается, но обвинять не может: русское описательное
    наименование по глагольным формам неотличимо от пункта договора."""
    d = load()
    assert "сказуемое" not in d.CLOSED, "глагольный признак попал в обвинение"
    только_сказуемое = "Изделие поставляется в собранном виде"
