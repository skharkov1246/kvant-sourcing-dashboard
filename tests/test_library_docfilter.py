def test_обе_вставки_номенклатуры_совпадают():
    """В flush() два литерала insert into lib_demand: пакетный и аварийный
    построчный. Если колонку добавить только в один, построчный путь начнёт
    падать на каждой строке, ошибка молча уйдёт в счётчик пропущенных, а файл
    уже записан как «разобран» — буфер до 4000 позиций потеряется безвозвратно."""
    ind = INDEXER.read_text(encoding="utf-8")
    вставки = re.findall(r"insert into lib_demand\s*\n?\s*\(([^)]*)\)", ind)
    assert len(вставки) == 2, f"вставок в lib_demand не две, а {len(вставки)}"
    колонки = [tuple(c.strip() for c in v.replace("\n", " ").split(",")) for v in вставки]
    assert колонки[0] == колонки[1], (
        f"пакетная и построчная вставки расходятся:\n  {колонки[0]}\n  {колонки[1]}")
    плейсхолдеры = re.search(r"values \((%s,?)+\)", ind)
    assert плейсхолдеры, "построчная вставка без плейсхолдеров"
    assert плейсхолдеры.group(0).count("%s") == len(колонки[0]), (
        "число плейсхолдеров не совпадает с числом колонок")


