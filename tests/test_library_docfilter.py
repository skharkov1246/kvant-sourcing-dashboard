def code_of(path: Path) -> str:
    """Текст модуля без его docstring: в шапке mark_prose.py приведена команда
    отката наследования сегментов, и она не должна путаться с исполняемым кодом."""
    import ast
    src = path.read_text(encoding="utf-8")
    doc = ast.get_docstring(ast.parse(src))
    return src.replace(doc, "") if doc else src


def test_разметка_не_удаляет_и_обратима():
    t = code_of(MARK)
    assert "insert into lib_row_junk" in t, "пометка должна лежать в таблице-спутнике"
    assert "update lib_demand" not in t, "разметка не имеет права трогать сам спрос"
    assert "delete from lib_row_junk where run_id" in t, "нет отката по ключу прогона"
    assert 'os.environ.get("APPLY"' in t, "нет холостого режима"
    assert "gates_ok" in t, "запись не привязана к гейтам приёмки"


