def test_модуль_без_зависимостей():
    """Его импортируют и тесты гейта, и индексатор, и разметка: одно правило."""
    text = DOCFILTER.read_text(encoding="utf-8")
    for heavy in ("import psycopg2", "import requests", "os.environ["):
        assert heavy not in text, f"в общее правило просочилось {heavy}"
    d = load()
    for fn in ("spec_marks", "prose_marks", "row_marks", "row_is_prose", "file_verdict"):
        assert hasattr(d, fn), f"в правиле нет {fn}"


def test_настоящая_номенклатура_не_помечается():
    """Главный тест. Ложное срабатывание здесь = потеря спроса без возврата."""
    d = load()
    ложные = [s for s in НОМЕНКЛАТУРА if d.row_is_prose(*d.row_marks(s))]
    assert not ложные, (
        "правило пометило настоящую номенклатуру как текст документа: "
        + " | ".join(ложные))


def test_номенклатура_имеет_защитный_признак():
    """Иммунитет должен опираться на признак, а не на отсутствие обвинения:
    иначе любое пополнение закрытого списка начнёт задевать номенклатуру."""
    d = load()
    без_защиты = [s for s in НОМЕНКЛАТУРА if not d.spec_marks(s)]
    assert len(без_защиты) <= 2, (
        "слишком много строк номенклатуры без защитного признака: "
        + " | ".join(без_защиты))


def test_проза_ловится_хотя_бы_наполовину():
    """Полнота вторична, но правило, которое не ловит ничего, не окупает прогон."""
