def test_каталог():
    s = собрать([строка("6205", "6205", "101", цена=1, валюта="EUR")],
                каталог=[("6205", "6205", "Подшипник", "SKF (Швеция)", None, None, None)])
    p = пары(s)["6205~skf"]
    assert (p["bn"], p["bs"]) == ("SKF", "каталог")


def test_каталог_словом_ведомости_без_реестра():
    """Каталог — наша ведомость: не узнанное реестром слово — бренд, кроме «не бренд»."""
    s = собрать([строка("a1", "A-1", "101"), строка("a2", "A-2", "101")], реестр=None,
                каталог=[("a1", "A-1", "Втулка", "Уралмаш", None, None, None),
                         ("a2", "A-2", "Втулка", "не указан", None, None, None)])
    п = пары(s)
    assert (п["a1~уралмаш"]["bn"], п["a1~уралмаш"]["bs"]) == ("Уралмаш", "каталог")
    assert п["a2"]["bw"] == "нет"


def test_строка_кп_узнанная_реестром():
    s = собрать([строка("7731", "RX-7731", "101", оем="FAG"),
                 строка("7732", "RX-7732", "101", оем="Неведомый Завод")])
