def test_разложение_держит_пары_раздельно():
    s = собрать([
        строка("6205", "6205", "101", оем="SKF", цена=10, валюта="EUR"),
        строка("6205", "6205", "102", оем="FAG", цена=11, валюта="EUR"),
    ])
    ключи = crossref.разложить(s)
    строки = [p for k in crossref.КЛЮЧИ_СПИСКА for p in ключи[k]["positions"]]
    assert {crossref.ид_позиции(p) for p in строки} == {"6205~skf", "6205~fag"}
    for p in строки:
        # Корзина — по ключу кода, пара — под своим ключом внутри неё.
        assert p["b"] == crossref.корзина("6205")
        подробно = ключи[crossref.КЛЮЧИ_КОРЗИН[p["b"]]]["positions"][crossref.ид_позиции(p)]
        assert [o["o"] for o in подробно["list"]] == ["с:" + p["bk"]]


def test_предложения_не_теряются_при_разбиении():
    """Случайный корпус: каждое предложение кода — ровно в одной паре.

    Предложение узнаётся по ключу точного дубля (crossref.ключ_дубля): до
    разбиения их по коду столько же, сколько после — во всех парах кода вместе,
    и ни одно не лежит в двух парах сразу."""
    rnd = random.Random(11)
    строки = []
    for i in range(400):
        код = f"rx{rnd.randrange(60):04d}"
        строки.append(строка(
            код, код.upper(), str(100 + rnd.randrange(15)),
            оем=rnd.choice((None, None, "SKF", "FAG", "SKF/FAG", "Неведомый Завод", "Skf AB")),
            бренды=rnd.choice((None, "501", "SKF,FAG", "777")),
            цена=rnd.choice((None, 10, 11, 12)), валюта="EUR",
            наименование=rnd.choice(("Втулка", "Фильтр Cummins"))))
    спрос = [(f"rx{i:04d}", "спецификация", rnd.choice(("SKF", "FAG")), 1)
             for i in range(0, 60, 7)]
    каталог = [(f"rx{i:04d}", f"RX{i:04d}", "Втулка", rnd.choice(("SKF", "FAG", "SKF/FAG")),
                None, None, None) for i in range(0, 60, 5)]
    s = собрать(строки, спрос_бренды=спрос, каталог=каталог)
    # До разбиения: предложения кода — различные ключи дубля по строкам кода.
    до = collections.defaultdict(set)
    for r in строки:
        о = crossref._коротко({"co": r[3], "price": crossref._число(r[8]), "cur": r[9],
                               "qty": crossref._число(r[10]),
                               "date": crossref._дата(r[24]) or crossref._дата(r[25])})
        до[r[0]].add(crossref.ключ_дубля(о))
    после = collections.defaultdict(list)
    for p in s["positions"]:
        assert p["offers"] == len(p["list"])            # корпус меньше предела показа
        после[p["k"]].extend(crossref.ключ_дубля(o) for o in p["list"])
    for код, ключи in до.items():
        assert sorted(после[код], key=str) == sorted(ключи, key=str), код
    б = s["totals"]["brand"]
    assert б["offers_coded"] == s["totals"]["offers"] == sum(len(v) for v in до.values())
    assert б["determined"] + б["none"] + б["disputed"] == s["totals"]["positions"]
    ид = [crossref.ид_позиции(p) for p in s["positions"]]
    assert len(ид) == len(set(ид)), "две пары с одним ключом"
    # Свой бренд предложения — всегда бренд его пары.
    for p in s["positions"]:
        for o in p["list"]:
            if "o" in o:
                assert o["o"].split(":", 1)[1] == p.get("bk"), (p["k"], o["o"])
    # Пар «Бренд не определён» у кода не больше одной.
    без = collections.Counter(p["k"] for p in s["positions"] if "bk" not in p)
    assert max(без.values(), default=0) <= 1


def test_журнал_публикатора_только_числа(capsys):
    """Доли бренда по источникам — в журнал прогона, и только агрегаты (правило 17)."""
    import importlib.util
    from pathlib import Path
    путь = Path(__file__).resolve().parents[1] / "scripts" / "publish_crossref.py"
    spec = importlib.util.spec_from_file_location("kvant_publish_crossref_brand", путь)
    мод = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(мод)
    s = собрать([строка("6205", "6205", "101", оем="SKF", наименование="Подшипник Выдумка"),
                 строка("6205", "6205", "102", оем="FAG"),
                 строка("4088833", "4088833", "103", наименование="Фильтр Cummins")])
    мод.печать_бренда(s["totals"], Р)
    вывод = capsys.readouterr().out
    assert "с определённым брендом 3 из 3" in вывод
    assert "каталог 0 · строка 2 · карточка 0 · маска 1" in вывод
    for запретное in ("SKF", "FAG", "Cummins", "6205", "4088833", "Выдумка", "101"):
        assert запретное not in вывод, запретное
