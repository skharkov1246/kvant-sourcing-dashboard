def test_код_у_двух_брендов_две_пары_и_не_определён():
    s = собрать([
        строка("6205", "6205", "101", оем="SKF", цена=10, валюта="EUR"),
        строка("6205", "6205", "102", оем="FAG", цена=11, валюта="EUR"),
        строка("6205", "6205", "103", цена=12, валюта="EUR"),
    ])
    п = пары(s)
    assert set(п) == {"6205~skf", "6205~fag", "6205"}
    assert [o["c"] for o in п["6205~skf"]["list"]] == ["101"]
    assert [o["c"] for o in п["6205~fag"]["list"]] == ["102"]
    # Предложение без бренда при двух брендах кода отнести некуда — спорно.
    assert п["6205"]["bw"] == "спорно"
    assert sorted(п["6205"]["bc"]) == [["FAG", "строка"], ["SKF", "строка"]]
    б = s["totals"]["brand"]
    assert (б["codes"], б["split"], б["moved"], б["offers_coded"]) == (1, 1, 2, 3)
    assert s["totals"]["offers"] == 3 and s["totals"]["positions"] == 3
    # Выбор из трёх компаний был у кода — у пар его нет: это видно числом.
    assert б["choice_lost"] == 1 and б["cmp_lost"] == 1


