"""Бренд позиции: пара «бренд + код» (правила номенклатуры П1 и П2) — при чтении.

Корпус придуман (CLAUDE.md, правило 18): бренды SKF, FAG, Cummins и Caterpillar —
настоящие имена ради масок, коды и компании выдуманы, ответы посчитаны руками.

Что защищается:
  · у каждого источника П2 свой случай, и порядок «каталог → строка → карточка →
    маска» соблюдается;
  · «спорно» — два бренда на одном, высшем уровне; разные уровни не спорят;
  · маска — предположение, и БЕЗ слова бренда у позиции брендом не становится;
  · код у двух брендов — две пары, и ни одно предложение не теряется и не
    удваивается (правило 0: итог не должен прятать потерю);
  · «Бренд не определён» — отдельная пара с причиной.
"""
from __future__ import annotations

import collections
import random

from library import crossref
from tests.test_crossref_snapshot import строка

СЛОВАРЬ = {"records": [
    {"oem_key": "skf", "name": "SKF", "kind": "бренд", "spellings": [{"spelling": "SKF"}, {"spelling": "Skf AB"}]},
    {"oem_key": "fag", "name": "FAG", "kind": "бренд", "spellings": [{"spelling": "FAG"}]},
    {"oem_key": "cummins", "name": "Cummins", "kind": "бренд", "spellings": [{"spelling": "Cummins"}]},
    {"oem_key": "caterpillar", "name": "Caterpillar", "kind": "бренд",
     "spellings": [{"spelling": "Caterpillar"}]},
    # Запись-указание: брендом не считается (library/oem_kind.py).
    {"oem_key": "заказпоспецификации", "name": "Заказ по спецификации", "kind": "указание",
     "spellings": [{"spelling": "Заказ по спецификации"}]},
]}
Р = crossref.реестр_брендов(СЛОВАРЬ, карточка={"501": "fag"}, откуда="словарь-файл")


def собрать(строки, **kw):
    kw.setdefault("реестр", Р)
    return crossref.собрать(строки, **kw)


def пары(s) -> dict:
    return {crossref.ид_позиции(p): p for p in s["positions"]}


# ── Правило по уровням ───────────────────────────────────────────────────────

def test_бренд_позиции_высший_уровень_решает():
    assert crossref.бренд_позиции([]) == {"why": "нет"}
    # Каталог выше строки: разные уровни не спорят.
    р = crossref.бренд_позиции([("строка", "fag", "FAG", 9), ("каталог", "skf", "SKF", 1)])
    assert р == {"k": "skf", "n": "SKF", "src": "каталог"}
    # Два бренда на одном уровне — спорно, оба названы, частый первым.
    р = crossref.бренд_позиции([("строка", "skf", "SKF", 1), ("строка", "fag", "FAG", 3),
                                ("карточка", "nsk", "NSK", 1)])
    assert р == {"why": "спорно", "cand": [["FAG", "строка"], ["SKF", "строка"]]}
    # Один бренд, названный многими строками, — не спор.
    assert crossref.бренд_позиции([("строка", "skf", "SKF", 1), ("строка", "skf", "Skf", 2)])["k"] == "skf"


def test_узнать_только_реестром():
    assert crossref.узнать("SKF", Р) == ["skf"]
    assert crossref.узнать("Skf AB", Р) == ["skf"]          # правовая форма снята
    assert crossref.узнать("SKF (Швеция)", Р) == ["skf"]   # страна — не бренд
    assert crossref.узнать("SKF/FAG", Р) == ["skf", "fag"]
    assert crossref.узнать("Неведомый Завод", Р) == []     # не узнан — не бренд
    assert crossref.узнать("Заказ по спецификации", Р) == []
    assert crossref.узнать("SKF", None) == []              # реестра нет — не узнан
    # Столкновение колонок: ячейка изготовителя — сам код.
    assert crossref.узнать("62-05", Р, "6205") == []


def test_не_бренд_закрытым_списком():
    for слово in ("не указан", "Китай", "аналог", "12345", "-"):
        assert crossref.не_бренд(слово), слово
    for слово in ("SKF", "3M", "Уралмаш", "Grundfos"):
        assert not crossref.не_бренд(слово), слово


def test_марки_карточки():
    assert crossref.бренды_карточки("501", Р) == [("fag", "FAG")]
    # Номер элемента без имени — не бренд; имя справочника — бренд словом.
    assert crossref.бренды_карточки("777", Р) == []
    assert crossref.бренды_карточки("777", Р, {"777": "Учебная марка"}) == [("учебнаямарка", "Учебная марка")]
    assert crossref.бренды_карточки("SKF, FAG", Р) == [("skf", "SKF"), ("fag", "FAG")]
    # Поле обрезано базой на 200 знаках: последний элемент мог обрубиться.
    длинное = ",".join(["501"] * 66) + ",SK"
    assert len(длинное) >= 200
    assert crossref.бренды_карточки(длинное, Р) == [("fag", "FAG")]


