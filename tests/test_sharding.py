"""Деление работы на части: ровно одно, и обход просит свою долю.

CLAUDE.md, правило дробления: «разбиение ровно одно. Два подряд — обход по частям
и отбор по хешу файла — выбрасывают то, что попало в часть 3 по первому признаку
и в часть 7 по второму: такой файл не берёт никто».

До 23.09.2026 разбор вызывал обход БЕЗ номера части: каждая из пятидесяти частей
читала портал целиком, а делила потом, по хешу файла. Пятьдесят полных обходов
вместо одного — и это при том, что распознавание и переразбор передают часть в
обход давно.
"""
from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent


def код(путь: str) -> str:
    текст = (КОРЕНЬ / путь).read_text(encoding="utf-8")
    return re.sub(r"(?<!\w)#[^\n]*", "", текст)


def test_разбор_просит_у_обхода_свою_часть():
    """Иначе каждая часть читает портал целиком."""
    ind = код("library/indexer.py")
    assert re.search(r"collect_refs_rfq\(DAYS,\s*SHARD,\s*SHARDS\)", ind), \
        "обход карточек запросов вызывается без номера части"
    assert re.search(r"collect_refs\(DAYS,\s*SHARD,\s*SHARDS\)", ind), \
        "обход сделок вызывается без номера части"


def test_делений_ровно_одно():
    """Отбор по хешу файла ПОСЛЕ обхода по частям теряет файлы."""
    ind = код("library/indexer.py")
    отбор = ind[ind.index("mine = [r for r in refs"):]
    отбор = отбор[:отбор.index("]")]
    assert "SHARDS" not in отбор and "sha1" not in отбор, \
        f"второе деление осталось в отборе: {отбор}"


def test_оба_обхода_умеют_делиться():
    """Правка держится на том, что обходы принимают часть и ограничивают себя."""
    ind = код("library/indexer.py")
    assert "def collect_refs(days: int, shard: int = 0, shards: int = 1" in ind
    assert "def collect_refs_rfq(days: int, shard: int = 0, shards: int = 1)" in ind
    # И сделки, и карточки запросов режутся диапазоном идентификаторов на стороне
    # портала (24.09.2026: деление сделок по остатку после полного списка
    # давало HTTP 429 на самом crm.deal.list).
    сделки = ind.split("def collect_refs(", 1)[1].split("\ndef ", 1)[0]
    карточки = ind.split("def collect_refs_rfq(", 1)[1].split("\ndef ", 1)[0]
    assert "диапазон_части(" in сделки, "обход сделок часть не ограничивает"
    assert "диапазон_части(" in карточки, "обход карточек часть не ограничивает"


def test_соседние_прогоны_делятся_так_же():
    """Распознавание и переразбор передают часть в обход — разбор не должен
    отличаться, иначе один и тот же портал читается по-разному в трёх прогонах."""
    for путь in ("library/ocr.py", "library/reparse.py"):
        текст = код(путь)
        assert re.search(r"collect_refs(_rfq)?\([^)]*SHARD", текст), \
            f"{путь} перестал передавать часть в обход"
