def test_точка_истории_повторяет_напечатанные_числа(корпус_в_public):
    """Цифра в истории обязана равняться напечатанной.

    Соблазн посчитать историю вторым проходом запросов велик, а цена —
    расхождение: между проходами идёт разбор, и точка разойдётся с выводом.
    """
    м = скрипт()
    код, вывод = прогон(м, WRITE="1", RUN_KEY="прогон-теста")
    assert код == 0
    (ключ, числа, оговорка), = точки(корпус_в_public)
    assert ключ == "прогон-теста"
    assert оговорка is None
    # Ровно те пять чисел, что напечатаны главным ответом.
    assert числа["asked"] == 5
    assert числа["with_kp"] == 1
    assert числа["other_feed"] == 2
    assert числа["no_price"] == 2
    assert числа["plausible"] == 4
    # И те, что напечатаны обратной стороной и каталогом.
    assert числа["price_codes"] == 2
    assert числа["price_asked"] == 1
    assert числа["price_not_asked"] == 1
    assert числа["catalog"] == 2
    assert числа["catalog_priced"] == 1
    # НАПЕЧАТАННОЕ И ЗАПИСАННОЕ — ОДНО И ТО ЖЕ. Проверяется не «число где-то
    # встречается» (так проходит любое совпадение пробелов), а число В СВОЕЙ
    # СТРОКЕ: подпись главного ответа против значения из точки истории.
    import re

    # Подпись привязана к НАЧАЛУ строки и отделена от числа пробелами: иначе
    # «всего кодов» совпадает и с «всего кодов с ценой предложения», и с
    # «всего кодов каталога», и проверка сверяет не то число.
    подписи = {
        "всего кодов": "asked",
        "с ценой ОТ ПОСТАВЩИКА (разбор КП)": "with_kp",
        "цена есть, но из другого потока": "other_feed",
        "БЕЗ ЦЕНЫ ВОВСЕ": "no_price",
    }
    найдено = 0
    for подпись, ключ in подписи.items():
        m = re.search(r"^\s*" + re.escape(подпись) + r"\s+(\d+)", вывод, re.M)
        assert m, f"подписи «{подпись}» нет в выводе"
        assert int(m.group(1)) == числа[ключ], \
            f"в строке «{подпись}» напечатано {m.group(1)}, а в точке {числа[ключ]}"
