"""Цена по ФОРМЕ данных: тройка «кол-во × цена = сумма» без заголовков.

ЗАЧЕМ ЭТО НУЖНО. Замер 23.09.2026 (прогон 35843048108, 368 файлов без шапки):
ослабление правила шапки возвращает 143 файла, а 225 — 61 % — не берутся никаким
ослаблением словаря или порога. Заголовка у них нет или он не слово, и остаётся
единственный признак — форма данных.

Корпуса придуманы, а не сняты с базы (CLAUDE.md, правило 18).
"""
from __future__ import annotations

from library import indexer


def test_тройка_находится_и_возвращает_номера_колонок():
    """Номера, а не «да/нет»: по ним цену можно ВЗЯТЬ, а не только узнать о ней."""
    таблица = [
        ["Насос ЦНС-38", "2", "1500", "3000"],
        ["Задвижка 30с41нж", "4", "250", "1000"],
        ["Подшипник 6208", "10", "35,50", "355"],
    ]
    найдено = indexer.тройка_колонок(таблица)
    assert найдено == (1, 2, 3), найдено


def test_округление_в_пределах_процента_не_ломает_тройку():
    """В предложениях округляют: 3 × 33,33 = 99,99, а в файле стоит 100."""
    таблица = [
        ["Позиция один", "3", "33,33", "100"],
        ["Позиция два", "7", "14,29", "100"],
        ["Позиция три", "6", "16,67", "100"],
    ]
    assert indexer.тройка_колонок(таблица) == (1, 2, 3)


def test_случайные_числа_тройкой_не_считаются():
    """Иначе цену начнут «находить» в таблице сроков и весов."""
    таблица = [
        ["Позиция один", "12", "45", "78"],
        ["Позиция два", "33", "21", "64"],
        ["Позиция три", "7", "90", "15"],
    ]
    assert indexer.тройка_колонок(таблица) is None


def test_двух_строк_недостаточно():
    """Одна-две совпавшие тройки — случайность, и на ней решать нельзя."""
    таблица = [["Позиция один", "2", "50", "100"], ["Позиция два", "3", "10", "30"]]
    assert indexer.тройка_колонок(таблица) is None


def test_широкая_таблица_не_съедает_прогон():
    """Перебор кубический: без предела 20 колонок дают 6 840 тройек на файл."""
    ширина = 24
    строка = ["текст"] + [str(i) for i in range(1, ширина)]
    таблица = [строка[:] for _ in range(5)]
    assert indexer.ЧИСЛОВЫХ_КОЛОНОК_МАКС <= 8
    indexer.тройка_колонок(таблица)          # не должно висеть


def test_форма_стоит_в_сетке_отдельной_строкой():
    """Объём этой работы должен быть известен ДО того, как её начинать."""
    таблица = [["Наименование", "", "", ""],
               ["Насос ЦНС-38", "2", "1500", "3000"],
               ["Задвижка", "4", "250", "1000"],
               ["Подшипник", "10", "35,50", "355"]]
    сетка = indexer.сетка_шапки(таблица)
    assert any("цена по форме" in v for v in сетка), сетка
