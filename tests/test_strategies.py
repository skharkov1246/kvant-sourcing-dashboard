"""Таблица стратегий чтения: какой читатель к какому виду и в каком порядке.

Замер 23.09.2026 по всей базе (31 869 файлов, 9 527 без позиций) показал, что
ветвление разбора покрывало три вида из шести. «Изображение», «архив» и «прочее»
не попадали ни в одну ветку: у них оставались пустые строки и пустой текст, и
файл получал «пусто» с причиной «нет текстового слоя».

    прочее   410 файлов · 410 без позиций · 100 %
    архив    169 файлов · 169 без позиций · 100 %

Корпуса собраны здесь же, а не сняты с базы (CLAUDE.md, правило 18).
"""
from __future__ import annotations

import io
import zipfile

from library import indexer

ШАПКА = "Наименование;Кол-во;Цена\n"
СПЕЦИФИКАЦИЯ = (ШАПКА + "Насос ЦНС-38;2;1500\nЗадвижка 30с41нж;4;250\n"
                "Подшипник 6208;10;35\n").encode()


def читать(b: bytes, rec: dict | None = None):
    return indexer.читать(b, indexer.подвид(b), rec)


def test_каждый_подвид_имеет_стратегию_и_ни_один_не_молчит():
    """Отказ без причины — это и есть потерянный файл: чинить по нему нечего."""
    for п in indexer.ВИД_ПО_ПОДВИДУ:
        строки, текст, отказ = indexer.читать(b"\x00" * 64, п)
        assert строки or текст or отказ, f"подвид {п} не дал ни строк, ни текста, ни причины"


def test_csv_становится_таблицей_а_не_прозой():
    """410 файлов «прочего» не давали ни одной позиции: читателя не было."""
    строки, текст, отказ = читать(СПЕЦИФИКАЦИЯ)
    assert len(строки) == 4 and отказ == "", (строки, отказ)
    assert строки[1] == ["Насос ЦНС-38", "2", "1500"]


def test_csv_без_шапки_уходит_текстом_а_не_ноль():
    """Ворота таблицы те же, что у прочих видов, и файл не теряется."""
    b = "Здравствуйте, просим предложение\nс уважением, отдел закупок\n".encode()
    строки, текст, отказ = читать(b)
    assert строки == [] and текст, "файл без шапки потерян целиком"


def test_архив_отдаёт_лучшего_участника_а_не_первого():
    """В архиве «КП и приложения» первым лежит письмо, спецификация вторым.

    Брать первого попавшегося — значит прочитать письмо и потерять спецификацию.
    """
    # ПЕРВЫЙ УЧАСТНИК ТОЖЕ ДАЁТ ТАБЛИЦУ, но короткую: лист согласования на две
    # строки. Без этого «брать первого» и «брать лучшего» дают один ответ, и
    # порядок не проверяется вовсе — мутация «брать первого» переживала проверку.
    лист = "Наименование;Кол-во\nЛист согласования;1\n"
    буфер = io.BytesIO()
    with zipfile.ZipFile(буфер, "w") as z:
        z.writestr("01_list.csv", лист)
        z.writestr("02_spec.csv", СПЕЦИФИКАЦИЯ.decode())
    строки, текст, отказ = читать(буфер.getvalue())
    assert len(строки) == 4, f"взят не лучший участник: {строки}"
    assert строки[1][0] == "Насос ЦНС-38", строки


def test_архив_без_читаемых_участников_называет_причину():
    буфер = io.BytesIO()
    with zipfile.ZipFile(буфер, "w") as z:
        z.writestr("foto.jpg", "\x89PNG")
    строки, текст, отказ = читать(буфер.getvalue())
    assert строки == [] and отказ, "архив без спецификации молчит о причине"


def test_ole2_пробует_книгу_потом_документ(monkeypatch):
    """Падение xlrd НЕ означает «формат не читаем»: 375 файлов терялись так.

    .doc и .msg — такой же контейнер OLE2, как .xls. Книга пробуется первой,
    потому что дешевле и встречается чаще; не вышло — идёт читатель .doc.
    """
    b = b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1" + b"rest"

    def падает(_b):
        raise ValueError("не книга")

    monkeypatch.setattr(indexer, "rows_from_xls", падает)
    monkeypatch.setattr(indexer.readers, "text_from_doc",
                        lambda _b: ("Насос ЦНС-38  2 шт.", ""))
    строки, текст, отказ = читать(b)
    assert "Насос" in текст and отказ == "", (текст, отказ)


def test_ole2_без_читателя_doc_называет_чего_не_хватает(monkeypatch):
    b = b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1" + b"rest"
    monkeypatch.setattr(indexer, "rows_from_xls", lambda _b: [])
    monkeypatch.setattr(indexer.readers.shutil, "which", lambda _и: None)
    строки, текст, отказ = читать(b)
    assert отказ == "нет ни antiword, ни catdoc", отказ


def test_картинка_названа_ждущей_распознавания_а_не_пустой():
    """«Нет текстового слоя» не говорит, ждёт файл распознавания или потерян.

    Картинок в базе 5 240, без позиций 3 666 — самый крупный разряд потерь.
    """
    строки, текст, отказ = читать(b"\x89PNG\r\n\x1a\n rest")
    assert строки == [] and текст == ""
    assert "распознаван" in отказ, отказ


def test_архивы_без_распаковщика_называют_чего_не_хватает():
    for b in (b"Rar!\x1a\x07\x00", b"7z\xbc\xaf\x27\x1c", b"\x1f\x8b\x08\x00"):
        _, _, отказ = читать(b)
        assert "распаковщик" in отказ, отказ


def test_выгрузка_1с_читается_стратегией_а_не_падает_в_xlrd():
    b = ('<?xml version="1.0"?><Workbook '
         'xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet">'
         '<Worksheet><Table>'
         '<Row><Cell><Data>Наименование</Data></Cell>'
         '<Cell><Data>Кол-во</Data></Cell></Row>'
         '<Row><Cell><Data>Насос ЦНС-38</Data></Cell>'
         '<Cell><Data>2</Data></Cell></Row>'
         '</Table></Worksheet></Workbook>').encode()
    строки, текст, отказ = читать(b)
    assert строки and строки[1][0] == "Насос ЦНС-38", (строки, отказ)


def test_причина_читателя_не_затирается_дежурной(monkeypatch):
    """Замер 23.09.2026: 150 docx и 57 xlsx значились «без текстового слоя».

    Для офисного документа это бессмыслица: читатель называл настоящую причину,
    а общий код в конце разбора стирал её дежурной фразой — и чинить было нечего.
    """
    монтаж = b"PK\x03\x04" + b"[Content_Types].xml xl/workbook.xml" + b"\x00" * 300
    monkeypatch.setattr(indexer, "download", lambda fo, rec=None: монтаж)

    def падает(_b):
        raise ValueError("книга битая")

    monkeypatch.setattr(indexer, "rows_from_xlsx", падает)
    rec, items = indexer.handle({"fo": {"id": "1"}, "deal": "1", "origin": "поле запроса",
                                 "field": "UF_TEST", "field_title": None})
    assert items == []
    assert rec["reason"] != "нет текстового слоя", "причина читателя затёрта дежурной"
    assert "книга не открылась" in rec["reason"] or "архив" in rec["reason"], rec["reason"]
