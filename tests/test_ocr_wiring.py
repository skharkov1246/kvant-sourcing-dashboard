"""Распознавание сканов обязано вести себя так же, как обычный разбор.

ЗАЧЕМ. Пятая часть предложений — сканы без текстового слоя: 1 631 файл из 7 559
(замер 35756373405), а распознано десять. Значит распознавание предстоит гонять, и
перед этим оно должно писать то же, что обычный разбор, и не убивать портал.

Три свойства. Первое молча искажает отчёт, второе молча теряет файлы, третье
молча убивает прогон.

1. КОММЕРЧЕСКИЕ УСЛОВИЯ И У СКАНА. Без свода цена из скана ложится без базиса,
   оплаты и сроков, а колонки источника остаются пустыми — то есть отсутствие НЕ
   ОТМЕЧЕНО, тогда как у обычного разбора оно отмечено как «проверено, не
   написано». Одна и та же пустота значит разное в зависимости от того, каким
   путём прошёл файл, и в отчёте это неразличимо (CLAUDE.md, правило 14).
2. ОТБОР ПО ХЕШУ ФАЙЛА ПОСЛЕ РАЗБИЕНИЯ ПО СДЕЛКАМ ТЕРЯЕТ ФАЙЛЫ. Два независимых
   разбиения подряд выбрасывают файл, попавший в часть 3 по сделке и в часть 7 по
   хешу: его не берёт никто. Разбиение должно быть одно.
3. ОБХОД ПОРТАЛА РАЗБИВАЕТСЯ ДО ЗАПРОСА ПОДРОБНОСТЕЙ. Прежде здесь стоял
   collect_refs(DAYS) без частей: все двенадцать частей делали один и тот же
   полный обход и получали HTTP 429 — ровно то, на чём 21.09.2026 умерли
   двенадцать частей переразбора. По карточкам запросов обход не разбивается
   вовсе, поэтому там работает одна часть, и хеш файла применять нельзя — иначе
   она возьмёт свою двенадцатую, а остальное потеряется.

Исходник читается КОДОМ, а не комментариями (CLAUDE.md, «Стиль работы»).
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "library"))


def без_комментариев(текст: str) -> str:
    строки = []
    for ln in текст.splitlines():
        if ln.lstrip().startswith("#"):
            continue
        строки.append(re.sub(r"\s+#.*$", "", ln))
    return "\n".join(строки)


КОД = без_комментариев((ROOT / "library" / "ocr.py").read_text())


def test_условия_применяются_и_к_распознанному_скану():
    """Иначе пустота у скана и пустота у разбора значат разное."""
    assert "применить_условия(items, text)" in КОД
    # И только для предложений: во вложении сделки условий поставщика нет.
    место = КОД.index("применить_условия")
    выше = КОД[max(0, место - 200):место]
    assert 'indexer.SOURCE == "rfq"' in выше


def test_цена_пишется_через_единственное_место_записи():
    """CLAUDE.md, правило 14: вставка цены одна на все разборы."""
    assert "price_store.записать" in КОД
    assert "price_store.строка" in КОД
    assert "insert into lib_prices" not in КОД.lower()


def test_разбиение_одно_а_не_два_подряд():
    """Отбор по хешу файла после разбиения по сделкам терял бы файлы."""
    assert "hashlib" not in КОД, "хеш файла как второе разбиение снят"
    # Разбиение делает сам обход.
    assert "collect_refs(DAYS, SHARD, SHARDS)" in КОД


def test_по_предложениям_работает_одна_часть():
    """Обход карточек запросов не разбивается — двенадцать обходов дадут 429."""
    assert "if SHARD != 0:" in КОД
    # Ветка предложений стоит раньше ветки сделок.
    assert КОД.index("collect_refs_rfq") < КОД.index("collect_refs(DAYS, SHARD, SHARDS)")


def test_модуль_импортируется():
    """Простейшая проверка, что правки не разъехались с остальным кодом."""
    import ocr
    assert hasattr(ocr, "main")
