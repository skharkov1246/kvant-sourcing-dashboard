"""Снимок перекрёстной системы помещается в предел KV с запасом.

ЗАЧЕМ. Публикация 22.09.2026 упала: 8,29 МиБ против предела 8. Гейт размера в
публикаторе сработал, и это правильно — молчаливое усечение унесло бы часть
номенклатуры невидимо. Но узнали мы о нём из упавшего прогона, а не из теста, и
страница до вечера осталась пустой.

Причина была не в объёме данных, а в форме снимка: списки позиций у компаний
лежали ВТОРОЙ КОПИЕЙ тех же рёбер и весили треть. После их удаления и отсева
пустых ключей 9,27 → 5,75 МиБ.

Этот тест держит форму. Он собирает снимок на корпусе с пропорциями настоящей
базы и требует запаса, а не «влезает впритык»: позиции прибывают с каждым
разбором, и снимок, занявший 7,9 МиБ, — это отложенное падение.

Корпус придуман (CLAUDE.md, правило 18): наименования и артикулы сочинены,
пропорции взяты из журнала прогона (агрегаты, правило 17).
"""
from __future__ import annotations

import datetime as dt
import importlib.util
import json
import random
from pathlib import Path

from library import crossref

ROOT = Path(__file__).resolve().parents[1]

# Замер 22.09.2026 по всей базе: позиций 9 578, предложений 18 388, компаний 612.
ПОЗИЦИЙ = 9_578
ПРЕДЛОЖЕНИЙ = 18_388
КОМПАНИЙ = 612

# Заполняемость полей — из воронки того же прогона.
ДОЛЯ_ВАЛЮТЫ = 0.86
ДОЛЯ_СРОКА = 0.15
ДОЛЯ_ИЗГОТОВИТЕЛЯ = 0.14
ДОЛЯ_БРЕНДА = 0.94
ДОЛЯ_СВЕДЕНИЯ = 0.90

# Запас на сегодняшнем объёме. Снимок, занявший 95 % предела, — это отложенное
# падение, а не «влезает».
ЗАПАС = 0.80

НАИМЕНОВАНИЯ = (
    "Подшипник роликовый конический однорядный",
    "Уплотнение торцовое вала насоса высокого давления",
    "Фильтроэлемент напорной линии гидросистемы",
    "Крышка подшипникового узла редуктора",
    "Втулка распорная промежуточного вала",
)


def предел() -> int:
    """Предел берётся из публикатора, а не переписывается сюда числом."""
    spec = importlib.util.spec_from_file_location(
        "kvant_publish_suppliers_size", ROOT / "scripts" / "publish_suppliers.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.MAX_BYTES


def корпус(позиций=ПОЗИЦИЙ):
    # Предложений — в той же пропорции к позициям, что в базе (1,92 на позицию).
    предложений = round(позиций * ПРЕДЛОЖЕНИЙ / ПОЗИЦИЙ)
    rnd = random.Random(7)
    на_позицию = [1] * позиций
    for _ in range(предложений - позиций):
        на_позицию[rnd.randrange(позиций)] += 1
    д = dt.date(2026, 9, 1)
    строки = []
    for i in range(позиций):
        номер = f"{rnd.choice(('SKF', 'FAG', 'PN', 'CAT', 'K'))}-{i:06d}-{rnd.randrange(10, 99)}"
        имя = f"{rnd.choice(НАИМЕНОВАНИЯ)} {i}"
        ключ = номер.lower().replace("-", "")
        for _ in range(на_позицию[i]):
            комп = str(100_000 + rnd.randrange(КОМПАНИЙ))
            сведена = rnd.random() < ДОЛЯ_СВЕДЕНИЯ
            строки.append((
                ключ, номер, имя, комп,
                f"KV-S-{rnd.randrange(999_999):06d}-{rnd.randrange(9)}" if сведена else None,
                f"Компания номер {комп}" if сведена else None,
                rnd.choice(("SKF", "FAG", "NSK")) if rnd.random() < ДОЛЯ_ИЗГОТОВИТЕЛЯ else None,
                "SKF,FAG" if rnd.random() < ДОЛЯ_БРЕНДА else None,
                round(rnd.uniform(1, 5000), 2),
                rnd.choice(("CNY", "USD", "EUR", "RUB")) if rnd.random() < ДОЛЯ_ВАЛЮТЫ else None,
                rnd.choice((1, 2, 10, None)),
                rnd.choice(("шт", None)),
                rnd.choice(("EXW", "DDP", None)),
                rnd.randrange(120) if rnd.random() < ДОЛЯ_СРОКА else None,
                f"RFQ-{rnd.randrange(99_999)}", rnd.choice(("med", "low")), д, None,
            ))
    return строки


def байт(позиций=ПОЗИЦИЙ) -> int:
    снимок = crossref.собрать(корпус(позиций))
    return len(json.dumps(снимок, ensure_ascii=False,
                          separators=(",", ":")).encode("utf-8"))


def test_снимок_влезает_с_запасом():
    снимок = crossref.собрать(корпус())
    raw = json.dumps(снимок, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    порог = int(предел() * ЗАПАС)
    t = снимок["totals"]
    assert t["positions"] == ПОЗИЦИЙ
    assert t["offers"] == ПРЕДЛОЖЕНИЙ
    assert len(raw) <= порог, (
        f"снимок {len(raw) / 1024 / 1024:.2f} МиБ при пороге "
        f"{порог / 1024 / 1024:.2f} МиБ ({ЗАПАС:.0%} от предела "
        f"{предел() / 1024 / 1024:.0f} МиБ). Публикация упадёт или упадёт скоро. "
        "Так уже было 22.09.2026: списки позиций у компаний лежали второй копией "
        "тех же рёбер и весили треть объёма.")


def test_записанный_потолок_соответствует_действительности():
    """ПОТОЛОК_ПОЗИЦИЙ в коде — поддерживаемый факт, а не комментарий.

    Рядом с ним записано, что делать при приближении: указатель отдельно от
    подробностей, подробности в корзинах по хешу ключа. Решение принято заранее
    именно для того, чтобы не принимать его в спешке на упавшем прогоне, — но
    цифра, к которой оно привязано, обязана быть верной. Иначе она устареет
    молча, как устаревают все числа в комментариях.

    Проверяется двумя сборками, а не поиском: при девяноста процентах потолка
    снимок обязан влезать, при самом потолке — нет. Это пиняет число в пределах
    десяти процентов и стоит две сборки вместо десяти.
    """
    потолок = crossref.ПОТОЛОК_ПОЗИЦИЙ
    ниже = байт(int(потолок * 0.9))
    assert ниже <= предел(), (
        f"при {int(потолок * 0.9)} позициях снимок уже {ниже / 1024 / 1024:.2f} МиБ — "
        f"ПОТОЛОК_ПОЗИЦИЙ = {потолок} завышен, форма держит меньше")
    на_потолке = байт(потолок)
    assert на_потолке > предел(), (
        f"при {потолок} позициях снимок всего {на_потолке / 1024 / 1024:.2f} МиБ — "
        f"ПОТОЛОК_ПОЗИЦИЙ занижен. Если форму облегчили, обнови число: заниженный "
        "потолок толкает делить снимок раньше, чем нужно")


def test_рёбра_не_хранятся_дважды():
    """У компаний нет списка позиций: он собирается страницей из positions.

    Отдельным тестом от размера, потому что это утверждение о форме, а не о
    байтах: вернувшийся список сначала просто съест запас, а потом уронит
    публикацию, и связь с причиной потеряется.
    """
    снимок = crossref.собрать(корпус(200))
    for c in снимок["companies"]:
        assert "list" not in c, "список позиций вернулся в companies — это вторая копия рёбер"
