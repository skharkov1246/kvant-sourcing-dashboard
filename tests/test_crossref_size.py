"""Снимок перекрёстной системы помещается в предел KV с запасом — КАЖДЫЙ ключ.

ЗАЧЕМ. Публикация дважды упала на пределе 8 МиБ. 22.09.2026 — 8,29 МиБ: списки
позиций у компаний лежали второй копией рёбер. 24.09.2026 — 10,51 МиБ при 16 400
позициях и 30 141 предложении (прогон 35986620488): одним ключом форма больше не
держала. Снимок разложен на заголовок crossref:v1, восемь частей списка и
тридцать две корзины подробностей (library/crossref.разложить).

Этот тест держит форму. Корпус ТЯЖЕЛЕЕ живой базы: каталожная часть (аналоги,
машины, изготовители) у трети позиций, спрос у всех, коммерческие условия
заполнены выше наблюдаемого. Требование — не «влезает сегодня», а «влезает при
росте в три раза»: позиции прибывают с каждым разбором.

Корпус придуман (CLAUDE.md, правило 18): наименования и артикулы сочинены,
пропорции взяты из журналов прогонов (агрегаты, правило 17).
"""
from __future__ import annotations

import datetime as dt
import functools
import importlib.util
import json
import random
from pathlib import Path

from library import crossref, offer_role

ROOT = Path(__file__).resolve().parents[1]

# Замер 24.09.2026 по журналу упавшего прогона: позиций 16 400, предложений
# 30 141. Компаний в журнале нет — берётся пропорция замера 22.09.2026 (612 на
# 9 578 позиций), предложений на позицию — прежние 1,92, а не нынешние 1,84:
# корпус тяжелее живой базы, а не легче.
ПОЗИЦИЙ = 16_400
ПРЕДЛОЖЕНИЙ_НА_ПОЗИЦИЮ = 18_388 / 9_578
КОМПАНИЙ_НА_ПОЗИЦИЮ = 612 / 9_578
# Рост, который форма обязана выдержать с запасом ЗАПАС: владелец просил запас
# «при росте в 2–3 раза», берётся верхняя граница.
РОСТ = 3

# Заполняемость полей — из воронки прогона 22.09.2026, коммерческие условия —
# выше наблюдаемых: снимок должен влезать на той заполняемости, к которой мы
# идём, иначе улучшение разбора уронит публикацию.
ДОЛЯ_ВАЛЮТЫ = 0.86
ДОЛЯ_СРОКА = 0.15
ДОЛЯ_ИЗГОТОВИТЕЛЯ = 0.14
ДОЛЯ_БРЕНДА = 0.94
ДОЛЯ_СВЕДЕНИЯ = 0.90
ДОЛЯ_ОПЛАТЫ = 0.35
ДОЛЯ_СРОКА_ИЗГ = 0.30
ДОЛЯ_СУММЫ = 0.60
# Каталожная часть. В каталоге 12 899 деталей, связей с машиной 9 869, аналогов
# 1 699, изготовителей 4 726 — на деталь каталога 0,77 машины, 0,13 аналога и
# 0,37 изготовителя. Здесь 1,5 машины, 0,5 аналога и 0,5 изготовителя на деталь,
# а в каталоге треть позиций: корпус тяжёлый намеренно.
ДОЛЯ_В_КАТАЛОГЕ = 1 / 3
ДОЛЯ_АНАЛОГА = 0.5
ДОЛЯ_ИЗГОТОВИТЕЛЯ_КАТАЛОГА = 0.5

# Запас: ключ, занявший больше 80 % предела, — отложенное падение, а не «влезает».
ЗАПАС = 0.80

НАИМЕНОВАНИЯ = (
    "Подшипник роликовый конический однорядный",
    "Уплотнение торцовое вала насоса высокого давления",
    "Фильтроэлемент напорной линии гидросистемы",
    "Крышка подшипникового узла редуктора",
    "Втулка распорная промежуточного вала",
)
МАШИНЫ = ("Выдуманная турбина ВТ-25", "Учебный компрессор УК-8", "Насос НП-400 опытный")


def предел() -> int:
    """Предел берётся из публикатора, а не переписывается сюда числом."""
    spec = importlib.util.spec_from_file_location(
        "kvant_publish_suppliers_size", ROOT / "scripts" / "publish_suppliers.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.MAX_BYTES


def корпус(позиций=ПОЗИЦИЙ):
    """Шесть наборов в порядке аргументов crossref.собрать."""
    rnd = random.Random(7)
    предложений = round(позиций * ПРЕДЛОЖЕНИЙ_НА_ПОЗИЦИЮ)
    компаний = max(1, round(позиций * КОМПАНИЙ_НА_ПОЗИЦИЮ))
    на_позицию = [1] * позиций
    for _ in range(предложений - позиций):
        на_позицию[rnd.randrange(позиций)] += 1
    д = dt.date(2026, 9, 1)
    строки, каталог, аналоги, машины, изготовители, спрос = [], [], [], [], [], []
    for i in range(позиций):
        номер = f"{rnd.choice(('SKF', 'FAG', 'PN', 'CAT', 'K'))}-{i:06d}-{rnd.randrange(10, 99)}"
        имя = f"{rnd.choice(НАИМЕНОВАНИЯ)} {i}"
        ключ = номер.lower().replace("-", "")
        for _ in range(на_позицию[i]):
            комп = str(100_000 + rnd.randrange(компаний))
            сведена = rnd.random() < ДОЛЯ_СВЕДЕНИЯ
            строки.append((
                ключ, номер, имя, комп,
                f"KV-S-{rnd.randrange(999_999):06d}-{rnd.randrange(9)}" if сведена else None,
                f"Компания номер {комп}" if сведена else None,
                rnd.choice(("SKF", "FAG", "NSK")) if rnd.random() < ДОЛЯ_ИЗГОТОВИТЕЛЯ else None,
                "SKF,FAG" if rnd.random() < ДОЛЯ_БРЕНДА else None,
                round(rnd.uniform(1, 5000), 2),
                rnd.choice(("CNY", "USD", "EUR", "RUB")) if rnd.random() < ДОЛЯ_ВАЛЮТЫ else None,
                rnd.choice((1, 2, 10, None)),
                rnd.choice(("шт", None)),
                rnd.choice(("EXW", "DDP", None)),
                rnd.randrange(120) if rnd.random() < ДОЛЯ_СРОКА else None,
                # срок изготовления, условия оплаты, доля аванса, сумма строки
                rnd.randrange(90) if rnd.random() < ДОЛЯ_СРОКА_ИЗГ else None,
                (rnd.choice(("LC, 30 на 70", "T/T 100 % предоплата",
                             "50 на 50 против документов"))
                 if rnd.random() < ДОЛЯ_ОПЛАТЫ else None),
                rnd.choice((30, 50, 100)) if rnd.random() < ДОЛЯ_ОПЛАТЫ else None,
                round(rnd.uniform(10, 500_000), 2) if rnd.random() < ДОЛЯ_СУММЫ else None,
                # четыре пометки источника условия
                rnd.choice(("строка", "файл", "нет", "не проверено")),
                rnd.choice(("строка", "файл", "нет", "не проверено")),
                rnd.choice(("строка", "файл", "нет", "несколько")),
                rnd.choice(("файл", "нет", "не проверено")),
                f"RFQ-{rnd.randrange(99_999)}", rnd.choice(("med", "low")), д, None,
            ))
        спрос.append((ключ, rnd.randrange(1, 40), rnd.randrange(1, 90),
                      rnd.choice((0, 1, 1, 2)), rnd.randrange(1, 5000), "шт"))
        if rnd.random() < ДОЛЯ_В_КАТАЛОГЕ:
            каталог.append((ключ, номер, f"{имя} по каталогу", rnd.choice(("SKF", "FAG")),
                            "подшипники", "шт", f"KV-{i:06d}-{rnd.randrange(9)}"))
            if rnd.random() < ДОЛЯ_АНАЛОГА:
                аналоги.append((ключ, f"ALT-{i:06d}",
                                rnd.choice(("номер изготовителя", "аналог")),
                                rnd.choice(("ГПЗ", "NSK")), "med"))
            for м in rnd.sample(МАШИНЫ, rnd.choice((1, 2))):
                машины.append((ключ, м))
            if rnd.random() < ДОЛЯ_ИЗГОТОВИТЕЛЯ_КАТАЛОГА:
                изготовители.append((ключ, "Учебный завод", "OEM", "Швеция",
                                     "подшипники качения", None, "low"))
    return строки, каталог, аналоги, машины, изготовители, спрос


# Сборка — как у публикатора: с ролью предложения (h, dr) и приведённой ценой
# (i, j и notes корзины). Без них тест мерил бы снимок легче публикуемого.
ПОЛНАЯ_СБОРКА = {"на_дату": "2026-09-24",
                 "роли": {"реестр": offer_role.реестр_файлов(), "ид": {}}}


@functools.lru_cache(maxsize=None)
def ключи(позиций=ПОЗИЦИЙ) -> dict[str, int]:
    """Размер каждого ключа KV в байтах — в той сериализации, что у публикатора.

    Сборка на утроенном объёме — секунды, поэтому результат держится на весь
    прогон тестов: три теста читают одни и те же две сборки."""
    снимок = crossref.собрать(*корпус(позиций), собран="2026-09-24T00:00:00Z", **ПОЛНАЯ_СБОРКА)
    return {k: len(json.dumps(v, ensure_ascii=False, separators=(",", ":")).encode("utf-8"))
            for k, v in crossref.разложить(снимок).items()}


def test_ключи_влезают_с_запасом_при_росте_втрое():
    размеры = ключи(ПОЗИЦИЙ * РОСТ)
    порог = int(предел() * ЗАПАС)
    assert set(размеры) == set(crossref.ВСЕ_КЛЮЧИ)
    for k, n in размеры.items():
        assert n <= порог, (
            f"{k}: {n / 1024 / 1024:.2f} МиБ при {ПОЗИЦИЙ * РОСТ} позициях, порог "
            f"{порог / 1024 / 1024:.2f} МиБ ({ЗАПАС:.0%} от предела). Форма не держит "
            "рост втрое: публикация упадёт так же, как 24.09.2026.")


def test_сегодняшний_объём_ровно_то_что_уронило_прогон():
    """На объёме упавшего прогона единый снимок НЕ влезал, а разложенный влезает.

    Первое — проверка самого корпуса: корпус, на котором прежняя форма влезала бы,
    ничего не доказывает о новой.
    """
    снимок = crossref.собрать(*корпус(), собран="2026-09-24T00:00:00Z", **ПОЛНАЯ_СБОРКА)
    целиком = len(json.dumps(снимок, ensure_ascii=False, separators=(",", ":")).encode("utf-8"))
    assert целиком > предел(), (
        f"единый снимок на корпусе {целиком / 1024 / 1024:.2f} МиБ — корпус легче живой "
        "базы, где тот же объём дал 10,51 МиБ")
    размеры = ключи(ПОЗИЦИЙ)
    assert max(размеры.values()) <= int(предел() * ЗАПАС)


def test_корзины_ровные():
    """Ни одна корзина не тяжелее средней вдвое: хеш раскладывает, а не сваливает."""
    размеры = ключи(ПОЗИЦИЙ)
    корзины = [размеры[k] for k in crossref.КЛЮЧИ_КОРЗИН]
    средняя = sum(корзины) / len(корзины)
    assert max(корзины) < 2 * средняя


def test_записанный_потолок_соответствует_действительности():
    """ПОТОЛОК_ПОЗИЦИЙ в коде — поддерживаемый факт, а не комментарий.

    Потолок теперь в девять раз выше нынешнего объёма, и собрать корпус такого
    размера дважды — минута на каждый прогон тестов. Поэтому число сверяется с
    ЭКСТРАПОЛЯЦИЕЙ по двум сборкам, которые тесты выше делают всё равно: размер
    каждого ключа линеен в числе позиций (части списка и корзины — доли одного
    и того же множества). Линейность проверяется здесь же, а не принимается на
    веру: отклонись форма от прямой — потолок не сверялся бы ни с чем.

    Потолок обязан совпасть с экстраполяцией в пределах десяти процентов и быть
    не ниже трёх нынешних объёмов — ради этого снимок и делили.
    """
    потолок = crossref.ПОТОЛОК_ПОЗИЦИЙ
    assert потолок >= ПОЗИЦИЙ * РОСТ
    n1, n2 = ПОЗИЦИЙ, ПОЗИЦИЙ * РОСТ
    а, б = ключи(n1), ключи(n2)
    # Линейность: промежуточная точка лежит на прямой с точностью до 3 %.
    n3 = ПОЗИЦИЙ * 2
    в = ключи(n3)
    for k in (crossref.КЛЮЧ, crossref.КЛЮЧИ_СПИСКА[0], crossref.КЛЮЧИ_КОРЗИН[0]):
        ожидается = а[k] + (б[k] - а[k]) * (n3 - n1) / (n2 - n1)
        assert abs(в[k] - ожидается) <= 0.03 * ожидается, f"{k}: размер не линеен в позициях"
    предел_ = предел()
    расчётный = min(n1 + (предел_ - а[k]) * (n2 - n1) / (б[k] - а[k])
                    for k in а if б[k] > а[k])
    assert 0.9 * расчётный <= потолок <= 1.1 * расчётный, (
        f"ПОТОЛОК_ПОЗИЦИЙ = {потолок}, а по замеру самый тяжёлый ключ достигает "
        f"предела при {расчётный:.0f} позициях. Обнови число: завышенный потолок "
        "обещает запас, которого нет, заниженный толкает делить снимок раньше нужного")


def test_рёбра_не_хранятся_дважды():
    """У компаний нет списка позиций: он собирается страницей из рёбер позиций.

    Отдельным тестом от размера, потому что это утверждение о форме, а не о
    байтах: вернувшийся список сначала просто съест запас, а потом уронит
    публикацию, и связь с причиной потеряется.
    """
    снимок = crossref.собрать(*корпус(200))
    for c in снимок["companies"]:
        assert "list" not in c, "список позиций вернулся в companies — это вторая копия рёбер"
    части = crossref.разложить(снимок)
    for p in [p for k in crossref.КЛЮЧИ_СПИСКА for p in части[k]["positions"]]:
        assert "list" not in p, "предложения вернулись в указатель — это их вторая копия"


