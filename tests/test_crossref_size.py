# ПЕРЕПОЛНЕНИЕ ПРЕДЕЛА ОБЯЗАНО ВАЛИТЬ ПРОГОН, А СБОЙ СЕТИ — НЕТ
#
# Шаг публикации стоял под continue-on-error, и это верно для недоступного
# Cloudflare: разбор уже сделан, терять его из-за чужого сбоя незачем. Но тем же
# глушителем накрывало переполнение предела, а это беда другой природы — она не
# пройдёт сама, карточка товара навсегда останется на вчерашнем снимке, и прогон
# при этом отчитается успехом. 24.09.2026 проверка сработала ровно так, как
# задумано: прогон покраснел на переполнении, и страница осталась на вчерашнем.

def test_переполнение_и_сбой_сети_различаются_кодом():
    """Разные беды — разные коды возврата, иначе их глушат одинаково."""
    spec = importlib.util.spec_from_file_location(
        "kvant_publish_crossref", ROOT / "scripts" / "publish_crossref.py")
    мод = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(мод)
    assert мод.КОД_ПЕРЕПОЛНЕНИЯ == 2
    исходник = (ROOT / "scripts" / "publish_crossref.py").read_text()
    код = "\n".join(ln for ln in исходник.splitlines()
                    if not ln.lstrip().startswith("#"))
    # Переполнение отдаёт свой код, всё прочее — общий.
    assert 'SNAPSHOT_TOO_LARGE" else 1' in код
    assert "КОД_ПЕРЕПОЛНЕНИЯ if" in код


def test_прогон_красится_именно_на_переполнении():
    """Глушитель снят, а код возврата разбирается в самом прогоне."""
    import yaml
    d = yaml.safe_load((ROOT / ".github" / "workflows"
                        / "suppliers-quotes.yml").read_text())
    шаги = [s for тело in d["jobs"].values() for s in тело.get("steps", [])
            if "Снимок перекрёстной системы" in str(s.get("name", ""))]
    assert len(шаги) == 1, "шаг публикации снимка не найден или задвоен"
    шаг = шаги[0]
    assert "continue-on-error" not in шаг, (
        "глушитель накрывает и переполнение предела: прогон отчитается успехом, "
        "а карточка товара останется на вчерашнем снимке")
    run = шаг.get("run", "")
    assert "= 2" in run, "код переполнения в прогоне не разбирается"
    assert "::error::" in run, "переполнение обязано быть видно как ошибка"
    assert "::warning::" in run, "сбой сети обязан оставаться предупреждением"
