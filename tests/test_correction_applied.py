"""Записанная поправка обязана быть выполненной — или не называться выполненной.

ОПЛАЧЕНО 18.09.2026. В строке 1019431-1600 скептик записал: «числовые поля
очищены, цифра и разбор оставлены в тексте источника цены». Поля очищены не
были: price_low и price_high держали 106 200 USD. Первый же подсчёт разрыва по
заниженным строкам взял эту цифру и выдал 737 600 USD — вторую по величине
строку убытка в отчёте владельцу.

Такая запись опаснее отсутствия записи. Отсутствие видно, а ложное «сделано»
закрывает вопрос для следующего читателя, в том числе для меня самого через
сутки: я читаю поправку, верю ей и не проверяю поле.

Проверка узкая намеренно: ловится не любое расхождение слов с данными, а ровно
утверждение о ВЫПОЛНЕННОЙ очистке числового поля цены. Закрытый список формул,
как велит правило «обвиняй только закрытым списком»: обвинить строку по
глагольной форме нельзя — разбор цены полон слов «снять», «убрать», «очистить»
в обсуждении того, что СЛЕДУЕТ сделать.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RV = ROOT / "gt/data/ship_reverify.json"

#: Утверждение о выполненной очистке — совершённый вид, закрытым списком.
CLAIM = re.compile(r"числовые поля (?:цены )?очищены|поле цены очищено|"
                   r"цифра из поля цены (?:снята|убрана)|убрана из поля цены|"
                   r"снята из поля цены", re.I)


def rows() -> list[dict]:
    return json.loads(RV.read_text(encoding="utf-8"))["rows"]


def test_заявленная_очистка_поля_цены_действительно_выполнена():
    broken = []
    for r in rows():
        for s in r.get("skeptics") or []:
            text = " ".join(str(v) for v in s.values())
            if not CLAIM.search(text):
                continue
            if isinstance(r.get("price_low"), (int, float)) or \
               isinstance(r.get("price_high"), (int, float)):
                broken.append((r.get("pn"), r.get("price_low"), r.get("price_high")))
    assert not broken, (
        "поправка заявляет очищенное поле цены, а число в нём стоит: "
        + "; ".join(f"{pn}: price_low={lo}, price_high={hi}" for pn, lo, hi in broken)
        + ". Либо выполнить правку, либо переписать поправку тем решением, которое принято.")


def test_проверка_различает_обещание_и_отчёт():
    """Сама проверка обязана ловить совершённый вид и не ловить намерение.

    Иначе она начнёт обвинять строки, где очистку только ОБСУЖДАЮТ, — а таких
    в разборе цен много, и тогда проверку отключат целиком.
    """
    assert CLAIM.search("числовые поля очищены, разбор оставлен в тексте")
    assert CLAIM.search("цифра из поля цены снята")
    assert not CLAIM.search("числовые поля надо очистить")
    assert not CLAIM.search("предлагаю снять цифру из поля цены")
    assert not CLAIM.search("цену снять нельзя: она единственная найденная")
