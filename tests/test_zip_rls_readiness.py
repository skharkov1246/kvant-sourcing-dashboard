# ────────────────────────────────────────────────────────────── представления
# Прогон ужесточения 20.09.2026 19:36 уперся в mach_channels_ask и тем показал
# дыру в самой миграции: это ПРЕДСТАВЛЕНИЕ «select * from mach_channels», то есть
# ровно та таблица, которую ступень 1 закрывает. Обычное представление
# исполняется правами владельца и RLS таблиц под собой не применяет, поэтому
# закрытие таблицы без закрытия вида не закрывает ничего — данные читаются через
# другое имя.
#
# Проверено на живом PostgreSQL 16: таблица 3 строки / вид 3 строки → закрыли
# только таблицу → таблица «permission denied», ВИД ВСЁ ЕЩЁ ОТДАЁТ 3 → применили
# ступень целиком → отказ и там и там.
#
# Тест статический: гейт не поднимает Postgres. Он стережёт не поведение, а то,
# что обе ступени вообще помнят про представления.

ФАЙЛЫ_СТУПЕНЕЙ = ("zip/supabase/migrations_rls_stage1.sql",
                  "zip/supabase/migrations_rls_stage2.sql")


def test_обе_ступени_снимают_права_с_представлений():
    for путь in ФАЙЛЫ_СТУПЕНЕЙ:
        текст = (ROOT / путь).read_text(encoding="utf-8")
        assert "view_table_usage" in текст, (
            f"{путь}: представления над закрытыми таблицами не обрабатываются. "
            "Закрытая таблица и открытый вид над ней — это открытая таблица")
        # Проверяем, что вид ЛИШАЕТСЯ прав, но не дословную форму оператора: роли
        # теперь подставляются через zip_роли_которые_есть, иначе файл не
        # применится там, где ролей Supabase нет.
        блок_видов = текст[текст.index("view_table_usage"):]
        блок_видов = блок_видов[:блок_видов.index("end $$;")]
        assert "revoke all on table public.%I from" in блок_видов, (
            f"{путь}: у представления не снимаются права")


def test_представления_ищутся_по_зависимости_а_не_по_имени():
    """Вид может называться как угодно и читать закрытую таблицу."""
    текст = (ROOT / ФАЙЛЫ_СТУПЕНЕЙ[0]).read_text(encoding="utf-8")
    блок = текст[текст.index("view_table_usage"):]
    блок = блок[:блок.index("end $$;")]
    assert "u.table_name" in блок, (
        "фильтр обязан стоять на ТАБЛИЦЕ, которую вид читает, а не на его имени")
    assert "u.view_name like" not in блок


def test_проверка_ступени_1_называет_забытые_таблицы():
    """«осталось 3 прав» — это и одна таблица с тремя грантами, и три таблицы."""
    текст = (ROOT / ФАЙЛЫ_СТУПЕНЕЙ[0]).read_text(encoding="utf-8")
    assert "string_agg(distinct g.table_name" in текст
    assert "остались права на таблицы ступени 1: %" in текст


def test_виды_с_security_invoker_не_трогаются():
    """Закрываем то, что течёт, а не всё подряд.

    Вид с security_invoker исполняется правами ВЫЗЫВАЮЩЕГО, поэтому закрытую
    таблицу под собой он уже не отдаёт: проверено на PostgreSQL 16 — чтение
    такого вида роль anon получает «permission denied for table», хотя грант на
    сам вид остался. Снимать с него права нечего: в защите не выиграть ничего, а
    будущего читателя сломать можно. Три вида библиотеки заведены именно так.
    """
    for путь in ФАЙЛЫ_СТУПЕНЕЙ:
        текст = (ROOT / путь).read_text(encoding="utf-8")
        блок = текст[текст.index("view_table_usage"):]
        блок = блок[:блок.index("end $$;")]
        assert "security_invoker=true" in блок, (
            f"{путь}: ступень снимает права и с видов, которые RLS не обходят")
        assert "not coalesce('security_invoker=true'" in блок


