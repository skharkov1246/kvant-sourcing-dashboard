def test_ступени_применяются_без_ролей_supabase():
    """Ужесточение должно быть проверяемым не только на проде.

    anon, authenticated и service_role заводит платформа Supabase. Пока файлы
    называли их в revoke/grant безусловно, применить ступень к чистому PostgreSQL
    было нельзя: «role "anon" does not exist», и весь файл откатывался. Против
    прода это не проявляется никогда — там роли есть. Цена: за одну сессию роли
    трижды создавались руками, чтобы прогнать ступень локально.

    Проверка статическая: поднять базу в гейте нельзя, а условие видно в файле.
    Проверено прогоном на живом PostgreSQL 16 без ролей — обе ступени код 0, а с
    ролями закрытие таблицы и вида работает как прежде.
    """
    import re
    оператор = re.compile(r"\b(?:revoke|grant)\s+(?:all|select|insert|update|delete|usage)\b",
                          re.I)
    for путь in ФАЙЛЫ_СТУПЕНЕЙ:
        текст = (ROOT / путь).read_text(encoding="utf-8")
        assert "zip_роли_которые_есть" in текст, (
            f"{путь}: роли названы безусловно — файл не применится без Supabase")
        for строка in текст.splitlines():
            голая = строка.split("--")[0]
            if not оператор.search(голая):
                continue
            for роль in ("anon", "authenticated", "service_role"):
                assert роль not in голая, (
                    f"{путь}: роль {роль} в операторе напрямую: {строка.strip()}")
