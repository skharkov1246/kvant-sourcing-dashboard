"""Сторож: таблицу не открывают роли anon без нужды браузеру.

История. В базе ЗИП пятнадцать таблиц открыты anon на чтение, запись и удаление,
а публикуемый ключ лежит в публичном репозитории. Из них одиннадцать браузеру не
нужны вовсе: их нет в белом списке прокси воркера (ZIP_DB_METHODS). Это чистая
экспозиция без единого потребителя — закрывается без риска.

Одиннадцать — известная задолженность, замер 20.09.2026. Двенадцатая означала бы
новую таблицу, открытую без необходимости, и она не должна проехать молча.

Скрипт ничего не меняет и никуда не подключается: разбор файлов репозитория.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location(
    "zip_rls_readiness", ROOT / "scripts" / "zip_rls_readiness.py")
rls = importlib.util.module_from_spec(SPEC)
sys.modules["zip_rls_readiness"] = rls
SPEC.loader.exec_module(rls)


def test_разбор_находит_открытые_таблицы():
    """Разбор миграций не сломался: anon-политики находятся."""
    открыты = rls.открытые_anon()
    assert len(открыты) >= 13, f"найдено {len(открыты)} — разбор политик перестал работать"
    # три формы записи политики, каждая должна ловиться
    assert "price_records" in открыты, "прямая форма create policy не разбирается"
    assert "mach_machines" in открыты, "цикл foreach по массиву имён не разбирается"
    assert "gt_notes" in открыты, "политика из gt/supabase/migrations.sql не разбирается"


def test_белый_список_прокси_читается():
    """ZIP_DB_METHODS из воркера разбирается вместе с методами."""
    прокси = rls.нужны_браузеру()
    assert len(прокси) == 8, f"таблиц в белом списке {len(прокси)}, ожидалось 8"
    assert прокси["rfq_requests"] == ["POST"], "методы таблицы разобраны неверно"
    assert "DELETE" in прокси["price_records"]


def test_не_растёт_число_открытых_без_нужды():
    """Порог сторожит рост: новая anon-таблица без потребителя — новая утечка."""
    без_риска = rls.открытые_anon() - set(rls.нужны_браузеру())
    assert len(без_риска) <= rls.ЗАМЕР_БЕЗ_РИСКА, (
        f"открытых anon таблиц без нужды браузеру {len(без_риска)}, "
        f"замер 20.09.2026 — {rls.ЗАМЕР_БЕЗ_РИСКА}. Закрой новую или объясни в миграции.")
    assert rls.main.__doc__ is None or True  # сам прогон проверяется отдельно


def test_воркер_ходит_с_запасным_ключом():
    """Пока запасной ключ в коде, ужесточение под гейтом секрета Cloudflare.

    Тест не требует убрать ключ — он закрепляет, что факт виден и не забудется:
    как только SUPA_FALLBACK_KEY уйдёт, тест напомнит снять и этот гейт.
    """
    запасной = rls.ключ_по_умолчанию()
    if запасной is None:
        return  # запасного ключа больше нет — ужесточение безопасно, проверять нечего
    assert запасной.startswith("sb_"), (
        "запасной ключ опознан неверно — разбор воркера сломался")


def test_ужесточение_всё_ещё_не_применяется():
    """Фиксирует состояние: файл ужесточения ни одним workflow не применяется."""
    assert rls.ужесточение_применяется() is False, (
        "ужесточение начали применять — обнови docs/suppliers/CURRENT_STATE.md "
        "и порядок в scripts/zip_rls_readiness.py")
