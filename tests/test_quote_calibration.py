"""Прибор для разбора отказов правила цены обязан быть честным прибором.

ЗАЧЕМ. scripts/quote_price_calibration.py прогоняет правило чтения цены по
живым строкам предложений и раскладывает отказы по воротам. По его выводу
принимается решение, что чинить в разборщике, поэтому врать он не имеет права
трижды:

1. ВОРОТА ДОЛЖНЫ СОВПАДАТЬ С ПРАВИЛОМ. Если прибор говорит «тройка не сошлась»
   там, где правило на самом деле остановилось раньше, вывод отправит чинить
   арифметику вместо отбора строк.
2. ПРОФИЛЬ ОТКАЗА НЕ ДОЛЖЕН ВЫНОСИТЬ СОДЕРЖИМОЕ СТРОКИ. Репозиторий публичный,
   журнал прогона видят все: наружу идут только структура и собственные
   константы кода (CLAUDE.md, правило 17).
3. ЗАМЕР ПОДАВЛЕНИЯ АРТИКУЛА ДОЛЖЕН ЛОВИТЬ САМО ПОДАВЛЕНИЕ. Ради него прибор и
   написан: в строке КП денежное слово есть всегда, и защита «голое число при
   деньгах — это сумма» бьёт по номенклатурным номерам. Если однажды защиту
   поправят, тест обязан покраснеть, а не промолчать.

Корпус придуман (CLAUDE.md, правило 18).
"""
from __future__ import annotations

import importlib.util
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]


def прибор():
    spec = importlib.util.spec_from_file_location(
        "kvant_price_calibration", ROOT / "scripts" / "quote_price_calibration.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# КОРПУС. Придуманные строки предложений, по одной на каждые ворота.
ТРОЙКА = "1  Подшипник 6205-2RS SKF   10 шт   1 250,00   12 500,00"
ПАРА_С_ВАЛЮТОЙ = "Подшипник 6205 ZZ, цена 1 250,00 руб/шт"
ЕДИНИЦА_БЕЗ_СУММЫ = "Уплотнение торцевое 22315 EK   4 шт   3 400,00 руб"
ШУМ = "ИТОГО с НДС 20%   1 234 567,00"
БЕЗ_БУКВ = "2 3 6"
БЕЗ_ЧИСЕЛ = "Крыльчатка насоса в сборе, чертёж заказчика"


def test_ворота_совпадают_с_правилом():
    """Каждая придуманная строка останавливается там, где и должна."""
    м = прибор()
    assert м.ворота(ТРОЙКА)[0] == "ЦЕНА ПРОЧИТАНА"
    assert м.ворота(ШУМ)[0] == "шум (НДС, итого, скидка)"
    assert м.ворота(БЕЗ_БУКВ)[0] == "меньше четырёх букв"
    assert м.ворота(ПАРА_С_ВАЛЮТОЙ)[0] == "чисел в строке: 2"
    assert м.ворота(БЕЗ_ЧИСЕЛ)[0] == "чисел в строке: 0"
    # Три числа есть (4, 3400 и разряды), а тройка не сходится.
    assert м.ворота(ЕДИНИЦА_БЕЗ_СУММЫ)[0] == "тройка не сошлась"


def test_ворота_не_опережают_правило():
    """«ЦЕНА ПРОЧИТАНА» ставится ровно тогда, когда правило и вправду её дало.

    Мутация «признавать цену по трём числам без проверки арифметики» обязана
    разойтись с правилом на строке, где тройка не сошлась.
    """
    м = прибор()
    from library import quotes
    for строка in (ТРОЙКА, ПАРА_С_ВАЛЮТОЙ, ЕДИНИЦА_БЕЗ_СУММЫ, ШУМ, БЕЗ_БУКВ, БЕЗ_ЧИСЕЛ):
        прочитана = м.ворота(строка)[0] == "ЦЕНА ПРОЧИТАНА"
        assert прочитана == (quotes.цена_из_текста(строка) is not None), строка


def test_профиль_не_выносит_содержимое_строки():
    """Ловушка 2: наружу идёт структура, а не текст. Репозиторий публичный.

    Проверяется ИМЕННО та строка, что попадает в журнал, — ключ_профиля.
    Первая версия теста стерегла возвращаемое значение ворот, а ключ собирался
    отдельно в цикле печати: подстановка текста строки в ключ тест не роняла.
    """
    м = прибор()
    for строка in (ТРОЙКА, ПАРА_С_ВАЛЮТОЙ, ЕДИНИЦА_БЕЗ_СУММЫ, БЕЗ_ЧИСЕЛ):
        причина, проф = м.ворота(строка)
        # В профиле только булевы признаки и счёт чисел.
        assert set(проф) <= {"валюта", "единица", "артикул", "чисел"}
        for v in проф.values():
            assert isinstance(v, (bool, int))
        ключ = м.ключ_профиля(причина, проф.get("чисел", 0),
                              проф["валюта"], проф["артикул"])
        # Ни одного слова строки длиннее трёх букв в журнальном ключе.
        слова = {w.lower() for w in re.findall(r"[A-Za-zА-Яа-яЁё]{4,}", строка)}
        в_ключе = set(re.findall(r"[A-Za-zА-Яа-яЁё]{4,}", ключ.lower()))
        assert not (слова & в_ключе), (строка, ключ)
        # И ни одной цифры, кроме счёта чисел.
        assert re.sub(r"чисел \d+", "", ключ).count("0") == 0 or "чисел 0" in ключ


def test_чужая_причина_в_журнал_не_попадает():
    """Закрытый список ворот: всё, чего в нём нет, обезличивается.

    Без этого достаточно одной новой ветки в ворота(), возвращающей причину с
    куском строки, — и она уедет в публичный журнал целиком.
    """
    м = прибор()
    ключ = м.ключ_профиля("Подшипник 6205 ZZ не разобран", 3, True, True)
    assert ключ.startswith("(неизвестные ворота)")
    assert "6205" not in ключ and "одшипник" not in ключ
    # А законная причина проходит как есть.
    assert м.ключ_профиля("тройка не сошлась", 3, True, True).startswith(
        "тройка не сошлась")
    assert м.ключ_профиля("чисел в строке: 2", 2, False, True).startswith(
        "чисел в строке: 2")


def test_в_ключ_нельзя_подсунуть_текст_ни_одним_полем():
    """Мутация, выжившая у первой версии: текст, положенный в профиль.

    Ключ строится из скаляров, поэтому текст, поданный на место любого поля,
    превращается в «да» или в число — но наружу не выходит.
    """
    м = прибор()
    ключ = м.ключ_профиля("тройка не сошлась", 3,
                          "Подшипник 6205 ZZ", "SKF 22315 EK")
    assert "6205" not in ключ and "SKF" not in ключ and "22315" not in ключ
    assert ключ == "тройка не сошлась · чисел 3 · валюта да · артикул да"
    # Текст на месте счёта чисел обязан уронить прибор, а не уехать в журнал:
    # int() от него не берётся, и это правильный исход — отказ, а не утечка.
    with pytest.raises(ValueError):
        м.ключ_профиля("тройка не сошлась", "Подшипник 6205 ZZ", True, True)


def test_подавление_артикула_денежным_словом_измеряется():
    """Ловушка 3: ради этого замера прибор и написан.

    «Подшипник 6205 ZZ, цена 1 250,00 руб/шт» — код в строке есть и он
    однозначен. part_number_of возвращает пусто: в строке денежные слова, а
    защита запрещает принимать голое число за артикул. Уберём денежные слова —
    артикул находится. Это и есть цена защиты на строках предложений.
    """
    from library import docfilter
    assert docfilter.MONEY.search(ПАРА_С_ВАЛЮТОЙ)
    assert docfilter.part_number_of(ПАРА_С_ВАЛЮТОЙ) == ""
    без_денег = docfilter.MONEY.sub(" ", ПАРА_С_ВАЛЮТОЙ)
    assert docfilter.part_number_of(без_денег) == "6205"


def test_кандидаты_берут_то_на_что_рассчитаны():
    м = прибор()
    # К1: число вплотную к валюте.
    assert м.к1_число_при_валюте(ПАРА_С_ВАЛЮТОЙ) == 1250.0
    assert м.к1_число_при_валюте(БЕЗ_ЧИСЕЛ) is None
    # К2: пара «кол-во ед. цена» — единственное число после слова единицы.
    assert м.к2_пара_количество_цена(ЕДИНИЦА_БЕЗ_СУММЫ) == 3400.0
    # У тройки после «шт» стоят два числа: цена и сумма. Различить их нечем,
    # поэтому К2 обязан молчать, а не брать первое попавшееся.
    assert м.к2_пара_количество_цена(ТРОЙКА) is None
    # К3 требует и валюту, и артикул разом.
    assert м.к3_последнее_число_при_артикуле(ЕДИНИЦА_БЕЗ_СУММЫ) == 3400.0
    assert м.к3_последнее_число_при_артикуле(БЕЗ_ЧИСЕЛ) is None


def test_кандидат_не_спорит_с_арифметикой_там_где_она_ответила():
    """Проверка на удержание: на известной строке кандидат обязан сойтись.

    Строка с сошедшейся тройкой И названной валютой — единственное место, где
    ответ известен и проверяем. Кандидат, называющий здесь другое число, на
    неизвестных строках доверия не заслуживает.
    """
    м = прибор()
    from library import quotes
    известная = "Вал ротора TRZ-4471/2   1 шт   985 000,00 руб   985 000,00 руб"
    эталон = quotes.цена_из_текста(известная)
    assert эталон is not None and эталон["price"] == 985000.0
    assert м.к1_число_при_валюте(известная) == эталон["price"]
