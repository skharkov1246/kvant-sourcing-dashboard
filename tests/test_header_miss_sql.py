"""Причина «шапки нет» доезжает до базы ОБЕИМИ вставками.

Правило 14 (CLAUDE.md): две записи в одну таблицу правятся вместе. У lib_files
таких записей две — пакетная в library/indexer.py и построчный UPDATE в
library/reparse.py. Колонка, добавленная в одну, роняет вторую на каждом файле,
а файл к тому моменту уже отмечен разобранным.

Обе записи строятся по списку колонок, которые есть в базе (indexer.вставка_файлов,
reparse.правка_файла), а значения берут из одного места (indexer.строка_файла).
Поэтому проверка держится за ПОВЕДЕНИЕ — сгенерированный запрос и кортеж
значений, — а не за написание кода: прежняя, по тексту исходника, падала от
перестановки при сохранном поведении (CLAUDE.md, стиль работы). Схема и прочие
файлы читаются как текст; разбор исходника читает КОД, а не комментарии,
поэтому строки с `--` и `#` снимаются.
"""
from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent


def запись_файла() -> dict:
    """Запись файла со всеми ключами, как её собирает handle(), и непустыми
    значениями проверяемых колонок."""
    rec = {к: None for к in ("kind", "size_bytes", "reason", "segment_id", "sha256",
                             "parse_path", "header_found", "doc_class", "class_rule",
                             "text_lines", "item_lines", "field_title", "side",
                             "doc_kind_conf", "doc_kind_why", "read_chain", "our_company")}
    rec.update(file_id="5", deal_id="11", origin="поле запроса", field="ufCrm18_1731179998",
               status="разобран", chars=10, rows_found=0, header_miss="нет цены в шапке",
               pdf_pages=3, pdf_pages_text=2, pdf_pages_lost=1, pdf_mixed=True,
               subkind="pdf_текст", doc_kind="предложение поставщика нам")
    return rec


def вставка() -> tuple[str, tuple]:
    from library import indexer
    колонки = indexer.КОЛОНКИ_ВСТАВКИ
    запрос, шаблон = indexer.вставка_файлов(колонки)
    строка = indexer.кортеж_файла(запись_файла(), колонки)
    assert шаблон.count("%s") == len(строка)
    return запрос, dict(zip(колонки, строка))


def правка() -> tuple[str, dict]:
    import library.reparse as r
    колонки = r.КОЛОНКИ_ЗАПИСИ
    sql = r.правка_файла(колонки)
    значения = r.значения_правки(запись_файла(), колонки)
    assert sql.count("%s") == len(значения)
    return sql, dict(zip(колонки, значения))


def код(путь: str) -> str:
    текст = (КОРЕНЬ / путь).read_text(encoding="utf-8")
    без_sql = re.sub(r"--[^\n]*", "", текст)
    return re.sub(r"(?<!\w)#[^\n]*", "", без_sql)


def запрос(текст: str, начало: str, конец: str) -> str:
    """Сам запрос, а не весь файл.

    Первая редакция этой проверки считала вхождения «header_miss» по файлу
    целиком — и мутация «снять колонку из UPDATE» её ПЕРЕЖИЛА: счёт добирался
    строками разбора причин, которые к записи отношения не имеют. Проверять надо
    тот отрезок кода, который исполняется при записи.
    """
    i = текст.index(начало)
    return текст[i:текст.index(конец, i) + len(конец)]


def test_пакетная_вставка_indexer_несёт_причину():
    запрос, значения = вставка()
    assert "header_miss" in запрос.split("values")[0], "нет в списке колонок"
    assert "header_miss = excluded.header_miss" in запрос, "нет в on conflict do update"


def test_значение_причины_подставляется_в_кортеж_вставки():
    _, значения = вставка()
    assert значения["header_miss"] == "нет цены в шапке", "колонка есть, а значения нет"


def test_построчный_update_переразбора_несёт_причину():
    sql, значения = правка()
    assert "header_miss = %s" in sql, "нет в set"
    assert значения["header_miss"] == "нет цены в шапке", "нет значения в кортеже UPDATE"


def test_колонка_заведена_в_схеме_добавлением_а_не_созданием():
    """`create table if not exists` существующую таблицу НЕ меняет (правило 21)."""
    схема = код("library/supabase/schema_junk.sql")
    m = re.search(r"alter table lib_files add column if not exists\s+header_miss", схема)
    assert m, "колонки header_miss нет в схеме или она заведена не через alter"


def test_переразбор_проверяет_колонки_до_записи():
    """Схема в файле может уйти вперёд базы, и это уже случилось.

    23.09.2026: колонка header_miss была добавлена в schema_junk.sql, миграцию
    никто не применил, и запись упала на первом же файле с причиной — успев
    записать часть файлов в каждой из пятидесяти частей. Проверка обязана стоять
    ДО обхода портала и перечислять ровно те колонки, которые называет UPDATE.
    Что она делает при нехватке (останавливает запись только без обязательной
    колонки, холостой прогон — никогда) — проверено поведением в
    tests/test_folder_wiring.py.
    """
    import library.reparse as r
    sql, _ = правка()
    названные = set(re.findall(r"(\w+) = (?:%s|coalesce\(%s)", sql[:sql.index("where")]))
    assert названные == set(r.КОЛОНКИ_ЗАПИСИ), \
        f"UPDATE и проверка разошлись: {sorted(названные ^ set(r.КОЛОНКИ_ЗАПИСИ))}"
    # И проверка должна стоять РАНЬШЕ обхода портала: иначе половина уже записана.
    текст = код("library/reparse.py")
    assert текст.index("колонки_базы(") < текст.index("collect_refs"), \
        "проверка колонок стоит после обхода портала"


def test_постраничные_счётчики_pdf_доезжают_обеими_записями():
    """Правило 14: две записи в одну таблицу правятся вместе.

    Смешанный PDF виден только по этим счётчикам; если их пишет одна запись из
    двух, переразобранный файл теряет пометку, и распознавание снова его не берёт.
    """
    for имя, (запрос, значения) in (("вставка разбора", вставка()),
                                    ("UPDATE переразбора", правка())):
        for колонка, ждём in (("pdf_pages", 3), ("pdf_pages_text", 2),
                              ("pdf_pages_lost", 1), ("pdf_mixed", True)):
            assert re.search(rf"(?<!\w){колонка}(?!\w)", запрос), f"{имя}: {колонка} не пишется"
            assert значения[колонка] == ждём, f"{имя}: {колонка} без значения"


def test_отбор_распознавания_берёт_смешанные_pdf():
    """Прежний отбор не брал их НИКОГДА: статус «разобран», chars > 0."""
    текст = код("library/ocr.py")
    отбор = запрос(текст, "CANDIDATES = ", '"""', )
    assert "pdf_mixed" in код("library/ocr.py"), "отбор не знает про смешанные PDF"
    assert "ocr_at is null" in текст


def test_отметка_распознавания_не_ставится_при_отказе_окружения():
    """Иначе один неудачный прогон выбрасывает файл из очереди навсегда.

    23.09.2026 так и вышло: распознавание падало по таймауту на 69 % файлов
    из-за потоков внутри tesseract, и 3 666 картинок остались с отметкой.
    """
    текст = код("library/ocr.py")
    assert "def виновато_окружение" in текст
    assert "coalesce(excluded.ocr_at, lib_files.ocr_at)" in текст, \
        "отметка ставится безусловным now(): отказ окружения выбросит файл из очереди"
    assert "ocr_at = now()" not in текст, "остался безусловный now()"


def test_повтор_отказавших_есть_и_включается_входом():
    """3 666 картинок помечены прежними прогонами, и обычный отбор их не берёт.

    Отметка ставилась за любой исход, в том числе за таймаут по вине потоков
    внутри tesseract. Потоки починены, отметка исправлена — но уже помеченные
    файлы вернуть в очередь нечем, кроме отдельного входа.
    """
    текст = код("library/ocr.py")
    assert "ПОВТОР_ОТКАЗАВШИХ" in текст, "нет отбора для повтора отказавших"
    assert 'os.environ.get("OCR_RETRY"' in текст, "повтор не включается входом"
    # Повтор берёт только файлы БЕЗ позиций: перечитывать удавшиеся незачем.
    отбор = запрос(текст, "ПОВТОР_ОТКАЗАВШИХ = ", '"""')
    assert "coalesce(rows_found, 0) = 0" in текст, "повтор возьмёт и прочитанные файлы"
    yml = код(".github/workflows/library-index.yml")
    assert "ocr_retry:" in yml and "OCR_RETRY:" in yml, "входа прогона нет"
    import re
    assert not re.search(r"OCR_RETRY=\S+\s+python", yml), "значение прибито в шаге"


def test_распознавание_не_затирает_статус_разбора():
    """Файл оказался не сканом — статус ставил разбор, и он должен остаться.

    Замер 23.09.2026: 1 022 файла xlsx/docx с причиной «распознавать нечего»,
    плюс 245 в «прочем» и 129 в архивах. Это распознавание писало «формат не
    читаем» поверх результата разбора и делало вид, будто файл нечитаем вовсе.
    """
    текст = код("library/ocr.py")
    assert "распознавать нечего" not in текст, "распознавание снова ставит свой статус"
    assert "status = coalesce(excluded.status, lib_files.status)" in текст, \
        "пустой статус затрёт чужой"
    # Не только статус: причина и счётчики тоже не должны затираться.
    for поле in ("reason", "chars", "rows_found"):
        assert f"{поле} = case when excluded.status is null" in текст, \
            f"{поле} затирается при «не моё дело»"
