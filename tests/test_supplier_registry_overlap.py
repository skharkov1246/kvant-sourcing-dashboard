"""Правило сведения реестров опирается на замер, а не на догадку.

Замер 20.09.2026 по пяти файловым реестрам (шестой, Bitrix, лежит в базе):

  • домен сильнее имени: 61 домен несёт по два и больше разных написания,
    144 строки за ними. По ship_sellers против pnw домен дал 41 совпадение
    против 17 по имени;
  • имя почти безопасно: 4 имени из 2394 указывают на разные домены, 0,17 %;
  • досье ГТУ совпадают с pnw на 878 имён, но НИ ОДНОГО сайта у них нет —
    проверить доменом нечем.

Здесь закреплены сами функции нормализации (на придуманных строках, правило 18)
и порядок величин замера. Тест сторожит две вещи: что нормализация не начала
склеивать лишнее и что соотношение «домен против имени» не перевернулось молча —
если перевернётся, правило сведения надо пересматривать, а не подкручивать.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location(
    "supplier_registry_overlap", ROOT / "scripts" / "supplier_registry_overlap.py")
ov = importlib.util.module_from_spec(SPEC)
sys.modules["supplier_registry_overlap"] = ov
SPEC.loader.exec_module(ov)


def test_правовая_форма_не_различает_компании():
    """«ABC GmbH» и «ABC Ltd» — одно имя: форму отбрасываем."""
    assert ov.norm_name("Придуманная ABC GmbH") == ov.norm_name("Придуманная ABC Ltd")
    assert ov.norm_name('ООО "Придуманный Завод"') == ov.norm_name("Придуманный Завод")
    assert ov.norm_name("A.B.C. Corp.") == ov.norm_name("ABC")


def test_нормализация_не_склеивает_разное():
    """Сторож от обратной беды: разные компании не должны сойтись."""
    assert ov.norm_name("Придуманный Насос") != ov.norm_name("Придуманный Компрессор")
    assert ov.norm_name("Завод 12") != ov.norm_name("Завод 21")
    assert ov.norm_name("") == ""
    assert ov.norm_name(None) == ""


def test_домен_чистится_и_отбрасывает_почтовики():
    assert ov.norm_domain("https://www.pridumanny.example.com/about") == "pridumanny.example.com"
    assert ov.norm_domain("PRIDUMANNY.EXAMPLE.COM") == "pridumanny.example.com"
    # почтовый хостинг компанию не опознаёт
    assert ov.norm_domain("mail.ru") == ""
    assert ov.norm_domain("gmail.com") == ""
    assert ov.norm_domain("не адрес") == ""
    assert ov.norm_domain(None) == ""


def test_маска_домена_скрывает_адрес():
    assert ov.маска("pridumanny.example.com") == "pr….com"
    assert ov.маска("a.ru").endswith(".ru")


def test_реестры_читаются_и_объёмы_не_обвалились():
    """Если набор переименовали или сломали, замер обязан это показать."""
    наборы = ov.читать()
    assert set(наборы) >= {"pnw/supplier_master", "gt/dossiers", "gt/ship_sellers"}, (
        f"реестры не прочитались: {sorted(наборы)}")
    строк = sum(len(v) for v in наборы.values())
    assert строк >= 3500, f"строк во всех реестрах {строк}, замер 20.09.2026 — 3874"
    # у досье действительно нет сайтов: на этом стоит вывод, что их нечем проверить
    досье = наборы["gt/dossiers"]
    assert sum(1 for _, d in досье if d) == 0, (
        "у досье ГТУ появились сайты — правило сведения для них можно усилить доменом")


def test_домен_находит_больше_имени():
    """Ключевое соотношение замера: перевернётся — правило пересматривать.

    Один домен под несколькими написаниями — это ровно те слияния, которые
    сведение по имени пропустит. Их обязано быть заметно больше, чем спорных
    имён, иначе домен не окупает себя как основной признак.
    """
    наборы = ov.читать()
    пары = [(n, d) for строки in наборы.values() for n, d in строки if n and d]
    домены_имени: dict[str, set[str]] = {}
    имена_домена: dict[str, set[str]] = {}
    for n, d in пары:
        домены_имени.setdefault(n, set()).add(d)
        имена_домена.setdefault(d, set()).add(n)

    спорных = sum(1 for v in домены_имени.values() if len(v) > 1)
    многоимённых = sum(1 for v in имена_домена.values() if len(v) > 1)

    assert многоимённых > спорных * 5, (
        f"доменов с несколькими написаниями {многоимённых}, спорных имён {спорных}. "
        "Замер 20.09.2026 давал 61 против 4 — если соотношение сошлось, "
        "домен перестал быть сильнейшим признаком и правило надо пересмотреть")
    доля = спорных / max(len(домены_имени), 1)
    assert доля < 0.02, (
        f"имён, указывающих на разные домены, {100 * доля:.2f} % — было 0,17 %. "
        "Сведение по имени стало опаснее: порог обязан пересматриваться замером")
