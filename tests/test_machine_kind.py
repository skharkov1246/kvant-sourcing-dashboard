def test_точность_правила_держится_порогом_по_эталону():
    """Мерило правила — ручной эталон, а не впечатление.

    Проверка запускает scripts/machine_segment_check.py с теми же порогами, что
    стоят в гейте: упавшая точность обязана ломать сборку, а не тихо снижать
    заполняемость клетки «Машина»."""
    р = subprocess.run([sys.executable, "scripts/machine_segment_check.py",
                        "--min-precision", "98", "--min-coverage", "99"],
                       cwd=ROOT, capture_output=True, text=True)
    assert р.returncode == 0, р.stdout + р.stderr


def test_эталон_покрывает_весь_источник():
    """Эталон обязан размечать ВСЕ обозначения источника.

    Иначе точность считается по удобной выборке: обозначение, которое правило
    путает, просто не попадёт в эталон."""
    эт = json.loads((ROOT / "data" / "machine_truth.json").read_text(encoding="utf-8"))
    имена = {r["обозначение"] for r in эт["строки"]}
    источник = {r.get("mach") for r in
                json.loads((ROOT / "gt/data/pn_db.json").read_text(encoding="utf-8"))["rows"]
                if r.get("mach")}
    assert not (источник - имена), f"в эталоне нет {len(источник - имена)} обозначений"
    assert все_виды(эт) == {"машина", "черновик", "не машина", "не опознать"}


def все_виды(эт: dict) -> set[str]:
    return {r["вид"] for r in эт["строки"]}


def test_клетка_машины_не_склеивает_разные_исполнения():
    """Близкие обозначения — не одна машина, и склеивать их нельзя.

    Склейка по вхождению («RB211» входит в «RB211-535» — значит одна турбина»)
    из пятнадцати склеек шесть сделала неверно: SGT-100 и SGT-100-2S —
    одновальная и двухвальная, Taurus 70 и Taurus 70MD — разные модели,
    Charmec 1605 B и 1605 BE — разные машины. Счётчик обязан держать их
    отдельно; завысить клетку на исполнение честнее, чем потерять машину."""
    import importlib.util
    спец = importlib.util.spec_from_file_location(
        "kvant_chain", ROOT / "scripts" / "build_chain_coverage.py")
    счётчик = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(счётчик)
    assert not hasattr(счётчик, "слить_по_вхождению"), \
        "склейка по вхождению вернулась — она сливает разные исполнения"
    # марка снимается, исполнение — нет
    assert счётчик.mkey_model("Rolls-Royce RR Olympus") == счётчик.mkey_model("Olympus")
    assert счётчик.mkey_model("SGT-100") != счётчик.mkey_model("SGT-100-2S")
    assert счётчик.mkey_model("Taurus 70") != счётчик.mkey_model("Taurus 70MD")
