def test_клетка_машины_не_склеивает_разные_исполнения():
    """Близкие обозначения — не одна машина, и склеивать их нельзя.

    Склейка по вхождению («RB211» входит в «RB211-535» — значит одна турбина»)
    из пятнадцати склеек шесть сделала неверно: SGT-100 и SGT-100-2S —
    одновальная и двухвальная, Taurus 70 и Taurus 70MD — разные модели,
    Charmec 1605 B и 1605 BE — разные машины. Счётчик обязан держать их
    отдельно; завысить клетку на исполнение честнее, чем потерять машину."""
    import importlib.util
