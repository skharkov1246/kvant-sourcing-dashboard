def test_массовые_машины_не_теряются_на_границе_слова():
    """Замыкающий \\b в семействах ломает правило молча.

    В LM2500 граница слова после «LM2» не наступает, и с замыкающим \\b самые
    массовые машины базы — LM2500 (3 664 позиции) и LM6000 (1 761) — уходят в
    «не опознать». 09.10.2026 я вернул эту границу правкой и потерял обе."""
    for имя in ("LM2500", "LM6000", "GE LMS100", "RB211-535", "SGT-400",
                "Taurus 60S", "GE Frame 6B", "Titan 130"):
        р = mk.разобрать(имя)
        assert р.вид == "машина", f"{имя}: вид {р.вид}"
        assert р.направление == "gtu", f"{имя}: направление {р.направление}"


def test_слово_детали_раньше_слова_машины_значит_деталь():
    """Главное слово русского названия стоит первым, и решает оно.

    «Фильтр масляный турбокомпрессора» — фильтр, а не компрессор. Общее правило
    «есть слово компрессор — значит машина» давало 4 ложные машины из 52."""
    for имя in ("Фильтр масляный турбокомпрессора", "Фильтрующий элемент для компрессора",
                "Бумажная вставка центробежного насоса", "Блок охлаждения буровой лебедки",
                "Ремонтный комплект обратного клапана для компрессора", "ЗАПЧАСТИ ПРИВОДА",
                "Шкаф управления насосной станции"):
        assert mk.разобрать(имя).вид == "не машина", имя
    # и наоборот: машина впереди детали остаётся машиной
    assert mk.разобрать("Насос высокого давления с масляным фильтром Дэмо 7.2").направление == "pumps"


def test_составное_обозначение_разбирается_на_машины():
    """Одна строка поля может называть несколько машин.

    Прежде «Taurus 70 и Taurus 70MD (унифицированнные)» давало ОДНУ запись
    реестра с таким именем, и 43 настоящие модели ГТУ выглядели как 66."""
    assert mk.разобрать("Taurus 70, Taurus 70MD").модели == ("Taurus 70", "Taurus 70MD")
    assert mk.разобрать("Taurus 70/70MD").модели == ("Taurus 70", "Taurus 70MD")
    assert mk.разобрать("SGT-100 / SGT-400").модели == ("SGT-100", "SGT-400")
    # часть, которая машины не называет, выбрасывается, а не становится машиной
    assert mk.разобрать("Taurus 70, Шкаф управления PMS").модели == ("Taurus 70",)


def test_косая_без_пробелов_не_рвет_код_изготовителя():
    """Косая чаще входит в код, чем делит его.

    «Multitec V50/8A-4.1 20.181» — один насос, и обозначение обрезалось до
    «Multitec V50»; «Pompetravaini TCH TRSA 200-2500/C/SX» разваливалось на три
    машины; «AC/DC 24V» теряло половину. Делит она только братские обозначения:
    короткое сокращение с цифры либо самостоятельное обозначение машины."""
    for имя in ("Multitec V50/8A-4.1 20.181", "SKC62/F",
                "Насос дистиллята Pompetravaini TCH 100-315/1X-RK/A4-T"):
        assert mk.разобрать(имя).модели == (имя,), имя
    assert mk.разобрать("Saturn/Centaur").модели == ("Saturn", "Centaur")
    assert mk.разобрать("GE Frame 5/6").модели == ("GE Frame 5", "GE Frame 6")
    assert mk.разобрать("SGT-400/800").модели == ("SGT-400", "SGT-800")


def test_направление_важнее_места_в_строке():
    """«вне» — это признание, что направления нет, а не соперник направления.

    В «центробежный компрессор Solar» слово «компрессор» стоит раньше бренда,
    но направление называет именно бренд. Пока «вне» соревновалось по месту в
    строке, две машины ГТУ уходили в «вне»."""
    assert mk.разобрать("центробежный компрессор Solar").направление == "gtu"
    assert mk.разобрать("Solar COMPRESSOR").направление == "gtu"
    # а машина, которой направления действительно нет, в «вне» и остаётся
    for имя in ("Лебедка буровая SSGD-500", "Превентор универсальный гидравлический",
                "Верхний привод TDS-8SA", "Цементировочный агрегат CPS-763"):
        р = mk.разобрать(имя)
        assert р.направление == mk.ВНЕ, f"{имя}: {р.направление}"
        assert р.направление not in mk.НАПРАВЛЕНИЯ


def test_машина_без_модели_идет_в_черновик():
    """Вид машины — ещё не модель: заполненной клетку делает модель.

    «Электродвигатель» — это вид, по нему нельзя ни запросить запчасть, ни
    найти узел. Такая запись идёт в черновик, а не в заполненное."""
    for имя in ("Электродвигатель", "Датчик температуры", "Контроллер", "Вентилятор",
                "Насос циркуляционный ОЖ", "Solar Centaur", "Saturn"):
        assert mk.разобрать(имя).вид == "черновик", имя
    for имя, напр in (("Электродвигатель AMI 500L2W BSFH", "electro"),
                      ("Буровой насос 12T1600", "pumps"),
                      ("Saturn 20", "gtu")):
        р = mk.разобрать(имя)
        assert р.вид == "машина", имя
        assert р.направление == напр, имя


def test_размер_и_величина_моделью_не_считаются():
    """Дюймы колеса и обороты — не обозначение модели.

    «Насос центробежные с электроприводом 8Х6Х14» — это размеры рабочего
    колеса; «1,2 KW; 705r/min» — мощность и обороты. Если считать их моделью,
    клетка «Машина» заполнится величинами."""
    assert mk.разобрать("Насос центробежные с электроприводом 8Х6Х14").вид == "черновик"
    assert mk.разобрать("Насос центробежные с электроприводом 5x6").вид == "черновик"
    assert mk.разобрать("Эл. двигатель эл. двигатель 1,2 KW; 705r/min").вид == "черновик"


def test_корзина_бренда_и_признание_незнания_машиной_не_считаются():
    """«Solar (сток)» — ярлык партии, «не указана» — признание незнания.

    Догадка тоже не знание: «вероятно Mars» направления не даёт, и две семьи
    в скобках («Centaur/Taurus») — тоже."""
    for имя in ("Solar (сток)", "Solar (общая)", "Solar пакет", "не указана",
                "не указана (вероятно Mars)", "не указана (Centaur/Taurus)",
                "не указана (каталог Saturn–Mars)", "пакетная (мульти-модель)"):
        assert mk.разобрать(имя).вид == "не опознать", имя
    # а модель, выведенная по серии и названная однозначно, — черновик направления
    р = mk.разобрать("не указана (Centaur 50 по серии 196xxx)")
    assert (р.вид, р.направление) == ("черновик", "gtu")


