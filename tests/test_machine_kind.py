"""Правило разбора обозначения машины: вид, направление, список моделей.

Обозначения в корпусе — публичные индексы машин (LM2500, Taurus 70MD) и
придуманные строки той же формы. Ни заказчиков, ни цен, ни поставщиков здесь
нет и быть не может (CLAUDE.md, правило 18).
"""
from __future__ import annotations

