def test_эталон_покрывает_весь_источник():
    """Эталон обязан размечать ВСЕ обозначения источника.

    Иначе точность считается по удобной выборке: обозначение, которое правило
    путает, просто не попадёт в эталон."""
    эт = json.loads((ROOT / "data" / "machine_truth.json").read_text(encoding="utf-8"))
    имена = {r["обозначение"] for r in эт["строки"]}
    источник = {r.get("mach") for r in
                json.loads((ROOT / "gt/data/pn_db.json").read_text(encoding="utf-8"))["rows"]
                if r.get("mach")}
    assert not (источник - имена), f"в эталоне нет {len(источник - имена)} обозначений"
    # Проверка ДВУСТОРОННЯЯ: придуманное обозначение, которого в источнике нет,
    # эталон пронёс бы при одностороннем вложении, и метрика считалась бы по
    # корпусу, которого в базе не существует.
    assert not (имена - источник), f"в эталоне {len(имена - источник)} лишних обозначений"
    assert все_виды(эт) == {"машина", "черновик", "не машина", "не опознать"}
    # Поле «модели» обязано стоять у каждой машины и каждого черновика: иначе
    # знаменатель замера выбирает сам эталон (так «41 из 41 = 100 %» и вышло).
    без = [r["обозначение"] for r in эт["строки"]
           if r["вид"] in ("машина", "черновик") and not r.get("модели")]
    assert not без, f"без поля «модели»: {len(без)}, напр. {без[:3]}"
    # и поле «строк» совпадает с источником: по нему считается взвешенная точность
    import collections
    факт = collections.Counter(
        r.get("mach") for r in
        json.loads((ROOT / "gt/data/pn_db.json").read_text(encoding="utf-8"))["rows"]
        if r.get("mach"))
    разошлись = [r["обозначение"] for r in эт["строки"] if r["строк"] != факт[r["обозначение"]]]
    assert not разошлись, f"поле «строк» разошлось с источником: {разошлись[:3]}"


def test_замер_способен_упасть():
    """Мерило, которое не может покраснеть, ничего не меряет.

    Первая редакция замера была ЗЕЛЁНОЙ на правиле с восемью воспроизведёнными
    дефектами: точность считалась от числа ответов, молчание было бесплатным, а
    вес строк базы не учитывался вовсе. Проверка возвращает в правило уже
    совершённую ошибку — замыкающий \b семействам ГТУ, из-за которого терялись
    LM2500 и LM6000, — и требует, чтобы замер на ней УПАЛ. Падает он на
    взвешенной точности: эти две машины — половина строк базы."""
    import importlib.util
    путь = ROOT / "library" / "machine_kind.py"
    спец = importlib.util.spec_from_file_location("kvant_mk_испорченный", путь)
    испорченный = importlib.util.module_from_spec(спец)
    # Модуль обязан стоять в sys.modules ДО исполнения: dataclass с отложенными
    # аннотациями ищет своё пространство имён именно там.
    sys.modules["kvant_mk_испорченный"] = испорченный
    спец.loader.exec_module(испорченный)
    import re as _re
    испорченный.МАШИНЫ = tuple(
        (напр, _re.compile(rx.pattern.replace("|газотурбин)", "|газотурбин)\\b"), _re.I)
         if напр == "gtu" else rx)
        for напр, rx in испорченный.МАШИНЫ)
    assert испорченный.разобрать("LM2500").вид == "не опознать", \
        "подмена не воспроизвела ошибку — проверка ничего не проверяет"

    спец2 = importlib.util.spec_from_file_location(
        "kvant_замер", ROOT / "scripts" / "machine_segment_check.py")
    замер = importlib.util.module_from_spec(спец2)
    sys.modules["kvant_замер"] = замер
    спец2.loader.exec_module(замер)
    замер.mk = испорченный
    старые = sys.argv
    sys.argv = ["machine_segment_check.py", "--gate"]
    try:
        код = замер.main()
    finally:
        sys.argv = старые
    assert код == 1, "замер не упал на правиле с воспроизведённой ошибкой"


