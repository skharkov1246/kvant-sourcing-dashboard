"""Звенья «диагностика», «дефект» и «ремонтное решение»: разбор разведки в справочник.

Материала мало и он разнородный: этапы ремонта записаны одной строкой через точку
с запятой, в текстах живёт вёрстка библиотеки (<b>), а идентификатор операции
нельзя брать порядковым номером — правка исходного файла завела бы дубли вместо
обновления. Тесты держат ровно эти три места.

Примеры придуманы здесь и не взяты из базы: репозиторий публичный (правило 5).
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(name: str):
    spec = importlib.util.spec_from_file_location(
        f"kvant_{name}", ROOT / "library" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


rp = load("load_repair")


def test_вёрстка_страницы_в_справочник_не_попадает():
    assert rp.clean("Ручной <b>TIG</b>;  лазерная  наплавка") == "Ручной TIG; лазерная наплавка"
    assert rp.clean(None) == ""


def test_этап_ремонта_разбирается_на_отдельные_операции():
    строка = "Визуальный контроль; ЛЮМ; вихретоковый; <b>цифровая рентгенография</b>"
    assert rp.методы(строка) == ["Визуальный контроль", "ЛЮМ", "Вихретоковый",
                                 "Цифровая рентгенография"]


def test_обрывок_без_букв_операцией_не_считается_а_короткий_метод_считается():
    # «УЗ» и «ЛЮМ» — настоящие методы контроля, и порог по длине выбросил бы
    # ровно их. Отсекается то, в чём букв нет вовсе.
    assert rp.методы("УЗ; —; ;") == ["УЗ"]


def test_идентификатор_не_зависит_от_порядка_и_различает_виды():
    # Один и тот же метод в одном виде — один идентификатор при любом прогоне.
    assert rp.ident("контроль", "ЛЮМ") == rp.ident("контроль", "ЛЮМ")
    # Тот же текст в другом виде — другая запись: инспекция это не ремонт.
    assert rp.ident("контроль", "ЛЮМ") != rp.ident("ремонт", "ЛЮМ")
    assert rp.ident("контроль", "ЛЮМ").startswith("контроль.")


def test_операции_и_дефекты_собираются_из_данных_репозитория():
    proc = rp.build_procedures()
    assert len(proc) >= 40, "разведка Ansaldo перестала читаться"
    виды = {p["kind"] for p in proc.values()}
    assert {"инспекция", "контроль", "ремонт"} <= виды
    # У операции, где назван исполнитель, обязан быть ключ для связи с компаниями.
    for p in proc.values():
        assert bool(p["performer"]) == bool(p["performer_key"]), p["name"]


def test_дефект_хранится_вместе_с_решением():
    defects = rp.build_defects()
    assert defects, "проработки позиций перестали читаться"
    assert any(d["fix"] for d in defects.values()), "ни у одного дефекта нет решения"
    for d in defects.values():
        assert d["consequence"], d["name"]
        assert d["unit_id"] is None or d["unit_id"] in rp.UNITS


def test_признаки_помечены_заготовкой_и_ведут_в_существующий_узел():
    """Справочник признаков составлен не по нашим измерениям, и это обязано быть
    видно в данных: низкая уверенность у каждой строки и названный источник
    связки. Иначе заготовка через месяц станет неотличима от факта."""
    symptoms = rp.build_symptoms()
    assert len(symptoms) >= 20, "справочник признаков перестал читаться"
    for s in symptoms.values():
        assert s["confidence"] == "low", s["name"]
        assert "заготовка" in (s["source"] or ""), s["name"]
        assert s["basis"], s["name"]
        assert s["measure"] and s["defect"] and s["confirm"], s["name"]
        assert s["unit_id"] in rp.UNITS, f"{s['name']}: узел {s['unit_id']} не существует"


def test_каждая_ссылка_признака_ведёт_в_существующую_операцию():
    """Ссылка «контроль|ЛЮМ (fluorescent penetrant)» превращается в идентификатор
    операции точным совпадением. Опечатка не создаёт тихо пустую связь — она
    обязана падать здесь, иначе признак просто окажется без подтверждения и
    никто этого не заметит."""
    proc = rp.build_procedures()
    symptoms = rp.build_symptoms()
    рёбра, потерянные = rp.ops_edges(symptoms, proc)
    assert not потерянные, f"ссылки в никуда: {потерянные}"
    assert len(рёбра) >= 20, "связи «признак → чем подтвердить» перестали читаться"
    # Обратная сторона: по методу контроля выбираются признаки, и у метода
    # обязан быть хотя бы один признак — иначе связь односторонняя и бесполезна.
    методы = {p for _, p, _ in рёбра}
    assert len(методы) >= 5


def test_справочник_методов_загружается_и_помечен_заготовкой():
    """Методов диагностики в разведке OEM нет — они завезены отдельным
    справочником. Раз это не наше измерение, пометка обязана быть в данных:
    источник называет заготовку и хранит основание связки (правило 16)."""
    proc = rp.build_procedures()
    методы = [p for p in proc.values()
              if "справочник методов" in (p["source"] or "")]
    assert len(методы) >= 9, "library/data/methods.json перестал читаться"
    for p in методы:
        assert p["kind"] == "контроль", p["name"]
        assert "заготовка" in p["source"], p["name"]
        assert p["source"].split(":", 1)[1].strip(), f"{p['name']}: не сохранено основание"
        assert p["scope"], p["name"]
        assert p["unit_id"] in rp.UNITS, f"{p['name']}: узел {p['unit_id']} не существует"


def test_у_каждого_признака_есть_чем_подтвердить():
    """Признак без метода подтверждения обрывает цепочку там, где в неё входит
    эксплуатация: «металл в масле» без анализа масла — жалоба, а не диагностика.
    Семь признаков висели так, пока справочника методов не было."""
    proc = rp.build_procedures()
    symptoms = rp.build_symptoms()
    рёбра, _ = rp.ops_edges(symptoms, proc)
    с_подтверждением = {s for s, _, _ in рёбра}
    без = [s["name"] for i, s in symptoms.items() if i not in с_подтверждением]
    assert not без, f"признаки без метода подтверждения: {без}"


def test_справочник_ремонтных_операций_загружается_и_помечен_заготовкой():
    """Разведка OEM собрана по горячему тракту и по генераторам. Ремонт
    подшипника, маслонасоса, фильтра и датчика в ней отсутствует — а отказывает
    чаще всего именно это. Операции завезены отдельным справочником и так же
    помечены заготовкой: выдавать их за нашу практику нельзя."""
    proc = rp.build_procedures()
    ремонты = [p for p in proc.values()
               if "справочник ремонтных операций" in (p["source"] or "")]
    assert len(ремонты) >= 15, "library/data/repairs.json перестал читаться"
    for p in ремонты:
        assert p["kind"] == "ремонт", p["name"]
        assert "заготовка" in p["source"], p["name"]
        assert p["scope"], p["name"]
        assert p["unit_id"] in rp.UNITS, f"{p['name']}: узел {p['unit_id']} не существует"


def test_типовой_дефект_знает_причину_последствие_и_узел():
    """Дефект без последствия — жалоба, дефект без причины — не знание, а
    наблюдение. Обе графы обязательны, иначе запись не отвечает ни закупщику
    («чем это кончится»), ни инженеру («откуда взялось»)."""
    defects = rp.build_defects()
    типы = [d for d in defects.values()
            if "справочник типовых дефектов" in (d["source"] or "")]
    assert len(типы) >= 25, "library/data/defect_types.json перестал читаться"
    for d in типы:
        assert "заготовка" in d["source"], d["name"]
        assert d["cause"] and d["consequence"], d["name"]
        assert d["unit_id"] in rp.UNITS, f"{d['name']}: узел {d['unit_id']} не существует"


def test_признак_ведёт_к_дефекту_ссылкой_а_не_текстом():
    """Связь словами не связь: у признака в поле defect написано «износ или
    проворот вкладыша», и человек догадывается, что речь о записи справочника, а
    машина — нет. Опечатка в ссылке обязана падать здесь."""
    defects = rp.build_defects()
    symptoms = rp.build_symptoms()
    рёбра, потерянные = rp.defect_edges(symptoms, defects)
    assert not потерянные, f"ссылки в никуда: {потерянные}"
    без = [s["name"] for i, s in symptoms.items() if i not in {r[0] for r in рёбра}]
    assert not без, f"признаки без дефекта: {без}"


def test_у_каждого_типового_дефекта_есть_чем_лечить():
    """Дефект без ремонтного решения обрывает цепочку на шаг до закупки. У
    позиционных записей («риск отказа детали») решение лежит текстом, у типов —
    ссылкой на операцию, и она обязана существовать."""
    proc = rp.build_procedures()
    defects = rp.build_defects()
    рёбра, потерянные = rp.ссылки_на_операции(defects, proc, "тест")
    assert not потерянные, f"ссылки в никуда: {потерянные}"
    типы = {i for i, d in defects.items()
            if "справочник типовых дефектов" in (d["source"] or "")}
    без = типы - {r[0] for r in рёбра}
    assert not без, f"типы дефектов без ремонтного решения: {[defects[i]['name'] for i in без]}"
