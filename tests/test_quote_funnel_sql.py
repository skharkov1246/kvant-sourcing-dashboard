@нужна_база
def test_доля_цен_внутри_прочитанных_файлов(cur):
    м = скрипт()
    cur.execute(м.ВНУТРИ_ПРОЧИТАННЫХ, (м.FEED, м.ПРЕДЛОЖЕНИЕ))
    ф, поз, сц, мд = cur.fetchone()
    # Только F-1: десять позиций, восемь цен. D-1 с её пятьюстами позициями
