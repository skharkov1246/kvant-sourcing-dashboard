    # И двое из трёх немых — pdf, то есть заведомо текстовый путь.


@нужна_база
def test_чужой_поток_не_делает_немого_говорящим(cur):
    """Ловушка 5: строка цены потока «прайс» на F-2 в воронку КП не идёт."""
    м = скрипт()
