"""Воронка разбора предложений считается по файлам, а не по строкам.

ЗАЧЕМ. Владелец прав: предложения приходят с чёткими позициями. Замер это
подтверждает с другой стороны — позиций извлечено 404 420, а цен 18 234.
Значит непрочитано не содержимое файлов, а цена в них, и надо знать, где именно
она теряется.

Считать надо ФАЙЛАМИ. Строка без цены бывает законной — заголовок раздела,
итог, примечание. А файл коммерческого предложения, не давший ни одной цены, —
это непрочитанное предложение целиком, и таких быть не должно.

Три ловушки, каждая даёт правдоподобное, но неверное число:

1. СЧЁТ ПО СТРОКАМ ВМЕСТО ФАЙЛОВ. Один огромный прайс с тысячей цен закроет
   собой сотню нечитаемых КП, и доля покажется приличной.
2. ФАЙЛ БЕЗ ПОЗИЦИЙ, ПОСЧИТАННЫЙ НЕМЫМ. Пустой файл цены не дал не потому, что
   её не прочитали, а потому что читать было нечего. Он в счёт не идёт.
3. ЧУЖОЙ ПОТОК В ЦЕНАХ. lib_prices держит и прайсы, и таможню; воронка разбора
   КП должна видеть только свой поток.

Корпус придуман (CLAUDE.md, правило 18).
"""
from __future__ import annotations

import importlib.util
import os
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
DSN = os.environ.get("LIBRARY_SQL_TEST_DSN")
pytestmark = pytest.mark.skipif(not DSN, reason="одноразовая база PostgreSQL не настроена")

СХЕМА = "тест_воронки_разбора"


def скрипт():
    spec = importlib.util.spec_from_file_location(
        "kvant_quote_funnel", ROOT / "scripts" / "quote_parse_funnel.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# КОРПУС. Шесть файлов, считаем руками.
#
#   F-1  разобран, таблица, шапка есть   — 10 позиций, 8 строк цены  → ГОВОРЯЩИЙ
#   F-2  разобран, таблица, шапки НЕТ    — 12 позиций, цены нет      → НЕМОЙ
#   F-3  разобран, таблица, шапки НЕТ    — 30 позиций, цены нет      → НЕМОЙ
#   F-4  разобран, текст,   шапки нет    —  5 позиций, цены нет      → НЕМОЙ
#   F-5  разобран, таблица, шапка есть   —  0 позиций, цены нет      → НЕ немой:
#        читать было нечего, и в счёт непрочитанных он идти не должен
#   F-6  пусто (скан без текстового слоя)                            → не разобран
#
# Плюс строка цены чужого потока на F-2: если фильтр по потоку снять, F-2
# перестанет быть немым, и вся картина перевернётся.
КОРПУС = """
create table lib_files (
  file_id text primary key, deal_id text, origin text, field text, kind text,
  size_bytes bigint, status text not null, reason text, chars int, rows_found int,
  segment_id text, sha256 text, parse_path text, header_found boolean);
create table lib_prices (
  id bigserial primary key, feed text, source_url text, price numeric);

insert into lib_files (file_id, status, kind, chars, rows_found, parse_path, header_found) values
  ('F-1', 'разобран', 'xlsx/docx', 5000, 10, 'таблица', true),
  ('F-2', 'разобран', 'xlsx/docx', 6000, 12, 'таблица', false),
  ('F-3', 'разобран', 'pdf',      12000, 30, 'таблица', false),
  ('F-4', 'разобран', 'pdf',       3000,  5, 'текст',   false),
  ('F-5', 'разобран', 'xlsx/docx',  400,  0, 'таблица', true),
  ('F-6', 'пусто',    'pdf',          0,  0, null,      null);

insert into lib_prices (feed, source_url, price) values
  ('разбор КП', 'F-1', 100), ('разбор КП', 'F-1', 200), ('разбор КП', 'F-1', 300),
  ('разбор КП', 'F-1', 400), ('разбор КП', 'F-1', 500), ('разбор КП', 'F-1', 600),
  ('разбор КП', 'F-1', 700), ('разбор КП', 'F-1', 800),
  -- Чужой поток на немом файле: воронка разбора КП его видеть не должна.
  ('прайс',     'F-2', 999);
"""


@pytest.fixture()
def cur():
    import psycopg2
    conn = psycopg2.connect(DSN)
    conn.autocommit = True
    c = conn.cursor()
    c.execute(f'drop schema if exists "{СХЕМА}" cascade')
    c.execute(f'create schema "{СХЕМА}"')
    c.execute(f'set search_path to "{СХЕМА}"')
    c.execute(КОРПУС)
    yield c
    c.execute(f'drop schema if exists "{СХЕМА}" cascade')
    c.close()
    conn.close()


def test_состояния_файлов(cur):
    м = скрипт()
    cur.execute(м.ПО_СОСТОЯНИЮ)
    по = {r[0]: r[1:] for r in cur.fetchall()}
    assert по["разобран"][0] == 5
    assert по["пусто"][0] == 1
    # Позиции суммируются по состоянию: 10+12+30+5+0 = 57.
    assert по["разобран"][1] == 57


def test_разрез_по_шапке_показывает_где_теряется_цена(cur):
    """Главный разрез: цена ищется только в опознанной строке заголовков."""
    м = скрипт()
    cur.execute(м.ПО_ШАПКЕ, (м.FEED,))
    по = {(r[0], r[1]): r[2:] for r in cur.fetchall()}
    # Таблица с шапкой: два файла (F-1 и F-5), цену дал один.
    файлов, дали, позиций, строк = по[("таблица", "true")]
    assert (файлов, дали, позиций, строк) == (2, 1, 10, 8)
    # Таблица без шапки: два файла, цену не дал ни один — и позиций у них 42,
    # то есть вчетверо больше, чем у говорящего.
    файлов, дали, позиций, строк = по[("таблица", "false")]
    assert (файлов, дали, позиций, строк) == (2, 0, 42, 0)
    # Текстовый путь: один файл, цены нет.
    assert по[("текст", "false")][:2] == (1, 0)


def test_немым_считается_файл_с_позициями_но_без_цены(cur):
    """Файл без позиций немым не считается: читать было нечего."""
    м = скрипт()
    cur.execute(м.НЕМЫЕ_ПО_ВИДУ, (м.FEED,))
    по = {r[0]: r[1:] for r in cur.fetchall()}
    # Немые: F-2 (xlsx), F-3 и F-4 (pdf). F-5 с нулём позиций сюда не идёт,
    # F-1 дал цену, F-6 не разобран.
    assert по["xlsx/docx"][0] == 1
    assert по["pdf"][0] == 2
    assert sum(v[0] for v in по.values()) == 3
    # Позиций у немых 12 + 30 + 5 = 47 — больше, чем у прочитанных.
    assert sum(v[1] for v in по.values()) == 47


def test_сравнение_немых_и_говорящих(cur):
    м = скрипт()
    cur.execute(м.СРАВНЕНИЕ, (м.FEED,))
    по = {r[0]: r[1:] for r in cur.fetchall()}
    # Говорящих один, немых три. F-5 отсечён нулём позиций в обоих.
    assert по[True][0] == 1
    assert по[False][0] == 3
    # У говорящего шапка есть, у немых ни у одного — это и есть ответ.
    assert по[True][3] == 1
    assert по[False][3] == 0


def test_чужой_поток_не_делает_немого_говорящим(cur):
    """Строка цены потока «прайс» на F-2 в воронку разбора КП не идёт."""
    м = скрипт()
    cur.execute(м.НЕМЫЕ_ПО_ВИДУ, ("прайс",))
    по = {r[0]: r[1:] for r in cur.fetchall()}
    # В потоке «прайс» цену дал F-2, значит немых становится трое других...
    # точнее: F-1 теперь немой, F-2 говорящий. Проверяем, что счёт вообще
    # зависит от потока — иначе фильтр не работает.
    assert по["xlsx/docx"][0] == 1      # F-1, ставший немым в этом потоке
    assert по["pdf"][0] == 2


def test_доля_цен_внутри_прочитанных_файлов(cur):
    м = скрипт()
    cur.execute(м.ВНУТРИ_ПРОЧИТАННЫХ, (м.FEED,))
    ф, поз, сц, мд = cur.fetchone()
    # Только F-1: десять позиций, восемь цен.
    assert (ф, поз, сц) == (1, 10, 8)
    assert abs(float(мд) - 0.8) < 1e-9
