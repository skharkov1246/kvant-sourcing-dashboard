@нужна_база
def test_ядро_показывает_где_цена_не_ищется(cur):
    """Главный разрез: код · путь · шапка. Цена ищется только в шапке таблицы."""
    м = скрипт()
    cur.execute(м.ЯДРО, (м.FEED, м.ПРЕДЛОЖЕНИЕ))
    ядро = cur.fetchall()
    по = {(r[0], r[1], r[2]): tuple(int(x) for x in r[3:]) for r in ядро}
    # Таблица с шапкой, текущий код: F-1 и F-5, цену дал один. Позиций десять —
    # пятьсот позиций спецификации заказчика сюда НЕ пришли.
    assert по[("v3", "таблица", "найдена")] == (2, 1, 10, 8)
    # Таблица без шапки: цена не ищется вовсе.
    assert по[("v3", "таблица", "НЕ найдена")] == (1, 0, 12, 0)
    # Текстовый путь (это весь pdf): цена не ищется вовсе.
    assert по[("v3", "текст", "НЕ найдена")] == (1, 0, 30, 0)
    # Разобран до записи цен: другая причина, другое лечение — переразбор.
    assert по[("до записи цен", "текст", "(нет данных)")] == (1, 0, 5, 0)
    # Клетки, где цена не ищется по устройству кода: три файла, 47 позиций
    # из 57 — восемьдесят два процента.
    глухо = [r for r in ядро
             if r[1] == "текст" or r[2] in ("НЕ найдена", "(нет данных)")]
    assert (sum(int(r[3]) for r in глухо), sum(int(r[5]) for r in глухо)) == (3, 47)


@нужна_база
def test_немым_считается_файл_с_позициями_но_без_цены(cur):
    """Ловушка 4: файл без позиций немым не считается — читать было нечего."""
    м = скрипт()
    cur.execute(м.НЕМЫЕ_ПО_ВИДУ, (м.FEED, м.ПРЕДЛОЖЕНИЕ))
    по = {r[0]: tuple(int(x) for x in r[1:]) for r in cur.fetchall()}
    # Немые: F-2 (xlsx), F-3 и F-4 (pdf). F-5 с нулём позиций сюда не идёт,
    # F-1 дал цену, F-6 не разобран, D-1 — чужой origin.
    assert по["xlsx/docx"][:2] == (1, 12)
    assert по["pdf"][:2] == (2, 35)
    assert sum(v[0] for v in по.values()) == 3
    # Позиций у немых 47 против десяти у прочитанного.
    assert sum(v[1] for v in по.values()) == 47


@нужна_база
def test_сравнение_немых_и_говорящих(cur):
    м = скрипт()
    cur.execute(м.СРАВНЕНИЕ, (м.FEED, м.ПРЕДЛОЖЕНИЕ))
    по = {r[0]: tuple(int(x) for x in r[1:]) for r in cur.fetchall()}
