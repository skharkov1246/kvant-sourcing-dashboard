def test_под_одним_именем_выбирается_своё_юрлицо():
    """В базе уже лежат оба — надо взять то, у которого форма совпала."""
    известные = {("alias", "romashka"): ["KV-S-000001-8", "KV-S-000002-6"]}
    формы = {"KV-S-000001-8": ["ооо"], "KV-S-000002-6": ["ао"]}
