def test_домен_не_спрашивает_правовую_форму():
    """Мера риска: домен сливает юрлица, которые имя развело бы.

    Тест НЕ требует это запретить — он закрепляет, что такое бывает и должно
    быть посчитано. Запрещать или нет — решение по замеру, а не по догадке.
    """
