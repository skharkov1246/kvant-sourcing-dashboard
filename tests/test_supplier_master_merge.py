def test_под_одним_именем_выбирается_своё_юрлицо():
    """В базе уже лежат оба — надо взять то, у которого форма совпала."""
    известные = {("alias", "romashka"): ["KV-S-000001-8", "KV-S-000002-6"]}
    формы = {"KV-S-000001-8": ["ооо"], "KV-S-000002-6": ["ао"]}
    assert опознание([("alias", "romashka")], известные, формы, ["ао"]) == "KV-S-000002-6"
    assert опознание([("alias", "romashka")], известные, формы, ["ооо"]) == "KV-S-000001-8"


def test_форма_неизвестна_с_одной_стороны_опознанию_не_мешает():
    """Форму часто не пишут — это не повод выдать компании второй номер."""
    известные = {("alias", "romashka"): ["KV-S-000001-8"]}
