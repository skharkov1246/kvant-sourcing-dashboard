def test_имя_не_опознаёт_при_разных_доменах():
    """Запись обязана повторять ВСЕ запреты сведения, не только форму.

    Уехало в прод 20.09.2026. Сведение развело «Полярную звезду» с двух разных
    сайтов в две сущности (ambiguous_match), а запись нашла вторую по алиасу
    первой и отдала ей тот же номер: один номер, два чужих друг другу домена.
    Так склеилась 171 сущность из 9 603 первой записи.
    """
    найден = опознание([("alias", "polyarnaya"), ("domain", "dva.example.com")],
                       {("alias", "polyarnaya"): ["KV-S-000001-8"]},
                       {}, [])
    # без сведений о доменах кандидата поведение прежнее
    assert найден == "KV-S-000001-8"

    с_доменами = lm.опознать(
        [(k, v, "тест", "stated") for k, v in
         [("alias", "polyarnaya"), ("domain", "dva.example.com")]],
        {("alias", lm.норма("polyarnaya")): {"KV-S-000001-8"}},
        {}, set(),
        {"KV-S-000001-8": {lm.норма("odin.example.com")}},
        {lm.норма("dva.example.com")})
    assert с_доменами is None, "запись склеила то, что сведение развело по домену"


