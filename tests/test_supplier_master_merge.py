# ─────────────────────────────────────────────────── опознание при записи
# Запись обязана запрещать ровно то же, что и сведение. Первая версия этого не
# делала, и прогон на живом PostgreSQL 16 показал цену: правило развело «ООО
# Ромашка» и «АО Ромашка» в две сущности, а запись искала каждую по алиасу
# «ромашка», находила первую и отдавала второй ЕЁ номер. Четыре сущности — три
# номера, два юрлица под одним номером, который уходит в договоры.
#
# Тут проверяется чистая логика опознания, без базы: она и была сломана.


def опознание(мои, известные, формы_базы, мои_формы):
    """Вызов lm.опознать в терминах теста: признаки задаются парами (вид, значение)."""
    return lm.опознать(
        [(k, v, "тест", "stated") for k, v in мои],
        {(k, lm.норма(v)): set(ids) for (k, v), ids in известные.items()},
        {sid: {lm.норма(f) for f in fs} for sid, fs in формы_базы.items()},
        {lm.норма(f) for f in мои_формы})


def test_твёрдый_ключ_опознаёт_сразу():
    найден = опознание([("bitrix", "77"), ("alias", "chtoto")],
                       {("bitrix", "77"): ["KV-S-000009-1"]}, {}, [])
    assert найден == "KV-S-000009-1"


def test_имя_опознаёт_когда_форма_не_противоречит():
    найден = опознание([("alias", "romashka")],
                       {("alias", "romashka"): ["KV-S-000001-8"]},
                       {"KV-S-000001-8": ["ооо"]}, ["ооо"])
    assert найден == "KV-S-000001-8"


