SPEC.loader.exec_module(lm)


def свод(наборы):
    """Принимает наборы простыми кортежами — так тесты читаются глазами.

    (имя, домен) — файловая строка; (имя, домен, ключ) или (имя, домен, ключ,
    формы) — строка с твёрдым идентификатором портала и правовой формой;
    пятым кортежем идут налоговые номера парами (вид, значение).
    """
    def строка(реестр, r):
        имя, домен, ключ, формы, налоги = (list(r) + ["", "", (), ()])[:5]
        return lm.Источник(реестр, имя, домен, ключ, frozenset(формы), frozenset(налоги))

    с, оч = lm.свести({реестр: [строка(реестр, r) for r in строки]
                       for реестр, строки in наборы.items()})
    return {e.статус: e for e in с}, с, оч


