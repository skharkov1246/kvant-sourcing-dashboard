def test_идентификатор_портала_сильнее_имени():
    """Одна карточка под двумя написаниями — одна сущность, а не две."""
    наборы = {"bitrix/companies": [("pervoeimya", "", "bitrix:7"),
                                   ("vtoroeimya", "", "bitrix:7")]}
    _, с, _ = свод(наборы)
    assert len(с) == 1
    assert с[0].имена == {"pervoeimya", "vtoroeimya"}


def test_задвоение_карточек_портала_схлопывается():
    """141 название в портале носят две и больше карточек (замер 20.09.2026).

    Не схлопнуть их значит оставить статистику одного поставщика расщеплённой
    надвое. Схлопнуть молча — выдать догадку за факт, поэтому статус candidate.
    """
    наборы = {"bitrix/companies": [("seldatlantiki", "", "bitrix:11"),
                                   ("seldatlantiki", "", "bitrix:22")]}
    _, с, _ = свод(наборы)
    assert len(с) == 1
    assert с[0].ключи == {"bitrix:11", "bitrix:22"}
    assert с[0].статус == "candidate", "схлопнутое задвоение ждёт человека"
    assert "задвоение" in с[0].причина


def test_файловое_имя_садится_на_карточку_портала():
    """Ради этого портал и добавлен: файловый реестр прилипает к сущности с ключом."""
    наборы = {
        "bitrix/companies": [("morskoyuzel", "seaknot.example.com", "bitrix:5")],
        "pnw": [("morskoyuzelltd", "seaknot.example.com")],
    }
    _, с, _ = свод(наборы)
    assert len(с) == 1
    assert с[0].ключи == {"bitrix:5"}, "сущность потеряла ключ портала"
    assert с[0].статус == "verified"


def test_разные_правовые_формы_не_сливаются():
    """«ООО Ромашка» и «АО Ромашка» после norm_name неотличимы, а юрлица разные.

    Слить их — приписать одному чужие сделки (ТЗ §1.12). На живых пяти реестрах
    это правило развело две пары, которые прежний код сливал молча.
    """
    наборы = {"а": [("romashka", "", "", ["ооо"])],
              "б": [("romashka", "", "", ["ао"])]}
    _, с, оч = свод(наборы)
    assert len(с) == 2, "разные правовые формы слились"
    assert [q["kind"] for q in оч] == ["different_legal_form"]


def test_форма_только_с_одной_стороны_слиянию_не_мешает():
    """Форму часто просто не пишут — это не повод расщеплять компанию."""
    наборы = {"а": [("romashka", "", "", ["ооо"])], "б": [("romashka", "", "", [])]}
    _, с, оч = свод(наборы)
    assert len(с) == 1 and not оч


def test_сокращение_той_же_формы_слиянию_не_мешает():
    """Ltd — это и есть Limited. Прогон 20.09.2026 поймал две такие ложные сработки."""
    from supplier_registry_overlap import форма
    for полное, кратко in (("Yasen Limited", "Yasen Ltd"),
                           ("Yasen Corporation", "Yasen Corp"),
                           ("Yasen Company", "Yasen Co"),
                           ("Yasen B.V.", "Yasen BV")):
        наборы = {"а": [("yasen", "", "", форма(полное))],
                  "б": [("yasen", "", "", форма(кратко))]}
        _, с, оч = свод(наборы)
        assert len(с) == 1, f"{полное} и {кратко} расщепились"
        assert not оч


def test_перевод_вывески_за_ту_же_форму_не_считается():
    """ооо ↔ llc — перевод, а не сокращение: про юрлицо он ничего не доказывает."""
    from supplier_registry_overlap import форма
    наборы = {"а": [("yasen", "", "", форма("ООО Ясень"))],
              "б": [("yasen", "", "", форма("Yasen LLC"))]}
    _, с, оч = свод(наборы)
    assert len(с) == 2
    assert [q["kind"] for q in оч] == ["different_legal_form"]


