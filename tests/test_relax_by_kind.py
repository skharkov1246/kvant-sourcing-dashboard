"""Ослабление правила шапки применяется ПО ВИДАМ, и PDF в список не входит.

Два холостых прогона на одних и тех же 328 файлах PDF, один и тот же код чтения
(35856258566 и 35856888614):

                          позиций стало   строк цены стало
    лежит в базе              26 932           1 425
    ослабление выключено      20 490           1 142
    ослабление включено       15 889             314

На PDF ослабление уносит 72 % строк цены, которые строгое правило сохраняет: в
тексте PDF довольно строки со словом «наименование», чтобы стать шапкой, и тогда
тело таблицы съезжает, а ценовые колонки опознаются не те.

На смешанной выборке всех форматов тот же вход давал строк цены 3 474 → 5 716,
плюс 64,5 % (прогон 35844131867). Прирост шёл от офисных файлов, а общий
выключатель складывал прибыль одних с убытком других в одно число — и сумма
выглядела прибылью.
"""
from __future__ import annotations

import re
from pathlib import Path

from library import indexer


def test_pdf_ослаблению_не_подлежит():
    assert "pdf" not in indexer.ШИРЕ_ПРИМЕНИМО, "PDF вернули в список — замер против"


def test_офисные_и_текстовые_виды_ослабляются():
    """Иначе правка, стоящая +64,5 % строк цены, не применится ни к чему."""
    for п in ("xlsx", "docx", "csv", "txt"):
        assert п in indexer.ШИРЕ_ПРИМЕНИМО, п


def test_ослаблять_смотрит_и_на_выключатель_и_на_вид(monkeypatch):
    monkeypatch.setattr(indexer, "ШАПКА_ШИРЕ", True)
    assert indexer.ослаблять("xlsx") is True
    assert indexer.ослаблять("pdf") is False, "PDF ослабляется при включённом входе"
    monkeypatch.setattr(indexer, "ШАПКА_ШИРЕ", False)
    assert indexer.ослаблять("xlsx") is False, "ослабление идёт без входа"


def test_ворота_таблицы_берут_правило_по_виду(monkeypatch):
    """Шапка, которую видит только ослабленное правило: для xlsx проходит, для PDF нет."""
    monkeypatch.setattr(indexer, "ШАПКА_ШИРЕ", True)
    # «Equipment» знает только расширенный словарь; «Qty» — обычный.
    таблица = [["Equipment", "Qty"], ["Pump CNS-38", "2"]]
    строки, текст = indexer.таблица_или_текст(таблица, lambda: "проза", None, "xlsx")
    assert строки == таблица, "офисный файл не получил ослабления"
    строки, текст = indexer.таблица_или_текст(таблица, lambda: "проза", None, "pdf")
    assert строки == [] and текст == "проза", "PDF получил ослабление"


def test_сборка_таблицы_pdf_тоже_идёт_строгим_правилом():
    """Ворота передаются ВНУТРЬ pdftable: там выбирается ступень допуска.

    Если туда уйдёт ослабленное правило, PDF получит ослабление окольным путём —
    мимо `ослаблять`, и замер по видам окажется обойдён.
    """
    код = re.sub(r"(?<!\w)#[^\n]*", "",
                 (Path(__file__).resolve().parent.parent
                  / "library/indexer.py").read_text(encoding="utf-8"))
    # Регулярка со [^)]* обрезала бы захват на ВЛОЖЕННОЙ скобе вызова
    # `ослаблять("pdf")` — берём строку целиком до конца выражения.
    ворота = [s for s in код.splitlines() if "годится=lambda rows: header_map(" in s]
    assert ворота, "ворота шапки в сборке таблицы PDF не найдены"
    assert len(ворота) == 1, f"ворот шапки больше одних: {ворота}"
    assert 'шире=ослаблять("pdf")' in ворота[0], \
        f"ворота PDF не спрашивают правило по виду: {ворота[0]!r}"


def test_разбор_позиций_тоже_берёт_правило_по_виду(monkeypatch):
    """Ворота шапки решали «PDF — строго», а разбор позиций брал общий выключатель
    и применял к PDF ослабленное правило. Холостой прогон 23.09.2026 с ослаблением:
    таблицам PDF 6 263 строки цены против 8 802, хуже у 381 файла."""
    monkeypatch.setattr(indexer, "ШАПКА_ШИРЕ", True)
    таблица = [["Equipment", "Qty"], ["Pump CNS-38", "2"]]
    assert indexer.header_map(таблица, шире=True)[0] == 0
    assert indexer.header_map(таблица, шире=False)[0] == -1
    # Разбор позиций со строгим правилом шапки не видит — как и ворота для PDF.
    строго = indexer.items_from_rows(таблица, шире=False)
    широко = indexer.items_from_rows(таблица, шире=True)
    assert all(it["item_name"] != "Equipment" for it in широко), "шапка стала позицией"
    assert any(it["item_name"] == "Equipment" for it in строго) or len(строго) != len(широко)


