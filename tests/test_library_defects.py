"""Правило извлечения дефекта из текста ТЗ: точность важнее полноты.

Ошибочно извлечённый «дефект» хуже пропущенного: он попадает в справочник,
которым пользуются как знанием об оборудовании, и отличить его там уже нечем.
Поэтому тесты сначала проверяют, на чём правило обязано молчать.

Предложения придуманы здесь и не взяты из базы: репозиторий публичный, а тексты
технических заданий заказчиков в него попадать не должны (правило 5 CLAUDE.md).
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(name: str):
    spec = importlib.util.spec_from_file_location(
        f"kvant_{name}", ROOT / "library" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


df = load("defects")


# Слово дефекта есть, оборудования нет — это не дефект оборудования.
НЕ_ДЕФЕКТЫ = [
    "Трещины в асфальтовом покрытии площадки устраняет подрядчик за свой счёт",
    "Износ трудовых ресурсов подрядной организации не допускается",
    "Оплата производится в течение тридцати банковских дней с даты подписания",
    "Коррозия репутации поставщика при срыве сроков поставки",
    "Деформация сметной стоимости работ согласовывается дополнительно",
]

# Оборудование названо и повреждение названо — дефект.
ДЕФЕКТЫ = [
    "При осмотре выявлен прогар жаровой трубы камеры сгорания по сварному шву",
    "Повышенная вибрация ротора компрессора при выходе на номинальные обороты",
    "Трещины на входных кромках рабочих лопаток первой ступени турбины",
    "Обнаружена течь масла по уплотнению подшипника опорного",
    "Наработка турбины с начала эксплуатации составляет сорок восемь тысяч часов",
    "Задиры на шейке вала под вкладышем и следы наволакивания баббита",
]


def test_на_словах_без_оборудования_правило_молчит():
    for s in НЕ_ДЕФЕКТЫ:
        assert not df.is_defect(s), s


def test_повреждение_названного_узла_извлекается():
    for s in ДЕФЕКТЫ:
        assert df.is_defect(s), s


def test_вид_дефекта_определяется_а_не_угадывается():
    assert df.terms_in("прогар жаровой трубы") == ["прогар"]
    assert "вибрация" in df.terms_in("повышенная вибрация и биение вала")
    assert df.terms_in("поставка запасных частей по спецификации") == []


def test_текст_режется_на_предложения_и_мусор_отсеивается():
    текст = ("1.2.3.\n\nВыявлен износ лопаток компрессора; трещина по кромке диска. "
             "-----\nОК")
    предложения = df.sentences(текст)
    assert any("износ лопаток" in s for s in предложения)
    assert any("трещина по кромке" in s for s in предложения)
    assert not any(s.strip("-. ") == "" for s in предложения)
    assert "ОК" not in предложения          # короче двадцати знаков


def test_повторы_склеиваются_несмотря_на_номера_пунктов_и_размеры():
    a = "5.1. Трещины на лопатках 1 ступени турбины не допускаются"
    b = "12.4. Трещины на лопатках 3 ступени турбины не допускаются"
    assert df.key_of(a) == df.key_of(b)
    # но разные по существу требования ключом не сводятся
    c = "Прогар жаровой трубы камеры сгорания не допускается"
    assert df.key_of(a) != df.key_of(c)


def test_слишком_длинная_простыня_предложением_не_считается():
    assert df.sentences("а" * 900) == []


def test_способ_ремонта_за_дефект_не_принимается():
    """«Электроэрозионная обработка» — это способ ремонта, а не эрозия. Найдено
    прогоном правила по техническим текстам репозитория: подстрока «эрози»
    ловилась внутри «электроэрозионная» и давала ложную находку."""
    assert df.terms_in("Электроэрозионная обработка профилей лопаток") == []
    assert df.terms_in("электро-эрозионная прошивка охлаждающих отверстий") == []
    # настоящая эрозия при этом находится
    assert df.terms_in("Эрозия лопаток компрессора от песка") == ["эрозия"]


# Профилактика и статистика: дефект тут НЕ произошёл. Класс найден прогоном
# правила по текстам разведки — из восемнадцати находок шесть были такими.
ПРОФИЛАКТИКА = [
    "Улучшенные боковые уплотнения и поршневое кольцо против износа лопаток",
    "Визуальный осмотр лобовых частей, поиск следов истирания обмотки статора",
    "Торцевые зубья на диске турбины с биением в единицы микрон",
    "Покрытие обеспечивает стойкость к эрозии лопаток компрессора",
    "Трещины на лопатках турбины не допускаются по условиям приёмки",
    "Парк LM6000: свыше 40 млн часов наработки на 1320 агрегатах",
    "Мониторинг вибрации ротора входит в объём поставки САУ",
]


def test_профилактика_и_статистика_дефектом_не_считаются():
    for s in ПРОФИЛАКТИКА:
        assert not df.is_defect(s), s
        # при этом слово дефекта в них есть — отсекает именно контекст
        assert df.terms_in(s), s


def test_случившийся_дефект_на_том_же_узле_по_прежнему_находится():
    assert df.is_defect("Обнаружены трещины на лопатках турбины первой ступени")
    assert df.is_defect("Выявлен износ лопаток компрессора от эрозии песком")
    assert df.is_defect("Наработка турбины с начала эксплуатации 48 000 часов")
