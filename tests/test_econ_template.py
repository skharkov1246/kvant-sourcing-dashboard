def _по_формуле(*, af=lambda стр: f"AC{стр}*$AA$6", ae=lambda стр: "$D$4", ячейки=None, **kw) -> bytes:
    """Книга, где D4 пуста, AE позиций — формула =$D$4 (кэш 0), AF — формула af(стр)."""
