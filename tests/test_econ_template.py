    и = et.разобрать(книга(ПОЗИЦИИ, заголовки={"AE": "Валюта сделки"}))
    assert (и.why, и.вид) == ("AE12", "текст-иное (11–30) · слов словаря шаблона 1 + иных 1 · слов ожидаемой подписи "
                                      "1 из 2 · ожидаемой подписи рядом нет"), "переименована, а не другая"
    и = _с_разделом("I", ИМЯ)
    assert (и.why, и.вид) == ("I11", "текст-иное (>30) · слов ожидаемой подписи 0 из 2 · ожидаемой подписи рядом нет")
    _чисто(и.вид)
    # позиция: столбец и вид ячейки, без строки
    и = et.разобрать(книга([ПОЗИЦИИ[0], dict(ПОЗИЦИИ[1], ячейки={"AF": "#VALUE!"}), ПОЗИЦИИ[2]]))
    assert (и.status, и.why, и.вид) == (et.НЕТ_КУРСА, "позиции", "столбец AF: ошибка формулы #VALUE!")
    и = et.разобрать(книга([ПОЗИЦИИ[0], dict(ПОЗИЦИИ[1], ячейки={"AE": ИМЯ}), ПОЗИЦИИ[2]]))
    assert (и.why, и.вид) == ("AE14", "текст-иное (>30)")
    # курс подачи: полоса и строка таблицы — словами
    и = et.разобрать(книга(ПОЗИЦИИ, курсы={"EUR": 1.0, "USD": 0.9}))
    assert и.why == "D4" and и.вид == ("текст-валюта:RUB · полоса курса есть · строка валюты подачи в Z:AA нет"
                                       " · Z:AA: EUR USD")
    и = et.разобрать(книга(ПОЗИЦИИ, курс_подачи=0.01, курсы={"EUR": 1.0, "RUB": 100.0, "USD": 1.1}))
    assert и.why == "AG2" and и.вид == "число · курс итогов ниже полосы · обратный курс — в полосе"
    # сверки — какая не сошлась, без чисел
    и = et.разобрать(книга(ПОЗИЦИИ, итоги={"R1": 99_999.0}))
    assert и.why == "проверка 1" and и.вид.startswith("сверка R1 ↔ Σ T · отклонение больше 50 %")
    assert et.разобрать(книга([dict(p, AK=15) for p in ПОЗИЦИИ], переторжка=True)).вид == "продажа ниже закупки"
    и = et.разобрать(книга([dict(ПОЗИЦИИ[0], AK=0.1), ПОЗИЦИИ[1], ПОЗИЦИИ[2]], переторжка=True))
    assert (и.why, и.вид) == ("AK:AL", "AK и AL пусты у части позиций")
    assert et.разобрать(книга(ПОЗИЦИИ)).вид == "", "у сверенного вида нет"
