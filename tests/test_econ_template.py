def _книга_с(b: bytes, правка) -> bytes:
    """Книга b, первый лист которой поправлен функцией правка(ws)."""
    wb = openpyxl.load_workbook(io.BytesIO(b))
    правка(wb.active)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


