# ── v5: путь «формула AF» — AE следует пустой D4, валюту называет строка Z:AA формулы AF ──

def _с_формулами(b: bytes, формулы: dict[str, str]) -> bytes:
    """Книга b, где у ячеек адреса — ещё и формула (кэш значения остаётся): так Excel хранит
    рассчитанную книгу. openpyxl пишет либо формулу, либо значение, — формула вписывается в
    XML листа рядом с кэшем."""
    import zipfile
    from xml.sax.saxutils import escape
    src = zipfile.ZipFile(io.BytesIO(b))
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as dst:
        for имя in src.namelist():
            data = src.read(имя)
            if имя == "xl/worksheets/sheet1.xml":
                x = data.decode("utf-8")
                for адрес, f in формулы.items():
                    # без lxml openpyxl пишет пустую ячейку закрытым тегом <c …/>: формулу — внутрь
                    # ячейки, а не после неё (иначе в гейте, где lxml нет, формула терялась)
                    def вписать(м, f=f):
                        тег = м.group(1)
                        if тег.endswith("/>"):
                            return тег[:-2].rstrip() + f"><f>{escape(f)}</f></c>"
                        return тег + f"<f>{escape(f)}</f>"
                    x, n = re.subn(rf'(<c r="{адрес}"[^>]*>)', вписать, x, count=1)
                    assert n == 1, адрес
                data = x.encode("utf-8")
            dst.writestr(имя, data)
    return out.getvalue()


