def _правка(b: bytes, fn) -> bytes:
    """Придуманная книга, поправленная руками: fn(лист)."""
    wb = openpyxl.load_workbook(io.BytesIO(b))
    fn(wb.active)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


