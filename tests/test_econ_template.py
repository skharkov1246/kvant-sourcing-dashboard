def _с_ячейками(b: bytes, ячейки: dict) -> bytes:
    """Книга b с переписанными ячейками первого листа."""
    wb = openpyxl.load_workbook(io.BytesIO(b))
    for адрес, v in ячейки.items():
        wb.active[адрес] = v
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


