def test_обход_делится_на_части_у_обоих_источников():
    """Распоряжение владельца, 22.09.2026: «всегда дели минимум на 10».

    До 22.09.2026 по предложениям работала ОДНА часть: обход карточек запросов
    читает страницы подряд по ключу, и поделить его было нечем — каждая часть
    прочитала бы всё целиком, а двенадцать одинаковых обходов дают HTTP 429.
    Заплатили за это полным переразбором, который шёл одной частью сорок минут и
    упал, потеряв всё несделанное.

    Теперь делится и он: часть берёт свой ДИАПАЗОН идентификаторов карточек, и
    один полный обход раскладывается на части, а не повторяется каждой. Границы
    диапазонов проверяются отдельно (tests/test_shard_ranges.py): пропуск между
    частями — это карточки, которых не увидел никто.
    """
    код = без_комментариев((ROOT / "library" / "reparse.py").read_text())
    assert "collect_refs_rfq(DAYS, SHARD, SHARDS)" in код, (
        "обход предложений не получает номер части — значит не делится")
    assert "collect_refs(DAYS, SHARD, SHARDS" in код   # у сделок — ещё и границы по файлам
    # И прежнего «работает только часть 1» больше нет.
    assert "if SHARD != 0:" not in код


