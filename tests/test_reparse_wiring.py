"""Переразбор обязан доходить до данных, иначе правки разборщика бесполезны.

ЗАЧЕМ. До 22.09.2026 переразбор умел только вложения сделок и не писал цен
ВООБЩЕ, ни для какого источника. Из-за этого любая правка чтения цены действовала
лишь на новые файлы, а 5 640 уже разобранных предложений оставались с прежним
результатом. Работа над разборщиком не доходила до данных — и это был главный
тормоз, дороже любой отдельной ошибки в правилах.

Четыре свойства, каждое из которых молча всё обесценивает:

1. ВЕРСИЯ РАЗБОРЩИКА ПОДНЯТА. Отбор кандидатов идёт по
   «coalesce(parser_version, 1) < PARSER_VERSION». Не поднял версию — переразбор
   не найдёт ни одного файла и честно скажет «нечего переразбирать».
2. ОТБОР И ОБХОД ПОРТАЛА СМОТРЯТ НА ОДИН ИСТОЧНИК. Кандидаты выбираются по
   origin, ссылки собираются обходом сделок либо карточек запросов. Разъехались —
   переразбор соберёт ссылки, среди которых нет ни одного кандидата.
3. ЦЕНЫ ПИШУТСЯ ЧЕРЕЗ price_store. Это единственное место записи цены на все
   разборы (CLAUDE.md, правило 14): вторая вставка мимо него разойдётся с первой
   по колонкам, и ошибка уйдёт в счётчик пропущенных.
4. PDF ВХОДИТ В ПЕРЕРАЗБОР ПО УМОЛЧАНИЮ. Главная потеря именно в нём: 2 498 немых
   файлов предложений с 258 363 позициями.

Исходник читается КОДОМ, а не комментариями (CLAUDE.md, «Стиль работы»):
пояснение вида «раньше писали X» регулярка найдёт раньше настоящей строки и
отчитается о том, чего в коде уже нет.
"""
from __future__ import annotations

