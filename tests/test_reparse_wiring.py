def test_решение_о_записи_принимается_по_ценам_а_не_по_позициям():
    """Холостой прогон обязан сравнивать ЦЕНЫ, иначе решать нечем.

    Прогон сравнивал только позиции и звал «хуже» всякий файл, где их стало
    меньше. Для правки сентября это годилось: .docx терял таблицу целиком, и
    больше строк значило лучше. Для табличного пути PDF — нет: он НАМЕРЕННО
    перестаёт делать позиции из прозы, и падение их числа бывает ростом
    качества. Замер 22.09.2026 на двухстах файлах дал «лучше 0, хуже 59» по
    позициям и не сказал о ценах ничего — то есть о том единственном, ради чего
    переразбор предложений и делается.

    Снятие прежних цен по файлу необратимо, в отличие от пометок на позициях,
    поэтому решение о записи обязано опираться на измеренную разницу цен.
    """
    код = без_комментариев((ROOT / "library" / "reparse.py").read_text())
    # ЗАПРОС ДОЛЖЕН ВЫПОЛНЯТЬСЯ, А НЕ ПРОСТО СУЩЕСТВОВАТЬ. Первая версия теста
    # искала имя константы и пережила мутацию, снявшую её вызов: константа-то
    # осталась. Проверяется вызов.
    assert "cur.execute(ЦЕНЫ_БЫЛО" in код, "цены до переразбора не спрашиваются"
    assert "цен_было_по_файлу = {r[0]: int(r[1]) for r in cur.fetchall()}" in код, (
        "ответ запроса никуда не кладётся: пустой словарь сделает всякий файл "
        "«приростом цены» и снимет запрет на запись")
    # Сравнение по файлам, а не только итогом: итог может расти, пока половина
    # файлов теряет цену.
    for имя in ("цена_лучше", "цена_хуже", "цена_так_же"):
        assert имя in код, имя
    # И прогон обязан сказать вслух, когда записывать нельзя.
    assert "ЗАПИСЫВАТЬ НЕЛЬЗЯ" in код


