def без_комментариев(текст: str) -> str:
    """Код без строк-комментариев и без хвостов после #."""
    строки = []
    for ln in текст.splitlines():
        if ln.lstrip().startswith("#"):
            continue
        строки.append(re.sub(r"\s+#.*$", "", ln))
    return "\n".join(строки)


def модуль(source: str):
    """reparse при заданном SOURCE. Модуль читает переменную при импорте."""
    было = os.environ.get("SOURCE")
    os.environ["SOURCE"] = source
    try:
        import indexer
        import reparse
        importlib.reload(indexer)
        importlib.reload(reparse)
        return reparse
    finally:
        if было is None:
            os.environ.pop("SOURCE", None)
        else:
            os.environ["SOURCE"] = было


def значений_в_вызове(имя_запроса: str) -> int:
    """Сколько значений передаётся в cur.execute(<имя_запроса>, (...)).

    Считается разбором синтаксиса, а не поиском скобок: у аргументов бывают свои
    вызовы и списки, и counting скобок вручную ошибается на первом же list(...).
    """
    import ast
    дерево = ast.parse((ROOT / "library" / "reparse.py").read_text(encoding="utf-8"))
    for узел in ast.walk(дерево):
        if not (isinstance(узел, ast.Call) and isinstance(узел.func, ast.Attribute)
                and узел.func.attr == "execute" and len(узел.args) == 2):
            continue
        цель = узел.args[0]
        if isinstance(цель, ast.Name) and цель.id == имя_запроса:
            значения = узел.args[1]
            assert isinstance(значения, ast.Tuple), "значения переданы не кортежем"
            return len(значения.elts)
    raise AssertionError(f"вызов cur.execute({имя_запроса}, …) не найден")


