def test_отбор_кандидатов_смотрит_на_источник():
    """Иначе обход портала и отбор кандидатов разъедутся."""
    r = модуль("rfq")
    assert r.ORIGIN == "поле запроса"
    код = без_комментариев(r.CANDIDATES)
    assert "f.origin = %s" in код
    # ЧИСЛО ПОДСТАНОВОК СВЕРЯЕТСЯ С ЧИСЛОМ ПЕРЕДАННЫХ ЗНАЧЕНИЙ, а не с прибитой
    # тройкой: прежняя редакция ломалась от каждого нового условия отбора, хотя
    # проверяемое правило не менялось. Несовпадение — настоящая ошибка, и падает
    # она уже в прогоне, на подстановке.
    assert код.count("%s") == значений_в_вызове("CANDIDATES"), (
        f"в запросе {код.count('%s')} подстановок, а передаётся "
        f"{значений_в_вызове('CANDIDATES')} значений")

    r = модуль("deals")
    assert r.ORIGIN == "поле сделки"


