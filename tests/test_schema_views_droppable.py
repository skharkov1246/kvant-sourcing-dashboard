"""Вид пересоздают, а не заменяют: иначе схема встаёт только на чистой базе.

ЗАЧЕМ. `create or replace view` разрешает ДОПИСАТЬ колонку в конец списка и
отказывается менять состав в середине:

    ERROR: cannot change name of view column "price" to "oem"

Коварство в том, КОГДА это проявляется. На чистой базе вида ещё нет, replace
работает как create, и всё зелено — и preflight, и гейт, и любой локальный
прогон. Падает ровно живая база, где вид уже стоит. То есть проверка,
которая у нас есть, этот случай увидеть не может в принципе.

Поймано 21.09.2026 прогоном «схема main, поверх неё схема ветки»: psql вернул
3, вид остался прежним, а миграция оборвалась на `set -e`. Это зеркало правила
20 из CLAUDE.md (роли Supabase): там схема валилась везде, кроме прода, здесь —
только на проде.

Правило: перед каждым созданием вида — `drop view if exists` того же имени.
Тогда состав колонок можно менять как угодно. Гранты при этом обязан выдавать
тот же файл (в suppliers_schema.sql так и сделано).

Проверка текстовая, база не нужна: она о том, как написана миграция.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ФАЙЛЫ = sorted(
    list((ROOT / "library" / "supabase").glob("*.sql"))
    + list((ROOT / "zip" / "supabase").glob("*.sql")))

# «create [or replace] view <имя>» и «drop view if exists <имя>». Имя может
# стоять после $v$ внутри do-блока, поэтому якоря на начало строки нет.
СОЗДАНИЕ = re.compile(r"create\s+(?:or\s+replace\s+)?view\s+([a-z_][a-z0-9_]*)", re.I)
СНОС = re.compile(r"drop\s+view\s+if\s+exists\s+([a-z_][a-z0-9_]*)", re.I)


def без_комментариев(текст: str) -> str:
    """Комментарии снимаются до разбора (CLAUDE.md, стиль работы).

    Пояснение вида «было `create or replace view X`» регулярка нашла бы раньше
    настоящего оператора и отчиталась бы о том, чего в коде уже нет."""
    return "\n".join(строка.split("--")[0] for строка in текст.splitlines())


def test_каждый_вид_сносится_перед_созданием():
    нарушения = []
    for файл in ФАЙЛЫ:
        код = без_комментариев(файл.read_text(encoding="utf-8"))
        сносимые = {m.group(1).lower() for m in СНОС.finditer(код)}
        for m in СОЗДАНИЕ.finditer(код):
            имя = m.group(1).lower()
            if имя not in сносимые:
                нарушения.append(f"{файл.relative_to(ROOT)}: {имя}")
    assert not нарушения, (
        "вид создаётся без предшествующего «drop view if exists» — на чистой "
        "базе это пройдёт, а на живой миграция упадёт «cannot change name of "
        "view column»:\n  " + "\n  ".join(нарушения))


def test_проверка_видит_хотя_бы_один_вид():
    """Пустой обход — это зелено ни на чём. Ловушка на переименование папок."""
    всего = sum(len(СОЗДАНИЕ.findall(без_комментариев(ф.read_text(encoding="utf-8"))))
                for ф in ФАЙЛЫ)
    assert всего >= 2, f"виды в схемах не нашлись ({всего}) — проверка смотрит не туда"


def test_комментарий_не_считается_оператором():
    """Разбор читает код, а не пояснения к нему."""
    образец = "-- было: create or replace view выдуманный_вид as select 1\nselect 1;"
    assert not СОЗДАНИЕ.findall(без_комментариев(образец))
