"""Расход и стоимость обслуживания: оценка обязана быть видна как оценка.

Источник собран по типовым интервалам ТО и нашим ценовым вилкам, а не по нашим
счетам. Смешать такую строку с фактом дешевле всего сейчас и дороже всего
потом, поэтому тесты держат три места: пометку расчётом, разницу между ценой за
единицу и ценой за год и допущение о наработке рядом с числом.

Строки придуманы здесь и не взяты из базы (правило 18).
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(name: str):
    spec = importlib.util.spec_from_file_location(
        f"kvant_{name}", ROOT / "library" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


lc = load("load_consumption")

ПРИМЕР = {
    "assumptions": {"hours_per_year": {"base": 8000}},
    "engines": [{
        "model": "Пример ГПУ П-100",
        "items": [
            {"key": "head", "name": "Головка блока цилиндров", "sys": "head",
             "qty_year": "8.0", "usd_unit": "3500", "usd_year": "28000",
             "interval": "30000", "note": "верхний ремонт"},
            {"key": "plug", "name": "Свеча зажигания", "sys": "ignition",
             "qty_year": "40", "usd_unit": "45", "usd_year": "1800",
             "interval": "2000"},
        ]}]}


def test_цена_за_единицу_и_за_год_остаются_разными():
    """Годовая сумма получается умножением на расход: у головки блока восемь
    штук в год. Подстановка одной вместо другой завысила бы позицию в восемь раз."""
    строки, _ = lc.разобрать(ПРИМЕР)
    головка = next(s for s in строки if "Головка" in s["name"])
    assert головка["usd_unit"] == 3500 and головка["usd_year"] == 28000
    assert головка["qty_year"] == 8


def test_каждая_строка_помечена_расчётом_и_хранит_допущение():
    строки, _ = lc.разобрать(ПРИМЕР)
    for s in строки:
        assert "расчёт" in s["source"], s["name"]
        assert "не наши счета" in s["source"], s["name"]
        assert s["hours_year"] == 8000, "допущение о наработке потерялось"


def test_узел_берётся_ключом_системы_а_не_угадывается():
    """В источнике узел уже проставлен инженером направления, и угадывать его по
    названию значило бы заменить разметку правилом там, где разметка есть."""
    строки, без_узла = lc.разобрать(ПРИМЕР)
    assert {s["unit_id"] for s in строки} == {"gpu.head", "gpu.ignition"}
    assert not без_узла


def test_строка_без_системы_попадает_в_список_без_узла_а_не_в_никуда():
    d = {"engines": [{"model": "Пример ГПУ П-200",
                      "items": [{"name": "Неведомая позиция", "usd_year": "10"}]}]}
    строки, без_узла = lc.разобрать(d)
    assert строки[0]["unit_id"] is None
    assert без_узла == ["Неведомая позиция"], "потеря узла обязана быть видна числом"


def test_идентификатор_устойчив_к_пересборке_источника():
    первый, _ = lc.разобрать(ПРИМЕР)
    второй, _ = lc.разобрать(ПРИМЕР)
    assert [s["id"] for s in первый] == [s["id"] for s in второй]
    assert len({s["id"] for s in первый}) == len(первый), "ключ не различает позиции"
