"""Зонд конверсии предложение → контракт: что считается предложением и что контрактом.

Проверяется то, что дало бы НЕВЕРНУЮ конверсию (разборы трёх и двух проверяющих и
первый прогон 08.10.2026):
1. Проигранная ПОСЛЕ выдачи ТКП сделка остаётся в знаменателе: предложение — по
   истории стадий, а не по текущей.
2. «Тендерное предложение выдано», «Quotation issued», «КП отправлено» — выдано;
   «Подготовка ТКП», «ТКП готово», «Отправка ТКП», сбор КП и голый суффикс
   EXECUTING — ещё нет; «Переторжка» — после предложения, без даты.
3. Победа — вход в кат. 0 ПОСЛЕ предпродажи; карточка, заведённая в кат. 0 и
   перенесённая в предпродажу, — предпродажная (кат. 0 — ещё и воронка по умолчанию).
4. Главная конверсия — симметричная: выигрыш без датированной стадии предложения в
   неё не входит, как и такой же проигрыш; широкая печатается отдельно.
5. Зрелая — только предложения старше 120 дней.
6. Карточка «только реализации» находит предпродажную пару той же компании.
7. Годы сходятся с итогом; в журнал не попадают названия компаний и слова вне
   общей лексики стадий (фамилии, названия клиентов в воронках).

Корпус придуман (правило 18).
"""
from __future__ import annotations

import datetime as dt
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("kvant_probe_conversion", ROOT / "scripts" / "probe_conversion.py")
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)

СЕГОДНЯ = dt.date(2026, 10, 8)


def стадия(name, sem="P", sort=10):
    return {"name": name, "sem": sem, "sort": sort}


МЕТА = {
    "C2:NEW": стадия("Новый запрос"), "C2:PREPARATION": стадия("Подготовка ТКП", sort=20),
    "C2:READY": стадия("ТКП готово", sort=25), "C2:UC_TKP": стадия("ТКП отправлено", sort=30),
    "C2:LOSE": стадия("Отказ в ТКП", "F", 90), "C2:PRICE": стадия("Не прошли по цене", "F", 91),
    "C8:NEW": стадия("New tender"), "C8:UC_BID": стадия("Тендерное предложение выдано | Работаем", sort=20),
    "C8:UC_RE": стадия("Переторжка | Торги", sort=25), "C8:UC_Q": стадия("Quotation Issued to Client", sort=30),
    "C8:EXECUTING": стадия("Поиск поставщиков и сбор КП", sort=15),
    "C8:PRICE": стадия("Не прошли по цене", "F", 91),
    "C4:NEW": стадия("Новый запрос"), "C4:SENT": стадия("КП отправлено", sort=30),
    "C4:PRICE": стадия("Не прошли по цене", "F", 91),
    "NEW": стадия("Реализация: старт"), "EXECUTING": стадия("Производство", sort=20),
}
for k in МЕТА:
    МЕТА[k]["cat"] = m.воронка_стадии(k)


def сделка(i, stage, sem="P", title="Учебная сделка", cat="2", created="2025-02-01T10:00:00+03:00", company="0"):
    return {"ID": str(i), "TITLE": title, "STAGE_ID": stage, "STAGE_SEMANTIC_ID": sem, "CATEGORY_ID": cat,
            "DATE_CREATE": created, "COMPANY_ID": company}


def t(d):
    return f"{d}T10:00:00+03:00"


def корпус():
    сделки = [
        сделка(1, "C2:LOSE", "F"),                                    # ТКП выдан, потом отказ
        сделка(2, "C2:UC_TKP"),                                       # ТКП выдан; заказ есть → контракт
        сделка(3, "C2:READY", created=t("2026-09-20")),               # «ТКП готово» — ещё не выдано
        сделка(4, "C2:NEW", title="871. Учебная реализация"),         # номер реализации, предложения нет
        сделка(5, "C2:LOSE", "F"),                                    # проиграна с заказом — не контракт
        сделка(6, "C2:UC_TKP", created=t("2026-09-01")),              # ТКП выдан недавно, живая
        сделка(7, "EXECUTING", cat="0"),                              # тендер выигран: C8 → кат. 0
        сделка(8, "C8:UC_Q"),                                         # Quotation issued, старая живая
        сделка(9, "C2:PRICE", "F"),                                   # «Не прошли по цене» без ТКП-стадии
        сделка(10, "EXECUTING", cat="0", created=t("2025-03-20"), company="77"),  # карточка реализации
        сделка(11, "C4:PRICE", "F"),                                  # заведена в кат. 0, перенесена в C4
        сделка(12, "C8:EXECUTING"),                                   # только сбор КП (суффикс EXECUTING)
        сделка(13, "C8:UC_RE"),                                       # переторжка без стадии предложения
        сделка(14, "C2:UC_TKP", company="77"),                        # предпродажа той же компании, что 10
    ]
    история = {
        "1": [("C2:NEW", t("2025-02-01")), ("C2:UC_TKP", t("2025-03-01")), ("C2:LOSE", t("2025-04-01"))],
        "2": [("C2:NEW", t("2025-02-01")), ("C2:UC_TKP", t("2025-03-10"))],
        "3": [("C2:NEW", t("2026-09-20")), ("C2:READY", t("2026-09-25"))],
        "5": [("C2:UC_TKP", t("2025-03-01")), ("C2:LOSE", t("2025-05-01"))],
        "6": [("C2:UC_TKP", t("2026-09-15"))],
        "7": [("C8:NEW", t("2025-01-10")), ("C8:UC_BID", t("2025-02-01")), ("NEW", t("2025-03-03")),
              ("EXECUTING", t("2025-12-20"))],
        "8": [("C8:NEW", t("2025-05-01")), ("C8:UC_Q", t("2025-06-01"))],
        "9": [("C2:NEW", t("2025-04-01")), ("C2:PRICE", t("2025-05-01"))],
        "10": [("NEW", t("2025-03-20")), ("EXECUTING", t("2025-04-01"))],
        "11": [("NEW", t("2025-02-01")), ("C4:NEW", t("2025-02-02")), ("C4:SENT", t("2025-02-10")),
               ("C4:PRICE", t("2025-03-01"))],
        "12": [("C8:NEW", t("2025-02-01")), ("C8:EXECUTING", t("2025-02-05"))],
        "13": [("C8:NEW", t("2025-02-01")), ("C8:UC_RE", t("2025-02-20"))],
        "14": [("C2:NEW", t("2025-01-20")), ("C2:UC_TKP", t("2025-02-15"))],
    }
    заказы = [{"parentId2": 2, "createdTime": "2025-04-09T00:00:00+03:00"},
              {"parentId2": 5, "createdTime": "2025-04-01T00:00:00+03:00"},
              {"parentId2": 0, "createdTime": "2025-04-01T00:00:00+03:00"}]
    холдинг = {str(i): m.HOLDING for i in range(1, 15)}
    return сделки, история, заказы, холдинг


def строки():
    сделки, история, заказы, холдинг = корпус()
    rows = m.классифицировать(сделки, история, МЕТА, заказы, холдинг, СЕГОДНЯ)
    m.найти_выигрыши_новой_карточкой(rows)
    return rows


def test_виды_стадий():
    вид = {k: m.вид_стадии(k, МЕТА)[0] for k in МЕТА}
    assert вид["C2:UC_TKP"] == вид["C8:UC_BID"] == вид["C8:UC_Q"] == вид["C4:SENT"] == "offer"
    assert вид["C2:PREPARATION"] == вид["C2:READY"] == вид["C8:EXECUTING"] == "none"
    assert вид["C8:UC_RE"] == вид["C2:PRICE"] == вид["EXECUTING"] == "beyond"
    assert вид["C2:LOSE"] == "none", "«Отказ в ТКП» — предложения не было"


def test_классификация():
    по = {r["id"]: r for r in строки()}
    assert по["1"]["offer_dated"] and по["1"]["cls"] == "lost", "проигранная после ТКП — в знаменателе"
    assert по["2"]["cls"] == "contract" and по["2"]["offer_date"] == "2025-03-10"
    assert not по["3"]["offer"]
    assert по["5"]["cls"] == "lost", "F с заказом — проигрыш, как company.py"
    r7 = по["7"]
    assert r7["cls"] == "contract" and r7["origin"] == "8" and r7["offer_date"] == "2025-02-01"
    assert r7["contract_date"] == "2025-03-03"
    assert по["10"]["realization_only"]
    assert not по["11"]["realization_only"] and по["11"]["origin"] == "4", "заведена в кат. 0, работала в C4"
    assert по["11"]["offer_dated"] and по["11"]["cls"] == "lost"
    assert not по["12"]["offer"], "голый суффикс EXECUTING — не предложение"
    assert по["13"]["offer_from"] == "beyond"
    assert по["9"]["offer_from"] == "beyond" and по["4"]["offer_from"] == "contract_only"
    assert по["14"]["twin_of"] == "10", "карточка реализации нашла предпродажную пару"


def test_свод_симметричная_зрелая_широкая():
    с = m.свод(строки())
    # датированные предложения: 1, 2, 5, 6, 7, 8, 11, 14
    assert (с["offers"], с["contracts"], с["lost"]) == (8, 2, 3)
    assert с["conv"] == 25                                   # 2 / 8
    assert (с["mature_n"], с["conv_mature"]) == (7, 29)      # без 6 (свежая): 2 / 7
    assert (с["twins"], с["conv_twins"]) == (1, 38)          # (2 + 1) / 8
    # широкая: + 9 (проигрыш по цене) и 13 (переторжка) без даты
    assert (с["offers_wide"], с["contracts_wide"], с["undated_lost"]) == (10, 2, 1)
    assert (с["contracts_only"], с["realization_only"]) == (1, 1)
    assert (с["days_median"], с["days_n"]) == (30, 2)


