"""Зонд конверсии предложение → контракт: что считается предложением и что контрактом.

Проверяется то, что дало бы НЕВЕРНУЮ конверсию (разбор трёх проверяющих 08.10.2026):
1. Проигранная ПОСЛЕ выдачи ТКП сделка остаётся в знаменателе: предложение — по
   истории стадий, а не по текущей стадии.
2. Тендерные стадии («Тендерное предложение выдано», «Quotation issued») — тоже
   выданное предложение; «Подготовка ТКП» — ещё нет.
3. Победа — переезд в воронку реализации (кат. 0): контракт и без заказа; его
   воронка — та, где сделка заведена, а не кат. 0; стадии кат. 0 и отгрузки не
   дают дату предложения.
4. Проигрыш с заказом — проигрыш (как company.py). Проигрыш «Не прошли по цене» —
   свидетельство поданного предложения без даты.
5. Контракт без отметки предложения в истории в знаменатель не идёт и считается
   отдельно; сделка, заведённая сразу в кат. 0, в конверсию не входит.
6. Зрелая конверсия не делит на молодые живые сделки; «тихие потери» (живые
   старше 120 дн.) идут в решённые как проигрыш.
7. Годы сходятся с итогом; в журнал не попадают названия клиентов вне разметки КАМ.

Корпус придуман (правило 18).
"""
from __future__ import annotations

import datetime as dt
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("kvant_probe_conversion", ROOT / "scripts" / "probe_conversion.py")
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)

СЕГОДНЯ = dt.date(2026, 10, 8)
МЕТА = {
    "C2:NEW": {"name": "Новый запрос", "sem": "P", "cat": "2", "sort": 10},
    "C2:PREPARATION": {"name": "Подготовка ТКП", "sem": "P", "cat": "2", "sort": 20},
    "C2:UC_TKP": {"name": "ТКП отправлен", "sem": "P", "cat": "2", "sort": 30},
    "C2:LOSE": {"name": "Отказ клиента", "sem": "F", "cat": "2", "sort": 90},
    "C2:PRICE": {"name": "Не прошли по цене", "sem": "F", "cat": "2", "sort": 91},
    "C8:NEW": {"name": "Тендер объявлен", "sem": "P", "cat": "8", "sort": 10},
    "C8:UC_BID": {"name": "Тендерное предложение выдано", "sem": "P", "cat": "8", "sort": 20},
    "C8:UC_Q": {"name": "Quotation issued", "sem": "P", "cat": "8", "sort": 25},
    "NEW": {"name": "Реализация: старт", "sem": "P", "cat": "0", "sort": 10},
    "EXECUTING": {"name": "Производство", "sem": "P", "cat": "0", "sort": 20},
}


def сделка(i, stage, sem="P", title="Учебная сделка", cat="2", created="2025-02-01T10:00:00+03:00"):
    return {"ID": str(i), "TITLE": title, "STAGE_ID": stage, "STAGE_SEMANTIC_ID": sem, "CATEGORY_ID": cat,
            "DATE_CREATE": created}


def корпус():
    сделки = [
        сделка(1, "C2:LOSE", "F"),                               # ТКП выдан, потом отказ
        сделка(2, "C2:UC_TKP"),                                  # ТКП выдан; заказ есть → контракт
        сделка(3, "C2:PREPARATION", created="2026-09-20T10:00:00+03:00"),  # ТКП не выдан
        сделка(4, "C2:NEW", title="871. Учебная реализация"),    # номер реализации, предложения в истории нет
        сделка(5, "C2:LOSE", "F"),                               # проиграна с заказом — не контракт
        сделка(6, "C2:UC_TKP", created="2026-09-01T10:00:00+03:00"),       # ТКП выдан недавно, живая
        сделка(7, "EXECUTING", cat="0"),                         # тендер выигран: переезд C8 → кат. 0, заказа нет
        сделка(8, "C8:UC_Q"),                                    # Quotation issued, живая и старая → тихая потеря
        сделка(9, "C2:PRICE", "F"),                              # «Не прошли по цене» без стадии ТКП
        сделка(10, "EXECUTING", cat="0"),                        # заведена сразу в кат. 0 — только реализация
    ]
    история = {
        "1": [("C2:NEW", "2025-02-01T10:00:00+03:00"), ("C2:UC_TKP", "2025-03-01T10:00:00+03:00"),
              ("C2:LOSE", "2025-04-01T10:00:00+03:00")],
        "2": [("C2:NEW", "2025-02-01T10:00:00+03:00"), ("C2:UC_TKP", "2025-03-10T10:00:00+03:00")],
        "3": [("C2:NEW", "2026-09-20T10:00:00+03:00"), ("C2:PREPARATION", "2026-09-25T10:00:00+03:00")],
        "5": [("C2:UC_TKP", "2025-03-01T10:00:00+03:00"), ("C2:LOSE", "2025-05-01T10:00:00+03:00")],
        "6": [("C2:UC_TKP", "2026-09-15T10:00:00+03:00")],
        "7": [("C8:NEW", "2025-01-10T10:00:00+03:00"), ("C8:UC_BID", "2025-02-01T10:00:00+03:00"),
              ("NEW", "2025-03-03T10:00:00+03:00"), ("EXECUTING", "2025-12-20T10:00:00+03:00")],
        "8": [("C8:NEW", "2025-05-01T10:00:00+03:00"), ("C8:UC_Q", "2025-06-01T10:00:00+03:00")],
        "9": [("C2:NEW", "2025-04-01T10:00:00+03:00"), ("C2:PRICE", "2025-05-01T10:00:00+03:00")],
        "10": [("NEW", "2025-02-01T10:00:00+03:00"), ("EXECUTING", "2025-03-01T10:00:00+03:00")],
    }
    заказы = [{"parentId2": 2, "createdTime": "2025-04-09T00:00:00+03:00"},
              {"parentId2": 5, "createdTime": "2025-04-01T00:00:00+03:00"},
              {"parentId2": 0, "createdTime": "2025-04-01T00:00:00+03:00"}]
    холдинг = {str(i): m.HOLDING for i in range(1, 11)}
    return сделки, история, заказы, холдинг


def строки():
    сделки, история, заказы, холдинг = корпус()
    return m.классифицировать(сделки, история, МЕТА, заказы, холдинг, СЕГОДНЯ)


def test_предложение_по_истории_и_тендерные_стадии():
    по = {r["id"]: r for r in строки()}
    assert по["1"]["offer"] and по["1"]["cls"] == "lost", "проигранная после ТКП — в знаменателе"
    assert по["2"]["cls"] == "contract" and по["2"]["offer_date"] == "2025-03-10"
    assert not по["3"]["offer"], "«Подготовка ТКП» — ещё не выдано"
    assert по["8"]["offer"] and по["8"]["offer_date"] == "2025-06-01", "Quotation issued — предложение"
    assert по["9"]["offer"] and по["9"]["offer_from"] == "beyond" and по["9"]["offer_date"] is None


def test_победа_переездом_в_реализацию():
    по = {r["id"]: r for r in строки()}
    r7 = по["7"]
    assert r7["cls"] == "contract" and r7["signals"]["кат0"] and not r7["signals"]["заказ"]
    assert r7["origin"] == "8", "воронка — где заведена, а не текущая кат. 0"
    assert r7["offer_date"] == "2025-02-01", "дата — по стадии предложения, а не по стадии реализации"
    assert r7["contract_date"] == "2025-03-03", "дата контракта — первый вход в кат. 0"
    assert по["10"]["realization_only"]
    assert по["5"]["cls"] == "lost", "F с заказом — проигрыш, как company.py"
    assert по["4"]["cls"] == "contract" and по["4"]["offer_from"] == "contract_only"


def test_свод_три_конверсии():
    с = m.свод(строки())
    # предложения: 1, 2, 5, 6, 7, 8, 9 (4 — контракт без отметки, 3 — не выдано, 10 — только реализация)
    assert (с["offers"], с["contracts"], с["lost"], с["stuck"], с["young"]) == (7, 2, 3, 1, 1)
    assert с["conv"] == 29                          # 2 / 7
    assert с["conv_mature"] == 33                   # 2 / (7 − 1 молодая)
    assert с["conv_decided"] == 33                  # 2 / (2 + 3 + 1 тихая)
    assert (с["contracts_only"], с["realization_only"], с["offers_undated"]) == (1, 1, 1)
    assert (с["days_median"], с["days_n"]) == (30, 2), "10.03→09.04 = 30, 01.02→03.03 = 30"


def test_пустая_выборка_не_делит_на_ноль():
    с = m.свод([])
    assert с["conv"] is None and с["conv_mature"] is None and с["days_median"] is None


def test_дата_по_москве():
    assert m.дата_мск("2025-03-01T22:30:00+00:00") == "2025-03-02"
    assert m.дата_мск("2025-03-01T10:00:00+03:00") == "2025-03-01"
    assert m.дата_мск("2025-03-01") == "2025-03-01"


def test_номер_реализации():
    assert m.номер_реализации("871. Поставка") == 871
    assert m.номер_реализации("871/2. Поставка") == 871
    assert m.номер_реализации("PO-871 Поставка") == 0


def test_журнал_без_клиентов_и_годы_сходятся(capsys):
    сделки, история, заказы, холдинг = корпус()
    холдинг["1"] = "ООО Учебный Клиент Вымысел"
    rows = m.классифицировать(сделки, история, МЕТА, заказы, холдинг, СЕГОДНЯ)
    мета = dict(МЕТА, **{"C2:UC_TKP": {"name": "ТКП отправлен Вымыслу", "sem": "P", "cat": "2", "sort": 30}})
    m.отчёт(rows, история, set(), мета, {"2": "Воронка Вымысел", "8": "Тендеры"},
            m.слова_клиентов({"1": "ООО Учебный Клиент Вымысел"}))
    out = capsys.readouterr().out
    assert "Учебный Клиент" not in out and "Прочие клиенты" in out
    assert "Вымысел" not in out and "Вымыслу" not in out, "названия воронок и стадий — с маской"
    assert "‹клиент›" in out
