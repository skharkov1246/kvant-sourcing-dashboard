"""Зонд конверсии ТКП → контракт: что считается предложением и что контрактом.

Проверяется то, что дало бы НЕВЕРНУЮ конверсию:
1. Проигранная ПОСЛЕ выдачи ТКП сделка остаётся в знаменателе: ТКП — по истории
   стадий, а не по текущей стадии (текущая — «Отказ», и её бы потеряли).
2. Контракт — по заказу поставщику СП-172 или номеру реализации; проигранная
   (semantic F) сделка с заказом — не контракт (как company.py).
3. Контракт без ТКП-стадии в истории — всё же выданное предложение, но отмечен
   как пробел данных и не участвует в сроке «ТКП → контракт».
4. Сделка без ТКП (запрос клиента без предложения) в знаменатель не входит.

Корпус придуман (правило 18).
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("kvant_probe_conversion", ROOT / "scripts" / "probe_conversion.py")
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)

МЕТА = {
    "C2:NEW": {"name": "Новый запрос", "sem": "P", "cat": "2"},
    "C2:PREPARATION": {"name": "Подготовка ТКП", "sem": "P", "cat": "2"},
    "C2:UC_TKP": {"name": "ТКП отправлен", "sem": "P", "cat": "2"},
    "C2:LOSE": {"name": "Отказ клиента", "sem": "F", "cat": "2"},
    "C2:WON": {"name": "Сделка успешна", "sem": "S", "cat": "2"},
}


def сделка(i, stage, sem="P", title="Учебная сделка", cat="2"):
    return {"ID": str(i), "TITLE": title, "STAGE_ID": stage, "STAGE_SEMANTIC_ID": sem, "CATEGORY_ID": cat,
            "DATE_CREATE": "2025-02-01T10:00:00+03:00"}


def корпус():
    сделки = [
        сделка(1, "C2:LOSE", "F"),                 # ТКП выдан, потом отказ
        сделка(2, "C2:UC_TKP"),                    # ТКП выдан, ждём; заказ есть → контракт
        сделка(3, "C2:PREPARATION"),               # ТКП не выдан
        сделка(4, "C2:NEW", title="871. Учебная реализация"),   # номер реализации, ТКП в истории нет
        сделка(5, "C2:LOSE", "F"),                 # проиграна с заказом — не контракт
        сделка(6, "C2:UC_TKP"),                    # ТКП выдан, в работе
    ]
    история = {
        "1": [("C2:NEW", "2025-02-01T10:00:00"), ("C2:UC_TKP", "2025-03-01T10:00:00"), ("C2:LOSE", "2025-04-01T10:00:00")],
        "2": [("C2:NEW", "2025-02-01T10:00:00"), ("C2:UC_TKP", "2025-03-10T10:00:00")],
        "3": [("C2:NEW", "2025-02-01T10:00:00"), ("C2:PREPARATION", "2025-02-05T10:00:00")],
        "5": [("C2:UC_TKP", "2025-03-01T10:00:00"), ("C2:LOSE", "2025-05-01T10:00:00")],
        "6": [("C2:UC_TKP", "2026-01-15T10:00:00")],
    }
    заказы = [{"parentId2": 2, "createdTime": "2025-04-09T00:00:00+03:00"},
              {"parentId2": 5, "createdTime": "2025-04-01T00:00:00+03:00"},
              {"parentId2": 0, "createdTime": "2025-04-01T00:00:00+03:00"}]
    холдинг = {str(i): m.HOLDING for i in range(1, 7)}
    return сделки, история, заказы, холдинг


def test_классификация_и_свод():
    сделки, история, заказы, холдинг = корпус()
    строки = m.классифицировать(сделки, история, МЕТА, заказы, холдинг)
    по = {r["id"]: r for r in строки}
    assert по["1"]["tkp"] and по["1"]["cls"] == "lost", "проигранная после ТКП — в знаменателе"
    assert по["2"]["cls"] == "contract" and по["2"]["tkp_date"] == "2025-03-10"
    assert not по["3"]["tkp"], "«Подготовка ТКП» — ещё не выдано"
    assert по["4"]["cls"] == "contract" and по["4"]["tkp_from"] == "contract"
    assert по["5"]["cls"] == "lost", "F с заказом — проигрыш, как company.py"
    с = m.свод(строки)
    assert (с["tkp"], с["contracts"], с["lost"], с["open"]) == (5, 2, 2, 1)
    assert с["conv"] == 40 and с["conv_decided"] == 50
    assert с["contracts_without_tkp_mark"] == 1
    assert (с["days_median"], с["days_n"]) == (30, 1), "срок — только по истории: 10.03 → 09.04"


def test_пустая_выборка_не_делит_на_ноль():
    с = m.свод([])
    assert с["conv"] is None and с["days_median"] is None


def test_номер_реализации():
    assert m.номер_реализации("871. Поставка") == 871
    assert m.номер_реализации("871/2. Поставка") == 871
    assert m.номер_реализации("PO-871 Поставка") == 0
