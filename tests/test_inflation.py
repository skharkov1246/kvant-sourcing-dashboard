"""Индексация цены на инфляцию и приведение к сравнимой цене.

Ряд индекса и цены — выдуманные. Реальный файл проверяется только на форму:
месяцы подряд по возрастанию, значения больше нуля, источник у каждой точки.
"""
import json
import re
from datetime import date

import pytest

from library import inflation as I
from library import price_norm as P

# Выдуманный ряд: две валюты, у «XUS» пропуск 2024-03, ряд кончается 2024-06.
РЯДЫ = {
    "XUS": {"2024-01": 100.0, "2024-02": 101.0, "2024-04": 104.0,
            "2024-05": 105.0, "2024-06": 110.0},
    "RUB": {"2018-12": 200.0, "2019-01": 202.0, "2025-12": 300.0,
            "2026-01": 303.0, "2026-06": 330.0},
}


# ── inflation.индексировать ────────────────────────────────────────────────

def test_коэффициент_отношение_двух_точек():
    цена, k, о = I.индексировать(50.0, "XUS", "2024-01-20", "2024-06-01", ряды=РЯДЫ)
    assert (цена, k, о) == (55.0, 1.1, None)


def test_валюта_без_регистра_и_даты_разных_видов():
    цена, k, _ = I.индексировать(10.0, " xus ", date(2024, 2, 5), "2024-05", ряды=РЯДЫ)
    assert k == round(105 / 101, 6) and цена == round(10 * k, 2)


def test_месяц_после_ряда_берёт_последний_известный():
    цена, k, о = I.индексировать(100.0, "XUS", "2024-01", "2024-09-26", ряды=РЯДЫ)
    assert k == 1.1 and цена == 110.0
    assert о == "индекс за 2024-09 не опубликован, взят 2024-06"


def test_пропуск_внутри_ряда_берёт_предыдущий_месяц():
    _, k, о = I.индексировать(100.0, "XUS", "2024-03-10", "2024-06", ряды=РЯДЫ)
    assert k == round(110 / 101, 6)
    assert "индекс за 2024-03 не опубликован, взят 2024-02" in о


def test_оба_месяца_за_краем_ряда_коэффициент_единица():
    цена, k, о = I.индексировать(100.0, "XUS", "2024-08", "2024-12", ряды=РЯДЫ)
    assert (цена, k) == (100.0, 1.0)
    assert "не опубликованы" in о


def test_валюта_без_ряда_не_индексируется():
    assert I.индексировать(100.0, "JPY", "2024-01", "2024-06", ряды=РЯДЫ) == (
        100.0, None, "индекса цен для валюты JPY нет — без индексации")
    цена, k, о = I.индексировать(100.0, None, "2024-01", "2024-06", ряды=РЯДЫ)
    assert (цена, k) == (100.0, None) and "(не указана)" in о


def test_цена_старше_ряда_не_индексируется():
    цена, k, о = I.индексировать(100.0, "XUS", "2023-12-31", "2024-06", ряды=РЯДЫ)
    assert (цена, k) == (100.0, None)
    assert "старше ряда" in о and "2024-01" in о


def test_приведение_назад_помечено():
    цена, k, о = I.индексировать(110.0, "XUS", "2024-06", "2024-01", ряды=РЯДЫ)
    assert цена == 100.0 and k == round(100 / 110, 6)
    assert "назад" in о


def test_нет_цены_коэффициент_есть():
    assert I.индексировать(None, "XUS", "2024-01", "2024-06", ряды=РЯДЫ) == (None, 1.1, None)


def test_не_дата_ошибка():
    with pytest.raises(ValueError):
        I.индексировать(1.0, "XUS", "вчера", "2024-06", ряды=РЯДЫ)
    with pytest.raises(ValueError):
        I.месяц("2024-13-01")


def test_загрузка_из_файла(tmp_path):
    f = tmp_path / "cpi.json"
    f.write_text(json.dumps({"ряды": {"XUS": {"точки": [
        {"месяц": "2024-01", "значение": 100, "источник": "https://example.invalid/", "выгружено": "2026-09-26"},
        {"месяц": "2024-02", "значение": 102, "источник": "https://example.invalid/", "выгружено": "2026-09-26"},
    ]}}}), encoding="utf-8")
    ряды = I.загрузить(f)
    assert ряды == {"XUS": {"2024-01": 100.0, "2024-02": 102.0}}
    assert I.индексировать(10.0, "XUS", "2024-01", "2024-02", ряды=ряды)[:2] == (10.2, 1.02)


