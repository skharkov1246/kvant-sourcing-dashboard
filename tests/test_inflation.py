def test_рублёвая_цена_с_ндс_2026_делится_на_22_процента():
    цена, о = P.привести(122.0, "RUB", "2026-01-15", на_дату="2026-06-30",
                         примечание="цена с НДС, FCA Екатеринбург", страна="RU", ряды=РЯДЫ)
    # 122 / 1,22 = 100; 100 × 330 / 303
    assert цена == round(100.0 * round(330 / 303, 6), 2)
    assert any("НДС 22 %" in x for x in о)
    assert not any("базис" in x for x in о)


