# ── реальный файл: только форма ────────────────────────────────────────────

def test_форма_реального_файла():
    doc = json.loads(I.PATH.read_text(encoding="utf-8"))
    assert set(doc["ряды"]) >= {"RUB", "USD", "EUR", "CNY", "GBP"}
    for вал, р in doc["ряды"].items():
        точки = р["точки"]
        assert точки, вал
        месяцы = [т["месяц"] for т in точки]
        assert all(re.fullmatch(r"\d{4}-(0[1-9]|1[0-2])", м) for м in месяцы), вал
        assert месяцы == sorted(set(месяцы)), f"{вал}: месяцы не строго по возрастанию"
        assert месяцы[0] >= "2018-01", вал
        assert (р["первый_месяц"], р["последний_месяц"], р["точек"]) == (
            месяцы[0], месяцы[-1], len(точки)), вал
        for т in точки:
            assert isinstance(т["значение"], (int, float)) and т["значение"] > 0, (вал, т)
            assert т["источник"].startswith("https://"), (вал, т)
            assert re.fullmatch(r"\d{4}-\d{2}-\d{2}", т["выгружено"]), (вал, т)
        assert р["url"] and "официальный" in р
        if not р["официальный"]:
            assert р.get("зеркало"), f"{вал}: зеркало не названо"
