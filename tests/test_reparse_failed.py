"""Переразбор умеет брать файлы, не давшие НИЧЕГО.

Замер по всей базе: 9 527 файлов не дали ни одной позиции, и ни один
существующий прогон их не перечитывает — переразбор требует статуса «разобран»,
распознавание берёт только сканы. То есть новые читатели (csv, rtf, html,
выгрузка 1С, архив, старый .doc) измерить было нечем: файлы, ради которых они
написаны, не попадают ни в одну выборку.
"""
from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent


def код(путь: str, знак: str = "#") -> str:
    текст = (КОРЕНЬ / путь).read_text(encoding="utf-8")
    return re.sub(rf"(?<!\w){re.escape(знак)}[^\n]*", "", текст)


def запрос(имя: str) -> str:
    m = re.search(имя + r' = """(.*?)"""', код("library/reparse.py"), re.S)
    assert m, f"нет запроса {имя}"
    return m.group(1)


def test_отбор_умеет_брать_неудавшиеся():
    q = запрос("CANDIDATES")
    assert "f.status = 'разобран'" in q, "успешные файлы должны браться всегда"
    assert "f.status = any(%s)" in q, "неудавшиеся взять нечем"


def test_по_умолчанию_неудавшиеся_не_берутся():
    """Подмешивать неудачи к успешным файлам значит мерить две правки одним числом."""
    текст = код("library/reparse.py")
    assert 'НЕУДАВШИЕСЯ = os.environ.get("REPARSE_FAILED", "") not in ("", "0", "false")' \
        in текст, "включено по умолчанию или читается не из входа"


def test_не_скачался_в_список_неудач_не_входит():
    """У такого файла нет ни вида, ни байтов: его лечит повтор закачки, а не
    другой читатель. Взять его сюда — значит гонять портал впустую."""
    текст = код("library/reparse.py")
    m = re.search(r"СТАТУСЫ_НЕУДАЧИ = \(([^)]*)\)", текст)
    assert m, "списка статусов неудачи нет"
    assert "не скачался" not in m.group(1), "«не скачался» попал в переразбор"
    for статус in ("пусто", "формат не читаем", "текст без спецификации"):
        assert статус in m.group(1), f"{статус} не берётся"


def test_выборка_называется_в_журнале():
    """Иначе по итогу непонятно, что за файлы считались."""
    текст = код("library/reparse.py")
    assert "включая НЕУДАВШИЕСЯ" in текст


def test_вход_прогона_есть_и_не_прибит():
    yml = код(".github/workflows/library-index.yml")
    assert "reparse_failed:" in yml
    assert re.search(r"REPARSE_FAILED:\s*\$\{\{\s*inputs\.reparse_failed", yml)
    assert not re.search(r"REPARSE_FAILED=\S+\s+python", yml), "значение прибито в шаге"


def test_итог_называет_почему_файл_остался_пустым():
    """«пусто 228» не говорит, какой читатель закроет эти файлы.

    Разбивка по формату и причине — единственный способ выбрать следующую правку
    по числам, а не на глаз.
    """
    текст = код("library/reparse.py")
    assert "ПОЧЕМУ ФАЙЛ ОСТАЛСЯ БЕЗ ПОЗИЦИЙ" in текст
    assert re.search(r"if not items:\s*\n\s*пустые\[", текст), \
        "пустые файлы не считаются"
    assert 'rec.get("subkind")' in текст[текст.index("if not items:"):][:300], \
        "разбивка без формата"
