# ── без флага не меняется ничего ─────────────────────────────────────────────
@pytest.mark.parametrize("шапка", [
    ["Unit price (13%VAT)", "Amount (13%VAT)"], ["Rate", "Amount (13%VAT)", "Line price"],
    ["Цена за ед., руб. (НДС 20%)", "Сумма, руб."], ["Цена без НДС", "Цена с НДС", "Сумма с НДС"],
])
def test_без_флага_прежнее_правило(шапка):
    items = _читать(шапка, lambda к, ц: [ц, ц * к, ц * к][:len(шапка)], v2=False)
    for it in items:
        assert "_цена_прежде" not in it
        assert НЕ_СКАЗАНО not in ((it["_цена"] or {}).get("note") or "")
