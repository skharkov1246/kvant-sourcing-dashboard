"""НДС в шапке цены: колонка налога или цена, при которой НДС лишь упомянут.

ЗАЧЕМ. До 27.09.2026 quotes.ндс_колонки считала налогом всякую шапку, где НДС
назван без «с» и «без»: «Unit price (13%VAT)», «Цена, руб. НДС 20%», «Amount
(13%VAT)». Вторая редакция словаря цены (PRICE_DICT_V2) из-за этого:
  • теряла цену, которую прежнее правило читало: перебор выдуманных шапок
    (37 853 шапки) — 902 шапки «прежнее дало цену за единицу, v2 ничего», пример
    `Qty | Unit price (13%VAT) | Amount (13%VAT)`;
  • на 12 шапках `Rate | Amount (13%VAT) | Line price` брала ценой сумму строки,
    и проверке indexer.цена_это_сумма опорной суммы не было.

Теперь налог — колонка, чей ПРЕДМЕТ налог («НДС», «Сумма НДС», «VAT amount»,
«Tax»); колонка со словом цены или суммы, при которой НДС лишь упомянут, —
«упомянут»: цена или сумма с оговоркой «включён ли НДС — не сказано», без
пересчёта на ставку (CLAUDE.md, «Цена и предложение»: ценой с НДС она не
объявляется, так сказано только при «с НДС», «incl.», «в т.ч.»). Берётся она
только там, где без неё у файла не было бы ни цены, ни суммы, или где
арифметика по файлу показала, что она одной природы с суммой строки: рядом с
ценой без оговорки такая колонка скорее с НДС, а цену без НДС владелец велел
предпочитать. Корпуса придуманы (CLAUDE.md, правило 18).
"""
from __future__ import annotations

import pytest

from library import indexer
from library import quotes as q
from library import reparse

ПОЗИЦИИ = [("Насос ЦНС 38-176 с рамой", 2, 150000.0), ("Задвижка 30с41нж Ду100", 4, 25000.0),
           ("Подшипник 6208-2RS", 10, 350.0), ("Уплотнение торцевое", 3, 12000.0)]
НЕ_СКАЗАНО = q.ОГОВОРКА_НДС_НЕ_СКАЗАНО


def _деньги(x: float) -> str:
    return f"{x:,.2f}".replace(",", " ").replace(".", ",")


def _таблица(шапка: list[str], ячейки) -> list[list[str]]:
    """ячейки(кол, цена) → числа денежных колонок строки."""
    return [["Наименование", "Кол-во"] + шапка] + [
        [имя, str(кол)] + [_деньги(x) for x in ячейки(кол, цена)] for имя, кол, цена in ПОЗИЦИИ]


def _читать(шапка, ячейки, *, v2=True):
    items = indexer.items_from_rows(_таблица(шапка, ячейки), словарь_v2=v2, без_шапки=False)
    assert len(items) == len(ПОЗИЦИИ)
    return items


