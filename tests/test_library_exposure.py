"""Очередь работ по деньгам: что можно брать из описи вложений, а что нельзя.

Источник отвечает не «сколько стоит», а «где цена лежит»: сделка, файл, сколько
в нём строк и сколько с ценой. Тесты держат три места, каждое из которых уже
ломалось или сломало бы выборку: свёртку двух написаний одного номера, выбор
адреса и перенос отрицательного контроля в данные.

Строки придуманы здесь и не взяты из базы (правило 18).
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(name: str):
    spec = importlib.util.spec_from_file_location(
        f"kvant_{name}", ROOT / "library" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


le = load("load_exposure")


def строка(pn, usd, qty=1, адреса=None):
    return {"pn": pn, "name": "Пример позиции", "qty": qty, "usd_exposure": usd,
            "we_already_have_price": "False",
            "found_in": адреса if адреса is not None else
            [{"deal": "сделка 1", "file": "a.xlsx", "rows": 10, "rows_with_price": 3}]}


def test_два_написания_одного_номера_дают_одну_строку_и_сумму_денег():
    """Номер приходит и с дефисами, и без; после нормализации ключ один, и две
    строки в одной вставке роняют её целиком. Деньги складываются: за деталью
    стоит вся сумма, иначе очередь недосчитается работы."""
    строки = le.разобрать({"rows": [строка("ПРИМЕР-12-34", 1000, 2),
                                    строка("пример 1234", 500, 3)]})
    assert len(строки) == 1, "написания не свернулись — вставка упадёт"
    z = строки[0]
    assert z["usd_exposure"] == 1500 and z["qty"] == 5
    assert z["написаний"] == 2


def test_адресом_становится_файл_где_цен_больше():
    """В описи рядом лежат двухтысячестрочный прайс поставщика и наш запрос из
    тридцати строк. Идти надо туда, где цен больше."""
    строки = le.разобрать({"rows": [строка("ПРИМЕР-1", 100, адреса=[
        {"deal": "сделка мелкая", "file": "мало.xlsx", "rows": 30, "rows_with_price": 6},
        {"deal": "сделка крупная", "file": "много.xlsx", "rows": 2371,
         "rows_with_price": 1843}])]}
    )
    z = строки[0]
    assert z["deal"] == "сделка крупная" and z["file_rows_priced"] == 1843
    assert z["addresses"] == 2, "число адресов обязано остаться видимым"


def test_основание_сверки_переносится_в_данные():
    """Отрицательный контроль — главное, что отличает измеренное от
    правдоподобного: выдуманные номера дали 0,0 % совпадений против 60,4 %
    у настоящих. Без этого через месяц не отличить одно от другого."""
    z = le.разобрать({"rows": [строка("ПРИМЕР-2", 10)]})[0]
    assert "отрицательный контроль" in z["source"]
    assert "0,0" in z["source"] and "60,4" in z["source"]


def test_сумма_не_выдумывается():
    """Позиция без суммы остаётся без суммы: ноль в очереди работ значил бы
    «денег нет», а на деле их просто не посчитали."""
    z = le.разобрать({"rows": [строка("ПРИМЕР-3", None)]})[0]
    assert z["usd_exposure"] is None
