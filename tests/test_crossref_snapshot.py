# Единый снимок перестал помещаться в 8 МиБ; разложить() делит провод, а граф
# остаётся тем же. Здесь проверяется, что при делении ничего не теряется и не
# переезжает: склейка частей даёт исходный порядок, подробности лежат ровно в
# той корзине, номер которой записан у строки, а рёбра совпадают со счётчиками.

def _склеить(ключи):
    строки = [p for k in crossref.КЛЮЧИ_СПИСКА for p in ключи[k]["positions"]]
    полные = []
    for p in строки:
        # Подробности пары — под ключом пары (ид_позиции): у кода, разбитого по
        # брендам, пар несколько, а корзина одна — по ключу кода.
        подробно = ключи[crossref.КЛЮЧИ_КОРЗИН[p["b"]]]["positions"].get(crossref.ид_позиции(p), {})
        полные.append({**{k: v for k, v in p.items() if k != "b"}, **подробно})
    return строки, полные


def test_разложение_без_потерь_и_в_том_же_порядке():
    s = снимок()
    ключи = crossref.разложить(s)
    assert tuple(ключи) == crossref.ВСЕ_КЛЮЧИ, "ключи не совпали с закрытым списком"
    заголовок = ключи[crossref.КЛЮЧ]
    assert "positions" not in заголовок
    assert заголовок["lists"] == crossref.СПИСОК_ЧАСТЕЙ
    assert заголовок["parts"] == crossref.КОРЗИН
    assert заголовок["totals"] == s["totals"] and заголовок["companies"] == s["companies"]
    строки, полные = _склеить(ключи)
    assert [p["k"] for p in строки] == [p["k"] for p in s["positions"]]
    for p, исходная in zip(полные, s["positions"]):
        # Пустое не едет, ложный признак тоже; всё остальное — то же самое.
        непустое = {k: v for k, v in исходная.items()
                    if v not in (None, "", [], {}) and not (k in ("cmp", "cat") and v is False)}
        assert p == непустое, p["k"]


def test_подробности_только_в_корзине_и_в_своей():
    ключи = crossref.разложить(снимок())
    строки, _ = _склеить(ключи)
    for p in строки:
        assert p["b"] == crossref.корзина(p["k"])
        for поле in crossref.ПОДРОБНОСТИ:
            assert поле not in p, f"{поле} лежит в списке — это вес, который списку не нужен"
