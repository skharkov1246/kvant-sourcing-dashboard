def test_усечение_видно_числом():
    много = [строка("bolt", "BOLT-1", f"c{i}", цена=i + 1, валюта="EUR")
             for i in range(crossref.ПРЕДЛОЖЕНИЙ_НА_ПОЗИЦИЮ + 7)]
    p = позиция(crossref.собрать(много), "bolt")
    assert p["offers"] == crossref.ПРЕДЛОЖЕНИЙ_НА_ПОЗИЦИЮ + 7
    assert p["shown"] == crossref.ПРЕДЛОЖЕНИЙ_НА_ПОЗИЦИЮ
    assert len(p["list"]) == crossref.ПРЕДЛОЖЕНИЙ_НА_ПОЗИЦИЮ
    # Число компаний считается по ВСЕМ строкам, а не по показанным: иначе
    # усечение занижало бы главный счётчик карточки.
    assert p["co"] == crossref.ПРЕДЛОЖЕНИЙ_НА_ПОЗИЦИЮ + 7


def test_пустые_ключи_в_предложение_не_едут():
    """Предложений 18 тысяч, ключей четырнадцать, заполнены обычно четыре.

    Пустой ключ — вес без сведений: отсев дал 0,64 МиБ из 9,27. Ноль при этом
    ОСТАЁТСЯ: «срок 0 дней» и «срок неизвестен» — разные вещи.
    """
    корпус = [строка("x", "X-1", "c1", цена=10, валюта="EUR", срок=0)]
    п = позиция(crossref.собрать(корпус), "x")
    о = п["list"][0]
    assert "qty" not in о and "basis" not in о and "unit" not in о
    assert "oem" not in о and "brands" not in о
    # Имя компании в предложении не лежит: оно одно на компанию, в companies.
    assert "ent_name" not in о
    assert о["lead"] == 0, "ноль выброшен вместе с пустыми — это разные вещи"
    assert о["price"] == 10 and о["cur"] == "EUR"


def test_позиция_вне_спроса_считается_отдельно():
    """Счётчик no_demand ловит котировку на артикул из-за пределов спецификаций.

    На живой базе он сегодня ноль: артикулы котировок берутся из спецификаций,
    и «спрашивали» для них тавтология. Первая версия счётчика считала «без выбора
    и со спросом» и выдала 8 823 — ровно все позиции без выбора: выглядела
    сужением списка работы, а не сужала ничего. Ноль честнее.

    Но множества могут разойтись, и тогда число обязано это сказать. Здесь
    проверяется, что скажет.
    """
    корпус = [строка("есть", "E-1", "c1", цена=1, валюта="EUR"),
              строка("нету", "N-1", "c2", цена=2, валюта="EUR")]
    спрос = [("есть", 3, 5, 1, 12)]        # на «нету» спроса нет вовсе
    s = crossref.собрать(корпус, спрос=спрос)
    assert s["totals"]["no_demand"] == 1
    assert позиция(s, "есть")["demand"]["deals"] == 3
    assert позиция(s, "нету")["demand"] is None


