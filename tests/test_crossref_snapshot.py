# 9 589 предложений из 29 020 имели в той же позиции точную копию — те же
# компания, цена, валюта, количество и дата. Сорсер видел одно предложение по
# два-три раза. Сборка схлопывает их по crossref.ключ_дубля; предложение,
# отличное хоть одним полем ключа, остаётся отдельным, а сведения копий (сколько
# их, с каких карточек, расходятся ли) едут с оставшимся.

К = crossref.ПОЛЯ_ПРЕДЛОЖЕНИЯ
БЕЗ_ДУБЛЕЙ = {"groups": 0, "rows": 0, "cards": 0, "one_card": 0, "one_file": 0,
              "no_file": 0, "differ": 0}


def _копия(компания="c7", ключ="vk12", **kw):
    """Одно и то же предложение: компания c7, 12,5 EUR за 4 шт., дата Д."""
    return строка(ключ, ключ.upper(), компания, **{"цена": 12.5, "валюта": "EUR", "qty": 4, **kw})


def test_точные_дубли_схлопываются_в_одно_предложение():
    корпус = [_копия(карточка="R-1", файл="f1"),
              _копия(карточка="R-1", файл="f2"),     # тот же КП в другом поле карточки
              _копия(карточка="R-2", файл="f3")]     # тот же КП на другой карточке
    s = crossref.собрать(корпус)
    p = позиция(s, "vk12")
    assert p["offers"] == 1 and p["shown"] == 1 and len(p["list"]) == 1
    o = p["list"][0]
    assert o[К["dups"]] == 3, "число копий потеряно"
    assert o[К["rfq"]] == "R-1" and o[К["rfq_more"]] == ["R-2"], "карточка копии потеряна"
    assert К["differ"] not in o
    # Счётчики — по предложениям, а не по строкам: иначе сумма рёбер больше
    # offers (n.e_cnt) и «строк» у компании втрое больше работы.
    assert p["e"] == [[0, 1, 12.5, "EUR", "2026-09-01"]]
    assert компания(s, "c7")["rows"] == 1
    assert s["totals"]["offers"] == 1 and s["totals"]["offer_rows"] == 3
    # Одна компания с одной ценой — сравнивать не с чем, сколько бы копий ни пришло.
    assert p["cmp"] is False and s["totals"]["comparable"] == 0
    assert s["dups"] == {**БЕЗ_ДУБЛЕЙ, "groups": 1, "rows": 2, "cards": 1}


@pytest.mark.parametrize("поле,иначе", [
    ("компания", "c8"), ("цена", 12.51), ("валюта", "USD"), ("qty", 5),
    ("дата", dt.date(2026, 9, 2)),
    # Пустое поле ключа — тоже значение: «количество не прочитано» и «4 шт.»
    # не одно предложение.
    ("qty", None), ("цена", None),
])
def test_отличие_в_поле_ключа_оставляет_предложение(поле, иначе):
    s = crossref.собрать([_копия(), _копия(**{поле: иначе})])
    p = позиция(s, "vk12")
    assert p["offers"] == 2 and len(p["list"]) == 2
    assert all(К["dups"] not in o for o in p["list"]), "у единичного предложения число копий"
    assert s["totals"]["offer_rows"] == s["totals"]["offers"] == 2
    assert s["dups"] == БЕЗ_ДУБЛЕЙ


def test_ни_одно_недублирующее_предложение_не_пропадает():
    """Сумма прячет потерю (CLAUDE.md, правило 0): проверяется не итог, а каждый ключ.

    Корпус с узкими наборами значений — копий много. Ожидаемое считается прямо
    по сырым строкам, мимо ключ_дубля: в каждой позиции каждый различный набор
    (компания, цена, валюта, количество, дата) обязан остаться ровно одним
    предложением, а сумма копий — равняться числу строк.
    """
    rnd = random.Random(25)
    корпус = []
    # По два значения на поле ключа, и у каждой позиции одно поле прибито: так
    # различных наборов у позиции 16, список не усекается, а копий на каждый —
    # около восьми. Поле вне ключа (срок, карточка, файл) меняется свободно.
    прибито = {"aa1": ("дата", Д), "bb2": ("валюта", "EUR"), "cc3": ("компания", "c1")}
    for _ in range(400):
        ключ = rnd.choice(sorted(прибито))
        поля = {"компания": rnd.choice(("c1", None)), "цена": rnd.choice((10.0, None)),
                "валюта": rnd.choice(("EUR", "USD")), "qty": rnd.choice((4, None)),
                "дата": rnd.choice((Д, dt.date(2026, 9, 3)))}
        поля[прибито[ключ][0]] = прибито[ключ][1]
        корпус.append(строка(
            ключ, ключ.upper(), поля.pop("компания"), **поля,
            срок=rnd.choice((None, 30, 60)), карточка=rnd.choice(("R-1", "R-2", "R-3")),
            файл=rnd.choice(("f1", "f2"))))
    ожидаемо = collections.defaultdict(collections.Counter)
    for r in корпус:
        ожидаемо[r[0]][(r[3], r[8], r[9], r[10], r[24].isoformat())] += 1
    s = crossref.собрать(корпус)
    for p in s["positions"]:
        assert p["offers"] <= crossref.ПРЕДЛОЖЕНИЙ_НА_ПОЗИЦИЮ, "корпус усёкся — проверка слепа"
        есть = collections.Counter(crossref.ключ_дубля(o) for o in p["list"])
        assert set(есть.values()) == {1}, "дубль остался в списке"
        assert set(есть) == set(ожидаемо[p["k"]]), "пропало недублирующее предложение"
        for o in p["list"]:
            assert o.get(К["dups"], 1) == ожидаемо[p["k"]][crossref.ключ_дубля(o)]
    assert s["totals"]["offer_rows"] == len(корпус)
    assert s["totals"]["offer_rows"] - s["totals"]["offers"] == s["dups"]["rows"] > 0


def test_происхождение_дублей_считается():
    """Три причины — три числа: чинить чтение полей карточки, разбор файла или ничего."""
    корпус = [
        # Строка повторена в самом файле.
        _копия(ключ="a1", карточка="R-1", файл="f1"), _копия(ключ="a1", карточка="R-1", файл="f1"),
        # Одна карточка, два файла: копия КП во втором поле.
        _копия(ключ="a2", карточка="R-1", файл="f1"), _копия(ключ="a2", карточка="R-1", файл="f2"),
        # Одно предложение на двух карточках.
        _копия(ключ="a3", карточка="R-1", файл="f1"), _копия(ключ="a3", карточка="R-2", файл="f2"),
        # Файл не известен (строка старого вида, без колонки файла).
        _копия(ключ="a4", карточка="R-1"), _копия(ключ="a4", карточка="R-1"),
    ]
    s = crossref.собрать(корпус)
    assert s["dups"] == {"groups": 4, "rows": 4, "cards": 1, "one_card": 1, "one_file": 1,
                         "no_file": 1, "differ": 0}
    assert {p["k"]: p["offers"] for p in s["positions"]} == {"a1": 1, "a2": 1, "a3": 1, "a4": 1}


def test_остаётся_самая_полная_копия_и_расхождение_видно():
    """Копия с условиями не теряется за более свежей копией без них.

    Составлять предложение из полей разных копий нельзя (пометки r относятся к
    своей строке), поэтому остаётся самая полная копия целиком. Копия, несущая
    значение, которого оставшееся не показывает, даёт пометку w.
    """
    бедная = _копия(карточка="R-1", бренды="SKF")
    полная = _копия(карточка="R-2", бренды="FAG", срок=30, базис="EXW",
                    базис_ист="строка", срок_ист="строка")
    o = позиция(crossref.собрать([бедная, полная]), "vk12")["list"][0]
    assert o[К["lead"]] == 30 and o[К["basis"]] == "EXW" and o[К["src"]] == "с?с?"
    assert o[К["rfq"]] == "R-2" and o[К["rfq_more"]] == ["R-1"]
    assert o[К["brands"]] == ["FAG", "SKF"], "бренд карточки копии потерян"
    assert К["differ"] not in o, "у бедной копии нет ничего, чего не показано"
    # Третья копия называет другой срок — показать его негде, и это видно.
    другая = _копия(карточка="R-3", срок=60, базис="EXW",
                    базис_ист="строка", срок_ист="строка")
    s = crossref.собрать([бедная, полная, другая])
    o = позиция(s, "vk12")["list"][0]
    assert o[К["dups"]] == 3 and o[К["lead"]] == 30 and o[К["differ"]] == 1
    assert o[К["rfq_more"]] == ["R-1", "R-3"]
    assert s["dups"]["differ"] == 1


def test_при_равной_полноте_остаётся_свежая():
    """Строки приходят свежими вперёд (ПРЕДЛОЖЕНИЯ_SQL), и при равной полноте
    остаётся первая — как у несхлопнутого списка «самые свежие»."""
    o = позиция(crossref.собрать([_копия(карточка="R-9"), _копия(карточка="R-1")]),
                "vk12")["list"][0]
    assert o[К["rfq"]] == "R-9" and o[К["rfq_more"]] == ["R-1"]
