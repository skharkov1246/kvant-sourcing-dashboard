    assert s["positions"][0]["e"] == [[0, 1, None, None, "2026-09-01"]]
    # Цена есть, валюты и дат нет вовсе: хвост отрезан.
    без_даты = list(строка("y", "Y-1", "556", цена=5))
    без_даты[-2:] = [None, None]
    s = crossref.собрать([tuple(без_даты)])
    assert s["positions"][0]["e"] == [[0, 1, 5.0]]


