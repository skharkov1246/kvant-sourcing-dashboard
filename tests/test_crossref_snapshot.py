def строка(ключ, написание, компания, **kw):
    """Строка предложения в том же порядке полей, что отдаёт ПРЕДЛОЖЕНИЯ_SQL.

    Файл-источник (последняя колонка запроса) — только если назван: сборка
    обязана читать и строки без него, как читала до 25.09.2026."""
    return (
        ключ, написание, kw.get("наименование", "подшипник"),
        компания, kw.get("сущность"), kw.get("сущность_имя"),
        kw.get("оем"), kw.get("бренды"),
        kw.get("цена"), kw.get("валюта"),
        kw.get("qty"), kw.get("ед"), kw.get("базис"), kw.get("срок"),
        # Коммерческие условия и четыре пометки источника. По умолчанию пусто и
        # «не проверено»: строка предложения чаще всего именно такая, и снимок
        # обязан быть маленьким на ней, а не на придуманном полном случае.
        kw.get("срок_изг"), kw.get("оплата"), kw.get("аванс"), kw.get("сумма"),
        kw.get("базис_ист"), kw.get("опл_ист"),
        kw.get("срок_ист"), kw.get("изг_ист"),
        kw.get("карточка", "RFQ-1"), kw.get("conf", "med"),
        kw.get("дата", Д), СОЗДАНО,
    ) + ((kw["файл"],) if "файл" in kw else ())


