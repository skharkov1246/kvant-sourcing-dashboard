"""Цена из КП поставщика.

Корпуса придуманы, а не взяты из базы (CLAUDE.md, правило 18). Проверяется то,
что дороже всего стоит при ошибке: подмена цены за единицу суммой строки. В КП
эти колонки стоят рядом, и перепутать их — завысить закупку в qty раз.
"""

from __future__ import annotations

import pytest

from library import quotes as q


# ── число ────────────────────────────────────────────────────────────────────
@pytest.mark.parametrize("ячейка,ждём", [
    ("1 200,50", 1200.5),          # русский разделитель дробной части
    ("1 200.50", 1200.5),
    ("1,200.50", 1200.5),          # английский разделитель тысяч
    ("1 234 567", 1234567.0),
    ("1.200", 1200.0),             # точка как разделитель тысяч
    ("12 345 ₽", 12345.0),
    ("$ 99.99", 99.99),
    ("—", None),
    ("по запросу", None),
    ("", None),
    (None, None),
])
def test_число(ячейка, ждём):
    assert q.число_из(ячейка) == ждём


# ── валюта ───────────────────────────────────────────────────────────────────
@pytest.mark.parametrize("текст,ждём", [
    ("Цена, EUR", "EUR"), ("стоимость, руб.", "RUB"), ("Price USD", "USD"),
    ("цена, ¥", "CNY"), ("сумма, ₸", "KZT"), ("кол-во", None), ("", None),
])
def test_валюта(текст, ждём):
    assert q.валюта_из(текст) == ждём


def test_валюта_файла_молчит_когда_их_две():
    assert q.валюта_файла("цена 100 EUR, НДС 20 руб") is None
    assert q.валюта_файла("итого 100 EUR за комплект") == "EUR"
    assert q.валюта_файла("никаких денег") is None


# ── срок ─────────────────────────────────────────────────────────────────────
@pytest.mark.parametrize("текст,ждём", [
    ("4-6 недель", 42),            # верхняя граница, а не обещанный минимум
    ("30 дней", 30),
    ("2 мес.", 60),
    ("10 рабочих дней", 10),
    ("склад", 0),
    ("в наличии", 0),
    ("", None),
    ("по согласованию", None),
])
def test_срок(текст, ждём):
    assert q.срок_из(текст) == ждём


# ── базис ────────────────────────────────────────────────────────────────────
def test_базис_только_целым_словом():
    assert q.базис_из("DDP Москва") == "DDP"
    assert q.базис_из("EXW склад продавца") == "EXW"
    assert q.базис_из("pacific ocean") is None      # CIF внутри слова — не базис


# ── колонки ──────────────────────────────────────────────────────────────────
def test_цена_и_сумма_не_путаются():
    ц = q.колонки_цены(["№", "Наименование", "Кол-во", "Цена за ед., EUR", "Сумма, EUR"])
    assert ц["price"] == 3
    assert ц["total"] == 4


def test_голая_цена_считается_ценой_за_единицу():
    ц = q.колонки_цены(["Наименование", "Кол-во", "Цена", "Сумма"])
    assert ц["price"] == 2 and ц["total"] == 3


def test_у_спецификации_заказчика_ценовых_колонок_нет():
    assert q.колонки_цены(["№", "Наименование", "Артикул", "Кол-во", "Ед.изм"]) == {}


# ── строка целиком ───────────────────────────────────────────────────────────
def test_цена_за_единицу_берётся_как_есть():
    шапка = ["Наименование", "Кол-во", "Цена за ед., EUR", "Сумма, EUR"]
    цк = q.колонки_цены(шапка)
    р = q.цена_строки(["Подшипник 6205", "10", "1 200,50", "12 005,00"], цк, 10.0,
                      q.валюта_заголовка(шапка, цк))
    assert р["price"] == 1200.5
    assert р["currency"] == "EUR"
    assert р["confidence"] == "med"
    assert р["note"] is None


def test_сумма_не_становится_ценой():
    """Есть только «Сумма» — цена выводится делением, и это сказано."""
    шапка = ["Наименование", "Кол-во", "Сумма, USD"]
    цк = q.колонки_цены(шапка)
    р = q.цена_строки(["Вал", "4", "4 000"], цк, 4.0, q.валюта_заголовка(шапка, цк))
    assert р["price"] == 1000.0
    assert р["confidence"] == "low"
    assert "делением" in р["note"]


def test_сумма_без_количества_строку_не_даёт():
    """Цифра без основания хуже пустоты: 4 000 могло быть и за штуку, и за всё."""
    цк = q.колонки_цены(["Наименование", "Сумма, USD"])
    assert q.цена_строки(["Вал", "4 000"], цк, None) is None
    assert q.цена_строки(["Вал", "4 000"], цк, 0) is None


def test_строка_без_цены_молчит():
    цк = q.колонки_цены(["Наименование", "Кол-во", "Цена"])
    assert q.цена_строки(["Вал", "4", "—"], цк, 4.0) is None
    assert q.цена_строки(["Вал", "4", ""], цк, 4.0) is None


def test_валюта_не_угадывается():
    цк = q.колонки_цены(["Наименование", "Кол-во", "Цена"])
    р = q.цена_строки(["Вал", "2", "500"], цк, 2.0)
    assert р["currency"] is None
    assert р["confidence"] == "low"
    assert "валюта" in р["note"]


def test_валюта_файла_подставляется_только_запасной():
    цк = q.колонки_цены(["Наименование", "Кол-во", "Цена"])
    р = q.цена_строки(["Вал", "2", "500"], цк, 2.0, валюта_файла="CNY")
    assert р["currency"] == "CNY"
    # а названная в шапке валюта файловую не слушает
    шапка = ["Наименование", "Кол-во", "Цена, EUR"]
    цк2 = q.колонки_цены(шапка)
    р2 = q.цена_строки(["Вал", "2", "500"], цк2, 2.0,
                       q.валюта_заголовка(шапка, цк2), валюта_файла="CNY")
    assert р2["currency"] == "EUR"


def test_срок_и_базис_из_своих_колонок():
    шапка = ["Наименование", "Кол-во", "Цена, USD", "Срок поставки", "Базис"]
    цк = q.колонки_цены(шапка)
    р = q.цена_строки(["Вал", "1", "10", "6 недель", "FCA Шанхай"], цк, 1.0,
                      q.валюта_заголовка(шапка, цк))
    assert р["lead_days"] == 42
    assert р["basis"] == "FCA"


def test_валюта_из_шапки_а_не_из_ячейки():
    """В ячейках КП стоят голые числа; валюта почти всегда только в шапке."""
    шапка = ["Наименование", "Кол-во", "Цена за ед., EUR"]
    цк = q.колонки_цены(шапка)
    assert q.валюта_заголовка(шапка, цк) == "EUR"
    # «Кол-во» валютой колонку не делает
    шапка2 = ["Наименование", "Кол-во", "Цена"]
    assert q.валюта_заголовка(шапка2, q.колонки_цены(шапка2)) is None


# ── разбор таблицы целиком ───────────────────────────────────────────────────
def _items(rows):
    """items_from_rows индексатора: он подтягивает сеть лениво, импорт безопасен."""
    from library import indexer
    return indexer.items_from_rows(rows)


КП = [
    ["Коммерческое предложение № 42"],
    ["№", "Наименование", "Артикул", "Кол-во", "Ед.изм", "Цена за ед., EUR", "Сумма, EUR",
     "Срок поставки"],
    ["1", "Подшипник роликовый", "NU 220 ECP", "10", "шт", "1 200,50", "12 005,00", "6 недель"],
    ["2", "Уплотнение торцевое", "M74N-50", "4", "шт", "850,00", "3 400,00", "склад"],
    ["", "ИТОГО", "", "", "", "", "15 405,00", ""],
]

СПЕЦИФИКАЦИЯ_ЗАКАЗЧИКА = [
    ["№", "Наименование", "Артикул", "Кол-во", "Ед.изм"],
    ["1", "Подшипник роликовый", "NU 220 ECP", "10", "шт"],
]


def test_кп_даёт_цену_каждой_позиции():
    поз = _items(КП)
    assert len(поз) == 2                         # строка «ИТОГО» отброшена
    ц = поз[0]["_цена"]
    assert ц["price"] == 1200.5 and ц["currency"] == "EUR"
    assert ц["lead_days"] == 42 and ц["confidence"] == "med"
    assert поз[1]["_цена"]["lead_days"] == 0     # «склад» — ноль дней, не пусто


def test_спецификация_заказчика_цены_не_получает():
    """Бюджетной цены заказчика в КП поставщика быть не должно: иначе своя же
    заявка ляжет в базу как чьё-то предложение."""
    поз = _items(СПЕЦИФИКАЦИЯ_ЗАКАЗЧИКА)
    assert поз and all(p["_цена"] is None for p in поз)


# ── вставка и схема ──────────────────────────────────────────────────────────
def test_колонки_вставки_цен_есть_в_схеме():
    """Опечатка в имени колонки роняет запись на КАЖДОЙ строке, а файл при этом
    уже помечен разобранным — потерянного не вернуть (CLAUDE.md, правило 14)."""
    import pathlib
    import re

    корень = pathlib.Path(__file__).resolve().parents[1]
    код = (корень / "library" / "indexer.py").read_text(encoding="utf-8")
    m = re.search(r"insert into lib_prices\s*\n\s*\(([^)]*)\)", код)
    assert m, "вставка в lib_prices не найдена"
    колонки = [c.strip() for c in m.group(1).replace("\n", " ").split(",") if c.strip()]

    sql = (корень / "library" / "supabase" / "schema.sql").read_text(encoding="utf-8")
    тело = re.search(r"create table if not exists lib_prices \((.*?)\n\);", sql, re.S).group(1)
    известные = {re.match(r"\s*([a-z_]+)", ln).group(1)
                 for ln in тело.splitlines() if re.match(r"\s*[a-z_]+\s", ln)}
    известные |= set(re.findall(r"alter table lib_prices add column if not exists\s+(\w+)", sql))

    неизвестные = [c for c in колонки if c not in известные]
    assert not неизвестные, f"в схеме lib_prices нет колонок: {неизвестные}"


def test_число_колонок_совпадает_с_кортежем():
    """Колонок в insert и полей в кортеже должно быть поровну: расхождение —
    сдвиг значений, цена уедет в срок поставки."""
    import ast
    import pathlib
    import re

    корень = pathlib.Path(__file__).resolve().parents[1]
    код = (корень / "library" / "indexer.py").read_text(encoding="utf-8")
    колонок = len(re.search(r"insert into lib_prices\s*\n\s*\(([^)]*)\)", код)
                  .group(1).replace("\n", " ").split(","))

    дерево = ast.parse(код)
    длины = [len(n.args[0].elts)
             for n in ast.walk(дерево)
             if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute)
             and n.func.attr == "append" and isinstance(n.func.value, ast.Name)
             and n.func.value.id == "buf_prices" and n.args
             and isinstance(n.args[0], ast.Tuple)]
    assert длины, "не нашлось наполнения buf_prices кортежем"
    assert all(d == колонок for d in длины), f"колонок {колонок}, в кортеже {длины}"
