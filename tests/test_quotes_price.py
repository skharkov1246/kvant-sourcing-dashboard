    "НДС 20 % 2 000,00 12 000,00 14 000,00",        # налоговая строка
    "Скидка 5 % 1 000,00 20 000,00 19 000,00",
    "1 2 2",                                        # без текста это не позиция
    "Подшипник 6205 цена 1 200 EUR",                # одно число: цена или вес?
