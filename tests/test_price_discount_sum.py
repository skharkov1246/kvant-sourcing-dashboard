"""Колонка скидки — не сумма строки; английская и каталожная прайсовая цена.

ЗАЧЕМ. Две находки перебора выдуманных шапок 27.09.2026 (словарь v2,
quotes.СЛОВАРЬ_V2):

1. «Сумма скидки», «Discount amount», «Итого скидка» v2 брал СУММОЙ СТРОКИ —
   слово суммы в них есть. При колонке цены тройка «кол-во × цена = сумма» не
   сходилась, и строка теряла количество; без колонки цены цена выходила
   «скидка ÷ количество». Простое исключение колонки скидки из сумм снимало
   количество у 5 092 строк перебора части C: скидка нулевая (прежде давала
   пустую сумму и количество оставалось), а следующей суммой становилась «Сумма
   с НДС» при цене без оговорки — тройка не сходится по построению. Поэтому
   сумма, ставшая суммой строки ВМЕСТО колонки скидки, при колонке цены
   берётся, только если сходится с ценой по файлу (правило 13); иначе суммы у
   файла нет, и количество остаётся.
2. «List price | Discount | Net price» v2 читал как «List price»: прайсовой
   считалась только шапка со словами «прайс» и «price list». По смыслу это тот
   же случай, что «Цена по прайсу | Скидка | Цена со скидкой» (#479): ценой
   предложения должна быть «Net price». «List price», «Catalogue price», «Цена
   по каталогу», «Цена по прейскуранту», «Listenpreis» — листовые: чужие, только
   если в шапке есть цена предложения из закрытого списка («Net price», «Your
   price», «Discounted price», «Special price», «Offer price», «Цена со
   скидкой»). Правило #479 целиком (чужая при ЛЮБОЙ другой цене, при сумме —
   только сошедшаяся) перебор отверг: другая «цена» бывает суммой строки под
   словом цены, а сумма с НДС не сходится с ценой без него.

Корпуса придуманы (CLAUDE.md, правило 18).
"""
from __future__ import annotations

import pytest

from library import indexer
from library import quotes as q

# Наименование, количество, цена предложения за единицу (со скидкой, без НДС).
ПОЗИЦИИ = [("Насос ЦНС 38-176 с рамой", 2, 150000.0), ("Задвижка 30с41нж Ду100", 4, 25000.0),
           ("Подшипник 6208-2RS", 10, 350.0), ("Уплотнение торцевое", 3, 12000.0)]
# Прайсовая цена при скидке 20 %: цена предложения — 0,8 прайсовой.
ПРАЙС = 1 / 0.8


def _деньги(x: float) -> str:
    return f"{x:,.2f}".replace(",", " ").replace(".", ",")


def _таблица(шапка: list[str], ячейки) -> list[list[str]]:
    """ячейки(кол, цена) → ячейки денежных колонок строки (строки или числа)."""
    return [["Наименование", "Кол-во"] + шапка] + [
        [имя, str(кол)] + [x if isinstance(x, str) else _деньги(x) for x in ячейки(кол, цена)]
        for имя, кол, цена in ПОЗИЦИИ]


def _v2(шапка, ячейки) -> list[dict]:
    items = indexer.items_from_rows(_таблица(шапка, ячейки), словарь_v2=True, без_шапки=True)
    assert len(items) == len(ПОЗИЦИИ)
    return items


def _note(it) -> str:
    return it["_цена"]["note"] or ""


def _скидка(к, ц, доля=0.25):
    """Сумма скидки строки: прайсовая на четверть выше цены предложения."""
    return к * ц * доля


# ── 1. колонка скидки суммой строки не бывает ────────────────────────────────
ЦЕНА_СКИДКА_СУММА = {
    "русская": ["Цена, руб.", "Сумма скидки, руб.", "Сумма, руб."],
    "английская": ["Net price", "Discount amount", "Amount"],
    "итого скидка": ["Цена", "Итого скидка", "Итого"],
    "total discount": ["Unit price", "Total discount", "Total"],
    "discount total": ["Unit price", "Discount total", "Total"],
    "скидка первой": ["Цена", "Скидка, сумма", "Сумма"],
    "discount, amount": ["Unit price", "Discount, amount", "Amount"],
}


@pytest.mark.parametrize("вариант", list(ЦЕНА_СКИДКА_СУММА))
def test_сумма_скидки_не_сумма_строки(вариант):
    """Прежде суммой шла колонка скидки: тройка не сходилась, количество
    снималось. Теперь сумма строки — настоящая сумма, количество на месте."""
    шапка = ЦЕНА_СКИДКА_СУММА[вариант]
    полная = ["Наименование", "Кол-во"] + шапка
    assert q.скидка_была_суммой(полная) == 3
    assert q.колонки_цены(полная, v2=True)["total"] == 4
    for it, (_, кол, цена) in zip(_v2(шапка, lambda к, ц: [ц, _скидка(к, ц), ц * к]), ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert it["_цена"]["total"] == цена * кол
        assert it["qty"] == кол
        assert q.КОЛ_НЕ_СОШЛОСЬ not in _note(it)


@pytest.mark.parametrize("шапка", [["Сумма скидки", "Сумма"], ["Discount amount", "Amount"],
                                   ["Итого скидка", "Итого"]])
def test_без_цены_цена_из_суммы_а_не_из_скидки(шапка):
    """Колонки цены нет: цена — сумма ÷ количество, а не скидка ÷ количество."""
    for it, (_, кол, цена) in zip(_v2(шапка, lambda к, ц: [_скидка(к, ц), ц * к]), ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert q.ОГОВОРКА_ИЗ_СУММЫ in _note(it)
        assert it["qty"] == кол


@pytest.mark.parametrize("шапка", [["Discount amount"], ["Сумма скидки, руб."]])
def test_одна_скидка_цены_не_даёт(шапка):
    """Прежде — «цена» скидка ÷ количество. Суммы строки нет — цены нет."""
    for it in _v2(шапка, lambda к, ц: [_скидка(к, ц)]):
        assert it["_цена"] is None


# ── защита: новая сумма при цене — только сошедшаяся по файлу ────────────────
@pytest.mark.parametrize("доля", [0.25, 0.0])
def test_сумма_другой_природы_ндс_вместо_скидки_не_берётся(доля):
    """5 092 строки перебора: скидка нулевая или нет, а следующая сумма — с НДС
    при цене без оговорки. Взятая суммой, она сняла бы количество (при нулевой
    скидке прежде оно оставалось). Суммы у файла нет — как при нулевой скидке."""
    шапка = ["Discount price", "Сумма скидки", "Сумма с НДС"]
    for it, (_, кол, цена) in zip(_v2(шапка, lambda к, ц: [ц, _скидка(к, ц, доля),
                                                          ц * к * 1.2]), ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert it["_цена"]["total"] is None
        assert it["qty"] == кол


def test_новая_сумма_сверяется_по_файлу_целиком():
    """Правило 13: одна несошедшаяся строка — суммы нет ни у одной, и количество
    не снимается ни у одной."""
    шапка = ["Цена, руб.", "Сумма скидки", "Сумма, руб."]
    rows = _таблица(шапка, lambda к, ц: [ц, _скидка(к, ц), ц * к])
    rows[-1][-1] = _деньги(12000.0 * 3 * 1.2)   # последняя строка — сумма с НДС
    items = indexer.items_from_rows(rows, словарь_v2=True, без_шапки=False)
    assert all(it["_цена"]["total"] is None for it in items)
    assert [it["qty"] for it in items] == [кол for _, кол, _ in ПОЗИЦИИ]


