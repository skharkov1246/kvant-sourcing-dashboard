def test_без_колонки_количества_новая_сумма_берётся():
    """Сверять нечем, и количество не снимается: сумма — настоящая сумма."""
    rows = [["Наименование", "Артикул", "Ед. изм.", "Цена, руб.", "Сумма скидки",
             "Сумма, руб."]] + [
        [имя, f"ВЫДУМ-{i}", "шт", _деньги(ц), _деньги(_скидка(к, ц)), _деньги(ц * к)]
        for i, (имя, к, ц) in enumerate(ПОЗИЦИИ)]
    items = indexer.items_from_rows(rows, словарь_v2=True, без_шапки=True)
    assert len(items) == len(ПОЗИЦИИ)
    assert [it["_цена"]["price"] for it in items] == [ц for _, _, ц in ПОЗИЦИИ]
    assert [it["_цена"]["total"] for it in items] == [ц * к for _, к, ц in ПОЗИЦИИ]


