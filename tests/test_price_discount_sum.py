# ── защита: сумма, бывшая парой листовой, при цене предложения — со сверкой ──
def test_сумма_по_прайсу_не_пара_цене_предложения():
    """Перебор части D: «List price | Net price | Total list price» — прежде цена
    листовая и сумма по прайсу сходились. Теперь цена — Net price, и сумма по
    прайсу с ней не сходится: суммы нет, количество на месте."""
    шапка = ["List price", "Net price", "Total list price"]
    for it, (_, кол, цена) in zip(_v2(шапка, lambda к, ц: [ц * ПРАЙС, ц, ц * ПРАЙС * к]),
                                  ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert it["_цена"]["total"] is None
        assert it["qty"] == кол


def test_из_двух_сумм_берётся_сошедшаяся():
    шапка = ["List price", "Net price", "Total list price", "Amount"]
    for it, (_, кол, цена) in zip(_v2(шапка, lambda к, ц: [ц * ПРАЙС, ц, ц * ПРАЙС * к,
                                                          ц * к]), ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert it["_цена"]["total"] == цена * кол
        assert it["qty"] == кол


def test_сумма_с_ндс_пара_листовой_с_ндс_не_снимает_количество():
    """«List price incl. VAT | Discounted price | Amount incl. VAT» при нулевой
    скидке: прежде цена с НДС и сумма с НДС сходились. Цена теперь без НДС —
    сумма с НДС не пара ей, и количество не снимается."""
    шапка = ["List price incl. VAT", "Discounted price", "Amount incl. VAT"]
    for it, (_, кол, цена) in zip(_v2(шапка, lambda к, ц: [ц * 1.2, ц, ц * к * 1.2]),
                                  ПОЗИЦИИ):
        assert it["_цена"]["price"] == цена
        assert it["_цена"]["total"] is None
        assert it["qty"] == кол


def test_прайсовая_чужая_при_любой_цене_листовая_только_при_цене_предложения():
    """Правила различаются: «Price list price» (#479) отдаёт место любой другой
    цене, «List price» — только цене предложения."""
    прайс = ["Наименование", "Кол-во", "Price list price", "Price"]
    лист = ["Наименование", "Кол-во", "List price", "Price"]
    assert q.колонки_цены(прайс, v2=True)["price"] == 3
    assert q.колонки_цены(лист, v2=True)["price"] == 2
