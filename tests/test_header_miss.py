"""Почему шапка таблицы не узнана — разбор причин, годный для починки.

Замер 23.09.2026: у 689 файлов предложений таблица есть, а шапки нет, и это
39 499 позиций без колонок. Одна пометка «шапки нет» не говорит, ЧТО чинить, —
за ней стоят четыре разные правки. Здесь проверяется, что причины различаются.

Корпуса придуманы, а не сняты с базы (CLAUDE.md, правило 18).
"""
from __future__ import annotations

from library import indexer

ШАПКА = ["№", "Наименование", "Кол-во", "Цена"]


def test_шапка_ниже_сорока_строк_названа_отдельно():
    """Длинная преамбула — правка «смотреть глубже», а не «добавить слово»."""
    rows = [["Приложение № 1 к договору", ""] for _ in range(45)] + [ШАПКА,
            ["1", "Насос ЦНС-38", "2", "1000"]]
    assert indexer.header_map(rows)[0] == -1, "шапка глубже сорока строк не ищется"
    причина = indexer.почему_нет_шапки(rows)
    assert "глубже" in причина and "46" in причина, причина


def test_наименование_узнали_а_второй_колонки_нет():
    """Правка — ослабить требование двух колонок, а не расширять словарь."""
    rows = [["Наименование оборудования"], ["Насос ЦНС-38"], ["Задвижка 30с41нж"]]
    rows = [r + ["", ""] for r in rows]           # не однослобцовая таблица
    assert indexer.header_map(rows)[0] == -1
    assert indexer.почему_нет_шапки(rows) == "наименование узнали, второй колонки — нет"


def test_колонки_узнали_а_наименования_среди_них_нет():
    """Правка — добавить слово для наименования, а не трогать остальное."""
    # Колонки цены в COLS нет вовсе — её ищет library/quotes.py отдельно, поэтому
    # в корпусе стоят артикул и количество: две узнаваемые колонки без имени.
    rows = [["Артикул", "Кол-во"], ["АБВ-1", "2"]]
    assert indexer.header_map(rows)[0] == -1
    assert indexer.почему_нет_шапки(rows) == "колонки узнали, а наименования среди них нет"
    # Одна узнанная колонка — это НЕ «ни одного известного слова»: правки разные.
    одна = [["№", "Кол-во"], ["1", "2"]]
    assert indexer.почему_нет_шапки(одна) == "узнали одну колонку, и та не наименование"


def test_один_столбец_и_пустая_таблица_различаются():
    """Читатель отдал не таблицу — правка в читателе, а не в правиле шапки."""
    assert indexer.почему_нет_шапки([]) == "читатель не дал строк"
    assert "один столбец" in indexer.почему_нет_шапки([["Насос ЦНС-38"], ["Задвижка"]])


def test_ни_одного_известного_слова():
    rows = [["Ромашка", "Василёк"], ["Одуванчик", "Клевер"]]
    assert indexer.почему_нет_шапки(rows) == "ни одного известного слова колонки"


def test_разбор_причин_идёт_тем_же_правилом_что_и_разбор():
    """Разведка, которая пишет СВОЙ перебор колонок, меряет не то, что делает
    разборщик: так и вышло 23.09.2026. Обе стороны обязаны звать одну функцию."""
    assert indexer.колонки_строки(ШАПКА).get("item_name") == 1
    hi, cols = indexer.header_map([ШАПКА, ["1", "Насос", "2", "10"]])
    assert hi == 0 and cols == indexer.колонки_строки(ШАПКА)
    # Узнанная шапка не может дать причину «шапки нет» — иначе они разошлись.
    assert indexer.почему_нет_шапки([ШАПКА]) == "шапка узнаётся — расходится с пометкой"


def test_причина_пишется_и_тогда_когда_таблицу_отвергли(monkeypatch):
    """PDF с таблицей без шапки уходит в ТЕКСТОВЫЙ путь, и строк таблицы там уже нет.

    Воронка 23.09.2026: 3 474 файла стоят в клетке «текст, шапка НЕ найдена» —
    334 535 позиций при 6 578 строках цены. Это и есть отвергнутые таблицы. Если
    причину писать только в ветке `if rows`, самый крупный пласт останется без
    разбора причин: до неё эти файлы не доходят.
    """
    # Таблица есть, но во всей ней узнаётся только наименование — шапки нет.
    таблица = [["Наименование оборудования", ""], ["Насос ЦНС-38", ""]]
    monkeypatch.setattr(indexer, "download", lambda fo: b"%PDF-1.4 " + b"x" * 300)
    monkeypatch.setattr(indexer, "sniff", lambda b: "pdf")
    monkeypatch.setattr(indexer, "rows_from_pdf", lambda b: таблица)
    monkeypatch.setattr(indexer, "text_from_pdf", lambda b: "Насос ЦНС-38 две штуки")
    rec, _ = indexer.handle({"fo": {"id": "1"}, "deal": "1", "origin": "поле запроса",
                             "field": "UF_TEST", "field_title": None})
    assert rec["parse_path"] == "текст", "проверяем именно отвергнутую таблицу"
    assert rec["header_miss"] == "наименование узнали, второй колонки — нет", rec["header_miss"]


def test_таблица_без_строк_причину_не_выдумывает(monkeypatch):
    """Читатель не дал таблицы вовсе — это не «шапки нет», и путать их нельзя."""
    monkeypatch.setattr(indexer, "download", lambda fo: b"%PDF-1.4 " + b"x" * 300)
    monkeypatch.setattr(indexer, "sniff", lambda b: "pdf")
    monkeypatch.setattr(indexer, "rows_from_pdf", lambda b: [])
    monkeypatch.setattr(indexer, "text_from_pdf", lambda b: "Насос ЦНС-38 две штуки")
    rec, _ = indexer.handle({"fo": {"id": "2"}, "deal": "1", "origin": "поле запроса",
                             "field": "UF_TEST", "field_title": None})
    assert rec["header_miss"] is None


def test_слова_кандидаты_берутся_из_строки_шапки_а_не_из_всего_файла():
    """47 файлов из 53 спотыкаются на наименовании — нужны слова ИЗ ТОЙ строки.

    Общий частотный список слов документа ответа не даёт: в нём утонут слова
    из тела таблицы. Берём строку, где количество или цена уже узнаны, и смотрим
    её неузнанные ячейки — там и стоит пропущенное название колонки.
    """
    # «Изделие» и «Примечание» правилу неизвестны, «Кол-во» — известно.
    rows = [["Спецификация к запросу 17"],
            ["№", "Изделие поставки", "Кол-во", "Примечание"],
            ["1", "Насос ЦНС-38", "2", "самотёком"]]
    assert indexer.header_map(rows)[0] == -1, "наименование тут не узнаётся"
    слова = indexer.слова_шапки_без_имени(rows)
    assert "изделие" in слова and "примечание" in слова, слова
    # Из ТЕЛА таблицы слова не берутся: иначе список заполнит номенклатура.
    assert "самотёком" not in слова and "спецификация" not in слова, слова
    # Узнанная колонка в список не идёт — она и так в COLS.
    assert not any(w.startswith("кол") for w in слова), слова


def test_короткие_слова_и_цифры_в_список_не_попадают():
    """Правило 17: журнал публичный, поэтому только буквы и от шести знаков."""
    rows = [["№", "Тип", "Кол-во", "Оснащение 12-34"], ["1", "A", "2", "X"]]
    слова = indexer.слова_шапки_без_имени(rows)
    assert слова == {"оснащение"}, слова


def test_когда_наименование_узнано_кандидатов_нет():
    """Иначе список пополнялся бы словами с файлов, где чинить нечего.

    В корпусе рядом с узнанным «Наименование» стоит длинное неизвестное слово:
    без этого проверка проходит и тогда, когда отбор по наименованию снят, —
    короткие «№» и «Цена» отсеются порогом длины сами.
    """
    шапка = ["№", "Наименование", "Кол-во", "Примечание"]
    assert indexer.header_map([шапка, ["1", "Насос", "2", "—"]])[0] == 0
    assert indexer.слова_шапки_без_имени([шапка, ["1", "Насос", "2", "—"]]) == set()


def test_сетка_различает_ослабления_и_ничего_не_меняет():
    """Ослабление порога меряется таблицей, а не одним прогоном (правило 4).

    Каждый корпус берётся ровно одним ослаблением: иначе сетка говорит «помогут
    все» и выбирать по ней нельзя.
    """
    # Наименование есть, второй колонки нет, но рядом стоит колонка цены.
    с_ценой = [["Description", "Price, EUR"], ["Pump CNS-38", "1000"]]
    assert indexer.header_map(с_ценой)[0] == -1
    assert "цена считается колонкой" in indexer.сетка_шапки(с_ценой)

    # Наименование есть и больше нет ничего — берёт только «одного хватает».
    одна = [["Наименование", "Примечание"], ["Насос ЦНС-38", "—"]]
    сетка = indexer.сетка_шапки(одна)
    assert "одного наименования хватает" in сетка
    assert "цена считается колонкой" not in сетка, сетка

    # Английская шапка: наименование неизвестно правилу, количество известно.
    англ = [["Equipment", "Qty"], ["Pump CNS-38", "2"]]
    assert indexer.header_map(англ)[0] == -1
    assert "слова замера в словаре" in indexer.сетка_шапки(англ)

    # Глубокая шапка — свой вариант, и он не приписывается прочим.
    глубоко = [["преамбула", ""] for _ in range(50)] + [ШАПКА, ["1", "Насос", "2", "10"]]
    сетка = indexer.сетка_шапки(глубоко)
    assert any("строк вместо" in v for v in сетка), сетка
    assert "одного наименования хватает" not in сетка, сетка


def test_сетка_не_трогает_сам_разбор():
    """Сетка — замер. Если она начнёт менять header_map, правило поедет молча."""
    англ = [["Equipment", "Qty"], ["Pump CNS-38", "2"]]
    до = indexer.header_map(англ)
    indexer.сетка_шапки(англ)
    assert indexer.header_map(англ) == до == (-1, {})
    # Узнанная шапка остаётся узнанной и после расширенного перебора.
    assert indexer.колонки_строки(["Equipment", "Qty"]).get("item_name") is None
    assert indexer.колонки_строки_шире(["Equipment", "Qty"]).get("item_name") == 0
