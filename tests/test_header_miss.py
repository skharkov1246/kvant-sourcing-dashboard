"""Почему шапка таблицы не узнана — разбор причин, годный для починки.

Замер 23.09.2026: у 689 файлов предложений таблица есть, а шапки нет, и это
39 499 позиций без колонок. Одна пометка «шапки нет» не говорит, ЧТО чинить, —
за ней стоят четыре разные правки. Здесь проверяется, что причины различаются.

Корпуса придуманы, а не сняты с базы (CLAUDE.md, правило 18).
"""
from __future__ import annotations

from library import indexer

ШАПКА = ["№", "Наименование", "Кол-во", "Цена"]


def test_шапка_ниже_сорока_строк_названа_отдельно():
    """Длинная преамбула — правка «смотреть глубже», а не «добавить слово»."""
    rows = [["Приложение № 1 к договору", ""] for _ in range(45)] + [ШАПКА,
            ["1", "Насос ЦНС-38", "2", "1000"]]
    assert indexer.header_map(rows)[0] == -1, "шапка глубже сорока строк не ищется"
    причина = indexer.почему_нет_шапки(rows)
    assert "глубже" in причина and "46" in причина, причина


def test_наименование_узнали_а_второй_колонки_нет():
    """Правка — ослабить требование двух колонок, а не расширять словарь."""
    rows = [["Наименование оборудования"], ["Насос ЦНС-38"], ["Задвижка 30с41нж"]]
    rows = [r + ["", ""] for r in rows]           # не однослобцовая таблица
    assert indexer.header_map(rows)[0] == -1
    assert indexer.почему_нет_шапки(rows) == "наименование узнали, второй колонки — нет"


def test_колонки_узнали_а_наименования_среди_них_нет():
    """Правка — добавить слово для наименования, а не трогать остальное."""
    # Колонки цены в COLS нет вовсе — её ищет library/quotes.py отдельно, поэтому
    # в корпусе стоят артикул и количество: две узнаваемые колонки без имени.
    rows = [["Артикул", "Кол-во"], ["АБВ-1", "2"]]
    assert indexer.header_map(rows)[0] == -1
    assert indexer.почему_нет_шапки(rows) == "колонки узнали, а наименования среди них нет"
    # Одна узнанная колонка — это НЕ «ни одного известного слова»: правки разные.
    одна = [["№", "Кол-во"], ["1", "2"]]
    assert indexer.почему_нет_шапки(одна) == "узнали одну колонку, и та не наименование"


def test_один_столбец_и_пустая_таблица_различаются():
    """Читатель отдал не таблицу — правка в читателе, а не в правиле шапки."""
    assert indexer.почему_нет_шапки([]) == "читатель не дал строк"
    assert "один столбец" in indexer.почему_нет_шапки([["Насос ЦНС-38"], ["Задвижка"]])


def test_ни_одного_известного_слова():
    rows = [["Ромашка", "Василёк"], ["Одуванчик", "Клевер"]]
    assert indexer.почему_нет_шапки(rows) == "ни одного известного слова колонки"


def test_разбор_причин_идёт_тем_же_правилом_что_и_разбор():
    """Разведка, которая пишет СВОЙ перебор колонок, меряет не то, что делает
    разборщик: так и вышло 23.09.2026. Обе стороны обязаны звать одну функцию."""
    assert indexer.колонки_строки(ШАПКА).get("item_name") == 1
    hi, cols = indexer.header_map([ШАПКА, ["1", "Насос", "2", "10"]])
    assert hi == 0 and cols == indexer.колонки_строки(ШАПКА)
    # Узнанная шапка не может дать причину «шапки нет» — иначе они разошлись.
    assert indexer.почему_нет_шапки([ШАПКА]) == "шапка узнаётся — расходится с пометкой"
