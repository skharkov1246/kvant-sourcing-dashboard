"""Таможенные декларации: что из них можно брать, а что нельзя.

Источник сам помечает надёжность сопоставления: strong — нашлось по партномеру,
weak — только по коду ТН ВЭД и описанию. Строгих 79 из 42 311, и если стереть
эту границу, товарная группа «части горного оборудования» станет ценой
конкретной коронки. Тесты держат ровно эту границу и ещё одну: поле «бренд»
в декларациях заполняют словом «ОТСУТСТВУЕТ» — 12 130 строк, и это не компания.

Строки придуманы здесь и не взяты из базы: репозиторий публичный (правило 18).
"""
from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(name: str):
    spec = importlib.util.spec_from_file_location(
        f"kvant_{name}", ROOT / "library" / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


cu = load("load_customs")
eq = load("equipment")


def строка(**kw):
    d = {"tag": "weak", "date": "2024-05-06", "hs10": "8431431000",
         "importer": "ООО «Пример»", "inn": "7700000000",
         "exporter": "EXAMPLE MACHINERY CO.LTD", "brand": "EXAMPLEBRAND",
         "origin": "CN", "dispatch": "CN", "cur": "USD", "incoterms": "CFR",
         "desc": "ЧАСТИ БУРОВОЙ УСТАНОВКИ, КОРПУС", "net_kg": "10.0",
         "usd_kg": "12.5", "val": "125.0", "_файл": "пример.json", "_группа": "8431"}
    d.update(kw)
    return d


def test_слабое_совпадение_не_даёт_ни_номера_ни_позиции_каталога():
    """Слабое совпадение — это «в этой товарной группе везли что-то похожее».
    Партномер из него брать нельзя: он относится к поисковому запросу, а не к
    этой декларации."""
    декл, _, цены = cu.разобрать([строка(tag="weak", pn="COP1838")])
    d = next(iter(декл.values()))
    assert d["match"] == "weak"
    assert d["part_number"] is None, "номер просочился из слабого совпадения"
    assert not цены, "цена детали не может браться из слабого совпадения"
    assert not cu.позиции(декл), "позиция каталога не может браться из слабого совпадения"


def test_строгое_совпадение_даёт_позицию_цену_за_килограмм_и_условия():
    декл, _, цены = cu.разобрать([строка(tag="strong", pn="ПРИМЕР-1838")])
    d = next(iter(декл.values()))
    assert d["part_number"] == "ПРИМЕР-1838"
    assert len(цены) == 1 and цены[0]["qty_unit"] == "кг"
    assert "килограмм" in цены[0]["note"], "цена за кг обязана быть названа ценой за кг"
    assert цены[0]["basis"] == "CFR", "условия поставки теряться не должны"
    поз = cu.позиции(декл)
    assert len(поз) == 1
    z = next(iter(поз.values()))
    assert z["catalog_no"] == "ПРИМЕР-1838" and z["oem"] == "EXAMPLEBRAND"


def test_пометка_незнания_в_поле_бренд_компанией_не_становится():
    """«ОТСУТСТВУЕТ» — самый частый «бренд» во всей выборке. Карточка компании с
    таким именем в справочнике уже появлялась, и стоила она чистки вручную."""
    for пометка in ("ОТСУТСТВУЕТ", "НЕ ОБОЗНАЧЕН", "не обозначена", "нет данных"):
        assert not eq.oem_is_real(пометка), пометка
    _, компании, _ = cu.разобрать([строка(brand="ОТСУТСТВУЕТ")])
    виды = {z["kind"] for z in компании.values()}
    assert "изготовитель" not in виды, "пометка незнания попала в справочник компаний"
    assert "экспортёр" in виды, "настоящий экспортёр обязан остаться"


def test_одна_и_та_же_декларация_дважды_даёт_одну_запись():
    """Идентификатор — хеш содержимого, а не номер строки: выгрузки за разные
    периоды перекрываются, и повторный прогон обязан обновлять, а не двоить."""
    декл, _, _ = cu.разобрать([строка(), строка(), строка(val="999.0")])
    assert len(декл) == 2


def test_ориентир_по_группе_не_считается_на_горстке_строк():
    """Медиана по десяти строкам — шум, и выдавать её за ориентир нельзя."""
    мало, _, _ = cu.разобрать([строка(desc=f"ПОЗИЦИЯ {i}") for i in range(10)])
    assert cu.ориентир(мало) == []
    много, _, _ = cu.разобрать([строка(desc=f"ПОЗИЦИЯ {i}", usd_kg=str(i + 1))
                                for i in range(40)])
    b = cu.ориентир(много)
    assert len(b) == 1 and b[0]["hs4"] == "8431" and b[0]["rows"] == 40
    assert b[0]["p25"] < b[0]["median"] < b[0]["p75"], "квартили перепутаны"
    assert b[0]["title"], "у товарной группы обязано быть название, иначе код ни о чём"


def test_импортёр_остаётся_в_декларациях_но_не_в_исполнителях():
    """Импортёр — покупатель. Смешать того, кто делает, с тем, кто покупает,
    значит сломать единственный вопрос, на который справочник отвечает."""
    декл, компании, _ = cu.разобрать([строка(importer="ООО «Покупатель»")])
    d = next(iter(декл.values()))
    assert d["importer"] == "ООО «Покупатель»" and d["importer_inn"]
    assert not any("покупатель" in z["name"].lower() for z in компании.values())
