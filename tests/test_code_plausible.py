def test_тройка_не_сошлась_количество_снято_и_помечено():
    п = _позиции([ШАПКА,
                  ["1", "Подшипник 6205-2RS", "6205-2RS", "8", "100", "900"],
                  ["2", "Подшипник 6206-2RS", "6206-2RS", "8", "100", "800"],
                  ["3", "Подшипник 6207-2RS", "6207-2RS", "3 163 518 182,316", "316", "316"]])
    плохо, хорошо, склейка = п
    assert плохо["qty"] is None
    assert quotes.КОЛ_НЕ_СОШЛОСЬ in плохо["_цена"]["note"]
    assert плохо["_цена"]["price"] == 100.0          # цена своей колонки цела
    assert хорошо["qty"] == 8.0 and quotes.КОЛ_НЕ_СОШЛОСЬ not in (хорошо["_цена"]["note"] or "")
    assert склейка["qty"] is None
    assert quotes.КОЛ_НЕ_ЧИТАЕТСЯ in склейка["_цена"]["note"]


def test_цена_не_вынимается_из_стандарта_с_размером():
    """Стандарт с размером — код, но ячейка цены с ним числа не несёт:
    число_из вынул бы из «DIN 471 25» цену 47125."""
    цк = quotes.колонки_цены(ШАПКА)
    assert quotes.цена_строки(["1", "Кольцо", "", "8", "DIN 471 25", ""], цк, 8.0) is None
    assert quotes.цена_строки(["1", "Кольцо", "", "8", "", "ГОСТ 9833-73 020-025-30"], цк, 8.0) is None


def test_ячейка_артикула_со_стандартом_и_размером_остаётся_кодом():
    п = _позиции([ШАПКА,
                  ["1", "Кольцо стопорное", "DIN 471 25", "10", "3", "30"],
                  ["2", "Кольцо уплотнительное", "ГОСТ 9833-73 020-025-30", "4", "5", "20"],
                  ["3", "Болт М12х60 KV-4417-B", "DIN 933", "2", "1", "2"]])
    # Голый стандарт в ячейке артикула уступает коду из наименования.
    assert [x["part_number"] for x in п] == ["DIN 471 25", "ГОСТ 9833-73 020-025-30", "KV-4417-B"]


def test_цена_не_вынимается_из_марки():
    """Из ячейки «SS316» число_из вынул бы цену 316 — ячейка марки числа не несёт."""
    цк = quotes.колонки_цены(ШАПКА)
    assert quotes.цена_строки(["1", "Труба", "", "8", "SS316", "SS316"], цк, 8.0) is None
    ц = quotes.цена_строки(["1", "Труба", "", "8", "3 200,00", "25 600,00"], цк, 8.0)
    assert ц["price"] == 3200.0 and ц["total"] == 25600.0
