def test_ключ_совпадает_с_lib_pn_key_загрузчиков():
    """Правило судит ключ; ключ обязан считаться как в базе (lib_pn_key)."""
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        "kvant_load_crossrefs_t", ROOT / "library" / "load_crossrefs.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    for t in ["SS 316L", "ШАЙБА-12Ё", "(19mm)", "12Х18Н10Т", "  "]:
        assert d.ключ_кода(t) == mod.part_key(t), t


def test_выражение_вписано_в_миграцию_буква_в_букву():
    """Двойник в SQL — то же выражение: гейт видит расхождение и без базы."""
    текст = (ROOT / "library" / "supabase" / "schema.sql").read_text(encoding="utf-8")
    assert f"select {d.sql_правдоподобен('t')}\n  $$;" in текст
    assert f"lib_pn_key(t) !~ '{d.ВЫРАЖЕНИЕ_НЕ_КОДА}'" in текст
    assert f"t ~ '{d.НАПИСАНИЕ_С_РАЗМЕРОМ}'" in текст
    # Функция по одному ключу (карточка кода и поиск портала) — те же выражения.
    функция = текст[текст.index("create or replace function lib_pn_std_sized"):]
    функция = функция[:функция.index("end $fn$;")]
    assert f"к.x ~ '{d.ВЫРАЖЕНИЕ_СТАНДАРТА}'" in функция
    assert функция.count(f"part_number ~ '{d.НАПИСАНИЕ_С_РАЗМЕРОМ}'") == 2


def test_невидимых_знаков_в_выражении_нет():
    """Неразрывный пробел пишется в выражении видимой записью, а не знаком:
    слой передачи команды однажды развернул её в невидимый символ (CLAUDE.md)."""
    невидимые = (chr(0xa0), chr(0x2009), chr(0x202f))
    текст = (ROOT / "library" / "supabase" / "schema.sql").read_text(encoding="utf-8")
    for знак in невидимые:
        assert знак not in d.НАПИСАНИЕ_С_РАЗМЕРОМ and знак not in текст
    assert d.стандарт_с_размером("DIN 471" + chr(0xa0) + "25")


@pytest.mark.parametrize("написание", ["ГОСТ 9833-73 020-025-30", "DIN 471 25", "GB 276 6205"])
def test_стандарт_с_размером_по_ключу_стандарт(написание):
    """Ключ пробелов не несёт: по одному ключу это стандарт. Код — по написанию."""
    assert d.класс_ключа(написание) == "стандарт"
