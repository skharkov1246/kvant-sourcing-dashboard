def _позиции(rows):
    from library import indexer
    return indexer.items_from_rows(rows)


ШАПКА = ["№", "Наименование", "Артикул", "Кол-во", "Цена", "Сумма"]


def test_ячейка_артикула_с_маркой_уступает_коду_из_строки():
    п = _позиции([ШАПКА,
                  ["1", "Клапан 12Х18Н10Т DN50 KV-4417-B", "12Х18Н10Т", "2", "10", "20"],
                  ["2", "(19mm) SS316 8 3200.0 25600.0", "SS316", "8", "3200", "25600"],
                  ["3", "Подшипник", "NU 316 ECP", "1", "5", "5"]])
    assert [x["part_number"] for x in п] == ["KV-4417-B", "", "NU 316 ECP"]


def test_колонка_кода_тн_вэд_не_артикул():
    """«Код ТН ВЭД» стоит левее артикула — прежде он и становился номером."""
    п = _позиции([["№", "Наименование", "Код ТН ВЭД", "Артикул", "Кол-во"],
                  ["1", "Подшипник шариковый", "8482100000", "6205-2RS", "4"],
                  ["2", "Подшипник роликовый", "8482500000", "NU 316 ECP", "2"]])
    assert [x["part_number"] for x in п] == ["6205-2RS", "NU 316 ECP"]
    # «Код товара» — законный артикул и остаётся им.
    п = _позиции([["№", "Наименование", "Код товара", "Кол-во"],
                  ["1", "Подшипник шариковый", "6205-2RS", "4"]])
    assert п[0]["part_number"] == "6205-2RS"


