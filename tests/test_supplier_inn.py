"""Разряд налогового номера по его форме. Корпус выдуман (CLAUDE.md, правило 18).

Ни одного настоящего ИНН здесь нет и быть не может: ИНН контрагентов —
чувствительные данные, их помечает scripts/build_catalog.py и исключает из
индекса scripts/build_index.py, а репозиторий публичный.
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location(
    "supplier_inn_coverage", ROOT / "scripts" / "supplier_inn_coverage.py")
cov = importlib.util.module_from_spec(SPEC)
sys.modules["supplier_inn_coverage"] = cov
SPEC.loader.exec_module(cov)


def test_российский_инн_опознаётся_по_длине():
    assert cov.вид_инн("7707083893") == "ИНН юрлица (10 цифр)"
    assert cov.вид_инн("770708389312") == "ИНН предпринимателя (12 цифр)"


def test_разделители_не_мешают():
    """В карточках номер пишут и через дефис, и через пробел."""
    for написание in ("7707-083-893", "7707 083 893", " 7707083893 ", "7707.083.893"):
        assert cov.вид_инн(написание) == "ИНН юрлица (10 цифр)", написание


def test_буква_в_номере_делает_его_иностранным():
    """Главный случай, и он поймал ошибку до первого прогона.

    Китайский USCC после выброса букв даёт ровно двенадцать цифр. Считай их —
    и иностранный завод запишется как российский предприниматель, а дальше
    сведение начнёт опирать на это тождество юрлица.
    """
    assert cov.вид_инн("CN91310000MA1K35QX8H") == "иностранный налоговый номер"
    for чужой in ("DE123456789", "GB123456789", "PL5260001246", "IT00159560366"):
        assert cov.вид_инн(чужой) == "иностранный налоговый номер", чужой


def test_цифры_неподходящей_длины_не_выдаются_за_инн():
    """Обрезанный или битый номер — повод для проверки, а не для тождества."""
    for битый in ("12345", "1", "123456789012345"):
        assert cov.вид_инн(битый) == "цифры, но не длина ИНН — проверить", битый


def test_пусто_значит_пусто():
    for пусто in ("", "   ", None):
        assert cov.вид_инн(пусто) == ""


def test_замер_не_печатает_сам_номер():
    """Правило 17: в журнал прогона — только агрегаты.

    Проверяется исходник: ни одна печать не должна выводить значение номера.
    Разряд («ИНН юрлица») печатать можно — это константа кода, а не данные.
    """
    # Запрет по ИМЕНАМ хранилищ самих номеров, а не по подстроке вроде «v)»:
    # первая версия ловила «sum(len(v) for v in общие.values())», где v — это
    # множество идентификаторов карточек и печатается только его длина.
    # Слишком широкая проверка ругается на безопасное и приучает её отключать.
    src = (ROOT / "scripts" / "supplier_inn_coverage.py").read_text(encoding="utf-8")
    ХРАНИЛИЩА = ("номера[", "номера.get", "значения", "RQ_INN", "ПОЛЯ_НОМЕРА")
    for строка in src.splitlines():
        голая = строка.split("#")[0]
        if "print(" not in голая:
            continue
        for опасное in ХРАНИЛИЩА:
            assert опасное not in голая, f"печать может вывести номер: {строка.strip()}"
