def test_быстро_на_мегабайте():
    """Строки до мегабайта: хороший текст — доли секунды, кракозябры с
    починкой — секунды. Пределы взяты с запасом в несколько раз над замером,
    чтобы не краснеть от загрузки машины гейта."""
    мегабайт = ("\n".join(НОРМА) + "\n") * (1_000_000 // len("\n".join(НОРМА)))
    мусор = мегабайт.encode("utf-8").decode("cp1251", "replace")
    t0 = time.perf_counter()
    assert tq.качество(мегабайт)[1] == "годится"
    assert tq.починить(мегабайт)[1] == ""
    t1 = time.perf_counter()
    починенный, _ = tq.починить(мусор)
    t2 = time.perf_counter()
    assert починенный == мегабайт
    assert t1 - t0 < 3.0, f"хороший мегабайт: {t1 - t0:.2f} с"
    assert t2 - t1 < 10.0, f"починка мегабайта: {t2 - t1:.2f} с"
