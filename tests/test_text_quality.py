def прочесть(b: bytes, кодировка: str) -> str:
    """Как читают Windows и Excel: байт, которого в кодировке нет, становится
    знаком с тем же номером (0x98 в cp1251 → U+0098)."""
    return "".join(bytes([x]).decode(кодировка, errors="ignore") or chr(x) for x in b)


def разрядка(т: str) -> str:
    return "\n".join("   ".join(" ".join(слово) for слово in строка.split(" "))
                     for строка in т.split("\n"))


def символьный_шрифт(т: str) -> str:
    return "".join(chr(0xF000 + b) if b >= 0x20 else chr(b) for b in т.encode("cp1251"))


def cid_cp1251(т: str) -> str:
    return "".join(f"(cid:{b})" if b >= 0x80 else chr(b) for b in т.encode("cp1251"))


def cid_индексы(т: str) -> str:
    """Шрифт CID: номер — индекс глифа, к кодировке отношения не имеет."""
    return "".join(f"(cid:{ord(ch) - 0x3F0})" if "А" <= ch <= "я" or ch in "Ёё" else ch for ch in т)


