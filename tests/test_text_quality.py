def _подставить_кандидата(monkeypatch, на_пробе: str, на_всём, вид: str):
    """Модуль с единственным кандидатом: на пробе он даёт `на_пробе`, на всём
    тексте — `на_всём(т)`. Проба укорочена, чтобы отличаться от текста."""
    mod = load()
    monkeypatch.setattr(mod, "ПРОБА", 300)

    def кандидат(т: str) -> str:
        return на_пробе if len(т) <= 400 else на_всём(т)
    monkeypatch.setattr(mod, "_кандидаты", lambda признаки: iter([("подставная починка", кандидат, вид)]))
    return mod


