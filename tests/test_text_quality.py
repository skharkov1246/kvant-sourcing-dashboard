def test_законные_знаки_целы_когда_чинятся_соседи():
    """Самое опасное место — починка по словам и строкам в тексте, где порча
    не сплошная. «ГОСТ Р 52857» с неразрывным пробелом — это одна пара «Р +
    0xA0»; «Ø» и «×» — байты D8 и D7, которые cp1251 прочла бы как «Ш» и «Ч»;
    «SKF®» — байт 0xAE, в cp866 это «о»; «ЕЁ» в cp1251 — законный utf-8 для
    «Ũ». Всё это должно пережить починку соседних строк."""
    целое = ("Стандарт ГОСТ Р\xa052857.1-2007, Ø50 мм, 10×10 мм, подшипник SKF®.\n"
             "Материал по Nestlé Waters, допуск ЕЁ не указан, давление 1,6 МПа.\n"
             "Буква «é» по-французски, «Größe» по-немецки, livraison à Moscou.")
    for порча in (lambda т: т.encode("cp1251").decode("latin-1"),
                  lambda т: прочесть(т.encode("utf-8"), "cp1251"),
                  lambda т: т.encode("utf-8").decode("latin-1")):
        смесь = целое + "\n" + порча(ТЕКСТ)
        починенный, сделано = tq.починить(смесь)
        assert починенный == целое + "\n" + ТЕКСТ, сделано


