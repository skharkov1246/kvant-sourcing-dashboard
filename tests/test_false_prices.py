def test_значение_реквизита_и_число_тройки_не_защищают():
    """Номер CIN и цифры телефона docfilter принял бы за код, сумму — за артикул.

    Защитой они не становятся: вырезаются до поиска признаков. Тот же код в
    своей колонке у настоящей позиции защищает."""
    cin = строка_базы("CIN NO L70109MH2010PLC123456", код="L70109MH2010PLC123456",
                      кол=12, цена=1.0, сумма=12)
    assert not quotes.признаки_позиции(cin["item_name"], cin["part_number"], "", 12, (12, 1.0, 12))
    assert причина(cin) == "регистрационный номер"
    итог = строка_базы("Total Amount (RMB): 143880", код="143880", кол=1, цена=143880.0,
                       сумма=143880)
    assert причина(итог) == "итог"
    # Тот же вид строки с кодом детали в своей колонке — позиция, а не итог.
    деталь = dict(итог, part_number="VYD-7788")
    assert причина(деталь) is None


