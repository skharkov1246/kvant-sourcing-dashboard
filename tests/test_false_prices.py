def _индексатор(monkeypatch):
    """Свежий модуль разбора карточек запросов: SOURCE читается при импорте."""
    pytest.importorskip("psycopg2", reason="индексатор импортирует psycopg2")
    monkeypatch.setenv("SOURCE", "rfq")
    for каталог in ("library",):
        monkeypatch.syspath_prepend(str(ROOT / каталог))
    spec = importlib.util.spec_from_file_location("indexer_false_prices", ROOT / "library" / "indexer.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _позиции() -> list[dict]:
    общие = {"oem": "", "source_file": "Ф1", "deal_id": "Д1", "company": "91001"}
    return [
        dict(общие, item_name="Page 1 of 1", part_number="", unit="", qty=1.0,
             _цена={"price": 1.0, "currency": "USD", "confidence": "low", "note": ИЗ_СУММЫ,
                    "total": 1.0}),
        dict(общие, item_name="Шайба выдуманная", part_number="ВЫД-125-01", unit="pcs", qty=1.0,
             _цена={"price": 1.0, "currency": "USD", "confidence": "med", "note": None,
                    "total": 1.0}),
        dict(общие, item_name="Втулка выдуманная", part_number="QX-1001", unit="pcs", qty=5.0,
             _цена={"price": 12.0, "currency": "USD", "confidence": "med", "note": None,
                    "total": 60.0}),
    ]


def test_запись_снимает_ложные_строки_и_считает_их(monkeypatch):
    ix = _индексатор(monkeypatch)
    monkeypatch.setattr(ix.quotes, "ОТБОР_ЛОЖНЫХ", True)
    monkeypatch.setattr(ix.price_store, "ОТКАЗАНО", ix.price_store.Counter())
    строки = ix.строки_цен({"side": None}, _позиции())
    имена = sorted(dict(zip(price_store.КОЛОНКИ, r))["item_name"] for r in строки)
    assert имена == ["Втулка выдуманная", "Шайба выдуманная"]
    assert dict(ix.price_store.ОТКАЗАНО) == {"страница": 1}
    журнал = ix.price_store.строка_отказов()
    assert "страница 1" in журнал and "Page" not in журнал
    # Переключатель выключен — прежнее поведение: пишутся все три.
    monkeypatch.setattr(ix.quotes, "ОТБОР_ЛОЖНЫХ", False)
    assert len(ix.строки_цен({"side": None}, _позиции())) == 3


