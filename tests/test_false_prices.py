# ── ОДНО ПРАВИЛО НА ЗАПИСЬ И НА ПОМЕТКУ ─────────────────────────────────────
# Строки, которые прежний текстовый путь брал ценой. Что новый путь отвергает,
# пометка обязана обвинить в строке, записанной прежним путём; что берёт —
# запись обязана пропустить.
ПРОВЕРКА_ОДНОГО_ПРАВИЛА = ЛОЖНЫЕ_ТЕКСТ + [
    "1 compressor crosshead ¥32890.00 1 ¥32890.00",
    "Подшипник выдуманный 6205, 2 шт 150,00 300,00",
    "Вал выдуманный 5 1200 6000",
    "Шайба DIN 125 М12, 100 шт 1,00 100,00",
    "Насос выдуманный 20 1 20",
    "Прокладка выдуманная 15000 2 30000",
]


def _кортеж(строка: str, ц: dict) -> tuple:
    """Строка цены текстового пути так, как её пишет разбор (indexer.handle)."""
    from library import docfilter
    поз = {"item_name": строка[:300], "part_number": docfilter.part_number_of(строка),
           "oem": "", "unit": "", "qty": ц["qty"], "source_file": "Ф1", "deal_id": "Д1"}
    return price_store.строка(поз, ц, str)


@pytest.mark.parametrize("строка", ПРОВЕРКА_ОДНОГО_ПРАВИЛА)
def test_одно_правило_на_запись_и_пометку(строка, monkeypatch):
    новая = quotes.цена_из_текста(строка)
    monkeypatch.setattr(quotes, "ОТБОР_ЛОЖНЫХ", False)
    прежняя = quotes.цена_из_текста(строка)
    monkeypatch.setattr(quotes, "ОТБОР_ЛОЖНЫХ", True)
    assert прежняя is not None, "корпус: прежний путь брал эту строку ценой"
    записанная = dict(zip(price_store.КОЛОНКИ, _кортеж(строка, прежняя)))
    if новая is None:
        assert причина(записанная) in quotes.ПРИЧИНЫ_ЛОЖНОЙ
    else:
        assert price_store.отобрать([_кортеж(строка, новая)], считать=False)
        if (новая["qty"], новая["price"]) == (прежняя["qty"], прежняя["price"]):
            assert причина(записанная) is None


