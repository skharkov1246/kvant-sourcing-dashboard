@pytest.mark.parametrize("строка, кол, цена", [
    # Первое число — правдоподобное количество: прежнее прочтение.
    ("Вал выдуманный 5 1200 6000", 5.0, 1200.0),
    ("Подшипник выдуманный 6205, 2 шт 150,00 300,00", 2.0, 150.0),
    # Единица за первым числом решает, даже когда оно дробное.
    ("Кабель выдуманный 150,5 м 20 3010", 150.5, 20.0),
    # Второе число с дробной частью количеством не считается.
    ("Кабель выдуманный 150,5 20,00 3010,00", 150.5, 20.0),
    # Первое число больше десяти тысяч, второе — целое: перестановка.
    ("Прокладка выдуманная 15000 2 30000", 2.0, 15000.0),
    # Единица за вторым числом: количество — оно.
    ("Шнур выдуманный 12,5 3 шт 37,5", 3.0, 12.5),
])
def test_прочтение_тройки(строка, кол, цена):
    ц = quotes.цена_из_текста(строка)
    assert (ц["qty"], ц["price"]) == (кол, цена)


