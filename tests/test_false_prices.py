def test_части_покрывают_диапазон_без_дыр():
    м = _прибор()
    for первый, последний, n in ((1, 100, 10), (5, 7, 10), (1, 1, 3), (10, 1009, 7)):
        ч = м.части(первый, последний, n)
        assert ч[0][0] == первый and ч[-1][1] == последний + 1
