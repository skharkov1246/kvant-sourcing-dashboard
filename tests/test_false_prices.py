"""Ложная строка цены: правило закрытым списком, прочтение тройки, запись.

ЗАЧЕМ. Недельный свод 21–27.09.2026 (прогон 36281598639): 20 строк цены из 83
проверенных — не цены. Номер страницы, телефон, CIN, условия оплаты, срок
действия, «Total Amount», срок поставки, строка служебной записки — цена 1,0
при сумме, равной количеству. И одна перепутанная тройка: «1 compressor
crosshead ¥32890.00 1 ¥32890.00» легла количеством 32 890 по цене 1,0.

Что закреплено:
  • каждый вид закрытого списка обвиняется — и в строке, уже лежащей в базе
    (quotes.ложная_цена по колонкам lib_prices), и в текстовом пути
    (quotes.цена_из_текста не берёт такую строку);
  • настоящая позиция с ценой 1,0 (шайба 1 шт × 1 USD при единице и коде) не
    обвиняется, как и позиция со стандартом, типоразмером, словом словаря;
  • значение реквизита (номер CIN, цифры телефона) и число самой тройки
    («143880») защитой не считаются;
  • перепутанная тройка читается 1 × 32 890 CNY; перестановка не делается там,
    где количество названо единицей или первое прочтение правдоподобно, и не
    создаёт цену там, где прежнее правило её не видело;
  • ОДНО ПРАВИЛО: всё, что текстовый путь теперь отвергает, пометка обвиняет в
    строке, записанной прежним путём; всё, что он берёт, запись пропускает;
  • запись (indexer.строки_цен → price_store.отобрать) снимает ложные строки и
    считает их; FALSE_PRICE_RULE=0 возвращает прежнее поведение;
  • замер пометки (scripts/mark_false_prices.py) считает гейты и печатает только
    агрегаты;
  • мутации правила ловятся корпусом.

Корпус придуман (CLAUDE.md, правило 18): ни одна строка не взята из базы.
"""
