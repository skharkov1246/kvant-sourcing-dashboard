def test_f1_смысл_колонок_страницы():
    """страница_сходится: в ячейке количества, цены и суммы — одно число, тройка
    сходится (с точностью до ставки НДС), а колонка, заполненная у страницы с
    шапкой, заполнена и на продолжении."""
    колонки = (3, 5, 6)
    строка = ["1", "Клапан", "ЖХ-1", "3", "шт", "8 004,85", "24 014,55"]
    assert ix._строка_сходится(строка, колонки, (True, True, True))
    assert ix._строка_сходится(строка[:5] + ["8 004,85", "28 817,46"], колонки, (True,) * 3), \
        "сумма с НДС 20 % при цене без НДС — та же строка"
    # Две суммы в одной ячейке — съехавший разрез, даже если тройка «сошлась».
    assert not ix._строка_сходится(строка[:5] + ["8 004,85 24 014,55", "24 014,55"], колонки,
                                   (True,) * 3)
    assert not ix._строка_сходится(строка[:5] + ["шт 8 004,85", "24 014,55"], колонки,
                                   (True,) * 3)
    # Без колонки суммы тройки нет — два числа в ячейке («3 12»: количество и
    # чужой номер, число_из склеит их в 312) ловит только счёт чисел.
    assert not ix._строка_сходится(строка[:3] + ["3 12", "шт", "8 004,85"], (3, 5, None),
                                   (True, True, False))
    assert ix._строка_сходится(строка[:3] + ["3", "шт", "8 004,85"], (3, 5, None),
                               (True, True, False))
    # Пустая обязательная колонка — отказ; пустая необязательная — не довод.
    пустая_сумма = строка[:6] + [""]
    assert not ix._строка_сходится(пустая_сумма, колонки, (True, True, True))
    assert ix._строка_сходится(пустая_сумма, колонки, (True, True, False))
    тело = [строка, строка[:6] + [""], строка]
    assert ix.заполненные_колонки(тело, колонки) == (True, True, False)
    assert ix.заполненные_колонки(тело + [строка], колонки) == (True, True, True)


