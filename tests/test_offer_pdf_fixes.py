#: Цена без НДС → количество, по всему корпусу (у вариантов одни позиции, у хвоста — свои).
ОЖИДАНИЕ = {**{ц: к for _, _, _, к, ц in позиции(64)}, **{ц: к for _, к, ц in хвост_позиции(52)}}


def верные(строки: list[dict], *, сумма: bool = True) -> list[dict]:
    """Строки с ценой без НДС из корпуса, её количеством и сошедшейся суммой."""
    out = []
    for с in строки:
        к = ОЖИДАНИЕ.get(round(с["price"], 2))
        if к is None or с.get("qty") != к:
            continue
        if сумма and (с.get("total") is None or abs(с["total"] - к * с["price"]) > 0.01):
            continue
        out.append(с)
