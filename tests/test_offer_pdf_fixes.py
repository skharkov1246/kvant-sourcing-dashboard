def _строка(ячейки: list[str], позиции: list[int]) -> str:
    """Строка раскладки pypdf: ячейки с левого края на заданных позициях."""
    out = ""
    for т, п in zip(ячейки, позиции):
        out = out.ljust(п) + т
    return out


