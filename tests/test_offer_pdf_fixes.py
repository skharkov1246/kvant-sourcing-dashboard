def test_признаки_строки_для_мусора_только_признаки_мусора():
    """Прежние строки цены файла спрашиваются только о признаках мусора
    (_мусор_прежде): дорогих (тройки строки, ячейки) быстрый путь не считает,
    а строку нумерации — считает."""
    import reparse
    it = _позиция("1 Клапан 3 шт 7 316,40 21 949,20", 37316.4, price="3  7 316,40")
