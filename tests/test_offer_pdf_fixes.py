    строка = ["1", "Клапан", "ЖХ-1", "3", "шт", "8 004,85", "24 014,55"]
    assert ix._строка_сходится(строка, колонки, (True, True, True))
    assert ix._строка_сходится(строка[:5] + ["8 004,85", "28 817,46"], колонки, (True,) * 3), \
        "сумма с НДС 20 % при цене без НДС — та же строка"
