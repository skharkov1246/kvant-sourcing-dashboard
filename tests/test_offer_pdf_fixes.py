def позиции_склейки(n: int) -> list[tuple[int, str, int, float]]:
    """(№, наименование, количество, цена без НДС) корпуса кп_склеенная_шапка."""
    return [(i, f"Клапан условный {i}", (i % 9) + 1, round(1000 + 173.37 * i, 2))
            for i in range(1, n + 1)]


@functools.lru_cache(maxsize=None)
def кп_склеенная_шапка(ширины: tuple[int, int, int, int] = (24, 52, 52, 60)) -> bytes:
    """Заголовки узких колонок шире самих колонок: pypdf склеивает их в строку
    «Кол-воЦена без НДС, руб.Цена с НДС, руб.Сумма с НДС, руб.», и ступень с
    допуском режет её посреди слов. Две страницы — чтобы работала F1."""
