class _Курсор:
    """Курсор базы для переразбора без базы: запросы — в журнал, ответы — по
    подстроке запроса."""

    def __init__(self, журнал: list, ответы: dict):
        self.журнал, self.ответы, self.запрос = журнал, ответы, ""

    def execute(self, запрос, параметры=None):
        self.запрос = запрос
        self.журнал.append(запрос)

    def fetchone(self):
        return (1,)

    def fetchall(self):
        return next((v for к, v in self.ответы.items() if к in self.запрос), [])

    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False


class _Соединение:
    def __init__(self, журнал: list, ответы: dict):
        self.журнал, self.ответы = журнал, ответы

    def cursor(self):
        return _Курсор(self.журнал, self.ответы)

    def commit(self):
        pass

    def close(self):
        pass


