def _hf_run(text: str) -> str:
    return (f'<w:r><w:rPr><w:color w:val="{MUTED}"/><w:sz w:val="18"/></w:rPr>'
            f'<w:t xml:space="preserve">{text}</w:t></w:r>')


def _fld(instr: str) -> str:
    """Простое поле Word (кэш «1» обновится при открытии/печати)."""
    return (f'<w:fldSimple w:instr=" {instr} ">'
            f'<w:r><w:rPr><w:color w:val="{MUTED}"/><w:sz w:val="18"/></w:rPr>'
            f'<w:t>1</w:t></w:r></w:fldSimple>')


