TAB = "<w:r><w:tab/></w:r>"


def write_docx(name: str, body: list) -> Path:
    document = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
                '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"'
                ' xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
                '<w:body>' + "".join(body) + SECT + '</w:body></w:document>')
    OUTDIR.mkdir(parents=True, exist_ok=True)
    out = OUTDIR / name
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", CONTENT_TYPES)
        z.writestr("_rels/.rels", bd.RELS)
        z.writestr("word/_rels/document.xml.rels", DOC_RELS)
        z.writestr("word/styles.xml", STYLES)
        z.writestr("word/header1.xml", HEADER_XML)
        z.writestr("word/footer1.xml", FOOTER_XML)
        z.writestr("word/document.xml", document)
    return out


def par(runs, *, style=None, jc=None, spacing=None, tabs=None, bottom=None, keep=False):
    """Абзац с pPr: стиль, выключка, интервалы, табуляторы, нижняя граница.

    Порядок детей pPr — по схеме CT_PPr: pStyle, keepNext, pBdr, tabs, spacing, jc.
    """
    ppr = ""
    if style:
        ppr += f'<w:pStyle w:val="{style}"/>'
    if keep:
        ppr += "<w:keepNext/>"
    if bottom:  # (толщина в 1/8 pt, цвет) — линия-отбивка абзаца
        ppr += (f'<w:pBdr><w:bottom w:val="single" w:sz="{bottom[0]}"'
                f' w:space="4" w:color="{bottom[1]}"/></w:pBdr>')
    if tabs:
        ppr += ("<w:tabs>" +
                "".join(f'<w:tab w:val="{v}" w:pos="{pos}"/>' for v, pos in tabs) +
                "</w:tabs>")
    if spacing:
        ppr += spacing
    if jc:
        ppr += f'<w:jc w:val="{jc}"/>'
    ppr = f"<w:pPr>{ppr}</w:pPr>" if ppr else ""
    return f"<w:p>{ppr}{''.join(runs)}</w:p>"


def tcell(paras, width, *, shade=None, valign=None):
    """Ячейка с внутренними отступами и верт. выравниванием (bd.cell их не умеет)."""
    sh = f'<w:shd w:val="clear" w:fill="{shade}"/>' if shade else ""
    va = f'<w:vAlign w:val="{valign}"/>' if valign else ""
    mar = ('<w:tcMar><w:top w:w="57" w:type="dxa"/><w:left w:w="113" w:type="dxa"/>'
           '<w:bottom w:w="57" w:type="dxa"/><w:right w:w="113" w:type="dxa"/></w:tcMar>')
    return (f'<w:tc><w:tcPr><w:tcW w:w="{width}" w:type="dxa"/>{sh}{mar}{va}</w:tcPr>'
            f'{"".join(paras)}</w:tc>')


def cpar(runs, jc="left"):
    """Абзац внутри ячейки: одинарный интервал, компактный отступ."""
    return par(runs, spacing='<w:spacing w:after="40" w:line="240" w:lineRule="auto"/>', jc=jc)


def h1(t):  return bd.p([bd.run(t)], style="Heading1")
def h2(t):  return bd.p([bd.run(t)], style="Heading2")
def pp(t, size=22, color=None, bold=False):
    return bd.p([bd.run(t, size=size, color=color, bold=bold)])
def ph(label):  # плейсхолдер
    return f"[{label}]"


def sub(t):
    """Подзаголовок под названием документа — по центру, серым."""
    return par([bd.run(t, size=20, color=MUTED)], jc="center",
               spacing='<w:spacing w:after="240"/>')


def letterhead():
    """Титульная шапка: наименование, строка реквизитов, линия-отбивка."""
    return [
        par([bd.run("ООО «КВАНТ»", bold=True, size=28, color=ACCENT)],
            jc="left", keep=True, spacing='<w:spacing w:after="40"/>'),
        par([bd.run(ph("ИНН/КПП/ОГРН, юридический адрес, телефон, e-mail — реквизиты компании"),
                    size=16, color=MUTED)],
            jc="left", bottom=(12, ACCENT), spacing='<w:spacing w:after="320"/>'),
    ]


def sign_block(post="должность подписанта", basis=False):
    """Подписной блок: должность, линия подписи «/ Ф.И.О. /», место печати.

    basis=True — добавляет строку об основании полномочий (устав/доверенность):
    для письма-заявки и КП, где подписант должен подтвердить полномочия.
    """
    rows = []
    if basis:
        rows.append(par([bd.run(ph(post), size=22),
                         bd.run(", действующий(ая) на основании ", size=22),
                         bd.run(ph("Устава / доверенности № ___ от ___"), size=22),
                         bd.run(",", size=22)],
                        jc="left", keep=True,
                        spacing='<w:spacing w:before="600" w:after="80"/>'))
        rows.append(par([TAB,
                         bd.run("___________________ / ", size=22),
                         bd.run(ph("Ф.И.О."), size=22),
                         bd.run(" /", size=22)],
                        jc="left", keep=True, tabs=[("right", CONTENT_W)],
                        spacing='<w:spacing w:after="80"/>'))
    else:
        rows.append(par([bd.run(ph(post), size=22), TAB,
                         bd.run("___________________ / ", size=22),
                         bd.run(ph("Ф.И.О."), size=22),
                         bd.run(" /", size=22)],
                        jc="left", keep=True, tabs=[("right", CONTENT_W)],
                        spacing='<w:spacing w:before="600" w:after="80"/>'))
    rows.append(par([bd.run("М.П.", size=20, color=MUTED)],
                    spacing='<w:spacing w:before="120"/>'))
    return rows


