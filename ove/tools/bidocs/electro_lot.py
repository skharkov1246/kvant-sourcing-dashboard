def _open_section(lot: int, secs: list) -> list:
    out = [_h1("15. Открытые позиции")]
    out.append(_para(
        "Ниже перечислено то, что на стадии Базового инжиниринга не может быть определено "
        "окончательно и требует решения Заказчика, технических условий сетевой организации, "
        "данных инженерных изысканий либо технических предложений изготовителей. Каждая позиция "
        "закрывается до выдачи материалов на этап основных технических решений."))
    seen = []
    for s in secs:
        for o in s.get("open") or []:
            t = _clean(o)
            if t and t not in seen:
                seen.append(t)
                out.append(_open(t))
    for t in OPEN_EXTRA.get(lot, []):
        if t not in seen:
            seen.append(t)
            out.append(_open(t))
    return out


def _fnum(v, nd=1) -> str:
    """Число с десятичной запятой и разделителем тысяч."""
    if v is None:
        return DASH
    try:
        f = float(v)
    except (TypeError, ValueError):
        return str(v)
    s = f"{f:,.{nd}f}".replace(",", " ").replace(".", ",")
    if s.endswith(",0"):
        s = s[:-2]
    return s


# ------------------------------------------------------------------- сборка

def build(row: dict) -> Path:
    lot = int(row.get("lot") or 0)
    secs = [s for s in c.bi_sections(lot) if re.match(SEC_RE, s.get("id", ""), re.I)]
    items = c.equipment(lot)
    res = c.load("resources")
    delivs = [d for d in c.load("deliverables")["items"] if d["id"] in SCOPE]
    delivs.sort(key=lambda d: d["id"])
    docs = _related(lot, row["code"])

    body = []
    body += _intro(lot, docs)
    body += _scope(lot, delivs)
    body += _norms(secs)
    body += _sources_section(lot)
    body += _scheme(lot)
    body += _loads_intro(lot)
    body += _known_loads(lot, res)
    extra = _extra_loads(lot)
    body += extra
    nx = 4 if extra else 3
    body += _vedomost(lot, items, f"4.{nx}")
    body += _totals(lot, f"4.{nx + 1}")
    body += _reliability(lot, f"4.{nx + 2}")
    body += _startup(lot, f"4.{nx + 3}")
    body += _krm(lot)
    body += _trafo(lot)
    body += _cables(lot)
    body += _shortcircuit(lot)
    body += _earth(lot)
    body += _light(lot)
    body += _exzone(lot)
    body += _equip(lot)
    body += _datasheets(lot)
    body += _graphics(lot)
    body += _open_section(lot, secs)
    return c.write_docx(c.out_path(row), body)
