def _norms(lot: int, secs: list) -> list:
    """Курируемый перечень норм плюс документы разделов базы решений без повторов."""
    rows, seen = [], set()
    for doc, what in NORMS_EXTRA.get(lot, []) + NORMS_COMMON:
        cs = _codes(doc)
        if cs and cs <= seen:
            continue
        seen |= cs
        rows.append([doc, what])
    for s in secs:
        for g in (s or {}).get("gost") or []:
            doc, what = _clean(g.get("doc")), _clean(g.get("what"))
            cs = _codes(doc)
            if not doc or (cs and cs <= seen):
                continue
            seen |= cs
            rows.append([doc, what])
    if not rows:
        return []
    return [_h2("1.4 Нормативная база"),
            _simple([("Документ", 2900), ("Область применения", 6454)], rows)]


