    widths = [w for _, w in COLS]
    out = [_h1("2. Ведомость тяжёлых и крупногабаритных монтажных единиц")]
    out.append(_para(
        "В ведомость включены позиции, определяющие выбор грузоподъёмных механизмов, габариты "
        "монтажных проёмов и последовательность работ: наиболее тяжёлые монтажные единицы, "
        "крупногабаритные и длинномерные части, а также позиции, требующие специальных способов "
        "подачи. Массы приведены для монтажного состояния — без рабочего заполнения, футеровки "
        "по месту и съёмных элементов, если иное не оговорено в графе."))
    rows = [[_cell([_cp(h, size=15, bold=True)], w, shade="EFEFEF") for h, w in COLS]]
    n, area = 0, None
    for row in UNITS.get(lot, []):
        if row[0] != area:
            area = row[0]
            rows.append(_group_row(area, widths))
        n += 1
