def _p(text, *, size=20, bold=False, italic=False, color=None, style=None) -> str:
    ppr = f'<w:pPr><w:pStyle w:val="{style}"/></w:pPr>' if style else ""
    return f"<w:p>{ppr}{bd.run(text, bold=bold, italic=italic, color=color, size=size)}</w:p>"


def _h1(text: str) -> str:
    return _p(text, size=28, bold=True, style="Heading1")


def _h2(text: str) -> str:
    return _p(text, size=24, bold=True, style="Heading2")


def _para(text: str) -> str:
    return _p(text, size=20)


def _bullet(text: str) -> str:
    return _p("— " + text, size=20)


def _source(text: str) -> str:
    return _p("Источник: " + text, size=17, color="666666")


def _note(text: str) -> str:
    return _p(text, size=18, color="555555")


def _open(text: str) -> str:
    return ("<w:p>" + bd.run("Определяется на стадии БИ: ", bold=True, size=19, color="8A6200")
            + bd.run(text, size=19) + "</w:p>")


def _cp(text, *, size=16, bold=False, color=None, keep=False) -> str:
    ppr = "<w:pPr><w:keepNext/></w:pPr>" if keep else ""
    return f"<w:p>{ppr}{bd.run(text, bold=bold, color=color, size=size)}</w:p>"


def _cell(paras, width, *, shade=None) -> str:
    if isinstance(paras, str):
        paras = [_cp(paras)]
    return bd.cell(paras, width, shade=shade)


def _tbl(rows: list, widths: list, *, head_rows: int = 1) -> str:
    """Таблица с повторяемой шапкой и неразрывными строками."""
    borders = "".join(f'<w:{s} w:val="single" w:sz="4" w:color="C9C9C9"/>'
                      for s in ("top", "left", "bottom", "right", "insideH", "insideV"))
    grid = "".join(f'<w:gridCol w:w="{w}"/>' for w in widths)
    trs = []
    for i, cells in enumerate(rows):
        trpr = "<w:trPr>" + ("<w:tblHeader/>" if i < head_rows else "") + "<w:cantSplit/></w:trPr>"
        trs.append(f"<w:tr>{trpr}{''.join(cells)}</w:tr>")
    return (f'<w:tbl><w:tblPr><w:tblW w:w="{sum(widths)}" w:type="dxa"/>'
            f'<w:tblBorders>{borders}</w:tblBorders><w:tblLayout w:type="fixed"/>'
            f'<w:tblCellMar><w:left w:w="57" w:type="dxa"/><w:right w:w="57" w:type="dxa"/>'
            f'</w:tblCellMar></w:tblPr><w:tblGrid>{grid}</w:tblGrid>{"".join(trs)}</w:tbl>')


def _simple(cols: list, rows: list, *, size=17) -> str:
    widths = [w for _, w in cols]
    body = [[_cell([_cp(h, size=15, bold=True)], w, shade="EFEFEF") for h, w in cols]]
    for r in rows:
        body.append([_cell([_cp(str(v), size=size)], w) for v, w in zip(r, widths)])
    return _tbl(body, widths)


def _group_row(text: str, widths: list) -> list:
    tc = (f'<w:tcW w:w="{sum(widths)}" w:type="dxa"/><w:gridSpan w:val="{len(widths)}"/>'
          '<w:shd w:val="clear" w:color="auto" w:fill="F3F3F3"/>')
    return [f"<w:tc><w:tcPr>{tc}</w:tcPr>{_cp(text, size=16, bold=True, keep=True)}</w:tc>"]


