def _open_section(lot: int, secs: list) -> list:
    out = [_h1("10. Открытые позиции")]
    out.append(_para(
        "Ниже перечислено то, что на стадии Базового инжиниринга не может быть определено "
        "окончательно и требует данных Заказчика, результатов обследования либо технических "
        "предложений изготовителей. Каждая позиция закрывается до выдачи проекта производства "
        "работ и до размещения заказов на оборудование."))
    seen = []
    for s in secs:
        for o in s.get("open") or []:
            if re.search(OPEN_SKIP, str(o)):
                continue
            t = _clean(o)
            if t and t not in seen:
                seen.append(t)
                out.append(_open(t))
    for t in OPEN_EXTRA.get(lot, []):
        if t not in seen:
            seen.append(t)
            out.append(_open(t))
    return out


# ------------------------------------------------------------------- сборка

def build(row: dict) -> Path:
    lot = int(row.get("lot") or 0)
    main = c.bi_section(lot, SEC_RE)
    docs = _related(lot, row["code"])

    body = []
    body += _intro(lot, docs)
    body += _norms(lot, main)
    body += _climate()
    body += _vedomost(lot)
    body += _transport(lot)
    body += _openings(lot)
    body += _sequence(lot)
    body += _cranes(lot)
    body += _special(lot)
    body += _tech_suit()
    body += _accept()
    body += _open_section(lot, [main] if main else [])
    return c.write_docx(c.out_path(row), body)
