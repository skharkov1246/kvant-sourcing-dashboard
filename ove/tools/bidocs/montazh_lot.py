# Позиции раздела базы, относящиеся к границам объёма (раздел 1.2), а не к открытым вопросам.
OPEN_SKIP = r"^ППР монтажа — этап СМР"


def _clean(text: str) -> str:
    t = str(text or "")
    for pat, rep in CLEAN:
        t = re.sub(pat, rep, t)
    return t.strip()


