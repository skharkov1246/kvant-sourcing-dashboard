def _norms(lot: int, sec: dict | None) -> list:
    """Нормативная база: документы раздела монтажа базы решений по лоту и дополнения."""
    seen, rows = [], []
    for g in (sec or {}).get("gost") or []:
        doc = _clean(g.get("doc"))
        if doc and doc not in seen:
            seen.append(doc)
            rows.append([doc, _clean(g.get("what"))])
    for doc, what in NORMS_EXTRA.get(lot, []):
        doc = _clean(doc)
        if doc not in seen:
            seen.append(doc)
            rows.append([doc, _clean(what)])
    if not rows:
        return []
    return [_h2("1.4 Нормативная база производства монтажных работ"),
            _simple([("Документ", 2700), ("Область применения", 6654)], rows),
            _note("Далее по тексту сокращение ФНП означает федеральные нормы и правила в области "
                  "промышленной безопасности, утверждённые приказом Ростехнадзора с указанным "
                  "номером.")]


