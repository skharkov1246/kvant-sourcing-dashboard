def _sheet(s: dict, lot: int) -> list:
    out = [_h1_break(f"Опросный лист ОЛ-ОВЭ75-{s['num']:02d}. {s['title']}")]
    sub = f"{c.df.lot_title(s['lot'])}, участок «{s['area']}»" if s["area"] else c.df.lot_title(s["lot"])
    if s["lot"] != lot:
        sub += f" — лист включён в альбом {_lot_gen(lot)}"
    out.append(c.note(sub))
    out += s["body"]
    return out


def _open(lot: int, sheets: list) -> list:
    out = [c.h1("Открытые позиции")]
    out.append(c.para("Позиции, значения которых определяются по технико-коммерческим предложениям "
                      "изготовителей либо на последующих этапах стадии БИ."))
    for s in sheets:
        if s["open"]:
            labels = "; ".join(lab.strip() for lab, _ in s["open"])
            out.append(c.open_item(f"ОЛ-ОВЭ75-{s['num']:02d} ({s['title']}) — {labels}: по ТКП изготовителя."))
    if PLANNED.get(lot):
        text, src = PLANNED[lot]
        out.append(c.open_item(f"{text} — определяется на стадии БИ (следующая ревизия альбома)."))
        out.append(c.source(src))
    if lot == 4:
        out.append(c.open_item("Отдельный опросный лист на мостовой кран железнодорожного фронта с автоматической "
                               "траверсой (грузоподъёмность не менее 3,2 т с учётом траверсы, крановый пролёт 22 м) "
                               "— определяется на стадии БИ; в настоящей ревизии за основу принят лист ОЛ-ОВЭ75-11 "
                               "специальных кранов Лота №3."))
    for t in LOT_OPEN.get(lot, []):
        out.append(c.open_item(t))
    out.append(c.open_item("Перечень изготовителей и поставщиков для рассылки листов, сроки ответа и порядок "
                           "сравнения ТКП — по реестру запросов бюджетных ТКП (документ ОВЭ75-БИ-ОБ-ТКП)."))
    out.append(c.open_item("Итоговая редакция листов — после согласования с Заказчиком перечня основного "
                           "оборудования лота и получения замечаний к настоящей ревизии."))
    return out


# --------------------------------------------------------------- сборка

def build(row: dict) -> Path:
    lot = int(row.get("lot") or 0)
    slugs = row.get("ol") or []
    if not slugs:
        raise ValueError(f"{row['code']}: в строке реестра нет поля ol (слаги опросных листов)")
    sheets = [_load(s) for s in slugs]
    body = []
    body += _intro(lot, sheets, row)
    for s in sheets:
        body += _sheet(s, lot)
    body += _open(lot, sheets)
    return c.write_docx(c.out_path(row), body)
