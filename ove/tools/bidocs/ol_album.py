def _h1_break(text: str) -> str:
    return ('<w:p><w:pPr><w:pStyle w:val="Heading1"/><w:pageBreakBefore/></w:pPr>'
            + bd.run(text, bold=True, size=28) + "</w:p>")


def _lot_gen(lot: int) -> str:
    """Название лота в родительном падеже: «Лота №1 «Цех обжига»»."""
    return f"Лота №{lot} «{c.LOTS[lot]}»" if lot else "комплекса"


def _req(text: str, src: str) -> str:
    return bd.p([bd.run("— " + text, size=20), bd.run(f" ({src})", size=17, color="666666")])


def _qty(positions: list) -> str:
    qs = [p[2].strip() for p in positions]
    if not qs:
        return "—"
    if all(re.fullmatch(r"\d+", q) for q in qs):
        if len(qs) == 1:
            return qs[0]
        return f"{sum(int(q) for q in qs)} ({' + '.join(qs)})"
    seen = []
    for q in qs:
        if q not in seen:
            seen.append(q)
    return "; ".join(seen)


def _pos(positions: list) -> str:
    ps = [p[0].strip() for p in positions if p[0].strip() and p[0].strip() != "—"]
    return ", ".join(ps) if ps else "—"


