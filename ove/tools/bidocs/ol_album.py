# ------------------------------------------------------------ разбор листа

def _split(body: str) -> list:
    """Тело document.xml → верхнеуровневые элементы (абзацы, таблицы)."""
    out, i, n = [], 0, len(body)
    while i < n:
        if body.startswith("<w:tbl>", i) or body.startswith("<w:tbl ", i):
            j = body.index("</w:tbl>", i) + len("</w:tbl>")
        elif body.startswith("<w:p/>", i):
            j = i + len("<w:p/>")
        elif body.startswith("<w:p>", i) or body.startswith("<w:p ", i):
            j = body.index("</w:p>", i) + len("</w:p>")
        elif body.startswith("<w:sectPr", i):
            j = body.index("</w:sectPr>", i) + len("</w:sectPr>")
            i = j
            continue
        else:
            raise ValueError(f"неизвестный элемент тела листа: {body[i:i + 40]!r}")
        out.append(body[i:j])
        i = j
    return out


def _text(xml: str) -> str:
    t = re.sub(r"</w:p>", "\n", xml)
    t = re.sub(r"<[^>]+>", "", t)
    return re.sub(r"[ \t]+", " ", t).strip()


def _cells(tr: str) -> list:
    return [_text(tc).replace("\n", " ").strip() for tc in re.findall(r"<w:tc>.*?</w:tc>", tr, re.S)]


def _rows(tbl: str) -> list:
    return [_cells(tr) for tr in re.findall(r"<w:tr>.*?</w:tr>", tbl, re.S)]


def _fix_text(xml: str) -> str:
    def fix(m):
        s = m.group(2)
        for pat, rep in FIX:
            s = re.sub(pat, rep, s)
        return m.group(1) + s + m.group(3)
    return re.sub(r"(<w:t(?:\s[^>]*)?>)([^<]*)(</w:t>)", fix, xml)


def _fit(tbl: str) -> str:
    """Таблица листа → ширина текстового поля каркаса; строки не рвутся, шапка повторяется."""
    grid = [int(x) for x in re.findall(r'<w:gridCol w:w="(\d+)"', tbl)]
    if grid and sum(grid) > W_TEXT:
        k = W_TEXT / sum(grid)
        tbl = re.sub(r'(<w:(?:gridCol|tcW|tblW) w:w=")(\d+)(")',
                     lambda m: f"{m.group(1)}{int(int(m.group(2)) * k)}{m.group(3)}", tbl)
    parts = tbl.split("<w:tr>")
    out = [parts[0]]
    for i, r in enumerate(parts[1:]):
        pr = "<w:trPr><w:cantSplit/>" + ("<w:tblHeader/>" if i == 0 else "") + "</w:trPr>"
        out.append(pr + r)
    return "<w:tr>".join(out)


def _load(slug: str) -> dict:
    path = SPECS / f"ove75-ol-{slug}.docx"
    if not path.exists():
        raise FileNotFoundError(f"нет опросного листа {path.name}")
    xml = c.zipfile.ZipFile(path).read("word/document.xml").decode("utf-8")
    body = re.search(r"<w:body>(.*)</w:body>", xml, re.S).group(1)
    els = _split(body)
    texts = [_text(e) for e in els]
    full = "\n".join(texts)

    m = re.search(r"ОПРОСНЫЙ ЛИСТ ОЛ-ОВЭ75-(\d+)", full)
    num = int(m.group(1)) if m else 0
    title, lot, area = "", 0, ""
    for i, t in enumerate(texts):
        if t.startswith("ОПРОСНЫЙ ЛИСТ") and i + 1 < len(texts):
            title = texts[i + 1].strip()
        mm = re.match(r"Лот №(\d).*?участок:\s*(.+?)(?:\s*·\s*сформирован.*)?$", t)
        if mm:
            lot, area = int(mm.group(1)), mm.group(2).strip()

    # начало содержательной части листа: перечень позиций либо таблица характеристик
    start = next((i for i, t in enumerate(texts)
                  if t.startswith("Позиции перечня") or t.startswith("Технические характеристики")), None)
    if start is None:
        raise ValueError(f"{path.name}: не найдено начало содержания листа")
    keep = []
    for e, t in zip(els[start:], texts[start:]):
        if t.startswith("Источники данных") or re.search(r"\.py\b", t):
            continue                      # служебная строка генератора
        if t.startswith("Жёлтым выделено") or t.startswith("Цветом выделено"):
            e = c.note("Поля, выделенные цветом («уточняется по ТКП»), заполняет изготовитель; остальные "
                       "значения — исходные требования Заказчика (ИД ч.1/ч.2, ТЗ на БИ) и решения Базового "
                       "инжиниринга.")
        if e.startswith("<w:tbl"):
            e = _fit(e)
        keep.append(_fix_text(e))

    positions, open_params = [], []
    for e, t in zip(els[start:], texts[start:]):
        if not e.startswith("<w:tbl"):
            continue
        rows = _rows(e)
        if not rows:
            continue
        if rows[0][:1] == ["Поз."]:
            positions = [r for r in rows[1:] if len(r) >= 4]
        elif rows[0][:1] == ["Параметр"]:
            open_params = [(r[0], r[2]) for r in rows[1:] if len(r) >= 3 and r[1].strip() == TBD]
    return dict(slug=slug, num=num, title=title, lot=lot, area=area, body=keep,
                positions=positions, open=open_params)


