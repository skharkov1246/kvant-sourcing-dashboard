DOC_ORDER = ["ПЗ", "PFD", "PID", "СО", "ОЛ", "ДЦ", "МТ", "ЭС", "АСУ", "СТ"]


def _related(lot: int, code: str) -> list:
    rows = [r for r in c.df.register() if r.get("lot") == lot and r["code"] != code]
    out = []
    for suf in DOC_ORDER:
        out += [r for r in rows if r["code"].endswith("-" + suf)]
    return out


def build(row: dict) -> Path:
    lot = int(row.get("lot") or 0)
    if lot not in AREAS:
        raise ValueError("перечень трубопроводов не определён для лота " + str(lot))
    sec = c.bi_section(lot, LINE_RE)
    pid = c.bi_section(lot, PID_RE)
    lotinfo = next((l for l in c.load("lots")["lots"] if l.get("id") == lot), {})
    docs = _related(lot, row["code"])

    body = []
    body += _intro(lot, sec, pid, lotinfo, docs)
    body += _sources(lot, lotinfo)
    body += _lines(lot)
    body += _armkip(lot)
    body += _valves(lot)
    body += _instr(lot)
    body += _crit(lot)
    body += _norms(lot, [sec, pid])
    body += _metro(lot)
    body += _open(lot, [sec, pid])
    return c.write_docx(c.out_path(row), body, landscape=True)
