def _tbl(cols, rows, *, size=16):
    """Таблица с повторяющейся на каждом листе шапкой и неразрывными строками."""
    xml = c.table([h for h, _ in cols], rows, [w for _, w in cols], size=size)
    xml = xml.replace("<w:tr>", "<w:tr><w:trPr><w:cantSplit/></w:trPr>")
    return xml.replace("<w:tr><w:trPr><w:cantSplit/></w:trPr>",
                       "<w:tr><w:trPr><w:tblHeader/><w:cantSplit/></w:trPr>", 1)


