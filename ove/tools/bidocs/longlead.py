# ------------------------------------------------------------------ сборка

def build(row: dict) -> Path:
    lot = int(row.get("lot") or 0)
    pos, extra, outside, opens = LOT[lot]()
    body = []
    body += _s1(lot, row, len(pos))
    body += _s2(lot, pos, extra, outside)
    body += _s3(lot, 3)
    n = 4
    for p in pos:
        body += _pos(n, p)
        n += 1
    body += _sched(n, lot)
    body += _open(n + 1, opens)
    return c.write_docx(c.out_path(row), body)


