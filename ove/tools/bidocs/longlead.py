def _reg_code(suffix: str, lot: int) -> str:
    for r in c.df.register():
        if r.get("lot") == lot and str(r["code"]).endswith("-" + suffix):
            return r["code"]
    return ""


def _poz(n: int) -> str:
    """Согласование числительного: 4 позиции, 8 позиций."""
    tail = n % 100
    if 11 <= tail <= 14:
        word = "позиций"
    elif n % 10 == 1:
        word = "позиция"
    elif n % 10 in (2, 3, 4):
        word = "позиции"
    else:
        word = "позиций"
    return f"{n} {word}"


def _lot_regime(lot: int) -> str:
    for l in c.load("lots")["lots"]:
        if l.get("id") == lot:
            return l.get("regime", "")
    return ""


