# ------------------------------------------------------------------ сборка

def build(row: dict) -> Path:
    lot = int(row.get("lot") or 0)
    sec = c.bi_section(lot, r"stoimost|postavka") or {}
    positions = _positions(lot)
    docs = _related(lot, row["code"])

    body = []
    body += _intro(lot, sec, docs, positions)
    body += _method(lot, sec)
    body += _register(lot, positions)
    body += _request(lot, positions)
    body += _compare(lot)
    body += _summary(lot, positions)
    body += _terms(lot)
    body += _open_section(lot)
    return c.write_docx(c.out_path(row), body)
