def _is_company(name: str) -> bool:
    return bool(name) and not PLACEHOLDER_RE.search(name)


def _key(name: str) -> str:
    s = re.sub(r"\([^)]*\)", " ", name).lower()
    s = s.replace("«", " ").replace("»", " ").replace('"', " ").replace("'", "")
    s = FORM_RE.sub(" ", s)
    s = re.sub(r"[^a-zа-яё0-9]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def _candidates(pos: dict, profiles: dict) -> tuple:
    """Уникальные кандидаты позиции: (список (имя, страна), есть ли пометки о рынке)."""
    found, order, loose = {}, [], False
    for grp in ("cn", "ru", "world"):
        for name in pos.get(grp) or []:
            if not _is_company(name):
                loose = True
                continue
            k = _key(name)
            prof = profiles.get(name) or profiles.get(k) or {}
            country = COUNTRY.get(prof.get("country"), None)
            if k not in found:
                found[k] = {"name": name, "country": country or GROUP_COUNTRY[grp]}
                order.append(k)
            else:
                if country:
                    found[k]["country"] = country
                if len(name) > len(found[k]["name"]):
                    found[k]["name"] = name
    return [(found[k]["name"], found[k]["country"]) for k in order], loose


def _geography(cands: list) -> str:
    counts = {}
    for _, country in cands:
        counts[country] = counts.get(country, 0) + 1
    parts = [f"{c} — {counts[c]}" for c in COUNTRY_ORDER if c in counts]
    parts += [f"{c} — {n}" for c, n in counts.items() if c not in COUNTRY_ORDER]
    return "; ".join(parts) if parts else "перечень формируется"


def _positions(lot: int) -> list:
    """Закупочные позиции лота и позиции, общие для всех лотов, с номерами запросов."""
    sup = c.load("suppliers")
    profiles = {}
    for p in sup.get("profiles", []):
        profiles[p["name"]] = p
        profiles.setdefault(_key(p["name"]), p)
    out = []
    for n, pos in enumerate(sup.get("positions", []), 1):
        if pos.get("lot") not in (lot, 9):
            continue
        cands, loose = _candidates(pos, profiles)
        out.append({
            "no": n,
            "cls": pos.get("cls", ""),
            "name": NAME_OVERRIDE.get(f"{pos.get('cls')}:{pos.get('lot')}",
                                       _clean(pos.get("name", ""))),
            "tier": pos.get("tier", ""),
            "spec": _clean(pos.get("spec", "")),
            "ask": ASK_OVERRIDE.get(f"{pos.get('cls')}:{pos.get('lot')}", _clean(pos.get("ask", ""))),
            "cands": cands,
            "loose": loose,
            "common": pos.get("lot") == 9,
            "outside": "(вне БИ)" in (pos.get("name") or ""),
        })
    return out


def _related(lot: int, code: str) -> list:
    keep = ("-ПЗ", "-СО", "-ОЛ", "-ДЦ", "-МТ", "-ЭС", "-НГ")
    rows = [r for r in c.df.register()
            if r.get("lot") == lot and r["code"] != code and r["code"].endswith(keep)]
    order = {suf: i for i, suf in enumerate(keep)}
    return sorted(rows, key=lambda r: order.get("-" + r["code"].split("-")[-1], 99))


def _doc(lot: int, suffix: str) -> str | None:
    for r in c.df.register():
        if r.get("lot") == lot and r["code"].endswith("-" + suffix):
            return f"{r['code']} «{r['title']}»"
    return None


