def _clean(text: str) -> str:
    """Убрать разметку и рабочие пометки из текста базы решений."""
    t = text or ""
    t = t.replace("**", "").replace("`", "")
    t = t.replace("Состав по ТЗ (пред. ред.) п. 6.3 (в v4.1 — п. 7.x, сверить по перечню границ Лота №4 v4.1)",
                  "Состав по перечню оборудования Лота №4 в ТЗ на БИ (ред. 4.1)")
    t = re.sub(r"\(см\. раздел ([^)]+)\)", r"(см. раздел \1 пояснительной записки)", t)
    return t.strip()


def _lines(text: str) -> list:
    """Абзацы текста базы: разделители — переводы строк (списки в базе записаны построчно)."""
    return [t.strip() for t in re.split(r"\n+", _clean(text)) if t.strip()]


def _q(title: str) -> str:
    """Название раздела в кавычках; внутренние кавычки — второго уровня."""
    t = (title or "").replace("«", "„").replace("»", "“")
    return f"«{t}»"


def _val(x) -> str:
    s = str(x).strip() if x is not None else ""
    return s if s and s != "—" else DASH


