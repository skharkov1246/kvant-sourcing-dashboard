def _fields(lot: int, it: dict) -> dict:
    """Значения граф позиции: из перечня оборудования плюс дополнения из текста базы.

    Возвращает {графа: (значение_ИД, [(дополнение, источник), ...])}. Если мощность записана
    среди габаритов (КСМ), она выносится в графу мощности.
    """
    nz = lambda v: "" if (v or "").strip() in ("", DASH) else str(v).strip()  # noqa: E731
    power, dims, param = nz(it.get("power")), nz(it.get("dims")), nz(it.get("param"))
    if not power and re.search(r"мощност", dims, re.I):
        parts = [s.strip() for s in dims.split(";")]
        pw = [s for s in parts if re.search(r"мощност", s, re.I)]
        power, dims = "; ".join(pw), "; ".join(s for s in parts if s not in pw)
    supp = SUPPLEMENT.get((lot, it.get("area"), it.get("name")), {})
    return {"param": (param, [supp["param"]] if "param" in supp else []),
            "dims": (dims, [supp["dims"]] if "dims" in supp else []),
            "power": (power, [supp["power"]] if "power" in supp else [])}


def _has(f: tuple) -> bool:
    return bool(f[0] or f[1])


def _cell_paras(f: tuple, *, note: str = "", empty: str = DASH) -> list:
    """Абзацы графы: значение ИД; дополнения (значение + источник мелким); примечание."""
    val, supp = f
    paras = []
    if val:
        paras.append(_p(val))
    for text, src in supp:
        paras.append(_p(text, size=15) if not val else _p(text, size=15, color="333333"))
        paras.append(_p("Источник: " + src, size=13, color="666666"))
    if note:
        paras.append(_p(note, size=14, italic=True, color="555555"))
    return paras or [_p(empty)]


