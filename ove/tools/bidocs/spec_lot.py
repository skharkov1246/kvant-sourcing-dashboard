def _summary(lot: int, items: list) -> list:
    out = [c.h1("3. Сводные показатели по лоту")]
    fields = {it["n"]: _fields(lot, it) for it in items}
    areas = {it["area"] for it in items}
    n_key = sum(1 for it in items if it.get("key"))
    statuses = {}
    for it in items:
        statuses[it.get("status") or DASH] = statuses.get(it.get("status") or DASH, 0) + 1
    n_qty = sum(1 for it in items if not _is_uncertain_qty(it.get("qty")))
    n_dims = sum(1 for it in items if _has(fields[it["n"]]["dims"]))
    n_pow = sum(1 for it in items if _has(fields[it["n"]]["power"]))
    rows = [
        ("Позиций в спецификации", f"{len(items)} (участков — {len(areas)})"),
        ("Ключевые позиции (основное оборудование)", str(n_key)),
        ("Распределение по статусам поставки",
         "; ".join(f"{k} — {v}" for k, v in sorted(statuses.items(), key=lambda kv: -kv[1]))),
        ("Количество задано", f"{n_qty} из {len(items)} позиций; по остальным — уточняется на стадии ОТР и по ТКП"),
        ("Габариты или масса заданы", f"{n_dims} из {len(items)} позиций; по остальным — по ТКП изготовителей"),
        ("Мощность электроприёмников задана", f"{n_pow} из {len(items)} позиций"),
    ]
    contrib, total = [], 0.0
    for it in items:
        val, supp = fields[it["n"]]["power"]
        p = _kw(val) if val else (_kw(supp[0][0]) if supp else None)
        n = _num_int(it.get("qty"))
        if p is not None and n:
            contrib.append(f"{it['name']} — {n} × {_fmt(p)} кВт")
            total += p * n
    if contrib:
        rows.append(("Установленная мощность по позициям с единичным значением",
                     f"≈{_fmt(total)} кВт: " + "; ".join(contrib)))
    out.append(c.kv(rows, widths=(4200, W_PAGE - 4200)))
    if contrib:
        out.append(c.note("Суммирование выполнено только по позициям, для которых задано одно значение мощности "
                          "и целое количество единиц; позиции с диапазоном мощности и без данных в сумму не "
                          "входят. Полная таблица электроприёмников лота сводится в документе по "
                          "электроснабжению после получения ТКП."))
    else:
        out.append(c.note("Единичных значений мощности, пригодных для суммирования, в исходных данных по "
                          "позициям лота нет; таблица электроприёмников сводится в документе по "
                          "электроснабжению по данным ТКП."))
    return out


