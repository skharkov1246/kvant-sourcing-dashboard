def _open(lot: int, items: list, secs: list) -> list:
    out = [c.h1("6. Открытые позиции")]
    out.append(c.para("Перечень вопросов, определяемых на стадии Базового инжиниринга и по результатам "
                      "запроса ТКП; до их закрытия соответствующие графы спецификации носят предварительный "
                      "характер."))
    seen = set()
    for s in secs:
        for o in (s or {}).get("open") or []:
            t = re.sub(r"\s*—\s*определяется на стадии БИ\.?$", "", _clean(str(o)))
            key = re.sub(r"\W+", " ", t.lower())[:32]
            if t and key not in seen:
                seen.add(key)
                out.append(c.open_item(t))
    fields = {it["n"]: _fields(lot, it) for it in items}
    unsure = [it["name"] for it in items if _is_uncertain_qty(it.get("qty"))]
    if unsure:
        out.append(c.open_item("Количество единиц по позициям: " + "; ".join(_lower(s) for s in unsure)
                               + " — по компоновке и балансам БИ, ТКП изготовителей."))
    no_dims = [it for it in items if not _has(fields[it["n"]]["dims"])]
    if no_dims:
        out.append(c.open_item(f"Габариты и масса по {len(no_dims)} позициям из {len(items)} "
                               "(в исходных данных не заданы) — по ТКП изготовителей; массы самых тяжёлых "
                               "неразъёмных частей — в требованиях к монтажу."))
    no_pow = [it for it in items if not _has(fields[it["n"]]["power"])]
    if no_pow:
        out.append(c.open_item(f"Установленная мощность электроприёмников по {len(no_pow)} позициям из "
                               f"{len(items)} — по ТКП; сводная таблица электроприёмников — в документе по "
                               "электроснабжению."))
    out.append(c.open_item("Итоговая редакция спецификации (характеристики, габариты, массы, энергопотребление "
                           "по всем позициям) — после получения бюджетных ТКП не менее чем от 2–3 изготовителей "
                           "на каждую позицию основного оборудования."))
    return out


# ------------------------------------------------------------------ сборка

DOC_ORDER = ["ПЗ", "PFD", "НО", "ЭЧ", "ОЛ", "ДЦ", "МТ", "ЭС", "LL", "СТ"]


def _related(lot: int, code: str) -> list:
    rows = [r for r in c.df.register() if r.get("lot") == lot and r["code"] != code]
    out = []
    for suf in DOC_ORDER:
        out += [r for r in rows if r["code"].endswith("-" + suf)]
    return out


def build(row: dict) -> Path:
    lot = int(row.get("lot") or 0)
    items = _ordered(c.equipment(lot), lot)
    for n, it in enumerate(items, 1):
        it["n"] = n
    lotinfo = next((l for l in c.load("lots")["lots"] if l.get("id") == lot), {})
    docs = _related(lot, row["code"])
    sec = c.bi_section(lot, LIST_RE)
    iface = c.bi_section(lot, IFACE_RE[lot]) if lot in IFACE_RE else None
    spec_sec = c.bi_section(lot, SPEC_RE[lot]) if lot in SPEC_RE else None
    adjacent = [it for it in c.equipment(0) if it.get("pos") in ADJACENT_POS.get(lot, [])]

    body = []
    body += _intro(lot, items, lotinfo, docs)
    body += _spec(lot, items)
    body += _summary(lot, items)
    body += _composition(lot, sec, spec_sec, docs)
    body += _boundary(lot, items, adjacent, iface, lotinfo)
    body += _open(lot, items, [sec, spec_sec])
    return c.write_docx(c.out_path(row), body, landscape=True)
