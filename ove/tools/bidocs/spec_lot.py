def _ordered(items: list, lot: int) -> list:
    order = AREA_ORDER.get(lot, [])
    seen = []
    for it in items:
        if it["area"] not in seen:
            seen.append(it["area"])
    rank = {a: (order.index(a) if a in order else len(order) + seen.index(a)) for a in seen}
    return sorted(items, key=lambda it: rank[it["area"]])


