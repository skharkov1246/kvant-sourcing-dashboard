def _pl(n: int, one: str, few: str, many: str) -> str:
    """Согласование существительного с числом: 1 набор, 2 набора, 5 наборов."""
    n = abs(int(n))
    if n % 100 in range(11, 15):
        return many
    return {1: one, 2: few, 3: few, 4: few}.get(n % 10, many)


def _clean(t: str) -> str:
    t = str(t or "")
    for pat, rep in CLEAN:
        t = re.sub(pat, rep, t)
    return t.strip(" ;")


def _rows(xml: str, *, header: bool) -> str:
    """Строки таблицы не разрываются между листами; шапка повторяется на каждом листе."""
    xml = xml.replace("<w:tr>", "<w:tr><w:trPr><w:cantSplit/></w:trPr>")
    if header:
        xml = xml.replace("<w:trPr><w:cantSplit/></w:trPr>",
                          "<w:trPr><w:cantSplit/><w:tblHeader/></w:trPr>", 1)
    return xml


