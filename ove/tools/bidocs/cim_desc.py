# --------------------------------------------------------------- сборка

def build(row: dict) -> Path:
    files = _files(row)
    if not files:
        raise ValueError(f"{row['code']}: файлы обмена IFC не найдены")
    body = []
    body += _intro(files)
    body += _status()
    body += _composition(files)
    body += _lod(files)
    body += _env()
    body += _quality(files)
    body += _beyond()
    body += _open_positions()
    return c.write_docx(c.out_path(row), body)
