# ------------------------------------------------------------ разбор файлов IFC

def _unescape(s: str) -> str:
    """Строки ISO-10303-21: \\X2\\04..\\X0\\ — кодировка не-ASCII символов в файле IFC."""
    def rep(m):
        hexs = m.group(1)
        return "".join(chr(int(hexs[i:i + 4], 16)) for i in range(0, len(hexs), 4))
    return re.sub(r"\\X2\\([0-9A-Fa-f]+)\\X0\\", rep, s)


def _ifc_stats(path: Path) -> dict:
    """Счётчики одного файла обмена: типы, классы, габаритные тела, атрибуты, схема."""
    text = path.read_text(encoding="utf-8", errors="replace")
    ents = Counter(re.findall(r"^#\d+=([A-Z0-9_]+)\(", text, re.M))
    classes = Counter({k: v for k, v in ents.items() if k.endswith("TYPE") and k.startswith("IFC")})
    attrs = Counter(_unescape(n) for n in re.findall(r"IFCPROPERTYSINGLEVALUE\('([^']*)'", text))
    schema = re.search(r"FILE_SCHEMA\(\('([^']+)'\)\)", text)
    return {
        "name": path.name,
        "bytes": path.stat().st_size,
        "kb": round(path.stat().st_size / 1024),
        "types": sum(classes.values()),
        "entities": sum(ents.values()),
        "bodies": ents.get("IFCREPRESENTATIONMAP", 0),
        "psets": ents.get("IFCPROPERTYSET", 0),
        "props": ents.get("IFCPROPERTYSINGLEVALUE", 0),
        "classes": classes,
        "attrs": attrs,
        "schema": schema.group(1) if schema else "IFC4",
    }


def _files(row: dict) -> list:
    out = []
    for rel in row.get("sources") or []:
        p = c.PUBLIC / rel
        if p.exists():
            out.append(_ifc_stats(p))
    return out


def _cls_name(cls: str) -> str:
    """IFCTANKTYPE → IfcTankType."""
    for k in IFC_CLASS:
        if k.upper() == cls:
            return k
    return cls.title().replace("Ifc", "Ifc")


