def _eq(name_re: str) -> dict:
    rx = re.compile(name_re, re.I)
    for it in c.equipment(LOT):
        if rx.search(it.get("name", "")):
            return it
    return {}


def _bi_item(label_re: str, sec_re: str | None = None) -> dict:
    rx = re.compile(label_re, re.I)
    for s in c.bi_sections(LOT):
        if sec_re and not re.search(sec_re, s.get("id", ""), re.I):
            continue
        for i in s.get("items") or []:
            if rx.search(i.get("label", "")):
                return i
    return {}


def _calc_block(bid: str) -> dict:
    for b in c.load("calc").get("blocks", []):
        if b.get("id") == bid:
            return b
    return {}


def _zak(zid: str) -> dict:
    for it in c.load("zakladki").get("items", []):
        if it.get("id") == zid:
            return it
    return {}


def _reg_code(tz_prefix: str, lot: int = LOT) -> str:
    """Обозначение документа выпуска по пункту ТЗ (для перекрёстных ссылок)."""
    for r in c.df.register():
        if r.get("lot") == lot and str(r.get("tz", "")).startswith(tz_prefix):
            return r["code"]
    return ""


# --------------------------------------------------------------- кирпичи

def P(t):
    return c.para(t)


def _lc(s: str) -> str:
    """Первая буква строчная (для вставки фразы базы в середину предложения)."""
    s = _norm(s)
    return s[:1].lower() + s[1:] if s else s


def _norm(s: str) -> str:
    """Единое написание марок из базы (кириллическое «РЕ500» → PE500)."""
    return (s or "").replace("РЕ500", "PE500")


def _strip(s: str, prefix_re: str) -> str:
    """Снять повторяющий заголовок префикс значения базы («Производительность 10–16 т/ч» → «10–16 т/ч»)."""
    return re.sub(prefix_re, "", _norm(s), count=1, flags=re.I).strip()


