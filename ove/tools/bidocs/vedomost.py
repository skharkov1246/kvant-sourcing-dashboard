        d = seen[s]
        lots = ", ".join(d["lots"])
        lots = lots if lots == "общий" else f"№ {lots}"
        body.append([s, d["title"], lots, d["n"],
                     ", ".join(str(x) for x in sorted(d["stages"]))])
