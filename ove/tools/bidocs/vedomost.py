def _suffix(code: str) -> str:
    parts = code.split("-")
    return "-".join(parts[3:]) if len(parts) > 3 else parts[-1]


def _tz(row: dict) -> str:
    """Пункты состава БИ без пояснения в скобках: «D-01…D-11 (…)» → «D-01…D-11»."""
    return re.sub(r"\s*\([^()]*\)\s*$", "", str(row.get("tz") or "—")).strip()


def _sheets(row: dict) -> int:
    return len(row.get("sheets") or row.get("sources") or []) or 1


def _kind(row: dict) -> str:
    kind = row.get("kind", "text")
    if kind == "sheet":
        n = _sheets(row)
        return f"Графические листы, {n} л." if n > 1 else "Графический лист"
    if kind == "album":
        return "Текстовый документ (альбом)"
    return "Текстовый документ"


def _name(row: dict) -> str:
    t = row["title"]
    sub = row.get("subtitle")
    if sub:
        t = f"{t} — {sub[0].lower()}{sub[1:]}"
    return t


def _lot_title(lot: int) -> str:
    return "Документы, общие по комплексу" if not lot else f"Лот №{lot} «{c.LOTS[lot]}»"


