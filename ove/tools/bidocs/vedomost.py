# --------------------------------------------------------------- сборка

def build(row: dict) -> Path:
    rows = _register()
    if not rows:
        raise ValueError(f"{row['code']}: реестр выпуска пуст")
    done = _released(row["code"])

    body = []
    body += _intro(rows, done)
    body += _codes(rows)
    body += _stages(rows, done)
    body += _lot_tables(rows, done)
    body += _summary(rows, done)
    body += _revisions()
    body += _open_positions(rows, done)
    return c.write_docx(c.out_path(row), body, landscape=True)
