def _norms(secs: list) -> list:
    """Нормативная база: перечень документов из разделов базы решений по лоту."""
    seen, rows = [], []
    for s in secs:
        for g in s.get("gost") or []:
            doc = _clean(g.get("doc"))
            if doc and doc not in seen:
                seen.append(doc)
                rows.append([doc, _clean(g.get("what"))])
    if not rows:
        return []
    return [_h2("1.3 Нормативная база расчёта нагрузок"),
            _simple([("Документ", 2700), ("Область применения в расчёте", 6654)], rows)]


