def _related(lot: int, code: str) -> list:
    """Документы выпуска по тому же лоту, на которые ссылается настоящий документ."""
    keep = ("-КР", "-СО", "-МТ", "-ОЛ", "-ПЗ")
    return [r for r in c.df.register()
            if r.get("lot") == lot and r["code"] != code and r["code"].endswith(keep)]


def build(row: dict) -> Path:
    lot = int(row.get("lot") or 0)
    secs = [s for s in c.bi_sections(lot)
            if re.search(SEC_RE, s.get("id", "") + " " + s.get("title", ""), re.I)]
    if lot in EXTRA_SEC:
        extra = c.bi_section(lot, EXTRA_SEC[lot])
        if extra and extra not in secs:
            secs.append(extra)
    items = c.equipment(lot)
    docs = _related(lot, row["code"])

    body = []
    body += _intro(lot, docs)
    body += _norms(secs)
    body += _climate(lot)
    body += _vedomost(lot, items)
    body += _other(lot)
    body += _summary(lot)
    body += _dynamics(lot)
    body += _civil(lot)
    body += _tkp()
    body += _node_table()
    body += _open_section(lot, secs)
    return c.write_docx(c.out_path(row), body)
