def fmt(x, nd=1):
    s = f"{x:,.{nd}f}".replace(",", " ").replace(".", ",")
    return s


def check(what, ours, idv, src, *, unit="", verdict=None, comment=""):
    dev = (ours - idv) / idv * 100 if idv else 0.0
    if verdict is None:
        verdict = "ok" if abs(dev) <= 1.5 else ("warn" if abs(dev) <= 6 else "question")
    return {"what": what, "ours": ours, "idv": idv, "unit": unit,
            "dev": round(dev, 2), "verdict": verdict, "src": src, "comment": comment}


def block(bid, lot, title, inputs, steps, checks, concl):
    blocks.append({"id": bid, "lot": lot, "title": title, "inputs": inputs,
                   "steps": steps, "checks": checks, "concl": concl})


