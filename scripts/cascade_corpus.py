def soffice(каталог: Path, вход: str, цель: str, фильтр: str = "") -> None:
    cmd = ["soffice", "--headless", f"-env:UserInstallation=file://{каталог}/.lo"]
    if фильтр:
        cmd.append(f"--infilter={фильтр}")
    cmd += ["--convert-to", цель, "--outdir", str(каталог), str(каталог / вход)]
    subprocess.run(cmd, capture_output=True, timeout=180, check=False)


def собрать(каталог: Path, кп: str = КП) -> list[str]:
    """Корпус в каталог. Возвращает пропущенные форматы с причиной."""
    (каталог / "kp.html").write_text(кп, encoding="utf-8")
    пропущено: list[str] = []
    if not shutil.which("soffice"):
        return ["все офисные форматы: нет soffice"]
    soffice(каталог, "kp.html", "odt")
    soffice(каталог, "kp.html", "pdf")
    for цель in ("xlsx", "ods", "xls"):
        soffice(каталог, "kp.html", цель, "HTML (StarCalc)")
    soffice(каталог, "kp.odt", "docx:MS Word 2007 XML")
    soffice(каталог, "kp.odt", "doc:MS Word 97")
    soffice(каталог, "kp.odt", "rtf:Rich Text Format")
    if (каталог / "kp.xlsx").exists():
        m = MIMEMultipart()
        m["From"], m["To"], m["Subject"] = "snab@primer.test", "z@primer-kvant.test", "КП"
        m.attach(MIMEText("Предложение во вложении. Условия поставки: DAP Москва.", "plain", "utf-8"))
        a = MIMEApplication((каталог / "kp.xlsx").read_bytes(), Name="kp.xlsx")
        a["Content-Disposition"] = 'attachment; filename="kp.xlsx"'
        m.attach(a)
        (каталог / "kp.eml").write_bytes(m.as_bytes())
    if (каталог / "kp.docx").exists():
        with zipfile.ZipFile(каталог / "kp.zip", "w", zipfile.ZIP_DEFLATED) as z:
            z.writestr("pismo.txt", "Здравствуйте, КП во вложении")
            z.write(каталог / "kp.docx", "kp.docx")
    if shutil.which("7z") and (каталог / "kp.pdf").exists():
        subprocess.run(["7z", "a", "-bd", str(каталог / "kp.7z"), str(каталог / "kp.pdf")],
                       capture_output=True, timeout=60, check=False)
    else:
        пропущено.append("7z: нет архиватора 7z")
    return пропущено


def прочитать(indexer, b: bytes, каскад: bool, правка: bool | None = None) -> dict:
    """правка — включить обе правки цены (None — как в окружении)."""
    indexer.КАСКАД = каскад
    rec: dict = {"file_id": "корпус", "side": None}
    строки, текст, отказ = indexer.читать(b, indexer.подвид(b), rec)
    как = {} if правка is None else {"словарь_v2": правка, "без_шапки": правка}
    позиции = indexer.items_from_rows(строки, **как) if строки else []
    цены = [float(п["_цена"]["price"]) for п in позиции if п.get("_цена")]
    суммы = [float(п["_цена"]["total"]) for п in позиции
             if п.get("_цена") and п["_цена"].get("total")]
    кол = [float(п["qty"]) for п in позиции if п.get("qty") is not None]
    return {"строк": len(строки), "текст": len(текст), "цены": цены, "кол": кол,
            "суммы": суммы,
            "отказ": отказ, "путь": rec.get("read_chain") or ""}


def сравнить_правку(indexer, корень: Path) -> tuple[list[str], list[str]]:
    """Без правки цены против правки — на тех же байтах, обоими читателями."""
    провалы: list[str] = []
    пропущено: list[str] = []
    print("\nПРАВКА ЦЕНЫ: строк цены без правки → с правкой (прежний читатель · каскад)")
    print(f"{'вариант':11s} {'формат':6s} | {'прежний':9s} | {'каскад':9s}")
    итог = {"без": 0, "с": 0, "клеток": 0, "хуже": 0, "чужих_без": 0, "чужих_с": 0}
    for имя, кп in ВАРИАНТЫ_ЦЕНЫ.items():
        каталог = корень / имя
        каталог.mkdir(parents=True, exist_ok=True)
        пропущено += [f"{имя}: {п}" for п in собрать(каталог, кп)]
        for файл in sorted(каталог.glob("kp.*")):
            b = файл.read_bytes()
            ф = файл.suffix[1:]
            клетки = []
            for каскад in (False, True):
                без = прочитать(indexer, b, каскад, правка=False)
                с = прочитать(indexer, b, каскад, правка=True)
                клетки.append(f"{len(без['цены']):2d} → {len(с['цены']):2d}")
                итог["без"] += len(без["цены"])
                итог["с"] += len(с["цены"])
                итог["клеток"] += 1
                кто = "каскад" if каскад else "прежний"
                if len(с["цены"]) < len(без["цены"]):
                    итог["хуже"] += 1
                    провалы.append(f"{имя}/{ф}/{кто}: с правкой цен меньше "
                                   f"({len(с['цены'])} против {len(без['цены'])})")
                чужие = [ц for ц in с["цены"] if ц not in ЦЕНЫ]
                итог["чужих_без"] += sum(1 for ц in без["цены"] if ц not in ЦЕНЫ)
                итог["чужих_с"] += len(чужие)
                if чужие:
                    провалы.append(f"{имя}/{ф}/{кто}: неправдоподобные цены {чужие[:4]}")
                if [к for к in с["кол"] if к not in КОЛИЧЕСТВА]:
                    провалы.append(f"{имя}/{ф}/{кто}: неправдоподобные количества {с['кол'][:4]}")
                if [x for x in с["суммы"] if x not in СУММЫ]:
                    провалы.append(f"{имя}/{ф}/{кто}: сумма строки не из корпуса (налог?)"
                                   f" {с['суммы'][:4]}")
                if ф in ("xlsx", "ods") and с["строк"] and not с["цены"]:
                    провалы.append(f"{имя}/{ф}/{кто}: с правкой у книги нет ни одной цены")
            print(f"{имя:11s} {ф:6s} | {клетки[0]:9s} | {клетки[1]:9s}")
    print(f"итого по клеткам ({итог['клеток']}): строк цены {итог['без']} → {итог['с']},"
          f" клеток, где с правкой хуже: {итог['хуже']};"
          f" цен не из корпуса (с НДС, сумма, номер) {итог['чужих_без']} → {итог['чужих_с']}")
    return провалы, пропущено


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--keep", help="оставить корпус в этом каталоге")
    ap.add_argument("--only-base", action="store_true", help="только каскад против прежнего")
    ap.add_argument("--only-price", action="store_true", help="только правка цены")
    арг = ap.parse_args()
    import indexer
    каталог = Path(арг.keep) if арг.keep else Path(tempfile.mkdtemp(prefix="korpus-"))
    каталог.mkdir(parents=True, exist_ok=True)
    try:
        провалы: list[str] = []
        пропущено: list[str] = []
        if not арг.only_price:
            пропущено, провалы = сравнить_каскад(indexer, каталог / "base")
        if not арг.only_base:
            п, пр = сравнить_правку(indexer, каталог / "price")
            провалы += п
            пропущено += пр
        for п in sorted(set(пропущено)):
            print(f"  пропущено — {п}")
        if провалы:
            print("\nПРОВАЛЫ:")
            for п in провалы:
                print(f"  {п}")
            return 1
        print("\nкаскад не хуже прежнего пути, правка цены не хуже прежнего правила ни в"
              " одной клетке, цены и количества правдоподобны")
        return 0
    finally:
        if not арг.keep:
            shutil.rmtree(каталог, ignore_errors=True)


def сравнить_каскад(indexer, каталог: Path) -> tuple[list[str], list[str]]:
    """Прежний раздел: каскад чтения против прежней таблицы стратегий."""
    каталог.mkdir(parents=True, exist_ok=True)
    пропущено = собрать(каталог)
    провалы: list[str] = []
    print(f"{'формат':6s} | {'прежний: строк/цен':18s} | {'каскад: строк/цен':17s} | путь каскада")
    for файл in sorted(каталог.glob("kp.*")):
        b = файл.read_bytes()
        стар, нов = прочитать(indexer, b, False), прочитать(indexer, b, True)
        ф = файл.suffix[1:]
        print(f"{ф:6s} | {стар['строк']:5d} / {len(стар['цены']):2d}        | "
              f"{нов['строк']:5d} / {len(нов['цены']):2d}       | {нов['путь'][:60]}")
        if len(нов["цены"]) < len(стар["цены"]):
            провалы.append(f"{ф}: у каскада цен меньше ({len(нов['цены'])} против {len(стар['цены'])})")
        if not нов["цены"] and not нов["текст"]:
            провалы.append(f"{ф}: каскад не дал ни цен, ни текста ({нов['отказ'][:60]})")
        чужие = [ц for ц in нов["цены"] if ц not in ЦЕНЫ]
        if чужие:
            провалы.append(f"{ф}: неправдоподобные цены {чужие[:4]}")
        if [к for к in нов["кол"] if к not in КОЛИЧЕСТВА]:
            провалы.append(f"{ф}: неправдоподобные количества {нов['кол'][:4]}")
    return пропущено, провалы


