def _деньги(x: float) -> str:
    return f"{x:,.2f}".replace(",", " ").replace(".", ",")


def _кп(шапка: list[str] | None, строка) -> str:
    """То же КП с другой шапкой. строка(№, имя, кол, цена) → ячейки."""
    тело = []
    if шапка:
        тело.append("<tr>" + "".join(f"<td>{c}</td>" for c in шапка) + "</tr>")
    for i, (имя, кол, цена) in enumerate(ПОЗИЦИИ, 1):
        тело.append("<tr>" + "".join(f"<td>{c}</td>" for c in строка(i, имя, кол, цена))
                    + "</tr>")
    return ("<html><head><meta charset=\"utf-8\"></head><body>\n"
            "<p>ООО «Техснаб-Пример». Кому: ООО «КВАНТ». Коммерческое предложение № 46</p>\n"
            "<table border=\"1\">\n" + "\n".join(тело) + "\n</table>\n"
            "<p>Условия поставки: DAP Москва. Оплата 30/70. Срок поставки 30 дней.</p>\n"
            "</body></html>\n")


