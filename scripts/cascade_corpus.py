def прочитать(indexer, b: bytes, каскад: bool, правка: bool | None = None) -> dict:
    """правка — включить обе правки цены (None — как в окружении)."""
    indexer.КАСКАД = каскад
    rec: dict = {"file_id": "корпус", "side": None}
    строки, текст, отказ = indexer.читать(b, indexer.подвид(b), rec)
    как = {} if правка is None else {"словарь_v2": правка, "без_шапки": правка}
    позиции = indexer.items_from_rows(строки, **как) if строки else []
    цены = [float(п["_цена"]["price"]) for п in позиции if п.get("_цена")]
    суммы = [float(п["_цена"]["total"]) for п in позиции
             if п.get("_цена") and п["_цена"].get("total")]
    кол = [float(п["qty"]) for п in позиции if п.get("qty") is not None]
    return {"строк": len(строки), "текст": len(текст), "цены": цены, "кол": кол,
            "суммы": суммы,
            "отказ": отказ, "путь": rec.get("read_chain") or ""}


def сравнить_правку(indexer, корень: Path) -> tuple[list[str], list[str]]:
    """Без правки цены против правки — на тех же байтах, обоими читателями."""
    провалы: list[str] = []
    пропущено: list[str] = []
    print("\nПРАВКА ЦЕНЫ: строк цены без правки → с правкой (прежний читатель · каскад)")
    print(f"{'вариант':11s} {'формат':6s} | {'прежний':9s} | {'каскад':9s}")
    итог = {"без": 0, "с": 0, "клеток": 0, "хуже": 0, "чужих_без": 0, "чужих_с": 0}
    for имя, кп in ВАРИАНТЫ_ЦЕНЫ.items():
        каталог = корень / имя
        каталог.mkdir(parents=True, exist_ok=True)
        пропущено += [f"{имя}: {п}" for п in собрать(каталог, кп)]
        for файл in sorted(каталог.glob("kp.*")):
            b = файл.read_bytes()
            ф = файл.suffix[1:]
            клетки = []
            for каскад in (False, True):
                без = прочитать(indexer, b, каскад, правка=False)
                с = прочитать(indexer, b, каскад, правка=True)
                клетки.append(f"{len(без['цены']):2d} → {len(с['цены']):2d}")
                итог["без"] += len(без["цены"])
                итог["с"] += len(с["цены"])
                итог["клеток"] += 1
                кто = "каскад" if каскад else "прежний"
                if len(с["цены"]) < len(без["цены"]):
                    итог["хуже"] += 1
                    провалы.append(f"{имя}/{ф}/{кто}: с правкой цен меньше "
                                   f"({len(с['цены'])} против {len(без['цены'])})")
                чужие = [ц for ц in с["цены"] if ц not in ЦЕНЫ]
                итог["чужих_без"] += sum(1 for ц in без["цены"] if ц not in ЦЕНЫ)
                итог["чужих_с"] += len(чужие)
                if чужие:
                    провалы.append(f"{имя}/{ф}/{кто}: неправдоподобные цены {чужие[:4]}")
                if [к for к in с["кол"] if к not in КОЛИЧЕСТВА]:
                    провалы.append(f"{имя}/{ф}/{кто}: неправдоподобные количества {с['кол'][:4]}")
                if [x for x in с["суммы"] if x not in СУММЫ]:
                    провалы.append(f"{имя}/{ф}/{кто}: сумма строки не из корпуса (налог?)"
                                   f" {с['суммы'][:4]}")
                if ф in ("xlsx", "ods") and с["строк"] and not с["цены"]:
                    провалы.append(f"{имя}/{ф}/{кто}: с правкой у книги нет ни одной цены")
            print(f"{имя:11s} {ф:6s} | {клетки[0]:9s} | {клетки[1]:9s}")
    print(f"итого по клеткам ({итог['клеток']}): строк цены {итог['без']} → {итог['с']},"
          f" клеток, где с правкой хуже: {итог['хуже']};"
          f" цен не из корпуса (с НДС, сумма, номер) {итог['чужих_без']} → {итог['чужих_с']}")
    return провалы, пропущено


