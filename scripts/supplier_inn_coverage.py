#!/usr/bin/env python3
"""Сколько компаний-поставщиков имеют ИНН или налоговый номер в портале.

ЗАЧЕМ. Распоряжение владельца 20.09.2026: компании проверять по ИНН или
TaxNumber, а чего нет в Bitrix — завести. Прежде чем заводить, надо знать,
скольких не хватает; прежде чем менять правило сведения — знать, на что его
опирать. Сейчас сведение опознаёт компанию доменом и именем, то есть косвенно:
домен ПРЕДПОЛАГАЕТ тождество юрлица, ИНН его ДОКАЗЫВАЕТ.

ЧЕМ ЭТО ВАЖНЕЕ ПРОЧЕГО. Правило сведения сливает две карточки портала с общим
сайтом, не спрашивая правовую форму. Группа из нескольких юрлиц под одним
доменом склеится в одну сущность и получит один вечный номер — а это запрет
смешивать юрлица (ТЗ §1.12). ИНН этот вопрос закрывает: совпал — одно лицо,
разошёлся — разные, и спорить не о чем.

ГДЕ ЛЕЖИТ. Не на карточке компании, а в реквизитах: crm.requisite.list по
ENTITY_TYPE_ID=4. Поэтому ни один прежний замер его не видел — реквизиты в
репозитории не читались ни разу.

ИНОСТРАНЦЫ. У них ИНН нет и не будет, есть налоговый номер своей страны
(RQ_VAT_ID и прочее). Считаются отдельной строкой: «нет ИНН» у китайского
завода — это не пробел в данных, а свойство мира.

ЧТО ПЕЧАТАЕТ. Только числа. Ни одного ИНН, ни названия, ни номера карточки:
ИНН контрагентов — чувствительные данные (scripts/build_catalog.py их помечает,
build_index.py исключает из индекса), а репозиторий публичный
(CLAUDE.md, правило 17).

    BITRIX_WEBHOOK_URL=... python scripts/supplier_inn_coverage.py
"""
from __future__ import annotations

import collections
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

SPA_RFQ = 166
ПОЛЕ_ПОСТАВЩИКА = "ufCrm18Supplier"
ТИП_КОМПАНИЯ = 4

# Поля реквизитов, где может лежать налоговый номер. RQ_INN — российский ИНН,
# RQ_VAT_ID — номер плательщика НДС, он же налоговый номер иностранца.
ПОЛЯ_НОМЕРА = ("RQ_INN", "RQ_VAT_ID")
ЦИФРЫ = re.compile(r"\D")


def crm_id(v) -> int:
    s = str(v or "")
    if "_" in s:
        s = s.rsplit("_", 1)[1]
    return int(s) if s.isdigit() else 0


def вид_инн(значение: str) -> str:
    """Что это за номер по форме. Значение НЕ печатается, только его разряд.

    Российский ИНН — 10 цифр у юрлица, 12 у предпринимателя. Всё прочее
    непустое считаем налоговым номером иностранного государства: проверять его
    по формату нечем, у каждой страны своя.

    БУКВА В НОМЕРЕ СРАЗУ ДЕЛАЕТ ЕГО ИНОСТРАННЫМ, и проверка на неё стоит ПЕРЕД
    счётом цифр. Без этого китайский USCC «CN91310000MA1K35QX8H» после выброса
    букв даёт ровно двенадцать цифр и опознаётся как ИНН предпринимателя —
    поймано собственным пробником до первого прогона. Российский ИНН состоит
    только из цифр; разделители (пробел, дефис) допускаются и отбрасываются.
    """
    сырое = (значение or "").strip()
    if not сырое:
        return ""
    if re.search(r"[^\d\s.\-]", сырое):
        return "иностранный налоговый номер"
    ц = ЦИФРЫ.sub("", сырое)
    if len(ц) == 10:
        return "ИНН юрлица (10 цифр)"
    if len(ц) == 12:
        return "ИНН предпринимателя (12 цифр)"
    return "цифры, но не длина ИНН — проверить"


def main() -> int:
    url = os.environ.get("BITRIX_WEBHOOK_URL", "")
    if not url:
        print("нет переменной BITRIX_WEBHOOK_URL", file=sys.stderr)
        return 2
    from bitrix_client import BitrixClient

    client = BitrixClient(url)
    print("выгрузка карточек запросов (СП-166)…", flush=True)
    карточки = client.list_items(SPA_RFQ, select=["id", ПОЛЕ_ПОСТАВЩИКА])
    компании = sorted({crm_id(k.get(ПОЛЕ_ПОСТАВЩИКА)) for k in карточки} - {0})
    print(f"компаний-поставщиков: {len(компании)}")

    print("чтение реквизитов (crm.requisite.list)…", flush=True)
    номера: dict[int, list[str]] = collections.defaultdict(list)
    прочитано = 0
    for i in range(0, len(компании), 50):
        часть = компании[i:i + 50]
        строки = client.list_paged("crm.requisite.list", {
            "filter": {"ENTITY_TYPE_ID": ТИП_КОМПАНИЯ, "ENTITY_ID": часть},
            "select": ["ID", "ENTITY_ID", *ПОЛЯ_НОМЕРА]}) or []
        прочитано += len(строки)
        for r in строки:
            cid = crm_id(r.get("ENTITY_ID"))
            for поле in ПОЛЯ_НОМЕРА:
                v = (r.get(поле) or "").strip()
                if v:
                    номера[cid].append(v)

    print(f"строк реквизитов прочитано: {прочитано}")
    print(f"компаний с НЕПУСТЫМ номером: {len(номера)}")
    print("  (строк реквизитов больше: карточка реквизитов может быть заведена,\n   а поле номера в ней пустым — это и есть основной случай)")
    print()

    по_виду: collections.Counter[str] = collections.Counter()
    for cid in компании:
        виды = {вид_инн(v) for v in номера.get(cid, [])} - {""}
        по_виду["не заполнено ничего" if not виды else
                ("несколько разных номеров" if len(виды) > 1 else next(iter(виды)))] += 1

    print("ЧТО ЗАПОЛНЕНО У КОМПАНИЙ-ПОСТАВЩИКОВ")
    for вид, n in по_виду.most_common():
        доля = 100 * n / max(len(компании), 1)
        print(f"  {вид:34} {n:6}  ({доля:.1f} %)")

    # Главное: годится ли ИНН как ключ сведения.
    ключ: dict[str, set[int]] = collections.defaultdict(set)
    for cid, значения in номера.items():
        for v in значения:
            ц = ЦИФРЫ.sub("", v)
            if ц:
                ключ[ц].add(cid)
    общие = {номер: карточки for номер, карточки in ключ.items() if len(карточки) > 1}
    с_номером = len(номера)

    print()
    print("ГОДИТСЯ ЛИ НОМЕР КЛЮЧОМ СВЕДЕНИЯ")
    print(f"  компаний с номером:                    {с_номером}")
    print(f"  различных номеров:                     {len(ключ)}")
    print(f"  номеров, общих для нескольких карточек: {len(общие)} "
          f"(это доказанные задвоения портала)")
    print(f"  карточек в них:                        "
          f"{sum(len(карточки) for карточки in общие.values())}")
    несколько = sum(1 for cid in номера if len({ЦИФРЫ.sub('', v) for v in номера[cid]}) > 1)
    print(f"  карточек с ДВУМЯ и более разными номерами: {несколько} "
          "(одна карточка на несколько юрлиц — разбирать человеком)")
    print()
    print("Доказанные задвоения сравнивать с 456, которые сведение схлопнуло по")
    print("домену и имени: расхождение покажет, где домен слил лишнее.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
