#!/usr/bin/env python3
"""Точность разбора обозначений машин: сверка правила с ручным эталоном.

ЗАЧЕМ. Правило `library/machine_kind.py` решает по тексту обозначения, машина
это или деталь, какому направлению принадлежит и какие машины названы. От его
ответа зависит клетка «Машина» счётчика цепочки (`data/chain_coverage.json`), по
которой берётся следующая работа, и имена записей в реестре `dict/machine.json`.
Проверять такое правило на глаз нельзя: выборка из двадцати строк покажет что
угодно.

ЧТО СЧИТАЕТСЯ. Эталон — `data/machine_truth.json`: все значения поля `mach`
размечены руками по тексту, правилом разметка не пользовалась (CLAUDE.md,
правило 1). Правило запускается только по обозначению, ручная метка скрыта и
служит ответом.

ПОЧЕМУ СЧИТАЕТСЯ ИМЕННО ТАК. Первая редакция этого замера была зелёной на
правиле с ВОСЕМЬЮ воспроизведёнными дефектами (09.10.2026): дефекты нашла
независимая ревизия, а не замер. Разобрано, чем он был слеп, и каждая слепота
закрыта здесь:

  · точность считалась от числа ОТВЕТОВ, а не от эталона, и «правило смолчало»
    выпадало и из числителя, и из знаменателя. Воздержание было бесплатным:
    заставить правило молчать на трудном всегда выгоднее, чем ответить неверно.
    Теперь точность — это `совпало / всего`, а молчание — такое же расхождение,
    и оно называется поимённо;
  · негативы («не машина», «не опознать») — 134 строки из 296, 45 % метрики, и
    они даровые. Сводное число ими разводится, поэтому порогом держится
    ОТДЕЛЬНАЯ точность по строкам «машина» и «черновик» — по тем, от которых
    зависит клетка счётчика;
  · все обозначения весили одинаково, хотя эталон знает фактический вес каждого
    (поле «строк»). Ошибка на LM2500 и LM6000 — это половина строк базы и 0,7
    пункта невзвешенной метрики. Поэтому рядом считается ВЗВЕШЕННАЯ точность;
  · разбор на модели проверялся только там, где эталон сам положил ответ: 41
    строка из 296, и печаталось «100 %». Теперь поле «модели» есть у каждой
    машины и каждого черновика, и разбор проверяется на всех;
  · «объяснённые расхождения» были заведены по ПАРЕ метка→ответ, и любая строка
    с той же парой тихо попадала под освобождение. Ключ — обозначение.

ЧТО ЭТОТ ЗАМЕР ДЕРЖИТ, А ЧТО — ТЕСТЫ. Замер судит правило на ЖИВОМ источнике:
296 обозначений, 11 005 строк. Дефект, который живой источник не задевает, он не
увидит — и это не изъян, а граница. Проверено подменой правила (09.10.2026):
возврат замыкающего \b семействам ГТУ роняет взвешенную точность с 100 % до
31,1 % и валит гейт — потому что LM2500 и LM6000 это половина строк базы. А
дефекты «косая рвёт код», «вид по целой строке» и «вольты как модель» замер НЕ
ловит: в источнике нет ни «Multitec V50/8A-4.1» без хвоста, ни «Электродвигатель,
Шкаф управления», ни «Электродвигатель 380 В». Их держит tests/test_machine_kind.py
придуманными входами той же формы. Ссылаться на одно из двух как на доказательство
исправности правила нельзя: нужны оба.

ЧЕГО ЭТОТ ЗАМЕР НЕ ВИДИТ. В поле `mach` базы ГТУ нет ни одного обозначения
горно-шахтных машин и поршневых компрессоров, поэтому по направлениям `gsho` и
`recip` эталон не говорит ничего: измеренная точность относится к пяти
направлениям из семи. Правило и не может вернуть эти два направления — в наборе
образцов их нет. Это печатается в выводе.

    python scripts/machine_segment_check.py
    python scripts/machine_segment_check.py --gate      # пороги гейта

Код возврата 1, если любое из чисел ниже порога.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from library import machine_kind as mk  # noqa: E402

ЭТАЛОН = ROOT / "data" / "machine_truth.json"

#: ПОРОГИ ГЕЙТА — ОДНИМ МЕСТОМ. Прежде порог стоял в gate.yml (97) и в тесте
#: (98) по отдельности, и они уже разъехались (LESSONS, «одно правило в двух
#: местах»). Теперь и гейт, и тест запускают `--gate`.
ПОРОГИ = {
    "точность по машинам": 97.0,       # строки «машина» и «черновик» — кормят клетку
    "точность взвешенная": 97.0,       # то же, но весом строк базы
    "точность по эталону": 98.0,       # все 296 строк, справочно
    "охват": 97.0,                     # на скольких опознанных эталоном правило не смолчало
    "разбор моделей": 97.0,            # список машин совпал с эталоном
}

# ОБЪЯСНЁННЫЕ РАСХОЖДЕНИЯ — КЛЮЧ ЕСТЬ ОБОЗНАЧЕНИЕ, а не пара метка→ответ: по
# паре под освобождение тихо попадал целый класс ошибок, и список расхождений —
# единственное место, которое говорит, ЧТО сломалось, — оставался пустым.
# Пусто и должно быть пусто: признанная ошибка эталона правится в эталоне, а не
# глушится здесь. Сюда идёт только обозначение, честно двусмысленное по тексту,
# и только с причиной.
ОБЪЯСНЁННЫЕ: dict[str, str] = {}

КОРМЯТ_КЛЕТКУ = ("машина", "черновик")


def ключ(вид: str, напр: str) -> str:
    return f"{вид}|{напр or '—'}"


def ключи_моделей(лст) -> tuple[str, ...]:
    """Список моделей в сравнимом виде: регистр и знаки не считаются."""
    return tuple(sorted("".join(ch for ch in str(x).lower() if ch.isalnum())
                        for x in лст if str(x).strip()))


def доля(часть: float, целое: float) -> float:
    return 100.0 * часть / целое if целое else 0.0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gate", action="store_true", help="держать пороги ПОРОГИ")
    a = ap.parse_args()

    строки = json.loads(ЭТАЛОН.read_text(encoding="utf-8"))["строки"]
    всего = len(строки)
    вес_всего = sum(r["строк"] for r in строки)

    совпало = совпало_вес = 0
    кормят = кормят_совпало = кормят_вес = кормят_вес_совпало = 0
    опознано = смолчал = 0
    моделей_всего = моделей_совпало = 0
    объяснено: list[str] = []
    расхождения: list[tuple[str, str, str, int]] = []
    модели_мимо: list[str] = []
    по_виду: Counter = Counter()

    for r in строки:
        имя, вес = r["обозначение"], r["строк"]
        ждём = ключ(r["вид"], r.get("направление", ""))
        дал = mk.разобрать(имя)
        ответ = ключ(дал.вид, дал.направление)
        верно = ответ == ждём
        кормит = r["вид"] in КОРМЯТ_КЛЕТКУ

        if r["вид"] != "не опознать":
            опознано += 1
            if дал.вид == "не опознать":
                смолчал += 1

        if верно:
            совпало += 1
            совпало_вес += вес
        elif имя in ОБЪЯСНЁННЫЕ:
            объяснено.append(имя)
        else:
            расхождения.append((имя, ждём, ответ, вес))
            по_виду[(ждём, ответ)] += 1

        if кормит:
            кормят += 1
            кормят_вес += вес
            if верно:
                кормят_совпало += 1
                кормят_вес_совпало += вес
            # Разбор на модели проверяется только там, где эталон его знает —
            # то есть у машин и черновиков; у негативов моделей нет по смыслу.
            моделей_всего += 1
            if ключи_моделей(дал.модели) == ключи_моделей(r.get("модели") or ()):
                моделей_совпало += 1
            else:
                модели_мимо.append(f"{имя[:52]} → {дал.модели} (эталон "
                                   f"{tuple(r.get('модели') or ())})")

    числа = {
        "точность по машинам": доля(кормят_совпало, кормят),
        "точность взвешенная": доля(кормят_вес_совпало, кормят_вес),
        "точность по эталону": доля(совпало, всего),
        "охват": доля(опознано - смолчал, опознано),
        "разбор моделей": доля(моделей_совпало, моделей_всего),
    }

    print(f"эталон: {всего} обозначений, {вес_всего} строк базы; из них кормят клетку "
          f"«Машина» {кормят} обозначений ({кормят_вес} строк)")
    print(f"  точность по машинам   {числа['точность по машинам']:6.1f} %   "
          f"{кормят_совпало} из {кормят}  ← этим и держится клетка")
    print(f"  точность взвешенная   {числа['точность взвешенная']:6.1f} %   "
          f"{кормят_вес_совпало} из {кормят_вес} строк базы")
    print(f"  точность по эталону   {числа['точность по эталону']:6.1f} %   "
          f"{совпало} из {всего}  (45 % эталона — даровые негативы, справочно)")
    print(f"  охват                 {числа['охват']:6.1f} %   правило смолчало на "
          f"{смолчал} из {опознано} опознанных эталоном")
    print(f"  разбор моделей        {числа['разбор моделей']:6.1f} %   "
          f"{моделей_совпало} из {моделей_всего}")
    if объяснено:
        print(f"  объяснённых расхождений {len(объяснено)} (в точность НЕ идут): "
              + " · ".join(объяснено))

    if расхождения:
        print(f"\nрасхождения ({len(расхождения)}), по весу строк базы:")
        for имя, ж, о, вес in sorted(расхождения, key=lambda x: -x[3])[:20]:
            print(f"  {вес:>5} строк  {имя[:48]:<50} эталон {ж:<16} правило {о}")
        if len(расхождения) > 20:
            print(f"  … и ещё {len(расхождения) - 20}")
        print("  по парам:", " · ".join(f"{ж}→{о} {n}" for (ж, о), n in по_виду.most_common(8)))
    if модели_мимо:
        print(f"\nсписок моделей разошёлся ({len(модели_мимо)}):")
        for строка in модели_мимо[:12]:
            print(f"  {строка}")
        if len(модели_мимо) > 12:
            print(f"  … и ещё {len(модели_мимо) - 12}")

    # КЛЕТКИ СЧИТАЮТСЯ РОВНО ТЕМ ЖЕ ВЫРАЖЕНИЕМ, ЧТО У ПОТРЕБИТЕЛЯ
    # (scripts/build_dict.py: `for модель in (р.модели or (stem,))`), иначе
    # зелёный замер и реестр расходятся молча.
    клетки: dict[tuple[str, str], set[str]] = {}
    for r in строки:
        д = mk.разобрать(r["обозначение"])
        if д.вид not in КОРМЯТ_КЛЕТКУ or д.направление not in mk.НАПРАВЛЕНИЯ:
            continue
        имена = д.модели or (mk.основа(r["обозначение"]),)
        клетки.setdefault((д.направление, д.вид), set()).update(
            "".join(ch for ch in и.upper() if ch.isalnum()) for и in имена)
    print("\nразных машин по направлениям (как их посчитает реестр):")
    for напр in mk.НАПРАВЛЕНИЯ:
        м = len(клетки.get((напр, "машина"), ()))
        ч = len(клетки.get((напр, "черновик"), ())) 
        if м or ч:
            print(f"  {напр:<9} машина {м:>4} · черновик {ч:>3}")
    нет_в_эталоне = [с for с in mk.НАПРАВЛЕНИЯ
                     if not any(r.get("направление") == с for r in строки)]
    if нет_в_эталоне:
        print(f"  НЕ ПРОВЕРЕНО ВОВСЕ: {', '.join(нет_в_эталоне)} — в поле mach базы ГТУ "
              f"таких обозначений нет, и правило их вернуть не может; измеренные числа "
              f"относятся к {len(mk.НАПРАВЛЕНИЯ) - len(нет_в_эталоне)} направлениям из "
              f"{len(mk.НАПРАВЛЕНИЯ)}")

    if not a.gate:
        return 0
    плохо = [f"{к}: {числа[к]:.1f} % ниже порога {п}" for к, п in ПОРОГИ.items()
             if числа[к] < п]
    for строка in плохо:
        print(f"::error::{строка}")
    return 1 if плохо else 0


if __name__ == "__main__":
    raise SystemExit(main())
