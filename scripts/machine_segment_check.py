#!/usr/bin/env python3
"""Точность разметки машин: сверка правила с ручным эталоном.

ЗАЧЕМ. Правило `library/machine_kind.py` решает по тексту обозначения, машина
это или деталь и какому направлению она принадлежит. От его ответа зависит
клетка «Машина» счётчика цепочки (`data/chain_coverage.json`), по которой
берётся следующая работа. Проверять такое правило на глаз нельзя: выборка из
двадцати строк покажет что угодно.

ЧТО СЧИТАЕТСЯ. Эталон — `data/machine_truth.json`: все обозначения поля `mach`
размечены руками по тексту, правилом разметка не пользовалась (CLAUDE.md,
правило 1). Правило запускается только по обозначению, ручная метка скрыта и
служит ответом.

    охват    — на скольких обозначениях правило назвало вид (не «не опознать»)
    точность — на скольких из них вид И направление совпали с эталоном

    python scripts/machine_segment_check.py
    python scripts/machine_segment_check.py --min-precision 90 --min-coverage 90

Код возврата 1, если точность или охват ниже порога.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from library import machine_kind as mk  # noqa: E402

ЭТАЛОН = ROOT / "data" / "machine_truth.json"

# ОБЪЯСНЁННЫЕ РАСХОЖДЕНИЯ. Не всякое несовпадение — ошибка правила: бывает, что
# обозначение честно двусмысленно, и обе метки защищаемы. Такие пары держатся
# здесь закрытым списком с причиной и печатаются отдельной строкой — спрятать их
# в «совпало» значило бы подогнать точность под себя, а не измерить её.
ОБЪЯСНЁННЫЕ: dict[tuple[str, str], str] = {
    ("машина|pumps", "черновик|pumps"):
        "«Насос охлаждающей жидкости НТК Gilkes»: имя изготовителя правило "
        "моделью не считает, и это сознательная сдержанность — иначе моделью "
        "стал бы и «Solar Centaur», где названо только семейство. Цена "
        "сдержанности — одна строка в черновике вместо заполненной.",
}


def ключ(вид: str, напр: str) -> str:
    return f"{вид}|{напр or '—'}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-precision", type=float, default=0.0)
    ap.add_argument("--min-coverage", type=float, default=0.0)
    a = ap.parse_args()

    эт = json.loads(ЭТАЛОН.read_text(encoding="utf-8"))
    строки = эт["строки"]
    совпало = разошлось = объяснено = не_ответил = 0
    пары: Counter = Counter()
    примеры: dict[tuple[str, str], list[str]] = {}
    for r in строки:
        ждём = ключ(r["вид"], r.get("направление", ""))
        дал = mk.разобрать(r["обозначение"])
        ответ = ключ(дал.вид, дал.направление)
        if дал.вид == "не опознать" and r["вид"] != "не опознать":
            не_ответил += 1
            continue
        if ответ == ждём:
            совпало += 1
            continue
        if (ждём, ответ) in ОБЪЯСНЁННЫЕ:
            объяснено += 1
            continue
        разошлось += 1
        пары[(ждём, ответ)] += 1
        примеры.setdefault((ждём, ответ), []).append(r["обозначение"][:70])

    всего = len(строки)
    ответов = совпало + разошлось + объяснено
    # Объяснённые в точность НЕ идут: засчитывать их значило бы подгонять
    # измерение под себя. Они печатаются отдельным числом, с причиной в списке.
    точность = 100.0 * совпало / ответов if ответов else 0.0
    охват = 100.0 * ответов / всего if всего else 0.0
    print(f"эталон: {всего} обозначений")
    print(f"охват:    {охват:5.1f} %  ({ответов} ответов, {не_ответил} раз правило "
          f"не опознало то, что эталон опознал)")
    print(f"точность: {точность:5.1f} %  (совпало {совпало}, объяснённых расхождений "
          f"{объяснено}, расхождений {разошлось})")
    if пары:
        print("\nрасхождения (эталон → правило, счёт):")
        for (ж, о), n in пары.most_common():
            print(f"  {ж:<18} → {о:<18} {n:>3}   напр.: {примеры[(ж, о)][0]}")

    # Клетки цепочки по правилу — то, ради чего правило и писалось.
    # РАЗБОР СОСТАВНЫХ ОБОЗНАЧЕНИЙ — отдельное измерение. Эталон называет
    # настоящие модели у 44 обозначений («Taurus 70/70MD» — это две машины);
    # если правило их не разложит, реестр посчитает составную строку за машину.
    def ключи_моделей(лст) -> set[str]:
        return {"".join(ch for ch in str(x).lower() if ch.isalnum()) for x in лст if x}

    с_моделями = [r for r in строки if r.get("модели")]
    моделей_совпало = 0
    моделей_мимо: list[str] = []
    for r in с_моделями:
        дал = mk.разобрать(r["обозначение"])
        if ключи_моделей(дал.модели) == ключи_моделей(r["модели"]):
            моделей_совпало += 1
        else:
            моделей_мимо.append(f"{r['обозначение'][:50]} → {дал.модели} "
                                f"(эталон {tuple(r['модели'])})")
    if с_моделями:
        доля = 100.0 * моделей_совпало / len(с_моделями)
        print(f"\nразбор составных обозначений: {моделей_совпало} из {len(с_моделями)} "
              f"({доля:.1f} %)")
        for строка in моделей_мимо[:8]:
            print(f"  мимо: {строка}")

    # Клетка цепочки считает РАЗНЫЕ модели, а не обозначения: «Taurus 70,
    # Taurus 70MD» и «Taurus 70/70MD» называют одни и те же две машины.
    по_клетке: dict[tuple[str, str], set[str]] = {}
    for r in строки:
        д = mk.разобрать(r["обозначение"])
        if д.вид in ("машина", "черновик") and д.направление in mk.НАПРАВЛЕНИЯ:
            ключи = д.модели if (д.вид == "машина" and д.модели) else (r["обозначение"],)
            по_клетке.setdefault((д.направление, д.вид), set()).update(
                к.strip().casefold() for к in ключи)
    print("\nразных машин по направлениям (по правилу, составные разложены):")
    for напр in mk.НАПРАВЛЕНИЯ:
        м = len(по_клетке.get((напр, "машина"), ()))
        ч = len(по_клетке.get((напр, "черновик"), ()))
        if м or ч:
            print(f"  {напр:<9} машина {м:>4} · черновик {ч:>3}")

    плохо = False
    if с_моделями and моделей_совпало < len(с_моделями) and a.min_precision:
        print(f"::warning::составных обозначений разобрано не всё: "
              f"{len(с_моделями) - моделей_совпало} мимо")
    if a.min_precision and точность < a.min_precision:
        print(f"\n::error::точность {точность:.1f} % ниже порога {a.min_precision}")
        плохо = True
    if a.min_coverage and охват < a.min_coverage:
        print(f"::error::охват {охват:.1f} % ниже порога {a.min_coverage}")
        плохо = True
    return 1 if плохо else 0


if __name__ == "__main__":
    raise SystemExit(main())
