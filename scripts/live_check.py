#!/usr/bin/env python3
"""Живая сверка метрик: правка против прода на одних и тех же данных портала.

ЗАЧЕМ. 23.09.2026 в прод трижды ушли данные, которые разошлись с
действительностью, и каждый раз это видели двадцать сотрудников раньше, чем
разработчик:
  * #396 — столбец «Получено КП» пустой на живых данных: входящих писем в
    карточках ноль, а синтетика их содержала;
  * #397 — служебной записью задан номер 2, у которого нет ни одной карточки:
    «Аккаунт №2» оказался именем, а не номером;
  * #400 — 517 запросов робота легли на руководителя отдела вместо сорсеров:
    поле сделки «Head of sourcing» стояло в цепочке первым.
Гейт этого поймать не мог: он проверяет синтетику, а ошибка была в том, как
правило ведёт себя на живых данных. Эта сверка закрывает ровно этот разрыв.

КАК. Прод (main) и правка считаются `main.py --dry-run` на одном и том же
замороженном окне (по вчерашний день включительно), друг за другом. Затем
сравниваются два JSON. Проверок шесть, и каждая привязана к реальной ошибке:

  1. целостность каждой сборки: отдел + вне отдела = всего; сумма по сорсерам
     равна отделу;
  2. итог не зависит от правки: всего запросов до и после совпадает;
  3. ни один человек и ни одна графа («отдел», «вне отдела») не сдвинулись
     сверх заявленного в описании PR — поймала бы #400;
  4. ряд недельного графика не пуст на живых данных — поймала бы #396;
  5. служебная запись, заданная номером, действительно заводит карточки —
     поймала бы #397;
  6. нераспознанных исполнителей не стало больше.

ЗАЯВКА ОЖИДАНИЙ. Строки в описании PR (или во входе ручного запуска):
    ожидается: #76 -517
    ожидается: вне отдела -540
    ожидается: отдел +540
    ожидается: сорсеры +517
    ожидается: без изменений
«сорсеры» — групповая заявка на сумму сдвигов по людям, которые не заявлены
поимённо: правка вроде #401 законно раскладывает запросы по десятку человек, и
предсказать это поимённо нельзя. Но если больше половины группового сдвига
легло на одного человека, это провал — ровно так выглядела ошибка #400.
Сдвиг, который не заявлен, — провал. Заявленный сдвиг, которого нет или
который разошёлся с заявкой больше допуска, — тоже провал. Правило заставляет
предсказать эффект ДО того, как его увидишь: так ошибка #400 была бы видна
как «заявлено: сорсерам +517, получено: #76 +517».

ТОЛЬКО АГРЕГАТЫ (CLAUDE.md, правило 17): номера учётных записей и счётчики,
без имён — журнал Actions публичен.

    python scripts/live_check.py <каталог_прод> <каталог_правка>
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

ПРОВАЛ, ВНИМАНИЕ, ГОДНО = "ПРОВАЛ", "ВНИМАНИЕ", "ГОДНО"

# Шум между двумя прогонами: они читают живой портал с разницей в минуты, и
# карточку за это время могут переназначить. Всё, что меньше шума, сдвигом не
# считается.
ШУМ_АБС, ШУМ_ДОЛЯ = 3, 0.02
# Допуск на заявленный сдвиг.
ДОПУСК_АБС, ДОПУСК_ДОЛЯ = 10, 0.10

ЗАЯВКА = re.compile(r"ожидается\s*:\s*(#\d+|отдел|вне\s+отдела|сорсеры|без\s+изменений)"
                    r"\s*([+\-−–]\s*\d+)?", re.I)
# Групповой сдвиг больше этого числа не может лечь на одного человека больше
# чем наполовину — иначе это не раскладка по людям, а перенос на одного.
КОНЦЕНТРАЦИЯ_ОТ, КОНЦЕНТРАЦИЯ_ДОЛЯ = 50, 0.5


def шум(база: int) -> int:
    return max(ШУМ_АБС, round(abs(база) * ШУМ_ДОЛЯ))


def допуск(заявлено: int) -> int:
    return max(ДОПУСК_АБС, round(abs(заявлено) * ДОПУСК_ДОЛЯ))


def ожидания(текст: str | None) -> dict[str, int]:
    """Заявленные сдвиги из описания PR. «без изменений» даёт пустой словарь с
    отметкой, что заявка была: любой сдвиг тогда провал."""
    out: dict[str, int] = {}
    for m in ЗАЯВКА.finditer(текст or ""):
        ключ = re.sub(r"\s+", " ", m.group(1).lower())
        if ключ == "без изменений":
            out.setdefault("__заявлено__", 0)
            continue
        if not m.group(2):
            continue
        знак = -1 if m.group(2).strip()[0] in "-−–" else 1
        out[ключ] = знак * int(re.sub(r"\D", "", m.group(2)))
    return out


def загрузить(каталог: str | Path) -> dict:
    p = Path(каталог)
    if p.is_file():
        return json.loads(p.read_text(encoding="utf-8"))
    files = sorted(p.glob("metrics_*.json"))
    if len(files) != 1:
        raise SystemExit(f"в {p} ожидался ровно один metrics_*.json, найдено {len(files)}")
    return json.loads(files[0].read_text(encoding="utf-8"))


def _люди(m: dict) -> dict[str, int]:
    out = {f"#{s['id']}": int(s.get("c") or 0) for s in m.get("sourcersA") or []}
    k = m.get("kpi") or {}
    out["отдел"] = int(k.get("deptA") or 0)
    out["вне отдела"] = int(k.get("outside") or 0)
    return out


def _не_определён(m: dict) -> int:
    for x in (m.get("origin") or {}).get("resolvedHow") or []:
        if x.get("how") == "не определён":
            return int(x.get("n") or 0)
    return 0


def сверить(до: dict, после: dict, заявлено: dict[str, int],
            служебные_номерами: set[str]) -> list[tuple[str, str]]:
    итог: list[tuple[str, str]] = []

    # 1. целостность каждой сборки
    for имя, m in (("прод", до), ("правка", после)):
        k = m.get("kpi") or {}
        total, a, b = int(k.get("total") or 0), int(k.get("deptA") or 0), int(k.get("outside") or 0)
        сумма = sum(int(s.get("c") or 0) for s in m.get("sourcersA") or [])
        if a + b != total:
            итог.append((ПРОВАЛ, f"{имя}: отдел {a} + вне отдела {b} ≠ всего {total}"))
        elif сумма != a:
            итог.append((ПРОВАЛ, f"{имя}: сумма по сорсерам {сумма} ≠ отдел {a}"))
        else:
            итог.append((ГОДНО, f"{имя}: целостность сходится ({a} + {b} = {total})"))

    # 2. итог не зависит от правки
    t0 = int((до.get("kpi") or {}).get("total") or 0)
    t1 = int((после.get("kpi") or {}).get("total") or 0)
    if abs(t1 - t0) > шум(t0):
        итог.append((ПРОВАЛ, f"всего запросов: прод {t0}, правка {t1} — правка атрибуции не может "
                             f"менять итог"))
    else:
        итог.append((ГОДНО, f"всего запросов совпадает: {t0} → {t1}"))

    # 3. сдвиги людей и граф против заявки
    л0, л1 = _люди(до), _люди(после)
    сдвиги = {к: л1.get(к, 0) - л0.get(к, 0) for к in set(л0) | set(л1)}
    была_заявка = bool(заявлено)
    группа = "сорсеры" in заявлено
    # люди, не заявленные поимённо, — они и составляют групповой сдвиг
    вольные = {к: д for к, д in сдвиги.items() if к.startswith("#") and к not in заявлено}
    групповой = sum(вольные.values())
    for к, д in sorted(сдвиги.items(), key=lambda kv: -abs(kv[1])):
        if к in заявлено or abs(д) <= шум(л0.get(к, 0)):
            continue
        if группа and к in вольные:
            if abs(групповой) > КОНЦЕНТРАЦИЯ_ОТ and abs(д) > abs(групповой) * КОНЦЕНТРАЦИЯ_ДОЛЯ:
                итог.append((ПРОВАЛ, f"{к}: {л0.get(к, 0)} → {л1.get(к, 0)} ({д:+d}) — больше половины "
                                     f"группового сдвига {групповой:+d} легло на одного человека"))
            continue
        итог.append((ПРОВАЛ, f"{к}: {л0.get(к, 0)} → {л1.get(к, 0)} ({д:+d}) — сдвиг не заявлен"
                             + ("" if была_заявка else "; в описании PR нет ни одной строки «ожидается:»")))
    if группа:
        сдвиги["сорсеры"] = групповой
    for к, ж in заявлено.items():
        if к.startswith("__"):
            continue
        д = сдвиги.get(к, 0)
        if abs(д - ж) > допуск(ж):
            итог.append((ПРОВАЛ, f"{к}: заявлено {ж:+d}, получено {д:+d}"))
        else:
            итог.append((ГОДНО, f"{к}: заявлено {ж:+d}, получено {д:+d}"))

    # 4. пустые ряды недельного графика
    нед0, нед1 = до.get("weekly") or [], после.get("weekly") or []
    ключи0 = set().union(*(w.keys() for w in нед0)) if нед0 else set()
    ключи1 = set().union(*(w.keys() for w in нед1)) if нед1 else set()
    for к in sorted(ключи1):
        if к in ("w", "d"):
            continue
        s1 = sum(w.get(к) or 0 for w in нед1 if isinstance(w.get(к), (int, float)))
        s0 = sum(w.get(к) or 0 for w in нед0 if isinstance(w.get(к), (int, float)))
        if s1 == 0 and (к not in ключи0 or s0 > 0):
            итог.append((ПРОВАЛ, f"ряд недельного графика «{к}» пуст на живых данных"
                                 + (" (новый ряд)" if к not in ключи0 else f" (в проде был {s0})")))

    # 5. служебные записи, заданные номером, действительно работают
    работают = {str(x.get("uid")) for x in (после.get("origin") or {}).get("service") or []}
    for u in sorted(служебные_номерами):
        if u not in работают:
            итог.append((ПРОВАЛ, f"служебная запись #{u} задана номером, но в окне у неё нет ни одной "
                                 f"карточки — номер неверен или запись к воронке не относится"))

    # 6. нераспознанных не стало больше
    н0, н1 = _не_определён(до), _не_определён(после)
    if н1 - н0 > шум(н0):
        итог.append((ПРОВАЛ, f"исполнитель не определён: было {н0}, стало {н1}"))
    else:
        итог.append((ГОДНО, f"нераспознанных исполнителей: {н0} → {н1}"))
    return итог


def таблица(до: dict, после: dict) -> list[str]:
    л0, л1 = _люди(до), _люди(после)
    строки = []
    for к in sorted(set(л0) | set(л1), key=lambda x: -abs(л1.get(x, 0) - л0.get(x, 0))):
        д = л1.get(к, 0) - л0.get(к, 0)
        if д:
            строки.append(f"  {к:12} {л0.get(к, 0):6} → {л1.get(к, 0):6}   {д:+6d}")
    return строки


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    import config
    до, после = загрузить(argv[1]), загрузить(argv[2])
    заявлено = ожидания(os.getenv("PR_BODY") or os.getenv("EXPECT") or "")
    print("ЖИВАЯ СВЕРКА МЕТРИК · прод против правки на одних данных")
    print(f"  заявлено в описании: {', '.join(f'{k} {v:+d}' for k, v in заявлено.items() if not k.startswith('__')) or ('без изменений' if заявлено else 'ничего')}")
    print()
    print("  сдвиги (номер учётной записи или графа · прод → правка):")
    for s in таблица(до, после) or ["  сдвигов нет"]:
        print(s)
    print()
    итог = сверить(до, после, заявлено, set(config.SERVICE_ACCOUNT_IDS))
    for уровень, текст in итог:
        print(f"  {уровень:9} {текст}")
    провалы = [t for u, t in итог if u == ПРОВАЛ]
    print()
    if провалы:
        print(f"НЕ ПРОЙДЕНО: {len(провалы)}. Мержить нельзя, пока причина не найдена и не устранена.")
        return 1
    print("Сверка пройдена.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
