ПРОВАЛ, ВНИМАНИЕ, ГОДНО = "ПРОВАЛ", "ВНИМАНИЕ", "ГОДНО"

# Шум — только когда часть данных прочитана мимо снимка: тогда две сборки
# видят портал с разницей в минуты, и карточку за это время могут
# переназначить. В точном режиме шума нет, и допуск нулевой.
ШУМ_АБС, ШУМ_ДОЛЯ = 3, 0.02
# Итог окна заморожен датой создания карточки: переназначение его не меняет.
ШУМ_ИТОГА = 3
# Допуск на заявленный сдвиг.
ДОПУСК_АБС, ДОПУСК_ДОЛЯ = 10, 0.10
# Сдвиг больше этого числа не может лечь на одного человека больше чем
# наполовину — иначе это не раскладка по людям, а перенос на одного.
КОНЦЕНТРАЦИЯ_ОТ, КОНЦЕНТРАЦИЯ_ДОЛЯ = 50, 0.5

РАЗДЕЛЫ_АТРИБУЦИИ = frozenset({"kpi", "weekly", "sourcersa", "origin"})
НЕ_СРАВНИВАТЬ = frozenset({"period", "_portal"})
ВКЛАДКИ = ("company", "kam", "eng", "prod", "contracts", "reps", "advisor", "people")
ЗАГЛУШКА_ИМЕНИ = re.compile(r"^user#\d+$")
НЕ_ОПРЕДЕЛЁН = "исполнитель не определён"      # строка разреза origin.byOwnerDept
ГЛАВНЫЕ_ИНВАРИАНТЫ = ("отдел + вне отдела = всего", "сумма по сорсерам = отдел")


def шум(база: int | float, точно: bool = False) -> int:
    return 0 if точно else max(ШУМ_АБС, round(abs(база) * ШУМ_ДОЛЯ))


def допуск(заявлено: int) -> int:
    return max(ДОПУСК_АБС, round(abs(заявлено) * ДОПУСК_ДОЛЯ))


# --------------------------------------------------------------------- заявка
@dataclass
class Заявка:
    сдвиги: dict[str, int] = field(default_factory=dict)
    без_изменений: bool = False
    пустые: set[str] = field(default_factory=set)
    разделы: set[str] = field(default_factory=set)
    ошибки: list[str] = field(default_factory=list)

    @property
    def была(self) -> bool:
        return bool(self.сдвиги or self.без_изменений or self.пустые or self.разделы)

    @property
    def атрибуция(self) -> bool:
        return any(к.startswith(("#", "звено ")) or к in ("отдел", "вне отдела", "сорсеры", "не определен")
                   for к in self.сдвиги)

    def текст(self) -> str:
        части = [f"{к} {в:+d}" for к, в in self.сдвиги.items()]
        части += [f"меняется {р}" for р in sorted(self.разделы)]
        части += [f"пустой {р}" for р in sorted(self.пустые)]
        if self.без_изменений and not части:
            части = ["без изменений"]
        return ", ".join(части) or "ничего"


_РАЗМЕТКА = str.maketrans({c: " " for c in "*_|"})
_ЧИСЛО = r"\d{1,3}(?:[   ]\d{3})+|\d+"
_СДВИГ = re.compile(rf"^(?P<k>.+?)\s*(?P<z>[+\-−–—±])?\s*(?P<n>{_ЧИСЛО})$")
_ГОЛОВА = re.compile(r"ожида(?:ется|ются)\s*:(.*)$")
_МАРКЕР = re.compile(r"^(?:[-•·]|\d+[.)])\s+")
_МИНУСЫ = ("-", "−", "–", "—")


def _норм(s: str) -> str:
    return re.sub(r"\s+", " ", s.replace("ё", "е").replace("Ё", "Е").lower()).strip()


def _ключ(k: str) -> str | None:
    k = k.strip(" «»\"':")
    if re.fullmatch(r"#\d+", k):
        return k
    if k == "отдел":
        return "отдел"
    if re.fullmatch(r"вне\s+отдела", k):
        return "вне отдела"
    if k.startswith("сорсер"):
        return "сорсеры"
    if k in ("всего", "итог", "всего запросов"):
        return "всего"
    if k.startswith("не определен"):
        return "не определен"
    m = re.fullmatch(r"звено\s+(.+)", k)
    if m:
        return "звено " + m.group(1).strip(" «»\"'")
    return None


def _пути(s: str) -> set[str]:
    return {p.strip(" .«»\"'") for p in re.split(r"[,\s]+", s) if p.strip(" .«»\"'")}


def _пункты(payload: str) -> list[str]:
    out: list[str] = []
    for seg in payload.split(";"):
        seg = seg.strip(" .")
        if not seg:
            continue
        if re.match(r"^(меня\w*|пуст\w*)\s", seg):
            out.append(seg)
            continue
        out += [x.strip(" .") for x in re.split(r",\s+", seg) if x.strip(" .")]
    return out


def _пункт(z: Заявка, s: str, исходник: str) -> None:
    if s in ("без изменений", "изменений нет", "ничего не меняется"):
        z.без_изменений = True
        return
    m = re.match(r"^пуст\w*\s+(.+)$", s)
    if m:
        z.пустые |= _пути(m.group(1))
        return
    m = re.match(r"^меня\w*\s+(.+)$", s)
    if m:
        z.разделы |= _пути(m.group(1))
        return
    m = _СДВИГ.match(s)
    if m and (k := _ключ(m.group("k"))):
        знак, n = m.group("z") or "", int(re.sub(r"\D", "", m.group("n")))
        if n and not знак:
            z.ошибки.append(f"{исходник} — у числа нет знака (+ или −)")
            return
        z.сдвиги[k] = -n if знак in _МИНУСЫ else n
        return
    z.ошибки.append(исходник)


def ожидания(текст: str | None) -> Заявка:
    """Заявка из описания PR. Разбирает и строку «ожидается: …», и заголовок
    «Ожидается:» со списком под ним. Нераспознанное — в `ошибки`, не в тишину."""
    z = Заявка()
    t = re.sub(r"```.*?```", " ", текст or "", flags=re.S)
    t = re.sub(r"`[^`\n]*`", " ", t)
    строки = t.splitlines()
    i = 0
    while i < len(строки):
        сырой = строки[i]
        i += 1
        m = _ГОЛОВА.search(_норм(сырой.translate(_РАЗМЕТКА)))
        if not m:
            continue
        payload = m.group(1).strip()
        пункты: list[tuple[str, str]] = []
        if payload:
            пункты = [(p, сырой.strip()) for p in _пункты(payload)]
        else:
            while i < len(строки) and строки[i].strip():
                s = _МАРКЕР.sub("", _норм(строки[i].translate(_РАЗМЕТКА)))
                пункты += [(p, строки[i].strip()) for p in _пункты(s)]
                i += 1
            if not пункты:
                z.ошибки.append(f"{сырой.strip()} — после заголовка нет ни одной строки")
        for p, src in пункты:
            _пункт(z, p, src)
    return z


# ------------------------------------------------------------------- загрузка
def загрузить(каталог: str | Path) -> tuple[dict | None, dict | None]:
    """(метрики, вкладки). Метрик нет — сборка не состоялась: (None, None)."""
    p = Path(каталог)
    if p.is_file():
        return json.loads(p.read_text(encoding="utf-8")), None
    files = sorted(p.glob("metrics_*.json")) if p.is_dir() else []
    if not files:
        return None, None
    if len(files) > 1:
        raise SystemExit(f"в {p} ожидался один metrics_*.json, найдено {len(files)}")
    мод = p / "modules.json"
    return (json.loads(files[0].read_text(encoding="utf-8")),
            json.loads(мод.read_text(encoding="utf-8")) if мод.exists() else None)


# -------------------------------------------------------------- плоский вид
# Сегмент узора печатается, только если он похож на имя поля из кода; всё
# прочее (названия подразделений, компаний, номера) сворачивается в {*}.
_ПОЛЕ_КОДА = re.compile(r"^(?:[a-z][A-Za-z0-9]{0,40}|[A-Z]{1,2})$")
_КЛЮЧИ_ЭЛЕМЕНТА = ("id", "uid", "key", "w", "dept", "how", "cat", "sup", "lbl")


def _метки(lst: list) -> list[str]:
    """Метки элементов списка для попарного сравнения: по полю-ключу, если оно
    есть у всех и не повторяется, иначе по позиции."""
    for k in _КЛЮЧИ_ЭЛЕМЕНТА:
        vals = [v.get(k) if isinstance(v, dict) else None for v in lst]
        if lst and all(isinstance(x, (str, int)) and not isinstance(x, bool) for x in vals) \
                and len(set(map(str, vals))) == len(vals):
            return [f"{k}={x}" for x in vals]
    return [str(i) for i in range(len(lst))]


def точки(obj, путь: str = "", узор: str = "", out: dict | None = None) -> dict[str, tuple[str, object]]:
    """{точный путь: (узор, значение)}. Узор — путь без номеров и динамических
    ключей: только он и печатается. Точный путь нужен для пары «прод — правка»
    и в журнал не идёт (в нём номера карточек и названия подразделений)."""
    out = {} if out is None else out
    if isinstance(obj, dict):
        for k, v in obj.items():
            ks = str(k)
            seg = ks if _ПОЛЕ_КОДА.match(ks) else "{*}"
            точки(v, f"{путь}.{ks}" if путь else ks, f"{узор}.{seg}" if узор else seg, out)
    elif isinstance(obj, list):
        for метка, v in zip(_метки(obj), obj):
            точки(v, f"{путь}[{метка}]", f"{узор}[*]", out)
    else:
        out[путь] = (узор, obj)
    return out


def _число(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _корень(узор: str) -> str:
    return re.split(r"[.\[]", узор, maxsplit=1)[0]


def _узор_без_звёзд(узор: str) -> str:
    return re.sub(r"\.?\{\*\}|\[\*\]", "", узор).lower()


def _заявлен(узор: str, пути: set[str] | frozenset) -> bool:
    u = _узор_без_звёзд(узор)
    return any(u == p.lower() or u.startswith(p.lower() + ".") for p in пути)


def _сборка(m: dict | None, мод: dict | None) -> dict:
    d = dict(m or {})
    for k in ВКЛАДКИ:
        if мод is not None:
            d[k] = мод.get(k)
    return d


# ----------------------------------------------------------------- инварианты
def инварианты(m: dict) -> list[tuple[str, bool, str]]:
    k = m.get("kpi") or {}
    total, a, b = int(k.get("total") or 0), int(k.get("deptA") or 0), int(k.get("outside") or 0)
    сорсеры = m.get("sourcersA") or []
    нед = m.get("weekly") or []
    origin = m.get("origin") or {}
    сумма_c = sum(int(s.get("c") or 0) for s in сорсеры)
    out = [
        ("отдел + вне отдела = всего", a + b == total, f"{a} + {b} против {total}"),
        ("сумма по сорсерам = отдел", сумма_c == a, f"{сумма_c} против {a}"),
    ]
    if нед:
        sa = sum(int(w.get("A") or 0) for w in нед)
        sb = sum(int(w.get("B") or 0) for w in нед)
        out.append(("недельный ряд A = отдел", sa == a, f"{sa} против {a}"))
        out.append(("недельный ряд B = вне отдела", sb == b, f"{sb} против {b}"))
    if сорсеры and all(isinstance(s.get("wk"), list) for s in сорсеры):
        плохие = sum(1 for s in сорсеры if sum(s["wk"]) != int(s.get("c") or 0))
        out.append(("недели каждого сорсера = его итог", not плохие, f"не сходится у {плохие} чел."))
    if сорсеры and all("closed" in s for s in сорсеры):
        плохие = sum(1 for s in сорсеры if int(s.get("closed") or 0) != int(s.get("kp") or 0)
                     + int(s.get("refusedCol") or 0) + int(s.get("noAnswer") or 0))
        out.append(("закрытые = КП + отказ + молчание", not плохие, f"не сходится у {плохие} чел."))
    if origin.get("byOwnerDept") is not None:
        s = sum(int(x.get("n") or 0) for x in origin["byOwnerDept"])
        out.append(("разрез «чья это работа» = всего", s == total, f"{s} против {total}"))
    if (origin.get("summary") or {}).get("total") is not None:
        s = int(origin["summary"]["total"])
        out.append(("сводка авторства = всего", s == total, f"{s} против {total}"))
    return out


def _люди(m: dict) -> dict[str, int]:
    out = {f"#{s['id']}": int(s.get("c") or 0) for s in m.get("sourcersA") or []}
    k = m.get("kpi") or {}
    out["отдел"] = int(k.get("deptA") or 0)
    out["вне отдела"] = int(k.get("outside") or 0)
    return out


def _звенья(m: dict) -> dict[str, int]:
    return {"звено " + _норм(str(x.get("how"))): int(x.get("n") or 0)
            for x in (m.get("origin") or {}).get("resolvedHow") or []}


def _без_исполнителя(m: dict) -> int:
    for x in (m.get("origin") or {}).get("byOwnerDept") or []:
        if x.get("dept") == НЕ_ОПРЕДЕЛЁН:
            return int(x.get("n") or 0)
    return 0


def _заглушки(d: dict) -> int:
    return sum(1 for у, v in точки(d).values() if isinstance(v, str) and ЗАГЛУШКА_ИМЕНИ.match(v))


def _провалов(итог: list) -> int:
    return sum(1 for u, _ in итог if u == ПРОВАЛ)


# ---------------------------------------------------------------------- сверка
def сверить(до: dict | None, после: dict, заявка: Заявка, *, служебные: set[str] | frozenset = frozenset(),
            служебные_прод: set[str] | None = None, модули_до: dict | None = None,
            модули_после: dict | None = None, точно: bool = False) -> list[tuple[str, str]]:
    итог: list[tuple[str, str]] = []

    def провал(t: str) -> None:
        итог.append((ПРОВАЛ, t))

    for строка in заявка.ошибки:
        провал(f"строка заявки не разобрана: «{строка[:120]}»")

    # 1. инварианты
    inv1 = инварианты(после)
    inv0 = {имя: ok for имя, ok, _ in инварианты(до)} if до is not None else {}
    сломано = 0
    for имя, ok, пояснение in inv1:
        if ok:
            continue
        сломано += 1
        if до is None:
            итог.append((ПРОВАЛ if имя in ГЛАВНЫЕ_ИНВАРИАНТЫ else ВНИМАНИЕ,
                         f"правка: {имя} — не сходится ({пояснение}); прод не собрался, сравнить не с чем"))
        elif inv0.get(имя, True):
            провал(f"правка: {имя} — не сходится ({пояснение}), а в проде сходилось")
        else:
            итог.append((ВНИМАНИЕ, f"правка: {имя} — не сходится ({пояснение}), как и в проде: не от этой правки"))
    if not сломано:
        итог.append((ГОДНО, f"инварианты правки сходятся: {len(inv1)} из {len(inv1)}"))

    if до is None:
        итог.append((ВНИМАНИЕ, "прод не собрался — сравнение с продом невозможно, проверена только сама правка"))
        _служебные(итог, None, после, служебные, служебные_прод)
        return итог

    # 2. итог
    t0 = int((до.get("kpi") or {}).get("total") or 0)
    t1 = int((после.get("kpi") or {}).get("total") or 0)
    if "всего" in заявка.сдвиги:
        ж = заявка.сдвиги["всего"]
        ok = abs((t1 - t0) - ж) <= допуск(ж) + (0 if точно else ШУМ_ИТОГА)
        итог.append((ГОДНО if ok else ПРОВАЛ, f"всего запросов: заявлено {ж:+d}, получено {t1 - t0:+d} ({t0} → {t1})"))
    elif abs(t1 - t0) > (0 if точно else ШУМ_ИТОГА):
        провал(f"всего запросов: прод {t0}, правка {t1} — итог изменился, а заявки «всего ±N» нет")
    else:
        итог.append((ГОДНО, f"всего запросов совпадает: {t0} → {t1}"))

    # 3. люди отдела и графы
    л0, л1 = _люди(до), _люди(после)
    сдвиги = {к: л1.get(к, 0) - л0.get(к, 0) for к in set(л0) | set(л1)}
    было = _провалов(итог)
    группа = заявка.сдвиги.get("сорсеры")
    вольные = {к: д for к, д in сдвиги.items() if к.startswith("#") and к not in заявка.сдвиги}
    приток = sum(д for д in вольные.values() if д > 0)
    отток = -sum(д for д in вольные.values() if д < 0)
    подсказка = "; если перенос задуман, назовите человека поимённо («ожидается: #N ±X»)"
    for к, д in sorted(сдвиги.items(), key=lambda kv: -abs(kv[1])):
        if к in заявка.сдвиги or abs(д) <= шум(л0.get(к, 0), точно):
            continue
        if группа is not None and к in вольные:
            сторона = приток if д > 0 else отток
            if (группа > 0 > д) or (группа < 0 < д):
                провал(f"{к}: {д:+d} — против знака групповой заявки «сорсеры {группа:+d}»" + подсказка)
            elif сторона > КОНЦЕНТРАЦИЯ_ОТ and abs(д) > сторона * КОНЦЕНТРАЦИЯ_ДОЛЯ:
                провал(f"{к}: {д:+d} — {abs(д) / сторона:.0%} всего {'притока' if д > 0 else 'оттока'} "
                       f"по сорсерам легло на одного человека" + подсказка)
            continue
        провал(f"{к}: {д:+d} — сдвиг не заявлен"
               + ("" if заявка.была else "; в описании PR нет ни одной строки «ожидается:»"))
    if группа is not None:
        сдвиги["сорсеры"] = sum(вольные.values())
    for к, ж in заявка.сдвиги.items():
        if к in ("всего", "не определен") or к.startswith("звено "):
            continue
        д = сдвиги.get(к, 0)
        ok = abs(д - ж) <= допуск(ж) + шум(л0.get(к, 0), точно)
        итог.append((ГОДНО if ok else ПРОВАЛ, f"{к}: заявлено {ж:+d}, получено {д:+d}"))
    if _провалов(итог) == было:
        итог.append((ГОДНО, f"сдвиги людей и граф соответствуют заявке (проверено {len(сдвиги)} позиций, "
                            + ("точно, без допуска)" if точно else f"шум не выше ±{ШУМ_АБС} или {ШУМ_ДОЛЯ:.0%})")))

    # 4. звенья цепочки и карточки без исполнителя
    з0, з1 = _звенья(до), _звенья(после)
    з0["не определен"], з1["не определен"] = _без_исполнителя(до), _без_исполнителя(после)
    было = _провалов(итог)
    заявленные = {к: ж for к, ж in заявка.сдвиги.items() if к.startswith("звено ") or к == "не определен"}
    сопоставлено: dict[str, list[str]] = defaultdict(list)
    for к in sorted(set(з0) | set(з1)):
        д = з1.get(к, 0) - з0.get(к, 0)
        свой = next((з for з in заявленные if к == з or (з.startswith("звено ") and к.startswith(з))), None)
        if свой:
            сопоставлено[свой].append(к)
        elif abs(д) > шум(з0.get(к, 0), точно):
            подпись = "карточки без исполнителя" if к == "не определен" else f"«{к}»"
            провал(f"{подпись}: {з0.get(к, 0)} → {з1.get(к, 0)} ({д:+d}) — сдвиг не заявлен")
    for з, ж in заявленные.items():
        свои = сопоставлено.get(з, [])
        д = sum(з1.get(к, 0) - з0.get(к, 0) for к in свои)
        ok = bool(свои) and abs(д - ж) <= допуск(ж) + шум(sum(з0.get(к, 0) for к in свои), точно)
        итог.append((ГОДНО if ok else ПРОВАЛ, f"«{з}»: заявлено {ж:+d}, получено {д:+d}"
                     + ("" if свои else " — такой строки нет ни в проде, ни в правке")))
    if _провалов(итог) == было:
        итог.append((ГОДНО, f"звенья цепочки исполнителя и карточки без исполнителя соответствуют заявке "
                            f"({len(set(з0) | set(з1))} строк)"))

    # 5–6. поля, ряды, вкладки
    _поля(итог, _сборка(до, модули_до), _сборка(после, модули_после), заявка, точно,
          вкладки_в_проде=модули_до is not None, вкладки_в_правке=модули_после is not None)

    # 7. служебные записи
    _служебные(итог, до, после, служебные, служебные_прод)

    # 8. заглушки имён
    n0, n1 = _заглушки(_сборка(до, модули_до)), _заглушки(_сборка(после, модули_после))
    if n1 - n0 > (0 if точно else шум(n0)):
        провал(f"имена не подтянулись: заглушек «user#N» было {n0}, стало {n1}")
    else:
        итог.append((ГОДНО, f"заглушек вместо имён: {n0} → {n1}"))
    return итог


def _поля(итог: list, д0: dict, д1: dict, заявка: Заявка, точно: bool, *,
          вкладки_в_проде: bool, вкладки_в_правке: bool) -> None:
    вкладки_сравнимы = вкладки_в_проде and вкладки_в_правке
    if not вкладки_в_проде:
        итог.append((ВНИМАНИЕ, "в проде нет выгрузки вкладок (прод старше сверки) — вкладки сравниваются "
                               "со следующей правки; здесь проверено только, что они собрались"))
    if not вкладки_в_правке:
        итог.append((ПРОВАЛ, "правка не выгрузила данные вкладок (modules.json) — сверить их нечем"))
    else:
        for в in ВКЛАДКИ:
            if д1.get(в) is not None:
                continue
            if вкладки_в_проде and д0.get(в) is not None:
                итог.append((ПРОВАЛ, f"вкладка «{в}» в проде собиралась, в правке не собралась"))
            else:
                итог.append((ВНИМАНИЕ, f"вкладка «{в}» не собралась" + (" и в проде" if вкладки_в_проде else "")))

    def сравнимо(узор: str) -> bool:
        к = _корень(узор)
        return к not in НЕ_СРАВНИВАТЬ and (к not in ВКЛАДКИ or вкладки_сравнимы)

    т0, т1 = точки(д0), точки(д1)
    узоры0: dict[str, list] = defaultdict(list)
    узоры1: dict[str, list] = defaultdict(list)
    for у, v in т0.values():
        if _число(v):
            узоры0[у].append(v)
    for у, v in т1.values():
        if _число(v):
            узоры1[у].append(v)
    корни0 = {_корень(у) for у, _ in т0.values()}

    # 5. ненулевое не стало пустым; новое поле не пришло пустым
    пустых = 0
    for у in sorted(set(узоры0) | set(узоры1)):
        if not сравнимо(у):
            continue
        v0, v1 = узоры0.get(у, []), узоры1.get(у, [])
        nz0, nz1 = sum(1 for x in v0 if x), sum(1 for x in v1 if x)
        if nz1 or _заявлен(у, заявка.пустые):
            continue
        if nz0:
            пустых += 1
            итог.append((ПРОВАЛ if (точно or nz0 > 2) else ВНИМАНИЕ,
                         f"«{у}»: в проде ненулевых значений {nz0}, в правке "
                         + ("поля нет" if not v1 else "все нули")
                         + f" (если так задумано — «ожидается: пустой {_узор_без_звёзд(у)}»)"))
        elif not v0 and len(v1) > 1 and _корень(у) in корни0:
            пустых += 1
            итог.append((ПРОВАЛ, f"«{у}»: новое поле, на живых данных все {len(v1)} значений нулевые "
                                 f"(если так задумано — «ожидается: пустой {_узор_без_звёзд(у)}»)"))
    if not пустых:
        итог.append((ГОДНО, f"полей с числами: {len(узоры1)}; ни одно не опустело и не пришло пустым"))

    # 6. незаявленные изменения по разделам
    изменения: dict[str, Counter] = defaultdict(Counter)
    for п in set(т0) | set(т1):
        у, v0 = т0.get(п, (None, None))
        у1, v1 = т1.get(п, (None, None))
        у = у or у1
        if not сравнимо(у) or not (_число(v0) or _число(v1)):
            continue
        a, b = (v0 if _число(v0) else 0), (v1 if _число(v1) else 0)
        if _число(v0) != _число(v1) or abs(b - a) > (0 if точно else шум(a)):
            изменения[_корень(у)][у] += 1
    разрешено = {р.lower() for р in заявка.разделы} | (set(РАЗДЕЛЫ_АТРИБУЦИИ) if заявка.атрибуция else set())
    for раздел, узоры in sorted(изменения.items()):
        лишние = Counter({у: n for у, n in узоры.items()
                          if not (_заявлен(у, разрешено) or _заявлен(у, заявка.пустые))})
        образцы = ", ".join(f"{у} ×{n}" for у, n in (лишние or узоры).most_common(5))
        if not лишние:
            итог.append((ГОДНО, f"раздел «{раздел}» заявлен меняющимся: изменилось {sum(узоры.values())} "
                                f"значений ({образцы})"))
        elif точно:
            итог.append((ПРОВАЛ, f"раздел «{раздел}»: изменилось {sum(лишние.values())} значений, а заявки "
                                 f"«меняется {раздел}» нет ({образцы})"))
        else:
            итог.append((ВНИМАНИЕ, f"раздел «{раздел}»: изменилось {sum(лишние.values())} значений сверх шума "
                                   f"({образцы}); сверка не точная, правку от шума портала не отличить"))
    if not изменения:
        итог.append((ГОДНО, "разделы метрик" + (" и вкладок" if вкладки_сравнимы else "")
                            + " совпадают значение в значение" + ("" if точно else " в пределах шума")))


def _служебные(итог: list, до: dict | None, после: dict, служебные, служебные_прод) -> None:
    def работают(m: dict | None) -> dict[str, dict]:
        return {str(x.get("uid")): x for x in ((m or {}).get("origin") or {}).get("service") or []}

    р0, р1 = работают(до), работают(после)
    прежние = set(служебные) if служебные_прод is None else set(служебные_прод)
    # Признак «числится в подразделении» у настоящих роботов портала тоже
    # стоит (замер 23.09.2026: у всех трёх подтверждённых), поэтому сам по себе
    # он ничего не доказывает. Вред — когда в служебные внесли сорсера: его
    # запросы уходят из его же строки. Это и есть провал.
    сорсеры_прод = {str(s.get("id")) for s in (до or {}).get("sourcersA") or []}
    в_подразделении: list[str] = []
    плохо = 0
    порядок = sorted(служебные, key=lambda x: (len(x), x))
    for u in порядок:
        новый = u not in прежние
        if u not in р1:
            if новый:
                плохо += 1
                итог.append((ПРОВАЛ, f"служебная запись #{u} задана номером в этой правке, но в окне у неё нет ни "
                                     f"одной карточки — номер неверен или запись к воронке не относится"))
            elif u in р0:
                плохо += 1
                итог.append((ПРОВАЛ, f"служебная запись #{u} в проде заводила карточки, в правке — ни одной"))
            else:
                итог.append((ВНИМАНИЕ, f"служебная запись #{u} не заводит карточек и в проде — проверьте, "
                                       f"нужна ли она в списке"))
        if новый and u in сорсеры_прод:
            плохо += 1
            итог.append((ПРОВАЛ, f"служебная запись #{u} добавлена этой правкой, но в проде это сорсер со своими "
                                 f"запросами: его работа исчезнет из его же статистики"))
        elif u in р1 and р1[u].get("looksHuman"):
            в_подразделении.append(f"#{u}" + (" (добавлена этой правкой)" if новый else ""))
    if в_подразделении:
        итог.append((ВНИМАНИЕ, "служебные записи, числящиеся в подразделении (у роботов портала это обычно): "
                               + ", ".join(в_подразделении)))
    if not плохо:
        итог.append((ГОДНО, "служебные записи, заданные номером, работают: "
                            + (", ".join(f"#{u}" for u in порядок) or "не заданы")))


