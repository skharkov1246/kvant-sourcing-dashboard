def таблица(до: dict, после: dict, точно: bool = False) -> list[str]:
    """Сдвиги для журнала. По людям — только разница и только выше шума: сами
    числа нагрузки человека в публичный журнал не идут (правило 17)."""
    k0, k1 = до.get("kpi") or {}, после.get("kpi") or {}
    строки = ["  графы: " + "; ".join(f"{подпись} {int(k0.get(к) or 0)} → {int(k1.get(к) or 0)}"
                                      for к, подпись in (("total", "всего"), ("deptA", "отдел"),
                                                         ("outside", "вне отдела")))]
    л0, л1 = _люди(до), _люди(после)
    люди = [(к, л1.get(к, 0) - л0.get(к, 0)) for к in set(л0) | set(л1) if к.startswith("#")]
    люди = sorted(((к, д) for к, д in люди if abs(д) > шум(л0.get(к, 0), точно)), key=lambda x: (-abs(x[1]), x[0]))
    строки.append("  люди отдела (только разница): " + (", ".join(f"{к} {д:+d}" for к, д in люди) or "сдвигов нет"))
    з0, з1 = _звенья(до), _звенья(после)
    з = [(к[6:], з0.get(к, 0), з1.get(к, 0)) for к in sorted(set(з0) | set(з1)) if з0.get(к, 0) != з1.get(к, 0)]
    строки.append("  звенья «чем определён»: " + ("; ".join(f"{к} {a} → {b}" for к, a, b in з) or "без изменений"))
    строки.append(f"  без исполнителя (все карточки): {_без_исполнителя(до)} → {_без_исполнителя(после)}")
    return строки


def _номера(s: str | None) -> set[str]:
    return {u.strip() for u in (s or "").split(",") if u.strip()}


