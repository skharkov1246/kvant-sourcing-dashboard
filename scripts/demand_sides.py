#!/usr/bin/env python3
"""ЧТО ИЗ «НАШЕГО СПРОСА» — НЕ СПРОС. Раскладка строк спроса по полю карточки.

ЗАЧЕМ. 22.09.2026 замер кодов перестал считать позиции из предложений
поставщиков нашим спросом: отбор по lib_files.origin = 'поле сделки'. Но поля
СДЕЛКИ — это не только спецификации заказчика. В них же лежат:

  · «Result, ТКП» (ufCrm_1733957302549) — НАШЕ исходящее предложение заказчику;
  · «Economics of the project» (ufCrm_1699270486) — наша экономика проекта;
  · «Offer from us», «Processed file for supplier» — наши исходящие документы;
  · «Offer from supplier(s)», «КП поставщика» — ВХОДЯЩИЕ предложения, лежащие
    в поле сделки, а не в карточке запроса.

Позиции из всех этих файлов сейчас считаются НАШИМ СПРОСОМ. То есть строки
нашего же исходящего ТКП попадают в знаменатель «по скольким позициям мы не
получили цену» — это та же тавтология, что и с предложениями, только на слой
глубже. Два известных кода поля дают 193 записи по замеру gt/data/ship_sale_side.json;
сколько дают остальные — неизвестно, и этот замер отвечает.

НАЗВАНИЯ ПОЛЕЙ. В lib_files хранится КОД поля (ufCrm_…), а не название, поэтому
сторону документа по названию из одной базы не определить. Если задан
BITRIX_WEBHOOK_URL, замер берёт названия одним вызовом crm.item.fields на каждый
тип сущности (сделка и карточка запроса) и раскладывает строки ПО СТОРОНАМ через
library/doc_side.py. Без Битрикса печатается только раскладка по кодам — этого
хватает, чтобы понять размер задачи, но не чтобы применить правило.

ОДНО ПОЛЕ В ДВУХ НАПИСАНИЯХ. Замер 22.09.2026: коды приходят и как
«ufCrm_1633502831», и как «UF_CRM_1633502831» — это одно поле, API отдаёт разный
регистр в разных контекстах. Правило по коду обязано складывать регистр, иначе
одно поле считается дважды и половина строк остаётся неопознанной.

Ничего не пишет. В журнал — только агрегаты (правило 17): коды и названия полей —
это настройки нашего же Битрикса, не данные заказчиков.

    SUPABASE_DB_URL=… python scripts/demand_sides.py
    SUPABASE_DB_URL=… BITRIX_WEBHOOK_URL=… python scripts/demand_sides.py
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from library import doc_side  # noqa: E402

# Известные коды полей. Взяты из замера gt/data/ship_sale_side.json, где они
# опознаны по названию, и из gt/tools/bitrix_tkp.py. Список НЕ полный и не
# претендует: он нужен, чтобы в выводе было видно, какие строки уже опознаны, а
# какие ещё нет.
ИЗВЕСТНЫЕ = {
    "ufCrm_1733957302549": ("Result, ТКП", "наше исходящее предложение"),
    "ufCrm_1699270486": ("Economics of the project", "наша экономика проекта"),
}

РАСКЛАДКА = """
select coalesce(f.origin, '(без файла)')      as происхождение,
       coalesce(f.field, '(поле не названо)')  as поле,
       count(*)::bigint                        as строк,
       count(distinct d.deal_id)::bigint       as сделок,
       count(distinct f.file_id)::bigint       as файлов,
       count(distinct lib_pn_key(d.part_number))
         filter (where length(lib_pn_key(d.part_number)) >= 2)::bigint as кодов
  from lib_demand_live d
  left join lib_files f on f.file_id = d.source_file
 group by 1, 2
 order by 3 desc
"""

# Цены, лежащие у файлов ПОЛЯ СДЕЛКИ: если разбор КП писал цены только для
# карточек запроса, здесь должен быть ноль. Ненулевое значение означает, что
# исходящие цены уже попали в lib_prices как входящие.
ЦЕНЫ_ИЗ_ПОЛЕЙ_СДЕЛКИ = """
select coalesce(f.field, '(поле не названо)')  as поле,
       count(*)::bigint                        as строк_цены,
       count(distinct p.feed)::bigint           as потоков
  from lib_prices p
  join lib_files f on f.file_id = p.source_url
 where f.origin = 'поле сделки'
 group by 1
 order by 2 desc
"""


def ключ_поля(код: str) -> str:
    """Код поля без регистра: «ufCrm_123» и «UF_CRM_123» — одно поле."""
    return (код or "").lower().replace("_", "")


def названия_полей() -> dict[str, str]:
    """Код поля → название, одним вызовом на тип сущности. Без Битрикса — пусто.

    Читаются оба типа: сделка (2) и карточка запроса (166). Файловые поля есть у
    обоих, и коды у них разные.
    """
    if not os.environ.get("BITRIX_WEBHOOK_URL", "").strip():
        return {}
    from library import indexer

    карта: dict[str, str] = {}
    for тип in (2, indexer.SPA_RFQ):
        ответ = indexer.bx("crm.item.fields", {"entityTypeId": тип})
        поля = (ответ.get("result") or {}).get("fields") or {}
        for код, свойства in поля.items():
            имя = (свойства or {}).get("title") or ""
            if имя:
                карта[ключ_поля(код)] = имя
    return карта


def ч(x) -> int:
    return int(x or 0)


def доля(часть, целое) -> str:
    часть, целое = ч(часть), ч(целое)
    return f"{часть:>9d}" + (f"  {100 * часть / целое:5.1f} %" if целое else "")


def main() -> int:
    dsn = os.environ.get("SUPABASE_DB_URL", "").strip()
    if not dsn:
        print("нет SUPABASE_DB_URL — мерить нечего")
        return 2
    import psycopg2

    conn = psycopg2.connect(dsn, connect_timeout=20,
                            options="-c statement_timeout=600000")
    try:
        with conn.cursor() as cur:
            print("=== ЧТО ИЗ «НАШЕГО СПРОСА» НА САМОМ ДЕЛЕ НЕ СПРОС ===")
            print("Строки спроса по полю карточки, из которого пришёл файл.\n")
            cur.execute(РАСКЛАДКА)
            строки = cur.fetchall()
            всего = sum(ч(r[2]) for r in строки)
            наших = sum(ч(r[2]) for r in строки if r[0] == "поле сделки")
            print(f"строк спроса всего {всего}, из них по полям сделок {доля(наших, всего)}\n")
            print("ПОЛЯ СДЕЛОК (это и есть нынешний «наш спрос»):")
            print(f"    {'поле':<28s} {'строк':>9s} {'доля':>8s}"
                  f" {'сделок':>7s} {'файлов':>7s} {'кодов':>7s}  что это")
            опознано = 0
            for происх, поле, стр, сдел, фай, код in строки:
                if происх != "поле сделки":
                    continue
                имя = ИЗВЕСТНЫЕ.get(поле)
                если = f"{имя[0]} — {имя[1]}" if имя else "название неизвестно"
                if имя:
                    опознано += ч(стр)
                print(f"    {поле:<28s} {доля(стр, наших)} {ч(сдел):>7d}"
                      f" {ч(фай):>7d} {ч(код):>7d}  {если}")
            print(f"\n    опознано по встроенному списку: {доля(опознано, наших)}")

            # ── РАСКЛАДКА ПО СТОРОНАМ. Главное число замера: сколько из «нашего
            # спроса» на самом деле наши же исходящие документы.
            карта = названия_полей()
            if not карта:
                print("    BITRIX_WEBHOOK_URL не задан — названия полей не взяты,")
                print("    раскладки по сторонам нет. Размер задачи виден выше.")
            else:
                print(f"\n    названий полей получено: {len(карта)}")
                по_стороне: dict[str, list[int]] = {}
                без_имени = [0, 0]
                for происх, поле, стр, _сдел, _фай, код in строки:
                    if происх != "поле сделки":
                        continue
                    имя = карта.get(ключ_поля(поле))
                    if not имя:
                        без_имени[0] += ч(стр)
                        без_имени[1] += ч(код)
                        continue
                    ст = doc_side.сторона(имя)
                    было = по_стороне.setdefault(ст, [0, 0])
                    было[0] += ч(стр)
                    было[1] += ч(код)
                print("\n    ПО СТОРОНАМ ДОКУМЕНТА (правило library/doc_side.py):")
                for ст in doc_side.СТОРОНЫ:
                    if ст not in по_стороне:
                        continue
                    стр, код = по_стороне[ст]
                    спрос = "СПРОС" if ст in doc_side.СПРОС else "не спрос"
                    print(f"        {ст:<12s} строк {доля(стр, наших)}"
                          f" · кодов {код:>7d}  — {спрос}")
                if без_имени[0]:
                    print(f"        {'нет названия':<12s} строк {доля(без_имени[0], наших)}"
                          f" · кодов {без_имени[1]:>7d}  — не спрос")
                спросом = sum(по_стороне.get(ст, [0, 0])[0] for ст in doc_side.СПРОС)
                print(f"\n    НАСТОЯЩИЙ СПРОС: строк {доля(спросом, наших)} от нынешнего")
                print("    «нашего спроса». Остальное — наши исходящие документы,")
                print("    внутренние файлы и предложения, лежащие в поле сделки.")

                # ПОИМЁННО ТОП ПОЛЕЙ: без названий раскладка по сторонам не
                # проверяема глазом, а поля — настройки нашего же Битрикса.
                print("\n    КРУПНЕЙШИЕ ПОЛЯ ПОИМЁННО:")
                показано = 0
                for происх, поле, стр, _с, _ф, код in строки:
                    if происх != "поле сделки" or показано >= 12:
                        continue
                    имя = карта.get(ключ_поля(поле)) or "(названия нет)"
                    ст = doc_side.сторона(имя) if имя != "(названия нет)" else "неизвестно"
                    print(f"        {доля(стр, наших)} · кодов {ч(код):>6d}"
                          f"  {ст:<12s} {имя[:48]}")
                    показано += 1

            print("\nПРОЧИЕ ПРОИСХОЖДЕНИЯ:")
            for происх, поле, стр, сдел, фай, код in строки:
                if происх == "поле сделки":
                    continue
                print(f"    {происх:<16s} {поле:<28s} {доля(стр, всего)}"
                      f" · кодов {ч(код)}")

            cur.execute(ЦЕНЫ_ИЗ_ПОЛЕЙ_СДЕЛКИ)
            цены = cur.fetchall()
            print("\nЦЕНЫ, ПРИШЕДШИЕ ИЗ ПОЛЕЙ СДЕЛОК:")
            if not цены:
                print("    ни одной — разбор писал цены только для карточек запроса.")
                print("    Значит наша исходящая цена во входящие не просочилась.")
            else:
                print("    ВНИМАНИЕ: цены из полей сделок есть. Если среди полей —")
                print("    «Result, ТКП» или «Economics of the project», то наша")
                print("    отпускная цена попала в базу как цена поставщика.")
                for поле, стр, пот in цены:
                    имя = ИЗВЕСТНЫЕ.get(поле)
                    print(f"    {поле:<28s} строк {ч(стр):>7d} · потоков {ч(пот)}"
                          + (f"  ← {имя[0]}" if имя else ""))
        return 0
    finally:
        conn.close()


if __name__ == "__main__":
    raise SystemExit(main())
