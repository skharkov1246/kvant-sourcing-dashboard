    def выбрать(self, совпали: list[dict], шаг: int) -> int | None:
        c = self.client
        if not совпали:
            # совпавшие номера только что прочитаны, а сделки по ним не вернулись: читать
            # карточки не по чему (пустой @parentId2 портал может понять как «без условия»)
            print("::error::совпавшие сделки не прочитаны повторно — разбирать нечего")
            return 1
        кандидаты = sorted(совпали, key=lambda d: (_вр(d.get("DATE_CREATE")) or dt.datetime.min.replace(tzinfo=MSK),
                                                  int(d["ID"])))[-КАНДИДАТОВ:]
        по_сделке: dict[str, list[dict]] = collections.defaultdict(list)
        try:
            if len(кандидаты) == 1:
                карточки = c.list_items(SPA, filter={"parentId2": int(кандидаты[0]["ID"])}, select=КАРТОЧКА_SELECT)
            else:
                карточки = c.list_items(SPA, filter={"@parentId2": [int(d["ID"]) for d in кандидаты]},
                                        select=КАРТОЧКА_SELECT)
            for к in карточки:
                по_сделке[str(к.get("parentId2") or "")].append(к)
            if len(кандидаты) > 1:
                клиенты = set(self.холдинг) | {str(d.get("COMPANY_ID")) for d in кандидаты
                                               if str(d.get("COMPANY_ID") or "") not in ("", "0")}
                названия = self._компании_поставщиков(карточки, клиенты)
                self.сделка = max(кандидаты, key=lambda d: ключ_выбора(d, по_сделке.get(str(d["ID"]), []),
                                                                       названия, клиенты))
            else:
                self.сделка = кандидаты[0]
        except Exception as e:  # noqa: BLE001
            print(f"::error::карточки СП-{SPA} не прочитаны: {код_ошибки(e)} · {место(e)}")
            return 1
        print(f"ВЫБОР: совпало сделок {len(совпали)} (шаг {шаг})"
              + (f", для выбора прочитаны карточки {len(кандидаты)} новейших" if len(кандидаты) > 1 else "")
              + " → разбирается ровно одна сделка")
        self.карточки_сырые = по_сделке.get(str(self.сделка["ID"]), [])
        return None

    # ── справочники поставщиков ───────────────────────────────────────────────────────────
    def _компании_поставщиков(self, карточки, клиенты) -> dict[str, str]:
        ids = set()
        for к in карточки:
            ids |= set(поставщик_карточки(к, {}, клиенты)["companies"])
        self._читать_компании(ids)
        return {i: v["title"] for i, v in self.компании.items()}

    def _читать_компании(self, ids) -> None:
        нужно = {str(i) for i in ids} - set(self.компании)
        for пачка in пачками(нужно):
            for x in по_ключу(self.client, "crm.company.list", {"@ID": пачка}, ["ID", "TITLE", "EMAIL"],
                              учёт=self.учёт, страниц=2):
                self.компании[str(x["ID"])] = {"title": str(x.get("TITLE") or ""), "domains": домены(x.get("EMAIL"))}

    def _читать_контакты(self, фильтр_поле: str, ids) -> dict[str, dict]:
        out: dict[str, dict] = {}
        for пачка in пачками(ids):
            # по @ID пачка в 50 — одна страница; по @COMPANY_ID контактов бывает больше
            for x in по_ключу(self.client, "crm.contact.list", {фильтр_поле: пачка}, ["ID", "COMPANY_ID", "EMAIL"],
                              учёт=self.учёт, страниц=2 if фильтр_поле == "@ID" else СТРАНИЦ_НА_СПИСОК):
                cid = str(x.get("COMPANY_ID") or "")
                out[str(x["ID"])] = {"company": "" if cid in ("", "0") else cid, "domains": домены(x.get("EMAIL"))}
        return out

    def клиенты(self) -> set[str]:
        cid = str(self.сделка.get("COMPANY_ID") or "")
        return set(self.холдинг) | ({cid} if cid not in ("", "0") else set())

    # ── сделка: паспорт, товарные строки, поставщики ──────────────────────────────────────
    def паспорт(self) -> int | None:
        c, d = self.client, self.сделка
