def silence_bucket(wd: int | None) -> str:
    if wd is None:
        return ВНЕ_КАЛЕНДАРЯ
    for порог, имя in КОРЗИНЫ_МОЛЧАНИЯ:
        if порог is None or wd <= порог:
            return имя
    return КОРЗИНЫ_МОЛЧАНИЯ[-1][1]


def card_status(к: dict, сегодня: dt.date) -> dict:
    """Один статус карточки по старшинству (шапка). Молчание — только без КП и без ответа."""
    b = к.get("bucket") or ""
    h = к.get("hist") or {}
    писем = int(к.get("letters") or 0)
    if к.get("offer") or к.get("quote_any") or b in KP_STAGES or any(x in h for x in KP_STAGES):
        sub = "выбран" if b == "selected" else "не выбран" if b == "notsel" else "без итога"
        return {"status": "КП", "sub": sub}
    if b == "refused":
        return {"status": "отказ", "sub": ""}
    по_стадии = b == "dialog" or any(x in h for x in ОТВЕТ_СТАДИИ)
    по_письму = к.get("reply") is not None or bool(к.get("in_card"))
    if по_стадии or по_письму:
        sub = "по стадии и письму" if по_стадии and по_письму else "по стадии" if по_стадии else "по письму"
        return {"status": "ответ без КП", "sub": sub}
    if писем or b in ("sent", "no_answer") or "sent" in h or "no_answer" in h:
        от = к.get("last_out") or h.get("sent") or к.get("created")
        wd = period_mod.workdays_ru(от, сегодня) if от else None
        return {"status": "молчание", "sub": silence_bucket(wd), "wd": wd,
                "closed": b == "no_answer", "no_letter": not писем}
    if not b:
        return {"status": "прочее", "sub": ""}
    if b == "new":
        return {"status": "не отправлена", "sub": ""}
    return {"status": "двинута без письма", "sub": ""}


def время_ответа(к: dict) -> dt.datetime | None:
    """Первый признак ответа: засчитанное письмо, входящее на карточке, вход в переписку,
    отказ или стадию КП."""
    h = к.get("hist") or {}
    метки = [к.get("reply")] + list(к.get("in_card") or [])[:1]
    метки += [h.get(x) for x in ("dialog", "refused", *sorted(KP_STAGES))]
    метки = [t for t in метки if t]
    return min(метки) if метки else None


def время_кп(к: dict) -> dt.datetime | None:
    """Вход в стадию КП по истории; нет — дата засчитанного ответа у карточки с файлом КП."""
    h = к.get("hist") or {}
    метки = [h[x] for x in KP_STAGES if h.get(x)]
    if метки:
        return min(метки)
    if (к.get("offer") or к.get("quote_any")) and к.get("reply"):
        return к["reply"]
    return None


def мед(xs) -> float | None:
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None


def _рд(a, b) -> int | None:
    if a is None or b is None:
        return None
    return period_mod.workdays_ru(a, b)


def _строка() -> dict:
    return {"строк": 0, "карточек": 0, "поставщики": set(), "производители": set(), "отправлено": 0,
            "ответ": 0, "КП": 0, "КП Offer": 0, "КП в любом поле": 0, "отказ": 0, "молчат": 0,
            f"молчат > {ДОЛГО_РД} р.д.": 0}


def aggregate(карточки: list[dict], бренды_строк: list[str], сегодня: dt.date,
              создана_сделка: dt.datetime | None = None) -> dict:
    """Свод по карточкам одной сделки. Карточка: id, brand, brand_src, stype, supplier, owner,
    owner_by, bucket, letters, first_out, last_out, hist, reply, reply_thread, offer,
    quote_any, created. Статус пишется в карточку (к['st'])."""
    итог: dict = {"всего": len(карточки), "статусы": collections.Counter(), "кп": collections.Counter(),
                  "кп_основание": collections.Counter(), "кп_сейчас": collections.Counter(),
                  "ответ": collections.Counter(),
                  "молчание": collections.Counter(), "закрыто_нет_ответа": 0, "молчат_без_письма": 0,
                  "молчат_с_дожимом": 0, "без_дожима_долго": 0, "отправлено": 0, "письмом": 0,
                  "дожим": 0, "бренд_откуда": collections.Counter()}
    по_бренду: dict[str, dict] = collections.defaultdict(_строка)
    по_виду: dict[str, dict] = collections.defaultdict(_строка)
    for b in бренды_строк:
        по_бренду[b or НЕТ_БРЕНДА]["строк"] += 1
    долго = f"молчат > {ДОЛГО_РД} р.д."
    for к in карточки:
        st = card_status(к, сегодня)
        к["st"] = st
        s = st["status"]
        итог["статусы"][s] += 1
        итог["бренд_откуда"][к.get("brand_src") or "не указан"] += 1
        письма = int(к.get("letters") or 0)
        итог["письмом"] += письма > 0
        итог["дожим"] += письма >= 2
        if s == "КП":
            итог["кп"][st["sub"]] += 1
            b = к.get("bucket") or ""
            основание = ("файл Offer from supplier" if к.get("offer") else
                         "файл только в архивном поле" if к.get("quote_any") else
                         "стадия КП сейчас" if b in KP_STAGES else "стадия КП только в истории")
            итог["кп_основание"][основание] += 1
            if основание == "стадия КП только в истории":
                итог["кп_сейчас"][b or "нет стадии"] += 1
        elif s == "ответ без КП":
            итог["ответ"][st["sub"]] += 1
        elif s == "молчание":
            итог["молчание"][st["sub"]] += 1
            итог["закрыто_нет_ответа"] += bool(st.get("closed"))
            итог["молчат_без_письма"] += bool(st.get("no_letter"))
            итог["молчат_с_дожимом"] += письма >= 2
            итог["без_дожима_долго"] += письма < 2 and (st.get("wd") or 0) > ДОЛГО_РД
        итог["отправлено"] += s in ОТПРАВЛЕНО
        for строка in (по_бренду[к.get("brand") or НЕТ_БРЕНДА], по_виду[к.get("stype") or ВИДЫ[2]]):
            строка["карточек"] += 1
            if к.get("supplier"):
                строка["поставщики"].add(к["supplier"])
                if к.get("stype") == "производитель":
                    строка["производители"].add(к["supplier"])
            строка["отправлено"] += s in ОТПРАВЛЕНО
            строка["ответ"] += s in С_ОТВЕТОМ
            строка["КП"] += s == "КП"
            строка["КП Offer"] += bool(к.get("offer"))
            строка["КП в любом поле"] += bool(к.get("offer") or к.get("quote_any"))
            строка["отказ"] += s == "отказ"
            строка["молчат"] += s == "молчание"
            строка[долго] += s == "молчание" and (st.get("wd") or 0) > ДОЛГО_РД
    итог["по_бренду"], итог["по_виду"] = dict(по_бренду), dict(по_виду)

    с_карточками = {b for b, r in по_бренду.items() if r["карточек"] and b != НЕТ_БРЕНДА}
    итог["покрытие"] = {
        "строки без карточек": sorted(b for b, r in по_бренду.items()
                                      if r["строк"] and not r["карточек"] and b != НЕТ_БРЕНДА),
        "нет запроса производителю": sorted(b for b in с_карточками if not по_бренду[b]["производители"]),
        "нет ни одного ответа": sorted(b for b in с_карточками if not по_бренду[b]["ответ"]),
    }
    у_поставщика = collections.Counter(к["supplier"] for к in карточки if к.get("supplier"))
    дубли = {k: n for k, n in у_поставщика.items() if n >= 2}
    итог["дубли"] = (len(дубли), sum(дубли.values()))

    первая = min((к["created"] for к in карточки if к.get("created")), default=None)
    сроки: dict[str, list] = {
        "сделка создана → первая карточка": [_рд(создана_сделка, первая)],
        "сделка создана → карточка создана": [_рд(создана_сделка, к.get("created")) for к in карточки],
        "карточка создана → первое письмо": [_рд(к.get("created"), к.get("first_out")) for к in карточки],
        "первое письмо → первый ответ": [_рд(к.get("first_out"), время_ответа(к)) for к in карточки
                                        if к["st"]["status"] in С_ОТВЕТОМ],
        "первое письмо → КП": [_рд(к.get("first_out"), время_кп(к)) for к in карточки if к["st"]["status"] == "КП"],
    }
    итог["сроки"] = {}
    for имя, xs in сроки.items():
        xs = [x for x in xs if x is not None]
        итог["сроки"][имя] = (мед([x for x in xs if x >= 0]), sum(1 for x in xs if x >= 0),
                              sum(1 for x in xs if x < 0))

    люди: dict[str, dict] = collections.defaultdict(lambda: {"карточек": 0, "отправлено": 0, "молчат": 0, "КП": 0})
    for к in карточки:
        r = люди[к.get("owner") or ""]
        r["карточек"] += 1
        r["отправлено"] += к["st"]["status"] in ОТПРАВЛЕНО
        r["молчат"] += к["st"]["status"] == "молчание"
        r["КП"] += к["st"]["status"] == "КП"
    порядок = sorted((u for u in люди if u), key=lambda u: (-люди[u]["карточек"], -люди[u]["отправлено"], u))
    итог["сорсеры"] = [(f"сорсер#{i}", люди[u]) for i, u in enumerate(порядок, 1)]
    if "" in люди:
        итог["сорсеры"].append(("не определён", люди[""]))
    итог["сорсеров"] = len(порядок)
    итог["сорсер_откуда"] = collections.Counter(к.get("owner_by") or "не определён" for к in карточки)
    итог["в_ветке"] = (sum(1 for к in карточки if к.get("reply") is not None and к.get("reply_thread")),
                       sum(1 for к in карточки if к.get("reply") is not None))
    return итог


