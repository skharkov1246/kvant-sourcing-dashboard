# ── чистые функции: бренд и поставщик ──────────────────────────────────────────────────────

def _текст(s) -> str:
    return str(s or "").lower().replace("ё", "е")


def бренд_текста(текст, по: int = 1) -> str | None:
    """Бренд, стоящий в тексте раньше других (по=1 — образец бренда, по=2 — производителя)."""
    s = _текст(текст)
    if not s:
        return None
    лучший = None
    for i, запись in enumerate(БРЕНДЫ):
        m = запись[по].search(s)
        if m and (лучший is None or (m.start(), i) < лучший[:2]):
            лучший = (m.start(), i, запись[0])
    return лучший[2] if лучший else None


def brand_of(название_карточки, название_поставщика, бренды_сделки=()) -> tuple[str, str]:
    """(бренд, откуда): карточка → поставщик (только образец бренда: материнская компания из
    образца производителя продаёт и другое) → ровно один бренд товарных строк сделки
    («сделка») → «бренд не указан»."""
    b = бренд_текста(название_карточки)
    if b:
        return b, "карточка"
    b = бренд_текста(название_поставщика)
    if b:
        return b, "поставщик"
    в_сделке = {x for x in бренды_сделки if x and x != НЕТ_БРЕНДА}
    if len(в_сделке) == 1:
        return next(iter(в_сделке)), "сделка"
    return НЕТ_БРЕНДА, ""


def supplier_type(бренд: str, название_поставщика, есть_поставщик: bool) -> str:
    """Производитель — название компании поставщика совпало с образцом производителя бренда;
    поставщик не указан — ни компании, ни контакта; иначе дилер/трейдер."""
    if not есть_поставщик:
        return "поставщик не указан"
    образец = ПРОИЗВОДИТЕЛЬ.get(бренд)
    if образец and образец.search(_текст(название_поставщика)):
        return "производитель"
    return "дилер/трейдер"


def ссылки_crm(val) -> tuple[list[str], list[str]]:
    """Значение crm-поля (['CO_5', 'C_7', 'CT_8', '9']) → (компании, контакты) в порядке поля;
    то же правило, что main._crm_ref_ids."""
    comps: list[str] = []
    conts: list[str] = []
    for x in (val if isinstance(val, list) else [val] if val else []):
        s = str(x).strip()
        if s.startswith("CO_"):
            comps.append(s[3:])
        elif s.startswith("CT_"):
            conts.append(s[3:])
        elif s.startswith("C_"):
            conts.append(s[2:])
        elif s.isdigit():
            comps.append(s)
    return ([c for c in dict.fromkeys(comps) if c not in ("", "0")],
            [c for c in dict.fromkeys(conts) if c not in ("", "0")])


def поставщик_карточки(к: dict, компания_контакта: dict[str, str], клиенты: set[str]) -> dict:
    """Компании и контакты поставщика карточки. Порядок компаний: поле «Supplier», затем
    companyId, затем компании контактов. Компании клиента (сделки и холдинга) — не поставщик:
    companyId карточки бывает унаследован от сделки."""
    c1, t1 = ссылки_crm(к.get("ufCrm18Supplier"))
    c2, t2 = ссылки_crm(к.get("ufCrm18SupplContact"))
    контакты = list(dict.fromkeys(t1 + t2))
    cid = str(к.get("companyId") or "")
    компании = c1 + c2 + ([cid] if cid not in ("", "0") else [])
    компании += [компания_контакта[t] for t in контакты if компания_контакта.get(t)]
    клиентская = cid in клиенты
    компании = [c for c in dict.fromkeys(компании) if c not in клиенты]
    ключ = f"CO{компании[0]}" if компании else f"CT{контакты[0]}" if контакты else ""
    return {"companies": компании, "contacts": контакты, "key": ключ, "client_company": клиентская}


def исполнитель(к: dict, служебные=None) -> tuple[str, str]:
    """(сорсер, чем определён): первый живой из ответственного и следов человека."""
    служебные = config.SERVICE_ACCOUNT_IDS if служебные is None else служебные
    for поле, как in СЛЕДЫ:
        u = str(к.get(поле) or "")
        if u and u not in ("0", "None") and u not in служебные:
            return u, как
    return "", "не определён"


def есть_файл(v) -> bool:
    return any(v) if isinstance(v, list) else bool(v)


def ключ_выбора(сделка: dict, карточки: list[dict], названия: dict[str, str], клиенты: set[str]) -> tuple:
    """Порядок совпавших сделок (больше — лучше): карточек с брендом компрессора (по названию
    карточки или поставщика; поставщик — и образцом производителя), затем карточек, затем
    дата создания, затем номер."""
    компр = 0
    for к in карточки:
        компании = поставщик_карточки(к, {}, клиенты)["companies"]
        название_п = названия.get(компании[0], "") if компании else ""
        if brand_of(к.get("title"), название_п)[0] != НЕТ_БРЕНДА or бренд_текста(название_п, по=2):
            компр += 1
    return (компр, len(карточки), _вр(сделка.get("DATE_CREATE")) or dt.datetime.min.replace(tzinfo=MSK),
            int(сделка["ID"]))


# ── чистые функции: письма ──────────────────────────────────────────────────────────────────

_АДРЕС = re.compile(r"[\w.%+\-]+@([\w\-]+(?:\.[\w\-]+)+)")
_ВТОРОЙ_УРОВЕНЬ = {"co", "com", "net", "org", "ac", "gov", "edu", "ltd", "plc", "or", "ne"}
_ПРЕФИКС = re.compile(r"^\s*(?:(?:re|fw|fwd|aw|wg|sv|tr|отв|ответ|пересл|переслано)\s*(?:\[\d+\])?\s*[:：]\s*)+", re.I)


def домен(адрес: str) -> str:
    """Регистрируемый домен адреса: eu.mail.example.com → example.com, x.co.uk → x.co.uk."""
    m = _АДРЕС.search(str(адрес or ""))
    if not m:
        return ""
    ч = m.group(1).lower().strip(".").split(".")
    if len(ч) >= 3 and ч[-2] in _ВТОРОЙ_УРОВЕНЬ and len(ч[-1]) == 2:
        return ".".join(ч[-3:])
    return ".".join(ч[-2:])


def домены(*значения) -> set[str]:
    """Все домены из строк, списков и словарей (мульти-поле EMAIL: [{'VALUE': …}])."""
    out: set[str] = set()
    for v in значения:
        if isinstance(v, dict):
            out |= домены(*v.values())
        elif isinstance(v, (list, tuple, set)):
            out |= домены(*v)
        elif v:
            for m in _АДРЕС.finditer(str(v)):
                d = домен(m.group(0))
                if d:
                    out.add(d)
    return out


def тема(s) -> str:
    s = _ПРЕФИКС.sub("", _текст(s))
    return re.sub(r"\s+", " ", s).strip()


def в_ветке(тема_входящего: str, темы_наших) -> bool:
    t = тема(тема_входящего)
    if len(t) < МИН_ТЕМА:
        return False
    return any(o and len(o) >= МИН_ТЕМА and (o in t or t in o) for o in темы_наших)


def _вр(v) -> dt.datetime | None:
    """Метка портала → datetime с поясом (без пояса — МСК); пусто и мусор — None."""
    if isinstance(v, list):
        return _вр(v[0]) if v else None
    if v in (None, "", 0, "0", False):
        return None
    if isinstance(v, dt.datetime):
        return v if v.tzinfo else v.replace(tzinfo=MSK)
    if isinstance(v, dt.date):
        return dt.datetime(v.year, v.month, v.day, tzinfo=MSK)
    s = str(v).strip()
    try:
        t = dt.datetime.fromisoformat(s)
    except ValueError:
        m = re.match(r"(\d{4}-\d\d-\d\d)", s)
        if not m:
            return None
        t = dt.datetime.fromisoformat(m.group(1))
    return t if t.tzinfo else t.replace(tzinfo=MSK)


def разбор_письма(a: dict) -> dict:
    """Дело-письмо → {id, type, owner, dir, t, subj, from, to, ents}. Адреса — только домены."""
    s = a.get("SETTINGS") if isinstance(a.get("SETTINGS"), dict) else {}
    meta = s.get("EMAIL_META") if isinstance(s.get("EMAIL_META"), dict) else {}
    направление = str(a.get("DIRECTION") or "")
    комм = [c for c in (a.get("COMMUNICATIONS") or []) if isinstance(c, dict)]
    адреса_комм = домены([c.get("VALUE") for c in комм])
    ents = set()
    for c in комм:
        тип, eid = str(c.get("ENTITY_TYPE_ID") or ""), str(c.get("ENTITY_ID") or "")
        if тип in (str(КОНТАКТ), str(КОМПАНИЯ)) and eid not in ("", "0"):
            ents.add((int(тип), eid))
    # «__to» — запасное поле получателя, как в main._email_to
    получатели = (meta.get("to"), meta.get("__to"), meta.get("cc"), meta.get("bcc"))
    if направление == ИСХОДЯЩЕЕ:
        от, кому = домены(meta.get("from")), домены(*получатели) | адреса_комм
    else:
        от, кому = домены(meta.get("from"), meta.get("replyTo")) | адреса_комм, домены(*получатели[:2])
    return {"id": str(a.get("ID") or ""), "type": int(a.get("OWNER_TYPE_ID") or 0),
            "owner": str(a.get("OWNER_ID") or ""), "dir": направление, "t": _вр(a.get("CREATED")),
            "subj": тема(a.get("SUBJECT")), "from": от, "to": кому, "ents": ents}


def сводка_писем(письма: list[dict], карточки: set[str]) -> tuple[dict[str, dict], int]:
    """Письма карточек → {карточка: {out, in, to, own, subj, ents}} и число писем с чужим
    владельцем (отброшены). out/in — отсортированные метки исходящих/входящих."""
    out: dict[str, dict] = {}
    чужие = 0
    for p in письма:
        cid = p["owner"]
        if cid not in карточки or p["type"] not in (0, SPA):
            чужие += 1
            continue
        с = out.setdefault(cid, {"out": [], "in": [], "to": set(), "own": set(), "subj": set(), "ents": set()})
        if p["dir"] == ВХОДЯЩЕЕ:
            if p["t"]:
                с["in"].append(p["t"])
            continue
        if p["t"]:
            с["out"].append(p["t"])
        с["to"] |= p["to"]
        с["own"] |= p["from"]
        с["ents"] |= p["ents"]
        if p["subj"]:
            с["subj"].add(p["subj"])
    for с in out.values():
        с["out"].sort()
        с["in"].sort()
    return out, чужие


def первые_входы(переходы) -> dict[str, dt.datetime]:
    """[(стадия, время), …] → {корзина: первый вход}."""
    out: dict[str, dt.datetime] = {}
    for s, t in sorted(((s, _вр(t)) for s, t in (переходы or ()) if _вр(t)), key=lambda x: x[1]):
        out.setdefault(classify_stage(str(s or "")), t)
    return out


def якорь(к: dict) -> dt.datetime | None:
    """От чего считать ответ письмом: первое наше письмо, иначе первый вход в «отправлен» или
    «нет ответа» по истории. Нет ни того, ни другого — None: карточку не отправляли, и письмо
    поставщика (он пишет и о других сделках) ответом ей не засчитывается. Создание карточки
    якорем не бывает."""
    if к.get("first_out"):
        return к["first_out"]
    h = к.get("hist") or {}
    входы = [h[x] for x in ("sent", "no_answer") if h.get(x)]
    return min(входы) if входы else None


def общие(карточки: list[dict], поле: str) -> set:
    """Домены или адресаты, которые встречаются у разных поставщиков: ничьи. Карточка без
    поставщика своего поставщика не заводит: её домен — обычно домен того же поставщика."""
    чьи: dict = collections.defaultdict(set)
    for к in карточки:
        if not к.get("supplier"):
            continue
        for x in к.get(поле) or ():
            чьи[x].add(к["supplier"])
    return {x for x, s in чьи.items() if len(s) > 1}


def сопоставить_ответы(карточки: list[dict], входящие: list[dict], не_поставщика: set[str]) -> dict[str, dict]:
    """Засчитанные ответы: {карточка: {t, thread, src, n}} — первое входящее письмо от поставщика
    карточки ПОСЛЕ её якоря; thread — есть ли засчитанное письмо в ветке нашего письма.
    Письмо, подходящее нескольким карточкам одного поставщика, идёт только тем, в чьей ветке
    оно лежит; ни в чьей — всем подходящим. не_поставщика — наши и клиентские домены.
    Карточка мутируется: domains и ents очищаются от общих у разных поставщиков."""
    ничьи_домены = общие(карточки, "domains")
    ничьи_адресаты = общие(карточки, "ents")
    кандидаты = []
    for к in карточки:
        к["domains"] = set(к.get("domains") or ()) - ничьи_домены - не_поставщика - БЕСПЛАТНАЯ_ПОЧТА
        к["ents"] = set(к.get("ents") or ()) - ничьи_адресаты
        компании = set(к.get("companies") or ()) | {e for т, e in к["ents"] if т == КОМПАНИЯ}
        контакты = set(к.get("contacts_all") or к.get("contacts") or ()) | {e for т, e in к["ents"] if т == КОНТАКТ}
        кандидаты.append((к, якорь(к), компании, контакты))
    out: dict[str, dict] = {}
    for p in sorted((p for p in входящие if p.get("t")), key=lambda p: p["t"]):
        кто = set(p.get("ents") or ())
        if p.get("type") in (КОНТАКТ, КОМПАНИЯ):
            кто.add((p["type"], p["owner"]))
        подошли = []
        for к, от, компании, контакты in кандидаты:
            if от is None or p["t"] <= от:
                continue
            if any(т == КОМПАНИЯ and e in компании for т, e in кто):
                src = "компания"
            elif any(т == КОНТАКТ and e in контакты for т, e in кто):
                src = "контакт"
            elif (set(p.get("from") or ()) - не_поставщика) & к["domains"]:
                src = "домен"
            else:
                continue
            подошли.append((к, src, в_ветке(p.get("subj") or "", к.get("subj") or ())))
        if any(ветка for _, _, ветка in подошли):
            подошли = [x for x in подошли if x[2]]
        for к, src, ветка in подошли:
            r = out.setdefault(к["id"], {"t": p["t"], "src": src, "thread": False, "n": 0})
            r["n"] += 1
            r["thread"] = r["thread"] or ветка
    return out


