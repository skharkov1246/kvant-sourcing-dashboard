class Учёт:
    """Запросы этого прогона — по общему счётчику клиента (bc._НАГРУЗКА), от старта."""

    def __init__(self, предел: int = БЮДЖЕТ["предел"]):
        self.предел = предел
        self.старт = int(bc._НАГРУЗКА.get("запросов", 0))

    def сейчас(self) -> int:
        return int(bc._НАГРУЗКА.get("запросов", 0)) - self.старт

    def проверить(self) -> None:
        if self.сейчас() >= self.предел:
            raise ОшибкаЧтения(f"предел прогона {self.предел} запросов исчерпан")


def чужих_много(свои: set[str], значения) -> bool:
    """Фильтр по номерам не сработал: чужих значений на странице не меньше МИН_ЧУЖИХ и больше
    половины. При отброшенном фильтре чужая — вся страница (50 строк); немного чужих бывает и
    при сработавшем: письмо привязано к нескольким владельцам одного типа, контакт — к
    нескольким компаниям, а в строке стоит номер основного."""
    значения = [str(v) for v in значения]
    чужих = sum(1 for v in значения if v not in свои)
    return чужих >= МИН_ЧУЖИХ and 2 * чужих > len(значения)


def _свои_номера(ids) -> set[str]:
    return {str(x) for x in (ids if isinstance(ids, list) else [ids])}


def владельцы_свои(фильтр: dict, ch: list[dict]) -> bool:
    """Строки дел — того владельца, что в фильтре. Дело с другим типом владельца (привязка) —
    не в счёт; того же типа с чужим номером — в счёт чужих (чужих_много)."""
    тип, ids = фильтр.get("OWNER_TYPE_ID"), фильтр.get("OWNER_ID")
    if тип is None or ids is None:
        return True
    значения = [r.get("OWNER_ID") for r in ch if str(r.get("OWNER_TYPE_ID")) == str(тип)]
    return not чужих_много(_свои_номера(ids), значения)


def строки_свои(фильтр: dict, ch: list[dict]) -> bool:
    """Строки компаний и контактов — тех номеров, что в фильтре @ID или @COMPANY_ID."""
    for ключ, поле in (("@ID", "ID"), ("@COMPANY_ID", "COMPANY_ID")):
        if ключ in фильтр and чужих_много(_свои_номера(фильтр[ключ]), [r.get(поле) for r in ch]):
            return False
    return True


def по_ключу(client, method: str, фильтр: dict, select, *, учёт: Учёт | None = None,
             страниц: int = СТРАНИЦ_НА_СПИСОК) -> list[dict]:
    """Список по ключу >ID со start −1 (без подсчёта total). Длиннее `страниц` — ошибка: у
    отфильтрованного по номерам списка столько страниц значит, что фильтр не сработал. Кроме
    того, каждая страница сверяется с фильтром по номерам (владельцы_свои у дел, строки_свои у
    компаний и контактов): не сработал — ошибка с первой же страницы."""
    out: list[dict] = []
    last = 0
    for _ in range(страниц):
        if учёт:
            учёт.проверить()
        f = dict(фильтр)
        f[">ID"] = last
        ch = client.call(method, {"filter": f, "select": list(select), "order": {"ID": "ASC"}, "start": -1}) or []
        if isinstance(ch, dict):
            ch = list(ch.values())
        if not ch:
            return out
        if method == "crm.activity.list" and not владельцы_свои(фильтр, ch):
            raise ОшибкаЧтения("crm.activity.list: фильтр OWNER_ID массивом не сработал — обход остановлен")
        if not строки_свои(фильтр, ch):
            raise ОшибкаЧтения(f"{method}: фильтр по номерам не сработал — обход остановлен")
        out.extend(ch)
        last = int(ch[-1]["ID"])
        if len(ch) < 50:
            return out
    raise ОшибкаЧтения(f"{method}: список длиннее {страниц} страниц — фильтр, похоже, не сработал")


def пачками(ids, n: int = 50):
    ids = sorted({str(x) for x in ids if str(x) not in ("", "0")}, key=int)
    for i in range(0, len(ids), n):
        yield [int(x) for x in ids[i:i + n]]


def код_ошибки(e: BaseException) -> str:
    """Код отказа портала без описания: в описании бывают имена. У ОшибкаЧтения сообщение —
    постоянная строка кода с числами, она печатается целиком."""
    if isinstance(e, ОшибкаЧтения):
        return str(e)
    m = re.match(r"^[\w.]+: ([A-Za-z][A-Za-z0-9_]{2,40})\b", str(e))
    return m.group(1) if m else type(e).__name__


def место(e: BaseException) -> str:
    места = []
    tb = e.__traceback__
    while tb:
        места.append(f"{Path(tb.tb_frame.f_code.co_filename).name}:{tb.tb_lineno}")
        tb = tb.tb_next
    return " → ".join(места[-3:])


def частей() -> tuple[int, str]:
    """PROBE_PARTS → (число частей, замечание): 10, 25 или 50; меньше 10 — 10."""
    сырое = os.environ.get("PROBE_PARTS") or str(ЧАСТИ[0])
    try:
        n = int(сырое)
    except ValueError:
        return ЧАСТИ[0], f"PROBE_PARTS не число — взято {ЧАСТИ[0]}"
    if n < ЧАСТИ[0]:
        return ЧАСТИ[0], f"PROBE_PARTS={n} меньше {ЧАСТИ[0]} — взято {ЧАСТИ[0]} (распоряжение 22.09)"
    if n in ЧАСТИ:
        return n, ""
    взято = next((k for k in ЧАСТИ if k >= n), ЧАСТИ[-1])
    return взято, f"PROBE_PARTS={n} не из {ЧАСТИ} — взято {взято}"


def разбить(ids, n: int) -> list[list[str]]:
    """Номера карточек → ровно min(n, число карточек) смежных срезов по возрастанию номера,
    почти равных (размеры отличаются не больше чем на 1, большие — первыми)."""
    ids = sorted({str(x) for x in ids}, key=int)
    if not ids or n < 1:
        return []
    k = min(n, len(ids))
    q, r = divmod(len(ids), k)
    out, i = [], 0
    for j in range(k):
        размер = q + (1 if j < r else 0)
        out.append(ids[i:i + размер])
        i += размер
    return out


def запасной_помещается(всего: int, предел_сделок: int, израсходовано: int, предел: int) -> str:
    """Почему запасной шаг 2 не читается ('' — читается): сделок больше предела шага, или его
    страниц (по 50 сделок) вместе с РЕЗЕРВОМ на разбор не хватает в остатке предела прогона."""
    if всего > предел_сделок:
        return f"сделок {всего} — больше предела запасного шага {предел_сделок}"
    страниц = -(-всего // 50)
    if израсходовано + страниц + РЕЗЕРВ > предел:
        return (f"страниц {страниц} и запас {РЕЗЕРВ} на разбор не помещаются в остаток предела "
                f"{предел - израсходовано} из {предел}")
    return ""


def запасной_предел() -> int:
    try:
        return int(os.environ.get("PROBE_LIMIT") or ЗАПАСНОЙ_ПРЕДЕЛ)
    except ValueError:
        return ЗАПАСНОЙ_ПРЕДЕЛ


def доля(a: int, b: int) -> str:
    return f"{a} из {b} ({100 * a / b:.0f} %)" if b else f"{a} из 0"


def чс(x) -> str:
    return "—" if x is None else f"{x:g}" if float(x).is_integer() else f"{x:.1f}"


def счёт(c: collections.Counter, порядок=()) -> str:
    ключи = [k for k in порядок if c.get(k)] + [k for k, _ in c.most_common() if k not in порядок]
    return " · ".join(f"{k} {c[k]}" for k in ключи if c.get(k)) or "—"


