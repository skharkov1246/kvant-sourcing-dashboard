# ── чистые функции: запрос и сделка ─────────────────────────────────────────────────────────

_НЕ_ЗНАК = re.compile(r"[^0-9a-zа-я]+")
_ХЕШ = re.compile(r"^[0-9a-f]{64}$")


def токены(текст) -> list[str]:
    """Нижний регистр, ё → е, разрез по всему, кроме a–z, а–я и цифр; пустые отброшены.
    «ТЕСТ-2030 ЗИП» → ['тест', '2030', 'зип']."""
    s = str(текст or "").lower().replace("ё", "е")
    return [t for t in _НЕ_ЗНАК.split(s) if t]


def хеш(токен: str) -> str:
    return hashlib.sha256(токен.encode("utf-8")).hexdigest()


def хеши_названия(текст) -> set[str]:
    return {хеш(t) for t in токены(текст)}


def разобрать_запрос(сырое: str | None) -> list[str] | None:
    """Вход → список хешей (без повторов, в порядке входа) или None, если вход не того вида:
    пусто, элементов (с повторами) больше 8, или хоть один элемент — после снятия пробелов по
    краям — не ровно ^[0-9a-f]{64}$ (заглавные и пустой элемент между запятыми — не того вида)."""
    s = str(сырое or "").strip()
    if not s:
        return None
    части = [x.strip() for x in s.split(",")]
    if not 1 <= len(части) <= 8 or not all(_ХЕШ.match(x) for x in части):
        return None
    return list(dict.fromkeys(части))


def сырой_запрос(environ=None) -> str | None:
    """Вход зонда: env PROBE_QUERY (тесты, локальный запуск), без него — inputs.query ручного
    запуска из файла события раннера ($GITHUB_EVENT_PATH). В env шага probe.yml вход нарочно
    не кладётся: значения env шага GitHub печатает в заголовке шага публичного журнала.
    Файл не читается или в нём нет входа — None (выход 2, без эха)."""
    environ = os.environ if environ is None else environ
    сырое = environ.get("PROBE_QUERY")
    if сырое:
        return сырое
    путь = environ.get("GITHUB_EVENT_PATH")
    if not путь:
        return None
    try:
        with open(путь, encoding="utf-8") as f:
            событие = json.load(f)
    except (OSError, ValueError):
        return None
    входы = событие.get("inputs") if isinstance(событие, dict) else None
    q = входы.get("query") if isinstance(входы, dict) else None
    return q if isinstance(q, str) else None


def маска(хеши) -> list[str]:
    """Строки ::add-mask:: для каждого хеша: раннер их не печатает и прячет значение, если
    оно где-то всплывёт в журнале. Зонд хешей не печатает; это вторая стена."""
    return [f"::add-mask::{x}" for x in хеши]


def совпадает(название, запрос) -> bool:
    """Каждый хеш запроса есть среди хешей токенов названия."""
    return bool(запрос) and set(запрос) <= хеши_названия(название)


def по_токенам(названия, запрос) -> list[int]:
    """По каждому хешу запроса — у скольких названий он есть (только числа)."""
    множества = [хеши_названия(н) for н in названия]
    return [sum(1 for м in множества if h in м) for h in запрос]


def из_холдинга(название, холдинг: str | None = None, образец: re.Pattern | None = None) -> bool:
    """Компания — из холдинга: kam.client_dir относит её к холдингу, или образец (латиница).
    Без аргументов — ХОЛДИНГ и ХОЛДИНГ_RX модуля в момент вызова (тесты подставляют свои)."""
    n = str(название or "")
