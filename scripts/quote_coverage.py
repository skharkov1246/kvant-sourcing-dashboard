#!/usr/bin/env python3
"""Котировка как документ: что о цене вообще известно в карточках СП-166.

ЗАЧЕМ. Этап 3 плана — хранить котировку документом: валюта, базис цены, единица,
наличие тремя осями. Прежде чем строить хранение, надо знать, из чего его
наполнять: сколько карточек несут сумму, в каких валютах, и у скольких вообще
приложено КП поставщика. Правило сначала меряют, потом применяют (CLAUDE.md,
правило 3).

СТОРОНА ДОКУМЕНТА ВАЖНЕЕ ЕГО НАЛИЧИЯ. В карточке лежат и наши файлы, и файлы
поставщика. «Request file» — наш запрос, и считать его за полученное КП значит
объявить прокотированным то, что мы сами же и отправили. Эта ошибка уже была
поймана в джойне brand_suppliers (пункт 0.3 плана), и здесь она повторена быть
не должна: ПОЛЯ_КП — закрытый список полей ТОЛЬКО со стороны поставщика.

СУММА НА КАРТОЧКЕ — НЕ ЦЕНА СТРОКИ. opportunity показывает величину сделки
целиком, а спецификация внутри может быть на сотни позиций. Из него нельзя
достать цену позиции, и складывать его с построчными ценами нельзя тоже.

В журнал идут только агрегаты: ни названий, ни номеров карточек (правило 17).

    BITRIX_WEBHOOK_URL=… python scripts/quote_coverage.py
"""
from __future__ import annotations

import collections
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from stages import classify_stage  # noqa: E402

SPA_RFQ = 166

# ФАЙЛЫ СО СТОРОНЫ ПОСТАВЩИКА. Закрытый список: добавлять сюда поле можно только
# убедившись, что его кладёт поставщик, а не мы.
ПОЛЯ_КП = {
    "ufCrm18_1700698211875": "КП поставщика",
    "ufCrm18_1703711961310": "Offer, old",
    "ufCrm18_1703712059311": "Processed offer",
    "ufCrm18_1703712074559": "Processed offer / archive",
    "ufCrm18_1731179998": "Offer from supplier",
}
# НАШ файл. Считается отдельно и в «прокотировано» не идёт никогда.
ПОЛЕ_ЗАПРОСА = "ufCrm18_1727423346"
ДАЛ_КП = {"selected"}


def есть_файл(v) -> bool:
    """Поле файла приходит списком, словарём или пустым. Пустое — это ноль файлов."""
    if not v:
        return False
    if isinstance(v, list):
        return any(есть_файл(x) for x in v)
    return True


def доля(часть: int, целое: int) -> str:
    return f"{часть}/{целое}" + (f" ({100 * часть / целое:.0f} %)" if целое else "")


def сводка(карточки: list[dict]) -> None:
    всего = len(карточки)
    с_суммой = с_валютой = с_кп = с_запросом = 0
    валюты: collections.Counter[str] = collections.Counter()
    по_полю: collections.Counter[str] = collections.Counter()
    стадия_без_кп = стадия_с_кп = 0

    for k in карточки:
        сумма = k.get("opportunity")
        try:
            если_число = float(сумма) if сумма not in (None, "") else 0.0
        except (TypeError, ValueError):
            если_число = 0.0
        if если_число:
            с_суммой += 1
        валюта = (k.get("currencyId") or "").strip()
        if валюта:
            с_валютой += 1
            валюты[валюта] += 1

        свои = [имя for поле, имя in ПОЛЯ_КП.items() if есть_файл(k.get(поле))]
        for имя in свои:
            по_полю[имя] += 1
        if свои:
            с_кп += 1
        if есть_файл(k.get(ПОЛЕ_ЗАПРОСА)):
            с_запросом += 1

        выбран = classify_stage(str(k.get("stageId") or "")) in ДАЛ_КП
        if выбран and not свои:
            стадия_без_кп += 1
        if выбран and свои:
            стадия_с_кп += 1

    print(f"карточек СП-166: {всего}")
    print()
    print("ЦЕНА НА САМОЙ КАРТОЧКЕ")
    print(f"  с ненулевой суммой:   {доля(с_суммой, всего)}")
    print(f"  с указанной валютой:  {доля(с_валютой, всего)}")
    for валюта, n in валюты.most_common(8):
        print(f"    {валюта:8} {n}")
    print()
    print("КОТИРОВКА ДОКУМЕНТОМ (только файлы со стороны поставщика)")
    print(f"  хотя бы один файл КП: {доля(с_кп, всего)}")
    for имя, n in по_полю.most_common():
        print(f"    {имя:28} {n}")
    print(f"  наш «Request file» (в КП НЕ считается): {доля(с_запросом, всего)}")
    print()
    print("СХОДИТСЯ ЛИ СТАДИЯ С ФАЙЛОМ")
    print(f"  стадия «КП получено», файл есть:  {стадия_с_кп}")
    print(f"  стадия «КП получено», файла нет:  {стадия_без_кп}")
    print("    Расхождение — не ошибка стадии: цену присылают и письмом в теле.")
    print("    Но оно и есть мера того, сколько котировок придётся доставать не из файла.")
    print()
    print("Замер, записи не было.")


def main() -> int:
    url = os.environ.get("BITRIX_WEBHOOK_URL", "")
    if not url:
        print("нет переменной BITRIX_WEBHOOK_URL", file=sys.stderr)
        return 2
    from bitrix_client import BitrixClient

    print("выгрузка карточек запросов (СП-166)…", flush=True)
    карточки = BitrixClient(url).list_items(
        SPA_RFQ, select=["id", "stageId", "opportunity", "currencyId",
                         *ПОЛЯ_КП, ПОЛЕ_ЗАПРОСА])
    сводка(карточки)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
