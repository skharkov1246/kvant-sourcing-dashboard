# Фамилии людей вне справочника — контакт клиента или поставщика (ревью 25.10.2026): слово с
# заглавной на -ов/-ев/-ин/-ын с окончаниями — где угодно; на -ский/-цкий — не в начале фразы
# (там это обычно прилагательное: «Китайский поставщик…»). Слова, которые так кончаются и в
