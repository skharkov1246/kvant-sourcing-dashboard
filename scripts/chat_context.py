# Без флагов «без учёта регистра»: латиница сверяется после lower(), кириллица — обоими
# регистрами явно (регистр кириллицы в базе зависит от локали).
# Домен: из списка ДОМЕНЫ (и рф) — без пути; любой латинский — с путём («bit.ly/…»; ревью 25.10.2026)
ОБРАЗЕЦ_ДОМЕНА = ("[a-z0-9А-Яа-яЁё-]+[.](" + "|".join(ДОМЕНЫ) + "|рф|РФ)([^a-z0-9]|$)"
                  "|[a-z0-9-]+([.][a-z0-9-]+)*[.][a-z]{2,}/")
ОБРАЗЕЦ_ССЫЛКИ = r"https?:|www[.]|@|\[|\]|" + ОБРАЗЕЦ_ДОМЕНА
ОБРАЗЕЦ_ВАЛЮТЫ = (r"₽|€|[$]|£|¥|(^|[^a-z])(eur|usd|cny|aed|inr|gbp|jpy|rub|rur)([^a-z]|$)"
                  r"|(^|[^А-Яа-яЁё])([Рр][Уу][Бб]([.Лл]|[^А-Яа-яЁё]|$)|[Ее][Вв][Рр][Оо]([^А-Яа-яЁё]|$)"
                  r"|[Дд][Оо][Лл][Лл][Аа][Рр]|[Юю][Аа][Нн]|[Дд][Ии][Рр][Хх][Аа][Мм]|[Рр][Уу][Пп][Ии])")
# «т.р.», «тр» и «500к» (кириллица, вплотную к цифре) — тоже множители (ревью 28.10.2026)
ОБРАЗЕЦ_МНОЖИТЕЛЯ = (r"[0-9][  ]*([Тт][Ыы][Сс]|[Мм][Лл][Нн]|[Мм][Лл][Рр][Дд]|[Мм][Ии][Лл][Лл][Ии]"
                     r"|[Тт][.]?[  ]?[Рр]([.]|[^А-Яа-яЁё]|$)|k([^a-z]|$))|[0-9][Кк]([^А-Яа-яЁё]|$)")
ОБРАЗЕЦ_ДАТЫ = (r"(?<![0-9.])[0-9]{1,2}[.][0-9]{1,2}([.]([0-9]{4}|[0-9]{2}))?(?![0-9])"
                r"|(?<![0-9])[0-9]{4}-[0-9]{2}-[0-9]{2}(?![0-9])")
ОБРАЗЕЦ_РАЗРЯДОВ = r"(?<=[0-9])[ .,'   ]+(?=[0-9])"
ОБРАЗЕЦ_ЦИТАТЫ = r"http|www[.]|@|\[user=|" + ОБРАЗЕЦ_ДОМЕНА
# сумма словами: «полтора миллиона», «2 млн» без цифры рядом (ревью 25.10.2026)
ОБРАЗЕЦ_МИЛЛИОНОВ = ("(^|[^А-Яа-яЁё])([Мм][Лл][Нн]|[Мм][Лл][Рр][Дд])([^А-Яа-яЁё]|$)"
                     "|[Мм][Ии][Лл][Лл][Ии][Оо][Нн]|[Мм][Ии][Лл][Лл][Ии][Аа][Рр][Дд]"
                     # «долг двести тысяч» (ревью 28.10.2026)
                     "|[Тт][Ыы][Сс][Яя][Чч]")
# местный номер «345-67-89» — в строке «главного» телефон и без кода (ревью 28.10.2026)
ОБРАЗЕЦ_ТЕЛЕФОНА = r"(?<![0-9])[0-9]{3}-[0-9]{2}-[0-9]{2}(?![0-9])"
ОБРАЗЕЦ_СПЕЦИФИКАЦИИ = r"^[0-9A-Za-zА-ЯЁа-яё№/._-]{1,20}$"
СНЯТЬ_В_ЦИТАТЕ = " \t\r\n   ()[]-"      # перед поиском десяти цифр подряд (телефон)
СНЯТЬ_В_ГЛАВНОМ = СНЯТЬ_В_ЦИТАТЕ + "+"   # то же в строке «главного», и «+7»


def текст_главного_ок(s) -> bool:
    """Строка «главного»: до 160 знаков, без ссылок и доменов, почт, скобок, валют, множителей
    сумм («1,25 млн», «500 т.р.», «полтора миллиона», «двести тысяч»), телефонов («345-67-89»;
    десять цифр подряд после снятия пробелов, скобок, дефисов и плюса) и чисел из 4+ цифр (даты
    ДД.ММ[.ГГГГ] и ГГГГ-ММ-ДД — можно). Имена — отдельно, маской (их справочника у базы нет)."""
    if not isinstance(s, str) or not s.strip() or len(s) > ТЕКСТ_ГЛАВНОГО:
        return False
    н = s.lower()
    if (re.search(ОБРАЗЕЦ_ССЫЛКИ, н) or re.search(ОБРАЗЕЦ_ВАЛЮТЫ, н) or re.search(ОБРАЗЕЦ_МНОЖИТЕЛЯ, н)
            or re.search(ОБРАЗЕЦ_МИЛЛИОНОВ, н) or re.search(ОБРАЗЕЦ_ТЕЛЕФОНА, н)):
        return False
    т = re.sub(ОБРАЗЕЦ_РАЗРЯДОВ, "", re.sub(ОБРАЗЕЦ_ДАТЫ, " ", н))
    if re.search(r"[0-9]{10,}", т.translate({ord(c): None for c in СНЯТЬ_В_ГЛАВНОМ})):
        return False
    return not re.search(r"[0-9]{4,}", т)


def цитата_ок(q) -> bool:
    """Цитата факта: до 200 знаков, без ссылок и доменов, почт и упоминаний, без десяти цифр
    подряд после снятия пробелов, скобок и дефисов (телефон)."""
    if q is None:
        return True
    if not isinstance(q, str) or not q or len(q) > ЦИТАТА_МАКС or re.search(ОБРАЗЕЦ_ЦИТАТЫ, q.lower()):
        return False
    return not re.search(r"[0-9]{10,}", q.translate({ord(c): None for c in СНЯТЬ_В_ЦИТАТЕ}))


def номер_спецификации_ок(s) -> bool:
    """Номер спецификации — до 20 знаков без пробелов, с цифрой, без десяти цифр подряд."""
    return s is None or (isinstance(s, str) and bool(re.search(ОБРАЗЕЦ_СПЕЦИФИКАЦИИ, s))
                         and bool(re.search(r"[0-9]", s)) and not re.search(r"[0-9]{10,}", s))


def факт_ок(kind: str, data, msg_id, ids, keys) -> bool:
    """Строка факта — та же проверка, что deal_chat_fact_ok в базе (сверяет тест)."""
    ids, keys = list(ids or []), list(keys or [])
    if kind not in ВИДЫ_ФАКТА or not isinstance(data, dict):
        return False
    if len(ids) > ДОКАЗАТЕЛЬСТВ_МАКС or len(set(ids)) != len(ids) or not all(_номер(x) for x in ids):
        return False
    if len(keys) > ДОКАЗАТЕЛЬСТВ_МАКС or len(set(keys)) != len(keys) or not all(k in КЛЮЧИ_СВОДКИ for k in keys):
        return False
    if kind == "главное":
        # хотя бы одно доказательство — сообщение или строка учёта: на одних прошлых выводах
        # модели (КЛЮЧИ_ПРОШЛОГО) пункт повторял бы сам себя
        return (set(data) == {"kind", "severity"} and _из(data["kind"], ВИДЫ_ГЛАВНОГО)
                and _из(data["severity"], ВАЖНОСТИ) and (len(ids) >= 1 or any(k not in КЛЮЧИ_ПРОШЛОГО for k in keys))
                and (msg_id is None or msg_id in ids))
    if keys or not _номер(msg_id) or msg_id not in ids:
        return False
    if kind == "деньги":
        a = data.get("amount")
        return (set(data) == {"amount", "currency", "money_kind", "side", "vat", "date"} and ids == [msg_id]
                and isinstance(a, (int, float)) and not isinstance(a, bool) and math.isfinite(a)
                and 0 < a < СУММА_МАКС and _из(data["currency"], ВАЛЮТЫ)
                and _из(data["money_kind"], ВИДЫ_ДЕНЕГ) and _из(data["side"], СТОРОНЫ_ДЕНЕГ)
                and _из(data["vat"], НДС) and (data["date"] is None or _дата(data["date"])))
    if kind == "договор":
        return (set(data) == {"status", "side", "where", "spec_no"} and len(ids) >= 1 and msg_id == max(ids)
                and _из(data["status"], СТАТУСЫ_ДОГОВОРА) and _из(data["side"], СТОРОНЫ_ДОГОВОРА)
                and _из(data["where"], ГДЕ_ДОГОВОР) and номер_спецификации_ок(data["spec_no"]))
    return (set(data) == {"signal", "author_role"} and ids == [msg_id] and _из(data["signal"], СИГНАЛЫ)
            and _из(data["author_role"], РОЛИ_АВТОРА))


def дата_денег_ок(kind: str, data, msg_at) -> bool:
    """Дата суммы — не позже дня сообщения по Москве: обещанная оплата — не пришедшая (как
    deal_chat_money_date_ok базы). Даты нет — годно; даты сообщения нет — дата не годится."""
    if kind != "деньги" or not isinstance(data, dict) or not isinstance(data.get("date"), str):
        return True
    if not _дата(data["date"]) or not isinstance(msg_at, dt.datetime):
        return False
    when = msg_at if msg_at.tzinfo else msg_at.replace(tzinfo=dt.timezone.utc)
    return dt.date.fromisoformat(data["date"]) <= when.astimezone(_MSK).date()


# Числа сообщения: «1 250 000», «1250000,50», «12.500,00», «12,500.00», «1,25 млн», «50 тыс».
_ЧИСЛО_В_ТЕКСТЕ = re.compile(r"(?<![\w.,])(\d{1,3}(?:[    ']\d{3})+(?!\d)|\d+)((?:[.,]\d+)*)(?!\d)")
_МНОЖИТЕЛЬ_СУММЫ = re.compile(r"[  ]*(тыс(?:яч[а-я]*|\.)?|т\.[  ]?р\.?|млн\.?|миллион[а-я]*|млрд\.?"
                              r"|миллиард[а-я]*|[kк](?![а-яa-z]))", re.I)


def _множитель(слово: str) -> tuple[float, bool]:
    """(множитель, однозначен ли он): «к» после числа бывает и предлогом («… к оплате»)."""
    w = слово.lower()
    if w.startswith(("млрд", "миллиард")):
        return 1e9, True
    if w.startswith(("млн", "миллион")):
        return 1e6, True
    if w.startswith("т"):
        return 1e3, True
    return 1e3, False


def _прочтения(целое: str, хвост: str) -> list[float]:
    """Все прочтения числа: «1.250» — и 1,25, и 1250; «24.10.2026» — ни одного."""
    цифры = re.sub(r"\D", "", целое)
    base = int(цифры)
    части = re.findall(r"([.,])(\d+)", хвост)
    if not части:
        return [float(base)]
    if len(части) == 1:
        sep, d = части[0]
        дробь = base + int(d) / 10 ** len(d)
        return [base * 1000.0 + int(d), дробь] if len(d) == 3 and len(цифры) <= 3 else [дробь]
    *тысячи, (sep_last, d_last) = части
    if not all(len(d) == 3 for _s, d in тысячи) or len({s for s, _d in тысячи}) != 1 or len(цифры) > 3:
        return []
    x = base
    for _s, d in тысячи:
        x = x * 1000 + int(d)
    if sep_last == тысячи[0][0] and len(d_last) == 3:
        return [float(x * 1000 + int(d_last))]          # «1.250.000»
    if sep_last != тысячи[0][0]:
        return [x + int(d_last) / 10 ** len(d_last)]    # «12.500,00», «1,250,000.50»
    return []


def _места_суммы(текст: str, amount):
    """Все места, где в тексте записана сумма: (начало, конец, конец числа) — конец больше
    конца числа, когда после него взят множитель («тыс», «млн», «k»)."""
    if not isinstance(amount, (int, float)) or isinstance(amount, bool) or not amount > 0:
        return
    s = str(текст or "")
    for m in _ЧИСЛО_В_ТЕКСТЕ.finditer(s):
        мм = _МНОЖИТЕЛЬ_СУММЫ.match(s, m.end())
        множители = [(1.0, m.end())]
        if мм:
            множ, однозначен = _множитель(мм.group(1))
            множители = [(множ, мм.end())] + ([] if однозначен else множители)
        for x in _прочтения(m.group(1), m.group(2)):
            for множ, конец in множители:
                if abs(x * множ - amount) <= max(0.01, amount * 0.001):
                    yield m.start(), конец, m.end()
                    break
            else:
                continue
            break


def найти_сумму(текст: str, amount) -> tuple[int, int] | None:
    """Где в тексте сообщения записана сумма факта: (начало, конец) — или None.
    Сумма сходится с числом сообщения (с множителем «тыс», «млн», «k» после него) с
    точностью 0,1 %: модель переписала число, а не придумала его."""
    return next(((a, b) for a, b, _ in _места_суммы(текст, amount)), None)


