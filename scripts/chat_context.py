def _участники(r: dict, участники: list | None) -> None:
    """Имена участников чата (поле users ответа) — в маску имён этого чата."""
    if участники is None or not isinstance(r.get("users"), list):
        return
    for u in r["users"]:
        if isinstance(u, dict):
            участники.extend(str(u.get(k) or "") for k in ("name", "first_name", "last_name") if u.get(k))


def прочитать_чат(client, chat_id: str, участники: list | None = None,
                  last_id: int | None = None) -> tuple[str, list[dict]]:
    """('ok' | 'denied' | 'limit' | 'error', сообщения). last_id — сообщения старше него
    (LAST_ID: «вернёт сообщения с идентификатором меньше указанного»)."""
    параметры = {"DIALOG_ID": f"chat{chat_id}", "LIMIT": СООБЩЕНИЙ}
    if last_id is not None:
        параметры["LAST_ID"] = int(last_id)
    try:
        r = client.call("im.dialog.messages.get", параметры, retries=1)
    except Exception as e:                           # noqa: BLE001
        if type(e).__name__ == "BitrixLimitError":
            return "limit", []
        if "ACCESS" in str(e).upper():
            return "denied", []
        return "error", []
    if isinstance(r, dict) and isinstance(r.get("messages"), list):
        _участники(r, участники)
        return "ok", r["messages"]
    return "error", []


@dataclass
class Листание:
    """Итог чтения истории чата: статус, сообщения (без повторов), страниц, чем кончилось."""
    статус: str
    msgs: list = field(default_factory=list)
    страниц: int = 0
    дошли: str = ""                     # конец_чата | предел
    нарушение: str = ""                 # страница не по правилу LAST_ID — метод портала не тот


def прочитать_историю(client, chat_id: str, top_id: int, участники: list | None = None) -> Листание:
    """Сообщения чата не новее top_id (курсор суточного прохода), по 50, от новых к
    старым: первая страница — LAST_ID = top_id + 1, следующая — LAST_ID = наименьший номер
    прошлой. Конец — страница короче 50 (конец_чата) или СТРАНИЦ_ИСТОРИИ страниц (предел).
    Каждая страница сверяется: все номера меньше LAST_ID, без повторов внутри и с прошлыми
    страницами — иначе «нарушение» (стоп «портал»: метод отдаёт не то, что описано)."""
    итог = Листание("ok")
    видели: set[int] = set()
    граница = int(top_id) + 1
    while итог.страниц < СТРАНИЦ_ИСТОРИИ:
        статус, msgs = прочитать_чат(client, chat_id, участники, last_id=граница)
        if статус != "ok":
            итог.статус = статус
            return итог
        итог.страниц += 1
        номера = [_mid(m) for m in msgs]
        if any(n <= 0 or n >= граница for n in номера):
            итог.нарушение = "номер не меньше LAST_ID"
        elif len(set(номера)) != len(номера):
            итог.нарушение = "повтор внутри страницы"
        elif set(номера) & видели:
            итог.нарушение = "страницы перекрываются"
        if итог.нарушение:
            return итог
        видели.update(номера)
        итог.msgs.extend(msgs)
        if len(msgs) < СООБЩЕНИЙ:
            итог.дошли = "конец_чата"
            return итог
        граница = min(номера)
    итог.дошли = "предел"
    return итог


def окно_истории(msgs: list[dict], роли: "Роли", дошли: str) -> tuple[list[dict], str]:
    """Сообщения истории от старых к новым в пределе ЗНАКОВ_ИСТОРИИ: лишнее отрезается с
    самых старых (новые важнее), и тогда чтение кончилось пределом."""
    по_порядку = sorted(msgs, key=_mid)
    строки = строки_сообщений(по_порядку, Роли(роли.service, роли.в_сделке))
    всего, с = 0, len(по_порядку)
    for i in range(len(строки) - 1, -1, -1):
        if всего + len(строки[i]) + 1 > ЗНАКОВ_ИСТОРИИ:
            break
        всего += len(строки[i]) + 1
        с = i
    if с > 0:
        return по_порядку[с:], "предел"
    return по_порядку, дошли


