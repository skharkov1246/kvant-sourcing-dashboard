_ФАМИЛИЯ = re.compile(r"(?<![\w])[А-ЯЁ][а-яё]+(?:ов|ев|ёв|ин|ын)(?:" + "|".join(_ОКОНЧАНИЯ_ФАМИЛИИ) + r")?(?![\w])")
_ФАМИЛИЯ_СКИЙ = re.compile(r"(?<![\w])[А-ЯЁ][а-яё]+[сц]к(?:ий|ого|ому|им|ом|ая|ой|ую|ие|их|ими)(?![\w])")
