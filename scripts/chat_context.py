def _позже(*метки):
    return max((x for x in метки if x), default=None)


ПОЛЯ_ИСТОРИИ = ("hist_low_id", "hist_state", "hist_at", "hist_run_id", "hist_fail_streak")
_ДАВНО = dt.datetime(2000, 1, 1, tzinfo=dt.timezone.utc)   # «за всё время» статьи «история»


def _сделка(x) -> str:
    return str(int(x)) if str(x).isdigit() else str(x)


def собрать_прошлые_факты(факты: list[dict], ctx: list[dict], hist: list[dict], deal: str) -> dict:
    """Последние факты сделки — как виды базы deal_chat_money_latest, deal_chat_contract_latest,
    deal_chat_sourcing_recent и deal_chat_important_latest (для Памяти и проверок)."""
    живые = [f for f in факты if not f.get("voided_at") and _сделка(f["deal_id"]) == deal]
    def по_времени(f):
        return (f.get("msg_at") or _ДАВНО, f.get("id") or 0)
    out: dict = {}
    деньги: dict[str, dict] = {}
    for f in sorted((f for f in живые if f["kind"] == "деньги" and f["data"]["side"] == "продажа"), key=по_времени):
        деньги[f["data"]["money_kind"]] = {**f["data"], "msg_at": f.get("msg_at")}
    договор: dict[str, dict] = {}
    for f in sorted((f for f in живые if f["kind"] == "договор"), key=по_времени):
        договор[f["data"]["side"]] = {**f["data"], "msg_at": f.get("msg_at")}
    сорсинг = [{**f["data"], "msg_at": f.get("msg_at")}
               for f in sorted((f for f in живые if f["kind"] == "сорсинг"), key=по_времени, reverse=True)[:5]]
    if деньги:
        out["money"] = sorted(деньги.values(), key=lambda x: x.get("msg_at") or _ДАВНО, reverse=True)
    if договор:
        out["contract"] = list(договор.values())
    if сорсинг:
        out["sourcing"] = сорсинг
    вызовы = [(r["assessed_at"], "сутки", r["id"]) for r in ctx
              if _сделка(r["deal_id"]) == deal and not r.get("voided_at") and r.get("method_ver") != "chat-ctx-1"]
    вызовы += [(r["assessed_at"], "история", r["id"]) for r in hist
               if _сделка(r["deal_id"]) == deal and not r.get("voided_at")]
    if вызовы:
        # суточный вызов chat-ctx-2 важнее любого вызова истории: история читает старые
        # сообщения и не гасит свежее «главное» (ревью 25.10.2026) — как deal_chat_important_latest
        at, проход, rid = max(вызовы, key=lambda x: (x[1] == "сутки", x[0], x[2]))
        поле = "ctx_id" if проход == "сутки" else "hist_id"
        пункты = [f for f in живые if f["kind"] == "главное" and f.get(поле) == rid]
        out["imp"] = {"at": at, "pass": проход, "conf": max((f["confidence"] for f in пункты), default=None),
                      "items": [{**f["data"], "statement": f["statement"], "keys": list(f["evidence_keys"])}
                                for f in пункты]}
    return out


class Память:
    """Хранилище в памяти: холостой прогон без базы и проверки. Повторяет базу: брони
    бюджета (deal_chat_take_budget), факты с отсечкой повторов, разовое чтение истории,
    откат пометкой."""

    def __init__(self, состояние: dict | None = None, прошлые: dict | None = None,
                 расход: list[dict] | None = None):
        self.state: dict[str, dict] = {k: dict(v) for k, v in (состояние or {}).items()}
        self.ctx: list[dict] = []
        self.hist: list[dict] = []
        self.facts: list[dict] = []
        self.holds: list[dict] = []
        self.spend: list[dict] = [dict(r) for r in расход or []]
        self._прошлые = dict(прошлые or {})
        self.схема = True
        self._номер = 0

    def _новый(self) -> int:
        self._номер += 1
        return self._номер

    def состояние(self) -> dict[str, dict]:
        return {k: dict(v) for k, v in self.state.items()}

    def прошлые(self, ids: list[str]) -> dict[str, dict]:
        out = {k: v for k, v in self._прошлые.items() if k in ids}
        for r in self.ctx:
            if r["deal_id"] in ids and not r.get("voided_at"):
                out[r["deal_id"]] = {"verdict": r["verdict"], "assessed_at": r["assessed_at"]}
        return out

    def факты(self, ids: list[str]) -> dict[str, dict]:
        out = {}
        for d in ids:
            f = собрать_прошлые_факты(self.facts, self.ctx, self.hist, _сделка(d))
            if f:
                out[d] = f
        return out

    def _когда_расход(self, r: dict) -> dt.datetime:
        """Метка расхода для окна суток — время его брони, если она есть (как
        deal_chat_take_budget): вызов около полуночи считается в те же сутки, что и бронь."""
        h = next((h for h in self.holds if r.get("hold_id") and h["id"] == r.get("hold_id")), None)
        return h["at"] if h else r["at"]

    def потрачено_с(self, момент: dt.datetime | None, статья: str = "сутки") -> float:
        return float(sum(r["usd"] for r in self.spend if r.get("kind", "сутки") == статья
                         and (момент is None or self._когда_расход(r) >= момент)))

    def брони_с(self, момент: dt.datetime | None, статья: str = "сутки") -> float:
        """Потолки неоплаченных брон статьи в окне: их деньги уже заняты."""
        оплачены = {r.get("hold_id") for r in self.spend if r.get("hold_id")}
        return float(sum(h["ceiling_usd"] for h in self.holds if h["kind"] == статья and h["id"] not in оплачены
                         and (момент is None or h["at"] >= момент)))

    def выход_p90(self, статья: str) -> int | None:
        """90-й процентиль tokens_out записанных вызовов chat-ctx-2 статьи (с бронью); меньше
        ВЫХОД_ЗАМЕР_ПОСЛЕ — None."""
        xs = [int(r["tokens_out"]) for r in self.spend if r.get("kind", "сутки") == статья and r.get("hold_id")
              and r.get("outcome") == "записано"]
        return _процентиль(xs, 0.9) if len(xs) >= ВЫХОД_ЗАМЕР_ПОСЛЕ else None

    def нижние_границы(self, ids: list[str]) -> dict[str, int]:
        """Самое старое сообщение, уже оценённое суточным проходом chat-ctx-2 (непомеченная
        оценка): история читает ниже него — те же сообщения дважды не оплачиваются."""
        out: dict[str, int] = {}
        for r in self.ctx:
            d = _сделка(r["deal_id"])
            if d in ids and not r.get("voided_at") and r.get("method_ver") != "chat-ctx-1":
                out[d] = min(out.get(d, r["msg_from_id"]), r["msg_from_id"])
        return out

    def взять_бюджет(self, run_id: str, part: int, deal_id: str, статья: str, потолок: float) -> int | None:
        """Как deal_chat_take_budget: потрачено статьёй в окне + потолки неоплаченных брон
        + новый потолок ≤ предела статьи — бронь; иначе None."""
        if статья not in ПРЕДЕЛ_СТАТЬИ or not потолок > 0:
            return None
        начало = начало_суток() if статья == "сутки" else None
        if self.потрачено_с(начало, статья) + self.брони_с(начало, статья) + потолок > ПРЕДЕЛ_СТАТЬИ[статья] + 1e-9:
            return None
        h = {"id": self._новый(), "at": dt.datetime.now(dt.timezone.utc), "run_id": run_id, "part": part,
             "deal_id": deal_id, "kind": статья, "ceiling_usd": round(потолок, 6)}
        self.holds.append(h)
        return h["id"]

    def _дописать_факты(self, факты, deal: str, run_id: str, ctx_id=None, hist_id=None) -> int:
        n = 0
        for f in факты:
            ключ = _ключ_факта(f["kind"], f["msg_id"], f["data"])
            if f["kind"] != "главное" and any(
                    not x.get("voided_at") and _сделка(x["deal_id"]) == _сделка(deal) and x["kind"] == f["kind"]
                    and x["msg_id"] == f["msg_id"] and x["fact_key"] == ключ for x in self.facts):
                continue                              # как on conflict do nothing базы
            self.facts.append({**f, "id": self._новый(), "deal_id": deal, "run_id": run_id,
                               "method_ver": METHOD_VER, "ctx_id": ctx_id, "hist_id": hist_id, "fact_key": ключ,
                               "voided_at": None})
            n += 1
        return n

    def записать_оценку(self, строка: dict, курсор: dict, трата: dict, факты=()) -> int:
        cid = self._новый()
        self.ctx.append(dict(строка, id=cid))
        n = self._дописать_факты(факты, строка["deal_id"], строка["run_id"], ctx_id=cid)
        self.spend.append(dict(трата))
        s = self.state.get(строка["deal_id"]) or {"last_msg_id": 0, "last_human_at": None,
                                                  "run_id": строка["run_id"], "fail_streak": 0}
        s.update(chat_id=курсор["chat_id"], checked_at=курсор["checked_at"], read_at=курсор["checked_at"],
                 last_msg_id=max(s.get("last_msg_id") or 0, курсор["last_msg_id"]),
                 last_human_at=_позже(s.get("last_human_at"), курсор["last_human_at"]),
                 run_id=строка["run_id"], method_ver=строка["method_ver"], fail_streak=0)
        self.state[строка["deal_id"]] = s
        return n

    def записать_историю(self, строка: dict, факты, курсор: dict, трата: dict) -> int:
        s = self.state.get(строка["deal_id"])
        if s is None:
            raise RuntimeError("курсора сделки нет")   # как update … where в базе: 0 строк — откат
        hid = self._новый()
        self.hist.append(dict(строка, id=hid))
        n = self._дописать_факты(факты, строка["deal_id"], строка["run_id"], hist_id=hid)
        self.spend.append(dict(трата))
        s.update(hist_low_id=курсор["hist_low_id"], hist_state=курсор["hist_state"], hist_at=курсор["hist_at"],
                 hist_run_id=строка["run_id"], hist_fail_streak=0)
        return n

    def записать_неудачу(self, трата: dict, курсор: dict | None, история: bool = False) -> None:
        self.spend.append(dict(трата))
        if курсор is None:
            return
        s = self.state.get(курсор["deal_id"])
        if история:
            if s is not None:
                s.update(hist_at=курсор["checked_at"], hist_fail_streak=int(s.get("hist_fail_streak") or 0) + 1)
            return
        if s is None:
            self.state[курсор["deal_id"]] = {
                "chat_id": курсор["chat_id"], "last_msg_id": 0, "last_human_at": курсор["last_human_at"],
                "checked_at": курсор["checked_at"], "read_at": курсор["checked_at"], "run_id": курсор["run_id"],
                "method_ver": METHOD_VER, "fail_streak": 1}
            return
        s.update(chat_id=курсор["chat_id"], checked_at=курсор["checked_at"], read_at=курсор["checked_at"],
                 last_human_at=_позже(s.get("last_human_at"), курсор["last_human_at"]),
                 fail_streak=int(s.get("fail_streak") or 0) + 1)

    def отметить_чтение(self, deal_id: str, chat_id: str, last_human_at, checked_at,
                        run_id: str, прочитан: bool = True) -> None:
        s = self.state.get(deal_id)
        if s is None:
            self.state[deal_id] = {"chat_id": chat_id, "last_msg_id": 0, "last_human_at": last_human_at,
                                   "checked_at": checked_at, "read_at": checked_at if прочитан else None,
                                   "run_id": run_id, "method_ver": METHOD_VER, "fail_streak": 0}
            return
        s.update(chat_id=chat_id, checked_at=checked_at,
                 last_human_at=_позже(s.get("last_human_at"), last_human_at))
        if прочитан:
            s["read_at"] = checked_at

    def отметить_историю(self, deal_id: str, run_id: str, когда: dt.datetime, курсор: dict | None) -> None:
        """История сделки без вызова модели (как База.отметить_историю): курсор None — чтение не
        удалось (нет доступа, сбой, страницы не по правилу): hist_at и серия неудач; иначе
        читать нечего (одни роботы, нет старых сообщений) — история прочитана."""
        s = self.state.get(deal_id)
        if s is None:
            return
        if курсор is None:
            s.update(hist_at=когда, hist_fail_streak=int(s.get("hist_fail_streak") or 0) + 1)
        else:
            s.update(hist_low_id=курсор["hist_low_id"], hist_state=курсор["hist_state"], hist_at=когда,
                     hist_run_id=run_id, hist_fail_streak=0)

    def аннулировать_факты(self, run_id: str) -> int:
        """Гейт снятых фактов суточного прохода: помечаются только факты прогона — оценки хода,
        курсоры и очередь остаются (ревью 25.10.2026)."""
        n = 0
        now = dt.datetime.now(dt.timezone.utc)
        for f in self.facts:
            if f["run_id"] == run_id and not f.get("voided_at") and f.get("ctx_id"):
                f["voided_at"] = now
                n += 1
        return n

    def аннулировать(self, run_id: str, прежние: dict[str, dict | None],
                     прежние_истории: dict[str, dict] | None = None) -> int:
        n = 0
        now = dt.datetime.now(dt.timezone.utc)
        история = прежние_истории or {}
        for r in self.ctx:
            # только сделки, чьи курсоры откат возвращает: иначе снялись бы оценки,
            # курсоры которых уже ушли вперёд
            if r["run_id"] == run_id and not r.get("voided_at") and str(r["deal_id"]) in прежние:
                r["voided_at"] = now
                n += 1
        for r in self.hist:
            if r["run_id"] == run_id and not r.get("voided_at") and str(r["deal_id"]) in история:
                r["voided_at"] = now
                n += 1
        for f in self.facts:
            if f["run_id"] == run_id and not f.get("voided_at") and (
                    (f.get("ctx_id") and str(f["deal_id"]) in прежние)
                    or (f.get("hist_id") and str(f["deal_id"]) in история)):
                f["voided_at"] = now
        for deal, было in прежние.items():
            if было is None:
                if (self.state.get(deal) or {}).get("run_id") == run_id:
                    del self.state[deal]
            else:
                self.state[deal] = dict(было)
        for deal, было in история.items():
            if deal in self.state:
                self.state[deal].update({k: было.get(k) for k in ПОЛЯ_ИСТОРИИ})
        return n


