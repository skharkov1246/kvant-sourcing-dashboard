def сверить_факты(v: dict, тексты: dict[int, str], сообщения: dict[int, dict], роли: Роли,
                  маска: МаскаИмён | None, сводка: dict[str, str], *, проход: str, сч: Counter,
                  со_сводкой: bool = False) -> list[dict]:
    """Ответ, прошедший проверить_ответ → строки фактов для базы (без deal/run/ctx — их
    ставит запись). Сначала разобрать_факты (форма по пункту; отправлено — номера текстов,
    ключи — строки сводки). Затем вторая ступень — сверка с текстом сообщения (ревью 25.10.2026):

      деньги — число есть в тексте и это деньги (не проценты, штуки, сроки, номер, артикул,
        часть даты; рядом валюта, множитель или денежное слово), вид суммы (счёт, оплата,
        переторжка, итог) назван словом — иначе факт снят; валюта и НДС — только по пометке
        рядом с числом: противоречит — снят, пометки нет — «неясно» и «не_указано» (не снят,
        «не подтверждено»); дата — только написанная в сообщении и не позже его дня, иначе null;
      «главное» — строка без сумм, ссылок и имён; хотя бы одно доказательство — сообщение или
        строка учёта (не одни прошлые выводы модели); без сводки сборки срыв срока клиента и
        расхождение суммы — только по сообщениям (со_сводкой).

    Снятый факт считается (факт_снят:…), поправленный — (факт_поправлен:…); ответ остаётся
    годным. Роль автора сигнала сорсинга ставит код. Повторы внутри ответа — один раз."""
    v = разобрать_факты(v, set(тексты), set(сводка), сч)
    out: list[dict] = []
    видели: set[tuple] = set()

    def когда(mid):
        return _когда(сообщения.get(mid) or {})

    def добавить(факт: dict) -> None:
        ключ = (факт["kind"], факт["msg_id"], _ключ_факта(факт["kind"], факт["msg_id"], факт["data"]))
        if факт["kind"] != "главное" and ключ in видели:
            сч["факт_повтор_в_ответе"] += 1
            return
        видели.add(ключ)
        if not (факт_ок(факт["kind"], факт["data"], факт["msg_id"], факт["evidence_msg_ids"], факт["evidence_keys"])
                and дата_денег_ок(факт["kind"], факт["data"], факт["msg_at"])):
            сч["факт_снят:форма"] += 1                 # не бывает после разбора и сверки: третий рубеж
            return
        if факт["quote"] is None and факт["msg_id"] is not None:
            сч["цитата_снята"] += 1
        сч[f"факт:{факт['kind']}"] += 1
        out.append(факт)

    for x in v["money"]:
        текст = тексты.get(x["msg_id"], "")
        почему = не_деньги(текст, x["amount"])
        if почему:
            сч[f"факт_снят:деньги:{почему}"] += 1
            continue
        if not вид_в_тексте(текст, x["money_kind"]):
            сч["факт_снят:деньги:вид_не_в_тексте"] += 1
            continue
        где = найти_сумму(текст, x["amount"])
        валюты = валюты_около(текст, где)
        _валюта, ндс = пометки_суммы(текст, где)
        валюта, vat, дата = x["currency"], x["vat"], x["date"]
        if валюта not in валюты and len(валюты) == 1 and валюта != "неясно":
            сч["факт_снят:деньги:валюта"] += 1
            continue
        if ндс and vat not in (ндс, "не_указано"):
            сч["факт_снят:деньги:ндс"] += 1
            continue
        if валюта != "неясно" and валюта not in валюты:
            валюта = "неясно"                         # пометки нет (или их две) — валюта не подтверждена
            сч["факт_поправлен:деньги:валюта_не_подтверждена"] += 1
        if ндс is None and vat != "не_указано":
            vat = "не_указано"
            сч["факт_поправлен:деньги:ндс_не_подтверждён"] += 1
        if дата is not None and (почему := дата_в_тексте(текст, дата, когда(x["msg_id"]))):
            дата = None
            сч[f"факт_поправлен:деньги:{почему}"] += 1
        data = {"amount": x["amount"], "currency": валюта, "money_kind": x["money_kind"], "side": x["side"],
                "vat": vat, "date": дата}
        добавить({"kind": "деньги", "pass": проход, "msg_id": x["msg_id"], "msg_at": когда(x["msg_id"]),
                  "evidence_msg_ids": [x["msg_id"]], "evidence_keys": [], "evidence_vals": None, "data": data,
                  "quote": цитата(текст, "деньги", маска, x["amount"]), "statement": None, "confidence": None})
    for x in v["contract"]:
        mid = max(x["evidence_msg_ids"])
        добавить({"kind": "договор", "pass": проход, "msg_id": mid, "msg_at": когда(mid),
                  "evidence_msg_ids": list(x["evidence_msg_ids"]), "evidence_keys": [], "evidence_vals": None,
                  "data": {k: x[k] for k in ("status", "side", "where", "spec_no")},
                  "quote": цитата(тексты.get(mid, ""), "договор", маска), "statement": None, "confidence": None})
    for x in v["sourcing"]:
        mid = x["msg_id"]
        роль = роли.роль_автора(_автор(сообщения.get(mid) or {}))
        добавить({"kind": "сорсинг", "pass": проход, "msg_id": mid, "msg_at": когда(mid),
                  "evidence_msg_ids": [mid], "evidence_keys": [], "evidence_vals": None,
                  "data": {"signal": x["signal"], "author_role": роль},
                  "quote": цитата(тексты.get(mid, ""), "сорсинг", маска), "statement": None, "confidence": None})
    for x in v["important"]:
        текст = " ".join(str(x["statement"]).split())
        if not текст_главного_ок(текст) or (маска is not None and маска.есть_имя(текст)):
            сч["факт_снят:главное:текст"] += 1
            continue
        ids, keys = list(x["evidence_msg_ids"]), list(x["evidence_keys"])
        if not ids and all(k in КЛЮЧИ_ПРОШЛОГО for k in keys):
            сч["факт_снят:главное:только_прошлое"] += 1
            continue
        if not ids and not со_сводкой and x["kind"] in ГЛАВНОЕ_ПО_СВОДКЕ:
            сч["факт_снят:главное:нет_основания"] += 1
            continue
        mid = max(ids) if ids else None
        добавить({"kind": "главное", "pass": проход, "msg_id": mid, "msg_at": когда(mid) if mid else None,
                  "evidence_msg_ids": ids, "evidence_keys": keys,
                  # правило 16: храни, почему — строки сводки, на которые сослалась модель
                  "evidence_vals": {k: сводка[k][:300] for k in keys if k in сводка} or None,
                  "data": {"kind": x["kind"], "severity": x["severity"]},
                  "quote": цитата(тексты.get(mid, ""), "главное", маска) if mid else None,
                  "statement": текст, "confidence": float(v["important_conf"])})
        сч[f"главное:{x['severity']}"] += 1
    return out


