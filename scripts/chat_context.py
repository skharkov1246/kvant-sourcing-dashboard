def загрузить_сводку(path: str | None, сейчас: dt.datetime | None = None) -> tuple[dict | None, str]:
    """Сводка по сделкам от сборки дашборда (dealdigest:v1 → файл DEALDIGEST_PATH):
    ({сделка: сводка}, «есть») — или (None, «нет» | «устарела» | «не по форме»).
    Старше СВОДКА_ЧАСОВ — не используется: модель увидела бы вчерашние сроки и фазы."""
    if not path:
        return None, "нет"
    try:
        raw = json.loads(open(path, encoding="utf-8").read())
    except FileNotFoundError:
        return None, "нет"
    except (OSError, ValueError):
        return None, "не по форме"
    if not isinstance(raw, dict) or raw.get("version") != 1 or not isinstance(raw.get("deals"), dict):
        return None, "не по форме"
    try:
        at = dt.datetime.fromisoformat(str(raw.get("at") or ""))
    except ValueError:
        return None, "не по форме"
    at = at if at.tzinfo else at.replace(tzinfo=_MSK)
    if (сейчас or dt.datetime.now(dt.timezone.utc)) - at > dt.timedelta(hours=СВОДКА_ЧАСОВ):
        return None, "устарела"
    return {str(k): v for k, v in raw["deals"].items() if isinstance(v, dict) and str(k).isdigit()}, "есть"


class _Прогон:
    """Один прогон: очередь → части → чтение → модель → запись. Счёт — в итог.
    Проход «daily» — новые сообщения (оценка хода, факты, главное); «history» — разовое
    чтение старых сообщений (факты и главное) со своей статьёй расхода."""

    def __init__(self, client, store, service_ids, *, режим, бюджет, сегодня, run_id, модель,
                 клиент_модели, итог: Итог, срок_с: float, проход: str = "daily",
                 имена: dict | None = None, сводка: dict | None = None, сводка_состояние: str = "нет"):
        self.client, self.store, self.service_ids = client, store, service_ids
        self.live = режим == "live"
        self.бюджет, self.сегодня, self.run_id, self.модель = бюджет, сегодня, run_id, модель
        self.клиент_модели, self.итог, self.срок_с = клиент_модели, итог, срок_с
        self.история = проход == "history"
        self.статья = ПРОХОДЫ[проход]
        self.сч = итог.счёт
        self.стоп = ""          # портал | бюджет | время | качество | запись | api | api_доступ | api_код
        self.старт = _часы()
        self.состояние: dict[str, dict] = {}
        self.прошлые: dict[str, dict] = {}
        self.факты: dict[str, dict] = {}
        self.границы: dict[str, int] = {}             # история: ниже этого — ещё не оценено сутками
        self.записанные: dict[str, dict | None] = {}   # сделка → курсор до прогона (для отката)
        self.записанные_истории: dict[str, dict] = {}  # сделка → поля истории до прогона
        self.сбоев_подряд = 0
        self.маска = МаскаИмён(n for u, n in (имена or {}).items() if str(u) not in service_ids)
        self.сводка, self.сводка_состояние = сводка, сводка_состояние
        self.ожидаемый_выход = ОЖИДАЕМЫЙ_ВЫХОД_ИСТОРИИ if self.история else ОЖИДАЕМЫЙ_ВЫХОД

    def _остановить(self, почему: str, код: int = 0) -> None:
        self.стоп = почему
        if код:
            self.итог.код = код

    def _запись(self, действие, *args) -> bool:
        """Запись в хранилище; упала — стоп «запись», код 1. Текст ошибки не печатается:
        в нём бывают номера сделок."""
        try:
            действие(*args)
            return True
        except Exception as e:                       # noqa: BLE001
            self.сч[f"сбой_записи:{type(e).__name__}:{getattr(e, 'pgcode', '') or ''}"] += 1
            self._остановить("запись", 1)
            return False

    def _замер_выхода(self) -> None:
        """Ожидаемый выход оценки dry — 90-й процентиль записанных вызовов chat-ctx-2 этой
        статьи, если он больше умолчания (бюджет ошибается вверх); замера нет — умолчание."""
        замер = getattr(self.store, "выход_p90", None)
        try:
            p90 = замер(self.статья) if замер else None
        except Exception:                            # noqa: BLE001  (замер — подсказка, не условие)
            p90 = None
        if p90:
            self.сч["выход:замер"] = int(p90)
            self.ожидаемый_выход = max(self.ожидаемый_выход, int(p90))
        self.итог.выход_ожидаемый = self.ожидаемый_выход

    def __call__(self, канд: list[Кандидат], лимит: int, частей: int) -> None:
        сейчас = dt.datetime.now(dt.timezone.utc)
        self.состояние = self.store.состояние()
        self._замер_выхода()
        if self.история:
            годные = очередь_истории(канд, self.состояние, сейчас, self.сч)
        else:
            годные = []
            for к in очередь(канд, self.состояние):
                if на_паузе(self.состояние.get(к.deal), сейчас):
                    self.сч["пауза_после_брака"] += 1
                else:
                    годные.append(к)
        взять = годные[:лимит]
        if len(годные) > len(взять):
            self.сч["не_дошли:лимит_чатов"] += len(годные) - len(взять)
        ids = [к.deal for к in взять]
        self.прошлые = self.store.прошлые(ids)
        факты = getattr(self.store, "факты", None)
        self.факты = факты(ids) if факты else {}
        границы = getattr(self.store, "нижние_границы", None)
        self.границы = границы(ids) if (границы and self.история) else {}
        for номер, часть in enumerate(нарезать(взять, частей), 1):
            if not часть:
                continue
            if self.стоп:
                self.сч[f"не_дошли:{self.стоп}"] += len(часть)
                continue
            ч: Counter = Counter()
            self.итог.части.append((номер, ч))
            for к in часть:
                if not self.стоп and _часы() - self.старт >= self.срок_с:
                    self._остановить("время")
                if self.стоп:
                    self.сч[f"не_дошли:{self.стоп}"] += 1
                    continue
                if self.история:
                    self.история_чата(к, номер, ч)
                else:
                    self.чат(к, номер, ч)
        if self.сч["гейт_не_пройден"] and self.live:
            self._откат()
        if self.стоп:
            self.сч[f"стоп:{self.стоп}"] += 1

    def _откат(self) -> None:
        """Гейт не пройден. Брак оценок хода (сбой метода задевает и прошедшие проверку) и
        любой гейт истории — откат целиком: оценки, строки истории, их факты, курсоры. Снятые
        факты суточного прохода — помечаются только факты прогона: оценки хода годны, курсоры и
        очередь стоят (ревью 25.10.2026)."""
        try:
            if self.сч["гейт:снятые_факты"] and not self.история:
                self.сч["фактов_помечено"] += self.store.аннулировать_факты(self.run_id)
                return
            if not (self.записанные or self.записанные_истории):
                return
            if self.записанные_истории:
                n = self.store.аннулировать(self.run_id, self.записанные, self.записанные_истории)
            else:
                n = self.store.аннулировать(self.run_id, self.записанные)
            self.сч["аннулировано"] += n
            self.сч["курсоров_возвращено"] += len(self.записанные) + len(self.записанные_истории)
        except Exception as e:                       # noqa: BLE001
            self.сч[f"сбой_отката:{type(e).__name__}:{getattr(e, 'pgcode', '') or ''}"] += 1

    # ---------------------------------------------------------------- общее
    def _маска_чата(self, участники: list) -> МаскаИмён:
        """Маска этого чата: справочник портала — обе формы (основы для цитаты, точные для
        проверки «главного»; ревью 25.10.2026) — плюс участники чата."""
        м = МаскаИмён()
        м.основы = set(self.маска.основы)
        м.точные = set(self.маска.точные)
        for имя in участники:
            м.добавить(имя)
        return м

    def _со_сводкой(self, к: Кандидат) -> bool:
        """Есть ли у сделки сводка учёта (сроки, заказы, договоры, экономика) — не одна стадия:
        у пресейла и у сделки реализации без заказов в сводке только стадия, и срыв срока или
        расхождение суммы на ней не стоят (ГЛАВНОЕ_ПО_СВОДКЕ; ревью 28.10.2026)."""
        своя = (self.сводка or {}).get(к.deal) or {}
        return isinstance(своя, dict) and any(своя.get(k) for k in СВОДКА_УЧЁТА)

    def _сводка(self, к: Кандидат, маска: МаскаИмён) -> list[tuple[str, str]]:
        """Строки [d:ключ] сделки: сводка сборки (или стадия из портала), прошлая оценка,
        прошлые факты и главное из базы."""
        своя = (self.сводка or {}).get(к.deal)
        self.сч[f"сводка:{'есть' if своя else (self.сводка_состояние if self.сводка is None else 'нет')}"] += 1
        строки = строки_сводки(своя, к, маска)
        if (x := строка_прошлой(self.прошлые.get(к.deal))):
            строки.append(("prev", x))
        f = self.факты.get(к.deal)
        if (x := строка_фактов(f)):
            строки.append(("facts", x))
        if (x := строка_главного(f)):
            строки.append(("imp", x))
        return строки

    def _оценить_расход(self, система: str, текст: str, схема_: dict, ч: Counter) -> tuple[float, float]:
        итог = self.итог
        вход_оц = токенов_оценка(система, текст, json.dumps(схема_, ensure_ascii=False))
        оценка = доллары([self.модель], вход_оц, self.ожидаемый_выход)
        потолок = потолок_вызова(self.модель, вход_оц)
        итог.вход_оценка += вход_оц
        итог.выход_оценка += self.ожидаемый_выход
        итог.usd_оценка += оценка
        итог.usd_потолок += потолок
        итог.оценено += 1
        if not self.live:
            ч["usd"] += оценка
            if итог.usd_оценка <= self.бюджет:
                итог.уложится += 1
        return оценка, потолок

    def _вызвать(self, к: Кандидат, номер: int, ч: Counter, запрос: dict, потолок: float, проверка,
                 неудача: dict, в_гейт: bool, now: dt.datetime):
        """Бронь бюджета → вызов → разбор и проверка ответа. (ответ, вход, выход, usd,
        модель ответа, трата) — или None (брак, отказ, сбой, бюджет: уже учтено)."""
        сч, итог = self.сч, self.итог
        if итог.потрачено + потолок > self.бюджет:
            self._остановить("бюджет")
            сч["не_дошли:бюджет"] += 1
            return None
        бронь = self._бронь(номер, к.deal, потолок)
        if бронь is False:
            return None
        сч["вызовов"] += 1
        ч["вызовов"] += 1
        трата = {"at": now, "run_id": self.run_id, "part": номер, "deal_id": к.deal, "model": self.модель,
                 "outcome": "", "defect": None, "api_status": None, "tokens_in": 0, "tokens_out": 0,
                 "usd": 0.0, "estimated": False, "kind": self.статья, "hold_id": бронь}
        ответ, ошибка = позвать(self.клиент_модели, запрос)
        if ошибка is not None:
            self._сбой_api(ошибка, трата, неудача, потолок, в_гейт, ч)
            return None
        self.сбоев_подряд = 0
        вход, выход, usd, отвечала = расход(ответ, self.модель)
        итог.потрачено += usd
        итог.вход += вход
        итог.выход += выход
        ч["usd"] += usd
        трата.update(model=отвечала, tokens_in=вход, tokens_out=выход, usd=usd)
        if отвечала != self.модель:
            сч["ответила_запасная"] += 1
        if not цена_известна(отвечала) or usd > потолок + 1e-9:
            # ответила модель не из таблицы цен: расход — по цене незнакомой, и он мог выйти за
            # бронь. Больше вызовов в этом прогоне нет — предел превышен не больше чем одним
            сч["расход_сверх_брони" if usd > потолок + 1e-9 else "цена_модели_неизвестна"] += 1
            self._остановить("бюджет")
        v, почему = разобрать_ответ(ответ)
        почему = почему or проверка(v)
        if почему:
            сч[f"брак:{почему}"] += 1
            if почему == "отказ модели":
                трата.update(outcome="отказ")
            else:
                трата.update(outcome="брак", defect=почему)
            self._неудача(трата, неудача, в_гейт, ч)
            return None
        return v, вход, выход, usd, отвечала, трата

    def _бронь(self, номер: int, deal: str, потолок: float):
        """Бронь потолка вызова в хранилище (deal_chat_take_budget): отказ — стоп «бюджет».
        Хранилище без броней (подпорка теста) — None: вызов без брони, как до 25.10.2026."""
        взять = getattr(self.store, "взять_бюджет", None)
        if взять is None:
            return None
        try:
            бронь = взять(self.run_id, номер, deal, self.статья, потолок)
        except Exception as e:                       # noqa: BLE001
            self.сч[f"сбой_записи:{type(e).__name__}:{getattr(e, 'pgcode', '') or ''}"] += 1
            self._остановить("запись", 1)
            return False
        if бронь is None:
            self.сч["бюджет:бронь_отказ"] += 1
            self.сч["не_дошли:бюджет"] += 1
            self._остановить("бюджет")
            return False
        return бронь

    def _после_вызова(self) -> None:
        сч, итог = self.сч, self.итог
        if итог.потрачено >= self.бюджет and not self.стоп:
            self._остановить("бюджет")
        брак = сч["вызовов_в_гейте"] >= БРАК_ПОСЛЕ and сч["брак_в_гейте"] / сч["вызовов_в_гейте"] > ДОЛЯ_БРАКА
        снято = (сч["фактов_предложено"] >= СНЯТЫХ_ПОСЛЕ
                 and сч["фактов_снято"] / сч["фактов_предложено"] > ДОЛЯ_СНЯТЫХ)
        if not сч["гейт_не_пройден"] and (брак or снято):
            # гейт важнее бюджета как причина остановки; прочие причины (запись,
            # доступ к API) остаются, но откат по гейту делается всё равно
            сч["гейт_не_пройден"] = 1
            сч["гейт:" + ("брак" if брак else "снятые_факты")] += 1
            итог.код = 1
            if self.стоп in ("", "бюджет"):
                self.стоп = "качество"

    def _факты(self, v, тексты, msgs, роли, маска, сводка, со_сводкой: bool) -> list[dict]:
        фч: Counter = Counter()
        факты = сверить_факты(v, тексты, {_mid(m): m for m in msgs}, роли, маска, dict(сводка),
                              проход=self.статья, сч=фч, со_сводкой=со_сводкой)
        self.сч.update(фч)
        self.сч["фактов_снято"] += sum(n for k, n in фч.items() if k.startswith("факт_снят:"))
        return факты

    def _записать_с_фактами(self, записать, факты: list[dict]) -> tuple[int, list[dict]]:
        """Запись строки вызова с фактами → (записано фактов, записанные в ней факты). База
        отвергла факт (третья ступень: проверка строки 23514 или триггер отрезка P0001) — та же
        транзакция ещё раз без фактов: оплаченная оценка не теряется, курсор идёт, факты
        считаются снятыми базой (ревью 25.10.2026). Прочие сбои — наверх (стоп «запись»)."""
        try:
            return int(записать(факты) or 0), факты
        except Exception as e:                       # noqa: BLE001
            if not факты or str(getattr(e, "pgcode", "") or "") not in ("23514", "P0001"):
                raise
            self.сч[f"факт_снят:база:{getattr(e, 'pgcode', '')}"] += len(факты)
            self.сч["фактов_снято"] += len(факты)
            self.сч["запись_без_фактов"] += 1
            записать([])
            return 0, []

    def _учесть_факты(self, факты: list[dict], записано: int, ч: Counter) -> None:
        self.сч["факт_записан"] += записано
        self.сч["факт_повтор"] += len(факты) - записано
        ч["фактов"] += записано
        for f in факты:
            self.итог.распределение[f"факт:{f['kind']}"] += 1
            if f["kind"] == "главное":
                self.итог.распределение[f"главное={f['data']['kind']}/{f['data']['severity']}"] += 1

    @staticmethod
    def _предложено_главного(v) -> int:
        """Сколько пунктов «главного» вернула модель (до проверок): строка вызова хранит число —
        «пункты сняты проверкой» отличимо от «модель важного не отметила» (ревью 25.10.2026)."""
        g = v.get("important") if isinstance(v, dict) else None
        return min(len(g), 50) if isinstance(g, list) else 1

    # ---------------------------------------------------------------- суточный проход
    def чат(self, к: Кандидат, номер: int, ч: Counter) -> None:
        сч = self.сч
        участники: list = []
        статус, msgs = прочитать_чат(self.client, к.chat, участники)
        сч["прочитано"] += 1
        ч["прочитано"] += 1
        now = dt.datetime.now(dt.timezone.utc)
        if статус == "limit":
            self._остановить("портал")
            сч["лимит_портала"] += 1
            return
        if статус != "ok":
            сч["нет_доступа" if статус == "denied" else "сбой_чтения"] += 1
            if self.live:                            # очередь сдвигается, курсор и read_at — нет
                self._запись(self.store.отметить_чтение, к.deal, к.chat, None, now, self.run_id, False)
            return
        было = self.состояние.get(к.deal)
        курсор = int((было or {}).get("last_msg_id") or 0)
        нов = новые(msgs, курсор)
        последний = последнее_человека(msgs, self.service_ids)
        if курсор and len(нов) >= СООБЩЕНИЙ:
            сч["разрыв"] += 1                        # новых больше окна: старшие не увидены
        if not any(человек(m, self.service_ids) for m in нов):
            сч["без_новых_людей"] += 1
            if self.live:
                self._запись(self.store.отметить_чтение, к.deal, к.chat, последний, now, self.run_id)
            return
        сч[f"с_новыми:{к.воронка}"] += 1
        ч["с_новыми"] += 1
        сч["новых_сообщений"] += len(нов)
        роли = Роли(self.service_ids, к.роли)
        маска = self._маска_чата(участники)
        сводка = self._сводка(к, маска)
        тексты: dict[int, str] = {}
        текст = текст_запроса(к, нов, роли, self.сегодня, сводка, тексты)
        запрос = запрос_модели(текст, self.модель)
        _оценка, потолок = self._оценить_расход(СИСТЕМА, текст, СХЕМА, ч)
        if not self.live:
            return
        lo, hi = _mid(нов[0]), _mid(нов[-1])
        отправлено = {_mid(m) for m in нов}
        в_гейт = int((было or {}).get("fail_streak") or 0) == 0   # прошлых неудач нет
        неудача = {"deal_id": к.deal, "chat_id": к.chat, "last_human_at": последний, "checked_at": now,
                   "run_id": self.run_id}
        r = self._вызвать(к, номер, ч, запрос, потолок,
                          lambda v: проверить_ответ(v, lo, hi, отправлено, (), True), неудача, в_гейт, now)
        if r is not None:
            v, вход, выход, usd, отвечала, трата = r
            со_сводкой = self._со_сводкой(к)
            факты = self._факты(v, тексты, нов, роли, маска, сводка, со_сводкой)
            self._записать(к, v, lo, hi, вход, выход, usd, отвечала, запрос, трата, now, последний, в_гейт, ч,
                           факты, неудача, со_сводкой)
        self._после_вызова()

    def _неудача(self, трата: dict, неудача: dict, в_гейт: bool, ч: Counter) -> None:
        """Неудача, повторимая на этом чате: расход, очередь и серия неудач."""
        ч["брак"] += 1
        if в_гейт:
            self.сч["вызовов_в_гейте"] += 1
            self.сч["брак_в_гейте"] += 1
        else:
            self.сч["брак_повторный"] += 1
        if self.история:
            self._запись(self.store.записать_неудачу, трата, неудача, True)
        else:
            self._запись(self.store.записать_неудачу, трата, неудача)

    def _сбой_api(self, e: BaseException, трата: dict, неудача: dict, потолок: float, в_гейт: bool,
                  ч: Counter) -> None:
        сч = self.сч
        сч[f"сбой_api:{_ошибка_api(e)}"] += 1
        код = getattr(e, "status_code", None)
        трата.update(outcome="сбой_api", api_status=код if isinstance(код, int) and 100 <= код <= 599 else None)
        род = род_сбоя(e)
        if род == "запрос":                          # плох этот запрос — неудача чата, не оплачен
            self.сбоев_подряд = 0
            self._неудача(трата, неудача, в_гейт, ч)
            return
        курсор = None
        if род == "код":                             # запрос не ушёл: не оплачен, чат не виноват
            self._запись(self.store.записать_неудачу, трата, None, self.история)
            self._остановить("api_код", 1)
            return
        if род == "связь":                           # мог быть оплачен: считаем потолок
            трата.update(usd=потолок, estimated=True)
            self.итог.потрачено += потолок
            ч["usd"] += потолок
            сч["расход_по_потолку"] += 1
            # очередь и серия неудач сделки сдвигаются (ревью 25.10.2026): чат, на котором вызов
            # всегда обрывается, не оплачивается по потолку в каждом прогоне первым; в гейт
            # качества сбой связи не идёт
            курсор = неудача
        if not self._запись(self.store.записать_неудачу, трата, курсор, self.история):
            return
        if род == "доступ":
            self._остановить("api_доступ", 1)
            return
        self.сбоев_подряд += 1
        if self.сбоев_подряд >= СБОЕВ_API_ПОДРЯД:
            self._остановить("api", 1)

    def _сбой_записи(self, e: BaseException, трата: dict, неудача: dict | None = None) -> None:
        # ни текста ошибки, ни значений: в нём бывают номера сделок
        self.сч[f"сбой_записи:{type(e).__name__}:{getattr(e, 'pgcode', '') or ''}"] += 1
        self._остановить("запись", 1)
        try:
            # деньги потрачены — расход пишется всё равно; очередь и серия неудач сделки
            # сдвигаются (ревью 25.10.2026): оплаченный вызов не повторяется первым каждый прогон
            self.store.записать_неудачу(dict(трата, outcome="сбой_записи"), неудача, self.история)
        except Exception:                            # noqa: BLE001
            self.сч["расход_не_записан"] += 1

    def _записать(self, к, v, lo, hi, вход, выход, usd, отвечала, запрос, трата, now, последний, в_гейт,
                  ч: Counter, факты: list[dict] | None = None, неудача: dict | None = None,
                  со_сводкой: bool = False) -> None:
        сч, итог = self.сч, self.итог
        вердикт = v["verdict"] if "verdict" in v else v
        строка = {"deal_id": к.deal, "model": отвечала, "prompt_sha256": отпечаток(запрос),
                  "method_ver": METHOD_VER, "msg_from_id": lo, "msg_to_id": hi,
                  "verdict": вердикт, "tokens_in": вход, "tokens_out": выход, "usd": usd,
                  "run_id": self.run_id, "assessed_at": now,
                  "imp_proposed": self._предложено_главного(v), "with_digest": со_сводкой}
        курсор_нов = {"chat_id": к.chat, "last_msg_id": hi, "last_human_at": последний, "checked_at": now}
        if в_гейт:
            сч["вызовов_в_гейте"] += 1
        трата = dict(трата, outcome="записано")
        try:
            if факты is None:
                записано, факты = int(self.store.записать_оценку(строка, курсор_нов, трата) or 0), []
            else:
                записано, факты = self._записать_с_фактами(
                    lambda ф: self.store.записать_оценку(строка, курсор_нов, трата, ф), факты)
        except Exception as e:                       # noqa: BLE001
            self._сбой_записи(e, трата, неудача)
            return
        self.записанные.setdefault(к.deal, self.состояние.get(к.deal))
        сч["записано"] += 1
        ч["записано"] += 1
        self._учесть_факты(факты, записано, ч)
        for ключ in ("state", "direction", "risk", "ball_role"):
            итог.распределение[f"{ключ}={вердикт[ключ]}"] += 1
        for x in вердикт["risk_kinds"]:
            итог.распределение[f"risk_kind={x}"] += 1
        итог.распределение[f"reply_expected={'да' if вердикт['reply_expected'] else 'нет'}"] += 1
        итог.распределение[f"due={'есть' if вердикт['due'] else 'нет'}"] += 1

    # ---------------------------------------------------------------- разовое чтение истории
    def _история_без_вызова(self, к: Кандидат, now: dt.datetime, курсор: dict | None) -> None:
        """Отметка истории без модели: курсор None — неудача чтения (серия, после БРАК_ПОДРЯД —
        пауза), иначе читать нечего — история прочитана (ревью 25.10.2026: иначе такая сделка
        вечно стоит кандидатом и читается из портала в каждом прогоне)."""
        if self.live and hasattr(self.store, "отметить_историю"):
            self._запись(self.store.отметить_историю, к.deal, self.run_id, now, курсор)

    def история_чата(self, к: Кандидат, номер: int, ч: Counter) -> None:
        сч, итог = self.сч, self.итог
        было = self.состояние.get(к.deal) or {}
        now = dt.datetime.now(dt.timezone.utc)
        # верх истории — ниже самого старого сообщения, уже оценённого сутками chat-ctx-2: те же
        # сообщения дважды не оплачиваются и не дают второго факта (ревью 25.10.2026)
        верх = int(было.get("last_msg_id") or 0)
        if self.границы.get(к.deal):
            верх = min(верх, int(self.границы[к.deal]) - 1)
        if верх <= 0:
            сч["история:нечего_читать"] += 1
            self._история_без_вызова(к, now, {"hist_low_id": None, "hist_state": "конец_чата"})
            return
        участники: list = []
        л = прочитать_историю(self.client, к.chat, верх, участники)
        сч["прочитано"] += 1
        ч["прочитано"] += 1
        сч["история:страниц"] += л.страниц
        if л.статус == "limit":
            self._остановить("портал")
            сч["лимит_портала"] += 1
            return
        if л.статус != "ok":
            сч["нет_доступа" if л.статус == "denied" else "сбой_чтения"] += 1
            self._история_без_вызова(к, now, None)
            return
        if л.нарушение:
            сч["страниц_с_нарушением"] += 1
            self._история_без_вызова(к, now, None)
            self._остановить("портал", 1)
            return
        сч[f"история:{л.дошли}"] += 1
        люди = sum(1 for m in л.msgs if человек(m, self.service_ids))
        сч["история:сообщений"] += len(л.msgs)
        сч["история:людей"] += люди
        сч["история:служебных"] += len(л.msgs) - люди
        итог.на_чат.append(len(л.msgs))
        if not люди:
            сч["история:без_людей"] += 1
            self._история_без_вызова(к, now, {"hist_low_id": min((_mid(m) for m in л.msgs), default=None),
                                              "hist_state": л.дошли})
            return
        роли = Роли(self.service_ids, к.роли)
        окно, дошли = окно_истории(л.msgs, роли, л.дошли)
        if дошли != л.дошли:
            сч["история:обрезано_по_знакам"] += 1
        сч[f"с_новыми:{к.воронка}"] += 1
        ч["с_новыми"] += 1
        маска = self._маска_чата(участники)
        сводка = self._сводка(к, маска)
        тексты: dict[int, str] = {}
        текст = текст_запроса(к, окно, роли, self.сегодня, сводка, тексты, история=True)
        запрос = запрос_модели(текст, self.модель, с_оценкой=False)
        _оценка, потолок = self._оценить_расход(СИСТЕМА_ИСТОРИИ, текст, СХЕМА_ИСТОРИИ, ч)
        if not self.live:
            return
        lo, hi = _mid(окно[0]), _mid(окно[-1])
        отправлено = {_mid(m) for m in окно}
        в_гейт = int(было.get("hist_fail_streak") or 0) == 0
        неудача = {"deal_id": к.deal, "chat_id": к.chat, "last_human_at": None, "checked_at": now,
                   "run_id": self.run_id}
        r = self._вызвать(к, номер, ч, запрос, потолок,
                          lambda v: проверить_ответ(v, lo, hi, отправлено, (), False), неудача, в_гейт, now)
        if r is not None:
            v, вход, выход, usd, отвечала, трата = r
            со_сводкой = self._со_сводкой(к)
            факты = self._факты(v, тексты, окно, роли, маска, сводка, со_сводкой)
            блок = "\n".join(f"[d:{k}] {x}" for k, x in сводка)
            строка = {"deal_id": к.deal, "model": отвечала, "prompt_sha256": отпечаток(запрос),
                      "method_ver": METHOD_VER, "msg_from_id": lo, "msg_to_id": hi, "msgs": len(окно),
                      "pages": л.страниц, "reached": дошли,
                      "digest_sha256": hashlib.sha256(блок.encode("utf-8")).hexdigest() if блок else None,
                      "tokens_in": вход, "tokens_out": выход, "usd": usd, "run_id": self.run_id,
                      "assessed_at": now, "imp_proposed": self._предложено_главного(v), "with_digest": со_сводкой}
            курсор = {"hist_low_id": lo, "hist_state": дошли, "hist_at": now}
            if в_гейт:
                сч["вызовов_в_гейте"] += 1
            трата = dict(трата, outcome="записано")
            try:
                записано, факты = self._записать_с_фактами(
                    lambda ф: self.store.записать_историю(строка, ф, курсор, трата), факты)
            except Exception as e:                   # noqa: BLE001
                self._сбой_записи(e, трата, неудача)
            else:
                self.записанные_истории.setdefault(к.deal, {k: было.get(k) for k in ПОЛЯ_ИСТОРИИ})
                сч["записано"] += 1
                ч["записано"] += 1
                self._учесть_факты(факты, записано, ч)
        self._после_вызова()


def обработать(client, store, канд: list[Кандидат], service_ids: set[str], *, режим: str,
               лимит: int, бюджет: float, сегодня: dt.date, run_id: str,
               модель: str = МОДЕЛЬ, клиент_модели=None, итог: Итог | None = None,
               частей: int = ЧАСТЕЙ_ПО_УМОЛЧАНИЮ, срок_с: float = ВРЕМЯ_МАКС_С, проход: str = "daily",
               имена: dict | None = None, сводка: dict | None = None, сводка_состояние: str = "нет") -> Итог:
    итог = итог or Итог(режим)
    итог.частей = частей
    итог.проход = проход
    прогон = _Прогон(client, store, service_ids, режим=режим, бюджет=бюджет, сегодня=сегодня,
                     run_id=run_id, модель=модель, клиент_модели=клиент_модели, итог=итог, срок_с=срок_с,
                     проход=проход, имена=имена, сводка=сводка, сводка_состояние=сводка_состояние)
    # как chat_activity: на лимите портала ждём не дольше минуты, потом стоп
    ждать_было = getattr(client, "limit_wait_budget", None)
    if ждать_было is not None:
        client.limit_wait_budget = min(ждать_было, chat_activity.LIMIT_WAIT_S)
    try:
        прогон(канд, лимит, частей)
    finally:
        if ждать_было is not None:
            client.limit_wait_budget = ждать_было
    return итог


