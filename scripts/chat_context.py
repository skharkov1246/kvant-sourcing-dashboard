def _места_дат(s: str) -> list[tuple[int, int]]:
    """Места настоящих дат в тексте (ГГГГ-ММ-ДД, ДД.ММ[.ГГГГ], «15 декабря»): число внутри — не
    деньги. «12.50 EUR» — не дата: месяца 50 нет."""
    out = []
    for m in _ДАТЫ_СООБЩЕНИЯ.finditer(s):
        g = m.groups()
        try:
            if g[0]:
                dt.date(int(g[0]), int(g[1]), int(g[2]))
            elif g[3]:
                dt.date(2000, int(g[4]), int(g[3]))       # 2000 — високосный: 29.02 тоже дата
        except ValueError:
            continue
        out.append((m.start(), m.end()))
    return out


def не_деньги(текст: str, amount) -> str:
    """'' — сумма записана в тексте как деньги; иначе причина: «нет_в_тексте» (числа нет) или
    «не_деньги» (проценты, штуки, сроки, номер, артикул, часть даты, рядом ни валюты, ни
    множителя, ни денежного слова)."""
    s = str(текст or "")
    н = s.lower()
    даты = _места_дат(s)
    мест = 0
    for a, b, конец_числа in _места_суммы(s, amount):
        мест += 1
        if _НЕ_ДЕНЬГИ_ПОСЛЕ.match(н, b) or _НЕ_ДЕНЬГИ_ДО.search(н[max(0, a - 14):a]):
            continue
        if b == конец_числа and any(x <= a < y for x, y in даты):
            continue                                  # часть даты (без множителя после неё)
        около = s[max(0, a - ОКНО_ВАЛЮТЫ[0]):a] + " " + s[b:b + ОКНО_ВАЛЮТЫ[1]]
        if (b > конец_числа or any(rx.search(около) for _код, rx in _ВАЛЮТА_РЯДОМ)
                or _ДЕНЕЖНЫЕ_СЛОВА.search(н[max(0, a - ОКНО_СЛОВ[0]):b + ОКНО_СЛОВ[1]])):
            return ""
    return "не_деньги" if мест else "нет_в_тексте"


def вид_в_тексте(текст: str, вид: str) -> bool:
    """Вид суммы (счёт, оплата, переторжка, итог) назван словом в сообщении."""
    rx = _СЛОВА_ВИДА.get(вид)
    return rx is None or bool(rx.search(str(текст or "")))


def дата_в_тексте(текст: str, дата, когда: dt.datetime | None) -> str:
    """'' — дата суммы написана в сообщении (ДД.ММ[.ГГ[ГГ]] — год сообщения или прошлый,
    ГГГГ-ММ-ДД, «15 декабря») и не позже дня сообщения по Москве; иначе «дата_не_в_тексте»
    или «дата_позже_сообщения»."""
    if not _дата(дата) or not isinstance(когда, dt.datetime):
        return "дата_не_в_тексте"
    d = dt.date.fromisoformat(дата)
    день = (когда if когда.tzinfo else когда.replace(tzinfo=_MSK)).astimezone(_MSK).date()
    for m in _ДАТЫ_СООБЩЕНИЯ.finditer(str(текст or "")):
        g = m.groups()
        try:
            if g[0]:
                варианты = [dt.date(int(g[0]), int(g[1]), int(g[2]))]
            elif g[3]:
                год = g[5]
                годы = [int(год) + (2000 if len(год) == 2 else 0)] if год else [день.year, день.year - 1]
                варианты = [dt.date(y, int(g[4]), int(g[3])) for y in годы]
            else:
                месяц = _МЕСЯЦЫ.index(g[7].lower()) + 1
                годы = [int(g[8])] if g[8] else [день.year, день.year - 1]
                варианты = [dt.date(y, месяц, int(g[6])) for y in годы]
        except ValueError:
            continue
        if d in варианты:
            return "" if d <= день else "дата_позже_сообщения"
    return "дата_не_в_тексте"


_СЛОВА_ДОГОВОРА = re.compile(r"договор|спецификац|контракт|подпис|эдо|диадок|сбис|оригинал|скан|допсоглаш", re.I)
_СЛОВА_СОРСИНГА = re.compile(r"ткп|кп|предложен|ответ|отказ|запрос|напомн|повторн|молч|цен", re.I)


def цитата(текст: str, вид: str, маска: МаскаИмён | None, сумма: float | None = None) -> str | None:
    """Короткая цитата факта (до ЦИТАТА_МАКС знаков) — режет код, а не модель. Источник —
    уже очищенное сообщение (ссылки, почты, телефоны скрыты, упоминания — роли); имена —
    маской. Окно — вокруг суммы, у договора и сорсинга — вокруг ключевого слова, иначе
    начало. Не прошла проверку базы (цитата_ок) — None: строка не уронит транзакцию."""
    s = маска.замаскировать(текст) if маска else str(текст or "")
    if not s:
        return None
    if вид == "деньги":
        где = найти_сумму(s, сумма)
    elif вид in ("договор", "сорсинг"):
        m = (_СЛОВА_ДОГОВОРА if вид == "договор" else _СЛОВА_СОРСИНГА).search(s)
        где = (m.start(), m.end()) if m else None
    else:
        где = None
    if len(s) <= ЦИТАТА_МАКС:
        q = s
    else:
        a, b = где or (0, 0)
        начало = max(0, min(a - (ЦИТАТА_МАКС - (b - a)) // 2, len(s) - ЦИТАТА_МАКС))
        q = s[начало:начало + ЦИТАТА_МАКС]
        if начало > 0:
            q = "…" + q[1:]
        if начало + ЦИТАТА_МАКС < len(s):
            q = q[:-1] + "…"
    q = q.strip()
    return q if q and цитата_ок(q) else None


def _ключ_факта(kind: str, msg_id, data: dict) -> str:
    """Как fact_key базы: вид, сообщение и данные — повтор того же факта не пишется."""
    return hashlib.md5(f"{kind}:{msg_id if msg_id is not None else ''}:"
                       f"{json.dumps(data, ensure_ascii=False, sort_keys=True)}".encode("utf-8")).hexdigest()


