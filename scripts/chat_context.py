# Ошибки нашего кода при вызове SDK — до отправки запроса (неверный аргумент, нет метода)
ОШИБКИ_КОДА = (TypeError, AttributeError, NameError, ImportError)


def род_сбоя(e: BaseException) -> str:
    """перегрузка — 429/529: запрос не исполнялся и не оплачен, его можно повторить;
    запрос — 400/413/422: плох именно этот запрос, это неудача чата;
    доступ — 401/403/404: ключ или модель, дальше звать бессмысленно;
    код — ошибка нашего вызова SDK (TypeError из-за betas или extra_body и т. п.): запрос не
    ушёл и не оплачен, повторять бессмысленно — стоп сразу, без потолка (ревью 28.10.2026);
    связь — остальное (таймаут, обрыв, 5xx): мог быть исполнен и оплачен."""
    код = getattr(e, "status_code", None)
    if код is None and isinstance(e, ОШИБКИ_КОДА):
        return "код"
    if код in (429, 529):
        return "перегрузка"
    if код in (400, 413, 422):
        return "запрос"
    if код in (401, 403, 404):
        return "доступ"
    return "связь"


