@dataclass
class Кандидат:
    deal: str
    chat: str
    воронка: str                       # real | pre
    стадия: str
    роли: dict[str, list[str]] = field(default_factory=dict)
    создана: str = ""                  # DATE_CREATE — порядок разового чтения истории


def кандидаты(real: list[dict], pre: list[dict], stage_meta: dict[str, dict],
              счёт: Counter) -> list[Кандидат]:
    """Открытые сделки обеих воронок с чатом. Открытость — по семантике стадии
    из справочника (запасной — поле сделки); «Оплата получена» — успех."""
    out: list[Кандидат] = []
    for воронка, сделки in (("real", real), ("pre", pre)):
        for d in сделки:
            sid = str(d.get("STAGE_ID") or "")
            m = stage_meta.get(sid) or {}
            sem = str(m.get("sem") or d.get("STAGE_SEMANTIC_ID") or "P").upper()
            имя = str(m.get("name") or sid)
            if sem != "P" or (воронка == "real" and contracts.PAID_RX.search(имя)):
                счёт[f"закрыта:{воронка}"] += 1
                continue
            cid = chat_activity.chat_id(d)
            if not cid:
                счёт[f"без_чата:{воронка}"] += 1
                continue
            счёт[f"кандидатов:{воронка}"] += 1
            out.append(Кандидат(str(d.get("ID")), cid, воронка, имя, роли_сделки(d, воронка),
                                str(d.get("DATE_CREATE") or "")))
    return out


def на_паузе_истории(s: dict | None, сейчас: dt.datetime) -> bool:
    """БРАК_ПОДРЯД неудач подряд в чтении истории — сделка не берётся ПАУЗА_БРАКА."""
    if not s or int(s.get("hist_fail_streak") or 0) < БРАК_ПОДРЯД:
        return False
    когда = s.get("hist_at")
    return isinstance(когда, dt.datetime) and сейчас - когда < ПАУЗА_БРАКА


def очередь_истории(канд: list[Кандидат], состояние: dict[str, dict], сейчас: dt.datetime,
                    счёт: Counter) -> list[Кандидат]:
    """Кандидаты разового чтения истории: суточный проход сделку уже оценивал (курсор > 0 —
    сделку с курсором 0 первым возьмёт он), история не читана и не на паузе после
    неудач. Порядок — ещё не пробованные первыми (ревью 25.10.2026: сделка, на которой
    чтение или вызов сорвались, не стоит в голове каждого прогона), внутри — новые сделки
    первыми (DATE_CREATE, затем номер)."""
    out = []
    for к in канд:
        s = состояние.get(к.deal)
        if not s or int(s.get("last_msg_id") or 0) <= 0:
            счёт[f"история:без_курсора:{к.воронка}"] += 1
        elif s.get("hist_state"):
            счёт[f"история:уже_читана:{к.воронка}"] += 1
        elif на_паузе_истории(s, сейчас):
            счёт["история:пауза_после_брака"] += 1
        else:
            счёт[f"история:кандидатов:{к.воронка}"] += 1
            if s.get("hist_at"):
                счёт["история:пробовали_раньше"] += 1
            out.append(к)
    новые_первыми = sorted(out, key=lambda к: (к.создана, int(к.deal) if к.deal.isdigit() else 0), reverse=True)
    return sorted(новые_первыми, key=lambda к: bool((состояние.get(к.deal) or {}).get("hist_at")))


def очередь(канд: list[Кандидат], состояние: dict[str, dict]) -> list[Кандидат]:
    """Давно не читанные первыми, ни разу не читанные — самыми первыми; затем новые сделки."""
    def ключ(к: Кандидат):
        s = состояние.get(к.deal)
        когда = s.get("checked_at") if s else None
        метка = когда.isoformat() if isinstance(когда, dt.datetime) else str(когда or "")
        return (s is not None, метка, -int(к.deal) if к.deal.isdigit() else 0)
    return sorted(канд, key=ключ)


def на_паузе(s: dict | None, сейчас: dt.datetime) -> bool:
    """БРАК_ПОДРЯД неудач подряд — чат не берётся ПАУЗА_БРАКА от последней."""
