def строки_итога(итог: Итог, бюджет: float, лимит: int, модель: str, схема: bool) -> list[str]:
    """Журнал — только агрегаты (правило 17): счётчики, токены, доллары, значения списков."""
    if итог.проход == "history":
        return строки_итога_истории(итог, бюджет, лимит, модель, схема)
    с = итог.счёт
    кандидатов = с["кандидатов:real"] + с["кандидатов:pre"]
    out = [
        f"чат сделок ({итог.режим}, {METHOD_VER}, {модель}): кандидатов {кандидатов} "
        f"(реализация {с['кандидатов:real']}, пресейл {с['кандидатов:pre']}) · без id чата "
        f"{с['без_чата:real'] + с['без_чата:pre']} · закрытых и «Оплата получена» отсеяно "
        f"{с['закрыта:real'] + с['закрыта:pre']} · на паузе после {БРАК_ПОДРЯД} неудач подряд "
        f"{с['пауза_после_брака']}",
        f"  чтение: прочитано {с['прочитано']} из лимита {лимит} · нет доступа {с['нет_доступа']} · "
        f"сбой {с['сбой_чтения']} · лимит портала {'— стоп' if с['лимит_портала'] else 'нет'} · "
        f"без новых сообщений людей {с['без_новых_людей']} · с новыми {с['с_новыми:real'] + с['с_новыми:pre']} "
        f"(реализация {с['с_новыми:real']}, пресейл {с['с_новыми:pre']}) · новых сообщений "
        f"{с['новых_сообщений']} · новых больше окна {с['разрыв']}"
        + ("" if схема else " · схемы в базе нет — курсоров нет, всё считается новым"),
        _строка_сводки_итога(с),
    ]
    if итог.бюджет_вход is not None:
        out.append(f"  бюджет: на прогон ${бюджет:.2f} (вход ${итог.бюджет_вход:.2f}; за сутки по Москве "
                   f"до прогона потрачено ${итог.потрачено_до:.2f}, удержано неоплаченными бронями "
                   f"${итог.брони_до:.2f} из ${БЮДЖЕТ_ДЕНЬ:.2f})")
    out.append(f"  оценка расхода: вход ~{итог.вход_оценка} ток., выход ~{итог.выход_оценка} ток. "
               f"({_строка_выхода(итог)}), ≈ ${итог.usd_оценка:.2f} (потолок ${итог.usd_потолок:.2f}) "
               f"при бюджете ${бюджет:.2f}")
    if итог.режим == "live":
        out += _строки_модели_итога(итог, бюджет)
    else:
        out.append(f"  в бюджет уложится оценок: {итог.уложится} из {с['с_новыми:real'] + с['с_новыми:pre']}"
                   + _строка_на_вызов(итог))
    out += _строки_частей_итога(итог)
    return out


def _строка_выхода(итог: Итог) -> str:
    с = итог.счёт
    return (f"на вызов {итог.выход_ожидаемый} ток." + (f", замер p90 записанных вызовов {с['выход:замер']}"
                                                       if с["выход:замер"] else ", по умолчанию — замера ещё нет"))


def _строка_на_вызов(итог: Итог) -> str:
    if not итог.оценено:
        return ""
    return (f" · на вызов в среднем ≈ ${итог.usd_оценка / итог.оценено:.3f}, потолок "
            f"${итог.usd_потолок / итог.оценено:.3f}")


def _строки_модели_итога(итог: Итог, бюджет: float) -> list[str]:
    с = итог.счёт
    брак = sorted((k.split(":", 1)[1], n) for k, n in с.items() if k.startswith("брак:"))
    сбои = sorted((k.split(":", 1)[1], n) for k, n in с.items() if k.startswith(("сбой_api:", "сбой_записи:")))
    out = [f"  модель: вызовов {с['вызовов']} · записано оценок {с['записано']} · ответила запасная "
           f"{с['ответила_запасная']} · брак {sum(n for _, n in брак)}"
           + (f" ({', '.join(f'{k} {n}' for k, n in брак)})" if брак else "")
           + (f" · сбои: {', '.join(f'{k} {n}' for k, n in сбои)}" if сбои else "")
           + f" · токенов вход {итог.вход} / выход {итог.выход} · потрачено ${итог.потрачено:.2f} "
           f"из ${бюджет:.2f}"
           + (f" (по потолку — {с['расход_по_потолку']} вызовов без ответа)" if с["расход_по_потолку"] else "")
           + (f" · отказ брони бюджета {с['бюджет:бронь_отказ']}" if с["бюджет:бронь_отказ"] else "")
           + (f" · ответила модель не из таблицы цен {с['цена_модели_неизвестна'] + с['расход_сверх_брони']} — стоп"
              if с["цена_модели_неизвестна"] or с["расход_сверх_брони"] else "")]
    out += _строки_фактов_итога(с, итог)
    out.append(f"  гейт качества: неудач {с['брак_в_гейте']} из {с['вызовов_в_гейте']} вызовов по чатам без "
               f"прошлых неудач (стоп — больше {ДОЛЯ_БРАКА:.0%} с {БРАК_ПОСЛЕ} вызовов) · снято фактов "
               f"{с['фактов_снято']} из {с['фактов_предложено']} (стоп — больше {ДОЛЯ_СНЯТЫХ:.0%} с "
               f"{СНЯТЫХ_ПОСЛЕ}) · повторных неудач {с['брак_повторный']}"
               + (f" · откат: оценок помечено {с['аннулировано']}, курсоров возвращено "
                  f"{с['курсоров_возвращено']}" if с["курсоров_возвращено"] else "")
               + (f" · откат фактов: помечено {с['фактов_помечено']} (оценки хода и курсоры стоят)"
                  if с["гейт:снятые_факты"] and итог.проход != "history" else ""))
    if итог.распределение:
        out.append(("  оценки (помечены откатом): " if с["аннулировано"] else "  оценки: ")
                   + ", ".join(f"{k} {n}" for k, n in sorted(итог.распределение.items())))
    return out


def _строки_частей_итога(итог: Итог) -> list[str]:
    с = итог.счёт
    out = []
    for номер, ч in итог.части:
        хвост = (f"вызовов {ч['вызовов']} · записано {ч['записано']} · неудач {ч['брак']} · фактов {ч['фактов']} · "
                 f"${ч['usd']:.2f}" if итог.режим == "live" else f"≈ ${ч['usd']:.2f}")
        с_людьми = "с людьми" if итог.проход == "history" else "с новыми"
        out.append(f"  часть {номер}/{итог.частей}: чатов {ч['прочитано']} · {с_людьми} {ч['с_новыми']} · {хвост}")
    недошли = sorted((k.split(":", 1)[1], n) for k, n in с.items() if k.startswith("не_дошли:"))
    if недошли:
        out.append("  не дошли: " + ", ".join(f"{k} {n}" for k, n in недошли))
    стоп = [k.split(":", 1)[1] for k in с if k.startswith("стоп:")]
    if стоп:
        out.append(f"  остановка: {стоп[0]}")
    return out


def _процентиль(xs: list[int], q: float) -> int:
    if not xs:
        return 0
    ys = sorted(xs)
    return ys[min(len(ys) - 1, max(0, math.ceil(q * len(ys)) - 1))]


def строки_итога_истории(итог: Итог, бюджет: float, лимит: int, модель: str, схема: bool) -> list[str]:
    """Журнал разового чтения истории — только числа: ни номеров, ни сумм, ни текста."""
    с = итог.счёт
    real, pre = с["история:кандидатов:real"], с["история:кандидатов:pre"]
    с_людьми = с["с_новыми:real"] + с["с_новыми:pre"]
    out = [
        f"история чатов ({итог.режим}, {METHOD_VER}, {модель}): кандидатов {real + pre} (реализация {real}, "
        f"пресейл {pre}) · без курсора суточного прохода {с['история:без_курсора:real'] + с['история:без_курсора:pre']}"
        f" · уже читана {с['история:уже_читана:real'] + с['история:уже_читана:pre']} · на паузе после "
        f"{БРАК_ПОДРЯД} неудач подряд {с['история:пауза_после_брака']} (не кандидаты) · из кандидатов пробовали "
        f"раньше (чтение или вызов сорвались) {с['история:пробовали_раньше']} — в конце очереди"
        + ("" if схема else " · схемы в базе нет — курсоров нет"),
        f"  чтение: прочитано чатов {с['прочитано']} из лимита {лимит} · страниц {с['история:страниц']} · "
        f"сообщений {с['история:сообщений']} (людей {с['история:людей']}, служебных {с['история:служебных']}) · "
        f"дошли до конца чата {с['история:конец_чата']}, упёрлись в предел {с['история:предел']} "
        f"({СТРАНИЦ_ИСТОРИИ} стр.; по знакам обрезано {с['история:обрезано_по_знакам']}) · нарушений порядка "
        f"страниц {с['страниц_с_нарушением']} · нет доступа {с['нет_доступа']} · сбой {с['сбой_чтения']} · "
        f"лимит портала {'— стоп' if с['лимит_портала'] else 'нет'} · без людей {с['история:без_людей']} · "
        f"старше оценённого сутками нечего читать {с['история:нечего_читать']}",
        f"  сообщений на чат: медиана {_процентиль(итог.на_чат, 0.5)}, 90-й процентиль "
        f"{_процентиль(итог.на_чат, 0.9)}",
        _строка_сводки_итога(с),
    ]
    остаток = max(0.0, БЮДЖЕТ_ИСТОРИИ - итог.потрачено_до - итог.брони_до)
    out.append(f"  оценка: вход ~{итог.вход_оценка} ток., выход ~{итог.выход_оценка} ток. ({_строка_выхода(итог)}), "
               f"≈ ${итог.usd_оценка:.2f} (потолок ${итог.usd_потолок:.2f}) при бюджете ${бюджет:.2f}; остаток "
               f"разового ${остаток:.2f} из ${БЮДЖЕТ_ИСТОРИИ:.2f} (потрачено ${итог.потрачено_до:.2f}, удержано "
               f"неоплаченными бронями ${итог.брони_до:.2f})"
               + (f"; уложится сделок {итог.уложится} из {с_людьми}" if итог.режим != "live" else ""))
    if итог.режим != "live" and итог.оценено and с["прочитано"]:
        кандидатов = real + pre
        на_сделку = итог.usd_оценка / с["прочитано"]
        out.append(f"  на сделку с людьми: ≈ ${итог.usd_оценка / итог.оценено:.3f}, потолок "
                   f"${итог.usd_потолок / итог.оценено:.3f} · ЭКСТРАПОЛЯЦИЯ (оценка, не замер: по {с['прочитано']} "
                   f"прочитанным из {кандидатов} кандидатов) — на всех ≈ ${на_сделку * кандидатов:.2f}, "
                   f"потолок ≈ ${итог.usd_потолок / с['прочитано'] * кандидатов:.2f}")
    if итог.режим == "live":
        out += _строки_модели_итога(итог, бюджет)
    out += _строки_частей_итога(итог)
    return out


def main(argv: list[str] | None = None, *, client=None, store=None, клиент_модели=None,
         сегодня: dt.date | None = None) -> int:
    ap = argparse.ArgumentParser(description="Чат сделки: оценка хода моделью, факты и главное")
    ap.add_argument("--mode", choices=("dry", "live"), default="dry")
    ap.add_argument("--pass", dest="проход", choices=tuple(ПРОХОДЫ), default="daily",
                    help="daily — новые сообщения (суточный предел); history — разовое чтение истории "
                         f"(своя статья, ${БЮДЖЕТ_ИСТОРИИ:g} за всё время)")
    ap.add_argument("--budget", type=float, default=None,
                    help=f"предел расхода на модель за прогон, $ (daily 0…{БЮДЖЕТ_ДЕНЬ:g}, history "
                         f"0…{БЮДЖЕТ_ИСТОРИИ:g}; и не больше остатка статьи)")
    ap.add_argument("--limit", type=int, default=ЛИМИТ_ПО_УМОЛЧАНИЮ, help="сколько чатов прочитать")
    ap.add_argument("--parts", type=int, choices=ЧАСТИ, default=ЧАСТЕЙ_ПО_УМОЛЧАНИЮ,
                    help="на сколько частей делить очередь прогона")
    ap.add_argument("--digest", default=None, help="файл сводки по сделкам (иначе DEALDIGEST_PATH)")
    a = ap.parse_args(argv)
    история = a.проход == "history"
    статья = ПРОХОДЫ[a.проход]
    предел = ПРЕДЕЛ_СТАТЬИ[статья]
    бюджет_вход = предел if a.budget is None else a.budget
    модель = (os.environ.get("CHAT_CTX_MODEL") or МОДЕЛЬ).strip()
    run_id = (os.environ.get("RUN_ID") or "").strip() or f"chat-ctx-{int(time.time())}"
    лимит = a.limit
    макс = ЛИМИТ_ИСТОРИИ if история else ЛИМИТ_МАКС
    if лимит <= 0 or лимит > макс:
        print(f"::warning::лимит чатов {лимит} вне 1…{макс} — беру {макс if лимит > 0 else 1}")
        лимит = макс if лимит > 0 else 1
    if not 0 <= бюджет_вход <= предел:               # nan не проходит тоже
        print(f"::error::бюджет {бюджет_вход} вне 0…{предел:g} долларов — предел владельца "
              + ("20 долларов на разовое чтение истории (решение 25.10.2026)" if история
                 else "5 долларов в сутки (решение 19.10.2026)"))
        return 1
    live = a.mode == "live"

    if live and клиент_модели is None:
        if not os.environ.get("ANTHROPIC_API_KEY", "").strip():
            print("::error::нет ANTHROPIC_API_KEY — оценка моделью невозможна")
            return 1
        клиент_модели = создать_клиента(ТАЙМАУТ_С[a.проход])
    if store is None:
        url = os.environ.get("SUPABASE_DB_URL", "").strip()
        if url:
            try:
                store = открыть_базу(url, только_чтение=not live)
            except Exception as e:                   # noqa: BLE001
                print(f"::error::база не открылась ({type(e).__name__})")
                return 1
        elif live:
            print("::error::нет SUPABASE_DB_URL — оценки некуда писать")
            return 1
        else:
            store = Память()
            print("::warning::нет SUPABASE_DB_URL: курсоров нет, все сообщения считаются новыми")
    итог = Итог(a.mode, частей=a.parts, бюджет_вход=бюджет_вход, проход=a.проход)
    окно = None if история else начало_суток()
    try:
        итог.потрачено_до = float(store.потрачено_с(окно, статья))
        брони = getattr(store, "брони_с", None)
        итог.брони_до = float(брони(окно, статья)) if брони else 0.0
    except Exception as e:                           # noqa: BLE001
        print(f"::error::расход статьи не прочитан ({type(e).__name__}) — предел не проверить")
        return 1
    # неоплаченные брони (прогон упал после брони) — их деньги заняты: остаток без них
    остаток = предел - итог.потрачено_до - итог.брони_до
    бюджет = max(0.0, min(бюджет_вход, остаток))
    # Чистая остановка (ревью 25.10.2026): остаток меньше потолка самого короткого вызова —
    # ни одного вызова не будет; live кончается до чтения портала, кодом 0
    мин_потолок = потолок_вызова(модель, токенов_оценка(СИСТЕМА_ИСТОРИИ if история else СИСТЕМА, json.dumps(
        СХЕМА_ИСТОРИИ if история else СХЕМА, ensure_ascii=False)))
    if остаток < мин_потолок:
        print(f"{'разовый' if история else 'суточный'} бюджет исчерпан: потрачено ${итог.потрачено_до:.2f}, "
              f"удержано неоплаченными бронями ${итог.брони_до:.2f} из ${предел:.2f} — остаток ${max(0.0, остаток):.2f} "
              f"меньше потолка самого короткого вызова ${мин_потолок:.2f}"
              + (" — портал не читается, вызовов нет" if live else " — холостой счёт ниже только для сведения"))
        if live:
            return 0
    сводка, сводка_состояние = загрузить_сводку(a.digest or os.environ.get("DEALDIGEST_PATH", "").strip())
    if сводка is None:
        print(f"::warning::сводки по сделкам нет ({сводка_состояние}) — модель видит стадию из портала, "
              "прошлую оценку и прошлые факты")
    if client is None:
        from bitrix_client import BitrixClient
        url = os.environ.get("BITRIX_WEBHOOK_URL", "").strip()
        if not url:
            print("::error::нет BITRIX_WEBHOOK_URL")
            return 1
        client = BitrixClient(url)
    # Чаты — от имени владельца (решение 19.10.2026): вебхук сборки не участник чатов
    # (сборка 19.10: из 129 чатов с простоем 123 — отказ). Вебхук владельца — только
    # чтение чатов, темп портала общий; сделки и справочники читает вебхук сборки.
    from bitrix_client import chat_reader_client
    чат_клиент, кто_читает = chat_reader_client(client)
    print(f"чаты читает {кто_читает}")

    try:
        канд, service_ids = собрать(client, итог.счёт)
        имена = client.users()
    except Exception as e:                           # noqa: BLE001
        print(f"::error::сделки из портала не выгружены ({type(e).__name__})")
        return 1
    try:
        обработать(чат_клиент, store, канд, service_ids, режим=a.mode, лимит=лимит, бюджет=бюджет,
                   сегодня=сегодня or начало_суток().date(), run_id=run_id, модель=модель,
                   клиент_модели=клиент_модели, итог=итог, частей=a.parts, проход=a.проход, имена=имена,
                   сводка=сводка, сводка_состояние=сводка_состояние,
                   срок_с=ВРЕМЯ_МАКС_ИСТОРИИ_С if история else ВРЕМЯ_МАКС_С)
    except Exception as e:                           # noqa: BLE001
        print(f"::error::прогон оборван ({type(e).__name__}: {getattr(e, 'pgcode', '') or ''})")
        итог.код = 1
    for s in строки_итога(итог, бюджет, лимит, модель, getattr(store, "схема", True)):
        print(s)
    if итог.счёт["лимит_портала"]:
        print("::warning::портал упёрся в лимит — чтение чатов остановлено, оценено то, что успели")
    if итог.счёт["страниц_с_нарушением"]:
        print("::error::портал отдал страницу истории не по правилу LAST_ID — чтение истории остановлено")
    if итог.счёт["стоп:время"]:
        print(f"::warning::прогон шёл дольше {(ВРЕМЯ_МАКС_ИСТОРИИ_С if история else ВРЕМЯ_МАКС_С) // 60} мин — "
              "остальное возьмёт следующий")
    if итог.счёт["гейт:снятые_факты"] and not история:
        print("::error::гейт снятых фактов не пройден — факты прогона помечены; оценки хода и курсоры на месте")
    elif итог.счёт["гейт_не_пройден"]:
        print("::error::гейт качества не пройден — оценки, факты и история прогона помечены, курсоры возвращены")
    if итог.счёт["цена_модели_неизвестна"] or итог.счёт["расход_сверх_брони"]:
        print("::warning::ответила модель не из таблицы цен — расход по цене незнакомой модели, прогон остановлен; "
              "добавить её в library/read_llm.ЦЕНЫ")
    if any(k.startswith("сбой_отката:") for k in итог.счёт):
        print("::error::откат не записан — пометить оценки прогона вручную (шапка deal_chat_schema.sql)")
    if итог.код:
        print("::error::прогон не чистый: см. «остановка» и «сбои» выше")
    return итог.код


