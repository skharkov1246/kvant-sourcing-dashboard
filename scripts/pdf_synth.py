#!/usr/bin/env python3
"""Придуманный PDF побайтно: каждая ячейка — свой текстовый объект по координатам.

ЗАЧЕМ. Причины, по которым наше КП заказчику в PDF давало 1,7 строки цены на
файл против 15,4 у книг Excel (разведка 28.09.2026, прогон 36465256273),
воспроизводятся только на PDF, собранном так, как собирает его печатная форма
1С: каждая ячейка таблицы — отдельный объект «BT … Tj ET» со своей точкой,
числа выровнены вправо, на первой странице крупный заголовок. Писать PDF в
зависимостях гейта нечем (reportlab там нет, pypdf только читает), поэтому
файл собирается руками — как у tests/test_pdftable.py и tests/test_read_pdf.py,
но с кириллицей и многими страницами.

КИРИЛЛИЦА. Байты строк — cp1251, шрифт Helvetica без встраивания, буква
извлекателю даётся таблицей /ToUnicode: pypdf берёт её оттуда, а ширины знаков —
из /Widths. Ширины заданы здесь же, поэтому правое выравнивание чисел считается
точно и не зависит от того, какие шрифты стоят в системе.

КОРПУС ПРИДУМАН (CLAUDE.md, правило 18): здесь только сборщик, содержимое даёт
вызывающий (tests/test_offer_pdf_fixes.py, scripts/cascade_corpus.py).
"""
from __future__ import annotations

from dataclasses import dataclass

#: Ширины знаков, тысячные кегля (как у Helvetica). Для правого выравнивания и
#: для /Widths — одна таблица, иначе извлекатель разместил бы текст не там, где
#: его поставил сборщик.
_ШИРИНЫ = {" ": 278, ",": 278, ".": 278, "-": 333, "(": 333, ")": 333, "%": 889,
           "/": 278, ":": 278, "«": 556, "»": 556, "№": 1000, "×": 584, "–": 556}
_ЦИФРА = 556
_ЗАГЛАВНАЯ = 667
_СТРОЧНАЯ = 556


def _ширина_знака(ч: str) -> int:
    if ч in _ШИРИНЫ:
        return _ШИРИНЫ[ч]
    if ч.isdigit():
        return _ЦИФРА
    if ч.isupper():
        return _ЗАГЛАВНАЯ
    return _СТРОЧНАЯ


def ширина(текст: str, кегль: float, жирный: bool = False) -> float:
    """Ширина строки в пунктах тем же счётом, что лежит в /Widths шрифта."""
    к = 1.05 if жирный else 1.0
    return sum(_ширина_знака(ч) for ч in текст) * к * кегль / 1000


@dataclass
class Надпись:
    """Текстовый объект: x, y — точка начала строки (левый край), пункты."""
    x: float
    y: float
    текст: str
    кегль: float = 8
    жирный: bool = False


def справа(край: float, y: float, текст: str, кегль: float = 8,
           жирный: bool = False) -> Надпись:
    """Надпись, выровненная вправо по краю ячейки."""
    return Надпись(край - ширина(текст, кегль, жирный), y, текст, кегль, жирный)


def _поток(тело: bytes) -> bytes:
    return b"<< /Length %d >>\nstream\n" % len(тело) + тело + b"\nendstream"


def _байты(ч: str) -> int:
    return ч.encode("cp1251")[0]


def _cmap() -> bytes:
    """ToUnicode для всех 224 знаков cp1251 от пробела: код → буква."""
    пары = []
    for код in range(0x20, 0x100):
        try:
            ч = bytes([код]).decode("cp1251")
        except UnicodeDecodeError:
            continue
        пары.append(b"<%02X> <%04X>" % (код, ord(ч)))
    куски = [пары[i:i + 100] for i in range(0, len(пары), 100)]
    тело = b"".join(b"%d beginbfchar\n" % len(к) + b"\n".join(к) + b"\nendbfchar\n"
                    for к in куски)
    return (b"/CIDInit /ProcSet findresource begin 12 dict begin begincmap\n"
            b"/CMapName /KV-cp1251 def /CMapType 2 def\n"
            b"1 begincodespacerange <00> <FF> endcodespacerange\n" + тело +
            b"endcmap CMapName currentdict /CMap defineresource pop end end\n")


def _ширины_шрифта(жирный: bool) -> bytes:
    к = 1.05 if жирный else 1.0
    out = []
    for код in range(0x20, 0x100):
        try:
            ч = bytes([код]).decode("cp1251")
        except UnicodeDecodeError:
            ч = " "
        out.append(b"%d" % round(_ширина_знака(ч) * к))
    return b"[" + b" ".join(out) + b"]"


def _экран(текст: str) -> bytes:
    б = текст.encode("cp1251", "replace")
    return б.replace(b"\\", b"\\\\").replace(b"(", b"\\(").replace(b")", b"\\)")


def собрать(страницы: list[list[Надпись]], размер: tuple[int, int] = (595, 842),
            перевод: bool = False) -> bytes:
    """PDF из страниц надписей. Каждая надпись — свой объект BT … ET.

    Шрифты F1 (обычный) и F2 (жирный) — Helvetica без встраивания с /Widths и
    /ToUnicode: извлекатель читает кириллицу и знает ширину каждого знака.

    перевод — за каждой надписью «T*» (переход на следующую строку), как пишут
    reportlab и печатные формы: обычный режим pypdf тогда ставит каждую ячейку
    на свою строку (причина F2), а режим выравнивания держит строку таблицы."""
    объекты: list[bytes | None] = [None, None]

    def добавить(тело: bytes) -> int:
        объекты.append(тело)
        return len(объекты)

    cmap = добавить(_поток(_cmap()))
    шрифты = []
    for жирный, имя in ((False, b"Helvetica"), (True, b"Helvetica-Bold")):
        шрифты.append(добавить(
            b"<< /Type /Font /Subtype /Type1 /BaseFont /" + имя +
            b" /FirstChar 32 /LastChar 255 /Widths " + _ширины_шрифта(жирный) +
            b" /ToUnicode %d 0 R >>" % cmap))
    листы = []
    for надписи in страницы:
        части = []
        for н in надписи:
            части.append(b"BT /%s %s Tf %s TL 1 0 0 1 %s %s Tm (%s) Tj%s ET" % (
                b"F2" if н.жирный else b"F1", b"%g" % н.кегль, b"%g" % (н.кегль * 1.2),
                b"%.2f" % н.x, b"%.2f" % н.y, _экран(н.текст), b" T*" if перевод else b""))
        поток = добавить(_поток(b"\n".join(части)))
        листы.append(добавить(
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 %d %d] "
            b"/Resources << /Font << /F1 %d 0 R /F2 %d 0 R >> >> /Contents %d 0 R >>"
            % (размер[0], размер[1], шрифты[0], шрифты[1], поток)))
    объекты[0] = b"<< /Type /Catalog /Pages 2 0 R >>"
    объекты[1] = (b"<< /Type /Pages /Kids [%s] /Count %d >>"
                  % (b" ".join(b"%d 0 R" % н for н in листы), len(листы)))
    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    смещения = []
    for н, тело in enumerate(объекты, 1):
        смещения.append(len(out))
        out += b"%d 0 obj\n" % н + (тело or b"") + b"\nendobj\n"
    xref = len(out)
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(объекты) + 1)
    for с in смещения:
        out += b"%010d 00000 n \n" % с
    out += (b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n"
            % (len(объекты) + 1, xref))
    return bytes(out)


@dataclass
class Колонка:
    """Колонка таблицы КП: ширина в пунктах, строки шапки, выравнивание данных."""
    ширина: float
    шапка: tuple[str, ...]
    вправо: bool = False


def таблица_кп(колонки: list[Колонка], строки: list[list[str]], *,
               заголовок: list[tuple[str, float]] = (),
               абзацы: list[str] = (), подвал: list[str] = (),
               строк_на_странице: int | None = None, повтор_шапки: bool = True,
               кегль: float = 8, поле: float = 2, x0: float = 30,
               размер: tuple[int, int] = (595, 842), перевод: bool = False,
               шапка_по_центру: bool = True) -> bytes:
    """КП в духе печатной формы: заголовок, абзацы, таблица по страницам, подвал.

    заголовок — строки (текст, кегль) над таблицей только на первой странице;
    крупный кегль и меняет среднюю ширину знака первой страницы, от которой
    pypdf считает раскладку (причина F1). Шапка колонки может быть в несколько
    строк: каждая строка шапки — своя надпись (причина F4). перевод — см. собрать.
    шапка_по_центру — заголовок колонки по центру, как в печатной форме 1С;
    выровненный влево заголовок широкой колонки отстоит от чисел, выровненных
    вправо, и разрез отдаёт его отдельной колонкой без данных."""
    _, высота = размер
    страницы: list[list[Надпись]] = []
    текущая: list[Надпись] = []
    y = высота - 40

    def новая() -> None:
        nonlocal текущая, y
        страницы.append(текущая)
        текущая = []
        y = высота - 40

    for текст, к in заголовок:
        текущая.append(Надпись(x0 + поле, y, текст, к, жирный=к > кегль))
        y -= к + 6
    for текст in абзацы:
        if y < 60:
            новая()
        текущая.append(Надпись(x0 + поле, y, текст, кегль))
        y -= кегль + 4

    def шапка() -> None:
        nonlocal y
        строк_шапки = max(len(к.шапка) for к in колонки)
        for k in range(строк_шапки):
            x = x0
            for к in колонки:
                if k < len(к.шапка) and к.шапка[k]:
                    т = к.шапка[k]
                    лево = (x + (к.ширина - ширина(т, кегль, True)) / 2 if шапка_по_центру
                            else x + поле)
                    текущая.append(Надпись(лево, y, т, кегль, жирный=True))
                x += к.ширина
            y -= кегль + 2
        y -= 3

    шапка()
    на_странице = 0
    for ячейки in строки:
        if y < 60 or (строк_на_странице and на_странице >= строк_на_странице):
            новая()
            на_странице = 0
            if повтор_шапки:
                шапка()
        x = x0
        for к, текст in zip(колонки, ячейки):
            if текст:
                if к.вправо:
                    текущая.append(справа(x + к.ширина - поле, y, текст, кегль))
                else:
                    текущая.append(Надпись(x + поле, y, текст, кегль))
            x += к.ширина
        y -= кегль + 4
        на_странице += 1
    y -= 6
    for текст in подвал:
        if y < 40:
            новая()
        текущая.append(Надпись(x0 + поле, y, текст, кегль))
        y -= кегль + 4
    страницы.append(текущая)
    return собрать(страницы, размер, перевод)


def деньги(x: float) -> str:
    """«12 345,60» — как печатает 1С."""
    return f"{x:,.2f}".replace(",", " ").replace(".", ",")
