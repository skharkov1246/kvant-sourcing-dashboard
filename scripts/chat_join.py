#!/usr/bin/env python3
"""Владелец — участник чатов открытых сделок реализации (решение владельца 22.10.2026).

ЗАЧЕМ. Чаты сделок читаются вебхуком владельца (секрет BITRIX_CHAT_WEBHOOK_URL,
решение 19.10.2026), а прочитать можно только чат, где владелец — участник.
Холостой прогон чатов 22.10: из 40 свежих чатов у 21 нет доступа, ни один чат
реализации не прочитан. Решение владельца: портал добавляет его в чаты открытых
сделок реализации.

КАК. 1) Кандидаты — тем же отбором, что пилот чатов (chat_context.собрать):
открытые сделки реализации (кат. 0, в работе, не «Оплата получена») с «ID чата
по сделке»; сделки читает вебхук сборки. 2) Проба доступа — вебхуком владельца,
одно сообщение (im.dialog.messages.get, LIMIT 1): читается — доступ есть.
3) live: где доступа нет — imopenlines.crm.chat.user.add (сделка, чат, владелец)
вебхуком владельца и повторная проба. Добавить себя в чужой чат методом
im.chat.user.add нельзя (право расширять чат — у участника); метод открытых линий
добавляет в чат объекта CRM пользователя с доступом к этому объекту — ему нужно
право вебхука «Открытые линии (imopenlines)». Владелец — номер пользователя из
адреса вебхука; адрес и номер в журнал не идут.

СНАЧАЛА МЕРЯЮТ. dry — шаги 1–2 и права вебхука (метод scope): сколько чатов без
доступа и хватит ли прав; в портал ничего не пишется. live — добавление, не больше
--limit чатов; первые ПРОБА добавлений — пробные: ни одно не удалось — стоп, в
журнал — классы ошибок. Повтор прогона безопасен: добавление идёт только туда,
где доступа нет.

ЧАСТИ (правило дробления 22.09.2026): очередь режется на --parts смежных отрезков
и идёт подряд в одном процессе; в журнале — счёт по частям. Портал — через
bitrix_client (≤ 2 запросов/с, темп общий у обоих вебхуков); первый
BitrixLimitError останавливает прогон.

В ЖУРНАЛ — ТОЛЬКО АГРЕГАТЫ (CLAUDE.md, правило 17): ни номеров сделок и чатов, ни
имён, ни адреса вебхука.

    python scripts/chat_join.py                       # dry: счёт и права
    python scripts/chat_join.py --mode live --limit 300
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts"))

import chat_context  # noqa: E402  (отбор кандидатов — одна точка правды с пилотом чатов)

ЛИМИТ_ПО_УМОЛЧАНИЮ = 300
ЛИМИТ_МАКС = 500
ЧАСТИ = (10, 25, 50)
ПРОБА = 3                       # первые добавления live: ни одно не удалось — стоп
ИСТОРИЯ = 5                     # сообщений в повторной пробе: больше одного — история видна
ПРАВО_ЧТЕНИЯ, ПРАВО_ДОБАВЛЕНИЯ = "im", "imopenlines"


def номер_владельца(url: str) -> int | None:
    """Номер пользователя из адреса входящего вебхука …/rest/<номер>/<код>/."""
    m = re.search(r"/rest/(\d+)/[^/]+", url or "")
    return int(m.group(1)) if m else None


def права(клиент) -> set[str] | None:
    """Права вебхука (метод scope); None — не узнать."""
    try:
        r = клиент.call("scope", {}, retries=1)
    except Exception:                                 # noqa: BLE001
        return None
    return {str(x) for x in r} if isinstance(r, list) else None


def проба(клиент, чат: str, сообщений: int = 1) -> tuple[str, int]:
    """('ok' | 'denied' | 'limit' | 'error', сколько сообщений видно)."""
    try:
        r = клиент.call("im.dialog.messages.get", {"DIALOG_ID": f"chat{чат}", "LIMIT": сообщений}, retries=1)
    except Exception as e:                            # noqa: BLE001
        if type(e).__name__ == "BitrixLimitError":
            return "limit", 0
        return ("denied" if "ACCESS" in str(e).upper() else "error"), 0
    if isinstance(r, dict) and isinstance(r.get("messages"), list):
        return "ok", len(r["messages"])
    return "error", 0


#: Класс отказа добавления по коду ошибки портала (текст ошибки в журнал не идёт).
КЛАССЫ = (
    ("INSUFFICIENT_SCOPE", "нет права imopenlines у вебхука"),
    ("CHAT_NOT_IN_CRM", "чат не привязан к сделке в CRM"),
    ("CRM_CHAT_USER_NOT_ACTIVE", "пользователь не активен"),
    ("WRONG_REQUEST", "уже участник или нет доступа"),
    ("ACCESS", "нет доступа к сделке или чату"),
)


def род_отказа(e: BaseException) -> str:
    if type(e).__name__ == "BitrixLimitError":
        return "лимит портала"
    s = str(e).upper()
    return next((имя for код, имя in КЛАССЫ if код in s), "сбой")


def добавить(клиент, сделка: str, чат: str, владелец: int) -> str:
    """'добавлен' или класс отказа."""
    try:
        r = клиент.call("imopenlines.crm.chat.user.add", {
            "CRM_ENTITY_TYPE": "deal", "CRM_ENTITY": int(сделка), "USER_ID": владелец, "CHAT_ID": int(чат)},
            retries=1)
    except Exception as e:                            # noqa: BLE001
        return род_отказа(e)
    return "добавлен" if r else "не добавлен (пустой ответ)"


def прогон(режим: str, лимит: int, частей: int, *, сборка, владелец_клиент, владелец: int | None,
           печать=print) -> int:
    live = режим == "live"
    счёт: Counter = Counter()
    канд, _служебные = chat_context.собрать(сборка, счёт)
    реализация = [к for к in канд if к.воронка == "real"]
    печать(f"чаты сделок реализации ({режим}): открытых сделок с чатом {len(реализация)} · без id чата "
           f"{счёт['без_чата:real']} · закрытых и «Оплата получена» отсеяно {счёт['закрыта:real']}")
    есть = права(владелец_клиент)
    if есть is None:
        печать("права вебхука владельца: не узнать (метод scope не ответил)")
    else:
        печать(f"права вебхука владельца: чтение чатов ({ПРАВО_ЧТЕНИЯ}) — {'есть' if ПРАВО_ЧТЕНИЯ in есть else 'нет'} · "
               f"добавление в чат сделки ({ПРАВО_ДОБАВЛЕНИЯ}) — {'есть' if ПРАВО_ДОБАВЛЕНИЯ in есть else 'нет'}")
    нет_права = есть is not None and ПРАВО_ДОБАВЛЕНИЯ not in есть
    if владелец is None:
        печать("::error::номер владельца не виден в адресе вебхука (…/rest/<номер>/<код>/) — добавлять некого")
        return 2
    if live and нет_права:
        печать(f"::error::у вебхука владельца нет права «Открытые линии ({ПРАВО_ДОБАВЛЕНИЯ})»: Битрикс24 → "
               "Разработчикам → вебхук → права; адрес вебхука после правки прав не меняется")
        return 2

    очередь = реализация[:лимит]
    if len(реализация) > лимит:
        печать(f"в очередь взято {лимит} из {len(реализация)} (лимит прогона)")
    итог: Counter = Counter()
    стоп = ""
    попыток = удач = 0
    for i, часть in enumerate(chat_context.нарезать(очередь, частей), 1):
        ч: Counter = Counter()
        for к in часть:
            if стоп:
                ч["не дошли"] += 1
                continue
            статус, _ = проба(владелец_клиент, к.chat)
            if статус == "limit":
                стоп = "лимит портала"
                ч["не дошли"] += 1
                continue
            ч[{"ok": "доступ есть", "denied": "нет доступа"}.get(статус, "сбой пробы")] += 1
            if статус != "denied" or not live:
                continue
            исход = добавить(владелец_клиент, к.deal, к.chat, владелец)
            попыток += 1
            ч[f"добавление: {исход}"] += 1
            if исход == "лимит портала":
                стоп = "лимит портала"
                continue
            if исход == "добавлен":
                удач += 1
                после, видно = проба(владелец_клиент, к.chat, ИСТОРИЯ)
                ч["после добавления читается" if после == "ok" else "после добавления не читается"] += 1
                if после == "ok" and видно > 1:
                    ч["история видна"] += 1
            if попыток == ПРОБА and not удач:
                стоп = "пробные добавления не удались"
        итог.update(ч)
        печать(f"  часть {i}/{частей}: чатов {len(часть)} · доступ есть {ч['доступ есть']} · нет доступа "
               f"{ч['нет доступа']}" + (f" · добавлено {ч['добавление: добавлен']}" if live else ""))
    печать(f"итог: доступ есть {итог['доступ есть']} · нет доступа {итог['нет доступа']} · сбой пробы "
           f"{итог['сбой пробы']} · не дошли {итог['не дошли']}")
    if live:
        отказы = sorted((к.split(": ", 1)[1], n) for к, n in итог.items()
                        if к.startswith("добавление: ") and к != "добавление: добавлен")
        печать(f"добавлено {итог['добавление: добавлен']} из {попыток} · после добавления читается "
               f"{итог['после добавления читается']} (история видна {итог['история видна']}) · не читается "
               f"{итог['после добавления не читается']}"
               + (" · отказы: " + ", ".join(f"{к} {n}" for к, n in отказы) if отказы else ""))
    else:
        печать(f"холостой прогон: в портал ничего не записано; live добавит в {итог['нет доступа']} чатов"
               + (f" — сначала право «Открытые линии ({ПРАВО_ДОБАВЛЕНИЯ})» вебхуку" if нет_права else ""))
    if стоп:
        печать(f"::error::остановлено: {стоп}")
        return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Владелец — участник чатов открытых сделок реализации")
    ap.add_argument("--mode", choices=("dry", "live"), default="dry")
    ap.add_argument("--limit", type=int, default=ЛИМИТ_ПО_УМОЛЧАНИЮ)
    ap.add_argument("--parts", type=int, choices=ЧАСТИ, default=ЧАСТИ[0])
    a = ap.parse_args(argv)
    if not 1 <= a.limit <= ЛИМИТ_МАКС:
        print(f"::error::--limit вне 1…{ЛИМИТ_МАКС}")
        return 2
    from bitrix_client import BitrixClient, chat_webhook_url
    сборка_url = os.environ.get("BITRIX_WEBHOOK_URL", "").strip()
    if not сборка_url:
        print("::error::нет BITRIX_WEBHOOK_URL")
        return 2
    чат_url = chat_webhook_url()
    if not чат_url:
        print("::error::нет BITRIX_CHAT_WEBHOOK_URL — вебхук владельца (решение 19.10.2026)")
        return 2
    сборка = BitrixClient(сборка_url)
    return прогон(a.mode, a.limit, a.parts, сборка=сборка, владелец_клиент=сборка.with_webhook(чат_url),
                  владелец=номер_владельца(чат_url))


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except SystemExit:
        raise
    except Exception as e:  # noqa: BLE001
        # текст исключения в журнал не идёт: в ошибке портала бывают номера и адрес
        print(f"::error::прогон упал: {type(e).__name__}")
        raise SystemExit(1)
