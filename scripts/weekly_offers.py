@dataclass
class Итог:
    окно: Окно
    поступило: list[Предложение]
    обработано: list[Предложение]
    вне_окна_дат: collections.Counter          # (откуда дата, где относительно окна) → файлов
    до_окна_обработаны: collections.Counter    # откуда дата → файлов (пришли до окна, обработаны в окне)
    замер: Замер
    сообщение_роли: str = ""
    отвергнуто_у_источника: int = 0            # дата у источника позже первой обработки — не взята


def собрать(cur, окно: Окно, подробно: bool = False, *, только_поступило: bool = False, роли: bool = True,
            калибровка: Калибровка | None = None, неделя=None) -> Итог | None:
    """Замер окна. С калибровкой (когорты) — ещё файлы, чья дата по номеру
    вложения в окне, и дата по номеру у файлов без точной даты."""
    з = Замер(cur, окно, подробно, только_поступило=только_поступило)
    if not з.проверить_схему():
        return None
    обработаны, датированы = з.найти()
    if калибровка is not None:
        датированы |= калибровка.кандидаты(окно, неделя)
    з.прочитать(обработаны | датированы)
    for о in з.предложения.values():
        выбрать_дату(о, з.даты_карточек.get(о.владелец) if о.источник == ИСТ_КАРТОЧКИ else None,
                     з.даты_писем.get(о.письмо) if о.письмо else None)
        if калибровка is not None:
            дата_по_номеру(о, калибровка, неделя)
    сообщение = з.посчитать_роли() if роли else "роль в когортах не считается"
    поступило, обработано = [], []
    вне = collections.Counter()
    до_окна_обработаны = collections.Counter()
    for о in з.предложения.values():
        где = о.где_поступило(окно)
        if где == В_ОКНЕ:
            поступило.append(о)
        elif not о.копия:
            вне[(о.откуда_дата, где)] += 1
        if о.момент_в_окне(окно) is not None:
            обработано.append(о)
            if где == ДО_ОКНА:
                до_окна_обработаны[о.откуда_дата] += 1
    отвергнуто = sum(1 for о in з.предложения.values() if о.у_источника_отвергнута and not о.копия)
    return Итог(окно, поступило, обработано, вне, до_окна_обработаны, з, сообщение, отвергнуто)


def впервые_записаны(предложения, окно: Окно) -> collections.Counter:
    """Файлы среза 2 по first_seen_at: впервые легли в lib_files в окне, раньше
    окна или до миграции дат (колонка пуста). Копии не считаются."""
    out: collections.Counter = collections.Counter()
    for о in предложения:
        if о.копия:
            continue
        if о.впервые is None:
            out["до миграции дат (не записано)"] += 1
        elif о.впервые < окно.начало:
            out["раньше окна"] += 1
        elif о.впервые < окно.конец:
            out["в окне"] += 1
        else:
            out["после окна"] += 1
    return out


def своды_по_источнику(предложения, окно, реестр) -> dict[str, Свод]:
    """Колонки источников, «всего» и копии. Копия во «всего» не входит."""
    своды = {КОРОТКО[и]: Свод() for и in ИСТОЧНИКИ}
    своды[ВСЕГО] = Свод()
    своды[КОПИИ] = Свод()
    for о in предложения:
        if о.копия:
            своды[КОПИИ].добавить(о, окно, реестр)
            continue
        своды[КОРОТКО[о.источник]].добавить(о, окно, реестр)
        своды[ВСЕГО].добавить(о, окно, реестр)
    return своды


def своды_по_дням(предложения, окно, реестр, день_предложения) -> dict[str, Свод]:
    """По дню; копии не считаются (как во «всего» таблицы по источнику)."""
    группы = группы_дней(окно)
    своды = {метка: Свод() for метка, _, _ in группы}
    своды[ВСЕГО] = Свод()
    for о in предложения:
        if о.копия:
            continue
        д = день_предложения(о)
        for метка, с, по in группы:
            if д is not None and с <= д <= по:
                своды[метка].добавить(о, окно, реестр)
                break
        своды[ВСЕГО].добавить(о, окно, реестр)
    return своды


