# ── Дата прихода по номеру вложения (когорты) ───────────────────────────────
#
# ЗАЧЕМ. Прогон 36314103300 (окно 21–27.09.2026) насчитал «поступило» всего 14 КП
# карточек и ни одного точного: у вложений карточек даты прихода в базе нет
# (first_seen_at заведён 27.09, заголовок закачки не принят, processed_at
# переписан переразбором). Ручная оценка — около 86 за неделю.
#
# ЧТО ИЗВЕСТНО. Номер вложения поля CRM (lib_files.file_id у полей карточек и
# сделок — id объекта вложения портала) растёт со временем загрузки: один ряд на
# портал (library/backfill_file_dates.py пользуется тем же). Из этого:
#   · НИЖНЯЯ граница номера X — самая поздняя дата создания карточки среди
#     вложений с номером ≤ X (файл загружен не раньше своей карточки, а номер
#     больше — значит, загружен позже тех);
#   · ВЕРХНЯЯ граница — самое раннее «мы видели» среди вложений с номером ≥ X
#     (first_seen_at, первая строка спроса, отметка обработки или
#     распознавания): файл с бо́льшим номером загружен позже X, и если мы его
#     уже видели, X к тому времени был.
# Обе границы — системные отметки, а не текст файла. Вложение, у которого своя
# нижняя позже своей верхней (карточка «создана» позже, чем мы видели файл), в
# распространение границ не идёт — одна битая отметка иначе сдвинула бы весь ряд
# выше неё — и считается нарушением. Пустой интервал после распространения
# (нижняя позже верхней) — нарушение монотонности; доля печатается.
# ТОЧКА — интерполяцией номера между соседними якорями (вложения, чей интервал
# не шире суток), обрезанной границами. Нет якорей с двух сторон — точки нет;
# для недели когорты годится и интервал, целиком лежащий в одной неделе (дата —
# его верхняя граница).
#
# ПИСЬМА СЮДА НЕ ИДУТ. Номер вложения письма — номер Диска («mail:<номер>»,
# library/mail_source.py), это ДРУГОЙ ряд чисел: калибровать по нему номера
# полей CRM нельзя. У писем и так есть точная дата — CREATED письма в CRM.

ОЦ_СУТКИ = "интервал по соседям не шире суток — верхняя граница"
ОЦ_ИНТЕРПОЛЯЦИЯ = "интерполяция номера между якорями"
ОЦ_НЕДЕЛЯ = "интервал целиком в неделе когорты — верхняя граница"
ОЦ_ИНТЕРВАЛ = "только интервал (якорей с двух сторон нет)"
ОЦ_ПУСТО = "интервал пуст — номер нарушает монотонность"
ОЦ_ПРОТИВОРЕЧИТ = "своя нижняя граница позже своей верхней"
ОЦ_ГРАНИЦЫ_НЕТ = "одной из границ нет"
_ЧИСЛО_SQL = "case when file_id ~ '^[0-9]{1,15}$' then file_id::bigint end"


class Калибровка:
    """Номер вложения поля CRM → интервал и точка даты прихода (дни портала)."""

    ЗАПАС_ДНЕЙ = 120          # хвост ряда: вложения карточек от «начало когорт − запас»
    ЯКОРЬ_ДНЕЙ = 1
    ЧАСТЬ_РЯДА = 20000

    def __init__(self, cur, кол) -> None:
        self.cur, self.кол = cur, кол
        self.номера: list[int] = []
        self.файлы: list[str] = []
        self.ид: dict[str, int] = {}
        self.низ: list = []
        self.верх: list = []
        self.противоречит: list[bool] = []
        self.хвост = 0
        self.якоря: list[tuple[int, date]] = []
        self.счёт: collections.Counter = collections.Counter()
        self.порций = 0
        self.оговорки: list[str] = []
        self.начало_хвоста: date | None = None

    def прочитать(self, с: date) -> None:
        ф, ц = self.кол["lib_files"], self.кол["lib_prices"]
        карточки: dict[str, date] = {}
        if {"rfq_id", "price_date_src"} <= ц:
            self.cur.execute("select rfq_id, min(price_date) from lib_prices"
                             " where feed = %s and price_date_src = %s and rfq_id is not null"
                             "   and price_date is not null group by 1", (FEED_КП, quote_date.КАРТОЧКА))
            карточки = {str(r): д for r, д in self.cur.fetchall()}
        else:
            self.оговорки.append("lib_prices без rfq_id/price_date_src — даты создания карточек нет, "
                                 "нижней границы по номеру нет")
        верх = "least(" + ", ".join(("processed_at", _к(ф, "first_seen_at", "timestamptz"),
                                     _к(ф, "ocr_at", "timestamptz"))) + ")"
        sql = (f"select n, file_id, origin, deal_id, верх from (select {_ЧИСЛО_SQL} as n, file_id, origin, deal_id,"
               f" {верх} as верх from lib_files where origin in (%(запрос)s, %(сделка)s)) t"
               " where n > %(после)s order by n limit %(k)s")
        ряд = []
        после = -1
        while True:
            self.порций += 1
            self.cur.execute(sql, {"запрос": ORIGIN_ЗАПРОСА, "сделка": ORIGIN_СДЕЛКИ, "после": после,
                                   "k": self.ЧАСТЬ_РЯДА})
            пачка = self.cur.fetchall()
            ряд += пачка
            if len(пачка) < self.ЧАСТЬ_РЯДА:
                break
            после = пачка[-1][0]
        свой_низ = [карточки.get(str(вл)) if origin == ORIGIN_ЗАПРОСА else None for _, _, origin, вл, _ in ряд]
        свой_верх = [в for *_, в in ряд]
        self.номера = [int(r[0]) for r in ряд]
        self.файлы = [str(r[1]) for r in ряд]
        self.ид = {f: i for i, f in enumerate(self.файлы)}
        self.счёт["ряд"] = len(ряд)
        порог = с - timedelta(days=self.ЗАПАС_ДНЕЙ)
        self.хвост = next((i for i, д in enumerate(свой_низ) if д is not None and д >= порог), len(ряд))
        self.начало_хвоста = порог
        хвост = self.файлы[self.хвост:]
        if not хвост:
            self.оговорки.append(f"нет вложений карточек, созданных с {порог.isoformat()} (по строкам цены"
                                 " «карточка: создана») — даты по номеру нет")
        if хвост and {"source_file", "created_at"} <= self.кол.get("lib_demand", set()):
            первые: dict[str, datetime] = {}
            for часть in _порции(хвост):
                self.порций += 1
                self.cur.execute("select source_file, min(created_at) from lib_demand"
                                 " where source_file = any(%s) group by 1", (часть,))
                первые.update(self.cur.fetchall())
            for i in range(self.хвост, len(ряд)):
                п = первые.get(self.файлы[i])
                if п is not None and (свой_верх[i] is None or п < свой_верх[i]):
                    свой_верх[i] = п
        свой_верх_д = [день_портала(м) for м in свой_верх]
        self.противоречит = [н is not None and в is not None and н > в for н, в in zip(свой_низ, свой_верх_д)]
        # Распространение: нижняя — снизу вверх, верхняя — сверху вниз; вложение
        # с противоречием в распространение не идёт.
        self.низ, текущий = [], None
        for н, плох in zip(свой_низ, self.противоречит):
            if н is not None and not плох and (текущий is None or н > текущий):
                текущий = н
            self.низ.append(текущий)
        self.верх, текущий = [None] * len(ряд), None
        for i in range(len(ряд) - 1, -1, -1):
            в = свой_верх_д[i]
            if в is not None and not self.противоречит[i] and (текущий is None or в < текущий):
                текущий = в
            self.верх[i] = текущий
        for i in range(self.хвост, len(ряд)):
            self.счёт["хвост"] += 1
            if self.противоречит[i]:
                self.счёт["своих противоречий"] += 1
                continue
            н, в = self.низ[i], self.верх[i]
            if н is None or в is None:
                continue
            self.счёт["с двумя границами"] += 1
            if н > в:
                self.счёт["пустой интервал"] += 1
            elif (в - н).days <= self.ЯКОРЬ_ДНЕЙ:
                self.якоря.append((self.номера[i], в))
        self.счёт["якорей"] = len(self.якоря)
        self._якоря_номера = [n for n, _ in self.якоря]
        if not self.якоря:
            self.оговорки.append("якорей (интервал по соседям не шире суток) нет — точки даты по номеру нет, "
                                 "только интервалы")

    def оценка(self, fid) -> dict | None:
        i = self.ид.get(str(fid))
        if i is None or i < self.хвост:
            return None
        н, в = self.низ[i], self.верх[i]
        о = {"номер": self.номера[i], "с": н, "по": в, "дата": None}
        if self.противоречит[i]:
            return {**о, "способ": ОЦ_ПРОТИВОРЕЧИТ}
        if н is None or в is None:
            return {**о, "способ": ОЦ_ГРАНИЦЫ_НЕТ}
        if н > в:
            return {**о, "способ": ОЦ_ПУСТО}
        if (в - н).days <= self.ЯКОРЬ_ДНЕЙ:
            return {**о, "дата": в, "способ": ОЦ_СУТКИ}
        n = self.номера[i]
        k = bisect.bisect_left(self._якоря_номера, n)
        if 0 < k < len(self.якоря):
            (na, да), (nb, дб) = self.якоря[k - 1], self.якоря[k]
            д = да + timedelta(days=int((n - na) / (nb - na) * (дб - да).days))
            return {**о, "дата": min(max(д, н), в), "способ": ОЦ_ИНТЕРПОЛЯЦИЯ}
        return {**о, "способ": ОЦ_ИНТЕРВАЛ}

    def дата(self, fid, неделя=None) -> tuple[date | None, dict | None]:
        """(дата для когорты, оценка). Без точки — верхняя граница, если интервал
        целиком в одной неделе когорт."""
        о = self.оценка(fid)
        if о is None:
            return None, None
        if о["дата"] is not None:
            return о["дата"], о
        if (неделя is not None and о["способ"] in (ОЦ_ИНТЕРВАЛ,) and неделя(о["с"]) == неделя(о["по"])):
            return о["по"], {**о, "дата": о["по"], "способ": ОЦ_НЕДЕЛЯ}
        return None, о

    def кандидаты(self, окно: Окно, неделя=None) -> set[str]:
        """Вложения хвоста, чья дата по номеру в окне: их находит только номер."""
        out = set()
        for i in range(self.хвост, len(self.файлы)):
            д, _ = self.дата(self.файлы[i], неделя)
            if д is not None and окно.с <= д <= окно.по:
                out.add(self.файлы[i])
        return out


