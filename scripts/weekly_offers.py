# ── Окно ─────────────────────────────────────────────────────────────────────

@dataclass(frozen=True)
class Окно:
    """Дни, обе границы включительно. Моменты (срез 2) — в UTC; даты (срез 1) —
    календарь портала, с которым сравниваются как есть."""
    с: date
    по: date

    @property
    def начало(self) -> datetime:
        return datetime(self.с.year, self.с.month, self.с.day, tzinfo=UTC)

    @property
    def конец(self) -> datetime:
        """Полночь ПОСЛЕ последнего дня — граница исключительно."""
        д = self.по + timedelta(days=1)
        return datetime(д.year, д.month, д.day, tzinfo=UTC)

    @property
    def начало_портала(self) -> datetime:
        """Полночь первого дня по календарю портала (МСК) — для дат среза 1."""
        return datetime(self.с.year, self.с.month, self.с.day, tzinfo=ПОЯС_ПОРТАЛА)

    @property
    def конец_портала(self) -> datetime:
        д = self.по + timedelta(days=1)
        return datetime(д.year, д.month, д.day, tzinfo=ПОЯС_ПОРТАЛА)

    @property
    def дней(self) -> int:
        return (self.по - self.с).days + 1

    def где(self, д: date | None) -> str:
        if д is None:
            return НЕ_ЗАПИСАНА
        if д < self.с:
            return ДО_ОКНА
        if д > self.по:
            return ПОСЛЕ_ОКНА
        return В_ОКНЕ

    def содержит_момент(self, м: datetime | None) -> bool:
        return м is not None and self.начало <= м < self.конец

    def дни(self) -> list[date]:
        return [self.с + timedelta(days=i) for i in range(self.дней)]


def _дата(имя: str, значение: str) -> date:
    try:
        return date.fromisoformat(значение.strip())
    except ValueError:
        raise ValueError(f"{имя}={значение!r}: нужна дата ГГГГ-ММ-ДД") from None


def окно_из_env(env, сегодня: date | None = None) -> Окно:
    """Окно по входам DAYS, FROM, TO. Ошибка входа — ValueError с понятным текстом."""
    сегодня = сегодня or datetime.now(UTC).date()
    дней_текст = str(env.get("DAYS") or "").strip() or "7"
    try:
        дней = int(дней_текст)
    except ValueError:
        raise ValueError(f"DAYS={дней_текст!r}: нужно целое число дней") from None
    if not 1 <= дней <= 366:
        raise ValueError(f"DAYS={дней}: допустимо от 1 до 366")
    с_текст = str(env.get("FROM") or "").strip()
    по_текст = str(env.get("TO") or "").strip()
    по = _дата("TO", по_текст) if по_текст else сегодня
    с = _дата("FROM", с_текст) if с_текст else по - timedelta(days=дней - 1)
    if с > по:
        raise ValueError(f"FROM {с.isoformat()} позже TO {по.isoformat()}")
    if (по - с).days + 1 > 366:
        raise ValueError("окно длиннее 366 дней — это уже не недельный свод")
    return Окно(с, по)


# ── Ключ подробной части ─────────────────────────────────────────────────────

def вид_ключа(pem: str) -> tuple[str, int | None]:
    """(«rsa» | «не rsa» | «не шифрует» | «не читается» | «нет openssl», бит).

    Спрашивается у openssl, и ровно тем действием, что у шага шифрования прогона:
    пробное RSA-OAEP. RSA-PSS читается как RSA с модулем, но шифровать им нельзя.
    Шаг проверяет то же самое, но уже после записи открытого файла; здесь
    негодный ключ отсекается раньше, и файла нет вовсе."""
    openssl = shutil.which("openssl")
    if not openssl:
        return "нет openssl", None
    try:
        with tempfile.TemporaryDirectory() as папка:
            путь = Path(папка) / "public.pem"
            путь.write_text(pem, encoding="ascii")
            r = subprocess.run([openssl, "pkey", "-pubin", "-in", str(путь), "-noout", "-text"],
                               capture_output=True, timeout=30)
            if r.returncode != 0:
                return "не читается", None
            текст = r.stdout.decode("ascii", "replace")
            if not re.search(r"^Modulus:", текст, re.M):
                return "не rsa", None
            м = re.search(r"Public-Key: \((\d+) bit\)", текст)
            бит = int(м.group(1)) if м else None
            проба = subprocess.run([openssl, "pkeyutl", "-encrypt", "-pubin", "-inkey", str(путь),
                                    "-pkeyopt", "rsa_padding_mode:oaep"], input=b"0" * 65,
                                   capture_output=True, timeout=30)
            if проба.returncode != 0 or not проба.stdout:
                return "не шифрует", бит
            return "rsa", бит
    except (OSError, subprocess.SubprocessError):
        return "нет openssl", None


def проверить_ключ(значение: str | None) -> tuple[bool, str]:
    """(писать ли подробности, что сказать в журнал). Сам ключ не печатается."""
    т = "".join(str(значение or "").split())
    if not т:
        return False, "подробная часть не пишется: вход pubkey пуст (журнал — только агрегаты)"
    try:
        pem = base64.b64decode(т, validate=True).decode("ascii")
    except (binascii.Error, ValueError, UnicodeDecodeError):
        return False, "::warning::вход pubkey не читается как base64 PEM — подробная часть не пишется"
    if "PRIVATE" in pem.upper():
        return False, ("::error::во входе pubkey ЗАКРЫТЫЙ ключ. Входы запуска видны всем, кто видит "
                       "прогоны: эту пару больше не использовать. Подробная часть не пишется")
    if "-----BEGIN PUBLIC KEY-----" not in pem and "-----BEGIN RSA PUBLIC KEY-----" not in pem:
        return False, "::warning::вход pubkey не похож на открытый ключ PEM — подробная часть не пишется"
    вид, бит = вид_ключа(pem)
    if вид == "не читается":
        return False, "::warning::openssl не читает вход pubkey как открытый ключ — подробная часть не пишется"
    if вид in ("не rsa", "не шифрует"):
        return False, ("::warning::вход pubkey — не ключ шифрования RSA: RSA-OAEP с ним не работает. "
                       "Подробная часть не пишется")
    if вид == "rsa" and (бит or 0) < МИН_БИТ_RSA:
        return False, (f"::warning::вход pubkey — RSA короче {МИН_БИТ_RSA} бит: слаб для данных, "
                       "выложенных артефактом. Подробная часть не пишется")
    return True, "подробная часть: пишется для шифрования открытым ключом из входа"


