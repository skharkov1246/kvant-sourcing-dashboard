def _iso(x) -> str | None:
    return x.isoformat() if x is not None else None


def _оценка_json(о: dict | None) -> dict | None:
    if о is None:
        return None
    return {"номер": о["номер"], "с": _iso(о["с"]), "по": _iso(о["по"]), "дата": _iso(о["дата"]),
            "способ": о["способ"]}


def _наше_json(записи: list, р: dict, на: date) -> list:
    """Наши строки той же сделки с тем же ключом кода: цена, приведённая, наценка."""
    out = []
    пр_с = None
    for fid, ц, почему in записи:
        if ц is None:
            out.append({"file_id": fid, "цена": None, "наценка_%": None, "несравнимо": почему})
            continue
        пр_н = приведённая(ц, на)
        запись = {"file_id": fid, "код": ц["код"], "наименование": ц["наименование"], "цена": ц["цена"],
                  "валюта": ц["валюта"], "единица": ц["единица"], "уверенность": ц["уверенность"],
                  "приведённая": пр_н, "наценка_%": None, "несравнимо": почему}
        if почему is None:
            пр_с = пр_с or приведённая(р, на)
            if пр_с["цена"] and пр_н["цена"] is not None:
                запись["наценка_%"] = round((пр_н["цена"] / пр_с["цена"] - 1) * 100, 1)
                if not (пр_с["стандартный_базис"] and пр_н["стандартный_базис"]):
                    запись["оговорка"] = ("базис не у обеих цен стандартный (FCA/EXW) — в наценке может"
                                          " сидеть доставка")
            else:
                запись["несравнимо"] = "приведённой цены нет"
        out.append(запись)
    return out


def строка_json(р: dict, по_строке: dict, на: date) -> dict:
    """Строка цены поставщика для подробной части: исходная и приведённая цена,
    пометки (письмо, низкая уверенность) и наши строки по тому же коду."""
    x = dict(р)
    x["приведённая"] = приведённая(р, на)
    x["письмо"] = р.get("поток") == FEED_ПИСЬМА
    x["в_сравнение"] = (р.get("уверенность") or "") != "low"
    пометки = []
    if x["письмо"]:
        пометки.append("цена из письма")
    if not x["в_сравнение"]:
        пометки.append("низкая уверенность — показывается, в сравнение не идёт")
    x["пометки"] = пометки
    записи = по_строке.get(р.get("id"))
    x["наше_кп"] = _наше_json(записи, р, на) if записи is not None else None
    return x


def _куда_json(п: Предложение, связи: Связи | None) -> dict | None:
    """Куда ушло КП: сделка и как связано, заказчик и название сделки (вид
    lib_deal_customer), название запроса (lib_rfq_cards) — значение или причина
    пустоты. «автокопия» — сделки автокопий у карточки, связанной по parentId2
    (второй путь той же связи; расхождение видно здесь поимённо)."""
    с = связи.связь(п) if связи is not None else None
    if с is None:
        return None
    з = связи.заказчик(с["сделка"])
    if п.источник == ИСТ_КАРТОЧКИ:
        название, почему = связи.название_карточки(п.владелец)
        запрос = {"карточка": п.владелец, "название": название, "название_почему": почему}
    else:
        запрос = None
    return {"сделка": с["сделка"], "связь": с["как"], "кандидаты": с["кандидаты"],
            "автокопия": с.get("автокопия"),
            "заказчик": з["заказчик"], "заказчик_почему": з["заказчик_почему"],
            "компания_заказчика": з["компания_заказчика"], "реестр_заказчика": з["реестр_заказчика"],
            "название_сделки": з["название"], "название_сделки_почему": з["название_почему"],
            "стадия_сделки": з["стадия"],
            "запрос": запрос,
            "наше_кп": [кп.file_id for кп in связи.наши.get(с["сделка"], [])] if с["сделка"] else []}


def _наше_кп_json(кп: НашеКП) -> dict:
    return {"file_id": кп.file_id, "поле": кп.поле, "статус": кп.статус, "дата": _iso(кп.дата),
            "откуда_дата": кп.откуда_дата, "по_номеру": _оценка_json(кп.по_номеру),
            "позиций_разбора": кп.позиций_разбора, "строк_живых": len(кп.строки), "строк_с_ценой": len(кп.цены),
            "почему_без_цены": None if кп.цены else НЕТ_НАШЕЙ_ЦЕНЫ,
            "строки": кп.строки[:СТРОК_ЦЕНЫ_В_ПОДРОБНОСТЯХ], "цены": кп.цены[:СТРОК_ЦЕНЫ_В_ПОДРОБНОСТЯХ]}


def _сделки_json(ск: Сквозное, реестр: dict) -> list:
    """Сводный раздел: по сделке — заказчик, запросы, КП поставщиков, наше КП, покрытие."""
    с = ск.связи
    по_корзине = ск.сопоставление["по_корзине"]
    out = []
    for д in sorted({с.сделка(п) for п in с.предложения if с.сделка(п)}):
        кп = sorted((п for п in с.предложения if с.сделка(п) == д), key=lambda x: x.file_id)
        з = с.заказчик(д)
        out.append({
            "сделка": д, "заказчик": з["заказчик"], "заказчик_почему": з["заказчик_почему"],
            "компания_заказчика": з["компания_заказчика"], "реестр_заказчика": з["реестр_заказчика"],
            "название": з["название"], "название_почему": з["название_почему"], "стадия": з["стадия"],
            "запросы": [{"карточка": к, **dict(zip(("название", "название_почему"), с.название_карточки(к)))}
                        for к in sorted(с.карточки_сделки.get(д, ()))],
            "кп_поставщиков": [{
                "file_id": п.file_id, "источник": п.источник, "связь": с.связь(п)["как"],
                "карточка": п.владелец if п.источник == ИСТ_КАРТОЧКИ else None, "письмо": п.письмо,
                "компании": [{"ключ_портала": к, "имя": реестр.get(к, (None, None))[1]} for к in sorted(п.компании)],
                "роль": п.роль, "бренды": sorted(п.бренды_файла, key=бренд_ключ)[:БРЕНДОВ_В_ПОДРОБНОСТЯХ],
                "бренды_карточки_СП176": sorted(п.бренды_карточки)[:БРЕНДОВ_В_ПОДРОБНОСТЯХ],
                "поступило": _iso(п.дата_поступления), "откуда_дата": п.откуда_дата,
                "строк_цены": len(с.ряды.get(п.file_id, []))} for п in кп],
            "наше_кп": [_наше_кп_json(x) for x in с.наши.get(д, [])],
            "покрытие": по_корзине.get(д),
        })
    return out


