class База:
    """Закрытая база Supabase. statement_timeout и lock_timeout — в строке
    подключения (правила 9 и 12): SET откатывается с транзакцией."""

    def __init__(self, dsn: str, схема: str | None = None):
        import psycopg2
        опции = "-c statement_timeout=120000 -c lock_timeout=10000"
        if схема:
            опции += f" -c search_path={схема}"
        self.с = psycopg2.connect(dsn, options=опции)

    def нет_таблиц(self) -> list[str]:
        """Таблицы и колонки, без которых запись не состоится, — до первого оплаченного
        вызова: таблица прежней версии без side_link упала бы на вставке уже после
        чтения."""
        with self.с, self.с.cursor() as c:
            c.execute("select to_regclass('contract_terms') is null, to_regclass('contract_b2b_flags') is null, "
                      "to_regclass('contract_deal_outcome') is null")
            нет_условий, нет_флагов, нет_исходов = c.fetchone()
            нет = [имя for имя, н in (("contract_terms", нет_условий), ("contract_b2b_flags", нет_флагов),
                                      ("contract_deal_outcome", нет_исходов)) if н]
            if not нет_условий:
                c.execute("select array_agg(attname::text) from pg_attribute "
                          "where attrelid = to_regclass('contract_terms') and attnum > 0 and not attisdropped")
                есть = set(c.fetchone()[0] or [])
                нет += [f"contract_terms.{к}" for к in self.КОЛОНКИ if к not in есть]
                # рамочный под спецификациями нескольких сделок и заказов — строка на каждую
                # пару «сделка, заказ»: ключ без deal_id и order_key молча снял бы строки второй
                # (on conflict do nothing)
                c.execute("select coalesce(array_agg(a.attname::text), '{}') from pg_constraint k "
                          "join pg_attribute a on a.attrelid = k.conrelid and a.attnum = any (k.conkey) "
                          "where k.conrelid = to_regclass('contract_terms') and k.contype = 'p'")
                в_ключе = set(c.fetchone()[0] or [])
                if not {"deal_id", "order_key"} <= в_ключе:
                    нет.append("contract_terms.primary key (deal_id, order_key)")
        return нет

    def прочитанные_файлы(self, модель: str) -> set[tuple[int, int, str]]:
        """Файлы (вид, карточка, номер файла), которые та же модель и версия метода уже
        прочитала, — после бюджета прогон качает только их (условия даром по sha256)."""
        with self.с, self.с.cursor() as c:
            c.execute("select distinct card_entity, card_id, file_id from contract_terms "
                      "where status in ('ok', 'reused') and model = %s and method_ver = %s and file_id <> ''",
                      (модель, METHOD_VER))
            return {(int(a), int(b), str(f)) for a, b, f in c.fetchall()}

    def из_кэша(self, sha256: str, модель: str) -> dict | None:
        """Условия того же файла, прочитанного раньше той же моделью и версией
        метода. Только status = 'ok': обрезанный файл так не пишется (он limit), и
        повтор по нему не найдёт неполных условий."""
        with self.с, self.с.cursor() as c:
            c.execute("select terms, evidence, pages, note, dropped from contract_terms "
                      "where sha256 = %s and model = %s and method_ver = %s and status = 'ok' "
                      "order by created_at desc limit 1", (sha256, модель, METHOD_VER))
            r = c.fetchone()
        if not r:
            return None
        return {"terms": r[0], "evidence": r[1] or {}, "pages": r[2], "note": r[3], "dropped": r[4] or []}

    КОЛОНКИ = ("run_id", "method_ver", "deal_id", "card_entity", "card_id", "order_id", "side", "side_source",
               "side_link", "side_template", "side_company", "link_source", "template", "doc_type", "file_field",
               "file_id", "sha256", "pages", "note", "status", "model", "terms", "evidence", "dropped", "usd")
    КОЛОНКИ_JSON = ("terms", "evidence", "dropped")

    def записать_условия(self, строки: list[dict]) -> None:
        import psycopg2.extras
        if not строки:
            return
        Json = psycopg2.extras.Json
        with self.с, self.с.cursor() as c:
            psycopg2.extras.execute_values(
                c, f"insert into contract_terms ({', '.join(self.КОЛОНКИ)}) values %s on conflict do nothing",
                [tuple(Json(r[к]) if к in self.КОЛОНКИ_JSON and r[к] is not None else r[к]
                       for к in self.КОЛОНКИ) for r in строки])

    def записать_флаги(self, флаги: list[dict], run_id: str) -> None:
        self.записать_итог(флаги, {}, run_id)

    def записать_итог(self, флаги: list[dict], исходы: dict[int, str], run_id: str) -> None:
        """Флаги и исход по каждой сделке — одной транзакцией: исход «пара» без своих
        флагов вкладка прочла бы как «рисков сверки нет»."""
        import psycopg2.extras
        if not флаги and not исходы:
            return
        with self.с, self.с.cursor() as c:
            if флаги:
                psycopg2.extras.execute_values(
                    c, "insert into contract_b2b_flags (run_id, method_ver, deal_id, order_id, code, days) "
                       "values %s on conflict do nothing",
                    [(run_id, ВЕРСИЯ_ИСХОДА, f["deal_id"], f["order_id"], f["code"], f["days"]) for f in флаги])
            if исходы:
                psycopg2.extras.execute_values(
                    c, "insert into contract_deal_outcome (run_id, method_ver, deal_id, outcome) "
                       "values %s on conflict do nothing",
                    [(run_id, ВЕРСИЯ_ИСХОДА, int(д), и) for д, и in sorted(исходы.items())])

    def итог_сделок(self, run_id: str) -> int:
        with self.с, self.с.cursor() as c:
            c.execute("select count(*) from contract_deal_outcome where run_id = %s", (run_id,))
            return int(c.fetchone()[0])

    def итог(self, run_id: str) -> tuple[int, int, float]:
        """Сколько записано — запросом по ключу прогона: rowcount у execute_values —
        счёт последней пачки (навык db-schema)."""
        with self.с, self.с.cursor() as c:
            c.execute("select count(*), coalesce(sum(usd), 0) from contract_terms where run_id = %s", (run_id,))
            строк, usd = c.fetchone()
            c.execute("select count(*) from contract_b2b_flags where run_id = %s", (run_id,))
            флагов = c.fetchone()[0]
        return int(строк), int(флагов), float(usd)

    def разборы(self) -> tuple[list[dict], dict[tuple[int, str], list[dict]], dict[tuple[int, str], list[dict]]]:
        """Для пересчёта: (выбор прогона по сделке — тот, что показывает вкладка, строки
        выбранных пар «сделка, прогон» всеми колонками, записанные флаги этих пар).

        Выбор — тем же правилом, что у свода для вкладки (realization_ctx.выбор_прогона):
        последний записанный исход, «недочитана» — прежним полным разбором с теми же
        файлами. Строки — в порядке свода (realization_ctx.ПОРЯДОК_СТРОК_SQL)."""
        rc = _rc()
        по_сделке: dict[int, list[dict]] = defaultdict(list)
        with self.с, self.с.cursor() as c:
            c.execute("select deal_id, run_id, outcome, created_at, method_ver from contract_deal_outcome "
                      "order by deal_id, created_at desc, run_id desc")
            for deal, run, исход, at, вер in c.fetchall():
                по_сделке[int(deal)].append({"deal": int(deal), "run": run, "outcome": исход, "at": at, "ver": вер})
        кандидаты = sorted({(x["deal"], x["run"]) for rr in по_сделке.values()
                            for x in (rr[0], next((y for y in rr if y["outcome"] not in rc.НЕ_ЗАТИРАЮТ), None)) if x})
        строки = self._строки_пар(кандидаты)
        файлы = {к: frozenset((r["card_entity"], r["card_id"], r["file_id"]) for r in rs if r["status"] != "no_file")
                 for к, rs in строки.items()}
        выбор = [rc.выбор_прогона(rr, файлы) for _d, rr in sorted(по_сделке.items())]
        нужны = {(v["deal"], v["run"]) for v in выбор}
        флаги: dict[tuple[int, str], list[dict]] = defaultdict(list)
        if нужны:
            with self.с, self.с.cursor() as c:
                c.execute("select deal_id, run_id, order_id, code, days from contract_b2b_flags "
                          "where (deal_id, run_id) in (select * from unnest(%s::bigint[], %s::text[]))",
                          ([d for d, _r in sorted(нужны)], [r for _d, r in sorted(нужны)]))
                for deal, run, заказ, код, дни in c.fetchall():
                    флаги[(int(deal), run)].append({"deal_id": int(deal), "order_id": заказ, "code": код, "days": дни})
        return выбор, {к: v for к, v in строки.items() if к in нужны}, dict(флаги)

    def _строки_пар(self, пары: list[tuple[int, str]], курсор=None) -> dict[tuple[int, str], list[dict]]:
        """Строки contract_terms пар «сделка, прогон» всеми колонками записи, в порядке свода."""
        out: dict[tuple[int, str], list[dict]] = defaultdict(list)
        if not пары:
            return out
        sql = (f"select {', '.join(self.КОЛОНКИ)} from contract_terms "
               "where (deal_id, run_id) in (select * from unnest(%s::bigint[], %s::text[])) "
               f"order by deal_id, run_id, {_rc().ПОРЯДОК_СТРОК_SQL}")
        параметры = ([d for d, _r in пары], [r for _d, r in пары])
        if курсор is None:
            with self.с, self.с.cursor() as c:
                c.execute(sql, параметры)
                записи = c.fetchall()
        else:
            курсор.execute(sql, параметры)
            записи = курсор.fetchall()
        for запись in записи:
            r = dict(zip(self.КОЛОНКИ, запись))
            r["usd"] = float(r["usd"] or 0)
            out[(int(r["deal_id"]), r["run_id"])].append(r)
        return out

    def записать_пересчёт(self, строки: list[dict], флаги: list[dict], исходы: dict[int, str], run_id: str,
                          сверить) -> tuple[bool, list[str]]:
        """Пересчёт — одной транзакцией: строки условий (копии с новым ключом), флаги и исходы,
        затем ВТОРАЯ проверка в той же транзакции — строки читаются из базы по ключу прогона
        и пересчитываются заново (сверить → список расхождений). Расхождение — откат
        целиком: в базе ни строки прогона. → (записано ли, расхождения)."""
        import psycopg2.extras
        Json = psycopg2.extras.Json
        try:
            with self.с, self.с.cursor() as c:
                psycopg2.extras.execute_values(
                    c, f"insert into contract_terms ({', '.join(self.КОЛОНКИ)}) values %s",
                    [tuple(Json(r[к]) if к in self.КОЛОНКИ_JSON and r[к] is not None else r[к]
                           for к in self.КОЛОНКИ) for r in строки])
                if флаги:
                    psycopg2.extras.execute_values(
                        c, "insert into contract_b2b_flags (run_id, method_ver, deal_id, order_id, code, days) "
                           "values %s",
                        [(run_id, ВЕРСИЯ_ИСХОДА, f["deal_id"], f["order_id"], f["code"], f["days"]) for f in флаги])
                psycopg2.extras.execute_values(
                    c, "insert into contract_deal_outcome (run_id, method_ver, deal_id, outcome) values %s",
                    [(run_id, ВЕРСИЯ_ИСХОДА, int(д), и) for д, и in sorted(исходы.items())])
                пары = sorted({(int(д), run_id) for д in исходы})
                из_базы = self._строки_пар(пары, курсор=c)
                c.execute("select deal_id, order_id, code from contract_b2b_flags where run_id = %s", (run_id,))
                флаги_базы = [{"deal_id": int(d), "order_id": з, "code": к} for d, з, к in c.fetchall()]
                c.execute("select deal_id, outcome from contract_deal_outcome where run_id = %s", (run_id,))
                исходы_базы = {int(d): и for d, и in c.fetchall()}
                расхождения = сверить(из_базы, флаги_базы, исходы_базы)
                if расхождения:
                    raise _Откат(расхождения)
        except _Откат as о:
            return False, о.расхождения
        return True, []

    def закрыть(self) -> None:
        self.с.close()


class _Откат(Exception):
    def __init__(self, расхождения: list[str]):
        super().__init__("пересчёт разошёлся со второй проверкой")
        self.расхождения = расхождения


