def строка(run_id: str, модель: str, д: Документ, fo: dict | None = None, *, status: str,
           sha256: str | None = None, итог: dict | None = None) -> dict:
    """Строка contract_terms. Условия и цитаты есть только у прочитанного файла."""
    итог = итог or {}
    прочитан = status in ПРОЧИТАН
    сторона_ = (итог.get("terms") or {}).get("side") if прочитан else None
    сторона_ = сторона_ if сторона_ in ("customer", "supplier") else None
    return {
        "run_id": run_id, "method_ver": METHOD_VER, "deal_id": д.deal_id, "card_entity": д.card_entity,
        "card_id": д.card_id, "order_id": д.order_id,
        # сторона — по модели (решение владельца 22.10.2026); связь и подпись — справочно
        "side": сторона_, "side_source": "model" if сторона_ else None, "side_link": д.side_link,
        "side_template": д.side_template, "side_company": д.side_company,
        "template": д.template, "doc_type": д.doc_type, "file_field": д.file_field,
        "file_id": str((fo or {}).get("id") or ""), "sha256": sha256, "pages": итог.get("pages"),
        "note": (str(итог.get("note") or "")[:400] or None), "status": status,
        "model": модель if (прочитан or итог.get("usd")) else None,
        "terms": итог.get("terms") if прочитан else None,
        "evidence": (итог.get("evidence") or {}) if прочитан else None,
        "dropped": list(итог.get("dropped") or []) if прочитан else None,
        "usd": float(итог.get("usd") or 0.0),
    }


#: Сверка стороны, которую назвала модель: имя → как взять из строки. Способ назвал
#: другую сторону — документ спорный.
СВЕРКА_СТОРОНЫ = (
    ("компания", lambda r: r.get("side_company")),
)
#: Справочно — считается в журнале, сторону не решает и спорным документ не делает:
#: связь с заказом (договоры с заказчиком привязывают к заказу, замер 22.10.2026) и
#: подпись «Чей шаблон» (шаблон заказчика бывает у договора с поставщиком, 19.10.2026).
СПРАВОЧНО_СТОРОНЫ = (
    ("связь", lambda r: r.get("side_link")),
    ("подпись", lambda r: r.get("side_template")),
)


def голоса_стороны(r: dict, способы=СВЕРКА_СТОРОНЫ) -> dict[str, str | None]:
    """{способ: сторона или None} — что сказал о стороне каждый способ."""
    out = {}
    for имя, взять in способы:
        с = взять(r)
        out[имя] = с if с in ("customer", "supplier") else None
    return out


def сторона_спорная(r: dict) -> bool:
    """Сверка назвала не ту сторону, что модель. Без стороны модели спора нет — есть
    документ без стороны (флаги_сделки)."""
    return r["side"] is not None and any(с is not None and с != r["side"] for с in голоса_стороны(r).values())


def свести(строки: list[dict]) -> dict:
    """Условия одной стороны из нескольких документов: по каждому полю — первое
    заполненное в порядке строк (разовый раньше рамочного, новый раньше старого),
    документы — объединением."""
    out: dict = {}
    for к in поля_условий():
        if к == "documents":
            виденные: list[str] = []
            for r in строки:
                for d in (r["terms"].get("documents") or []):
                    if d not in виденные:
                        виденные.append(d)
            out[к] = виденные
            continue
        out[к] = next((r["terms"][к] for r in строки if not _пусто(r["terms"].get(к))), None)
    return out


НЕ_ПРОЧИТАН = ("budget", "time", "download", "format", "limit", "model", "parse", "api")


def снятые_поля(строки: list[dict], свод: dict) -> set[str]:
    """Поля, которые в своде стороны пусты, а хоть в одном её документе сняты как
    значение без цитаты: о них известно не «нет», а «не доказано»."""
    снято = {к for r in строки for к in (r.get("dropped") or [])}
    return {к for к in снято if _пусто(свод.get(к))}


def флаги_сделки(строки: list[dict], снятые_флаги: Counter | None = None) -> tuple[list[dict], str]:
    """(флаги по заказам, исход): исход — «пара», «недочитана», «без стороны»,
    «спорная», «поставщик без заказа», «нет пары».

    Сделка, где хоть один файл договора не прочитан (бюджет, срок, закачка,
    предел, отказ), флагов не получает: без него свод условий другой, и флаг соврал
    бы — или промолчал там, где риск есть. По той же причине их не получает сделка
    с документом без стороны (модель её не назвала) и со спорным (компания карточки
    назвала другую сторону): ни с ним, ни без него свод условий верным не назовёшь.
    И сделка с договором поставщика без связи с заказом СП-172: к какому заказу и
    какому поставщику его условия, неизвестно, а общий свод таких документов разных
    поставщиков спрятал бы риск одного за условиями другого. Карточка без файла договора —
    не недочитанность: читать в ней нечего.

    Флаг, срабатывающий на отсутствии условия (ФЛАГИ_ПО_ОТСУТСТВИЮ), не ставится,
    если это условие снято как значение без цитаты; счёт таких — в снятые_флаги."""
    if any(r["status"] in НЕ_ПРОЧИТАН for r in строки):
        return [], "недочитана"
    прочитанные = [r for r in строки if r["status"] in ПРОЧИТАН and r["terms"]]
    if any(r["side"] is None for r in прочитанные):
        return [], "без стороны"
    if any(сторона_спорная(r) for r in прочитанные):
        return [], "спорная"
    if any(r["side"] == "supplier" and r["order_id"] is None for r in прочитанные):
        return [], "поставщик без заказа"
    заказчик = [r for r in прочитанные if r["side"] == "customer"]
    по_заказам: dict[int | None, list[dict]] = defaultdict(list)
    for r in прочитанные:
        if r["side"] == "supplier":
            по_заказам[r["order_id"]].append(r)
    if not заказчик or not по_заказам:
        return [], "нет пары"
    условия_заказчика = свести(заказчик)
    снято_заказчика = снятые_поля(заказчик, условия_заказчика)
    out = []
    for заказ, rs in sorted(по_заказам.items(), key=lambda x: x[0] or 0):
        условия_поставщика = свести(rs)
        снято = {"customer": снято_заказчика, "supplier": снятые_поля(rs, условия_поставщика)}
        for f in contract_b2b.flags(условия_заказчика, условия_поставщика):
            if any(поле in снято[сторона_] for сторона_, поле in ФЛАГИ_ПО_ОТСУТСТВИЮ.get(f["code"], ())):
                if снятые_флаги is not None:
                    снятые_флаги[f["code"]] += 1
                continue
            out.append({"deal_id": строки[0]["deal_id"], "order_id": заказ, "code": f["code"],
                        "days": f.get("days")})
    return out, "пара"


# --------------------------------------------------------------------------- база
class База:
    """Закрытая база Supabase. statement_timeout и lock_timeout — в строке
    подключения (правила 9 и 12): SET откатывается с транзакцией."""

    def __init__(self, dsn: str, схема: str | None = None):
        import psycopg2
        опции = "-c statement_timeout=120000 -c lock_timeout=10000"
        if схема:
            опции += f" -c search_path={схема}"
        self.с = psycopg2.connect(dsn, options=опции)

    def нет_таблиц(self) -> list[str]:
        """Таблицы и колонки, без которых запись не состоится, — до первого оплаченного
        вызова: таблица прежней версии без side_link упала бы на вставке уже после
        чтения."""
        with self.с, self.с.cursor() as c:
            c.execute("select to_regclass('contract_terms') is null, to_regclass('contract_b2b_flags') is null")
            нет_условий, нет_флагов = c.fetchone()
            нет = [имя for имя, н in (("contract_terms", нет_условий), ("contract_b2b_flags", нет_флагов)) if н]
            if not нет_условий:
                c.execute("select array_agg(attname::text) from pg_attribute "
                          "where attrelid = to_regclass('contract_terms') and attnum > 0 and not attisdropped")
                есть = set(c.fetchone()[0] or [])
                нет += [f"contract_terms.{к}" for к in self.КОЛОНКИ if к not in есть]
        return нет

    def из_кэша(self, sha256: str, модель: str) -> dict | None:
        """Условия того же файла, прочитанного раньше той же моделью и версией
        метода. Только status = 'ok': обрезанный файл так не пишется (он limit), и
        повтор по нему не найдёт неполных условий."""
        with self.с, self.с.cursor() as c:
            c.execute("select terms, evidence, pages, note, dropped from contract_terms "
                      "where sha256 = %s and model = %s and method_ver = %s and status = 'ok' "
                      "order by created_at desc limit 1", (sha256, модель, METHOD_VER))
            r = c.fetchone()
        if not r:
            return None
        return {"terms": r[0], "evidence": r[1] or {}, "pages": r[2], "note": r[3], "dropped": r[4] or []}

    КОЛОНКИ = ("run_id", "method_ver", "deal_id", "card_entity", "card_id", "order_id", "side", "side_source",
               "side_link", "side_template", "side_company", "template", "doc_type", "file_field", "file_id", "sha256",
               "pages", "note", "status", "model", "terms", "evidence", "dropped", "usd")
    КОЛОНКИ_JSON = ("terms", "evidence", "dropped")

    def записать_условия(self, строки: list[dict]) -> None:
        import psycopg2.extras
        if not строки:
            return
        Json = psycopg2.extras.Json
        with self.с, self.с.cursor() as c:
            psycopg2.extras.execute_values(
                c, f"insert into contract_terms ({', '.join(self.КОЛОНКИ)}) values %s on conflict do nothing",
                [tuple(Json(r[к]) if к in self.КОЛОНКИ_JSON and r[к] is not None else r[к]
                       for к in self.КОЛОНКИ) for r in строки])

    def записать_флаги(self, флаги: list[dict], run_id: str) -> None:
        import psycopg2.extras
        if not флаги:
            return
        with self.с, self.с.cursor() as c:
            psycopg2.extras.execute_values(
                c, "insert into contract_b2b_flags (run_id, method_ver, deal_id, order_id, code, days) "
                   "values %s on conflict do nothing",
                [(run_id, METHOD_VER, f["deal_id"], f["order_id"], f["code"], f["days"]) for f in флаги])

    def итог(self, run_id: str) -> tuple[int, int, float]:
        """Сколько записано — запросом по ключу прогона: rowcount у execute_values —
        счёт последней пачки (навык db-schema)."""
        with self.с, self.с.cursor() as c:
            c.execute("select count(*), coalesce(sum(usd), 0) from contract_terms where run_id = %s", (run_id,))
            строк, usd = c.fetchone()
            c.execute("select count(*) from contract_b2b_flags where run_id = %s", (run_id,))
            флагов = c.fetchone()[0]
        return int(строк), int(флагов), float(usd)

    def закрыть(self) -> None:
        self.с.close()


