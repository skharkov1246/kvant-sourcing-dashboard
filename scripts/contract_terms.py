#: Откуда сторона строки (side_source; схема contract_terms_side_chk):
#:   model — назвала модель, прочитав документ (решение владельца 22.10.2026);
#:   card  — модель не назвала, сторона — по компании карточки (решение владельца
#:           25.10.2026, «сторона по карточке»): компания сделки — заказчик, компания
#:           заказа СП-172 сделки — поставщик, Purchase order заказа — поставщик (по виду
#:           документа). Живой прогон ct-40206159351-1: модель не назвала сторону у 116 из
#:           1 243 прочитанных документов, и 124 сделки остались «без стороны». Спорный
#:           документ (модель и компания разошлись) — как прежде, вне флагов.
ПО_МОДЕЛИ, ПО_КАРТОЧКЕ = "model", "card"
ИСТОЧНИКИ_СТОРОНЫ = (ПО_МОДЕЛИ, ПО_КАРТОЧКЕ)


def сторона_строки(terms: dict | None, side_company: str | None) -> tuple[str | None, str | None]:
    """(сторона документа, откуда она): названная моделью — главная; модель не назвала —
    компания карточки (side_company: компания сделки, заказа сделки, вид Purchase order);
    компания о стороне не говорит — (None, None), документ без стороны."""
    м = (terms or {}).get("side")
    if м in ("customer", "supplier"):
        return м, ПО_МОДЕЛИ
    if side_company in ("customer", "supplier"):
        return side_company, ПО_КАРТОЧКЕ
    return None, None


def сторона_модели(r: dict) -> str | None:
    """Сторона, которую назвала модель: у строки «по карточке» — None. Гейт стороны
    меряет модель, а не карточку: иначе доля названных росла бы сама собой."""
    return None if r.get("side_source") == ПО_КАРТОЧКЕ else r.get("side")


def строка(run_id: str, модель: str, д: Документ, fo: dict | None = None, *, status: str,
           sha256: str | None = None, итог: dict | None = None) -> dict:
    """Строка contract_terms. Условия и цитаты есть только у прочитанного файла."""
    итог = итог or {}
    прочитан = status in ПРОЧИТАН
    сторона_, источник = сторона_строки(итог.get("terms"), д.side_company) if прочитан else (None, None)
    return {
        "run_id": run_id, "method_ver": METHOD_VER, "deal_id": д.deal_id, "card_entity": д.card_entity,
        "card_id": д.card_id, "order_id": д.order_id,
        # сторона — по модели (решение владельца 22.10.2026), модель не назвала — по
        # карточке (решение владельца 25.10.2026); связь и подпись — справочно
        "side": сторона_, "side_source": источник, "side_link": д.side_link,
        "side_template": д.side_template, "side_company": д.side_company, "link_source": д.link_source,
        "template": д.template, "doc_type": д.doc_type, "file_field": (fo or {}).get(ПОЛЕ_ФАЙЛА) or д.file_field,
        "file_id": str((fo or {}).get("id") or ""), "sha256": sha256, "pages": итог.get("pages"),
        "note": (str(итог.get("note") or "")[:400] or None), "status": status,
        "model": модель if (прочитан or итог.get("usd")) else None,
        "terms": итог.get("terms") if прочитан else None,
        "evidence": (итог.get("evidence") or {}) if прочитан else None,
        "dropped": list(итог.get("dropped") or []) if прочитан else None,
        "usd": float(итог.get("usd") or 0.0),
    }


#: Сверка стороны, которую назвала модель: имя → как взять из строки. Способ назвал
#: другую сторону — документ спорный.
СВЕРКА_СТОРОНЫ = (
    ("компания", lambda r: r.get("side_company")),
)
#: Справочно — считается в журнале, сторону не решает и спорным документ не делает:
#: связь с заказом (договоры с заказчиком привязывают к заказу, замер 22.10.2026) и
#: подпись «Чей шаблон» (шаблон заказчика бывает у договора с поставщиком, 19.10.2026).
СПРАВОЧНО_СТОРОНЫ = (
    ("связь", lambda r: r.get("side_link")),
    ("подпись", lambda r: r.get("side_template")),
)


def голоса_стороны(r: dict, способы=СВЕРКА_СТОРОНЫ) -> dict[str, str | None]:
    """{способ: сторона или None} — что сказал о стороне каждый способ."""
    out = {}
    for имя, взять in способы:
        с = взять(r)
        out[имя] = с if с in ("customer", "supplier") else None
    return out


def сторона_спорная(r: dict) -> bool:
    """Сверка назвала не ту сторону, что модель. Без стороны модели спора нет — есть
    документ без стороны или со стороной по карточке (флаги_сделки)."""
    м = сторона_модели(r)
    return м is not None and any(с is not None and с != м for с in голоса_стороны(r).values())


def свести(строки: list[dict]) -> dict:
    """Условия одной стороны из нескольких документов: по каждому полю — первое
    заполненное в порядке строк (ПОРЯДОК_ВИДОВ: спецификации, Purchase order, рамочные;
    новый раньше старого), документы — объединением."""
    out: dict = {}
    for к in поля_условий():
        if к == "documents":
            виденные: list[str] = []
            for r in строки:
                for d in (r["terms"].get("documents") or []):
                    if d not in виденные:
                        виденные.append(d)
            out[к] = виденные
            continue
        out[к] = next((r["terms"][к] for r in строки if not _пусто(r["terms"].get(к))), None)
    return out


#: Отказ, который следующий прогон не вылечит: файла у портала нет (download —
#: статус_закачки), формат не читается, файл больше предела чтения — нужен человек:
#: перезалить или разделить файл.
НЕ_ЧИТАЕТСЯ = ("download", "format", "limit")
#: Файл ещё не прочитан: бюджет и срок прогона, временный отказ закачки (fetch), модели,
#: разбора, API — дочитает следующий прогон (прочитанное — даром по sha256).
НЕ_ДОЧИТАН = ("budget", "time", "fetch", "model", "parse", "api")
НЕ_ПРОЧИТАН = НЕ_ДОЧИТАН + НЕ_ЧИТАЕТСЯ
#: Причина отказа закачки (indexer.скачать_адрес через Портал.скачать), которую следующий
#: прогон не вылечит: файла у портала нет (код 404, 410), тело меньше порога (пустой
#: файл), у поля нет ссылки. Прочее — сеть, 5xx и 429/503 дольше бюджета ожидания,
#: страница входа вместо файла (протух токен вебхука), 401/403 (права вебхука) —
#: временное или общее для всего прогона: не повод звать человека перезаливать файл.
ЗАКАЧКА_НАВСЕГДА = re.compile(r"код (?:404|410)\b|меньше порога|нет urlMachine|ссылок на файл нет")


def статус_закачки(почему: str | None) -> str:
    """Статус строки неудачной закачки по причине: download — файла не скачать и
    следующим прогоном (НЕ_ЧИТАЕТСЯ, «не читается»), fetch — временный отказ (НЕ_ДОЧИТАН,
    «недочитана»). Сомнение — в пользу fetch: «перезалить файл» по сбою сети — ложный
    пункт очереди ответственному."""
    return "download" if ЗАКАЧКА_НАВСЕГДА.search(str(почему or "")) else "fetch"


def уточнить_статус(status: str, note: str | None) -> str:
    """Статус строки базы по нынешним правилам. Строки до 25.10.2026 писали временный
    отказ закачки как download, а непредвиденный сбой подготовки файла — как format;
    нынешний прогон пишет их fetch и api, и для его строк уточнение ничего не меняет
    (заметка download — та же причина закачки). Через него пересчитывает исход выгрузка
    для вкладки (scripts/realization_ctx.py)."""
    if status == "download":
        return статус_закачки(note)
    if status == "format" and str(note or "").startswith("документ не подготовлен ("):
        return "api"
    return status
#: Исход разбора договоров сделки — флаги_сделки и «нет договоров» (у сделки нет ни
#: одного документа). Пишется в contract_deal_outcome вместе с флагами: по нему
#: вкладка «Реализация» отличает «договоров нет» от «сделку не читали».
ИСХОДЫ = ("пара", "недочитана", "не читается", "без стороны", "спорная", "поставщик без заказа", "нет пары",
          "нет договоров")
#: Поля поставщика, чьё отсутствие читают ФЛАГИ_ПО_ОТСУТСТВИЮ (пени, перечень документов).
#: У заказа, где у поставщика только Purchase order, отсутствие не доказано: в Purchase
#: order их обычно нет, а договор поставщика может лежать в карточке без связи со
