def прогон(режим: str, сделок: int, бюджет: float, модель: str, *, портал, run_id: str,
           читатель: Читатель | None = None, база=None, печать=print,
           срок_мин: float | None = None, часы=time.monotonic, открытые: bool = False) -> int:
    """Весь прогон. Портал, читатель, база и часы подставляются (тесты); печать —
    только агрегаты. срок_мин — сколько минут от начала прогона ещё начинать
    закачку и чтение файла; дальше файлы пишутся статусом time."""
    срок = часы() + срок_мин * 60 if срок_мин else None
    печать(f"договоры · режим {режим} · сделок до {сделок}{' (открытые)' if открытые else ''} · модель {модель} · "
           f"бюджет ${бюджет:.2f} · ключ прогона {run_id}" + (f" · срок {срок_мин:g} мин" if срок_мин else ""))
    отбор = отобрать(портал, сделок, открытые)
    for s in журнал_отбора(отбор):
        печать(s)
    if режим == "dry":
        файлов, по_видам = файлы_по_видам(отбор)
        модели = [модель] + ([МОДЕЛЬ_ДЛЯ_СРАВНЕНИЯ] if модель != МОДЕЛЬ_ДЛЯ_СРАВНЕНИЯ else [])
        for s in журнал_оценки(файлов, бюджет, модели, по_видам):
            печать(s)
        печать("холостой прогон: модель не вызывалась, файлы не качались, база не тронута")
        return 0

    читатель = читатель or Читатель(модель, бюджет)
    статусы: Counter = Counter()
    исходы: Counter = Counter()
    снятые_флаги: Counter = Counter()
    все_строки: list[dict] = []
    все_флаги: list[dict] = []
    исход_сделки: dict[int, str] = {}
    пары: list = []
    прочитано: dict[str, dict] = {}            # sha256 → итог чтения в этом прогоне
    # файл карточки → (статус, sha256, итог) первой встречи в прогоне: рамочный под
    # спецификациями нескольких сделок второй раз не качается и не читается
    встречено: dict[tuple, tuple[str, str | None, dict]] = {}
    по_сроку = False
    читанные: set[tuple[int, int, str]] | None = None   # файлы, прочитанные раньше, — после бюджета
    не_качались = 0
    for сделка in отбор.сделки:
        дд = отбор.документы[int(сделка["ID"])]
        строки_сделки: list[dict] = []
        for д in дд:
            if not д.files:
                строки_сделки.append(строка(run_id, модель, д, status="no_file"))
                continue
            for fo in д.files:
                ключ = ключ_файла(д, fo)
                if ключ in встречено:
                    # уже встречен в прогоне (до срока или после — повтор даром): итог тот же
                    статус, sha, было = встречено[ключ]
                    if статус in ПРОЧИТАН:
                        строки_сделки.append(строка(run_id, модель, д, fo, status="reused", sha256=sha, итог={
                            **было, "usd": 0.0, "note": "условия того же файла из этого прогона"}))
                    else:
                        строки_сделки.append(строка(run_id, модель, д, fo, status=статус, sha256=sha,
                                                    итог={"pages": было.get("pages"), "note": было.get("note")}))
                    continue
                if срок is not None and (по_сроку or часы() > срок):
                    # Срок прогона вышел: job не убьют таймаутом посреди записи, а
                    # флаги и итог по уже прочитанному дойдут до базы и журнала.
                    по_сроку = True
                    строки_сделки.append(строка(run_id, модель, д, fo, status="time",
                                                итог={"note": f"срок прогона {срок_мин:g} мин вышел раньше"}))
                    continue
                if читатель.стоп:
                    # Бюджет кончился: новый файл всё равно не прочесть — его закачка лишь
                    # запрос к порталу (CLAUDE.md, «Битрикс не перегружать»). Качается только
                    # файл, который та же модель и версия уже читали: номер файла поля
                    # (b_file) при новой загрузке новый, и его условия — даром по sha256.
                    if читанные is None:
                        читанные = база.прочитанные_файлы(модель) if база is not None else set()
                    if (д.card_entity, д.card_id, str(fo.get("id") or "")) not in читанные:
                        итог = {"note": "бюджет прогона исчерпан раньше; файл этой моделью не читан — не качался"}
                        встречено[ключ] = ("budget", None, итог)
                        строки_сделки.append(строка(run_id, модель, д, fo, status="budget", итог=итог))
                        не_качались += 1
                        continue
                b, почему = портал.скачать(fo)
                if not b:
                    # 404 / пустой файл — «не читается» (нужен человек); сеть, лимит портала,
                    # страница входа — «недочитана»: дочитает следующий прогон
                    статус = статус_закачки(почему)
                    встречено[ключ] = (статус, None, {"note": почему})
                    строки_сделки.append(строка(run_id, модель, д, fo, status=статус, итог={"note": почему}))
                    continue
                sha = hashlib.sha256(b).hexdigest()
                готово, откуда = прочитано.get(sha), "этого прогона"
                if готово is None and база is not None:
                    готово, откуда = база.из_кэша(sha, модель), "прошлого прогона"
                if готово is not None:
                    встречено[ключ] = ("reused", sha, готово)
                    строки_сделки.append(строка(run_id, модель, д, fo, status="reused", sha256=sha, итог={
                        **готово, "usd": 0.0, "note": f"условия того же файла (sha256) из {откуда}"}))
                    continue
                # бюджет кончился — новый файл не читается, но прочитанный раньше (тот же
                # sha256) выше взят даром: недельный прогон не теряет готовые сделки
                if читатель.стоп:
                    итог = {"note": "бюджет прогона исчерпан раньше"}
                    встречено[ключ] = ("budget", sha, итог)
                    строки_сделки.append(строка(run_id, модель, д, fo, status="budget", sha256=sha, итог=итог))
                    continue
                итог = читатель.прочитать(b, None, успеть=lambda: срок is None or часы() <= срок)
                if итог["status"] == "ok":
                    прочитано[sha] = итог
                встречено[ключ] = (итог["status"], sha, итог)
                строки_сделки.append(строка(run_id, модель, д, fo, status=итог["status"], sha256=sha, итог=итог))
        for r in строки_сделки:
            статусы[r["status"]] += 1
        флаги, исход = (флаги_сделки(строки_сделки, снятые_флаги, пары) if строки_сделки
                        else ([], "нет договоров"))
        исходы[исход] += 1
        исход_сделки[int(сделка["ID"])] = исход
        все_флаги += флаги
        все_строки += строки_сделки
        if база is not None:
            база.записать_условия(строки_сделки)

    печать("файлов: " + " · ".join(f"{к} {статусы[к]}" for к in СТАТУСЫ_ЖУРНАЛА if статусы[к]))
    печать(f"модель: вызовов {читатель.вызовов} · страниц {читатель.страниц} · токенов вход {читатель.вход} / "
           f"выход {читатель.выход} · ${читатель.потрачено:.2f} из ${читатель.бюджет:.2f} "
           f"(оценка до вызова ${читатель.оценка:.2f})" + (" · остановлено бюджетом" if читатель.стоп else "")
           + (" · остановлено сроком" if по_сроку else ""))
    if не_качались:
        печать(f"после бюджета не качались (той же моделью и версией не читаны): {не_качались} файлов")
    if читатель.оборвано:
        печать(f"оборванных попыток {читатель.оборвано}: в бюджет списано по оценке ${читатель.списано_оценкой:.2f} "
               "(в строках usd — только оплата по usage)")
    if читатель.секунды:
        с = sorted(читатель.секунды)
        печать(f"время вызова модели: медиана {с[len(с) // 2]:.0f} с · макс {с[-1]:.0f} с · вызовов {len(с)}")
    причины = причины_отказов(все_строки)
    if причины:
        печать("причины отказов: " + " · ".join(f"{к} {н}" for к, н in причины.most_common()))
    if читатель.по_частям:
        печать(f"прочитано по частям (PDF больше LLM_READ_MAX_MB или LLM_READ_MAX_PAGES): файлов "
               f"{читатель.по_частям}, частей {читатель.частей}")
    печать(f"не читались — больше предела чтения: {читатель.обрезано} · значений без цитаты снято: "
           f"{читатель.снято_без_цитаты} · флагов по снятому значению не поставлено: {sum(снятые_флаги.values())}")
    гейт, журнал_гейта = гейт_стороны(все_строки)
    for s in журнал_гейта + журнал_пар(пары):
        печать(s)
    печать("сделки: " + " · ".join(f"{к} {н}" for к, н in sorted(исходы.items())))
    по_коду = Counter(f["code"] for f in все_флаги)
    печать("флаги: " + (" · ".join(f"{к} {н}" for к, н in sorted(по_коду.items())) or "нет") +
           f" · сделок с флагами {len({f['deal_id'] for f in все_флаги})}")
    if база is not None:
        if гейт:
            # исходы — только вместе с флагами: прогон, не прошедший гейт стороны,
            # вкладке не источник (scripts/realization_ctx.py берёт последний исход)
            база.записать_итог(все_флаги, исход_сделки, run_id)
        строк, флагов, usd = база.итог(run_id)
        печать(f"в базе по ключу прогона: строк условий {строк}, флагов {флагов}, "
               f"исходов сделок {база.итог_сделок(run_id)}, ${usd:.2f}")
    return 0 if гейт else 1


# --------------------------------------------------------------------------- пересчёт без модели
ПРЕФИКС_ПЕРЕСЧЁТА = "пересчёт без модели из "


def копия_строки(r: dict, run_id: str) -> dict:
    """Строка прежнего прогона → строка пересчёта: новый ключ прогона, статус по нынешним
    правилам (уточнить_статус; прочитанный — reused: модель в этом прогоне не читала), сторона
    по нынешнему правилу (модель, затем карточка), usd 0 — за пересчёт не платили. Откуда
    строка — в заметке (правило 16); условия, цитаты, страницы и версия чтения — как были."""
    статус = уточнить_статус(r["status"], r.get("note"))
    прочитан = статус in ПРОЧИТАН and r.get("terms") is not None
    if статус == "ok":
        статус = "reused"
    сторона_, источник = сторона_строки(r.get("terms"), r.get("side_company")) if прочитан else (None, None)
    заметка = str(r.get("note") or "")
    if заметка.startswith(ПРЕФИКС_ПЕРЕСЧЁТА):
        заметка = заметка.split("; ", 1)[1] if "; " in заметка else ""
    return {**r, "run_id": run_id, "status": статус, "side": сторона_, "side_source": источник, "usd": 0.0,
            "note": (f"{ПРЕФИКС_ПЕРЕСЧЁТА}{r['run_id']}" + (f"; {заметка}" if заметка else ""))[:400]}


def _набор_флагов(флаги: list[dict]) -> set[tuple]:
    return {(f.get("order_id"), f["code"]) for f in флаги}


def сверить_пересчёт(ожидается: dict[int, tuple[str, list[dict]]]):
    """Вторая проверка пересчёта (CLAUDE.md, «Качество прежде скорости»): строки, прочитанные
    из базы по ключу прогона, пересчитываются заново и сверяются с записанным исходом и
    флагами — другой путь (база, порядок строк SQL, JSON), тот же итог. → функция для
    База.записать_пересчёт: (строки базы, флаги базы, исходы базы) → расхождения (счёт)."""
    def сверить(строки: dict, флаги_базы: list[dict], исходы_базы: dict[int, str]) -> list[str]:
        по_сделке: dict[int, list[dict]] = defaultdict(list)
        for f in флаги_базы:
            по_сделке[f["deal_id"]].append(f)
        счёт: Counter = Counter()
        for д, (исход, флаги) in ожидается.items():
            rs = next((v for (dd, _r), v in строки.items() if dd == д), [])
            ф2, и2 = флаги_сделки(rs) if rs else ([], "нет договоров")
            if и2 != исход or исходы_базы.get(д) != исход:
                счёт["исход"] += 1
            if _набор_флагов(ф2) != _набор_флагов(флаги) or _набор_флагов(по_сделке.get(д, [])) != _набор_флагов(флаги):
                счёт["флаги"] += 1
        if len(исходы_базы) != len(ожидается):
            счёт["сделок"] += 1
        return [f"{к} {н}" for к, н in sorted(счёт.items())]
    return сверить


def пересчёт(база, run_id: str, *, применить: bool, печать=print) -> int:
    """Исходы и флаги сделок заново — по уже извлечённым условиям, без модели и портала.

    Берётся разбор каждой сделки, который показывает вкладка (База.разборы), строки
    копируются с новым ключом прогона и нынешним правилом стороны (копия_строки) и
    пересчитываются нынешними правилами сверки (флаги_сделки). Пишутся только сделки, у
    которых исход или флаги изменились; прежние строки не удаляются и не правятся — новый
    исход старше по времени и сам становится разбором вкладки (откат — delete по ключу
    прогона). Холостой по умолчанию (применить=False): только счёт.

    Проверки до записи: (1) гейт стороны по всем строкам — как у чтения; (2) строки со
    стороной, с которой их записали, повторяют записанный исход — иначе сделка не пишется,
    как и сделка, чей исход сменился без стороны по карточке (причина не в правиле); (3)
    после записи, в той же транзакции, — пересчёт из базы (сверить_пересчёт). (1) или (3) не
    пройдены — ничего не записано, код 1. В журнал — только счёт."""
    rc = _rc()
    печать(f"договоры · пересчёт исходов и флагов без модели · ключ прогона {run_id} · "
           + ("запись" if применить else "холостой: база не меняется"))
    выбор, строки_пар, флаги_пар = база.разборы()
    печать(f"сделок с записанным разбором: {len(выбор)} (разбор — тот, что показывает вкладка: последний, "
           "«недочитана» — прежним полным с теми же файлами)")
    все_копии: list[dict] = []
    к_записи: dict[int, tuple[str, list[dict]]] = {}
    копии_записи: list[dict] = []
    переходы: Counter = Counter()
    без_причины = 0
    по_коду: Counter = Counter()
    стало_меньше = 0
    снятые_флаги: Counter = Counter()
    пары: list = []
    исходы_после: Counter = Counter()
    for v in выбор:
        ключ = (v["deal"], v["run"])
        прежние = строки_пар.get(ключ, [])
        копии = [копия_строки(r, run_id) for r in прежние]
        все_копии += копии
        # сторона, с которой строки записаны (до 25.10.2026 — только модель), на тех же
        # строках со статусом по нынешним правилам: так получен записанный исход
        как_было = [{**к, "side": r["side"], "side_source": r.get("side_source")} for к, r in zip(копии, прежние)]
        флаги, исход = флаги_сделки(копии, снятые_флаги, пары) if копии else ([], "нет договоров")
        _ф0, исход0 = флаги_сделки(как_было) if как_было else ([], "нет договоров")
        записан = v.get("outcome") or исход0
        исходы_после[исход] += 1
        по_карточке = any(к.get("side_source") == ПО_КАРТОЧКЕ for к in копии)
        прежние_флаги = флаги_пар.get(ключ, [])
        if исход0 != записан and (записан, исход0) not in rc.СХОДЯТСЯ:
            без_причины += 1                  # прежнее правило не повторяет записанного — не пишем
            continue
        было, стало = _набор_флагов(прежние_флаги), _набор_флагов(флаги)
        if исход == записан and было == стало:
            continue
        if исход != записан and not по_карточке and (записан, исход) not in rc.СХОДЯТСЯ:
            без_причины += 1
            continue
        переходы[f"{записан} → {исход}"] += 1
        for _з, код in стало - было:
            по_коду[f"+{код}"] += 1
        for _з, код in было - стало:
            по_коду[f"−{код}"] += 1
        if было - стало:
            стало_меньше += 1
        к_записи[v["deal"]] = (исход, флаги)
        копии_записи += копии
    гейт, журнал_гейта = гейт_стороны(все_копии)
    for x in журнал_гейта + журнал_пар(пары):
        печать(x)
    печать("сделки по пересчёту: " + " · ".join(f"{к} {н}" for к, н in sorted(исходы_после.items())))
    печать(f"сделок, у которых пересчёт меняет исход или флаги: {len(к_записи)}"
           + (" — " + " · ".join(f"{к} {н}" for к, н in sorted(переходы.items())) if переходы else ""))
    печать("флаги пересчёта против записанных: " + (" · ".join(f"{к} {н}" for к, н in sorted(по_коду.items()))
                                                   or "без изменений")
           + f" · сделок, где какой-то флаг пропал: {стало_меньше}")
    if без_причины:
        печать(f"::warning::сделок, где пересчёт прежним правилом стороны не повторил записанный исход: "
               f"{без_причины} — не пишутся, нужен разбор")
    if not гейт:
        печать("::error::гейт стороны не пройден — пересчёт не записан")
        return 1
    if not применить:
        печать("холостой пересчёт: база не тронута; запись — с --apply (вход apply прогона)")
        return 0
    if not к_записи:
        печать("писать нечего: исходы и флаги не меняются")
        return 0
    флаги_записи = [f for _и, фф in к_записи.values() for f in фф]
    записано, расхождения = база.записать_пересчёт(копии_записи, флаги_записи,
                                                   {д: и for д, (и, _ф) in к_записи.items()}, run_id,
                                                   сверить_пересчёт(к_записи))
    if not записано:
        печать("::error::вторая проверка (пересчёт из базы) разошлась: " + ", ".join(расхождения)
               + " — запись откатана целиком")
        return 1
    строк, флагов, _usd = база.итог(run_id)
    печать(f"в базе по ключу прогона: строк условий {строк}, флагов {флагов}, исходов сделок "
           f"{база.итог_сделок(run_id)} · вторая проверка (пересчёт из базы) сошлась")
    return 0


def _ключ_прогона() -> str:
    return (os.environ.get("RUN_ID") or "").strip() or "ct-" + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Пилот чтения договоров (только агрегаты в журнал)")
    ap.add_argument("--mode", choices=("dry", "live", "reflag"),
                    default=os.environ.get("CONTRACT_TERMS_MODE") or "dry",
                    help="reflag — исходы и флаги заново по извлечённым условиям, без модели и портала")
    ap.add_argument("--apply", action="store_true", default=os.environ.get("APPLY") == "1",
                    help="reflag: записать пересчёт (без него — холостой счёт)")
    ap.add_argument("--deals", type=int, default=СДЕЛОК_ПО_УМОЛЧАНИЮ)
    ap.add_argument("--open", action="store_true",
                    help="только открытые сделки реализации (недельный прогон по расписанию)")
    ap.add_argument("--budget", type=float, default=БЮДЖЕТ_ПО_УМОЛЧАНИЮ)
    ap.add_argument("--model", default=(os.environ.get("CONTRACT_TERMS_MODEL") or МОДЕЛЬ_ПО_УМОЛЧАНИЮ).strip())
    ap.add_argument("--deadline-min", type=float, default=СРОК_МИН_ПО_УМОЛЧАНИЮ,
                    help="сколько минут от начала ещё начинать чтение файла (0 — без срока, только вне Actions)")
    a = ap.parse_args(argv)
    if not 1 <= a.deals <= СДЕЛОК_МАКС:
        print(f"::error::--deals вне 1…{СДЕЛОК_МАКС}")
        return 2
    if not 0 < a.budget <= 100:
        print("::error::--budget вне (0; 100] USD")
        return 2
    if not 0 <= a.deadline_min <= СРОК_МИН_МАКС:
        print(f"::error::--deadline-min вне [0; {СРОК_МИН_МАКС}]: job ограничен 180 минутами")
        return 2
    if a.deadline_min == 0 and os.environ.get("GITHUB_ACTIONS"):
        # без срока прогон 400 сделок убил бы таймаут job до записи флагов и итога
        print(f"::error::--deadline-min 0 (без срока) в Actions не берётся: нужно 1…{СРОК_МИН_МАКС}")
        return 2
    if a.mode == "reflag":
        dsn = os.environ.get("SUPABASE_DB_URL", "").strip()
        if not dsn:
            print("::error::режим reflag без SUPABASE_DB_URL")
            return 2
        база = База(dsn)
        try:
            нет = база.нет_таблиц()
            if нет:
                print(f"::error::в базе нет таблиц или колонок {', '.join(нет)}: примените library/supabase/"
                      "contract_terms_schema.sql")
                return 2
            return пересчёт(база, _ключ_прогона(), применить=a.apply)
        finally:
            база.закрыть()
    if not os.environ.get("BITRIX_WEBHOOK_URL", "").strip():
        print("::error::нет BITRIX_WEBHOOK_URL")
        return 2
    база = None
    if a.mode == "live":
        # Всё, без чего запись не состоится, проверяется ДО закачки и до первого
        # оплаченного вызова.
        if not os.environ.get("ANTHROPIC_API_KEY", "").strip():
            print("::error::режим live без ANTHROPIC_API_KEY")
            return 2
        dsn = os.environ.get("SUPABASE_DB_URL", "").strip()
        if not dsn:
            print("::error::режим live без SUPABASE_DB_URL")
            return 2
        # Повтор вызова модели — следующим прогоном (даром для прочитанного, по
        # sha256), а не внутри: попытка, оборванная посреди потока, могла быть
        # оплачена, и бюджет проверяется только перед первой попыткой файла.
        os.environ.setdefault("LLM_READ_RETRIES", "1")
        база = База(dsn)
        нет = база.нет_таблиц()
        if нет:
            print(f"::error::в базе нет таблиц или колонок {', '.join(нет)}: примените library/supabase/"
                  "contract_terms_schema.sql (шаг «Схема в рабочей базе» прогона live или zip-db.yml)")
            база.закрыть()
            return 2
    try:
        return прогон(a.mode, a.deals, a.budget, a.model, портал=Портал(), run_id=_ключ_прогона(), база=база,
                      срок_мин=a.deadline_min or None, открытые=a.open)
    finally:
        if база is not None:
            база.закрыть()


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except SystemExit:
        raise
    except Exception as e:  # noqa: BLE001
        # Текст исключения в журнал не идёт: у ошибки базы в нём бывают значения
        # строки, у ошибки портала — номера. Класс и место — достаточно для разбора.
        места = []
        tb = e.__traceback__
        while tb:
            места.append(f"{Path(tb.tb_frame.f_code.co_filename).name}:{tb.tb_lineno}")
            tb = tb.tb_next
        код = getattr(e, "pgcode", None)
        print(f"::error::прогон упал: {type(e).__name__}" + (f" (pgcode {код})" if код else "")
              + " · " + " → ".join(места[-4:]))
        raise SystemExit(1)
