def журнал_пар(пары: list) -> list[str]:
    """Чем заполнены поля флагов срока, приёмки и валюты в парах — только счёт."""
    if not пары:
        return []
    n = len(пары)
    части = []
    for к in ПОЛЯ_РАЗБОРА:
        счёт = []
        for сторона_, i in (("заказчик", 0), ("поставщик", 1)):
            есть = sum(1 for x in пары if not _пусто(x[i].get(к)))
            снято = sum(1 for x in пары if к in x[2]["customer" if i == 0 else "supplier"])
            счёт.append(f"{сторона_} {есть}" + (f" (снято {снято})" if снято else ""))
        части.append(f"{к}: " + ", ".join(счёт))
    срок = Counter(contract_b2b.запас_по_сроку(з, п, contract_b2b.ЛОГИСТИКА_ДНИ)[1] for з, п, _с in пары)
    поздняя = sum(1 for з, _п, _с in пары
                  if any(м in contract_b2b._слитно(з.get("acceptance")) for м in contract_b2b.ПОЗДНЯЯ_ПРИЁМКА))
    валюта = Counter(("RUB" if str(x[i].get("currency") or "").upper() in contract_b2b.РУБЛИ
                      else ("нет" if _пусто(x[i].get("currency")) else "валюта")) + f":{i}"
                     for x in пары for i in (0, 1))
    return [f"поля флагов срока, приёмки и валюты в парах ({n}, есть значение; снято — без цитаты или не "
            "разобрано): " + " · ".join(части),
            f"срок в парах сравним: в днях у обеих {срок['дни']} · датой у обеих {срок['даты']} · дни против даты "
            f"(без даты отсчёта не сравнить) {срок['дни против даты']} · у одной стороны срока нет {срок['нет срока']}",
            f"приёмка у заказчика поздняя (монтаж, пусконаладка, ввод): {поздняя} · валюта заказчика: рубли "
            f"{валюта['RUB:0']}, валюта {валюта['валюта:0']}, нет {валюта['нет:0']} · поставщика: рубли "
            f"{валюта['RUB:1']}, валюта {валюта['валюта:1']}, нет {валюта['нет:1']}"]


