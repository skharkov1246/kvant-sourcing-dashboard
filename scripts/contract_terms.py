def гейт_стороны(строки: list[dict]) -> tuple[bool, list[str]]:
    """(можно ли писать флаги, строки журнала) по прочитанным документам прогона.

    Два условия (пороги — ДОЛЯ_НАЗВАННЫХ_МИН, ДОЛЯ_СПОРНЫХ_МАКС): модель назвала
    сторону у достаточной доли документов — иначе сторона не определена и «не
    разошлась» ничего не значит; и документов, где компания карточки назвала другую
    сторону, немного. Связь и подпись — справочно. Пустой прогон (ничего не
    прочитано) флагов не имеет — гейт ему не нужен."""
    прочитанные = [r for r in строки if r["status"] in ПРОЧИТАН and r["terms"]]
    всего = len(прочитанные)
    названо = [r for r in прочитанные if r["side"] is not None]
    журнал = [f"сторона по модели названа: {_доля(len(названо), всего)} прочитанных документов — "
              f"без стороны {всего - len(названо)}, их сделки флагов не получают"]
    for способы, пометка in ((СВЕРКА_СТОРОНЫ, ""), (СПРАВОЧНО_СТОРОНЫ, " (справочно, сторону не решает)")):
        for имя, _взять in способы:
            с = Counter()
            for r in названо:
                голос = голоса_стороны(r, способы)[имя]
                с["молчит" if голос is None else ("совпала" if голос == r["side"] else "разошлась")] += 1
            журнал.append(f"сторона по модели ↔ {имя}{пометка}: совпала {с['совпала']} · разошлась "
                          f"{с['разошлась']} · не сказано {с['молчит']}")
    сказано = [r for r in названо if any(голоса_стороны(r).values())]
    спорных = sum(1 for r in сказано if сторона_спорная(r))
    доля_названных = len(названо) / всего if всего else 1.0
    доля_спорных = спорных / len(сказано) if сказано else 0.0
    журнал.append(f"спорных документов (компания карточки назвала другую сторону) — из тех, где сказали и модель, "
                  f"и компания: {_доля(спорных, len(сказано))} — во флаги не идут, их сделки флагов не получают")
    гейт = True
    if доля_названных < ДОЛЯ_НАЗВАННЫХ_МИН:
        гейт = False
        журнал.append(f"::error::модель назвала сторону у {_доля(len(названо), всего)} прочитанных документов "
                      f"(нужно не меньше {ДОЛЯ_НАЗВАННЫХ_МИН:.0%}): сторона не определена — "
                      f"флаги прогона не записаны; проверить, как мы названы в договорах (НАШИ_КОМПАНИИ)")
    if доля_спорных > ДОЛЯ_СПОРНЫХ_МАКС:
        гейт = False
        журнал.append(f"::error::компания карточки разошлась с моделью у {доля_спорных:.0%} документов "
                      f"(порог {ДОЛЯ_СПОРНЫХ_МАКС:.0%}): флаги прогона не записаны, правило стороны — на разбор")
    return гейт, журнал


СТАТУСЫ_ЖУРНАЛА = ("ok", "reused", "no_file", "download", "format", "limit", "budget", "time",
                   "model", "parse", "api")


def прогон(режим: str, сделок: int, бюджет: float, модель: str, *, портал, run_id: str,
           читатель: Читатель | None = None, база=None, печать=print,
           срок_мин: float | None = None, часы=time.monotonic) -> int:
    """Весь прогон. Портал, читатель, база и часы подставляются (тесты); печать —
    только агрегаты. срок_мин — сколько минут от начала прогона ещё начинать
    закачку и чтение файла; дальше файлы пишутся статусом time."""
    срок = часы() + срок_мин * 60 if срок_мин else None
    печать(f"договоры · режим {режим} · сделок до {сделок} · модель {модель} · бюджет ${бюджет:.2f} · "
           f"ключ прогона {run_id}" + (f" · срок {срок_мин:g} мин" if срок_мин else ""))
    отбор = отобрать(портал, сделок)
    for s in журнал_отбора(отбор):
        печать(s)
    файлов = sum(len(д.files) for д in отбор.все())
    if режим == "dry":
        модели = [модель] + ([МОДЕЛЬ_ДЛЯ_СРАВНЕНИЯ] if модель != МОДЕЛЬ_ДЛЯ_СРАВНЕНИЯ else [])
        for s in журнал_оценки(файлов, бюджет, модели):
            печать(s)
        печать("холостой прогон: модель не вызывалась, файлы не качались, база не тронута")
        return 0

    читатель = читатель or Читатель(модель, бюджет)
    статусы: Counter = Counter()
    исходы: Counter = Counter()
    снятые_флаги: Counter = Counter()
    все_строки: list[dict] = []
    все_флаги: list[dict] = []
    прочитано: dict[str, dict] = {}            # sha256 → итог чтения в этом прогоне
    по_сроку = False
    for сделка in отбор.сделки:
        дд = отбор.документы[int(сделка["ID"])]
        строки_сделки: list[dict] = []
        for д in дд:
            if not д.files:
                строки_сделки.append(строка(run_id, модель, д, status="no_file"))
                continue
            for fo in д.files:
                if читатель.стоп:
                    строки_сделки.append(строка(run_id, модель, д, fo, status="budget",
                                                итог={"note": "бюджет прогона исчерпан раньше"}))
                    continue
                if срок is not None and (по_сроку or часы() > срок):
                    # Срок прогона вышел: job не убьют таймаутом посреди записи, а
                    # флаги и итог по уже прочитанному дойдут до базы и журнала.
                    по_сроку = True
                    строки_сделки.append(строка(run_id, модель, д, fo, status="time",
                                                итог={"note": f"срок прогона {срок_мин:g} мин вышел раньше"}))
                    continue
                b, почему = портал.скачать(fo)
                if not b:
                    строки_сделки.append(строка(run_id, модель, д, fo, status="download", итог={"note": почему}))
                    continue
                sha = hashlib.sha256(b).hexdigest()
                готово, откуда = прочитано.get(sha), "этого прогона"
                if готово is None and база is not None:
                    готово, откуда = база.из_кэша(sha, модель), "прошлого прогона"
                if готово is not None:
                    строки_сделки.append(строка(run_id, модель, д, fo, status="reused", sha256=sha, итог={
                        **готово, "usd": 0.0, "note": f"условия того же файла (sha256) из {откуда}"}))
                    continue
                итог = читатель.прочитать(b, None)
                if итог["status"] == "ok":
                    прочитано[sha] = итог
                строки_сделки.append(строка(run_id, модель, д, fo, status=итог["status"], sha256=sha, итог=итог))
        for r in строки_сделки:
            статусы[r["status"]] += 1
        флаги, исход = флаги_сделки(строки_сделки, снятые_флаги) if строки_сделки else ([], "нет договоров")
        исходы[исход] += 1
        все_флаги += флаги
        все_строки += строки_сделки
        if база is not None:
            база.записать_условия(строки_сделки)

    печать("файлов: " + " · ".join(f"{к} {статусы[к]}" for к in СТАТУСЫ_ЖУРНАЛА if статусы[к]))
    печать(f"модель: вызовов {читатель.вызовов} · страниц {читатель.страниц} · токенов вход {читатель.вход} / "
           f"выход {читатель.выход} · ${читатель.потрачено:.2f} из ${читатель.бюджет:.2f} "
           f"(оценка до вызова ${читатель.оценка:.2f})" + (" · остановлено бюджетом" if читатель.стоп else "")
           + (" · остановлено сроком" if по_сроку else ""))
    if читатель.оборвано:
        печать(f"оборванных попыток {читатель.оборвано}: в бюджет списано по оценке ${читатель.списано_оценкой:.2f} "
               "(в строках usd — только оплата по usage)")
    печать(f"не читались — больше предела чтения: {читатель.обрезано} · значений без цитаты снято: "
           f"{читатель.снято_без_цитаты} · флагов по снятому значению не поставлено: {sum(снятые_флаги.values())}")
    гейт, журнал_гейта = гейт_стороны(все_строки)
    for s in журнал_гейта:
        печать(s)
    печать("сделки: " + " · ".join(f"{к} {н}" for к, н in sorted(исходы.items())))
    по_коду = Counter(f["code"] for f in все_флаги)
    печать("флаги: " + (" · ".join(f"{к} {н}" for к, н in sorted(по_коду.items())) or "нет") +
           f" · сделок с флагами {len({f['deal_id'] for f in все_флаги})}")
    if база is not None:
        if гейт:
            база.записать_флаги(все_флаги, run_id)
        строк, флагов, usd = база.итог(run_id)
        печать(f"в базе по ключу прогона: строк условий {строк}, флагов {флагов}, ${usd:.2f}")
    return 0 if гейт else 1


def _ключ_прогона() -> str:
    return (os.environ.get("RUN_ID") or "").strip() or "ct-" + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Пилот чтения договоров (только агрегаты в журнал)")
    ap.add_argument("--mode", choices=("dry", "live"), default=os.environ.get("CONTRACT_TERMS_MODE") or "dry")
    ap.add_argument("--deals", type=int, default=СДЕЛОК_ПО_УМОЛЧАНИЮ)
    ap.add_argument("--budget", type=float, default=БЮДЖЕТ_ПО_УМОЛЧАНИЮ)
    ap.add_argument("--model", default=(os.environ.get("CONTRACT_TERMS_MODEL") or МОДЕЛЬ_ПО_УМОЛЧАНИЮ).strip())
    ap.add_argument("--deadline-min", type=float, default=СРОК_МИН_ПО_УМОЛЧАНИЮ,
                    help="сколько минут от начала ещё начинать чтение файла (0 — без срока)")
    a = ap.parse_args(argv)
    if not 1 <= a.deals <= СДЕЛОК_МАКС:
        print(f"::error::--deals вне 1…{СДЕЛОК_МАКС}")
        return 2
    if not 0 < a.budget <= 100:
        print("::error::--budget вне (0; 100] USD")
        return 2
    if not 0 <= a.deadline_min <= 300:
        print("::error::--deadline-min вне [0; 300]")
        return 2
    if not os.environ.get("BITRIX_WEBHOOK_URL", "").strip():
        print("::error::нет BITRIX_WEBHOOK_URL")
        return 2
    база = None
    if a.mode == "live":
        # Всё, без чего запись не состоится, проверяется ДО закачки и до первого
        # оплаченного вызова.
        if not os.environ.get("ANTHROPIC_API_KEY", "").strip():
            print("::error::режим live без ANTHROPIC_API_KEY")
            return 2
        dsn = os.environ.get("SUPABASE_DB_URL", "").strip()
        if not dsn:
            print("::error::режим live без SUPABASE_DB_URL")
            return 2
        # Повтор вызова модели — следующим прогоном (даром для прочитанного, по
        # sha256), а не внутри: попытка, оборванная посреди потока, могла быть
        # оплачена, и бюджет проверяется только перед первой попыткой файла.
        os.environ.setdefault("LLM_READ_RETRIES", "1")
        база = База(dsn)
        нет = база.нет_таблиц()
        if нет:
            print(f"::error::в базе нет таблиц или колонок {', '.join(нет)}: примените library/supabase/"
                  "contract_terms_schema.sql прогоном «ZIP base — apply DB migrations» (zip-db.yml)")
            база.закрыть()
            return 2
    try:
        return прогон(a.mode, a.deals, a.budget, a.model, портал=Портал(), run_id=_ключ_прогона(), база=база,
                      срок_мин=a.deadline_min or None)
    finally:
        if база is not None:
            база.закрыть()


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except SystemExit:
        raise
    except Exception as e:  # noqa: BLE001
        # Текст исключения в журнал не идёт: у ошибки базы в нём бывают значения
        # строки, у ошибки портала — номера. Класс и место — достаточно для разбора.
        места = []
        tb = e.__traceback__
        while tb:
            места.append(f"{Path(tb.tb_frame.f_code.co_filename).name}:{tb.tb_lineno}")
            tb = tb.tb_next
        код = getattr(e, "pgcode", None)
        print(f"::error::прогон упал: {type(e).__name__}" + (f" (pgcode {код})" if код else "")
              + " · " + " → ".join(места[-4:]))
        raise SystemExit(1)
