def _пусто(v) -> bool:
    return v is None or v == "" or v == []


_НЕ_РАЗОБРАНО = object()


def _значение(тип: str, сырое):
    """Строку записи — к типу поля. Пусто — None; не читается — _НЕ_РАЗОБРАНО."""
    s = " ".join(str(сырое if сырое is not None else "").split())
    if not s:
        return None
    if тип == "boolean":
        return {"true": True, "false": False, "да": True, "нет": False}.get(s.lower(), _НЕ_РАЗОБРАНО)
    if s.lower() in ("null", "none", "нет", "-", "—"):
        return None                                   # «нет условия» словами — записи нет
    if тип in ("integer", "number"):
        try:
            f = float(s.replace(" ", "").replace(",", ".").rstrip("%"))
        except ValueError:
            return _НЕ_РАЗОБРАНО
        if тип == "number":
            return f
        return int(f) if f == int(f) else _НЕ_РАЗОБРАНО
    return s


def разобрать_ответ(сырой: str) -> tuple[dict, dict, list[str]]:
    """JSON модели {side, items: [{field, value, quote, page}]} → (условия, evidence
    {поле: {quote, page}}, поля, снятые как недоказанные).

    Значение без цитаты или нечитаемое по типу поля снимается (правило 16: храни,
    почему получилось значение) — кроме side: сторона — вывод из всего документа, а не
    из строки. Имена снятых полей возвращаются: «снято как недоказанное» не то же, что
    «в договоре нет», и флаги, срабатывающие на отсутствии, по снятому полю не
    ставятся. Поле в нескольких записях — берётся первая; documents — все."""
    данные = read_llm._json_из(сырой)
    if not isinstance(данные, dict):
        raise read_llm._Отказ("разбор", "ответ модели не разобран как JSON")
    условия: dict = {к: None for к in поля_условий()}
    условия["documents"] = []
    условия["side"] = данные.get("side") if данные.get("side") in ("customer", "supplier") else None
    доказательства: dict = {}
    снято: set[str] = set()
    for e in данные.get("items") or []:
        к = e.get("field") if isinstance(e, dict) else None
        if к not in условия or к == "side":
            continue
        значение = _значение("string" if к == "documents" else _тип(к), e.get("value"))
        if значение is None:
            continue                                  # пустая запись — условия нет
        цитата = " ".join(str(e.get("quote") or "").split())[:ЦИТАТА_ЗНАКОВ]
        if значение is _НЕ_РАЗОБРАНО or not цитата:
            снято.add(к)
            continue
        стр = e.get("page")
        if к == "documents":
            if значение not in условия["documents"]:
                условия["documents"].append(значение)
        elif условия[к] is None:
            условия[к] = значение
        else:
            continue
        доказательства.setdefault(к, {"quote": цитата, "page": стр if isinstance(стр, int) and стр > 0 else None})
    return условия, доказательства, [к for к in поля_условий() if к in снято and _пусто(условия.get(к))]


# --------------------------------------------------------------------------- портал
class Портал:
    """Портал через indexer: indexer.bx — одна очередь частоты на процесс
    (bitrix_client.интервал_портала: BITRIX_RPS / BITRIX_PARALLEL), indexer.download —
    закачка в той же очереди. Модуль тяжёлый и импортируется лениво; тесты
    подставляют свой портал с теми же двумя методами."""

    def __init__(self):
        import indexer
        self._ix = indexer

    def вызов(self, метод: str, параметры: dict) -> dict:
        return self._ix.bx(метод, параметры)

    def скачать(self, fo: dict) -> tuple[bytes | None, str]:
        """Файл поля CRM — только по urlMachine. Объект поля целиком indexer.download
        не отдаётся: не скачав по ссылкам, он идёт в disk.file.get с fo['id'], а у
        файла поля смарт-процесса это номер b_file, не объекта Диска, — другое
        пространство номеров, и закачка взяла бы чужой файл Диска, видимый вебхуку.
        fo['id'] остаётся только в колонке file_id."""
        адрес = (fo or {}).get("urlMachine")
        if not адрес:
            return None, "у файла поля нет urlMachine"
        rec: dict = {}
        тело = self._ix.download({"urlMachine": адрес}, rec)
        return тело, ("" if тело else str(rec.get("reason") or "не скачался"))


def _номер(v) -> int | None:
    try:
        n = int(str(v).strip())
    except (TypeError, ValueError):
        return None
    return n if n > 0 else None


def выбрать_сделки(портал, сколько: int, открытые: bool = False) -> list[dict]:
    """Последние по DATE_CREATE не проигранные сделки реализации; открытые=True —
    только открытые (недельный прогон по расписанию, решение владельца 23.10.2026:
    вкладка «Реализация» показывает договоры открытых сделок).

    Список — смещением по страницам, но не дальше нужного: при 30 сделках это ОДИН
    запрос. Фильтр портала проверяется ещё раз здесь: проигранная сделка, попавшая
    в выборку, тратила бы деньги модели на договоры, которых уже нет."""
    сделки: dict[int, dict] = {}
    старт = 0
    фильтр = ({"CATEGORY_ID": КАТЕГОРИЯ_РЕАЛИЗАЦИИ, "STAGE_SEMANTIC_ID": "P"} if открытые
              else {"CATEGORY_ID": КАТЕГОРИЯ_РЕАЛИЗАЦИИ, "!STAGE_SEMANTIC_ID": "F"})
    while len(сделки) < сколько:
        ответ = портал.вызов("crm.deal.list", {
            "filter": фильтр,
            "order": {"DATE_CREATE": "DESC", "ID": "DESC"},
            "select": ["ID", "DATE_CREATE", "COMPANY_ID", "STAGE_SEMANTIC_ID", "CATEGORY_ID"],
            "start": старт}) or {}
        часть = ответ.get("result") or []
        for d in часть:
            n = _номер(d.get("ID"))
            сем = str(d.get("STAGE_SEMANTIC_ID") or "").upper()
            if (n and str(d.get("CATEGORY_ID", КАТЕГОРИЯ_РЕАЛИЗАЦИИ)) == str(КАТЕГОРИЯ_РЕАЛИЗАЦИИ)
                    and сем != "F" and (not открытые or сем == "P")):
                сделки[n] = d
        следующая = ответ.get("next")
        if not часть or not следующая:
            break
        старт = следующая
    return sorted(сделки.values(), key=lambda d: (str(d.get("DATE_CREATE") or ""), int(d["ID"])),
                  reverse=True)[:сколько]


def поля_типа(портал, тип: int) -> dict:
    ответ = портал.вызов("crm.item.fields", {"entityTypeId": тип}) or {}
    return (ответ.get("result") or {}).get("fields") or {}


def подписи_списка(описание: dict) -> dict[str, str]:
    """{номер значения: подпись} у поля-списка из crm.item.fields."""
    out = {}
    for x in (описание or {}).get("items") or []:
        if isinstance(x, dict) and x.get("ID") is not None:
            out[str(x["ID"])] = str(x.get("VALUE") or "")
    return out


def подпись(значение, словарь: dict[str, str]) -> str | None:
    """Подпись значения списка; у множественного поля — через « / »."""
    значения = значение if isinstance(значение, list) else [значение]
    подп = [словарь.get(str(v), "") for v in значения if v not in (None, "", 0, "0")]
    подп = [p for p in подп if p]
    return " / ".join(подп) or None


def _по_ключу(портал, тип: int, связь: str, номера: list[int], выбрать: list[str]) -> list[dict]:
    """Записи типа, у которых поле связь — из номеров: по ключу (>id, start=-1), пачками
    по 50 номеров (навык bitrix-ingest: полного обхода нет, запрос — на 50 записей)."""
    out: list[dict] = []
    for i in range(0, len(номера), 50):
        пачка = номера[i:i + 50]
        после = 0
        while True:
            ответ = портал.вызов("crm.item.list", {
                "entityTypeId": тип, "order": {"id": "ASC"},
                "filter": {f"@{связь}": пачка, ">id": после},
                "select": выбрать, "start": -1}) or {}
            записи = (ответ.get("result") or {}).get("items") or []
            out.extend(записи)
            if len(записи) < 50:
                break
            после = int(записи[-1]["id"])
    return out


def карточки_типа(портал, тип: int, номера: list[int], поля: dict, связь: str = "parentId2") -> list[dict]:
    """Карточки типа со связью (parentId2 — сделки, parentId172 — заказы) из номеров.
    Поля, которых у типа нет, не спрашиваются; связь спецификации с рамочным — только
    у спецификаций."""
    нужные = ["id", "parentId2", "parentId172", *(СВЯЗЬ_С_РАМОЧНЫМ if тип in СПЕЦИФИКАЦИИ else ()),
              "companyId", "createdTime", *ПОЛЯ_ФАЙЛА[тип], *ПОЛЯ_ПОДПИСЕЙ[тип]]
    выбрать = [к for к in dict.fromkeys(нужные) if к == "id" or к in поля]
    return _по_ключу(портал, тип, связь, номера, выбрать)


def карточки_по_номерам(портал, тип: int, номера: list[int], поля: dict) -> list[dict]:
    """Рамочные по номерам (@id): только компания, время заведения и поля файла типа."""
    выбрать = [к for к in ("id", "companyId", "createdTime", *ПОЛЯ_ФАЙЛА[тип]) if к == "id" or к in поля]
    return _по_ключу(портал, тип, "id", номера, выбрать)


def сторона_по_связи(карточка: dict) -> tuple[str, str]:
    """(сторона по связи, откуда она): связь с заказом поставщику — поставщик. Только
    справочно: договоры с заказчиком привязывают к заказу (замер 22.10.2026)."""
    if _номер(карточка.get("parentId172")):
        return "supplier", "order_link"
    return "customer", "deal_link"


СЛОВА_ЗАКАЗЧИКА = ("заказчик", "покупател", "клиент", "customer", "buyer", "client")
СЛОВА_ПОСТАВЩИКА = ("поставщик", "supplier", "vendor")


def сторона_по_подписи(текст: str | None) -> str | None:
    """Сторона по подписи «Чей шаблон» / «Тип документа»: «шаблон заказчика» —
    договор с заказчиком, «шаблон поставщика» — с поставщиком; наш шаблон и
    подпись без этих слов о стороне не говорят."""
    s = (текст or "").lower()
    з = any(w in s for w in СЛОВА_ЗАКАЗЧИКА)
    п = any(w in s for w in СЛОВА_ПОСТАВЩИКА)
    if з == п:
        return None
    return "customer" if з else "supplier"


def сторона_по_компании(карточка: dict, сделка: dict, поставщики: set[int] | None = None) -> str | None:
    """Компания карточки — компания сделки: договор с заказчиком; поставщик одного из
    заказов СП-172 этой сделки — с поставщиком; любая другая (дочка клиента, логист,
    второе юрлицо холдинга) о стороне не говорит. Без списка поставщиков (поставщики
    None) — прежнее правило «другая — поставщик»: холостой прогон 19.10 показал, что
    так спорными выходят 41 % документов (21 из 51) и гейт стороны встаёт."""
    к, с = _номер(карточка.get("companyId")), _номер(сделка.get("COMPANY_ID"))
    if not к or not с:
        return None
    if к == с:
        return "customer"
    if поставщики is None:
        return "supplier"
    return "supplier" if к in поставщики else None


def чья_компания(карточка: dict, сделка: dict, поставщики: set[int]) -> str:
    """Чья компания стоит в карточке — для счёта в журнале: deal / supplier / other / none."""
    к, с = _номер(карточка.get("companyId")), _номер(сделка.get("COMPANY_ID"))
    if not к:
        return "none"
    if к == с:
        return "deal"
    return "supplier" if к in поставщики else "other"


def заказы_сделок(портал, номера_сделок: list[int], поля: dict | None = None) -> dict[int, dict]:
    """{заказ СП-172: {"deal", "company", "created", "stage", "category", "card"}} по
    сделкам выборки — пачками по 50 сделок, по ключу (>id). card — запись заказа с
    полями Purchase order / Order confirmation (те из них, что есть у типа): из неё
    берётся файл, когда у заказа нет документа поставщика. live и sem ставит
    семантика_заказов."""
    выбрать = ["id", "parentId2", "companyId", "createdTime", "stageId", "categoryId",
               *[к for к in ПОЛЯ_ФАЙЛА[СП_ЗАКАЗ] if к in (поля or {})]]
    номера = set(номера_сделок)
    out: dict[int, dict] = {}
    for з in _по_ключу(портал, СП_ЗАКАЗ, "parentId2", номера_сделок, выбрать):
        з_id, сд = _номер(з.get("id")), _номер(з.get("parentId2"))
        if з_id and сд in номера:
            стадия = str(з.get("stageId") or "")
            m = re.match(rf"DT{СП_ЗАКАЗ}_(\d+):", стадия)
            out[з_id] = {"deal": сд, "company": _номер(з.get("companyId")),
                         "created": str(з.get("createdTime") or ""), "stage": стадия,
                         "category": int(m.group(1)) if m else _номер(з.get("categoryId")),
                         "card": з, "sem": "?", "live": True}
    return out


def семантика_заказов(портал, заказы: dict[int, dict]) -> Counter:
    """Живой ли заказ: семантика его стадии по справочнику crm.status.list ENTITY_ID
    DYNAMIC_172_STAGE_<воронка> (как bitrix_client.spa_stage_meta) — один запрос на
    воронку, через общую очередь портала. Провал (F) — заказ не живой: карточки,
    связанные только с ним, и его Purchase order в разбор не идут. Стадии нет в
    справочнике — провал по суффиксу «:FAIL» (как spa_semantics без справочника).
    → счёт {S, F, P, ?} для журнала (? — у заказа нет стадии)."""
    сем: dict[str, str] = {}
    for воронка in sorted({з["category"] for з in заказы.values() if з["category"] is not None}):
        старт = 0
        while True:
            ответ = портал.вызов("crm.status.list", {
                "filter": {"ENTITY_ID": f"DYNAMIC_{СП_ЗАКАЗ}_STAGE_{воронка}"},
                "order": {"SORT": "ASC"}, "start": старт}) or {}
            часть = ответ.get("result") or []
            for s in часть:
                if isinstance(s, dict) and s.get("STATUS_ID"):
                    сем[str(s["STATUS_ID"])] = str(s.get("SEMANTICS") or "P").upper()[:1] or "P"
            if not часть or not ответ.get("next"):
                break
            старт = ответ["next"]
    счёт: Counter = Counter()
    for з in заказы.values():
        с = з["stage"]
        з["sem"] = сем.get(с) or (("F" if с.upper().endswith(":FAIL") else "P") if с else "?")
        з["live"] = з["sem"] != "F"
        счёт[з["sem"]] += 1
    return счёт


def поставщики_сделок(заказы: dict[int, dict]) -> dict[int, set[int]]:
    """{сделка: компании её заказов СП-172}."""
    out: dict[int, set[int]] = defaultdict(set)
    for з in заказы.values():
        if з["company"]:
            out[з["deal"]].add(з["company"])
    return dict(out)


def _время(v) -> datetime | None:
    try:
        return datetime.fromisoformat(str(v).strip())
    except (TypeError, ValueError):
        return None


def откуда_компания(карточка: dict, сделка: dict, заказы: dict[int, dict]) -> tuple[str, bool | None]:
    """У карточки со связью с заказом — (чья компания в ней, заведена ли карточка
    раньше своего заказа). Разбор спорных по компании: компания клиента в договоре,
    привязанном к заказу, — либо скопирована из сделки при заведении карточки, либо
    договор с заказчиком привязан к заказу. Только счёт, сторону не решает.

    Метки: order — как у своего заказа, deal — как у сделки, order_is_client — у
    самого заказа компания клиента, other, none — не указана, order_unknown — заказ
    не из сделки выборки, "" — связи с заказом нет."""
    з_id = _номер(карточка.get("parentId172"))
    if not з_id:
        return "", None
    заказ = заказы.get(з_id)
    if заказ is None:
        return "order_unknown", None
    к, с = _номер(карточка.get("companyId")), _номер(сделка.get("COMPANY_ID"))
    tк, tз = _время(карточка.get("createdTime")), _время(заказ["created"])
    раньше = (tк < tз) if tк and tз and (tк.tzinfo is None) == (tз.tzinfo is None) else None
    if not к:
        return "none", раньше
    if заказ["company"] and заказ["company"] == с:
        return "order_is_client", раньше
    if к == заказ["company"]:
        return "order", раньше
    if к == с:
        return "deal", раньше
    return "other", раньше


def порядок_файла(file_id: str) -> tuple[int, str]:
    """Новый файл раньше старого: номер файла поля больше — файл новее. Тот же порядок
    восстанавливает по строкам базы выгрузка для вкладки (scripts/realization_ctx.py:
    length(file_id) desc, file_id desc) — свод условий берёт первое заполненное."""
    return len(file_id), file_id


def группы_файла(тип: int) -> tuple[tuple[str, ...], ...]:
    return ГРУППЫ_ФАЙЛА.get(тип, (ПОЛЯ_ФАЙЛА[тип],))


def файлы_карточки(карточка: dict, тип: int) -> tuple[str | None, list[dict]]:
    """(поле первого взятого файла, файлы): у каждой группы ГРУППЫ_ФАЙЛА — файлы первого
    непустого поля по приоритету; файл несёт своё поле (ПОЛЕ_ФАЙЛА → file_field строки).
    Файлы карточки — новый раньше старого (порядок_файла), а не в порядке ответа портала;
    тот же файл в двух группах — один раз."""
    первое: str | None = None
    файлы: dict[str, dict] = {}
    for группа in группы_файла(тип):
        for поле in группа:
            v = карточка.get(поле)
            взяты = [x for x in (v if isinstance(v, list) else [v])
                     if isinstance(x, dict) and (x.get("id") or x.get("urlMachine") or x.get("url"))]
            if взяты:
                первое = первое or поле
                for x in взяты:
                    файлы.setdefault(str(x.get("id") or x.get("urlMachine") or x.get("url")), {**x, ПОЛЕ_ФАЙЛА: поле})
                break
    return первое, sorted(файлы.values(), key=lambda x: порядок_файла(str(x.get("id") or "")), reverse=True)


@dataclass
class Документ:
    """Документ сделки выборки: карточка договора, рамочный над её спецификацией или
    Purchase order заказа (link_source)."""
    deal_id: int
    card_entity: int
    card_id: int
    order_id: int | None
    side_link: str | None                       # сторона по связи карточки — справочно
    link_source: str                            # ИСТОЧНИКИ
    template: str | None
    doc_type: str | None
    side_template: str | None
    side_company: str | None
    file_field: str | None
    files: list[dict] = field(default_factory=list)
    company_rel: str = ""                       # чья компания в карточке: deal / supplier / other / none
    company_origin: str = ""                    # у карточки со связью с заказом — откуда_компания
    card_before_order: bool | None = None       # карточка заведена раньше своего заказа
    company_id: int | None = None               # компания карточки (у Purchase order — заказа)
    frameworks: list[tuple[int, int]] = field(default_factory=list)  # рамочные над спецификацией: (тип, номер)


@dataclass
class Отбор:
    сделки: list[dict]
    документы: dict[int, list[Документ]]      # сделка → документы
    нет_полей: list[str]                        # коды настроенных полей, которых у типа нет
    заказы: dict[int, dict] = field(default_factory=dict)   # заказы СП-172 сделок выборки
    счёт: Counter = field(default_factory=Counter)          # агрегаты отбора для журнала

    def все(self) -> list[Документ]:
        return [д for дд in self.документы.values() for д in дд]


def порядок_документа(card_entity: int, card_id: int) -> tuple[int, int]:
    """Ключ порядка документов сделки: вид по ПОРЯДОК_ВИДОВ, внутри — новая карточка
    раньше старой (номер больше — новее)."""
    вид = ПОРЯДОК_ВИДОВ.index(card_entity) if card_entity in ПОРЯДОК_ВИДОВ else len(ПОРЯДОК_ВИДОВ)
    return вид, -int(card_id)


def порядок_строки(r: dict) -> tuple:
    """Тот же порядок для строк contract_terms одной сделки: документ (порядок_документа),
    затем файл — длиннее номер раньше, при равной длине больший раньше (порядок_файла).
    Это ORDER BY выгрузки для вкладки (scripts/realization_ctx.py): array_position по
    ПОРЯДОК_ВИДОВ, card_id desc, length(file_id) desc, file_id desc."""
    f = str(r.get("file_id") or "")
    return (*порядок_документа(int(r["card_entity"]), int(r["card_id"])), -len(f), tuple(-ord(c) for c in f))


def документ_карточки(к: dict, тип: int, сделка: dict, заказы: dict[int, dict], поставщики: set[int],
                      словари: dict, источник: str | None = None) -> Документ:
    """Карточка договора → документ сделки. источник None — по связи карточки
    (deal_link / order_link)."""
    сделка_id = int(сделка["ID"])
    с, откуда = сторона_по_связи(к)
    шаблон = подпись(к.get(ПОЛЕ_ШАБЛОН), словари.get(ПОЛЕ_ШАБЛОН, {})) if тип == СП_РАЗОВЫЙ else None
    вид = подпись(к.get(ПОЛЕ_ТИП), словари.get(ПОЛЕ_ТИП, {})) if тип == СП_РАЗОВЫЙ else None
    поле, файлы = файлы_карточки(к, тип)
    происхождение, раньше = откуда_компания(к, сделка, заказы)
    return Документ(
        deal_id=сделка_id, card_entity=тип, card_id=int(_номер(к.get("id")) or 0),
        order_id=_номер(к.get("parentId172")), side_link=с, link_source=источник or откуда,
        template=шаблон, doc_type=вид, side_template=сторона_по_подписи(шаблон) or сторона_по_подписи(вид),
        side_company=сторона_по_компании(к, сделка, поставщики), file_field=поле, files=файлы,
        company_rel=чья_компания(к, сделка, поставщики), company_origin=происхождение, card_before_order=раньше,
        company_id=_номер(к.get("companyId")),
        frameworks=[(т, n) for код, т in СВЯЗЬ_С_РАМОЧНЫМ.items()
                    if тип in СПЕЦИФИКАЦИИ and (n := _номер(к.get(код)))])


def рамочные_сделок(портал, документы: dict[int, list[Документ]], по_номеру: dict[int, dict],
                    поставщики: dict[int, set[int]], поля_типов: dict[int, dict], счёт: Counter) -> None:
    """Отбор (в): рамочные, под которыми стоят спецификации сделки, если он уже не
    документ сделки. Рамочный читается по номерам (@id) — только компания и поля файла.

    Заказ документа — заказы его спецификаций в сделке, кроме спецификаций, которые
    компания карточки называет договором с заказчиком (их привязывают к заказу
    поставщику, замер 22.10.2026: рамочный заказчика заказа не наследует). Рамочный
    поставщика над спецификациями двух заказов — условия обоих: документ на каждый
    заказ («сделка, рамочный, заказ»; файл качается и читается один раз, ключ строки
    базы — с order_key). Спецификации без заказа — документ без заказа: рамочный
    поставщика без заказа снимает флаги сделки («поставщик без заказа»), а не
    приписывается чужому заказу."""
    нужны: dict[int, set[int]] = defaultdict(set)
    for дд in документы.values():
        for д in дд:
            for т, n in д.frameworks:
                нужны[т].add(n)
    карточки: dict[tuple[int, int], dict] = {}
    for т, номера in sorted(нужны.items()):
        if not поля_типов.get(т):
            continue                    # полей типа нет (crm.item.fields пуст) — спрашивать нечего
        for к in карточки_по_номерам(портал, т, sorted(номера), поля_типов[т]):
            n = _номер(к.get("id"))
            if n:
                карточки[(т, n)] = к
    for сделка_id, дд in документы.items():
        есть = {(д.card_entity, д.card_id) for д in дд}
        под: dict[tuple[int, int], set] = {}
        for д in дд:
            for ref in д.frameworks:
                заказы_спец = под.setdefault(ref, set())
                if д.side_company != "customer":
                    заказы_спец.add(д.order_id)
        for ref, заказы_спец in sorted(под.items()):
            счёт["рамочных: ссылок сделка → рамочный"] += 1
            if ref in есть:
                счёт["рамочных: уже документ сделки"] += 1
                continue
            к = карточки.get(ref)
            if к is None:
                счёт["рамочных: карточка не найдена"] += 1
                continue
            т, n = ref
            сделка = по_номеру[сделка_id]
            свои = поставщики.get(сделка_id, set())
            поле, файлы = файлы_карточки(к, т)
            заказы_док = sorted(заказы_спец, key=lambda з: (з is not None, з or 0)) or [None]
            if len(заказы_док) > 1:
                счёт["рамочных: над спецификациями нескольких заказов"] += 1
            for заказ in заказы_док:
                дд.append(Документ(
                    deal_id=сделка_id, card_entity=т, card_id=n, order_id=заказ, side_link=None,
                    link_source="framework", template=None, doc_type=None, side_template=None,
                    side_company=сторона_по_компании(к, сделка, свои), file_field=поле, files=файлы,
                    company_rel=чья_компания(к, сделка, свои), company_id=_номер(к.get("companyId"))))
            есть.add(ref)


def purchase_order_заказов(документы: dict[int, list[Документ]], заказы: dict[int, dict], счёт: Counter) -> None:
    """Отбор (г): Purchase order (затем Order confirmation) живого заказа, у которого нет
    документа поставщика. Документ поставщика заказа — карточка договора, связанная с
    этим заказом (кроме известной по компании как договор с заказчиком: такие
    привязывают к заказу, замер 22.10.2026), или документ с компанией заказа (договор с
    поставщиком без связи с заказом, рамочный поставщика). Рамочный над спецификацией
    своей связи с заказом не имеет — он документ поставщика заказа только по компании:
    рамочный заказчика без компании иначе снимал бы Purchase order. Заказ без файла в
    этих полях — не документ. Purchase order — всегда документ поставщика (заказ
    поставщику): side_company «supplier» и у заказа без компании — модель, назвавшая
    его договором с заказчиком, делает его спорным.
    Решение владельца 19.10.2026: гарантия — из договора, без договора — из Purchase order."""
    for з_id, з in sorted(заказы.items()):
        дд = документы.get(з["deal"])
        if дд is None or not з["live"]:
            continue
        if any(д.order_id == з_id and д.link_source != "framework" and д.side_company != "customer" for д in дд):
            continue
        if з["company"] and any(д.company_id == з["company"] for д in дд):
            счёт["заказов: документ поставщика по компании"] += 1
            continue
        счёт["заказов живых без документа поставщика"] += 1
        поле, файлы = файлы_карточки(з.get("card") or {}, СП_ЗАКАЗ)
        if not файлы:
            счёт["из них без Purchase order и Order confirmation"] += 1
            continue
        дд.append(Документ(
            deal_id=з["deal"], card_entity=СП_ЗАКАЗ, card_id=з_id, order_id=з_id, side_link="supplier",
            link_source="purchase_order", template=None, doc_type=None, side_template=None,
            side_company="supplier", file_field=поле, files=файлы,
            company_rel="supplier" if з["company"] else "none", company_id=з["company"]))


def отобрать(портал, сколько: int, открытые: bool = False) -> Отбор:
    сделки = выбрать_сделки(портал, сколько, открытые)
    по_номеру = {int(d["ID"]): d for d in сделки}
    номера = list(по_номеру)
    документы: dict[int, list[Документ]] = {n: [] for n in номера}
    нет_полей: list[str] = []
    счёт: Counter = Counter()
    if not номера:
        return Отбор(сделки, документы, нет_полей)
    поля_заказа = поля_типа(портал, СП_ЗАКАЗ)
    for код in ПОЛЯ_ФАЙЛА[СП_ЗАКАЗ]:
        if код not in поля_заказа:
            нет_полей.append(f"СП-{СП_ЗАКАЗ} {код}")
    заказы = заказы_сделок(портал, номера, поля_заказа)
    for сем, n in семантика_заказов(портал, заказы).items():
        счёт[f"заказов со стадией {сем}"] += n
    поставщики = поставщики_сделок(заказы)
    живые = {з_id: з for з_id, з in заказы.items() if з["live"]}
    поля_типов: dict[int, dict] = {}
    взяты: set[tuple[int, int]] = set()
    # (а) карточки договоров, связанные со сделкой
    for тип in ТИПЫ_ДОГОВОРОВ:
        поля = поля_типов[тип] = поля_типа(портал, тип)
        for код in ("parentId2", *ПОЛЯ_ФАЙЛА[тип], *ПОЛЯ_ПОДПИСЕЙ[тип]):
            if код not in поля:
                нет_полей.append(f"СП-{тип} {код}")
        if "parentId2" not in поля:
            continue                    # тип не связан со сделками — читать нечего
        словари = {код: подписи_списка(поля.get(код) or {}) for код in ПОЛЯ_ПОДПИСЕЙ[тип]}
        for к in карточки_типа(портал, тип, номера, поля):
            сделка_id, карт_id = _номер(к.get("parentId2")), _номер(к.get("id"))
            if сделка_id not in по_номеру or not карт_id or (тип, карт_id) in взяты:
                continue
            документы[сделка_id].append(документ_карточки(к, тип, по_номеру[сделка_id], заказы,
                                                          поставщики.get(сделка_id, set()), словари))
            взяты.add((тип, карт_id))
    # (б) карточки, связанные только с живым заказом сделки
    if живые:
        for тип in ТИПЫ_ДОГОВОРОВ:
            поля = поля_типов[тип]
            if "parentId172" not in поля:
                continue
            словари = {код: подписи_списка(поля.get(код) or {}) for код in ПОЛЯ_ПОДПИСЕЙ[тип]}
            for к in карточки_типа(портал, тип, sorted(живые), поля, связь="parentId172"):
                карт_id, заказ_id = _номер(к.get("id")), _номер(к.get("parentId172"))
                if not карт_id or (тип, карт_id) in взяты or заказ_id not in живые:
                    continue
                if _номер(к.get("parentId2")) in по_номеру:
                    continue            # своя сделка выборки — её документ взят в (а)
                if _номер(к.get("parentId2")):
                    # связана с другой сделкой (вне выборки): её документ, а не сделки заказа —
                    # иначе он менял бы флаги чужой сделки и по-разному при разной выборке
                    счёт["у заказа, но связана с другой сделкой — не взята"] += 1
                    continue
                счёт["только с заказом, без сделки"] += 1
                сделка_id = живые[заказ_id]["deal"]
                документы[сделка_id].append(документ_карточки(к, тип, по_номеру[сделка_id], заказы,
                                                              поставщики.get(сделка_id, set()), словари,
                                                              источник="order_only"))
                взяты.add((тип, карт_id))
    # (в) рамочные над спецификациями, (г) Purchase order заказов без документа поставщика
    рамочные_сделок(портал, документы, по_номеру, поставщики, поля_типов, счёт)
    purchase_order_заказов(документы, заказы, счёт)
    for дд in документы.values():
        дд.sort(key=lambda д: порядок_документа(д.card_entity, д.card_id))
    return Отбор(сделки, документы, нет_полей, заказы, счёт)


# --------------------------------------------------------------------------- части PDF
#: Чтение по частям (25.10.2026): живой прогон ct-40206159351-1 не отдал модели 86 файлов
#: (limit) — около 85 PDF больше LLM_READ_MAX_MB (20,7–37 МБ, сканы) и один длиннее
#: LLM_READ_MAX_PAGES. Такой PDF делится по страницам на части меньше обоих пределов,
#: каждая читается своим вызовом, записи частей сводятся в одну строку с номерами страниц
#: исходного файла. Условия из ЧАСТИ договора по-прежнему не пишутся: не прочитана хоть
#: одна часть — файл не прочитан (статус по причине).
#:   ДОЛЯ_ПРЕДЕЛА_ЧАСТИ — часть не больше этой доли LLM_READ_MAX_MB: запас на разметку
#:     PDF, которую pypdf пишет у части заново;
#:   ЧАСТЕЙ_МАКС, СТРАНИЦ_ПО_ЧАСТЯМ_МАКС — больше частей или страниц — limit, как прежде:
#:     том на сотни страниц — не договор, а комплект, и его цена — решение человека;
#:   ЗНАКОВ_СЛОЯ_МИН — страница больше предела сама по себе читается текстовым слоем,
#:     если в нём не меньше стольких знаков; иначе (скан без слоя) файл — limit.
ДОЛЯ_ПРЕДЕЛА_ЧАСТИ = 0.9
ЧАСТЕЙ_МАКС = 8
СТРАНИЦ_ПО_ЧАСТЯМ_МАКС = 200
ЗНАКОВ_СЛОЯ_МИН = 200


@dataclass
class Часть:
    """Часть PDF: страницы с первой по последнюю (с 1, исходного файла); тело — PDF этих
    страниц или (вид text) текстовый слой одной страницы, которая больше предела сама."""
    первая: int
    последняя: int
    тело: bytes
    вид: str = "pdf"


def _pdf_страниц(страницы: list) -> bytes:
    from pypdf import PdfWriter
    писатель = PdfWriter()
    for стр in страницы:
        писатель.add_page(стр)
    буфер = io.BytesIO()
    писатель.write(буфер)
    return буфер.getvalue()


def части_pdf(b: bytes) -> list[Часть] | None:
    """PDF больше LLM_READ_MAX_MB или длиннее LLM_READ_MAX_PAGES → части по страницам,
    каждая меньше обоих пределов; файл в пределах, не PDF или PDF, который pypdf не
    открыл, — None (обычное чтение решит само). Не делится — read_llm._Отказ «предел»:
    страница больше предела без текстового слоя, частей или страниц больше предела.

    Размер части оценивается суммой размеров её страниц, записанных поодиночке (общие
    шрифты так считаются с запасом), и проверяется записью: больше предела — пополам."""
    if not b.startswith(b"%PDF"):
        return None
    предел_байт = read_llm._число("LLM_READ_MAX_MB", 20.0) * 1_000_000
    предел_страниц = max(1, int(read_llm._число("LLM_READ_MAX_PAGES", 20)))
    try:
        from pypdf import PdfReader
        чтец = PdfReader(io.BytesIO(b))
        if чтец.is_encrypted and not чтец.decrypt(""):
            return None
        страницы = list(чтец.pages)
    except Exception:                                                       # noqa: BLE001
        return None
    всего = len(страницы)
    if len(b) <= предел_байт and всего <= предел_страниц:
        return None
    if всего > СТРАНИЦ_ПО_ЧАСТЯМ_МАКС:
        raise read_llm._Отказ("предел", f"PDF на {всего} стр. больше предела чтения по частям "
                                        f"{СТРАНИЦ_ПО_ЧАСТЯМ_МАКС} стр.")
    потолок = предел_байт * ДОЛЯ_ПРЕДЕЛА_ЧАСТИ
    try:
        размеры = [len(_pdf_страниц([стр])) for стр in страницы]
    except Exception as e:                                                  # noqa: BLE001
        raise read_llm._Отказ("предел", f"PDF на {всего} стр. не разделился на части ({type(e).__name__})") from None
    части: list[Часть] = []
    набор: list[int] = []

    def сбросить(номера: list[int]) -> None:
        if not номера:
            return
        тело = _pdf_страниц([страницы[i] for i in номера])
        if len(тело) > потолок and len(номера) > 1:
            середина = len(номера) // 2
            сбросить(номера[:середина])
            сбросить(номера[середина:])
            return
        части.append(Часть(номера[0] + 1, номера[-1] + 1, тело))

    for i, размер in enumerate(размеры):
        if размер > потолок:
            сбросить(набор)
            набор = []
            try:
                слой = " ".join(str(страницы[i].extract_text() or "").split())
            except Exception:                                               # noqa: BLE001
                слой = ""
            if len(слой) < ЗНАКОВ_СЛОЯ_МИН:
                raise read_llm._Отказ("предел", f"страница {i + 1} из {всего} — {размер / 1e6:.1f} МБ, больше "
                                                f"предела части, а текстового слоя у неё нет")
            части.append(Часть(i + 1, i + 1, f"[страница {i + 1}]\n{слой}".encode("utf-8"), "text"))
            continue
        if набор and (sum(размеры[j] for j in набор) + размер > потолок or len(набор) >= предел_страниц):
            сбросить(набор)
            набор = []
        набор.append(i)
    сбросить(набор)
    if len(части) > ЧАСТЕЙ_МАКС:
        raise read_llm._Отказ("предел", f"PDF на {всего} стр. делится на {len(части)} частей, больше предела "
                                        f"{ЧАСТЕЙ_МАКС}")
    return части


def свести_части(ответы: list[tuple[Часть, dict]]) -> tuple[str, list[str]]:
    """Ответы модели по частям ({side, items}) → один ответ того же вида (JSON) и заметки.

    Страница записи — номер в исходном файле: у PDF-части page с 1 — от её первой
    страницы, у текстового слоя — его страница; номер вне части — 0 (страница не
    названа). Записи — в порядке страниц: разобрать_ответ берёт первую запись поля, как
    у чтения целиком, и снимает значение без цитаты. Сторона — названная частями; части
    назвали разные — unknown (сторону скажет карточка, или документ останется без
    стороны)."""
    стороны = {д.get("side") for _ч, д in ответы} & {"customer", "supplier"}
    items = []
    for часть, данные in ответы:
        длина = часть.последняя - часть.первая + 1
        for e in данные.get("items") or []:
            if not isinstance(e, dict):
                continue
            стр = e.get("page")
            if часть.вид == "text":
                стр = часть.первая
            elif isinstance(стр, int) and not isinstance(стр, bool) and 1 <= стр <= длина:
                стр = часть.первая + стр - 1
            else:
                стр = 0
            items.append({**e, "page": стр})
    заметки = []
    if len(стороны) > 1:
        заметки.append("части назвали разные стороны — сторона не названа")
    return json.dumps({"side": стороны.pop() if len(стороны) == 1 else "unknown", "items": items},
                      ensure_ascii=False), заметки


# --------------------------------------------------------------------------- модель
class Читатель:
    """Чтение одного файла моделью с бюджетом прогона.

    Документ готовит read_llm.собрать_запрос (одна точка правды для PDF, сканов и
    офисных файлов); подсказка, схема ответа, effort и потолок выхода — свои.
    Вызов — read_llm._вызвать: поток с повторами на сеть и 429/5xx (в прогоне
    LLM_READ_RETRIES=1: повтор — следующим прогоном, даром по sha256 для прочитанных).

    потрачено — по usage ответов ПЛЮС оценка до вызова за каждую неудачную попытку:
    обрыв посреди потока мог быть оплачен, а бюджет обязан ошибаться в большую
    сторону. В строку (usd) идёт только счёт по usage; списанное по оценке — в
    заметке строки и в журнале отдельной суммой."""

    def __init__(self, модель: str, бюджет: float, клиент=None):
        self.модель = модель
        self.бюджет = float(бюджет)
        self.потрачено = 0.0
        self.оценка = 0.0
        self.списано_оценкой = 0.0
        self.оборвано = 0
        self.стоп = False
        self.фатально: str | None = None
        self.вызовов = 0
        self.секунды: list[float] = []      # длительность каждого вызова модели — для журнала
        self.страниц = 0
        self.вход = self.выход = 0
        self.снято_без_цитаты = 0
        self.обрезано = 0
        self.по_частям = 0                  # файлов, прочитанных по частям
        self.частей = 0                     # их частей (вызовов)
        self._клиент = клиент

    def клиент(self):
        if self._клиент is None:
            self._клиент = read_llm._клиент()
        return self._клиент

    def запрос(self, b: bytes, подвид: str | None, пометка: str | None = None) -> tuple[dict, dict, str]:
        """(запрос к API, оценка {страниц, вход, долларов, потолок}, заметка). Отказ —
        read_llm._Отказ. пометка — текст перед просьбой (какая это часть документа)."""
        запрос, оценка, заметка = read_llm.собрать_запрос(b, подвид)
        блоки = [бл for бл in запрос["messages"][0]["content"]
                 if not (бл.get("type") == "text" and бл.get("text") == read_llm.ПРОСЬБА)]
        вывод: dict = {"format": {"type": "json_schema", "schema": СХЕМА_ОТВЕТА}}
        # У младшей модели 4-го поколения параметра effort нет (400); у 5-го есть.
        if not self.модель.startswith("claude-haiku-4"):
            вывод["effort"] = УСИЛИЕ
        запрос.update(
            model=self.модель,
            max_tokens=МАКС_ВЫХОД,
            system=[{"type": "text", "text": СИСТЕМА, "cache_control": {"type": "ephemeral"}}],
            messages=[{"role": "user", "content": блоки + ([{"type": "text", "text": пометка}] if пометка else [])
                       + [{"type": "text", "text": ПРОСЬБА}]}],
            output_config=вывод,
        )
        вход = оценка["вход"] - read_llm.ТОКЕНОВ_ПОДСКАЗКИ + ТОКЕНОВ_ПОДСКАЗКИ
        return запрос, {"страниц": оценка["страниц"], "вход": вход,
                        "долларов": read_llm._доллары(self.модель, вход, ТОКЕНОВ_ВЫХОДА_ОЖИДАНИЕ),
                        "потолок": read_llm._доллары(self.модель, вход, МАКС_ВЫХОД),
                        "обрезан": bool(оценка.get("обрезан")),
                        "всего_страниц": оценка.get("всего_страниц")}, заметка

    def _списать(self, оценка: dict, попыток: int) -> float:
        """Неудачные попытки — в бюджет по оценке до вызова (см. описание класса)."""
        if попыток <= 0:
            return 0.0
        сумма = попыток * оценка["долларов"]
        self.потрачено += сумма
        self.списано_оценкой += сумма
        self.оборвано += попыток
        return сумма

    def прочитать(self, b: bytes, подвид: str | None = None, успеть=None) -> dict:
        """{status, terms, evidence, dropped, usd, pages, note}. Исключений не бросает.
        PDF больше пределов чтения — по частям (части_pdf); успеть() — не вышел ли срок
        прогона: проверяется перед каждой частью после первой."""
        if self.стоп:
            return {"status": "budget", "note": "бюджет прогона исчерпан раньше"}
        try:
            части = части_pdf(b)
        except read_llm._Отказ as о:
            self.обрезано += 1
            return {"status": СТАТУС_ОТКАЗА.get(о.класс, "api"), "note": ("не читался: " + о.причина)[:300]}
        if части is not None:
            return self._прочитать_по_частям(части, успеть)
        try:
            запрос, оценка, заметка = self.запрос(b, подвид)
        except read_llm._Отказ as о:
            return {"status": СТАТУС_ОТКАЗА.get(о.класс, "api"), "note": о.причина[:300]}
        except Exception as e:                                              # noqa: BLE001
            # Непредвиденный сбой подготовки — не «формат» (тот — «не читается», и
            # ответственный получил бы «перезалить файл»): им бывает и ошибка кода, а
            # формат read_llm называет своим отказом «формат» выше. Дочитает следующий прогон.
            return {"status": "api", "note": f"документ не подготовлен ({type(e).__name__})"}
        if оценка["обрезан"]:
            # Правило 15: статус не врёт. Условия из первых страниц — не условия
            # договора: потолок пеней, гарантия, право, перечень документов часто
            # в конце, и их «нет» стало бы ложным флагом. Модель не зовётся — платить
            # за чтение, которое во флаги не пойдёт, незачем.
            self.обрезано += 1
            return {"status": "limit", "pages": оценка["всего_страниц"] or None,
                    "note": ("не читался: файл больше предела чтения — "
                             + заметка.replace("модель прочла", "модель прочла бы"))[:300]}
        отказ = self._до_вызова(оценка["потолок"], оценка["страниц"])
        if отказ:
            return отказ
        ответ, отказ = self._спросить(запрос, оценка)
        if отказ:
            return отказ
        usd = self._учесть(getattr(ответ, "usage", None))
        self.страниц += оценка["страниц"]
        итог = {"pages": оценка["страниц"], "usd": usd, "note": заметка}
        сырой, отказ = self._текст_ответа(ответ)
        if отказ:
            return {**итог, **отказ}
        try:
            условия, доказательства, снято = разобрать_ответ(сырой)
        except read_llm._Отказ as о:
            return {**итог, "status": "parse", "note": о.причина}
        self.снято_без_цитаты += len(снято)
        return {**итог, "status": "ok", "terms": условия, "evidence": доказательства, "dropped": снято}

    def _до_вызова(self, потолок: float, страниц: int | None) -> dict | None:
        """Отказ до вызова: потолок цены не помещается в остаток бюджета (стоп насовсем)
        или API уже отказал запросу целиком. None — звать можно."""
        if self.потрачено + потолок > self.бюджет:
            # Стоп насовсем, а не «следующий поменьше»: очередь идёт от новых сделок
            # к старым, и дыра посреди очереди хуже ровного обрыва в конце.
            self.стоп = True
            return {"status": "budget", "pages": страниц,
                    "note": f"файлу нужно до ${потолок:.2f}, остаток "
                            f"${max(0.0, self.бюджет - self.потрачено):.2f}"}
        if self.фатально:
            return {"status": "api", "pages": страниц, "note": self.фатально}
        return None

    def _спросить(self, запрос: dict, оценка: dict) -> tuple[object | None, dict | None]:
        """Один вызов модели → (ответ, None) или (None, строка отказа). Неудачные попытки —
        в бюджет по оценке до вызова (см. описание класса)."""
        повторов_до = read_llm.итог()["повторов"]
        try:
            клиент = self.клиент()
            self.вызовов += 1
            self.оценка += оценка["долларов"]
            начало = time.monotonic()
            try:
                ответ = read_llm._вызвать(клиент, запрос)
            finally:
                self.секунды.append(time.monotonic() - начало)
        except read_llm._Отказ as о:
            if о.класс in НЕ_ОПЛАЧЕН or any(п in о.причина for п in ОТКАЗ_ЗАПРОСА):
                # Ключ не принят, пакета нет, схема или модель отвергнуты — не лечится
                # следующим файлом: дальше не зовём, а строки честно говорят «api», а
                # не «бюджет» (живой прогон 22.10: 14 одинаковых отказов схемы по 3 мин).
                self.фатально = о.причина[:300]
                return None, {"status": "api", "pages": оценка["страниц"], "note": о.причина[:300]}
            попыток = read_llm.итог()["повторов"] - повторов_до + 1
            списано = self._списать(оценка, попыток)
            return None, {"status": СТАТУС_ОТКАЗА.get(о.класс, "api"), "pages": оценка["страниц"],
                          "note": f"{о.причина[:240]}; в бюджет прогона списано по оценке ${списано:.2f}: "
                                  "оплата оборванного вызова неизвестна"}
        # Удачный ответ после повторов: повторы тоже могли быть оплачены.
        self._списать(оценка, read_llm.итог()["повторов"] - повторов_до)
        return ответ, None

    @staticmethod
    def _текст_ответа(ответ) -> tuple[str, dict | None]:
        """(текст ответа, None) или ("", отказ): модель отказалась читать, выход обрезан
        потолком и JSON не целый."""
        стоп = getattr(ответ, "stop_reason", None)
        if стоп == "refusal":
            return "", {"status": "model", "note": "модель отказалась читать файл (refusal)"}
        сырой = "".join(getattr(бл, "text", "") or "" for бл in (getattr(ответ, "content", None) or [])
                        if getattr(бл, "type", "") == "text")
        if стоп == "max_tokens" and not isinstance(read_llm._json_из(сырой), dict):
            return "", {"status": "parse", "note": f"ответ обрезан пределом {МАКС_ВЫХОД} токенов"}
        return сырой, None

    def _прочитать_по_частям(self, части: list[Часть], успеть=None) -> dict:
        """PDF больше пределов чтения — частью на вызов (части_pdf). Потолок цены ВСЕХ
        частей проверяется до первого вызова: файл, который не дочитать бюджетом, не
        начинается. Срок прогона — перед каждой частью после первой. Срок вышел или
        часть не прочитана — файл не прочитан (условия части договора — не условия
        договора), а оплаченное за прочитанные части — в usd строки."""
        n = len(части)
        всего = части[-1].последняя
        запросы = []
        for k, ч in enumerate(части, 1):
            пометка = (f"Это часть {k} из {n} одного документа: страницы {ч.первая}–{ч.последняя} из {всего}. "
                       "page — номер страницы внутри этой части, начиная с 1. Сторону назови, если она видна "
                       "в этой части; не видна — unknown.")
            try:
                запрос, оценка, _заметка = self.запрос(ч.тело, "txt" if ч.вид == "text" else None, пометка)
            except read_llm._Отказ as о:
                return {"status": СТАТУС_ОТКАЗА.get(о.класс, "api"), "pages": всего,
                        "note": f"часть {k} из {n}: {о.причина}"[:300]}
            except Exception as e:                                          # noqa: BLE001
                return {"status": "api", "pages": всего,
                        "note": f"часть {k} из {n} не подготовлена ({type(e).__name__})"}
            if оценка["обрезан"]:
                self.обрезано += 1
                return {"status": "limit", "pages": всего, "note": f"часть {k} из {n} больше предела чтения"}
            запросы.append((ч, запрос, оценка))
        отказ = self._до_вызова(sum(о["потолок"] for _ч, _з, о in запросы), всего)
        if отказ:
            return отказ
        usd = 0.0
        ответы: list[tuple[Часть, dict]] = []
        for k, (ч, запрос, оценка) in enumerate(запросы, 1):
            if k > 1 and успеть is not None and not успеть():
                return {"status": "time", "pages": всего, "usd": round(usd, 6),
                        "note": f"срок прогона вышел на части {k} из {n}: файл не дочитан"}
            отказ = self._до_вызова(оценка["потолок"], всего) if k > 1 else None
            ответ = None
            if not отказ:
                ответ, отказ = self._спросить(запрос, оценка)
            if not отказ:
                usd += self._учесть(getattr(ответ, "usage", None))
                self.страниц += оценка["страниц"] or 1
                self.частей += 1
                сырой, отказ = self._текст_ответа(ответ)
            if not отказ:
                данные = read_llm._json_из(сырой)
                if not isinstance(данные, dict):
                    отказ = {"status": "parse", "note": "ответ модели не разобран как JSON"}
            if отказ:
                return {**отказ, "pages": всего, "usd": round(usd, 6),
                        "note": f"часть {k} из {n}: {отказ.get('note') or ''}"[:300]}
            ответы.append((ч, данные))
        сводный, заметки = свести_части(ответы)
        условия, доказательства, снято = разобрать_ответ(сводный)
        self.снято_без_цитаты += len(снято)
        self.по_частям += 1
        слой = [ч.первая for ч in части if ч.вид == "text"]
        заметка = "; ".join([f"прочитан по частям: {n} (стр. " + ", ".join(
            f"{ч.первая}–{ч.последняя}" for ч in части) + ")"]
            + ([f"текстовым слоем стр. {', '.join(map(str, слой))}"] if слой else []) + заметки)
        return {"status": "ok", "pages": всего, "usd": round(usd, 6), "note": заметка[:400],
                "terms": условия, "evidence": доказательства, "dropped": снято}

    def _учесть(self, исп) -> float:
        def n(поле: str) -> int:
            try:
                return int(getattr(исп, поле, 0) or 0)
            except (TypeError, ValueError):
                return 0
        вход, выход = n("input_tokens"), n("output_tokens")
        usd = read_llm._доллары(self.модель, вход, выход, n("cache_creation_input_tokens"),
                                n("cache_read_input_tokens"))
        self.вход += вход
        self.выход += выход
        self.потрачено += usd
        return round(usd, 6)


def оценка_денег(файлов: int, модель: str) -> dict:
    """Оценка dry по допущению о страницах: {обычно, мало, много, потолок_обычного}."""
    def за_файл(страниц: int, выход: int) -> float:
        вход = страниц * (read_llm.ТОКЕНОВ_ТЕКСТА_НА_СТРАНИЦУ + read_llm.ТОКЕНОВ_КАРТИНКИ_НА_СТРАНИЦУ) + ТОКЕНОВ_ПОДСКАЗКИ
        return read_llm._доллары(модель, вход, выход)
    return {"обычно": файлов * за_файл(СТРАНИЦ_ОБЫЧНО, ТОКЕНОВ_ВЫХОДА_ОЖИДАНИЕ),
            "мало": файлов * за_файл(СТРАНИЦ_МАЛО, ТОКЕНОВ_ВЫХОДА_ОЖИДАНИЕ),
            "много": файлов * за_файл(СТРАНИЦ_МНОГО, ТОКЕНОВ_ВЫХОДА_ОЖИДАНИЕ),
            "потолок_обычного": за_файл(СТРАНИЦ_ОБЫЧНО, МАКС_ВЫХОД)}


