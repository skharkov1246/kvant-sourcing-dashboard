def документы_строк(строки: list[dict]) -> list[list[dict]]:
    """Прочитанные строки, собранные по документу — файлу карточки (вид, номер, файл): у
    рамочного под спецификациями N сделок или N заказов — N строк одного прочтения."""
    документы: dict[tuple, list[dict]] = {}
    for r in строки:
        if r["status"] in ПРОЧИТАН and r["terms"]:
            документы.setdefault((r["card_entity"], r["card_id"], r.get("file_id") or r.get("sha256") or ""),
                                 []).append(r)
    return list(документы.values())


def гейт_стороны(строки: list[dict]) -> tuple[bool, list[str]]:
    """(можно ли писать флаги, строки журнала) по прочитанным документам прогона.

    Два условия (пороги — ДОЛЯ_НАЗВАННЫХ_МИН, ДОЛЯ_СПОРНЫХ_МАКС): модель назвала
    сторону у достаточной доли документов — иначе сторона не определена и «не
    разошлась» ничего не значит; и документов, где компания карточки назвала другую
    сторону, немного. Связь и подпись — справочно. Пустой прогон (ничего не
    прочитано) флагов не имеет — гейт ему не нужен.

    Счёт — по документам (документы_строк), а не по строкам: рамочный под многими
    сделками иначе топил бы спорные своими согласиями — или один спорный встал бы за
    многих. Документ спорный, если компания разошлась с моделью хоть у одной его
    сделки. Purchase order — вне доли спорных: его сторона «поставщик» — по виду
    документа (заказ поставщику), а не по компании, и его согласие правила стороны по
    компании не проверяет; спорный Purchase order снимает флаги своей сделки."""
    документы = документы_строк(строки)
    всего = len(документы)
    названо = [rs for rs in документы if сторона_модели(rs[0]) is not None]
    по_карточке = [rs for rs in документы if rs[0].get("side_source") == ПО_КАРТОЧКЕ]
    без_стороны = sum(1 for rs in документы if rs[0]["side"] is None)
    стороны_карточки = Counter(rs[0]["side"] for rs in по_карточке)
    журнал = [f"сторона по модели названа: {_доля(len(названо), всего)} прочитанных документов",
              f"сторона по карточке (модель не назвала; решение владельца 25.10.2026): {len(по_карточке)} "
              f"документов — заказчик {стороны_карточки['customer']} · поставщик {стороны_карточки['supplier']}",
              f"без стороны (ни модель, ни карточка не назвали): {без_стороны} — их сделки флагов не получают"]
    for способы, пометка in ((СВЕРКА_СТОРОНЫ, ""), (СПРАВОЧНО_СТОРОНЫ, " (справочно, сторону не решает)")):
        for имя, _взять in способы:
            с = Counter()
            for rs in названо:
                голоса = {голоса_стороны(r, способы)[имя] for r in rs} - {None}
                с["молчит" if not голоса else ("разошлась" if голоса - {сторона_модели(rs[0])} else "совпала")] += 1
            журнал.append(f"сторона по модели ↔ {имя}{пометка}: совпала {с['совпала']} · разошлась "
                          f"{с['разошлась']} · не сказано {с['молчит']}")
    сказано = [rs for rs in названо if rs[0].get("link_source") != "purchase_order"
               and any(any(голоса_стороны(r).values()) for r in rs)]
    спорных = sum(1 for rs in сказано if any(сторона_спорная(r) for r in rs))
    доля_названных = len(названо) / всего if всего else 1.0
    доля_спорных = спорных / len(сказано) if сказано else 0.0
    журнал.append(f"спорных документов (компания карточки назвала другую сторону) — из тех, где сказали и модель, "
                  f"и компания, без Purchase order: {_доля(спорных, len(сказано))} — во флаги не идут, их сделки "
                  "флагов не получают")
    гейт = True
    if доля_названных < ДОЛЯ_НАЗВАННЫХ_МИН:
        гейт = False
        журнал.append(f"::error::модель назвала сторону у {_доля(len(названо), всего)} прочитанных документов "
                      f"(нужно не меньше {ДОЛЯ_НАЗВАННЫХ_МИН:.0%}): сторона не определена — "
                      f"флаги прогона не записаны; проверить, как мы названы в договорах (НАШИ_КОМПАНИИ)")
    if доля_спорных > ДОЛЯ_СПОРНЫХ_МАКС:
        гейт = False
        журнал.append(f"::error::компания карточки разошлась с моделью у {доля_спорных:.0%} документов "
                      f"(порог {ДОЛЯ_СПОРНЫХ_МАКС:.0%}): флаги прогона не записаны, правило стороны — на разбор")
    return гейт, журнал


def причины_отказов(строки: list[dict]) -> Counter:
    """Причины отказов чтения — для журнала, агрегатом. Заметка строки до «;» (хвост —
    про списание бюджета), длинные числа скрыты (номера в тексте ответа API не нужны
    журналу), не длиннее 120 знаков. Бюджет, срок и отсутствие файла — не отказы."""
    out: Counter = Counter()
    for r in строки:
        if r["status"] in ("ok", "reused", "no_file", "budget", "time"):
            continue
        причина = str(r.get("note") or "без заметки").split(";", 1)[0]
        причина = re.sub(r"\d{5,}", "…", " ".join(причина.split()))[:120]
        out[f"{r['status']}: {причина}"] += 1
    return out


#: Поля, от которых зависят флаги срока, приёмки и валюты (lateByDesign, thinBuffer,
