#: берёт из Purchase order гарантию, а не вывод «пеней нет».
ПОЛЯ_ОТСУТСТВИЯ_ПОСТАВЩИКА = tuple(dict.fromkeys(
    поле for пары in ФЛАГИ_ПО_ОТСУТСТВИЮ.values() for сторона_, поле in пары if сторона_ == "supplier"))


def снятые_поля(строки: list[dict], свод: dict) -> set[str]:
    """Поля, которые в своде стороны пусты, а хоть в одном её документе сняты как
    значение без цитаты: о них известно не «нет», а «не доказано»."""
    снято = {к for r in строки for к in (r.get("dropped") or [])}
    return {к for к in снято if _пусто(свод.get(к))}


def флаги_сделки(строки: list[dict], снятые_флаги: Counter | None = None,
                 пары: list | None = None) -> tuple[list[dict], str]:
    """(флаги по заказам, исход): исход — «пара», «не читается», «недочитана», «без
    стороны», «спорная», «поставщик без заказа», «нет пары».

    Сделка, где хоть один файл договора не прочитан (бюджет, срок, закачка,
    предел, отказ), флагов не получает: без него свод условий другой, и флаг соврал
    бы — или промолчал там, где риск есть. «Не читается» (НЕ_ЧИТАЕТСЯ: закачка,
    формат, предел) главнее «недочитана» (НЕ_ДОЧИТАН): следующий прогон его не
    вылечит, нужен человек — перезалить файл или разделить. По той же причине их не получает сделка
    с документом без стороны (модель её не назвала) и со спорным (компания карточки
    назвала другую сторону): ни с ним, ни без него свод условий верным не назовёшь.
    И сделка с договором поставщика без связи с заказом СП-172: к какому заказу и
    какому поставщику его условия, неизвестно, а общий свод таких документов разных
    поставщиков спрятал бы риск одного за условиями другого. Карточка без файла договора —
    не недочитанность: читать в ней нечего.

    Флаг, срабатывающий на отсутствии условия (ФЛАГИ_ПО_ОТСУТСТВИЮ), не ставится,
    если это условие снято как значение без цитаты или, у поставщика, весь его документ
    по заказу — Purchase order (ПОЛЯ_ОТСУТСТВИЯ_ПОСТАВЩИКА); счёт таких — в снятые_флаги."""
    if any(r["status"] in НЕ_ЧИТАЕТСЯ for r in строки):
        return [], "не читается"
    if any(r["status"] in НЕ_ДОЧИТАН for r in строки):
        return [], "недочитана"
    прочитанные = [r for r in строки if r["status"] in ПРОЧИТАН and r["terms"]]
    if any(r["side"] is None for r in прочитанные):
        return [], "без стороны"
    if any(сторона_спорная(r) for r in прочитанные):
        return [], "спорная"
    if any(r["side"] == "supplier" and r["order_id"] is None for r in прочитанные):
        return [], "поставщик без заказа"
    заказчик = [r for r in прочитанные if r["side"] == "customer"]
    по_заказам: dict[int | None, list[dict]] = defaultdict(list)
    for r in прочитанные:
        if r["side"] == "supplier":
            по_заказам[r["order_id"]].append(r)
    if not заказчик or not по_заказам:
        return [], "нет пары"
    условия_заказчика = свести(заказчик)
    снято_заказчика = снятые_поля(заказчик, условия_заказчика)
    out = []
    for заказ, rs in sorted(по_заказам.items(), key=lambda x: x[0] or 0):
        условия_поставщика = свести(rs)
        снято_поставщика = снятые_поля(rs, условия_поставщика)
        if all(r.get("link_source") == "purchase_order" for r in rs):
            снято_поставщика |= {к for к in ПОЛЯ_ОТСУТСТВИЯ_ПОСТАВЩИКА if _пусто(условия_поставщика.get(к))}
        снято = {"customer": снято_заказчика, "supplier": снято_поставщика}
        if пары is not None:
            пары.append((условия_заказчика, условия_поставщика, снято))
        for f in contract_b2b.flags(условия_заказчика, условия_поставщика):
            if any(поле in снято[сторона_] for сторона_, поле in ФЛАГИ_ПО_ОТСУТСТВИЮ.get(f["code"], ())):
                if снятые_флаги is not None:
                    снятые_флаги[f["code"]] += 1
                continue
            out.append({"deal_id": строки[0]["deal_id"], "order_id": заказ, "code": f["code"],
                        "days": f.get("days")})
    return out, "пара"


#: Версия правил сверки — свода, исхода и флагов по строкам условий. Отдельна от версии
#: чтения (METHOD_VER: ключ повтора по sha256): правка флага или стороны не должна
#: делать прочитанное непригодным и звать модель второй раз — для неё есть пересчёт
#: (--mode reflag). Выведена из текста правил (contract_b2b.py целиком и функции
#: свода здесь): правка любой из них сама меняет версию. Ею помечены исходы и флаги
#: (contract_deal_outcome.method_ver, contract_b2b_flags.method_ver); по ней свод для
#: вкладки (scripts/realization_ctx.py) отличает расхождение нынешних правил (шаг
#: красный) от расхождения с правилами прежней версии (пометка).
def версия_сверки() -> str:
    части = [Path(contract_b2b.__file__).read_text(encoding="utf-8")]
    части += [inspect.getsource(ф) for ф in (сторона_строки, сторона_модели, сторона_спорная, свести,
                                             снятые_поля, флаги_сделки)]
    части.append(json.dumps({"ПО_ОТСУТСТВИЮ": ФЛАГИ_ПО_ОТСУТСТВИЮ, "НЕ_ЧИТАЕТСЯ": НЕ_ЧИТАЕТСЯ,
                             "НЕ_ДОЧИТАН": НЕ_ДОЧИТАН}, ensure_ascii=False, sort_keys=True))
    return "сверка:" + hashlib.sha256("\n".join(части).encode("utf-8")).hexdigest()[:12]


ВЕРСИЯ_ИСХОДА = f"{METHOD_VER}+{версия_сверки()}"


