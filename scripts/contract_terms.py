def _доля(a: int, b: int) -> str:
    return f"{a} из {b} ({100 * a / b:.0f} %)" if b else "0 из 0"


def сверка_сторон(документы: list[Документ]) -> list[str]:
    """Холостой прогон стороны не знает (её назовёт модель): что скажет компания
    карточки и что говорят связь и подпись — справочно, только счёт."""
    out = []
    с_файлом = [д for д in документы if д.files]
    по_компании = Counter(д.side_company or "молчит" for д in с_файлом)
    out.append("сторона — по модели после чтения (решение владельца 22.10.2026); у документов с файлом "
               f"компания карточки скажет: заказчик {по_компании['customer']} · поставщик "
               f"{по_компании['supplier']} · не говорит {по_компании['молчит']}")
    чья = Counter(д.company_rel or "none" for д in документы)
    out.append(f"компания карточки (все карточки, и без файла): компания сделки {чья['deal']} · поставщик заказов "
               f"сделки {чья['supplier']} · другая (о стороне не говорит) {чья['other']} · не указана {чья['none']}")
    for имя, взять in (("подпись «Чей шаблон» / «Тип документа»", lambda д: д.side_template),
                       ("связь карточки с заказом", lambda д: д.side_link)):
        с = Counter("молчит" if взять(д) is None or д.side_company is None
                    else ("совпала" if взять(д) == д.side_company else "разошлась") for д in с_файлом)
        out.append(f"{имя} ↔ компания (справочно, сторону не решает): совпала {с['совпала']} · "
                   f"разошлась {с['разошлась']} · не сказано {с['молчит']}")
    спор = Counter((д.side_link, д.side_company) for д in с_файлом
                   if д.side_company and д.side_company != д.side_link)
    if спор:
        out.append("расхождения связь → компания: " + " · ".join(
            f"{'заказчик' if a == 'customer' else 'поставщик'} → {'заказчик' if b == 'customer' else 'поставщик'} {n}"
            for (a, b), n in sorted(спор.items())))
    out += разбор_спорных(документы)
    return out


def разбор_спорных(документы: list[Документ]) -> list[str]:
    """Откуда компания клиента в карточке, привязанной к заказу поставщику, — только
    счёт. Две причины расхождения различаются: компания скопирована из сделки при
    заведении карточки (договор с поставщиком) — или договор с заказчиком привязан
    к заказу (связь о стороне не говорит; замер 22.10.2026 — так у 19 из 20)."""
    с_заказом = [д for д in документы if д.company_origin]
    if not с_заказом:
        return []
    о = Counter(д.company_origin for д in с_заказом)
    out = [f"карточки со связью с заказом ({len(с_заказом)}): компания как у своего заказа {о['order']} · "
           f"как у сделки {о['deal']} · у самого заказа компания клиента {о['order_is_client']} · "
           f"другая {о['other']} · не указана {о['none']} · заказ не из сделки {о['order_unknown']}"]
    спорные = [д for д in с_заказом if д.side_link == "supplier" and д.side_company == "customer"]
    if not спорные:
        return out
    заказчик_по_связи = {д.deal_id for д in документы if д.side_link == "customer"}
    поставщик_у_заказа = {д.order_id for д in документы if д.order_id and д.company_rel == "supplier"}
    раньше = Counter("да" if д.card_before_order else ("нет" if д.card_before_order is False else "?")
                     for д in спорные)
    подпись = Counter({"customer": "заказчик", "supplier": "поставщик"}.get(д.side_template, "молчит")
                      for д in спорные)
    out.append(f"связь «поставщик», компания «заказчик» ({len(спорные)}): у сделки нет документа с заказчиком по связи "
               f"{sum(1 for д in спорные if д.deal_id not in заказчик_по_связи)} · у того же заказа есть карточка "
               f"с компанией поставщика {sum(1 for д in спорные if д.order_id in поставщик_у_заказа)} · "
               f"карточка заведена раньше своего заказа: да {раньше['да']}, нет {раньше['нет']}, "
               f"не известно {раньше['?']} · подпись говорит: заказчик {подпись['заказчик']}, "
               f"поставщик {подпись['поставщик']}, молчит {подпись['молчит']}")
    return out


def журнал_отбора(отбор: Отбор) -> list[str]:
    сделки = отбор.сделки
    по_стадии = Counter(str(d.get("STAGE_SEMANTIC_ID") or "?").upper() for d in сделки)
    строки = [f"сделок реализации, не проигранных: {len(сделки)} (в работе {по_стадии['P']}, "
              f"успешных {по_стадии['S']})"]
    for тип in (СП_РАЗОВЫЙ, СП_РАМОЧНЫЙ):
        дд = [д for д in отбор.все() if д.card_entity == тип]
        стороны = Counter(д.side_link for д in дд)
        поля = Counter(д.file_field for д in дд if д.file_field)
        подписи = ", ".join(f"{i + 1}-е поле {поля[код]}" for i, код in enumerate(ПОЛЯ_ФАЙЛА[тип]))
        строки.append(f"карточек СП-{тип}: {len(дд)} (по связи, справочно: с заказчиком {стороны['customer']}, "
                      f"с поставщиком {стороны['supplier']}) · с файлом {_доля(sum(поля.values()), len(дд))} ({подписи}) · "
                      f"файлов {sum(len(д.files) for д in дд)}")
    с_парой = sum(1 for дд in отбор.документы.values()
                  if {д.side_company for д in дд if д.files} >= {"customer", "supplier"})
    без_договоров = sum(1 for дд in отбор.документы.values() if not дд)
    строки.append(f"сделок, где компания карточек с файлом уже называет обе стороны: {_доля(с_парой, len(сделки))} "
                  f"(остальное скажет модель) · без карточек договора {без_договоров}")
    без_заказчика = sum(1 for дд in отбор.документы.values()
                        if дд and not any(д.side_link == "customer" for д in дд))
    клиент = {int(d["ID"]): _номер(d.get("COMPANY_ID")) for d in сделки}
    з_клиент = sum(1 for з in отбор.заказы.values() if з["company"] and з["company"] == клиент.get(з["deal"]))
    строки.append(f"заказов СП-172 у сделок выборки: {len(отбор.заказы)}, из них с компанией клиента сделки "
                  f"{з_клиент} · сделок с договорами, но без документа с заказчиком по связи (справочно) "
                  f"{без_заказчика}")
    строки += сверка_сторон(отбор.все())
    if отбор.нет_полей:
        строки.append("::warning::настроенных полей нет у типа: " + ", ".join(отбор.нет_полей))
    return строки


def журнал_оценки(файлов: int, бюджет: float, модели: list[str]) -> list[str]:
    строки = [f"оценка денег — по допущению {СТРАНИЦ_ОБЫЧНО} стр. на файл (вилка {СТРАНИЦ_МАЛО}–{СТРАНИЦ_МНОГО}; "
              f"страниц dry не знает: файлы не качаются), выход ~{ТОКЕНОВ_ВЫХОДА_ОЖИДАНИЕ} ток. на файл"]
    for м in модели:
        о = оценка_денег(файлов, м)
        на_файл = о["обычно"] / файлов if файлов else 0.0
        влезет = int(бюджет / на_файл) if на_файл else 0
        строки.append(f"  {м}: файлов {файлов} ≈ ${о['обычно']:.2f} (вилка ${о['мало']:.2f}–${о['много']:.2f}); "
                      f"бюджет ${бюджет:.2f} — примерно {min(влезет, файлов)} файлов из {файлов}; "
                      f"потолок обычного файла до вызова ${о['потолок_обычного']:.2f}")
    return строки


