#: Коды ISO, которые узнаются и внутри подписи («Рубли (RUB)», «EUR без НДС») — закрытый
#: список; RUR и RMB — прежние имена рубля и юаня. Подпись из одного кода вне списка
#: («SEK») по-прежнему — код как есть: полосы КУРС_ЗА_ЕВРО у неё нет, и числа не будет.
КОДЫ_ВАЛЮТ = ("EUR", "RUB", "RUR", "USD", "CNY", "RMB", "AED", "GBP", "CHF", "JPY", "KZT", "TRY", "INR",
              "KRW", "RSD", "BYN")
_ПСЕВДОНИМЫ = {"RUR": "RUB", "RMB": "CNY"}
#: Слова валют по основе — образец на слово целиком (после нормализации: нижний регистр,
#: ё → е). Основы с короткими словами-двойниками («вон», «лир», «иен», «франко» — базис
#: поставки, «Франкфурт») — только с окончаниями валюты.
_СЛОВА_ВАЛЮТ = tuple((re.compile(о), код) for о, код in (
    (r"евро|euros?", "EUR"),
    (r"руб(?:л\w*)?|r(?:o)?ubles?", "RUB"),
    (r"долл\w*|dollars?", "USD"),
    (r"юан\w*|yuan|renminbi", "CNY"),
    (r"дирхам\w*|dirhams?", "AED"),
    (r"фунт\w*|pounds?|sterling", "GBP"),
    (r"франк(?:и|а|ов|ам|ами|ах|ом|у|е)?|francs?", "CHF"),      # не «франко», не «Франкфурт»
    (r"иен(?:а|ы|у|ой|е)?|yen", "JPY"),
    (r"тенге|tenge", "KZT"),
    (r"лир(?:а|ы|у|ой|е)?|lira|lire", "TRY"),
    (r"рупи\w*|rupees?", "INR"),
    (r"вон(?:а|ы|у|ой|е)?|won", "KRW"),
    (r"динар\w*|dinars?", "RSD"),
))
#: Знаки валют; ¥ — и юань, и иена: решает слово или код рядом, без них — юань (как прежде).
_ЗНАКИ = {"€": "EUR", "₽": "RUB", "£": "GBP"}
#: Иные валюты и страны одноимённых валют: подпись с ними — не валюта из списка (код None).
_ЧУЖИЕ = re.compile(
    r"(?:крон|злот|песо|гривн|ринггит|шекел|манат|рэнд|бат$|лари$|сом$|сомони|драм$|условн|приднестров|"
    r"канад|австрал|сингапур|гонконг|новозеланд|тайван|египет|кувейт|бахрейн|иордан|ирак|алжир|тунис|"
    r"ливийск|марокк|пакистан|индонез|непал|ланкийск|ливанск|сирийск|"
    # страны иных долларов и сокращения («австр. $», «кан. доллар»)
    r"бруне|фиджи|ямайк|багам|барбадос|белиз|бермуд|кайман|карибск|гайан|либери|намиби|соломон|суринам|"
    r"тринидад|зимбабв|мексик|бразил|аргентин|чилийск|колумби|австр$|кан$|синг$|сингап$|гонк$|тайв$|нз$|"
    r"kron|zlot|peso|hryvn|ringgit|shekel|manat|rand$|baht|lari$|canad|austral|singapor|hong$|zealand|taiwan|"
    r"egypt|kuwait|bahrain|jordan|iraq|alger|tunis|libya|morocc|pakistan|indonesia|nepal|lanka|leban|syria|"
    r"brunei|fiji|jamaica|bahama|barbad|beliz|bermud|cayman|caribbean|guyan|liberia|namibia|solomon|surinam|"
    r"trinidad|zimbabw|mexic|brazil|argentin|chile|colomb|"
    # коды ISO иных валют — частые в расчётах; вне КОДЫ_ВАЛЮТ
    r"(?:cad|aud|sgd|hkd|nzd|twd|sek|nok|dkk|pln|czk|huf|egp|sar|qar|kwd|bhd|omr|jod|mad|pkr|idr|thb|myr|vnd|"
    r"brl|mxn|zar|uah|amd|gel|azn|uzs|kgs|tjs|ils|php|byr)$)")
#: Белорусский рубль — не российский: «бел. руб.», «белорусский рубль».
_БЕЛОРУССКИЙ = re.compile(r"белорус\w*|бел|рб|belarus\w*|bel")
#: Кириллица, похожая на латиницу, — в слове из двух азбук («ЕUR» с русской Е).
_ЛАТИНИЦА = str.maketrans("авекмнорстух", "abekmhopctyx")
_УЕ = re.compile(r"(?<![a-zа-я])у\s*\.\s*е(?![a-zа-я])")
#: Знак $ и приставка перед ним — через пробел или точку тоже («C $», «S.$»).
_ЗНАК_ДОЛЛАРА = re.compile(r"([a-zа-я]*)([\s.]*)\$")
#: «U.S. $» — приставка США с точками.
_США = re.compile(r"(?<![a-zа-я])u\s*\.\s*s\s*\.?(?![a-zа-я])")
#: Приставки знака $ у иных долларов — закрытый список латиницей (C$, A$, S$, NZ$, HK$, NT$,
#: R$ — бразильский реал, B$ и BND$ — брунейский, J$, TT$, EC$, Z$, BZ$, FJ$, T$, Mex$).
#: Список закрыт, чтобы «в $» и «цена $» оставались долларом США.
ЧУЖИЕ_ДОЛЛАРЫ = frozenset(("c", "ca", "cad", "can", "a", "au", "aud", "s", "sg", "sgd", "nz", "nzd", "hk", "hkd",
                           "nt", "ntd", "r", "mx", "mex", "b", "bnd", "bd", "bds", "bs", "fj", "j", "jm", "t", "tt",
                           "ec", "z", "bz", "si", "sr", "l", "ld"))
#: Слова-двойники кодов и валют, обычные английские слова («Try», «won»): в подписи из
#: нескольких слов — только прописными (TRY, WON) или рядом со страной валюты.
_ДВОЙНИКИ_СЛОВ = {"try": ("turk", "турец", "турк"), "won": ("korea", "корей")}


def _норм_подписи(v: str) -> str:
    """Регистр, ё, неразрывные и узкие пробелы, полноширинные знаки (NFKC)."""
    return unicodedata.normalize("NFKC", v).lower().replace("ё", "е")


def _слова(t: str) -> list[str]:
    """Слова нормализованной подписи; слово из двух азбук — латиницей («ruв» → «rub»)."""
    out = []
    for w in re.findall(r"[a-zа-я]+", t):
        if re.search(r"[a-z]", w) and re.search(r"[а-я]", w):
            w = w.translate(_ЛАТИНИЦА)
        out.append(w)
    return out


def _доллар_чужой(приставка: str, промежуток: str) -> bool:
    """Приставка знака $ — иного доллара (C$, «C $», «С$» с русской С, «австр. $»)."""
    кир, лат = bool(re.search(r"[а-я]", приставка)), bool(re.search(r"[a-z]", приставка))
    if кир and (лат or (not промежуток and re.fullmatch(r"[авекмнорстух]+", приставка))):
        # из двух азбук или кириллица вплотную к знаку буквами-двойниками («С$») — латиницей;
        # через пробел кириллица — слово («в $»), не приставка
        приставка = приставка.translate(_ЛАТИНИЦА)
    if приставка in ("", "us", "usd"):
        return False
    return приставка in ЧУЖИЕ_ДОЛЛАРЫ or bool(_ЧУЖИЕ.match(приставка))


def коды_валют(v: str) -> tuple[set[str], bool]:
    """Подпись → (коды валют из списка, есть ли иное: чужая валюта, страна одноимённой,
    «у.е.», знак $ с чужой приставкой «HK$», «C $»). Сам текст не возвращается."""
    исходная = unicodedata.normalize("NFKC", v)
    t = _норм_подписи(v)
    иное = bool(_УЕ.search(t))
    слова = _слова(t)
    белорусский = any(_БЕЛОРУССКИЙ.fullmatch(w) for w in слова)
    коды: set[str] = set()
    for w in слова:
        if _ЧУЖИЕ.match(w):
            иное = True
            continue
        if (w in _ДВОЙНИКИ_СЛОВ and len(слова) > 1
                and not re.search(rf"(?<![A-Za-z]){w.upper()}(?![A-Za-z])", исходная)
                and not any(x.startswith(_ДВОЙНИКИ_СЛОВ[w]) for x in слова)):
            continue                     # «Try», «won» в английской фразе — не валюта
        код = (_ПСЕВДОНИМЫ.get(w.upper(), w.upper()) if w.upper() in КОДЫ_ВАЛЮТ
               else next((к for образец, к in _СЛОВА_ВАЛЮТ if образец.fullmatch(w)), None))
        if код:
            коды.add("BYN" if код == "RUB" and белорусский else код)     # «бел. руб.», «Bel. rub»
    for знак, код in _ЗНАКИ.items():
        if знак in t:
            коды.add(код)
    for м in _ЗНАК_ДОЛЛАРА.finditer(_США.sub("us", t)):
        if _доллар_чужой(м.group(1), м.group(2)):
            иное = True
        else:
            коды.add("USD")
    if "¥" in t and not коды & {"CNY", "JPY"}:
        коды.add("CNY")
    return коды, иное


def валюта(v) -> str | None:
    """Подпись валюты → код ISO (EUR, RUB…); не валюта, несколько валют, «у.е.» — None.

    Прежние правила — первыми (подпись из словаря _ВАЛЮТЫ или из одного кода из трёх
    латинских букв: код вне КОДЫ_ВАЛЮТ — как есть, если это не слово валюты вроде «won»);
    затем код из КОДЫ_ВАЛЮТ, слово валюты или знак в любом месте подписи (коды_валют) —
    ровно одна валюта."""
    if not isinstance(v, str):
        return None
    t = re.sub(r"[\s.]+", "", v).upper()
    if t in _ВАЛЮТЫ:
        return _ВАЛЮТЫ[t]
    коды, иное = коды_валют(v)
    одна = next(iter(коды)) if len(коды) == 1 and not иное else None
    if _КОД.match(t):
        return _ПСЕВДОНИМЫ.get(t) or (t if t in КОДЫ_ВАЛЮТ else одна or t)
    return одна


# ── вид значения для журнала ─────────────────────────────────────────────────────
#: Коды ошибок Excel — закрытый список: в журнал идёт только такой код, иной текст с «#» — нет.
ОШИБКИ_EXCEL = ("#NULL!", "#DIV/0!", "#VALUE!", "#REF!", "#NAME?", "#NUM!", "#N/A", "#SPILL!", "#CALC!",
                "#GETTING_DATA")
#: Корзины длины текста (знаков после сжатия пробелов) — порог таблицей (правило 4).
КОРЗИНЫ_ДЛИНЫ = ((3, "1–3"), (10, "4–10"), (30, "11–30"))
#: Корзины отклонения сверки (проверка 1).
КОРЗИНЫ_ОТКЛОНЕНИЯ = ((0.02, "до 2 %"), (0.1, "до 10 %"), (0.5, "до 50 %"))
#: Словарь подписей шаблона — закрытый: у текста, который не сошёлся, в вид идёт только СЧЁТ
#: его слов из словаря и иных, сами слова — нет: из обычных слов словаря («новая», «логистика»,
#: «код», «базис») складываются имена клиентов. Слова РАЗДЕЛЫ, ЗАГОЛОВКИ и подписи D4 и
#: обычные слова подписей расчёта.
СЛОВА_ШАБЛОНА = frozenset(
    w for текст in (*РАЗДЕЛЫ.values(), *ЗАГОЛОВКИ.values(), "Валюта подачи") for w in _слова(_норм_подписи(текст))
) | frozenset((
    "наименование", "артикул", "код", "производитель", "бренд", "позиция", "позиции", "номер", "количество", "шт",
    "ед", "изм", "сумма", "всего", "итог", "курс", "курсы", "валюте", "валюты", "клиента", "заказчика", "срок",
    "поставка", "доставка", "логистика", "таможня", "пошлина", "маржа", "наценка", "закупка", "продажа",
    "предложение", "коэффициент", "новая", "переторжки", "с", "в", "за", "и", "на", "по", "от", "до", "ндс",
    "%", "eur", "rub", "usd", "cny", "рубли", "рублях", "рубль", "руб",
))


def _корзина(x: float, корзины, иначе: str) -> str:
    return next((имя for порог, имя in корзины if x <= порог), иначе)


def _токены(t: str) -> list[str]:
    """Слова, числа и «%» нормализованной подписи."""
    return re.findall(r"[a-zа-я]+|\d+|%", _норм_подписи(t))


def _счёт(n: int) -> str:
    """Счёт для журнала — до 4, больше — «4+»."""
    return f"{min(n, 4)}{'+' if n > 4 else ''}"


def _слова_подписи(t: str) -> tuple[list[str], int]:
    """(слова словаря шаблона в порядке подписи, без повторов; счёт иных слов и чисел).
    Сами слова — только для счёта: в журнал они не идут."""
    свои, иных = [], 0
    for w in _токены(t):
        if w in СЛОВА_ШАБЛОНА:
            if w not in свои:
                свои.append(w)
        else:
            иных += 1
    return свои, иных


def вид_значения(v, *, формула: bool = False) -> str:
    """Вид значения ячейки — из закрытого списка, для журнала прогона. Текст ячейки в него
    не попадает: только код валюты из КОДЫ_ВАЛЮТ, код ошибки из ОШИБКИ_EXCEL, корзина длины
    и счёт слов словаря шаблона (СЛОВА_ШАБЛОНА) и иных — ни одного слова. формула — в ячейке
    формула (книга открыта второй раз без data_only): пустой кэш — «формула без кэша»."""
    if v is None:
        return "формула без кэша" if формула else "пусто"
    if isinstance(v, bool):
        return "логическое"
    if isinstance(v, (int, float)):
        return "число"
    if isinstance(v, (dt.datetime, dt.date, dt.time, dt.timedelta)):
        return "дата"
    if not isinstance(v, str):
        return "иное"
    s = re.sub(r"\s+", " ", unicodedata.normalize("NFKC", v)).strip()
    if not s:
        return "пусто"
    if s.upper() in ОШИБКИ_EXCEL:
        return f"ошибка формулы {s.upper()}"
    if s.startswith("#"):
        return "ошибка формулы"
    коды, иное = коды_валют(s)
    if _УЕ.search(_норм_подписи(s)):
        return "текст-у.е."
    if иное:
        return "текст-валюта-иная"
    if len(коды) > 1:
        return "текст-валюта-несколько"
    if коды:
        return f"текст-валюта:{next(iter(коды))}"
    if _КОД.match(re.sub(r"[\s.]+", "", s).upper()):
        return "текст-код вне списка"
    свои, иных = _слова_подписи(s)
    вид = f"текст-иное ({_корзина(len(s), КОРЗИНЫ_ДЛИНЫ, '>30')})"
    if свои:
        вид += f" · слов словаря шаблона {_счёт(len(свои))}" + (f" + иных {_счёт(иных)}" if иных else "")
    return вид


def _норм(v) -> str:
    return re.sub(r"\s+", " ", str(v if v is not None else "")).strip().lower().replace("ё", "е")


def _число(v) -> float | None:
    """Кэш ячейки → число; не число (пусто, текст, ошибка, да/нет) — None."""
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return None
    f = float(v)
    return f if math.isfinite(f) else None


def _пусто(v) -> bool:
    return v is None or (isinstance(v, str) and not v.strip())


def _ошибка(v) -> bool:
    """«нет курса», «#ДЕЛ/0!», «#VALUE!» и прочий текст там, где должно быть число."""
    return isinstance(v, str) and bool(v.strip())


def отклонение(a: float, b: float) -> float:
    """|a − b| относительно большего по модулю; оба ноль — 0."""
    m = max(abs(a), abs(b))
    return abs(a - b) / m if m else 0.0


@dataclass
class Итог:
    """Итог чтения файла. Числа заполнены, где их удалось посчитать; публикуются они
    только при status == СВЕРЕНО (scripts/realization_ctx.py)."""
    status: str
    sub_cur: str | None = None          # валюта подачи (D4)
    sale_sub: float | None = None       # продажа в валюте подачи, без НДС
    sale_eur: float | None = None       # продажа, € без НДС
    kp_sale_sub: float | None = None    # у переторжки — продажа «Нашего КП» в валюте подачи (AG2)
    purchase_eur: float | None = None   # закупка, € без НДС (Σ T)
    markup: float | None = None         # наценка над поставщиком: продажа / закупка − 1
    rebid: bool | None = None           # продажа — по переторжке
    items: int = 0                      # позиций (строк с количеством)
    coef_median: float | None = None    # медиана коэффициента позиций
    totals_dev: float | None = None     # наибольшее отклонение итога от суммы строк (проверка 1)
    bad_lines: int = 0                  # позиций с «нет курса» или ошибкой
    fx: dict[str, float] = field(default_factory=dict)   # единиц валюты подачи за 1 единицу валюты
    why: str = ""                       # где сломалось: адрес ячейки шаблона или имя проверки
    #                                     (закрытый вид — ограничение econ_file_reads_keys_chk)
    вид: str = ""                       # вид значения там, где не сошлось (вид_значения), или
    #                                     какая сверка не сошлась — только журналу, не в базу
    ячейка: str = ""                    # чей вид, когда why — не адрес («позиции»)
    sub_src: str | None = None          # откуда валюта подачи (ИСТОЧНИКИ_ВАЛЮТЫ)
    rate_src: str | None = None         # чем сверен курс валюты подачи (ИСТОЧНИКИ_КУРСА)
    сдвиг: int | None = None            # на сколько столбцов вправо сдвинут шаблон (None — не узнан)
    зонд: tuple[str, ...] = ()          # у нераспознанной D4 — признаки листа, только журналу

    @property
    def сверено(self) -> bool:
        return self.status == СВЕРЕНО


def _проверить_шаблон(ws) -> str:
    """Адрес первой ячейки, где подпись не та, или ''."""
    for кол, текст in РАЗДЕЛЫ.items():
        if _норм(ws[f"{кол}{СТРОКА_РАЗДЕЛОВ}"].value) != _норм(текст):
            return f"{кол}{СТРОКА_РАЗДЕЛОВ}"
    for кол, текст in ЗАГОЛОВКИ.items():
        if _норм(ws[f"{кол}{СТРОКА_ЗАГОЛОВКОВ}"].value) != _норм(текст):
            return f"{кол}{СТРОКА_ЗАГОЛОВКОВ}"
    return ""


def _курсы(ws, столбцы: tuple[str, str]) -> dict[str, float]:
    return {код: курс for код, (курс, _стр) in _курсы_по_строкам(ws, столбцы).items()}


def _курсы_по_строкам(ws, столбцы: tuple[str, str]) -> dict[str, tuple[float, int]]:
    """Валюта → (курс, строка таблицы); первая строка валюты — её."""
    out: dict[str, tuple[float, int]] = {}
    for стр in СТРОКИ_КУРСОВ:
        код = валюта(ws[f"{столбцы[0]}{стр}"].value)
        курс = _число(ws[f"{столбцы[1]}{стр}"].value)
        if код and курс and курс > 0:
            out.setdefault(код, (курс, стр))
    return out


def сторона_таблицы(sub: str, k_sub: float, таблица: dict[str, float]) -> str | None:
    """В какую сторону таблица подачи пишет курс: «за €» (единиц валюты за 1 €), «в €»
    (€ за 1 единицу) или None — её строка валюты подачи не сходится с k_sub ни так ни так
    (или строки нет)."""
    t = таблица.get(sub)
    if not t or k_sub <= 0:
        return None
    if отклонение(t, k_sub) <= ДОПУСК_КУРСА:
        return "за €"
    if отклонение(1 / t, k_sub) <= ДОПУСК_КУРСА:
        return "в €"
    return None


def курсы_в_подаче(sub: str, k_sub: float, таблица: dict[str, float],
                   по_строкам: dict[str, float]) -> dict[str, float]:
    """Сколько единиц валюты подачи стоит 1 единица валюты X — по курсам файла.

    k_sub — единиц валюты подачи за 1 € (продажа в валюте подачи / продажа в €, обе из
    файла). Таблица подачи (Z:AA) пишет курс в одну из двух сторон — «единиц за евро» или
    «евро за единицу»; сторона узнаётся по её же строке валюты подачи, сверенной с k_sub
    (ДОПУСК_КУРСА). Не сошлось ни так ни так — таблица не берётся. Для валюты подачи EUR
    сторону таблицы не узнать (курс 1 в обе), и берутся курсы строк оффера:
    по_строкам — € за единицу валюты оффера (медиана S/Q по позициям этой валюты)."""
    fx: dict[str, float] = {sub: 1.0}
    if k_sub > 0:
        fx.setdefault("EUR", k_sub)
    сторона = сторона_таблицы(sub, k_sub, таблица) if sub != "EUR" else None
    if сторона == "за €":
        for код, курс in таблица.items():
            fx.setdefault(код, k_sub / курс)
    elif сторона == "в €":
        for код, курс in таблица.items():
            fx.setdefault(код, k_sub * курс)
    for код, eur_за_единицу in по_строкам.items():
        if eur_за_единицу > 0 and k_sub > 0:
            fx.setdefault(код, eur_за_единицу * k_sub)
    return {к: round(v, 8) for к, v in fx.items() if v > 0 and math.isfinite(v)}


#: Курса валюты подачи нет ни в одной таблице файла — не «итоги не сходятся», а «нет курса».
НЕТ_СТРОКИ = "нет строки"


def сверить_курс(sub: str, k_sub: float, таблица: dict[str, tuple[float, int]],
                 поставщика: dict[str, tuple[float, int]] | None = None) -> tuple[str, str]:
    """(адрес, где курс валюты подачи из итогов файла — k_sub, единиц за 1 € — противоречит
    файлу или здравому смыслу, или ''; чем сверен — из ИСТОЧНИКИ_КУРСА, или НЕТ_СТРОКИ).

    Подача в евро — курс 1 (иначе D4). Иначе: валюты нет в полосах КУРС_ЗА_ЕВРО — сверять не
    с чем (D4); курс вне полосы — продажа в валюте подачи не в той валюте или курс вбит не в
    ту сторону (AG2); строка валюты подачи таблицы Z:AA не сходится с ним ни в одну сторону
    (ДОПУСК_КУРСА) — её адрес. Строки в Z:AA нет — строка таблицы поставщика K:L (те же курсы
    к евро на дату расчёта); не сошлась — её адрес. Нет ни там, ни там — (D4, НЕТ_СТРОКИ):
    курс берётся только из строки файла, не выдумывается."""
    if sub == "EUR":
        return ("", "евро") if отклонение(k_sub, 1.0) <= ДОПУСК_КУРСА else (ВАЛЮТА_ПОДАЧИ, "")
    полоса = КУРС_ЗА_ЕВРО.get(sub)
    if not полоса:
        return ВАЛЮТА_ПОДАЧИ, ""
    if not полоса[0] <= k_sub <= полоса[1]:
        return ИТОГ_ПРОДАЖИ_ПОДАЧИ, ""
    for столбцы, т, имя in ((КУРСЫ_ПОДАЧИ, таблица, "Z:AA"), (КУРСЫ_ПОСТАВЩИКА, поставщика or {}, "K:L")):
        if sub in т:
            курс, стр = т[sub]
            return ("", имя) if сторона_таблицы(sub, k_sub, {sub: курс}) else (f"{столбцы[1]}{стр}", "")
    return ВАЛЮТА_ПОДАЧИ, НЕТ_СТРОКИ


def _курс_не_сходится(sub: str, k_sub: float, таблица: dict[str, tuple[float, int]],
                      поставщика: dict[str, tuple[float, int]] | None = None) -> str:
    """Адрес, где курс валюты подачи не сверен (сверить_курс), или ''."""
    return сверить_курс(sub, k_sub, таблица, поставщика)[0]


def _вид_курса(sub: str, k_sub: float, таблица: dict[str, tuple[float, int]], где: str,
               поставщика: dict[str, tuple[float, int]] | None = None) -> str:
    """Почему курс валюты подачи не сверен — словами из закрытого списка (без курса)."""
    if sub == "EUR":
        return "подача в евро, а курс итогов (AG2 / AG1) не 1"
    if где == ИТОГ_ПРОДАЖИ_ПОДАЧИ:
        lo, hi = КУРС_ЗА_ЕВРО[sub]
        return (f"курс итогов {'ниже' if k_sub < lo else 'выше'} полосы"
                + (" · обратный курс — в полосе" if lo <= 1 / k_sub <= hi else ""))
    for столбцы, т in ((КУРСЫ_ПОДАЧИ, таблица), (КУРСЫ_ПОСТАВЩИКА, поставщика or {})):
        if sub in т and где == f"{столбцы[1]}{т[sub][1]}":
            t = т[sub][0]
            return ("строка таблицы против курса итогов: расхождение "
                    + _корзина(min(отклонение(t, k_sub), отклонение(1 / t, k_sub)), КОРЗИНЫ_ОТКЛОНЕНИЯ, "больше 50 %"))
    return ""


# ── v5: запасная валюта подачи, сдвиг шаблона, зонд ──────────────────────────────
def _валюта_ячейки(v) -> tuple[str, str] | None:
    """(код, «код» | «подпись») — ячейка ровно код валюты (подпись словаря _ВАЛЮТЫ или код из
    КОДЫ_ВАЛЮТ) или подпись шаблона с валютой: валюта ровно одна, иного нет, и каждое прочее
    слово — из словаря шаблона (СЛОВА_ШАБЛОНА; чисел нет). Иначе None: имя клиента «Новый
    рубль» — не подпись («новый» не из словаря). Код — только из КОДЫ_ВАЛЮТ."""
    if not isinstance(v, str) or not v.strip():
        return None
    t = re.sub(r"[\s.]+", "", unicodedata.normalize("NFKC", v)).upper()
    if t in _ВАЛЮТЫ:
        return _ВАЛЮТЫ[t], "код"
    if t in КОДЫ_ВАЛЮТ:
        return _ПСЕВДОНИМЫ.get(t, t), "код"
    коды, иное = коды_валют(v)
    if иное or len(коды) != 1:
        return None
    for w in _токены(v):
        if w not in СЛОВА_ШАБЛОНА and not коды_валют(w)[0]:
            return None
    return next(iter(коды)), "подпись"


def _подписи_с_валютой(ws, адреса) -> set[str]:
    """Коды валют подписей шаблона в ячейках адреса (_валюта_ячейки)."""
    return {в[0] for a in адреса if (в := _валюта_ячейки(ws[a].value))}


def _валюта_AE(ws) -> tuple[str | None, str]:
    """(код, состояние) столбца AE «Валюта подачи» у позиций (строк с количеством): код —
    только если у ВСЕХ позиций AE — одна и та же валюта. Состояние — для вида и зонда, из
    закрытого списка: «нет позиций», «пусто», «пусто у части позиций», «не валюта» (у
    позиции AE не пуст и не валюта: формула =$D$4 при пустой D4 кэширует 0), «несколько
    валют», код из КОДЫ_ВАЛЮТ или «код вне списка»."""
    коды: set[str] = set()
    позиций = пустых = иных = 0
    for стр in range(ПЕРВАЯ, ПОСЛЕДНЯЯ + 1):
        кол = _число(ws[f"G{стр}"].value)
        if not кол or кол <= 0:
            continue
        позиций += 1
        v = ws[f"AE{стр}"].value
        if _пусто(v):
            пустых += 1
        elif (к := валюта(v)):
            коды.add(к)
        else:
            иных += 1
    if not позиций:
        return None, "нет позиций"
    if иных:
        return None, "не валюта"
    if len(коды) > 1:
        return None, "несколько валют"
    if пустых:
        return None, "пусто" if пустых == позиций else "пусто у части позиций"
    код = next(iter(коды))
    return код, _код_журнала(код)


def _код_журнала(код: str | None) -> str:
    """Код для журнала — только из КОДЫ_ВАЛЮТ; иной — «код вне списка»."""
    return код if код in КОДЫ_ВАЛЮТ else "код вне списка"


def _курс_итогов(ws) -> float | None:
    """AG2 / AG1 — единиц валюты подачи за 1 € по итогам «Нашего КП»; не числа — None."""
    ag1, ag2 = _число(ws[ИТОГ_ПРОДАЖИ_EUR].value), _число(ws[ИТОГ_ПРОДАЖИ_ПОДАЧИ].value)
    return ag2 / ag1 if ag1 and ag2 and ag1 > 0 and ag2 > 0 else None


def _позиции(ws) -> list[int]:
    """Строки позиций — с количеством больше нуля в G."""
    return [стр for стр in range(ПЕРВАЯ, ПОСЛЕДНЯЯ + 1) if (кол := _число(ws[f"G{стр}"].value)) and кол > 0]


#: Ссылка на ячейку в формуле: столбец и строка (с $ или без); имя функции перед «(» и имя
#: листа перед «!» — не ссылка (их отсекает _формула_AF до разбора ссылок).
_ССЫЛКА = re.compile(r"(?<![A-Z0-9_.$])\$?([A-Z]{1,3})\$?([0-9]{1,7})(?![0-9A-Z_(])")
#: AE позиции по шаблону следует D4: «=D4», «=$D$4» — и ничего больше.
_ОТ_D4 = re.compile(r"^=\s*\$?D\$?4\s*$")


def _формула_AE(ws, формулы, строки: list[int]) -> str:
    """Состояние AE позиций для пути «формула AF» и зонда — закрытый список: «от D4» (у ВСЕХ
    позиций формула =D4 и кэш пуст или 0 — D4 пуста), «нет» (ни у одной не формула), «иная»."""
    if not строки:
        return "нет позиций"
    тексты = [формулы(f"AE{стр}") for стр in строки]
    if all(t is None for t in тексты):
        return "нет"
    if all(t is not None and _ОТ_D4.match(t.upper()) and (ws[f"AE{стр}"].value in (None, "", 0))
           for t, стр in zip(тексты, строки)):
        return "от D4"
    return "иная"


def _формула_AF(формулы, строки: list[int]) -> tuple[int | None, str]:
    """(строка таблицы подачи Z:AA, состояние) — по формуле AF ВСЕХ позиций: AF — цена в
    валюте подачи, по шаблону — AC своей строки, умноженная (или делённая) на курс строки
    таблицы подачи. Строка берётся, только если каждая формула AF ссылается ровно на две
    ячейки — AC своей строки и одну и ту же AA5…AA9 — без диапазонов, поиска по таблице и
    иных листов. Состояние — закрытый список: «ссылка на строку Z:AA», «нет позиций», «не
    формула», «поиск или иной лист», «ссылки иные», «разные строки»."""
    if not строки:
        return None, "нет позиций"
    найдено: set[int] = set()
    for стр in строки:
        t = формулы(f"AF{стр}")
        if t is None:
            return None, "не формула"
        t = t.upper()
        if "!" in t or ":" in t:
            return None, "поиск или иной лист"
        ссылки = {(м.group(1), int(м.group(2))) for м in _ССЫЛКА.finditer(t)}
        курсы = {n for к, n in ссылки if к == КУРСЫ_ПОДАЧИ[1] and n in СТРОКИ_КУРСОВ}
        if len(курсы) != 1 or ссылки != {("AC", стр), (КУРСЫ_ПОДАЧИ[1], next(iter(курсы)))}:
            return None, "ссылки иные"
        найдено |= курсы
    if len(найдено) != 1:
        return None, "разные строки"
    return next(iter(найдено)), "ссылка на строку Z:AA"


def _валюта_по_формуле(ws, формулы, подпись: str | None) -> tuple[str | None, str]:
    """Путь «формула AF» (AE позиций следует пустой D4): (код, '') или (None, почему).

    Первый способ — устройство шаблона: AF всех позиций = AC × курс одной строки таблицы
    подачи (_формула_AF), подпись этой строки (Z) — валюта X кроме евро, и X называет ещё
    кто-то второй: подпись итога AG2 или строка X таблицы поставщика K:L (одна подпись Z —
    один источник: полоса RUB от TRY не отличит). Второй способ — число: курс итогов AG2 / AG1
    лежит в полосе КУРС_ЗА_ЕВРО валюты X (полоса — знание вне файла), сходится с курсом этой
    строки (AA) в одну из сторон и со строкой X в K:L, а ни с одной строкой иной валюты таблиц
    не сходится (_двойник). Евро так не узнаётся: у него курс 1, и формула его не называет."""
    строки = _позиции(ws)
    ae = _формула_AE(ws, формулы, строки)
    if ae != "от D4":
        return None, f"формула AE: {ae}"
    n, af = _формула_AF(формулы, строки)
    if n is None:
        return None, f"формула AF: {af}"
    код = валюта(ws[f"{КУРСЫ_ПОДАЧИ[0]}{n}"].value)
    курс = _число(ws[f"{КУРСЫ_ПОДАЧИ[1]}{n}"].value)
    if not код or код == "EUR" or код not in КУРС_ЗА_ЕВРО or not курс or курс <= 0:
        return None, "формула AF: строка Z:AA не валюта с полосой курса"
    if подпись and подпись != код:
        return None, "формула AF: источники расходятся"
    k = _курс_итогов(ws)
    if k is None:
        return None, "формула AF: курса итогов нет (AG1 или AG2 не число)"
    lo, hi = КУРС_ЗА_ЕВРО[код]
    if not lo <= k <= hi or not сторона_таблицы(код, k, {код: курс}):
        return None, "формула AF: курс итогов не сверен"
    # курс строки AA формула AF и так даёт итогам; независимая от неё цифра файла — строка той же
    # валюты в таблице поставщика K:L (курсы к евро на ту же дату): есть — не должна спорить
    z, kl = _курсы_по_строкам(ws, КУРСЫ_ПОДАЧИ), _курсы_по_строкам(ws, КУРСЫ_ПОСТАВЩИКА)
    if код in kl and not сторона_таблицы(код, k, {код: kl[код][0]}):
        return None, "формула AF: строка K:L против курса итогов"
    if _двойник(код, k, z, kl):
        return None, f"формула AF: {ДВОЙНИК}"
    # валюту называет подпись Z строки — одна ячейка; полоса RUB от TRY и INR, USD от CHF не
    # отличает, а AA — тот самый курс формулы. Второй, кто назовёт ту же валюту: подпись итога
    # AG2 или строка той же валюты в K:L, сошедшаяся с курсом итогов. Нет ни той ни другой — нет
    if подпись != код and код not in kl:
        return None, "формула AF: валюту называет одна подпись Z"
    return код, ""


#: Курс итогов сходится не только со строкой своей валюты: число её не подтверждает.
ДВОЙНИК = "курс итогов сходится и с иной валютой таблиц"


def _двойник(код: str, k: float, z: dict, kl: dict) -> bool:
    """Курс итогов k сходится (в любую сторону, ДОПУСК_КУРСА) со строкой иной валюты таблиц
    Z:AA или K:L — число валюту не различает (устаревшая подпись строки, доллар и франк около
    одного курса, евро и доллар около 1)."""
    return any(к != код and сторона_таблицы(к, k, {к: курс}) for т in (z, kl) for к, (курс, _с) in т.items())


def валюта_запасная(ws, формулы=None) -> tuple[str | None, str | None, str]:
    """D4 пуста → (код, источник из ИСТОЧНИКИ_ВАЛЮТЫ, '') или (None, None, почему).

    Первый способ — текст шаблона: AE «Валюта подачи» у всех позиций (_валюта_AE; без неё
    разбор и при D4 — «не распознана»); подпись итога AG2 (ПОДПИСИ_AG2), если называет
    валюту, — та же. Второй — число: курс итогов AG2 / AG1 сверен с
    файлом (сверить_курс: полоса и строка Z:AA или K:L; у евро — 1), и ни одна иная валюта
    таблиц файла не стоит рядом с этим курсом (_двойник: доллар около 1 у евро, устаревшая
    подпись строки — рубль и лира при одном курсе). AE не
    валюта, а формула =D4 у всех позиций — путь «формула AF» (_валюта_по_формуле; формулы —
    текст формулы ячейки по адресу, книга открыта второй раз). Почему не вышло — словами из
    закрытого списка, коды — из КОДЫ_ВАЛЮТ."""
    ae, ae_вид = _валюта_AE(ws)
    подписи = _подписи_с_валютой(ws, ПОДПИСИ_AG2)
    подпись = next(iter(подписи)) if len(подписи) == 1 else None
    сказано = (f"запасной путь — AE: {ae_вид} · подпись AG2: "
               + (_код_журнала(подпись) if подпись else "несколько валют" if подписи else "нет"))
    if len(подписи) > 1 or (ae and подпись and ae != подпись):
        return None, None, f"{сказано} · источники расходятся"
    код = ae
    if not код:
        # AF и AG — в валюте подачи позиции (AE): без неё и при D4 разбор дальше не идёт, и
        # одной подписи AG2 не хватает — она лишь подтверждает AE. AE следует пустой D4
        # формулой — валюту называет формула AF (строка таблицы подачи), а сверяет число
        if формулы is None or ae_вид not in ("не валюта", "пусто"):
            return None, None, сказано
        код, почему = _валюта_по_формуле(ws, формулы, подпись)
        if not код:
            return None, None, f"{сказано} · {почему}"
        return код, ("формула AF, Z:AA и подпись AG2" if подпись else "формула AF, Z:AA и K:L"), ""
    k = _курс_итогов(ws)
    if k is None:
        return None, None, f"{сказано} · курса итогов нет (AG1 или AG2 не число)"
    z, kl = _курсы_по_строкам(ws, КУРСЫ_ПОДАЧИ), _курсы_по_строкам(ws, КУРСЫ_ПОСТАВЩИКА)
    где, _чем = сверить_курс(код, k, z, kl)
    if где:
        return None, None, f"{сказано} · курс итогов не сверен"
    if _двойник(код, k, z, kl):
        return None, None, f"{сказано} · {ДВОЙНИК}"
    return код, ("AE и подпись AG2" if подпись else "AE"), ""


class _Пустая:
    value = None


class Сдвинутый:
    """Лист в адресах шаблона, когда весь шаблон стоит на d столбцов правее: ws["D4"] — E4."""

    def __init__(self, ws, d: int):
        self.ws, self.d = ws, d
        self.parent = getattr(ws, "parent", None)

    def адрес(self, адрес: str) -> str | None:
        м = _АДРЕС.match(адрес)
        n = _столбец(м.group(1)) + self.d if м else 0
        return f"{_буквы(n)}{м.group(2)}" if n >= 1 else None

    def __getitem__(self, адрес: str):
        a = self.адрес(адрес)
        return self.ws[a] if a else _Пустая()


def _подписей_на_месте(ws) -> int:
    """Сколько подписей разделов (строка 11) и заголовков (строка 12) шаблона на месте."""
    return (sum(_норм(ws[f"{к}{СТРОКА_РАЗДЕЛОВ}"].value) == _норм(т) for к, т in РАЗДЕЛЫ.items())
            + sum(_норм(ws[f"{к}{СТРОКА_ЗАГОЛОВКОВ}"].value) == _норм(т) for к, т in ЗАГОЛОВКИ.items()))


def найти_шаблон(ws) -> tuple[object, int | None, str]:
    """(лист в адресах шаблона, сдвиг, где не сошлось). Подписи на месте — (ws, 0, '').
    Иначе — сдвиг из СДВИГИ, у которого на месте ВСЕ подписи разделов и заголовков
    (_проверить_шаблон сдвинутого листа пуст); нет такого — (ws, None, адрес первой
    несошедшейся подписи)."""
    где = _проверить_шаблон(ws)
    if not где:
        return ws, 0, ""
    for d in СДВИГИ:
        лист = Сдвинутый(ws, d)
        if not _проверить_шаблон(лист):
            return лист, d, ""
    return ws, None, где


_ЯКОРЯ = frozenset({(СТРОКА_РАЗДЕЛОВ, к) for к in РАЗДЕЛЫ} | {(СТРОКА_ЗАГОЛОВКОВ, к) for к in ЗАГОЛОВКИ}
                   | {(СТРОКА_ЗАГОЛОВКОВ, ЦЕНА_ПЕРЕТОРЖКИ)})


def зонд_валюты(ws, формулы=None) -> tuple[str, ...]:
    """Признаки листа у нераспознанной D4 — для журнала прогона (гистограмма по файлам):
    адреса A1:AP15 и номера листов книги, где ячейка (имя листа) — код валюты или подпись
    шаблона с валютой («E3:RUB», «AF2:подпись:RUB», «лист 2:RUB»); сколько валют в таблицах
    Z:AA и K:L и сколько кроме евро; валюта подписей итогов AG1 и AG2; состояние AE и (если
    формулы известны) формул AE и AF — _формула_AE, _формула_AF, у ссылки — код строки (на
    сдвинутом листе — «формулы: лист сдвинут»: формулы там в настоящих адресах); валюты, в
    полосу которых попадает курс итогов AG2 / AG1, и с какой строкой Z:AA он сходится. Только
    адреса шаблона, коды из КОДЫ_ВАЛЮТ, счёт и слова закрытого списка — ни текста, ни чисел."""
    out: list[str] = []
    for стр in range(1, ЗОНД_СТРОК + 1):
        for n in range(1, ЗОНД_СТОЛБЦОВ + 1):
            a = f"{_буквы(n)}{стр}"
            if (стр, _буквы(n)) in _ЯКОРЯ:
                continue                 # подписи шаблона строк 11 и 12 («…, евро») — сверены и так
            if (в := _валюта_ячейки(ws[a].value)) and в[0] in КОДЫ_ВАЛЮТ:
                out.append(f"{a}:{в[0]}" if в[1] == "код" else f"{a}:подпись:{в[0]}")
    книга = getattr(ws, "parent", None)
    for i, имя in enumerate(getattr(книга, "sheetnames", None) or (), 1):
        if (в := _валюта_ячейки(имя)) and в[0] in КОДЫ_ВАЛЮТ:
            out.append(f"лист {i}:{в[0]}" if в[1] == "код" else f"лист {i}:подпись:{в[0]}")
    z, kl = _курсы_по_строкам(ws, КУРСЫ_ПОДАЧИ), _курсы_по_строкам(ws, КУРСЫ_ПОСТАВЩИКА)
    for имя, т in (("Z:AA", z), ("K:L", kl)):
        out.append(f"{имя}: валют {_счёт(len(т))}, кроме EUR {_счёт(sum(1 for к in т if к != 'EUR'))}")
    for имя, адреса in (("AG1", ПОДПИСИ_AG1), ("AG2", ПОДПИСИ_AG2)):
        коды = sorted({_код_журнала(к) for к in _подписи_с_валютой(ws, адреса)})
        out.append(f"подпись {имя}: {' '.join(коды) or 'нет'}")
    out.append(f"AE: {_валюта_AE(ws)[1]}")
    if формулы is not None and isinstance(ws, Сдвинутый):
        # формулы сдвинутого листа ссылаются на настоящие адреса (=$E$4, AD13*$AB$6): сверка с
        # адресами шаблона показала бы «иная» там, где устройство то же, — не меряется
        out.append("формулы: лист сдвинут")
    elif формулы is not None:
        # устройство формул позиций (путь «формула AF»): только состояние и код строки Z:AA
        строки = _позиции(ws)
        out.append(f"формула AE: {_формула_AE(ws, формулы, строки)}")
        n, af = _формула_AF(формулы, строки)
        if n is None:
            out.append(f"формула AF: {af}")
        else:
            код = валюта(ws[f"{КУРСЫ_ПОДАЧИ[0]}{n}"].value)
            out.append(f"формула AF: {af}:{_код_журнала(код) if код else 'не валюта'}")
    k = _курс_итогов(ws)
    if k is None:
        out.append("курс итогов AG2/AG1: нет")
    else:
        полосы = sorted(к for к, (lo, hi) in КУРС_ЗА_ЕВРО.items() if lo <= k <= hi)
        if отклонение(k, 1.0) <= ДОПУСК_КУРСА:
            полосы = ["EUR", *полосы]
        out.append(f"курс итогов AG2/AG1 в полосе: {' '.join(полосы) or 'ни одной'}")
        сошлись = sorted({_код_журнала(к) for к, (курс, _с) in z.items()
                          if к != "EUR" and сторона_таблицы(к, k, {к: курс})})
        out.append(f"курс итогов сходится со строкой Z:AA: {' '.join(сошлись) or 'нет'}")
    return tuple(dict.fromkeys(out))


def разобрать(b: bytes) -> Итог:
    """Байты xlsx → Итог. Файл не трогается: только чтение кэша значений."""
    try:
        ws = _открыть(b, data_only=True).worksheets[ЛИСТ]
    except Exception:                                    # noqa: BLE001 — любой отказ открыть
        return Итог(НЕ_ОТКРЫЛСЯ)
    return разобрать_лист(ws, формулы=_Формулы(b))


def _открыть(b: bytes, data_only: bool):
    """Книга из байтов — без предупреждений openpyxl: они печатают в stderr (публичный журнал
    прогона) содержимое файла — число ячейки с форматом даты, имя листа, значение имени,
    имя свойства документа."""
    import openpyxl
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return openpyxl.load_workbook(io.BytesIO(b), data_only=data_only)


class _Формулы:
    """Текст формулы ячейки по адресу или None — вторым открытием книги без data_only, один
    раз и только если спросили (вид значения у ячейки с пустым кэшем, путь «формула AF» и
    зонд у нераспознанной D4). Текст формулы наружу не идёт: по нему узнаются лишь ссылки."""

    def __init__(self, b: bytes):
        self.b, self.ws, self.открыта = b, None, None

    def __call__(self, адрес: str) -> str | None:
        if self.открыта is None:
            try:
                self.ws = _открыть(self.b, data_only=False).worksheets[ЛИСТ]
                self.открыта = True
            except Exception:                            # noqa: BLE001 — формула не важнее чтения
                self.открыта = False
        if not self.открыта:
            return None
        try:
            v = self.ws[адрес].value
        except Exception:                                # noqa: BLE001
            return None
        if isinstance(v, str) and v.startswith("="):
            return v
        if type(v).__name__ in ("ArrayFormula", "DataTableFormula"):
            t = getattr(v, "text", None)
            return t if isinstance(t, str) and t.startswith("=") else "="
        return None


_АДРЕС = re.compile(r"^([A-Z]{1,3})(\d+)$")


def _столбец(буквы: str) -> int:
    n = 0
    for ch in буквы:
        n = n * 26 + ord(ch) - 64
    return n


def _буквы(n: int) -> str:
    s = ""
    while n:
        n, r = divmod(n - 1, 26)
        s = chr(65 + r) + s
    return s


#: Ячейки рядом с D4 — где искать валюту подачи, когда D4 её не дал (шаблон сдвинут):
#: строка 4 до ±3 столбцов, столбец D до ±2 строк; ближние — первыми.
РЯДОМ_С_D4 = ("E4", "C4", "F4", "B4", "G4", "A4", "D3", "D5", "D2", "D6")


def _подпись_на_месте(адрес: str):
    """(проверка подписи шаблона в ячейке адреса, текст ожидаемой подписи) — строки 11 и 12;
    у AP12 — смысл («цена…»); иначе None."""
    м = _АДРЕС.match(адрес)
    if not м:
        return None
    кол, стр = м.group(1), int(м.group(2))
    if стр == СТРОКА_РАЗДЕЛОВ and кол in РАЗДЕЛЫ:
        return (lambda v: _норм(v) == _норм(РАЗДЕЛЫ[кол])), РАЗДЕЛЫ[кол]
    if стр == СТРОКА_ЗАГОЛОВКОВ and кол in ЗАГОЛОВКИ:
        return (lambda v: _норм(v) == _норм(ЗАГОЛОВКИ[кол])), ЗАГОЛОВКИ[кол]
    if стр == СТРОКА_ЗАГОЛОВКОВ and кол == ЦЕНА_ПЕРЕТОРЖКИ:
        return (lambda v: bool(ПОДПИСЬ_AP.match(_норм(v)))), "Цена"
    return None


def _вид_ячейки(ws, адрес: str, формула) -> str:
    v = ws[адрес].value
    return вид_значения(v, формула=bool(v is None and формула and формула(адрес)))


def _вид_сбоя(ws, итог: Итог, формула) -> str:
    """Вид значения там, где не сошлось, — для журнала. У подписи шаблона — ещё сколько слов
    ожидаемой подписи в ячейке (переименована или другая) и столбец рядом (±3), где стоит
    ожидаемая подпись: шаблон сдвинут, а не другой. У нераспознанной D4 — адрес ячейки рядом
    (РЯДОМ_С_D4), где валюта есть. У D4 при несверенном курсе — есть ли полоса КУРС_ЗА_ЕВРО
    и строка таблицы Z:AA (коды — только из КОДЫ_ВАЛЮТ, иных — счёт). Наружу — только
    адреса шаблона, коды из списков и числа: ни слова из ячеек."""
    по_адресу = bool(_АДРЕС.match(итог.why or ""))
    адрес = итог.why if по_адресу else итог.ячейка
    if not адрес:
        return итог.вид
    вид = _вид_ячейки(ws, адрес, формула)
    if итог.вид:
        # why — не адрес («позиции»): «столбец AM: пусто»; адрес — почему не сошлось после вида
        вид = f"{вид} · {итог.вид}" if по_адресу else f"{итог.вид}: {вид}"
    на_месте = _подпись_на_месте(адрес)
    if на_месте:
        подпись, ожидаемая = на_месте
        ожид = set(_токены(ожидаемая))
        вид += f" · слов ожидаемой подписи {len(ожид & set(_токены(str(ws[адрес].value or ''))))} из {len(ожид)}"
        м = _АДРЕС.match(адрес)
        кол, стр = _столбец(м.group(1)), int(м.group(2))
        сдвиг = next((d for d in (-1, 1, -2, 2, -3, 3) if кол + d >= 1
                      and подпись(ws[f"{_буквы(кол + d)}{стр}"].value)), None)
        вид += f" · ожидаемая подпись — в столбце {сдвиг:+d}" if сдвиг else " · ожидаемой подписи рядом нет"
        if итог.status == ШАБЛОН_ДРУГОЙ and ЦЕНА_ПЕРЕТОРЖКИ not in адрес:
            # сдвиг читается, только если на столбец правее стоят ВСЕ подписи: счёт — чтобы
            # видеть, сдвинут ли шаблон целиком или переехала одна подпись
            всего = len(РАЗДЕЛЫ) + len(ЗАГОЛОВКИ)
            вид += f" · подписей на месте {_подписей_на_месте(ws)} из {всего}" + "".join(
                f" · со сдвигом {d:+d} — {_подписей_на_месте(Сдвинутый(ws, d))} из {всего}" for d in СДВИГИ)
    if адрес == ВАЛЮТА_ПОДАЧИ and итог.status == НЕТ_ВАЛЮТЫ:
        рядом = next((a for a in РЯДОМ_С_D4 if валюта(ws[a].value)), None)
        вид += f" · валюта — рядом, в {рядом}" if рядом else " · валюты рядом нет"
    if адрес == ВАЛЮТА_ПОДАЧИ and итог.status in (ИТОГИ_НЕ_СХОДЯТСЯ, НЕТ_КУРСА) and итог.sub_cur:
        вид += f" · полоса курса {'есть' if итог.sub_cur in КУРС_ЗА_ЕВРО else 'нет'}"
        for имя, столбцы in (("Z:AA", КУРСЫ_ПОДАЧИ), ("K:L", КУРСЫ_ПОСТАВЩИКА)):
            таблица = _курсы_по_строкам(ws, столбцы)
            свои = sorted(к for к in таблица if к in КОДЫ_ВАЛЮТ)
            вид += (f" · строка валюты подачи в {имя} {'есть' if итог.sub_cur in таблица else 'нет'}"
                    f" · {имя}: {' '.join(свои) or 'нет'}" + (f" (+ вне списка {len(таблица) - len(свои)})"
                                                             if len(таблица) > len(свои) else ""))
    столбец_строк = {ИТОГ_ЗАКУПКИ: "T", ИТОГ_ПРОДАЖИ_EUR: "AD", ИТОГ_ПРОДАЖИ_ПОДАЧИ: "AG"}.get(адрес)
    if столбец_строк and итог.status == НЕТ_КУРСА and _ошибка(ws[адрес].value):
        # ошибка в итоге — от ошибки в строке его столбца (СУММ(T13:T1007) и т. п.): счёт
        n = sum(1 for стр in range(ПЕРВАЯ, ПОСЛЕДНЯЯ + 1) if _ошибка(ws[f"{столбец_строк}{стр}"].value))
        вид += f" · ошибок в строках столбца {столбец_строк}: {_счёт(n)}"
    return вид


def разобрать_лист(ws, формула=None, формулы=None) -> Итог:
    """Лист → Итог; у несверенного — вид значения там, где не сошлось (Итог.вид). формула(адрес)
    — есть ли в ячейке формула, формулы(адрес) — её текст или None (разобрать открывает книгу
    второй раз), иначе не узнать. Текст формулы — только для разбора: наружу — состояния."""
    if формулы is not None and формула is None:
        формула = lambda адрес: формулы(адрес) is not None   # noqa: E731
    лист, сдвиг, где = найти_шаблон(ws)
    ф, фт = формула, формулы
    if сдвиг:
        # формула ячейки — по настоящему адресу сдвинутого листа
        def _настоящий(адрес):
            return лист.адрес(адрес)
        if формула:
            def ф(адрес):
                return bool(н := _настоящий(адрес)) and формула(н)
        if формулы:
            def фт(адрес):
                return формулы(н) if (н := _настоящий(адрес)) else None
    if где:
        итог = Итог(ШАБЛОН_ДРУГОЙ, why=где)
    else:
        sub, источник, почему = валюта_подачи(лист, сдвиг, исходный=ws, формулы=фт)
        итог = (_разобрать_лист(лист, sub, ae_по_D4=источник in _ПУТИ_ФОРМУЛЫ) if sub
                else Итог(НЕТ_ВАЛЮТЫ, why=ВАЛЮТА_ПОДАЧИ, вид=почему))
        итог.сдвиг, итог.sub_src = сдвиг, (источник if sub else None)
    if not итог.сверено:
        try:
            итог.вид = _вид_сбоя(лист, итог, ф)
        except Exception:                                # noqa: BLE001 — вид не важнее чтения
            итог.вид = "вид не определён"
        if итог.сдвиг:
            итог.вид = (f"{итог.вид} · " if итог.вид else "") + f"шаблон сдвинут на столбец {итог.сдвиг:+d}"
        if итог.status == НЕТ_ВАЛЮТЫ and итог.why == ВАЛЮТА_ПОДАЧИ:
            try:
                итог.зонд = зонд_валюты(лист, фт)
            except Exception:                            # noqa: BLE001 — зонд не важнее чтения
                итог.зонд = ("зонд не определён",)
    return итог


def валюта_подачи(ws, сдвиг: int | None = 0, исходный=None, формулы=None) -> tuple[str | None, str | None, str]:
    """(код, источник, почему нет) валюты подачи листа в адресах шаблона. D4 — первой; пуста —
    запасной путь (валюта_запасная: текст шаблона и курс итогов — два способа), но только на
    несдвинутом листе: догадка о валюте поверх догадки о сдвиге — нет. Текст в D4, не
    валюта, — D4 говорит иное: «не распознана» без запасного пути.

    Сдвинутый лист (исходный — тот же лист без сдвига): столбец вставлен где-то между A и G
    (подпись G12 сдвинута со всеми), и D4 сдвинута, только если вставлен левее D. Сдвинутая
    D4 пуста, а на месте, в D4 листа, — валюта: столбец вставлен правее D, валюта — оттуда
    («D4 вне сдвига»). Это не запасной путь: валюту называет сама D4, а сверяют её, как у
    всякой D4, AE каждой позиции (сдвинутые) и курс итогов."""
    d4 = ws[ВАЛЮТА_ПОДАЧИ].value
    if (sub := валюта(d4)):
        return sub, "D4", ""
    if not _пусто(d4):
        return None, None, ""
    if сдвиг:
        if исходный is not None and (sub := валюта(исходный[ВАЛЮТА_ПОДАЧИ].value)):
            return sub, "D4 вне сдвига", ""
        return None, None, "запасной путь — не на сдвинутом листе"
    return валюта_запасная(ws, формулы)


#: Пути, где AE позиций следует пустой D4 формулой (валюта — из формулы AF и строки Z:AA).
_ПУТИ_ФОРМУЛЫ = ("формула AF, Z:AA и K:L", "формула AF, Z:AA и подпись AG2")


def _разобрать_лист(ws, sub: str, ae_по_D4: bool = False) -> Итог:
    """Лист в адресах шаблона (подписи сверены) и валюта подачи → Итог. ae_по_D4 — валюта
    подачи из формулы AF (_валюта_по_формуле): у всех позиций AE — формула =D4 при пустой D4,
    и валюту позиции она не называет; сверено это там же."""
    итоги = {a: ws[a].value for a in (ИТОГ_ЗАКУПКИ, ИТОГ_ПРОДАЖИ_EUR, ИТОГ_ПРОДАЖИ_ПОДАЧИ)}
    for адрес, v in итоги.items():
        if v is None:
            return Итог(НЕТ_ЗНАЧЕНИЙ, sub_cur=sub, why=адрес)
    for адрес, v in итоги.items():
        if _число(v) is None:
            return Итог(НЕТ_КУРСА, sub_cur=sub, why=адрес)
    r1, ag1, ag2 = (_число(итоги[a]) for a in (ИТОГ_ЗАКУПКИ, ИТОГ_ПРОДАЖИ_EUR, ИТОГ_ПРОДАЖИ_ПОДАЧИ))

    позиции: list[dict] = []
    плохих = 0
    первая_плохая = ""                   # ячейка первой «нет курса» или ошибки — для вида в журнале
    for стр in range(ПЕРВАЯ, ПОСЛЕДНЯЯ + 1):
        g = ws[f"G{стр}"].value
        if _ошибка(g) and _ОШИБКА.search(g):
            плохих += 1
            первая_плохая = первая_плохая or f"G{стр}"
            continue
        кол = _число(g)
        if not кол or кол <= 0:
            continue
        позиции.append({к: ws[f"{к}{стр}"].value
                        for к in ("P", "Q", "S", "T", "Z", "AC", "AD", "AE", "AF", "AG", "AK", "AL", "AM", "AN",
                                  "AP")}
                       | {"G": кол, "стр": стр})
    if not позиции and not плохих:
        return Итог(НЕТ_СТРОК, sub_cur=sub)

    # переторжка: хоть у одной позиции заполнены AK или AL (правило владельца: «если
    # заполнена»). AM, AN и AP тогда — в «нужны»: ошибка в них (скидка текстом «10 %» →
    # #VALUE!) — «нет курса или ошибка», а не «Наше КП» вместо переторжки
    переторжка = any(not _пусто(p["AK"]) or not _пусто(p["AL"]) for p in позиции)
    # при пустых AK и AL формула шаблона даёт AM = ОКРВВЕРХ(AL·S) = 0: не ноль или ошибка в AM
    # или AN — цену переторжки вписали руками поверх формулы; переторжка есть, но не по шаблону
    руками = any(_пусто(p["AK"]) and _пусто(p["AL"])
                 and (bool(_число(p["AM"]) or _число(p["AN"])) or _ошибка(p["AM"]) or _ошибка(p["AN"]))
                 for p in позиции)
    if переторжка and not ПОДПИСЬ_AP.match(_норм(ws[f"{ЦЕНА_ПЕРЕТОРЖКИ}{СТРОКА_ЗАГОЛОВКОВ}"].value)):
        return Итог(ШАБЛОН_ДРУГОЙ, sub_cur=sub, items=len(позиции), rebid=True,
                    why=f"{ЦЕНА_ПЕРЕТОРЖКИ}{СТРОКА_ЗАГОЛОВКОВ}")
    нужны = ["S", "T", "AC", "AD", "AF", "AG"] + (["AM", "AN", "AP"] if переторжка else [])
    for p in позиции:
        if (к := next((к for к in нужны if p[к] is None), None)):
            return Итог(НЕТ_ЗНАЧЕНИЙ, sub_cur=sub, items=len(позиции), rebid=переторжка, why="позиции",
                        вид=f"столбец {к}", ячейка=f"{к}{p['стр']}")
    for p in позиции:
        if (к := next((к for к in нужны + ["Z"] if _ошибка(p[к]) or (к in нужны and _число(p[к]) is None)),
                      None)):
            плохих += 1
            первая_плохая = первая_плохая or f"{к}{p['стр']}"
    if плохих:
        return Итог(НЕТ_КУРСА, sub_cur=sub, items=len(позиции), rebid=переторжка, bad_lines=плохих,
                    why="позиции", вид=f"столбец {_АДРЕС.match(первая_плохая).group(1)}", ячейка=первая_плохая)
    # AF и AG — в валюте подачи позиции (AE): не та, что D4, или пусто — в какой валюте
    # продажа, не сказать
    for p in позиции:
        if валюта(p["AE"]) != sub and not (ae_по_D4 and p["AE"] in (None, "", 0)):
            return Итог(НЕТ_ВАЛЮТЫ, sub_cur=sub, items=len(позиции), rebid=переторжка, why=f"AE{p['стр']}")
    if руками or (переторжка and not all(not _пусто(p["AK"]) or not _пусто(p["AL"]) for p in позиции)):
        # у позиции без AK и AL формула даёт AM = AL·S = 0 — продажа переторжки занижена;
        # или AM вписана руками — по какой цене продано, по шаблону не сказать
        return Итог(ПЕРЕТОРЖКА_НЕПОЛНАЯ, sub_cur=sub, items=len(позиции), rebid=True, why="AK:AL",
                    вид="AM или AN вписаны поверх формулы при пустых AK и AL" if руками
                    else "AK и AL пусты у части позиций")

    н = lambda p, к: _число(p[к]) or 0.0   # noqa: E731
    закупка = sum(н(p, "T") for p in позиции)
    закупка_расчёт = sum(p["G"] * н(p, "S") for p in позиции)
    кп_eur = sum(н(p, "AD") for p in позиции)
    кп_eur_расчёт = sum(p["G"] * н(p, "AC") for p in позиции)
    кп_sub = sum(н(p, "AG") for p in позиции)
    кп_sub_расчёт = sum(p["G"] * н(p, "AF") for p in позиции)
    сверки = [отклонение(r1, закупка), отклонение(r1, закупка_расчёт),
              отклонение(ag1, кп_eur), отклонение(ag1, кп_eur_расчёт),
              отклонение(ag2, кп_sub), отклонение(ag2, кп_sub_расчёт)]
    # имена сверок — в журнал: какая не сошлась (адреса шаблона, без чисел)
    имена = ["R1 ↔ Σ T", "R1 ↔ Σ G·S", "AG1 ↔ Σ AD", "AG1 ↔ Σ G·AC", "AG2 ↔ Σ AG", "AG2 ↔ Σ G·AF"]
    if переторжка:
        продажа_eur = sum(н(p, "AN") for p in позиции)
        сверки.append(отклонение(продажа_eur, sum(p["G"] * н(p, "AM") for p in позиции)))
        имена += ["Σ AN ↔ Σ G·AM", "Σ G·AP ↔ Σ AN·AG2/AG1", "Σ G·AP ↔ Σ G·AM·AF/AC"]
        продажа_sub = sum(p["G"] * н(p, "AP") for p in позиции)
        # валюта подачи — ещё двумя способами: по курсу файла (AG2 / AG1, тот же, что у
        # «Нашего КП») и по курсу каждой строки (AF / AC). AP — итог строки, а не цена,
        # или AP в евро при подаче в рублях — здесь и не сойдётся
        сверки.append(отклонение(продажа_sub, продажа_eur * ag2 / ag1) if ag1 > 0 else 1.0)
        сверки.append(отклонение(продажа_sub, sum(p["G"] * н(p, "AM") * н(p, "AF") / н(p, "AC")
                                                  for p in позиции if н(p, "AC") > 0)))
        коэф = [н(p, "AM") / н(p, "S") for p in позиции if н(p, "S") > 0]
    else:
        # «Наше КП»: итоги файла (проверка 1 уже свела их с суммой строк)
        продажа_eur = ag1
        продажа_sub = ag2
        коэф = [_число(p["Z"]) for p in позиции if _число(p["Z"]) is not None]

    # курсы оффера по строкам: € за единицу валюты поставщика (S / Q)
    по_валюте: dict[str, list[float]] = {}
    for p in позиции:
        код, q, s = валюта(p["P"]), _число(p["Q"]), _число(p["S"])
        if код and q and q > 0 and s and s > 0:
            по_валюте.setdefault(код, []).append(s / q)
    по_строкам = {к: statistics.median(v) for к, v in по_валюте.items()}
    k_sub = продажа_sub / продажа_eur if продажа_eur > 0 else 0.0
    таблица = _курсы_по_строкам(ws, КУРСЫ_ПОДАЧИ)
    поставщика = _курсы_по_строкам(ws, КУРСЫ_ПОСТАВЩИКА)
    где_курс, чем_курс = сверить_курс(sub, k_sub, таблица, поставщика) if k_sub > 0 else ("", "")
    # курсы иных валют — из той таблицы, что сверила курс подачи (K:L — если строки в Z:AA нет)
    таблица_fx = поставщика if чем_курс == "K:L" else таблица

    sale_eur, purchase_eur = round(продажа_eur, 2), round(закупка, 2)
    итог = Итог(
        status=СВЕРЕНО, sub_cur=sub, sale_sub=round(продажа_sub, 2), sale_eur=sale_eur,
        purchase_eur=purchase_eur, rebid=переторжка, items=len(позиции),
        kp_sale_sub=round(ag2, 2) if переторжка else None,
        coef_median=round(statistics.median(коэф), 4) if коэф else None,
        totals_dev=round(max(сверки), 6),
        # наценка — из тех же округлённых чисел, что лягут в базу (база сверяет её сама)
        markup=round(sale_eur / purchase_eur - 1, 6) if purchase_eur > 0 else None,
        fx=курсы_в_подаче(sub, k_sub, {к: v for к, (v, _с) in таблица_fx.items()}, по_строкам),
        rate_src=чем_курс if чем_курс in ИСТОЧНИКИ_КУРСА else None)
    if итог.totals_dev > ДОПУСК_ИТОГА:
        итог.status, итог.why = ИТОГИ_НЕ_СХОДЯТСЯ, "проверка 1"
        худшая = max(range(len(сверки)), key=lambda i: сверки[i])
        итог.вид = (f"сверка {имена[худшая]} · отклонение {_корзина(сверки[худшая], КОРЗИНЫ_ОТКЛОНЕНИЯ, 'больше 50 %')}"
                    f" · не сошлось сверок {sum(1 for x in сверки if x > ДОПУСК_ИТОГА)} из {len(сверки)}")
    elif где_курс and чем_курс == НЕТ_СТРОКИ:
        # итоги сошлись, а строки курса валюты подачи нет ни в Z:AA, ни в K:L: курс — только
        # из строки файла, не выдуманный; вид (полоса, таблицы) допишет _вид_сбоя
        итог.status, итог.why = НЕТ_КУРСА, где_курс
    elif где_курс:
        # продажа в валюте подачи не в той валюте, что D4 и таблица курсов (AF в евро при
        # подаче в рублях и т. п.): курс, выведенный из итогов, противоречит файлу
        итог.status, итог.why = ИТОГИ_НЕ_СХОДЯТСЯ, где_курс
        итог.вид = _вид_курса(sub, k_sub, таблица, где_курс, поставщика)
    elif (закупка <= 0 or продажа_eur < закупка or продажа_sub <= 0 or итог.coef_median is None
          or not КОЭФ_МИН <= итог.coef_median <= КОЭФ_МАКС):
        итог.status, итог.why = НЕПРАВДОПОДОБНО, "проверка 2"
        итог.вид = ("закупка не больше нуля" if закупка <= 0 else "продажа ниже закупки" if продажа_eur < закупка
                    else "продажа в валюте подачи не больше нуля" if продажа_sub <= 0
                    else "коэффициента нет" if итог.coef_median is None
                    else f"медиана коэффициента {'ниже' if итог.coef_median < КОЭФ_МИН else 'выше'} "
                         f"{КОЭФ_МИН:g}…{КОЭФ_МАКС:g}")
    if not итог.сверено:
        итог.fx, итог.rate_src = {}, None
    return итог
