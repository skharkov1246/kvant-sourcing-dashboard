#
# Файл «впервые» — по ВСЕМ строкам lib_demand, включая помеченные: у
# переразобранного файла прежние строки помечены, и без них каждый переразбор
# выглядел бы новым файлом.
СПРОС = """
with файлы as (
  select source_file, min(created_at) as впервые
    from lib_demand
   where source_file is not null
   group by 1
), строки as (
  select lib_pn_key(d.part_number)                                  as ключ,
         (d.created_at at time zone %(пояс)s)::date                  as день,
         (j.demand_id is null)                                       as живая,
         (j.marked_at at time zone %(пояс)s)::date                   as снята,
         coalesce(f.side, 'без стороны')                             as сторона,
         case when d.source = 'распознавание скана' then 'распознавание'
              when ф.впервые is not null
                   and (ф.впервые at time zone %(пояс)s)::date
                       < (d.created_at at time zone %(пояс)s)::date then 'переразбор'
              else 'новый файл' end                                  as путь
    from lib_demand d
    left join lib_row_junk j on j.demand_id = d.id and j.revoked_at is null
    left join lib_files f    on f.file_id = d.source_file
    left join файлы ф        on ф.source_file = d.source_file
   where length(lib_pn_key(d.part_number)) >= 2
     and (hashtext(lib_pn_key(d.part_number)) & 2147483647) %% %(частей)s = %(часть)s
), по_ключу as (
  select ключ,
         min(день::text || '|' || путь)                                       as все,
         min(день::text || '|' || путь) filter (where сторона = 'заказчик')    as заказчик,
         min(день::text || '|' || путь) filter (where сторона = 'поставщик')   as поставщик,
         bool_or(живая)                                                        as жив_все,
         bool_or(живая and сторона = 'заказчик')                               as жив_заказчик,
         bool_or(живая and сторона = 'поставщик')                              as жив_поставщик,
         max(снята)                                                            as снята_все,
         max(снята) filter (where сторона = 'заказчик')                         as снята_заказчик,
         max(снята) filter (where сторона = 'поставщик')                        as снята_поставщик
    from строки
   group by ключ
)
select группа, событие, день, путь, count(*)::bigint from (
  select 'все' as группа, 'появился' as событие,
         split_part(все, '|', 1)::date as день, split_part(все, '|', 2) as путь
    from по_ключу
  union all
  select 'заказчик', 'появился', split_part(заказчик, '|', 1)::date, split_part(заказчик, '|', 2)
    from по_ключу where заказчик is not null
  union all
  select 'поставщик', 'появился', split_part(поставщик, '|', 1)::date, split_part(поставщик, '|', 2)
    from по_ключу where поставщик is not null
  union all
  select 'все', 'ушёл', снята_все, '' from по_ключу where not жив_все
  union all
  select 'заказчик', 'ушёл', снята_заказчик, ''
    from по_ключу where заказчик is not null and not жив_заказчик
  union all
  select 'поставщик', 'ушёл', снята_поставщик, ''
    from по_ключу where поставщик is not null and not жив_поставщик
) x
group by 1, 2, 3, 4
"""

