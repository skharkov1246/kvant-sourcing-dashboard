#!/usr/bin/env python3
"""Отвечает ли предложение на нашу заявку: сопоставление кодов.

ЗАЧЕМ. Владелец, 22.09.2026: «все предложения приходят точно с артикулированной
чёткой позицией… и отсылками к нашему запросу» и «очень важно всегда искать в
каждом входящем офере сопоставление кодов». Это последний пункт списка, который
измерить было нечем.

ЧТО СЧИТАЕТСЯ. Две встречные доли, и путать их нельзя:

  · СО СТОРОНЫ ПРЕДЛОЖЕНИЯ: какая доля строк цены отвечает позиции нашего запроса.
    Низкая доля значит либо что поставщик предложил не то, либо что мы не умеем
    сопоставить — и второе куда вероятнее.
  · СО СТОРОНЫ ЗАЯВКИ: какая доля позиций, которые мы спрашивали, получила хоть
    одну цену. Это и есть закупочная величина: по остальным мы вышли на рынок и
    остались без ответа.

Вторая доля важнее первой, и считать надо обе. Только первая даёт лестную картину:
поставщик прислал прайс на тысячу позиций, из них десять — наши, доля со стороны
предложения ничтожна, а заявка при этом закрыта.

ПОДГОТОВКА ВМЕСТО КОРРЕЛИРОВАННЫХ ПОДЗАПРОСОВ. Ключи заявок складываются во
временную таблицу с индексом, и соединение идёт по ней. Коррелированный
«exists (… where d.deal_id = p.rfq_id)» прямо по lib_demand выполнялся бы заново
для каждой из двадцати двух тысяч строк цены по таблице в полтора миллиона — ровно
на такой форме замер мостов уже упирался в statement_timeout (CLAUDE.md, правило 8).

Коррелированный exists ниже ОСТАЛСЯ, и это не противоречие: он идёт по временной
таблице с индексом по (deal_id, ключ), то есть каждая проверка — обращение к
индексу, а не проход по таблице. Правило запрещает не форму, а повторный
последовательный проход; форма без индекса и форма с индексом — разные вещи.
Проверять надо планом, что и сделано: соединение идёт индексом.

СОПОСТАВЛЕНИЕ ИДЁТ ДВУМЯ СПОСОБАМИ, И ВТОРОЙ ВАЖНЕЕ. По ключу артикула — точно, но
у предложений артикул часто пуст, а код сидит в тексте наименования (замер
калибровки: распознан у 31 % строк). Поэтому считается и совпадение по ключу, и
вхождение ключа заявки в текст строки предложения.

Ничего не пишет. В журнал — только агрегаты (правило 17).

    SUPABASE_DB_URL=… python scripts/offer_match.py
"""
from __future__ import annotations

import os

FEED = "разбор КП"

# ПОЧЕМУ РАЗРЯДА «СВОЯ СДЕЛКА» БОЛЬШЕ НЕТ. До 22.09.2026 замер сравнивал ключи
# внутри «одной сделки» и получал 83 % совпадений. Обе половины этого сравнения
# были неверны:
#
# 1. `lib_prices.rfq_id` — это id КАРТОЧКИ ЗАПРОСА (СП-166), а не сделки:
#    indexer.py кладёт в него `str(элемент СП-166 ["id"])`. Строки спроса из наших
#    спецификаций несут id СДЕЛКИ. Это два РАЗНЫХ пространства идентификаторов,
#    численно пересекающихся, — соединение по ним совпадает случайно. Связь
#    «карточка → сделка» (`parentId2`) индексатор не читает вовсе, поэтому
#    восстановить сделку у цены сейчас нечем.
# 2. Разбор КП кладёт каждую позицию предложения И в lib_prices, И в lib_demand
#    под тем же id карточки. Значит строка предложения совпадала с СОБСТВЕННОЙ
#    строкой спроса: эталон был производным от правила (CLAUDE.md, правило 1).
#
# Поэтому заявки собираются ТОЛЬКО из наших спецификаций (lib_files.origin =
# 'поле сделки'), а сравнение идёт по ключу на всей базе — то, что вообще
# вычислимо. Разряд «в своей сделке» вернётся, когда у цены появится настоящий
# deal_id; до тех пор его отсутствие названо вслух, а не заменено похожим числом.
НАШ_ИСТОЧНИК = "поле сделки"

ПОДГОТОВКА = """
create temp table сделки_с_кп as
  select distinct p.rfq_id as card_id
    from lib_prices p
   where p.feed = %s and p.rfq_id is not null;
create index on сделки_с_кп (card_id);
analyze сделки_с_кп;

-- ТОЛЬКО НАШИ СПЕЦИФИКАЦИИ. Без отбора по происхождению файла сюда попадают
-- позиции самих предложений, и замер сравнивает предложение с самим собой.
create temp table ключи_заявок as
  select distinct d.deal_id, lib_pn_key(d.part_number) as ключ
    from lib_demand_live d
    join lib_files f on f.file_id = d.source_file
   where f.origin = %s
     and coalesce(btrim(d.part_number), '') <> ''
     and length(lib_pn_key(d.part_number)) >= 4;
create index on ключи_заявок (deal_id, ключ);
create index on ключи_заявок (ключ);
analyze ключи_заявок;

-- ТЕКСТ НОРМАЛИЗУЕТСЯ ЗДЕСЬ, А НЕ В СОЕДИНЕНИИ. regexp_replace внутри join
-- считается на КАЖДУЮ пару «позиция заявки × строка предложения»: у сделки с
-- тысячей позиций и тысячей строк цены это миллион вызовов на одну сделку.
-- Один раз на строку — это двадцать две тысячи вызовов на всю базу.
create temp table строки_кп as
  select p.id, p.rfq_id as card_id, lib_pn_key(p.part_number) as ключ,
         regexp_replace(lower(coalesce(p.item_name, '')),
                        '[^0-9a-zа-я]', '', 'g') as текст_ключ
    from lib_prices p
   where p.feed = %s;
create index on строки_кп (card_id, ключ);
create index on строки_кп (ключ);
analyze строки_кп;
"""

ОБЪЁМ = """
select (select count(*)::bigint from строки_кп)                        as строк_кп,
       (select count(distinct card_id)::bigint from сделки_с_кп)        as карточек_с_кп,
       (select count(*)::bigint from ключи_заявок)                      as ключей_заявок,
       (select count(distinct deal_id)::bigint from ключи_заявок)       as сделок_с_заявкой
"""

# СО СТОРОНЫ ПРЕДЛОЖЕНИЯ. Разряды взаимоисключающие и идут по убыванию строгости:
# своя сделка точнее чужой, ключ точнее текста.
СО_СТОРОНЫ_КП = """
select case
         when к.ключ is null or length(к.ключ) < 4 then 'артикула в строке нет'
         when exists (select 1 from ключи_заявок з where з.ключ = к.ключ)
              then 'ключ совпал с нашей спецификацией'
         else 'артикул есть, в наших спецификациях нет' end             as разряд,
       count(*)::bigint                                                 as строк
  from строки_кп к
 group by 1 order by 2 desc
"""

# Вхождение ключа заявки в ТЕКСТ строки предложения — для тех строк, где своего
# артикула нет. Соединение по сделке, поэтому перебор идёт внутри одной сделки, а
# не по всей базе.
ПО_ТЕКСТУ = """
select count(distinct к.id)::bigint
  from строки_кп к
  join ключи_заявок з on position(з.ключ in к.текст_ключ) > 0
 where (к.ключ is null or length(к.ключ) < 4)
   and к.текст_ключ <> ''
   and length(з.ключ) >= 5
"""

# СО СТОРОНЫ ЗАЯВКИ — закупочная величина: по скольким нашим позициям пришла цена.
СО_СТОРОНЫ_ЗАЯВКИ = """
select count(*)::bigint                                                 as позиций_заявок,
       count(*) filter (where есть_цена)::bigint                        as с_ценой
  from (select з.deal_id, з.ключ,
               exists (select 1 from строки_кп к where к.ключ = з.ключ)  as есть_цена
          from ключи_заявок з) x
"""

# По сделкам: сколько заявок закрыто ценой целиком, сколько частично, сколько никак.
ПО_СДЕЛКАМ = """
with по_сделке as (
  select з.deal_id, count(*) as позиций,
         count(*) filter (where exists (select 1 from строки_кп к
                                         where к.ключ = з.ключ)) as с_ценой
    from ключи_заявок з group by 1
)
select case when с_ценой = 0 then 'ни одной позиции с ценой'
            when с_ценой = позиций then 'все позиции с ценой'
            when с_ценой * 2 >= позиций then 'половина и более'
            else 'меньше половины' end                                  as разряд,
       count(*)::bigint                                                 as сделок,
       sum(позиций)::bigint                                             as позиций,
       sum(с_ценой)::bigint                                             as с_ценой
  from по_сделке group by 1 order by 2 desc
"""


def ч(x) -> int:
    return int(x or 0)


def доля(часть, целое) -> str:
    часть, целое = ч(часть), ч(целое)
    return f"{часть}" + (f" ({100 * часть / целое:.1f} %)" if целое else "")


def main() -> int:
    dsn = os.environ.get("SUPABASE_DB_URL", "").strip()
    if not dsn:
        print("нет SUPABASE_DB_URL — мерить нечего")
        return 2
    import psycopg2

    conn = psycopg2.connect(dsn, connect_timeout=20,
                            options="-c statement_timeout=600000")
    try:
        with conn.cursor() as cur:
            print("=== ОТВЕЧАЕТ ЛИ ПРЕДЛОЖЕНИЕ НА НАШУ ЗАЯВКУ ===")
            cur.execute(ПОДГОТОВКА, (FEED, НАШ_ИСТОЧНИК, FEED))
            cur.execute(ОБЪЁМ)
            строк, карточек, ключей, с_заявкой = cur.fetchone()
            print(f"\nОБЪЁМ: строк цены {ч(строк)} · карточек запроса {ч(карточек)}")
            print(f"       позиций в НАШИХ спецификациях {ч(ключей)}"
                  f" · сделок с прочитанной спецификацией {ч(с_заявкой)}")
            print("\nСРАВНЕНИЕ ИДЁТ ПО КЛЮЧУ НА ВСЕЙ БАЗЕ, А НЕ ВНУТРИ СДЕЛКИ.")
            print("У цены хранится id КАРТОЧКИ ЗАПРОСА, а у строки спроса — id")
            print("СДЕЛКИ; связь между ними (parentId2) индексатор не читает,")
            print("поэтому разряда «совпало в своей сделке» здесь нет. Прежние 83 %")
            print("были совпадением предложения с его же строкой спроса.")
            # Прежде здесь печаталось «у N сделок с предложениями заявка не
            # прочитана» — вычитанием карточек запроса из сделок со спецификацией.
            # Вычитать их друг из друга нельзя: это разные сущности, и разность
            # ничего не значит. Оба числа напечатаны выше порознь.

            cur.execute(СО_СТОРОНЫ_КП)
            разряды = cur.fetchall()
            print("\nСО СТОРОНЫ ПРЕДЛОЖЕНИЯ (какая строка цены отвечает нашей позиции):")
            for разряд, n in разряды:
                print(f"    {разряд:32s} {доля(n, строк):>18s}")

            cur.execute(ПО_ТЕКСТУ)
            по_тексту = cur.fetchone()[0]
            print(f"\n    из строк без своего артикула ключ заявки нашёлся В ТЕКСТЕ:"
                  f" {доля(по_тексту, строк)}")
            print("    Это и есть тот случай, о котором говорит владелец: код в")
            print("    предложении есть, но стоит внутри наименования, а колонка")
            print("    артикула пуста. Вхождение ищется по всей базе ключей наших")
            print("    спецификаций, поэтому число — верхняя граница: короткий ключ")
            print("    может случайно найтись в чужом наименовании.")

            cur.execute(СО_СТОРОНЫ_ЗАЯВКИ)
            позиций, с_ценой = cur.fetchone()
            print(f"\nСО СТОРОНЫ ЗАЯВКИ — ЗАКУПОЧНАЯ ВЕЛИЧИНА:")
            print(f"    позиций в заявках {ч(позиций)} · получили цену"
                  f" {доля(с_ценой, позиций)}")
            print("    По остальным мы вышли на рынок и остались без ответа — либо")
            print("    ответ есть, но мы его не сопоставили.")

            cur.execute(ПО_СДЕЛКАМ)
            print("\nПО СДЕЛКАМ (насколько заявка закрыта ценой — по КЛЮЧУ, не")
            print("внутри сделки: цена могла прийти по другой сделке с тем же кодом):")
            for разряд, сд, поз, сц in cur.fetchall():
                print(f"    {разряд:26s} сделок {ч(сд):>5d}"
                      f" · позиций {ч(поз):>7d} · с ценой {ч(сц):>7d}")
        return 0
    finally:
        conn.close()


if __name__ == "__main__":
    raise SystemExit(main())
