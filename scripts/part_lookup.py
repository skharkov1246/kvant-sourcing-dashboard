#!/usr/bin/env python3
"""Всё, что база знает об одном артикуле: перебор по всем звеньям цепочки.

ЗАЧЕМ. Распоряжение владельца, 22.09.2026: «Только код подшипника 6265ZZ. Давай,
перебирай все, но в гитхабе, свой ресурс не жги». То есть поиск идёт прогоном
Actions против живой базы, а не локально: строка подключения — секрет, и локально
её нет.

ЧТО ЗНАЧИТ «ПЕРЕБИРАЙ ВСЕ». Один артикул записывают десятком способов, и точное
совпадение находит меньшую часть. Перебираются:

  · ключ номера (lib_pn_key): регистр, дефисы, пробелы и точки снимаются, поэтому
    «6265ZZ», «6265-ZZ», «6265 ZZ», «6265.zz» — это ОДИН ключ. Отдельно их
    перебирать не нужно, и это проверено, а не предположено;
  · семья по префиксу: 6265Z, 6265ZZ, 6265-2Z, 6265 2RS, 6265ZZ/C3 — один и тот
    же подшипник с разным уплотнением и зазором, и для закупки это близкие вещи;
  · голое число без суффикса: часто артикул записан «6265», а «ZZ» ушло в
    отдельную колонку исполнения;
  · вхождение в ТЕКСТ наименования. Это главное: у предложений артикул сплошь и
    рядом сидит внутри строки («Подшипник 6265ZZ SKF, 4 шт»), а колонка артикула
    пуста. Искать только по колонке значит не находить большую часть.

ГДЕ ИЩЕТ. По всем звеньям цепочки разом: каталог деталей, взаимозаменяемость,
привязка к машинам, состав изделия, поставщики детали, спрос (что у нас
спрашивали) и цены (что нам предлагали).

ЧТО ПЕЧАТАЕТ, А ЧТО НЕТ. Репозиторий публичный, и журнал прогона виден всем
(CLAUDE.md, правило 17). Поэтому в журнал идут: количества, каталожные номера и
изготовители (это обозначения производителя, открытые сведения), модели машин,
валюты и статистика цен. НЕ идут: названия компаний-поставщиков, номера сделок и
тексты наименований — «такой-то поставщик дал нам такую-то цену» это коммерческие
сведения, и место им не в открытом журнале. Их выдаёт ПОДРОБНО=1 — включать
осознанно и понимая, что прогон станет публичным.

    SUPABASE_DB_URL=… PN=6265ZZ python scripts/part_lookup.py
"""
from __future__ import annotations

import os
import re

PN = os.environ.get("PN", "").strip()
ПОДРОБНО = os.environ.get("ПОДРОБНО", os.environ.get("DETAIL", "")) not in ("", "0", "false")


def ключ(t: str) -> str:
    """То же, что lib_pn_key в базе: регистр, ё, только буквы и цифры, 80 знаков.

    Повторено здесь, чтобы печатать ключ до запроса и чтобы рассинхрон с базой был
    виден сразу. На расхождении этих двух реализаций уже разъезжались замеры.
    """
    return re.sub(r"[^0-9a-zа-я]", "", t.lower().replace("ё", "е"))[:80]


# Суффиксы исполнения подшипника: уплотнение и зазор. Снимаются С КОНЦА, и только
# потом берутся ведущие цифры. Наоборот нельзя: «62652rs» ведущими цифрами даёт
# «62652» — двойка от «2RS» приклеивается к номеру, и поиск семьи вырождается в
# поиск несуществующего номера.
#
# Список намеренно короткий и закрытый: он расширяет поиск, а не сужает его, но
# ошибочное снятие «EK» у 22315 EK отрезало бы значащую часть обозначения.
СУФФИКСЫ = ("c0", "c2", "c3", "c4", "c5", "p5", "p6", "p0")
УПЛОТНЕНИЯ = ("2rs1", "2rsr", "2rs", "2rz", "2z", "zz", "rsr", "rs", "rz",
              "ddu", "llu", "nse", "nr")


def основа(k: str) -> str:
    """Числовая основа артикула: «6265zz» → «6265», «62652rs» → «6265».

    Только для РАСШИРЕНИЯ поиска семьёй. Точный поиск идёт по полному ключу, и
    эта эвристика на него не влияет.
    """
    t = k
    for _ in range(2):                       # зазор и уплотнение, в любом порядке
        for суф in СУФФИКСЫ + УПЛОТНЕНИЯ:
            if t.endswith(суф) and len(t) > len(суф) + 2:
                t = t[:-len(суф)]
                break
    # БУКВЕННЫЙ ПРЕФИКС ТИПА СОХРАНЯЕТСЯ. «NU 2216» и «2216» — разные подшипники:
    # первый роликовый с бортами на внутреннем кольце, второй шариковый
    # сферический. Отбросив «NU», поиск семьи смешал бы два разных изделия, и это
    # хуже, чем узкий поиск.
    m = re.match(r"^([a-zа-я]{0,3}\d{3,})", t) or re.match(r"^([a-zа-я]{0,3}\d{3,})", k)
    return m.group(1) if m else k


# ── ЗАПРОСЫ. Каждый возвращает только агрегаты либо открытые обозначения.

# ПРОЗВИЩА ДЕТАЛИ — МАССИВ, И ИСКАТЬ ПО НИМ НАДО КЛЮЧОМ, А НЕ РЕГУЛЯРКОЙ. Первая
# версия писала «p.aliases ~* %s» и падала с «malformed array literal»: колонка
# text[], регулярное сравнение к ней не применяется. Ключ здесь и правильнее по
# сути — в прозвищах лежат альтернативные НОМЕРА, а номер сравнивают ключом, а не
# вхождением подстроки.
КАТАЛОГ = """
select p.id, p.catalog_no, coalesce(p.oem, '(не указан)'),
       coalesce(p.name, ''), coalesce(p.model, ''),
       array_to_string(coalesce(p.aliases, '{}'), ', ')
  from lib_parts p
 where lib_pn_key(p.catalog_no) = any(%s)
    or lib_pn_key(p.kv_no) = any(%s)
    or lib_pn_key(p.catalog_no) like %s
    or exists (select 1 from unnest(coalesce(p.aliases, '{}')) as пс
                where lib_pn_key(пс) = any(%s))
 order by 1 limit 60
"""

# Взаимозаменяемость хранит НОМЕР аналога текстом (alt_pn), а не ссылку на строку
# каталога: аналог бывает и такой, какого у нас в каталоге нет. Поэтому ищем и по
# part_id нашей детали, и по ключу номера в alt_pn — второе находит случай, когда
# наш артикул назван аналогом чужой детали.
АНАЛОГИ = """
select coalesce(a.alt_pn, ''), coalesce(a.alt_maker, ''), coalesce(a.kind, ''),
       coalesce(a.confidence, '')
  from lib_part_alt a
 where a.part_id = any(%s) or lib_pn_key(a.alt_pn) = any(%s)
 order by 1 limit 40
"""

МАШИНЫ = """
select coalesce(m.name, m.id), coalesce(m.oem, ''), coalesce(m.family, '')
  from lib_part_models pm
  join lib_models m on m.id = pm.model_id
 where pm.part_id = any(%s)
 order by 1 limit 30
"""

# Поставщики детали. Названий компаний здесь нет намеренно (см. заголовок модуля),
# а наличие НЕ СВОДИТСЯ К БУЛЕВУ. Колонка in_stock — текст, и это не небрежность
# схемы: подтверждённый остаток на весь объём, наличие без покрытия количества,
# «отгрузим, если есть» и незаверенная запись прошлой проверки — четыре разные
# вещи, складывать их в одно число нельзя (CLAUDE.md, «Числа в выгрузках
# владельцу»). Поэтому здесь разрез по вердикту и по записи наличия как есть.
ПОСТАВЩИКИ_СЧЁТ = """
select coalesce(nullif(btrim(ps.verdict), ''), '(нет вердикта)')  as вердикт,
       coalesce(nullif(btrim(ps.in_stock), ''), '(не сказано)')   as наличие,
       count(*)::bigint                                           as связей,
       count(distinct ps.supplier_id)::bigint                     as компаний,
       count(*) filter (where ps.price is not null)::bigint       as с_ценой
  from lib_part_suppliers ps
 where ps.part_id = any(%s)
 group by 1, 2 order by 3 desc limit 20
"""

# Спрос: что у нас спрашивали. И по колонке артикула, и внутри наименования —
# у предложений артикул сплошь и рядом сидит в тексте, а колонка пуста.
СПРОС = """
select count(*)::bigint                                          as строк,
       count(distinct d.deal_id)::bigint                         as сделок,
       count(*) filter (where lib_pn_key(d.part_number) = any(%s))::bigint as по_колонке,
       coalesce(sum(d.qty), 0)::numeric                          as всего_штук,
       count(distinct d.source_file)::bigint                     as файлов
  from lib_demand_live d
 where lib_pn_key(d.part_number) = any(%s)
    or d.item_name ~* %s
"""

ЦЕНЫ = """
select coalesce(p.currency, '(не названа)')                      as валюта,
       count(*)::bigint                                          as строк,
       count(distinct p.rfq_company)::bigint                     as компаний,
       min(p.price)::numeric                                     as минимум,
       percentile_disc(0.5) within group (order by p.price)::numeric as медиана,
       max(p.price)::numeric                                     as максимум
  from lib_prices p
 where lib_pn_key(p.part_number) = any(%s)
    or p.item_name ~* %s
 group by 1 order by 2 desc
"""

УСЛОВИЯ = """
select coalesce(p.basis, '(нет)')                                as базис,
       coalesce(p.pay_terms, '(нет)')                            as оплата,
       count(*)::bigint                                          as строк,
       min(p.lead_days)::int                                     as срок_мин,
       max(p.lead_days)::int                                     as срок_макс
  from lib_prices p
 where lib_pn_key(p.part_number) = any(%s)
    or p.item_name ~* %s
 group by 1, 2 order by 3 desc limit 20
"""

# ЕСТЬ ЛИ В БАЗЕ КОЛОНКИ КОММЕРЧЕСКИХ УСЛОВИЙ. Они добавляются миграцией, и между
# мержем кода и её применением есть промежуток. Прогон 35761985937 прошёл весь
# поиск, напечатал результат и упал на последнем запросе с «column p.pay_terms does
# not exist» — код возврата 1 при полностью полученном ответе. Прибор для
# интерактивного вопроса так вести себя не должен: недостающая колонка это повод
# сказать о ней, а не потерять ответ.
ЕСТЬ_УСЛОВИЯ = """
select count(*)::int
  from information_schema.columns
 where table_name = 'lib_prices'
   and column_name in ('pay_terms', 'make_days', 'basis_src', 'total')
"""

ПОДРОБНОСТИ = """
select coalesce(p.rfq_company, '(не указана)'), p.price, p.currency,
       p.lead_days, p.basis, p.pay_terms
  from lib_prices p
 where lib_pn_key(p.part_number) = any(%s)
    or p.item_name ~* %s
 order by p.price nulls last limit 100
"""


def ч(x) -> int:
    return int(x or 0)


def main() -> int:
    if not PN:
        print("не задан PN — нечего искать")
        return 2
    dsn = os.environ.get("SUPABASE_DB_URL", "").strip()
    if not dsn:
        print("нет SUPABASE_DB_URL — мерить нечего")
        return 2
    import psycopg2

    k = ключ(PN)
    осн = основа(k)
    ключи = sorted({k, осн})
    # Вхождение в ТЕКСТ наименования: основа артикула, не приклеенная к другим
    # цифрам. Без этих границ «6265» найдётся внутри «162650» и внутри года.
    рег = r"(?<![0-9])" + осн + r"(?![0-9])"
    print(f"=== ЧТО БАЗА ЗНАЕТ ОБ АРТИКУЛЕ {PN} ===")
    print(f"ключ номера: {k} · числовая основа: {осн}")
    print(f"ключи точного поиска: {', '.join(ключи)}")
    print(f"поиск в тексте наименования по основе: {рег}")
    print("Регистр, дефисы, пробелы и точки ключом снимаются, поэтому 6265ZZ,")
    print("6265-ZZ, 6265 ZZ и 6265.zz — это один ключ, а не четыре.\n")

    conn = psycopg2.connect(dsn, connect_timeout=20,
                            options="-c statement_timeout=300000")
    try:
        with conn.cursor() as cur:
            cur.execute(КАТАЛОГ, (ключи, ключи, осн + "%", ключи))
            строки = cur.fetchall()
            print(f"КАТАЛОГ ДЕТАЛЕЙ: найдено {len(строки)} (семья по основе {осн})")
            for _id, кат, oem, имя, модель, прозвища in строки:
                метка = "точно" if ключ(кат) in ключи else "семья"
                print(f"    {метка:5s} {str(кат)[:26]:26s} изготовитель {oem[:22]:22s}"
                      f" {имя[:30]:30s} {модель[:18]}")
                if прозвища:
                    print(f"          прозвища: {прозвища[:80]}")
            if not строки:
                print(f"    в каталоге ничего: ни {PN}, ни семьи по основе {осн}")
            # ИДЕНТИФИКАТОР БЕРЁТСЯ ИЗ ТАБЛИЦЫ, А НЕ СЧИТАЕТСЯ КЛЮЧОМ. У 82 деталей
            # из 13 501 id не равен lib_pn_key(catalog_no) — он считается по
            # catalog_norm, когда тот заполнен. Такая деталь выпала бы из связей
            # МОЛЧА, и это неотличимо от «связей нет» (schema_junk.sql).
            ids = [r[0] for r in строки]

            if ids:
                cur.execute(АНАЛОГИ, (ids, ключи))
                ан = cur.fetchall()
                print(f"\nВЗАИМОЗАМЕНЯЕМОСТЬ: {len(ан)}")
                for пн, мейкер, вид, ув in ан:
                    print(f"    {str(пн)[:26]:26s} {str(мейкер)[:20]:20s}"
                          f" {str(вид)[:14]:14s} уверенность {ув}")
                cur.execute(МАШИНЫ, (ids,))
                маш = cur.fetchall()
                print(f"МАШИНЫ, ГДЕ СТОИТ: {len(маш)}")
                for имя_м, oem_м, сем in маш:
                    print(f"    {str(имя_м)[:34]:34s} {str(oem_м)[:18]:18s} {str(сем)[:18]}")
                cur.execute(ПОСТАВЩИКИ_СЧЁТ, (ids,))
                пост = cur.fetchall()
                print(f"ПОСТАВЩИКИ ДЕТАЛИ: наборов {len(пост)}"
                      f" · связей всего {sum(ч(r[2]) for r in пост)}")
                print("    (наличие показано как записано: подтверждённый остаток,")
                print("     наличие без покрытия объёма и «отгрузим, если есть» —")
                print("     разные вещи, в одно число их складывать нельзя)")
                for вердикт, наличие, св, комп, сц in пост:
                    print(f"    вердикт {вердикт[:18]:18s} наличие {наличие[:16]:16s}"
                          f" связей {ч(св):>4d} · компаний {ч(комп):>4d}"
                          f" · с ценой {ч(сц):>4d}")

            cur.execute(СПРОС, (ключи, ключи, рег))
            строк, сделок, по_кол, штук, файлов = cur.fetchone()
            print(f"\nСПРОС (что у нас спрашивали): строк {ч(строк)} в {ч(сделок)} сделках"
                  f" · из {ч(файлов)} файлов · по колонке артикула {ч(по_кол)}"
                  f" · остальное найдено в тексте · всего штук {ч(штук)}")

            cur.execute(ЦЕНЫ, (ключи, рег))
            цены = cur.fetchall()
            print(f"\nЦЕНЫ (что нам предлагали): наборов по валютам {len(цены)}")
            for вал, n, комп, мин, мед, макс in цены:
                print(f"    {вал:12s} строк {ч(n):>5d} · компаний {ч(комп):>4d}"
                      f" · мин {float(мин or 0):>12,.2f} · медиана {float(мед or 0):>12,.2f}"
                      f" · макс {float(макс or 0):>12,.2f}".replace(",", " "))
            if not цены:
                print("    цен по этому артикулу в базе нет")

            cur.execute(ЕСТЬ_УСЛОВИЯ)
            колонок = ч(cur.fetchone()[0])
            if колонок < 4:
                print(f"\nКОММЕРЧЕСКИЕ УСЛОВИЯ не спрошены: в базе есть {колонок} из 4")
                print("нужных колонок. Их добавляет миграция — примените прогон")
                print("«ZIP base — apply DB migrations». Остальной ответ выше полон.")
            else:
                cur.execute(УСЛОВИЯ, (ключи, рег))
                усл = cur.fetchall()
                if усл:
                    print("\nКОММЕРЧЕСКИЕ УСЛОВИЯ по этим предложениям:")
                    for базис, оплата, n, смин, смакс in усл:
                        срок = ("—" if смин is None else
                                f"{смин}" if смин == смакс else f"{смин}–{смакс}")
                        print(f"    базис {базис[:10]:10s} оплата {оплата[:24]:24s}"
                              f" строк {ч(n):>5d} · срок поставки {срок} дн")

            if ПОДРОБНО and колонок >= 4:
                cur.execute(ПОДРОБНОСТИ, (ключи, рег))
                п = cur.fetchall()
                print(f"\nПОДРОБНО ({len(п)} строк). Включено переменной ПОДРОБНО=1:")
                for комп, цена, вал, срок, базис, оплата in п:
                    print(f"    {str(комп)[:30]:30s} {float(цена or 0):>12,.2f} {вал or '?':4s}"
                          f" срок {срок if срок is not None else '—'} базис {базис or '—'}"
                          f" оплата {оплата or '—'}".replace(",", " "))
            elif ПОДРОБНО:
                print("\nПодробности не выведены: колонок условий в базе нет.")
            else:
                print("\nНазвания компаний и цены построчно в журнал НЕ выведены:")
                print("репозиторий публичный, журнал прогона виден всем, а «такой-то")
                print("поставщик дал такую-то цену» — коммерческие сведения")
                print("(CLAUDE.md, правило 17). Нужны — прогон с ПОДРОБНО=1.")
        return 0
    finally:
        conn.close()


if __name__ == "__main__":
    raise SystemExit(main())
