#!/usr/bin/env python3
"""Почему цена не прочитана: разбор отказов правила на живых строках КП.

ЗАЧЕМ. Владелец, 22.09.2026: «предложения приходят с артикулированной чёткой
позицией, 99 % точно с номенклатурными позициями и отсылками к нашему запросу.
Ищи, разработай инструмент, который нормально читает предложения и распознаёт
коды». Значит надо знать не «сколько потеряно», а ГДЕ ИМЕННО правило говорит
«нет» и что было бы, если бы оно говорило «да».

ПОЧЕМУ ПЕРЕРАЗБОР НЕ НУЖЕН. Текст строки уже лежит в lib_demand.item_name —
это ровно то, что разборщик скормил правилу. Правило прогоняется по нему
заново, и видно, какие ворота его остановили. Ни одного файла качать не надо.

ЧТО МЕРЯЕТСЯ

1. ОТКАЗЫ ПРАВИЛА ЦЕНЫ. quotes.цена_из_текста требует тройку подряд идущих
   чисел с сошедшейся арифметикой кол-во × цена = сумма. До арифметики стоят
   ещё трое ворот: шум, мало букв, меньше трёх чисел. Разложение по воротам
   говорит, что чинить: если строки не доходят до арифметики, ослаблять допуск
   бессмысленно.

2. РАСПОЗНАВАНИЕ КОДА. docfilter.part_number_of отказывает голому числу, если
   в строке есть денежные слова (защита от «сумма принята за артикул»). Но
   строка КП денежные слова содержит ВСЕГДА. Значит в предложениях эта защита
   бьёт по канонической номенклатуре — 6205, 22315 — то есть ровно по тому, о
   чём говорит владелец. Мерится цена защиты: сколько строк получают артикул,
   если денежное подавление снять.

3. СЕТКА КАНДИДАТОВ, ЗА ОДИН ПРОХОД (правило 4). Каждое послабление считается
   на том же корпусе, и у каждого — своя проверка на удержание:

   ПРОВЕРКА НА УДЕРЖАНИЕ. Эталона «правильной цены» у нас нет, придумывать его
   нельзя. Но там, где арифметика сошлась, ответ известен и самопроверяем.
   Кандидат прогоняется по ЭТИМ строкам тоже, и меряется, называет ли он ту же
   цену. Кандидат, который на известных строках врёт, на неизвестных не лучше.
   Это не оценка полноты — это отсев заведомо негодных правил.

Ничего не пишет. В журнал — только агрегаты и собственные константы (правило 17).

    SUPABASE_DB_URL=… LIMIT=200000 python scripts/quote_price_calibration.py
"""
from __future__ import annotations

import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from library import docfilter, quotes  # noqa: E402

ПРЕДЛОЖЕНИЕ = "поле запроса"
LIMIT = int(os.environ.get("LIMIT", "200000"))

# Строки предложений: текст позиции и путь, которым файл разобран. Порядок по
# id — выборка не случайная, но и не отсортированная по качеству; для разложения
# отказов по воротам этого достаточно, а случайная выборка на полутора миллионах
# строк стоит полного прохода.
СТРОКИ = """
select coalesce(f.parse_path, '(не указан)'), d.item_name
  from lib_demand d
  join lib_files f on f.file_id = d.source_file
 where f.origin = %s and coalesce(d.item_name, '') <> ''
 order by d.id
 limit %s
"""

# ─────────────────────────────────────────────────────────────────────────────
# Ворота правила цены, по одному. Повторяют quotes.цена_из_текста шаг в шаг:
# если правило изменится, а это — нет, замер станет врать. Поэтому здесь не
# копия правила, а его же примитивы.
ЕДИНИЦА = re.compile(
    r"(?i)(?<![а-яёa-z])(шт|штук|компл|комплект|пар|набор|pcs?|pieces?|ea|set|"
    r"units?|кг|kg|м|mm|мм|л|lt?r)\.?(?![а-яёa-z])")


# Закрытый список ворот. Всё, что не отсюда и не «чисел в строке: N», в журнал
# не попадает: список ворот — константы кода, а не данные.
ПРИЧИНЫ = ("шум (НДС, итого, скидка)", "меньше четырёх букв",
           "тройка не сошлась", "ЦЕНА ПРОЧИТАНА")


def ворота(строка: str) -> tuple[str, dict]:
    """Каким воротом остановлена строка и её структурный профиль.

    Профиль — только структура: сколько чисел, названа ли валюта, есть ли
    артикул, есть ли слово единицы. Ни одного знака самой строки наружу
    не выходит (правило 17).
    """
    проф = {
        "валюта": quotes.валюта_из(строка) is not None,
        "единица": ЕДИНИЦА.search(строка) is not None,
        "артикул": bool(docfilter.part_number_of(строка)),
    }
    if quotes.ШУМ_СТРОКИ.search(строка):
        return "шум (НДС, итого, скидка)", проф
    if len(re.sub(r"[^A-Za-zА-Яа-яЁё]", "", строка)) < 4:
        return "меньше четырёх букв", проф
    числа = quotes._числа_строки(строка)
    проф["чисел"] = len(числа)
    if len(числа) < 3:
        return f"чисел в строке: {len(числа)}", проф
    if quotes.цена_из_текста(строка) is not None:
        return "ЦЕНА ПРОЧИТАНА", проф
    return "тройка не сошлась", проф


def ключ_профиля(причина: str, чисел, валюта, артикул) -> str:
    """Строка профиля для журнала. ТОЛЬКО структура и собственные константы.

    ПРИНИМАЕТ СКАЛЯРЫ, А НЕ СЛОВАРЬ ПРОФИЛЯ, И ЭТО НЕ ПРИДИРКА. Первая версия
    брала dict и подставляла из него поля: тогда достаточно положить в профиль
    ещё один ключ с куском строки — и он уедет в публичный журнал, а тест,
    стерегущий вывод ворот, этого не увидит (проверено мутацией, она выжила).
    У версии со скалярами прятать текст негде: причина сверяется с закрытым
    списком, число приводится к int, признаки — к «да/нет». CLAUDE.md, 17.
    """
    if причина not in ПРИЧИНЫ and not причина.startswith("чисел в строке:"):
        причина = "(неизвестные ворота)"
    return (f"{причина[:24]} · чисел {int(чисел or 0)}"
            f" · валюта {'да' if валюта else 'нет'}"
            f" · артикул {'да' if артикул else 'нет'}")


# ─────────────────────────────────────────────────────────────────────────────
# КАНДИДАТЫ. Каждый — функция строка → цена или None. Ни один не пишется в базу
# по итогам этого замера: замер только говорит, сколько он берёт и врёт ли он
# там, где ответ известен.

def к1_число_при_валюте(строка: str) -> float | None:
    """Число, стоящее вплотную к знаку или коду валюты.

    «1 250,00 руб», «USD 1 250.00», «€1250». Валюта рядом с числом — это
    утверждение продавца, что число денежное; гадать не приходится.
    Берётся самое правое такое число: справа в строке стоят деньги.
    """
    метки = [m for _, ms in quotes.ВАЛЮТЫ for m in ms]
    лучшее = None
    low = строка.lower()
    for m in quotes._ТОКЕН.finditer(строка):
        хвост = low[m.end():m.end() + 12].lstrip("  .,")
        голова = low[max(0, m.start() - 12):m.start()].rstrip("  ")
        рядом = any(хвост.startswith(x) for x in метки) or \
                any(голова.endswith(x) for x in метки)
        if рядом:
            v = quotes.число_из(m.group(0))
            if v and v > 0:
                лучшее = v
    return лучшее


def к2_пара_количество_цена(строка: str) -> float | None:
    """Пара «кол-во ед. цена» без суммы: «10 шт 1 250,00».

    Суммы в строке нет, проверить арифметикой нечем — опорой служит слово
    единицы сразу после первого числа. Берётся число, следующее за единицей.
    """
    m = ЕДИНИЦА.search(строка)
    if not m:
        return None
    после = [quotes.число_из(t.group(0))
             for t in quotes._ТОКЕН.finditer(строка) if t.start() >= m.end()]
    после = [v for v in после if v and v > 0]
    return после[0] if len(после) == 1 else None


def к3_последнее_число_при_артикуле(строка: str) -> float | None:
    """Самое правое число в строке, где есть артикул и названа валюта.

    Самый щедрый кандидат и самый опасный: правое число — это и цена, и сумма,
    и вес. Считается, чтобы увидеть верхнюю границу охвата, а не чтобы
    применяться.
    """
    if not quotes.валюта_из(строка) or not docfilter.part_number_of(строка):
        return None
    числа = [v for v in quotes._числа_строки(строка) if v and v > 0]
    return числа[-1] if числа else None


КАНДИДАТЫ = (("К1 число вплотную к валюте", к1_число_при_валюте),
             ("К2 пара «кол-во ед. цена»", к2_пара_количество_цена),
             ("К3 правое число при артикуле", к3_последнее_число_при_артикуле))


def таблица(заголовок: str, счётчик: dict, всего: int, ширина: int = 34) -> None:
    print(f"\n{заголовок}")
    for ключ, n in sorted(счётчик.items(), key=lambda kv: -kv[1]):
        доля = f"{100 * n / всего:.1f} %" if всего else "—"
        print(f"    {str(ключ)[:ширина]:{ширина}s} {n:>8d}  {доля:>7s}")


def main() -> int:
    dsn = os.environ.get("SUPABASE_DB_URL", "").strip()
    if not dsn:
        print("нет SUPABASE_DB_URL — мерить нечего")
        return 2
    import psycopg2

    conn = psycopg2.connect(dsn, connect_timeout=20,
                            options="-c statement_timeout=600000")
    отказ: dict[str, int] = {}
    по_пути: dict[str, int] = {}
    прочитано_по_пути: dict[str, int] = {}
    профиль_отказа: dict[str, int] = {}
    # Коды.
    с_артикулом = 0
    с_артикулом_без_денег = 0
    денежных_строк = 0
    # Кандидаты: сколько взяли там, где правило молчит, и как ведут себя там,
    # где ответ известен.
    взяли = {имя: 0 for имя, _ in КАНДИДАТЫ}
    совпали = {имя: 0 for имя, _ in КАНДИДАТЫ}
    ответили_на_известном = {имя: 0 for имя, _ in КАНДИДАТЫ}
    известных = 0
    всего = 0

    try:
        with conn.cursor(name="калибровка") as cur:
            cur.itersize = 5000
            cur.execute(СТРОКИ, (ПРЕДЛОЖЕНИЕ, LIMIT))
            for путь, строка in cur:
                всего += 1
                по_пути[путь] = по_пути.get(путь, 0) + 1
                причина, проф = ворота(строка)
                отказ[причина] = отказ.get(причина, 0) + 1

                # Коды: цена денежного подавления в part_number_of.
                деньги = bool(docfilter.MONEY.search(строка))
                денежных_строк += деньги
                есть = bool(docfilter.part_number_of(строка))
                с_артикулом += есть
                if деньги and not есть:
                    # Та же строка без денежных слов: получила бы она артикул?
                    без = docfilter.MONEY.sub(" ", строка)
                    if docfilter.part_number_of(без):
                        с_артикулом_без_денег += 1

                эталон = quotes.цена_из_текста(строка)
                if эталон is not None:
                    прочитано_по_пути[путь] = прочитано_по_пути.get(путь, 0) + 1
                    известных += 1
                else:
                    ключ = ключ_профиля(причина, проф.get("чисел", 0),
                                        проф["валюта"], проф["артикул"])
                    профиль_отказа[ключ] = профиль_отказа.get(ключ, 0) + 1

                for имя, f in КАНДИДАТЫ:
                    v = f(строка)
                    if v is None:
                        continue
                    if эталон is None:
                        взяли[имя] += 1
                    else:
                        ответили_на_известном[имя] += 1
                        совпали[имя] += abs(v - эталон["price"]) < 0.01
    finally:
        conn.close()

    if not всего:
        print("строк предложений не нашлось")
        return 1

    print(f"=== ПОЧЕМУ ЦЕНА НЕ ПРОЧИТАНА. Строк предложений в выборке: {всего} "
          f"(предел выборки {LIMIT}) ===")
    таблица("СТРОКИ ПО ПУТИ РАЗБОРА ФАЙЛА:", по_пути, всего, 20)
    for путь, n in sorted(по_пути.items(), key=lambda kv: -kv[1]):
        п = прочитано_по_пути.get(путь, 0)
        print(f"    из них цена прочитана: {путь:14s} {п:>8d}"
              f"  {100 * п / n:.1f} %")

    таблица("ВОРОТА, ОСТАНОВИВШИЕ СТРОКУ (правило цены из текста):",
            отказ, всего)

    print("\nПРОФИЛЬ ОТКАЗА (структура строки, не её содержимое). Двадцать")
    print("самых частых сочетаний — по ним видно, какое послабление что даст:")
    for ключ, n in sorted(профиль_отказа.items(), key=lambda kv: -kv[1])[:20]:
        print(f"    {ключ:64s} {n:>8d}  {100 * n / всего:.1f} %")

    print("\nРАСПОЗНАВАНИЕ КОДА (владелец: «99 % с номенклатурными позициями»):")
    print(f"    артикул распознан                  {с_артикулом:>8d}"
          f"  {100 * с_артикулом / всего:.1f} %")
    print(f"    строк с денежными словами          {денежных_строк:>8d}"
          f"  {100 * денежных_строк / всего:.1f} %")
    print(f"    артикул ПОДАВЛЕН денежным словом   {с_артикулом_без_денег:>8d}"
          f"  {100 * с_артикулом_без_денег / всего:.1f} %")
    print("    Подавление защищает от «сумма принята за артикул». В строке КП")
    print("    денежное слово есть всегда, поэтому здесь оно бьёт по голым")
    print("    номенклатурным номерам — 6205, 22315 — то есть по самому частому")
    print("    виду кода в предложении.")

    print(f"\nКАНДИДАТЫ. «Взял» — строки, где правило молчит, а кандидат назвал")
    print(f"цену. «Согласие» — доля совпадений там, где арифметика уже дала")
    print(f"ответ ({известных} строк): кандидат, который врёт на известном,")
    print("на неизвестном не лучше.")
    for имя, _ in КАНДИДАТЫ:
        о = ответили_на_известном[имя]
        с = f"{100 * совпали[имя] / о:.1f} %" if о else "не проверен"
        print(f"    {имя:32s} взял {взяли[имя]:>7d} (+{100 * взяли[имя] / всего:.1f} %)"
              f" · согласие {с:>12s} на {о} строках")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
