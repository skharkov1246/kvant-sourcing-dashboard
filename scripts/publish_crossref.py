#!/usr/bin/env python3
"""Снимок перекрёстной системы «позиция ↔ поставщик» в KV.

КЛЮЧЕЙ СОРОК ОДИН, ЗАКРЫТЫМ СПИСКОМ (library/crossref.ВСЕ_КЛЮЧИ): заголовок
crossref:v1, восемь частей списка crossref:list:NN и тридцать две корзины
подробностей crossref:offers:NN. Одним ключом снимок перестал помещаться в
8 МиБ 24.09.2026 (прогон 35986620488: 10,51 МиБ); почему разложен именно так —
над crossref.ПОТОЛОК_ПОЗИЦИЙ.

ЗАЧЕМ ОТДЕЛЬНЫЙ КЛЮЧ, А НЕ ПОЛЕ В suppliers:v1. Реестр поставщиков меняется
сведением (раз в неделю), а котировки — каждым ночным разбором. Один ключ
означал бы перезапись реестра при каждом разборе и наоборот: два прогона,
пишущие один ключ, рано или поздно затрут работу друг друга.

ПОЧЕМУ ОДНА СБОРКА НА ОБЕ КАРТОЧКИ. Это один граф, прочитанный с двух сторон.
Разойдись две сборки — и страница позиции покажет поставщика, которого страница
поставщика не знает. Поэтому ключи — части ОДНОГО снимка одного прохода, а не
отдельные сборки.

Клиент Cloudflare берётся у публикатора поставщиков: второй стек разбора
ответов, повторов и сверки записи был бы второй же поверхностью для ошибок.
Список ключей при этом СВОЙ и по-прежнему закрытый — этот публикатор не может
переписать ни suppliers:v1, ни acl:v1, ни brands:*.

В журнал — только агрегаты (правило 17): счётчики, размер снимка, свои
константы. Ни наименований позиций, ни названий компаний.

    SUPABASE_DB_URL=… CLOUDFLARE_ACCOUNT_ID=… CLOUDFLARE_API_TOKEN=… \
      python scripts/publish_crossref.py --apply
"""
from __future__ import annotations

import argparse
import datetime as dt
import importlib.util
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from library import brands, company_names, crossref  # noqa: E402

KEY = crossref.КЛЮЧ
# Код возврата для переполнения предела: прогон обязан покраснеть именно на нём, а
# на сбое сети — нет. Разбор этого кода — в .github/workflows/suppliers-quotes.yml.
КОД_ПЕРЕПОЛНЕНИЯ = 2
# Запас до предела: больше этой доли — предупреждение в журнал. Не отказ: ключ
# ещё влезает, но о приближении к потолку надо узнать до упавшего прогона.
ЗАПАС = 0.80


def _публикатор():
    """Модуль публикатора поставщиков как библиотека.

    Обычным импортом он не берётся: scripts/ — не пакет, и делать его пакетом
    ради одного класса значит менять пути у всего, что там лежит.
    """
    spec = importlib.util.spec_from_file_location(
        "kvant_publish_suppliers", ROOT / "scripts" / "publish_suppliers.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def читать_базу(dsn):
    ps = _публикатор()
    ps.require(isinstance(dsn, str) and dsn.strip(), "SUPABASE_DSN_MISSING")
    import psycopg2

    conn = psycopg2.connect(dsn, connect_timeout=20,
                            options="-c statement_timeout=180000")
    # ТОЛЬКО ЧТЕНИЕ, ОДНИМ СНИМКОМ БАЗЫ. Бренд позиции решается при чтении
    # (правило П9): база не переписывается, и сессия это гарантирует, а не
    # обещает. Одна транзакция — чтобы котировки, спрос и реестр брендов
    # посчитались по одному состоянию, пока ночной разбор пишет цены.
    conn.set_session(readonly=True, isolation_level="REPEATABLE READ")
    try:
        with conn.cursor() as cur:
            наборы = []
            # Вида имён может ещё не быть в рабочей базе — тогда на его месте
            # пустая выборка, и имя компании остаётся display_name.
            есть = company_names.вид_имён_есть(cur)
            for sql in (crossref.ПРЕДЛОЖЕНИЯ_SQL, crossref.КАТАЛОГ_SQL,
                        crossref.АНАЛОГИ_SQL, crossref.МАШИНЫ_SQL,
                        crossref.ИЗГОТОВИТЕЛИ_SQL, crossref.СПРОС_SQL):
                cur.execute(company_names.имена_sql(sql, есть), (crossref.FEED,))
                наборы.append(cur.fetchall())
            # Имена брендов карточки запроса — из реестра, если он в базе есть.
            наборы.append(crossref.имена_брендов(cur))
            # Бренд позиции (П2): ячейки изготовителя спецификаций по коду и
            # реестр брендов, которым узнаётся бренд строки. Реестра нет —
            # None, и сборка узнаёт бренд по словарю-файлу.
            cur.execute(crossref.СПРОС_БРЕНДЫ_SQL, (crossref.FEED,))
            наборы.append(cur.fetchall())
            наборы.append(brands.читать_реестр(cur))
        conn.rollback()
        return наборы
    finally:
        conn.close()


def реестр_сборки(реестр_базы):
    """Чем сборка узнаёт бренд: реестр базы, а без него — словарь-файл.

    То же, что у публикатора /brands: записи словаря, которые не бренд
    (указание, несколько, описание, номер — library/oem_kind.py), брендом не
    считаются и в реестре базы, засеянном до пометок; их части раскладываются
    по брендам словаря-файла (brands.разложение_словаря)."""
    словарь = brands.читать_файл(brands.ФАЙЛ_СЛОВАРЯ)
    разложение = brands.разложение_словаря(словарь)
    if реестр_базы:
        реестр_базы = brands.реестр_без_не_брендов(реестр_базы, brands.ключи_не_брендов(словарь))
        return crossref.реестр_брендов(реестр_базы["словарь"], разложение=разложение,
                                       карточка=реестр_базы["карточка"],
                                       откуда="реестр базы")
    return crossref.реестр_брендов(словарь, разложение=разложение, откуда="словарь-файл")


def печать_бренда(t: dict, р: dict) -> None:
    """Бренд позиции в журнал — только числа (правило 17)."""
    б = t.get("brand") or {}
    всего = t["positions"]
    доля = 100 * б.get("determined", 0) / всего if всего else 0.0
    print(f"бренд позиции (пара «бренд + код», П1–П2): кодов {б.get('codes', 0)} → позиций "
          f"{всего}; с определённым брендом {б.get('determined', 0)} из {всего} ({доля:.1f} %)")
    по = б.get("by") or {}
    print("  по источнику: " + " · ".join(f"{и} {по.get(и, 0)}" for и in crossref.ИСТОЧНИКИ_БРЕНДА)
          + f"; ключ бренда — {р.get('откуда')} (брендов {len(р.get('имена') or {})}, "
          f"написаний {len(р.get('карта') or {})})")
    print(f"  «Бренд не определён»: нет источников {б.get('none', 0)} · спорно {б.get('disputed', 0)}")
    print(f"  кодов разбито на две пары и больше: {б.get('split', 0)}; предложений ушло в другую "
          f"пару кода: {б.get('moved', 0)}; отнесено к бренду кода без своего бренда: "
          f"{б.get('joined', 0)}")
    print(f"  предложений по кодам до разбиения {б.get('offers_coded', 0)} → по парам "
          f"{t['offers']} (обязаны совпасть: разбиение предложений не теряет)")
    print(f"  стало хуже: выбор из двух компаний пропал у {б.get('choice_lost', 0)} кодов, "
          f"сравнимость цен — у {б.get('cmp_lost', 0)}")
    # «Сравнимы» — цены двух компаний (crossref.сравнима); снятое прежним
    # правилом «две цены в одной валюте» — по двум причинам раздельно.
    print(f"  «сравнимы» снято: две цены одной компании {б.get('cmp_one_co', 0)} (дефект "
          f"n.cmp_co) · компаний две, цену в валюте дала одна {б.get('cmp_one_priced', 0)} "
          f"(стало хуже); сравнимых теперь {t.get('comparable', 0)}")
    print(f"  маска кода без подтверждения (бренд не дан): {б.get('mask_unconfirmed', 0)}; "
          f"каталог против спецификации (взят каталог): {б.get('cat_vs_row', 0)}; строка КП "
          f"с двумя брендами реестра: {б.get('row_multi', 0)}; ячеек спроса не со стороны "
          f"заказчика (в дело не шли): {б.get('spec_other_side', 0)}")


def main(argv=None):
    parser = argparse.ArgumentParser(description="Снимок перекрёстной системы в KV")
    parser.add_argument("--apply", action="store_true", help="записать в KV (иначе вхолостую)")
    parser.add_argument("--out", help="сохранить снимок в файл (для проверки глазами)")
    args = parser.parse_args(argv)

    ps = _публикатор()

    class CloudflareCross(ps.Cloudflare):
        КЛЮЧИ = crossref.ВСЕ_КЛЮЧИ

    try:
        наборы = читать_базу(os.environ.get("SUPABASE_DB_URL"))
        (предложения, каталог, аналоги, машины, изготовители, спрос, имена,
         спрос_бренды, реестр_базы) = наборы
        р = реестр_сборки(реестр_базы)
        собран = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        снимок = crossref.собрать(предложения, каталог, аналоги, машины,
                                  изготовители, спрос, собран=собран,
                                  имена_брендов=имена, спрос_бренды=спрос_бренды,
                                  реестр=р)
        print(f"брендов карточки запроса с именем из реестра: {len(имена)}"
              + ("" if имена else " — реестра нет, бренды остаются номерами"))
        сырые = {k: json.dumps(v, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
                 for k, v in crossref.разложить(снимок).items()}
        t = снимок["totals"]
        print(f"позиций: {t['positions']}, из них с выбором из двух компаний: "
              f"{t['with_choice']}, сравнимых по цене: {t['comparable']}")
        print(f"в каталоге: {t['in_catalog']} — только у них будут аналоги, "
              "машина и изготовитель")
        print(f"компаний: {t['companies']}, сведено с реестром: "
              f"{t['companies_resolved']} — у остальных карточка не откроется")
        # Позиции без выбора — это и есть список работы по вторым поставщикам;
        # число выводится вычитанием, а не отдельным счётчиком. Отдельный
        # счётчик «без выбора и со спросом» уже был и выдал ровно ту же цифру:
        # спрос есть у всех позиций, потому что артикулы котировок берутся из
        # спецификаций. Печатается то, что действительно сужает: позиции, которых
        # в спросе нет вовсе.
        печать_бренда(t, р)
        print(f"без выбора: {t['positions'] - t['with_choice']}"
              " — по ним и надо запрашивать вторых поставщиков")
        print(f"нет в спросе вовсе: {t.get('no_demand', 0)}"
              " — котировка на артикул из-за пределов наших спецификаций")
        # ТОЧНЫЕ ДУБЛИ ПРЕДЛОЖЕНИЙ (crossref.ключ_дубля) — сколько схлопнуто и
        # откуда они: по этим числам видно, чинить ли чтение полей карточки,
        # разбор файла или ничего (одно КП на нескольких карточках).
        д = снимок.get("dups") or {}
        print(f"строк котировок: {t.get('offer_rows', t['offers'])} → предложений: {t['offers']}; "
              "точные дубли (компания, цена, валюта, количество, дата): предложений с копиями — "
              f"{д.get('groups', 0)}, лишних строк — {д.get('rows', 0)}")
        print(f"  откуда: с разных карточек {д.get('cards', 0)} · одна карточка, разные файлы "
              f"{д.get('one_card', 0)} · повтор в одном файле {д.get('one_file', 0)} · "
              f"файл неизвестен {д.get('no_file', 0)}")
        print(f"  копия несла значение, которого предложение не покажет: {д.get('differ', 0)}"
              " (у предложения пометка «копии различаются»)")
        # РАЗМЕР КАЖДОГО ВИДА КЛЮЧЕЙ: заголовок, самая тяжёлая часть списка,
        # самая тяжёлая корзина. Сумма — для сравнения с прежним единым снимком.
        предел = ps.MAX_BYTES
        def доля(n):
            return f"{n} Б ({n / 1024 / 1024:.2f} МиБ, {100 * n / предел:.1f} % предела)"
        части = [len(сырые[k]) for k in crossref.КЛЮЧИ_СПИСКА]
        корзины = [len(сырые[k]) for k in crossref.КЛЮЧИ_КОРЗИН]
        print(f"предложений всего: {t['offers']}; ключей {len(сырые)}, "
              f"всего {sum(map(len, сырые.values())) / 1024 / 1024:.2f} МиБ")
        print(f"  заголовок {KEY}: {доля(len(сырые[KEY]))}")
        print(f"  часть списка, самая тяжёлая из {len(части)}: {доля(max(части))}")
        print(f"  корзина, самая тяжёлая из {len(корзины)}: {доля(max(корзины))}")
        самый = max(map(len, сырые.values()))
        if самый > предел * ЗАПАС:
            print(f"::warning::самый тяжёлый ключ занимает {100 * самый / предел:.0f} % "
                  "предела: при росте он перестанет помещаться (crossref.ПОТОЛОК_ПОЗИЦИЙ)")

        # РАЗМЕР — ГЕЙТ, А НЕ ПРИМЕЧАНИЕ, и для КАЖДОГО ключа. Отказ здесь
        # громче, чем усечённая страница: усечение молча уносит часть номенклатуры.
        ps.require(all(len(v) <= предел for v in сырые.values()), "SNAPSHOT_TOO_LARGE")
        ps.require(t["positions"] > 0, "SNAPSHOT_EMPTY")
        # Разбиение кода на пары «бренд + код» не теряет и не удваивает
        # предложений: каждое идёт ровно в одну пару (crossref.бренд_позиции).
        ps.require((t.get("brand") or {}).get("offers_coded") == t["offers"], "OFFERS_LOST")

        if args.out:
            папка = Path(args.out)
            папка.mkdir(parents=True, exist_ok=True)
            for k, raw in сырые.items():
                (папка / (k.replace(":", "_") + ".json")).write_bytes(raw)
            print(f"ключи сохранены в {папка}")

        if not args.apply:
            print("вхолостую: в KV ничего не записано (--apply включает запись)")
            return 0

        cf = CloudflareCross(os.environ.get("CLOUDFLARE_ACCOUNT_ID", ""),
                             os.environ.get("CLOUDFLARE_API_TOKEN", ""))
        namespace = cf.namespace()
        # ПОРЯДОК ЗАПИСИ: корзины, части списка, заголовок последним. Страница
        # читает заголовок первой; пока он прежний (единый снимок с positions),
        # она не идёт ни в части, ни в корзины, а прежний снимок самодостаточен.
        # Упади запись посередине — страница останется на вчерашнем целиком, а не
        # на смеси там, где смесь опасна.
        #
        # СМЕСЬ ВСЁ РАВНО ВОЗМОЖНА: запись оборвалась после частей, но до
        # заголовка, или KV ещё не разнёс новый заголовок по узлам (до минуты).
        # Тогда номера компаний в рёбрах указывали бы в чужой список companies.
        # Поэтому у каждой части и корзины стоит published_at своей сборки, и
        # страница сверяет её с заголовком: часть списка чужой сборки — отказ со
        # словами «снимок обновляется», корзина чужой сборки — оговорка в карточке.
        for k in crossref.КЛЮЧИ_КОРЗИН + crossref.КЛЮЧИ_СПИСКА + (KEY,):
            cf.put(namespace, k, сырые[k])
        print(f"опубликовано в KV: {len(сырые)} ключей ({KEY}, частей списка "
              f"{crossref.СПИСОК_ЧАСТЕЙ}, корзин {crossref.КОРЗИН})")
        return 0
    except ps.PublishError as e:
        print(f"::error::публикация не состоялась: {e}")
        # РАЗНЫЕ КОДЫ ВОЗВРАТА — РАЗНЫЕ БЕДЫ, И ГЛУШИТЬ ИХ ОДИНАКОВО НЕЛЬЗЯ.
        # Шаг публикации стоит под continue-on-error, и это верно для
        # недоступного Cloudflare: разбор уже сделан, терять его из-за чужого
        # сбоя незачем. Но тем же глушителем накрывало и переполнение предела, а
        # это беда другой природы: она не пройдёт сама, страница навсегда
        # останется на вчерашнем снимке, и прогон при этом отчитается успехом.
        # Позиции растут с каждым разбором, поэтому случай не гипотетический:
        # 24.09.2026 единый снимок так и упал (см. crossref.ПОТОЛОК_ПОЗИЦИЙ).
        return КОД_ПЕРЕПОЛНЕНИЯ if str(e) == "SNAPSHOT_TOO_LARGE" else 1


if __name__ == "__main__":
    raise SystemExit(main())
