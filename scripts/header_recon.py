#!/usr/bin/env python3
"""ПОЧЕМУ ШАПКА ТАБЛИЦЫ НЕ УЗНАНА. Разведка перед правкой правила.

ЗАЧЕМ. Воронка разбора 22.09.2026 назвала главный резерв цифрами:

    таблица + шапка найдена   1 430 файлов ·  74 514 позиций · 17 684 строк цены
    таблица, шапка НЕ найдена   720 файлов ·  59 214 позиций ·    187 строк цены
    текст (таблицы нет)       3 471 файл  · 334 155 позиций ·  6 578 строк цены

Там, где шапка нашлась, цену дают 71,5 % файлов; где таблица есть, а шапка нет —
0,8 %. Файлы при этом похожи: медиана позиций 30 против 37, медиана знаков 1 657
против 1 644. Значит дело в разборщике, а не в документах.

ТРИ ВОЗМОЖНЫЕ ПРИЧИНЫ, И ПРАВИТЬ НАДО РАЗНОЕ:

  1. заголовки написаны словами вне закрытого списка («Unit price», «Amount») —
     править список слов;
  2. шапка разбита на две строки или склеена объединёнными ячейками — править
     правило склейки;
  3. шапки нет вовсе — переходить к опознанию колонки по ФОРМЕ данных: колонка,
     где большинство ячеек — правдоподобные числа, а тройка «кол-во × цена =
     сумма» сходится по строкам.

Разведка меряет, какая из трёх, и ничего не меняет. Правило сначала меряют
(CLAUDE.md, правило 3).

ПОЧЕМУ НУЖЕН ПЕРЕЧИТ ФАЙЛОВ. Текст файла в базе не хранится — только счётчики
(chars, text_lines, item_lines, header_found). Ни одна из трёх причин по ним не
различима, поэтому файлы читаются заново через портал. Берётся ВЫБОРКА (LIMIT), а
не все: ответ на вопрос «какая причина» выборка даёт, а портал жалеть надо.

ЧТО ПЕЧАТАЕТСЯ И ПОЧЕМУ ЭТО МОЖНО. Только агрегаты и частотный список слов из
ЗАГОЛОВКОВ под фильтром правила 17: от шести букв и порог по числу РАЗНЫХ файлов.
Заголовок таблицы — устройство документа, а не его содержимое; наименований
позиций, количеств и цен в выводе нет. Латиница печатается на тех же условиях, что
кириллица: именно латинские заголовки и нужно обнаружить, а название компании,
встретившееся в шапках трёх разных поставщиков, — невозможное событие.

    SUPABASE_DB_URL=… BITRIX_WEBHOOK_URL=… LIMIT=200 python scripts/header_recon.py
"""
from __future__ import annotations

import collections
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "library"))
sys.path.insert(0, str(ROOT / "scripts"))

import pdftable  # noqa: E402
import quotes  # noqa: E402
from library import indexer  # noqa: E402

# СНАЧАЛА СПРОСИ БАЗУ, КАКИЕ ЭТО ФАЙЛЫ. Первая версия разведки отбирала kind =
# 'pdf' по догадке — и дала бы пусто: rows_from_pdf отвергает разрез, если шапка не
# узнана (годится=header_map), значит для PDF «таблица без шапки» невозможна по
# устройству кода. Разбор xlsx/docx устроен иначе: таблица там уже есть, и шапка
# ищется в ней. Догадка о виде файла стоила бы холостого перечита портала.
РАЗБОРКА = """
select coalesce(f.kind, '(не определён)')            as вид,
       coalesce(f.parser_version, 1)                  as версия,
       count(*)::bigint                               as файлов,
       sum(coalesce(f.rows_found, 0))::bigint          as позиций
  from lib_files f
 where f.status = 'разобран'
   and f.origin = 'поле запроса'
   and f.parse_path = 'таблица'
   and f.header_found is not true
 group by 1, 2
 order by 4 desc nulls last
"""

# Файлы, где таблица восстановлена, а шапка не узнана. Только предложения: у
# спецификаций заказчика цены нет по определению, и искать её там нечего.
КАНДИДАТЫ = """
select f.file_id, coalesce(f.kind, ''), coalesce(f.rows_found, 0) as позиций
  from lib_files f
 where f.status = 'разобран'
   and f.origin = 'поле запроса'
   and f.parse_path = 'таблица'
   and f.header_found is not true
 order by f.rows_found desc nulls last
 limit %s
"""

# Похоже на строку заголовков: несколько коротких нечисловых ячеек с буквами.
# Порог мягкий намеренно: разведка ищет КАНДИДАТОВ, а не выносит приговор.
МИН_ЯЧЕЕК = 3
МАКС_ДЛИНА_ЯЧЕЙКИ = 48
ЧИСЛО = re.compile(r"^[\s\d.,%×xX*/+()-]+$")
СЛОВО = re.compile(r"[0-9A-Za-zА-Яа-яЁё]{6,}")
# Порог частотного списка — по числу РАЗНЫХ файлов, а не по числу вхождений: одно
# слово, повторённое сто раз в одном документе, о рынке не говорит ничего.
ПОРОГ_ФАЙЛОВ = 3


def похоже_на_шапку(ячейки: list[str]) -> bool:
    годных = [c for c in ячейки
              if c and len(c) <= МАКС_ДЛИНА_ЯЧЕЙКИ and not ЧИСЛО.match(c)
              and re.search(r"[A-Za-zА-Яа-яЁё]", c)]
    return len(годных) >= МИН_ЯЧЕЕК


def числовая_доля(колонка: list[str]) -> float:
    заполнено = [c for c in колонка if c and c.strip()]
    if not заполнено:
        return 0.0
    чисел = sum(1 for c in заполнено if quotes.число_из(c) is not None)
    return чисел / len(заполнено)


def тройка_сходится(таблица: list[list[str]]) -> bool:
    """Есть ли три колонки, где «кол-во × цена = сумма» сходится по строкам.

    Это проверка причины 3: если тройка сходится, цену можно взять по ФОРМЕ, не
    зная заголовков вовсе. Допуск — процент: в КП округляют.
    """
    if not таблица:
        return False
    ширина = max(len(r) for r in таблица)
    колонки = [[r[j] if j < len(r) else "" for r in таблица] for j in range(ширина)]
    числовые = [j for j, k in enumerate(колонки) if числовая_доля(k) >= 0.6]
    for a in числовые:
        for b in числовые:
            for c in числовые:
                if len({a, b, c}) < 3:
                    continue
                сошлось = 0
                всего = 0
                for r in таблица:
                    x, y, z = (quotes.число_из(r[j]) if j < len(r) else None for j in (a, b, c))
                    if None in (x, y, z) or 0 in (x, y):
                        continue
                    всего += 1
                    if abs(x * y - z) <= max(abs(z) * 0.01, 0.02):
                        сошлось += 1
                if всего >= 3 and сошлось >= max(3, int(всего * 0.7)):
                    return True
    return False


def main() -> int:
    for имя in ("SUPABASE_DB_URL", "BITRIX_WEBHOOK_URL"):
        if not os.environ.get(имя, "").strip():
            print(f"::error::нет {имя}")
            return 2
    предел = int(os.environ.get("LIMIT", "200") or 200)
    import psycopg2

    conn = psycopg2.connect(os.environ["SUPABASE_DB_URL"], connect_timeout=20,
                            options="-c statement_timeout=120000")
    try:
        with conn.cursor() as cur:
            cur.execute(РАЗБОРКА)
            разборка = cur.fetchall()
            cur.execute(КАНДИДАТЫ, (предел,))
            файлы = cur.fetchall()
    finally:
        conn.close()

    print("=== ПОЧЕМУ ШАПКА ТАБЛИЦЫ НЕ УЗНАНА ===")
    print("ЧТО ЭТО ЗА ФАЙЛЫ (таблица есть, шапки нет), по виду и версии разборщика:")
    for вид, версия, файлов, позиций in разборка:
        print(f"    {вид:<16s} v{версия}  файлов {int(файлов):>6d} · позиций"
              f" {int(позиций or 0):>8d}")
    if not разборка:
        print("    ни одного — резерв закрыт, мерить нечего")
        return 0
    print(f"\nвыборка к перечитыванию: {len(файлы)} файлов. Это ВЫБОРКА, а не все:")
    print("ответ на «какая причина» она даёт, и портал читается меньше.\n")

    итог = collections.Counter()
    слова_по_файлам: dict[str, set[str]] = collections.defaultdict(set)
    прочитано = 0
    for file_id, вид, _позиций in файлы:
        b = indexer.download({"id": file_id})
        if not b:
            итог["файл не скачался"] += 1
            continue
        прочитано += 1
        # ЧИТАТЕЛЬ ПО ВИДУ ФАЙЛА — ТОТ ЖЕ, ЧТО У РАЗБОРА. Свой читатель здесь
        # означал бы, что разведка меряет не то, что делает разборщик.
        # Читатели — ровно те, что у разбора: свой означал бы, что разведка меряет
        # не то, что делает разборщик. Для PDF шапку НЕ навязываем: rows_from_pdf
        # отвергает разрез без узнанной шапки, а нам нужен именно разрез без неё.
        if вид == "pdf":
            текст = indexer.text_from_pdf(b)
            таблица = pdftable.строки_в_таблицу(текст) if текст else []
        elif вид == "xlsx/docx":
            таблица = indexer.rows_from_xlsx(b) or indexer.rows_from_docx(b) or []
        else:
            таблица = (indexer.rows_from_xlsx(b) or indexer.rows_from_docx(b)
                       or pdftable.строки_в_таблицу(indexer.text_from_pdf(b) or "") or [])
        if not таблица or max((len(r) for r in таблица), default=0) < 2:
            итог["таблица не восстановилась при перечитывании"] += 1
            continue
        шапки = [r for r in таблица[:12] if похоже_на_шапку(r)]
        if not шапки:
            итог["строки, похожей на шапку, НЕТ"] += 1
        else:
            узнана = any(quotes.колонки_цены(r).get("price") is not None
                         or quotes.колонки_цены(r).get("total") is not None
                         for r in шапки)
            if узнана:
                итог["шапка ЕСТЬ и правило её узнаёт — расходится с пометкой в базе"] += 1
            else:
                итог["шапка ЕСТЬ, но слова правилу неизвестны"] += 1
                for r in шапки:
                    for c in r:
                        if c and len(c) <= МАКС_ДЛИНА_ЯЧЕЙКИ and not ЧИСЛО.match(c):
                            for w in СЛОВО.findall(c.lower()):
                                слова_по_файлам[w].add(file_id)
        if тройка_сходится(таблица):
            итог["тройка «кол-во × цена = сумма» сходится — цену можно взять по форме"] += 1

    print(f"прочитано файлов: {прочитано} из {len(файлы)}\n")
    print("ПРИЧИНЫ:")
    for причина, n in итог.most_common():
        доля = f"  {100 * n / max(прочитано, 1):5.1f} %" if прочитано else ""
        print(f"    {n:>5d}{доля}  {причина}")

    частые = sorted(((len(ф), w) for w, ф in слова_по_файлам.items()
                     if len(ф) >= ПОРОГ_ФАЙЛОВ), reverse=True)
    print(f"\nСЛОВА ЗАГОЛОВКОВ, КОТОРЫХ ПРАВИЛО НЕ ЗНАЕТ (от {ПОРОГ_ФАЙЛОВ} разных"
          " файлов, от шести букв):")
    if not частые:
        print("    ни одного — значит причина не в словах")
    for n, w in частые[:40]:
        print(f"    {n:>4d} файлов  {w}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
