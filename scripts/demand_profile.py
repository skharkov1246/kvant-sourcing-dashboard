#!/usr/bin/env python3
"""Что у нас спрашивают: профиль спроса и чего мы по нему не сделали.

ЗАЧЕМ. Распоряжение владельца 22.09.2026: сначала понять, в чём наша боль, —
изучить то, что мы запрашиваем, — и только потом искать, у кого запрашивать.
Порядок верный: кому писать, определяется тем, что спрашивают.

ГЛАВНЫЙ ВОПРОС ЗДЕСЬ НЕ «СКОЛЬКО У НАС СПРОСА», а «ПО ЧЕМУ МЫ НА РЫНОК НЕ
ВЫХОДИЛИ ВОВСЕ». Позиция, которую заказчик спросил, а мы даже не запросили
поставщиков, — это не пробел в данных, это упущенная сделка. Число таких позиций
и есть боль в чистом виде, всё остальное в этом отчёте — её разрез.

ЧИТАЕМ ЖИВОЙ ВИД, А НЕ ТАБЛИЦУ. lib_demand_live исключает строки, помеченные как
текст тендерного документа (lib_row_junk). Считать пункт договора номенклатурой
значит завысить и спрос, и «непокрытое»: пункт договора никто не спрашивал, и
запрашивать его не надо.

ПОЗИЦИЯ БЕЗ АРТИКУЛА СЧИТАЕТСЯ ОТДЕЛЬНО. По ней ключа нет, значит с котировками
она не сводится — но и терять её молча нельзя: это спрос, по которому мы не можем
даже проверить, выходили ли на рынок.

В журнал — только агрегаты (правило 17): счётчики, доли, распределения. Ни
наименований позиций, ни номеров сделок, ни названий заказчиков.

    SUPABASE_DB_URL=… python scripts/demand_profile.py
"""
from __future__ import annotations

import os

FEED = "разбор КП"

# Пороги концентрации. Если 80 % спроса дают двести позиций, работа ограничена
# двумястами позициями, а не девятью тысячами — и это меняет всё планирование.
ДОЛИ = (0.50, 0.80, 0.95)

ОБЪЁМ = """
select count(*)                                                    as строк,
       count(distinct deal_id)                                     as сделок,
       count(*) filter (where coalesce(btrim(part_number), '') <> '') as с_артикулом,
       count(distinct lib_pn_key(part_number))
         filter (where lib_pn_key(part_number) <> '')               as позиций,
       count(*) filter (where qty is not null)                      as с_количеством,
       count(distinct coalesce(btrim(unit), ''))
         filter (where coalesce(btrim(unit), '') <> '')             as единиц,
       count(*) filter (where coalesce(btrim(oem), '') <> '')       as с_изготовителем,
       count(*) filter (where coalesce(btrim(model), '') <> '')     as с_машиной,
       count(distinct segment_id)                                   as сегментов
  from lib_demand_live
"""

# СКОЛЬКО МУСОРА ОТСЕЧЕНО. Разница между таблицей и живым видом — это то, что
# разметка признала текстом документа. Число нужно рядом: если оно велико, все
# доли ниже считаются от другого знаменателя, чем можно было ожидать.
ОТСЕВ = """
select (select count(*) from lib_demand)                            as всего_в_таблице,
       (select count(*) from lib_demand_live)                       as живых
"""

# КОНЦЕНТРАЦИЯ. Позиции по числу спросивших сделок, сверху вниз, и накопленная
# доля. Считается по СДЕЛКАМ, а не по строкам: две строки одной сделки об одной
# позиции — это один спрос, а не два.
КОНЦЕНТРАЦИЯ = """
with поз as (
  select lib_pn_key(part_number) as ключ,
         count(distinct deal_id) as сделок
    from lib_demand_live
   where lib_pn_key(part_number) <> ''
   group by 1
), сорт as (
  select ключ, сделок,
         sum(сделок) over (order by сделок desc, ключ)              as накоплено,
         sum(сделок) over ()                                        as итого,
         row_number() over (order by сделок desc, ключ)             as номер
    from поз
)
select %s::numeric as порог,
       min(номер)  as позиций_нужно,
       (select count(*) from поз) as позиций_всего
  from сорт
 where накоплено >= итого * %s
"""

ПОВТОРЯЕМОСТЬ = """
with поз as (
  select lib_pn_key(part_number) as ключ,
         count(distinct deal_id) as сделок
    from lib_demand_live
   where lib_pn_key(part_number) <> ''
   group by 1
)
select count(*)                                              as позиций,
       count(*) filter (where сделок = 1)                     as разовых,
       count(*) filter (where сделок >= 2)                    as повторных,
       count(*) filter (where сделок >= 5)                    as от_пяти,
       percentile_disc(0.5) within group (order by сделок)    as медиана,
       percentile_disc(0.9) within group (order by сделок)    as p90,
       max(сделок)                                            as максимум
  from поз
"""

# ПО ЧЕМУ МЫ НА РЫНОК НЕ ВЫХОДИЛИ. Позиции спроса, по которым нет ни одной
# котировки. Это и есть боль: заказчик спросил, а поставщиков мы не спрашивали.
#
# Воронка идёт по убыванию: спросили → запросили → получили цену → получили две
# цены. Каждая ступень — своя работа, и смешивать их нельзя.
НЕПОКРЫТОЕ = """
with спрос as (
  select lib_pn_key(part_number) as ключ,
         count(distinct deal_id) as сделок
    from lib_demand_live
   where lib_pn_key(part_number) <> ''
   group by 1
), котировки as (
  select lib_pn_key(part_number)                              as ключ,
         count(*)                                             as строк,
         count(*) filter (where price is not null and price > 0
                            and currency is not null)          as с_ценой,
         count(distinct rfq_company)                           as компаний
    from lib_prices
   where feed = %s and lib_pn_key(part_number) <> ''
   group by 1
)
select count(*)                                               as позиций_спроса,
       count(к.ключ)                                           as запрашивали,
       count(*) filter (where к.с_ценой > 0)                   as есть_цена,
       count(*) filter (where к.компаний >= 2)                 as есть_выбор,
       -- Те же ступени, но взвешенные спросом: позиция из тридцати сделок
       -- весит тридцать, а не одну. Иначе редкие позиции размывают картину.
       sum(с.сделок)                                           as спросов_всего,
       sum(с.сделок) filter (where к.ключ is not null)          as спросов_запрашивали,
       sum(с.сделок) filter (where к.с_ценой > 0)               as спросов_с_ценой,
       sum(с.сделок) filter (where к.компаний >= 2)             as спросов_с_выбором
  from спрос с
  left join котировки к on к.ключ = с.ключ
"""

# Разрезы: по сегменту и по изготовителю из спецификации. Оба — свои константы
# и названия сегментов, наименований позиций тут нет.
ПО_СЕГМЕНТАМ = """
select coalesce(segment_id, '(без сегмента)')                  as сегмент,
       count(*)                                                as строк,
       count(distinct deal_id)                                 as сделок,
       count(distinct lib_pn_key(part_number))
         filter (where lib_pn_key(part_number) <> '')          as позиций
  from lib_demand_live
 group by 1 order by 2 desc limit 15
"""

ПО_ИЗГОТОВИТЕЛЯМ = """
select btrim(oem)                                              as изготовитель,
       count(distinct deal_id)                                 as сделок,
       count(distinct lib_pn_key(part_number))
         filter (where lib_pn_key(part_number) <> '')          as позиций
  from lib_demand_live
 where coalesce(btrim(oem), '') <> ''
 group by 1 having count(distinct deal_id) >= 5
 order by 2 desc limit 20
"""


def доля(часть, целое) -> str:
    часть = часть or 0
    return f"{часть}" + (f" ({100 * часть / целое:.1f} %)" if целое else "")


def main() -> int:
    dsn = os.environ.get("SUPABASE_DB_URL", "").strip()
    if not dsn:
        print("нет SUPABASE_DB_URL — мерить нечего")
        return 2
    import psycopg2

    conn = psycopg2.connect(dsn, connect_timeout=20,
                            options="-c statement_timeout=300000")
    try:
        with conn.cursor() as cur:
            cur.execute(ОТСЕВ)
            всего, живых = cur.fetchone()
            print("=== ПРОФИЛЬ СПРОСА ===")
            print(f"строк в таблице: {всего} · живых (без текста документов): "
                  f"{доля(живых, всего)}")
            if живых == всего:
                print("  разметка текста документов не применялась — доли ниже "
                      "считаются по всему, что разобрано")

            cur.execute(ОБЪЁМ)
            (строк, сделок, с_артикулом, позиций, с_кол, единиц,
             с_изг, с_маш, сегментов) = cur.fetchone()
            print(f"\nсделок: {сделок} · сегментов: {сегментов}")
            print(f"строк: {строк}")
            print(f"  с артикулом:     {доля(с_артикулом, строк)}"
                  f"  → различных позиций: {позиций}")
            print(f"  с количеством:   {доля(с_кол, строк)} · единиц измерения: {единиц}")
            print(f"  с изготовителем: {доля(с_изг, строк)}")
            print(f"  с машиной:       {доля(с_маш, строк)}")
            if строк and с_артикулом < строк:
                print(f"  БЕЗ АРТИКУЛА {строк - с_артикулом} строк: по ним ключа нет,")
                print("  и проверить, выходили ли мы по ним на рынок, нельзя вовсе.")

            print("\nКОНЦЕНТРАЦИЯ (сколько позиций даёт такую долю всех спросов):")
            for д in ДОЛИ:
                cur.execute(КОНЦЕНТРАЦИЯ, (д, д))
                _, нужно, всего_поз = cur.fetchone()
                print(f"    {д:.0%} спроса дают {доля(нужно, всего_поз)} позиций")

            cur.execute(ПОВТОРЯЕМОСТЬ)
            (поз, разовых, повторных, от_пяти, мед, p90, макс) = cur.fetchone()
            print("\nПОВТОРЯЕМОСТЬ (позиция, которую спрашивают многие сделки,")
            print("стоит того, чтобы знать её наизусть):")
            print(f"    позиций: {поз} · спросили один раз: {доля(разовых, поз)}")
            print(f"    спросили дважды и более: {доля(повторных, поз)}"
                  f" · от пяти раз: {доля(от_пяти, поз)}")
            print(f"    сделок на позицию: медиана {мед} · p90 {p90} · максимум {макс}")

            cur.execute(НЕПОКРЫТОЕ, (FEED,))
            (поз_спроса, запрашивали, есть_цена, есть_выбор,
             сп_всего, сп_запр, сп_цена, сп_выбор) = cur.fetchone()
            print("\n=== ПО ЧЕМУ МЫ НА РЫНОК НЕ ВЫХОДИЛИ ===")
            print("воронка по ПОЗИЦИЯМ:")
            print(f"    спросили нас:        {поз_спроса}")
            print(f"    запрашивали рынок:   {доля(запрашивали, поз_спроса)}")
            print(f"    получили цену:       {доля(есть_цена, поз_спроса)}")
            print(f"    получили выбор (2+): {доля(есть_выбор, поз_спроса)}")
            print("та же воронка, ВЗВЕШЕННАЯ спросом (позиция из тридцати сделок")
            print("весит тридцать — иначе редкие позиции размывают картину):")
            print(f"    спросов всего:       {сп_всего}")
            print(f"    запрашивали рынок:   {доля(сп_запр, сп_всего)}")
            print(f"    получили цену:       {доля(сп_цена, сп_всего)}")
            print(f"    получили выбор (2+): {доля(сп_выбор, сп_всего)}")
            не_выходили = (поз_спроса or 0) - (запрашивали or 0)
            print(f"\nБОЛЬ: {не_выходили} позиций спросили, а поставщиков по ним")
            print("не запрашивали ни разу. Это не пробел в данных, это упущенные сделки.")

            cur.execute(ПО_СЕГМЕНТАМ)
            строки = cur.fetchall()
            if строки:
                print("\nпо сегментам (первые 15 по числу строк):")
                for сег, стр, сд, поз_с in строки:
                    print(f"    {сег[:34]:34s} строк {стр:>8d} · сделок {сд:>5d}"
                          f" · позиций {поз_с:>6d}")

            cur.execute(ПО_ИЗГОТОВИТЕЛЯМ)
            строки = cur.fetchall()
            if строки:
                print("\nизготовители, названные в спецификациях (от 5 сделок):")
                for имя, сд, поз_и in строки:
                    print(f"    {имя[:34]:34s} сделок {сд:>5d} · позиций {поз_и:>6d}")
        return 0
    finally:
        conn.close()


if __name__ == "__main__":
    raise SystemExit(main())
