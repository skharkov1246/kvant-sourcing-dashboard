_NEAR = re.compile(r"красноярск|абакан|кемеров|новокузнецк|иркутск|новосибирск|томск|ачинск", re.I)
_KRSK = re.compile(r"красноярск", re.I)

# Состояние наличия. Правило репозитория: «наличие» — не одно состояние, и складывать
# эти четыре в одно число нельзя.
#   по детали     — продавец подтвердил остаток по нашему парт-номеру. У нас таких НЕТ.
#   склад заявлен — компания заявляет склад и работает по этому классу. Не то же самое.
#   под заказ     — склада нет, возит под конкретную поставку.
#   не склад      — каталог, агрегатор, агент ввоза.
def stock_state(org: dict) -> str:
    text = " ".join(str(org.get(k) or "") for k in ("stock", "role", "note")).lower()
    if org.get("kind") == "маркетплейс" or "не склад" in text or "не поставщик" in text:
        return "не склад"
    if "нет склада" in text or "канал не работает" in text or "не продаёт" in text or "не торгует" in text:
        return "не склад"
    if re.search(r"склад|наличи|точ(?:ек|ки)|филиал|выдача|наименован", text):
        return "склад заявлен"
    return "под заказ"


