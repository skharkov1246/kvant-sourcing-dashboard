def canon(value: str) -> str:
    return re.sub(r"[^A-Z0-9]", "", str(value or "").upper())


def clean(value: str) -> str:
    """Убираем управляющие символы и лишние пробелы из полей таможни."""
    s = unicodedata.normalize("NFKC", str(value or "")).replace('"', "").strip()
    return re.sub(r"\s+", " ", s)


def _neg_date(value: str) -> str:
    """Ключ для сортировки дат по убыванию внутри возрастающего sort."""
    return "".join(chr(ord("9") - int(c)) if c.isdigit() else c for c in value or "")


def customs_leads() -> tuple[list[dict], dict]:
    """Импортёры genuine CAT из нашей таможенной базы: кто, откуда, каким маршрутом."""
    rows, files = [], sorted(CUSTOMS.glob("customs_*.json"))
    for path in files:
        if path.name == "_summary.json":
            continue
        payload = json.loads(path.read_text(encoding="utf-8"))
        for rec in payload.get("matched", []):
            blob = " ".join(clean(rec.get(k)) for k in ("brand", "exporter", "desc")).upper()
            if not re.search(r"\bCAT\b|CATERPILLAR", blob):
                continue
            rows.append({
                "date": rec.get("date"),
                "importer": clean(rec.get("importer")),
                "inn": clean(rec.get("inn")),
                "exporter": clean(rec.get("exporter")),
                "origin": clean(rec.get("origin")),
                "dispatch": clean(rec.get("dispatch")),
                "incoterms": clean(rec.get("incoterms")),
                "place": clean(rec.get("place")),
                "hs10": clean(rec.get("hs10")),
                "desc": clean(rec.get("desc"))[:180],
                "src": path.name,
            })

    # genuine = отправитель сам Caterpillar: такие компании имеют рабочий канал к заводу
    genuine = [r for r in rows if "CATERPILLAR" in r["exporter"].upper()]
    leads: dict[tuple[str, str], dict] = {}
    for r in genuine:
        key = (r["importer"], r["inn"])
        lead = leads.setdefault(key, {
            "importer": r["importer"], "inn": r["inn"], "shipments": 0,
            "last": "", "routes": Counter(), "hs": Counter(), "evidence": [],
            "_hs4": set(), "_desc": [],
        })
        lead["shipments"] += 1
        lead["last"] = max(lead["last"], r["date"] or "")
        lead["_hs4"].add(r["hs10"][:4])
        lead["_desc"].append(r["desc"])
        lead["routes"][f'{r["origin"]}→{r["dispatch"]}, {r["incoterms"]} {r["place"]}'] += 1
        lead["hs"][r["hs10"][:4]] += 1
        if len(lead["evidence"]) < 3:
            lead["evidence"].append({"date": r["date"], "hs10": r["hs10"], "desc": r["desc"], "src": r["src"]})

    out = []
    for lead in leads.values():
        lead["routes"] = [r for r, _ in lead["routes"].most_common()]
        lead["hs"] = [h for h, _ in lead["hs"].most_common()]
        lead["fit"] = fit_of(lead.pop("_hs4"), " ".join(lead.pop("_desc")))
        lead["role"], lead["role_note"] = ROLE.get(lead["inn"], ("трейдер", ""))
        out.append(lead)
    # Порядок обзвона, а не хронология: дилер, затем профильные трейдеры по свежести,
    # брокеры и владельцы парка — в конец.
    out.sort(key=lambda x: (ROLE_ORDER[x["role"]], FIT_ORDER[x["fit"]], _neg_date(x["last"])))

    stats = {
        "files": len([f for f in files if f.name != "_summary.json"]),
        "cat_rows": len(rows),
        "genuine_rows": len(genuine),
        "period": ["2023-01-01", "2026-03-31"],
        "note": "Агрегат нашей платной таможенной выгрузки: только факт ввоза и маршрут. "
                "Стоимости, веса и номера деклараций не переносятся.",
    }
    return out, stats


