def odm_leads() -> dict:
    """Афтермаркет Caterpillar в нашем справочнике ODM — и что из него годится сюда."""
    path = DATA / "odm_suppliers.json"
    if not path.exists():
        return {"relevant": [], "cat_records": 0, "note": "справочник ODM не найден"}
    cat, useful = 0, []
    need = re.compile(r"цилиндр|cylinder|литьё|литье|casting|поковк|forging|кронштейн|bracket|"
                      r"жгут|harness|проводк|wiring|трубк|tube |шланг|фитинг|elbow|adapter|"
                      r"радиатор|radiator|трансмисс|transmission gear|крышк[аи] (?!фильтр)", re.I)
    skip = re.compile(r"фильтр|filter|filtration", re.I)
    for rec in json.loads(path.read_text(encoding="utf-8")):
        blob = clean(rec.get("name")) + " " + clean(rec.get("makes"))
        if not re.search(r"CATERPILLAR|\bCAT\b", blob.upper()):
            continue
        cat += 1
        if skip.search(blob) or not need.search(blob):
            continue
        useful.append({
            "name": clean(rec.get("name")),
            "country": clean(rec.get("country")) or clean(rec.get("region")),
            "makes": clean(rec.get("makes"))[:180],
            "url": rec.get("catalog_url") or rec.get("source_url"),
            "confidence": rec.get("confidence"),
        })
    seen, uniq = set(), []
    for rec in useful:
        if rec["name"] in seen:
            continue
        seen.add(rec["name"])
        uniq.append(rec)
    return {"cat_records": cat, "relevant": uniq[:10], "note": ""}


def price_block(pp: int, qty: int) -> dict:
    """Оценка цены по позиции: genuine EXW и два альтернативных канала."""
    low, base, high, src = PRICE_USD[pp]
    out = {
        "price_exw_usd": {"low": low, "base": base, "high": high, "src": src},
        "line_exw_usd": {"low": low * qty, "base": base * qty, "high": high * qty},
    }
    alt = {}
    if pp not in NO_AFTERMARKET:
        f = CHANNEL_FACTOR["aftermarket_cn"]
        alt["aftermarket_cn"] = {"unit": round(base * f), "line": round(base * f) * qty}
    if pp not in NO_USED:
        f = CHANNEL_FACTOR["used_za"]
        alt["used_za"] = {"unit": round(base * f), "line": round(base * f) * qty}
    out["alt_exw_usd"] = alt
    return out


def budget(positions: list[dict]) -> dict:
    """Три сценария закупки по всей спецификации, USD EXW."""
    genuine = {k: sum(p["line_exw_usd"][k] for p in positions) for k in ("low", "base", "high")}
    # Смешанный: тяжёлое и узловое берём genuine, массовое — афтермаркет или б/у,
    # что дешевле из доступного по позиции.
    mixed = 0
    for p in positions:
        if p["stock_class"] == "массовый" and p["alt_exw_usd"]:
            mixed += min(v["line"] for v in p["alt_exw_usd"].values())
        else:
            mixed += p["line_exw_usd"]["base"]
    # Тяжёлое б/у: цилиндры и КПП берём с разбора, остальное genuine. Это и есть
    # настоящий рычаг — массовая механика в бюджете почти ничего не весит.
    heavy_used = 0
    for p in positions:
        alt = p["alt_exw_usd"].get("used_za")
        heavy_used += alt["line"] if (p["stock_class"] == "тяжёлый" and alt) else p["line_exw_usd"]["base"]
    # Экономный: где альтернатива есть — берём её, иначе genuine.
    cheap = sum(min([v["line"] for v in p["alt_exw_usd"].values()] or [p["line_exw_usd"]["base"]])
                for p in positions)
    heavy = sum(p["line_exw_usd"]["base"] for p in positions if p["stock_class"] == "тяжёлый")
    return {
        "currency": "USD", "basis": "EXW склад поставщика за рубежом, без фрахта, страховки и пошлин",
        "genuine": genuine,
        "mixed": round(mixed),
        "heavy_used": round(heavy_used),
        "cheap": round(cheap),
        "heavy_share_pct": round(100 * heavy / genuine["base"]),
        "transmission_share_pct": round(100 * next(p["line_exw_usd"]["base"] for p in positions
                                                   if p["pp"] == 16) / genuine["base"]),
        "note": "Ширина low…high — это ширина незнания: прайса Caterpillar у нас нет, "
                "в нашей базе цен по CAT лежат только фильтры. "
                "Цифры нужны, чтобы понимать порядок и спорить с поставщиком, а не чтобы "
                "ставить их в ТКП заказчику.",
    }


