# Заполняется расчётом в build_mass_table().
def build_mass_table():
    import sys, os
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from bearing_price import bronze_bush
    out = []
    for num, pn, kind, mat, price, qty in ITEMS:
        need = None
        m = 0.5
        while m <= 200:
            if bronze_bush(m, qty)["цена EXW"] * FX_ASSUMED >= price:
                need = round(m, 1)
                break
            m += 0.1
        out.append((num, pn, kind, mat, price, need))
    return out


