#!/usr/bin/env python3
"""Пилотный заказ №1: целевые цены от расчётной себестоимости (не от КП).

Логика (по постановке владельца):
  1) rough-оценка себестоимости производства детали ПО СВОЕМУ РКД
     (параметрическая модель: класс детали → материал+передел, Китай EXW,
     партия из pilot-количества, китайский материал — как в имеющихся КП);
  2) целевая цена = себестоимость × 1.20;
  3) сравнение с лучшим живым КП: КП ≤ цели → «брать по КП»,
     КП > цели → «торговаться до цели».

Выход:
  zip/orders/ПИЛОТ-ЗАКАЗ-1.md            — документ заказа
  zip/orders/pilot_order_rfq.csv         — таблица для рассылки RFQ
  zip/orders/pilot_order_bom_rkd.csv     — заказ по готовому РКД (BOM)
"""
import json
import re
from pathlib import Path
from datetime import date

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT = ROOT / "orders"
OUT.mkdir(exist_ok=True)

CNY = 0.138  # USD за CNY (грубо, для сопоставимости)

# ── параметрическая модель себестоимости (Китай EXW, кит. материал, партия) ──
# est — себестоимость $/шт при указанной пилотной партии; qty — партия пилота.
# Оценка ±40%: без чертёжных масс считаем по классу детали.
CLASSES = [
    # (regex по наименованию, класс, est $, qty, обоснование)
    (r"диафрагм|мембран", "Диафрагма HNBR армированная", 4.0, 10,
     "HNBR ~$14/кг, 150-300 г + армирование, прессформа, вулканизация"),
    (r"комплект уплот|ремкомплект|комплект ремон|seal kit|набор уплот", "Комплект уплотнений", 12.0, 10,
     "5-30 колец/манжет + сборка; малый ~$4-8, большой сервисный до ~$100 (фабричные КП Sanshan подтверждают диапазон)"),
    (r"мотор гидравл|гидромотор|гидравлический двигат", "Гидромотор (узел)", 300.0, 1,
     "корпус+ротор+распределитель, прецизионная механика — покупной узел/сложное производство"),
    (r"шток", "Шток", 60.0, 3,
     "легир. пруток 3-8 кг, токарка+шлифовка+ХТО, хромирование"),
    (r"муфта", "Муфта", 20.0, 5, "сталь ~1-2 кг, токарка+зубодолбление+ТО"),
    (r"манжет|скребок|сальник|грязесъемн", "Манжета/скребок PU", 0.8, 30,
     "полиуретан ~$8/кг, 20-60 г, литьё в форму"),
    (r"стеклоочист", "Скребок-стеклоочиститель", 1.5, 20, "PU-профиль + мех.обработка"),
    (r"уплотнение|кольцо уплотн|прокладк|o-?ring", "Уплотнение/O-ring NBR", 0.20, 50,
     "NBR ~$4/кг, 3-20 г, формовое литьё, амортизация формы"),
    (r"стопорное кольцо|распорное кольцо", "Кольцо стопорное/распорное (сталь)", 1.5, 20,
     "пружинная сталь, штамповка/навивка + ТО"),
    (r"кольцо", "Кольцо (резин.)", 0.20, 50, "как O-ring"),
    (r"сапун", "Сапун", 2.5, 10, "мелкая токарка + фильтр-элемент"),
    (r"клапан|седло", "Клапан/седло (мелкое)", 1.5, 10,
     "инстр. сталь, токарка+ТО+шлифовка, деталь <0.2 кг"),
    (r"штифт|шайба|гайка|болт|шпильк|винт|пружин", "Метиз/пружина", 0.8, 30,
     "легированный пруток, токарка/накатка + ТО"),
    (r"втулка поршня", "Втулка поршня (цементуемая)", 18.0, 5,
     "18CrNiMo ~1.5-3 кг + токарка + цементация + шлифовка"),
    (r"направляющая|втулка направл|букса|bushing", "Втулка направляющая/букса", 20.0, 5,
     "легир. сталь 1-3 кг, токарка + цементация + шлифовка"),
    (r"втулка", "Втулка прочая", 12.0, 5, "сталь ~1 кг + мех.обработка + ТО"),
    (r"поршень|ударник|бо[её]к", "Поршень-ударник", 100.0, 2,
     "18CrNiMo/40CrNiMo 10-15 кг, глубокая токарка, ХТО, шлифовка (кит. материал; импортный +40-60%)"),
    (r"гильза", "Гильза цилиндра", 110.0, 2,
     "легир. труба/поковка 8-12 кг, расточка+хонинговка+ХТО"),
    (r"драйвер", "Драйвер (вращатель)", 60.0, 3, "поковка + зубофрезеровка + цементация"),
    (r"голова промывки", "Голова промывки", 50.0, 3, "поковка/пруток + токарка + сверловка + ТО"),
    (r"хвостовик|shank", "Хвостовик", 200.0, 2,
     "поковка 18CrNiMo 8-12 кг, глубокая цементация, шлицефрезеровка (кит. материал)"),
    (r"фильтр", "Фильтр-элемент", 3.0, 10, "покупной элемент + корпус"),
]
DEFAULT = ("Прочее (мелкая механика)", 2.0, 10, "консервативная оценка мелкой детали")


def classify(name):
    n = (name or "").lower()
    for rx, cls, est, qty, why in CLASSES:
        if re.search(rx, n):
            return cls, est, qty, why
    return DEFAULT


def main():
    pos = {p["id"]: p for p in json.loads((DATA / "positions.json").read_text(encoding="utf-8"))}
    prices = json.loads((DATA / "price_records.json").read_text(encoding="utf-8"))
    bom = json.loads((DATA / "bom.json").read_text(encoding="utf-8"))

    # лучшие КП по позициям
    best = {}
    for r in prices:
        if not str(r.get("source", "")).startswith("КП поставщика") or not r.get("unit_price"):
            continue
        usd = r["unit_price"] * (CNY if r.get("currency") == "CNY" else 1.0)
        pid = r["position_id"]
        if pid not in best or usd < best[pid][0]:
            best[pid] = (usd, r.get("exporter", ""), r.get("currency", ""), r["unit_price"])

    rows = []
    for pid, (q_usd, sup, cur, raw) in sorted(best.items()):
        d = pos.get(pid)
        if not d:
            continue
        cls, est, qty, why = classify(d.get("name"))
        target = round(est * 1.20, 2)
        verdict = "брать по КП" if q_usd <= target else "торговаться до цели"
        rows.append({
            "pp": d.get("pp"), "catalog_no": d.get("catalog_no"), "name": (d.get("name") or "")[:60],
            "cls": cls, "est_cost": est, "target": target, "qty": qty,
            "quote_usd": round(q_usd, 2), "quote_sup": sup, "quote_raw": f"{raw} {cur}",
            "verdict": verdict,
            "sum_target": round(target * qty, 2), "sum_quote": round(q_usd * qty, 2),
            "why": why,
        })

    take = [r for r in rows if r["verdict"] == "брать по КП"]
    push = [r for r in rows if r["verdict"] != "брать по КП"]
    wms_only = sum(1 for r in rows if r["quote_sup"] == "WMS")
    t_quote = sum(r["sum_quote"] for r in rows)
    t_target = sum(min(r["sum_quote"], r["sum_target"]) for r in rows)

    # BOM: детали с готовым РКД (заказ по чертежу)
    bomrows = []
    for p in bom["machines"][0]["parts"]:
        if "готов" not in (p.get("st_rkd") or ""):
            continue
        cls, est, qty, why = classify(p.get("desc"))
        bomrows.append({
            "kv_pn": p.get("kv_pn") or "", "epiroc_pn": p.get("epiroc_pn") or "",
            "desc": p.get("desc") or "", "cls": cls,
            "est_cost": est, "target": round(est * 1.2, 2), "qty": qty,
            "sum_target": round(est * 1.2 * qty, 2), "why": why,
        })
    t_bom = sum(r["sum_target"] for r in bomrows)

    # ── CSV ──
    def csv(path, rows, cols):
        q = lambda v: ('"' + str(v).replace('"', '""') + '"') if any(c in str(v) for c in ';"\n') else str(v)
        path.write_text("﻿" + "\n".join(
            [";".join(cols)] + [";".join(q(r.get(c, "")) for c in cols) for r in rows]),
            encoding="utf-8")
    csv(OUT / "pilot_order_rfq.csv", rows,
        ["pp", "catalog_no", "name", "cls", "qty", "est_cost", "target",
         "quote_usd", "quote_sup", "quote_raw", "verdict", "sum_target", "sum_quote"])
    csv(OUT / "pilot_order_bom_rkd.csv", bomrows,
        ["kv_pn", "epiroc_pn", "desc", "cls", "qty", "est_cost", "target", "sum_target"])

    # ── MD ──
    def money(v):
        return f"${v:,.2f}".replace(",", " ")
    md = [f"""# Пилотный заказ №1 — ЗИП перфораторов (черновик для снабжения)

Дата: {date.today().isoformat()} · Основа: {len(rows)} позиций с живыми КП + {len(bomrows)} деталей BOM COP3060MUX с готовым РКД.

## Методика целевой цены
1. **Rough-оценка себестоимости производства по своему РКД** — параметрическая модель по классу детали
   (материал + передел; Китай EXW; **китайский материал** — как в имеющихся КП; партия = пилотное кол-во). Точность ±40%.
2. **Целевая цена = себестоимость × 1.20** (наши +20% к производству).
3. Сравнение с лучшим КП: КП ≤ цели → **брать по КП**; КП > цели → **торговаться до цели**.
4. Цены EXW: до склада РФ добавить логистику/пошлину/НДС (~+25–40%). Импортный материал (для критичных деталей) +40–60% к себестоимости — второй раунд.

## Итоги
| | |
|---|---|
| Позиций в заказе (по КП) | **{len(rows)}** |
| — брать по КП (цена уже ниже цели) | **{len(take)}** |
| — торговаться до цели | **{len(push)}** |
| Сумма пилота по текущим КП | **{money(t_quote)}** |
| Сумма при достижении целевых цен | **{money(t_target)}** |
| Экономия торга | **{money(t_quote - t_target)}** |
| + Заказ по готовому РКД (BOM, 10 деталей, целевые) | **{money(t_bom)}** |

**Ключевой инсайт:** у {wms_only} из {len(rows)} позиций лучшее КП — только от **WMS (перекупщик, цены близки к OEM:
шпилька $110, кольцо $308)**. Эти цены не принимать — это позиции, по которым фабрики ещё не котировали:
им и слать RFQ с нашей целевой ценой. Фабричные КП Sanshan ($0.3–99) подтверждают порядок расчётной себестоимости.

## Раздел А — торговаться до цели ({len(push)} поз.)
| П/П | Деталь | Класс | Себест. | **Цель** | Лучшее КП | Пост. | Кол-во | Сумма цель |
|---|---|---|---|---|---|---|---|---|"""]
    for r in sorted(push, key=lambda r: -(r["sum_quote"] - r["sum_target"])):
        md.append(f"| {r['pp']} | {r['name'][:38]} | {r['cls'][:24]} | ${r['est_cost']} | **${r['target']}** | ${r['quote_usd']} | {r['quote_sup']} | {r['qty']} | {money(r['sum_target'])} |")
    md.append(f"""
## Раздел Б — брать по КП ({len(take)} поз., цена уже честная)
| П/П | Деталь | Класс | Цель | КП | Пост. | Кол-во | Сумма КП |
|---|---|---|---|---|---|---|---|""")
    for r in sorted(take, key=lambda r: -r["sum_quote"]):
        md.append(f"| {r['pp']} | {r['name'][:38]} | {r['cls'][:24]} | ${r['target']} | **${r['quote_usd']}** | {r['quote_sup']} | {r['qty']} | {money(r['sum_quote'])} |")
    md.append(f"""
## Раздел В — заказ по готовому РКД (BOM COP 3060MUX, {len(bomrows)} деталей)
Чертежи наши — RFQ на изготовление (Sanshan/ковочные заводы из вкладки «Материалы»).
| КВАНТ | Epiroc PN | Деталь | Класс | Себест. | **Цель** | Кол-во | Сумма |
|---|---|---|---|---|---|---|---|""")
    for r in bomrows:
        md.append(f"| {r['kv_pn']} | {r['epiroc_pn']} | {r['desc'][:34]} | {r['cls'][:24]} | ${r['est_cost']} | **${r['target']}** | {r['qty']} | {money(r['sum_target'])} |")
    md.append("""
## Допущения модели себестоимости (по классам)
""")
    seen = set()
    for r in rows + bomrows:
        if r["cls"] in seen:
            continue
        seen.add(r["cls"])
        md.append(f"- **{r['cls']}** — ${r['est_cost']}/шт: {r['why']}.")
    md.append("""
## Следующие шаги
1. Разослать RFQ-пакеты с целевыми ценами (CSV приложен): Sanshan — металл+РТИ, YLF/Fuxuan — РТИ (для конкуренции), KAT — втулки.
2. В письме фиксировать: цель = «наша расчётная себестоимость +20%», объём пилота, опцион серии при прохождении входного контроля.
3. Приёмка → склад → тест (конвейер образцов в базе), критерии — вкладка «Материалы» (протоколы испытаний).
4. По критичным деталям (поршень, гильза, хвостовик) параллельно запросить цену на импортном материале (18CrNiMo7-6/300M).""")
    (OUT / "ПИЛОТ-ЗАКАЗ-1.md").write_text("\n".join(md), encoding="utf-8")

    print(f"позиций: {len(rows)} (брать {len(take)} / торговаться {len(push)})")
    print(f"по КП {money(t_quote)} → по целям {money(t_target)} (экономия {money(t_quote-t_target)})")
    print(f"BOM РКД: {len(bomrows)} деталей на {money(t_bom)}")
    print(f"→ {OUT}/ПИЛОТ-ЗАКАЗ-1.md + 2 CSV")


if __name__ == "__main__":
    main()
