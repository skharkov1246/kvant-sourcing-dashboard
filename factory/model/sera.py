# -*- coding: utf-8 -*-
"""Серный баланс как критерий выбора технологии для площадки в Карелии.

Медный концентрат содержит 36,0 % серы при 15,3 % меди. Судьба этой серы различается
принципиально по маршрутам переработки и определяет и экономику, и разрешительную часть.

Подтверждено мировой практикой (Dreisinger, Cominco CESL, процесс Albion, автоклавы
Freeport на Bagdad и Morenci): при умеренной температуре автоклавного окисления
(до 150-165 C) 80-90 % сульфидной серы переходит в ЭЛЕМЕНТНУЮ форму; выше 180 C
происходит полное окисление до сульфата, то есть до серной кислоты.
"""
MASSA_KONC = 85_000      # т/год медного концентрата
S_DOLYA = 0.360          # доля серы
CU_DOLYA = 0.153
M_H2SO4, M_S = 98.08, 32.06

S_VSEGO = MASSA_KONC * S_DOLYA
print(f'Серы в концентрате: {S_VSEGO:,.0f} т/год при массе концентрата {MASSA_KONC:,} т\n'.replace(',', ' '))

CENA = dict(sera_elem=150, kislota_prodazha=45, kislota_neytral=-45, izvest=90)

print('СУДЬБА СЕРЫ ПО МАРШРУТАМ')
print(f"{'Маршрут':<46}{'форма серы':<22}{'т/год':>10}{'эффект, млн $':>15}")
print('-' * 94)

def stroka(nazv, forma, dolya_elem):
    """dolya_elem — доля серы, выходящей в элементной форме; остальное в кислоту."""
    s_el = S_VSEGO * dolya_elem
    s_sulf = S_VSEGO * (1 - dolya_elem)
    kislota = s_sulf * M_H2SO4 / M_S
    # элементная сера продаётся; кислота в Карелии сбыта не имеет, принимаем нейтрализацию
    dohod = s_el * CENA['sera_elem'] / 1e6
    # нейтрализация известняком: около 0,8 т известняка на тонну кислоты плюс обращение с гипсом
    zatraty = kislota * 0.8 * CENA['izvest'] / 1e6 if kislota > 0 else 0
    gips = kislota * 1.7
    itog = dohod - zatraty
    print(f'{nazv:<46}{forma:<22}{s_el if dolya_elem>0.5 else kislota:>10,.0f}{itog:>15.1f}'.replace(',', ' '))
    return itog, gips, kislota

r = {}
r['piro'] = stroka('Пирометаллургия (шахтная печь, конвертер)', 'серная кислота', 0.0)
r['obzhig'] = stroka('Обжиг — выщелачивание — электроэкстракция', 'серная кислота', 0.0)
r['pox_vys'] = stroka('Автоклав при высокой температуре (>180 C)', 'серная кислота', 0.0)
r['pox_sred'] = stroka('Автоклав при умеренной температуре (150 C)', 'элементная сера', 0.85)
r['albion'] = stroka('Атмосферное выщелачивание (процесс Albion)', 'элементная сера', 0.80)
r['prodazha'] = stroka('Продажа концентрата (сера уходит покупателю)', 'проблема покупателя', 0.0)

print('\nМАСШТАБ ПРОБЛЕМЫ ДЛЯ КИСЛОТНЫХ МАРШРУТОВ')
_, gips, kislota = r['piro']
print(f'  Серной кислоты в пересчёте на 100 %: {kislota:,.0f} т/год'.replace(',', ' '))
print(f'  Это эквивалент {kislota/93700*100:.0f} % годового выпуска среднего сернокислотного цеха')
print(f'  При отсутствии сбыта требуется нейтрализация: известняка {kislota*0.8:,.0f} т/год,'.replace(',', ' '))
print(f'  образование гипса {gips:,.0f} т/год, что требует отдельной карты складирования'.replace(',', ' '))
print(f'  Ближайший крупный производитель кислоты — Кольская ГМК — обеспечивает себя сам.')

print('\nСВЯЗЬ С КАЧЕСТВОМ КОНЦЕНТРАТА')
for grade, massa, s_dolya in [(0.153, 85_000, 0.360), (0.20, 64_248, 0.345), (0.25, 50_777, 0.330)]:
    s = massa * s_dolya
    print(f'  концентрат {grade*100:.1f} % Cu: масса {massa:>6,} т -> серы {s:>6,.0f} т/год '
          f'({s/S_VSEGO*100:.0f} % от базового)'.replace(',', ' '))
print('  Повышение качества концентрата до 25 % меди снижает серную нагрузку почти вдвое')
print('  и одновременно уменьшает размер любого металлургического передела.')

print('\nВЫВОД ДЛЯ ВЫБОРА ТЕХНОЛОГИИ В КАРЕЛИИ')
for s in [
  'Кислотные маршруты (пирометаллургия, обжиг, высокотемпературный автоклав) создают в Карелии',
  'около 93 700 т серной кислоты в год без местного сбыта. Это не только затраты на нейтрализацию,',
  'но и разрешительная нагрузка: обращение с опасным веществом, транспорт, складирование гипса.',
  'Маршруты с элементной серой (умеренный автоклав, атмосферное выщелачивание) дают складируемый',
  'и продаваемый твёрдый продукт вместо жидкого отхода. Для региона с обилием водных объектов',
  'это самостоятельный аргумент, не сводящийся к экономике.',
]:
    print(f'  {s}')
