    ('Фтор',              0.03,   15.0,   0.0000,   'не определялся'),
    ('Свинец',            1.0,     0.3,   2.0600,   'таблица 10 паспорта'),
    ('Ртуть',             0.0005, 3000.0, 0.000022, 'элементный анализ: 0,22 г/т'),
    ('Никель и кобальт',  0.5,     1.0,   0.0130,   'элементный анализ руды, пересчёт'),
    ('Селен',             0.03,   15.0,   0.0000,   'не определялся'),
    ('Цинк',              3.0,     0.3,   0.0580,   'элементный анализ руды'),
