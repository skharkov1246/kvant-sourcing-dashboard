# -*- coding: utf-8 -*-
"""Агентское вознаграждение: от чего считать 15 % и чем они обеспечены.

Наша модель работы с заказчиком: проектный офис, координация размещения заказа
на проектирование, координация и консультирование по заказу оборудования.
Заявленная ставка — 15 % агентского вознаграждения.

Модель отвечает на три вопроса:
  1) 15 % ОТ ЧЕГО — три возможные базы дают разброс от 9 до 82 млн $;
  2) сколько стоит сама работа, то есть каков наш собственный расход;
  3) чем ставка обеспечена — какие уже посчитанные решения её оправдывают.

Реперы по рынку услуг:
  · EPCM (проектирование + поставка + управление стройкой) — 15-25 % от стоимости
    смонтированного оборудования; в оценке Jacobs по установке на 100 тыс. т/год
    статья EPCM составила 8,7 млн $ при полном капитале 66,2 млн $ (13,1 %)
    и 21,8 % от суммы прямых и косвенных затрат;
  · управление проектом со стороны заказчика (PMC, owner's engineer) — 5-15 %,
    обычно 7-12 %;
  · агентское вознаграждение по закупке оборудования — 3-10 % от суммы заказа.
"""
KURS = 85.85
KAPEX_OCH1 = 548.0        # млн $, первая очередь на площадке в Карелии (kareliya.py)
KAPEX_POLN = 1_158.0      # млн $, обе очереди
DOLYA_OBOR = 0.42         # доля оборудования в капитале горно-обогатительного объекта
DOLYA_PROEKT = 0.055      # доля проектно-изыскательских работ

print('=' * 100)
print('1. «15 %» — ОТ ЧЕГО? ТРИ БАЗЫ, РАЗНИЦА В ДЕВЯТЬ РАЗ')
print('=' * 100)
BAZY = [
    ('От полного капитала первой очереди', KAPEX_OCH1, 'заказчик услышит это первым'),
    ('От стоимости оборудования первой очереди', KAPEX_OCH1*DOLYA_OBOR, 'то, что мы реально координируем'),
    ('От стоимости проектных работ', KAPEX_OCH1*DOLYA_PROEKT, 'то, что мы реально размещаем'),
]
print(f"{'база начисления':<44}{'база, млн $':>14}{'15 %, млн $':>14}{'в млрд руб.':>14}")
print('-' * 100)
for n, b, _ in BAZY:
    print(f'{n:<44}{b:>14.0f}{b*0.15:>14.1f}{b*0.15*KURS/1000:>14.2f}')
print('-' * 100)
print('  Первая строка — это то, как ставку услышит заказчик, если базу не оговорить.')
print(f'  {KAPEX_OCH1*0.15:.0f} млн $ за проектный офис он не примет и будет прав.')
print('  Ставку надо предъявлять вместе с базой, иначе переговоры сорвутся на цифре,')
print('  а не на существе.')

print()
print('=' * 100)
print('2. СКОЛЬКО СТОИТ САМА РАБОТА')
print('=' * 100)
SHTAT = [
    ('Руководитель проекта', 1, 190),
    ('Главный инженер проекта', 1, 170),
    ('Технолог по обогащению и гидрометаллургии', 2, 150),
    ('Инженер по горным работам', 1, 140),
    ('Инженер по оборудованию и закупкам', 3, 130),
    ('Инженер по стройке и смежным разделам', 2, 130),
    ('Экономист проекта, сметчик', 2, 120),
    ('Юрист по контрактам, специалист по разрешениям', 2, 130),
    ('Административная и переводческая поддержка', 2, 70),
]
LET = 4
god = sum(k*z for _, k, z in SHTAT)/1000
print(f"{'должность':<48}{'чел.':>6}{'тыс. $/год':>13}{'итого, млн $/год':>19}")
print('-' * 100)
for n, k, z in SHTAT:
    print(f'{n:<48}{k:>6}{z:>13}{k*z/1000:>19.2f}')
print('-' * 100)
print(f"{'Фонд оплаты труда с накладными':<48}{sum(k for _,k,_ in SHTAT):>6}{'':>13}{god:>19.2f}")
komandirovki = 0.9
print(f"{'Командировки, экспертиза, испытания, ПО':<48}{'':>6}{'':>13}{komandirovki:>19.2f}")
vsego_god = god + komandirovki
print(f"{'ВСЕГО в год':<48}{'':>6}{'':>13}{vsego_god:>19.2f}")
print(f"{'ВСЕГО за ' + str(LET) + ' года работы':<48}{'':>6}{'':>13}{vsego_god*LET:>19.2f}")
print('-' * 100)
print(f'  Прямой расход на проектный офис — около {vsego_god*LET:.0f} млн $ за {LET} года.')
for n, b, _ in BAZY:
    print(f'   · 15 % от базы «{n.lower()}» = {b*0.15:.1f} млн $ '
          f'— это {b*0.15/(vsego_god*LET):.1f} к затратам')

print()
print('=' * 100)
print('3. ЧЕМ СТАВКА ОБЕСПЕЧЕНА: ПОСЧИТАННЫЕ РЕШЕНИЯ')
print('=' * 100)
EFFEKT = [
    ('Доводка концентрата с 15,3 до 25 % меди: прирост выручки от продажи',
     8.6, 'в год', 'модель vybor.py'),
    ('Она же: снижение капитала любого будущего передела',
     66.0, 'единовременно', 'модель gidromet.py'),
    ('Серебро: обработка кека против связывания в аргентоярозит',
     24.1, 'в год', 'модель vybor.py'),
    ('Пересчёт капитала под площадку в Карелии вместо типового решения',
     97.0, 'единовременно', 'модель kareliya.py'),
    ('Отказ от строительства передела в первой очереди',
     205.0, 'единовременно', 'модель vybor.py, минимальный из маршрутов'),
    ('Поэтапный ввод вместо единовременного: снижение капитала под риском',
     580.0, 'капитал под риском', 'модель staged.py'),
]
print(f"{'решение':<66}{'эффект':>12}{'характер':>21}")
print('-' * 100)
for n, v, h, src in EFFEKT:
    print(f'{n:<66}{v:>10.1f} $М{h:>21}')
print('-' * 100)
god_eff = sum(v for n, v, h, s in EFFEKT if h == 'в год')
raz_eff = sum(v for n, v, h, s in EFFEKT if h == 'единовременно')
print(f'  Разовый эффект уже посчитанных решений: {raz_eff:.0f} млн $.')
print(f'  Годовой эффект: {god_eff:.1f} млн $ в год.')
for n, b, _ in BAZY[1:]:
    print(f'  Вознаграждение 15 % от базы «{n.lower()}» = {b*0.15:.0f} млн $ — '
          f'это {b*0.15/raz_eff*100:.0f} % только от разового эффекта.')

print()
print('=' * 100)
print('4. ПРЕДЛАГАЕМАЯ КОНСТРУКЦИЯ ВОЗНАГРАЖДЕНИЯ')
print('=' * 100)
obor = KAPEX_OCH1*DOLYA_OBOR
proekt = KAPEX_OCH1*DOLYA_PROEKT
SHEMA = [
    ('Фиксированная плата за проектный офис', vsego_god*1.35, 'в год',
     f'{LET} года, себестоимость {vsego_god:.1f} + маржа 35 %'),
    ('Агентское по размещению заказа на проектирование', proekt*0.10, 'единовременно',
     '10 % от суммы проектных договоров'),
    ('Агентское по заказу оборудования', obor*0.05, 'единовременно',
     '5 % от суммы заказов, в рыночном коридоре 3-10 %'),
    ('Премия за результат: выход на проектные показатели', 12.0, 'единовременно',
     'выплачивается после подтверждения извлечений на промышленной пульпе'),
]
print(f"{'элемент':<50}{'сумма':>12}{'характер':>16}{'основание':>22}")
print('-' * 100)
itog_raz, itog_god = 0.0, 0.0
for n, v, h, o in SHEMA:
    print(f'{n:<50}{v:>10.1f} $М{h:>16}')
    print(f'{"":<50}{o:>50}')
    if h == 'в год': itog_god += v
    else: itog_raz += v
print('-' * 100)
vsego = itog_god*LET + itog_raz
print(f'  Итого за весь срок работ: {vsego:.1f} млн $ = {vsego*KURS/1000:.2f} млрд руб.')
print(f'  Это {vsego/KAPEX_OCH1*100:.1f} % от капитала первой очереди — против 15 %,')
print(f'  которые заказчик услышит как {KAPEX_OCH1*0.15:.0f} млн $.')
print(f'  Наша маржа при такой конструкции: {vsego - vsego_god*LET:.1f} млн $ '
      f'при затратах {vsego_god*LET:.1f} млн $.')
print()
print('  ЗАЧЕМ ЭТО НУЖНО НАМ. Плоские 15 % от полного капитала выглядят как рента')
print('  и обсуждаются как рента. Разложенная ставка обсуждается как смета: у каждой')
print('  части есть рыночный ориентир, и торг идёт по частям, а не по принципу.')
print('  При этом сумма для нас получается сопоставимой, а вероятность подписания выше.')
print()
print('  ЗАЧЕМ ЭТО НУЖНО ЗАКАЗЧИКУ. Он платит за проектный офис по факту работы,')
print('  а не процент от суммы, которую сам же и увеличивает. Плоский процент от')
print('  капитала создаёт у него законное подозрение: подрядчик заинтересован')
print('  в дорогом проекте. Разложенная ставка это подозрение снимает.')
