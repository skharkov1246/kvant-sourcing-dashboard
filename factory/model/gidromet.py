"""Гидрометаллургия на этом концентрате: что определяет выбор — состав, а не мода.

Заказчик просит гидрометаллургическую технологию. Модель проверяет, что именно
получает гидрометаллургия на входе, и во что это обходится.

Исходные:
  · состав концентрата — китайский техпроект, табл. 2-1 (Cu 15,3 %, Fe 42,18 %, S 36,0 %,
    Au 35,57 г/т, Ag 174,33 г/т), совпадает с отчётом ЦНИГРИ по пробе Л-1;
  · масса концентрата — из собственной модели audit.py по календарному плану;
  · реперы по капиталу — Амурский ГМК (линия 2), Покровский АГК, Ertis POX (Казахстан),
    установка Albion на предприятии GPM Gold (Армения, Арарат).
"""
OZ = 31.1035
KURS = 85.85                       # руб./долл. на 31.08.2026

# ── 1. РАСЧЁТНАЯ НАГРУЗКА НА МЕТАЛЛУРГИЧЕСКИЙ ПЕРЕДЕЛ ──────────────────────
M_KONC = 86_621                    # т/год, пик по собственному расчёту (audit.py, 2031 г.)
M_KITAY = 85_000                   # т/год, расчётная нагрузка китайского техпроекта
DNEY = 330                         # рабочих суток в году
CHASOV = 8_000                     # часов работы кислородной станции

W = dict(cu=0.153, fe=0.4218, s=0.360)
A = dict(cu=63.546, fe=55.845, s=32.06, o=31.999, ca=40.078, c=12.011, h=1.008)
M_CHALK = A['cu'] + A['fe'] + 2*A['s']        # CuFeS2  183,52
M_PIRIT = A['fe'] + 2*A['s']                  # FeS2    119,97
M_PIRRO = A['fe'] + A['s']                    # FeS      87,91
M_H2SO4 = 2*A['h'] + A['s'] + 4*A['o']
M_CACO3 = A['ca'] + A['c'] + 3*A['o']
M_GIPS = A['ca'] + A['s'] + 4*A['o'] + 2*(2*A['h'] + A['o'])   # CaSO4·2H2O

print('=' * 98)
print('1. РАСЧЁТНАЯ НАГРУЗКА НА МЕТАЛЛУРГИЧЕСКИЙ ПЕРЕДЕЛ')
print('=' * 98)
print(f'  Собственный расчёт по календарному плану (пик 2031 г.):   {M_KONC:>9,.0f} т/год'.replace(',', ' '))
print(f'  Расчётная нагрузка китайского техпроекта:                 {M_KITAY:>9,.0f} т/год'.replace(',', ' '))
print(f'  Расхождение:                                              {(M_KONC/M_KITAY-1)*100:>9.1f} %')
print(f'  Суточная нагрузка:                                        {M_KONC/DNEY:>9.0f} т/сут')
print('  Вывод: масштаб передела сторонами фактически согласован. Спор идёт о технологии,')
print('  а не о производительности.')

# ── 2. ЧТО НА САМОМ ДЕЛЕ ПРЕДСТАВЛЯЕТ СОБОЙ КОНЦЕНТРАТ ─────────────────────
cu_t, fe_t, s_t = (M_KONC*W[k] for k in ('cu', 'fe', 's'))
DOLYA_CU_V_CHALK = 0.90            # фазовый анализ ЦНИГРИ: ~90 % отн. меди — халькопирит
cu_chalk = cu_t * DOLYA_CU_V_CHALK
m_chalk = cu_chalk * M_CHALK / A['cu']
s_chalk = m_chalk * 2*A['s'] / M_CHALK
fe_chalk = m_chalk * A['fe'] / M_CHALK

s_ost, fe_ost = s_t - s_chalk, fe_t - fe_chalk
k_pir, k_pirro = 2*A['s']/A['fe'], A['s']/A['fe']
fe_pirit = (s_ost - k_pirro*fe_ost) / (k_pir - k_pirro)
fe_pirro = fe_ost - fe_pirit
m_pirit = fe_pirit * M_PIRIT / A['fe']
m_pirro = fe_pirro * M_PIRRO / A['fe']
m_sulf = m_chalk + m_pirit + m_pirro

print()
print('=' * 98)
print('2. МИНЕРАЛЬНЫЙ СОСТАВ КОНЦЕНТРАТА, ВОССТАНОВЛЕННЫЙ ИЗ ХИМИЧЕСКОГО АНАЛИЗА')
print('=' * 98)
print(f"{'минерал':<28}{'масса, т/год':>14}{'доля массы':>13}{'серы, т/год':>14}{'доля серы':>12}")
print('-' * 98)
for n, m, s in [('Халькопирит CuFeS2', m_chalk, s_chalk),
                ('Пирит FeS2', m_pirit, fe_pirit*k_pir),
                ('Пирротин FeS', m_pirro, fe_pirro*k_pirro)]:
    print(f'{n:<28}{m:>14,.0f}{m/M_KONC*100:>12.1f} %{s:>14,.0f}{s/s_t*100:>11.1f} %'.replace(',', ' '))
print(f"{'Нерудная часть':<28}{M_KONC-m_sulf:>14,.0f}{(M_KONC-m_sulf)/M_KONC*100:>12.1f} %{0:>14.0f}{0:>11.1f} %".replace(',', ' '))
print('-' * 98)
print(f'  Медьсодержащий минерал — {m_chalk/M_KONC*100:.0f} % массы концентрата.')
print(f'  Сульфиды железа без меди — {(m_pirit+m_pirro)/M_KONC*100:.0f} % массы и '
      f'{(s_t-s_chalk)/s_t*100:.0f} % серы.')
print('  Это не медный концентрат в общепринятом смысле, а смесь халькопирита с пиритом')
print('  и пирротином примерно поровну. Пирротин — наихудшая примесь для гидрометаллургии:')
print('  окисляется быстрее халькопирита, забирает на себя кислород и даёт тиосоли,')
print('  разрушающие цианид на последующем цианировании.')

# ── 3. СЕРА КАК ТОПЛИВО: ТЕПЛОВОЙ БАЛАНС АВТОКЛАВА ────────────────────────
Q = dict(chalk=26.3, pirit=24.1, pirro=31.2)      # МДж на кг серы, окисление до сульфата
q_vsego = (s_chalk*Q['chalk'] + fe_pirit*k_pir*Q['pirit'] + fe_pirro*k_pirro*Q['pirro'])
q_na_t = q_vsego / M_KONC                          # ГДж на т концентрата
CP = 3.9e-3                                        # ГДж/(т·К) для пульпы
T_PIT, T_VYS, T_SRED = 85.0, 220.0, 150.0

print()
print('=' * 98)
print('3. СЕРА КАК ТОПЛИВО: ПОЧЕМУ 36 % СЕРЫ — ЭТО ПРОБЛЕМА АВТОКЛАВА, А НЕ ПОДАРОК')
print('=' * 98)
print(f'  Тепловыделение при полном окислении: {q_na_t*1000:.0f} МДж на тонну концентрата.')
print(f'  Для сравнения: сжигание тонны бурого угля даёт около 15 000 МДж.')
print()
print(f"{'режим':<38}{'ΔT, К':>8}{'т пульпы на т к-та':>22}{'содержание твёрдого':>22}")
print('-' * 98)
for nazv, t_rab in [('Автоклав высокотемпературный 220 °C', T_VYS),
                    ('Автоклав умеренный 150 °C (85 % S°)', T_SRED)]:
    dolya = 1.0 if t_rab > 180 else 0.15 + 0.85*0.33   # S° несёт ~1/3 теплоты сульфатного окисления
    q = q_na_t * dolya
    dt = t_rab - T_PIT
    pulpa = q / (CP*dt)
    print(f'{nazv:<38}{dt:>8.0f}{pulpa:>22.1f}{100/pulpa:>21.1f} %')
print('-' * 98)
print('  Автоклавы проектируют на содержание твёрдого 12-18 %. Наш концентрат по теплу')
print('  требует разбавления до однозначных величин — то есть в автоклав идёт почти вода.')
print('  Практических выходов два: гасить тепло впрыском воды, увеличивая объём аппарата')
print('  и расход пара на подогрев, — либо снижать серу в питании. Второе — то же самое,')
print('  что поднять качество концентрата.')

# ── 4. КИСЛОРОД ───────────────────────────────────────────────────────────
O_NA_S_SULF = 1.5*2*A['o']/A['s']          # 1,5 моль O2 на моль S до сульфата
O_NA_S_ELEM = 0.5*2*A['o']/A['s']
O_NA_FE = 0.25*2*A['o']/A['fe']
CENA_EL = 0.080                            # $/кВт·ч, промышленный тариф в Карелии
UD_MOSHCH = 0.26                           # кВт·ч на кг кислорода, установка VPSA

def kislorod(nazv, dolya_elem, dolya_okisl, ispolz):
    s_ok = s_t * dolya_okisl
    o2 = (s_ok*(dolya_elem*O_NA_S_ELEM + (1-dolya_elem)*O_NA_S_SULF)
          + fe_t*dolya_okisl*O_NA_FE) / ispolz
    kislota = s_ok*(1-dolya_elem)*M_H2SO4/A['s']
    return dict(nazv=nazv, o2=o2, t_sut=o2/DNEY, mvt=o2*1000*UD_MOSHCH/CHASOV/1000,
                energ=o2*1000*UD_MOSHCH*CENA_EL/1e6, kislota=kislota,
                s_elem=s_ok*dolya_elem, izvest=kislota*M_CACO3/M_H2SO4*1.15,
                gips=kislota*M_GIPS/M_H2SO4, ud=o2/M_KONC*1000)

MARSHRUT = [
    kislorod('Автоклав высокотемпературный (>200 °C)', 0.00, 1.00, 0.90),
    kislorod('Автоклав умеренный (150 °C), сера в S°', 0.85, 1.00, 0.90),
    kislorod('Атмосферное выщелачивание Albion, 60 % S', 0.00, 0.60, 0.85),
]
print()
print('=' * 98)
print('4. КИСЛОРОД И ТО, ЧТО ОСТАЁТСЯ ПОСЛЕ ОКИСЛЕНИЯ')
print('=' * 98)
print(f"{'маршрут':<44}{'O2, т/сут':>11}{'кг O2/т к-та':>14}{'станция':>10}{'энергия':>11}")
print('-' * 98)
for m in MARSHRUT:
    print(f"{m['nazv']:<44}{m['t_sut']:>11.0f}{m['ud']:>14.0f}{m['mvt']:>8.1f} МВт{m['energ']:>7.1f} млн$")
print('-' * 98)
print(f"  Репер: установка Albion на предприятии GPM Gold (Армения) проектировалась на")
print(f"  336 кг O2 на тонну концентрата, фактический расход — около 215 кг/т при сере 17,6 %.")
print(f"  У нас серы вдвое больше, поэтому и кислорода вдвое больше — это прямое следствие состава.")
print()
print(f"  Высокотемпературный автоклав даёт {MARSHRUT[0]['kislota']:,.0f} т серной кислоты в год.".replace(',', ' '))
print(f"  Нейтрализация: известняка {MARSHRUT[0]['izvest']:,.0f} т/год, гипса на карту {MARSHRUT[0]['gips']:,.0f} т/год.".replace(',', ' '))
print(f"  Умеренный автоклав даёт {MARSHRUT[1]['s_elem']:,.0f} т элементной серы — товарный твёрдый".replace(',', ' '))
print('  продукт, но именно она портит последующее цианирование золота (модель zoloto_sera.py).')
print('  Кислородная станция — единственный передел, которому Карелия помогает: гидроэнергетика')
print('  Кемского и Выгского каскадов, тариф ниже среднего по стране.')

# ── 5. КАПИТАЛ: РЕПЕРЫ ПО ДЕЙСТВУЮЩИМ ПРЕДПРИЯТИЯМ ────────────────────────
REPER = [
    ('Амурский ГМК, линия 2 (Хабаровский край, 2025)', 300_000, 60_000/KURS, 'автоклав'),
    ('Ertis POX (Павлодар, Казахстан, пуск 2028)',      275_000, 765.0,       'автоклав'),
    ('Покровский АГК (Амурская обл., 2018)',            500_000, 500.0,       'автоклав'),
    ('GPM Gold, Арарат (Армения, 2014), Albion',        100_000,  45.0,       'атмосферный'),
    ('Оценка Jacobs, класс 5: Albion, 100 тыс. т/год',  100_000,  66.2,       'атмосферный'),
    ('Оценка Jacobs, класс 5: автоклав, 100 тыс. т/год',100_000,  95.9,       'автоклав'),
]
print()
print('=' * 98)
print('5. КАПИТАЛ ПО ДЕЙСТВУЮЩИМ ПРЕДПРИЯТИЯМ И ПЕРЕСЧЁТ НА НАШУ НАГРУЗКУ')
print('=' * 98)
print(f"{'объект':<48}{'т к-та/год':>12}{'капитал':>12}{'$/т·год':>10}{'на 86,6 тыс. т':>16}")
print('-' * 98)
for n, m, c, typ in REPER:
    print(f'{n:<48}{m:>12,.0f}{c:>9.0f} млн${c*1e6/m:>10,.0f}{c*(M_KONC/m)**0.6:>13.0f} млн$'.replace(',', ' '))
print('-' * 98)
avt = [c*(M_KONC/m)**0.6 for n, m, c, t in REPER if t == 'автоклав']
alb = [c*(M_KONC/m)**0.6 for n, m, c, t in REPER if t == 'атмосферный']
bazovyy_kap = sum(avt)/len(avt)
avt_post = [c*(M_KONC/m)**0.6 for n, m, c, t in REPER if t == 'автоклав' and 'Jacobs' not in n]
avt_sm = [c*(M_KONC/m)**0.6 for n, m, c, t in REPER if t == 'автоклав' and 'Jacobs' in n]
print(f'  Автоклав по сметной оценке класса 5:      {avt_sm[0]:>5.0f} млн $')
print(f'  Автоклав по фактически построенным:       {min(avt_post):>5.0f}-{max(avt_post):.0f} млн $')
print(f'  Атмосферное выщелачивание, факт и смета:  {min(alb):>5.0f}-{max(alb):.0f} млн $')
print('  Разрыв между сметной оценкой и фактически построенными автоклавами — от двух до')
print('  четырёх раз. Это не ошибка расчёта, а свойство ранних оценок этого передела.')
print('  Прямое сопоставление на одинаковой нагрузке (Jacobs, оценка класса 5, точность ±50 %,')
print('  концентрат 100 тыс. т/год): атмосферное выщелачивание 66,2 млн $ против автоклава')
print('  95,9 млн $ — автоклав дороже в 1,45 раза при извлечении золота 94 % против 93 %.')
print('  Годовые эксплуатационные: 6,0 против 10,0 млн $, из них реагенты 2,4 против 5,1.')
print('  Оговорка: Амурский ГМК-2 и Ertis перерабатывают дважды упорное сырьё и несут переделы,')
print('  которые нам не нужны; Покровский АГК ближе по составу задачи. Ни один из реперов')
print('  не извлекает медь — под медь добавляются экстракция и электроэкстракция.')
print()
print('  ПРЕДУПРЕЖДЕНИЕ О ТОЧНОСТИ РАННИХ ОЦЕНОК АВТОКЛАВА:')
print(f'  Амурский ГМК-2 при объявлении оценивался в 431 млн $, фактически освоено свыше')
print(f'  60 млрд руб. — {60_000/KURS:.0f} млн $ по курсу на дату расчёта, то есть {(60_000/KURS)/431-1:+.0%}')
print('  к первой оценке. Любую раннюю оценку автоклавного передела следует принимать')
print('  с этим коэффициентом.')

# ── 6. ЧТО ДАЁТ ПОВЫШЕНИЕ КАЧЕСТВА КОНЦЕНТРАТА ────────────────────────────
print()
print('=' * 98)
print('6. ПОВЫШЕНИЕ КАЧЕСТВА КОНЦЕНТРАТА КАК УСЛОВИЕ ВХОДА В ГИДРОМЕТАЛЛУРГИЮ')
print('=' * 98)
print(f"{'качество':<14}{'масса, т/год':>14}{'серы, т/год':>13}{'O2, т/сут':>11}{'твёрдого в автоклаве':>22}{'капитал':>13}")
print('-' * 98)
for grade in (0.153, 0.20, 0.25, 0.28):
    poteri = 0.0 if grade <= 0.153 else (grade-0.153)/0.153*0.06
    m = cu_t*(1-poteri)/grade
    s_g = s_chalk + (s_t-s_chalk)*max(0.0, (m-m_chalk)/(M_KONC-m_chalk))
    o2 = (s_g*O_NA_S_SULF + fe_t*(m/M_KONC)*O_NA_FE)/0.90/DNEY
    q_g = (s_g/m)*1000*25.0/1000                # ГДж на т концентрата, средняя теплота 25 МДж/кг S
    tv = 100/(q_g/(CP*(T_VYS-T_PIT)))
    print(f'{grade*100:>5.1f} % Cu{"":<4}{m:>14,.0f}{s_g:>13,.0f}{o2:>11.0f}{tv:>21.1f} %'
          f'{bazovyy_kap*(m/M_KONC)**0.6:>10.0f} млн$'.replace(',', ' '))
print('-' * 98)
m25 = cu_t*(1-(0.25-0.153)/0.153*0.06)/0.25
print(f'  Переход с 15,3 % на 25 % меди уменьшает массу передела на {(1-m25/M_KONC)*100:.0f} %,')
print(f'  капитал автоклава — примерно на {bazovyy_kap-bazovyy_kap*(m25/M_KONC)**0.6:.0f} млн $,')
print(f'  кислород — с {MARSHRUT[0]["t_sut"]:.0f} до {MARSHRUT[0]["t_sut"]*m25/M_KONC:.0f} т/сут,')
print(f'  выход кислоты — со {MARSHRUT[0]["kislota"]:,.0f} до {MARSHRUT[0]["kislota"]*m25/M_KONC:,.0f} т/год.'.replace(',', ' '))
print()
print('  ЧЕГО ПОВЫШЕНИЕ КАЧЕСТВА НЕ ДАЁТ. Удельное содержание серы при доводке почти не')
print('  меняется: выводится пирит-пирротиновая смесь, в которой серы примерно столько же,')
print('  сколько в среднем по концентрату. Поэтому расчётное содержание твёрдого в автоклаве')
print('  остаётся около 6 % при любом качестве. Доводка уменьшает масштаб передела,')
print('  но не снимает ограничение по теплу. Ограничение по теплу снимает только отказ')
print('  от автоклава в пользу аппарата, открытого в атмосферу.')
