"""Экономика проекта при поэтапной реализации: очередь 1 (2,3 млн т) -> очередь 2 (+6,2 млн т).

Ключевая идея проверки: капитал под риском равен не полной стоимости комплекса, а стоимости
первой очереди. Первая очередь работает на богатой руде (паспорт: 1,6 г/т Au) и, если её
денежный поток достаточен, финансирует вторую очередь без нового привлечения средств.

Данные: паспорт месторождения (тоннаж и металл в готовой продукции по годам),
китайский технический проект (разбивка очередей 2,3 + 6,2 = 8,5 млн т/год).
Котировки на 31.08.2026: золото 4430, медь 14500, серебро 67.
"""
OZ = 31.1035
PRICE = {'spot': dict(au=4430, ag=67, cu=14500), 'base': dict(au=3500, ag=50, cu=11000),
         'stress': dict(au=3000, ag=45, cu=10000)}
PAY = dict(au=0.925, ag=0.90, cu=0.935)

# год, руда т, Au ГП т, Ag ГП т, Cu ГП т, концентрат т  (паспорт, извлечения 0,80/0,76/0,85)
PLAN = [
 (2029,2_343_750,3.00,7.13,4_781,37_500),  (2030,2_343_750,3.00,7.13,4_781,37_500),
 (2031,7_455_522,2.50,17.67,13_065,102_469),(2032,8_503_597,2.50,14.50,12_474,97_832),
 (2033,8_503_597,2.50,14.50,12_474,97_832),(2034,8_503_597,2.50,14.50,12_474,97_832),
 (2035,8_503_597,2.50,14.50,12_474,97_832),(2036,8_503_597,2.50,14.50,12_474,97_832),
 (2037,8_503_597,2.50,14.50,12_474,97_832),(2038,4_476_294,1.32,7.63,6_566,51_499),
]
# поправка на схему первой очереди: гравитация + флотация на богатой руде дала в 1996 г.
# извлечение Au 91,9 % против 80 % по паспорту -> металл в продукции выше в 1,149 раза
K_OCH1_AU = 0.919 / 0.80
K_OCH1_CU = 0.953 / 0.85

CAPEX_OCH1 = {2027: 180.0, 2028: 400.0, 2029: 65.0}          # итого 645
CAPEX_OCH2 = {2030: 200.0, 2031: 350.0, 2032: 60.0}          # итого 610
CAPEX_PLAVKA = {2033: 150.0, 2034: 200.0}                     # итого 350
SUSTAIN, CLOSURE, NDPI = 22.0, 50.0, 0.07
CAP1, CAP2 = 2.3e6, 8.5e6


def nsr(au_t, ag_t, cu_t, conc_t, pr):
    p = PRICE[pr]
    au_oz, ag_oz = au_t * 1e6 / OZ, ag_t * 1e6 / OZ
    gross = (au_oz * PAY['au'] * p['au'] + ag_oz * PAY['ag'] * p['ag']
             + cu_t * PAY['cu'] * p['cu']) / 1e6
    ded = (70 * conc_t + 176 * cu_t * PAY['cu'] + 18 * au_oz * PAY['au']
           + 1.5 * ag_oz * PAY['ag'] + 100 * conc_t / 0.91) / 1e6
    return gross - ded


def opex(t, cap, strip=4.5):
    """Постоянная часть переработки не масштабируется с загрузкой; малый завод дороже на тонну."""
    prm = 72.0 * (cap / 7.6e6)
    return t * (1 + strip) / 1e6 * 2.0 + prm * (0.30 + 0.70 * min(t / cap, 1.0)) + 22.0 * (0.8 if cap < 4e6 else 1.0)


def npv(f, r=0.10):
    return sum(v / (1 + r) ** (i + 1) for i, v in enumerate(f))


def irr(f):
    lo, hi = -0.9, 3.0
    for _ in range(300):
        m = (lo + hi) / 2
        if npv(f, m) > 0: lo = m
        else: hi = m
    return (lo + hi) / 2


def model(pr, s2=True, plavka=False, boost1=True):
    flows, rows = [], []
    for y in range(2027, 2041):
        cx = CAPEX_OCH1.get(y, 0.0)
        if s2: cx += CAPEX_OCH2.get(y, 0.0)
        if plavka: cx += CAPEX_PLAVKA.get(y, 0.0)
        cf, r, o = -cx, 0.0, 0.0
        row = next((x for x in PLAN if x[0] == y), None)
        if row:
            _, t, au, ag, cu, conc = row
            och1 = y <= 2030
            if not s2 and not och1:
                t, au, ag, cu, conc = [min(t, CAP1)] + [v * CAP1 / t for v in (au, ag, cu, conc)]
            if och1 and boost1:
                au, cu, conc = au * K_OCH1_AU, cu * K_OCH1_CU, conc * K_OCH1_CU
            cap = CAP1 if (och1 or not s2) else CAP2
            r = nsr(au, ag, cu, conc, pr); o = opex(t, cap)
            cf += r - o - r * NDPI - SUSTAIN * min(t / cap * 1.2, 1.0)
        if y == 2040: cf -= CLOSURE
        rows.append((y, r, o, cf)); flows.append(cf)
    return flows, rows


