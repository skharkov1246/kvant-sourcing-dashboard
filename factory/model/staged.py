print('Золото в январе 2026 г. достигало 5602 долл., то есть упало на 21 %\n')
print(f"{'КОНФИГУРАЦИЯ':<46}{'капитал':>9}{'ЧДД@10%':>10}{'ВНД':>8}{'мин.поток':>11}")
print('-' * 84)
for lbl, kw, cx in [
    ('Только очередь 1 (2,3 млн т), спот', dict(pr='spot', s2=False), 645),
    ('Очередь 1 + очередь 2, спот', dict(pr='spot'), 1255),
    ('Очередь 1 + 2 + медеплавильный завод, спот', dict(pr='spot', plavka=True), 1605),
    ('Очередь 1 + 2, базовые цены', dict(pr='base'), 1255),
    ('Очередь 1 + 2, стресс (золото 3000)', dict(pr='stress'), 1255),
    ('Очередь 1 + 2, спот, без выигрыша гравитации', dict(pr='spot', boost1=False), 1255),
]:
    f, _ = model(**kw)
    cum = 0.0; mn = 0.0
    for v in f:
        cum += v; mn = min(mn, cum)
    print(f'{lbl:<46}{cx:>9}{npv(f):>10.0f}{irr(f)*100:>7.1f}%{mn:>11.0f}')

f, rows = model('spot')
print('\nДЕНЕЖНЫЙ ПОТОК ПО ГОДАМ (обе очереди, спот), млн долл.')
print(f"{'год':<6}{'выручка':>10}{'затраты':>10}{'поток':>9}{'накопл.':>10}")
