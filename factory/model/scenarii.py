# -*- coding: utf-8 -*-
"""Сценарии по цене золота для рекомендуемой конфигурации проекта.

Конфигурация: две очереди горно-обогатительного комплекса без металлургического
передела, капитал с поправкой на площадку в Карелии (модель kareliya.py):
очередь 1 — 548 млн $, очередь 2 — 610 млн $, всего 1 158 млн $.
Серебро в сценариях движется пропорционально золоту, медь зафиксирована.
"""
import importlib.util, itertools, os
_d = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('st', os.path.join(_d, 'staged.py'))
st = importlib.util.module_from_spec(spec); spec.loader.exec_module(st)

st.CAPEX_OCH1 = {2027: 153.0, 2028: 340.0, 2029: 55.0}     # 548 вместо 645
KURS = 85.85

print()
print('=' * 78)
print('СЦЕНАРИИ ПО ЦЕНЕ ЗОЛОТА')
print('=' * 78)
print(f"{'цена золота, $/унц.':<26}{'ЧДД при 10 %':>16}{'ВНД':>9}{'потребность в деньгах':>26}")
print('-' * 78)
for au, kom in [(5602, 'пик января 2026 г.'), (5000, ''), (4425, 'котировка 01.09.2026'),
                (4000, ''), (3500, 'долгосрочный консенсус'), (3000, ''), (2600, '')]:
    st.PRICE['x'] = dict(au=au, ag=67*au/4430, cu=14500)
    fl, _ = st.model('x', s2=True, plavka=False)
    pik = -min(itertools.accumulate(fl))
    print(f'{au:<26,}{st.npv(fl):>14.0f} $М{st.irr(fl)*100:>8.1f}%'
          f'{pik:>13.0f} $М = {pik*KURS/1000:.1f} млрд руб.'.replace(',', ' '))
print('-' * 78)

lo, hi = 1500.0, 4430.0
for _ in range(60):
    m = (lo + hi) / 2
    st.PRICE['x'] = dict(au=m, ag=67*m/4430, cu=14500)
    if st.npv(st.model('x', s2=True, plavka=False)[0]) > 0: hi = m
    else: lo = m
b = (lo + hi) / 2
print(f'  Безубыточная цена золота по чистому дисконтированному доходу: {b:,.0f} $/унц.'.replace(',', ' '))
print(f'  Запас до котировки 01.09.2026: {(1-b/4425)*100:.0f} %; до пика января 2026 г.: {(1-b/5602)*100:.0f} %.')
print()
st.PRICE['x'] = dict(au=4425, ag=66.6, cu=14595)
fl, _ = st.model('x', s2=True, plavka=False)
pik = -min(itertools.accumulate(fl))
print('  ПОТРЕБНОСТЬ В ФИНАНСИРОВАНИИ ПРИ ТЕКУЩИХ КОТИРОВКАХ')
print(f'  Максимальный отрицательный накопленный поток: {pik:.0f} млн $ = {pik*KURS/1000:.1f} млрд руб.')
print(f'  Заказчик называет первый этап в 50 млрд руб. — расхождение {abs(pik*KURS/1000-50)/50*100:.0f} %.')
print('  Это не полный капитал 1 158 млн $, а именно то, что надо привлечь: вторая')
print('  очередь финансируется потоком первой. Разница между этими двумя числами —')
print(f'  {1158-pik:.0f} млн $, и она возникает исключительно из поэтапности.')
