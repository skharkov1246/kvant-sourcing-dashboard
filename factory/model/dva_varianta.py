# -*- coding: utf-8 -*-
"""Проверка исходной посылки: «две технологии по процентному содержанию металлов».

Заказчик формулирует задачу так: НИЦ разработает две технологии извлечения
согласно процентному содержанию металлов в руде. Модель проверяет, действительно
ли содержания металлов образуют две разные задачи — и какая из них главная.

Данные по очередям — паспорт месторождения:
  очередь 1: Au 1,6 г/т, Cu 0,24 %;  очередь 2: Au 0,37 г/т, Cu 0,173 %;
  среднее по запасам: Au 0,46 г/т, Cu 0,178 %.
Серебро — по отношению Ag/Au в пробах ЦНИГРИ.
Котировки 01.09.2026: Au 4 425 $/унц., Ag 66,6 $/унц., Cu 6,62 $/фунт = 14 595 $/т.
"""
OZ, FUNT = 31.1035, 2204.62
P = dict(au=4425.0/OZ, ag=66.6/OZ, cu=6.62*FUNT/1000)   # $/г, $/г, $/кг

OCHERED = [
    ('Очередь 1 (богатая зона, 2,3 млн т/год)', 1.60, 0.24, 5.4, 2.3e6),
    ('Очередь 2 (бедная зона, 6,2 млн т/год)',  0.37, 0.173, 2.3, 6.2e6),
    ('Среднее по запасам',                      0.46, 0.178, 2.5, 8.5e6),
]

print('=' * 96)
print('1. ЧТО НА САМОМ ДЕЛЕ ДАЁТ ДЕНЬГИ В КАЖДОЙ ОЧЕРЕДИ')
print('=' * 96)
print(f"{'очередь':<42}{'золото':>12}{'медь':>11}{'серебро':>11}{'всего $/т':>12}")
print('-' * 96)
dolya = {}
for n, au, cu, ag, t in OCHERED:
    v_au, v_cu, v_ag = au*P['au'], cu*10*P['cu'], ag*P['ag']
    v = v_au + v_cu + v_ag
    dolya[n] = (v_au/v, v_cu/v, v_ag/v)
    print(f'{n:<42}{v_au:>9.1f} $ {v_cu:>8.1f} $ {v_ag:>8.1f} ${v:>11.1f}')
    print(f'{"доля в стоимости руды":<42}{v_au/v*100:>10.0f} %{v_cu/v*100:>10.0f} %{v_ag/v*100:>10.0f} %')
print('-' * 96)
print('  Золото даёт основную стоимость в ОБЕИХ очередях: 84 % в первой и 64 % во второй.')
print('  Медь нигде не становится главным металлом. Это золоторудное месторождение')
print('  с попутной медью, а не медное с попутным золотом.')
print()
print('  СЛЕДСТВИЕ ДЛЯ ПОСТАНОВКИ ЗАДАЧИ. Формулировка «разработать технологию')
print('  извлечения и разделения меди с золотом и серебром» задаёт неверный приоритет.')
print('  Технологию надо выбирать по потерям ЗОЛОТА, а медь принимать как ограничение,')
print('  а не как цель. Любое решение, которое прибавляет 2 п.п. по меди ценой')
print('  1 п.п. по золоту, — убыточное.')

print()
print('=' * 96)
print('2. ЦЕНА ОДНОГО ПРОЦЕНТНОГО ПУНКТА ИЗВЛЕЧЕНИЯ ПО КАЖДОМУ МЕТАЛЛУ')
print('=' * 96)
print(f"{'очередь':<42}{'1 п.п. Au':>14}{'1 п.п. Cu':>14}{'1 п.п. Ag':>14}")
print('-' * 96)
for n, au, cu, ag, t in OCHERED[:2]:
    print(f'{n:<42}{t*au*P["au"]/1e8:>11.2f} $М{t*cu*10*P["cu"]/1e8:>11.2f} $М'
          f'{t*ag*P["ag"]/1e8:>11.2f} $М')
print('-' * 96)
t1, t2 = 2.3e6, 6.2e6
k_au1 = t1*1.60*P['au']/1e8
k_cu1 = t1*0.24*10*P['cu']/1e8
print(f'  В первой очереди один пункт золота стоит в {k_au1/k_cu1:.1f} раза больше пункта меди.')
print('  Это соотношение и есть техническое задание: схему настраивают на золото.')

print()
print('=' * 96)
print('3. НУЖНЫ ЛИ ДВЕ РАЗНЫЕ ТЕХНОЛОГИИ')
print('=' * 96)
print('  Разница между очередями — не в соотношении металлов, а в СОДЕРЖАНИИ золота:')
print('  1,60 против 0,37 г/т, то есть в 4,3 раза. Соотношение медь/золото при этом')
print(f'  меняется с {0.24*10/1.60:.1f} до {0.173*10/0.37:.1f} кг меди на грамм золота — то есть медь')
print('  относительно золота становится вдвое весомее, но главным металлом не становится.')
print()
print('  Из этого следует, что различаться должны не ДВЕ ТЕХНОЛОГИИ, а два РЕЖИМА')
print('  одной схемы. Практически это означает:')
for s in [
 '· одна флотационная схема с перенастройкой режима перечисток под разное содержание;',
 '· один и тот же передел концентрата, потому что концентрат в обеих очередях',
 '  по составу близок — он определяется минералогией, а не содержанием в руде;',
 '· разными будут только производительность и, возможно, глубина доизмельчения.',
]:
    print('  ' + s)
print()
print('  ЧТО ЭТО МЕНЯЕТ В ЗАКАЗЕ НИЦ. Заказывать «две технологии» — значит платить')
print('  дважды за одну работу и получить два несовместимых комплекта оборудования.')
print('  Заказывать надо одну схему с проверенным диапазоном работы по питанию:')
print('  содержание золота 0,3-2,0 г/т, меди 0,15-0,30 %, с подтверждением показателей')
print('  на обоих крайних композитах и на их смеси.')

print()
print('=' * 96)
print('4. ГЛАВНАЯ ОШИБКА, КОТОРУЮ ЭТО ПОЗВОЛЯЕТ ИЗБЕЖАТЬ')
print('=' * 96)
IZVLECH = [
    ('Схема настроена на медь: Cu 98 %, Au 85 %', 0.85, 0.98),
    ('Схема настроена на золото: Cu 92 %, Au 94 %', 0.94, 0.92),
]
print(f"{'вариант настройки схемы':<48}{'очередь 1, год':>18}{'очередь 2, год':>18}{'за весь срок':>16}")
print('-' * 96)
baz = None
for n, ra, rc in IZVLECH:
    v1 = t1*(1.60*P['au']*ra + 0.24*10*P['cu']*rc)/1e6
    v2 = t2*(0.37*P['au']*ra + 0.173*10*P['cu']*rc)/1e6
    vsego = v1*2 + v2*10
    if baz is None: baz = vsego
    print(f'{n:<48}{v1:>15.0f} $М{v2:>15.0f} $М{vsego:>13.0f} $М')
print('-' * 96)
v_au = t1*(1.60*P['au']*0.94 + 0.24*10*P['cu']*0.92)/1e6*2 + t2*(0.37*P['au']*0.94 + 0.173*10*P['cu']*0.92)/1e6*10
print(f'  Настройка схемы на золото вместо меди стоит {v_au-baz:+.0f} млн $ выручки за срок')
print('  отработки — при том, что «медный» вариант даёт формально более высокие цифры')
print('  по меди и лучше смотрится в отчёте. Это и есть цена неправильно поставленной')
print('  задачи, и она платится один раз, при выборе технологии.')
