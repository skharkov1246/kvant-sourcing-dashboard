print('=' * 96)
for t, au_gt, ag_gt, nazv in [(2.3e6, 1.60, 5.4, 'Очередь 1'), (7.6e6, 0.42, 2.53, 'Полная мощность')]:
    m = t*VYHOD
    au_kg = t*au_gt/1000*DOLYA_AU
    ag_kg = t*ag_gt/1000*DOLYA_AG
    dohod = (au_kg/OZ*1000*0.995*P['au'] + ag_kg/OZ*1000*0.98*P['ag'])/1e6
    reag = (m*NACN_NA_KONC/1000*CENA['nacn'] + m*IZVEST_NA_KONC/1000*CENA['izvest']
            + m*PB_NA_KONC/1000*CENA['pb'])/1e6
    # доизмельчение до 95 % кл. −0,071 мм и 24-часовое выщелачивание
