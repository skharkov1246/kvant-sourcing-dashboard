    zatraty = reag + energ + prochee
    print(f'  {nazv}: концентрата {m:,.0f} т/год'.replace(',', ' '))
    print(f'      золота {au_kg:>7,.0f} кг, серебра {ag_kg:>7,.0f} кг -> выручка {dohod:>7.1f} млн $/год'.replace(',', ' '))
    print(f'      цианид {m*NACN_NA_KONC/1000:>7,.0f} т/год, известь {m*IZVEST_NA_KONC/1000:>6,.0f} т, '
          f'нитрат свинца {m*PB_NA_KONC/1000:>5,.0f} т'.replace(',', ' '))
    print(f'      реагенты {reag:>5.1f}, энергия {energ:>4.1f}, прочее {prochee:>4.1f} -> '
          f'затраты {zatraty:>5.1f} млн $/год')
