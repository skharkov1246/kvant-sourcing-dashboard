IZVEST_NA_KONC, PB_NA_KONC = 4.0, 0.5
DOLYA_AU, DOLYA_AG = 0.1114, 0.089           # прибавка к извлечению от руды
CENA = dict(nacn=2500.0, izvest=150.0, pb=3200.0, smola=9.0)   # $/т, смола $/л

VYHOD = NACN_NA_RUDU / NACN_NA_KONC          # выход пирротинового концентрата из руды

# ── проверка выхода по независимому балансу серы ──────────────────────────
