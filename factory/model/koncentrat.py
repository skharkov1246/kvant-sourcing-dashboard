"""Развилка, которую обошли и китайский поставщик, и научно-исследовательский центр:
качество медного концентрата 15,3 % меди.

Теоретическое содержание меди в халькопирите 34,6 %. Концентрат 15,3 % означает, что
халькопирита в нём около 44 %, а остальное — пирит и пирротин. В испытаниях ЦНИГРИ
медный цикл вёлся на пониженных расходах собирателя ради селективности, а в коллективном
цикле медный купорос подавался как АКТИВАТОР сульфидов железа. Задача повышения качества
концентрата не ставилась вообще: концентрат доводился до нижней границы кондиции КМ-7 (15 % Cu).
"""
KURS = 85.85
P = dict(au=4430, ag=67, cu=14500)
OZ = 31.1035

BAZ = dict(masса=85_000, cu=0.153, au=35.57, ag=174.33, rec_cu=0.837, rec_au=0.755, rec_ag=0.703)
CU_V_RUDE = 13_005.0   # т меди в концентрате при базовом извлечении
AU_V_KONC = 3.024      # т золота
AG_V_KONC = 14.82      # т серебра

def variant(cu_grade, poteri_cu_pp, poteri_au_pp):
    """cu_grade — доля меди в концентрате; потери в процентных пунктах извлечения."""
    cu = CU_V_RUDE * (BAZ['rec_cu'] - poteri_cu_pp) / BAZ['rec_cu']
    au = AU_V_KONC * (BAZ['rec_au'] - poteri_au_pp) / BAZ['rec_au']
    ag = AG_V_KONC * (BAZ['rec_ag'] - poteri_au_pp) / BAZ['rec_ag']
    massa = cu / cu_grade
    vlazh = massa / 0.91
    # выручка при продаже концентрата
    payable = (cu * 0.935 * P['cu'] + au * 1e6 / OZ * 0.925 * P['au']
               + ag * 1e6 / OZ * 0.90 * P['ag']) / 1e6
    tc = 70 * massa / 1e6
    rc = (176 * cu * 0.935 + 18 * au * 1e6 / OZ * 0.925 + 1.5 * ag * 1e6 / OZ * 0.90) / 1e6
    fraht = 100 * vlazh / 1e6
    # штраф за низкое содержание меди: ниже 20 % медьзаводы применяют надбавку к плате за переработку
    shtraf = (20 - cu_grade * 100) * 1.5 * massa / 1e6 if cu_grade < 0.20 else 0.0
    nsr = payable - tc - rc - fraht - shtraf
    return dict(grade=cu_grade * 100, massa=massa, cu=cu, au=au, ag=ag,
                nsr=nsr, tc=tc, rc=rc, fraht=fraht, shtraf=shtraf)

print('ВЛИЯНИЕ КАЧЕСТВА МЕДНОГО КОНЦЕНТРАТА, котировки 31.08.2026')
print(f"{'Cu в к-те':>9}{'масса, т':>10}{'потери':>18}{'NSR, млн':>10}{'фрахт':>8}{'плата':>8}{'штраф':>8}")
print('-' * 76)
baza = variant(0.153, 0.0, 0.0)
rez = [('базовый 15,3 %', baza, '—')]
for g, dcu, dau in [(0.20, 0.010, 0.010), (0.22, 0.015, 0.015), (0.25, 0.020, 0.020),
                    (0.25, 0.035, 0.040), (0.28, 0.030, 0.035)]:
    v = variant(g, dcu, dau)
    rez.append((f'{g*100:.0f} % при потере {dcu*100:.1f}/{dau*100:.1f} п.п.', v,
                f'{v["nsr"]-baza["nsr"]:+.1f}'))
for n, v, d in rez:
    print(f'{v["grade"]:>8.1f}%{v["massa"]:>10.0f}{n.split("при")[-1][:16]:>18}'
          f'{v["nsr"]:>10.1f}{v["fraht"]:>8.1f}{v["tc"]+v["rc"]:>8.1f}{v["shtraf"]:>8.1f}')

print('\nЧТО ЭТО ДАЁТ, если строим СВОЙ металлургический передел')
b, u = variant(0.153, 0, 0), variant(0.25, 0.020, 0.020)
sokr = 1 - u['massa'] / b['massa']
print(f'  масса концентрата: {b["massa"]:.0f} -> {u["massa"]:.0f} т/год, сокращение {sokr*100:.0f} %')
print(f'  металлургический передел масштабируется как мощность^0,7:')
for cap in (350, 300, 250):
    print(f'    при капитале {cap} млн долл. на 85 тыс. т -> {cap*(1-sokr)**0.7:.0f} млн долл. '
          f'на {u["massa"]/1000:.0f} тыс. т, экономия {cap - cap*(1-sokr)**0.7:.0f} млн')
print(f'  потеря металла при этом: медь {b["cu"]-u["cu"]:.0f} т/год, золото {(b["au"]-u["au"])*1000:.0f} кг/год')
poterya = ((b['cu']-u['cu'])*0.935*P['cu'] + (b['au']-u['au'])*1e6/OZ*0.925*P['au'])/1e6
print(f'  стоимость потери металла: {poterya:.1f} млн долл./год')
print(f'  экономия на плате за переработку и фрахте: {(b["tc"]+b["rc"]+b["fraht"]+b["shtraf"])-(u["tc"]+u["rc"]+u["fraht"]+u["shtraf"]):.1f} млн долл./год')
