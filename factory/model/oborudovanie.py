"""Подбор оборудования по укрупнённым блокам: расчёт мощностей и поставщики.

Мощности считаются от производительности, а не берутся из чужого перечня.
Полученные величины сверяются с перечнем оборудования китайского техпроекта
на 2,3 млн т/год — совпадение служит проверкой расчёта.
"""
import math

OCH1, OCH2 = 2.3e6, 8.5e6          # т руды в год
SUT, CH_DROB, CH_IZM = 330, 18.0, 24.0
WI = 14.0                          # индекс работы по Бонду, кВт·ч/т (кварц-сульфидный штокверк)
F80, P80 = 12_000.0, 71.0          # мкм: питание измельчения и крупность слива

def bond(f80, p80, wi=WI):
    return 10*wi*(1/math.sqrt(p80) - 1/math.sqrt(f80))

print('=' * 102)
print('1. РАСЧЁТНЫЕ ЧАСОВЫЕ ПРОИЗВОДИТЕЛЬНОСТИ')
