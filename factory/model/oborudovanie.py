print('=' * 102)
print('3. ФЛОТАЦИЯ: ОБЪЁМ КАМЕР ИЗ ВРЕМЕНИ ФЛОТАЦИИ')
print('=' * 102)
TV, RHO_P, T_OSN, T_PER = 0.30, 1.25, 25.0, 30.0
for nazv, t in [('Очередь 1', OCH1), ('Полная мощность', OCH2)]:
    q = t/SUT/CH_IZM
    v_ch = q/TV/RHO_P
    v_osn = v_ch*T_OSN/60/0.80
    print(f'  {nazv}: пульпы {v_ch:.0f} м³/ч; основная флотация {T_OSN:.0f} мин -> {v_osn:.0f} м³ камер')
    for vol in (30, 50, 100, 160):
        print(f'      камерами по {vol:>3} м³: {math.ceil(v_osn/vol):>2} шт.', end='')
    print()
