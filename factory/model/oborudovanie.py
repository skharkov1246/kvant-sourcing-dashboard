print(f'  подтверждения испытанием — это одно из первых чисел, которое надо измерить).')
print(f'  Удельная работа измельчения с {F80/1000:.0f} мм до {P80:.0f} мкм: {w:.1f} кВт·ч/т.')
for nazv, t in [('Очередь 1', OCH1), ('Полная мощность', OCH2)]:
    q = t/SUT/CH_IZM
    n_kvt = q*w/0.90
    print(f'  {nazv}: {q:.0f} т/ч × {w:.1f} = {n_kvt/1000:.1f} МВт на валу мельниц')
print(f'  Китайский перечень первой очереди: две мельницы ZTMY4060 по 1 800 кВт и две')
print(f'  ZTMY3655 по 1 250 кВт — итого 6,1 МВт против расчётных '
      f'{OCH1/SUT/CH_IZM*w/0.90/1000:.1f} МВт. Сходится.')
print(f'  Доизмельчение концентрата до 10-12 мкм перед гидрометаллургией — отдельная')
print(f'  статья: по данным GPM Gold 59 кВт·ч на тонну концентрата, то есть при')
print(f'  87 тыс. т/год это {87000*59/1e6:.1f} ГВт·ч в год, около {87000*59/8000/1000:.1f} МВт установленной мощности.')

