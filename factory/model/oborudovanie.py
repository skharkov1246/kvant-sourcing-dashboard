print(f'  15 камер по 50 м³ = 750 м³ на основную и перечистные операции вместе.')
print(f'  Наш расчёт даёт {OCH1/SUT/CH_IZM/TV/RHO_P*T_OSN/60/0.80:.0f} м³ только на основную. Сходится с учётом')
print('  того, что перечистки в китайском перечне идут камерами XCF-30 и KYF-30.')

