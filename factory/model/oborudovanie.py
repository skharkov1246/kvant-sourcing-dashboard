print('-' * 102)
for n, ch in [('Дробление', CH_DROB), ('Измельчение и флотация', CH_IZM)]:
    print(f'{n:<38}{OCH1/SUT/ch:>13.0f} т/ч{OCH2/SUT/ch:>19.0f} т/ч{f"{ch:.0f} ч/сут":>18}')
print('-' * 102)
print(f'  Китайский техпроект на первую очередь: 7 000 т/сут при 18 ч/сут на дроблении')
