def prodazha(tc, rc_cu, pay_cu=None, m_konc=None, skidka=0.0):
    """Выручка нетто и удержания при продаже концентрата, млн $/год."""
    m_konc = m_konc or M_KONC
    pay_cu = pay_cu if pay_cu is not None else d.PAY['cu']
