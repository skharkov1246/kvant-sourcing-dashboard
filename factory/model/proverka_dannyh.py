 'что не бьётся, и указанием, какие величины приняты расчётными. Считать',
 'по несходящимся данным — переносить ошибку в проектные решения, где она',
 'обойдётся во много раз дороже, чем стоил бы запрос.',
 '',
 'Отдельно по висмуту: если верна цифра 0,87 %, медный концентрат этого',
 'месторождения не продаётся на общих условиях вообще — при содержании висмута',
 'выше 0,05 % большинство заводов вводит штраф, выше 0,1 % — отказывается',
 'от партии. Это меняет не технологию, а саму возможность продавать концентрат,',
