# -*- coding: utf-8 -*-
"""Логистика медного концентрата из Карелии и её влияние на выбор «продавать или перерабатывать».

В расчёте выручки от продажи концентрата принята доставка 100 $ на влажную тонну.
Величина взята как отраслевой ориентир и до сих пор не проверялась, между тем от неё
прямо зависит порог, начиная с которого собственный передел становится оправданным.
Здесь она разложена по составляющим и проверена на чувствительность.

ВАЖНО: железнодорожные тарифы на перевозку концентратов в открытом доступе
не публикуются и устанавливаются договором. Все ставки ниже — ДОПУЩЕНИЯ,
заданные диапазоном. Задача расчёта не в том, чтобы назвать точную цифру,
а в том, чтобы показать, меняет ли разброс по логистике принимаемое решение.
"""
import importlib.util, os
_d = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('dcf', os.path.join(_d, 'dcf.py'))
d = importlib.util.module_from_spec(spec); spec.loader.exec_module(d)

KURS = 85.85
M_KONC = 86_621
VLAGA = 0.09
M_VLAZH = M_KONC / (1 - VLAGA)

# ставка железнодорожной перевозки, руб. на тонно-километр — ДОПУЩЕНИЕ, диапазон
TARIF = (1.5, 2.5)
POGRUZKA = (250, 450)      # руб./т: погрузка, выгрузка, подача вагонов, оформление
PORT = (700, 1200)         # руб./т: перевалка в порту
MORE = (30.0, 50.0)        # $/т: морской фрахт до портов Китая

NAPRAVLENIYA = [
    ('«Карабашмедь», Челябинская обл.', 2300, False, 'внутренний покупатель, черновая медь 230 тыс. т/год'),
    ('Предприятия УГМК, Свердловская обл.', 2500, False, 'внутренний покупатель'),
    ('Норильск (через Мурманск)', 1400, True, 'внутренний покупатель, морское плечо короткое'),
    ('Порт Усть-Луга и далее морем в Китай', 600, True, 'внешний покупатель'),
    ('Балхаш, Казахстан', 3400, False, 'внешний покупатель в ЕАЭС, без морского плеча'),
]

print('=' * 104)
print('1. СТОИМОСТЬ ДОСТАВКИ ПО НАПРАВЛЕНИЯМ')
print('=' * 104)
print(f"{'направление':<40}{'км':>7}{'$/влажн. т':>22}{'млн $/год':>18}")
print('-' * 104)
rez = []
for nazv, km, morem, kom in NAPRAVLENIYA:
    lo = (km*TARIF[0] + POGRUZKA[0] + (PORT[0] if morem else 0))/KURS + (MORE[0] if morem else 0)
    hi = (km*TARIF[1] + POGRUZKA[1] + (PORT[1] if morem else 0))/KURS + (MORE[1] if morem else 0)
    rez.append((nazv, lo, hi))
    print(f'{nazv:<40}{km:>7,}{lo:>10.0f}—{hi:<11.0f}{lo*M_VLAZH/1e6:>8.1f}—{hi*M_VLAZH/1e6:<9.1f}'.replace(',', ' '))
print('-' * 104)
vsе_lo = min(r[1] for r in rez); vsе_hi = max(r[2] for r in rez)
print(f'  Разброс по всем направлениям: {vsе_lo:.0f}—{vsе_hi:.0f} $ на влажную тонну.')
print(f'  Принятая в расчёте выручки величина 100 $/т лежит {"внутри" if vsе_lo <= 100 <= vsе_hi else "вне"} этого диапазона')
print(f'  и ближе к его верхней границе. То есть допущение консервативное: реальная')
print(f'  доставка, скорее всего, дешевле, и продажа концентрата выгоднее, чем в расчёте.')
print()
print('  Отдельно: перевозка концентрата в Карелии короче, чем у большинства российских')
print('  медных проектов. До портов Балтики 500-700 км, что для внешнего покупателя')
print('  выгоднее, чем из Сибири или с Урала. Это самостоятельное преимущество площадки,')
print('  и оно работает именно в пользу продажи концентрата, а не собственного передела.')

print()
print('=' * 104)
print('2. ЧТО МЕНЯЕТ СТОИМОСТЬ ДОСТАВКИ В РЕШЕНИИ «ПРОДАВАТЬ ИЛИ ПЕРЕРАБАТЫВАТЬ»')
print('=' * 104)
OZ = 31.1035
P = dict(au=4425.0, ag=66.6, cu=14595.0)
CU_T, AU_KG, AG_KG = 13_253.0, 2_072.0, 13_410.0

def vyruchka_prodazhi(freight):
    gross = (CU_T*d.PAY['cu']*P['cu'] + AU_KG/OZ*1000*d.PAY['au_conc']*P['au']
             + AG_KG/OZ*1000*d.PAY['ag_conc']*P['ag']) / 1e6
    ded = (70.0*M_KONC + 176.0*CU_T*d.PAY['cu']
           + d.RC_AU*AU_KG/OZ*1000*d.PAY['au_conc']
           + d.RC_AG*AG_KG/OZ*1000*d.PAY['ag_conc']
           + freight*M_VLAZH) / 1e6
    return gross - ded

print(f"{'доставка, $/влажн. т':<26}{'выручка от продажи':>24}{'изменение к базе':>22}{'направление':>28}")
print('-' * 104)
baza = vyruchka_prodazhi(100.0)
for f, kom in [(55, 'Усть-Луга, нижняя оценка'), (70, 'Карабашмедь, нижняя оценка'),
               (85, 'Карабашмедь, середина'), (100, 'принято в расчёте'),
               (115, 'Балхаш, верхняя оценка'), (130, 'верхняя граница по всем')]:
    v = vyruchka_prodazhi(f)
    print(f'{f:<26}{v:>17.1f} млн $/год{v-baza:>+17.1f} млн $/год{kom:>28}')
print('-' * 104)
print(f'  Каждые 10 $ на тонне доставки стоят {(vyruchka_prodazhi(100)-vyruchka_prodazhi(110)):.2f} млн $ в год.')
print(f'  За двенадцать лет при ставке 10 % это {(vyruchka_prodazhi(100)-vyruchka_prodazhi(110))*sum(1/1.1**i for i in range(1,13)):.0f} млн $ приведённых.')

print()
print('=' * 104)
print('3. ПРИ КАКОЙ ДОСТАВКЕ ПЕРЕДЕЛ СТАНОВИТСЯ ОПРАВДАННЫМ')
print('=' * 104)
# порог окупаемости атмосферного маршрута: капитал 205, opex 17.5, выручка 466.5 (модель vybor.py)
MARSH = [
    ('Атмосферное выщелачивание, кислый режим', 205.0, 17.5, 466.5),
    ('Автоклав с известковой обработкой кека', 261.0, 29.7, 485.5),
    ('Пирометаллургия, шахтная печь', 312.0, 42.0, 494.5),
]
ann = sum(1/1.1**i for i in range(1, 13))
print(f"{'маршрут':<44}{'безубыточная доставка':>26}{'реальна ли':>22}")
print('-' * 104)
for n, kap, opx, vyr in MARSH:
    lo, hi = 0.0, 2000.0
    for _ in range(80):
        mid = (lo + hi)/2
        god = vyr - opx - vyruchka_prodazhi(mid)
        kapital = sum(kap*w/1.1**i for i, w in [(1, .30), (2, .55), (3, .15)])
        if god*ann/1.1**3 - kapital > 0: hi = mid
        else: lo = mid
    porog = (lo + hi)/2
    ocenka = 'да' if porog <= vsе_hi else ('на границе' if porog <= vsе_hi*1.5 else 'нет')
    print(f'{n:<44}{porog:>19.0f} $/влажн. т{ocenka:>22}')
print('-' * 104)
print('  Читать так: передел окупается, только если доставка концентрата покупателю')
print('  обойдётся дороже указанной величины. Ни одно из реальных направлений')
print('  таких величин не даёт даже по верхней границе допущений.')
print()
print('  ВЫВОД. Логистика в Карелии не создаёт оснований для собственного передела.')
print('  Наоборот: короткое плечо до портов Балтики и наличие внутренних покупателей')
print('  делают продажу концентрата более выгодной, чем принято в базовом расчёте.')
print('  Основанием для передела может быть только невозможность продать концентрат')
print('  как таковая — по примесям либо по условиям покупателей, — а не расстояние.')
