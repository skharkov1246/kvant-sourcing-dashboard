# -*- coding: utf-8 -*-
"""Экономика по плану отработки из паспорта месторождения (первая и вторая очереди).

ПРЕДВАРИТЕЛЬНЫЙ расчёт. Источник данных — паспорт месторождения, полученный 01.09.2026.
Отличия от плана, по которому считает audit.py: руда 67,64 вместо 72,07 млн т, срок
2029—2038, профиль 2,34 -> 7,46 -> 8,5 млн т в год, содержание первой очереди 1,6 г/т
против 0,37 г/т второй.

Коэффициенты извлечения приняты по паспорту: Au 0,80, Ag 0,76, Cu 0,85. Это третий
набор значений после 0,90 из календарного плана и 0,866 / 0,792 / 0,837 из отчёта
ЦНИГРИ; какой из них считать плановым — открытый вопрос Т-1. Капитал 1300 млн долл.
принят с поправкой на пиковую мощность 8,5 млн т против 7,6 млн т в базовой оценке.

Выручка считается напрямую от металла в готовой продукции, приведённого в паспорте,
без разделения на концентрат и сплав Доре.
"""
import importlib.util
spec = importlib.util.spec_from_file_location("dcf", "dcf.py")
d = importlib.util.module_from_spec(spec); spec.loader.exec_module(d)
OZ = 31.1035
P = {'base': dict(au=3500, ag=50, cu=11000), 'spot': dict(au=4400, ag=66, cu=14000)}

# год, руда т, Au ГП т, Ag ГП т, Cu ГП т, концентрат т
PLAN = [
 (2029,2_343_750,3.00,7.13,4_781,37_500),  (2030,2_343_750,3.00,7.13,4_781,37_500),
 (2031,7_455_522,2.50,17.67,13_065,102_469),(2032,8_503_597,2.50,14.50,12_474,97_832),
 (2033,8_503_597,2.50,14.50,12_474,97_832),(2034,8_503_597,2.50,14.50,12_474,97_832),
 (2035,8_503_597,2.50,14.50,12_474,97_832),(2036,8_503_597,2.50,14.50,12_474,97_832),
 (2037,8_503_597,2.50,14.50,12_474,97_832),(2038,4_476_294,1.32,7.63,6_566,51_499),
]
CAP = 8.5e6  # проектная мощность по пиковым годам

def nsr(au_t, ag_t, cu_t, conc_t, pr):
    p = P[pr]
    au_oz, ag_oz = au_t*1e6/OZ, ag_t*1e6/OZ
    gross = (au_oz*0.925*p['au'] + ag_oz*0.90*p['ag'] + cu_t*0.935*p['cu'])/1e6
    ded = (70*conc_t + 176*cu_t*0.935 + 18*au_oz*0.925 + 1.5*ag_oz*0.90
           + 100*conc_t/0.91)/1e6
    return gross - ded

def opex(t, strip=4.5):
    return t*(1+strip)/1e6*2.0 + 72.0*(CAP/7.6e6)*(0.30+0.70*min(t/CAP,1.0)) + 22.0

def run(pr, capex_total):
    k = capex_total/1227.0
    capex = {2027:220.0*k, 2028:620.0*k, 2029:387.0*k}
    flows=[]
    for y in range(2027, 2040):
        row = next((r for r in PLAN if r[0]==y), None)
        cf = -capex.get(y,0.0)
        if row:
            _,t,au,ag,cu,conc = row
            r = nsr(au,ag,cu,conc,pr)
            cf += r - opex(t) - r*0.07 - 28.0*min(t/CAP*1.2,1.0)
        if y==2039: cf -= 50.0
        flows.append(cf)
    return d.npv(flows,0.10), d.irr(flows), flows

print('ПЛАН ИЗ ПАСПОРТА: руда 67,6 млн т, Au в продукции 24,8 т, срок 2029—2038')
print(f"{'сценарий':<44}{'ЧДД@10%':>10}{'ВНД':>8}")
print('-'*64)
for pr in ('base','spot'):
    for cap,lbl in ((1300,'капитал 1300 (фабрика 8,5 млн т)'),(950,'капитал 950 (низкий случай)')):
        n,i,_ = run(pr,cap)
        print(f"{('Цены: '+pr+' · '+lbl):<44}{n:>9.0f}{i*100:>7.1f}%")
n,i,fl = run('spot',1300)
print('\nДенежный поток, спот, капитал 1300 (млн $):')
for y,f in zip(range(2027,2040), fl): print(f'  {y}: {f:>8.0f}')
