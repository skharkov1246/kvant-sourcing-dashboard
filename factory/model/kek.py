# -*- coding: utf-8 -*-
"""Масса и состав кека кислого выщелачивания: почему остаток тяжелее исходного концентрата.

При кислом окислительном выщелачивании медь уходит в раствор, но железо, освобождённое
из халькопирита и пирротина, возвращается в твёрдую фазу в виде ярозита или гётита,
а сера частично остаётся в элементной форме. В результате масса кека, идущего
на цианирование, оказывается не меньше, а больше массы исходного концентрата.

Это меняет две вещи, которые в предложениях никем не посчитаны:
  · узел цианирования надо считать на массу кека, а не на массу концентрата;
  · разложение ярозита и разрушение элементной серы требуют извести, и это
    самая крупная реагентная статья маршрута.

Все стехиометрические коэффициенты выведены в тексте, чтобы их можно было проверить.
"""
M = dict(fe=55.845, s=32.06, cu=63.546, ca=40.078, o=15.999, h=1.008, k=39.098, pb=207.2)
M_JAROZIT = M['k'] + 3*M['fe'] + 2*(M['s'] + 4*M['o']) + 6*(M['o'] + M['h'])   # KFe3(SO4)2(OH)6
M_GETIT = M['fe'] + M['o'] + (M['o'] + M['h'])                                  # FeO(OH)
M_CAOH2 = M['ca'] + 2*(M['o'] + M['h'])
M_GIPS = M['ca'] + M['s'] + 4*M['o'] + 2*(2*M['h'] + M['o'])
M_PBSO4 = M['pb'] + M['s'] + 4*M['o']

# состав концентрата, восстановленный в модели gidromet.py
KONC = 86_621
MIN = dict(halkopirit=34_445, pirit=15_680, pirrotin=29_522, porода=6_973)
FE_HALK, FE_PIRRO, FE_PIRIT = 10_483, 18_746, 7_308
S_HALK, S_PIRRO, S_PIRIT = 12_035, 10_767, 8_381
CU = 13_253
PB = KONC * 0.0206

# режим: вскрываются халькопирит и пирротин, пирит наиболее упорен
DOLYA_HALK, DOLYA_PIRRO, DOLYA_PIRIT = 0.98, 0.99, 0.35
DOLYA_S_ELEM = 0.65      # доля окисленной сульфидной серы, остающаяся элементной

print('=' * 100)
print('1. ЧТО ПРОИСХОДИТ С ЖЕЛЕЗОМ')
print('=' * 100)
fe_v_rastvor = FE_HALK*DOLYA_HALK + FE_PIRRO*DOLYA_PIRRO + FE_PIRIT*DOLYA_PIRIT
print(f'  Железа в концентрате всего:                         {FE_HALK+FE_PIRRO+FE_PIRIT:>8,.0f} т/год'.replace(',', ' '))
print(f'  Освобождается при вскрытии сульфидов:               {fe_v_rastvor:>8,.0f} т/год'.replace(',', ' '))
print('  В растворе железо оставаться не может: оно связывает кислоту и отравляет')
print('  экстракцию меди, поэтому его осаждают. Форма осадка определяет массу кека.')
print()
print(f"{'форма осаждения':<34}{'коэффициент':>14}{'масса, т/год':>16}{'примечание':>34}")
print('-' * 100)
for nazv, koef, prim in [
    ('Ярозит KFe3(SO4)2(OH)6', M_JAROZIT/(3*M['fe']), 'связывает и серу, и щёлочь'),
    ('Гётит FeO(OH)', M_GETIT/M['fe'], 'требует более высокой температуры'),
]:
    print(f'{nazv:<34}{koef:>14.2f}{fe_v_rastvor*koef:>16,.0f}{prim:>34}'.replace(',', ' '))
print('-' * 100)
print('  Ярозит образуется в кислом сульфатном растворе при 90-100 °C, то есть ровно')
print('  в условиях атмосферного выщелачивания. Гётит требует более жёстких условий.')
print('  Для расчёта принимается ярозит как основная форма — это консервативно.')

print()
print('=' * 100)
print('2. СОСТАВ И МАССА КЕКА')
print('=' * 100)
s_okislenno = S_HALK*DOLYA_HALK + S_PIRRO*DOLYA_PIRRO + S_PIRIT*DOLYA_PIRIT
s_elem = s_okislenno * DOLYA_S_ELEM
ne_vskryto = (MIN['halkopirit']*(1-DOLYA_HALK) + MIN['pirrotin']*(1-DOLYA_PIRRO)
              + MIN['pirit']*(1-DOLYA_PIRIT))
jarozit = fe_v_rastvor * M_JAROZIT/(3*M['fe'])
pbso4 = PB * M_PBSO4/M['pb']
KEK = jarozit + s_elem + ne_vskryto + MIN['porода'] + pbso4

print(f"{'составляющая кека':<44}{'т/год':>14}{'доля кека':>14}")
print('-' * 100)
for nazv, m in [('Ярозит от осаждения железа', jarozit),
                ('Сера элементная', s_elem),
                ('Невскрытые сульфиды (в основном пирит)', ne_vskryto),
                ('Нерудная часть исходного концентрата', MIN['porода']),
                ('Сульфат свинца', pbso4)]:
    print(f'{nazv:<44}{m:>14,.0f}{m/KEK*100:>13.1f} %'.replace(',', ' '))
print('-' * 100)
print(f'{"ИТОГО кек на цианирование":<44}{KEK:>14,.0f}{100.0:>13.1f} %'.replace(',', ' '))
print(f'{"Исходный концентрат":<44}{KONC:>14,.0f}'.replace(',', ' '))
print(f'{"Отношение кек / концентрат":<44}{KEK/KONC:>14.2f}')
print()
print(f'  Кек ТЯЖЕЛЕЕ исходного концентрата в {KEK/KONC:.2f} раза: {KEK/330:,.0f} т/сут против {KONC/330:.0f} т/сут.'.replace(',', ' '))
print('  Содержание золота в кеке при полном его переходе в твёрдое:')
au_konc = 2_391  # кг золота в медном концентрате, модель vybor.py
print(f'  {au_konc*1000/KEK:.1f} г/т против {au_konc*1000/KONC:.1f} г/т в концентрате — золото РАЗУБОЖИВАЕТСЯ.')
print()
print('  СЛЕДСТВИЕ, КОТОРОГО НЕТ НИ В ОДНОМ ПРЕДЛОЖЕНИИ. Узел сорбционного цианирования')
print(f'  надо считать на {KEK:,.0f} т/год, а не на {KONC:,.0f} т/год. Это на {(KEK/KONC-1)*100:.0f} % больше'.replace(',', ' '))
print('  по объёму аппаратов, по расходу цианида и по обезвреживанию. Любая оценка,')
print('  привязанная к массе концентрата, занижена на эту величину.')

print()
print('=' * 100)
print('3. ИЗВЕСТЬ: САМАЯ КРУПНАЯ РЕАГЕНТНАЯ СТАТЬЯ МАРШРУТА')
print('=' * 100)
# разложение ярозита: KFe3(SO4)2(OH)6 + 2 Ca(OH)2 -> 3 Fe(OH)3 + 2 CaSO4 + KOH
ca_jarozit = fe_v_rastvor/(3*M['fe']) * 2 * M_CAOH2
# разрушение элементной серы известковой варкой: принимается 1 моль Ca(OH)2 на моль серы
ca_sera = s_elem/M['s'] * M_CAOH2
CENA_IZVEST = 150.0
print(f"{'назначение':<52}{'Ca(OH)2, т/год':>18}{'стоимость':>16}")
print('-' * 100)
print(f'{"Разложение ярозита для освобождения серебра":<52}{ca_jarozit:>18,.0f}{ca_jarozit*CENA_IZVEST/1e6:>13.1f} млн$'.replace(',', ' '))
print(f'{"Разрушение элементной серы перед цианированием":<52}{ca_sera:>18,.0f}{ca_sera*CENA_IZVEST/1e6:>13.1f} млн$'.replace(',', ' '))
print('-' * 100)
ca = ca_jarozit + ca_sera
print(f'{"ИТОГО":<52}{ca:>18,.0f}{ca*CENA_IZVEST/1e6:>13.1f} млн$'.replace(',', ' '))
print()
print(f'  {ca:,.0f} т гашёной извести в год — это {ca/330:.0f} т в сутки, то есть отдельное'.replace(',', ' '))
print('  известковое хозяйство с приёмом, гашением, складом и дозированием, а не мешки.')
print('  Для сравнения: цианида на этот же кек нужно около 900-1 100 т/год.')
print(f'  Гипса при этом образуется {ca/M_CAOH2*M_GIPS:,.0f} т/год, и он идёт на карту складирования.'.replace(',', ' '))
print()
print('  Это не довод против маршрута, но это статья, которой нет ни в одной из оценок,')
print('  и она сопоставима по деньгам с расходом кислорода.')

print()
print('=' * 100)
print('4. ЧТО ЭТО МЕНЯЕТ В СРАВНЕНИИ МАРШРУТОВ')
print('=' * 100)
for s in [
 'Приростные затраты кислого атмосферного маршрута против ранее принятых в модели vybor.py:',
 f'  · известь {ca*CENA_IZVEST/1e6:.1f} млн $ в год — не учитывалась;',
 f'  · цианирование на {(KEK/KONC-1)*100:.0f} % большей массе — узел дороже примерно на 8-12 млн $ капитала;',
 f'  · складирование {jarozit:,.0f} т ярозита в год — отдельная карта, 10-15 млн $ капитала.'.replace(',', ' '),
 '',
 'Ни одно из этих обстоятельств не отменяет вывода о том, что атмосферный маршрут',
 'дешевле автоклавного: у автоклава с полным окислением железо осаждается точно так же,',
 'а кислоты образуется вчетверо больше. Но абсолютные величины по атмосферному маршруту',
 'надо поднять, и делать это следует до, а не после разговора с заказчиком.',
 '',
 f'Отдельно: разубоживание золота в кеке с {au_konc*1000/KONC:.1f} до {au_konc*1000/KEK:.1f} г/т означает, что цианирование',
 'идёт на более бедном материале, чем принято в расчёте извлечения. При прочих равных',
 'это ухудшает кинетику и повышает удельный расход реагентов на грамм золота.',
 'Величину надо получить опытом, а не принимать по аналогии.',
]:
    print('  ' + s)
