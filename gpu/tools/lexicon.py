# граница слова с учётом кириллицы: слева не буква и не дефис, справа не буква
RULES = [(re.compile(r"(?<![^\W\d_]|-)" + re.escape(a) + r"(?![^\W\d_])"), b) for a, b in PAIRS]


def normalize(text: str) -> str:
    """Приводит строку к терминологии словаря."""
    for rx, b in RULES:
        text = rx.sub(b, text)
    return text


def walk(obj):
    """Рекурсивно нормализует все строковые значения структуры JSON."""
    if isinstance(obj, str):
        return normalize(obj)
    if isinstance(obj, list):
        return [walk(x) for x in obj]
    if isinstance(obj, dict):
        return {k: walk(v) for k, v in obj.items()}
    return obj


